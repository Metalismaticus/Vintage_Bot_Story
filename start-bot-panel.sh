#!/usr/bin/env sh
# Копатель с окном настроек в браузере.
#
# Окно откроется само: http://127.0.0.1:42462/?k=<ключ>
# Ключ рождается заново при каждом запуске и печатается в журнале.
# Дверь только на этой машине; с другой машины смотреть через
#   ssh -L 42462:127.0.0.1:42462 пользователь@сервер
#
# Если игра стоит в необычном месте:  export VINTAGE_STORY=/путь/к/игре
set -e
cd "$(dirname "$0")"
exec dotnet run --project VintageBotStory -- --preset digger --panel --diag "$@"
