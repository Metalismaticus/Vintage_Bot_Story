using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Text.Unicode;

namespace VsBotKit;

/// <summary>
/// ОДНО МЕСТО, НАЗВАННОЕ ЧЕЛОВЕКОМ. Пустые координаты — это не «не знаю», а
/// «человек СНЯЛ место»: снятое возвращать обратно нельзя, иначе бот спорит
/// с хозяином.
/// </summary>
public sealed class НазванноеМесто
{
    public int? X { get; set; }
    public int? Y { get; set; }
    public int? Z { get; set; }

    /// <summary>Когда человек это сказал — чтобы бот мог назвать день.</summary>
    public string Когда { get; set; } = "";

    /// <summary>В каком готовом боте это было сказано — чтобы назвать файл.</summary>
    public string Где { get; set; } = "";

    /// <summary>
    /// В КАКИХ КООРДИНАТАХ ЗАПИСАНЫ ЭТИ ТРИ ЧИСЛА: «игровые», «мировые» или
    /// пусто (старая запись, до 28.08 системы никто не хранил).
    ///
    /// ЗАЧЕМ ЭТО ПОЛЕ ЕСТЬ, И ЭТО НЕ ЗАПАС НА БУДУЩЕЕ. Вид ручки у обеих
    /// клеток ОДИН — «клетка», — а числа разные: (258, 111, −260) в игровых и
    /// (512258, 111, 511740) в мировых означают одно место. Ключ памяти — ИМЯ
    /// ручки; значит первая же роль, заведшая «Дом» другого типа, получила бы
    /// из памяти точку за полмиллиона блоков. Ровно так заказчик уже потерял
    /// склад — об этом написано в описании <c>LivingRole.Дом</c>.
    /// </summary>
    public string Координаты { get; set; } = "";

    /// <summary>Место названо (а не снято).</summary>
    [JsonIgnore]
    public bool Задано => X != null && Y != null && Z != null;

    public override string ToString() =>
        Задано ? $"({X}, {Y}, {Z})" : "снято";
}

/// <summary>Что делать с местом, которого нет в ручке роли.</summary>
public enum ЧтоСМестом
{
    /// <summary>Ничего: либо место есть, либо человек его не называл, либо снял сам.</summary>
    Оставить,

    /// <summary>Вернуть из памяти и СКАЗАТЬ об этом вслух.</summary>
    Вернуть
}

/// <summary>
/// ПАМЯТЬ МЕСТ, НАЗВАННЫХ ЧЕЛОВЕКОМ: дом, склад, пост — рядом с ботом, а не
/// внутри готового бота.
///
/// ЖИВАЯ ПОТЕРЯ, РАДИ КОТОРОЙ ЭТО ЗАВЕДЕНО (28.08, словами заказчика: «после
/// твоих обнов ОПЯТЬ забыл где склад и дом. задал, поотносил несколько раз всё
/// на склад и стоит афк в карьере»). Улики лежат на диске у него и сходятся
/// одна к одной:
///   • presets-мои\digger.json  — «Склад» (62, 112, 255), «Дом» (62, 122, 255),
///     195 накрученных ручек. Это ЕГО копатель, он его настраивал неделю;
///   • presets-мои\resident.json — ни «Дома», ни «Склада», 10 ручек;
///   • bot.json                  — "preset": "resident".
/// В журнале 27.08 21:49: «пресет „resident“: настроек применено 10», следом
/// «дом не задан: ни точки дома, ни постоянного склада роли мне не давали», а
/// «Житель» — это роль, про которую в её же описании сказано «Работу сам не
/// затевает». Вот и весь «афк в карьере»: дом, склад и работа пропали ОДНИМ
/// движением — сменой имени готового бота в bot.json.
///
/// ПОЧЕМУ ЭТО НЕ ЧИНИТСЯ ВНУТРИ ПРЕСЕТА. Готовый бот — это «КЕМ БЫТЬ», и файл
/// этот заводится общим: в нём стоит «этим файлом можно делиться» (presets/*.json),
/// он приезжает с программой и ложится в git. А «где мой дом» — это факт про
/// ЭТОТ мир и ЭТОГО хозяина, и он не обязан ни делиться, ни умирать вместе со
/// сменой того, кем бот сегодня работает. Пока дом жил только в пресете, его
/// уносило ВСЁ: смена готового бота в окне, чужая строка запуска
/// «--preset …», перезапись bot.json чужим прогоном.
///
/// ЧЕГО ЭТА ПАМЯТЬ НЕ ПЕРЕЖИВЁТ, И ОБ ЭТОМ НАДО СКАЗАТЬ ВСЛУХ: РАСПАКОВКУ
/// НОВОЙ ВЕРСИИ. «места.json» ложится в <see cref="BotFolders.State"/>, а это
/// каталог сборки (папка bin рядом с ботом) — про него в GameFolders прямо
/// написано, что распаковка стирает его целиком. Не хуже «presets-мои»,
/// которые лежат там же, но и не лучше: обещать больше, чем есть, значит
/// завести четвёртую пропажу дома.
///
/// ПРАВИЛО ОДНО И ОНО УЗКОЕ: память хранит ПОСЛЕДНЕЕ, ЧТО ЧЕЛОВЕК СКАЗАЛ про
/// каждое место, и подставляет его ТОЛЬКО в пустую ручку, ТОЛЬКО на том же
/// сервере — и ВСЛУХ (закон 4). Место, названное в готовом боте, всегда
/// старше памяти: файл человек правит руками и ждёт, что его послушают.
///
/// КАКИЕ РУЧКИ СЧИТАЮТСЯ МЕСТАМИ — спрашивается у ТИПА (<see cref="RoleKnobs.KindOf"/>
/// отвечает «клетка»), а не по списку имён. Список «Дом, Склад, Пост» отстал бы
/// от первой же роли, которая заведёт себе четвёртое место.
/// </summary>
public sealed class ПамятьМест
{
    /// <summary>Имя файла — по образцу botsession.json и botmeetings.json.</summary>
    public const string DefaultFileName = "места.json";

    /// <summary>Версия формата: чужую читать не берёмся, а говорим об этом.</summary>
    public const int FormatVersion = 1;

    /// <summary>
    /// Вид ручки, который считается местом. Слово берётся у
    /// <see cref="WorkFieldKinds.Cell"/> — там же, где его берёт окно
    /// управления: второй словарь названий разошёлся бы с первым на первой же
    /// новой роли, и узнать об этом было бы неоткуда.
    /// </summary>
    public const string ВидМеста = WorkFieldKinds.Cell;

    private static readonly JsonSerializerOptions Json = new()
    {
        PropertyNameCaseInsensitive = true,
        ReadCommentHandling = JsonCommentHandling.Skip,
        AllowTrailingCommas = true,
        WriteIndented = true,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        Encoder = JavaScriptEncoder.Create(UnicodeRanges.All)
    };

    /// <summary>Что лежит на диске: версия и «сервер → имя ручки → место».</summary>
    private sealed class Файл
    {
        public int Version { get; set; } = FormatVersion;

        public Dictionary<string, Dictionary<string, НазванноеМесто>> Места { get; set; } =
            new(StringComparer.OrdinalIgnoreCase);
    }

    /// <summary>Куда положен файл.</summary>
    public string Path { get; }

    /// <summary>
    /// ЧЕЙ ЭТО МИР. Одни и те же три числа на другом сервере означают другое
    /// место — там дома нет, а есть чужой погреб. Поэтому память разложена по
    /// серверам, и подсказывает она только про свой.
    /// </summary>
    public string Сервер { get; }

    /// <summary>Что случилось с файлом — словами. Молчания тут быть не должно.</summary>
    public event Action<string>? OnLog;

    /// <summary>
    /// КАКИЕ МЕСТА ЭТОТ ЗАПУСК ВИДЕЛ У РОЛИ ЗАПОЛНЕННЫМИ. Живёт в памяти
    /// процесса нарочно: вопрос «а было ли что снимать» — про ЭТОТ запуск, и
    /// записать его в файл значило бы поверить прошлому запуску на слово.
    /// </summary>
    private Dictionary<string, bool> ВиделЖивьём { get; } =
        new(StringComparer.OrdinalIgnoreCase);

    public ПамятьМест(string сервер, string? path = null)
    {
        Сервер = сервер is { Length: > 0 } ? сервер : "неизвестный сервер";
        string p = path is { Length: > 0 } ? path : DefaultFileName;
        Path = System.IO.Path.IsPathRooted(p)
            ? System.IO.Path.GetFullPath(p)
            : System.IO.Path.GetFullPath(System.IO.Path.Combine(BotFolders.State(), p));
    }

    /// <summary>Как назвать сервер одной строкой: «127.0.0.1:42420».</summary>
    public static string ИмяСервера(string? host, int port) =>
        host is { Length: > 0 } h ? $"{h.Trim()}:{port}" : "неизвестный сервер";

    // ---------------- ЧИСТОЕ ПРАВИЛО ----------------

    /// <summary>
    /// ВЕРНУТЬ ЛИ МЕСТО ИЗ ПАМЯТИ — чистое правило: ни файлов, ни ролей, потому
    /// и проверяется стендом. Четыре ответа, и три из них — «не лезь».
    ///
    /// <list type="bullet">
    /// <item>место в ручке ЕСТЬ — оставить: готовый бот старше памяти, его
    /// человек правит руками и ждёт, что послушают именно файл;</item>
    /// <item>памяти нет — оставить: человек про это место ничего не говорил, и
    /// выдумывать ему дом мы не станем;</item>
    /// <item>в памяти «снято» — оставить: человек СНЯЛ место сам, и вернуть его
    /// значило бы спорить с хозяином;</item>
    /// <item>ручка пуста, а человек место называл — вернуть и сказать вслух.</item>
    /// </list>
    /// </summary>
    /// <param name="вРучке">что стоит в ручке роли сейчас (null — пусто)</param>
    /// <param name="память">что человек говорил про это место (null — ничего)</param>
    public static ЧтоСМестом Решение(object? вРучке, НазванноеМесто? память) =>
        вРучке == null && память is { Задано: true } ? ЧтоСМестом.Вернуть : ЧтоСМестом.Оставить;

    /// <summary>
    /// ЧТО СКАЗАТЬ, ВЕРНУВ МЕСТО. Отдельно от самого возврата затем, что слова
    /// эти — половина починки: «опять забыл где склад и дом» человек написал
    /// ровно потому, что бот молча начинал жить без дома. Строка обязана
    /// назвать ИМЯ потерянного, координаты, день и того готового бота, в
    /// котором место было названо.
    /// </summary>
    public static string СловамиОВозврате(string ручка, НазванноеМесто место, string пресет) =>
        $"«{ручка}» {место} взял из своей памяти мест: в готовом боте «{пресет}» этой " +
        $"точки нет, а вы называли её{(место.Когда.Length > 0 ? " " + место.Когда : "")}" +
        $"{(место.Где.Length > 0 && !string.Equals(место.Где, пресет, StringComparison.OrdinalIgnoreCase)
            ? $" в готовом боте «{место.Где}»" : "")}. " +
        "Не то место — задайте его в окне управления или словом в чате, и я запомню новое";

    // ---------------- ЧТЕНИЕ И ЗАПИСЬ ФАЙЛА ----------------

    private Файл Прочитать()
    {
        if (!File.Exists(Path))
            return new Файл();
        try
        {
            var файл = JsonSerializer.Deserialize<Файл>(File.ReadAllText(Path, Encoding.UTF8), Json);
            if (файл == null)
                return new Файл();
            if (файл.Version != FormatVersion)
            {
                OnLog?.Invoke($"память мест {Path} записана в формате {файл.Version}, а я знаю " +
                              $"{FormatVersion} — читать не берусь, начинаю с пустой");
                return new Файл();
            }
            return файл;
        }
        catch (Exception e)
        {
            // Тихий ноль означал бы «человек мне ничего не называл», хотя
            // называл, и файл просто не прочитался
            OnLog?.Invoke($"память мест {Path} не прочиталась ({e.Message}) — начинаю с пустой");
            return new Файл();
        }
    }

    private void Записать(Файл файл)
    {
        try
        {
            System.IO.Directory.CreateDirectory(System.IO.Path.GetDirectoryName(Path)!);
            File.WriteAllText(Path, JsonSerializer.Serialize(файл, Json), new UTF8Encoding(false));
        }
        catch (Exception e)
        {
            OnLog?.Invoke($"память мест НЕ записана ({Path}): {e.Message} — заданное вами " +
                          "переживёт только этот запуск");
        }
    }

    /// <summary>Что человек называл на ЭТОМ сервере. Пусто — ничего не называл.</summary>
    public IReadOnlyDictionary<string, НазванноеМесто> Мои() =>
        Прочитать().Места.TryGetValue(Сервер, out var свои)
            ? свои
            : new Dictionary<string, НазванноеМесто>(StringComparer.OrdinalIgnoreCase);

    // ---------------- ТРИ ДВЕРИ НАРУЖУ ----------------

    /// <summary>
    /// ЗАПОМНИТЬ МЕСТА ЖИВОЙ РОЛИ — ЧЕЛОВЕК КРУТИЛ РУЧКУ САМ. Зовётся тем же
    /// единственным записывающим, каким пишутся ручки
    /// (<see cref="PresetLibrary.ЗапомнитьРучки"/>), — то есть и из окна
    /// управления, и из «!дом тут», и из «!склад тут».
    ///
    /// ПУСТАЯ РУЧКА ЗДЕСЬ — ЭТО СЛОВО «СНЯЛ», и оно записывается: иначе
    /// «убрать склад» стало бы невозможным действием, бот подставлял бы его
    /// обратно каждый запуск, и спорить с ним было бы нечем.
    /// </summary>
    /// <param name="роль">живая роль — с неё и снимаются места</param>
    /// <param name="пресет">в каком готовом боте это сказано</param>
    public IReadOnlyList<string> Запомнить(BotRole роль, string пресет) =>
        СнятьИЗаписать(роль, пресет, снятиеЭтоСлово: true);

    /// <summary>
    /// ПОДОБРАТЬ МЕСТА, УЖЕ ЛЕЖАЩИЕ В ГОТОВОМ БОТЕ, — ЧТОБЫ ПОЧИНКА РАБОТАЛА С
    /// ПЕРВОГО ЗАПУСКА, А НЕ СО ВТОРОГО.
    ///
    /// Живой случай ровно про это: у заказчика дом и склад УЖЕ вписаны в
    /// готовых ботов («digger», «resident»), а памяти мест ещё нет — она
    /// заведётся только когда он в следующий раз тронет ручку. До тех пор
    /// смена готового бота унесла бы дом в третий раз. Место, вписанное в
    /// пресет, тоже сказано человеком — значит его надо подобрать.
    ///
    /// ПУСТАЯ РУЧКА ЗДЕСЬ НЕ ЗНАЧИТ «СНЯЛ», и это главное отличие от
    /// <see cref="Запомнить"/>: она значит «этот готовый бот такого места не
    /// называет». Запиши мы её как снятие — первый же запуск на «resident»
    /// стирал бы память о доме, и починка отменяла бы сама себя.
    /// </summary>
    public IReadOnlyList<string> Подобрать(BotRole роль, string пресет) =>
        СнятьИЗаписать(роль, пресет, снятиеЭтоСлово: false);

    /// <param name="снятиеЭтоСлово">
    /// пустая ручка — это «человек снял место» (правда для поворота ручки) или
    /// «этот готовый бот места не называет» (правда для сборки роли)
    /// </param>
    private IReadOnlyList<string> СнятьИЗаписать(BotRole роль, string пресет, bool снятиеЭтоСлово)
    {
        var сказать = new List<string>();
        var файл = Прочитать();
        if (!файл.Места.TryGetValue(Сервер, out var свои))
            файл.Места[Сервер] = свои = new Dictionary<string, НазванноеМесто>(
                StringComparer.OrdinalIgnoreCase);

        bool менялось = false;
        foreach (var ручка in RoleKnobs.Of(роль))
        {
            if (ручка.Kind != ВидМеста)
                continue;

            // ДОГАДКА БОТА — НЕ «ЧТО ЧЕЛОВЕК НАЗВАЛ», а память хранит именно
            // названное человеком. Самопоиск склада при входе в мир кладёт в
            // ручку ближний сундук (может быть и чужой, соседский), и попади он
            // сюда — пережил бы смену готового бота и перезапуск, то есть
            // навсегда. Пометку ставит и снимает одно место
            // (BotRole.ПометитьДогадку), и второго правила «чьё это значение»
            // в проекте нет: тот же вопрос задаёт себе и пресет.
            //
            // МИМО «ВиделЖивьём» НАРОЧНО: не увидев догадку, память не сочтёт
            // потом пустую ручку словом «снял» — снимать можно лишь то, что
            // человек ставил
            if (роль.ЭтоДогадкаБота(ручка.Name))
                continue;

            var стало = Разобрать(ручка.Value);
            стало.Координаты = Panel.PanelSettings.CoordsOf(RoleKnobs.TypeOf(роль, ручка.Name));

            if (стало.Задано)
            {
                // ВИДЕЛ ЖИВЬЁМ. Только это и отличает потом «человек снял» от
                // «этой роли такого места не давали» — см. ниже
                ВиделЖивьём[ручка.Name] = true;
            }
            else if (!снятиеЭтоСлово || !ВиделЖивьём.ContainsKey(ручка.Name))
            {
                // ПУСТАЯ РУЧКА — ЭТО «СНЯЛ» ТОЛЬКО ТОГДА, КОГДА БЫЛО ЧТО СНИМАТЬ.
                //
                // ЧЕМ ЭТО БЫЛО ПЛОХО ДО 28.08 И КАК ЛОВИЛОСЬ. Единственный
                // записывающий зовётся на ЛЮБОЙ поворот ЛЮБОЙ ручки и обходит
                // ВСЕ клетки роли. Значит запуск без готового бота («preset» в
                // заводском bot.json нет вовсе) шёл так: человек сказал «!дом
                // тут» — записалось; следующий запуск поднял роль с пустой
                // ручкой; человек повернул громкость чата — и память пометила
                // «Дом снято», а снятое не возвращается никогда. Дом терялся
                // ИМЕННО памятью, которой без неё не было.
                //
                // Мерка «видел живьём» честна ровно потому, что живёт один
                // запуск: снять место можно только там, где оно перед этим
                // стояло, а стоять оно могло только в этом же запуске — его
                // туда положил либо готовый бот, либо возврат из памяти
                // (см. Подсказать), либо сам человек минуту назад
                continue;
            }

            свои.TryGetValue(ручка.Name, out var было);

            // ТО ЖЕ САМОЕ — МОЛЧА И БЕЗ ЗАПИСИ. Иначе файл переписывался бы на
            // каждый поворот громкости чата
            if (было != null && было.Задано == стало.Задано &&
                было.X == стало.X && было.Y == стало.Y && было.Z == стало.Z &&
                string.Equals(было.Координаты, стало.Координаты, StringComparison.Ordinal))
                continue;

            стало.Когда = DateTime.Now.ToString("dd.MM в HH:mm");
            стало.Где = пресет;
            свои[ручка.Name] = стало;
            менялось = true;
            сказать.Add(стало.Задано
                ? $"запомнил «{ручка.Name}» {стало} — переживёт смену готового бота и перезапуск"
                : $"«{ручка.Name}» вы сняли — из памяти мест тоже убрал, назад подставлять не буду");
        }

        if (менялось)
            Записать(файл);
        return сказать;
    }

    /// <summary>
    /// ВЕРНУТЬ В ПУСТЫЕ РУЧКИ ТО, ЧТО ЧЕЛОВЕК УЖЕ НАЗЫВАЛ, И СКАЗАТЬ ОБ ЭТОМ.
    /// Зовётся сразу после сборки роли из готового бота и после горячего
    /// наката пресета — то есть везде, где место могло пропасть.
    /// </summary>
    /// <param name="роль">роль, только что собранная</param>
    /// <param name="пресет">имя готового бота — оно идёт в слова человеку</param>
    public IReadOnlyList<string> Подсказать(BotRole роль, string пресет)
    {
        var сказать = new List<string>();
        var свои = Мои();
        if (свои.Count == 0)
            return сказать;

        foreach (var ручка in RoleKnobs.Of(роль))
        {
            if (ручка.Kind != ВидМеста)
                continue;
            свои.TryGetValue(ручка.Name, out var память);
            if (Решение(ручка.Value, память) != ЧтоСМестом.Вернуть)
                continue;

            // ЧУЖИЕ КООРДИНАТЫ НЕ ПОДСТАВЛЯЕМ, А НАЗЫВАЕМ. Вид у обеих клеток
            // один, а числа разные: подставь мировые в игровую ручку — и бот
            // уйдёт за полмиллиона блоков, ровно как терялся склад. Пустая
            // запись «Координаты» — это память до 28.08: она системы не знала,
            // и молчаливо верить ей нельзя тоже
            string нужны = Panel.PanelSettings.CoordsOf(RoleKnobs.TypeOf(роль, ручка.Name));
            if (!string.Equals(память!.Координаты, нужны, StringComparison.Ordinal))
            {
                сказать.Add($"«{ручка.Name}» {память} из памяти мест НЕ вернул: там записаны " +
                            $"{(память.Координаты.Length > 0 ? память.Координаты : "неизвестно какие")} " +
                            $"координаты, а этой роли нужны {(нужны.Length > 0 ? нужны : "неизвестно какие")}. " +
                            "Одни и те же три числа в разных координатах — это разные места; " +
                            "задайте точку заново в окне управления или словом в чате");
                continue;
            }

            string? жалоба = RoleKnobs.Set(роль, ручка.Name,
                new { x = память.X, y = память.Y, z = память.Z });
            // Молчаливый отказ вернуть дом неотличим от «дома не было» —
            // человек второй вечер подряд вписывал бы одно и то же
            if (жалоба == null)
            {
                // Вернули — значит место в ручке ЕСТЬ, и снять его теперь можно
                ВиделЖивьём[ручка.Name] = true;
                сказать.Add(СловамиОВозврате(ручка.Name, память, пресет));
            }
            else
            {
                сказать.Add($"«{ручка.Name}» {память} из памяти мест вернуть НЕ вышло: {жалоба}");
            }
        }
        return сказать;
    }

    /// <summary>
    /// ЧТО ЧЕЛОВЕК НАЗЫВАЛ, А ЭТА РОЛЬ НЕ НЕСЁТ — ИМЕНЕМ ПОТЕРЯННОГО.
    ///
    /// Спрашивается у ПАМЯТИ, а не у ручек роли, и это не мелочь: роль может
    /// не нести ручки, которую человек называл, — и обход по ручкам роли о
    /// пропавшем месте промолчал бы, то есть ровно там, где человек и заметил
    /// бы пропажу. (Улика, на которой это писалось: до 29.08 ручки «Склад» не
    /// было у стражника вовсе. Теперь «Склад» и «Дом» есть у всякой живущей
    /// роли, но правило от этого не устарело: своих точек у ролей хватает —
    /// «Пост» есть только у стражника.)
    ///
    /// Живой случай: у заказчика дом и склад лежат в готовом боте «digger», а
    /// поднялся «resident». Дом с этой ролью возвращается сам
    /// (<see cref="Подсказать"/>), но роль без такой ручки принять его не может
    /// — и тогда единственное, что честно, это назвать вслух, ЧТО потеряно и
    /// откуда оно взялось. Молчание здесь неотличимо от «вы этого не задавали».
    ///
    /// Пусто — сказать нечего, и придумывать не будем.
    /// </summary>
    public IReadOnlyList<string> ЧегоНеХватает(BotRole роль)
    {
        var сказать = new List<string>();
        var ручки = RoleKnobs.Of(роль).ToDictionary(k => k.Name, StringComparer.OrdinalIgnoreCase);
        foreach (var (имя, память) in Мои())
        {
            if (!память.Задано)
                continue;
            if (ручки.TryGetValue(имя, out var ручка))
            {
                if (ручка.Value != null)
                    continue;                     // место на месте — жаловаться не на что
                сказать.Add($"«{имя}» {память} у меня сейчас не задано, хотя вы называли эту " +
                            $"точку{(память.Когда.Length > 0 ? " " + память.Когда : "")} в " +
                            $"готовом боте «{память.Где}»");
                continue;
            }
            сказать.Add($"«{имя}» {память} вы называли в готовом боте «{память.Где}», а у роли " +
                        $"«{роль.Name}» такой настройки нет вовсе — здесь эта точка не работает");
        }
        return сказать;
    }

    /// <summary>
    /// Клетка, как её отдаёт <see cref="RoleKnobs.Of"/>: безымянный объект
    /// {x,y,z} или null. Разбираем ЗАПИСЬЮ — тип этого объекта библиотеке
    /// не принадлежит, и ловить его отражением значило бы завести вторую
    /// правду о том, как выглядит клетка.
    /// </summary>
    private static НазванноеМесто Разобрать(object? значение)
    {
        if (значение == null)
            return new НазванноеМесто();
        try
        {
            var место = JsonSerializer.Deserialize<НазванноеМесто>(
                JsonSerializer.Serialize(значение, Json), Json);
            return место ?? new НазванноеМесто();
        }
        catch
        {
            return new НазванноеМесто();
        }
    }
