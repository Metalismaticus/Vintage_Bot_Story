    /// <summary>Сколько такого материала в сумках.</summary>
    private int Have(string code) => ctx.Hands.CountOf(code);

    /// <summary>
    /// Блок игры по коду — терпимо к домену, но БЕЗ ПЕРЕБОРА РЕЕСТРА.
    ///
    /// Реестр блоков и реестр рецептов приходят разными пакетами и зовут одно
    /// и то же то «stonepath-free», то «game:stonepath-free». Три обращения к
    /// словарю закрывают оба написания за постоянное время.
    ///
    /// Перебора здесь быть не может: этот вопрос задаётся про КАЖДЫЙ рецепт
    /// сервера, а их тысячи. Поиск подстрокой по всем кодам блоков превратил
    /// бы разбор рецептов в секунды глухого ожидания на ровном месте — и это
    /// на глазах у человека, который просто попросил дорогу.
    /// </summary>
    private Vintagestory.API.Common.Block? GameBlock(string code)
    {
        if (ctx.World.GetGameBlockByCode(code) is { BlockId: > 0 } exact)
            return exact;
        string bare = RoadPlan.ShortCode(code);
        if (!string.Equals(bare, code, StringComparison.Ordinal) &&
            ctx.World.GetGameBlockByCode(bare) is { BlockId: > 0 } stripped)
            return stripped;
        return ctx.World.GetGameBlockByCode("game:" + bare) is { BlockId: > 0 } prefixed
            ? prefixed
            : null;
    }

    /// <summary>
    /// Коробки коллизии блока из реестра сервера. null — блок вовсе без
    /// коллизии (трава, цветок, деревянная дорожка поверх пола): полотном
    /// такое не бывает.
    /// </summary>
    private static IReadOnlyList<BlockBox>? BoxesOf(Vintagestory.API.Common.Block? block)
    {
        if (block?.CollisionBoxes is not { Length: > 0 } src)
            return null;
        var boxes = new BlockBox[src.Length];
        for (int i = 0; i < src.Length; i++)
            boxes[i] = new BlockBox(src[i].X1, src[i].Y1, src[i].Z1, src[i].X2, src[i].Y2, src[i].Z2);
        return boxes;
    }

    /// <summary>
    /// Что реестр игры говорит про блок как про покрытие: материал, множитель
    /// хода, форма — и вывод, годится ли он под ноги. null — сервер такого
    /// блока не знает.
    /// </summary>
    public RoadPlan.SurfaceOption? Describe(string code, int count = 0)
    {
        if (GameBlock(code) is not { BlockId: > 0 } block)
            return null;
        string known = ctx.World.BlockIdToCode(block.BlockId) ?? code;
        return new RoadPlan.SurfaceOption(known, count, block.BlockMaterial,
            block.WalkSpeedMultiplier,
            RoadPlan.JudgeSurface(known, block.BlockMaterial, block.WalkSpeedMultiplier,
                BoxesOf(block), ctx.Metal?.MetalInside(known) ?? false));
    }

    /// <summary>Что лежит в сумках блоками: код и сколько штук.</summary>
    private List<(string Code, int Count)> BlocksInBags() =>
        ctx.Self.CarrySlots()
            .Where(s => !s.Content.IsEmpty && s.Content.Code is { } c &&
                        ctx.World.GetGameBlockByCode(c) is { BlockId: > 0 } &&
                        // Инструмент в полотно не кладут: прочность есть — не блок под ноги
                        ctx.World.Durability(c) == 0)
            .GroupBy(s => s.Content.Code!)
            .Select(g => (Code: g.Key, Count: g.Sum(s => s.Content.Count)))
            .ToList();

    /// <summary>
    /// Лучшее покрытие ИЗ СУМОК со всем, что о нём знает реестр. null — годного
    /// в сумках нет.
    /// </summary>
    public RoadPlan.SurfaceOption? BestInBags() =>
        RoadPlan.BestSurface(BlocksInBags()
            .Where(t => t.Count > KeepInReserve)
            .Select(t => Describe(t.Code, t.Count))
            .OfType<RoadPlan.SurfaceOption>());

    // ЧЕМ МОСТИТЬ — СПРАШИВАЮТ У EnsureSurfaceAsync, И ТОЛЬКО У НЕЁ.
    // Здесь стоял её мёртвый двойник ChooseMaterial: та же цепочка «названо
    // настройкой → годно ли → хватает ли → лучшее из сумок», только без двух
    // последних шагов (сделать по рецепту, сходить за материалом). Не звал его
    // НИКТО — ни укладка, ни панель, ни стенды, — и это худший вид второй
    // копии: она не спорит с живой сегодня, потому что её не спрашивают, а
    // завтра кто-нибудь возьмёт короткую и получит «мостить нечем» там, где
    // настоящая дорога сходила бы за покрытием.

    /// <summary>
    /// ЧТО ЧЕЛОВЕК НАЗВАЛ НАСТРОЙКОЙ — разобранное тем же реестром, что и всё
    /// прочее. null — сервер такого блока не знает и в сумках его нет: сказать
    /// о нём нечего, и мешать человеку мы не станем.
    ///
    /// Код бывает КУСКОМ. По всей библиотеке материал зовут коротко
    /// («stonepath»), а сервер зовёт его полным именем («stonepath-free»), и
    /// сумки ищут вхождением. Спросить реестр в лоб мало: точного такого кода
    /// в нём нет — поэтому, не найдя точного, смотрим, что под этот кусок
    /// подходит в сумках.
    ///
    /// ЗАЧЕМ ВООБЩЕ СПРАШИВАТЬ. Названное настройкой шло в полотно БЕЗ ЕДИНОЙ
    /// ПРОВЕРКИ — это была дыра ровно в том законе, ради которого написан весь
    /// разбор покрытия: «руду в полотно НИКОГДА». Строка «ore-poor-nativecopper»
    /// в поле настройки означала дорогу из медной руды, и никакой стенд бы
    /// этого не поймал.
    /// </summary>
    public RoadPlan.SurfaceOption? Named(string mask)
    {
        if (mask.Length == 0)
            return null;
        if (Describe(mask) is { } exact)
            return exact;
        foreach (var (code, count) in BlocksInBags())
            if (code.Contains(mask, StringComparison.OrdinalIgnoreCase) &&
                Describe(code, count) is { } found)
                return found;
        return null;
    }

    /// <summary>
    /// Почему названное настройкой в полотно не годится — словами, а не
    /// перечислением. Человек написал код сам и обязан узнать, чем он не
    /// подошёл, иначе поле выглядит сломанным.
    /// </summary>
    private static string WhyUnfit(RoadPlan.SurfaceOption what) => what.Fit switch
    {
        RoadPlan.SurfaceFit.Precious =>
            $"{what.Code} — это ценное ({what.Material}), а ценное в полотно не кладут никогда",
        _ => $"{what.Code} ({what.Material}) полотном не бывает: под ноги нужен сплошной пол " +
             "на всю клетку, а это не он"
    };

    // Разобранный реестр рецептов: рецептов тысячи, а нужен он ровно дважды за
    // дорогу — перебирать их на каждый ряд незачем
    private List<RoadPlan.SurfaceOption>? roadRecipes;
    private List<string>? slabRecipes;

    private void ForgetRecipes()
    {
        roadRecipes = null;
        slabRecipes = null;
    }

    /// <summary>
    /// ЧТО В ЭТОМ МИРЕ СЧИТАЕТСЯ ДОРОГОЙ И ЧТО ИЗ ЭТОГО МОЖНО СДЕЛАТЬ.
    ///
    /// Спрашиваем реестр рецептов сервера, а не свой список кодов: «дорожное»
    /// здесь значит «игра сама сказала, что по нему ходят быстрее»
    /// (WalkSpeedMultiplier > 1). В ванильной игре так находится каменная
    /// дорожка — четыре камня и земля, ровно то, чего у копателя навалом.
    /// В мире с модами найдётся то, что дорогой считают там, и ни строчки
    /// править не придётся.
    ///
    /// Живой случай: заказчик сказал «дороги он не крафтил», а бот в ту же
    /// минуту мостил медной рудой и писал «быстрых блоков нет» — искал их
    /// только в сумках.
    /// </summary>
    public IReadOnlyList<RoadPlan.SurfaceOption> CraftableRoads()
    {
        if (roadRecipes != null)
            return roadRecipes;
        roadRecipes = [];
        if (ctx.Crafting is not { Ready: true } crafting)
            return roadRecipes;
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var recipe in crafting.All)
            if (seen.Add(recipe.OutputCode) &&
                Describe(recipe.OutputCode) is { Fit: RoadPlan.SurfaceFit.Road } road)
                roadRecipes.Add(road);
        roadRecipes.Sort((a, b) => b.WalkSpeed.CompareTo(a.WalkSpeed));
        return roadRecipes;
    }

    /// <summary>
    /// Полублоки этого мира, которые вообще делаются по рецепту. Быстрые
    /// впереди: лесенка из дорожного камня лучше лесенки из земли.
    ///
    /// ИГРОВЫХ СТУПЕНЕЙ ЗДЕСЬ НЕТ И БЫТЬ НЕ МОЖЕТ. Раньше тот же перебор умел
    /// искать и их (<see cref="RoadPlan.LooksLikeStair"/>), и заказчик поймал
    /// это в крафте: бот писал «беру полублоками», а делал ступени дороги.
    /// Ступенька теперь складывается из блока покрытия и полублока на нём —
    /// значит и рецепт нужен ровно один, на полублок.
    /// </summary>
    private List<string> SlabRecipes()
    {
        if (slabRecipes is { } cached)
            return cached;
        var found = new List<(string Code, float Speed)>();
        if (ctx.Crafting is { Ready: true } crafting)
        {
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var recipe in crafting.All)
            {
                if (!seen.Add(recipe.OutputCode) ||
                    GameBlock(recipe.OutputCode) is not { BlockId: > 0 } block)
                    continue;
                string code = ctx.World.BlockIdToCode(block.BlockId) ?? recipe.OutputCode;
                if (!GoodSlab(code, block))
                    continue;
                found.Add((code, block.WalkSpeedMultiplier));
            }
        }
        found.Sort((a, b) => b.Speed.CompareTo(a.Speed));
        slabRecipes = found.Select(t => t.Code).ToList();
        return slabRecipes;
    }

    /// <summary>
    /// Годится ли блок в ВЕРХ СТУПЕНЬКИ. Спрашиваем реестр: материал, ценность
    /// и форму коробок.
    ///
    /// Игровая ступень отсеивается ОТДЕЛЬНОЙ СТРОКОЙ, хотя формально её и так
    /// не пропустил бы <see cref="RoadPlan.LooksLikeSlab"/> (у ступени две
    /// коробки, а у полублока одна). Строка стоит нарочно: «ступень — не
    /// полублок» это решение, а не побочное следствие счёта коробок, и молча
    /// опираться на такое следствие нельзя — заказчик уже получил в крафте
    /// ступени вместо полублоков.
    /// </summary>
    private bool GoodSlab(string code, Vintagestory.API.Common.Block block)
    {
        // Снежный настил тоже «полкуба», но лесенка из него растает к полудню.
        // «Ценное» спрашивает реестр (Metals.MetalInside): метеоритом дорогу
        // не мостят, хотя материал у него самый каменный
        if (RoadPlan.IsPrecious(block.BlockMaterial, ctx.Metal?.MetalInside(code) ?? false) ||
            !RoadPlan.IsSurfaceMaterial(block.BlockMaterial) ||
            BoxesOf(block) is not { } boxes)
            return false;
        return !RoadPlan.LooksLikeStair(boxes) && RoadPlan.LooksLikeSlab(boxes);
    }

    /// <summary>Полублок из сумок (или тот, что назвали). null — нет ни одного.</summary>
    public string? ChooseSlab()
    {
        if (SlabCode.Length > 0)
            // Названное проверяем ФОРМОЙ из реестра: не полублок наверху
            // ступеньки — это подъём в целый блок, на который без прыжка не
            // всходят, то есть дорога, по которой не пройти
            return Have(SlabCode) > 0 && NamedSlabIsSlab() ? SlabCode : null;
        foreach (var (code, count) in BlocksInBags().OrderByDescending(t => t.Count))
            if (count > 0 && GameBlock(code) is { BlockId: > 0 } block && GoodSlab(code, block))
                return code;
        return null;
    }

    /// <summary>
    /// Полублок ли то, что назвали настройкой. Реестр такого блока не знает —
    /// не спорим: настройку человек мог написать куском кода, и о неизвестном
    /// честнее промолчать, чем отказать.
    /// </summary>
    private bool NamedSlabIsSlab() =>
        GameBlock(SlabCode) is not { BlockId: > 0 } named || GoodSlab(SlabCode, named);

    /// <summary>Можно ли сделать это прямо сейчас (рецепт есть и материалы есть).</summary>
    private bool CanMake(string code) =>
        MayCraft && ctx.Crafting is { Ready: true } crafting && crafting.CanCraft(code);

    /// <summary>
    /// Полублок, который БУДЕТ сделан по рецепту прямо сейчас. null — нечего
    /// или не из чего.
    ///
    /// Нужен ровно для того, чтобы журнал на выходе назвал КОД, а не отделался
    /// словом «полублоками»: жалоба заказчика была именно о расхождении слова
    /// и дела.
    /// </summary>
    private string? SlabToMake()
    {
        if (!MayCraft)
            return null;
        if (SlabCode.Length > 0)
            return CanMake(SlabCode) ? SlabCode : null;
        return SlabRecipes().FirstOrDefault(CanMake);
    }

    /// <summary>
    /// Почему этого не сделать — по фактам реестра, а не «не вышло».
    ///
    /// Спрашиваем <c>Crafting.Shortfall</c>, а не первый попавшийся рецепт.
    /// Живой случай 16.08: «на дорожное (stonepath-free) не хватает:
    /// stone-meteorite-iron (надо 4, есть 0)» — сервер разворачивает рецепт на
    /// каждую породу, а здесь брался recipes[0], то есть порядок реестра.
    /// Метеоритным железом дорогу не мостят, и рейс за ним был бы впустую.
    /// </summary>
    private string WhyCannotMake(string code)
    {
        if (ctx.Crafting is not { Ready: true } crafting)
            return "реестр рецептов сервера ещё не пришёл";
        var рецепты = crafting.RecipesFor(code);
        if (рецепты.Count == 0)
            return $"рецепта на {code} в этом мире нет";

        // ВСЕ РЕЦЕПТЫ ЗАПЕРТЫ ЧЕРТОЙ КЛАССА — ОТКАЗ ОБЯЗАН НАЗВАТЬ ЧЕРТУ.
        //
        // ПРИЁМКА 27.08, НАХОДКА 9. Здесь спрашивался сырой RecipesFor (черты
        // не знает), а Shortfall для целиком запертого кода отвечает ПУСТЫМ
        // списком — и отказ выходил немым: «{code} сделать не вышло». Немой
        // отказ запрещён законом 4: человек обязан узнать, что повернуть.
        // В ванилле дорожных материалов с чертой нет, но комментарий в
        // Crafting объявлял дорогу починенной этой же правкой — а она была
        // починена наполовину.
        if (рецепты.All(Crafting.LockedByTrait))
        {
            var черты = string.Join(", ", рецепты
                .Select(r => r.RequiresTrait).Where(t => t is { Length: > 0 }).Distinct());
            return $"{code} требует черту класса ({черты}) — своего класса я не знаю, " +
                   "и сервер такой сбор не примет";
        }

        var lack = crafting.Shortfall(code)
            .Select(m => $"{m.Code} (надо {m.Need}, есть {m.Have})")
            .ToList();
        return lack.Count > 0
            ? $"на {code} не хватает: {string.Join(", ", lack)}"
            : $"{code} сделать не вышло";
    }

    /// <summary>
    /// Сделать по рецепту целый стак — и сказать вслух, что вышло.
    /// </summary>
    /// <param name="supply">
    /// РАЗРЕШИТЬ СХОДИТЬ ЗА МАТЕРИАЛОМ. Без этого дорога и вставала: гейт
    /// <see cref="CanMake"/> спрашивает «хватает ли материала ПРЯМО СЕЙЧАС», и
    /// на «нет» бот молча не звал крафт вовсе — а крафт умеет снабжение
    /// (<see cref="Crafting.RestockAsync"/>), и до него дело не доходило.
    /// Живой прогон 16.08: «мостить нечем: блоков в сумках нет вовсе», и
    /// полминуты спустя опись насчитала в шестнадцати сундуках 1023 предмета.
    /// </param>
    private async Task<bool> MakeAsync(string code, CancellationToken ct, bool supply = false)
    {
        if (!MayCraft || ctx.Crafting is not { Ready: true } crafting)
            return false;
        if (!supply && !crafting.CanCraft(code))
            return false;
        // Рецепта нет вовсе — идти некуда и незачем, и снабжение тут не поможет
        if (crafting.RecipesFor(code).Count == 0)
            return false;

        int want = Math.Max(1, ctx.World.MaxStackSize(code));
        OnLog?.Invoke($"делаю {code} по рецепту — до {want} шт." +
                      (supply && !crafting.CanCraft(code)
                          ? "; материала в сумках нет — снабжение поищет его на складе, дома и рядом"
                          : ""));
        var made = await crafting.CraftAsync(code, want, ct);
        if (made.Crafted > 0)
        {
            OnLog?.Invoke($"сделал {code} ×{made.Crafted}");
            return true;
        }
        OnLog?.Invoke($"{code} сделать не вышло: {made.Message}");
        return false;
    }

    /// <summary>
    /// МОЖНО ЛИ ИДТИ ЗА ПОКРЫТИЕМ ПРЯМО СЕЙЧАС. ЧИСТОЕ ПРАВИЛО, и оно про
    /// МЕТАНИЯ МЕЖДУ ДОМОМ И СТРОЙКОЙ.
    ///
    /// ЖИВОЙ СЛУЧАЙ, слова заказчика: «допустим дал ему задачу дорогу делать, а
    /// он метался между домом и строительством, хотел что-то сделать, возможно
    /// недостающие инструменты». В журнале это выглядит так: дорога кладёт
    /// полотно, покрытие кончается ПОСРЕДИ РЯДА — и <c>LayAsync</c> зовёт
    /// снабжение, которое уводит бота домой к сундукам. Бот возвращается,
    /// кладёт ещё стопку (сколько влезло — <c>MaxStackSize</c>), покрытие
    /// кончается снова — и он идёт домой снова. Потолка у таких рейсов не было
    /// НИКАКОГО: сколько стопок нужно на сто клеток полотна, столько раз бот и
    /// сходит туда-обратно.
    ///
    /// ПРАВИЛО: рейс делается ОДИН РАЗ — ДО начала работы, когда полотно ещё не
    /// начато и бросать нечего. Кончилось посреди ряда — сперва сделать ещё по
    /// рецепту НЕ СХОДЯ С МЕСТА (это дёшево, порода у копателя своя), потом
    /// перейти на другое годное покрытие, а нет ни того ни другого — ЧЕСТНО
    /// ВСТАТЬ и назвать нехватку. Встать посреди дороги не стыдно: остаток
    /// домостит ОЧЕРЕДЬ ЗАДАЧ — она сходит за материалом СВОИМ рейсом между
    /// заходами и зовёт дорогу доделывать с того места, где та встала
    /// (<c>WorkRunner.HomeForMaterialAsync</c>, и потолок рейсов есть там).
    /// Стыдно бросить начатое полотно и уйти.
    ///
    /// СПАСИТЕЛЬ ЗДЕСЬ ОДИН, А НЕ ДВА, И ПРЕЖДЕ ТУТ СТОЯЛА ЛОЖЬ. Строка
    /// обещала, что остаток домостит «либо возврат (<see cref="RoadResume"/>),
    /// либо очередь» — но возврат за нехватку материала не берётся НИКОГДА, и
    /// отменяет это обещание тот же самый файл: <see cref="WhatStopped"/>
    /// переводит <see cref="RoadStop.NoMaterial"/> в <c>Setback.NoMaterial</c>,
    /// а <c>Resume.Passing</c> на этом слове повтор ЗАПРЕЩАЕТ — «кончился
    /// материал — сам он не заведётся». Так и задумано: помеха, которая не
    /// проходит сама, за пять секунд ожидания не пройдёт, и второй заход встал
    /// бы на том же ряду, заплатив полную цену первого.
    ///
    /// ЧТО ОТСЮДА СЛЕДУЕТ ДЛЯ ЧЕЛОВЕКА. Дорога, пущенная БЕЗ очереди задач,
    /// после нехватки покрытия не доделается сама ничем: рейс ей запрещён
    /// правилом выше, повтор — правилом помех. Она честно встанет и назовёт
    /// нехватку, а остаток ждёт человека или очереди. Третьего ответа —
    /// «сходи, устрани причину и вернись» — у механизма помех сегодня нет, и
    /// обещать его здесь нельзя.
    ///
    /// Кому этот порядок не годится (дом в двух шагах от стройки), включает
    /// <see cref="MaySupplyMidRoad"/> и получает прежнее поведение.
    ///
    /// «НАЧАТАЯ РАБОТА» — ЭТО НЕ ТОЛЬКО ПОЛОЖЕННОЕ ПОЛОТНО, НО И ВЫКОПАННЫЙ
    /// ХОД. При «сперва копать» бот сначала проходит весь ход и только потом
    /// спрашивает, чем его мостить; полотна в эту секунду ноль клеток, а
    /// брошено будет всё равно многое — сам ход и место, где бот в нём стоит.
    /// Живой прогон 29.08: полный рейс из этой точки увёл бота домой, и отказ
    /// лёг строкой «ход выкопан (1 кл. выемки), а мостить всё равно нечем…
    /// остановка на (60, 110, 280)» — у дома, а не в ходе. Поэтому второй
    /// вопрос о покрытии (<c>BuildAsync</c>, после проходки) идёт сюда с
    /// <c>midRoad: true</c>.
    /// </summary>
    /// <param name="midRoad">Рейс посреди начатой работы, а не до неё.</param>
    /// <param name="mayLeaveWork">Разрешено ли бросать полотно ради рейса.</param>
    public static bool MaySupply(bool midRoad, bool mayLeaveWork) => !midRoad || mayLeaveWork;

    /// <summary>
    /// ПОЧЕМУ НЕ ПОШЁЛ — словами, и с именем ручки. Молчание тут человек
    /// читает как «бот поленился»: он-то знает, что камня дома два сундука.
    /// </summary>
    public static string WhyNoSupply(string knob) =>
        "за покрытием посреди полотна домой не бегу — начатую дорогу бросать нельзя " +
        $"(ручка «{knob}»); доделаю тем, что сделаю на месте, или встану и назову нехватку";

    /// <summary>
    /// СХОДИТЬ ЗА ПОКРЫТИЕМ — ДВЕРЬ К ЕДИНОМУ СНАБЖЕНИЮ, а не второй его
    /// экземпляр. Дорога здесь только называет, чего ей не хватает; сумки,
    /// склад этой работы, дом, крафт и добычу рядом перебирает
    /// <see cref="Supply.GetAsync"/> — тот же самый, каким снаряжаются факелы и
    /// инструменты.
    ///
    /// Просим ГОТОВОЕ ПОКРЫТИЕ, а не его составляющие, и это нарочно: в
    /// сундуке дома дорожный камень лежит и целым, а если его там нет —
    /// снабжение само дойдёт до звена «крафт» и спросит уже составляющие.
    /// </summary>
    /// <param name="midRoad">
    /// Рейс ПОСРЕДИ ПОЛОТНА, а не до начала работы. Разница не в дороге, а в
    /// цене: см. <see cref="MaySupplyMidRoad"/>.
    /// </param>
    private async Task<(bool Got, string Why)> FetchSurfaceAsync(string code, CancellationToken ct,
        bool midRoad = false)
    {
        if (!MaySupply(midRoad, MaySupplyMidRoad))
            return (false, WhyNoSupply(Knobs.MidRoadSupply));
        if (ctx.Supply is not { } supply)
            return (false, "снабжение к боту не подключено — искать материал некому");
        int want = Math.Max(1, ctx.World.MaxStackSize(code));
        // ГОТОВОЕ ПОКРЫТИЕ В МИРЕ НЕ ВЫКАПЫВАЕМ. «Добыть рядом дорожный
        // камень» означает разобрать чью-то дорогу — а то и своё же вчерашнее
        // полотно, которое бот только что положил. Составляющие (камень, землю)
        // копать можно, и их спросит вложенный вызов из крафта
        OnLog?.Invoke($"ищу покрытие {code}: в сумках, на складе этой работы, дома и по рецепту. " +
                      "Готовое покрытие в мире не выкапываю — это разбирать чужую дорогу");
        var поиск = await supply.GetAsync([(code, want, Have(code))], ct: ct, nearby: false);
        OnLog?.Invoke($"покрытие {code}: {поиск.Reason}");
        return (Have(code) > KeepInReserve, поиск.Reason);
    }

    // ---------------- правила захода ----------------

    /// <summary>
    /// Сколько рядов полотна кладём за ОДИН заход. Меньше одного не бывает:
    /// заход, кладущий ноль рядов, это вечный цикл, а не бережливость.
    /// </summary>
    public static int RowsPerRun(int rows, int width, int maxCells)
    {
        int w = Math.Max(1, width);
        return rows * w <= maxCells ? rows : Math.Max(1, maxCells / w);
    }

    /// <summary>
    /// ЧЕМ КОНЧИЛСЯ ЗАХОД. Дошли до конца ЗАХОДА — это ещё не дошли до конца
    /// ДОРОГИ: полотно длиннее <see cref="MaxCells"/> кладётся в несколько
    /// вызовов, а отчитывалось полным успехом. Очередь по Success ставила
    /// задаче «сделано» и шла дальше, и утром человек видел зелёную очередь
    /// и дорогу в треть длины.
    /// </summary>
    public static (RoadStop Stop, string Reason) JudgeRun(RoadStop stop, string reason,
        int rowsDone, int wholeRows, int maxCells)
    {
        if (stop != RoadStop.Done || rowsDone >= wholeRows)
            return (stop, reason);
        return (RoadStop.Unfinished,
            $"за заход положено {rowsDone} рядов из {wholeRows} (потолок {maxCells} кл. " +
            "на вызов) — остаток кладу следующим заходом");
    }

    /// <summary>
    /// ПОМЕХА ВРЕМЕННАЯ ИЛИ ПОСТОЯННАЯ — СЛОВАМИ ДОРОГИ, ПЕРЕВЕДЁННЫМИ В ОБЩИЕ
    /// (<see cref="Setback"/>). ЧИСТОЕ ПРАВИЛО.
    ///
    /// ЗАЧЕМ ПЕРЕВОД, А НЕ ОДИН СЛОВАРЬ НА ВСЕХ. <see cref="RoadStop"/>
    /// отвечает на «чем кончилась ИМЕННО ЭТА дорога» и нужен её отчёту:
    /// «уклон круче полублока за клетку» — это не «задание невыполнимо вообще»,
    /// а очень определённая вещь, которую человек и читает. Общее слово
    /// отвечает на другой вопрос — «пройдёт ли это само», — и по нему решает
    /// возврат. Каждая работа переводит СВОЙ словарь; сводить их в один значило
    /// бы потерять слова, ради которых оба и заведены.
    ///
    /// ПРОСЬБА ЗАКАЗЧИКА, РАДИ КОТОРОЙ ЭТО НАПИСАНО: «если мешает игрок, то
    /// пробовать заново, а не сбрасывать и вообще на все бы задачи так».
    /// </summary>
    /// <param name="cell">
    /// Чем отказала клетка, если проходка встала на клетке (<see cref="Tally.Cell"/>).
    /// Ею уточняется самое общее слово дороги — <see cref="RoadStop.Blocked"/>, —
    /// и ЕЮ ЖЕ отчитывается срок: клетка мешала, ПОКА ШЛИ ЧАСЫ, и называть
    /// вместо неё сам срок значит подсунуть симптом вместо причины
    /// (<see cref="Resume.TimeIsNotACause"/>). Второй памяти о помехе дороге
    /// поэтому не заводится.
    /// </param>
    public static Setback WhatStopped(RoadStop stop, MiningRefusal cell = MiningRefusal.None) =>
        stop switch
        {
            RoadStop.Done => Setback.None,

            // ЗАХОД КОНЧИЛСЯ ПО СВОЕМУ ПОТОЛКУ — И ЭТО НЕ ПОМЕХА, А ДОЛЯ.
            // Живьём дорога говорила «остаток дороги надо задать ещё раз», и
            // задавать его было НЕКОМУ: очередь читала Success=false как конец
            RoadStop.Unfinished => Setback.Unfinished,

            // Реестр сервера и непришедший чанк проходят сами — их и ждут
            RoadStop.NotReady => Setback.NotLoaded,
            RoadStop.NoGround => Setback.NotLoaded,

            // «Тело не смогло пройти по своей же дороге» — это и есть игрок,
            // вставший на клетку, и тварь, пробежавшая поперёк
            RoadStop.Stuck => Setback.Crowd,

            RoadStop.NoRoute => Setback.NoRoute,
            RoadStop.NoMaterial => Setback.NoMaterial,
            RoadStop.Cancelled => Setback.Stopped,

            // СРОК ДОКЛАДЫВАЕТ ПОМЕХУ, А НЕ ВСТАЁТ НА ЕЁ МЕСТО.
            //
            // ДОРОГА БЫЛА ПОСЛЕДНЕЙ, КТО ЭТОГО НЕ УМЕЛ, и вот чем это стоило
            // человеку: игрок встал на клетку полотна, проходка честно
            // записала отказ клетки в Tally.Cell («сервер не ответил», «блок
            // встал бы в самого бота») — а дорога доработала до своего
            // потолка и отдала «вышло отведённое время». Слово OutOfTime лежит
            // среди ПОСТОЯННЫХ, и возврат читал его как «дальше пробовать
            // незачем»; мешал же Crowd, который проходит сам за полминуты.
            // Заготовка лежала рядом всё это время — ровно та же, что у наряда
            // (lastMiss) и у карьера (Run.Live), — и в отказ не попадала.
            //
            // ПОЧЕМУ ЭТА ПОМЕХА И ПРАВДА ЖИВАЯ, А НЕ СТАРАЯ. Клетка, на которой
            // встала проходка, ДЕРЖИТ дорогу до конца захода: рядом с Tally.Cell
            // ставится halted, и все ряды от него и дальше заход уже не копает
            // (см. BuildAsync). То есть это не мелькнувшая когда-то неудача, а
            // помеха, мешавшая ровно пока шли часы, — потому срок ею и
            // отчитывается.
            //
            // Своего суждения тут нет: слово клетки переводит тот же
            // WhatCellSaid, каким уточняется Blocked, а «срок — это симптом»
            // — общее правило на все работы (Resume.TimeIsNotACause).
            RoadStop.Timeout => Resume.TimeIsNotACause(WhatCellSaid(cell)),

            // Задание само себе противоречит и узнаётся до первого удара
            RoadStop.TooSteep => Setback.Impossible,
            RoadStop.NoHeadroom => Setback.Impossible,

            // САМОЕ ОБЩЕЕ СЛОВО ДОРОГИ — УТОЧНЯЕМ ЕГО КЛЕТКОЙ
            RoadStop.Blocked => WhatCellSaid(cell),

            _ => Setback.None
        };

    /// <summary>
    /// ЧТО СКАЗАЛА КЛЕТКА — общим словом. ЧИСТОЕ ПРАВИЛО.
    ///
    /// Разбор каждой строки — в самом <see cref="MiningRefusal"/>, там он и
    /// написан живыми словами («причина ПОПРАВИМАЯ, и повторить стоит»,
    /// «повторять бессмысленно, сколько ни пробуй»). Здесь только перевод, и
    /// своих суждений тут нет ни одного.
    /// </summary>
    public static Setback WhatCellSaid(MiningRefusal cell) => cell switch
    {
        // «Ответа от сервера не было вовсе… причина ПОПРАВИМАЯ, и повторить
        // стоит» — это дословно из описания самого отказа
        MiningRefusal.NoAnswer => Setback.NotLoaded,
        // Блок встал бы в самого бота: «лечится шагом в сторону» — то есть
        // мир вокруг тела, а он переменится
        MiningRefusal.SelfInTheWay => Setback.Crowd,
        // Ломать нечего: клетку уже сняли — мир под руками стал другим
        MiningRefusal.Nothing => Setback.Shifted,

        MiningRefusal.OutOfReach => Setback.OutOfReach,
        MiningRefusal.Claimed => Setback.NotMine,
        MiningRefusal.Spared => Setback.NotMine,
        MiningRefusal.Rejected => Setback.NotMine,
        MiningRefusal.NeedBetterTool => Setback.NoMaterial,
        MiningRefusal.Unbreakable => Setback.Impossible,
        MiningRefusal.Occupied => Setback.Impossible,

        // Клетка молчит (лава, вода, чужая разметка — сюда сходится всё, что
        // проходка называет своими словами). Гадать за неё нельзя
        _ => Setback.None
    };

    // ---------------- работа ----------------

    /// <summary>
    /// Клетка, в которой стоят ноги. Спрашивается ОДНИМ входом —
    /// <see cref="Movement.FeetCell"/>, тем же, каким её спрашивает половина
    /// этого же файла (<c>SplitTopDown</c>, <c>StandingOn</c>, <c>UnderMe</c>).
    ///
    /// СВОЕЙ СКЛЕЙКИ ЗДЕСЬ БОЛЬШЕ НЕТ, И ВОТ ПОЧЕМУ ОНА БЫЛА ЛИШНЕЙ. Стояло
    /// <c>ctx.World.StandingCellAt(ctx.Self.Position)</c> — то же правило и та
    /// же точка: <c>SelfState.Position</c> берёт координаты у
    /// <c>entities.Self</c>, и ровно у него же берёт их <c>Movement</c>. То
    /// есть один и тот же вопрос задавался в одном файле двумя входами, и
    /// разъехаться им было куда: у <c>StandingCellAt</c> есть просадка
    /// (<c>sink</c>), и добавь её кто-нибудь одному входу — дорога стала бы
    /// мерить свои ряды двумя разными мерками.
    ///
    /// Само правило остаётся тем же и нужно по той же причине: полотно дороги
    /// — это stonepath-free с верхом коробки 0.9375, тело на нём стоит на
    /// 110,94, и голый <c>floor(Y)</c> отвечал клеткой САМОГО полотна. Дорога
    /// от этого мерила свой же ряд этажом ниже и честно докладывала «дорога до
    /// … есть, а тело по ней не идёт», стоя ровно на ней.
    /// </summary>
    private BlockPos? Feet => ctx.Movement.FeetCell;

    /// <summary>
    /// Проложить дорогу от того места, где бот стоит, до цели — шириной
    /// <see cref="Width"/>. Старый вход, которым зовут навык и панель.
    /// </summary>
    public Task<RoadReport> PaveToAsync(BlockPos target, CancellationToken ct = default)
    {
        if (Feet is not { } from)
            // «Не знаю, где стою» — это недоехавший мир, а не свойство места:
            // помеха временная, и возврат вправе взяться за дорогу заново
            return Task.FromResult(new RoadReport(RoadStop.Stuck, "не знаю, где стою",
                target, NoSurface, 0, 0, 0, 0, 0, 0, 0, 0)
            { Hindrance = WhatStopped(RoadStop.Stuck) });
        return BuildAsync(from, target, Width, ct);
    }

    /// <summary>Счёт сделанного: его показывают в отчёте, и врать в нём нельзя.</summary>
    private sealed class Tally
    {
        public int Paved, Steps, Cleared, Skipped, RowsDone;

        /// <summary>
        /// ЭТОТ ЗАХОД — ВОЗВРАТ К НАЧАТОЙ ДОРОГЕ (см. <see cref="Roads.BuildAsync"/>,
        /// параметр <c>resumed</c>). Лежит здесь, потому что спрашивают это
        /// глубоко в укладке (<see cref="Roads.LayAsync"/>), а тащить слово
        /// через полдюжины подписей значило бы завести шестое место, где о нём
        /// можно забыть.
        /// </summary>
        public bool Resumed;

        /// <summary>
        /// Уровень ряда, ВЫЛОЖЕННОГО ПОСЛЕДНИМ (полублоки) — его отдают
        /// возврату, чтобы второй заход начал с той высоты, где дорога
        /// вправду кончилась (см. <see cref="RoadReport.LastLevel"/>).
        /// </summary>
        public int LastLevel = RoadReport.Unknown;

        /// <summary>
        /// КЛЕТКИ УБОРКИ, ДО КОТОРЫХ НЕ ДОТЯНУЛСЯ. Трава и папоротник в
        /// просвете над полотном не мешают ни телу, ни установке, и вставать
        /// из-за них всей дорогой не за что — но и молчать о них нельзя:
        /// человек увидит их на готовой дороге и спросит, откуда они там.
        /// Уходят в причину отчёта (см. <see cref="Roads.BuildAsync"/>).
        ///
        /// ЗДЕСЬ ЛЕЖАТ КЛЕТКИ, А НЕ ГОТОВЫЕ СТРОКИ, И ЭТО НАРОЧНО. Отказ
        /// случается в середине работы, а отчёт пишется в конце — между ними
        /// клетка успевает измениться, и чаще всего именно ТАК, как разобрано
        /// у <see cref="Roads.DigTopDownAsync"/>: до папоротника не дотянулись
        /// потому, что луч перекрывала земля ПОД ним, а её бот тут же и снял —
        /// держаться папоротнику стало не на чем, и он упал сам. Запомни мы
        /// строку, отчёт назвал бы «оставшимся» то, чего в мире уже нет.
        /// Поэтому имя блока спрашивается у мира ПЕРЕД самой печатью
        /// (см. <see cref="Roads.BuildAsync"/>).
        /// </summary>
        public readonly List<BlockPos> Untouched = [];

        /// <summary>
        /// ЧЕМ ИМЕННО ОТКАЗАЛА КЛЕТКА, НА КОТОРОЙ ВСТАЛА ПРОХОДКА, — словами
        /// самой добычи (<see cref="MiningRefusal"/>).
        ///
        /// ЗАЧЕМ. <see cref="RoadStop.Blocked"/> — самое общее слово дороги:
        /// под ним и лава, и «не дотянуться», и «сервер не ответил». Первые два
        /// не пройдут никогда, третье пройдёт само за секунду, и решать про
        /// повтор (<see cref="Setback"/>) по одному «Blocked» значило бы либо
        /// топтаться у лавы трижды, либо бросать дорогу из-за потерянного
        /// пакета. Добыча это РАЗЛИЧАЕТ и говорит честно — берём её слово.
        ///
        /// Лежит здесь по той же причине, что и <see cref="Resumed"/>: узнаётся
        /// глубоко в проходке, а нужно отчёту.
        /// </summary>
        public MiningRefusal Cell = MiningRefusal.None;
    }

    /// <summary>Разведанный ряд: где он и на какой высоте ляжет его полотно.</summary>
    private sealed record Planned(RoadRow Row, RoadLevel Step);

    /// <summary>
    /// ПОСТРОИТЬ ДОРОГУ ОТРЕЗКОМ: от A до B полосой заданной ширины.
    ///
    /// ДВА ПРОХОДА. Сперва бот идёт вдоль ВСЕЙ дороги и выкапывает выемку —
    /// и ход над будущим полотном, и постель под него
    /// (<see cref="RoadPlan.Cut"/>), — и только потом возвращается к началу и
    /// мостит. Порядок задаёт чистое правило <see cref="RoadPlan.Order"/>,
    /// ручка — <see cref="DigFirst"/>.
    ///
    /// ВЫСОТА — ИЗ ЗАДАНИЯ. Полотно ложится там, где велено (прямая от y1 к y2),
    /// а земля под осью служит мерой: по ней видно, где выемка, а где провал.
    /// Выемку глубже <see cref="MaxCutFill"/> бот не режет и честно называет
    /// число; провал под полотном — мостит (<c>BridgeRunAsync</c>).
    ///
    /// РАЗВЕДКА ВСЕГО ХОДА ИДЁТ ДО ПЕРВОГО УДАРА (<see cref="Scouted"/>): то,
    /// чего бот не осилит, называется человеку ДО работы, а не после того, как
    /// выкопаны восемь рядов впустую.
    ///
    /// Перепад — ступенька «блок + полублок»: низ кладётся тем же покрытием,
    /// что и полотно (он и есть полотно, только на клетку раньше), верх —
    /// полублоком из сумок, а нет в сумках — по рецепту. Чего нет ни там, ни
    /// там, о том говорится вслух с названием и с причиной, а не пропускается
    /// молча.
    /// </summary>
    /// <remarks>
    /// ПОЧЕМУ virtual — по той же причине, что и у наряда
    /// (<see cref="MiningOrder.FetchAsync"/>): настоящая укладка требует мира и
    /// сервера, а шов «роль → <see cref="RoadResume.KeepBuildingAsync"/> →
    /// дорога» проверить надо. Без подставной дороги возврат к прерванному
    /// полотну можно было выкинуть одной строкой, и ни один тест не покраснел бы.
    /// </remarks>
    /// <param name="resumed">
    /// ЭТО ВОЗВРАТ К НАЧАТОЙ ДОРОГЕ, А НЕ ПЕРВЫЙ ВЫХОД. Отвечает ровно на один
    /// вопрос: считать ли работу НАЧАТОЙ, когда дело доходит до покрытия
    /// (<see cref="MaySupply"/>).
    ///
    /// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЗАВЕДЕНО (журнал заказчика 30.08). Дорога
    /// шла в семь заходов, и каждый заход отчитывался одинаково:
    /// «возвращаюсь на дорогу: положено 0 рядов из 21, кладу дальше с
    /// (61,105,245) (заход 7)». Ноль рядов — все семь раз. Причина здесь:
    /// возврат зовёт эту укладку ЗАНОВО, а она про прошлые заходы не знала
    /// НИЧЕГО и честно считала полотно неначатым — то есть шла за камнем
    /// домой, за тридцать шесть блоков от дороги, и там её перебивали снова.
    /// Правило «за покрытием посреди начатой работы домой не бегу» было цело;
    /// спросить его было некому, потому что «начатой» работа с точки зрения
    /// нового захода не была.
    ///
    /// ПОЧЕМУ ПАРАМЕТРОМ, А НЕ ПАМЯТЬЮ ВНУТРИ ДОРОГИ. Ровно по той же причине,
    /// по какой это сделано у наряда (<c>MiningOrder.FetchAsync</c>, тот же
    /// <c>resumed: attempt > 1</c>): счёт заходов ведёт возврат
    /// (<see cref="Resume"/>), и второй его памяти заводить нельзя — две
    /// памяти о заходах разъедутся в первый же день.
    /// </param>
    public virtual async Task<RoadReport> BuildAsync(BlockPos from, BlockPos to, int width,
        CancellationToken ct = default, bool resumed = false)
    {
        var started = DateTime.UtcNow;
        var deadline = started.AddSeconds(MaxSeconds);
        var tally = new Tally { Resumed = resumed };
        var at = Feet ?? from;
        // Отложенное с прошлой дороги — чужое: клетки там свои, и доламывать
        // их посреди новой дороги незачем
        deferred.Clear();

        RoadReport Report(RoadStop stop, string why, string material, int rows, int cells) =>
            new(stop, why, Feet ?? at, material, rows, tally.RowsDone, cells, tally.Paved,
                tally.Steps, tally.Cleared, tally.Skipped,
                (DateTime.UtcNow - started).TotalSeconds)
            {
                LastLevel = tally.LastLevel,
                // Помеху общим словом считает чистое правило, и считает ЗДЕСЬ —
                // в одном месте на все выходы из дороги. Расставь его по
                // тринадцати return'ам, и один из них рано или поздно забудут
                Hindrance = WhatStopped(stop, tally.Cell)
            };

        if (!ctx.World.GameBlocksReady)
            return Report(RoadStop.NotReady, "реестр блоков сервера ещё не пришёл", NoSurface, 0, 0);

        width = Math.Clamp(width <= 0 ? Width : width, 1, RoadPlan.MaxWidth);
        var rows = RoadPlan.Rows(from, to, width).ToList();

        int wholeRows = rows.Count;              // сколько рядов у дороги ЦЕЛИКОМ
        int fit = RowsPerRun(wholeRows, width, MaxCells);
        if (fit < wholeRows)
        {
            OnLog?.Invoke($"полотно на {wholeRows * width} кл. — за заход кладу {fit} рядов " +
                          $"из {wholeRows}, остальное следующим вызовом");
            rows = rows.Take(fit).ToList();
        }
        // ЧИСЛА В ОТЧЁТЕ — ПРО ВСЮ ДОРОГУ, а не про заход. Пока Rows было
        // урезанным, отчёт говорил «341 рядов из 341» и Success=true про
        // треть дороги, а про отброшенный остаток не было ни слова
        int cells = wholeRows * width;
        bool cut = fit < wholeRows;

        // ВЫЕМКА, В КОТОРУЮ НЕ ВЛЕЗАЕТ ТЕЛО, — ЭТО ОТКАЗ ДО ПЕРВОГО УДАРА.
        //
        // Копать ход ниже собственного роста бот умеет, а ходить по нему — нет,
        // и живьём это выглядело строкой без причины: «клетка вскрыта, а тело в
        // неё не идёт». Просвет тела — не наше число, а общее правило
        // (Walker.MinHeadroom, из хитбокса игрока), и здесь только проверка.
        //
        // Выключенный ClearHeadroom сюда не попадает нарочно: там человек прямо
        // сказал «над дорогой не убирать» — это не низкая выемка, а её
        // отсутствие, и обещания пройти дорога в этом случае не даёт
        if (ClearHeadroom && Height < Walker.MinHeadroom)
            return Report(RoadStop.NoHeadroom,
                $"не хватает просвета: выемка задана в {Height} кл. над полотном, а телу нужно " +
                $"хотя бы {Walker.MinHeadroom} (рост {Walker.BodyHeight:0.##} бл — ноги и голова). " +
                $"Такой ход я выкопаю, но пройти по нему не смогу — поднимите ручку " +
                $"«{Knobs.Height}» до {Walker.MinHeadroom} или больше",
                NoSurface, wholeRows, cells);

        // УКЛОН, КОТОРЫЙ Я НЕ ВЫБЕРУ, — ЭТО ОТКАЗ ДО ВЫХОДА, А НЕ ДЕСЯТЬ
        // ПАДЕНИЙ ПОДРЯД. Бот и раньше ЗНАЛ это заранее и говорил вслух («до
        // конца этот подъём не выберет»), но всё равно брался — а потом вставал
        // на первых же рядах, потому что полотно уходило от земли дальше
        // MaxCutFill. Знание, с которым ничего не делают, — это враньё в
        // рассрочку.
        //
        // ЧИСЛА, А НЕ ПРИСКАЗКА: сколько нужно рядов и куда полотно дойдёт на
        // самом деле, считает чистое правило рядом с самим профилем
        // (RoadPlan.Reached / RowsToClimb / NearestEnd) — второй арифметики тут нет
        int reached = RoadPlan.Reached(from.Y, to.Y, wholeRows);
        if (reached != to.Y * 2)
        {
            string steep =
                $"уклон не по силам: от {from.Y} к {to.Y} — это {Math.Abs(to.Y - from.Y)} бл " +
                $"{(to.Y > from.Y ? "подъёма" : "спуска")} на {wholeRows} рядов, а круче " +
                $"полублока за ряд дорога не идёт. На последнем ряду полотно будет на " +
                $"{RoadPlan.FeetY(reached):0.#}, а не на {to.Y}; чтобы взять " +
                $"{Math.Abs(to.Y - from.Y)} бл, нужно {RoadPlan.RowsToClimb(from.Y, to.Y)} рядов";
            if (!LeadTooSteep)
            {
                // ОТКАЗ ОБЯЗАН ПРЕДЛОЖИТЬ ВЫПОЛНИМОЕ. Живьём человек, прочитав
                // прежнюю строку, три раза подряд пробовал наугад другие высоты
                // (80, 79, 92) и лишь четвёртой попыткой попал в 93 — то самое
                // число, которое бот знал с первой секунды. Все три выхода
                // считаются уже посчитанным, ничего нового тут не изобретается
                int end = RoadPlan.NearestEnd(from.Y, to.Y, wholeRows);
                return Report(RoadStop.TooSteep,
                    steep + $". Выполнимое: задайте конец на высоте {end} — дорога ляжет " +
                    $"целиком; или растяните её до {RoadPlan.RowsToClimb(from.Y, to.Y)} рядов " +
                    $"(сейчас {wholeRows}); или включите ручку «{Knobs.LeadTooSteep}» — тогда " +
                    "поведу до предела, докуда возьму",
                    NoSurface, wholeRows, cells);
            }
            OnLog?.Invoke(steep + ". Веду до предела: полотно ляжет, но заданной высоты " +
                          "не достанет — где встану, скажу числом");
        }

        // Покрытие: дорожное из сумок, дорожное по рецепту, и только потом —
        // ровный пол. Заказчик просил именно так: «выкапывать и крафтить боту
        // дорогу», а не мостить тем, чего в сумке больше всего
        ForgetRecipes();
        // ВОЗВРАТ — ЭТО «ПОСРЕДИ НАЧАТОЙ РАБОТЫ», И РЕЙС ОТСЮДА ЗАПРЕЩЁН ТОЙ ЖЕ
        // РУЧКОЙ, ЧТО И ПОСРЕДИ РЯДА. Здесь стоял голый первый выход (midRoad
        // по умолчанию false), и заход 7 уходил домой за камнем так же, как
        // заход 1, — разбор целиком у самого параметра resumed
        var (chosen, whyNoSurface) = await EnsureSurfaceAsync(ct, midRoad: resumed);

        // ПУСТЫЕ РУКИ БОЛЬШЕ НЕ ОТМЕНЯЮТ ХОД. Разбор и живой прогон, из-за
        // которого это правило появилось, — у самого правила
        // (<see cref="DigWithoutSurface"/>): при «сперва копать» ход выкопан
        // будет, а чем мостить — спросим у собственной выемки, когда вернёмся
        var (digAnyway, sayNoSurface) = DigWithoutSurface(DigFirst, whyNoSurface);
        if (chosen == null && !digAnyway)
            return Report(RoadStop.NoMaterial, whyNoSurface, NoSurface, wholeRows, cells);
        string surface = chosen ?? NoSurface;
        if (chosen == null)
            OnLog?.Invoke(sayNoSurface);

        OnLog?.Invoke($"дорога {from} → {to}, ширина {width}: {rows.Count} рядов" +
                      (cut ? $" из {wholeRows} за этот заход" : "") +
                      $", {cells} кл. полотна; " +
                      (chosen == null
                          ? "покрытие возьму у самого хода — сперва копка"
                          : $"покрытие {surface} (множитель хода {SpeedOf(surface):0.##})"));

        // ВЫСОТУ ИЗ ЗАДАНИЯ НАЗЫВАЕМ ВСЛУХ. Жалоба была дословно «он не
        // учитывает высоту в задании», и проверить обратное человек должен
        // ПЕРВОЙ строкой, а не по готовой дороге
        OnLog?.Invoke(from.Y == to.Y
            // ВВЕРХ И ВНИЗ — РАЗНЫЕ РАБОТЫ И РАЗНЫЕ ПРЕДЕЛЫ, и говорить о них
            // одним числом нельзя: выемку меряет глубина, провал — мост
            ? $"веду по заданной высоте {from.Y} (ноги на ней): где земля выше — выемка " +
              $"(глубже {MaxCutFill} бл не режу), где ниже — навожу мост"
            // ВВЕРХ ИЛИ ВНИЗ — СПРАШИВАЕМ У ЧИСЕЛ, А НЕ ВШИВАЕМ В СТРОКУ.
            // Живой случай: «от 112 к 80, это 32 бл подъёма» — от 112 к 80 это
            // СПУСК, и человек, читая журнал, первым делом спотыкался об это
            : $"веду по заданной высоте: от {from.Y} к {to.Y}, это {Math.Abs(to.Y - from.Y)} бл " +
              $"{(to.Y > from.Y ? "подъёма" : "спуска")} на {wholeRows} рядов");

        // ЧЕМ БЕРУ ПЕРЕПАДЫ — говорю ДО выхода, а не на первой кочке за сто
        // блоков отсюда, и НАЗЫВАЮ КОД. Здесь стояла та самая строка, из-за
        // которой слово разошлось с делом: «ступеней нет — перепады беру
        // полублоками» говорилось один раз на выходе, а решение «есть ли
        // ступени» пересчитывалось на каждом окне и молча переворачивалось.
        // Ступеней больше нет вовсе, спросить осталось про одно — полублок.
        //
        // ПРО ПОЛУБЛОКИ ГОВОРИМ ПЕРВОЙ СТРОКОЙ, А НЕ ПОСЛЕ РАБОТЫ.
        //
        // ЖИВОЙ СЛУЧАЙ 29.08, СПУСК: «ход пройден весь, 7 рядов, 23 кл.» и тут
        // же «дорога 1 рядов из 7… на ступеньку нужен ПОЛУБЛОК, в сумках его
        // нет». Семьдесят шесть секунд копки, один ряд полотна — и о преграде
        // человек узнал ПОСЛЕ. Молчало здесь условие «if (chosen != null)»: с
        // пустыми руками («сперва копка») про полублоки не говорилось ни слова,
        // а на спуске ступенька есть в КАЖДОМ ряду — то есть ровно в том
        // заходе, где предупреждение и нужно, его и не было (закон 4).
        //
        // Условие стояло не зря: сказать с пустыми руками «полублоков нет ни в
        // сумках, ни в рецептах» — значит соврать наперёд, через минуту ход
        // отдаст породу. Поэтому молчит теперь не строка, а НЕПРАВДА: с пустыми
        // руками говорится условное («спрошу у самого хода»), и это правда в
        // обе стороны. Про какой случай речь, знает одно место — SayAboutSlabs
        SayAboutSlabs(beforeDig: chosen == null);

        OnLog?.Invoke(DigFirst
            ? $"порядок работ: сперва прохожу весь ход ({rows.Count} рядов) и копаю его, " +
              "потом возвращаюсь к началу и мощу"
            : "порядок работ: ряд за рядом, копка и укладка вперемешку " +
              "(«сперва выкопать, потом мостить» выключено)");

        // Дойти до начала. Дорога начинается там, где сказали, а не там, где
        // бот оказался: иначе первый же отрезок уезжает на десятки блоков.
        //
        // СТОИТ ЭТО ПОСЛЕ РЕЙСА ЗА ПОКРЫТИЕМ, И ЭТО ГЛАВНОЕ ЗДЕСЬ. Рейс
        // (EnsureSurfaceAsync выше) уводит бота домой и в карьер — он на то и
        // рейс. Пока «дойти до начала» стояло ВЫШЕ него, порядок был такой:
        // пришёл на дорогу → ушёл домой за камнем → вернулся ни с чем → и начал
        // работать ОТТУДА, ГДЕ ВСТАЛ. Живой прогон 29.08: «дорога 0 рядов из 7,
        // замощено 0 кл. из 7; 37 с; ОСТАНОВКА НА (60, 114, 280)» — а дорога
        // задана в (95, 112, 256): бот стоял у дома. Тридцать семь секунд и два
        // нуля. Теперь место работы занимается ПОСЛЕДНИМ действием перед
        // работой, после всех рейсов, и лишнего конца «дорога → дом → дорога»
        // тоже больше нет.
        //
        // ВЫСОТА СЧИТАЕТСЯ НАРАВНЕ С ПЛАНОМ. Пока смотрели только на X и Z, бот,
        // стоящий на обрыве над самым началом дороги, считал себя пришедшим и
        // начинал класть полотно двадцатью блоками ниже собственных ног —
        // дотянуться до него он не мог ни разу
        //
        // ИДЁМ ТУДА, ГДЕ ЕСТЬ ПОЛ, А НЕ НА ЧЕРТЁЖНУЮ ВЫСОТУ. Живой случай
        // 19.08, 23:59–00:01: пять заходов подряд легли строкой «до начала
        // дороги (512052, 112, 512252) не дошёл», и каждый раз бот заново
        // обещал в чат «Мощу дорогу». Прошлый заход выкопал у начала выемку —
        // пола на заданной высоте там больше не было, — а сюда шла голая
        // цифра из задания. Возврат перед укладкой то же место спрашивал
        // ИНАЧЕ (по дну хода), и два ответа на один вопрос расходились ровно
        // в тех заходах, где мир между ними переменился. Ответ теперь один
        // (StandAt), и спрашивает он мир
        if (Feet is not { } stand)
            return Report(RoadStop.Stuck, "не знаю, где стою", surface, wholeRows, cells);
        var head0 = StandAt(from, from.Y * 2);
        if (Math.Abs(stand.X - head0.X) + Math.Abs(stand.Z - head0.Z) > 2 ||
            Math.Abs(stand.Y - head0.Y) > 2)
        {
            OnLog?.Invoke($"иду к началу дороги {head0}" +
                          (head0.Y == from.Y ? "" : $" (заданная высота {from.Y}, а пол там " +
                                                    $"на {head0.Y}: тут уже копано)"));
            if (!await ctx.Movement.TravelToAsync(head0, ApproachSeconds, ct))
                // ОТКАЗ ОБЯЗАН НАЗВАТЬ ВЫПОЛНИМОЕ (см. Roads.WhyNoStart): голое
                // «не дошёл» человек прочёл 19.08 пять раз подряд и пять раз
                // повторил тот же заказ — повернуть в нём было нечего
                return Report(RoadStop.NoRoute,
                    WhyNoStart(ctx.Movement.FeetCell ?? stand, head0, rows),
                    surface, wholeRows, cells);
        }

        var stop = RoadStop.Done;                 // чем кончилась УКЛАДКА
        string reason = "дорога доведена до конца";
        var digStop = RoadStop.Done;              // чем кончилась ПРОХОДКА
        string digWhy = "";
        int halted = rows.Count;                  // докуда прошла проходка
        var plan = new Planned?[rows.Count];      // разведанные ряды
        int misses = 0;                           // сколько раз подряд тело не сдвинулось
        bool back = false;                        // к началу перед укладкой уже вернулись
        bool? mayPave = null;                     // мостить ли после вставшей проходки

        // ЗЕМЛЯ ПОД ОСЬЮ, ПРОЧИТАННАЯ У МИРА, — отдельно от разметки полотна.
        // Разделены они не для порядка: профиль теперь выбирается СРАЗУ ПО
        // ВСЕЙ прочитанной земле (RoadPlan.Levels), потому что решить, где
        // полотну прижаться к земле, а где подняться к заданному концу, нельзя,
        // видя двенадцать рядов из тридцати трёх
        var soil = new int?[rows.Count];

        // ЧТЕНИЕ ЗЕМЛИ, БЕЗ ХОДЬБЫ: высоты под осью на PlanAhead рядов вперёд
        // по УЖЕ ПРОГРУЖЕННОМУ миру. Сколько рядов прибавилось; ноль — земли
        // не видно (чанка нет или там пусто)
        int ReadGround(int first)
        {
            // Землю ищем ОТ ПРЕДЫДУЩЕЙ НАЙДЕННОЙ, а не от заданной высоты:
            // она мера рельефа, и мерить её надо по рельефу. Ищи мы от
            // заданной, за землю сошла бы крона дерева, случись она к ней ближе
            int hint = first > 0 && soil[first - 1] is { } was ? was : rows[first].Centre.Y;
            int got = 0;
            for (int i = first; i < rows.Count && got < PlanAhead; i++, got++)
            {
                if (soil[i] is { } known)
                {
                    hint = known;
                    continue;
                }
                if (GroundAt(rows[i].Centre.X, rows[i].Centre.Z, hint) is not { } g)
                    break;
                soil[i] = g;
                hint = g;
            }
            return got;
        }

        // РАЗМЕТКА ПО ПРОЧИТАННОЙ ЗЕМЛЕ: концы закреплены заданием, между ними
        // полотно жмётся к земле (RoadPlan.Levels). Коридор считается по
        // ДОРОГЕ ЦЕЛИКОМ (wholeRows), а не по этому куску: заданный конец
        // остаётся законом, даже если мир показал только половину хода
        int Replan(int first)
        {
            var ground = new List<int>();
            for (int i = first; i < rows.Count && soil[i] is { } g; i++)
                ground.Add(g);
            if (ground.Count == 0)
                return 0;
            int? before = first == 0 ? null : plan[first - 1]!.Step.Level;
            var profile = RoadPlan.Profile(ground, first, wholeRows,
                from.Y * 2, to.Y * 2, before);
            for (int k = 0; k < ground.Count; k++)
                plan[first + k] = new Planned(rows[first + k], profile[k]);
            return ground.Count;
        }

        // РАЗВЕДКА БЕЗ ХОДЬБЫ: прочитать землю, сколько её показывает мир, и
        // разметить профиль по ВСЕЙ прочитанной разом.
        //
        // Отдельно от SurveyAsync нарочно: тот же вопрос задают ДВОЕ. Разведка
        // всего хода перед работой обязана только ЧИТАТЬ мир и не имеет права
        // никуда идти, а разведка на ходу подходит ближе, если мир молчит.
        // Пока это была одна функция, «разведать весь ход заранее» означало бы
        // «пройти его весь заранее», то есть ту же ходьбу, ради экономии
        // которой всё и затевалось
        int SurveyWindow(int first)
        {
            for (int at = first; at < rows.Count && ReadGround(at) is var got && got > 0; at += got)
            {
            }
            return Replan(first);
        }

        // РАЗВЕДКА НА ХОДУ: то же окно, но если мир молчит — подходим ближе.
        async Task<(RoadStop Stop, string Why)> SurveyAsync(int first)
        {
            for (int tries = 0; tries < 2; tries++)
            {
                if (SurveyWindow(first) > 0)
                    return (RoadStop.Done, "");
                // Земли не видно — либо чанк не прогружен, либо там пусто.
                // Отличить можно только подойдя: подходим и спрашиваем ещё раз.
                // Второй раз повторять нечего: «подойду ещё ближе» на месте —
                // это вечный круг, а не работа
                if (tries > 0)
                    break;
                var next = rows[first].Centre;
                OnLog?.Invoke($"под {next} земли не вижу — подхожу ближе");
                double left = Math.Max(15, (deadline - DateTime.UtcNow).TotalSeconds);
                await ctx.Movement.TravelToAsync(next, Math.Min(90, left), ct);
            }
            return (RoadStop.NoGround,
                $"под {rows[first].Centre} земли не видно — дальше вести дорогу не по чему");
        }

        // ВЕСЬ ХОД РАЗВЕДЫВАЕТСЯ ДО ПЕРВОГО УДАРА, И ПОМЕХА НАЗЫВАЕТСЯ ЗДЕСЬ.
        //
        // ЖИВОЙ СЛУЧАЙ 22.08 — два захода подряд в ноль (17:18:35 и 17:25:14):
        // «ПРОХОДКА ВСТАЛА на ряду 11 из 29 … выкопанные 11 рядов ждут» и
        // «ПРОХОДКА ВСТАЛА на ряду 8 из 31 … выкопанные 8 рядов ждут».
        // Заказчик написал «не идет делать дорогу», и это была правда: обе
        // помехи стояли в уже прогруженном мире и были видны с первой секунды,
        // а бот узнавал о них, выкопав десять рядов и восемь.
        //
        // Разведка ЧИТАЕТ мир и не делает ни шага: тридцать рядов — это тридцать
        // вопросов «где тут земля». Дальше прогруженного мира она не заглядывает
        // и честно говорит, докуда дошла; хвост разведает работа своим чередом
        //
        // ОДНИМ ВЫЗОВОМ, И ЭТО НЕ УПРОЩЕНИЕ РАДИ КРАСОТЫ: разметка выбирается
        // сразу по всей прочитанной земле, и звать её кусками значило бы
        // решать за первые двенадцать рядов, не зная про остальные двадцать
        SurveyWindow(0);
        var seen = new List<(BlockPos Centre, RoadLevel Step)>();
        for (int i = 0; i < plan.Length && plan[i] is { } known; i++)
            seen.Add((known.Row.Centre, known.Step));
        var (mayGo, scoutSaid) = Scouted(seen, rows.Count, MaxCutFill, Knobs.MaxCutFill,
            ctx.Scaffolding?.MaxBridgeSpan ?? 0, ctx.Mining.SpareBlocks(),
            // ТА ЖЕ ОГОВОРКА, ЧТО И У СТОРОЖА ПРОСВЕТА: выключенная расчистка —
            // это не низкий ход, а его отсутствие, и мерить её высотой нечем
            ClearHeadroom ? Height : 0, Knobs.Height);
        if (scoutSaid.Length > 0)
            OnLog?.Invoke(scoutSaid);
        if (!mayGo)
            return Report(RoadStop.Blocked, scoutSaid, surface, wholeRows, cells);

        // ПОРЯДОК РАБОТ — ИЗ ЧИСТОГО ПРАВИЛА, а не из вложенности циклов:
        // перепутать «копать всё, потом мостить всё» с «клетка за клеткой»
        // было делом одной строки, а заказчик разницу видит с первого взгляда
        foreach (var (work, index) in RoadPlan.Order(rows.Count, DigFirst))
        {
            if (stop != RoadStop.Done)
                break;
            // Проходка встала — дальше не копаем, и невыкопанное не мостим
            if (index >= halted)
                continue;
            if (ct.IsCancellationRequested)
            {
                (stop, reason) = (RoadStop.Cancelled, "отменено");
                break;
            }
            if (DateTime.UtcNow > deadline)
            {
                (stop, reason) = (RoadStop.Timeout, $"вышло отведённое время ({MaxSeconds:0} с)");
                break;
            }

            if (work == RoadWork.Dig)
            {
                if (plan[index] == null)
                {
                    var (surveyStop, surveyWhy) = await SurveyAsync(index);
                    if (surveyStop != RoadStop.Done)
                    {
                        (digStop, digWhy, halted) = (surveyStop, surveyWhy, index);
                        at = Feet ?? at;
                        continue;
                    }
                }

                var (row, step) = plan[index]!;
                if (step.Piece == RoadPiece.None)
                {
                    int? was = index == 0 ? null : plan[index - 1]!.Step.Level;
                    (digStop, digWhy, halted) = (RoadStop.Blocked,
                        $"у {row.Centre} перепад в {(step.Level - (was ?? step.Level)) / 2.0:0.#} бл " +
                        "одной клеткой не берётся", index);
                    continue;
                }
                var (tooDeep, whyTooDeep) = CutTooDeep(row.Centre, step.Level,
                    step.OffGround, MaxCutFill, Knobs.MaxCutFill);
                if (tooDeep)
                {
                    (digStop, digWhy, halted) = (RoadStop.Blocked, whyTooDeep, index);
                    continue;
                }

                // ПРОВАЛ ПОД ПОЛОТНОМ — ЭТО МОСТ, А НЕ ОТКАЗ (см. BridgeRunAsync)
                bool overVoid = VoidUnder(step.OffGround);
                if (overVoid)
                {
                    var (crossed, whyBridge) = await BridgeRunAsync(plan, index, ct);
                    if (!crossed)
                    {
                        (digStop, digWhy, halted) = (RoadStop.Blocked, whyBridge, index);
                        continue;
                    }
                }

                // Подходим ТОЛЬКО ради настоящей копки: на голой скале копать
                // нечего, и гонять тело по каждому ряду впустую — это те самые
                // полчаса, которых у дороги нет.
                //
                // Предыдущий ряд несём с собой: на дороге, идущей вниз или в
                // гору, стоять надо на нём — он уже выкопан (см. WalkAlongAsync)
                if (ToBreak(row, step, surface, bed: !overVoid).Count > 0)
                    await WalkAlongAsync(row.Centre, step.Level,
                        index > 0 && plan[index - 1] is { } past
                            ? (past.Row.Centre, past.Step.Level)
                            : null, ct);

                // ПОСТЕЛЬ НАД ПРОВАЛОМ НЕ ВЫНИМАЕТСЯ, и это не мелочь: там, где
                // полотно висит в воздухе, вынимать нечего, а лежит в этой
                // клетке НАШ ЖЕ ТОЛЬКО ЧТО ПОЛОЖЕННЫЙ МОСТ. Копни её первый
                // проход — бот выломал бы пол у себя под ногами и упал в тот
                // самый провал, который минуту назад перешёл
                var (digRowStop, digRowWhy) =
                    await DigRowAsync(row, step, surface, bed: !overVoid, tally, ct);
                at = Feet ?? at;
                if (digRowStop != RoadStop.Done)
                {
                    // Отмена и время — это конец всему заходу, а не только копке
                    if (digRowStop is RoadStop.Cancelled or RoadStop.Timeout)
                    {
                        (stop, reason) = (digRowStop, digRowWhy);
                        break;
                    }
                    (digStop, digWhy, halted) = (digRowStop, digRowWhy, index);
                }
                continue;
            }

            var (paveRow, paveStep) = plan[index]!;

            // МОСТИТЬ ЛИ ВООБЩЕ, РАЗ ХОД НЕ ПРОЙДЕН, — решает чистое правило
            // (AfterHalt) и решает ОДИН РАЗ на заход. Умолчание: не мостить.
            // Заказчик жалуется третий раз на одно и то же — «он всё ещё
            // начинает в середине стройки мостить дорогу», — и обрубок
            // полотна посреди недокопанного хода это ровно он и есть
            if (mayPave is null)
            {
                var (canPave, saidAboutHalt) = AfterHalt(digStop == RoadStop.Done, PaveUndug,
                    halted, rows.Count, digWhy, Knobs.PaveUndug);
                mayPave = canPave;
                // ГОВОРИМ В ТОТ ЖЕ МИГ, а не только отчётом. Между этой
                // секундой и отчётом бот успевает доломать отложенное и
                // вернуться к началу — живьём это минута, и человек узнавал о
                // вставшей копке минутой позже, связать одно с другим не мог
                // (стенд RoadDigBeforePaveTests
                //  .ЖИВОЙ_СЛУЧАЙ_остановка_проходки_названа_в_тот_же_миг).
                // Пробовал убрать эту строку ради борьбы с трёхкратным
                // повтором отказа — стенд покраснел, и правильно сделал:
                // повтор живёт не здесь, а в том, что ОДИН И ТОТ ЖЕ итог
                // печатают трижды («[дорога]», «[навык дорога]», «[коротко в
                // чат]»), и лечится он у них
                if (saidAboutHalt.Length > 0)
                    OnLog?.Invoke(saidAboutHalt);
                if (!canPave)
                {
                    // Отложенное доламываем и здесь: клетка под ногами
                    // последнего ряда ждала следующего ряда, а его не будет.
                    // Неудачу дороге переживать можно, а отчитываться ею —
                    // нет (см. DigDeferredSurvivingAsync)
                    if (deferred.Count > 0 && await StepOffAsync(deferred, ct) == null)
                        await DigDeferredSurvivingAsync(surface, tally, ct);
                    deferred.Clear();
                    (stop, reason) = (digStop, saidAboutHalt);
                    at = Feet ?? at;
                    break;
                }
            }

            // ЧЕМ МОСТИТЬ — СПРАШИВАЕМ ЗДЕСЬ, ЕСЛИ ДО КОПКИ ОТВЕТА НЕ БЫЛО:
            // ход к этой секунде выкопан, и порода с грунтом из него лежат в
            // сумках. Почему вопрос перенесён сюда, с живым прогоном и
            // числами, — у самого правила (DigWithoutSurface).
            //
            // СТОИТ ЭТО ПЕРЕД ВОЗВРАТОМ К НАЧАЛУ НАРОЧНО: не вышло и здесь —
            // возвращаться незачем, и человек получит отказ с числом
            // ВЫКОПАННОГО, а не два нуля.
            //
            // А ВОТ РЕЙС ОТСЮДА — УЖЕ «ПОСРЕДИ РАБОТЫ» (midRoad), и это не
            // мелочь. Правило рейса (MaySupply) говорит: сходить можно ОДИН
            // раз, ДО начала работы, когда бросать нечего. К этой секунде ход
            // выкопан — бросать ЕСТЬ ЧТО, и бот в нём стоит. Полный рейс отсюда
            // уводил его с только что выкопанного хода: живой прогон 29.08 —
            // «ход выкопан (1 кл. выемки), а мостить всё равно нечем…
            // остановка на (60, 110, 280)», то есть у дома, а не в ходе.
            // Теперь тут остаётся дешёвое и не уводящее (крафт на месте, другое
            // годное покрытие), а рейс — по ручке «MaySupplyMidRoad», и отказ
            // называет её вслух
            if (surface == NoSurface)
            {
                var (now, whyStill) = await EnsureSurfaceAsync(ct, midRoad: true);
                if (now == null)
                {
                    (stop, reason) = (RoadStop.NoMaterial,
                        $"ход выкопан ({tally.Cleared} кл. выемки), а мостить всё равно " +
                        $"нечем: {whyStill}");
                    at = Feet ?? at;
                    break;
                }
                surface = now;
                OnLog?.Invoke($"ход дал, чем его же и мостить: покрытие {surface} " +
                              $"(множитель хода {SpeedOf(surface):0.##})");
                SayAboutSlabs();
            }

            // ВЕРНУТЬСЯ К НАЧАЛУ ПЕРЕД УКЛАДКОЙ — один раз на заход. Первым
            // проходом бот ушёл в конец дороги; мостить оттуда назад нельзя:
            // профиль считался от начала, и ступеньки смотрят в ту же сторону
            if (DigFirst && !back)
            {
                back = true;
                // ДОЛОМАТЬ ОТЛОЖЕННОЕ, ПОКА МЫ ЗДЕСЬ. Клетка под ногами
                // последнего ряда ждала следующего ряда, а его не будет: уйдём
                // к началу — до неё останется вся дорога. Не вышло сойти —
                // не беда, её снимет укладка, дойдя сюда своим чередом; и
                // отчитываться этой неудачей дорога права не имеет — она её
                // пережила (см. DigDeferredSurvivingAsync)
                if (deferred.Count > 0 && await StepOffAsync(deferred, ct) == null)
                    await DigDeferredSurvivingAsync(surface, tally, ct);
                deferred.Clear();

                // ВОЗВРАЩАЮСЬ ТУДА, ГДЕ ЕСТЬ ПОЛ, а не на будущее полотно.
                // Первый проход вынул и постель тоже, значит в начале дороги
                // стоять можно ниже, чем ляжет покрытие. Живой случай 01:32:26:
                // бот шёл на 112, а пол там был на 111, и с дна собственной
                // выемки до цели честно не находилось пути — «ход выкопан, а к
                // началу дороги я не вернулся». Спрашиваем МИР (StandAt): у
                // экономной ступеньки под плитой не копали, и дно там выше
                var head = StandAt(paveRow.Centre, paveStep.Level);

                // «ХОД ПРОЙДЕН» ГОВОРИТСЯ ТОЛЬКО ТОГДА, КОГДА ОН ПРОЙДЕН.
                // Живой случай 17.08, 23:53 — вопрос заказчика дословно: «а
                // нафиг он начал делать не закончив копать». Здесь стояла одна
                // строка на оба случая, и она врала. Про вставшую проходку
                // сказано строкой выше (AfterHalt), тут остаётся только «куда иду»
                OnLog?.Invoke((digStop == RoadStop.Done ? "ход пройден весь" : "ход пройден не весь") +
                              $", {halted} рядов ({tally.Cleared} кл.) — возвращаюсь " +
                              $"к началу {head} и кладу полотно");
                if (!await ctx.Movement.TravelToAsync(head, ApproachSeconds, ct))
                {
                    (stop, reason) = (RoadStop.NoRoute,
                        $"ход выкопан, а к началу дороги {head} я не вернулся — " +
                        "полотно класть неоткуда");
                    at = Feet ?? at;
                    break;
                }
            }

            var (rowStop, rowWhy, nextSurface) =
                await PaveRowAsync(paveRow, paveStep, surface, tally, ct);
            surface = nextSurface;
            if (rowStop != RoadStop.Done)
            {
                (stop, reason) = (rowStop, rowWhy);
                at = Feet ?? at;
                break;
            }

            tally.RowsDone++;
            // ВЫСОТА ПОСЛЕДНЕГО ВЫЛОЖЕННОГО — ДЛЯ ВОЗВРАТА. Ряд лёг, и
            // теперь дорога кончается ЗДЕСЬ: с этой высоты и продолжать
            tally.LastLevel = paveStep.Level;
            at = Feet ?? at;

            // ШАГ ПО СВОЕЙ ЖЕ ДОРОГЕ. Ставить блоки можно и с соседней клетки,
            // поэтому один несостоявшийся шаг — не беда; беда, когда тело не
            // двигается вовсе.
            //
            // Шагаем StepIntoAsync, а не MoveToCellAsync: та отвечает «дошёл»
            // с допуском в КЛЕТКУ, то есть на соседнюю клетку — всегда и не
            // сдвинув тела. Бот оставался стоять, а счётчик misses при этом
            // обнулялся, и «тело по дороге не идёт» не наступало никогда
            var onRoad = new BlockPos(paveRow.Centre.X, RoadPlan.FeetCell(paveStep.Level),
                paveRow.Centre.Z);
            var wasAt = ctx.Movement.FeetCell;
            if (!StandingOn(onRoad))
            {
                await ctx.Movement.StepIntoAsync(onRoad, StepAsideSeconds, ct);
                if (!StandingOn(onRoad))
                    await ctx.Movement.MoveToCellAsync(onRoad, ct);
            }
            if (StandingOn(onRoad) || ctx.Movement.FeetCell != wasAt)
            {
                misses = 0;
            }
            else if (++misses >= 2)
            {
                (stop, reason) = (RoadStop.Stuck,
                    $"дорога до {onRoad} есть, а тело по ней не идёт: стою на " +
                    $"{ctx.Movement.FeetCell?.ToString() ?? "неизвестно где"}");
                at = Feet ?? at;
                break;
            }
        }

        // ПРОХОДКА ВСТАЛА РАНЬШЕ УКЛАДКИ. Полотно легло на всё выкопанное — и
        // это успех укладки, но НЕ успех дороги: молчать о том, где встала
        // копка, значит отдать наверх зелёный отчёт про полдороги
        if (stop == RoadStop.Done && digStop != RoadStop.Done)
            (stop, reason) = (digStop, digWhy);
        else if (digStop != RoadStop.Done)
            reason = AlsoHalted(reason, digWhy);

        // ПОЛОТНО КОНЧИЛОСЬ, А ДОРОГА — НЕТ (см. JudgeRun)
        (stop, reason) = JudgeRun(stop, reason, tally.RowsDone, wholeRows, MaxCells);

        // РАБОТА КОНЧИЛАСЬ — УБИРАЕМ ЗА СОБОЙ И СВЕРЯЕМСЯ. Всё, что после
        // этого осталось не так, дописывается в ПРИЧИНУ отчёта: зелёный отчёт
        // при забытых посреди дороги лесах — это ровно то враньё, за которое
        // ловили урезанный заход («341 рядов из 341» про треть дороги).
        //
        // ТОЛЬКО ПРИ ЗАКОНЧЕННОЙ ДОРОГЕ, и это важно: заход, прерванный ради
        // еды или упёршийся в потолок клеток, будет ПРОДОЛЖЕН — снять сейчас
        // подпорку, по которой бот через минуту полезет обратно, значит
        // помешать самому себе. Незаконченная дорога взамен НАЗЫВАЕТ свои
        // леса вслух (см. ниже), а снимет их последний заход или
        // <see cref="RoadResume.KeepBuildingAsync"/>, когда всё кончится
        if (stop == RoadStop.Done)
        {
            string after = await AfterWorkAsync(plan, tally.RowsDone, ct);
            if (after.Length > 0)
                reason += "; " + after;
        }
        // Слова про недоснятые леса живут у самих лесов (TempBlocks.OweRule):
        // тот же случай бывает и у карьера, и говорить про него двумя голосами
        // незачем
        else if (ctx.Temp.Owe("дорога") is { Length: > 0 } owed)
            reason += "; " + owed;

        // ТРАВА, ДО КОТОРОЙ НЕ ДОТЯНУЛСЯ, — В ОТЧЁТ, А НЕ В МОЛЧАНИЕ. Из-за неё
        // дорога больше не встаёт (см. DigTopDownAsync), и ровно поэтому о ней
        // надо сказать: иначе «дорога доведена до конца» стало бы зелёным
        // отчётом про ход, в котором торчит папоротник. Называем поимённо и с
        // числом — по трое, чтобы строка осталась читаемой.
        //
        // СПРАШИВАЕМ МИР, А НЕ ПАМЯТЬ, И ЭТО НЕ ПРИДИРКА К СЛОВУ. Причина, по
        // которой до папоротника не дотянулись, — земля ПОД ним («мешает
        // soil-medium-normal в (512035, 111, 512236)»), и её бот снимает
        // следующим же ударом: выемку копают сверху вниз. Держаться папоротнику
        // становится не на чем, он падает сам — и клетка, честно записанная в
        // отказ минуту назад, к отчёту стоит пустой. Печатай мы память,
        // законченная дорога отчитывалась бы «в просвете осталось 3 кл.» про
        // чистый ход: то же враньё, ради устранения которого затевался счёт.
        // Пустую и непрогруженную клетку молча выбрасываем: NeedsClearing
        // отвечает «есть ли тут что ломать» по нынешнему миру
        var stillThere = tally.Untouched.Where(NeedsClearing).ToList();
        if (stillThere.Count > 0)
            reason += $"; в просвете осталось {stillThere.Count} кл., до которых не " +
                      $"дотянулся (проходу и полотну они не мешают): " +
                      string.Join(", ", stillThere.Take(3)
                          .Select(c => $"{c} ({ctx.World.GetBlockCode(c) ?? "?"})")) +
                      (stillThere.Count > 3 ? " и ещё " + (stillThere.Count - 3) : "");

        var report = Report(stop, reason, surface, wholeRows, cells);
        OnLog?.Invoke(report.ToString());
        return report;
    }

    /// <summary>
    /// ЧТО ДЕЛАЕТСЯ, КОГДА ДОРОГА КОНЧИЛАСЬ: снять свои временные леса и
    /// сверить положенное полотно с раскладкой.
    ///
    /// ЗАКАЗ ЧЕЛОВЕКА, дословно: «надо проверять объекты потом на лишние блоки,
    /// разрешить строить временные леса во время стройки или копания объектов,
    /// которые в конце убираем».
    ///
    /// СВЕРЯЕМ ТОЛЬКО ПОЛОЖЕННОЕ, а не всю задуманную дорогу: ряды, до которых
    /// заход не дошёл, ещё не строились, и объявлять их «недостачей» значило бы
    /// назвать недоделкой то, что честно отложено на следующий заход.
    ///
    /// Механизмы тут чужие — своих ни одного: леса снимает
    /// <see cref="TempBlocks.TakeDownAsync"/>, сверяет <see cref="BuildCheck"/>,
    /// раскладку даёт <see cref="RoadPlan.MeantCells"/>. Здесь только «когда».
    ///
    /// Возвращает жалобу для отчёта или пустую строку, если всё чисто.
    /// </summary>
    private async Task<string> AfterWorkAsync(Planned?[] plan, int rowsDone,
        CancellationToken ct)
    {
        var complaints = new List<string>();

        if (ctx.Temp.TakeDownAfterWork && ctx.Temp.Count > 0)
        {
            var cleanup = await ctx.Temp.TakeDownAsync(ct: ct);
            if (!cleanup.Success)
                complaints.Add(cleanup.ToString());
        }

        if (ctx.Check.AfterWork && rowsDone > 0)
        {
            var meant = new List<MeantCell>();
            for (int i = 0; i < rowsDone && i < plan.Length; i++)
                if (plan[i] is { } row)
                    meant.AddRange(RoadPlan.MeantCells(row.Row.Cells, row.Step.Level,
                        ClearHeadroom ? Height : 0,
                        // Сверка спрашивает ТЕМ ЖЕ, чем клали: у экономной
                        // ступеньки нижнего блока нет, и требовать его значит
                        // объявлять брак там, где сделано по заказу
                        cell => BedHolds(cell, row.Step.Level)));
            var check = await ctx.Check.CheckAsync("дорогу", BuildCheck.Merge(meant), ct);
            if (!check.Success)
                complaints.Add(check.ToString());
        }

        return string.Join("; ", complaints);
    }

    /// <summary>
    /// Высота ПОЛА под клеткой оси — клетка, куда встанут ноги.
    ///
    /// Ищем ОТ ПОДСКАЗКИ наружу, а не сверху вниз. Сверху вниз первым
    /// «полом» оказывается крона дерева, и дорога полезла бы по веткам;
    /// подсказка же — уровень предыдущего ряда, то есть та самая земля,
    /// по которой дорога и идёт.
    ///
    /// null — земли под осью не видно: либо чанк не прогружен, либо там
    /// действительно пусто. Отличить эти два случая, не подойдя, нельзя.
    /// </summary>
    private int? GroundAt(int x, int z, int hintY)
    {
        for (int d = 0; d <= GroundLook; d++)
        {
            for (int side = 0; side < 2; side++)
            {
                int y = side == 0 ? hintY - d : hintY + d;
                if (d == 0 && side == 1)
                    continue;
                int under = y - 1;
                bool floor = ctx.World.IsSolid(x, under, z) ||
                             (BridgeWater && ctx.World.IsWater(x, under, z));
                if (!floor || !ctx.World.IsPassable(x, y, z))
                    continue;
                // Над лавой дороги не бывает: туда не встать и оттуда не уйти.
                // Говорим прямо, иначе выше это выйдет как «земли не видно»,
                // и человек пойдёт искать непрогруженный чанк вместо лавы
                if (ctx.World.IsDangerousLiquid(x, under, z))
                {
                    OnLog?.Invoke($"под ({x}, {under}, {z}) лава — дороге тут не место");
                    return null;
                }
                return y;
            }
        }
        return null;
    }

    // ---------------- первый проход: проходка ----------------

    /// <summary>
    /// ЕСТЬ ЛИ В КЛЕТКЕ ЧТО ЛОМАТЬ. Вопрос не «пройду ли я сквозь неё», а
    /// «свободна ли она под блок», и это разные вопросы.
    ///
    /// ЖИВОЙ СЛУЧАЙ, дословно: «если на месте установки растет растения, то оно
    /// мешает ставить блок и его нужно сломать». Занятость клетки спрашивали у
    /// проходимости (<c>IsPassable</c>), а у травы, цветка, папоротника и гриба
    /// НЕТ коробки коллизии — клетка считалась пустой. Бот не ломал ничего и
    /// слал установку в занятую клетку: игра ставит блок поверх другого, только
    /// если тот помечен заменяемым (трава помечена, а цветы, папоротники, грибы
    /// и кусты этого мира — нет), и сервер такую установку отбрасывает.
    ///
    /// Вода — не помеха: покрытие встаёт прямо в неё, и получается брод. Лава
    /// не помеха тем более: дорогу над ней бот не поведёт вовсе
    /// (<see cref="GroundAt"/>).
    ///
    /// НЕИЗВЕСТНАЯ КЛЕТКА (чанк не пришёл) — не «занята» и не «пуста»: ломать
    /// там нечего, пока мир не приехал, и говорить о ней нечего.
    /// </summary>
    public bool NeedsClearing(BlockPos p) =>
        // Спрашиваем НАЛИЧИЕ БЛОКА, а не проходимость: > 0 — это «блок есть»,
        // 0 — «точно воздух», а UnknownBlock (−1) — «чанка нет», и там ломать
        // нечего (иначе первый проход бьёт по несуществующим блокам на краю
        // выгруженного мира и ряд встаёт Blocked)
        ctx.World.BlockIdOrUnknown(p.X, p.Y, p.Z) > 0 &&
        !ctx.World.IsWater(p.X, p.Y, p.Z) &&
        !ctx.World.IsDangerousLiquid(p.X, p.Y, p.Z);

    /// <summary>Эта клетка полотна уже закрыта тем, что нам и нужно.</summary>
    private bool AlreadyGood(BlockPos spot, string surface) =>
        Same(ctx.World.GetBlockCode(spot), surface) ||
        (KeepExistingRoad && ctx.World.IsRoadLike(spot.X, spot.Y, spot.Z));

    /// <summary>
    /// ЕСТЬ ЛИ ПОД БУДУЩЕЙ ПЛИТОЙ ТО, ЧТО ЕЁ ДЕРЖИТ, — единственный вопрос,
    /// которым экономная ступенька отличается от прежней (см.
    /// <see cref="RoadPlan.Layers"/>).
    ///
    /// СЛОВА ЗАКАЗЧИКА 19.08, дословно: «схема у лестницы твоя не экономная,
    /// зачем ставить под плиты дороги блок дороги? если можно было под ней не
    /// выкапывать просто и ставить на природный блок?». Он прав: на спуске
    /// склон под плитой чаще всего уже сплошной, и прежняя схема выламывала
    /// его ради того, чтобы положить на то же место блок покрытия, который
    /// тут же накрывался плитой и больше никогда не показывался.
    ///
    /// СПРАШИВАЕМ МИР, А НЕ ПРОФИЛЬ. По числам профиля («полотно разошлось с
    /// землёй на полблока») выходило бы, что земля там есть всегда, — а под
    /// склоном бывает пещера, под насыпью пусто, а под бродом вода, и плиту
    /// туда ставить не на что. Мерка одна на весь проект:
    /// <see cref="WorldModel.IsSolid"/> — «на это встают ногой».
    ///
    /// ОДИН И ТОТ ЖЕ ОТВЕТ ОБОИМ ПРОХОДАМ. Копка спрашивает его, чтобы не
    /// снимать эту клетку, укладка — чтобы не класть в неё блок. Разойдись
    /// они на одном ряду, и второй проход клал бы плиту в яму, вырытую первым.
    /// </summary>
    public bool BedHolds(BlockPos cell, int level) =>
        RoadPlan.IsHalf(level) &&
        ctx.World.IsSolid(cell.X, RoadPlan.Bed(level), cell.Z);

    /// <summary>
    /// КУДА ВСТАВАТЬ У ЭТОГО РЯДА ПРЯМО СЕЙЧАС. Один вопрос — один ответ, и
    /// отвечает на него МИР, а не раскладка.
    ///
    /// ЖИВОЙ СЛУЧАЙ 19.08, 23:59–00:01: пять заходов подряд кончились строкой
    /// «до начала дороги (512052, 112, 512252) не дошёл», и каждый раз бот
    /// заново обещал в чат «Мощу дорогу». Ответов на «где у дороги начало» в
    /// боте было ДВА: подход к началу шёл на заданную высоту полотна (там ещё
    /// не выкопано — или уже выкопано, смотря по заходу), а возврат перед
    /// укладкой — на дно выемки (<see cref="RoadPlan.DugFeetCell"/>). Между
    /// заходами мир меняется, и любая из двух догадок промахивается.
    ///
    /// Поэтому спрашиваем: где рядом с этим рядом есть пол. Не нашли — берём
    /// раскладку выкопанного хода, как и раньше: непрогруженный чанк не повод
    /// стоять на месте.
    /// </summary>
    private BlockPos StandAt(BlockPos centre, int level) =>
        new(centre.X,
            ctx.World.FindStandableY(centre.X, RoadPlan.FeetCell(level), centre.Z,
                up: 0, down: 1)
            ?? RoadPlan.DugFeetCell(level, BedHolds(centre, level)),
            centre.Z);

    /// <summary>
    /// ЧТО ЛОМАТЬ В ЭТОМ РЯДУ — по фактам мира, сверху вниз.
    ///
    /// <paramref name="bed"/> — ПЕРВЫЙ ПРОХОД: вынимаем и ход над полотном, и
    /// саму постель полотна (<see cref="RoadPlan.Cut"/>). Это и есть та копка,
    /// которой заказчик не дождался: «выкопал блок и туда блок дороги, а я
    /// просил в начале копать, а только потом пойти ставить блоки».
    ///
    /// Без <paramref name="bed"/> — ход и только ход (<see cref="RoadPlan.Trench"/>):
    /// так ряд пересматривают ПЕРЕД укладкой, потому что между проходами гравий
    /// сыплется, а трава растёт. Трогать там постель нельзя: в ней к этому часу
    /// может уже лежать полотно.
    ///
    /// УЖЕ ПОЛОЖЕННОЕ НЕ ВЫЛАМЫВАЕМ. Клетка постели, где лежит наше покрытие
    /// или чужая дорога (<see cref="KeepExistingRoad"/>), остаётся на месте:
    /// иначе повторный заход по своей же дороге разбирал бы её и клал заново.
    ///
    /// Метод открыт нарочно: это единственное место, где решается «копать или
    /// нет», и стенду он нужен без мира и без кирки.
    /// </summary>
    public IReadOnlyList<BlockPos> ToBreak(RoadRow row, RoadLevel step, string surface, bool bed)
    {
        // Ход над полотном чистим по ручке, постель — всегда: в занятую клетку
        // блок не встанет, сколько ни проси
        var cells = bed
            ? RoadPlan.Cut(row.Cells, step.Level, ClearHeadroom ? Height : 0,
                cell => BedHolds(cell, step.Level))
            : ClearHeadroom ? RoadPlan.Trench(row.Cells, step.Level, Height) : [];

        var todo = new List<BlockPos>();
        foreach (var cell in cells)
        {
            if (!NeedsClearing(cell))
                continue;
            // ОБА СЛОЯ ПОЛОТНА, А НЕ ОДНА ПОСТЕЛЬ. Здесь спрашивали только
            // про постель, а у ступеньки слоёв два — и верхний, полублок,
            // ничем не был защищён. Живой случай 17.08, 23:48:09: заход
            // прервали ради еды, возврат начал дорогу с той же клетки, и
            // первый проход снёс полублок, положенный секундой раньше
            // («[добыча] ломаю stonepathslab-free»). Ровно это заказчик и
            // назвал «ступени дороги неправильно делает»
            if (RoadPlan.LayerAt(step.Level, cell.Y, BedHolds(cell, step.Level)) is { } layer &&
                AlreadyLaid(cell, layer, surface))
                continue;
            todo.Add(cell);
        }
        return todo;
    }

    /// <summary>
    /// В КЛЕТКЕ УЖЕ ЛЕЖИТ ТО, ЧТО МЫ СОБИРАЛИСЬ СЮДА ПОЛОЖИТЬ.
    ///
    /// Полный слой сверяем с покрытием (<see cref="AlreadyGood"/>), верх
    /// ступеньки — ФОРМОЙ из реестра (<see cref="GoodSlab"/>), тем же
    /// правилом, каким полублок и выбирается. Код полублока тут нарочно НЕ
    /// сравнивается: он пересчитывается на каждом ряду и посреди дороги может
    /// смениться (см. <see cref="RoadPlan.SlabSwitch"/>) — требуй мы совпадения
    /// кода, бот выламывал бы собственные ступеньки всякий раз, когда в сумках
    /// кончился один полублок и начался другой.
    /// </summary>
    private bool AlreadyLaid(BlockPos spot, RoadLayer layer, string surface) =>
        layer == RoadLayer.Full
            ? AlreadyGood(spot, surface)
            : ctx.World.GetBlockCode(spot) is { } code &&
              GameBlock(code) is { BlockId: > 0 } block && GoodSlab(code, block);

    /// <summary>
    /// ЧТО ИЗ НАМЕЧЕННОГО БЕРЁМ ПРЯМО СЕЙЧАС, А ЧТО ОСТАВЛЯЕМ ДО СЛЕДУЮЩЕГО
    /// РЯДА. Единственное место, где дорога делит выемку на «беру» и «потом», —
    /// через него ходит и свежий ряд, и отложенное с прошлого
    /// (<see cref="DigTopDownAsync"/>).
    ///
    /// Клетка прямо под ногами не трогается — сломать её значит упасть в
    /// собственную работу, — а вместе с ней и ВСЁ, что под ней в том же
    /// столбце: над оставшимся стоит порода, и до нижнего блока ни дотянуться,
    /// ни увидеть. Живой случай 01:31:00: бот задержал (512066, 111, 512241)
    /// как пол под собой, тут же взялся за (512066, 110, 512241) и получил
    /// «нет прямой видимости: мешает soil-medium-normal в (512066, 111,
    /// 512241)» — то есть уткнулся в собственную кровлю и остановил всю дорогу.
    ///
    /// Само правило — чистое и лежит у раскладки выемки
    /// (<see cref="RoadPlan.TopDown"/>); здесь только «чьи ноги мешают».
    /// Метод открыт нарочно — ровно затем же, зачем открыт
    /// <see cref="ToBreak"/>: стенду он нужен без мира и без кирки.
    /// </summary>
    /// <param name="feet">Клетка ног бота; null — где стоим, неизвестно.</param>
    public (IReadOnlyList<BlockPos> Now, IReadOnlyList<BlockPos> Later) SplitTopDown(
        IEnumerable<BlockPos> cells, BlockPos? feet) =>
        RoadPlan.TopDown(cells, cell => feet is { } f && RoadPlan.FloorUnderFeet(f, [cell]));

    /// <summary>
    /// ПОДОЙТИ К РЯДУ ПЕРВЫМ ПРОХОДОМ. Полотна ещё нет, и идём мы по той самой
    /// земле, по которой дорога пойдёт: раз <see cref="GroundAt"/> нашёл под
    /// осью пол, стоять там есть на чём.
    ///
    /// Несостоявшийся шаг здесь НЕ приговор, и «не дошёл» тут не сообщается
    /// нарочно: ломать блоки можно и с соседней клетки, а не дотянулся — об
    /// этом честно скажет сама кирка, назвав клетку. Отказывать всей дороге
    /// из-за того, что тело замешкалось на кочке, — это отказ на пустом месте.
    ///
    /// Шагаем тем же приёмом, что и второй проход (StepInto, а не дальняя
    /// дорога с её пятью минутами на попытку): в насыпи клетка хода висит в
    /// воздухе, встать в неё нельзя вовсе, и дальняя дорога честно проискала
    /// бы туда путь весь свой срок — на каждый такой ряд.
    ///
    /// ДОРОГА, ИДУЩАЯ ВНИЗ (И В ГОРУ), — ОТДЕЛЬНЫЙ СЛУЧАЙ, и ради него метод
    /// знает про ПРЕДЫДУЩИЙ ряд. Клетка ног будущего ряда там — ещё нетронутая
    /// порода: её и предстоит выкопать, встать в неё нельзя, пока она стоит.
    /// Живой случай 01:31:33, дословно:
    ///   «маршрут до клетки: 1 точек (попытка 1): (512064, 112, 512241)»
    ///   «до (512064, 110, 512241) не хватает 3 бл по высоте, и ближе не
    ///    становится — обычной дорогой отсюда не выйти»
    ///   «наверх не полезу: цель на 2 бл НИЖЕ меня»
    /// — и так на каждый ряд, по нескольку секунд впустую. А кончалось это
    /// хуже, чем потерей времени: бот оставался стоять НА том самом столбце,
    /// который копал, и весь столбец уходил в отложенное как пол под ногами.
    ///
    /// ЖИВОЙ ЗЕМЛЕКОП СТОИТ НА ВЫКОПАННОМ И КОПАЕТ ПЕРЕД СОБОЙ. Поэтому, когда
    /// клетка ног нового ряда — твердь, бот идёт не в неё, а на ДНО УЖЕ
    /// ВЫКОПАННОГО предыдущего ряда (<see cref="RoadPlan.DugFeetCell"/>):
    /// оттуда до всего столбца рукой подать, и никакая его клетка не
    /// оказывается под собственными ногами.
    /// </summary>
    /// <param name="before">
    /// Осевая клетка и уровень предыдущего ряда — того, что уже выкопан.
    /// null у самого первого ряда: позади ещё ничего нет.
    /// </param>
    private async Task WalkAlongAsync(BlockPos centre, int level,
        (BlockPos Centre, int Level)? before, CancellationToken ct)
    {
        var onLine = new BlockPos(centre.X, RoadPlan.FeetCell(level), centre.Z);
        if (StandingOn(onLine))
            return;

        // Твердь в клетке ног — это не «не дошёл», это «ещё не выкопано».
        // Ходить туда незачем и вредно
        if (ctx.World.IsSolid(onLine.X, onLine.Y, onLine.Z) && before is { } was)
        {
            // Дно предыдущего ряда — на клетку ниже полотна, пока постель
            // вынута, и вровень с полотном, если ряд успели замостить (так
            // ходит выключенный DigFirst). Спрашиваем мир, а гадаем только
            // когда он молчит: непрогруженный чанк — не повод стоять на месте
            var dug = StandAt(was.Centre, was.Level);
            if (!StandingOn(dug))
                await ctx.Movement.StepIntoAsync(dug, StepAsideSeconds, ct);
            return;
        }

        await ctx.Movement.StepIntoAsync(onLine, StepAsideSeconds, ct);
        if (!StandingOn(onLine))
            await ctx.Movement.MoveToCellAsync(onLine, ct);
    }

    /// <summary>
    /// НАВЕСТИ МОСТ ТАМ, ГДЕ ПОЛОТНО ВИСИТ НАД ЗЕМЛЁЙ, И ПЕРЕЙТИ ПО НЕМУ.
    ///
    /// ЖИВОЙ СЛУЧАЙ 22.08, 17:18:35, дословно из журнала заказчика:
    ///   «ПРОХОДКА ВСТАЛА на ряду 11 из 29: у (55, 112, 263) полотно на
    ///    заданной высоте 112 разошлось с землёй на 5 бл — ТУТ НУЖЕН МОСТ, а
    ///    насыпь в воздухе бот не держит».
    /// Бот сам назвал приём, которым эта беда лечится, — и не позвал его. Мост
    /// к тому дню в дереве был и был проверен телом
    /// (<see cref="Scaffolding.BridgeAsync"/>, стенд
    /// <c>МостТеломПроходитсяTests</c>): присед, блок по боковой грани, шаг на
    /// него, повтор. Дорога же отвечала словами прошлой волны и вставала,
    /// отдавая заказчику ноль рядов там, где раньше он получал одиннадцать.
    ///
    /// ВТОРОГО МОСТА ЗДЕСЬ НЕТ И БЫТЬ НЕ ДОЛЖНО. Дорога считает КЛЕТКИ (это её
    /// дело: она одна знает, где идёт полотно), а кладёт и переходит — тот же
    /// <see cref="Scaffolding.BridgeAsync"/>, каким через провалы ходит всё
    /// остальное тело бота. Присед, выбор боковой грани, честная проверка «ноги
    /// на той стороне» и отказ с числами приходят оттуда целиком.
    ///
    /// КУДА ЛОЖИТСЯ НАСТИЛ. В клетку <see cref="RoadPlan.Bed"/> осевой полосы —
    /// ту, что на клетку ниже ног. Это НЕ второй ответ на вопрос «где лежит
    /// полотно»: у ровного места там и лежит полный блок покрытия, а у
    /// ступеньки — её нижний блок (<see cref="RoadPlan.Layers"/>), и обе
    /// раскладки сходятся на одной клетке. Настил кладётся не покрытием, а
    /// тем, что не жалко (<c>Mining.SpareBlock</c> внутри моста): полотно
    /// ляжет сюда вторым проходом, как и на всей остальной дороге, а под
    /// ступенькой этот же блок и останется опорой — ровно та экономия, которую
    /// просил заказчик («ставить на природный блок»).
    ///
    /// ТОЛЬКО ОСЬ, А НЕ ВСЯ ШИРИНА. По оси бот идёт сам, и держать его должно
    /// именно её полотно; края ряда кладёт укладка, стоя уже на этом мосту, —
    /// рукой до них подать. Мостить всю ширину первым проходом значило бы
    /// тратить втрое больше блоков на то, по чему никто не пойдёт дважды.
    /// </summary>
    /// <param name="plan">Разведанные ряды захода.</param>
    /// <param name="first">Ряд, на котором полотно оторвалось от земли.</param>
    private async Task<(bool Crossed, string Why)> BridgeRunAsync(Planned?[] plan, int first,
        CancellationToken ct)
    {
        // ПРОЛЁТ — ЭТО ПОДРЯД ИДУЩИЕ ВИСЯЧИЕ РЯДЫ, а не один. Мост кладут и
        // проходят целиком: остановиться на середине — это остаться стоять над
        // пустотой, и сам мост об этом говорит прямо («по половине моста никуда
        // не придёшь»)
        var deck = new List<BlockPos>();
        for (int i = first; i < plan.Length && plan[i] is { } p && VoidUnder(p.Step.OffGround); i++)
        {
            var cell = new BlockPos(p.Row.Centre.X, RoadPlan.Bed(p.Step.Level), p.Row.Centre.Z);
            // Начало пролёта, уже сложенное прошлым заходом (или прошлым рядом
            // этого же), пропускаем: позови мы мост от самого начала, он повёл
            // бы тело НАЗАД по готовому настилу — туда, откуда мы только что
            // пришли
            if (deck.Count == 0 && ctx.World.IsSolid(cell.X, cell.Y, cell.Z))
                continue;
            deck.Add(cell);
        }
        if (deck.Count == 0)
            return (true, "");

        if (ctx.Scaffolding is not { } builder)
            // ЧЕСТНЫЙ ОТКАЗ, А НЕ МОЛЧАНИЕ: библиотеку можно собрать и без
            // стройки, и тогда мостить некому — но человек обязан прочитать
            // ИМЕННО ЭТО, а не «насыпь в воздухе бот не держит»
            return (false,
                $"у {plan[first]!.Row.Centre} под полотном провал в {deck.Count} кл, " +
                "и его надо мостить — а мостить некому: стройка не подключена");

        var bridge = await builder.BridgeAsync(deck, ct);
        return (bridge.Success, bridge.Success
            ? ""
            : $"у {plan[first]!.Row.Centre} под полотном провал в {deck.Count} кл — {bridge.Why}");
    }

    /// <summary>
    /// Клетки, отложенные до следующего ряда: в свой черёд они были прямо ПОД
    /// НОГАМИ — или ПОД ТАКОЙ КЛЕТКОЙ в том же столбце, что то же самое:
    /// сквозь неё до них не дотянуться. Ломать пол под собой — это упасть в
    /// собственную работу, а отходить ради него в сторону на каждом ряду — это
    /// не стройка, а переминание с ноги на ногу. Живой землекоп доламывает
    /// ПОЗАДИ СЕБЯ, и бот теперь тоже: со следующего ряда до отложенной клетки
    /// рукой подать.
    ///
    /// На РОВНОЙ дороге сюда попадает постель клетки, в которой бот стоит; на
    /// дороге ВНИЗ не попадает ничего — там землекоп стоит на уже выкопанном
    /// предыдущем ряду и копает перед собой (см. <see cref="WalkAlongAsync"/>).
    /// </summary>
    private readonly List<BlockPos> deferred = [];

    /// <summary>
    /// ВЫКОПАТЬ ОДИН РЯД. Что именно ломать, решает <see cref="ToBreak"/>;
    /// здесь только руки и порядок.
    ///
    /// <paramref name="bed"/> — первый проход, с постелью полотна. Иначе —
    /// пересмотр хода перед укладкой.
    /// </summary>
    private async Task<(RoadStop Stop, string Reason)> DigRowAsync(RoadRow row, RoadLevel step,
        string surface, bool bed, Tally tally, CancellationToken ct)
    {
        // СПЕРВА ДОЛАМЫВАЕМ ОТЛОЖЕННОЕ: пока мы шли сюда, та клетка осталась
        // позади и из-под ног ушла
        var (leftStop, leftWhy) = await DigDeferredAsync(surface, tally, ct);
        if (leftStop != RoadStop.Done)
            return (leftStop, leftWhy);

        return await DigTopDownAsync(ToBreak(row, step, surface, bed),
            bed ? "в выемке дороги" : "над полотном", _ => false,
            cell => Vital(cell, step), tally, ct);
    }

    /// <summary>
    /// БЕЗ ЭТОЙ КЛЕТКИ ДОРОГИ НЕ БУДЕТ — или это уборка над головой.
    ///
    /// Спрашиваются два готовых ответа и ни одного своего: РАСКЛАДКА говорит,
    /// ляжет ли сюда слой полотна (<see cref="RoadPlan.LayerAt"/>), а МИР —
    /// проходит ли сквозь клетку тело (<see cref="WorldModel.IsPassable"/>).
    ///
    /// ЖИВОЙ СЛУЧАЙ, ради которого правило и появилось (17.08, 23:53, из чата
    /// игры): «дорога 18 рядов из 44 … остановка на (512036, 110, 512236):
    /// (512035, 112, 512236) в выемке дороги: до fern-deerfern не дотянуться».
    /// Дорогу в сорок четыре ряда убил папоротник над полотном: коробки
    /// столкновений у него нет — сквозь него ходят, — и класть в него ничего не
    /// собирались. Такую клетку бот теперь чистит, если достанет, а не достанет
    /// — говорит о ней и работает дальше (<see cref="DigTopDownAsync"/>).
    ///
    /// Метод открыт нарочно — ровно затем же, зачем открыт <see cref="ToBreak"/>:
    /// это решение «встать или идти дальше», и стенду оно нужно без кирки.
    /// </summary>
    public bool Vital(BlockPos cell, RoadLevel step) =>
        RoadPlan.LayerAt(step.Level, cell.Y, BedHolds(cell, step.Level)) != null ||
        !ctx.World.IsPassable(cell.X, cell.Y, cell.Z);

    /// <summary>
    /// ВЫКОПАТЬ СПИСОК КЛЕТОК СВЕРХУ ВНИЗ, откладывая то, до чего сейчас не
    /// добраться. ОДНО МЕСТО НА ОБА СЛУЧАЯ — и свежий ряд, и отложенное с
    /// прошлого: заведи второе, и правило «ниже задержанной клетки ничего не
    /// беру» разошлось бы по копиям, а разойтись ему нельзя — ровно на нём
    /// дорога вниз и вставала десять заходов подряд (живой случай 01:31:00).
    ///
    /// Само правило — чистое и лежит у раскладки выемки
    /// (<see cref="RoadPlan.TopDown"/>). Здесь только руки: удары, переезды
    /// тела и честный отказ.
    ///
    /// ПОСЛЕ КАЖДОГО ПЕРЕЕЗДА ТЕЛА ОСТАТОК ПЕРЕСОБИРАЕТСЯ ТЕМ ЖЕ ПРАВИЛОМ.
    /// Бот и подходит к клетке сам, и падает в собственную выемку: пропусти он
    /// одну задержанную клетку и возьмись за следующую по списку — под кровлей
    /// снова оказалась бы взятая.
    ///
    /// ЖИЗНЕННО ВАЖНАЯ КЛЕТКА И КЛЕТКА УБОРКИ — РАЗНЫЕ ВЕЩИ, И ЭТО ГЛАВНОЕ,
    /// ЧТО ЗДЕСЬ РЕШАЕТСЯ. Живой случай 17.08, 23:53, дословно из чата игры:
    /// «дорога 18 рядов из 44 … остановка на (512036, 110, 512236): (512035,
    /// 112, 512236) в выемке дороги: до fern-deerfern не дотянуться». Дорогу в
    /// 44 ряда убил ПАПОРОТНИК в двух клетках над полотном: у растения нет
    /// коробки столкновений — сквозь него проходят как сквозь воздух, и
    /// положить в него ничего не собирались. А не дотянулся бот до него потому,
    /// что луч перекрывала земля ПОД ним — та самая, которую он и шёл копать
    /// («[руки] до (512035, 112, 512236) нет прямой видимости: мешает
    /// soil-medium-normal в (512035, 111, 512236)»): выемку снимают сверху вниз,
    /// и верхушка столбца видна не всегда. Убери землю — папоротник упадёт сам,
    /// держаться ему не на чем.
    ///
    /// Поэтому: не вышло взять клетку, куда ляжет полотно или сквозь которую не
    /// пройти, — это остановка дороги, как и было. Не вышло взять траву в
    /// просвете — это строка в отчёте и работа дальше.
    ///
    /// СТОЛБ ВЫШЕ СОБСТВЕННОЙ ГОЛОВЫ БЕРЁТСЯ ЦЕЛИКОМ, А НЕ НА ОДНУ ПОМЕХУ
    /// (02.09). Разбор — у самого круга снятия помех ниже; коротко: при
    /// <see cref="Height"/> = 5 луч до верхней клетки идёт почти отвесно и
    /// пересекает НЕСКОЛЬКО клеток той же выемки, а снималась одна. Живьём
    /// это стоило заказчику «дорога 0 рядов из 24, выкопано 33 кл.».
    /// </summary>
    /// <param name="where">Как назвать место в отказе: выемка или ход над полотном.</param>
    /// <param name="skip">
    /// Клетка, которую трогать уже не надо (осыпалась сама, легло полотно).
    /// У свежего ряда таких нет — их отсеял <see cref="ToBreak"/>; у
    /// отложенного есть: между откладыванием и возвратом проходят минуты.
    /// </param>
    /// <param name="vital">
    /// «Без этой клетки дороги не будет»: туда ляжет слой полотна либо сквозь
    /// неё не проходит тело. Остальное — уборка над головой.
    /// </param>
    private async Task<(RoadStop Stop, string Reason)> DigTopDownAsync(
        IReadOnlyList<BlockPos> cells, string where, Func<BlockPos, bool> skip,
        Func<BlockPos, bool> vital, Tally tally, CancellationToken ct)
    {
        var rest = new List<BlockPos>(cells);
        // Клетки, снятые РАНЬШЕ СВОЕЙ ОЧЕРЕДИ, потому что перекрывали луч до
        // соседки. Второй раз бить по воздуху нечего: сервер ответит отказом,
        // и честный отказ дороги вышел бы на пустом месте
        var taken = new HashSet<BlockPos>();
        while (rest.Count > 0)
        {
            var (сперва, later) = SplitTopDown(rest, ctx.Movement.FeetCell);
            Postpone(later);
            rest.Clear();
            if (сперва.Count == 0)
                break;

            // ШАХМАТКИ ЗДЕСЬ НЕТ, И ЭТО НЕ ЗАБЫВЧИВОСТЬ, А СЧЁТ.
            //
            // Тут стояло «var now = ctx.Mining.Очередь(сперва, забойДороги)» с
            // обещанием «дорога шире — целые блоки идут без правок». Обещание
            // было ложным: дорога кормит шахматку ОДНИМ РЯДОМ, у всех клеток
            // ряда координата вдоль полотна ОДНА (чередовать поперечные слои
            // нечего), а сосед ВПЕРЁД в снимаемое не входит и стоит нетронутой
            // породой — значит твёрдая грань есть у КАЖДОЙ клетки ряда, а игра
            // отдаёт целый блок только при всех шести свободных
            // (BreakIfFloating). Целых НОЛЬ при любой ширине; проверено
            // числами: ход 3×3×8 объёмом даёт 3 целых из 72, он же срезами —
            // 0 из 72 (стенд ШахматкаПорядкомTests).
            //
            // Правило, которое заведомо возвращает свой же список, — это
            // рычаг, который ничего не двигает, и подмену его никакой стенд
            // дороги не покраснеет. Ровно так же из этого файла ушла в своё
            // время перестановка граней у цельного камня. Дорога снова копает
            // своим порядком — СВЕРХУ ВНИЗ (нижняя клетка спрятана за верхней,
            // см. живой случай 01:31:00), — и обещание снято из окна и пресетов.
            //
            // ЧТО НУЖНО, ЧТОБЫ ЦЕЛЫЕ БЛОКИ У ДОРОГИ ПОЯВИЛИСЬ: кормить шахматку
            // не рядом, а ДВУМЯ рядами разом — тогда сосед впереди окажется в
            // списке. Это переделка ритма дороги (ряд — мост — полотно — шаг),
            // и в эту волну она не входит; названо вслух в ОСТАЛОСЬ.md
            var wasAt = ctx.Movement.FeetCell;
            for (int i = 0; i < сперва.Count; i++)
            {
                if (ct.IsCancellationRequested)
                    return (RoadStop.Cancelled, "отменено");
                if (ctx.Movement.FeetCell != wasAt)
                {
                    rest.AddRange(сперва.Skip(i));
                    break;
                }
                if (skip(сперва[i]))
                    continue;
                if (taken.Contains(сперва[i]))
                    continue;               // сняли раньше очереди: она мешала соседке
                var cut = await ctx.Mining.BreakAsync(сперва[i], ct);

                // ЛУЧ УПЁРСЯ В МОЮ ЖЕ ВЫЕМКУ — СНИМАЮ ПОМЕХУ И БЕРУСЬ ЗАНОВО.
                // Сам выбор — чистое правило с живым случаем заказчика в
                // описании (<see cref="ClearTheAim"/>); здесь только руки.
                //
                // ЛУЧ СЧИТАЕМ ТОЛЬКО ПОСЛЕ НЕУДАЧИ: на удачном ударе спрашивать
                // «а что мешало» незачем, а ход стоит одного прохода по клеткам
                //
                // ПОМЕХУ БЕРЁМ ТОЛЬКО ИЗ «сперва», А НЕ ИЗ ВСЕГО СПИСКА. В «cells»
                // лежит и отложенное — пол под собственными ногами и всё, что
                // под ним (см. SplitTopDown). Сними его «раньше очереди» — и
                // бот выломает пол под собой и упадёт в свою же выемку: та
                // самая беда, ради которой откладывание и заведено
                //
                // ПОМЕХ НА ЛУЧЕ БЫВАЕТ НЕ ОДНА, И ЭТО ПЕРЕПИСАНО 02.09. Здесь
                // стояло «if»: снимали РОВНО ОДНУ помеху и брались за цель
                // второй раз. На выемке высотой в пять клеток
                // (Roads.Height — слово заказчика) этого не хватает никогда:
                // бот стоит на дне своей же выемки и целится в верх соседнего
                // столбца, луч при этом идёт почти отвесно и пересекает
                // НЕСКОЛЬКО клеток той же выемки — и свой неснятый столбец над
                // головой, и целевой. На стенде таких клеток четыре. Первая
                // снималась, остальные оставались — и дорога вставала.
                // Живой журнал 01.09, 23:01:48, дословно:
                //   «до (72, 111, 239) нет прямой видимости … (стою в 72,5,
                //    106, 240,4)»
                //   «ПРОХОДКА ВСТАЛА на ряду 4 из 24: до soil-medium-normal
                //    не дотянуться»
                // Заказчик получил «дорога 0 рядов из 24». Расстояние тут ни
                // при чём: до цели 3,9 бл при руке 4,5 — иначе бот пошёл бы
                // (Hands.WalkingCanHelp), — мешал именно луч.
                //
                // КРУГ КОНЕЧЕН И БЕЗ СЧЁТЧИКА: каждая снятая помеха уходит в
                // «taken», а ClearTheAim снятое второй раз не предлагает
                // (taken.Contains) — значит помех не больше, чем клеток в
                // «сперва». Не поддалась помеха — выходим сразу: долбить её
                // второй раз тем же ударом бессмысленно
                while (!cut.Success && ctx.Hands.Look(сперва[i]).BlockedBy is { } wall &&
                       ClearTheAim(сперва[i], wall, сперва, taken, where) is { Take: true } aim)
                {
                    var first = await ctx.Mining.BreakAsync(wall, ct);
                    if (!first.Success)
                        break;
                    taken.Add(wall);
                    tally.Cleared++;
                    // Слова — ПО ФАКТУ снятия, а не по намерению: помеха
                    // могла и не поддаться, и тогда говорить не о чем
                    OnLog?.Invoke(aim.Say);
                    cut = await ctx.Mining.BreakAsync(сперва[i], ct);
                }

                if (!cut.Success)
                {
                    // ПОЛОТНО И ПРОХОД — ЭТО ДОРОГА. Не вышло — вставать честно
                    if (vital(сперва[i]))
                    {
                        // ЧЕМ ИМЕННО ОТКАЗАЛА КЛЕТКА — В ОТЧЁТ, А НЕ ТОЛЬКО В
                        // СТРОКУ. По этому слову возврат и решает, пробовать ли
                        // снова: «сервер не ответил» проходит за секунду, а «не
                        // дотянуться» не пройдёт никогда (см. Roads.WhatStopped)
                        tally.Cell = cut.Why;
                        return (RoadStop.Blocked, $"{сперва[i]} {where}: {cut}");
                    }

                    // А ТРАВА НАД ГОЛОВОЙ — ЭТО УБОРКА, и хоронить из-за неё
                    // сорок четыре ряда нельзя (живой случай с папоротником
                    // разобран у метода). Но и молчать нельзя: клетка попадёт
                    // в причину отчёта поимённо.
                    //
                    // ЗАПОМИНАЕМ КЛЕТКУ, А НЕ СТРОКУ: имя блока к концу дороги
                    // может уже ничего не значить — сними землю под
                    // папоротником, и он упадёт сам (см. Tally.Untouched)
                    if (!tally.Untouched.Contains(сперва[i]))
                        tally.Untouched.Add(сперва[i]);
                    OnLog?.Invoke($"{сперва[i]} {where}: {cut} — сквозь неё проходят и полотна " +
                                  "в неё не кладут, дорогу из-за неё не бросаю");
                    continue;
                }
                tally.Cleared++;
            }
            // Круг, на котором не сделано ни одного удара, — это круг на месте:
            // остаток честно уходит в отложенное, а не крутится тут до конца
            // отведённого дороге срока
            if (rest.Count == сперва.Count)
            {
                Postpone(rest);
                break;
            }
        }
        return (RoadStop.Done, "");
    }

    /// <summary>
    /// Отложить клетки до следующего ряда. Не «пропустил молча»: их выкопают
    /// со следующего ряда, а не выйдет и там — на худой конец снимет укладка.
    /// </summary>
    private void Postpone(IEnumerable<BlockPos> cells)
    {
        foreach (var cell in cells)
            if (!deferred.Contains(cell))
                deferred.Add(cell);
    }

    /// <summary>
    /// Доломать то, что осталось позади. Клетка, из-под которой мы так и не
    /// ушли, ждёт дальше — второго прохода или следующего ряда.
    ///
    /// ПОЛОТНО, ЛЁГШЕЕ ТУДА, НЕ ТРОГАЕМ. При выключенном
    /// <see cref="DigFirst"/> ряд копают и мостят подряд: отложенную клетку
    /// закрывает укладка того же ряда, и доламывать её со следующего значило
    /// бы разбирать собственную дорогу через клетку от себя.
    ///
    /// СВЕРХУ ВНИЗ И ЗДЕСЬ: в отложенном лежат клетки ОДНОГО столбца — та, что
    /// была под ногами, и всё, что под ней. Возьмись за нижнюю первой —
    /// упрёшься в верхнюю ровно так же, как в живом случае 01:31:00. Порядок и
    /// откладывание держит общий <see cref="DigTopDownAsync"/>.
    /// </summary>
    private async Task<(RoadStop Stop, string Reason)> DigDeferredAsync(string surface,
        Tally tally, CancellationToken ct)
    {
        if (deferred.Count == 0)
            return (RoadStop.Done, "");
        var left = new List<BlockPos>(deferred);
        deferred.Clear();
        // ОТЛОЖЕННОЕ — ВСЕГДА ЖИЗНЕННО ВАЖНОЕ, и потому здесь стоит «true», а не
        // повтор правила из DigRowAsync. Откладывают только клетку ПОД НОГАМИ и
        // то, что под ней в том же столбце (см. SplitTopDown), а ниже ног в
        // выемке лежит ровно постель полотна: клетка, без которой дороги нет
        return await DigTopDownAsync(left, "в выемке дороги",
            spot => !NeedsClearing(spot) || AlreadyGood(spot, surface), _ => true, tally, ct);
    }

    /// <summary>
    /// ТО ЖЕ ДОЛАМЫВАНИЕ, НО ЕГО НЕУДАЧУ ДОРОГА ПЕРЕЖИВАЕТ — И ЗНАЧИТ НЕ ИМЕЕТ
    /// ПРАВА ЕЮ ОТЧИТЫВАТЬСЯ.
    ///
    /// ЗАЧЕМ ОТДЕЛЬНАЯ ДВЕРЬ. Два места зовут доламывание «на всякий случай» и
    /// ответ его выбрасывают нарочно: клетку под ногами последнего ряда ждать
    /// больше некому, а не поддалась она — не беда, её снимет укладка. Дорога
    /// после этого ИДЁТ ДАЛЬШЕ. Но отказ клетки при этом успевал лечь в
    /// <see cref="Tally.Cell"/> — в поле, чьё имя говорит «клетка, НА КОТОРОЙ
    /// ВСТАЛА проходка», — и с тех пор, как этим полем отчитывается СРОК
    /// (<see cref="WhatStopped"/>), пережитая помеха подменяла бы им часы.
    ///
    /// ЭТО РОВНО ТА БЕДА, КОТОРУЮ В ПРОЕКТЕ УЖЕ ЛОВИЛИ У КАРЬЕРА: «обошёл воду
    /// и упёрся в срок — значит в отказе СРОК, а не „дальше опасно для жизни“»
    /// (<c>ПережитаяПомехаНеПричинаОстановкиTests</c>). Карьер решает это на
    /// месте записи (<c>Run.Skip</c> кладёт слово только у ЖИВЫХ пропусков);
    /// дороге проще здесь: пережившему помеху достаточно не оставлять следа.
    /// </summary>
    private async Task DigDeferredSurvivingAsync(string surface, Tally tally,
        CancellationToken ct)
    {
        var было = tally.Cell;
        await DigDeferredAsync(surface, tally, ct);
        tally.Cell = было;
    }

    // ---------------- где стоять, пока мостишь ----------------

    /// <summary>Ноги на этой клетке дороги (правило — в RoadPlan.FeetOnRoad).</summary>
    private bool StandingOn(BlockPos cell) =>
        ctx.Movement.FeetCell is { } f && RoadPlan.FeetOnRoad(f, cell);

    /// <summary>Эта клетка полотна занята моим же телом: я в ней или на ней.</summary>
    private bool UnderMe(BlockPos floor) =>
        ctx.Movement.FeetCell is { } f && RoadPlan.StandsOn(f, floor);

    /// <summary>Стороны света так, как их считает игра: север — это −Z.</summary>
    private static readonly (int Dx, int Dz, string Name)[] Sides =
        [(0, -1, "север"), (1, 0, "восток"), (0, 1, "юг"), (-1, 0, "запад")];

    /// <summary>
    /// Что мешает встать на соседнюю клетку — по-человечески и по фактам.
    ///
    /// Нужно ровно для одного случая: бот говорит «отойти некуда», и человек
    /// обязан узнать ПОЧЕМУ, не поднимая игру. «Некуда» без этого списка
    /// проверить нельзя, а в живом случае 20:16 вокруг было чистое поле.
    /// </summary>
    private string DescribeSide(BlockPos feet, int dx, int dz, HashSet<BlockPos> busy)
    {
        int x = feet.X + dx, z = feet.Z + dz;
        if (ctx.World.FindStandableY(x, feet.Y, z, up: 1, down: 2) is not { } y)
            return ctx.World.IsSolid(x, feet.Y, z)
                ? $"стена {ctx.World.GetBlockCode(new BlockPos(x, feet.Y, z)) ?? "?"}"
                : "опоры нет — обрыв, вода или непрогруженный чанк";
        if (ctx.World.IsDangerousLiquid(x, y, z) || ctx.World.IsDangerousLiquid(x, y - 1, z))
            return "лава";
        if (busy.Contains(new BlockPos(x, y, z)) || busy.Contains(new BlockPos(x, y - 1, z)))
            return "туда же ляжет полотно";
        return $"место есть ({x}, {y}, {z}), но тело туда не пошло";
    }

    /// <summary>
    /// ОТОЙТИ С КЛЕТОК, которые сейчас будем ломать и мостить.
    ///
    /// ЖИВОЙ СЛУЧАЙ 20:16. Дорога кончилась, не начавшись: «0 рядов из 27,
    /// замощено 0 кл. из 81; (512294, 111, 511742) — клетка подо мной, а
    /// отойти с неё некуда». Отойти было куда: вокруг чистое поле.
    ///
    /// Причина в общем приёме Movement.StepAsideFromAsync: он ходит через
    /// MoveToCellAsync, а та считает «дошёл» с допуском в КЛЕТКУ и на соседнюю
    /// клетку отвечает «ты уже там», не сдвинув тела. Проверка «ноги не на той
    /// клетке» после такого ответа не проходила НИКОГДА, а ближайшие три места
    /// (перебираются только они) — ровно соседние клетки. Отказ был
    /// предрешён на ровном поле.
    ///
    /// Поэтому шагаем StepIntoAsync: она доводит тело до ЦЕНТРА клетки и
    /// меряет успех по ногам, а не по допуску.
    /// </summary>
    /// <param name="busy">Клетки полотна, которые сейчас тронем.</param>
    /// <returns>null — отошли (или мешать было нечему); иначе — что вокруг.</returns>
    private async Task<string?> StepOffAsync(IReadOnlyCollection<BlockPos> busy,
        CancellationToken ct)
    {
        if (ctx.Movement.FeetCell is not { } feet)
            return "не знаю, где стою";
        if (!RoadPlan.InTheWay(feet, busy))
            return null;

        // Где вокруг вообще можно стоять — спрашиваем мир; какие из этих мест
        // годятся и в каком порядке — чистое правило RoadPlan.StepOffSpots
        var standable = new List<BlockPos>();
        for (int dx = -StepAsideRadius; dx <= StepAsideRadius; dx++)
        for (int dz = -StepAsideRadius; dz <= StepAsideRadius; dz++)
        {
            if (dx == 0 && dz == 0)
                continue;
            int x = feet.X + dx, z = feet.Z + dz;
            if (ctx.World.FindStandableY(x, feet.Y, z, up: 1, down: 2) is not { } y)
                continue;
            if (ctx.World.IsDangerousLiquid(x, y, z) || ctx.World.IsDangerousLiquid(x, y - 1, z))
                continue;
            standable.Add(new BlockPos(x, y, z));
        }
        var spots = RoadPlan.StepOffSpots(feet, standable, busy);

        foreach (var spot in spots.Take(StepAsideTries))
        {
            if (ct.IsCancellationRequested)
                return "отменено";
            await ctx.Movement.StepIntoAsync(spot, StepAsideSeconds, ct);
            // Успех — только по факту: ноги не в клетке полотна и не на ней
            if (ctx.Movement.FeetCell is { } now && !RoadPlan.InTheWay(now, busy))
                return null;
        }

        var around = new HashSet<BlockPos>(busy);
        return $"стою на {feet}, сойти не вышло ({spots.Count} мест вокруг; " +
               string.Join("; ", Sides.Select(s => $"{s.Name} — {DescribeSide(feet, s.Dx, s.Dz, around)}")) +
               ")";
    }

    // ---------------- один ряд ----------------

    /// <summary>
    /// ВЫЛОЖИТЬ ОДИН ПОПЕРЕЧНЫЙ РЯД — второй проход. Возвращает, чем кончилось,
    /// и код покрытия: он мог смениться посреди ряда, когда прежний кончился.
    ///
    /// СЛОЯМИ, А НЕ ПО БЛОКУ НА КЛЕТКУ. Ровное место — один полный блок
    /// покрытия. Ступенька — ДВА слоя, как и просил заказчик: «блок, полублок
    /// на блок той же высоты что дорога». Что за слои и в каком порядке,
    /// говорит чистое правило <see cref="RoadPlan.Layers"/>.
    ///
    /// ПОРЯДОК ДЕЙСТВИЙ ПЕРЕСОБРАН по разбору живого случая. Раньше бот на
    /// КАЖДУЮ клетку сперва отходил в сторону и только потом смотрел, надо ли
    /// её вообще трогать: на готовой дороге он топтался впустую, а на первом
    /// ряду отказывал ещё до того, как выяснял, что класть. Теперь сначала
    /// решается, что и куда кладём, и только ради настоящей работы бот сходит
    /// с полотна — один раз на ряд.
    /// </summary>
    /// <summary>
    /// ПОДВЕСТИ ОСНОВАНИЕ ПОД ВЕСЬ РЯД — по столбику под каждой клеткой полосы.
    ///
    /// ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ МОСТА. Мост бот кладёт ПЕРВЫМ проходом и только по
    /// ОСИ: ему надо перейти провал, а ходят по одной клетке. Полоса же шириной
    /// в три, и края настил не держит — они ложатся в воздух. Ровно это заказчик
    /// и увидел 23.08: «лестница висит в воздухе». Насыпь идёт ВТОРЫМ проходом,
    /// при укладке, и подводит опору под каждую клетку ряда.
    ///
    /// ЗЕМЛЮ СПРАШИВАЕМ ПО КЛЕТКЕ, А НЕ ПО РЯДУ. Под краем полосы грунт бывает
    /// не тот, что под осью, — на склоне это обычное дело; подсыпь мы всем трём
    /// клеткам «как по центру», и одна повисла бы, а другая получила бы блок
    /// внутрь горы. Высота из профиля идёт лишь ПОДСКАЗКОЙ поиска
    /// (<see cref="GroundAt"/>), чтобы за землю не сошла крона рядом.
    ///
    /// ОТКАЗ ОСТАНАВЛИВАЕТ ДОРОГУ, и это нарочно. Полотно на воздухе — это
    /// ровно та жалоба, ради которой насыпь и заведена; уложить его молча,
    /// «раз уж основание не вышло», значило бы повторить её второй раз.
    /// </summary>
    /// <param name="working">
    /// Клетки полосы (X, Z), где ряду и правда есть что класть. Лежащее уже
    /// на чём-то держится, и подпирать его — не наше дело.
    /// </param>
    private async Task<(bool Based, string Why)> FootingRowAsync(RoadRow row, RoadLevel step,
        IReadOnlyCollection<(int X, int Z)> working, CancellationToken ct)
    {
        // Класть нечего, пустоты нет вовсе (полотно лежит на земле)
        // или подсыпать не велено
        if (working.Count == 0 || MaxFill <= 0 || RoadPlan.FillDepth(step.OffGround) == 0)
            return (true, "");

        // ГЛУБОКИЙ ПРОВАЛ — ЭТО МОСТ, А НЕ НАСЫПЬ, и отказом тут не пахнет:
        // засыпать пропасть землёй не станет и живой игрок
        if (RoadPlan.FillDepth(step.OffGround) > MaxFill)
            return (true, "");

        if (ctx.Scaffolding is not { } builder)
            return (false,
                $"под {row.Centre} полотну не на чем лежать, а подсыпать некому: " +
                "стройка не подключена");

        int hint = (step.Level - step.OffGround) / 2;
        foreach (var cell in row.Cells)
        {
            if (ct.IsCancellationRequested)
                return (false, "отменено");
            if (!working.Contains((cell.X, cell.Z)))
                continue;

            if (GroundAt(cell.X, cell.Z, hint) is not { } soil)
                return (false,
                    $"под клеткой ({cell.X}, {cell.Z}) земли не видно — " +
                    "подсыпать основание не от чего");

            var column = RoadPlan.Footing(step.Level, BedHolds(cell, step.Level), soil);
            if (column.Count == 0)
                continue;

            var cells = column.Select(y => new BlockPos(cell.X, y, cell.Z)).ToList();
            var fill = await builder.EmbankAsync(cells, ct);
            if (!fill.Success)
                return (false,
                    $"под клеткой ({cell.X}, {cell.Z}) основание в {cells.Count} бл " +
                    $"не встало: {fill.Why} (высоту насыпи задаёт «{Knobs.MaxFill}»)");
        }
        return (true, "");
    }

    private async Task<(RoadStop Stop, string Reason, string Surface)> PaveRowAsync(
        RoadRow row, RoadLevel step, string surface, Tally tally, CancellationToken ct)
    {
        // 1. ПОЛУБЛОК НА ВЕРХ СТУПЕНЬКИ. Кусок профиля у ряда один, и
        // спрашивать сумки на каждую клетку незачем
        string slab = "";
        if (step.Piece == RoadPiece.Step)
        {
            // «Полотно уже начато» меряем ПОЛОЖЕННЫМИ КЛЕТКАМИ этого захода, а
            // не рядами и не временем: ровно с первой положенной клетки уходить
            // домой становится «бросить начатое» (см. Roads.MaySupply)
            var (code, why) = await SlabAtHandAsync(tally.Paved > 0, ct);
            if (code == null)
                return (RoadStop.NoMaterial, $"на ступеньку у {row.Centre} {why}", surface);
            slab = code;

            // ХВАТИТ ЛИ ПОЛУБЛОКОВ НА ВЕСЬ РЯД — ДО ПЕРВОГО ПОЛОЖЕННОГО БЛОКА.
            // Спрашивалось «есть ли хоть один», а ряд шириной три требует трёх,
            // и отказ приходил МЕЖДУ слоями одной клетки: низ уже лежал, верха
            // не было. Разбор живого случая и цена ошибки — у Roads.WholeSteps
            int need = row.Cells.Count(c => !Same(
                ctx.World.GetBlockCode(new BlockPos(c.X, RoadPlan.BlockY(step.Level), c.Z)), slab));
            // Не хватило — доделываем тем же рецептом, которым и брали: другой
            // механики добора тут нет, MakeAsync берёт сразу целый стак
            if (Have(slab) < need)
                await MakeAsync(slab, ct);
            var (whole, tooFew) =
                WholeSteps(Have(slab), need, slab, row.Centre, WhyCannotMake(slab));
            if (!whole)
                return (RoadStop.NoMaterial, tooFew, surface);
        }

        // 2. ХОД МОГ ЗАСЫПАТЬСЯ, ПОКА ШЛИ ПЕРВЫМ ПРОХОДОМ: гравий сыплется,
        // трава растёт, а между копкой и укладкой на длинной дороге проходят
        // минуты. Проверка дешёвая (уже чистые клетки не трогаются вовсе), а
        // дорога, по которой не пройти, — нет.
        //
        // Постель тут НЕ трогаем (bed: false): к этому часу в ней может уже
        // лежать полотно — своё с прошлого захода или чужая дорога
        var (digStop, digWhy) = await DigRowAsync(row, step, surface, bed: false, tally, ct);
        if (digStop != RoadStop.Done)
            return (digStop, digWhy, surface);

        // 3. ЧТО ПРИДЁТСЯ КЛАСТЬ. Уже готовое не трогаем: и своё бережём, и чужое
        var todo = new List<(BlockPos At, RoadLayer Layer, bool Counts)>();
        foreach (var cell in row.Cells)
        {
            // Слои спрашиваются ПО КЛЕТКЕ, а не по ряду: под краем полосы склон
            // бывает не тот, что под осью, и экономная ступенька у одной клетки
            // не означает экономной у соседней (см. BedHolds)
            var layers = RoadPlan.Layers(step.Level, BedHolds(cell, step.Level));
            foreach (var (y, layer) in layers)
            {
                var spot = new BlockPos(cell.X, y, cell.Z);
                // КЛЕТКУ СЧИТАЕМ РОВНО ОДИН РАЗ — по её НИЖНЕМУ слою.
                //
                // «Замощено N кл. из M» и «всего под ногами» — это КЛЕТКИ, и
                // слагаемое, считающее слои, ломает их сумму: у неэкономной
                // ступеньки слоёв два. Здесь стояло «считаем только полный
                // слой», и это работало ровно до тех пор, пока полный слой был
                // у каждой клетки; у экономной ступеньки его нет вовсе — она
                // одна плита, — и клетка не попадала в счёт ни разу
                bool counts = y == layers[0].Y;
                string want = layer == RoadLayer.Full ? surface : slab;
                if (Same(ctx.World.GetBlockCode(spot), want) ||
                    (KeepExistingRoad && layer == RoadLayer.Full &&
                     ctx.World.IsRoadLike(spot.X, spot.Y, spot.Z)))
                {
                    if (counts)
                        tally.Skipped++;
                    continue;
                }
                if (ctx.World.IsDangerousLiquid(spot.X, spot.Y, spot.Z))
                    return (RoadStop.Blocked, $"в {spot} лава — дорогу тут не проложить", surface);
                if (ctx.World.IsWater(spot.X, spot.Y, spot.Z) && !BridgeWater)
                    return (RoadStop.Blocked, $"в {spot} вода, а мостить через воду не велено",
                        surface);
                todo.Add((spot, layer, counts));
            }
        }

        // 4. НАСЫПЬ ПОД ТЕМ, ЧТО КЛАДЁМ, — И ТОЛЬКО ПОД НИМ.
        //
        // ПОСЛЕ разбора работы, а не до него, и это НАХОДКА СТЕНДА, а не вкус:
        // «RoadDigBeforePave/ОТЧЁТ на ступеньке» покраснел на первом же заходе.
        // Подсыпая под ВЕСЬ ряд, бот брался подпирать и клетки, где полотно
        // уже лежало с прошлого захода, — а заход, которому класть нечего,
        // обязан пройти молча и сосчитать. Он вместо этого встал: «основание в
        // 1 бл не встало, в сумках 0».
        //
        // Правило же простое и общее: опора нужна тому, что КЛАДУТ. Лежащее
        // уже на чём-то держится — не нам решать, на чём.
        var (based, whyBase) = await FootingRowAsync(row, step,
            todo.Select(t => (t.At.X, t.At.Z)).Distinct().ToList(), ct);
        if (!based)
            return (RoadStop.Blocked, whyBase, surface);

        // 5. КЛАДЁМ, СХОДЯ С ПОЛОТНА. Заходов несколько нарочно: если сойти с
        // последней клетки некуда, кладём те, на которых не стоим, — и уже с
        // готового полотна сходим с последней. Ровно так мостит пол под собой
        // живой игрок, а не отказывается начинать.
        //
        // Порядок внутри ряда не перетасовывается: у ступеньки блок обязан
        // лечь ДО полублока, иначе полублок ставится в воздух
        string? stuck = null;
        for (int pass = 0; pass < 3 && todo.Count > 0; pass++)
        {
            stuck = await StepOffAsync(todo.Select(t => t.At).ToList(), ct);
            if (ct.IsCancellationRequested)
                return (RoadStop.Cancelled, "отменено", surface);
            var now = stuck == null ? todo : todo.Where(t => !UnderMe(t.At)).ToList();
            if (now.Count == 0)
                break;

            var laid = new HashSet<BlockPos>();
            foreach (var (spot, layer, counts) in now)
            {
                // ПОКА КЛАЛИ СОСЕДА, ТЕЛО МОГЛО ПЕРЕЕХАТЬ СЮДА: подход к месту
                // установки — это тоже ходьба, и встать бот мог ровно на
                // следующую клетку полотна. Ломать пол под собой нельзя, а
                // отказывать всему ряду из-за одной клетки — тем более:
                // оставляем её следующему заходу
                if (UnderMe(spot) && await StepOffAsync([spot], ct) != null)
                    continue;
                string code = layer == RoadLayer.Full ? surface : slab;
                var (cellStop, cellWhy, next) =
                    await LayAsync(spot, layer, counts, code, surface, tally, ct);
                if (cellStop != RoadStop.Done)
                    return (cellStop, cellWhy, next);
                if (layer == RoadLayer.Full)
                    surface = next;
                laid.Add(spot);
            }
            todo = todo.Where(t => !laid.Contains(t.At)).ToList();
        }

        if (todo.Count > 0)
            return (RoadStop.Blocked,
                $"ряд {row.Index} у {row.Centre}: осталось {todo.Count} кл. полотна " +
                $"под собственными ногами — {stuck ?? "сойти не удалось"}", surface);

        return (RoadStop.Done, "", surface);
    }

    /// <summary>
    /// Закрыть ОДИН слой одной клетки полотна. Возвращает код покрытия — он мог
    /// смениться прямо здесь, когда прежний кончился.
    /// </summary>
    /// <param name="counts">
    /// Этот слой — НИЖНИЙ у своей клетки, значит им клетка и считается
    /// («замощено N кл.»). У ровного места и у неэкономной ступеньки это
    /// полный блок, у экономной — сама плита: другого слоя у неё нет.
    /// </param>
    private async Task<(RoadStop Stop, string Reason, string Surface)> LayAsync(
        BlockPos spot, RoadLayer layer, bool counts, string code, string surface, Tally tally,
        CancellationToken ct)
    {
        if (ct.IsCancellationRequested)
            return (RoadStop.Cancelled, "отменено", surface);

        bool water = ctx.World.IsWater(spot.X, spot.Y, spot.Z);

        // МАТЕРИАЛ МОГ КОНЧИТЬСЯ ПОСРЕДИ РЯДА. Спрашиваем ДО того, как сняли
        // старый пол: иначе на месте дороги остаётся яма, в которую же и падаешь
        if (Have(code) <= (layer == RoadLayer.Full ? KeepInReserve : 0))
        {
            if (layer == RoadLayer.Half)
            {
                if (!await MakeAsync(code, ct))
                    return (RoadStop.NoMaterial,
                        $"{code} кончился, а ступеньку им не закрыть: {WhyCannotMake(code)}",
                        surface);
            }
            else
            {
                // «ПОСРЕДИ РАБОТЫ» — ЭТО И ВОЗВРАТ ТОЖЕ, а не только полотно
                // ЭТОГО захода. Заход, положивший пока ноль клеток, работу всё
                // равно не начинает с чистого места: до него уже копали и
                // мостили, и рейс домой отсюда — то самое «метался между домом
                // и строительством» (журнал 30.08, семь заходов по нулю рядов)
                if (await MoreSurfaceAsync(code, tally.Resumed || tally.Paved > 0, ct)
                    is not { } more)
                    return (RoadStop.NoMaterial,
                        $"{code} кончился, другого покрытия нет: {WhyCannotMake(code)}", surface);
                if (!Same(more, code))
                    OnLog?.Invoke($"{code} кончился — перехожу на {more}");
                surface = more;
                code = more;
            }
        }

        // Старый пол снимаем — и вместе с ним ВСЁ, что в клетке стоит.
        // Спрашиваем «есть ли тут блок» (NeedsClearing), а не «пройду ли
        // сквозь»: у травы и цветка нет коробки коллизии, прежняя проверка
        // считала такую клетку пустой, и установка уходила в занятую клетку —
        // «если на месте установки растет растения, то оно мешает ставить блок
        // и его нужно сломать». Вода блоком не считается: покрытие встаёт
        // прямо в неё, и получается брод
        if (!water && NeedsClearing(spot))
        {
            var broken = await ctx.Mining.BreakAsync(spot, ct);
            if (!broken.Success)
                return (RoadStop.Blocked, $"{spot}: {broken}", surface);
        }

        var laid = await ctx.Mining.PlaceAsync(spot, code, 4, ct);
        if (!laid.Success)
            return (RoadStop.Blocked, $"{spot} {code}: {laid}", surface);

        if (layer == RoadLayer.Half)
        {
            tally.Steps++;
            // Плита встаёт нижней или верхней половиной по клику. Если сервер
            // поставил её верхом, ход поднялся на блок, а не на полблока —
            // молчать об этом нельзя, по такой дороге пойдут
            if (ctx.World.GetCollisionTop(spot.X, spot.Y, spot.Z) > 0.75f)
                OnLog?.Invoke($"{spot}: {code} встал целым, а не половиной — " +
                              "ступенька вышла выше задуманной");
        }
        // КЛЕТКА СЧИТАЕТСЯ ОДИН РАЗ, СВОИМ НИЖНИМ СЛОЁМ (см. counts). У
        // экономной ступеньки нижний слой — это и есть плита, и оба счёта
        // сходятся на ней: одна ступенька и одна закрытая клетка полотна
        if (counts)
            tally.Paved++;
        return (RoadStop.Done, "", surface);
    }

    /// <summary>
    /// ЧЕМ ЗАКРЫТЬ ВЕРХ СТУПЕНЬКИ: полублок из сумок, а нет в сумках — ПО
    /// РЕЦЕПТУ.
    ///
    /// Раньше здесь спрашивалось «полублок ИЛИ игровая ступень», и крафт уходил
    /// в ступени, пока журнал обещал полублоки, — жалоба заказчика была ровно
    /// об этом. Спрашивать осталось про одно, потому что и кладётся теперь одно.
    ///
    /// Что считать полублоком, знает реестр (форма коробок коллизии), из чего
    /// его сделать — реестр рецептов; выдумывать код руками человек не обязан.
    ///
    /// ЗДЕСЬ ЖЕ ЕДИНСТВЕННЫЙ ВЫХОД ЧЕРЕЗ <see cref="SlabNow"/>. Спрашивают
    /// отсюда на КАЖДОМ ряду со ступенькой, а человеку полублок назвали один раз
    /// на выходе (<see cref="SayAboutSlabs"/>) — значит расхождение слова с
    /// делом рождается ровно тут, тут его и называют вслух.
    /// </summary>
    private async Task<(string? Code, string Why)> SlabAtHandAsync(bool midRoad,
        CancellationToken ct)
    {
        var (code, why) = await PickSlabAsync(midRoad, ct);
        // СМЕНА НАЗЫВАЕТСЯ ЗДЕСЬ И БОЛЬШЕ НИГДЕ. Путей к полублоку два (сумки и
        // крафт), и раньше каждый звал SlabNow сам: убери обёртку у одного — и
        // молчаливая подмена возвращается наполовину, а стенд этого не увидит.
        // Один выход на оба пути обойти нечем
        return (code is null ? null : SlabNow(code), why);
    }

    /// <summary>
    /// ОТКУДА БЕРЁТСЯ ПОЛУБЛОК: сперва сумки, потом рецепт. Про смену здесь ни
    /// слова — о ней говорит один <see cref="SlabAtHandAsync"/>.
    /// </summary>
    private async Task<(string? Code, string Why)> PickSlabAsync(bool midRoad,
        CancellationToken ct)
    {
        if (ChooseSlab() is { } inBags)
            return (inBags, "");
        // Названное настройкой проверяем ДО крафта: сделать по рецепту не
        // полублок и положить его наверх ступеньки — это ступенька в целый
        // блок, через которую бот не перешагнёт
        if (!NamedSlabIsSlab())
            return (null, $"в настройке полублока назван {SlabCode}, а это не полублок " +
                          "(нужен блок в половину клетки — на него всходят без прыжка); " +
                          "сотрите настройку, и я найду полублок сам");
        if (!MayCraft)
            return (null, "нужен ПОЛУБЛОК, а в сумках его нет и крафт выключен");

        var options = SlabCode.Length > 0 ? [SlabCode] : SlabRecipes();
        if (options.Count == 0)
            return (null, SlabCode.Length > 0
                ? $"нужен ПОЛУБЛОК: {SlabCode} нет в сумках, и {WhyCannotMake(SlabCode)}"
                : "нужен ПОЛУБЛОК, а в этом мире нет ни одного рецепта на него " +
                  "(назовите код настройкой — сделаю названное)");

        foreach (string option in options)
            if (CanMake(option) && await MakeAsync(option, ct))
                return (option, "");

        // ИЗ СВОЕГО НЕ ВЫШЛО — СХОДИТЬ ЗА МАТЕРИАЛОМ. Ровно здесь дорога и
        // вставала 16.08: «нужен ПОЛУБЛОК ... на stonepathslab-free не хватает:
        // stone-meteorite-iron (надо 1, есть 0)» — при полном доме камня.
        // Ходит снабжение, дорога только называет, чего ей не хватает
        var (взял, почему) = await FetchSurfaceAsync(options[0], ct, midRoad);
        if (взял || Have(options[0]) > 0)
            return (options[0], "");

        // Ни одного не сделать — называем, чего не хватило на самом
        // подходящем; «материала нет» без подробностей человеку бесполезно
        return (null, "нужен ПОЛУБЛОК, в сумках его нет и сделать не вышло: " +
                      WhyCannotMake(options[0]) + "; " + почему);
    }

    /// <summary>
    /// Чем берём перепады ПРЯМО СЕЙЧАС — то, что было названо человеку
    /// последним. Пусто — ещё ничего не называли.
    /// </summary>
    private string slabSaid = "";

    /// <summary>
    /// ВЗЯТЬ ПОЛУБЛОК И НАЗВАТЬ СМЕНУ, ЕСЛИ ОНА СЛУЧИЛАСЬ.
    ///
    /// Место одно на все пути к полублоку (сумки и крафт) нарочно: выбор
    /// пересчитывается на КАЖДОМ ряду со ступенькой, а сказано о нём было один
    /// раз на выходе (<see cref="SayAboutSlabs"/>). Разойтись слову с делом
    /// можно ровно здесь — здесь и говорим. Что именно сказать, решает чистое
    /// правило <see cref="RoadPlan.SlabSwitch"/>.
    /// </summary>
    private string SlabNow(string code)
    {
        // Пустой код в Have спрашивать нельзя: подстрока «» есть в любом коде,
        // и счёт вышел бы «всё, что в сумках»
        if (slabSaid.Length > 0 &&
            RoadPlan.SlabSwitch(slabSaid, code, Have(slabSaid), Have(code)) is { } news)
            OnLog?.Invoke(news);
        slabSaid = code;
        return code;
    }

    /// <summary>
    /// СКАЗАТЬ ВСЛУХ, ЧЕМ БУДУ БРАТЬ ПЕРЕПАДЫ, — и назвать КОД, а не отделаться
    /// словом «полублоками».
    ///
    /// ЖИВОЙ СЛУЧАЙ, ради которого это стало отдельным местом: «полублоки пишет
    /// бот, а крафтит лестницы (ступеньки) дороги». Сказано было один раз на
    /// выходе, а решение пересчитывалось на каждом окне; теперь решение одно на
    /// всю дорогу (ступенька «блок + полублок»), и сказать о нём можно честно.
    /// </summary>
    /// <param name="beforeDig">
    /// Зовут ДО КОПКИ И С ПУСТЫМИ РУКАМИ: покрытия ещё нет, и оно, и полублок
    /// придут из самого хода. Меняется от этого ровно одна строка — та, где
    /// полублока нет нигде. «Полублоков нет ни в сумках, ни в рецептах»
    /// сказанное в эту секунду — вранья наперёд: через минуту ход отдаст
    /// породу, и рецепт станет по силам. А молчать нельзя тем более: на спуске
    /// ступенька в КАЖДОМ ряду, и живьём 29.08 человек узнал про нехватку
    /// полублока после семидесяти шести секунд копки и одного ряда полотна.
    /// Честный ответ здесь один — условный: чего нет СЕЙЧАС и откуда возьмётся.
    /// </param>
    private void SayAboutSlabs(bool beforeDig = false)
    {
        // ЧТО СКАЗАЛИ — ТО И ПОМНИМ. Сменится полублок посреди дороги — смену
        // назовёт SlabNow, сравнивая как раз с этим кодом
        if (ChooseSlab() is { } inBags)
        {
            slabSaid = inBags;
            OnLog?.Invoke($"перепады беру ступеньками «блок + полублок»: блок — покрытием, " +
                          $"полублок — {inBags} ×{Have(inBags)} из сумок");
            return;
        }
        if (SlabToMake() is { } recipe)
        {
            slabSaid = recipe;
            OnLog?.Invoke($"перепады беру ступеньками «блок + полублок»: полублоков в сумках " +
                          $"нет, буду делать {recipe} по рецепту");
            return;
        }
        slabSaid = "";
        OnLog?.Invoke(beforeDig
            ? "полублоков СЕЙЧАС нет ни в сумках, ни в рецептах — как и покрытия: и то и " +
              "другое спрошу у самого хода, когда он отдаст породу. На перепадах (спуск и " +
              "подъём — это ступенька в каждом ряду) без полублока я встану и назову, чего " +
              "не хватило"
            : "полублоков нет ни в сумках, ни в рецептах: по ровному дорога ляжет, " +
              "а на первом же перепаде я встану и назову, чего не хватило");
    }

    /// <summary>
    /// ЧЕМ МОСТИТЬ ЭТУ ДОРОГУ. Порядок такой:
    ///   1. назвали код настройкой — только он (нет в сумках — сделать по рецепту);
    ///   2. дорожное покрытие ИЗ СУМОК — игра сама говорит, что по нему быстрее;
    ///   3. дорожное покрытие ПО РЕЦЕПТУ — заказчик просил «выкапывать и
    ///      крафтить боту дорогу», и вот это оно: каменная дорожка ванильной
    ///      игры делается из четырёх камней и земли, а этого у копателя горы;
    ///   4. ровный пол из сумок — ходить не быстрее, но и не спотыкаться.
    ///
    /// Ценное (руда, самородки, металл) не берётся ни на одном шаге, даже
    /// когда больше нечего положить. Живой случай 20:16: «быстрых блоков нет —
    /// кладу ore-poor-nativecopper-andesite ровным полом».
    /// </summary>
    /// <param name="midRoad">
    /// Зовут ПОСРЕДИ уже начатого полотна (из <see cref="MoreSurfaceAsync"/>), а
    /// не до первой положенной клетки. От этого зависит одно: пойдёт ли бот за
    /// материалом домой — см. <see cref="MaySupply"/>.
    /// </param>
    private async Task<(string? Code, string Why)> EnsureSurfaceAsync(CancellationToken ct,
        bool midRoad = false)
    {
        if (RoadCode.Length > 0)
        {
            // ЗАКОН ВЫШЕ НАСТРОЙКИ. «Мостить только этим» не отменяет «руду в
            // полотно никогда»: поле настройки было единственным путём в обход
            // всего разбора покрытия
            if (Named(RoadCode) is { Fit: RoadPlan.SurfaceFit.Precious or RoadPlan.SurfaceFit.Unfit } bad)
                return (null, $"мостить нечем: в настройке покрытия назван {RoadCode}, " +
                              $"а {WhyUnfit(bad)} — сотрите настройку, и я возьму дорожное сам");
            if (Have(RoadCode) > KeepInReserve)
                return (RoadCode, "");
            if (await MakeAsync(RoadCode, ct))
                return (RoadCode, "");
            // НАЗВАННОЕ ЧЕЛОВЕКОМ ИЩЕМ ВЕЗДЕ, а не только в сумках: он вписал
            // код, а не «сделай из того, что есть»
            var (взял, почему) = await FetchSurfaceAsync(RoadCode, ct, midRoad);
            if (взял)
                return (RoadCode, "");
            return (null, $"мостить нечем: {RoadCode} нет в сумках, {WhyCannotMake(RoadCode)}; " +
                          почему);
        }

        var inBags = BestInBags();
        if (inBags is { Fit: RoadPlan.SurfaceFit.Road })
            return (inBags.Code, "");

        if (MayCraft)
            foreach (var road in CraftableRoads())
            {
                if (!CanMake(road.Code))
                    continue;
                OnLog?.Invoke($"дорожного покрытия в сумках нет, зато {road.Code} " +
                              $"делается по рецепту (ход {road.WalkSpeed:0.##}) — делаю");
                if (await MakeAsync(road.Code, ct))
                    return (road.Code, "");
            }

        if (inBags != null)
        {
            OnLog?.Invoke($"быстрого покрытия нет ни в сумках, ни в рецептах — кладу " +
                          $"{inBags.Code} ровным полом (ходить не быстрее, но и не спотыкаться)");
            return (inBags.Code, "");
        }

        // НИ В СУМКАХ, НИ ИЗ СВОЕГО — СХОДИТЬ ЗА МАТЕРИАЛОМ. Живой прогон
        // 16.08: «мостить нечем: блоков в сумках нет вовсе», а полминуты спустя
        // опись насчитала в шестнадцати сундуках дома 1023 предмета. Ходит не
        // дорога — ходит снабжение (Supply): та же цепочка снаряжает факелы и
        // инструменты, и второй её копии здесь нет
        var roads = CraftableRoads();
        string сходил = "";
        if (roads.Count > 0)
        {
            var (взял, почему) = await FetchSurfaceAsync(roads[0].Code, ct, midRoad);
            if (взял)
                return (roads[0].Code, "");
            сходил = "; " + почему;
        }

        // Отказ обязан назвать, ЧЕГО не хватило. «Блоков под покрытие нет»
        // при полной сумке руды человек справедливо считает враньём
        string craft = roads.Count == 0
            ? "дорожных рецептов в этом мире не нашлось"
            : $"на дорожное ({roads[0].Code}) {WhyCannotMake(roads[0].Code)}";
        string bags = BlocksInBags().Count == 0
            ? "блоков в сумках нет вовсе"
            : "всё, что есть в сумках, — ценное или негодное под ноги: " +
              string.Join(", ", BlocksInBags()
                  .Select(t => Describe(t.Code, t.Count))
                  .OfType<RoadPlan.SurfaceOption>()
                  .Take(6));
        return (null, $"мостить нечем: {bags}; {craft}{сходил}");
    }

    /// <summary>
    /// Добрать покрытия посреди дороги: сперва сделать ещё того же, потом
    /// сходить за ним, и только потом выбирать заново с нуля. Крафт — вслух:
    /// человек должен видеть, куда ушла его порода.
    ///
    /// Поход стоит ВТОРЫМ, а не последним, нарочно: дорога уже начата этим
    /// покрытием, и домостить её тем же материалом дешевле и честнее, чем
    /// переходить на другое посреди полотна. Ходит при этом не дорога, а
    /// снабжение (<see cref="FetchSurfaceAsync"/>).
    ///
    /// А ХОДИТЬ ЛИ ВООБЩЕ, решает <see cref="MaySupply"/>: с первой положенной
    /// клетки рейс домой означает «бросил начатую дорогу и ушёл», и именно это
    /// заказчик увидел как метания между домом и стройкой. Крафт на месте и
    /// переход на другое покрытие остаются — они никуда не уводят.
    /// </summary>
    /// <param name="midRoad">Полотно этого захода уже начато.</param>
    private async Task<string?> MoreSurfaceAsync(string code, bool midRoad, CancellationToken ct)
    {
        if (await MakeAsync(code, ct))
            return code;
        var (взял, почему) = await FetchSurfaceAsync(code, ct, midRoad);
        if (взял)
            return code;
        // ОТКАЗ РЕЙСА — ВСЛУХ. Он один объясняет, почему бот встал посреди
        // полотна, имея дома два сундука камня; без него человек читает
        // «покрытие кончилось» как поломку
        if (почему.Length > 0)
            OnLog?.Invoke(почему);
        var (next, _) = await EnsureSurfaceAsync(ct, midRoad);
        return next;
    }

    /// <summary>
    /// Тот ли это блок. Сравниваем ВХОЖДЕНИЕМ, а не равенством: по всей
    /// библиотеке материал называют куском кода («cobblestone»), а сервер
    /// зовёт его полным именем («game:cobblestone-granite»). При сравнении
    /// на равенство уже положенная клетка каждый раз считалась чужой и
    /// перекладывалась заново.
    /// </summary>
    private static bool Same(string? code, string? part) =>
        code != null && part is { Length: > 0 } &&
        code.Contains(part, StringComparison.OrdinalIgnoreCase);
