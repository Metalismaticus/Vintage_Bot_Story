    /// </summary>
    public int MaxCutFill { get; set; } = 12;

    /// <summary>
    /// ВЫСОТА НАСЫПИ, блоков: насколько глубокую пустоту под полотном бот
    /// засыпает землёй, вместо того чтобы оставить дорогу висеть.
    ///
    /// ЖИВОЙ СЛУЧАЙ 23.08, СЛОВА ЗАКАЗЧИКА: «если не хватает блоков и лестница
    /// висит в воздухе, то пусть достраивает землей основу и на ней строит».
    ///
    /// НАСЫПЬ И МОСТ — РАЗНЫЕ ПРИЁМЫ, И ЭТО ГЛАВНОЕ ЗДЕСЬ. Мост
    /// (<see cref="Scaffolding.BridgeAsync"/>) — ход СКВОЗЬ пустоту: один слой
    /// блоков по оси, и глубина ему безразлична. По нему бот и переходит
    /// провал первым проходом. Но настил держит ОДНУ клетку из трёх — края
    /// полосы над ним висят, и со стороны это ровно «лестница в воздухе».
    /// Насыпь (<see cref="Scaffolding.EmbankAsync"/>) подводит опору под ВСЮ
    /// ширину, снизу доверху, и делает это вторым проходом, при укладке.
    ///
    /// ЦЕНА ЧЕСТНАЯ И ЛИНЕЙНАЯ: клетка насыпи — это блок земли и удар. Ряд
    /// шириной 3 при глубине 2 стоит 6 блоков, при глубине 3 — девять. Поэтому
    /// предел тут маленький: глубокий провал дешевле перейти мостом, чем
    /// засыпать, и над пропастью насыпь бессмысленна вовсе.
    ///
    /// ТРОЙКА — ЭТО ДЛИНА РУКИ, А НЕ ВКУС. Подсыпая, бот стоит на соседней
    /// клетке сверху; до дна насыпи в 3 бл от глаз ≈ 4,3 при досягаемости игры
    /// 4,5, а до дна четвёрки уже ≈ 5,3 — сервер такого клика не примет.
    /// Поставив больше, человек получит отказ механизма
    /// (<see cref="Scaffolding.MaxFillHeight"/>), а не молчание.
    ///
    /// Ноль означает «не подсыпать вовсе»: дорога останется на настиле, как и
    /// была до этой правки.
    /// </summary>
    public int MaxFill { get; set; } = 3;

    /// <summary>
    /// УШЛО ЛИ ПОЛОТНО ПОД ЗЕМЛЮ ГЛУБЖЕ ПОЗВОЛЕННОГО — чистое правило без мира
    /// и без тела.
    ///
    /// ЖИВОЙ СЛУЧАЙ 16.08, 20:30:25, дословно из журнала заказчика:
    ///   «у (512059, 107, 512241) полотно на заданной высоте 107,5 разошлось
    ///    с землёй на −4,5 бл — выемку глубже 4 бл не роем».
    /// Дорога встала ровно тут, не добрав полблока до предела. Отказ был
    /// честный и с числами — и всё равно тупиковый: ЧЕМ поднять этот предел,
    /// в нём не было сказано, потому что говорить было нечего (четвёрка сидела
    /// в библиотеке). Теперь есть ручка, и отказ обязан её назвать — иначе
    /// повторится история «вести до предела мне не велено настройкой», где
    /// человек трижды пробовал наугад (см. <see cref="RoadKnobs"/>).
    ///
    /// ТОЛЬКО ВНИЗ, И ЭТО ПРАВКА 22.08. Раньше та же функция мерила и насыпь,
    /// отвечая на неё «тут нужен мост, а насыпь в воздухе бот не держит», —
    /// и вставала. Мост бот умеет, глубина провала мосту безразлична
    /// (<see cref="MaxCutFill"/>), поэтому вверх это правило больше не смотрит
    /// вовсе: там работа не отказа, а <c>BridgeRunAsync</c>.
    ///
    /// ПОЧЕМУ ОТДЕЛЬНОЙ ФУНКЦИЕЙ. Правило это чистое: полушаги профиля,
    /// предел и имя ручки — больше ему ничего не нужно. Живя строкой внутри
    /// цикла укладки, оно проверялось только полным стендом с чанком, сумкой и
    /// покрытием; отсюда его видно целиком и в отказе, и в тесте.
    ///
    /// СЧЁТ В ПОЛУБЛОКАХ, и это не описка: профиль дороги ходит полушагами
    /// (полблока за ряд), поэтому предел в блоках удваивается.
    /// </summary>
    /// <param name="centre">Клетка оси ряда — та, о которой идёт речь.</param>
    /// <param name="level">Уровень полотна в полублоках (см. RoadPlan.FeetY).</param>
    /// <param name="offGround">
    /// На сколько ПОЛУБЛОКОВ полотно разошлось с землёй: меньше нуля — полотно
    /// в земле (выемка, о ней и речь), больше — полотно в воздухе (мост, и
    /// здесь про него молчат нарочно).
    /// </param>
    /// <param name="maxCutFill">Предел глубины выемки, блоков (<see cref="MaxCutFill"/>).</param>
    /// <param name="knob">Как эта ручка зовётся у человека (<see cref="RoadKnobs.MaxCutFill"/>).</param>
    public static (bool Stop, string Why) CutTooDeep(BlockPos centre, int level,
        int offGround, int maxCutFill, string knob)
    {
        if (offGround >= 0 || -offGround <= 2 * Math.Max(0, maxCutFill))
            return (false, "");

        // Числом называем И заданную высоту: расхождение с землёй — прямое
        // следствие заказа, и человек должен видеть, что именно он заказал
        // «НА ЗАДАННОЙ ВЫСОТЕ» ЗДЕСЬ БОЛЬШЕ НЕ ПИШЕТСЯ, И ЭТО ПРАВКА ПРИЁМКИ.
        // Пока полотно держало прямую от y1 к y2, любая его высота была прямым
        // следствием заказа, и слово «заданной» было честным. Теперь заданы
        // только КОНЦЫ, а высоту промежуточных рядов выбирает разметка по земле
        // (RoadPlan.Levels): сказать про такой ряд «на заданной высоте» значит
        // свалить на человека число, которого он не называл, — и отправить его
        // искать опечатку в собственном заказе
        return (true,
            $"у {centre} полотно на высоте {RoadPlan.FeetY(level):0.#} " +
            $"разошлось с землёй на {offGround / 2.0:0.#} бл — выемку глубже не роем " +
            $"(предел {maxCutFill} бл, ручка «{knob}»)");
    }

    /// <summary>
    /// ПРОВАЛ ПОД ПОЛОТНОМ — ТО ЕСТЬ МЕСТО, ГДЕ БЕЗ МОСТА НЕ ОБОЙТИСЬ. Чистое
    /// правило, и оно ОДНО на разведку и на саму проходку: разойдись они, и
    /// бот обещал бы мост там, где потом кладёт ступеньку, или наоборот.
    ///
    /// СЧИТАЕМ ПО КЛЕТКАМ, А НЕ «ПОЛОТНО ВЫШЕ ЗЕМЛИ». Земля стоит верхом на
    /// клетку ниже уровня ног (<paramref name="offGround"/> меряется по клетке
    /// НОГ), а самый нижний слой полотна ложится в <see cref="RoadPlan.Bed"/> —
    /// тоже на клетку ниже ног. Значит:
    ///   0 и 1 полублока выше земли — полотно ложится ПРЯМО НА ЗЕМЛЮ (ровное
    ///     место или экономная ступенька, плита на природном блоке);
    ///   2 и 3 — блок полотна встаёт в пустую клетку, но ПОД НЕЙ земля: обычная
    ///     установка, сосед для клика есть снизу;
    ///   4 и больше (то есть от двух блоков) — под будущим полотном пусто и на
    ///     клетку ниже тоже пусто: встать не на что и кликнуть не по чему.
    ///     Вот это и есть провал, и берётся он мостом.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ИЗ-ЗА КОТОРОГО ПОРОГ НЕ «БОЛЬШЕ НУЛЯ». Стенд
    /// <c>RoadDigBeforePaveTests</c> ведёт дорогу с подъёмом в один блок: там
    /// полотно расходится с землёй на полблока и на блок — и мостить там
    /// нечего, ступенька ложится на природный склон. Правило «выше земли —
    /// значит мост» отправило бы бота мостить ровный подъём.
    /// </summary>
    /// <param name="offGround">
    /// На сколько ПОЛУБЛОКОВ полотно разошлось с землёй (см. RoadLevel.OffGround).
    /// </param>
    public static bool VoidUnder(int offGround) => offGround >= 4;

    /// <summary>
    /// ЗЕМЛЯНЫЕ РАБОТЫ ХОДА ОДНИМ ВЗГЛЯДОМ: сколько рыть, сколько мостить.
    /// </summary>
    /// <param name="Cut">Самая глубокая выемка, ПОЛУБЛОКОВ (0 — выемки нет).</param>
    /// <param name="CutRow">На каком ряду она (−1 — выемки нет).</param>
    /// <param name="Span">Самый длинный пролёт над пустотой, клеток.</param>
    /// <param name="SpanRow">С какого ряда он начинается (−1 — пролётов нет).</param>
    /// <param name="Hanging">Сколько всего рядов висит над пустотой.</param>
    public readonly record struct RoadEarth(int Cut, int CutRow, int Span, int SpanRow, int Hanging);

    /// <summary>
    /// САМЫЙ КРУТОЙ ШАГ ВНИЗ НА ХОДУ И СКОЛЬКО КЛЕТОК ХОДА ОН ТРЕБУЕТ — чистое
    /// правило по разведанному профилю.
    ///
    /// ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ ПРОСТОГО ПРОСВЕТА. Дорога уже отказывается копать
    /// выемку ниже роста тела (<see cref="Walker.MinHeadroom"/>). На РОВНОМ
    /// ходу этого хватает: бот стоит в выемке и идёт по ней. На СПУСКЕ — нет, и
    /// вот почему, слово в слово по устройству самой копки (см. поле
    /// <c>deferred</c>): «на дороге ВНИЗ землекоп стоит на уже выкопанном
    /// предыдущем ряду и копает перед собой». То есть в новый ряд тело входит
    /// НА СВОЕЙ, ПРЕЖНЕЙ ВЫСОТЕ — сперва шагает вбок, и только потом опускается.
    /// Ровно так же считает свои клетки и штольня
    /// (<c>Tunnel.CellsToClear</c>: <c>Math.Max(next.Y, at.Y) + height - 1</c>),
    /// и второго правила физики тут нет — есть одно, записанное для дороги.
    ///
    /// АРИФМЕТИКА, А НЕ ПРИКИДКА. Ноги на предыдущем ряду стоят в клетке
    /// <c>F₀ = RoadPlan.FeetCell(level₀)</c>, макушка — в
    /// <c>F₀ + MinHeadroom − 1</c>. Новый ряд вычищен от своей клетки ног
    /// <c>F₁</c> вверх на <c>Height</c> клеток, то есть до
    /// <c>F₁ + Height − 1</c>. Чтобы макушка прошла, нужно
    /// <c>F₁ + Height − 1 ≥ F₀ + MinHeadroom − 1</c>, откуда
    /// <c>Height ≥ MinHeadroom + (F₀ − F₁)</c>. Разность <c>F₀ − F₁</c> и есть
    /// ШАГ ВНИЗ, и она здесь СЧИТАЕТСЯ ПО ПРОФИЛЮ, а не берётся из головы:
    /// круче полублока за ряд дорога не идёт (<see cref="RoadPlan.Lead"/>),
    /// значит клетка ног роняется не больше чем на одну — но проверять это
    /// правило обязано у профиля, а не верить ему на слово.
    ///
    /// ЧЕМ ЭТО КОНЧАЛОСЬ БЫ МОЛЧА. Поставь человек «ВысотаТоннеляДороги» = 2
    /// (ровно рост тела — прежний отказ такое пропускает), и спуск был бы
    /// выкопан весь, до последнего ряда, а пройти по нему бот не смог бы ни на
    /// шаг: макушка упирается в породу на клетку выше пола нового ряда. Дорога
    /// в 620 выкопанных клеток и ноль положенных рядов — это ровно тот вид,
    /// на который заказчик и жаловался.
    /// </summary>
    /// <param name="profile">Разведанный профиль по рядам, от начала.</param>
    /// <returns>
    /// <c>Drop</c> — самый крутой шаг ВНИЗ между соседними рядами, клеток
    /// (0 — спуска нет); <c>Row</c> — номер ряда, КУДА этот шаг ведёт
    /// (−1 — спуска нет); <c>Need</c> — сколько клеток хода над полотном для
    /// него нужно.
    /// </returns>
    public static (int Drop, int Row, int Need) StepDownHeadroom(IReadOnlyList<RoadLevel> profile)
    {
        int drop = 0, row = -1;
        for (int i = 1; i < profile.Count; i++)
        {
            // Клетку ног спрашиваем у той же раскладки, по которой копают
            // (RoadPlan.FeetCell): свой пересчёт полублоков в клетки разошёлся
            // бы с ней на первом же полублоке ступеньки
            int step = RoadPlan.FeetCell(profile[i - 1].Level) - RoadPlan.FeetCell(profile[i].Level);
            if (step > drop)
                (drop, row) = (step, i);
        }
        return (drop, row, Walker.MinHeadroom + drop);
    }

    /// <summary>
    /// ПОСЧИТАТЬ ЗЕМЛЯНЫЕ РАБОТЫ ПО ПРОФИЛЮ — чистое правило, и оно ОДНО на
    /// два дела: на приговор разведки (<see cref="Scouted"/>) и на проверку
    /// выполнимого числа (<see cref="OnGroundEnd"/>). Разойдись они — и бот
    /// советовал бы высоту, которую сам же потом не берёт.
    /// </summary>
    public static RoadEarth Earthwork(IReadOnlyList<RoadLevel> profile)
    {
        int worst = 0, worstRow = -1;        // самая глубокая выемка, полублоки
        int run = 0, longest = 0, longestRow = -1, hanging = 0;
        for (int i = 0; i < profile.Count; i++)
        {
            int off = profile[i].OffGround;
            if (off < worst)
                (worst, worstRow) = (off, i);
            if (!VoidUnder(off))
            {
                run = 0;
                continue;
            }
            hanging++;
            if (++run > longest)
                (longest, longestRow) = (run, i - run + 1);
        }
        return new RoadEarth(-worst, worstRow, longest, longestRow, hanging);
    }

    /// <summary>
    /// ЧИСЛО, А НЕ НАПРАВЛЕНИЕ: какую высоту КОНЦА задать, чтобы дорога легла
    /// целиком, — и что из этого выйдет по земляным работам.
    ///
    /// ЖИВОЙ СЛУЧАЙ 22.08, дословно из отказа: «Выполнимое: … или задайте
    /// высоту, идущую ближе к земле». Ближе — это НА СКОЛЬКО? Человеку
    /// оставалось подбирать вручную, и он подбирал: 16.08 в 20:25–20:29 три
    /// отказа подряд и лишь четвёртая попытка угадала число. А бот его знает:
    /// землю в конце дороги он только что разведал.
    ///
    /// СЧИТАЕТСЯ ПЕРЕСЧЁТОМ ТОГО ЖЕ ПРОФИЛЯ, а не прикидкой: конец кладётся на
    /// землю, разметка (<see cref="RoadPlan.Levels"/>) пересчитывается целиком
    /// — и её земляные работы меряются теми же двумя пределами. Сказать
    /// «задайте 114» и не проверить значило бы отправить человека во второй
    /// такой же отказ.
    ///
    /// ЗЕМЛЮ БЕРЁМ ИЗ САМОГО ПРОФИЛЯ: <see cref="RoadLevel.OffGround"/> и есть
    /// расхождение полотна с землёй, значит земля — это уровень минус
    /// расхождение. Второй меры рельефа тут заводить нельзя: она разошлась бы
    /// с той, по которой ход и размечали.
    ///
    /// ОДНОГО КОНЦА МАЛО, И ЭТО ПОЙМАЛА ПРИЁМКА. Сначала правило пробовало
    /// РОВНО ОДИН конец — землю под последним рядом, — и, если с ним ход не
    /// брался, отвечало «но и с таким концом ход не берётся». Звучит честно, а
    /// правдой не было: щуп на четырёх тысячах случайных рельефов дал 1208
    /// отказов, и в 137 из них (каждый девятый) рабочая высота СУЩЕСТВОВАЛА —
    /// бот её просто не искал. Живьём это тот же тупик, из-за которого правило
    /// и заводили: человек читает отказ без числа и подбирает наугад.
    ///
    /// ПОЧЕМУ КОНЕЦ ПО ЗЕМЛЕ НЕ ВСЕГДА ЛУЧШИЙ. Земля под последним рядом бывает
    /// в яме или на останце: конец, положенный туда, тянет к себе коридор
    /// последних рядов и режет ими соседний бугор (или наоборот — уводит
    /// полотно в воздух над подходом). Конец на пару блоков в сторону от земли
    /// такой ход берёт, а «прямо по земле» — нет.
    ///
    /// ИЩЕМ БЛИЖАЙШИЙ К ЗЕМЛЕ, А НЕ ЛЮБОЙ: советовать «конец на 20 блоков выше
    /// местности» бессмысленно, даже если он проходит по пределам. Порядок
    /// перебора — по удалению от земли, при равном удалении ниже: выемку бот
    /// роет всегда, а мост длиннее восьми клеток не кладёт вовсе.
    ///
    /// ГДЕ ГРАНИЦЫ ПЕРЕБОРА, И ПОЧЕМУ ОН НЕ БЕСКОНЕЧЕН. Сверху и снизу — то,
    /// докуда полотно вообще дотягивается за столько рядов (<see
    /// cref="RoadPlan.Lead"/>, полблока за ряд). Внутри — полоса самого
    /// рельефа, опущенная на предел выемки: ниже неё последний ряд один уже
    /// перебирает глубину, выше — висит над всем, что тут есть. Считается это
    /// ТОЛЬКО на отказе, где второй профиль и так уже считался: там, где ход
    /// берётся, не считается ничего.
    ///
    /// НИЧЕГО НЕ НАШЛОСЬ — так и говорим, и теперь эти слова ЗАРАБОТАНЫ:
    /// перебраны все достижимые концы, а не один.
    /// </summary>
    /// <returns>
    /// Готовая половина фразы «Выполнимое: …». Разведан не весь ход — про
    /// конец говорить нечего, и это сказано прямо.
    /// </returns>
    public static string OnGroundEnd(
        IReadOnlyList<(BlockPos Centre, RoadLevel Step)> scouted, int rows,
        int maxCut, int maxSpan)
    {
        if (scouted.Count == 0 || scouted.Count < rows)
            return "разведан не весь ход — про высоту конца скажу, когда мир дойдёт " +
                   "до последнего ряда";

        var ground = new int[rows];
        for (int i = 0; i < rows; i++)
            ground[i] = (scouted[i].Step.Level - scouted[i].Step.OffGround) / 2;

        int start = scouted[0].Step.Level;
        int soil = ground[^1];
        int cut = 2 * Math.Max(0, maxCut), span = Math.Max(0, maxSpan);

        // ОДНА ПРОВЕРКА КОНЦА НА ВСЕХ: тот же профиль и те же два предела, что
        // у приговора разведки. Разойдись они — и бот советовал бы высоту,
        // которую сам же потом не берёт
        (bool Ok, RoadEarth Work) Weigh(int whole)
        {
            var work = Earthwork(RoadPlan.Profile(ground, 0, rows, start, whole * 2));
            return (work.Cut <= cut && work.Span <= span, work);
        }

        // ЦЕНУ НАЗЫВАЕМ ТУ, КОТОРАЯ ЕСТЬ: «мостить 0 рядов» — это не отчёт, а
        // шум, и человек за ним не видит главного числа
        static string Price(RoadEarth work)
        {
            var price = new List<string>();
            if (work.Cut > 0)
                price.Add($"выемка {work.Cut / 2.0:0.#} бл");
            if (work.Hanging > 0)
                price.Add($"мостить {work.Hanging} ряд(ов), самый длинный пролёт {work.Span} кл.");
            return price.Count == 0
                ? "и ляжет прямо по земле, без выемки и без моста"
                : "и ляжет вся: " + string.Join(", ", price);
        }

        // КЛЕТКУ НАЗЫВАЕМ С ВЫСОТОЙ ЗЕМЛИ, а не с высотой полотна: строка «земля
        // у (55, 128, 281) на 114» заставляет человека гадать, какое из двух
        // чисел про землю
        var end0 = scouted[^1].Centre;
        string where = $"земля в конце дороги у {new BlockPos(end0.X, soil, end0.Z)} на {soil}";

        int onSoil = RoadPlan.WholeEnd(start, soil * 2, rows);
        var (fits, onSoilWork) = Weigh(onSoil);
        if (fits)
            return $"{where} — задайте конец {onSoil}, " + Price(onSoilWork);

        // Конец по земле не берётся — но это ещё не «никакой не берётся».
        // Перебираем достижимые концы от ближнего к земле к дальнему
        int steps = Math.Max(0, rows - 1);
        int low = Math.Max((int)Math.Ceiling((start - steps) / 2.0), ground.Min() - Math.Max(0, maxCut));
        int high = Math.Min((int)Math.Floor((start + steps) / 2.0), ground.Max() + 2);
        var reachable = Enumerable.Range(low, Math.Max(0, high - low + 1))
            .Where(e => e != onSoil)
            .OrderBy(e => Math.Abs(e - soil))
            .ThenBy(e => e);
        foreach (int candidate in reachable)
            if (Weigh(candidate) is { Ok: true, Work: var good })
                return $"{where}, и с таким концом ход не берётся " +
                       $"(выемка {onSoilWork.Cut / 2.0:0.#} бл при пределе {maxCut}, " +
                       $"пролёт {onSoilWork.Span} кл. при пределе {maxSpan}); " +
                       $"а вот задайте конец {candidate} — " + Price(good);

        // Перебраны ВСЕ достижимые концы, и ни один не берёт этот ход: беда не
        // в конце, а в самом рельефе между концами, и врать про «задайте
        // столько-то» нельзя
        return $"{where}, но ход не берётся ни с ним, ни с любой другой высотой конца, " +
               $"какую я отсюда достану ({low}…{high}): с концом по земле " +
               $"выемка {onSoilWork.Cut / 2.0:0.#} бл (предел {maxCut}), " +
               $"пролёт над пустотой {onSoilWork.Span} кл. (предел {maxSpan})";
    }

    /// <summary>
    /// ЧТО ЖДЁТ ДОРОГУ НА ВСЁМ ХОДУ, СКАЗАННОЕ ДО ПЕРВОГО УДАРА, — чистое
    /// правило без мира и без тела: разведанный профиль, два предела и слова.
    ///
    /// ЖИВОЙ СЛУЧАЙ 22.08, И ОН ЖЕ ПРИГОВОР ПРЕЖНЕМУ ПОРЯДКУ. Дважды подряд
    /// заход кончался НУЛЁМ, и оба раза помеха была видна заранее:
    ///   17:18:35 «ПРОХОДКА ВСТАЛА на ряду 11 из 29 … Полотно НЕ кладу ни на
    ///             один ряд … выкопанные 11 рядов ждут»;
    ///   17:25:14 «ПРОХОДКА ВСТАЛА на ряду 8 из 31 … выкопанные 8 рядов ждут».
    /// Заказчик прочитал это как «не идет делать дорогу» — и был прав: работы
    /// сделано на восемь рядов, показать нечего. Профиль же считался окном в
    /// <see cref="PlanAhead"/> рядов ПРЯМО В ЦИКЛЕ, поэтому про одиннадцатый
    /// ряд бот узнавал, уже выкопав десять.
    ///
    /// РАЗВЕДАТЬ ВЕСЬ ХОД ДЕШЕВЛЕ, ЧЕМ КОПАТЬ И БРОСАТЬ. Разведка — это чтение
    /// уже прогруженного мира: тридцать рядов стоят тридцати вопросов «где тут
    /// земля», то есть долей секунды. Восемь выкопанных и брошенных рядов
    /// стоили двенадцати секунд работы киркой и всего заказа целиком.
    ///
    /// ДВА ПРЕДЕЛА, И ОНИ РАЗНОЙ ПРИРОДЫ:
    ///   • ВНИЗ — ГЛУБИНА (<paramref name="maxCut"/>): сколько земли над
    ///     полотном бот согласен держать кровлей.
    ///   • ВВЕРХ — ПРОЛЁТ (<paramref name="maxSpan"/>), а НЕ высота: провал под
    ///     полотном мостится, и мост над ямой в блок ровно такой же, как над
    ///     пропастью в пятьдесят. Ограничивает его длина, потому что бот кладёт
    ///     мост, стоя на нём же (<see cref="Scaffolding.MaxBridgeSpan"/>).
    ///
    /// ОТКАЗ ОБЯЗАН НАЗВАТЬ ВЫПОЛНИМОЕ — здесь это ЧИСЛО, которое надо
    /// поставить в ручку. Живьём человек, получив отказ без числа, четырежды
    /// подряд подбирал высоту наугад (журнал 16.08, 20:25–20:29).
    /// </summary>
    /// <param name="scouted">
    /// Разведанные ряды по порядку: осевая клетка и её кусок профиля. Столько,
    /// сколько показал прогруженный мир, — не больше и не меньше.
    /// </param>
    /// <param name="rows">Сколько рядов у хода всего: разведано может быть меньше.</param>
    /// <param name="maxCut">Предел глубины выемки, блоков (<see cref="MaxCutFill"/>).</param>
    /// <param name="cutKnob">Имя ручки глубины у человека.</param>
    /// <param name="maxSpan">Длиннее скольких клеток мост не кладётся.</param>
    /// <param name="spare">Сколько блоков в сумках не жалко пустить под ноги.</param>
    /// <param name="height">
    /// Сколько клеток чистим НАД полотном (<see cref="Height"/>); 0 — расчистка
    /// выключена человеком, и тогда прохода дорога не обещает вовсе.
    /// </param>
    /// <param name="heightKnob">Имя ручки высоты хода у человека.</param>
    public static (bool Go, string Say) Scouted(
        IReadOnlyList<(BlockPos Centre, RoadLevel Step)> scouted, int rows,
        int maxCut, string cutKnob, int maxSpan, int spare,
        int height, string heightKnob)
    {
        if (scouted.Count == 0)
            return (true, "");

        var dug = Earthwork([.. scouted.Select(s => s.Step)]);
        int worst = -dug.Cut, worstRow = dug.CutRow;
        int longest = dug.Span, longestRow = dug.SpanRow, hanging = dug.Hanging;

        // Про неразведанный хвост молчать нельзя: иначе «разведал ход» человек
        // прочтёт как «весь ход», а там ещё может стоять что угодно
        string tail = scouted.Count < rows
            ? $" Дальше {scouted.Count}-го ряда мир ещё не пришёл: остальные " +
              $"{rows - scouted.Count} разведаю на ходу и скажу тем же порядком."
            : "";

        // ОТКАЗ НАЗЫВАЕТ ЧИСЛО, А НЕ НАПРАВЛЕНИЕ. Считается число ТОЛЬКО ради
        // отказа: там, где ход берётся, второй профиль никому не нужен
        string Doable() => OnGroundEnd(scouted, rows, maxCut, maxSpan);

        // ВЫЕМКА ГЛУБЖЕ ПОЗВОЛЕННОГО — отказ ДО работы и с числом для ручки.
        //
        // СЛОВА БЕРУТСЯ У САМОГО ПРАВИЛА (CutTooDeep), а не пишутся заново:
        // одна беда — одна формулировка. Разойдись они, и человек читал бы про
        // «выемку глубже не роем» в цикле и что-нибудь другое в разведке,
        // считая это двумя разными помехами
        if (worstRow >= 0 &&
            CutTooDeep(scouted[worstRow].Centre, scouted[worstRow].Step.Level, worst,
                maxCut, cutKnob) is { Stop: true, Why: var whyDeep })
            return (false,
                $"разведал ход ДО ПЕРВОГО УДАРА и не берусь: на {worstRow + 1}-м ряду " +
                $"из {rows} {whyDeep}. НИ ОДНОГО БЛОКА НЕ ТРОНУЛ. Выполнимое: {Doable()}; " +
                $"или поставьте «{cutKnob}» {(int)Math.Ceiling(-worst / 2.0)} или больше — " +
                $"тогда весь разведанный ход берётся." + tail);

        // ХОД, В КОТОРЫЙ ТЕЛО НЕ ВОЙДЁТ НА СПУСКЕ, — ОТКАЗ ДО ПЕРВОГО УДАРА.
        //
        // Прежний сторож просвета (в BuildAsync, по Walker.MinHeadroom) меряет
        // ход СТОЯ на месте и потому пропускает ровно ту беду, на которую
        // жаловался заказчик: спуск. Вниз бот входит в новый ряд НА ПРЕЖНЕЙ
        // ВЫСОТЕ, и клетки над полотном нужно на шаг больше — сколько именно,
        // считает StepDownHeadroom по разведанному профилю.
        //
        // ЗДЕСЬ, А НЕ ТАМ, ПОТОМУ ЧТО ЗДЕСЬ ИЗВЕСТЕН ПРОФИЛЬ. Спуск бывает и у
        // дороги, заказанной «по ровному»: концы на одной высоте, а между ними
        // бугор, и полотно ныряет за землёй. До разведки об этом не знает никто,
        // и отказывать по одному лишь заданию значило бы врать в обе стороны.
        //
        // Расчистка выключена (height == 0) — молчим: там человек прямо сказал
        // «над дорогой не убирать», и обещания пройти дорога не даёт (та же
        // оговорка, что и у сторожа просвета).
        if (height > 0 && StepDownHeadroom([.. scouted.Select(s => s.Step)])
                is { Drop: > 0 } down && height < down.Need)
            return (false,
                $"разведал ход ДО ПЕРВОГО УДАРА и не берусь: на {down.Row + 1}-м ряду из {rows} " +
                $"у {scouted[down.Row].Centre} полотно опускается на {down.Drop} кл., а ход над " +
                $"полотном задан в {height} кл. Вниз я вхожу в новый ряд НА ПРЕЖНЕЙ ВЫСОТЕ — " +
                $"стою на прошлом ряду и шагаю вперёд, — и макушка упирается в породу: телу " +
                $"нужно {Walker.MinHeadroom} кл. просвета (рост {Walker.BodyHeight:0.##} бл), " +
                $"а на спуске ещё {down.Drop} сверх того. Такой ход я выкопаю весь, но не пройду " +
                $"по нему ни шагу. НИ ОДНОГО БЛОКА НЕ ТРОНУЛ. Выполнимое: поставьте " +
                $"«{heightKnob}» {down.Need} или больше." + tail);

        // ПРОЛЁТ ДЛИННЕЕ, ЧЕМ БОТ БЕРЁТСЯ МОСТИТЬ, — тоже отказ ДО работы
        if (longest > Math.Max(0, maxSpan))
            return (false,
                $"разведал ход ДО ПЕРВОГО УДАРА и не берусь: с {longestRow + 1}-го ряда из {rows} " +
                $"у {scouted[longestRow].Centre} полотно висит над землёй {longest} рядов " +
                $"подряд, а мост я кладу не длиннее {maxSpan} кл. НИ ОДНОГО БЛОКА НЕ ТРОНУЛ. " +
                $"Выполнимое: {Doable()}; или проведите дорогу в обход провала." + tail);

        var said = new List<string>();
        if (worst < 0)
            said.Add($"самая глубокая выемка {-worst / 2.0:0.#} бл на {worstRow + 1}-м ряду " +
                     $"у {scouted[worstRow].Centre} (предел {maxCut} бл, ручка «{cutKnob}»)");
        if (hanging > 0)
            said.Add($"над землёй висит {hanging} рядов, самый длинный пролёт {longest} кл. — " +
                     $"навожу мост; под ноги уйдёт {hanging} блоков, в сумках {spare}" +
                     (spare < hanging ? ", остальное доберу выломанным из выемки" : ""));
        if (said.Count == 0)
            said.Add("ни выемки, ни провала — полотно ложится по земле");
        // «N РЯДОВ ИЗ M» ЗДЕСЬ НЕ ПИШЕТСЯ НАРОЧНО: этими словами отчитывается
        // ГОТОВАЯ дорога («дорога 11 рядов из 29»), и разведка, заговорив ими,
        // читалась бы как итог работы — в стенде RoadDigBeforePaveTests она
        // ровно так и сошла за отчёт, придя на три строки раньше него
        return (true, (scouted.Count < rows
                          ? $"разведал ДО ПЕРВОГО УДАРА {scouted.Count} ряд(ов) хода, всего их {rows}: "
                          : $"разведал ДО ПЕРВОГО УДАРА весь ход ({rows} ряд(ов)): ") +
                      string.Join("; ", said) + "." + tail);
    }

    /// <summary>
    /// Сколько рядов ЧИТАТЬ у мира за один заход чтения. Дальше по курсу
    /// чанков может не быть вовсе, а профиль по непрогруженному миру — это
    /// профиль по воздуху.
    ///
    /// РАЗМЕТКУ ЭТО ЧИСЛО БОЛЬШЕ НЕ РЕЖЕТ. Пока профиль считался окном, дорога
    /// решала высоту первых двенадцати рядов, не зная про остальные двадцать, —
    /// и это была вторая половина живого случая 22.08. Теперь чтение идёт
    /// такими окнами подряд, докуда отвечает мир, а разметка (RoadPlan.Levels)
    /// выбирается СРАЗУ ПО ВСЕЙ прочитанной земле.
    /// </summary>
    public int PlanAhead { get; set; } = 12;

    /// <summary>В каком окне по высоте искать землю под осью, блоков.</summary>
    public int GroundLook { get; set; } = 24;

