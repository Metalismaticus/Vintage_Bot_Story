    /// <summary>
    /// НА СКОЛЬКО БЛОКОВ ПОЛОТНУ ПОЗВОЛЕНО УЙТИ ПОД ЗЕМЛЮ — то есть какой
    /// глубины выемку бот согласен резать. Число меряет ТОЛЬКО эту сторону, и
