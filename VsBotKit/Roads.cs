namespace VsBotKit;

/// <summary>Почему укладка дороги остановилась.</summary>
public enum RoadStop
{
    /// <summary>Дорога доведена до конца.</summary>
    Done,
    /// <summary>Отменили снаружи.</summary>
    Cancelled,
    /// <summary>Кончилось отведённое время.</summary>
    Timeout,
    /// <summary>Реестр блоков сервера ещё не пришёл.</summary>
    NotReady,
    /// <summary>До начала дороги не дойти.</summary>
    NoRoute,
    /// <summary>Кончился материал.</summary>
    NoMaterial,
    /// <summary>Клетка не поддалась: не сломать или не поставить.</summary>
    Blocked,
    /// <summary>Тело не смогло пройти по своей же дороге.</summary>
    Stuck,
    /// <summary>Впереди не видно земли: чанк не прогружен или там пусто.</summary>
    NoGround,

    /// <summary>
    /// ЗАДАННЫЙ УКЛОН ДОРОГЕ НЕ ПО СИЛАМ: за ряд полотно берёт полблока, и на
    /// названной длине до названной высоты оно не дойдёт.
    ///
    /// Отдельно от <see cref="Blocked"/> нарочно: это не «клетка не поддалась»,
    /// а «задание само себе противоречит», и узнаётся оно ДО первого удара.
    /// Живой случай, дословно из журнала: «от 112 к 80, это 32 бл подъёма на
    /// 38 рядов — круче полублока за клетку дорога не идёт, до конца этот
    /// подъём не выберет» — и следом десять заходов, каждый из которых честно
    /// падал на первых рядах.
    /// </summary>
    TooSteep,

    /// <summary>
    /// ВЫЕМКА НИЖЕ РОСТА ТЕЛА: такой ход можно выкопать, но пройти по нему
    /// нельзя, а значит и дорогой он не станет.
    ///
    /// Отдельно от <see cref="Blocked"/> и <see cref="Stuck"/> нарочно: там
    /// «мир помешал», а здесь задание само себе противоречит, и узнаётся это
    /// ДО первого удара. Живой случай — десятки строк «клетка вскрыта, а тело
    /// в неё не идёт»: бот честно копал столько, сколько сказано, и честно не
    /// влезал; сказать «не хватает просвета» было некому.
    /// </summary>
    NoHeadroom,

    /// <summary>
    /// Заход кончился, а полотно — нет: длинную дорогу кладут в несколько
    /// вызовов (<see cref="Roads.MaxCells"/>).
    ///
    /// Отдельно от <see cref="Done"/> нарочно. Урезанный список рядов раньше
    /// доходил до конца и отчитывался полным успехом: очередь ставила задаче
    /// «сделано» и шла дальше, а человек утром видел дорогу в треть длины и
    /// зелёную очередь.
    /// </summary>
    Unfinished
}

/// <summary>
/// ЧЕЛОВЕЧЕСКИЕ ИМЕНА РУЧЕК, КОТОРЫМИ ПРАВЯТ ДОРОГУ. Кладёт их сюда роль —
/// она их и придумала; механизм только вставляет их в свои отказы, чтобы
/// человеку было что покрутить.
///
/// ЖИВОЙ СЛУЧАЙ 16.08, 20:25:33, дословно: «…чтобы взять 31 бл, нужно 63 рядов
/// — вести до предела мне не велено настройкой». Отказ был честный и с
/// числами, но человек трижды подряд пробовал наугад другие высоты, потому что
/// НАЗВАНИЯ настройки в строке не было.
///
/// Умолчания — имена свойств самого механизма: библиотеку можно взять и без
/// роли, и тогда честнее назвать хоть их, чем не назвать ничего.
/// </summary>
public sealed class RoadKnobs
{
    /// <summary>Чем включают «вести до предела» (<see cref="Roads.LeadTooSteep"/>).</summary>
    public string LeadTooSteep { get; set; } = nameof(Roads.LeadTooSteep);

    /// <summary>Чем задают высоту выемки (<see cref="Roads.Height"/>).</summary>
    public string Height { get; set; } = nameof(Roads.Height);

    /// <summary>
    /// Чем задают ГЛУБИНУ выемки — предел расхождения полотна с землёй
    /// (<see cref="Roads.MaxCutFill"/>).
    ///
    /// ЖИВОЙ СЛУЧАЙ 16.08, 20:30:25: «у (512059, 107, 512241) полотно на
    /// заданной высоте 107,5 разошлось с землёй на −4,5 бл — выемку глубже
    /// 4 бл не роем». Число в отказе было, а имени ручки не было — потому что
    /// ручки и не существовало: четвёрка сидела в библиотеке. Человек читал
    /// «не роем» и не знал, что вообще можно попросить рыть глубже.
    /// </summary>
    public string MaxCutFill { get; set; } = nameof(Roads.MaxCutFill);

    /// <summary>
    /// Чем разрешают бросить полотно и сходить домой за покрытием
    /// (<see cref="Roads.MaySupplyMidRoad"/>). Имя уходит прямо в отказ: без
    /// него человек читает «домой не бегу» как каприз бота, а не как настройку,
    /// которую он сам может повернуть.
    /// </summary>
    public string MidRoadSupply { get; set; } = nameof(Roads.MaySupplyMidRoad);

    /// <summary>
    /// Чем разрешают мостить огрызок недокопанного хода
    /// (<see cref="Roads.PaveUndug"/>). Имя уходит прямо в отказ: иначе человек
    /// читает «встал и жду» и не знает, чем это отменить.
    /// </summary>
    public string PaveUndug { get; set; } = nameof(Roads.PaveUndug);

    /// <summary>
    /// Чем меняют высоту насыпи (<see cref="Roads.MaxFill"/>). Имя уходит прямо
    /// в отказ: прочитав «полотно висит на 4 бл, а подсыпаю я до 3», человек
    /// должен знать, что именно крутить.
    /// </summary>
    public string MaxFill { get; set; } = nameof(Roads.MaxFill);
}

/// <summary>Итог укладки — по фактам.</summary>
/// <param name="Paved">
/// КЛЕТОК полотна закрыто — по одной на клетку, а не по слою. Считает их
/// нижний слой клетки: у ровного места и у неэкономной ступеньки это полный
/// блок покрытия, у экономной ступеньки — сама плита, другого слоя у неё нет.
///
/// Клетками, а не слоями, потому что в одной строке с ними стоят «из {Cells}»
/// и «всего под ногами» — тоже клетки. Заказчик уже споткнулся об эту сумму
/// однажды: «как при ширине 3 на 18 рядов выходит 18 клеток».
/// </param>
/// <param name="Steps">
/// Ступенек сложено — клеток «блок + полублок на нём». Отдельного счёта
/// «сколько игровых ступеней» больше нет: дорога их не кладёт вовсе, и число,
/// которое всегда ноль, в отчёте только сбивает с толку.
/// </param>
/// <param name="Cleared">
/// Клеток ВЫЕМКИ выкопано: и ход над полотном, и постель под него. Постель
/// сюда попала не для красоты счёта — именно её отсутствие в первом проходе
/// заказчик и увидел: «выкопал блок и туда блок дороги».
/// </param>
/// <param name="Skipped">
/// Слоёв полотна, которые УЖЕ ЛЕЖАЛИ на месте и класть их не пришлось: своё с
/// прошлого захода или чужая дорога под трассой.
///
/// ЖИВОЙ СЛУЧАЙ 17.08, 23:53. Заказчик прочёл «дорога 18 рядов из 44, замощено
/// 18 кл. из 132» и справедливо спросил, как при ширине 3 на восемнадцать рядов
/// выходит восемнадцать клеток. Считалось всё верно: 18 положено сейчас, 36
/// лежало с прошлого захода, 18 + 36 = 54 = 18 × 3. Но число «уже было 36»
/// стояло в строке ПОСЛЕ выкопанного и читалось как часть копки. Слагаемые
/// одной суммы обязаны стоять рядом — см. <see cref="ToString"/>.
/// </param>
public sealed record RoadReport(
    RoadStop Stop,
    string Reason,
    BlockPos StoppedAt,
    string Material,
    int Rows,
    int RowsDone,
    int Cells,
    int Paved,
    int Steps,
    int Cleared,
    int Skipped,
    double Seconds)
{
    public bool Success => Stop == RoadStop.Done;

    /// <summary>
    /// УРОВЕНЬ ПОСЛЕДНЕГО ВЫЛОЖЕННОГО РЯДА, в полублоках. <see cref="Unknown"/>
    /// — не выложено ни одного ряда, спрашивать не о чем.
    ///
    /// ЗАЧЕМ ОТЧЁТУ ЭТО ЧИСЛО. Прерванная дорога доделывается вторым заходом, а
    /// он начинается с клетки <see cref="RoadResume.ResumeFrom"/>. Пока полотно
    /// держало ПРЯМУЮ от y1 к y2, высоту этой клетки можно было брать у осевой
    /// линии (<see cref="RoadPlan.Centerline"/>): подсказка прямой совпадала с
    /// делом. Теперь полотно идёт ПО ЗЕМЛЕ, и подсказка от настоящего уровня
    /// расходится тем сильнее, чем живее рельеф. Второй заход закреплял бы
    /// начало на высоте, где дороги нет, — и упирался в «до начала дороги не
    /// дошёл» (журнал 19.08, пять раз подряд).
    ///
    /// Число ЗДЕСЬ, а не считается заново в возврате, нарочно: считать высоту
    /// полотна второй раз значило бы завести вторую разметку рядом с первой.
    /// Дорога уровень ЗНАЕТ — она его и отдаёт.
    /// </summary>
    public int LastLevel { get; init; } = Unknown;

    /// <summary>
    /// ПОМЕХА ОБЩИМ СЛОВОМ: пройдёт ли она сама (<see cref="Setback"/>).
    ///
    /// Это НЕ вторая копия <see cref="Stop"/>, а ответ на другой вопрос.
    /// <see cref="Stop"/> отвечает человеку — «уклон круче посильного», «до
    /// клетки не дотянуться»; <see cref="Hindrance"/> отвечает возврату —
    /// «ждать бесполезно» или «подожди и возьмись заново». Считается одним
    /// чистым правилом (<see cref="Roads.WhatStopped"/>), своего суждения у
    /// отчёта тут нет.
    /// </summary>
    public Setback Hindrance { get; init; } = Setback.None;

    /// <summary>Ряды не клали — уровня нет. Не ноль: ноль это законная высота.</summary>
    public const int Unknown = int.MinValue;

    // «УЖЕ ЛЕЖАЛО» СТОИТ РЯДОМ С «ЗАМОЩЕНО», А НЕ ПОСЛЕ ВЫКОПАННОГО: это
    // слагаемые одной суммы, и порознь они читаются как разные величины —
    // на этом заказчик и споткнулся (см. <see cref="Skipped"/>)
    public override string ToString() =>
        $"дорога {RowsDone} рядов из {Rows}, замощено {Paved} кл. из {Cells} ({Material})" +
        (Skipped > 0 ? $", уже лежало {Skipped}, всего под ногами {Paved + Skipped}" : "") +
        (Steps > 0 ? $", ступенек {Steps}" : "") +
        (Cleared > 0 ? $", выкопано {Cleared} кл. выемки" : "") +
        $"; {Seconds:0} с; остановка на {StoppedAt}: {Reason}";
}

/// <summary>
/// ДОРОГА: замостить полосу от точки до точки, по которой потом ходить быстрее.
///
/// Зачем это боту. Поиск пути уже умеет ЛЮБИТЬ дороги — шаг по клетке с
/// повышенной скоростью стоит дешевле (PathOptions.RoadCostFactor), и маршрут
/// сам к ним липнет. Но строить их было некому.
///
/// ЖИВОЙ СЛУЧАЙ, ради которого класс переписан. На «!дорога 323 113 -258» бот
/// весь вечер только ХОДИЛ: мощения не было ни одного блока. Причин две.
/// Первая — команда «дорога» в диагностике перебивала одноимённый навык (это
/// проводка, см. отчёт). Вторая — сама укладка шла по маршруту поиска пути
/// шириной в одну клетку и без единого полублока: маршрут обходит перепады
/// стороной, а дорога обязана их ВЗЯТЬ. Заказчик сказал прямо: точка старта,
/// точка конца, ширина; перепады — лесенкой из полублоков и блоков.
///
/// ПОЭТОМУ ДОРОГА — ОТРЕЗОК, А НЕ МАРШРУТ. Полотно кладётся по прямой от A к B
/// нужной ширины (<see cref="RoadPlan.Rows"/>), а на какой высоте лечь каждому
/// ряду, решает разметка (<see cref="RoadPlan.Levels"/>). Обе раскладки —
/// чистые правила без мира и закрыты тестами; здесь остаётся работа руками.
///
/// ВЫСОТА ИЗ ЗАДАНИЯ — ЭТО КОНЦЫ, А МЕЖДУ НИМИ ДОРОГА ИДЁТ ПО ЗЕМЛЕ. Сначала
/// заданный Y был только подсказкой, где искать землю, и заказчик сказал «он не
/// учитывает высоту в задании». Потом полотно стало держать ПРЯМУЮ от y1 к y2
/// — и встало на первом же живом рельефе: 22.08 в 20:59 вниз («разошлось с
/// землёй на −17,5 бл») и в 21:02 вверх («висит над землёй 30 рядов подряд»),
/// оба заказа в ноль. Слова заказчика: «а теперь просто не строит дорогу вниз и
/// вверх». Настоящая дорога так и не строится: она сглаживает землю в пределах
/// уклона и попадает в заданные концы — этим и занята разметка. Земля под осью
/// при этом остаётся МЕРОЙ: по ней видно, какой глубины выемку и какой длины
/// мост дорога набрала на самом деле.
///
/// РАЗОШЛОСЬ ВНИЗ — ЭТО ВЫЕМКА, ВВЕРХ — ЭТО МОСТ, И ЭТО ДВЕ РАЗНЫЕ РАБОТЫ.
/// Выемку меряет глубина (<see cref="MaxCutFill"/>): глубже позволенного бот
/// не режет и называет число. Провал под полотном мостится тем же приёмом,
/// каким бот ходит через любую пропасть (<see cref="Scaffolding.BridgeAsync"/>),
/// и глубина провала мосту безразлична — настил один слой что над ямой в блок,
/// что над пропастью в пятьдесят. Ограничивает мост ДЛИНА пролёта, а не
/// глубина. Живой случай 22.08, 17:18:35, из-за которого это и разведено:
/// «полотно … разошлось с землёй на 5 бл — ТУТ НУЖЕН МОСТ, а насыпь в воздухе
/// бот не держит (предел 4 бл)» — бот назвал приём, которым беда лечится, и
/// вместо него встал, отдав ноль рядов из двадцати девяти.
///
/// ВЕСЬ ХОД РАЗВЕДЫВАЕТСЯ ДО ПЕРВОГО УДАРА (<see cref="Scouted"/>). Профиль
/// считался окном в дюжину рядов прямо в цикле, и о помехе на одиннадцатом
/// ряду бот узнавал, выкопав десять. Заказчик увидел это дважды за семь минут
/// и написал «не идет делать дорогу»: работы на восемь рядов, показать нечего.
/// Читать мир дёшево, копать и бросать — дорого.
///
/// ЧТО СЧИТАЕТСЯ ПОКРЫТИЕМ. Не код блока, а то, что о блоке говорит РЕЕСТР
/// игры: множитель хода (Block.WalkSpeedMultiplier) — «дорога» это то, по чему
/// быстрее; материал (EnumBlockMaterial) — руда и металл в полотно не идут
/// НИКОГДА; форма коробок коллизии — по ней узнаётся полублок, в модах его
/// зовут как угодно, а полкуба остаётся полкубом. Разбирает всё это
/// <see cref="RoadPlan.JudgeSurface"/>, и оно закрыто тестами.
///
/// ПОКРЫТИЕ КРАФТИТСЯ ПО ПОТРЕБНОСТИ. Заказчик сказал прямо: «дороги он не
/// крафтил». Дорожное покрытие ищется не только в сумках, но и в реестре
/// РЕЦЕПТОВ: в ванильной игре каменная дорожка — это четыре камня и земля,
/// то есть ровно то, чего у копателя горы. Своего списка кодов при этом нет:
/// «дорожное» — то, чему сама игра поставила скорость выше единицы.
///
/// ПЕРЕПАД — ЭТО СТУПЕНЬКА «БЛОК + ПОЛУБЛОК», И БОЛЬШЕ НИЧЕГО. Дословный заказ:
/// «я просил из них делать ступеньки — блок, полублок на блок той же высоты
/// что дорога». Игровой блок-ступень (stonepathstairs и родня) не кладётся и
/// не крафтится НИГДЕ — вместе с ним ушла и развилка «есть ступени / нет
/// ступеней», из-за которой слово расходилось с делом: в журнале стояло
/// «перепады беру полублоками», сказанное один раз на выходе, а решение
/// пересчитывалось на каждом окне и молча переворачивалось, стоило выломать
/// достаточно камня на рецепт ступени. Заказчик увидел это так: «полублоки
/// пишет бот, а крафтит лестницы (ступеньки) дороги».
///
/// ПОРЯДОК РАБОТЫ — ДВА ПРОХОДА, И ПЕРВЫЙ ИЗ НИХ ВЫНИМАЕТ ЗЕМЛЮ. Сперва бот
/// проходит ВЕСЬ ход и выкапывает выемку под полотно, и только потом
/// возвращается к началу и мостит (<see cref="RoadPlan.Order"/>, ручка
/// <see cref="DigFirst"/>).
///
/// ЭТО ВТОРОЙ ЗАХОД НА ОДИН И ТОТ ЖЕ ЗАКАЗ, и первый не сработал. Прошлая
/// волна развела проходы по рядам, но копала первым проходом ОДИН ЛИШЬ ход над
/// полотном (<see cref="RoadPlan.Trench"/>) — а над полотном на ровном поле
/// пусто, копать там нечего. Землю же из-под самого полотна выламывала укладка
/// за миг до установки блока, и заказчик увидел ровно это: «дорогу все еще
/// моментально ставит — выкопал блок и туда блок дороги, а я просил в начале
/// копать, а только потом пойти ставить блоки». Теперь первый проход вынимает
/// ПОСТЕЛЬ полотна (<see cref="RoadPlan.Cut"/>) — то самое, что человек и
/// звал копкой.
///
/// КОПАЕТ БОТ ПОЗАДИ СЕБЯ, как живой землекоп. Клетку прямо под своими ногами
/// он не ломает — упадёт; но и отходить ради неё в сторону на каждом ряду
/// нельзя, иначе весь первый проход уйдёт в переминание с ноги на ногу.
/// Поэтому такая клетка откладывается и доламывается с СЛЕДУЮЩЕГО ряда, откуда
/// до неё рукой подать: бот идёт вперёд по нетронутой земле и выбирает траншею
/// за собой.
///
/// Внутри одного ряда порядок прежний: ряд готовится ДО того, как в него
/// шагнут. С клетки, которую сейчас мостим, бот СХОДИТ — один раз на ряд
/// и с честной проверкой по ногам (<see cref="StepOffAsync"/>).
///
/// РАСТЕНИЕ НА МЕСТЕ УСТАНОВКИ ЛОМАЕТСЯ. Дословно: «если на месте установки
/// растет растения, то оно мешает ставить блок и его нужно сломать». Так и
/// есть, и виновата была проверка: занятость клетки спрашивали у проходимости
/// (<c>IsPassable</c>), а у травы, цветка, папоротника и гриба нет коробки
/// коллизии — клетка считалась пустой, бот не ломал ничего и слал установку в
/// занятую клетку. Игра ставит блок поверх другого, только если тот помечен
/// заменяемым (у травы это так), а цветы, папоротники, грибы и кусты этого
/// мира помечены иначе — и сервер установку отбрасывает. Спрашиваем теперь
/// прямо: ЕСТЬ ЛИ В КЛЕТКЕ БЛОК (<see cref="NeedsClearing"/>).
///
/// Класс — МЕХАНИЗМ. Куда вести дорогу, какой ширины и стоит ли ради неё
/// крафтить, решает роль.
/// </summary>
public class Roads
{
    private readonly BotContext ctx;

    public Roads(BotContext ctx) => this.ctx = ctx;

    public event Action<string>? OnLog;

    // ---------------- настройки ----------------

    /// <summary>
    /// МОСТИТЬ ТОЛЬКО ЭТИМ И НИЧЕМ ДРУГИМ. Пусто (и так надо почти всегда) —
    /// бот выбирает сам: дорожное покрытие из сумок, дорожное по рецепту, и
    /// лишь потом ровный пол.
    ///
    /// ЭТО НЕ ВЫБОР «КАКАЯ БЫВАЕТ ДОРОГА». Заказчик спросил прямо: «Покрытие
    /// дороги — странная настройка, мы же дороги делаем по рецепту из игры
    /// которые каменная, других и не надо или я не понял твою мысль». Он прав:
    /// какой блок в этом мире дорога, решает не человек и не список в боте, а
    /// сама игра — по множителю хода. В ванильной игре такой рецепт ОДИН:
    /// каменная дорожка (четыре камня и земля, ход 1,3), и бот находит его сам,
    /// не спрашивая. Деревянная дорожка игре тоже «дорога», но у неё нет
    /// коробки коллизии — её кладут ПОВЕРХ пола, полотном она не бывает, и
    /// автоматический выбор её не возьмёт.
    ///
    /// ТОГДА ЗАЧЕМ ПОЛЕ. Затем, что у выбора есть последний шаг: не нашлось
    /// дорожного — бот кладёт ровный пол, то есть булыжник, а то и землю
    /// («ходить не быстрее, но и не спотыкаться»). Кому это не нужно, пишет
    /// сюда «stonepath» — и бот либо кладёт каменную дорожку, либо честно
    /// встаёт и говорит, чего не хватило на рецепт. Второй случай — мир с
    /// модами, где дорожных покрытий несколько и хочется именно одно.
    ///
    /// ЗАКОН ЗДЕСЬ НЕ ОТМЕНЯЕТСЯ. Названное проверяется тем же реестром, что и
    /// выбранное самим ботом: руду, самородки и металл в полотно не кладут
    /// НИКОГДА, полублоком и ступенью полотно не мостят. Прежде это поле было
    /// дырой в законе — «ore-poor-nativecopper» в нём означало дорогу из медной
    /// руды, ровно ту, из-за которой закон и появился.
    /// </summary>
    public string RoadCode { get; set; } = "";

    /// <summary>
    /// Класть ВЕРХ СТУПЕНЬКИ только этим полублоком. Пусто (и так надо почти
    /// всегда) — искать в сумках по форме, а нет в сумках — сделать по рецепту
    /// (что считать полублоком, знает реестр: в ванильной игре это дорожная
    /// плита, два камня и земля). Низ ступеньки кладётся тем же покрытием, что
    /// и полотно: он и есть полотно, только на клетку раньше.
    ///
    /// Названное проверяется формой из реестра: не полублок сюда не пройдёт.
    /// Верх ступеньки целым блоком — это ступенька в целый блок, на которую без
    /// прыжка не всходят, то есть дорога, по которой не пройти.
    /// </summary>
    public string SlabCode { get; set; } = "";

    /// <summary>Ширина полотна в клетках, если её не назвали при вызове.</summary>
    public int Width { get; set; } = 1;

    /// <summary>
    /// «ПОКРЫТИЕ ЕЩЁ НЕ ВЫБРАНО» — одно слово на отчёт и на проверки.
    ///
    /// Прочерк, а не пустая строка, нарочно: этой же чёрточкой отчёт дороги
    /// называл неизвестный материал и раньше («замощено 0 кл. из 13 (—)»), и
    /// заводить рядом второе обозначение того же самого значило бы дать
    /// человеку два разных слова про один случай. Пустая строка к тому же
    /// напечаталась бы в отчёте как «()».
    /// </summary>
    private const string NoSurface = "—";

    /// <summary>
    /// СПЕРВА ПРОЙТИ ВЕСЬ ХОД И ВЫКОПАТЬ ВЫЕМКУ, ПОТОМ МОСТИТЬ. Прямая просьба
    /// заказчика: «может для реализма в начале плюс копает, а уже потом
    /// пробежит и поставит везде дорогу? а то нереалистично смотрится».
    ///
    /// Цена честная и её надо знать: ход бот проходит ДВАЖДЫ, и на дорогу
    /// уходит примерно вдвое больше ходьбы. Выключишь — вернётся прежний
    /// порядок, ряд за рядом; на дороге в два ряда он и разумнее.
    /// </summary>
    public bool DigFirst { get; set; } = true;

    /// <summary>
    /// МОСТИТЬ ЛИ ОГРЫЗОК, КОГДА ПРОХОДКА ВСТАЛА, НЕ ДОЙДЯ ДО КОНЦА.
    ///
    /// ТРЕТЬЯ ЖАЛОБА НА ОДНО И ТО ЖЕ, слова заказчика 19.08 дословно: «он всё
    /// ещё начинает в середине стройки начинать мостить дорогу, а я просил в
    /// начале выкапывать, а потом уже ставить блоки». В журнале 23:51:14 бот
    /// перед этим честно объявил порядок работ — «сперва прохожу весь ход
    /// (39 рядов) и копаю его, потом возвращаюсь к началу и мощу», — а следом
    /// сам же его нарушил: «ПРОХОДКА ВСТАЛА на ряду 11 из 39 … возвращаюсь к
    /// началу и кладу полотно только на выкопанные 11 рядов». Формально это не
    /// враньё, по существу — ровно то, на что человек жалуется третий раз:
    /// посреди стройки появляется мощёный обрубок.
    ///
    /// ВЫКЛЮЧЕНО, И ЭТО РАЗУМНОЕ УМОЛЧАНИЕ. Встала проходка — бот НЕ мостит
    /// ничего, а встаёт и называет: где встал, почему, что можно повернуть.
    /// Выкопанное при этом никуда не девается: подняли ручку, о которой сказал
    /// отказ, — следующий заход докопает и замостит всё разом.
    ///
    /// ВКЛЮЧАЮТ, когда полотно нужно хоть какое-то прямо сейчас: тогда
    /// возвращается прежнее поведение — мостим ровно выкопанное, о недокопанном
    /// говорим вслух.
    /// </summary>
    public bool PaveUndug { get; set; }

    /// <summary>
    /// МОСТИТЬ ЛИ ПОСЛЕ ВСТАВШЕЙ ПРОХОДКИ — чистое правило и слова, которыми
    /// об этом говорят. Ни мира, ни тела: только «дошла ли копка до конца»,
    /// положение ручки и числа.
    ///
    /// ПОЧЕМУ ОТДЕЛЬНО ОТ ЦИКЛА. Живьём это место стоит в середине
    /// <see cref="BuildAsync"/> и проверяется только полным стендом с чанком,
    /// сумкой и покрытием, — а заказчик разницу видит с первого взгляда и
    /// жалуется на неё третий раз подряд. Правилу, за которое отчитываются
    /// трижды, положен свой тест.
    /// </summary>
    /// <param name="digDone">Проходка дошла до конца захода.</param>
    /// <param name="paveUndug">Ручка <see cref="PaveUndug"/>.</param>
    /// <param name="halted">Докуда проходка дошла, рядов.</param>
    /// <param name="rows">Сколько рядов в заходе.</param>
    /// <param name="digWhy">Чем именно встала проходка.</param>
    /// <param name="knob">Как ручка зовётся у человека (<see cref="RoadKnobs.PaveUndug"/>).</param>
    public static (bool Pave, string Say) AfterHalt(bool digDone, bool paveUndug, int halted,
        int rows, string digWhy, string knob)
    {
        if (digDone)
            return (true, "");
        string beda = $"ПРОХОДКА ВСТАЛА на ряду {halted} из {rows}: {digWhy}";
        return paveUndug
            ? (true, beda + $". Мощу выкопанное ({halted} рядов) — так велено ручкой «{knob}»")
            // «Встал и жду» без выполнимого — это тупик, за который в этом
            // проекте уже ловили дважды: человек читает беду и не знает, что
            // ему-то делать. Поэтому оба выхода называются здесь же
            : (false, beda + ". Полотно НЕ кладу ни на один ряд: обещал сперва пройти весь ход, " +
                       $"а он не пройден — выкопанные {halted} рядов ждут. Уберите помеху " +
                       $"(её причина названа выше) и повторите — докопаю и замощу всё разом; " +
                       $"либо включите ручку «{knob}», и тогда замощу выкопанное как есть");
    }

    /// <summary>
    /// ПОКРЫТИЯ ПОКА НЕТ — КОПАТЬ ЛИ ХОД ВСЁ РАВНО. Чистое правило и слова,
    /// которыми об этом говорят.
    ///
    /// ЖИВОЙ ПРОГОН 29.08, СТЕНД, ОТРЕЗОК «12 БЛОКОВ ВБОК И 6 ВНИЗ»:
    ///   20:18:55 «дорога 0 рядов из 13, замощено 0 кл. из 13 (—); 62 с;
    ///             остановка …: мостить нечем … на stonepath-free не хватает:
    ///             stone-andesite (надо 4, есть 0), soil-* (надо 1, есть 0)».
    /// Шестьдесят две секунды бот ходил домой и читал шестнадцать сундуков — и
    /// НЕ СДЕЛАЛ НИ ОДНОГО УДАРА КИРКОЙ. Ровно те же числа заказчик и прислал
    /// как беду: «дорога 0 рядов из 41, замощено 0 кл. из 123».
    ///
    /// А НЕ ХВАТАЛО ЕМУ ЧЕТЫРЁХ КАМНЕЙ И ОДНОЙ ЗЕМЛИ — и стоял он на том самом
    /// склоне, который ему велено прокопать: спуск в 13 рядов это 13 столбцов
    /// выемки по <see cref="Height"/> + 1 клетке, то есть под восемь десятков
    /// клеток породы и грунта. ХОД САМ И ЕСТЬ КАРЬЕР ДЛЯ СВОЕЙ ДОРОГИ.
    ///
    /// ПОЭТОМУ ВОПРОС «ЧЕМ МОСТИТЬ» ЗАДАЮТ ТОГДА, КОГДА МОСТЯТ. Это не новая
    /// вольность, а та самая договорённость, которую бот и так объявляет вслух
    /// при <see cref="DigFirst"/>: «сперва прохожу весь ход и копаю его, потом
    /// возвращаюсь к началу и мощу». Спрашивать материал укладки ДО копки
    /// значило обещать одно, а делать другое — и отдавать человеку два нуля.
    ///
    /// ВЫКЛЮЧЕННЫЙ <see cref="DigFirst"/> сюда не попадает нарочно: там копка и
    /// укладка идут вперемешку, клетка за клеткой, и «выкопаю, а мостить нечем»
    /// означало бы вскрытую постель под открытым небом на каждом ряду. Отказ
    /// остаётся прежним — до первого удара.
    ///
    /// ОТДЕЛЬНОЙ РУЧКИ ЗДЕСЬ НЕТ И БЫТЬ НЕ ДОЛЖНО: ручка «сперва копать»
    /// уже есть, и вторая означала бы «копать сперва, но не совсем» — то есть
    /// человек включил бы первую и всё равно получил бы «0 рядов, 0 клеток».
    /// </summary>
    /// <param name="digFirst">Ручка <see cref="DigFirst"/>.</param>
    /// <param name="whyNoSurface">Чем именно отказало покрытие (со всеми числами).</param>
    public static (bool Dig, string Say) DigWithoutSurface(bool digFirst, string whyNoSurface) =>
        digFirst
            ? (true, $"покрытия пока нет ({whyNoSurface}), но обещано сперва пройти и " +
                     "выкопать весь ход — иду копать. Породу и грунт ход даст сам, и чем " +
                     "мостить, спрошу заново, когда вернусь к началу")
            : (false, whyNoSurface);

    /// <summary>
    /// ДОПИСАТЬ В ПРИЧИНУ, ЧТО РАНЬШЕ ВСТАЛА ПРОХОДКА, — но только если это и
    /// правда ДРУГАЯ беда.
    ///
    /// ЖИВОЙ СЛУЧАЙ 22.08, 17:18:35. Отказ дороги кончался так:
    ///   «…ПРОХОДКА ВСТАЛА на ряду 11 из 29: у (55, 112, 263) полотно на
    ///    заданной высоте 112 разошлось с землёй на 5 бл — тут нужен мост …;
    ///    ещё раньше встала проходка: у (55, 112, 263) полотно на заданной
    ///    высоте 112 разошлось с землёй на 5 бл — тут нужен мост …»
    /// Одна и та же беда названа дважды в одной строке, и второй раз — под
    /// словом «ещё раньше», то есть человек ищет ВТОРУЮ помеху, которой нет.
    ///
    /// Так вышло не по недосмотру: когда мостить нечего (ручка
    /// <see cref="PaveUndug"/> опущена), причиной отчёта становится сам рассказ
    /// про вставшую проходку (<see cref="AfterHalt"/>), а он уже несёт в себе
    /// <paramref name="digWhy"/>. Приписка нужна в ДРУГОМ случае: полотно
    /// легло, а копка встала раньше — тогда причины и правда две.
    ///
    /// Чистое правило: живьём разница между этими двумя случаями видна только
    /// полным прогоном дороги в двух положениях ручки.
    /// </summary>
    public static string AlsoHalted(string reason, string digWhy) =>
        digWhy.Length == 0 || reason.Contains(digWhy, StringComparison.Ordinal)
            ? reason
            : reason + $"; ещё раньше встала проходка: {digWhy}";

    /// <summary>
    /// СТУПЕНЬКА КЛАДЁТСЯ ЦЕЛИКОМ ИЛИ НЕ КЛАДЁТСЯ ВОВСЕ — чистое правило и
    /// слова, которыми об этом говорят. Ни мира, ни тела: только «сколько
    /// полублоков нужно ряду» и «сколько их есть».
    ///
    /// ЖИВОЙ СЛУЧАЙ 19.08, И ИМЕННО ИЗ НЕГО ВЫРОСЛИ «СТРАННЫЕ ОТКАЗЫ». Ступенька
    /// — это два слоя: полный блок покрытия и полублок на нём
    /// (<see cref="RoadPlan.Layers"/>). Полублок спрашивался ОДИН раз на ряд и
    /// только «есть ли хоть один», а ряд шириной три требует трёх. В журнале
    /// 23:53:44 бот сделал ровно четыре плиты, разложил их — и на пятой клетке
    /// упёрся:
    ///   «остановка на (512052, 111, 512255): stonepathslab-free кончился,
    ///    а ступеньку им не закрыть»
    /// К этой секунде полный блок той клетки УЖЕ ЛЕЖАЛ: слои кладутся снизу
    /// вверх, и отказ приходил между ними. В дороге оставался приступок в целый
    /// блок вместо половинки — и дальше начиналось то, на что заказчик и
    /// жалуется третьим пунктом:
    ///   23:59:23 «не пойду на точку 3/5 (512052, 111, 512255): она на 2 бл выше
    ///             меня … шагом берётся 0,6 бл, прыжком ровно 1 бл»
    ///   23:59:28 «до начала дороги (512052, 112, 512252) не дошёл»
    /// и так пять заходов подряд. Бот построил лестницу, по которой сам же не
    /// поднимается, а потом отказывался — и беда случилась на два шага раньше.
    ///
    /// ПРИГОВОР ОТКАЗА БЫЛ ВЕРЕН, А ОБЪЯСНЕНИЕ ЛГАЛО, и это стоило отдельного
    /// разбора. Два блока в соседней клетке телу и правда не по силам, но
    /// «прыжком РОВНО 1 бл» — неправда: ноги в апексе поднимаются на 1,27
    /// (<see cref="JumpPhysics.ApexRise"/>, замер на игровой физике). Заказчик
    /// поймал нас именно на этих словах: «разве у героя прыжок ровно 1? мне
    /// казалось на снег запрыгивает?» — запрыгивает. Теперь отказ называет
    /// замеренное число, а не переписанное от руки.
    ///
    /// РУЧКИ ЗДЕСЬ НЕТ И НЕ БУДЕТ. «Класть ступеньку по половинке» — это не
    /// выбор политики, а порча дороги: пройти по такой нельзя ни боту, ни
    /// человеку. Выбор у человека остаётся прежний и настоящий — дать полублоков
    /// или дать материал на них.
    /// </summary>
    /// <param name="have">Сколько полублоков в сумках прямо сейчас.</param>
    /// <param name="need">Сколько клеток ряда ждут верха ступеньки.</param>
    /// <param name="slab">Код полублока — тот самый, что назван человеку.</param>
    /// <param name="at">Осевая клетка ряда: с ней человек и найдёт место.</param>
    /// <param name="whyNoMore">Почему больше не сделать (из реестра рецептов).</param>
    public static (bool Lay, string Say) WholeSteps(int have, int need, string slab, BlockPos at,
        string whyNoMore)
    {
        if (have >= need)
            return (true, "");
        return (false,
            $"на ступеньки ряда у {at} нужно ПОЛУБЛОКОВ {need} ({slab}), а есть {have}. " +
            "Ступеньку кладу целиком или не кладу вовсе: положи я низ без верха — " +
            "в дороге останется приступок в целый блок, по которому не поднимусь ни я, " +
            $"ни человек. Ни одной клетки этого ряда не тронул. {whyNoMore}");
    }

    /// <summary>
    /// ПОЧЕМУ НЕ ВЫШЛО ДОЙТИ ДО НАЧАЛА ДОРОГИ — и что с этим делать человеку.
    ///
    /// ЖИВОЙ СЛУЧАЙ 19.08, 23:59–00:01, слова заказчика: «странные отказы
    /// строить дальше». Пять заходов подряд кончались одной и той же строкой —
    /// «до начала дороги (512052, 112, 512252) не дошёл», — и в ней не было
    /// НИЧЕГО, что человек мог бы повернуть. А повернуть было что: бот стоял
    /// на пятом ряду ЭТОЙ ЖЕ дороги, в собственной выемке, на два блока ниже
    /// её начала. Дорога с той клетки заказывается и ведётся дальше как ни в
    /// чём не бывало — но об этом надо было сказать.
    ///
    /// ПРАВИЛО ЧИСТОЕ. Ни мира, ни пути: где стою, где начало и как разложены
    /// ряды — всё это уже посчитано к этой секунде.
    /// </summary>
    /// <param name="stand">Где бот стоит ногами.</param>
    /// <param name="head">Куда шёл — клетка начала дороги, как её нашёл мир.</param>
    /// <param name="rows">Ряды этого захода (<see cref="RoadPlan.Rows"/>).</param>
    public static string WhyNoStart(BlockPos stand, BlockPos head, IReadOnlyList<RoadRow> rows)
    {
        string where = $"до начала дороги {head} не дошёл: стою в {stand}";
        int dy = stand.Y - head.Y;
        if (dy != 0)
            where += $", это на {Math.Abs(dy)} бл {(dy < 0 ? "ниже" : "выше")} начала";

        // СТОЮ ЛИ Я НА САМОЙ ЭТОЙ ДОРОГЕ. Сравниваем по X и Z: высота у
        // выкопанного ряда своя, и требовать совпадения по ней значило бы не
        // узнать себя в собственной выемке — а это ровно живой случай
        int mine = -1;
        for (int i = 0; i < rows.Count && mine < 0; i++)
            foreach (var cell in rows[i].Cells)
                if (cell.X == stand.X && cell.Z == stand.Z)
                {
                    mine = i;
                    break;
                }

        return mine >= 0
            ? where + $" — это ряд {mine + 1} из {rows.Count} этой же дороги: я в своей выемке, " +
                      "а вверх из неё шагом не выйти. Выполнимое: закажите дорогу от " +
                      $"{rows[mine].Centre} — поведу дальше с того ряда, где стою; либо " +
                      "уберите стенку между мной и началом, и повторите прежний заказ"
            // Не на дороге — значит между нами что-то чужое, и трогать его без
            // спроса нельзя (правило проекта). Называем оба конца: с ними
            // человек хотя бы знает, куда идти
            : where + " — перебрал все маршруты, какие умею, и не дошёл. Выполнимое: " +
                      $"уберите помеху между {stand} и {head}, либо закажите дорогу от " +
                      "той клетки, где я стою";
    }

    /// <summary>
    /// ЛУЧ ДО КЛЕТКИ ПЕРЕКРЫТ — СНИМАТЬ ЛИ ПОМЕХУ РАНЬШЕ ЕЁ ОЧЕРЕДИ. Чистое
    /// правило и слова, которыми об этом говорят: ни мира, ни руки, ни кирки.
    ///
    /// ЖИВОЙ СЛУЧАЙ 19.08, 23:50:26, дословно из журнала заказчика:
    ///   «[добыча] мелочь в (512055, 112, 512259) не смахнул: soil-medium-normal
    ///    — Soil не подлесок, и мусором игра его не зовёт»
    ///   «[руки] до (512055, 113, 512259) нет прямой видимости: мешает
    ///    soil-medium-normal … мешает не расстояние»
    ///   «[дорога] (512055, 113, 512259) в выемке дороги: до fern-deerfern
    ///    не дотянуться»
    /// Заказчик разобрал это верно: земля НЕ мелочь, смахивать её рука не
    /// обязана — но она лежит В ВЫЕМКЕ ДОРОГИ, и выкопать её всё равно
    /// предстоит. Бот стоял на дне уже выкопанного ряда, то есть НИЖЕ будущего
    /// полотна, и целился вверх-вперёд: столбец снимают сверху вниз, а с
    /// такого места верхушка столбца закрыта его же серединой. Клетка уходила
    /// в «не дотянулся» насовсем — а будь она клеткой полотна, встала бы вся
    /// дорога.
    ///
    /// ПОРЯДОК «СВЕРХУ ВНИЗ» ТУТ НЕ НАРУШАЕТСЯ ЗРЯ: он бережёт от осыпи НАД
    /// головой, а помеха эта — под целью и в том же столбце. Сняли её — до
    /// цели стало видно, и цель либо падает сама (трава, папоротник), либо
    /// берётся тем же ударом.
    ///
    /// ТОЛЬКО СВОЮ ВЫЕМКУ И ТОЛЬКО ОДИН РАЗ. Чужой блок ломать без спроса
    /// нельзя (правило проекта), а уже снятый ломать нечем: сервер ответит
    /// отказом, и честная остановка дороги вышла бы на пустом месте.
    ///
    /// ПОЧЕМУ ОТДЕЛЬНОЙ ФУНКЦИЕЙ. Живьём это место стоит внутри цикла ударов и
    /// проверяется только полным стендом с чанком, киркой и отвечающим
    /// сервером; сам же выбор — четыре сравнения, и сломать его можно одной
    /// строкой. Заказчик жалуется на эту клетку прямым текстом, значит правилу
    /// положен свой тест.
    /// </summary>
    /// <param name="aim">Клетка, до которой не дотянулись.</param>
    /// <param name="blocked">Во что упёрся луч (<c>Hands.Look(...).BlockedBy</c>).</param>
    /// <param name="mine">
    /// Клетки, которые мне можно снять ПРЯМО СЕЙЧАС, — не вся выемка.
    ///
    /// ЭТО НЕ ПРИДИРКА К СЛОВУ. Выемка целиком содержит и то, что
    /// <see cref="RoadPlan.TopDown"/> нарочно отложил: пол под собственными
    /// ногами и всё, что под ним в том же столбце. Снять пол под собой раньше
    /// очереди — это упасть в свою же работу, ровно от чего откладывание и
    /// заведено (живой случай 01:31:00). Поэтому сюда идёт <c>Now</c> из
    /// <see cref="SplitTopDown"/>, а не список, с которого начали.
    /// </param>
    /// <param name="taken">Что уже снято раньше очереди в этом же заходе.</param>
    /// <param name="where">Как зовётся место в словах: выемка или ход над полотном.</param>
    /// <returns>
    /// Брать ли помеху сейчас и что сказать, КОГДА она снята: слова говорятся
    /// по факту снятия, а не по намерению (правило 4 проекта).
    /// </returns>
    public static (bool Take, string Say) ClearTheAim(BlockPos aim, BlockPos? blocked,
        IReadOnlyCollection<BlockPos> mine, IReadOnlyCollection<BlockPos> taken, string where)
    {
        // Луч не считали или помеху не назвали: далёкая цель — это просто
        // «не дотянуться», снимать там нечего
        if (blocked is not { } wall)
            return (false, "");
        // Сама цель себе не помеха: её мы и собрались ломать
        if (wall == aim || taken.Contains(wall) || !mine.Contains(wall))
            return (false, "");
        return (true, $"до {aim} {where} луч перекрывал {wall} — это моя же выемка, " +
                      "снял её раньше очереди и целюсь заново");
    }

