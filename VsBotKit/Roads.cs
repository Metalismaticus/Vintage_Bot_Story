    /// длину дороги». ЭТО НЕПРАВДА. Выемку под ряд размечает
    /// <see cref="RoadPlan.Cut"/>, и высота столбца там — <see cref="Height"/>
    /// клеток над полотном плюс постель, СКОЛЬКО БЫ НИ БЫЛО ЗЕМЛИ СВЕРХУ.
    /// Выемка в 4 бл и выемка в 12 бл — это ровно 6 клеток на клетку полотна и
    /// там и там; глубже просто остаётся кровля, и ход из открытой выемки
    /// становится крытым. Значит четвёрка не берегла ни одного удара киркой —
    /// она только останавливала дорогу.
    ///
    /// А ОСТАНАВЛИВАЛА ЧАСТО. Живой случай 22.08, 17:25:14: спуск 112 → 97 на
    /// 31 ряд, уклон посильный, — и проходка встала на ВОСЬМОМ ряду, потому
    /// что полотно ушло в бугор на 4,5 бл. Полблока сверх предела, восемь
    /// выкопанных рядов впустую и ноль полотна. На живом рельефе Vintage Story
    /// перепад в 4 бл на тридцати рядах — это обычный бугор, а не пропасть.
    /// Двенадцать — это ход под кровлей в 7 бл над просветом в 5: всё ещё
    /// дорога, по которой бот ходит.
    ///
    /// ГЛАВНОЕ ЖЕ НЕ САМО ЧИСЛО, А ТО, ЧТО ОНО БОЛЬШЕ НЕ ЛОВУШКА: весь ход
    /// разведывается ДО ПЕРВОГО УДАРА (<see cref="Scouted"/>), и если предела
    /// не хватает — бот называет самую глубокую выемку, её ряд, её клетку и
    /// ЧИСЛО, которое надо поставить, не тронув ни одного блока.
    ///
    /// Число — политика, и живёт оно ручкой роли («ГлубинаВыемкиДороги» у
