    /// половины этой строки к тому дню устарели: мост бот уже умел
    /// (<see cref="Scaffolding.BridgeAsync"/>), а предел глубины к нему не
    /// относится вовсе — НАД ПРОВАЛОМ РАБОТА ОТ ЕГО ГЛУБИНЫ НЕ ЗАВИСИТ. Мост
    /// — это один слой блоков под ногами, и над ямой в один блок его ровно
    /// столько же, сколько над пропастью в пятьдесят. Мерить мост «глубиной
    /// выемки» было попросту не тем инструментом; теперь провал под полотном
    /// мостится (см. <c>BridgeRunAsync</c>), а здешнее число к нему не
    /// применяется.
    ///
    /// ДВЕНАДЦАТЬ, А НЕ ЧЕТЫРЕ, И ВОТ ЦЕНА ЧИСЛА. Прежние четыре стояли на
