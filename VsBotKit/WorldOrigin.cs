    /// <summary>Клетка словами, с живым началом отсчёта.</summary>
    public static string Say(int x, int y, int z) => Say(x, y, z, spawn);

    /// <summary>Клетка словами без скобок, с живым началом отсчёта.</summary>
    public static string SayBare(int x, int y, int z) => SayBare(x, y, z, spawn);

    /// <summary>Точка с дробью словами, с живым началом отсчёта.</summary>
    public static string Say(double x, double y, double z) => Say(x, y, z, spawn);

    /// <summary>Точка с дробью без скобок, с живым началом отсчёта.</summary>
    public static string SayBare(double x, double y, double z) => SayBare(x, y, z, spawn);

    /// <summary>Пара «X и Z» словами, с живым началом отсчёта.</summary>
    public static string SayFlat(double x, double z) => SayFlat(x, z, spawn);

    /// <summary>Клетка тела без скобок, с живым началом отсчёта.</summary>
    public static string SayStanding(double x, double y, double z) =>
        SayStanding(x, y, z, spawn);
