namespace VsBotKit;

/// <summary>
/// НАЧАЛО ОТСЧЁТА МИРА — одно на весь запуск, и единственное правило перевода
/// «мировые ↔ игровые».
///
/// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЭТО ЕСТЬ (журнал заказчика 19.08, соседние
/// строки одного и того же места):
///     18:33:54  дом: (61, 112, 257)
///     18:33:54  [укрытие] иду домой ((512061, 112, 512257))
/// Одно место, два адреса. Первый человек находит у себя на экране, второго —
/// нет нигде: 512061 не показывает ни одно окно игры. Слова заказчика:
/// «везде в веб форме нужно указывать координаты как я их вижу».
///
/// ОТКУДА ИГРА БЕРЁТ СВОЁ НАЧАЛО ОТСЧЁТА — сверено по сборкам игры 1.22.7,
/// а не угадано:
///   • <c>Vintagestory.Client.NoObf.HudElementCoordinates.Every250ms</c>
///     (VintagestoryLib.dll) берёт КЛЕТКУ игрока и вычитает из неё КЛЕТКУ
///     спавна: <c>asBlockPos.Sub(capi.World.DefaultSpawnPosition.AsBlockPos)</c>;
///   • ВЫСОТУ он запоминает ДО вычитания (<c>int y = asBlockPos.Y</c>) и
///     показывает как есть — Y не сдвигается НИКОГДА;
///   • <c>ClientMain.DefaultSpawnPosition</c> — это поле <c>SpawnPosition</c>
///     (<c>public EntityPos DefaultSpawnPosition => SpawnPosition;</c>), а
///     выставляет его ровно один обработчик:
///     <c>GeneralPacketHandler.HandleSpawnPosition</c> по пакету сервера 51
///     (<c>Packet_ServerIdEnum.SpawnPosition = 51</c>), разбирая его тем же
///     <c>ClientSystemEntities.entityPosFromPacket</c>, что и мы, —
///     <c>CollectibleNet.DeserializeDoublePrecise</c> по X, Y и Z;
///   • <c>EntityPos.AsBlockPos</c> (VintagestoryAPI.dll) — это
///     <c>new BlockPos((int)x, (int)y, (int)z, Dimension)</c>, то есть
///     отсечение дроби ПРИВЕДЕНИЕМ, а не округлением вниз.
/// Личная точка возрождения игрока (<c>ClientPlayer.SpawnPosition</c>, кровать)
/// — ДРУГОЕ поле и к началу отсчёта отношения не имеет: окно координат её не
/// спрашивает. Перепутать их значило бы двигать все адреса в журнале всякий
/// раз, когда бот поспал.
///
/// ЧТО ИМЕННО СЕРВЕР КЛАДЁТ В ЭТОТ ПАКЕТ — сверено там же:
///   • <c>ServerMain.DefaultSpawnPosition</c> — это
///     <c>EntityPosFromSpawnPos(SaveGameData.DefaultSpawn ?? mapMiddleSpawnPos)</c>,
///     то есть СПАВН ЭТОГО МИРА из его сохранения; нет заданного — берётся
///     середина карты (<c>ServerSystemSupplyChunks</c> кладёт в
///     <c>mapMiddleSpawnPos</c> клетку у <c>ChunkMapSizeX/2</c>,
///     <c>ChunkMapSizeZ/2</c>);
///   • <c>EntityPosFromSpawnPos</c> отдаёт
///     <c>new FuzzyEntityPos(x + 0.5, y, z + 0.5)</c> — вот откуда те самые
///     полблока, которые здесь отсекаются.
/// Значит, число 512000 нигде в игре не зашито и константой быть не может:
/// это лишь середина карты шириной 1024000 у мира с обычными размерами. У
/// мира с другим размером карты или с передвинутым спавном оно ДРУГОЕ.
/// Спрашивать надо мир, а не константу — поэтому здесь и лежит то, что
/// прислал сервер.
///
/// ПОЧЕМУ ОДНО МЕСТО НА ВЕСЬ ЗАПУСК. Клетку спавна печатает КАЖДАЯ строка
/// журнала, где есть <see cref="BlockPos"/>, — а их в библиотеке сотни, и
/// подать туда сдвиг аргументом нельзя ни в одну. Начало отсчёта принадлежит
/// МИРУ, а не боту: один запуск — один мир, и так оно и живёт здесь.
/// ЧЕСТНО О ПРЕДЕЛЕ: два бота в одном процессе на РАЗНЫХ серверах разъедутся —
/// второй перепишет начало отсчёта первому. Так бот сейчас не запускают
/// (Program.cs создаёт ровно одного), а спрятать это молча нельзя.
/// СТЕНД — ЕДИНСТВЕННЫЙ, КТО ЖИВЁТ ИНАЧЕ, и дверь у него своя и названная:
/// <see cref="StartTask"/>. Там ботов в процессе не два, а четыре тысячи, и
/// разъезжались они по-настоящему — разбор у самого метода.
///
/// ПОСЛЕ ОБРЫВА СВЯЗИ НАЧАЛО ОТСЧЁТА НЕ ЗАБЫВАЕТСЯ. Оно нужно, чтобы понять
/// клетку, которую человек ВВЁЛ в окне управления, пока бот не в мире: забудь
/// мы его — задача, поставленная на «61 112 257», ушла бы за полмиллиона
/// блоков от дома. Новый мир перепишет начало своим пакетом 51.
/// </summary>
public static class WorldOrigin
{
    /// <summary>Клетка спавна мира. Отдельный тип — чтобы читать её одним словом.</summary>
    public sealed record Spawn(int X, int Z);

    // Ссылка, а не пара полей: присваивание ссылки атомарно, и читающий поток
    // никогда не увидит X от одного мира вместе с Z от другого
    private static volatile Spawn? общее;

    /// <summary>
    /// ЯЩИК С НАЧАЛОМ ОТСЧЁТА, ОБЩИЙ НА ОДНУ ЗАДАЧУ И ВСЕХ ЕЁ ДЕТЕЙ.
    ///
    /// Почему ящик, а не просто значение в <see cref="AsyncLocal{T}"/>: значение
    /// у AsyncLocal пишется В СВОЮ КОПИЮ обстановки, и написанное потоком-читателем
    /// сети наружу не выходит. Ровно на этом опыт сборщика и споткнулся: пакет 51
    /// приходит в задаче приёмника, <see cref="Learn"/> клал начало отсчёта туда, а
    /// тест читал своё — пустое. Два стенда и покраснели, оба про начало отсчёта
    /// (<c>WorldOriginTests.ШОВ_пакет_спавна_доезжает_до_начала_отсчёта…</c> и
    /// <c>PanelHomeOnMapTests.ГЛАВНОЕ_точка_с_карты_ложится_в_дом…</c>). Ссылку же
    /// на ящик дети наследуют, и пишут все в ОДИН ящик — свой на каждый тест.
    /// </summary>
    private sealed class Ящик { public volatile Spawn? Значение; }

    private static readonly AsyncLocal<Ящик?> задача = new();

    /// <summary>
    /// ЗАВЕСТИ ЭТОЙ ЗАДАЧЕ СВОЁ НАЧАЛО ОТСЧЁТА. Живой бот этого не зовёт НИКОГДА
    /// и о ящике не знает: у него начало отсчёта одно на процесс, как и было.
    ///
    /// ЗАЧЕМ ЭТО ЕСТЬ. Начало отсчёта — единственное, что мешало стенду идти
    /// вразнобой: оно одно на процесс, его печатает КАЖДАЯ строка с
    /// <see cref="BlockPos"/>, и восемь классов стенда «входят в мир» пакетом 51,
    /// переписывая его всем соседям разом. Стенд от этого краснел двадцатью тремя
    /// тестами, каждый прогон разными, — и его пришлось выстроить в одну нитку
    /// (VsBotKit.Tests/СтендОдинПоток.cs). Ценою вышло восемь минут на прогон
    /// вместо полутора: набор, который столько идёт, перестают гонять, а тогда он
    /// не нужен вовсе.
    ///
    /// Приём в проекте не новый: так же стенду отданы <c>Pickup.Now</c> и
    /// <c>Pickup.Wait</c> (свой отсчёт вместо секундомера машины) и сроки ответа
    /// сервера <c>Container.OpenWaitMs</c>, <c>Butchering.DecayWaitMs</c>. Живой
    /// бот про них тоже ничего не знает.
    /// </summary>
    public static void StartTask() => задача.Value = new Ящик();

    /// <summary>
    /// ЕСТЬ ЛИ У ЭТОЙ ЗАДАЧИ СВОЙ ЯЩИК. У живого бота — всегда false.
    ///
    /// Нужно СТОРОЖУ, и не для красоты: убери <see cref="StartTask"/> из
    /// <c>ЗабытьМирAttribute.Before</c> — и весь стенд снова сядет на общее поле,
    /// а видно это станет не сразу, а редким красным вразнобой. Спросить «а свой
    /// ли у меня ящик» иначе нечем: само начало отсчёта в обоих случаях
    /// читается одинаково.
    /// </summary>
    public static bool TaskHasOwn => задача.Value is not null;

    // ОДНА ДВЕРЬ К НАЧАЛУ ОТСЧЁТА НА ЧТЕНИЕ И НА ЗАПИСЬ. Ящика нет (живой бот) —
    // живём общим полем, как и раньше; ящик есть (стенд) — только им, иначе
    // тесты снова писали бы соседям
    private static Spawn? spawn
    {
        get => задача.Value is { } я ? я.Значение : общее;
        set
        {
            if (задача.Value is { } я)
                я.Значение = value;
            else
                общее = value;
        }
    }

    /// <summary>
    /// Начало отсчёта, если сервер его уже прислал. null — ещё не прислал, и
    /// тогда переводить НЕЧЕМ: числа остаются мировыми, а строка о них честно
    /// об этом говорит (см. <see cref="Say(int,int,int)"/>).
    /// </summary>
    public static Spawn? Known => spawn;

    /// <summary>
    /// Сдвиг «игровые = мировые − сдвиг» по X и Z. Пока спавн не пришёл — (0, 0),
    /// то есть перевода нет. Ровно это и проверяет <c>GameCoords.CoordsKnown</c>:
    /// настоящий спавн стоит около середины карты и нулём не бывает.
    /// </summary>
    public static (int X, int Z) Offset => OffsetOf(spawn);

    /// <summary>
    /// Слово сервера о спавне (пакет 51). Дробь отсекается ровно так же, как в
    /// <c>EntityPos.AsBlockPos</c>: сервер шлёт спавн серединой блока
    /// (…512000,5), и без отсечения адрес уезжал бы на полблока.
    ///
    /// ВОЗВРАЩАЕТ НОВОСТЬ, А НЕ ЗОВЁТ СОБЫТИЕ, и это починка. Раньше здесь
    /// висело статическое <c>OnLearned</c>, и о начале отсчёта говорил КАЖДЫЙ
    /// живой бот процесса — даже тот, который в этот мир не входил. У живого
    /// бота процесс один, и беды не видно; на стенде, где рядом идут десятки
    /// ботов, она вылезла редким красным: <c>PanelLogRingTests.Закладка_не_
    /// откатывается_и_строки_не_повторяются</c> получал строку «[координаты]
    /// начало отсчёта мира» ДВАЖДЫ — оба раза из чужих тестов, вошедших в свои
    /// миры, — и честно жаловался «окно отдало одну и ту же строку дважды».
    ///
    /// Ящик задачи (<see cref="StartTask"/>) разводил по тестам ЗНАЧЕНИЕ, а
    /// новость расходилась всем: половина шва. Теперь новость едет той же
    /// дорогой, что и пакет, — её отдаёт тот, кто её услышал
    /// (<c>BotClient.OnOriginLearned</c>), и слышит её только его бот.
    /// </summary>
    /// <returns>
    /// Новое начало отсчёта — если оно вправду новое. null — пришло то же
    /// самое (сервер шлёт пакет 51 при каждом входе), и говорить не о чем.
    /// </returns>
    public static Spawn? Learn(double spawnX, double spawnZ)
    {
        var (x, z) = Cell(spawnX, spawnZ);
        var было = spawn;
        if (было is { } b && b.X == x && b.Z == z)
            return null;                   // то же самое — и говорить не о чем
        var стало = new Spawn(x, z);
        spawn = стало;
        return стало;
    }

    /// <summary>
    /// Забыть начало отсчёта. Нужно СТЕНДУ: чистые правила проверяются с
    /// подставленным началом, а живое не должно течь из теста в тест.
    /// </summary>
    public static void Forget() => spawn = null;

    // --- чистые правила: ни мира, ни сети, поэтому они и закрыты тестами ---

    /// <summary>
    /// Клетка спавна из координат, что прислал сервер. Отдельно от
    /// <see cref="Learn"/>, чтобы «полблока» можно было проверить тестом.
    ///
    /// ДРОБЬ ОТСЕКАЕТСЯ ПРИВЕДЕНИЕМ, а не округлением вниз, — ровно как в
    /// <c>EntityPos.AsBlockPos</c>, откуда игра берёт клетку спавна для окна
    /// координат. Разница видна только при отрицательных числах, и мир их не
    /// даёт (карта идёт от нуля), но повторять игру наугад нельзя: если
    /// однажды даст, разъедемся с окном игры на один блок и искать это будет
    /// негде.
    /// </summary>
    public static (int X, int Z) Cell(double spawnX, double spawnZ) =>
        ((int)spawnX, (int)spawnZ);

    /// <summary>
    /// МИРОВАЯ КЛЕТКА → ИГРОВАЯ, СДВИГОМ. Единственное место во всей
    /// библиотеке, где из адреса вычитается начало отсчёта.
    ///
    /// Отдельная перегрузка «со сдвигом парой чисел» нужна не для красоты:
    /// сдвиг подают снаружи и карта транслокаторов, и окно управления, и
    /// хозяйство роли. Пока каждый вычитал сам, копий этих трёх строк было
    /// пять, и найти, какая из них забыла про высоту, было негде.
    ///
    /// Высота НЕ трогается — так делает и игра: <c>HudElementCoordinates</c>
    /// запоминает <c>int y = asBlockPos.Y</c> ДО вычитания.
    /// </summary>
    public static (int X, int Y, int Z) ToGame(int x, int y, int z, (int X, int Z) offset) =>
        (x - offset.X, y, z - offset.Z);

    /// <summary>Игровая клетка → мировая, сдвигом. Обратный ход к <see cref="ToGame(int,int,int,ValueTuple{int,int})"/>.</summary>
    public static (int X, int Y, int Z) ToWorld(int x, int y, int z, (int X, int Z) offset) =>
        (x + offset.X, y, z + offset.Z);

    /// <summary>
    /// ИГРОВАЯ ТОЧКА С ДРОБЬЮ → МИРОВАЯ. Для тех, кому нужна не клетка, а место
    /// внутри неё: «иди на 31,5 −12,5» — середина клетки, а не её угол.
    ///
    /// ПОЧЕМУ ЭТА ПЕРЕГРУЗКА ЗАВЕДЕНА, а дробь не приводят к клетке заранее.
    /// Пока её не было, каждый, кому нужны были дробные числа, складывал сам —
    /// и складывал НЕ С ТЕМ. Сервер шлёт спавн СЕРЕДИНОЙ БЛОКА (512000,5), и
    /// прибавлять надо КЛЕТКУ спавна (<see cref="Cell"/>), а не присланную
    /// дробь. Прибавляли дробь: разбор команд чата, набор действий нейросети и
    /// пять команд-щупов — семь рукописных копий одного сложения.
    ///
    /// ЧТО ИЗ ЭТОГО ВЫХОДИЛО ЖИВЬЁМ. «!заберись 31.9 108 29» превращалось в
    /// floor(31,9 + 512000,5) = 512032 вместо 512031 — целый блок мимо, молча,
    /// и только у чисел с дробью не меньше половины. А там, где мировые числа
    /// оставались дробными (ходьба по приказу нейросети), бот вставал на
    /// полблока в стороне от названного места — навсегда и без единой жалобы.
    ///
    /// ВЫСОТА НЕ ТРОГАЕТСЯ — как и у <see cref="ToWorld(int,int,int,ValueTuple{int,int})"/>.
    /// </summary>
    public static (double X, double Y, double Z) ToWorld(double x, double y, double z,
        (int X, int Z) offset) =>
        (x + offset.X, y, z + offset.Z);

    /// <summary>Сдвиг этого начала отсчёта; начала нет — сдвига нет.</summary>
    public static (int X, int Z) OffsetOf(Spawn? origin) =>
        origin is { } o ? (o.X, o.Z) : (0, 0);

    /// <summary>Мировая клетка → игровая. Высота не трогается: так делает и игра.</summary>
    public static (int X, int Y, int Z) ToGame(int x, int y, int z, Spawn? origin) =>
        ToGame(x, y, z, OffsetOf(origin));

    /// <summary>Игровая клетка → мировая. Обратный ход к <see cref="ToGame(int,int,int,Spawn)"/>.</summary>
    public static (int X, int Y, int Z) ToWorld(int x, int y, int z, Spawn? origin) =>
        ToWorld(x, y, z, OffsetOf(origin));

    /// <summary>
    /// ПОМЕТКА «ЭТО НЕ ТО, ЧТО У ВАС НА ЭКРАНЕ». Ставится, только когда начала
    /// отсчёта ещё нет: без неё «(512061, 112, 512257)» неотличимо от игрового
    /// адреса, и человек пошёл бы искать место, которого у него на экране нет.
    /// Молчать тут нельзя, а врать — тем более.
    /// </summary>
    public const string Unknown = " мировые";

    /// <summary>
    /// КЛЕТКА СЛОВАМИ ДЛЯ ЧЕЛОВЕКА: «(61, 112, 257)». Высота как есть — так
    /// её показывает и сама игра.
    /// </summary>
    public static string Say(int x, int y, int z, Spawn? origin) =>
        $"({SayBare(x, y, z, origin)})";

    /// <summary>Та же клетка, но БЕЗ скобок: их ставит вызывающий сам.</summary>
    public static string SayBare(int x, int y, int z, Spawn? origin)
    {
        if (origin is null)
            return $"{x}, {y}, {z}{Unknown}";
        // Вычитает ToGame, а не эта строка: своё вычитание здесь было бы шестой
        // копией одного и того же — той самой, что однажды забудет про высоту
        var (gx, gy, gz) = ToGame(x, y, z, origin);
        return $"{gx}, {gy}, {gz}";
    }

    /// <summary>
    /// ТОЧКА С ДРОБЬЮ СЛОВАМИ: «(61,5, 112, 257,3)». Дробь нужна там, где
    /// важно, где именно внутри клетки стоит тело («упёрся … стою (…)»), —
    /// поэтому она и не округляется до клетки.
    /// </summary>
    public static string Say(double x, double y, double z, Spawn? origin) =>
        $"({SayBare(x, y, z, origin)})";

    /// <summary>Та же точка с дробью, но без скобок.</summary>
    public static string SayBare(double x, double y, double z, Spawn? origin) =>
        origin is { } o
            ? $"{x - o.X:0.#}, {y:0.#}, {z - o.Z:0.#}"
            : $"{x:0.#}, {y:0.#}, {z:0.#}{Unknown}";

    /// <summary>
    /// ПАРА «X и Z» без высоты: «(61, 257)». Так говорят о цели по горизонтали
    /// («до (25, 254) не хватает высоты») — высоты у такой цели просто нет.
    /// </summary>
    public static string SayFlat(double x, double z, Spawn? origin) =>
        origin is { } o
            ? $"({x - o.X:0.#}, {z - o.Z:0.#})"
            : $"({x:0.#}, {z:0.#}{Unknown})";

    /// <summary>
    /// КЛЕТКА, В КОТОРОЙ СТОИТ ТЕЛО, без скобок: «61, 112,3, 257».
    ///
    /// Отдельная форма нужна из-за живой разницы: X и Z здесь — КЛЕТКА (дробь
    /// отбрасывается ПРИВЕДЕНИЕМ, ровно как в <c>EntityPos.AsBlockPos</c> у
    /// игры, — иначе адрес не совпадёт с окном координат), а высота остаётся с
    /// дробью: по ней видно, стоит тело на полу или на полублоке.
    ///
    /// Клетку считает <see cref="Cell"/> — та же, что разбирает и спавн: как
    /// ИГРА ОТСЕКАЕТ ДРОБЬ, показывая адрес в окне координат, проект решает
    /// один раз.
    ///
    /// ЧЕСТНО О ГРАНИЦЕ ЭТОГО ОБЕЩАНИЯ — она уже, чем звучала. Здесь стояло
    /// шире: «во что игра превращает дробную координату» решается в проекте
    /// один раз». Неправда: <see cref="Cell"/> отвечает только на вопрос ОКНА
    /// КООРДИНАТ (отсечение приведением, как <c>EntityPos.AsBlockPos</c>).
    /// Вопрос «какая клетка СОДЕРЖИТ точку» — ДРУГОЙ (там нужен floor, и он
    /// расходится с приведением на отрицательных), и на него в проекте
    /// отвечают порознь: правило <c>WorldModel.StandingCellAt</c> зовут
    /// восемнадцать раз, а голый <c>Math.Floor</c> стоит две сотни раз в
    /// полусотне файлов. Обещать за них за все эта подпись не может, и раз
    /// свести их одной правкой нельзя — пусть хотя бы не врёт.
    /// </summary>
    public static string SayStanding(double x, double y, double z, Spawn? origin)
    {
        var (кx, кz) = Cell(x, z);
        var (гx, _, гz) = ToGame(кx, 0, кz, origin);
        return origin is null
            ? $"{кx}, {y:0.#}, {кz}{Unknown}"
            : $"{гx}, {y:0.#}, {гz}";
    }

