namespace VsBotKit;

/// <summary>
/// ПАЛЕЦ НА КЛАВИШЕ ПРЫЖКА — один на всё тело.
///
/// ЖИВОЙ СЛУЧАЙ, словами заказчика: «при беге лишние прыжки и из-за этого может
/// упасть в пропасть и показалось как-будто у бота двойной прыжок».
///
/// ЧТО ГОВОРЯТ СБОРКИ ИГРЫ (PModuleOnGround из VintagestoryAPI.dll, разобран
/// ilspycmd, ничего не додумано):
///   • прыжок применяется, только пока модуль ПРИМЕНИМ, а применим он при
///     <c>entity.OnGround &amp;&amp; !entity.Swimming</c> либо ещё 0.15 с после схода
///     с земли (coyoteTimer — та самая поблажка, которой пользуется и живой
///     игрок, шагнув с кромки);
///   • между двумя прыжками обязаны пройти
///     <see cref="GameCooldownSeconds"/> (в игре это поле MinimumJumpInterval
///     = 500 мс);
///   • сам прыжок — это одна строка <c>pos.Motion.Y = BaseJumpForce / 60</c>,
///     и делается она КАЖДЫЙ ТИК, пока клавиша нажата и кулдаун истёк.
///
/// Отсюда сразу два вывода, и оба важные.
///
/// ПЕРВЫЙ: ПРЫЖКА В ВОЗДУХЕ В ИГРЕ НЕТ. Поблажка живёт 0.15 с, кулдаун — 0.5 с,
/// и они не пересекаются: к мигу, когда игра снова разрешила бы прыгнуть, тело
/// давно вне поблажки. Ни зажатой клавишей, ни двумя нажатиями подряд второго
/// прыжка в полёте не выжать. То есть «двойной прыжок» в воздухе боту недоступен
/// ровно так же, как и живому игроку.
///
/// ВТОРОЙ, И ЭТО НАША БЕДА: прыжок длится 0,683 с
/// (<see cref="JumpPhysics.AirTime"/> — ЗАМЕР на игровой физике; раньше тут
/// стояло списанное с бумаги 0,72), а кулдаун — 0.5 с. Разрыв меньше, чем
/// думали, но он есть, и вывод от этого не меняется: к посадке игра снова
/// готова прыгать, и если клавиша
/// в этот миг всё ещё зажата, тело подпрыгивает СРАЗУ, без всякой просьбы. Со
/// стороны два прыжка, разделённые одним касанием земли, и выглядят «двойным
/// прыжком» — а у самой кромки второй скачок уносит бота за край.
///
/// ПОЧЕМУ ЭТО НЕ ЛЕЧИЛОСЬ В ХОДЬБЕ. Движение заглядывает на тело раз в 50 мс,
/// а физика считает 60 раз в секунду: между «сел» и «отпустил» помещается до
/// трёх игровых тиков, и первого же хватает. Отпускать клавишу обязан тот, кто
/// тикает физику, — то есть <see cref="Body"/>, и правило поэтому живёт здесь
/// одно на всех: и на погоню, и на прыжок к точке маршрута, и на стройку лесов.
///
/// Своих чисел, кроме игрового кулдауна, тут нет: это чистые правила от «жму ли
/// я», «отрывался ли уже» и «стою ли на земле».
/// </summary>
public sealed class JumpKey
{
    /// <summary>
    /// Сколько игра выжидает между двумя прыжками, секунд. Замерено не нами:
    /// это константа MinimumJumpInterval = 500 мс в PModuleOnGround.
    /// </summary>
    public const double GameCooldownSeconds = 0.5;

    private bool airborne;

    /// <summary>Оторвались ли мы от земли с тех пор, как клавишу нажали.</summary>
    public bool Airborne => airborne;

    /// <summary>
    /// ТЕЛО СТОИТ НА ЗЕМЛЕ — то есть прыжок кончился.
    ///
    /// Лазание и плавание сюда не входят НАРОЧНО. На лестнице клавиша прыжка
    /// означает «лезь вверх» (в физике игры она задаёт вертикальную скорость на
    /// лестнице, а не толчок), в воде — «всплывай», и держат их там подолгу и
    /// по делу. Отпускай мы клавишу по одному лишь <c>OnGround</c>, бот замирал
    /// бы на середине лестницы всякий раз, когда игра на тик признаёт его
    /// стоящим (IsStepping такое даёт), — то есть починка одной беды завела бы
    /// другую.
    /// </summary>
    public static bool Landed(bool onGround, bool climbing, bool swimming) =>
        onGround && !climbing && !swimming;

    /// <summary>
    /// ОТПУСКАТЬ ЛИ КЛАВИШУ ПРЯМО СЕЙЧАС: прыжок мы просили, тело успело
    /// оторваться и уже снова на земле. Больше держать нечего — а держать
    /// значит попросить у игры второй прыжок.
    /// </summary>
    public static bool ReleaseNow(bool jumpHeld, bool wasAirborne, bool landed) =>
        jumpHeld && wasAirborne && landed;

    /// <summary>
    /// Оторвались ли мы от земли ПО ЭТОМУ нажатию. Признак живёт ровно столько,
    /// сколько нажата клавиша: отпустили — забыли, иначе следующий прыжок
    /// считался бы состоявшимся ещё до того, как случился.
    /// </summary>
    public static bool NowAirborne(bool wasAirborne, bool jumpHeld, bool landed) =>
        jumpHeld && (wasAirborne || !landed);

    /// <summary>
    /// ПОЧЕМУ ТЕЛО НЕ ПОДНИМАЕТСЯ НА КЛЕТКУ ВВЕРХ, ХОТЯ ТА ВСКРЫТА — чистое
    /// правило. Пустая строка значит «эта помеха ни при чём, ищи другую».
    ///
    /// ЖИВОЙ СЛУЧАЙ (журнал 16.08, 12:53–12:54, строка встречается двадцать
    /// четыре раза): «ступень в сторону (-1, 0) не вышла (клетка (512183, 106,
    /// 512278) вскрыта, а тело в неё не идёт)». Клетка и правда была пуста, и
    /// опора под ней стояла. Мешало другое: минутой раньше бот повесил себе
    /// перекладину лестницы В СОБСТВЕННУЮ КЛЕТКУ НОГ.
    ///
    /// ЧТО ГОВОРЯТ СБОРКИ ИГРЫ. Тело, касающееся лестницы, игра считает
    /// лазающим (DetectClimbing), а лазающему НЕ ДАЁТ ОПОРЫ — в конце того же
    /// такта стоит <c>OnGround = (CollidedVertically &amp;&amp; falling &amp;&amp;
    /// !IsClimbing) || IsStepping</c>. Прыжок же применим только «на земле»
    /// (PModuleOnGround.Applicable). Значит на лестнице прыжка нет вовсе — а
    /// шаг на клетку ВВЕРХ без прыжка не делается: игровая StepHeight равна
    /// 0.6 блока. Тело упирается в стену и стоит там до самого конца терпения.
    ///
    /// Из этого же следует, что вниз и вбок помеха не работает: там прыжок не
    /// нужен, и лестница под ногами шагу не мешает.
    /// </summary>
    /// <param name="stepUp">Шаг ведёт на клетку ВВЕРХ (иначе прыжок ни при чём).</param>
    /// <param name="climbing">Игра считает тело лазающим прямо сейчас.</param>
    public static string WhyNoStepUp(bool stepUp, bool climbing) =>
        stepUp && climbing
            ? "я вишу на лестнице, а лазающему игра не даёт опоры — без опоры " +
              "нет прыжка, а без прыжка не взойти на клетку выше"
            : "";

    /// <summary>
    /// Один такт пальца: сказать, держать ли клавишу дальше. Зовётся ровно там,
    /// где крутится физика, — иначе решение опаздывает на игровые тики, а игре
    /// хватает одного.
    /// </summary>
    /// <param name="jumpHeld">Клавиша нажата прямо сейчас (чьей бы волей).</param>
    /// <param name="onGround">Тело стоит на земле.</param>
    /// <param name="climbing">Тело висит на лестнице.</param>
    /// <param name="swimming">Тело плывёт.</param>
    public bool Hold(bool jumpHeld, bool onGround, bool climbing, bool swimming)
    {
        bool landed = Landed(onGround, climbing, swimming);
        if (ReleaseNow(jumpHeld, airborne, landed))
        {
            airborne = false;
            return false;
        }
        airborne = NowAirborne(airborne, jumpHeld, landed);
        return jumpHeld;
    }
}
