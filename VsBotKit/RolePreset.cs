using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Text.Unicode;

namespace VsBotKit;

/// <summary>
/// ПРЕСЕТ — готовый бот: «кем быть», а не «куда подключаться».
///
/// Разделение принципиальное. Пресетами удобно обмениваться: выложить,
/// переслать другу, положить в проект. А в настройках подключения лежат
/// адрес сервера, пароль сервера и токен — то, что пересылать нельзя. Поэтому
/// в пресете этих полей НЕТ ВОВСЕ: не «мы их не пишем», а «их некуда положить»
/// (см. <see cref="Forbidden"/> — при чтении чужого файла лишнее замечается
/// и о нём говорят вслух).
/// </summary>
public sealed class RolePreset
{
    /// <summary>Короткое имя пресета, оно же имя файла.</summary>
    public string Id { get; set; } = "";

    /// <summary>Как показывать человеку.</summary>
    public string Title { get; set; } = "";

    /// <summary>Одна-две фразы: чем этот бот занимается.</summary>
    public string About { get; set; } = "";

    /// <summary>Какую роль брать из каталога (<see cref="RoleCatalog"/>).</summary>
    public string Role { get; set; } = "";

    /// <summary>Что должно быть готово, чтобы бот заработал.</summary>
    public string[] Needs { get; set; } = [];

    /// <summary>Значения ручек роли: «СмелостьВПути», «Дом», «СобиратьЕду».</summary>
    public JsonElement? Settings { get; set; }

    /// <summary>Отладочные команды в чате.</summary>
    public bool Diag { get; set; }

    /// <summary>Ботом управляет нейросеть.</summary>
    public bool Ai { get; set; }

    /// <summary>Фразы в чат сразу после входа.</summary>
    public string[] Script { get; set; } = [];

    /// <summary>Откуда прочитан (пусто — создан в памяти).</summary>
    [JsonIgnore]
    public string? SourcePath { get; set; }

    /// <summary>
    /// Ключи, которых в пресете быть не должно. Если они попались в чужом
    /// файле — это не «лишние поля», а утечка: пресет с токеном аккаунта,
    /// пересланный другу, отдаёт ему доступ к игровому аккаунту.
    /// </summary>
    public static readonly string[] Forbidden =
        ["host", "port", "name", "uid", "mptoken", "serverpassword", "sessionkey",
         "password", "email", "account"];

    public override string ToString() =>
        $"{Id} — {(Title.Length > 0 ? Title : Role)}" +
        (About.Length > 0 ? $": {About}" : "");
}

/// <summary>
/// Библиотека пресетов: папка presets рядом с ботом.
///
/// Механизм чтения и записи; какие пресеты нужны и что в них положить, решает
/// приложение. Библиотека только следит, чтобы в пресет не попало секретное.
///
/// ПАПОК ДВЕ, И ЭТО НЕ УСЛОЖНЕНИЕ, А ПОЧИНКА. Готовые пресеты ЕДУТ С
/// ПРОГРАММОЙ: publish.sh кладёт папку presets рядом с ботом, и раздают именно
/// её. Свои пресеты бот ПИШЕТ В СОСТОЯНИЕ (<see cref="BotFolders.State"/>).
/// Пока состояние и было папкой рядом с ботом, эти два места совпадали и
/// разницы не было видно. Стоит им разойтись — бот в /opt (писать нельзя),
/// контейнер с состоянием на отдельном томе — и готовые боты ПРОПАДАЛИ из окна
/// управления: их искали там, куда их никто не клал.
///
/// Старшинство одно: своё перебивает приехавшее с программой. Иначе правка
/// готового пресета не имела бы силы, а это хуже, чем его отсутствие.
///
/// И СВОЯ ПАПКА НИКОГДА НЕ БЫВАЕТ ПРИЕХАВШЕЙ — см.
/// <see cref="Folders(string, string, string)"/>: там живой случай, ради
/// которого это правило появилось.
/// </summary>
public sealed class PresetLibrary
{
    private static readonly JsonSerializerOptions Json = new()
    {
        PropertyNameCaseInsensitive = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        ReadCommentHandling = JsonCommentHandling.Skip,
        AllowTrailingCommas = true,
        WriteIndented = true,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        Encoder = JavaScriptEncoder.Create(UnicodeRanges.All)
    };

    /// <summary>Где лежат СВОИ пресеты — сюда же и пишем.</summary>
    public string Directory { get; }

    /// <summary>
    /// Где лежат пресеты, ПРИЕХАВШИЕ С ПРОГРАММОЙ. Только чтение. Совпадает с
    /// <see cref="Directory"/> при обычной установке — тогда папка одна.
    /// </summary>
    public string ShippedDirectory { get; }

    /// <summary>
    /// ПОЧЕМУ СВОЯ ПАПКА НАЗЫВАЕТСЯ НЕ ТАК, КАК ПРИЕХАВШАЯ. Пусто — папки и так
    /// разные, объяснять нечего. Говорится ОДИН раз при запуске: человек будет
    /// искать свои настройки там, где привык, и молча увести их нельзя.
    /// </summary>
    public string? FoldersWhy { get; }

    /// <summary>
    /// Прибавка к имени своей папки, когда та совпала бы с приехавшей.
    /// «-мои» — тем же словом, каким это место называет человек.
    /// </summary>
    public const string OwnSuffix = "-мои";

    /// <summary>
    /// ГДЕ ДЕРЖАТЬ СВОИ ПРЕСЕТЫ, А ГДЕ ЛЕЖАТ ПРИЕХАВШИЕ С ПРОГРАММОЙ — чистое
    /// правило: ни файлов, ни бота, потому и проверяется стендом.
    ///
    /// ЖИВОЙ СЛУЧАЙ 15.08, РАДИ КОТОРОГО ОНО ПОЯВИЛОСЬ. Заказчик задал дом в
    /// окне управления — в журнале стоит
    ///     21:11:02 [панель] Дом = {"x":61,"y":112,"z":254}
    ///     21:11:02 [пресет] пресет «digger» сохранён:
    ///              …\TradeBot\bin\Debug\net10.0\presets\digger.json
    /// (путь в журнале приведён как есть: 17.08 приложение переименовано в
    /// VintageBotStory, и сегодня та же папка зовётся
    /// …\VintageBotStory\bin\Debug\net10.0\presets)
    /// и дом заработал: в 21:17 бот отметил им точку возрождения. А в 22:01, при
    /// следующем запуске, — «[дом] дом не задан — отмечать нечего», и «применено
    /// 72» вместо прежних 137. Между этими двумя строками была ПЕРЕСБОРКА: тот
    /// самый файл кладёт туда сборка (VintageBotStory.csproj: presets/*.json →
    /// CopyToOutputDirectory), а в исходном «Дом»: null. Панель писала в файл,
    /// который ей не принадлежит, и честно отвечала «сохранено» — а сохранённое
    /// молча откатывалось. У обычного хозяина бота то же самое делает не
    /// сборка, а распаковка новой версии поверх старой.
    ///
    /// Отсюда правило: в папку, которая ПРИЕЗЖАЕТ С ПРОГРАММОЙ, бот не пишет
    /// НИКОГДА. Совпали — своя получает своё имя, а приехавшая остаётся
    /// читаемой, и старшинство прежнее (своё перебивает приехавшее).
    /// </summary>
    /// <param name="state">Где бот держит своё хозяйство (<see cref="BotFolders.State"/>).</param>
    /// <param name="beside">Папка рядом с программой (<see cref="BotFolders.Beside"/>).</param>
    /// <param name="name">Имя папки пресетов («presets»).</param>
    public static (string Own, string Shipped, string? Why) Folders(
        string state, string beside, string name)
    {
        string shipped = Path.GetFullPath(Path.Combine(beside, name));
        string own = Path.GetFullPath(Path.Combine(state, name));
        if (!string.Equals(own, shipped, StringComparison.OrdinalIgnoreCase))
            return (own, shipped, null);

        own = Path.GetFullPath(Path.Combine(state, name + OwnSuffix));
        return (own, shipped,
            $"свои пресеты держу в «{own}», а не в «{shipped}»: вторая папка приезжает " +
            "с программой, и обновление (у разработчика — пересборка) молча кладёт туда " +
            "исходный файл поверх накрученного в окне управления. Готовые пресеты оттуда " +
            "по-прежнему читаются, свой одноимённый их перебивает");
    }

    public PresetLibrary(string? directory = null)
    {
        string d = directory ?? "presets";
        if (Path.IsPathRooted(d))
        {
            // Сказали точную папку — значит она и есть единственная: подмешивать
            // к ней что-то ещё было бы враньём про то, откуда взялся пресет
            Directory = ShippedDirectory = Path.GetFullPath(d);
            return;
        }
        (Directory, ShippedDirectory, FoldersWhy) =
            Folders(BotFolders.State(), BotFolders.Beside, d);
    }

    /// <summary>
    /// Обе папки заданы точно: своя (в неё пишем) и приехавшая с программой
    /// (только читаем). Нужно стенду: настоящие пути берутся из
    /// <see cref="BotFolders"/>, а их на стенде не подменишь — значит проверить
    /// разошедшиеся папки иначе нечем.
    /// </summary>
    public PresetLibrary(string ownDirectory, string shippedDirectory)
    {
        Directory = Path.GetFullPath(ownDirectory);
        ShippedDirectory = Path.GetFullPath(shippedDirectory);
    }

    public event Action<string>? OnLog;

    /// <summary>
    /// ПАМЯТЬ МЕСТ, НАЗВАННЫХ ЧЕЛОВЕКОМ (дом, склад, пост). Ставится снаружи
    /// тем, кто знает сервер (<see cref="ПамятьМест.Сервер"/>): три числа на
    /// другом сервере означают другое место. Пусто — память не подключена, и
    /// всё работает как прежде: места живут только в готовом боте.
    ///
    /// ПОЧЕМУ ОНА ВИСИТ ИМЕННО ЗДЕСЬ. Записывающий ручки в этом проекте ОДИН
    /// (<see cref="ЗапомнитьРучки"/>) и собирающий роль тоже один
    /// (<see cref="Build"/>) — обе двери в этом же классе. Заведи память
    /// отдельно от них, и она разошлась бы с ручками в первый же вечер:
    /// человек крутит дом словом в чате, а память об этом не узнаёт.
    /// </summary>
    public ПамятьМест? Места { get; set; }

    /// <summary>
    /// ЧТО ПРО СВОИ ДОГАДКИ УЖЕ СКАЗАНО — И КОМУ ИМЕННО. Ключ — тот, кому ушёл
    /// голос; пусто для этого получателя — не говорили ничего (или гадать
    /// перестали).
    ///
    /// ЗАЧЕМ ПАМЯТЬ, А НЕ ПРОСТО ПРИПИСКА (находка приёмки 31.08). Записывающий
    /// зовётся на КАЖДЫЙ поворот ЛЮБОЙ ручки (<c>ControlPanel.SetKnob</c> →
    /// <see cref="ЗапомнитьРучки"/>), а догадка живёт весь заход. Значит
    /// приписка «Своё же догадкой не пишу: „Склад“…» повторялась в ответе окна
    /// на громкость чата, на высоту штольни, на что угодно — и не как новость,
    /// а как шум. Образец стоит рядом и уже назван годным: так же помнит свой
    /// голос штольня (<c>Tunnel.сказаноПроНизкуюРучку</c>).
    ///
    /// ПОЧЕМУ ПО ПОЛУЧАТЕЛЮ, А НЕ ОДНА НА ПРОЦЕСС, — ВТОРАЯ НАХОДКА ТОЙ ЖЕ
    /// ПРИЁМКИ, И ОНА ВЕРНУЛА В ЧАТ РОВНО ТО МОЛЧАНИЕ, ОТ КОТОРОГО ЛЕЧИЛИ.
    /// Библиотека пресетов ОДНА НА БОТА, а дверей к записывающему ТРИ: окно
    /// (<c>ControlPanel.SetKnob</c>), «!дом тут» и «!склад тут». Живьём: человек
    /// крутит в окне любую ручку — новость про незаписанную догадку мелькает
    /// секунду в углу браузера; потом говорит в чат «!дом тут» — и получает
    /// «настройки записаны…» и НИ СЛОВА про склад, который в файл не поехал.
    /// Сказанное в окне не считается сказанным в чат.
    ///
    /// КЛЮЧ — ЖУРНАЛ ЗВАВШЕГО (<c>вЖурнал</c>), потому что это и есть «кому
    /// говорим»: окно передаёт свой (человек читает его в браузере), а чат и
    /// запуск не передают ничего и слушают общий <see cref="OnLog"/>. Своего
    /// понятия «канал» тут не заводится: второе такое понятие разъехалось бы с
    /// тем, куда голос уходит на самом деле.
    ///
    /// ПОМНИМ СКАЗАННОЕ, А НЕ «ГОВОРИЛ ЛИ»: догадок может стать больше или
    /// меньше — про новый их список человек услышит снова. Перестал бот гадать
    /// — память по этому получателю чистая, и следующая догадка снова прозвучит.
    /// </summary>
    private readonly Dictionary<object, string> сказаноПроДогадки = [];

    /// <summary>
    /// «Получатель — общий журнал бота»: так зовут записывающего чат («!дом
    /// тут») и запуск. Отдельная метка нужна потому, что ключом словаря null
    /// быть не может, а «журнала не передали» — это законный и самый частый
    /// случай, а не отсутствие получателя.
    /// </summary>
    private static readonly object ОбщийЖурнал = new();

    private string FileOf(string id) =>
        Path.Combine(Directory, BotFolders.SafeName(id) + ".json");

    /// <summary>Папки по старшинству: своё перебивает приехавшее с программой.</summary>
    private IEnumerable<string> Folders()
    {
        yield return Directory;
        if (!string.Equals(ShippedDirectory, Directory, StringComparison.OrdinalIgnoreCase))
            yield return ShippedDirectory;
    }

    /// <summary>
    /// Все пресеты: свои и приехавшие с программой. Одноимённый свой перебивает
    /// готовый. Битые пропускаются с жалобой в журнал.
    /// </summary>
    public IReadOnlyList<RolePreset> All()
    {
        var found = new List<RolePreset>();
        var взято = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (string dir in Folders())
        {
            if (!System.IO.Directory.Exists(dir))
                continue;
            foreach (string file in System.IO.Directory.GetFiles(dir, "*.json").Order())
                if (Read(file) is { } preset && взято.Add(preset.Id))
                    found.Add(preset);
        }
        // Порядок в окне не должен зависеть от того, в какой папке пресет лежит
        found.Sort((a, b) => string.Compare(a.Id, b.Id, StringComparison.OrdinalIgnoreCase));
        return found;
    }

    /// <summary>Прочитать пресет по имени (без учёта регистра). null — такого нет.</summary>
    public RolePreset? Find(string id)
    {
        foreach (string dir in Folders())
        {
            string file = Path.Combine(dir, BotFolders.SafeName(id) + ".json");
            if (File.Exists(file))
                return Read(file);
        }

        // Регистр: на Linux «Копатель» и «копатель» — разные файлы, и пресет
        // «пропадал» от одной заглавной буквы
        return All().FirstOrDefault(
            p => string.Equals(p.Id, id, StringComparison.OrdinalIgnoreCase));
    }

    private RolePreset? Read(string file)
    {
        try
        {
            string text = File.ReadAllText(file, Encoding.UTF8);
            var preset = JsonSerializer.Deserialize<RolePreset>(text, Json);
            if (preset == null)
                return null;
            preset.SourcePath = file;
            if (preset.Id.Length == 0)
                preset.Id = Path.GetFileNameWithoutExtension(file);

            WarnAboutSecrets(file, text);
            return preset;
        }
        catch (Exception e)
        {
            OnLog?.Invoke($"пресет «{Path.GetFileName(file)}» не прочитался: {e.Message}");
            return null;
        }
    }

    /// <summary>
    /// Сказать вслух, если в чужом пресете лежит то, чего там быть не должно.
    /// Мы это НЕ применяем — но человек должен знать, что файл, который он
    /// собрался переслать, несёт в себе доступ к его серверу или аккаунту.
    /// </summary>
    private void WarnAboutSecrets(string file, string text)
    {
        try
        {
            using var doc = JsonDocument.Parse(text);
            if (doc.RootElement.ValueKind != JsonValueKind.Object)
                return;
            var bad = doc.RootElement.EnumerateObject()
                .Select(p => p.Name)
                .Where(n => RolePreset.Forbidden.Contains(n, StringComparer.OrdinalIgnoreCase))
                .ToList();
            if (bad.Count > 0)
                OnLog?.Invoke($"в пресете «{Path.GetFileName(file)}» лежит лишнее: " +
                              $"{string.Join(", ", bad)}. Пресет — это «кем быть», а не «куда " +
                              "подключаться»; такие поля бот не применяет, но переслать этот " +
                              "файл кому-то нельзя");
        }
        catch
        {
            // Файл уже прочитался выше — сюда попадаем разве что на гонке
        }
    }

    /// <summary>Сохранить пресет (перезаписывает одноимённый).</summary>
    public void Save(RolePreset preset)
    {
        if (preset.Id.Length == 0)
            throw new BotConfigException("у пресета нет имени");
        System.IO.Directory.CreateDirectory(Directory);
        string file = FileOf(preset.Id);
        File.WriteAllText(file, JsonSerializer.Serialize(preset, Json), new UTF8Encoding(false));
        preset.SourcePath = file;
        OnLog?.Invoke($"пресет «{preset.Id}» сохранён: {file}");
    }

    /// <summary>
    /// Удалить свой пресет. false — удалять нечего ИЛИ пресет приехал с
    /// программой; почему именно — уходит в журнал, молча false не бывает.
    /// </summary>
    public bool Delete(string id)
    {
        var preset = Find(id);
        if (preset?.SourcePath is not { } file || !File.Exists(file))
        {
            OnLog?.Invoke($"пресета «{id}» нет — удалять нечего");
            return false;
        }
        // ПРИЕХАВШЕЕ С ПРОГРАММОЙ НЕ ТРОГАЕМ. Это часть поставки: следующее
        // обновление положит его обратно, а на отгруженной папке «только для
        // чтения» удаление ещё и упадёт. Честный отказ лучше пропажи, которая
        // сама отменяется
        if (!string.Equals(Path.GetDirectoryName(file), Directory,
                StringComparison.OrdinalIgnoreCase))
        {
            OnLog?.Invoke($"пресет «{id}» приехал с программой ({file}) и не удаляется: " +
                          "это часть поставки. Свой пресет с тем же именем перебьёт его");
            return false;
        }
        File.Delete(file);
        OnLog?.Invoke($"пресет «{id}» удалён");
        return true;
    }

    /// <summary>
    /// Собрать роль по пресету: взять её из каталога и повернуть ручки.
    ///
    /// Возвращает роль и список жалоб. Жалобы НЕ отменяют роль: из-за опечатки
    /// в одной настройке терять остальные девять глупо. Но и молчать нельзя —
    /// иначе бот всю ночь работает не так, как написано в файле.
    /// </summary>
    public (BotRole? Role, List<string> Problems) Build(RolePreset preset, RoleCatalog catalog)
    {
        var problems = new List<string>();
        var entry = catalog.Find(preset.Role);
        if (entry == null)
        {
            problems.Add($"пресет «{preset.Id}» просит роль «{preset.Role}», а такой нет. " +
                         $"Есть: {catalog.Names()}");
            return (null, problems);
        }

        var role = entry.Create();
        if (preset.Settings is { } settings)
        {
            int applied = RoleKnobs.ApplyAll(role, settings, out var complaints, out var старые);
            problems.AddRange(complaints);
            OnLog?.Invoke($"пресет «{preset.Id}»: настроек применено {applied}" +
                          (complaints.Count > 0 ? $", отвергнуто {complaints.Count}" : ""));

            // СТАРЫЕ ИМЕНА — В ЖУРНАЛ, А НЕ В ЖАЛОБЫ. Такая настройка
            // ПОДЕЙСТВОВАЛА, и попади она в problems — строкой выше стояло бы
            // «отвергнуто», то есть прямая неправда о работающей ручке. Но и
            // молчать нельзя: пока человек не поправит слово в своём файле, он
            // живёт на нашей доброй памяти, а она не вечна
            foreach (string строка in старые)
                OnLog?.Invoke($"пресет «{preset.Id}»: {строка}");
        }

        if (role != null)
            МестаНаРоль(role, preset.Id);

        return (role, problems);
    }

    /// <summary>
    /// МЕСТА, НАЗВАННЫЕ ЧЕЛОВЕКОМ, — НА ТОЛЬКО ЧТО РОЖДЁННУЮ РОЛЬ. Зовётся
    /// отовсюду, где роль рождается: сборка по готовому боту
    /// (<see cref="Build"/>), горячий накат в окне и ЗАПУСК БЕЗ ГОТОВОГО БОТА.
    ///
    /// ПОЧЕМУ ОТДЕЛЬНЫМ МЕТОДОМ, А НЕ СТРОКАМИ ВНУТРИ <see cref="Build"/>.
    /// Там было написано «здесь и только здесь: сборка роли — единственная
    /// дверь, через которую бот рождается» — и это было неправдой. Заводской
    /// пример bot.json ключа «preset» не несёт вовсе, и такой запуск идёт
    /// мимо: <c>каталог.Find(roleId)?.Create()</c>. То есть у самого частого
    /// запуска память мест не спрашивал никто, а единственный записывающий при
    /// этом исправно обходил его пустые ручки. Дом на этой дороге не
    /// возвращался — он на ней ТЕРЯЛСЯ.
    /// </summary>
    /// <param name="роль">роль, только что собранная</param>
    /// <param name="пресет">имя готового бота (или роли) — оно идёт в слова человеку</param>
    public IReadOnlyList<string> МестаНаРоль(BotRole роль, string пресет)
    {
        var сказать = new List<string>();
        if (Места is not { } память)
            return сказать;

        сказать.AddRange(память.Подсказать(роль, пресет));

        // …И ПОДОБРАТЬ ТО, ЧТО УЖЕ ЛЕЖИТ В САМОЙ РОЛИ. Без этой строки починка
        // начинала работать только со ВТОРОГО раза: у заказчика дом и склад уже
        // вписаны в «digger» и «resident», а памяти мест ещё нет — и первая же
        // смена готового бота унесла бы их в третий раз, ровно как 27.08
        сказать.AddRange(память.Подобрать(роль, пресет));

        // Без своей приписки: этот поток слов уже подписан тем, кто его
        // читает («[пресет] …»), и вторая метка дала бы «[пресет] [места]»
        foreach (string строка in сказать)
            OnLog?.Invoke(строка);
        return сказать;
    }

    /// <summary>
    /// ЗАПОМНИТЬ НАКРУЧЕННЫЕ РУЧКИ РОЛИ В ФАЙЛ — единственный записывающий на
    /// всех, кто эти ручки крутит. Возвращает ответ человеку словами; молчания
    /// тут не бывает ни при удаче, ни при беде.
    ///
    /// ПОЧЕМУ ОН ЖИВЁТ ЗДЕСЬ, А НЕ В ОКНЕ УПРАВЛЕНИЯ. Жалоба заказчика дословно:
    /// «запоминание не работает у дома и склада». Ручки крутят ТРЕМЯ дверями —
    /// окном управления, «!дом тут» и «!склад тут», — а записывать их умело
    /// одно место, и сидело оно ВНУТРИ окна (<c>ControlPanel.SaveKnobs</c>).
    /// Первую половину беды закрыли дверью <see cref="VsBot.ЗапомнитьРучкиРоли"/>,
    /// но вторая осталась: бот, поднятый без окна (обычный «start-bot», где
    /// «panel.use» выключено с завода), записать сказанное словом не мог ВООБЩЕ
    /// и честно отвечал «нет окна управления». Человеку от этой честности дом
    /// не возвращался.
    ///
    /// Библиотека пресетов есть у бота ВСЕГДА — её заводит запуск, а не окно.
    /// Поэтому записывающий переехал сюда целиком, а окно теперь зовёт его же:
    /// второй записи ручек в проекте нет, и разойтись двум ответам не на чем.
    /// </summary>
    /// <param name="роль">Живая роль — с неё и снимаются значения ручек.</param>
    /// <param name="настройки">
    /// Настройки запуска: из них берётся имя пресета, и в них же уезжает
    /// поправка, если пресет не был выбран вовсе. null — работаем в
    /// зарезервированный «последний» и файл запуска не трогаем.
    /// </param>
    /// <param name="каталог">
    /// Каталог ролей — чтобы записать, КЕМ поднимать бота в следующий раз.
    /// </param>
    /// <param name="вЖурнал">
    /// Куда эхом уходит беда. Пусто — в <see cref="OnLog"/> библиотеки. Окно
    /// управления передаёт СВОЙ журнал: у него он показывается человеку прямо
    /// в браузере, и увести оттуда «настройки НЕ записаны» значило бы вернуть
    /// молчание в то самое место, где на него и жаловались.
    /// </param>
    public string ЗапомнитьРучки(BotRole роль, BotConfig? настройки, RoleCatalog? каталог,
        Action<string>? вЖурнал = null)
    {
        try
        {
            // Имя пресета пусто — берём зарезервированное «последний», чтобы
            // накрученное не пропало и поднялось при следующем запуске
            string имя = Panel.PanelSettings.KnobPreset(настройки?.Preset);

            // Название и описание пресета придумал человек — автосохранение
            // ручек не имеет права их стирать
            var было = Find(имя);

            // ЧЬИ это настройки, надо знать точно. Записать «не знаю, пусть
            // будет обычный житель» значит подменить роль при следующем
            // запуске — молча и не там, где человек будет её искать
            string? свояId = каталог?.All.FirstOrDefault(e => e.Title == роль.Name)?.Id;

            // В ЧУЖОЙ ФАЙЛ НЕ ПИШЕМ — ЭТО БЫЛА ПОРЧА, И МОЛЧАЛИВАЯ. Имя файла
            // берётся из настроек запуска, а роль — из шапки САМОГО ФАЙЛА:
            // выбрал человек «trader», роль на ходу не сменилась (нет держателя
            // бота, сборка не удалась), повернул любую ручку — и trader.json
            // оказывался перезаписан ручками КОПАТЕЛЯ под шапкой "role":"trader".
            // Файл, которым он делится, после этого поднимает не того бота
            if (было?.Role is { Length: > 0 } чей && свояId is { Length: > 0 } моя
                && !string.Equals(чей.Trim(), моя.Trim(), StringComparison.OrdinalIgnoreCase))
                return $"в пресет НЕ записал: файл «{имя}» ({было.SourcePath}) собран для роли " +
                       $"«{чей}», а я сейчас «{моя}». Записать туда свои ручки значило бы " +
                       $"испортить чужого готового бота. Выберите готового бота роли «{моя}» " +
                       "или сохраните текущего под своим именем";

            string? рольId = было?.Role is { Length: > 0 } r ? r : свояId;
            if (рольId == null)
                return $"в пресет не записал: не знаю, какой ролью из каталога назвать " +
                       $"«{роль.Name}», а записать наугад значило бы поднять при следующем " +
                       "запуске другую роль. Сохраните бота вручную — там имя роли спрашивают";

            var пресет = Capture(имя, рольId, роль, было?.Title, было?.About);
            if (было != null)
            {
                пресет.Needs = было.Needs;
                пресет.Diag = было.Diag;
                пресет.Ai = было.Ai;
                пресет.Script = было.Script;
            }
            Save(пресет);

            // …И В ПАМЯТЬ МЕСТ — ТЕМ ЖЕ ДВИЖЕНИЕМ. Дом и склад человек задаёт
            // тремя дверями (окно, «!дом тут», «!склад тут»), и все три ведут
            // сюда. Второй записи мест в проекте нет и быть не должно: разойдись
            // они, и «!дом тут» переживал бы смену пресета, а окно — нет
            string местами = "";
            if (Места is { } память)
            {
                var сказано = память.Запомнить(роль, пресет.Id);
                foreach (string строка in сказано)
                    (вЖурнал ?? OnLog)?.Invoke($"[места] {строка}");
                // КОРОТКО НАРОЧНО: этот ответ уходит в чат, а там не больше
                // двух сотен букв (BotVoice.MaxChatLength), и обрезанный ответ
                // читается как поломка. Полный путь к файлу памяти бот
                // называет один раз при запуске — там место есть
                if (сказано.Count > 0)
                    местами = " И в память мест рядом с ботом — переживёт смену готового бота.";
            }

            // Пресет был не выбран — значит, следующий запуск про «последний»
            // не узнает, и записанное только что не поднимется. Поправку
            // говорим вслух: человек должен понимать, что правится и файл
            // запуска тоже
            string хвост = "";
            if (настройки is { } c &&
                !string.Equals(c.Preset, имя, StringComparison.OrdinalIgnoreCase))
            {
                c.Preset = имя;
                хвост = " " + ЗаписатьНастройкиЗапуска(c, вЖурнал);
            }
            // …А ЧЕГО В ФАЙЛ НЕ ПОЛОЖИЛИ — НАЗЫВАЕМ ЗДЕСЬ ЖЕ (закон 4).
            // Пропущенное молча неотличимо от записанного: человек читает
            // «настройки записаны», закрывает окно и назавтра ищет пропавший
            // склад. А назвать ручку — значит и подсказать, чем это чинится.
            //
            // И СКАЗАНО ЭТО ОДИН РАЗ КАЖДОМУ, А НЕ НА КАЖДЫЙ ПОВОРОТ ЛЮБОЙ
            // РУЧКИ И НЕ ОДИН РАЗ НА ВЕСЬ ПРОЦЕСС — разбор у самой памяти
            // (сказаноПроДогадки): окно и чат слышат порознь
            object кому = (object?)вЖурнал ?? ОбщийЖурнал;
            string догадками = "";
            if (роль.ДогадкиБота is { Count: > 0 } свои)
            {
                string голос =
                    $"Своё же догадкой не пишу: {string.Join(", ", свои.Select(и => $"«{и}»"))} " +
                    "— задайте это в окне или словом, и запомню надолго.";
                if (!сказаноПроДогадки.TryGetValue(кому, out string? былоСказано) ||
                    голос != былоСказано)
                {
                    сказаноПроДогадки[кому] = голос;
                    догадками = " " + голос;
                    // И В ЖУРНАЛ — ТЕМ ЖЕ ДВИЖЕНИЕМ, ЧТО У МЕСТ ВЫШЕ. Ответ
                    // окна человек видит секунду в углу браузера, ответ в чате
                    // уезжает вверх; сказанное один раз обязано где-то лежать,
                    // иначе «один раз» превращается в «мимо всех»
                    (вЖурнал ?? OnLog)?.Invoke(голос);
                }
            }
            else
                // ГАДАТЬ ПЕРЕСТАЛИ — ЧИСТИМ ПАМЯТЬ ЭТОГО ЖЕ ПОЛУЧАТЕЛЯ, а не
                // всю: чужая память о сказанном ему — не наша, и стирать её
                // значило бы повторить новость тому, кто её уже читал
                сказаноПроДогадки.Remove(кому);

            // Ответ обязан называть ФАЙЛ: человек должен понимать, что правит
            // общий файл, а не «настройку в окне».
            //
            // ПОРЯДОК ЗДЕСЬ — НЕ КРАСОТА, А ТО, ЧТО ЧЕЛОВЕК УСПЕЕТ ПРОЧЕСТЬ.
            // Ответ уходит и в чат, а там предел (ДлинаСтрокиВЧате, заводские
            // 220 букв), и режется он С ХВОСТА (BotVoice.Shorten). Замер
            // приёмки 31.08: «!дом тут» при живой догадке про склад давал 276
            // букв, приписка про догадку стояла последней — и отсекало ровно
            // её. Человек читал «настройки записаны» и не узнавал НИКОГДА, что
            // склад в файл не поехал. Поэтому первым идёт то, чего НЕ сделали
            // (закон 4), а уж потом ободрение про память мест: обрезанное
            // ободрение стоит дешевле обрезанного отказа, и в журнале оно
            // лежит целиком в любом случае
            return $"настройки записаны в пресет «{пресет.Id}»: {пресет.SourcePath}."
                   + догадками + местами + хвост;
        }
        catch (Exception e)
        {
            string беда = $"в пресет НЕ записал: {e.Message}";
            (вЖурнал ?? OnLog)?.Invoke(беда);
            return беда;
        }
    }

    /// <summary>
    /// ЗАПИСАТЬ НАСТРОЙКИ ЗАПУСКА — тоже один на всех и тоже вслух.
    ///
    /// Отказ здесь бывает законным (<see cref="Panel.PanelSettings.WhySkipSave"/>:
    /// токен или пароль пришли аргументом запуска, а файл пишется целиком —
    /// запись была бы утечкой), и он обязан дойти до человека словами. Молчаливое
    /// «не записалось» неотличимо от «записалось» до следующего запуска.
    /// </summary>
    public string ЗаписатьНастройкиЗапуска(BotConfig? настройки, Action<string>? вЖурнал = null)
    {
        if (Panel.PanelSettings.WhySkipSave(настройки) is { } почему)
        {
            (вЖурнал ?? OnLog)?.Invoke(почему);
            return почему;
        }
        try
        {
            // СБЕРЕЖЁННОЕ СПРАШИВАЕМ ДО ЗАПИСИ: после записи файл уже совпадает
            // с тем, что мы в него положили, и сказать было бы нечего
            string сбережено = настройки!.ЧтоСбереженоПриЗаписи();
            настройки.Save();
            if (сбережено.Length > 0)
                (вЖурнал ?? OnLog)?.Invoke(сбережено);
            return $"настройки записаны в {настройки.SourcePath}" +
                   (сбережено.Length > 0 ? $". {сбережено}" : "");
        }
        catch (Exception e)
        {
            string беда = $"настройки НЕ записаны ({e.Message})";
            (вЖурнал ?? OnLog)?.Invoke(беда);
            return беда;
        }
    }

    /// <summary>
    /// Снять пресет с ЖИВОЙ роли: что настроено сейчас, то и запишем.
    ///
    /// ПИШУТСЯ ТОЛЬКО ОТЛИЧИЯ ОТ ЗАВОДСКОГО, и это не косметика. Снимок брался
    /// со ВСЕХ ручек, а зовут его на КАЖДЫЙ поворот любой ручки
    /// (<c>ControlPanel.SetKnob</c> → <see cref="ЗапомнитьРучки"/>): человек
    /// накатывал «ночной» из одной строки, окно отвечало «перезапуск не нужен»,
    /// он крутил первую же ручку — и его <c>ночной.json</c> распухал на две
    /// сотни строк, которых он туда не писал. Рядом с этим в окне стояла
    /// приписка, обещавшая ровно ту защиту, которой не было.
    ///
    /// СМЫСЛ ФАЙЛА ОТ ЭТОГО НЕ МЕНЯЕТСЯ: и запуск (<see cref="PresetLibrary.Build"/>),
    /// и горячий накат (<c>ControlPanel.НакатитьПресетНаЖивого</c>) начинают с
    /// ЗАВОДСКОЙ роли и кладут поверх названное — значит «заводское + названные
    /// отличия» даёт того же бота, что и полный список.
    ///
    /// Заводских значений не знаем (у роли нет пустого конструктора) — пишем
    /// ВСЁ, как раньше: потерять настройку страшнее, чем распухнуть.
    /// </summary>
    public static RolePreset Capture(string id, string roleId, BotRole role,
        string? title = null, string? about = null)
    {
        var settings = new Dictionary<string, object?>();
        var заводские = Panel.RoleDefaults.Of(role.GetType());
        foreach (var knob in RoleKnobs.Of(role))
        {
            // ДОГАДКА БОТА В ФАЙЛ НЕ ИДЁТ. Снимок берётся с ЖИВОЙ роли, а в
            // живой роли лежит не только сказанное человеком: самопоиск склада
            // при входе в мир кладёт в ручку «Склад» ближний сундук и честно
            // говорит «в пресет не пишу». Сам он и не писал — писал ОТСЮДА
            // первый же поворот любой другой ручки, потому что снимается
            // роль целиком. Живьём это выглядело так: человек двинул
            // «ВысотаШтольни», и в файл заодно уехал «Дом», которого он не
            // задавал (разбор — BotRole.ПометитьДогадку)
            if (role.ЭтоДогадкаБота(knob.Name))
                continue;
            if (заводские == null
                || !заводские.TryGetValue(knob.Name, out object? было)
                || !Panel.RoleDefaults.Same(knob.Value, было))
                settings[knob.Name] = knob.Value;
        }

        return new RolePreset
        {
            Id = id,
            Title = title ?? role.Name,
            About = about ?? "",
            Role = roleId,
            Settings = JsonSerializer.SerializeToElement(settings, Json)
        };
    }
