namespace VsBotKit;

/// <summary>
/// ПОРОГ ВАЖНОСТИ: число из таблицы весов и что оно значит человеку.
///
/// Нужен окну и только окну: в списке способностей стоят голые числа, и без
/// подписи «75 — это неудобство» человек не знает, куда тянуть ползунок и по
/// какой границе отбирать. Числа при этом НЕ ПОВТОРЯЮТСЯ: они приходят из
/// констант <see cref="BehaviorWeights"/> (см. <see cref="BehaviorWeights.Marks"/>).
/// </summary>
/// <param name="Weight">Само число.</param>
/// <param name="Name">Как порог зовут человеку («пол жизненных»).</param>
/// <param name="About">Что стоит на этой высоте.</param>
public readonly record struct WeightMark(double Weight, string Name, string About);

/// <summary>
/// ВЕС ВАЖНОСТИ: НАСКОЛЬКО ВАЖНА СПОСОБНОСТЬ И ЧТО ЧЕМ ПЕРЕБИВАЕТСЯ.
///
/// Зачем понадобился. До этого порядок способностей задавался ПОРЯДКОМ их
/// подключения в <see cref="Presets.Survive"/> — то есть местом строки в чужом
/// файле. Человеку это не видно и не крутится: заказчик прямо просил «вес
/// важности, что над чем превалирует, так проще будет настроить бота». Теперь
/// у каждой способности есть ЧИСЛО: больше — важнее, и решает именно оно, а
/// место в списке остаётся лишь мерилом для равных.
///
/// ОПАСНЫЙ КРАЙ, о котором надо знать. Весом можно поставить «копать» выше
/// «спасаться», и бот честно послушается. Поэтому у трёх способностей есть
/// ПОЛ (<see cref="LifeFloor"/>) — предел, ниже которого их вес не опускается
/// ни настройкой, ни пресетом: возрождение, лечение и еда. Это прямое
/// требование по живому случаю: бот рыл карьер и потихоньку умирал с голоду,
/// имея хлеб в кармане. Смерть от голода при наличии еды недопустима НИ ПРИ
/// КАКОЙ настройке весов.
///
/// ОДНОГО ПОЛА НЕ ХВАТИЛО, И ЭТО СТОИТ НАЗВАТЬ. Пол запрещает ОПУСТИТЬ еду под
/// работу, но ничего не говорил про то, чтобы ПОДНЯТЬ работу над едой: строка
/// «без дела 99» молча принималась, безделье вставало выше еды (80), лечения
/// (85) и боя (90), уходило гулять на свои секунды и возвращало true — и еда
/// в этот тик не тикала вовсе. Поэтому у работы есть и ПОТОЛОК
/// (<see cref="CeilingOf(Type)"/>): способность, чьё дело по умолчанию стоит
/// НИЖЕ пола жизненных, выше этого пола и не поднимется, а неудобство (холод,
/// уход от нестабильности) — не выше самой еды. Правило само распространяется на
/// НОВЫЕ способности (незнакомая считается делом роли, то есть работой) — списка
/// имён, который однажды забудут пополнить, здесь нарочно нет.
///
/// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Спасение из воды и лавы весом не управляется
/// вовсе: всплытие на исходе воздуха живёт НИЖЕ способностей, прямо в теле и
/// в движении (<c>Body</c>, <c>Movement</c> — «воздух на исходе, всплываю, что
/// бы ни делал»). Способности, которую можно было бы обесценить весом, там
/// нет, и это лучшая из возможных защит — а не забывчивость.
///
/// Долгие дела (карьер, штольня, приказ из чата) в этот список не входят
/// вовсе: они спорят за ТЕЛО, а не за ход, и разбирает их
/// <see cref="BodyArbiter"/> своей важностью. Ручки для неё нарочно нет —
/// иначе «копать» можно было бы поставить выше «есть» с чёрного хода.
/// </summary>
public static class BehaviorWeights
{
    /// <summary>Мёртвому сервер отказывает во всём — возрождение впереди всего.</summary>
    public const double Dead = 100;

    /// <summary>Спасение из беды с телом: не висеть в воздухе, выбраться.</summary>
    public const double Rescue = 95;

    /// <summary>Опасность снаружи: буря, бой, ночь без крыши.</summary>
    public const double Danger = 90;

    /// <summary>Здоровье: лечение ран.</summary>
    public const double Health = 85;

    /// <summary>Голод: поесть.</summary>
    public const double Food = 80;

    /// <summary>Холод и прочее «неприятно, но не смертельно сейчас».</summary>
    public const double Comfort = 75;

    /// <summary>Дела роли: сходить за вещами, подобрать своё, набрать дикой еды.</summary>
    public const double Work = 50;
    /// <summary>Хозяйство: сменить сточенный инструмент, разложить снаряжение, факелы.</summary>
    public const double Upkeep = 40;

    /// <summary>Приличия и вид: поздороваться, взять фонарь, оглядеться.</summary>
    public const double Manners = 20;

    /// <summary>Совсем ничего не делаем (безделье — всегда последним).</summary>
    public const double Nothing = 0;

    /// <summary>
    /// ПОЛ ЖИЗНЕННЫХ РЕФЛЕКСОВ: ниже этого веса возрождение, лечение и еда не
    /// опускаются. Стоит ВЫШЕ любой работы (<see cref="Work"/>) и хозяйства,
    /// но НИЖЕ опасности: живой игрок посреди драки не садится обедать, а вот
    /// бросить кирку и пожевать — обязан.
    /// </summary>
    public const double LifeFloor = 60;

    /// <summary>
    /// Веса способностей по умолчанию. Числа подобраны так, чтобы порядок
    /// обхода СОВПАДАЛ с прежним порядком подключения в
    /// <see cref="Presets.Survive"/>: равный вес не переставляет способности
    /// местами (обход устойчив, см. <see cref="BehaviorRunner.Ordered"/>).
    ///
    /// Таблица одна на всех и лежит здесь, а не по одному числу в двадцати
    /// файлах: иначе «что над чем превалирует» пришлось бы собирать по всей
    /// библиотеке, а именно этого заказчик и просил не делать.
    /// </summary>
    private static readonly Dictionary<Type, double> Defaults = new()
    {
        [typeof(BehaviorRespawnWhenDead)] = Dead,
        [typeof(BehaviorStayGrounded)] = Rescue,
        // УЙТИ ИЗ ОГНЯ — ТА ЖЕ СТУПЕНЬ, ЧТО «НЕ ВИСЕТЬ В ВОЗДУХЕ», и это
        // разобранное число, а не вкус. Обе беды одного семейства: тело
        // оказалось там, где ему нельзя быть, и лечится это одним движением.
        // Разница в цене: вися в воздухе, бот просто не может ходить, а стоя в
        // костре — теряет по два здоровья в секунду (BEBehaviorBurning) и
        // умирает за десяток секунд. Живой случай: сгорел в СВОЁМ костре, куда
        // сам пришёл греться, и унёс с собой 48 стопок вещей.
        //
        // ПОЧЕМУ НЕ ВЫШЕ БОЯ ОТДЕЛЬНОЙ СТУПЕНЬЮ: Rescue (95) и так выше
        // Danger (90), то есть выше боя и бури. Равный вес не переставляет
        // способности местами, и в пресете уход из огня стоит сразу за
        // падением — сперва долететь до земли, потом сойти с горящей клетки
        [typeof(BehaviorLeaveHarm)] = Rescue,
        [typeof(BehaviorSleepAtNight)] = Danger,
        [typeof(BehaviorShelterFromStorm)] = Danger,
        [typeof(BehaviorAttackHostiles)] = Danger,
        [typeof(BehaviorHealWhenHurt)] = Health,
        [typeof(BehaviorEatWhenHungry)] = Food,
        [typeof(BehaviorKeepWarm)] = Comfort,
        // УХОД ОТ НЕСТАБИЛЬНОСТИ — рядом с холодом, и это разобранное число, а
        // не вкус: временной урон начинается ниже 0,13 стабильности и снимает
        // 0,15 − стабильность за четыре секунды (EntityBehaviorTemporal-
        // StabilityAffected.OnGameTick), то есть убивает медленнее голода и
        // куда медленнее дрифтера. Бросать ради него бой или обед незачем
        [typeof(BehaviorSeekStability)] = Comfort,
        [typeof(BehaviorRecoverLoot)] = Work,
        // ТОЧКА ВОЗРОЖДЕНИЯ ДОМА — ХОЗЯЙСТВО, А НЕ ДЕЛО РОЛИ, и это правка по
        // живому случаю 23.08, 10:55:35. Бот сказал «проголодался, а еды нет»
        // — и ушёл на склад за ВРЕМЕННОЙ ШЕСТЕРЁНКОЙ. Есть собрался через пять
        // минут, уже теряя здоровье от голода.
        //
        // Виноват был не порядок в очереди, а НИЧЬЯ в ней. Голод весит 80, но
        // когда еды нет, он выбывает: закрывать нужду нечем. Остаются его руки
        // — «пойти добыть еду» (Work), — и поход за шестерёнкой весил ровно
        // столько же. Обход останавливается на первом, кто взял ход, и
        // шестерёнка, начатая секундой раньше, держала тело всё это время.
        //
        // Хозяйство — её настоящее место. Шестерёнка не приносит ни блока и не
        // спасает ни одной жизни: она готовит УДОБСТВО ПОСЛЕ смерти, ровно как
        // запасной инструмент и факелы про запас. Ниже неё в этой же ступени
        // стоят замена сточенного и раскладка снаряжения, выше — сборы
        // (Upkeep + 1): за киркой идти нужнее, чем за шестерёнкой.
        //
        // ЧТО НЕ ТРОНУТО НАРОЧНО: подбор своей добычи остался делом роли и
        // по-прежнему идёт ПЕРЕД вылазкой за едой. Своё под ногами — это
        // секунды, а вылазка — минуты; стенд PickupTests сторожит этот порядок
        // и правильно возразил на попытку поднять вылазку выше
        [typeof(BehaviorKeepHomeSpawn)] = Upkeep,
        [typeof(BehaviorPickUpDrops)] = Work,
        // ДОБЫЧА С УБИТЫХ — РОВНО ТАКОЕ ЖЕ ДЕЛО РОЛИ, как и своя добыча после
        // кирки, и вес у неё тот же нарочно: шкура и шестерёнка не стоят ни
        // брошенного обеда, ни брошенного боя, но стоят того, чтобы забрать их
        // прежде, чем идти дальше. Равный вес не переставляет способности
        // местами — она встаёт сразу за подбором, как её и подключает пресет
        [typeof(BehaviorLootKills)] = Work,
        // РАЗГРУЗКА — ДЕЛО РОЛИ, А НЕ СПАСЕНИЕ. Полная сумка стоит потерянной
        // добычи, а не здоровья: рейс на склад обязан ждать своей очереди
        // после еды, лечения и боя. Потолок ей достаётся сам собой — всё, что
        // по умолчанию ниже LifeFloor, выше него и не поднимается
        [typeof(BehaviorHaulWhenFull)] = Work,
        [typeof(BehaviorForageWhenNoFood)] = Work,
        [typeof(BehaviorGatherWhenIdle)] = Work,
        // УДЕРЖАНИЕ ПОСТА — ДЕЛО РОЛИ, А НЕ СПАСЕНИЕ, и число здесь названо
        // прямо, хотя незнакомая способность и так получила бы Work. Молчание
        // тут стоило бы дорого: это ровно то место, где легче всего поставить
        // «стоять на посту» выше еды и получить стражника, умершего на посту с
        // хлебом в кармане. Ниже еды, лечения, боя и бури — уступает им всем,
        // а вернётся сам, потому что смотрит на расстояние, а не на часы
        [typeof(BehaviorHoldPost)] = Work,
        [typeof(BehaviorSwapWornTool)] = Upkeep,
        [typeof(BehaviorKeepGearReady)] = Upkeep,
        // ДОДЕЛАТЬ НАЧАТОЕ — ХОЗЯЙСТВО, А НЕ РАБОТА, и вес у неё тот же, что у
        // замены сточенного инструмента: собрать нож из уже вытесанного лезвия
        // не стоит ни брошенного обеда, ни брошенного боя, но стоит того, чтобы
        // сделать это прежде, чем встать без дела. Ходить она никуда не ходит
        // (Stock.CanFinishInPlace), потому и не мешает делам роли
        [typeof(BehaviorFinishStarted)] = Upkeep,
        // СНАРЯДИТЬСЯ — ТОЖЕ ХОЗЯЙСТВО, НО ОНО ХОДИТ, и потому стоит ВЫШЕ
        // доделки: сходить на склад за киркой стоит дороже, чем собрать нож
        // из готового лезвия, и делать это надо раньше. Выше работы её
        // ставить нельзя — тогда бот бросал бы наряд ради лишней лестницы, —
        // а ниже безделья бессмысленно: без кирки работы всё равно не будет.
        //
        // Живой случай 23.08: бот перечислил, что у него нет ни кирки, ни
        // ножа, ни лестниц, и стал ждать; за девять минут умер дважды
        [typeof(BehaviorEquipSelf)] = Upkeep + 1,
        [typeof(BehaviorWeaponAtNight)] = Upkeep,
        [typeof(BehaviorKeepLit)] = Upkeep,
        [typeof(BehaviorGreetPlayers)] = Manners,
        [typeof(BehaviorCarryLight)] = Manners,
        [typeof(BehaviorLookAlive)] = Manners,
        [typeof(BehaviorIdle)] = Nothing
    };

    /// <summary>
    /// У КОГО ЕСТЬ ПОЛ. Ровно три: встать после смерти, полечиться, поесть.
    /// Всё остальное роль вправе обесценить в ноль — эти три нет.
    /// </summary>
    private static readonly Dictionary<Type, double> Floors = new()
    {
        [typeof(BehaviorRespawnWhenDead)] = LifeFloor,
        [typeof(BehaviorHealWhenHurt)] = LifeFloor,
        [typeof(BehaviorEatWhenHungry)] = LifeFloor
    };

