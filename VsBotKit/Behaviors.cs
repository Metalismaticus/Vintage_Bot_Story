/// <summary>
/// СНИМОК СОСТОЯНИЯ, ПО КОТОРОМУ СЧИТАЮТСЯ КРИВЫЕ ПОТРЕБНОСТЕЙ.
///
/// Зачем он отдельным типом, а не «спросить у бота на месте». Кривая должна
/// уметь отвечать не только «как сейчас», но и «как будет через 90 секунд» —
/// иначе никакого планирования нет вовсе. Спросить у мира «а какая будет
/// сытость через полторы минуты» нельзя: у мира есть только «сейчас». Поэтому
/// состояние снимается один раз, а вперёд его двигает <see cref="After"/> — по
/// ИЗМЕРЕННЫМ скоростям, а не по выдуманным.
///
/// НИ ОДНОГО ВЫДУМАННОГО ЧИСЛА ЗДЕСЬ НЕТ. Сытость и её убыль, доля замерзания
/// и её рост, время до темноты — всё это либо приходит от сервера
/// (<c>SelfState</c>, <c>BodyHeat</c>, <c>GameClock</c>), либо ЗАМЕРЯЕТСЯ по
/// его же числам (<see cref="Drift"/>). Не намерили — поле остаётся null, и
/// кривая честно отвечает «созрело в полную силу», то есть ведёт себя ровно
/// как прежний постоянный вес. Догадка о скорости голода стоила бы бота,
/// вышедшего в дорогу с уверенностью «дотерплю».
/// </summary>
/// <param name="Fullness">Сытость долей от полной, 0..1. null — сервер не сказал.</param>
/// <param name="FullnessFallPerSecond">
/// ЗАМЕРЕННАЯ убыль сытости, долей в секунду. null — ещё не намерили или
/// сытость сейчас растёт (бот только что поел).
/// </param>
/// <param name="Health">Здоровье долей от полного, 0..1.</param>
/// <param name="Cold">Доля замерзания 0..1, как её считает игра (freezingEffectStrength).</param>
/// <param name="ColdRisePerSecond">ЗАМЕРЕННЫЙ рост замерзания, долей в секунду.</param>
/// <param name="SecondsToDusk">Сколько РЕАЛЬНЫХ секунд до темноты (0 — уже ночь).</param>
/// <param name="SecondsPerGameHour">
/// Сколько реальных секунд идёт игровой час. Нужен, чтобы «за час до темноты»
/// из настройки способности перевести в секунды планирования: на сервере с
/// ускоренным временем этот час — полминуты.
/// </param>
/// <param name="Stability">
/// Своя темпоральная стабильность 0..1 — то самое число, что сервер шлёт
/// клиенту атрибутом сущности. null — сервер его не шлёт (в этом мире
/// стабильности нет) или бот ещё не в мире.
/// </param>
/// <param name="StabilityFallPerSecond">
/// ЗАМЕРЕННОЕ падение стабильности, единиц в секунду. null — не намерили или
/// она сейчас растёт. Формулы у этого числа нет и быть не может: место считает
/// сервер по шуму от сида мира, а сида у клиента нет — только замер.
/// </param>
public readonly record struct NeedNow(
    double? Fullness = null,
    double? FullnessFallPerSecond = null,
    double? Health = null,
    double? Cold = null,
    double? ColdRisePerSecond = null,
    double? SecondsToDusk = null,
    double? SecondsPerGameHour = null,
    double? Stability = null,
    double? StabilityFallPerSecond = null)
{
    /// <summary>Ничего не известно: все кривые ответят «как раньше».</summary>
    public static readonly NeedNow Unknown = new();

    /// <summary>Известно ли хоть что-нибудь (иначе планировать нечем и не о чем).</summary>
    public bool Anything =>
        Fullness != null || Health != null || Cold != null || SecondsToDusk != null ||
        Stability != null;

    /// <summary>
    /// Тот же снимок, сдвинутый вперёд на столько-то секунд.
    ///
    /// ЧТО СДВИГАЕТСЯ, А ЧТО НЕТ, — и это не мелочь. Сытость убывает, холод
    /// копится, темнота приближается: у всех трёх есть измеренная или
    /// вычисленная скорость. У ЗДОРОВЬЯ скорости нет и быть не может: оно
    /// падает от удара и растёт от сытости, ровной скоростью тут не описать
    /// ничего. Поэтому здоровье вперёд НЕ двигается вовсе — лучше не знать,
    /// чем знать неправду.
    /// </summary>
    public NeedNow After(double seconds)
    {
        if (!(seconds > 0))
            return this;
        return this with
        {
            Fullness = Fullness is { } f && FullnessFallPerSecond is { } fall
                ? Math.Clamp(f - fall * seconds, 0, 1)
                : Fullness,
            Cold = Cold is { } c && ColdRisePerSecond is { } rise
                ? Math.Clamp(c + rise * seconds, 0, 1)
                : Cold,
            SecondsToDusk = SecondsToDusk is { } dusk ? Math.Max(0, dusk - seconds) : null,
            // Стабильность двигаем вперёд ТОЛЬКО замеренным падением: пока бот
            // стоит на месте, скорость честная, а угадывать её формулой нечем —
            // место считает сервер по сиду мира
            Stability = Stability is { } s && StabilityFallPerSecond is { } drain
                ? Math.Clamp(s - drain * seconds, 0, 1)
                : Stability
        };
    }

    public override string ToString()
    {
        var parts = new List<string>();
        if (Fullness is { } f)
            parts.Add($"сытость {f * 100:0}%" +
                      (FullnessFallPerSecond is { } d ? $" (убывает на {d * 100 * 60:0.#}% в минуту)" : ""));
        if (Health is { } h)
            parts.Add($"здоровье {h * 100:0}%");
        if (Cold is { } c)
            parts.Add($"замерзание {c * 100:0}%" +
                      (ColdRisePerSecond is { } r ? $" (растёт на {r * 100 * 60:0.#}% в минуту)" : ""));
        if (SecondsToDusk is { } t)
            parts.Add(t <= 0 ? "уже ночь" : $"до темноты {t:0} с");
        if (Stability is { } st)
            parts.Add($"стабильность {st:0.##}" +
                      (StabilityFallPerSecond is { } sd ? $" (падает на {sd * 60:0.###} в минуту)" : ""));
        return parts.Count > 0 ? string.Join(", ", parts) : "о состоянии ничего не известно";
    }
}

/// <summary>
/// ИЗМЕРИТЕЛЬ СКОРОСТИ: насколько быстро меняется число, которое присылает
/// сервер (сытость, доля замерзания).
///
/// Зачем он вообще. Заказчику обещано «потребность голода будет расти со
/// временем» — а насколько быстро, не знает никто: скорость голода в игре
/// зависит от того, что бот делает (бег, копка, сон), от настроек сервера и от
/// модов. Написать сюда число значило бы соврать на первом же чужом сервере.
/// Поэтому скорость ЗАМЕРЯЕТСЯ по тем же числам, что уже приходят боту.
///
/// Правило простое: держим точку отсчёта; когда от неё набралось либо заметное
/// изменение (<see cref="MinChange"/>) за приличный срок (<see cref="MinSeconds"/>),
/// либо просто много времени (<see cref="MaxSeconds"/>) — объявляем скорость и
/// катим точку отсчёта дальше. Пока не набралось — <see cref="PerSecond"/>
/// остаётся null, и это честное «не знаю», а не ноль. Ноль здесь означал бы
/// «никогда не проголодается» и был бы худшим из ответов.
/// </summary>
public sealed class Drift
{
    private double? anchor;
    private DateTime anchorAt;

    /// <summary>Меньше этого срока скорость не объявляем: шум сильнее сигнала.</summary>
    public double MinSeconds { get; set; } = 20;

    /// <summary>Заметное изменение величины — с него можно считать скорость.</summary>
    public double MinChange { get; set; } = 0.01;

    /// <summary>
    /// Через столько секунд отвечаем даже без заметного изменения: «почти не
    /// меняется» — тоже ответ, и его надо уметь дать, а не молчать вечно.
    /// </summary>
    public double MaxSeconds { get; set; } = 300;

    /// <summary>
    /// Изменение в секунду СО ЗНАКОМ: минус — величина убывает (сытость),
    /// плюс — растёт (замерзание). null — ещё не намерили.
    /// </summary>
    public double? PerSecond { get; private set; }

    /// <summary>Сколько секунд длилось окно последнего замера (0 — замеров не было).</summary>
    public double MeasuredOver { get; private set; }

    /// <summary>Новое показание. Время доводом, чтобы правило проверялось стендом.</summary>
    public void Add(double value, DateTime at)
    {
        if (anchor is not { } was)
        {
            anchor = value;
            anchorAt = at;
            return;
        }
        double seconds = (at - anchorAt).TotalSeconds;
        if (seconds <= 0)
            return;
        double change = value - was;
        bool enough = Math.Abs(change) >= MinChange && seconds >= MinSeconds;
        bool longEnough = seconds >= MaxSeconds;
        if (!enough && !longEnough)
            return;
        PerSecond = change / seconds;
        MeasuredOver = seconds;
        anchor = value;
        anchorAt = at;
    }

    /// <summary>Забыть намеренное (сменился бот, сменился мир).</summary>
    public void Forget()
    {
        anchor = null;
        PerSecond = null;
        MeasuredOver = 0;
    }
}

/// <summary>
/// КРИВЫЕ ПОТРЕБНОСТЕЙ: насколько потребность СОЗРЕЛА, от 0 до 1.
///
/// Заказ дословно (хозяин, переписка 10.08): «раз в X времени каждый раз
/// пересчитываем веса потребности», «потребность голода будет расти со
/// временем». То есть вес — не число, а кривая от состояния.
///
/// ПОЧЕМУ СОЗРЕЛОСТЬ, А НЕ СРАЗУ ВЕС. Веса уже есть, и у них есть пол и
/// потолок, стоившие заказчику бота, умершего от голода с хлебом в кармане
/// (<see cref="BehaviorWeights"/>). Считай кривая сразу вес — она обошла бы и
/// пол, и потолок с чёрного хода: «еда 12» из кривой выглядело бы как
/// настройка, которой никто не давал. Поэтому кривая отвечает ДОЛЕЙ, а вес
/// получается умножением: <c>вес × созрелость</c>. Пол и потолок остаются на
/// своём месте нетронутыми, а созрелость 1 означает РОВНО прежнее число.
///
/// ОТСЮДА ГЛАВНОЕ СВОЙСТВО БЕЗОПАСНОСТИ: когда потребность настоящая (голоден,
/// ранен, замерзает, стемнело), кривая отдаёт 1 — и бот ведёт себя в точности
/// как до всей этой переделки. Кривая умеет только ПРИГЛУШИТЬ вес того, чего
/// ещё нет, и никогда — усилить или ослабить то, что уже есть.
///
/// ПОРОГИ НЕ КОПИРУЮТСЯ. «Голоден» — это порог самой способности
/// (<c>BehaviorEatWhenHungry.HungerThreshold</c>), и кривая спрашивает его у
/// неё. Второе такое число здесь разошлось бы с первым в тот же день, когда
/// человек подкрутит порог в панели.
/// </summary>
public static class NeedCurves
{
    /// <summary>Созрелость, при которой потребность считается настоящей.</summary>
    public const double Ripe = 1.0;

    /// <summary>
    /// Незнакомая потребность: всегда в полную силу. Это и есть прежнее
    /// поведение бота — постоянный вес, — и оно нарочно взято умолчанием:
    /// новая способность, о кривой которой никто не подумал, не должна тихо
    /// подешеветь.
    /// </summary>
    public static double Steady(NeedNow now) => Ripe;

    /// <summary>
    /// ГОЛОД. Ниже порога способности — созрел (1), дальше вверх падает до
    /// нуля при полной сытости. Простая пропорция, второго числа сверх
    /// порога здесь нет нарочно: каждое такое число пришлось бы объяснять.
    /// </summary>
    public static double Hunger(NeedNow now, double eatsBelow)
    {
        if (now.Fullness is not { } full)
            return Ripe;                       // не знаем — считаем как раньше
        double bar = Math.Clamp(eatsBelow, 0, 1);
        if (full <= bar)
            return Ripe;
        if (bar >= 1)
            return Ripe;                       // «есть всегда» — тоже настройка
        return Math.Clamp((1 - full) / (1 - bar), 0, Ripe);
    }

    /// <summary>РАНЫ. Та же пропорция от порога лечения.</summary>
    public static double Wounds(NeedNow now, double healsBelow)
    {
        if (now.Health is not { } hp)
            return Ripe;
        double bar = Math.Clamp(healsBelow, 0, 1);
        if (hp <= bar)
            return Ripe;
        if (bar >= 1)
            return Ripe;
        return Math.Clamp((1 - hp) / (1 - bar), 0, Ripe);
    }

    /// <summary>ХОЛОД. Доля замерзания против той доли, с которой пора к огню.</summary>
    public static double Chill(NeedNow now, double fireAt)
    {
        if (now.Cold is not { } cold)
            return Ripe;
        if (!(fireAt > 0))
            return Ripe;                       // «греться всегда» — настройка
        return Math.Clamp(cold / fireAt, 0, Ripe);
    }

    /// <summary>
    /// ТЕМНОТА. Внутри окна подготовки («за час до заката») — созрело; раньше
    /// — обратной пропорцией: за два окна до заката это половина, за десять —
    /// десятая. Гипербола, а не ещё одна прямая с ещё одним числом.
    /// </summary>
    public static double Dusk(NeedNow now, double prepareGameHours)
    {
        if (now.SecondsToDusk is not { } toDusk)
            return Ripe;
        double window = prepareGameHours * (now.SecondsPerGameHour ?? 0);
        if (!(window > 0))
            return Ripe;                       // сколько идёт игровой час, не знаем
        return toDusk <= window ? Ripe : Math.Clamp(window / toDusk, 0, Ripe);
    }

    /// <summary>
    /// ТЕМПОРАЛЬНАЯ СТАБИЛЬНОСТЬ. Та же пропорция от порога ухода, что у голода
    /// и ран: ниже порога — созрело, выше — падает к нулю у полной единицы.
    ///
    /// Считаем от ЕДИНИЦЫ, а не от «сколько бывает»: единица — настоящий
    /// потолок этого числа (сервер зажимает его в 0..1 каждым тиком,
    /// EntityBehaviorTemporalStabilityAffected.OnGameTick).
    /// </summary>
    public static double Instability(NeedNow now, double runsBelow)
    {
        if (now.Stability is not { } stability)
            return Ripe;                       // не знаем — считаем как раньше
        double bar = Math.Clamp(runsBelow, 0, 1);
        if (stability <= bar)
            return Ripe;
        if (bar >= 1)
            return Ripe;                       // «уходить всегда» — тоже настройка
        return Math.Clamp((1 - stability) / (1 - bar), 0, Ripe);
    }

    /// <summary>
    /// ПРЕДВИДЕТЬ НЕЧЕМ — так отвечает всё, у чего своей кривой нет.
    ///
    /// Отдельным именем, а не «false по месту», нарочно: это ответ на вопрос,
    /// который стоил револьверу всей его работы (см. <see cref="NeedCurve"/>).
    /// </summary>
    public static bool Blind(NeedNow now) => false;

    /// <summary>
    /// КРИВАЯ ПОТРЕБНОСТИ ВМЕСТЕ С ОТВЕТОМ «А ЕСТЬ ЛИ ЧЕМ ЕЁ ПРЕДВИДЕТЬ».
    ///
    /// ЗАЧЕМ ВТОРОЕ ПОЛЕ И ЧТО БЕЗ НЕГО СЛОМАЛОСЬ. Кривая обязана отвечать
    /// «созрело в полную силу», когда числа нет: не знаем — ведём себя как
    /// прежде (см. оговорку у <see cref="Steady"/>). Но у слов «созрело» тогда
    /// два разных смысла: «голод НАСТОЯЩИЙ, сытость 20%» и «про бой я не знаю
    /// ничего». Планировщик их различить не мог и считал жизненным ВСЁ, что
    /// тяжелее пола: возрождение, не висеть в воздухе, сон, буря, бой созревшие
    /// ВСЕГДА — а значит, «жизненное не переставляем» срабатывало каждый раз, и
    /// ни одной переприоритизации по сроку у заказчика не случалось ни разу.
    ///
    /// Поэтому кривая теперь говорит и второе: ВИДИТ ли она то число, по
    /// которому считает. Оба ответа рождаются в ОДНОМ разборе
    /// (<see cref="Of"/>) — два разных списка «у кого какая кривая» разошлись
    /// бы в первый же день, когда кривых станет пять.
    /// </summary>
    /// <param name="Ripeness">Насколько потребность созрела при таком состоянии.</param>
    /// <param name="Sees">
    /// Пришло ли от сервера то самое число, по которому кривая считает.
    /// Ложь — «созрело» из <see cref="Ripeness"/> означает не «нужно прямо
    /// сейчас», а «предвидеть нечем».
    /// </param>
    public sealed record NeedCurve(Func<NeedNow, double> Ripeness, Func<NeedNow, bool> Sees);

    /// <summary>
    /// Кривая этой способности. Порог берётся У НЕЁ САМОЙ, поэтому подкрученный
    /// в панели порог сразу меняет и планирование.
    ///
    /// Кого здесь нет — тот <see cref="Steady"/>, то есть работает как прежде.
    /// Списка «всех остальных» нарочно не заводим: он бы устарел на первой же
    /// новой способности, и та повела бы себя неожиданно.
    ///
    /// «Видим ли» перечислено ровно теми же полями снимка, на которых у кривой
    /// стоит её собственное «не знаю — считаю как раньше»: ошибись здесь, и
    /// планировщик либо снова ослепнет, либо начнёт планировать по числу,
    /// которого нет.
    /// </summary>
    public static NeedCurve Of(BotBehavior behavior) => behavior switch
    {
        BehaviorEatWhenHungry eat => new NeedCurve(
            now => Hunger(now, eat.HungerThreshold), now => now.Fullness != null),
        BehaviorHealWhenHurt heal => new NeedCurve(
            now => Wounds(now, heal.HealthThreshold), now => now.Health != null),
        BehaviorKeepWarm warm => new NeedCurve(
            now => Chill(now, warm.FireAtFraction), now => now.Cold != null),
        BehaviorSeekStability flee => new NeedCurve(
            now => Instability(now, flee.RunBelow), now => now.Stability != null),
        BehaviorWeaponAtNight arm => new NeedCurve(
            now => Dusk(now, arm.PrepareHours),
            now => now.SecondsToDusk != null && now.SecondsPerGameHour is > 0),
        _ => new NeedCurve(Steady, Blind)
    };

    /// <summary>
    /// ЧЕРЕЗ СКОЛЬКО СЕКУНД ПОТРЕБНОСТЬ СОЗРЕЕТ. null — не созреет за
    /// отпущенное время (или предвидеть её нечем).
    ///
    /// Считается перебором вперёд, а не формулой, нарочно: кривых уже четыре,
    /// и у каждой своя форма — общая формула обратного хода была бы пятой
    /// механикой, которую пришлось бы чинить при каждой новой кривой. Перебор
    /// грубый (сто с небольшим шагов на весь горизонт) и потом уточняется
    /// делением пополам: секунда точности здесь ничего не решает, а вот
    /// «созреет или нет» решает всё.
    /// </summary>
    public static double? RipeIn(Func<NeedNow, double> curve, NeedNow now, double horizonSeconds)
    {
        if (!(horizonSeconds > 0))
            return null;
        if (curve(now) >= Ripe)
            return 0;

        const int steps = 120;
        double step = horizonSeconds / steps;
        double before = 0;
        for (int i = 1; i <= steps; i++)
        {
            double at = step * i;
            if (curve(now.After(at)) < Ripe)
            {
                before = at;
                continue;
            }
            // Нашли шаг, на котором созрело: уточняем делением пополам
            double low = before, high = at;
            for (int n = 0; n < 8; n++)
            {
                double mid = (low + high) / 2;
                if (curve(now.After(mid)) >= Ripe)
                    high = mid;
                else
                    low = mid;
            }
            return high;
        }
        return null;
    }
}

/// <summary>
/// ЧТО БОТ СОБИРАЕТСЯ СДЕЛАТЬ И ПОЧЕМУ — одной записью для панели и журнала.
/// </summary>
/// <param name="Pick">Название выбранного дела (пусто — выбирать не из чего).</param>
/// <param name="Why">Причина ЧЕЛОВЕЧЕСКИМИ словами: её читает заказчик.</param>
/// <param name="Order">Все дела в том порядке, в каком их теперь обойдут.</param>
/// <param name="Ahead">
/// Дело, ПРОПУЩЕННОЕ ВПЕРЁД своей очереди (null — никого не пропускали).
///
/// Отдельным полем, а не «догадайся по Pick», по одной причине: такое дело по
/// определению ЕЩЁ НЕ СОЗРЕЛО, и само по себе оно откажется работать — у него
/// свой порог, и он не пройден. Один только новый порядок обхода для него
/// пустой звук, и обещание «делаю это сейчас» без подталкивания было бы
/// враньём. Кто пропускает вперёд, тот и обязан поторопить (см.
/// <see cref="NeedHurry"/>).
/// </param>
public sealed record PlanChoice(string Pick, string Why, IReadOnlyList<PlanCandidate> Order,
    PlanCandidate? Ahead = null)
{
    public override string ToString() => Pick.Length == 0 ? Why : $"{Pick} — {Why}";

    /// <summary>
    /// ЧЕМ ЭТОТ ПЛАН ОТЛИЧАЕТСЯ ОТ ПРЕЖНЕГО — устойчивый повод для сторожа
    /// повторов. Без чисел.
    ///
    /// ЗАЧЕМ ОТДЕЛЬНО ОТ <see cref="ToString"/>, И ЭТО НЕ УКРАШЕНИЕ. Сторож
    /// (<c>Alarm</c>) считает НОВОЙ ПРИЧИНОЙ любую перемену в строке, а в
    /// строке плана дрожат вес и секунды: вес голода растёт с каждой секундой,
    /// срок дела замеряется по прошлым заходам. Тик идёт каждые 400 мс —
    /// значит человек получал бы ДВЕ С ПОЛОВИНОЙ СТРОКИ В СЕКУНДУ, каждая
    /// отличается последней цифрой. Ровно тот шум, от которого в этом проекте
    /// уже лечили голод, разломы, бурю и опись склада.
    ///
    /// Новость здесь ровно одна: БОТ РЕШИЛ ДЕЛАТЬ ДРУГОЕ. «То же самое, но
    /// тридцать шесть секунд вместо тридцати семи» новостью не является.
    /// Пропущенное вперёд входит в повод отдельно: «делаю то же, но теперь
    /// потому, что иначе оно оборвётся» — это перемена, и её надо услышать.
    /// </summary>
    public string Key => Pick + "|" + (Ahead?.Name ?? "");
}

/// <summary>Одно дело глазами планировщика.</summary>
/// <param name="Name">Как звать человеку.</param>
/// <param name="Weight">Вес ПРЯМО СЕЙЧАС (уже с полом, потолком и созрелостью).</param>
/// <param name="RipeIn">
/// Через сколько секунд потребность созреет: 0 — уже созрела, null — не
/// созреет за горизонт планирования или предвидеть её нечем.
/// </param>
/// <param name="Eta">
/// Сколько примерно займёт дело, с. null — ДЕЛО НЕ СКАЗАЛО, и выдумывать за
/// него нельзя.
/// </param>
/// <param name="Floor">
/// Пол веса. Нужен ровно для одного: РАЗБИРАТЬ НИЧЬЮ так же, как её разбирал
/// прежний обход (<see cref="BehaviorRunner.Ordered"/>) — при равном весе
/// жизненные идут первыми. Человек вправе свести еду и работу вплотную («еда
/// 5» даёт 60, «без дела 99» даёт те же 60), и разрешать такую ничью порядком
/// подключения нельзя: роль, добавившая свою способность до пресета выживания,
/// получила бы работу выше еды.
/// </param>
/// <param name="Foreseen">
/// ЕСТЬ ЛИ ЧЕМ ПРЕДВИДЕТЬ эту потребность, то есть можно ли верить сроку
/// <see cref="RipeIn"/> как ЗНАНИЮ, а не как отговорке.
///
/// Зачем это здесь. «Созреет через 0 с» приходит и от настоящего голода
/// (сытость 20% — есть надо сейчас), и от способности БЕЗ СВОЕЙ КРИВОЙ (бой,
/// сон, возрождение: про них не известно ничего, и кривая честно отвечает «в
/// полную силу»). Спутай их — и «жизненное не переставляем» сработает на
/// каждом тике для каждого рефлекса, а планировать станет нечего вовсе:
/// ровно это и случилось, см. <see cref="NeedCurves.NeedCurve"/>.
///
/// По умолчанию ИСТИНА: у чистого правила «сказано созрело — значит созрело»,
/// и это осторожная сторона (лишний раз не переставим), а не удобная.
/// </param>
/// <param name="Of">Кто это на самом деле. Правило выбора сюда не смотрит.</param>
public sealed record PlanCandidate(string Name, double Weight, double? RipeIn, double? Eta,
    double Floor = 0, bool Foreseen = true, object? Of = null)
{
    public override string ToString() =>
        $"{Name} {Weight:0.#}" +
        (RipeIn is { } r ? $", созреет через {r:0} с" : "") +
        (Eta is { } e ? $", займёт ~{e:0} с" : ", сколько займёт — не говорит");
}

/// <summary>
/// РЕВОЛЬВЕР: ЧТО ДЕЛАТЬ ДАЛЬШЕ, если смотреть не только на «кто тяжелее
/// сейчас», но и на «что успеет созреть, пока мы заняты».
///
/// ЗАКАЗ (хозяин, 10.08): «выбираем наиболее приоритетный исходя из
/// сочетания вес приоритета &amp; ETA на выполнение», «приближающееся время
/// выполнения несрочной но быстрой задачи может переприоритизировать её».
/// Заказчик своими словами: «простыми словами заранее планировать, что и когда
/// сделает бот».
///
/// ОТКУДА ЗАКАЗ ВЫРОС (журнал 23:31): бот вышел в наряд за 90 блоков, на
/// середине дороги проголодался, еда весом 80 перебила наряд, наряд отменился
/// ЦЕЛИКОМ — «принёс 0 из 10». И так по кругу. Живой игрок в этот миг поступает
/// иначе: он доедает ПЕРЕД выходом, потому что знает, что в пути проголодается.
///
/// ЧЕГО РЕВОЛЬВЕР НЕ ДЕЛАЕТ, И ЭТО НАДО ЗНАТЬ ТОЧНО. Сам по себе он НЕ КОРМИТ.
/// Он чистое правило: раскладывает дела по порядку и говорит словами, что
/// собирается делать и почему. Тот самый наряд из 23:31 спасает ДРУГОЕ место —
/// <c>WorkRunner.PlanBeforeLeavingAsync</c> (Jobs.cs), которое перед выходом на
/// задачу спрашивает «что созреет в пути» и подталкивает потребность через
/// <see cref="NeedHurry"/>; строку «делаю «еда» сейчас, потому что в пути…»
/// печатает именно оно, а не этот класс. Револьвер отвечает за очередь
/// способностей — там за него подталкивает <see cref="BehaviorRunner"/> (см.
/// <see cref="PlanChoice.Ahead"/>), тем же самым <see cref="NeedHurry"/>, а не
/// вторым его подобием.
///
/// И ОН НЕ ЛЕЧИТ БЕГОТНЮ — ЭТО НЕ ЕГО ВОПРОС, И СКАЗАНО ЗДЕСЬ НАРОЧНО. Жалоба
/// 30.08 («он бегал вперед назад с резкими разворотами как сумасшедший») на
/// первый взгляд читается как ошибка выбора, и чинить её тянет тут. Но выбор в
/// том журнале был ВЕРЕН каждый раз: бот и правда был голоден, сумки и правда
/// были полны. Неверна была ЧЕРЕДА — шесть смен хозяина тела за четырнадцать
/// секунд, — а хозяина тела меняет не револьвер, а
/// <see cref="BodyArbiter"/>. Там же и лечение: цена смены хозяина
/// (<see cref="BodyArbiter.SettleSeconds"/>). Заведи мы здесь второй сторож
/// дрожи — он разошёлся бы с тем в первый же день, а бот получил бы два
/// разных ответа на вопрос «можно ли сейчас бросить дело».
///
/// ПРАВИЛО ЦЕЛИКОМ (оно чистое, и стенд проверяет именно его):
///
/// 1. Кто СЕЙЧАС весит не меньше пола жизненных И чья потребность УЖЕ
///    настоящая, тот стоит в начале обхода, по весу вниз — ровно как раньше.
///    Возрождение, спасение, бой, лечение и голод не переставляет НИКТО и ни
///    при каких расчётах: револьвер решает, что делать ДАЛЬШЕ, а не отменяет
///    право рефлекса вмешаться.
///
///    Оба условия нужны, и вот почему второе. Голод при сытости 55% весит уже
///    немало (кривая подняла его почти к полной силе), но его ЕЩЁ НЕТ: бот не
///    голоден, еда в этот тик ничего не сделает и честно вернёт «нет». Считать
///    такое жизненным значило бы запретить себе его планировать — то есть
///    выкинуть ровно тот случай, ради которого всё и затевалось.
/// 2. НО ГОЛОВА ОБХОДА — НЕ КОНЕЦ РАЗГОВОРА, и это стоило заказчику всего
///    механизма. У возрождения, «не висеть в воздухе», сна, бури и боя своей
///    кривой нет, а «нет кривой» отвечает «созрело в полную силу» — значит
///    жизненными они выходят ВСЕГДА, и прежнее «раз жизненное есть, планировать
///    нечего» срабатывало на каждом тике живого бота. Заказчик, включив
///    револьвер, не получал ни одной переприоритизации, а в журнал ему весь
///    вечер шла одна и та же строка про возрождение. Поэтому «жизненное» и
///    «ПРЕДВИДЕННОЕ жизненное» теперь разные вещи
///    (<see cref="PlanCandidate.Foreseen"/>): планирование останавливает только
///    то, про что мы и правда ЗНАЕМ, что оно созрело сейчас, — голод по
///    измеренной сытости, раны по здоровью. Рефлексы, про которые нам не
///    известно ничего, остаются наверху обхода и названы в объяснении, но
///    планировать среди остальных они больше не мешают.
/// 3. Среди оставшихся (это работа, хозяйство, приличия) выбирается вожак —
///    самый тяжёлый. Обычно им дело и кончается.
/// 4. НО: если у кого-то из них потребность СОЗРЕЕТ ПОСРЕДИ дела вожака
///    (<c>созреет через</c> меньше, чем <c>вожак займёт</c>) и сам он ДЕШЕВЛЕ
///    вожака — вперёд пропускают его. Это и есть «дешёвое и скорое обгоняет
///    дорогое», и это ровно тот случай с обедом перед дорогой. Выше рефлексов
///    его при этом НЕ поднимают: он встаёт в голову НЕсрочной части, а не
///    впереди боя.
/// 5. Не знаем, сколько займёт вожак, — НЕ ПЛАНИРУЕМ и говорим об этом вслух.
///    Догадаться о сроке нельзя: цена догадки — прерванный на середине наряд.
/// </summary>
public static class Revolver
{
    /// <summary>
    /// Разложить дела по порядку и сказать, почему первым идёт именно это.
    /// </summary>
    /// <param name="all">Все дела с весами, сроками созревания и ETA.</param>
    /// <param name="lifeFloor">
    /// Пол жизненных (<see cref="BehaviorWeights.LifeFloor"/>): выше него
    /// планировщик не трогает НИЧЕГО.
    /// </param>
    public static PlanChoice Order(IReadOnlyList<PlanCandidate> all, double lifeFloor)
    {
        // Ничья разбирается ТОЧНО ТАК ЖЕ, как её разбирал прежний обход: при
        // равном весе жизненные вперёд. Иначе включение револьвера тихо
        // переставило бы еду и работу, сведённые человеком вплотную
        var byWeight = all.OrderByDescending(c => c.Weight)
            .ThenByDescending(c => c.Floor)
            .ToList();
        if (byWeight.Count == 0)
            return new PlanChoice("", "делать нечего: способностей нет", byWeight);

        bool Vital(PlanCandidate c) => c.Weight >= lifeFloor && c.RipeIn is 0;
        var vital = byWeight.Where(Vital).ToList();
        var rest = byWeight.Where(c => !Vital(c)).ToList();

        // ВОЖАК И ТОТ, КОГО ПРОПУСКАЮТ ВПЕРЁД, — считаются СРЕДИ НЕСРОЧНЫХ и
        // считаются ВСЕГДА, есть наверху рефлексы или нет. Раньше расчёт сюда
        // просто не доходил: рефлекс без своей кривой «созрел» на каждом тике,
        // и планировщик выходил ранним возвратом (см. пункт 2 у класса)
        var leader = rest.Count > 0 ? rest[0] : null;
        PlanCandidate? early = null;
        if (leader?.Eta is { } forEarly)
            // Кто созреет ПОСРЕДИ дела вожака и при этом дешевле его. «Уже
            // созрело» (срок 0) сюда не годится: такое дело либо и так тяжелее,
            // либо ему просто не пришло время торопиться.
            // Сравнение по ССЫЛКЕ, а не по значению: PlanCandidate — запись, и
            // два дела с одинаковыми числами равны друг другу. Два одинаковых
            // дела в списке выкинули бы друг друга из порядка обхода — молча
            early = rest
                .Where(c => !ReferenceEquals(c, leader) &&
                            c.RipeIn is { } ripe && ripe > 0 && ripe < forEarly &&
                            c.Eta is { } eta && eta < forEarly)
                .OrderBy(c => c.RipeIn!.Value)
                .ThenByDescending(c => c.Weight)
                .FirstOrDefault();

        // ПОРЯДОК ОБХОДА. Пропущенный вперёд встаёт в голову НЕСРОЧНОЙ части, а
        // не всего списка: поднять его над боем и возрождением значило бы
        // отдать рефлексам второй ход, а рефлексы тут не пересматриваются
        var order = new List<PlanCandidate>(byWeight);
        if (early != null)
        {
            order.RemoveAll(c => ReferenceEquals(c, early));
            int at = order.FindIndex(c => !Vital(c));
            order.Insert(at < 0 ? order.Count : at, early);
        }

        // ЖИЗНЕННОЕ, КОТОРОЕ МЫ И ПРАВДА ВИДИМ, планировать не даёт — и это та
        // самая граница, за которую револьвер не заходит. Но «видим» здесь
        // означает именно знание: голод по измеренной сытости, раны по
        // здоровью. Рефлекс, про который не известно ничего, границей не
        // становится, иначе планировать нельзя было бы никогда
        if (vital.FirstOrDefault(c => c.Foreseen) is { } urgent)
            return new PlanChoice(urgent.Name,
                $"{urgent.Name} — это не терпит (вес {urgent.Weight:0.#} " +
                $"не ниже жизненного порога {lifeFloor:0.#}), планировать тут нечего",
                order);

        // РЕФЛЕКСЫ НАЗЫВАЮТСЯ ВСЛУХ. Человек читает «делаю то-то» и вправе
        // знать, что выше стоят дела, которые вмешаются без спроса: иначе
        // бот, бросивший «своё» ради боя, выглядит нарушившим собственный план
        string reflexes = vital.Count == 0
            ? ""
            : $"; выше стоят рефлексы ({Named(vital)}) — предвидеть их нечем, " +
              "они вмешаются сами";

        if (leader == null)
            return new PlanChoice("",
                vital.Count == 0
                    ? "делать нечего"
                    : $"планировать нечего: всё, что есть, — рефлексы ({Named(vital)}), " +
                      "они сработают сами, когда понадобятся",
                order);

        if (leader.Eta is not { } leaderEta)
            return new PlanChoice(leader.Name,
                $"{leader.Name} — самое важное из несрочного (вес {leader.Weight:0.#}); " +
                "сколько оно займёт, оно не говорит — вперёд не планирую, чтобы не гадать" +
                reflexes,
                order);

        if (early == null)
            return new PlanChoice(leader.Name,
                $"{leader.Name} — самое важное из несрочного (вес {leader.Weight:0.#}), " +
                $"займёт ~{leaderEta:0} с; за это время ничего не созреет" + reflexes,
                order);

        return new PlanChoice(early.Name,
            $"{early.Name} сейчас: за {leaderEta:0} с дела «{leader.Name}» это созреет " +
            $"через {early.RipeIn!.Value:0} с и оборвёт его, а само займёт " +
            $"~{early.Eta!.Value:0} с — дешевле сделать до выхода" + reflexes,
            order, Ahead: early);
    }

    /// <summary>
    /// Перечислить дела человеку, не заливая строку целиком. Семь рефлексов
    /// подряд в каждой строке журнала — тот же шум, за которым однажды не
    /// увидели настоящей беды (см. <see cref="Alarm"/>).
    /// </summary>
    private static string Named(IReadOnlyList<PlanCandidate> some, int most = 3) =>
        some.Count <= most
            ? string.Join(", ", some.Select(c => c.Name))
            : string.Join(", ", some.Take(most).Select(c => c.Name)) +
              $" и ещё {some.Count - most}";
}

/// <summary>
/// ПОТОРОПИТЬ ПОТРЕБНОСТЬ: сделать дело ЗАРАНЕЕ, пока оно ещё не приспичило.
///
/// Зачем это отдельно от выбора. Револьвер умеет сказать «поешь перед
/// выходом», но сама еда в этот миг отвечает «я не голоден»: у неё свой порог
/// (сытость ниже 40%), и при 60% она честно не делает ничего. Получилось бы
/// планирование на словах: сказали и не сделали.
///
/// Поэтому порог способности на ОДИН заход поднимается ровно настолько, чтобы
/// дело сработало сейчас, — и тут же возвращается. Возврат обязателен и
/// возвращается ВСЕГДА (см. <c>WorkTweaks</c> у очереди задач, где живёт та же
/// беда): забытый порог «есть при 95%» сделал бы из бота обжору навсегда.
///
/// КТО ЭТО ЗОВЁТ — ДВОЕ, И МЕХАНИКА У НИХ ОДНА ЭТА. Очередь задач перед выходом
/// на дальнюю работу (<c>WorkRunner.PlanBeforeLeavingAsync</c>, Jobs.cs) и цикл
/// способностей, когда планировщик пропустил дело вперёд его срока
/// (<see cref="BehaviorRunner"/>, <see cref="PlanChoice.Ahead"/>). Вопросы у них
/// разные («перед этой задачей» и «перед этим ходом»), а подкрутка порога и его
/// возврат — одни и те же и живут только здесь: два подобия этого кода
/// разошлись бы в первый же день, а цена расхождения — бот-обжора с навсегда
/// поднятым порогом.
///
/// ТОРОПИМ НЕ ВСЕХ, И ЭТО НАРОЧНО. Поесть и взять оружие — дёшево и обратимо.
/// А «полечиться заранее» тратит бинты на царапину, «погреться заранее» — это
/// костёр и остановка всех дел; такое заранее не делают и живые игроки.
/// Кого торопить не умеем — о том честно говорим и просто предупреждаем
/// человека, что оно созреет в пути.
/// </summary>
public static class NeedHurry
{
    /// <summary>
    /// Подготовить способность к тому, чтобы она сработала прямо сейчас.
    /// false — торопить эту потребность мы не умеем (и <paramref name="what"/>
    /// говорит почему); true — порог подкручен, и <paramref name="undo"/>
    /// ОБЯЗАН быть вызван после захода.
    /// </summary>
    public static bool Prepare(BotBehavior behavior, NeedNow now, out string what,
        out Action undo)
    {
        undo = static () => { };
        switch (behavior)
        {
            case BehaviorEatWhenHungry eat when now.Fullness is { } full:
            {
                // Выше этой сытости жевать бессмысленно: сервер не засчитает
                // еду сытому, и бот будет тыкать в хлеб до конца задачи
                const double tooFull = 0.95;
                if (full >= tooFull)
                {
                    what = $"сытость {full * 100:0}% — жевать некуда, торопиться незачем";
                    return false;
                }
                double was = eat.HungerThreshold;
                double bar = Math.Min(tooFull, full + 0.01);
                if (bar <= was)
                {
                    what = "порог голода и так выше нынешней сытости — тороплю не я, а сам голод";
                    return false;
                }
                eat.HungerThreshold = bar;
                undo = () => eat.HungerThreshold = was;
                what = $"порог голода на один заход {was * 100:0}% → {bar * 100:0}%";
                return true;
            }

            case BehaviorWeaponAtNight arm when now.SecondsToDusk is { } toDusk &&
                                                now.SecondsPerGameHour is { } hour && hour > 0:
            {
                double hoursLeft = toDusk / hour;
                double was = arm.PrepareHours;
                if (was >= hoursLeft)
                {
                    what = "до темноты уже ближе, чем окно подготовки — торопить нечего";
                    return false;
                }
                arm.PrepareHours = hoursLeft + 0.01;
                undo = () => arm.PrepareHours = was;
                what = $"окно «оружие к ночи» на один заход {was:0.##} → {hoursLeft + 0.01:0.##} игр. ч";
                return true;
            }

            default:
                what = "торопить эту потребность я не умею — просто знаю, что она созреет в пути";
                return false;
        }
    }
}

/// <summary>
/// ОТКУДА БЕРЁТСЯ СОСТОЯНИЕ ДЛЯ КРИВЫХ: снимает <see cref="NeedNow"/> с живого
/// бота и попутно ЗАМЕРЯЕТ скорости (голод, замерзание).
///
/// Своей памяти о боте здесь нет и не должно быть: сытость спрашивается у
/// <c>SelfState</c>, замерзание — у <c>BodyHeat</c>, время до темноты — у
/// <c>GameClock</c>. Каждое из этих мест уже отвечает за своё число боту, и
/// второй такой ответ разошёлся бы с первым.
///
/// Замеряется ровно две скорости, и обе — <see cref="Drift"/>-ом по числам
/// сервера. Скорость голода в игре зависит от занятия, от настроек сервера и
/// от модов; вписать её числом значило бы соврать на первом же чужом сервере.
/// </summary>
public sealed class NeedSense
{
    private readonly BotContext ctx;

    /// <summary>Убыль сытости, долей в секунду.</summary>
    public Drift Fullness { get; } = new();

    /// <summary>Рост замерзания, долей в секунду.</summary>
    public Drift Cold { get; } = new();

    /// <summary>
    /// Ход темпоральной стабильности, единиц в секунду (минус — падает).
    /// Порог заметности меньше общего: стабильность тянется медленно —
    /// на серверных числах это тысячные в секунду, — и с общим порогом в 0,01
    /// первый замер объявился бы только через несколько минут.
    /// </summary>
    public Drift Stability { get; } = new() { MinChange = 0.002 };

    public NeedSense(BotContext ctx) => this.ctx = ctx;

    /// <summary>Снять состояние. Зовётся на каждом тике — заодно копит замеры.</summary>
    public NeedNow Read() => Read(DateTime.UtcNow);

    /// <summary>То же с явным временем: так правило проверяется стендом.</summary>
    public NeedNow Read(DateTime at)
    {
        double? full = null;
        if (ctx.Self.Saturation is { } sat && ctx.Self.MaxSaturation is { } maxSat && maxSat > 0)
        {
            full = Math.Clamp(sat / maxSat, 0, 1);
            Fullness.Add(full.Value, at);
        }

        double? health = null;
        if (ctx.Self.Health is { } hp && ctx.Self.MaxHealth is { } maxHp && maxHp > 0)
            health = Math.Clamp(hp / maxHp, 0, 1);

        double? cold = null;
        if (ctx.Cold is { Ready: true } heat)
        {
            cold = Math.Clamp(heat.ColdFraction, 0, 1);
            Cold.Add(cold.Value, at);
        }

        double? toDusk = null;
        double? hourSeconds = null;
        if (ctx.Clock is { Ready: true } clock)
        {
            // Сколько РЕАЛЬНЫХ секунд идёт игровой час — спрашиваем у часов
            // (<see cref="GameClock.RealSecondsPerGameHour"/>), своей копии
            // формулы здесь больше нет. Перевод нужен не одному планировщику:
            // тем же вопросом разделка считает, через сколько минут сгниёт
            // туша, — и две копии одной формулы разъехались бы молча
            if (clock.RealSecondsPerGameHour is { } perHour)
            {
                hourSeconds = perHour;
                toDusk = clock.HoursUntilNight * perHour;
            }
        }

        // ТЕМПОРАЛЬНАЯ СТАБИЛЬНОСТЬ: число берём у механизма, а замер скорости
        // ведём здесь, как у сытости и холода. Своего Drift-а у стабильности в
        // механизме нет нарочно — там своё окно и свой вопрос («растёт или
        // падает прямо сейчас»), а планировщику нужна скорость в секунду
        double? stability = null;
        if (ctx.Stability?.Own is { } own)
        {
            stability = Math.Clamp(own, 0, 1);
            Stability.Add(stability.Value, at);
        }

        return new NeedNow(
            Fullness: full,
            // Убыль — это падение. Растущая сытость (только что поел) не
            // говорит ничего о том, когда бот проголодается снова
            FullnessFallPerSecond: Fullness.PerSecond is { } fall && fall < 0 ? -fall : null,
            Health: health,
            Cold: cold,
            ColdRisePerSecond: Cold.PerSecond is { } rise && rise > 0 ? rise : null,
            SecondsToDusk: toDusk,
            SecondsPerGameHour: hourSeconds,
            Stability: stability,
            // Как и с сытостью: РОСТ стабильности не говорит ничего о том,
            // когда она снова просядет
            StabilityFallPerSecond: Stability.PerSecond is { } drain && drain < 0 ? -drain : null);
    }
}

/// <summary>
/// ТРЕВОГА: беда, о которой надо сказать ГРОМКО И ОДИН РАЗ.
///
/// Живой случай, ради которого она появилась. Бот рыл карьер и каждые шесть
/// секунд терял по 0,13 хп от голода — десятки строк «Потеряно 0,13 хп от
/// hunger» подряд, и ни одной строки о том, ПОЧЕМУ он не ест (еда в кармане
/// была, а рука не освобождалась). Молчание тут ничем не лучше вранья, но и
/// сто одинаковых строк ничем не лучше молчания: в шуме заказчик и не увидел
/// настоящей беды.
///
/// Правило простое: пока причина та же — говорим один раз (и повторяем не
/// чаще <see cref="RepeatAfter"/>, чтобы про долгую беду не забыли совсем).
/// Причина сменилась — это новость, говорим сразу. Беда прошла — <see
/// cref="Clear"/>, и следующая такая же снова прозвучит как первая.
/// </summary>
public sealed class Alarm
{
    private DateTime saidAt = DateTime.MinValue;
    private string reason = "";

    /// <summary>Про что тревога — попадает в сообщение как есть.</summary>
    public string About { get; }

    public Alarm(string about) => About = about;

    /// <summary>
    /// Как часто напоминать, пока беда не прошла. Полностью замолчать нельзя:
    /// бот, который час назад сказал «поесть нечем» и с тех пор молчит,
    /// выглядит здоровым.
    /// </summary>
    public TimeSpan RepeatAfter { get; set; } = TimeSpan.FromMinutes(5);

    /// <summary>Беда сейчас идёт.</summary>
    public bool Ringing { get; private set; }

    /// <summary>Текущая причина (пусто — тревоги нет).</summary>
    public string Reason => Ringing ? reason : "";

    /// <summary>Сказать вслух: «{About}: {why}».</summary>
    public event Action<string>? OnRaise;

    /// <summary>Отбой вслух — только если тревога и правда звучала.</summary>
    public event Action<string>? OnClear;

    /// <summary>
    /// Поднять тревогу. Возвращает true, если СКАЗАЛИ вслух (первый раз,
    /// причина сменилась или пришёл срок напомнить).
    /// </summary>
    public bool Raise(string why, DateTime? now = null)
    {
        var at = now ?? DateTime.UtcNow;
        bool fresh = !Ringing || why != reason || at - saidAt >= RepeatAfter;
        Ringing = true;
        reason = why;
        if (!fresh)
            return false;
        saidAt = at;
        OnRaise?.Invoke($"{About}: {why}");
        return true;
    }

    /// <summary>
    /// Отбой: беда прошла. Возвращает true, если тревога и правда звучала —
    /// тогда об отбое стоит сказать, а не молча забыть.
    /// </summary>
    public bool Clear(string? why = null)
    {
        if (!Ringing)
            return false;
        Ringing = false;
        reason = "";
        saidAt = DateTime.MinValue;
        OnClear?.Invoke(why is { Length: > 0 } w ? $"{About}: {w}" : $"{About}: обошлось");
        return true;
    }
}

/// <summary>
/// Способность бота: небольшой автономный кусок поведения (поесть, поспать,
/// отбиться, поглядывать на игроков...). Раннер обходит способности ПО ВЕСУ
/// ВАЖНОСТИ, от большего к меньшему; если способность «взяла ход» (вернула
/// true), остальные в этом тике пропускаются.
/// </summary>
public abstract class BotBehavior
{
    private double? weight;

    /// <summary>
    /// ВЕС ВАЖНОСТИ: больше — важнее, и обходятся способности именно в этом
    /// порядке. Не задан — берётся вес по умолчанию для этого вида способности
    /// (<see cref="BehaviorWeights.DefaultOf(BotBehavior)"/>).
    ///
    /// Записать можно любое число, но ПРОЧИТАЕТСЯ оно между
    /// <see cref="WeightFloor"/> и <see cref="WeightCeiling"/>: у еды, лечения
    /// и возрождения есть пол — опустить их под работу нельзя ни настройкой, ни
    /// пресетом, ни опечаткой; у работы, хозяйства и безделья есть потолок —
    /// поднять их над жизненными нельзя тем же способом. Обе причины названы в
    /// <see cref="BehaviorWeights"/> и стоили заказчику бота, умершего от
    /// голода с хлебом в кармане.
    /// </summary>
    public double Weight
    {
        get => Math.Min(WeightCeiling,
            Math.Max(WeightFloor, weight ?? BehaviorWeights.DefaultOf(this)));
        set => weight = value;
    }

    /// <summary>Ниже этого веса способность не опускается (0 — можно до нуля).</summary>
    public double WeightFloor => BehaviorWeights.FloorOf(this);

    /// <summary>Выше этого веса способность не поднимается (∞ — предела нет).</summary>
    public double WeightCeiling => BehaviorWeights.CeilingOf(this);

    /// <summary>Вес крутили руками (иначе стоит значение по умолчанию).</summary>
    public bool WeightSet => weight != null;

    /// <summary>
    /// НАСКОЛЬКО ПОТРЕБНОСТЬ СОЗРЕЛА при таком состоянии: 0 — её ещё нет,
    /// 1 — она настоящая. Умножается на <see cref="Weight"/>, а не заменяет
    /// его: пол и потолок остаются нетронутыми (см. <see cref="NeedCurves"/>).
    ///
    /// По умолчанию берётся кривая своего вида; незнакомая способность —
    /// всегда 1, то есть ведёт себя ровно как прежде. Своя способность роли
    /// вправе ответить по-своему, переопределив это.
    /// </summary>
    public virtual double Ripeness(NeedNow now) => NeedCurves.Of(this).Ripeness(now);

    /// <summary>
    /// ЕСТЬ ЛИ ЧЕМ ПРЕДВИДЕТЬ эту потребность при таком состоянии: ложь —
    /// «созрело» из <see cref="Ripeness"/> означает не «нужно прямо сейчас», а
    /// «я про это не знаю ничего».
    ///
    /// Разница не философская, она стоила планировщику всей работы. У боя, сна,
    /// возрождения и «не висеть в воздухе» своей кривой нет, а «нет кривой»
    /// отвечает «в полную силу» — и планировщик считал их СОЗРЕВШИМИ ЖИЗНЕННЫМИ
    /// на каждом тике, то есть не планировал никогда (см.
    /// <see cref="Revolver"/>, пункт 2).
    ///
    /// Умолчание — ЛОЖЬ для всего незнакомого: не знаем и не притворяемся, что
    /// знаем. Своя способность роли, умеющая предсказывать себя, вправе
    /// переопределить это вместе с <see cref="Ripeness"/> — но обязана делать
    /// это ЧЕСТНО: сказавший «вижу» получает право остановить планирование.
    /// </summary>
    public virtual bool Foresees(NeedNow now) => NeedCurves.Of(this).Sees(now);

    /// <summary>
    /// Вес с оглядкой на состояние: <c>вес × созрелость</c>. Пока состояние
    /// неизвестно (<see cref="NeedNow.Unknown"/>), это РОВНО обычный вес —
    /// поэтому включённый револьвер без данных не меняет поведения ни на волос.
    /// </summary>
    public double WeightAt(NeedNow now) => Weight * Math.Clamp(Ripeness(now), 0, 1);

    /// <summary>
    /// ЧЬЮ НУЖДУ ЗАКРЫВАЕТ ЭТА СПОСОБНОСТЬ (null — свою собственную, как у
    /// голода, боя и сна).
    ///
    /// ЗАЧЕМ ОБЪЯВЛЕНИЕ, А НЕ ЕЩЁ ОДНО ЧИСЛО В ТАБЛИЦЕ ВЕСОВ. За два дня одна
    /// и та же болезнь нашлась ЧЕТЫРЕ раза: нужда, которую нечем закрыть
    /// прямо сейчас, ВЫБЫВАЕТ из очереди (закрывать нечем — способность честно
    /// возвращает false), а её руки живут отдельной жизнью с отдельным весом,
    /// который приходится подгонять к весу нужды руками. Живой случай 23.08:
    /// голод весит 80, но без еды выбывает; «пойти добыть еду» весило 50 —
    /// ровно столько же, сколько поход за временной шестерёнкой, — и
    /// шестерёнка, начатая секундой раньше, держала тело пять минут, пока бот
    /// терял здоровье.
    ///
    /// ТАК ДЕЛАЮТ ДАВНО, И НЕ МЫ ПЕРВЫЕ. В The Sims (2000) предметы
    /// «рекламируют» себя нуждам: кровать обещает «+10 к энергии», унитаз
    /// «+20 к пузырю», — и вес поступка считается КАК ПРОИЗВЕДЕНИЕ обещанной
    /// прибавки на текущий уровень нужды. Сытому симу кровать не становится
    /// важнее еды не потому, что кому-то выставили правильное число, а потому
    /// что число это ВЫВОДИТСЯ. У нас ровно та же беда решалась ровно
    /// наоборот — подгонкой чисел, — и потому возвращалась.
    ///
    /// ЧТО ЭТО ДАЁТ. Объявив «я руки голода», способность получает срочность
    /// САМОЙ НУЖДЫ, помноженную на её созрелость: бот сыт — руки весят своё
    /// скромное, бот голодает — руки весят как голод. Новая жизненная нужда
    /// заводит эту дыру заново только в одном случае: если её руки забудут
    /// объявиться. Число подгонять больше не нужно ни разу.
    ///
    /// ПОТОЛОК ОСТАЁТСЯ. Унаследованная срочность режется тем же потолком
    /// (<see cref="WeightCeiling"/>): дело роли не встаёт над жизненными ни
    /// наследством, ни ручкой, ни опечаткой.
    /// </summary>
    public virtual Type? Serves => null;

    /// <summary>
    /// СКОЛЬКО ПРИМЕРНО ЗАЙМЁТ ЭТО ДЕЛО, секунд. null — способность не знает,
    /// и тогда срок ЗАМЕРЯЕТСЯ по прошлым её заходам
    /// (<see cref="BehaviorRunner.EtaOf"/>). Выдумывать за дело его срок
    /// нельзя: на выдуманном сроке строится решение «успею ли до того, как
    /// проголодаюсь», и цена ошибки — брошенный на середине наряд.
    /// </summary>
    public virtual double? SaysEta => null;

    /// <summary>Вернуть вес к умолчанию своего вида.</summary>
    public void ResetWeight() => weight = null;

    /// <summary>
    /// КАК НАЗЫВАТЬ СПОСОБНОСТЬ ЧЕЛОВЕКУ.
    ///
    /// ИМЕНА БИБЛИОТЕЧНЫХ СПОСОБНОСТЕЙ ЛЕЖАТ В ОДНОМ МЕСТЕ
    /// (<see cref="BehaviorWeights.NameOf(Type)"/>) и здесь не повторяются:
    /// второй таблицы имён в проекте нет.
    ///
    /// ПЕРЕКРЫВАТЬ ЭТО МОЖЕТ ТОЛЬКО СПОСОБНОСТЬ ИЗ РОЛИ, и вот почему это
    /// вообще понадобилось. Та таблица живёт в БИБЛИОТЕКЕ, а роли лежат в
    /// приложении и в чужих папках <c>roles</c> — ссылка идёт в одну сторону,
    /// и вписать туда способность роли НЕЛЬЗЯ НИКОГДА. Пока перекрыть было
    /// нечем, любая способность роли называлась человеку своим типом:
    /// «GuardGate» среди двух десятков русских строк.
    ///
    /// ЧЕГО ЭТО СТОИЛО ЖИВЬЁМ. Имя способности — не украшение: им человек
    /// ДВИГАЕТ ВЕС в строке «ВесаВажности» («еда 95; бой 70»), и по нему же
    /// ищет строку в списке важности, который заказчик просил прямо («вес
    /// важности, что над чем превалирует, так проще будет настроить бота»).
    /// Стражник, у которого еда весит 80, а стража 50, уходит с поста за
    /// едой — и единственный рычаг, которым это чинят, назывался в русском
    /// окне «GuardGate».
    /// </summary>
    public virtual string Title => BehaviorWeights.NameOf(this);

    /// <summary>
    /// СВОЁ ИМЯ, КОГДА ОДНОГО ТИПА МАЛО; null — имя берётся по типу.
    ///
    /// Спрашивается только у способностей, которых нет в таблице имён
    /// (<see cref="BehaviorWeights.NameOf(BotBehavior)"/>): у знакомых имя
    /// менять нельзя — им названы сохранённые настройки человека.
    /// </summary>
    public virtual string? SelfName => null;

    /// <summary>Сделать шаг поведения. true — способность действует, остальных не тикать.</summary>
    public abstract Task<bool> TickAsync(CancellationToken ct);
}

/// <summary>
/// Планировщик способностей. Добавьте способности и запустите StartAsync после
/// входа бота в мир.
///
/// ПОРЯДОК ОБХОДА РЕШАЕТ ВЕС, а не место в списке: <see cref="BotBehavior.Weight"/>
/// от большего к меньшему. Порядок добавления остаётся мерилом ДЛЯ РАВНЫХ —
/// обход устойчив, и способности с одинаковым весом идут в том же порядке, в
/// каком их подключили. Именно поэтому веса по умолчанию (<see
/// cref="BehaviorWeights"/>) не меняют прежнего поведения бота ни на волос.
/// </summary>
public class BehaviorRunner
{
    public List<BotBehavior> Behaviors { get; } = new();

    /// <summary>Добавить способность (вес — по умолчанию для её вида).</summary>
    public void Add(BotBehavior behavior) => Behaviors.Add(behavior);

    /// <summary>Добавить способность с явным весом важности.</summary>
    public void Add(BotBehavior behavior, double weight)
    {
        behavior.Weight = weight;
        Behaviors.Add(behavior);
    }

    /// <summary>Убрать способность.</summary>
    public bool Remove(BotBehavior behavior) => Behaviors.Remove(behavior);

    /// <summary>Найти подключённую способность нужного типа (чтобы донастроить).</summary>
    public T? Get<T>() where T : BotBehavior => Behaviors.OfType<T>().FirstOrDefault();

    public int Count => Behaviors.Count;

    /// <summary>
    /// Способности в том порядке, в каком их обходит тик: по весу вниз, равные
    /// — по порядку подключения. Именно это стоит показывать в окне управления:
    /// «что над чем превалирует» человек должен ВИДЕТЬ, а не выводить из чужого
    /// исходника.
    ///
    /// ПРИ РАВНОМ ВЕСЕ ЖИЗНЕННЫЕ ИДУТ ПЕРВЫМИ. Пол жизненных и потолок работы —
    /// одно и то же число (<see cref="BehaviorWeights.LifeFloor"/>), и человек
    /// вправе свести их вплотную: «еда 5» даст 60, «без дела 99» даст те же 60.
    /// Разрешать такую ничью порядком подключения нельзя — роль, добавившая
    /// свою способность до пресета выживания, получила бы работу выше еды. На
    /// умолчаниях сортировка ничего не меняет: там ничьих между жизненными и
    /// работой нет вовсе.
    ///
    /// ПРИ ВКЛЮЧЁННОМ РЕВОЛЬВЕРЕ (<see cref="UseRevolver"/>) порядок считает
    /// <see cref="Revolver"/>: вес берётся кривой от состояния, а среди
    /// НЕсрочных дел вперёд пропускается то, что иначе созреет посреди начатого
    /// и оборвёт его. Жизненные и рефлексы он не переставляет, а ничью
    /// разбирает тем же полом — то есть на умолчаниях и без данных о состоянии
    /// список получается ровно тот же самый, что и здесь.
    /// </summary>
    public IReadOnlyList<BotBehavior> Ordered =>
        UseRevolver
            ? Plan().Order.Select(c => (BotBehavior)c.Of!).ToList()
            : ByWeight;

    /// <summary>
    /// СРОЧНОСТЬ СПОСОБНОСТИ С УЧЁТОМ ТОЙ НУЖДЫ, ЧЬИ ЭТО РУКИ.
    ///
    /// Одно место на обе раскладки — и на прежнюю (только вес), и на
    /// револьверную. Разойдись они, и «руки голода» слушались бы наследства
    /// лишь при включённой галочке, то есть у заказчика — никогда: галочка
    /// «ПланироватьНаперёд» стоит выключенной, и в его пресетах её нет вовсе.
    ///
    /// Правило само по себе — <see cref="BotBehavior.Serves"/>; здесь только
    /// сложение: своё против унаследованного, больше — то и берём.
    /// </summary>
    public double UrgencyOf(BotBehavior b, NeedNow now)
    {
        double own = b.WeightAt(now);
        if (b.Serves is not { } need)
            return own;
        var нужда = Behaviors.FirstOrDefault(x => need.IsInstanceOfType(x));
        if (нужда == null)
            return own;

        // НЕ ВИЖУ НУЖДЫ — НЕ НАСЛЕДУЮ, и это не осторожность, а тот же закон,
        // на котором стоит весь револьвер: без данных о состоянии поведение не
        // меняется НИ НА ВОЛОС. Кривая голода, не зная сытости, отвечает
        // «созрело в полную силу» — так задумано, чтобы незнание не гасило
        // саму нужду. Но НАСЛЕДОВАТЬ по такому ответу нельзя: вылазка за едой
        // получила бы срочность голода у бота, про которого мы даже не знаем,
        // голоден ли он. Стенд поймал это сразу: без данных вылазка прыгала
        // через возврат вещей и подбор своей добычи
        if (!нужда.Foresees(now))
            return own;
        // Потолок берём СВОЙ, а не у нужды: наследство не отменяет правила
        // «дело роли над жизненными не встаёт»
        return Math.Max(own, Math.Min(b.WeightCeiling, нужда.WeightAt(now)));
    }

    /// <summary>Прежний порядок: вес и наследство от своей нужды, ничего кроме.</summary>
    private IReadOnlyList<BotBehavior> ByWeight
    {
        get
        {
            var now = Now;
            return Behaviors.OrderByDescending(b => UrgencyOf(b, now))
                .ThenByDescending(b => b.WeightFloor)
                .ToList();
        }
    }

    // ------------------------------------------------------------------
    //  РЕВОЛЬВЕРНЫЙ ЦИКЛ
    // ------------------------------------------------------------------

    /// <summary>
    /// ВКЛЮЧИТЬ ПЛАНИРОВАНИЕ ВПЕРЁД. Выключено по умолчанию, и это не
    /// нерешительность, а цена вопроса: револьвер трогает сердце бота — то,
    /// чем он решает, что делать. Живьём он ещё не бегал ни минуты, а откат
    /// обязан быть в одну галочку. Выключенный, он не считает ничего и не
    /// стоит ни такта: <see cref="Ordered"/> идёт прежней дорогой.
    ///
    /// Что меняется, когда включён:
    /// • вес считается кривой от состояния (<see cref="NeedCurves"/>), а не
    ///   постоянным числом — но при настоящей потребности кривая даёт то же
    ///   самое число, что и раньше;
    /// • среди НЕсрочных дел вперёд пропускается то, что иначе созреет и
    ///   оборвёт начатое (<see cref="Revolver"/>), и пропущенному вперёд тут же
    ///   поднимается его собственный порог на ОДИН заход
    ///   (<see cref="NeedHurry"/>) — иначе бот пообещал бы «делаю сейчас» и не
    ///   сделал: у самой еды при сытости 55% порог не пройден;
    /// • жизненные и рефлексы не переставляются вовсе.
    ///
    /// ВКЛЮЧАЕТ ЭТО РОЛЬ, ручкой «ПланироватьНаперёд». Ручка была ровно у
    /// одного Копателя, и у Жителя, Продавца и ИИ откат «в одну галочку»
    /// существовал только на бумаге: включить или выключить планирование им
    /// было нечем — настройки просто не существовало.
    /// </summary>
    public bool UseRevolver { get; set; }

    /// <summary>
    /// Откуда брать состояние для кривых. Не задано — <see cref="NeedNow.Unknown"/>,
    /// и тогда все кривые отвечают «в полную силу», то есть бот ведёт себя как
    /// прежде. Обычно ставится один раз через <see cref="SenseFrom"/>.
    /// </summary>
    public Func<NeedNow>? Sense { get; set; }

    /// <summary>
    /// Снимать состояние с живого бота. Одна строка на всё подключение:
    /// <c>bot.Behaviors.SenseFrom(bot.Context)</c>.
    /// </summary>
    public NeedSense SenseFrom(BotContext ctx)
    {
        var sense = new NeedSense(ctx);
        Sense = sense.Read;
        return sense;
    }

    /// <summary>
    /// Состояние прямо сейчас. Упавший датчик не должен ронять бота: беда
    /// называется вслух один раз, а планирование честно откатывается к
    /// «ничего не знаю» — то есть к прежнему поведению.
    /// </summary>
    public NeedNow Now
    {
        get
        {
            if (Sense is not { } sense)
                return NeedNow.Unknown;
            try
            {
                return sense();
            }
            catch (Exception e)
            {
                if (senseBroken.Raise(e.Message))
                    OnLog?.Invoke($"[план] состояние снять не вышло: {e.Message} — " +
                                  "планирую как раньше, по постоянным весам");
                return NeedNow.Unknown;
            }
        }
    }

    private readonly Alarm senseBroken = new("состояние для планирования");

    /// <summary>
    /// Горизонт планирования, секунд: дальше него «созреет» не заглядываем.
    /// Пять минут — это дальний рейс на склад и обратно; заглядывать дальше
    /// бессмысленно, потому что за это время всё равно случится что-нибудь,
    /// чего мы не предвидели.
    ///
    /// НАСКОЛЬКО ДАЛЕКО ЗАГЛЯДЫВАТЬ — РЕШЕНИЕ РОЛИ, и она доносит его ручкой
    /// («ГоризонтПланированияСекунд»): у копателя один заход длится полчаса, и
    /// заглядывать ему стоит далеко, а продавцу за прилавком дальше минуты
    /// смотреть не на что — он никуда не уходит.
    /// </summary>
    public double HorizonSeconds { get; set; } = 300;

    /// <summary>
    /// ЧТО БОТ СОБИРАЕТСЯ ДЕЛАТЬ И ПОЧЕМУ. Это и показывают человеку — в
    /// панели (через <see cref="Report"/>) и в журнале.
    /// </summary>
    public PlanChoice Plan() => Plan(Now);

    /// <summary>
    /// То же по УЖЕ СНЯТОМУ состоянию. Тик снимает его один раз и передаёт
    /// сюда: второй вызов <see cref="Now"/> за тот же тик не только гоняет
    /// кривые впустую, но и кормит измеритель скоростей (<see cref="Drift"/>)
    /// одним и тем же показанием дважды.
    /// </summary>
    public PlanChoice Plan(NeedNow now)
    {
        var candidates = Behaviors
            .Select(b => new PlanCandidate(b.Title, UrgencyOf(b, now),
                NeedCurves.RipeIn(b.Ripeness, now, HorizonSeconds), EtaOf(b),
                b.WeightFloor, b.Foresees(now), b))
            .ToList();
        return Revolver.Order(candidates, BehaviorWeights.LifeFloor);
    }

    /// <summary>
    /// Что созреет за отпущенное время, ближайшее первым. Спрашивает очередь
    /// задач перед выходом из дома: «пока я буду в пути, что мне понадобится?»
    /// </summary>
    public IReadOnlyList<(BotBehavior Need, double In)> Ripening(double withinSeconds)
    {
        var now = Now;
        var found = new List<(BotBehavior, double)>();
        foreach (var b in Behaviors)
        {
            // Срок 0 — потребность УЖЕ настоящая: её незачем торопить, она и
            // так возьмёт своё первым же тиком. null — предвидеть нечем
            if (NeedCurves.RipeIn(b.Ripeness, now, withinSeconds) is { } at && at > 0)
                found.Add((b, at));
        }
        return found.OrderBy(f => f.Item2).ToList();
    }

    /// <summary>
    /// СКОЛЬКО ЗАЙМЁТ ЭТО ДЕЛО. Сперва спрашиваем само дело
    /// (<see cref="BotBehavior.SaysEta"/>), а если оно молчит — берём ЗАМЕР по
    /// его прошлым заходам: сколько секунд подряд оно держало ход. Замеров не
    /// было — null, и планировщик честно откажется планировать.
    ///
    /// Замер, а не число из головы: сколько длится обед, зависит от сервера,
    /// от еды и от того, свободна ли рука, — и это ровно то, что уже видно из
    /// прошлых заходов.
    /// </summary>
    public double? EtaOf(BotBehavior behavior)
    {
        if (behavior.SaysEta is { } said)
            return said;
        lock (spent)
        {
            if (!spent.TryGetValue(behavior.GetType(), out var runs) || runs.Count == 0)
                return null;
            var sorted = runs.OrderBy(s => s).ToList();
            return sorted[sorted.Count / 2];   // серединный заход, а не средний
        }
    }

    /// <summary>Сколько заходов замерено у этого вида дел (0 — ни одного).</summary>
    public int MeasuredRuns(BotBehavior behavior)
    {
        lock (spent)
            return spent.TryGetValue(behavior.GetType(), out var runs) ? runs.Count : 0;
    }

    /// <summary>Сколько последних заходов помним. Больше — дольше помним старое.</summary>
    public int RememberRuns { get; set; } = 5;

    private readonly Dictionary<Type, List<double>> spent = new();
    private BotBehavior? holding;
    private DateTime holdingSince;

    /// <summary>
    /// Записать, что ход перешёл к другому (или ни к кому). Ровно здесь и
    /// замеряется ETA: заход — это НЕПРЕРЫВНАЯ череда тиков одной способности.
    /// Отдельным методом, а не строкой в цикле, чтобы правило можно было
    /// проверить стендом без запуска цикла.
    /// </summary>
    public void TurnWentTo(BotBehavior? behavior, DateTime at)
    {
        if (ReferenceEquals(holding, behavior))
            return;
        if (holding is { } was)
        {
            double seconds = (at - holdingSince).TotalSeconds;
            if (seconds > 0)
                lock (spent)
                {
                    if (!spent.TryGetValue(was.GetType(), out var runs))
                        spent[was.GetType()] = runs = [];
                    runs.Add(seconds);
                    while (runs.Count > Math.Max(1, RememberRuns))
                        runs.RemoveAt(0);
                }
        }
        holding = behavior;
        holdingSince = at;
    }

    /// <summary>
    /// Поставить вес способности по её типу. Возвращает false, если такой
    /// способности у бота нет вовсе — молчаливое «настроил» тут недопустимо:
    /// человек повернул ручку и вправе знать, что она никуда не доехала.
    /// </summary>
    public bool SetWeight<T>(double weight) where T : BotBehavior
    {
        var found = Behaviors.OfType<T>().ToList();
        foreach (var b in found)
            b.Weight = weight;
        return found.Count > 0;
    }

    /// <summary>
    /// Поставить вес по названию (русскому из <see cref="BehaviorWeights"/> или
    /// имени типа), можно неполному. Возвращает, скольким способностям вес
    /// достался (0 — ни одной, и это повод сказать вслух).
    /// </summary>
    public int SetWeight(string name, double weight)
    {
        int done = 0;
        foreach (var b in Match(name))
        {
            b.Weight = weight;
            done++;
        }
        return done;
    }

    private IEnumerable<BotBehavior> Match(string name)
    {
        string want = name.Trim();
        if (want.Length == 0)
            return [];
        // Сперва точное совпадение: «еда» не должна цеплять «сбор еды»,
        // если такое название есть само по себе
        var exact = Behaviors.Where(b =>
            string.Equals(b.Title, want, StringComparison.OrdinalIgnoreCase) ||
            string.Equals(b.GetType().Name, want, StringComparison.OrdinalIgnoreCase)).ToList();
        if (exact.Count > 0)
            return exact;
        return Behaviors.Where(b =>
            b.Title.Contains(want, StringComparison.OrdinalIgnoreCase) ||
            b.GetType().Name.Contains(want, StringComparison.OrdinalIgnoreCase)).ToList();
    }

    /// <summary>
    /// Повернуть веса одной строкой из панели или пресета: «еда 95; бой 70».
    /// Возвращает отчёт для журнала — и про то, что применилось, и про то, что
    /// не понято или никуда не доехало.
    ///
    /// СТРОКА ЗАДАЁТ ВЕСА ЦЕЛИКОМ: всё, что в ней не названо, возвращается к
    /// значению по умолчанию. Иначе выходило бы вот что — человек стёр из
    /// панели строчку «бой 10», нажал сохранить, а бой так и остался
    /// десятым до перезапуска. Настройки доносятся до механизмов целиком и на
    /// каждый поворот ручки, и этот метод обязан быть таким же: сколько раз ни
    /// позови с той же строкой, итог один.
    /// </summary>
    public string ApplyWeights(string? text)
    {
        foreach (var b in Behaviors)
            b.ResetWeight();
        var wanted = BehaviorWeights.Parse(text, out var problems);
        var done = new List<string>();
        foreach (var (name, weight) in wanted)
        {
            var hit = Match(name).ToList();
            if (hit.Count == 0)
            {
                problems.Add($"«{name}» — такой способности у бота нет");
                continue;
            }
            foreach (var b in hit)
            {
                b.Weight = weight;
                done.Add($"{b.Title} {b.Weight:0.#}");
                // ПОЛ НАЗЫВАЕТСЯ ВСЛУХ. Человек поставил еде вес 5, получил 60
                // и должен узнать об этом здесь, а не гадать, почему бот
                // всё равно бросает работу и ест
                if (weight < b.WeightFloor)
                    problems.Add($"«{b.Title}» ниже {b.WeightFloor:0.#} не опускается " +
                                 $"(просили {weight:0.#}) — иначе бот умрёт с едой в кармане");
                // ПОТОЛОК — ТОЖЕ ВСЛУХ. «без дела 99» раньше принималось молча,
                // и безделье вставало выше еды, лечения и боя: обход доходил до
                // него первым, оно уходило гулять и возвращало true. То же самое
                // приёмка нашла и у «ухода от нестабильности 99» — потолка у
                // неудобств не было вовсе, хотя заказчику он был назван
                if (weight > b.WeightCeiling)
                    problems.Add($"«{b.Title}» выше {b.WeightCeiling:0.#} не поднимается " +
                                 $"(просили {weight:0.#}) — иначе " +
                                 (b.WeightCeiling >= BehaviorWeights.Food
                                     ? "бот бросал бы ради этого еду и лечение"
                                     : "работа встанет над едой и лечением"));
            }
        }

        return (done.Count > 0 ? "веса: " + string.Join(", ", done) : "веса не менялись") +
               (problems.Count > 0 ? "; не понял: " + string.Join("; ", problems) : "");
    }

    /// <summary>
    /// Кто над кем — одной строкой для журнала и окна управления. Пол и потолок
    /// называются прямо, чтобы «почему еда не опускается» и «почему безделье не
    /// поднимается» не пришлось искать в исходниках.
    /// </summary>
    public string Report()
    {
        if (Behaviors.Count == 0)
            return "способностей нет";
        // План считается ОДИН раз: он же задаёт порядок, он же идёт в строку.
        // Спросить его дважды значило бы не только гонять кривые впустую, но и
        // скормить измерителю скоростей (Drift) одно показание за два
        var plan = UseRevolver ? Plan(Now) : null;
        var order = plan is null
            ? ByWeight
            : plan.Order.Select(c => (BotBehavior)c.Of!).ToList();
        return string.Join("; ", order.Select(b =>
                   $"{b.Title} {b.Weight:0.#}" +
                   (b.WeightFloor > 0 ? $" (пол {b.WeightFloor:0.#})" : "") +
                   (double.IsFinite(b.WeightCeiling) ? $" (потолок {b.WeightCeiling:0.#})" : ""))) +
               (plan is null ? "" : $". Ближайшее: {plan}");
    }

    /// <summary>Интервал тика, мс.</summary>
    public int TickMs { get; set; } = 400;

    /// <summary>Ошибки способностей (сами тики от них защищены).</summary>
    public event Action<BotBehavior, Exception>? OnBehaviorError;

    /// <summary>
    /// Что происходит с планированием — словами, в общий журнал бота.
    /// Заказчик просил видеть, «что и когда сделает бот»; молчаливый
    /// планировщик со стороны неотличим от сломанного.
    /// </summary>
    public event Action<string>? OnLog;

    /// <summary>
    /// План говорится ГРОМКО ОДИН РАЗ. Способности тикают дважды в секунду, и
    /// строка «делаю то-то, потому что то-то» без этой заглушки дала бы сотню
    /// одинаковых строк в минуту — тот самый шум, за которым однажды не
    /// увидели настоящей беды.
    /// </summary>
    private readonly Alarm planSaid = new("план");

    /// <summary>
    /// То же и про подталкивание пропущенного вперёд: и удача, и отказ
    /// говорятся один раз на причину, а не дважды в секунду.
    /// </summary>
    private readonly Alarm aheadSaid = new("вперёд очереди");

    /// <summary>
    /// ПРОПУЩЕННОЕ ВПЕРЁД НАДО ЕЩЁ И СДЕЛАТЬ ВОЗМОЖНЫМ. Дело, которое
    /// планировщик поднял в голову очереди (<see cref="PlanChoice.Ahead"/>), по
    /// определению ЕЩЁ НЕ СОЗРЕЛО: у еды свой порог (сытость ниже 40%), и при
    /// 55% она честно откажется работать. Один только новый порядок обхода для
    /// неё пустой звук — бот сказал бы «делаю еду сейчас» и не поел.
    ///
    /// Поэтому порог поднимается ровно НА ОДИН ЗАХОД и возвращается ВСЕГДА, тем
    /// же самым <see cref="NeedHurry"/>, которым это делает очередь задач перед
    /// выходом (Jobs.cs). Второго такого механизма здесь нарочно нет: забытый
    /// порог «есть при 95%» сделал бы из бота обжору навсегда, и чинить это
    /// пришлось бы в двух местах.
    ///
    /// Возвращает то, что ОБЯЗАНО быть вызвано после обхода.
    /// </summary>
    private Action Hurry(PlanChoice plan, NeedNow now)
    {
        if (plan.Ahead?.Of is not BotBehavior need)
        {
            aheadSaid.Clear();
            return static () => { };
        }
        // Торопить умеем не всех (лечиться заранее — бинт на царапину,
        // греться заранее — костёр и остановка всех дел). Молчать об этом
        // нельзя: человек должен знать, что бот ЗНАЛ про помеху и не убрал её
        if (!NeedHurry.Prepare(need, now, out string what, out var undo))
        {
            if (aheadSaid.Raise($"{need.Title}: {what}"))
                OnLog?.Invoke($"[план] «{need.Title}» стоило бы сделать заранее, но {what} " +
                              "— жду, пока она возьмёт своё сама");
            return static () => { };
        }
        if (aheadSaid.Raise($"{need.Title}: {what}"))
            OnLog?.Invoke($"[план] «{need.Title}» делаю заранее, не дожидаясь её срока; {what}");
        return undo;
    }

    /// <summary>
    /// Когда цикл тикал в последний раз. ПУЛЬС: если способности молчат,
    /// первым делом надо знать — они не сработали или не тикали вовсе.
    /// Живьём мы этого не различали и три минуты гадали, почему бот не ест.
    /// </summary>
    public DateTime? LastTick { get; private set; }

    /// <summary>Сколько раз цикл прошёл по списку.</summary>
    public long Ticks { get; private set; }

    /// <summary>Кто взял ход последним и когда.</summary>
    public (string Who, DateTime When)? LastActed { get; private set; }

    /// <summary>
    /// КАЖДЫЙ ЗАХОД ЦИКЛА — наружу. Здесь бьётся пульс (<see cref="Heartbeat"/>):
    /// сторожу молчания нужны РОВНЫЕ удары, а своего таймера у него нет, и
    /// заводить второй цикл рядом с этим — это вторая копия одной механики.
    /// Никто не подписался — цикл работает как прежде.
    /// </summary>
    public event Action? OnTick;

    public async Task StartAsync(CancellationToken ct = default)
    {
        while (!ct.IsCancellationRequested)
        {
            // Обход по СНИМКУ. Список способностей меняют на ходу (роль,
            // команда в чате), а перебор изменённой коллекции роняет
            // исключение ВНЕ try — и цикл умирает целиком, вместе с едой,
            // лечением и самообороной, молча и навсегда.
            //
            // Снимок заодно и УПОРЯДОЧЕН: порядок задаёт вес важности, а не
            // место в списке. Сортировка устойчива, поэтому равные по весу
            // идут в порядке подключения — как было всегда
            LastTick = DateTime.UtcNow;
            Ticks++;
            // ПЛАН ВСЛУХ. Молчать нельзя: заказчик просил видеть, что и когда
            // бот собирается делать, а молчаливый планировщик со стороны
            // неотличим от сломанного
            IReadOnlyList<BotBehavior> order;
            // Порог, поднятый на ОДИН заход ради пропущенного вперёд дела.
            // Возврат обязан случиться и на отказе, и на исключении, и на
            // отмене — поэтому он живёт в finally, а не строкой после обхода
            var undoHurry = static () => { };
            if (UseRevolver)
            {
                // План считается ОДИН раз на тик и тут же служит порядком
                // обхода: спрашивать его дважды (сперва для порядка, потом
                // для строчки в журнале) значило бы гонять кривые впустую
                var now = Now;
                var plan = Plan(now);
                order = plan.Order.Select(c => (BotBehavior)c.Of!).ToList();
                // СТОРОЖУ — УСТОЙЧИВЫЙ ПОВОД, ЧЕЛОВЕКУ — СТРОКА С ЧИСЛАМИ.
                // Раньше сюда уходила сама строка, а в ней дрожат вес и
                // секунды: при тике в 400 мс это две с половиной строки в
                // секунду, каждая отличается последней цифрой (см. PlanChoice.Key)
                if (planSaid.Raise(plan.Key))
                    OnLog?.Invoke($"[план] {plan}");
                undoHurry = Hurry(plan, now);
            }
            else
            {
                order = ByWeight;
            }
            BotBehavior? took = null;
            try
            {
                foreach (var behavior in order)
                {
                    bool acted;
                    try
                    {
                        acted = await behavior.TickAsync(ct);
                    }
                    catch (OperationCanceledException) when (ct.IsCancellationRequested)
                    {
                        return;
                    }
                    catch (Exception ex)
                    {
                        OnBehaviorError?.Invoke(behavior, ex);
                        acted = false;
                    }
                    if (acted)
                    {
                        LastActed = (behavior.GetType().Name, DateTime.UtcNow);
                        took = behavior;
                        break;
                    }
                }
            }
            finally
            {
                undoHurry();
            }
            // СКОЛЬКО ЭТО ЗАНИМАЕТ — ЗАМЕРЯЕМ ЗДЕСЬ, а не выдумываем в таблице.
            // Заход это непрерывная череда тиков одной способности: пока ход
            // держит она, идёт один заход; перешёл ход к другому или к никому
            // — заход кончился, и его длина уходит в память сроков
            TurnWentTo(took, DateTime.UtcNow);
            // СТОРОЖ МОЛЧАНИЯ БЬЁТСЯ ЗДЕСЬ, и падать ему нельзя: цикл
            // способностей — это еда, лечение и самооборона, и уронить их
            // из-за сторожа журнала было бы обменом плохим
            try { OnTick?.Invoke(); }
            catch (Exception ex) { OnLog?.Invoke($"пульс не вышел: {ex.Message}"); }
            await Task.Delay(TickMs, ct);
        }
    }
}
