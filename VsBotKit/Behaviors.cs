    /// <summary>
    /// ПОРОГИ ВАЖНОСТИ — ТЕ ЖЕ КОНСТАНТЫ, ТОЛЬКО НАЗВАННЫЕ ЧЕЛОВЕКУ.
    ///
    /// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЗАВЕДЕНО. Заказчик 16.08: «неудобно выставлять
