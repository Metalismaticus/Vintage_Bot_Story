    /// <summary>Вес способности по умолчанию (незнакомая считается делом роли).</summary>
    public static double DefaultOf(BotBehavior behavior) => DefaultOf(behavior.GetType());

    /// <summary>То же по типу.</summary>
    public static double DefaultOf(Type type) => Defaults.GetValueOrDefault(type, Work);

    /// <summary>Ниже какого веса эту способность опускать нельзя (0 — можно до нуля).</summary>
    public static double FloorOf(BotBehavior behavior) => FloorOf(behavior.GetType());

    /// <summary>То же по типу.</summary>
    public static double FloorOf(Type type) => Floors.GetValueOrDefault(type, 0);

    /// <summary>Выше какого веса эту способность поднимать нельзя (∞ — можно куда угодно).</summary>
    public static double CeilingOf(BotBehavior behavior) => CeilingOf(behavior.GetType());

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО ПОТОЛКА: кто по умолчанию стоит НИЖЕ жизненных, тот над
    /// ними и не встанет. Ступени ровно две:
    /// • дело роли (умолчание ниже <see cref="LifeFloor"/> — работа, хозяйство,
    ///   приличия, безделье) выше пола жизненных не поднимается;
    /// • неудобство (умолчание между полом жизненных и едой — холод, уход от
    ///   нестабильности) поднимается не выше самой еды (<see cref="Food"/>).
    ///
    /// ВТОРАЯ СТУПЕНЬ ПОЯВИЛАСЬ ПО НАХОДКЕ ПРИЁМКИ, и это была ложь заказчику:
    /// отчёт обещал, что «уход от нестабильности» (умолчание <see cref="Comfort"/>
    /// = 75) не встанет над едой и боем, а правило смотрело только на пол
    /// жизненных — 75 не ниже 60, значит потолок выходил бесконечным, и строка
    /// «уход от нестабильности 99» принималась МОЛЧА, ставя побег от
    /// нестабильности выше еды (80), лечения (85) и боя (90). Живьём это ровно
    /// та же смерть с хлебом в кармане: пока способность уходит наверх, она
    /// держит ход, а голод в этот тик не тикает. Временной урон при этом
    /// начинается лишь ниже 0,13 стабильности и снимает 0,15 − стабильность раз
    /// в четыре секунды — он медленнее и голода, и дрифтера.
    ///
    /// Потолок берётся из умолчания, а не из списка имён, нарочно: список
    /// однажды забыли бы пополнить, и НОВАЯ способность (роли или библиотеки)
    /// снова получила бы право встать над едой. Незнакомая способность считается
    /// делом роли (<see cref="Work"/> = 50), то есть работой, — и потолок ей
    /// достаётся сам собой.
    ///
    /// РАВНЫЙ ВЕС — НЕ ОБХОД ПОТОЛКА: при ничьей вперёд идёт тот, у кого есть
    /// пол жизненных (<see cref="BehaviorRunner.Ordered"/>), то есть еда, лечение
    /// и возрождение. Поэтому «тепло 80» ставит холод вплотную к еде, но НЕ
    /// впереди неё.
    ///
    /// У жизненных (еда, лечение, возрождение) и у спасательных (не висеть в
    /// воздухе, бой, буря, сон) потолка НЕТ: их порядок между собой человек
    /// вправе менять — живой игрок посреди драки тоже не садится обедать.
    /// </summary>
    public static double CeilingOf(Type type)
    {
        double def = DefaultOf(type);
        if (def >= Food)
            return double.PositiveInfinity;
        return def < LifeFloor ? LifeFloor : Food;
    }

    /// <summary>Название способности по-русски.</summary>
    public static string NameOf(BotBehavior behavior)
    {
        // ТАБЛИЦА ПЕРВОЙ — иначе у знакомой способности молча сменилось бы имя,
        // а имя тут не украшение: им человек двигает вес в строке
        // «ВесаВажности», и им же названы сохранённые настройки.
        //
        // ОДИН ТИП — МНОГО СПОСОБНОСТЕЙ, и это не выдумка: BehaviorMeetNeed
        // заводится по одной штуке на КАЖДУЮ нужду (еда, лечебное, тепло), а
        // таблица ключуется типом. Второй бланк, заполненный по инструкции из
        // шапки того класса, показался бы человеку латинским «MeetNeed» — и
        // двум разным нуждам одним и тем же словом. Поэтому у способности
        // спрашивается её собственное имя
        if (Names.TryGetValue(behavior.GetType(), out string? known))
            return known;
        return behavior.SelfName is { Length: > 0 } own ? own : NameOf(behavior.GetType());
    }

    /// <summary>То же по типу.</summary>
    public static string NameOf(Type type)
    {
        if (Names.TryGetValue(type, out string? name))
            return name;
        string plain = type.Name;
        return plain.StartsWith("Behavior", StringComparison.Ordinal) && plain.Length > 8
            ? plain[8..]
            : plain;
    }

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: разобрать человеческий список весов.
    ///
    /// Человек пишет в панели одной строкой: «еда 95; бой 70; без дела 0» —
    /// разделители любые из «,;» и перевода строки, между именем и числом
    /// пробел или «=». Имя может быть неполным («без дел» найдёт «без дела»).
    ///
    /// Ни мира, ни бота здесь нет — только строка, поэтому правило проверяется
    /// стендом. Непонятое НЕ выбрасывается молча: оно возвращается жалобами,
    /// иначе опечатка в панели выглядит как «настройка не работает».
    /// </summary>
    public static IReadOnlyList<(string Name, double Weight)> Parse(
        string? text, out List<string> problems)
    {
        problems = [];
        var found = new List<(string, double)>();
        if (string.IsNullOrWhiteSpace(text))
            return found;

        foreach (string piece in text.Split([',', ';', '\n', '\r'],
                     StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            // Имя и число разделены «=» или последним пробелом: «без дела 0»
            int cut = piece.LastIndexOf('=');
            if (cut < 0)
                cut = piece.LastIndexOf(' ');
            if (cut <= 0)
            {
                problems.Add($"«{piece}» — не понял: надо «название число», например «еда 95»");
                continue;
            }
            string name = piece[..cut].Trim();
            string number = piece[(cut + 1)..].Trim();
            if (name.Length == 0)
            {
                problems.Add($"«{piece}» — не сказано, чему менять вес");
                continue;
            }
            if (!double.TryParse(number, System.Globalization.NumberStyles.Float,
                    System.Globalization.CultureInfo.InvariantCulture, out double weight) &&
                !double.TryParse(number, System.Globalization.NumberStyles.Float,
                    System.Globalization.CultureInfo.CurrentCulture, out weight))
            {
                problems.Add($"«{piece}» — «{number}» не число");
                continue;
            }
            found.Add((name, weight));
        }
        return found;
    }
}

