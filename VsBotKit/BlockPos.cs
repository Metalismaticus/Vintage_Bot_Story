namespace VsBotKit;

/// <summary>
/// Позиция блока в мировых координатах.
///
/// Живёт отдельным файлом, а не внутри модели мира, потому что нужна и там,
/// где никакой сетевой модели нет: в поиске пути и в клиентском МОДЕ. Всё,
/// что переезжает в мод, должно быть отделимо — иначе за одной строчкой
/// тянется тысяча триста строк разбора пакетов.
/// </summary>
public readonly record struct BlockPos(int X, int Y, int Z)
{
    /// <summary>
    /// КЛЕТКА СЛОВАМИ — ВСЕГДА ИГРОВАЯ, как её показывает игра человеку.
    ///
    /// Внутри бота X и Z остаются мировыми (около полумиллиона) — считает он
    /// как считал. Переводится только ВЫХОД, и он здесь: в журнал, в чат и в
    /// окно управления клетка попадает через это самое ToString сотнями строк
    /// («упёрся на точке 3/6 …», «маршрут до клетки: 38 точек …», «иду домой
    /// (…)»). Подать сдвиг аргументом в каждую из них нельзя, а забыть его
    /// хоть в одной — значит вернуть заказчику ровно ту жалобу, с которой всё
    /// началось: адрес, которого нет у него на экране.
    ///
    /// Само правило и то, откуда игра берёт начало отсчёта, — в
    /// <see cref="WorldOrigin"/>. Второй копии перевода нет.
    /// </summary>
    public override string ToString() => WorldOrigin.Say(X, Y, Z);
}
