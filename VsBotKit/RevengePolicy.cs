using System.Text.Json.Serialization;

namespace VsBotKit;

/// <summary>
/// Как бот отвечает тому, кто его ударил и держится поодаль.
///
/// Появилось из живого случая: боуторны обстреливали бота, а он только надевал
/// броню и стоял — обидчик был вне радиуса ответа, значит «врагов рядом нет».
/// Кому мстить, решает роль: торговцу отходить от прилавка незачем, охотнику
/// наоборот, а сторожу важно вернуться на пост.
///
/// ИМЕНА ЗДЕСЬ РУССКИЕ И В СТРОКУ — по тому же правилу, что и у
/// <see cref="IdleAction"/>, и по той же причине. С появлением ручки «Мстить»
/// это перечисление человек ВИДИТ И НАБИРАЕТ в окне управления: панель
/// показывает «выбор» обычным полем и отправляет написанное как есть, а
/// <c>RoleKnobs</c> разбирает его через Enum.Parse. Оставь имена
/// английскими — и в русском окне пришлось бы вслепую набирать «Chase»; не
/// навесь преобразователь — панель показала бы номер («2»), и этот же номер
/// лёг бы в сохранённый пресет, из которого через полгода не понять ничего.
/// </summary>
[JsonConverter(typeof(JsonStringEnumConverter))]
public enum RevengePolicy
{
    /// <summary>Не мстить вовсе: только отбиваться от того, кто подошёл вплотную.</summary>
    Никогда,

    /// <summary>Ответить, если обидчик в пределах RevengeRadius, но не гнаться.</summary>
    Рядом,

    /// <summary>Догнать и наказать — в пределах радиуса и отпущенного времени.</summary>
    Догонять
}
