    /// <summary>
    /// СКОЛЬКО ИГРОВЫХ ЧАСОВ ТУШЕ ОСТАЛОСЬ ЛЕЖАТЬ. null — не знаем, и врать
    /// числом тут нельзя: на этом сроке стоит решение бросать ли работу.
    ///
    /// СЧИТАЕТСЯ РОВНО ТАК ЖЕ, КАК СЧИТАЕТ СЕРВЕР (EntityBehaviorDeadDecay.
    /// OnGameTick: <c>TotalHoursDead + HoursToDecay &lt; Calendar.TotalHours</c>),
    /// и обе половины взяты у игры, а не у нас:
    /// <list type="bullet">
    /// <item>КОГДА УМЕРЛА — от сервера, <c>WatchedAttributes["decay"]["totalHoursDead"]</c>,
    /// НО ТОЛЬКО ЕСЛИ ЭТО ПРАВДА ЧАС СМЕРТИ. В том же поле игра держит час
    /// РОЖДЕНИЯ (<c>EntityBehaviorDeadDecay.Initialize</c>), и переписанный на
    /// смерти он по сети не едет: запись идёт во ВЛОЖЕННОЕ простое дерево, а
    /// грязным метит только верхний <c>SyncedTreeAttribute</c>. Разбор и
    /// правило — в <see cref="EntityInfo.WasDeadWhenFullDataCame"/>. Живой
    /// случай: бот сам убил дрифтера, которого видел живым, и говорил про
    /// свежую тушу «сгниёт вот-вот», вычитая возраст твари вместо лежания;</item>
    /// <item>СКОЛЬКО ОТВЕДЕНО — с диска, из описания сущности: серверную
    /// половину описания сервер не шлёт вовсе (разбор — в <see cref="CarcassDecay"/>).</item>
    /// </list>
    ///
    /// Число может выйти ОТРИЦАТЕЛЬНЫМ, и затирать это нулём нельзя: значит
    /// срок вышел, а сервер ещё не дошёл до неё тиком. «Вот-вот» и «полчаса» —
    /// разные вести.
    /// </summary>
    public double? ЧасовДоРаспада(EntityInfo e)
    {
        if (Decay.HoursToDecay(e.Code) is not { } отведено)
            return null;
        if (e.WatchedAttributes.GetTreeAttribute("decay") is not { } дерево ||
            !дерево.HasAttribute("totalHoursDead"))
            return null;
        // ПОЛЕ ЕСТЬ — ЭТОГО МАЛО. Пришло оно по живой твари — там час РОЖДЕНИЯ,
        // и «не знаю» тут честнее числа: на этом сроке стоит решение бросать ли
        // работу, а прожившая три игровых часа тварь давала бы отрицательное
        // «сгниёт вот-вот» про тушу, ещё тёплую
        if (!e.WasDeadWhenFullDataCame)
            return null;
        if (ctx.Clock is not { Ready: true } часы)
            return null;
        return отведено - (часы.TotalHours - дерево.GetDouble("totalHoursDead"));
    }

    /// <summary>
    /// ТО ЖЕ, НО В РЕАЛЬНЫХ МИНУТАХ — в них живёт человек, и в них же меряются
    /// все паузы бота. Перевод спрашивается у часов
    /// (<see cref="GameClock.RealSecondsPerGameHour"/>), своей формулы тут нет:
    /// на ускоренном сервере игровой час — это полминуты, и вторая копия
    /// пересчёта разъехалась бы с первой молча.
    /// </summary>
    public double? МинутДоРаспада(EntityInfo e) =>
        ЧасовДоРаспада(e) is { } часов && ctx.Clock?.RealSecondsPerGameHour is { } всекунд
            ? часов * всекунд / 60.0
            : null;

    /// <summary>
    /// СРОК ТУШИ ЧЕЛОВЕЧЕСКИМИ СЛОВАМИ — и отдельной строкой нарочно, потому
    /// что её читает не программа, а хозяин бота: это она объясняет ему, зачем
    /// бот бросил карьер.
    ///
    /// НЕЗНАНИЕ НАЗЫВАЕТСЯ, А НЕ ПРЯЧЕТСЯ (закон 4). Молчаливое «через 0 мин»
    /// или бодрое «успею» на неизвестном сроке — это то самое враньё, за
    /// которым не видно настоящей беды: у мода или чужого сервера описания
    /// может не быть вовсе, и честнее сказать это, чем подставить число.
    /// </summary>
    public string СрокТуши(EntityInfo e)
    {
        if (МинутДоРаспада(e) is { } минут)
            return минут <= 0
                ? $"туша {e.Code} сгниёт вот-вот — вместе со всем, что в ней"
                : $"туша {e.Code} сгниёт через {минут:0.#} мин вместе с добычей";
        // ПЕРВАЯ ПРИЧИНА НАЗЫВАЕТСЯ ОТДЕЛЬНО, потому что она самая частая и
        // самая обидная: тварь мы видели живой, значит часа смерти у нас нет
        // вовсе — сервер его не шлёт. Валить это в общее «мод или чужой
        // сервер» значило бы послать человека искать беду не там
        if (Decay.HoursToDecay(e.Code) is not null && !e.WasDeadWhenFullDataCame)
            return $"сколько пролежит туша {e.Code}, не знаю: я застал её ЖИВОЙ, " +
                   "а час смерти сервер не пересылает — в этом поле у него лежит " +
                   "час рождения. Срок будет виден, если подойти к уже мёртвой";
        // Прочих причин три, и они разные: ассетов не нашлось вовсе (о том
        // скажет сам механизм), у этой твари нет распада тела, либо кода нет в
        // описаниях игры — мод или чужой сервер. Какая именно, мы отсюда не
        // видим, и выбирать одну наугад значит врать
        string почему = Decay.Why is { Length: > 0 } беда
            ? беда
            : "в описаниях игры у него либо нет распада тела (deaddecay), либо нет " +
              "самого кода — это мод или чужой сервер";
        return $"сколько пролежит туша {e.Code}, не знаю: {почему}";
    }

    /// <summary>
    /// Сколько держать нож. Скорость ножа берётся из игры так же, как её берёт
    /// ItemKnife.GetKnifeHarvestingSpeed: из его скорости добычи по растениям
    /// (<see cref="HarvestSpeedMaterial"/> — там же разобрано, почему именно
    /// по ним, а не «по коже», как тут было написано до 27.08).
    /// </summary>
    public double HarvestSeconds(string? knifeCode)
    {
        float speed = ctx.World.MiningSpeed(knifeCode, HarvestSpeedMaterial);
        double factor = 1.0 / ((Math.Max(speed, 1f) - 1f) * 0.5 + 1.0);
        return factor * BaseHarvestSeconds + ExtraHoldSeconds;
    }

    /// <summary>Подойти к сущности на расстояние руки.</summary>
    private async Task<bool> ApproachAsync(EntityInfo target, CancellationToken ct)
    {
        if (hands.DistanceToPoint(target.X, target.Y + 0.5, target.Z) <= hands.Reach)
            return true;
        await ctx.Movement.ApproachAsync(() =>
        {
            var live = ctx.Entities.Get(target.Id);
            return (live?.X ?? target.X, live?.Y ?? target.Y, live?.Z ?? target.Z);
        }, stopDistance: 1.5, maxSeconds: 30, ct: ct);
        bool close = hands.DistanceToPoint(target.X, target.Y + 0.5, target.Z) <= hands.Reach;
        if (!close)
            OnLog?.Invoke($"до туши {target.Code} не дойти");
        return close;
    }

    /// <summary>
    /// Разделать тушу ножом. Успех — только по флагу «harvested» от сервера,
    /// а не по факту «подержали кнопку».
    /// </summary>
    public async Task<bool> HarvestAsync(long entityId, CancellationToken ct = default)
    {
        if (ctx.Entities.Get(entityId) is not { } target)
        {
            // Туша могла и ПРОПАСТЬ, пока мы шли: у дрифтера на распад отведено
            // три игровых часа (deaddecay, hoursToDecay: 3), и вместе с телом
            // пропадает всё, что в нём лежало, — на землю оно не выпадает
            OnLog?.Invoke($"туши {entityId} не вижу — либо пропала, либо ушла из виду");
            return false;
        }
        if (IsHarvested(target))
            return true;
        if (!IsCarcass(target))
        {
            OnLog?.Invoke($"{target.Code} ещё жив — разделывать нечего");
            return false;
        }
        if (!CanBeButchered(target))
        {
            OnLog?.Invoke($"{target.Code} не разделывают — что с него причиталось, " +
                          "выпало на землю (это подбор, а не разделка)");
            return false;
        }
        // ИЩЕМ В СУМКАХ ТЕМ ЖЕ ВОПРОСОМ, каким отвечает <see cref="HasKnife"/>.
        // Пока взятие искало подстроку «knife», оно первым же делом хватало
        // лежащее в хотбаре ЛЕЗВИЕ (knifeblade-*) — а настоящий нож мог
        // спокойно лежать слотом дальше: <c>PutIntoHandAsync</c> берёт ПЕРВОЕ
        // подошедшее, и «подошедшим» лезвие было по букве, а не по делу
        if (await hands.TakeToHandAsync(s => IsKnife(s.Code), ct) is null)
        {
            OnLog?.Invoke(НечемРезать());
            return false;
        }
        if (!await ApproachAsync(target, ct))
            return false;

        // ЧТО В РУКЕ НА САМОМ ДЕЛЕ. Взять предмет и держать его — разные вещи:
        // пока бот шёл к туше, рефлексы могли переложить хотбар (живьём он
        // пришёл резать с горстью клюквы). Режем только если в руке правда нож
        string? inHand = hands.Held?.Code;
        if (!IsKnife(inHand))
        {
            if (await hands.TakeToHandAsync(s => IsKnife(s.Code), ct) is null ||
                !IsKnife(hands.Held?.Code))
            {
                OnLog?.Invoke($"в руке {inHand ?? "пусто"}, а это не нож — резать нечем");
                return false;
            }
            inHand = hands.Held?.Code;
        }

        double seconds = HarvestSeconds(inHand);
        OnLog?.Invoke($"разделываю {target.Code}: {seconds:0.#} с ножом {inHand}");
        if (!await hands.UseHeldOnEntityAsync(entityId, seconds, sneak: true, ct: ct))
            return false;
        await Task.Delay(600, ct).ContinueWith(_ => { });

        bool done = ctx.Entities.Get(entityId) is { } after && IsHarvested(after);
        OnLog?.Invoke(done ? $"разделал {target.Code}" : $"{target.Code} разделать не вышло");
        return done;
    }

    /// <summary>
    /// Забрать добычу из разделанной туши: клик по ней открывает её содержимое
    /// (EntityBehaviorHarvestable.OnInteract сам зовёт OpenInventory), дальше
    /// обычный перенос. Возвращает, сколько стопок забрал.
    /// </summary>
    public async Task<int> LootAsync(long entityId, CancellationToken ct = default)
    {
        if (ctx.Entities.Get(entityId) is not { } target)
            return 0;
        if (!IsHarvested(target))
        {
            OnLog?.Invoke($"{target.Code} ещё не разделан — забирать нечего");
            return 0;
        }

        // Дальше — общий слой хранилищ: «забрать всё» написано один раз
        // и для сундука, и для костра, и для туши (см. Containers)
        var box = Container.Carcass(ctx, hands, entityId);
        box.OnLog += m => OnLog?.Invoke(m);
        return await box.TakeAllAsync(ct: ct);
    }

    /// <summary>
    /// ТУША УЛЕГЛАСЬ ИЛИ НЕТ — СПРАШИВАЕМ У СЕРВЕРА, А НЕ У СЕБЯ.
    ///
    /// ЗАЧЕМ ЭТО ЕСТЬ ВООБЩЕ. Закрытие окна мы шлём, но «отправил пакет» и
    /// «туша пропала» — разные вещи, а разницу между ними заказчик 20.08
    /// увидел раньше нас: «после разделки бота никто не исчезает». Пока успех
    /// не проверяется, о такой поломке снова узнает человек, а не журнал
    /// (правило 4: успех — только по факту от сервера).
    ///
    /// ПРОПАЖА СУЩНОСТИ И ЕСТЬ ФАКТ. Сервер, убрав тушу, шлёт пакет о пропаже,
    /// и мир бота забывает её — то же самое видит настоящий клиент.
    ///
    /// Четыре случая, когда проверять нечего, и они не отказ:
    /// в туше ещё что-то лежит (пустую и только пустую убирает
    /// <c>Inv_OnInventoryClosed</c>); до туши не дошли — тогда мы и не
    /// открывали её, а причину назвал тот, кто не дошёл; туши уже нет;
    /// и ОБХОД ПЕРЕБИЛИ — разбор ниже, у самой отмены.
    /// </summary>
    private async Task<bool> УлеглаAsync(EntityInfo carcass, CancellationToken ct)
    {
        if (ctx.Entities.Get(carcass.Id) is not { } живая)
            return true;
        if (HasLoot(живая))
            return true;
        if (hands.DistanceToPoint(живая.X, живая.Y + 0.5, живая.Z) > hands.Reach)
            return true;

        for (int ждём = 0; ждём < DecayWaitMs; ждём += 100)
        {
            if (ctx.Entities.Get(carcass.Id) is null)
                return true;

            // ОБХОД ПЕРЕБИЛИ — ЭТО НЕ ПРИГОВОР ТУШЕ, А КОНЕЦ НАШЕГО ХОДА.
            //
            // Ниже туша заносится в <see cref="упрямые"/> НАВСЕГДА, и держится
            // это на одном основании: «мы честно отждали срок, а она не
            // пропала». Отмена ломает ровно это основание — ждать перестали мы
            // сами, потому что тело понадобилось бою, еде или лечению
            // (BodyArbiter.Hold.Token гаснет при перехвате). Считать сорванный
            // обход доказательством «у этого зверя нет распада тела» — то же
            // враньё себе, что и «отправил пакет, значит прибрал», только с
            // другого конца: там успех без факта, здесь приговор без факта.
            //
            // И цена выше: после приговора бот не вернётся к туше НИКОГДА, а
            // копятся незакрытые туши как раз от СОРВАННЫХ обходов — тот самый
            // случай, ради которого третий список и заведён. Причину ухода
            // назвал тот, кто перебил; нам добавить нечего
            if (ct.IsCancellationRequested)
                return true;

            await Task.Delay(100, ct).ContinueWith(_ => { });
        }

        if (ctx.Entities.Get(carcass.Id) is not { } всёЕщё)
            return true;
        if (HasLoot(всёЕщё))
            return true;

        упрямые.Add(carcass.Id);
        OnLog?.Invoke($"туша {carcass.Code} обобрана дочиста, окно закрыто — а с земли она " +
                      $"не пропала за {DecayWaitMs} мс. Значит, распада тела у этого зверя " +
                      "нет (deaddecay) или сервер закрытия не принял; второй раз к ней не иду");
        return false;
    }

    /// <summary>
    /// Разделать и обобрать все туши рядом — ровно то, что игрок делает после
    /// охоты, и ровно то, чего бот не умел вовсе: он убивал зверя и уходил.
    /// Возвращает разбор с числами и причиной (<see cref="ButcherReport"/>).
    ///
    /// ТРЕТИЙ СПИСОК — НЕ ЛИШНИЙ. Кроме «кого резать» и «из кого забирать»
    /// обход разбирает и «кого прибрать»: вскрытые пустые туши, у которых окно
    /// так и не закрыли (<see cref="UnrestedNear"/>). Для игрока такого списка
    /// не существует — он закрывает окно сразу и туша рассыпается при нём; у
    /// бота они копятся от каждого сорванного обхода.
    /// </summary>
    public async Task<ButcherReport> ButcherNearbyAsync(double radius = 16,
        CancellationToken ct = default)
    {
        var toCut = CarcassesNear(radius).ToList();
        var toLoot = LootableNear(radius).ToList();
        var toRest = UnrestedNear(radius).ToList();
        if (toCut.Count == 0 && toLoot.Count == 0 && toRest.Count == 0)
        {
            // «НЕ НАШЁЛ» И «НАШЁЛ, ДА БРАТЬ НЕЧЕГО» — РАЗНЫЕ ОТВЕТЫ. Вскрытая
            // и обобранная туша лежит ещё несколько игровых часов
            // (EntityBehaviorDeadDecay), и сказать про лежащую под ногами тушу
            // «в радиусе 12 бл не нашёл» — прямая ложь: ровно её человек и
            // прочёл 19.08 в 18:33:51, секунда в секунду после «ближайшая в
            // 1,1 бл». Считаем пустые отдельно и называем их своим словом.
            //
            // Сюда доходят только УПРЯМЫЕ — те, кого мы уже закрывали, а они
            // остались лежать: остальные пустые лежат в toRest и разбираются.
            // Спрашиваем их ТОЙ ЖЕ меркой, что и сам обход, иначе строка
            // «окна закрыты» была бы сказана про тех, кого мы не закрывали
            int упрямых = ПустыеВскрытые(radius, свои: true).Count;
            return new ButcherReport(0, 0, 0, упрямых > 0
                ? $"туш в радиусе {radius:0} бл: {упрямых}, все вскрыты и пусты, окна закрыты — " +
                  "а с земли они так и не пропали"
                : $"туш в радиусе {radius:0} бл не нашёл");
        }

        // НОЖ СПРАШИВАЕМ ДО ПЕРВОГО ШАГА. Раньше про него узнавала каждая туша
        // по отдельности — уже подойдя к ней вплотную: три туши давали три
        // одинаковые строки «нет ножа» и три бесполезные дороги
        string why = "";
        if (toCut.Count > 0 && !HasKnife)
        {
            why = НечемРезать(toCut.Count);
            OnLog?.Invoke(why);
            toCut.Clear();
        }

        int butchered = 0, looted = 0, прибрано = 0;
        foreach (var carcass in toCut.Concat(toLoot).Concat(toRest).ToList())
        {
            if (ct.IsCancellationRequested)
            {
                why = Прервали;
                break;
            }
            bool wasHarvested = IsHarvested(carcass);
            if (!wasHarvested && !await HarvestAsync(carcass.Id, ct))
            {
                // Причину назвал сам HarvestAsync (нет ножа, не дойти, пропала);
                // здесь она нужна лишь для итоговой строки
                why = $"{carcass.Code} разделать не вышло";
                continue;
            }
            if (!wasHarvested)
                butchered++;
            int взято = await LootAsync(carcass.Id, ct);
            looted += взято;

            // ДОБЫЧА ОСТАЛАСЬ В ТУШЕ — И ЭТО ОБЯЗАНО ЗВУЧАТЬ, А НЕ МОЛЧАТЬ.
            //
            // Заказчик 28.08 назвал это своими словами: «трупы остаются с
            // вещами и не исчезают». Так и есть, и вот почему: игра убирает
            // тушу только на закрытии ПУСТОГО окна
            // (EntityBehaviorHarvestable.Inv_OnInventoryClosed: условие
            // inv.Empty), а непустую оставляет лежать до естественного распада
            // ВМЕСТЕ со всем, что в ней (у дрифтера это три игровых часа,
            // deaddecay/hoursToDecay: 3 в lore/drifter.json 1.22.7).
            //
            // Причину, по которой не взяли, назвало вынимание строкой выше
            // (полные сумки, сервер не принял перенос) — здесь называется
            // ПОСЛЕДСТВИЕ, то самое, которое человек видит глазами. Раньше
            // здесь стояло молчание: <see cref="УлеглаAsync"/> на «в туше ещё
            // что-то лежит» отвечает «улеглась» и уходит без слова, и обход
            // докладывал бодрое «разделал туш: 1, забрал стопок: 0» над
            // лежащей полной тушей
            // СПРАШИВАЕМ ОПИСЬ, А НЕ <see cref="HasLoot"/>, И ЭТО НЕ ВТОРАЯ
            // МЕРКА. Вопросы разные, и разница между ними — закон 4. HasLoot
            // отвечает «стоит ли идти»: описи нет — считаем, что добыча есть,
            // иначе бросим её не заглянув. Здесь вопрос другой — «объявлять ли
            // человеку, что добыча осталась», — и на него незнание отвечает
            // МОЛЧАНИЕМ: заявить о невзятой добыче, не увидев описи, значит
            // назвать беду, которой можем и не быть.
            //
            // «ВЗЯТО == 0» — ЭТО НЕ ОСТОРОЖНОСТЬ, А ЕДИНСТВЕННОЕ, ЧТО МЫ ТУТ
            // ЗНАЕМ ТОЧНО. Опись туши приезжает ОТДЕЛЬНЫМ пакетом и ПОЗЖЕ
            // переноса: игра лишь помечает её грязной
            // (EntityBehaviorHarvestable.Inv_SlotModified → MarkPathDirty
            // «harvestableInv»), а Container.TakeOneAsync уходит по первому же
            // факту — прибавке в СВОЕЙ сумке. То есть сразу после удачного
            // выема опись ещё старая и полна, и без этой заставы бот выдавал
            // одной строкой «забрал стопок: 1» и тут же «добыча так и осталась
            // в туше». Забрал — и сам же говорит, что не забрал.
            //
            // Взяли хоть что-то — верим не описи, а МИРУ: пропала ли туша с
            // земли (УлеглаAsync ниже). Это и есть та сверка, ради которой
            // заведён счёт «прибрано» после жалобы 20.08.
            if (взято == 0 && ctx.Entities.Get(carcass.Id) is { } недобрана &&
                Contents(недобрана.Id) is { } опись && опись.Any(s => !s.IsEmpty))
                why = $"{carcass.Code}: добыча так и осталась в туше — пока туша не пуста, " +
                      "игра её не уберёт, и лежать ей до распада";
            // ПОСЛЕДНИЙ ХОД РАЗДЕЛКИ. Вынимание уже открыло и закрыло тушу
            // (Container.TakeAllReportAsync — окно закрывается на любом
            // исходе), а закрытие пустой туши и есть её исчезновение. Здесь мы
            // только СВЕРЯЕМ ЭТО С МИРОМ: без сверки о поломке снова узнал бы
            // человек, как 20.08 («после разделки бота никто не исчезает»)
            else if (!await УлеглаAsync(carcass, ct))
                why = $"{carcass.Code}: обобрал дочиста и закрыл, а туша осталась лежать";
            else if (ctx.Entities.Get(carcass.Id) is null)
                прибрано++;   // рассыпалась при нас — это и есть «как у игрока»
        }

        // ОБОРВАЛИ НА ПОСЛЕДНЕЙ ТУШЕ — ПРИЧИНА ВСЁ РАВНО ЕСТЬ. Проверка в
        // начале круга её не назовёт: следующего круга уже не будет, а
        // «делать было нечего» про перебитый обход — неправда того же сорта,
        // что и «не нашёл» про тушу под ногами.
        //
        // И ОНА СИЛЬНЕЕ ВСЕГО, ЧТО МОГЛО НАКОПИТЬСЯ В ЭТОМ КРУГЕ. Сторож
        // «why.Length == 0» стоял здесь до 28.08 и вправду молчал, стоило
        // последней туше оставить в себе добычу: человек читал «добыча так и
        // осталась в туше — игра её не уберёт», то есть рассказ про устройство
        // игры вместо настоящей причины «тело забрали». А забирают его
        // постоянно: разделка держит тело важностью Urgent — выше приказа, но
        // НИЖЕ рефлекса, — и её перебивают бой, еда и лечение (в живом журнале
        // 28.08 — трижды за пятнадцать секунд). Обе вести правдивы, но первой
        // обязана идти та, по которой человек может что-то сделать
        if (ct.IsCancellationRequested)
            why = why.Length == 0 || why == Прервали ? Прервали : $"{Прервали}; и ещё: {why}";

        // СКОЛЬКО ОСТАЛОСЬ — пересчитываем ПОСЛЕ обхода, а не вычитаем из
        // начального: пока мы резали одну, рядом могли убить вторую. Вскрытая
        // пустая незакрытая туша тоже «осталась»: разделка над ней не доведена
        int left = CarcassesNear(radius).Count() + LootableNear(radius).Count() +
                   UnrestedNear(radius).Count();
        return new ButcherReport(butchered, looted, left, why, прибрано);
    }
}

/// <summary>
/// ЧЕМ КОНЧИЛСЯ ОБХОД ТУШ — числами и причиной, а не одним «сколько».
///
/// Прежде обход отдавал голое число обработанных туш, и по нему нельзя было
/// отличить «туш не было» от «туши есть, а ножа нет» и от «разделал, но
/// добыча не полезла в полные сумки». А отличать их надо: первое — обычная
/// жизнь, второе чинится одним ножом в сумке, третье — рейсом на склад.
/// </summary>
/// <param name="Butchered">Сколько туш разделано ножом.</param>
/// <param name="Looted">Сколько стопок вынуто из туш.</param>
/// <param name="Left">Сколько туш осталось поблизости необработанными.</param>
/// <param name="Why">Почему остановились (пусто — всё разобрано).</param>
/// <param name="Rested">
/// Сколько туш ПРОПАЛО С ЗЕМЛИ при нас — обобранных дочиста и закрытых.
///
/// Это не украшение отчёта, а та самая новость, которой человеку не хватало:
/// «после разделки бота никто не исчезает» (20.08). Число считается по факту
/// от сервера — туши нет в мире, — а не по тому, что мы отправили пакет.
/// </param>
public readonly record struct ButcherReport(int Butchered, int Looted, int Left, string Why,
    int Rested = 0)
{
    /// <summary>Хоть что-то сделано: иначе способность не имеет права занимать ход.</summary>
    public bool Any => Butchered > 0 || Looted > 0 || Rested > 0;

    public override string ToString() => Any
        ? $"разделал туш: {Butchered}, забрал стопок: {Looted}" +
          (Rested > 0 ? $", прибрал туш: {Rested}" : "") +
          (Left > 0 ? $"; рядом ещё туш: {Left}" : "") +
          (Why.Length > 0 ? $" ({Why})" : "")
        : Why.Length > 0 ? Why : "делать было нечего";
}
