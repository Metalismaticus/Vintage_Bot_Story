namespace VsBotKit;

/// <summary>
/// Разделка туш: мясо, шкура, жир с убитого зверя.
///
/// Как это устроено в игре (EntityBehaviorHarvestable, ItemKnife):
/// - разделывать можно ТОЛЬКО мёртвого и ещё не разделанного зверя
///   (<c>IsHarvestable = !entity.Alive &amp;&amp; !harvested</c>);
/// - в руке нужен НОЖ: удержание правой кнопки на туше, время —
///   <c>скорость ножа × duration зверя</c> (у большинства 5 секунд);
/// - на отпускании сервер сверяет накопленное время и ставит «harvested»
///   (ItemKnife.OnHeldInteractStop → SetHarvested), нож при этом тупится на 3;
/// - разделанная туша — это контейнер «harvestableContents-&lt;id&gt;»:
///   обычный правый клик по ней открывает его, дальше перенос как из сундука;
/// - и ПОСЛЕДНИЙ ХОД — ЗАКРЫТИЕ ОКНА: на него подписана сама разделка
///   (<c>EntityBehaviorHarvestable.Inv_OnInventoryClosed</c>), и пустая туша
///   от него рассыпается тут же (<c>EntityBehaviorDeadDecay.DecayNow</c>).
///   Пакет закрытия шлётся из одного места на весь проект
///   (<see cref="Actions.CloseInventoryByIdAsync"/>), а разделка только
///   СВЕРЯЕТ С МИРОМ, что туша и правда пропала (<see cref="ButcherReport.Rested"/>).
///
/// Флаг «harvested» лежит в WatchedAttributes зверя, то есть бот читает его
/// оттуда же, откуда и настоящий клиент, — врать себе об успехе нечем.
///
/// Всё это — механизм. КОГО и когда разделывать — политика роли.
/// </summary>
public class Butchering
{
    private readonly BotContext ctx;
    private readonly Hands hands;

    /// <summary>
    /// ТУШИ, КОТОРЫЕ БОТ ЗАКРЫЛ, А ОНИ НЕ РАССЫПАЛИСЬ. Второй раз к такой не
    /// подходим: игра убирает пустую тушу только у зверей с поведением
    /// «распад тела» (deaddecay), а у кого его нет — тому лежать и лежать, и
    /// хождение к нему каждый обход было бы той самой беготнёй впустую, от
    /// которой бережётся подбор своей памятью о неудачах.
    /// </summary>
    private readonly HashSet<long> упрямые = [];

    public Butchering(BotContext ctx, Hands hands)
    {
        this.ctx = ctx;
        this.hands = hands;
    }

    public event Action<string>? OnLog;

    /// <summary>
    /// НОЖ ЛИ ЭТО — СПРАШИВАЕМ РЕЕСТР СЕРВЕРА, А НЕ БУКВЫ КОДА.
    ///
    /// Здесь стояло <c>KnifeCode = "knife"</c> и сверялось ПОДСТРОКОЙ. В игре
    /// 1.22.7 под эту подстроку попадает не только нож: рядом с
    /// <c>itemtypes/tool/knife.json</c> (class ItemKnife, tool: "knife") лежит
    /// <c>itemtypes/toolhead/knifeblade.json</c> — ЗАГОТОВКА, шестнадцать
    /// разновидностей от knifeblade-flint до knifeblade-steel, без класса и без
    /// поля tool. Резать ею нельзя ничем: разделку начинает
    /// <c>ItemKnife.OnHeldInteractStart</c>, а у лезвия этого класса нет вовсе —
    /// сервер использование даже не открывает.
    ///
    /// ЧЕМ ЭТО КОНЧАЛОСЬ ЖИВЬЁМ, И ЭТО НЕ ДОГАДКА. Лезвие в сумке у бота —
    /// обычный день: он сам его вытёсывает по дороге к ножу, и живой журнал
    /// 16.08 записан в этом же проекте — «вытесанное knifeblade-peridotite
    /// пролежало в сумке весь вечер» (см. <c>Presets</c>, где заведена доделка
    /// начатого). С таким лезвием бот отвечал «нож есть», шёл к туше, брал
    /// лезвие в руку (взятие искало ТОЙ ЖЕ подстрокой), проверка «а что в
    /// руке» пропускала его (тоже подстрока), бот честно держал кнопку шесть
    /// секунд — и получал ноль. Наружу это выходило тремя жалобами заказчика
    /// 28.08 сразу: «разучился разделывать», «не лутает» (из невскрытой туши
    /// брать нечего) и «трупы остаются с вещами и не исчезают» (туша
    /// рассыпается только на закрытии ПУСТОГО окна, а невскрытую закрывать
    /// нечего). И ни одного отказа вслух: «ножа в сумках нет» не звучало
    /// НИКОГДА, потому что нож «был».
    ///
    /// ВТОРАЯ МЕРКА В ПРОЕКТЕ (закон 2). «Инструмент ли это и какой» весь
    /// проект спрашивает у реестра одним местом —
    /// <see cref="WorldModel.GetToolTypeByCode"/> (снаряжение, поручения,
    /// добыча, справочник, оружие). Разделка была единственной, кто завёл свою
    /// мерку буквами, — и единственной, кого лезвие обмануло.
    /// </summary>
    public bool IsKnife(string? code) =>
        code is { Length: > 0 } c &&
        ctx.World.GetToolTypeByCode(c) == (int)Vintagestory.API.Common.EnumTool.Knife;

    /// <summary>
    /// Время разделки по умолчанию, секунд. В игре оно записано у каждого
    /// зверя в JSON (<c>harvestable.duration</c>, обычно 5), а по сети тип
    /// зверя не приходит — поэтому берём общее значение и держим с запасом.
    /// Передержать не страшно: сервер сверяет «прошло НЕ МЕНЬШЕ нужного».
    /// </summary>
    public double BaseHarvestSeconds { get; set; } = 5;

    /// <summary>Насколько дольше нужного держать нож (сеть и тики съедают доли).</summary>
    public double ExtraHoldSeconds { get; set; } = 1.5;

    /// <summary>
    /// СКОЛЬКО ЖДАТЬ, ПОКА ЗАКРЫТАЯ ПУСТАЯ ТУША ПРОПАДЁТ С ЗЕМЛИ.
    ///
    /// Это не порог политики, а срок ответа сервера, и он взят из его же
    /// устройства: <c>DecayNow()</c> только ставит зверю «можно убирать»
    /// (AllowDespawn), а уносит его ближайший тик мира —
    /// <c>ServerSystemEntitySimulation</c> собирает всех, у кого
    /// <c>ShouldDespawn</c>, и шлёт нам пакет о пропаже. Полторы секунды — это
    /// с запасом на десяток тиков и дорогу туда-обратно; роли крутить тут
    /// нечего, а вот стенду срок нужен коротким, потому он и поле.
    /// </summary>
    public int DecayWaitMs { get; set; } = 1500;

    /// <summary>
    /// МАТЕРИАЛ, ПО КОТОРОМУ ИГРА МЕРЯЕТ СКОРОСТЬ НОЖА ПРИ РАЗДЕЛКЕ, — И ЭТО
    /// «РАСТЕНИЕ», А НЕ «КОЖА».
    ///
    /// Здесь стояло <c>LeatherMaterial = (EnumBlockMaterial)13</c> с подписью
    /// «кожа — EnumBlockMaterial.Leather». Подпись была ВЫДУМАНА: перечисления
    /// <c>Leather</c> в игре нет вовсе. Разобрано ilspycmd по
    /// VintagestoryAPI.dll 1.22.7 — весь список ровно такой: Air, Soil, Gravel,
    /// Sand, Wood, Leaves, Stone, Ore, Water, Snow, Ice, Metal, Mantle, Plant,
    /// Glass, Ceramic, Cloth, Lava, Brick, Fire, Meta, Other. Тринадцатый —
    /// <c>Plant</c>.
    ///
    /// САМО ЧИСЛО ПРИ ЭТОМ БЫЛО ВЕРНЫМ, и это важно: игра берёт РОВНО ЕГО.
    /// <c>ItemKnife.GetKnifeHarvestingSpeed</c> (VSSurvivalMod.dll 1.22.7)
    /// считает <c>1 / ((GetMiningSpeeds(slot)[13] − 1) · 0,5 + 1)</c>. То есть
    /// живьём НЕ ЛОМАЛОСЬ НИЧЕГО — врал только комментарий, и врал коварно:
    /// человек, пришедший «починить» его на настоящую кожу, поменял бы число
    /// и сломал разделку. Теперь тут имя, а не число: подставить другое
    /// перечисление молча уже нельзя.
    ///
    /// Почему у ножа скорость записана именно по растениям, видно в его
    /// описании: assets/survival/itemtypes/tool/knife.json, таблица
    /// <c>miningspeedbytype</c> — в ней у КАЖДОГО ножа ровно одна строка,
    /// <c>plant</c> (у каменных 1…1,4, у обсидианового 1,4, у ржавого 2), и
    /// никакой другой материал там не упомянут.
    /// </summary>
    private const Vintagestory.API.Common.EnumBlockMaterial HarvestSpeedMaterial =
        Vintagestory.API.Common.EnumBlockMaterial.Plant;

    /// <summary>
    /// Почему обход кончился раньше времени, когда тело забрали. Слово одно на
    /// оба места, где это говорится (круг и его конец): двух разных объяснений
    /// одному и тому же случаю человек не заслужил.
    /// </summary>
    private const string Прервали = "разделку прервали — тело понадобилось другому делу";

    /// <summary>Id инвентаря разделанной туши для переноса предметов.</summary>
    public static string CarcassInventoryId(long entityId) => $"harvestableContents-{entityId}";

    /// <summary>
    /// Что лежит в туше.
    ///
    /// Инвентарь туши НЕ приходит по общему инвентарному каналу — он живёт
    /// в WatchedAttributes самой сущности, под ключом «harvestableInv»
    /// (EntityBehaviorHarvestable.Initialize читает его оттуда же). Клиент игры
    /// узнаёт добычу так же. Живьём это стоило отдельного захода: бот честно
    /// докладывал «туша не открылась», ожидая инвентарь там, где его не бывает.
    /// </summary>
    public SlotContent[]? Contents(long entityId) =>
        Container.Carcass(ctx, hands, entityId).Contents();

    /// <summary>Труп зверя: не игрок, не предмет, здоровья нет.</summary>
    public bool IsCarcass(EntityInfo e) =>
        !e.IsPlayer && !e.IsItem && e.Id != ctx.Entities.OwnEntityId &&
        e.Health is { } hp && hp <= 0;

    /// <summary>Тушу уже разделали (флаг из WatchedAttributes, как у клиента).</summary>
    public static bool IsHarvested(EntityInfo e) => e.WatchedAttributes.GetBool("harvested", false);

    /// <summary>
    /// ЭТУ ТВАРЬ ВООБЩЕ РАЗДЕЛЫВАЮТ — или всё, что с неё причитается, уже
    /// лежит на земле.
    ///
    /// СМЕРТЬ В ИГРЕ УСТРОЕНА ДВУМЯ РАЗНЫМИ СПОСОБАМИ, и путать их дорого
    /// (проверено по описаниям сущностей самой игры 1.22.6):
    /// <list type="bullet">
    /// <item>у оленя, волка, ДРИФТЕРА и шивера есть поведение «harvestable», а
    /// список <c>drops</c> пуст — на землю не падает НИЧЕГО, вся добыча
    /// (шестерёнка, гниль, волокна) лежит внутри туши и достаётся ножом;</item>
    /// <item>у саранчи, звонаря и рыбы harvestable нет, зато есть <c>drops</c> —
    /// вещи выбрасываются на землю в самый миг смерти
    /// (<c>Entity.Die</c> → <c>SpawnItemEntity</c>), и разделывать там нечего.</item>
    /// </list>
    ///
    /// Отличить одно от другого можно БЕЗ ДОГАДОК: поведение harvestable
    /// ставит зверю «вес животного» ещё при рождении
    /// (<c>EntityBehaviorHarvestable.AfterInitialized</c>: <c>AnimalWeight =
    /// …</c>), а вес живёт в WatchedAttributes — то есть приходит боту тем же
    /// пакетом, что и здоровье, и читается оттуда же, откуда его читает
    /// настоящий клиент. У саранчи и звонаря его нет вовсе.
    ///
    /// ЗАЧЕМ ЭТО НУЖНО. Без такой проверки бот шёл к трупу саранчи, доставал
    /// нож и держал кнопку пять секунд впустую — и так над каждым трупом, а
    /// потом честно докладывал «разделать не вышло».
    /// </summary>
    public static bool CanBeButchered(EntityInfo e) =>
        e.WatchedAttributes.HasAttribute("animalWeight") ||
        e.WatchedAttributes.HasAttribute("harvestableInv");

    /// <summary>
    /// Есть ли чем резать. Спрашивается ОДИН раз на весь обход, а не у каждой
    /// туши: без ножа отказ один и тот же, и три туши дали бы три одинаковые
    /// строки в журнале.
    ///
    /// «Чем резать» решает <see cref="IsKnife"/> — реестр, а не буквы кода:
    /// там же разобрано, как лезвие ножа притворялось ножом.
    /// </summary>
    public bool HasKnife => hands.CountOf(s => IsKnife(s.Code)) > 0;

    /// <summary>
    /// ОТКАЗ «НЕЧЕМ РЕЗАТЬ» — ОДНОЙ СТРОКОЙ НА ВСЕ ТРИ МЕСТА, ГДЕ ОН ЗВУЧИТ, и
    /// мест этих правда три, а не два: разделка одной туши
    /// (<see cref="HarvestAsync"/>), обход всех туш рядом
    /// (<see cref="ButcherNearbyAsync"/>) и решение «идти ли за добычей вообще»
    /// (<see cref="KillLootRules.Decide"/>). Ради третьего он и открыт наружу.
    ///
    /// ПОЧЕМУ ОТКАЗ ОБЪЯСНЯЕТСЯ, А НЕ ПРОСТО НАЗЫВАЕТСЯ. Человек смотрит в
    /// сумку бота, видит там «Лезвие ножа из кремнистого сланца» и читает
    /// «ножа нет» как враньё. Врать тут нечем — лезвием в игре не режут вовсе,
    /// — но сказать это надо прямо, иначе следующий вечер уйдёт на спор о том,
    /// слепой бот или нет.
    ///
    /// ТРЕТЬЕ МЕСТО ЧУТЬ НЕ ОСТАЛОСЬ С ГОЛЫМ ОТКАЗОМ, и это не мелочь: у
    /// решения «идти ли» голое «тушу вскрывают ножом, а ножа в сумках нет»
    /// доходит до человека ПЕРВЫМ И ЧАЩЕ остальных. Живой журнал 28.08: голый
    /// отказ напечатан дважды в 01:38:00, а объяснённый пришёл только в
    /// 01:39:33 — через 93 секунды. То есть случай, ради которого всё
    /// переписывали, оставался бы живым, а починка — рассказом о ней.
    /// </summary>
    public static string НечемРезать(int туш = 0) =>
        (туш > 0 ? $"ножа нет — {туш} туш(и) не разделать" : "ножа нет — тушу не разделать") +
        ". Нож узнаю по реестру игры (инструмент вида Knife), а не по буквам кода: " +
        "заготовка-лезвие ножом не считается — сервер ею разделку даже не начинает";

    /// <summary>Туши рядом, которые ещё можно разделать — ближние первыми.</summary>
    public IEnumerable<EntityInfo> CarcassesNear(double radius = 16)
    {
        if (ctx.Self.Position is not { } me)
            return [];
        return ctx.Entities.Nearby(me.X, me.Y, me.Z, radius)
            .Where(e => IsCarcass(e) && CanBeButchered(e) && !IsHarvested(e))
            .ToList();
    }

    /// <summary>
    /// Туши рядом, уже разделанные, — из них ещё не забрали добычу.
    ///
    /// ПУСТАЯ ТУША СЮДА НЕ ПОПАДАЕТ, и это не мелочь: разделанная и обобранная
    /// туша лежит ещё несколько игровых часов
    /// (<c>EntityBehaviorDeadDecay</c>), а без проверки содержимого бот
    /// возвращался бы к ней снова и снова — «забирать нечего» каждые три
    /// секунды до самого её распада.
    ///
    /// Но и без присмотра она не остаётся: пустая вскрытая туша — это
    /// НЕДОДЕЛАННАЯ РАЗДЕЛКА (окно не закрыто), и её берёт
    /// <see cref="UnrestedNear"/>. Здесь список именно про ДОБЫЧУ.
    /// </summary>
    public IEnumerable<EntityInfo> LootableNear(double radius = 16)
    {
        if (ctx.Self.Position is not { } me)
            return [];
        return ctx.Entities.Nearby(me.X, me.Y, me.Z, radius)
            .Where(e => IsCarcass(e) && IsHarvested(e) && HasLoot(e))
            .ToList();
    }

    /// <summary>
    /// ТУШИ РЯДОМ, КОТОРЫЕ ВСКРЫТЫ И ПУСТЫ, А ВСЁ ЕЩЁ ЛЕЖАТ — то есть окно у
    /// них так и не закрывали.
    ///
    /// ЗАЧЕМ ОТДЕЛЬНЫЙ СПИСОК, РАЗ ЗАБИРАТЬ ИЗ НИХ НЕЧЕГО. Исчезновение туши в
    /// игре висит не на разделке и не на вынимании, а на ЗАКРЫТИИ ОКНА
    /// (EntityBehaviorHarvestable.Inv_OnInventoryClosed → DecayNow(); весь
    /// разбор — у <see cref="Actions.CloseInventoryByIdAsync"/>). Свежую тушу
    /// бот теперь закрывает сам, пройдя через <see cref="LootAsync"/>. А вот
    /// туша, у которой обход сорвался посередине — до неё не дошли, тело
    /// понадобилось бою, — остаётся вскрытой, пустой и НЕ ЗАКРЫТОЙ, и лежать
    /// ей до естественного распада. Живой журнал 19–20.08 полон таких:
    ///     [с убитых] drifter-normal: туша вскрыта и пуста — забирать нечего
    /// повторялось про одни и те же туши час за часом. У живого игрока их не
    /// бывает вовсе: он закрывает окно всегда, и туша рассыпается при нём.
    ///
    /// ЛИШНИХ ХОДОК ОТ ЭТОГО СПИСКА НЕ БУДЕТ. Он разбирается ПОПУТНО — обходом,
    /// который и так позван к соседней туше (<see cref="ButcherNearbyAsync"/>);
    /// звать обход ради одной такой туши некому, и это нарочно: ходить за
    /// нулём добычи бот не должен.
    /// </summary>
    public IEnumerable<EntityInfo> UnrestedNear(double radius = 16) =>
        ПустыеВскрытые(radius, свои: false);

    /// <summary>
    /// ВСКРЫТЫЕ ПУСТЫЕ ТУШИ РЯДОМ — ОДНОЙ МЕРКОЙ НА ОБА ВОПРОСА.
    ///
    /// Вопроса два и они противоположные: «к кому идти» (<paramref name="свои"/>
    /// = false — этих ещё не закрывали) и «про кого сказать, что мы уже
    /// сделали всё, что могли» (<paramref name="свои"/> = true — <see
    /// cref="упрямые"/>). Написать вторую мерку своими буквами тут проще
    /// всего — и ровно на этом проект уже обжёгся: пока мерок про добычу в
    /// туше было две, живой журнал 19.08 в 18:33:51 за одну секунду сказал
    /// «иду разделывать: туш 1» и «туш в радиусе 12 бл не нашёл». Мерка одна;
    /// расходится только память о своих неудачах.
    /// </summary>
    private List<EntityInfo> ПустыеВскрытые(double radius, bool свои)
    {
        // Тех, кого мы уже закрывали, а они не рассыпались, из мира могло и
        // унести (естественный распад, выгрузка чанка) — тогда и помнить нечего
        упрямые.RemoveWhere(id => ctx.Entities.Get(id) is null);
        if (ctx.Self.Position is not { } me)
            return [];
        return ctx.Entities.Nearby(me.X, me.Y, me.Z, radius)
            // Мерка «эту тварь вообще разделывают» — та же, что у двух других
            // списков: над трупом саранчи (harvestable у неё нет вовсе, всё
            // выпало на землю) закрывать нечего, и ходить туда незачем
            .Where(e => IsCarcass(e) && CanBeButchered(e) && IsHarvested(e) &&
                        !HasLoot(e) && упрямые.Contains(e.Id) == свои)
            .ToList();
    }

    /// <summary>
    /// В туше что-то есть. Опись НЕ ПРИШЛА — считаем, что есть: соврать «там
    /// пусто», не заглянув, значит бросить добычу; а от вечного возвращения
    /// к одной туше бережёт память того, кто ходит (см. BehaviorLootKills).
    ///
    /// СПРАШИВАЮТ ЭТО ДВОЕ, И МЕРКА У НИХ ОДНА. Кроме обхода туш
    /// (<see cref="LootableNear"/>) сюда ходит решение по телу
    /// (<see cref="KillLootRules.Decide"/> через <see cref="BehaviorLootKills"/>).
    /// Пока мерок было две, живой журнал 19.08 в 18:33:51 выдавал за одну
    /// секунду взаимоисключающее:
    ///     [с убитых] shiver-surface: туша уже вскрыта — забираю добычу
    ///     [с убитых] иду разделывать: туш 1, ближайшая в 1,1 бл
    ///     [с убитых] туш в радиусе 12 бл не нашёл
    /// Решение знало только флаг «вскрыта» и звало в поход; обход знал ещё и
    /// опись — и не находил ничего. Одно из двух обязано было быть ложью.
    /// </summary>
    public bool HasLoot(EntityInfo e) =>
        Contents(e.Id) is not { } inside || inside.Any(s => !s.IsEmpty);

