namespace VsBotKit;

/// <summary>Одна потребность: чего и сколько надо иметь, и сколько есть сейчас.</summary>
/// <param name="Why">
/// ПОЧЕМУ ЭТОГО НЕ ХВАТАЕТ — словами последнего отказа цепочки снабжения
/// (<see cref="Stock.Hopeless"/>). Пусто — за этим ещё не ходили.
///
/// ЖИВОЙ ВОПРОС ЗАКАЗЧИКА 22.08, ДОСЛОВНО: «почему лестницы красные, их же и
/// просил носить стак». В окне управления стояло «Запасы: ladder 8/64», и
/// красное было честным — не хватало. А ПОЧЕМУ не хватает, строка не говорила
/// ничего: ни «на складе пусто», ни «палок нет», ни «за этим ещё не ходил».
/// Причина при этом у бота была — она лежала в безнадёге и уезжала в отчёт
/// наряда, то есть в журнал, между сотней других строк. Человек читал окно.
///
/// Живёт ЗДЕСЬ, а не в окне управления: эту же фразу печатают чат, журнал,
/// отчёт наряда и строка простоя. Собери окно свою — одна нужда звучала бы в
/// двух местах по-разному.
/// </param>
public sealed record StockNeed(string Code, int Want, int Have, string Why = "")
{
    /// <summary>Сколько недостаёт (0 — хватает).</summary>
    public int Missing => Math.Max(0, Want - Have);

    public override string ToString() =>
        Missing == 0
            ? $"{Code}: {Have}/{Want}"
            : $"{Code}: {Have}/{Want} (не хватает {Missing}; " +
              (Why.Length > 0 ? Why : "за этим ещё не ходил") + ")";
}

/// <summary>Чем кончилось пополнение запасов.</summary>
public sealed record StockReport(
    bool Ready,
    string Message,
    IReadOnlyList<StockNeed> Short,
    int Crafted,
    int Fetched,
    double Seconds)
{
    public override string ToString() =>
        (Ready ? "запасы в порядке" : "запасов не хватает: " +
            string.Join(", ", Short.Where(n => n.Missing > 0))) +
        (Crafted > 0 ? $"; сделано {Crafted}" : "") +
        (Fetched > 0 ? $"; добыто {Fetched}" : "") +
        $"; {Seconds:0} с";
}

/// <summary>Каким способом вещь оказывается в сумке.</summary>
public enum MakeWay
{
    /// <summary>Собрать в сетке 3×3 (<see cref="Crafting"/>).</summary>
    Grid,

    /// <summary>Вытесать из камня (<see cref="Knapping"/>).</summary>
    Knap,

    /// <summary>Взять в мире: подобрать с земли или сломать блок (<see cref="Errands"/>).</summary>
    Fetch,

    /// <summary>
    /// НАМЫТЬ ЛОТКОМ (<see cref="Panning"/>). Четвёртый способ, и в зимнем мире
    /// для некоторых вещей — единственный: льняные волокна падают ровно с одного
    /// блока (спелый лён crop-flax-9), а лоток достаёт их из костяной земли
    /// круглый год. Пока этого способа тут не было, «!какдобыть bow-simple»
    /// отвечал «flaxfibers негде взять», и две волны подряд принимали этот
    /// ответ за правду о мире, а не о боте.
    /// </summary>
    Pan
}

/// <summary>Одна составляющая рецепта.</summary>
/// <param name="Codes">
/// Чем её можно закрыть — ОДИН из этих кодов. Список, а не код: в рецепте сетки
/// ингредиент бывает маской («plank-*») или условием по меткам, и какие коды под
/// него подходят, называет реестр сервера, а не мы.
/// </param>
/// <param name="PerCraft">Сколько уходит на КАЖДЫЙ повтор рецепта.</param>
/// <param name="Once">
/// Сколько нужно СВЕРХ ТОГО один раз на всю работу, сколько бы повторов ни было.
/// Ради двух живых правил игры: инструмент в рецепте сетки не тратится, а
/// стирается (GridRecipe.ConsumeInputAt снимает прочность) — значит одного
/// хватит на любое число сборов; и один камень обязан ОСТАВАТЬСЯ В РУКЕ всё
/// камнетёсство — с пустой рукой сервер молча перестаёт считать удары
/// (BlockEntityKnappingSurface.OnUseOver).
/// </param>
public sealed record MakeInput(IReadOnlyList<string> Codes, int PerCraft = 1, int Once = 0)
{
    public MakeInput(string code, int perCraft = 1, int once = 0)
        : this([code], perCraft, once) { }

    public override string ToString() =>
        string.Join(" или ", Codes) + (PerCraft > 1 ? $" ×{PerCraft}" : "");
}

/// <summary>Строка производственного справочника: что во что превращается.</summary>
public sealed record MakeRecipe(MakeWay Way, string Output, int OutputCount,
    IReadOnlyList<MakeInput> Inputs)
{
    public override string ToString() =>
        $"{Output} ×{OutputCount} из " + string.Join(" + ", Inputs);
}

/// <summary>Один шаг снаряжения: что и сколько получить этим способом.</summary>
public sealed record MakeStep(MakeWay Way, string Code, int Count)
{
    public override string ToString() => Way switch
    {
        MakeWay.Fetch => $"добыть {Code} ×{Count}",
        MakeWay.Knap => $"вытесать {Code} ×{Count}",
        MakeWay.Pan => $"намыть лотком {Code} ×{Count}",
        _ => $"сделать {Code} ×{Count}"
    };
}

/// <summary>
/// Что надо проделать, чтобы вещь оказалась в сумке.
/// </summary>
/// <param name="Steps">
/// Шаги СНИЗУ ВВЕРХ: сперва добыть сырьё, потом вытесать, потом собрать. Пустой
/// список при <see cref="Possible"/> означает «всё нужное уже в сумке».
/// </param>
/// <param name="DeadEnds">
/// Коды, на которых план упёрся: ни рецепта, ни источника в мире. Ради них весь
/// разбор и написан — отказ обязан называть, ЧЕГО не хватает, а не «не из чего».
/// </param>
public sealed record MakePlan(string Want, IReadOnlyList<MakeStep> Steps,
    IReadOnlyList<string> DeadEnds)
{
    /// <summary>План сходится: каждый недостающий кусок откуда-то берётся.</summary>
    public bool Possible => DeadEnds.Count == 0;

    public override string ToString() =>
        Possible
            ? Steps.Count == 0 ? $"{Want} уже есть" : string.Join("; ", Steps)
            : $"{Want} не из чего сделать: негде взять " + string.Join(", ", DeadEnds);
}

/// <summary>
/// ЗАПАСЫ: что бот обязан иметь при себе, чтобы делать свою работу.
///
/// Зачем. Копатель уходит на полдня, и половина остановок — не про камень:
/// кончилась кирка, кончились факелы, кончилась еда. Каждый раз это выглядело
/// как «бот встал», а на деле его просто не снарядили. Живой игрок перед
/// выходом смотрит на пояс и доделывает недостающее.
///
/// ПОРЯДОК ПОПОЛНЕНИЯ выбран по цене: сперва ВЗЯТЬ СО СКЛАДА, потом СДЕЛАТЬ
/// (материалы обычно уже есть — из той же породы, что бот и копал), а нет
/// материалов — СХОДИТЬ ЗА НИМИ и сделать, и только потом ДОБЫТЬ саму вещь
/// (это долго и уводит с места). Ничего не вышло — честный отказ со списком,
/// чего именно не хватает и откуда это берут, а не молчаливый выход с пустыми
/// руками.
///
/// ЖИВОЙ СЛУЧАЙ, ИЗ-ЗА КОТОРОГО ПОЯВИЛСЯ ПОИСК МАТЕРИАЛА (журнал 09.08):
///     [запасы] не хватает Axe ×1
///     [запасы] Axe сделать не из чего: подходящего рецепта нет или не хватает материалов
///     [запасы] Axe в мире не добывают — только сделать или принести самому
///     [наряд] запасов не хватает: Axe: 0/1 (не хватает 1)
/// — и так на КАЖДЫЙ наряд, при том что палки и камни лежали кругом, а
/// «крафтить по потребности» стояло включённым. Цепочка обрывалась на первом
/// же шаге: рецепт спрашивался только «на то, что можно собрать ПРЯМО СЕЙЧАС»,
/// а недостающие МАТЕРИАЛЫ не просил никто. Теперь просит — см. PlanFor.
///
/// Класс — механизм. Что именно требовать и сколько, решает роль: рудокопу
/// нужны кирка и факелы, лесорубу топор, а строителю доски.
/// </summary>
public class Stock
{
    private readonly BotContext ctx;

    public Stock(BotContext ctx)
    {
        this.ctx = ctx;
        // НОВОЕ СОЕДИНЕНИЕ — ВОЗМОЖНО, ДРУГОЙ МИР И ДРУГОЙ НАБОР ПРЕДМЕТОВ.
        // Список «какие вообще бывают кирки» снят с реестра прошлого сервера;
        // помнить его на новом — значит требовать вещи, которых там нет
        ctx.Bot.OnSessionReset += () =>
        {
            toolFamilies.Clear();
            recipeBook.Clear();
            fetchable.Clear();
            // И БЕЗНАДЁГУ — ТОЖЕ. «Топора нигде нет» снято с прошлого мира и
            // прошлого склада; тащить его в новый заход значит не пойти за
            // топором, который там лежит
            Hopeless.Forget();
        };
        Hopeless.OnSay += m => OnLog?.Invoke(m);
        // РЕЕСТР ПРИШЁЛ — ПЕРЕСПРОСИТЬ ПРО ИНСТРУМЕНТЫ. Пока его нет, «какими
        // предметами бывает кирка» ответить нечем, и требование не заводится
        // вовсе. Ждать, пока кто-нибудь снаружи повернёт ручку ещё раз, — это
        // надежда, а не механизм: живьём бота спасало то, что настройки заново
        // доносит вход в мир, и только потому список инструментов появлялся
        // через девять секунд. Спрашиваем сами и ровно один раз на реестр
        ctx.World.OnBlockRegistryReady += RetryToolsOnRegistry;
    }

    public event Action<string>? OnLog;

    /// <summary>
    /// ЗА ЧЕМ БОЛЬШЕ НЕ ХОДИМ, ПОКА НЕ ИЗМЕНИТСЯ ОБСТАНОВКА.
    ///
    /// ЖИВОЙ СЛУЧАЙ (журнал 16.08, 12:45-12:57): наряд перебивала еда, возврат
    /// заводил новый заход — и КАЖДЫЙ заход начинался с той же цепочки за
    /// топором и ножом. Десять строк отказа, четыре раза за две минуты, и
    /// каждый раз с настоящей ходьбой: осмотреть округу на stone-chert,
    /// спросить опись, залезть в реестр рецептов. Ни новостей, ни толку — а
    /// секунды съедены у самого наряда.
    ///
    /// Механизм общий (<see cref="VsBotKit.Hopeless"/>), второй копии правила
    /// в запасах нет: то же самое давно делает отметка дома («если не нашёл в
    /// игровой сессии дома шестеренку, то больше не бегает по кд домой»).
    /// </summary>
    public Hopeless Hopeless { get; } = new();

    /// <summary>
    /// ЗАМОК НА СПИСОК ТРЕБОВАНИЙ.
    ///
    /// НАХОДКА ПРИЁМКИ, И ОНА ПРО ОБЫЧНУЮ ОБСТАНОВКУ ЗАКАЗЧИКА. С тех пор как
    /// <see cref="Check"/> перед каждым опросом подновляет требования
    /// (<see cref="BeforeCheck"/>), он из читателя стал ПИСАТЕЛЕМ. А зовут его
    /// три разных потока: цикл бота, поток окна управления
    /// (<c>/api/state</c> раз в две секунды, свой поток пула) и поток чата
    /// («!запасы»). Одновременно с этим поток бота перебирает
    /// <c>Wants.Keys</c> в <see cref="Wanted"/> — рейс на склад
    /// (<c>Depot.HaulLoadAsync</c>) спрашивает про каждую вещь в сундуке.
    /// Перебор словаря во время чужой записи — это
    /// <c>InvalidOperationException</c> посреди сундука, а при неудачном
    /// совпадении и порча словаря.
    /// </summary>
    private readonly object gate = new();

    private readonly Dictionary<string, int> wants = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// Что и сколько держать при себе: часть кода предмета → штук.
    ///
    /// ОТДАЁТСЯ СНИМКОМ, А НЕ ЖИВЫМ СЛОВАРЁМ: список правят из трёх потоков
    /// (см. <see cref="gate"/>), и перебирать его снаружи безопасно только
    /// копией. Читатели у него все до одного — окно, «!запасы», запас по
    /// расходу, наряд.
    /// </summary>
    public IReadOnlyDictionary<string, int> Wants
    {
        get { lock (gate) return new Dictionary<string, int>(wants, StringComparer.OrdinalIgnoreCase); }
    }

    /// <summary>Сколько секунд отводится на всё пополнение.</summary>
    public double MaxSeconds { get; set; } = 300;

    /// <summary>
    /// ХОДИТЬ ЗА НЕДОСТАЮЩИМ В МИР: и за самой вещью, и за МАТЕРИАЛОМ на неё —
    /// палками с кустов, камнями с земли, кремнем из россыпи.
    ///
    /// Выключать стоит боту, который стоит у лавки: за камнем он уйдёт с места.
    /// Копателю выключать нельзя — без этого он не соберёт себе первый топор.
    /// </summary>
    public bool MayFetch { get; set; } = true;

    /// <summary>Пробовать делать недостающее по рецептам.</summary>
    public bool MayCraft { get; set; } = true;

    /// <summary>
    /// Сколько цепочек «сделать из сделанного» разбирать вглубь. Четырёх хватает
    /// на самое длинное живое дерево: топор ← топорище + палка, топорище ←
    /// вытесать из камня, камень ← подобрать с земли. Глубже — это уже не
    /// снаряжение, а производство, и туда бот сам не полезет.
    /// </summary>
    public int MaxMakeDepth { get; set; } = 4;

    /// <summary>
    /// Сколько разных предметов пробовать на один вид инструмента.
    ///
    /// ЧИСЛО С ЗАПАСОМ, И ЭТО НАРОЧНО. Кандидаты идут ЛУЧШИМ ПО ТИРУ ВПЕРЁД, а
    /// каменный топор — самый низкий тир, то есть последний в очереди. Стояло
    /// бы здесь двенадцать — десяток металлических топоров (все делаются из
    /// откованного топорища, которого у голого бота нет) вытеснил бы из очереди
    /// ровно тот единственный, который бот и правда может себе сделать.
    /// </summary>
    public int MaxMakeCandidates { get; set; } = 32;

    /// <summary>
    /// Брать недостающее из сундуков склада. Включено: сундук склада — это и
    /// есть кладовая бота, и рукотворное (кирка, шестерёнка) берётся только
    /// оттуда. Выключить стоит боту, который делит склад с людьми и не должен
    /// выгребать чужое.
    /// </summary>
    public bool TakeFromDepot { get; set; } = true;

    /// <summary>
    /// Чего НЕ пытаться добывать поручением, даже если не хватает.
    ///
    /// Поручение ищет источник по реестру блоков, и для вещей, которых в мире
    /// не растёт, оно даёт дичь: живьём бот на «нужна кирка» пошёл искать
    /// «toolmold-blue-fired-pickaxe», а на «нужен факел» — настенные держатели
    /// факелов. Кирку не выкапывают из земли: её либо делают, либо её просто
    /// нет, и об этом надо сказать, а не изображать поиск.
    /// </summary>
    private readonly HashSet<string> noFetch = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// Чем МЕРИТЬ потребность, если простого «код содержит такую-то подстроку»
    /// мало. Нужно ради инструментов: «держать при себе кирку» — это не про
    /// слово «pickaxe» в коде, а про вид инструмента из реестра. Живой пример,
    /// на котором подстрока ломается: меч в игре называется «blade-longsword-
    /// iron», а щуп «prospectingpick-copper» и считается КИРКОЙ (tool: pickaxe).
    /// </summary>
    private readonly Dictionary<string, Func<string, bool>> matchers =
        new(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// ТРЕБОВАНИЯ, ОХВАТЫВАЮЩИЕ РАЗНЫЕ ВЕЩИ, а не взаимозаменяемые. Нужно
    /// РОВНО ради вида орудия: «держать кирку» удовлетворяет и кирка, и щуп
    /// (у обоих <c>tool: pickaxe</c>), но кирка щупа не заменяет — искать руду
    /// ею нельзя. Считать излишек по всей такой охапке значило бы увезти щуп в
    /// сундук как «вторую кирку».
    ///
    /// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ПРИЗНАК, А НЕ «ЕСТЬ ЛИ МЕРКА». Так и стояло, и
    /// приёмка 26.08 поймала на этом весь долг про излишек: мерка есть у ТРЁХ
    /// требований из четырёх, и две из них — семейные («ЗапасПоРасходу: arrow»
    /// в <see cref="Upkeep"/>, прямое имя предмета в «ДержатьИнструменты»).
    /// По ним излишек считался «сколько ровно таких же», и бот с двумя
    /// материалами стрел держал при себе два запаса вместо одного: велено 80,
    /// при боте 160, а с третьим материалом было бы 240. Признак теперь
    /// ставится ТАМ, ГДЕ ЕГО ЗНАЮТ, — при записи требования, — а не угадывается
    /// по косвенной примете.
    /// </summary>
    private readonly HashSet<string> mixedKinds = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>Одно требование в снимке: что, сколько, чем мерить, разные ли вещи.</summary>
    private readonly record struct Правило(
        string Что, int Надо, Func<string, bool>? Мерка, bool Разные);

    /// <summary>
    /// ГОТОВЫЙ СНИМОК ТРЕБОВАНИЙ ДЛЯ ГОРЯЧЕГО СЧЁТА. Пересобирается в
    /// <see cref="Require"/> под тем же замком, читается одной ссылкой без
    /// замка — присваивание ссылки атомарно, а сам массив после сборки не
    /// меняется.
    ///
    /// ЗАЧЕМ. <see cref="SurplusOf(string?)"/> зовут из горячего такта
    /// (<c>BehaviorHaulWhenFull.CargoSlots</c> — на каждый занятый слот каждый
    /// тик), и прежний «снимок под замком» копировал там два словаря на КАЖДЫЙ
    /// вызов: при сорока слотах это сорок словарей за такт. Ровно на этом
    /// проект уже горел (коммит cb4e80d, «опись перечитывали под каждую вещь»).
    /// </summary>
    private Правило[] снимокТребований = [];

    /// <summary>Пересобрать снимок. Звать ТОЛЬКО под <c>gate</c>.</summary>
    private void ПересобратьСнимок() =>
        снимокТребований = [.. wants.Select(w => new Правило(
            w.Key, w.Value,
            matchers.TryGetValue(w.Key, out var м) ? м : null,
            mixedKinds.Contains(w.Key)))];

    /// <summary>Потребовать иметь при себе столько-то.</summary>
    /// <param name="fetch">
    /// Можно ли добывать это поручением. Для инструментов и прочего рукотворного
    /// — нет: такое делают, а не выкапывают.
    /// </param>
    /// <param name="match">
    /// Чем мерить «это оно» (null — по подстроке кода, как было всегда).
    /// </param>
    /// <param name="interchangeable">
    /// Всё, что подходит под требование, ВЗАИМОЗАМЕНЯЕМО (arrow-crude и
    /// arrow-flint стреляют одинаково). false — вещи РАЗНЫЕ и только делят
    /// вид орудия (кирка и щуп); см. <see cref="mixedKinds"/>.
    /// </param>
    public Stock Require(string code, int count, bool fetch = true,
        Func<string, bool>? match = null, bool interchangeable = true)
    {
        lock (gate)
        {
            if (count <= 0)
            {
                wants.Remove(code);
                noFetch.Remove(code);
                matchers.Remove(code);
                mixedKinds.Remove(code);
                ПересобратьСнимок();
                return this;
            }
            wants[code] = count;
            if (fetch)
                noFetch.Remove(code);
            else
                noFetch.Add(code);
            // Мерка задаётся ЦЕЛИКОМ на каждый вызов: иначе прежняя (например,
            // «любая кирка по реестру») пережила бы обычное требование с тем же
            // именем, и человек не понял бы, почему бот считает щуп киркой
            if (match != null)
                matchers[code] = match;
            else
                matchers.Remove(code);
            // Признак — тоже целиком на каждый вызов, и по той же причине
            if (interchangeable)
                mixedKinds.Remove(code);
            else
                mixedKinds.Add(code);
            ПересобратьСнимок();
            return this;
        }
    }

    /// <summary>Сколько такого есть в сумках.</summary>
    public int Have(string code) => Сколько(MatcherOf(code), code);

    /// <summary>
    /// СКОЛЬКО ПОДХОДЯЩЕГО В СУМКАХ — одно тело на всех. Мерка есть — считаем
    /// ею, нет — подстрокой кода, как было всегда.
    ///
    /// Отдельным методом ради закона 2: то же самое нужно и <see cref="Have"/>
    /// (по имени требования), и <see cref="SurplusOf(string?)"/> (по готовому
    /// снимку, без похода за меркой под замок). Две записи разошлись бы молча.
    /// </summary>
    private int Сколько(Func<string, bool>? мерка, string что) =>
        мерка is { } m
            ? ctx.Hands.CountOf(s => s.Code is { } c && m(c))
            : ctx.Hands.CountOf(что);

    /// <summary>Это требование меряется реестром, а не подстрокой кода.</summary>
    public bool ByRegistry(string code) => MatcherOf(code) != null;

    /// <summary>Снимок «за этим в мир не ходим» — перебирать живой набор нельзя.</summary>
    private string[] NoFetchSnapshot()
    {
        lock (gate)
            return [.. noFetch];
    }

    /// <summary>Мерка этого требования под замком; null — меряем подстрокой.</summary>
    private Func<string, bool>? MatcherOf(string code)
    {
        lock (gate)
            return matchers.TryGetValue(code, out var match) ? match : null;
    }

    // ---------------- ИНСТРУМЕНТЫ ЦЕЛИКОМ, А НЕ ОДНА КИРКА ----------------

    /// <summary>
    /// Какие инструменты бот держит при себе сейчас (канонические имена из
    /// игрового перечисления EnumTool). Меняется только через
    /// <see cref="RequireTools"/>: список надо уметь не только пополнять, но и
    /// УБАВЛЯТЬ, иначе снятая в панели галочка не снимала бы требование.
    /// </summary>
    private readonly HashSet<string> toolWants = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>Реестр уже спрошен: какой вид инструмента какими предметами бывает.</summary>
    private readonly Dictionary<string, List<string>> toolFamilies =
        new(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// ПРИШЁЛ ЛИ РЕЕСТР ПРЕДМЕТОВ. «Не знаю» и «там пусто» — разные вещи, и
    /// путать их нельзя: до пакета реестра у бота нет НИ ОДНОГО кода предмета,
    /// и любой вопрос «а есть ли на сервере кирка» честно отвечается «пока не
    /// знаю», а не «таких нет».
    ///
    /// Спрашиваем пустой маской — это «все коды реестра»: другого способа
    /// узнать у модели мира, есть ли у неё вообще предметы, снаружи нет, а
    /// заводить второй признак того же самого значит развести два источника
    /// правды.
    /// </summary>
    private bool RegistryHere => ctx.World.SearchItemCodes("", 1).Any();

    /// <summary>Что просили держать при себе в последний раз (для переспроса по реестру).</summary>
    private string? toolList;

    /// <summary>Ответ, который на это дали (чтобы не повторять его слово в слово).</summary>
    private string? toolSaid;

    /// <summary>
    /// ПЕРЕСПРОСИТЬ ПРО ИНСТРУМЕНТЫ, КОГДА ПРИШЁЛ РЕЕСТР.
    ///
    /// Живой журнал 22:05, ровно этот случай:
    ///     [запасы] «кирка» (Pickaxe) — на этом сервере таких предметов нет
    ///     …через девять секунд…
    ///     [инструменты] держу при себе: Pickaxe, Shovel, Axe, Knife
    /// Первая строка была неправдой дважды: и по существу (предметы есть), и по
    /// смыслу (бот сказал «нет», зная только, что не знает).
    ///
    /// Молчим, если ответ не переменился: реестр приходит и на переподключении,
    /// а одинаковая строка на каждый вход — это шум, а не новость.
    /// </summary>
    private void RetryToolsOnRegistry()
    {
        if (toolList is not { } list)
            return;
        string before = toolSaid ?? "";
        string now = RequireTools(list);
        if (!string.Equals(now, before, StringComparison.Ordinal))
            OnLog?.Invoke("реестр пришёл, инструменты пересчитал — " + now);
    }

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: код без домена. «game:pickaxe-copper» → «pickaxe-copper».
    /// Домен сервер шлёт не всегда одинаково, и сравнивать коды с ним и без
    /// него — верный способ не найти собственную кирку.
    /// </summary>
    public static string WithoutDomain(string code)
    {
        int colon = code.IndexOf(':');
        return colon >= 0 ? code[(colon + 1)..] : code;
    }

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: семья предмета — слово до первой чёрточки.
    /// «game:pickaxe-copper» → «pickaxe», «blade-longsword-iron» → «blade».
    /// </summary>
    public static string FamilyOf(string code)
    {
        string plain = WithoutDomain(code);
        int dash = plain.IndexOf('-');
        return dash > 0 ? plain[..dash] : plain;
    }

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: предмет подходит под просимое имя.
    ///
    /// Мерка нарочно НЕ «содержит подстроку»: по подстроке «axe» кирка
    /// (pickaxe-copper) сходит за топор, и бот, которому велели держать топор,
    /// уходит рубить лес киркой. Считается либо полное совпадение, либо
    /// «просили род, а это его вид»: «pickaxe» → «pickaxe-copper».
    /// </summary>
    public static bool InFamily(string? code, string want)
    {
        if (code is not { Length: > 0 } || want.Length == 0)
            return false;
        string c = WithoutDomain(code), w = WithoutDomain(want);
        return string.Equals(c, w, StringComparison.OrdinalIgnoreCase) ||
               c.StartsWith(w + "-", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: разобрать человеческий список через запятую.
    /// «кирка, лопата; топор» → три слова. Пусто — пустой список.
    /// </summary>
    public static IReadOnlyList<string> ParseList(string? text) =>
        string.IsNullOrWhiteSpace(text)
            ? []
            : text.Split([',', ';', '\n', '\r'],
                    StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                .Where(w => w.Length > 0)
                .ToList();

    /// <summary>
    /// Все виды инструментов, какие знает ИГРА (а не мы). Показывается человеку
    /// в ответ на непонятое слово: гадать, что бот умеет, он не должен.
    /// </summary>
    public static IReadOnlyList<string> KnownToolKinds() =>
        Enum.GetNames(typeof(Vintagestory.API.Common.EnumTool));

    /// <summary>
    /// ВО ЧТО ПРЕВРАЩАЕТСЯ СЛОВО ЧЕЛОВЕКА: канонический вид инструмента из
    /// игрового перечисления (null — игра такого вида не знает).
    ///
    /// ПРЯМАЯ ПРЕТЕНЗИЯ ЗАКАЗЧИКА, ПОВТОРЁННАЯ 22.08: «я же просил делать тулзы
    /// чтобы не вписывать их в каждый инструмент». Здесь лежал РУКОПИСНЫЙ
    /// СЛОВАРЬ на тринадцать строк с падежами: «кирка» → Pickaxe, «топор» → Axe,
    /// «коса» → Scythe и так далее. Он и был тем единственным местом, где
    /// инструменты вписаны поодиночке: сама работа с ними давно общая — вид
    /// берётся из реестра сервера (<see cref="WorldModel.ToolOf"/>), цепочка
    /// «добыть → вытесать → собрать» одна на все.
    ///
    /// ТЕПЕРЬ СПРАШИВАЕМ ИГРУ, а список слов не ведём вовсе. Порядок вопросов:
    ///   1. это имя вида прямо из игры («Pickaxe», «axe», «prospectingpick»
    ///      как EnumTool) — переводить нечего;
    ///   2. это человеческое имя ВЕЩИ из языковых файлов игры («кирка»,
    ///      «монтировка», «фалькс») — находим вещи тем же разбором имён, каким
    ///      бот понимает «медь» и «метеоритное железо»
    ///      (<see cref="GameLang.FindByName"/>, второй копии не заведено), и
    ///      спрашиваем у РЕЕСТРА, какой это вид инструмента.
    ///
    /// ЧТО ЭТО ДАЁТ СВЕРХ СЛОВАРЯ. Понимаются вещи, которых в словаре не было
    /// вовсе, — «монтировка» (в словаре она звалась «ломом», а игра зовёт её
    /// монтировкой), «геологический молоток», «фалькс»; МОДОВЫЕ (мод везёт свой
    /// ru.json и свой предмет с полем tool); падежи и опечатки («кирку»,
    /// «топоры») — их разбирает та же лесенка точности имён.
    ///
    /// ЧЕГО ЭТО НЕ ДАЁТ, И ЭТО НАДО ЗНАТЬ: слова, которых в языке игры нет
    /// вовсе. «Серп» — в ванильной игре нет ни одной вещи с таким именем, и
    /// словарь врал вдвойне, ведя его в Scythe (косу), тогда как у игры есть
    /// отдельный вид Sickle; «лом» в игре — это «Металлический лом»
    /// (metal-scraps), сырьё, а не монтировка; «оружие» и «тяпка» — не имена, а
    /// разговор. Такие слова теперь честно не понимаются, и отказ называет, что
    /// именно нашлось (см. <see cref="WhatToolIs"/>).
    /// </summary>
    public string? ToolKind(string word) => WhatToolIs(word).Kind;

    /// <summary>
    /// ТО ЖЕ САМОЕ, НО СО СЛОВАМИ ОТКАЗА. Нужно требованиям
    /// (<see cref="RequireTools"/>): молча проглоченное слово выглядит как
    /// «настройка не работает», а «не понял» и «понял, но это не инструмент» —
    /// две разные беды, и чинят их по-разному.
    /// </summary>
    /// <returns>
    /// Kind — вид из <see cref="Vintagestory.API.Common.EnumTool"/> (null — не вышло);
    /// Why — почему не вышло (пусто, когда вышло).
    /// </returns>
    public (string? Kind, string Why) WhatToolIs(string word)
    {
        string w = word.Trim();
        if (w.Length == 0)
            return (null, "пустое слово");

        // 1. ИМЯ ВИДА ПРЯМО ИЗ ИГРЫ. Это не перевод, а само перечисление игры:
        // «Pickaxe» и «axe» бот обязан понимать и без языковых файлов — их на
        // машине может не оказаться вовсе
        if (Enum.TryParse<Vintagestory.API.Common.EnumTool>(w.Replace(" ", ""),
                ignoreCase: true, out var прямо))
            return (прямо.ToString(), "");

        if (ctx.Errands?.Lang is not { NameCount: > 0 } язык)
            return (null, $"«{word}» — не вид инструмента из игры, а языковых файлов игры " +
                          "у меня нет: перевести человеческое слово нечем. " +
                          $"Понимаю виды: {string.Join(", ", KnownToolKinds())}");

        // 2. ЧЕЛОВЕЧЕСКОЕ ИМЯ ВЕЩИ — И ВИД ЭТОЙ ВЕЩИ ПО РЕЕСТРУ. «Кирка» не
        // подписывает в игре ни одного предмета: подписаны «Медная кирка»,
        // «Кирка из оловянной бронзы» и ещё пять. ВЫБИРАТЬ из них не надо и
        // нельзя — нам нужен не предмет, а ВИД, и вид у всех семи один
        var нашлось = язык.FindByName(w);
        if (нашлось.Count == 0)
            return (null, $"«{word}» — ни вида инструмента с таким именем, ни вещи: " +
                          $"среди {язык.NameCount} названий игры такого нет. " +
                          $"Понимаю виды: {string.Join(", ", KnownToolKinds())}");

        // Только лучшая ступень точности: ниже неё «нож» тянул бы за собой
        // «Лезвие ножа» (тоже не инструмент) и «Ножны»
        int точнее = нашлось.Min(t => t.Nearness);
        var виды = new List<string>();
        var примеры = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        var неИнструменты = new List<string>();
        var неВРеестре = new List<string>();
        foreach (var вещь in нашлось.Where(t => t.Nearness == точнее))
        {
            // РЕЕСТР СЕРВЕРА — ПОСЛЕДНЕЕ СЛОВО, ровно как у разбора имён для
            // поручений (Errands.Resolve). В языке игры есть вещи, которых на
            // ЭТОМ сервере нет: урезанная сборка, выключенный мод. Скажи мы про
            // такую «это не инструмент» — соврали бы про игру вместо правды про
            // сервер, и человек чинил бы не то
            if (ctx.Errands is { } поручения && !поручения.Knows(вещь.Code))
            {
                if (неВРеестре.Count < 3)
                    неВРеестре.Add($"{вещь.Name} ({вещь.Code})");
                continue;
            }
            if (ctx.World.ToolOf(вещь.Code) is not { } вид)
            {
                if (неИнструменты.Count < 3)
                    неИнструменты.Add($"{вещь.Name} ({вещь.Code})");
                continue;
            }
            string имя = вид.ToString();
            if (виды.Contains(имя))
                continue;
            виды.Add(имя);
            примеры[имя] = вещь.Code;
        }

        if (виды.Count == 1)
            return (виды[0], "");

        if (виды.Count > 1)
            // ДВА РАЗНЫХ ВИДА ПОД ОДНИМ СЛОВОМ — ЭТО ПЕРЕСПРОС, А НЕ ДОГАДКА.
            // Взяв первый попавшийся, бот однажды уйдёт рубить лес щупом
            return (null, $"«{word}» игра относит сразу к нескольким видам: " +
                          string.Join(", ", виды.Select(в => $"{в} ({примеры[в]})")) +
                          " — напишите вид одним словом");

        if (неИнструменты.Count > 0)
            return (null, $"«{word}» в игре есть ({string.Join("; ", неИнструменты)}), " +
                          "но инструментом игра это не считает: поля «tool» у него нет. " +
                          $"Понимаю виды: {string.Join(", ", KnownToolKinds())}");

        return (null, $"«{word}» — на этом сервере таких предметов нет: " +
                      $"в языке игры это {string.Join("; ", неВРеестре)}, " +
                      "а в реестре, который прислал сервер, их нет вовсе");
    }

    /// <summary>
    /// Какими предметами этот вид инструмента бывает НА ЭТОМ СЕРВЕРЕ — по его
    /// же реестру. Ни одного кода в нашем коде: щуп окажется киркой, а меч
    /// найдётся под именем «blade», потому что так сказал сервер, а не мы.
    /// </summary>
    public IReadOnlyList<string> FamiliesOfTool(string kind)
    {
        if (toolFamilies.TryGetValue(kind, out var known))
            return known;
        if (!Enum.TryParse<Vintagestory.API.Common.EnumTool>(kind, ignoreCase: true, out var tool))
            return [];

        var families = new List<string>();
        // Пустая маска = «все коды»: другого способа обойти реестр предметов
        // снаружи WorldModel нет, а заводить второй список предметов ради
        // обхода — это ровно тот второй источник правды, которого быть не должно
        foreach (string code in ctx.World.SearchItemCodes("", int.MaxValue))
        {
            if (ctx.World.ToolOf(code) != tool)
                continue;
            string family = FamilyOf(code);
            if (!families.Contains(family, StringComparer.OrdinalIgnoreCase))
                families.Add(family);
        }
        if (families.Count > 0)
            toolFamilies[kind] = families;
        return families;
    }

    /// <summary>
    /// ДЕРЖАТЬ ПРИ СЕБЕ ВСЕ НАЗВАННЫЕ ИНСТРУМЕНТЫ и делать недостающие по
    /// рецепту.
    ///
    /// Заказчик просил дословно: «инструменты нужно крафтить все (я про
    /// настройки, а не только кирку)». Живой случай, который это стоил: бот
    /// копал землю МЕЧОМ 1,8 с вместо 0,4 лопатой — лопата была не в руке и не
    /// в требованиях, а требовалась одна кирка.
    ///
    /// Список пишется человеческими словами: «кирка, лопата, топор, нож».
    /// Понимаются и имена видов из самой игры («Pickaxe»), и начало кода
    /// предмета («prospectingpick»), и человеческие имена вещей из языковых
    /// файлов игры — включая модовые и с падежами (см. <see cref="WhatToolIs"/>);
    /// СВОЕГО СЛОВАРЯ РУССКИХ СЛОВ У БОТА НЕТ. Возвращает строку для журнала —
    /// и про то, что взято в требования, и про то, что не понято: молчаливо
    /// проглоченная опечатка выглядит как «настройка не работает».
    ///
    /// «НЕ ЗНАЮ» И «ТАМ ПУСТО» — РАЗНЫЕ ОТВЕТЫ. Пока реестр предметов не пришёл,
    /// сказать «таких предметов на сервере нет» нельзя: бот не знает НИ ОДНОГО
    /// кода и отвечает не про сервер, а про собственную неосведомлённость.
    /// Такой список переспрашивается сам, когда реестр придёт
    /// (<see cref="RetryToolsOnRegistry"/>).
    /// </summary>
    public string RequireTools(string? list, int each = 1)
    {
        var asked = ParseList(list);
        var now = new List<string>();
        var problems = new List<string>();
        bool registry = RegistryHere;

        foreach (string word in asked)
        {
            var (kind, почемуНеВид) = WhatToolIs(word);
            if (kind == null)
            {
                // Не вид инструмента — может быть, прямое имя предмета.
                // Требовать «его самого» честно: человек мог написать
                // «prospectingpick», и это не ошибка
                if (ctx.World.SearchItemCodes(WithoutDomain(word), 1).Any())
                {
                    string want = WithoutDomain(word);
                    Require(want, Math.Max(1, each), fetch: false,
                        match: c => InFamily(c, want));
                    now.Add(want);
                    continue;
                }
                // Слово не похоже ни на вид орудия из игры, ни на код предмета.
                // Второе проверяется ПО РЕЕСТРУ — а его может ещё не быть, и
                // тогда «игра такого не знает» сказано про пустой стол.
                // Про первое словами отвечает сам разбор слова: он один знает,
                // нашлось ли имя в языке игры и почему оно не подошло
                problems.Add(registry
                    ? почемуНеВид
                    : $"«{word}» — реестра предметов пока нет, проверить не по чему; " +
                      "переспрошу, когда сервер его пришлёт");
                continue;
            }

            var families = FamiliesOfTool(kind);
            if (families.Count == 0)
            {
                problems.Add(registry
                    ? $"«{word}» ({kind}) — на этом сервере таких предметов нет"
                    : $"«{word}» ({kind}) — реестра предметов пока нет: " +
                      "чем на этом сервере бывает такой инструмент, я ещё не знаю; " +
                      "переспрошу, когда придёт");
                continue;
            }
            // Требование ОДНО на вид, а не по одному на каждую семью: «держать
            // кирку» удовлетворяет и кирка, и щуп (у обоих tool: pickaxe), и
            // требовать оба — значит гонять бота за вещью, которая ему не нужна
            var kindTool = Enum.Parse<Vintagestory.API.Common.EnumTool>(kind);
            // ВЕЩИ ТУТ РАЗНЫЕ, И ЭТО ЕДИНСТВЕННОЕ ТАКОЕ МЕСТО ВО ВСЁМ ПРОЕКТЕ:
            // вид орудия сводит под одно требование кирку и щуп, а они друг
            // друга не заменяют. Отсюда interchangeable: false — иначе излишек
            // считался бы по всей охапке и щуп уехал бы в сундук как «вторая
            // кирка» (см. mixedKinds)
            Require(kind, Math.Max(1, each), fetch: false,
                match: c => ctx.World.ToolOf(c) == kindTool,
                interchangeable: false);
            now.Add(kind);
        }

        // УБРАТЬ СНЯТОЕ. Без этого «лопата» осталась бы в требованиях навсегда,
        // и бот до конца смены искал бы то, чего у него больше не просят
        foreach (string gone in toolWants.Except(now, StringComparer.OrdinalIgnoreCase).ToList())
            Require(gone, 0);
        toolWants.Clear();
        foreach (string kept in now)
            toolWants.Add(kept);

        string said = now.Count > 0
            ? "держу при себе: " + string.Join(", ", now)
            : "инструментов при себе не требую";
        if (problems.Count > 0)
        {
            // «Не понял» — про опечатку человека, а «жду реестр» — про себя.
            // Одним словом это называть нельзя: человек начнёт править список,
            // в котором нет ошибки
            said += (registry ? "; не понял: " : "; жду реестр: ") +
                    string.Join("; ", problems);
            foreach (string p in problems)
                OnLog?.Invoke(p);
        }

        // ЗАПОМИНАЕМ ПРОСЬБУ ЦЕЛИКОМ — ради переспроса, когда придёт реестр.
        // Не «чего не хватило», а весь список: реестр меняет ответ и по тем
        // словам, которые сейчас разобрались (на другом сервере кирок может не
        // оказаться вовсе)
        toolList = list;
        toolSaid = said;
        return said;
    }

    /// <summary>
    /// Чего сколько есть и сколько надо — И ПОЧЕМУ НЕ ХВАТАЕТ.
    ///
    /// Причину не считаем заново и нигде не храним второй раз: её помнит
    /// безнадёга (<see cref="Hopeless"/>) — тот самый механизм, который и
    /// решает, ходить ли за этим снова. Заведи мы здесь свою память «почему»,
    /// она разошлась бы с безнадёгой в первый же вечер: бот молчал бы про
    /// починившуюся обстановку, показывая вчерашнюю причину.
    /// </summary>
    public IReadOnlyList<StockNeed> Check()
    {
        BeforeCheck?.Invoke();
        // СНИМОК ПОД ЗАМКОМ, а считаем уже по нему: Have и Почему ходят в
        // сумки и в безнадёгу, и держать на этом время замок незачем
        List<KeyValuePair<string, int>> список;
        lock (gate)
            список = [.. wants];
        return список.Select(w => new StockNeed(w.Key, w.Value, Have(w.Key), Почему(w.Key)))
            .OrderByDescending(n => n.Missing)
            .ToList();
    }

    /// <summary>
    /// КТО ПОДНОВЛЯЕТ ТРЕБОВАНИЯ ПЕРЕД КАЖДЫМ ОПРОСОМ.
    ///
    /// Зачем это здесь. Список требований был НЕПОДВИЖНЫМ: роль один раз
    /// сказала «64 лестницы», и дальше число не зависело ни от чего. Для кирки
    /// так и надо, для расходника — нет: сколько держать стрел, знает только
    /// тот, кто видел, сколько их истрачено (<see cref="Upkeep"/>).
    ///
    /// СОБЫТИЕ, А НЕ ЗВОНОК ПО ИМЕНИ: запасы не должны знать про запас по
    /// расходу ничего, кроме того, что кто-то может подновить список. Иначе
    /// «список требований» и «правило, откуда берутся числа» слиплись бы в один
    /// класс, и добавить второе такое правило было бы негде.
    ///
    /// ЗОВЁТСЯ ПЕРЕД КАЖДЫМ ОПРОСОМ, а не по таймеру, ровно потому, что число
    /// нужно тогда, когда его читают: окно управления, «!запасы», сборы,
    /// пополнение. Подписчик обязан быть дешёвым и не опрашивать запасы в
    /// ответ — иначе получится круг.
    /// </summary>
    public event Action? BeforeCheck;

    /// <summary>
    /// ЭТО ИЗ ТОГО, ЧТО ВЕЛЕНО ДЕРЖАТЬ ПРИ СЕБЕ?
    ///
    /// Спрашивает склад (<see cref="Depot.Keep(string)"/>), и вот почему это
    /// один вопрос, а не два. «Что моё» у склада меряется своими масками
    /// («pickaxe, shovel, axe, torch»), а «что держать» — этим списком. Пока
    /// оба списка писала одна рука, они совпадали случайно; стоило запасам
    /// потребовать 64 лестницы, как склад начал их сдавать в сундук — лестницы
    /// ни в одной маске не значатся. Сделанные боту стрелы уехали бы туда же
    /// в первый же рейс, и он пошёл бы делать новые.
    ///
    /// Мерка берётся ТА ЖЕ, что и у наличия (<see cref="Have"/>): «держать
    /// кирку» — это вид инструмента из реестра, а не слово в коде.
    ///
    /// ЭТО ВОПРОС ПРО РОД, И ОТВЕЧАТЬ ИМ НА «СКОЛЬКО» НЕЛЬЗЯ: «моё» тут
    /// сказано и про одну стрелу, и про четыреста. Сколько ИЗ ЭТОГО моё —
    /// отдельный вопрос с числом в ответе (<see cref="SurplusOf(string)"/>), и
    /// рейс на склад спрашивает теперь его.
    /// </summary>
    public bool Wanted(string? code)
    {
        if (code is not { Length: > 0 })
            return false;
        // ПО ГОТОВОМУ СНИМКУ, а не под замком: этот перебор идёт из потока бота
        // у каждого предмета в сундуке и на каждый занятый слот в горячем
        // такте. Снимок пересобирает Require — см. снимокТребований
        foreach (var (что, _, мерка, _) in снимокТребований)
            if (мерка is { } м ? м(code) : code.Contains(что, StringComparison.OrdinalIgnoreCase))
                return true;
        return false;
    }

    /// <summary>
    /// ПОД КАКИМ ЗАПАСОМ ХОДИТ ЭТА ВЕЩЬ И СКОЛЬКО ИХ ПРИ БОТЕ ВСЕГО — ради
    /// ЧЕСТНОЙ строки в журнале. null — ни одно требование про неё не говорило.
    ///
    /// ЗАЧЕМ ОТДЕЛЬНЫЙ ОТВЕТ, ЕСЛИ ЕСТЬ <see cref="SurplusOf(string?)"/>.
    /// Затем, что рейс отчитывается ПО КОДАМ, а требование одно на всю семью, и
    /// приёмка 26.08 поймала на этом прямую ложь: при «ЗапасПоРасходу: arrow»
    /// журнал печатал «при себе оставил 80» дважды — за flint и за crude, — а у
    /// бота выходило 160. Про убыль слота строка была честна, про ЗАПАС врала.
    /// Теперь запас называется своим именем и своим общим числом, по одному
    /// разу на требование.
    ///
    /// ТРЕБОВАНИЕ ВЫБИРАЕТСЯ ТО ЖЕ, ЧТО И РЕШАЛО, — с наименьшим излишком:
    /// иначе отчёт объяснял бы поступок не тем правилом, по которому он сделан.
    /// </summary>
    public (string Запас, int Держать, int Есть)? KeptUnder(string? code)
    {
        if (code is not { Length: > 0 })
            return null;
        (string, int, int)? ответ = null;
        int лучший = int.MaxValue;
        foreach (var (что, надо, мерка, разные) in снимокТребований)
        {
            if (мерка is { } м ? !м(code) : !code.Contains(что, StringComparison.OrdinalIgnoreCase))
                continue;
            int есть = разные ? ctx.Hands.CountExactly(code) : Сколько(мерка, что);
            int держать = KeepOf(надо, KeepExtraPercent);
            int излишек = SurplusOf(есть, держать);
            if (излишек >= лучший)
                continue;
            лучший = излишек;
            ответ = (что, держать, есть);
        }
        return ответ;
    }

    // ---------------- СКОЛЬКО ИЗ ЭТОГО МОЁ ----------------
    //
    // ЗАЧЕМ ЭТОТ РАЗДЕЛ ПОЯВИЛСЯ. Долг, названный приёмкой 26.08 дословно:
    // «Stock.Wanted отвечает „моё“ на любое количество: бот, подбирающий
    // отстрелянные стрелы, накопит их сколько угодно». Всё подобранное оседало
    // в сумках навсегда — сумка забивалась, рейс на склад начинался и
    // кончался словами «в сумке только своё — нести нечего».
    //
    // ВТОРОГО ОТВЕТА НА «СКОЛЬКО ДЕРЖАТЬ» ЗДЕСЬ НЕ ЗАВЕДЕНО: число берётся из
    // того же списка требований (Wants), который набивают роль, лестницы и
    // запас по расходу (Upkeep.Reserve). Своей памяти «а стрел бы побольше» у
    // этого правила нет и быть не должно — иначе две записи одного числа
    // разошлись бы в первый же вечер.

    /// <summary>
    /// СКОЛЬКО ДЕРЖАТЬ СВЕРХ ТРЕБОВАНИЯ, ПРОЦЕНТОВ — ручка роли
    /// («ДержатьСверхЗапасаПроцентов»).
    ///
    /// ЗАЧЕМ ПРИБАВКА ВООБЩЕ НУЖНА. Сдавать всё, что выше требования, до
    /// последней штуки — значит уходить в лес ровно с тем, что посчиталось
    /// полчаса назад: бот, оставшийся без стрел посреди охоты, хуже бота с
    /// лишними двадцатью. Она же служит и ПОРОГОМ РЕЙСА: пока излишек не
    /// перевалил за прибавку, нести нечего и с места бот не сходит.
    ///
    /// ПРОЦЕНТАМИ, А НЕ ШТУКАМИ, И ЭТО НАРОЧНО. Одна ручка обслуживает и
    /// стрелы (64 → 80), и кирку (1 → 1). Стой здесь «16 штук», бот таскал бы
    /// семнадцать кирок и был бы прав по букве настройки.
    /// </summary>
    public double KeepExtraPercent { get; set; } = 25;

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: СКОЛЬКО ШТУК ОСТАВЛЯТЬ ПРИ СЕБЕ, когда велено держать
    /// <paramref name="want"/> и сверх того разрешено
    /// <paramref name="extraPercent"/> процентов.
    ///
    /// Округление ОБЫЧНОЕ, а не вверх. Четверть сверх одной кирки — это ноль
    /// кирок, а не вторая: округляй мы вверх, любая прибавка заводила бы
    /// «запасную» вещь на каждое требование, о которой никто не просил.
    /// </summary>
    public static int KeepOf(int want, double extraPercent) =>
        want <= 0
            ? 0
            : want + (int)Math.Round(want * Math.Max(0, extraPercent) / 100.0,
                MidpointRounding.AwayFromZero);

    /// <summary>ЧИСТОЕ ПРАВИЛО: сколько штук из имеющихся лишние.</summary>
    public static int SurplusOf(int atHand, int keep) =>
        Math.Max(0, atHand - Math.Max(0, keep));

    /// <summary>
    /// СКОЛЬКО ШТУК ЭТОГО ЛИШНИЕ ПРЯМО СЕЙЧАС — ответ числом на «сколько из
    /// этого моё». Ноль — всё при мне по делу (или это вообще не из
    /// требований: тогда решает склад своими масками).
    ///
    /// ЧЕМ МЕРЯЕТСЯ НАЛИЧИЕ — ЗАВИСИТ ОТ ТОГО, ВЗАИМОЗАМЕНЯЕМЫ ЛИ ВЕЩИ ПОД
    /// ТРЕБОВАНИЕМ, и это не украшение, а защита от потери нужной вещи:
    ///   • ТРЕБОВАНИЕ ВЗАИМОЗАМЕНЯЕМЫХ («arrow», «ladder», «prospectingpick»)
    ///     — arrow-crude и arrow-flint стреляют одинаково. Излишек считается по
    ///     всему, что подходит под требование: 200 стрел при велённых 64 (и
    ///     прибавке 25 %) — это 120 лишних, какими бы они ни были;
    ///   • ТРЕБОВАНИЕ ВИДА ОРУДИЯ («Pickaxe») охватывает вещи РАЗНЫЕ: у кирки и
    ///     у щупа один вид Pickaxe, и «лишним» при общем счёте оказался бы щуп,
    ///     которым бот ищет руду. У таких требований лишними считаются только
    ///     ОДИНАКОВЫЕ вещи: три pickaxe-copper — это две лишних, а кирка и щуп
    ///     — не лишние ни одна.
    ///
    /// ПРИЗНАК БЕРЁТСЯ ИЗ ЗАПИСИ ТРЕБОВАНИЯ (<see cref="mixedKinds"/>), А НЕ ИЗ
    /// НАЛИЧИЯ МЕРКИ. Стояло второе, и это был не изящный сокращённый путь, а
    /// прямая ошибка: мерка есть и у семейных требований («ЗапасПоРасходу:
    /// arrow» ставит её через <see cref="InFamily"/>), так что живой запас
    /// стрел мерялся «сколько ровно таких же». Бот с двумя материалами стрел
    /// держал два запаса вместо одного (велено 80 — при боте 160), а рейс за
    /// излишком при 64+64 не начинался вовсе: по каждому коду излишка было
    /// ноль. Поймано приёмкой 26.08.
    ///
    /// СОВПАЛО НЕСКОЛЬКО ТРЕБОВАНИЙ — БЕРЁМ САМОЕ ОСТОРОЖНОЕ (наименьший
    /// излишек): вещь, которую хоть кто-то считает нужной, на склад не едет.
    /// Здесь <c>Math.Min</c>, и подмена его на <c>Math.Max</c> — не мелочь:
    /// под Max бот сдавал бы по самому щедрому требованию, увозя в сундук то,
    /// что другое требование ещё считает нужным (сторожит
    /// <c>ИзлишекЗапасаTests.Совпали_два_требования_берём_осторожное</c>).
    /// </summary>
    public int SurplusOf(string? code)
    {
        if (code is not { Length: > 0 })
            return 0;
        // СНИМОК ГОТОВ ЗАРАНЕЕ, А НЕ СОБИРАЕТСЯ ЗДЕСЬ. Этот счёт зовут из
        // ГОРЯЧЕГО ТАКТА (BehaviorHaulWhenFull.CargoSlots — на каждый занятый
        // слот каждый тик), и копировать под замком два словаря на каждый вызов
        // значило заводить сорок словарей за такт. Список правят из трёх
        // потоков, поэтому снимок пересобирается в Require, а читается он одной
        // ссылкой — без замка и без выделения памяти
        var правила = снимокТребований;

        int лишних = int.MaxValue;
        foreach (var (что, надо, мерка, разные) in правила)
        {
            if (мерка is { } м
                    ? !м(code)
                    : !code.Contains(что, StringComparison.OrdinalIgnoreCase))
                continue;
            int есть = разные ? ctx.Hands.CountExactly(code) : Сколько(мерка, что);
            лишних = Math.Min(лишних, SurplusOf(есть, KeepOf(надо, KeepExtraPercent)));
        }
        // int.MaxValue означает «ни одно требование про это не говорило» — а
        // это не «всё лишнее», а «не мой вопрос»: ответить тут числом сумки
        // значило бы отобрать у склада его собственные маски
        return лишних == int.MaxValue ? 0 : лишних;
    }

    /// <summary>
    /// ПОЧЕМУ НЕ ХВАТАЕТ — и БУДУ ЛИ ПРОБОВАТЬ СНОВА. Второе так же важно, как
    /// первое: человек, читающий «на складе пусто», вправе знать, пойдёт ли бот
    /// туда ещё раз сам или ждёт его руки.
    ///
    /// СРОК БЕРЁТСЯ У САМОЙ БЕЗНАДЁГИ, А НЕ СОЧИНЯЕТСЯ ЗДЕСЬ. Тут стояло
    /// «больше не пробую, пока обстановка не изменится» — и это было неправдой:
    /// безнадёга держит отказ <see cref="Hopeless{TKey}.TryAgainAfter"/> (по
    /// заводским десять минут), после чего сама говорит «прошло 10 мин — пробую
    /// снова». Человек же читал в окне «бот сдался насовсем» и шёл нести
    /// лестницы руками. Мерка одна: спрашиваем её у того, кто по ней и решает.
    /// </summary>
    private string Почему(string code) =>
        Hopeless.Why(code) is { Length: > 0 } почему
            ? почему + (Hopeless.TryAgainAfter is { } срок
                ? $" — сам пойду за этим снова через {срок.TotalMinutes:0.#} мин " +
                  "или раньше, если обстановка переменится"
                : " — до конца захода больше не пробую")
            : "";

    /// <summary>Всё нужное при себе.</summary>
    public bool Ready => Check().All(n => n.Missing == 0);

    /// <summary>Чего не хватает прямо сейчас (пусто — всё есть).</summary>
    public IReadOnlyList<StockNeed> Missing() =>
        Check().Where(n => n.Missing > 0).ToList();

    /// <summary>
    /// Пополнить запасы — ОДНОЙ ЦЕПОЧКОЙ СНАБЖЕНИЯ, а не своим порядком.
    ///
    /// ЧТО ЗДЕСЬ БЫЛО И ПОЧЕМУ ЭТО ДОЛГ. Порядок стоял выписанным прямо тут:
    /// кладовые (0) → сделать (1) → добыть (2). Ровно тот же порядок, и с теми
    /// же словами, живёт в <see cref="Supply"/> — там он звеньями «сумки →
    /// склад этой работы → дом → крафт → добыть рядом». Две записи одного
    /// правила расходятся молча и в мелочах: здешняя, например, не знала про
    /// склад, отмеченный ДЛЯ ЭТОЙ РАБОТЫ, и запасы шли домой мимо сундука под
    /// боком. Прошлый заход это назвал вслух («по сути ВТОРАЯ цепочка „крафт →
    /// добыть“»), и вот она сведена: здесь остался только СПИСОК ТРЕБОВАНИЙ и
    /// ЧЕСТНЫЙ ОТЧЁТ, а «где взять» решает снабжение.
    ///
    /// ТРИ ВЕЩИ ПЕРЕДАЮТСЯ ЦЕПОЧКЕ, И ВСЕ ТРИ — ПРАВДА ЗАПАСОВ, А НЕ СКЛАДА:
    ///   • мерка <see cref="Have"/> — «держать кирку» меряется видом
    ///     инструмента из реестра, а не подстрокой кода;
    ///   • можно ли в кладовые (<see cref="DepotUnderstands"/>) — склад ищет по
    ///     куску кода, и за «любым топором» идти ему некуда;
    ///   • можно ли добывать это в мире (<see cref="noFetch"/>) — кирку не
    ///     выкапывают из земли.
    ///
    /// Возвращает честный отчёт: чего добрали, а чего так и нет. Вызывающий
    /// сам решает, идти ли работать без части запасов, — рудокопу без кирки
    /// идти незачем, а без факелов можно, просто хуже.
    /// </summary>
    public async Task<StockReport> ReplenishAsync(CancellationToken ct = default)
    {
        var started = DateTime.UtcNow;
        var deadline = started.AddSeconds(MaxSeconds);
        int crafted = 0, fetched = 0, fromDepot = 0;
        // ПОЧЕМУ НЕ ВЫШЛО — НЕ СВОИМ СПИСКОМ, А В БЕЗНАДЁГЕ. Здесь стоял свой
        // список «причины», и он же вторым хвостом уезжал в отчёт: одна и та же
        // правда жила в двух местах и печаталась дважды. Хуже того, окно
        // управления не видело её вовсе — оно берёт нужду (StockNeed), а не
        // отчёт, и человек читал голое «ladder 8/64» неделю подряд.
        // Теперь причина одна и лежит там, где ей и место: в механизме,
        // который по ней решает, ходить ли за этим снова.

        // Справочник «что из чего» пересобирается на каждое снаряжение: он
        // отсортирован по тому, чего в сумке больше, а сумка меняется на каждом
        // шаге. Держать его между заходами — значит идти по вчерашней сумке.
        // Память «где это взять» — тоже: она смотрит в опись сундуков
        recipeBook.Clear();
        fetchable.Clear();

        // НЕХВАТКА ЗАКРЫЛАСЬ — ЗНАЧИТ ОБСТАНОВКА ДРУГАЯ, и вчерашнее «нигде
        // нет» больше не действительно. Спрашивается ДО перебора нарочно: в
        // самом переборе закрытых нехваток уже нет (Missing их не отдаёт), и
        // безнадёга по ним висела бы вечно — бот не пошёл бы за топором, вместо
        // которого ему разок хватило чужого
        var нехватка = Missing();
        foreach (string код in Hopeless.All)
            if (!нехватка.Any(n => string.Equals(n.Code, код, StringComparison.OrdinalIgnoreCase)))
                Hopeless.TryAgain(код, "нехватки больше нет");

        foreach (var need in нехватка)
        {
            if (ct.IsCancellationRequested)
                break;
            if (DateTime.UtcNow > deadline)
            {
                OnLog?.Invoke($"на пополнение запасов ушло всё время ({MaxSeconds:0} с)");
                break;
            }

            // БЕЗНАДЁЖНОЕ НЕ ПЕРЕСПРАШИВАЕМ. Спрашивается ДО первой строки в
            // журнал нарочно: «не хватает Axe ×1» на каждом заходе — это уже
            // тот самый шум, ради которого всё и написано. Причина при этом не
            // теряется: её держит сама безнадёга, и оттуда она едет и в окно
            // управления (StockNeed.Why), и в отчёт, а вслух её один раз
            // сказала та же безнадёга
            if (Hopeless.Given(need.Code))
                continue;

            int lack = need.Missing;
            OnLog?.Invoke($"не хватает {need.Code} ×{lack}");

            if (ctx.Supply is not { } снабжение)
            {
                // ОТКАЗ БЕЗ ПОХОДА — ТОЖЕ ОТКАЗ, и помнить его надо так же:
                // иначе «снабжение не подключено» звучало бы на каждом наряде
                // заново, а в окне управления не звучало бы вовсе
                Hopeless.GiveUp(need.Code, "взять негде: снабжение к боту не подключено");
                continue;
            }

            // ПОРУЧЕНИЕ ОБЯЗАНО УКЛАДЫВАТЬСЯ В СРОК СНАРЯЖЕНИЯ. Иначе один
            // поход за палками съедает время, отведённое на кирку, топор и нож
            // разом, и остальные требования молча остаются несобранными
            double было = ctx.Errands?.MaxSeconds ?? 0;
            if (ctx.Errands is { } errands)
                errands.MaxSeconds = Math.Max(10, (deadline - DateTime.UtcNow).TotalSeconds);

            int доКладовых = Have(need.Code);
            SupplyOutcome итог;
            try
            {
                итог = await снабжение.GetAsync([(need.Code, need.Want, доКладовых)], null, ct,
                    // «Не велено» и «реестр рецептов ещё не пришёл» — РАЗНЫЕ
                    // ответы, и первый на месте второго был бы враньём про
                    // настройку человека. Про реестр звено скажет само
                    craft: MayCraft,
                    // КИРКУ НЕ ВЫКАПЫВАЮТ ИЗ ЗЕМЛИ. Живьём бот на «нужна кирка»
                    // ушёл искать «toolmold-blue-fired-pickaxe» — форму для
                    // отливки: кусок кода подошёл. Спрашиваем ОБЩЕЕ правило
                    // запрета (BannedFromWorld), а не голый список имён: под
                    // требованием «ladder» ходят коды «ladder-wood-acacia-north»
                    nearby: MayFetch && !BannedFromWorld(need.Code),
                    stores: TakeFromDepot && DepotUnderstands(need.Code),
                    have: Have);
            }
            finally
            {
                if (ctx.Errands is { } e)
                    e.MaxSeconds = было;
            }

            int стало = Have(need.Code) - доКладовых;
            lack -= Math.Max(0, стало);
            // ЧЕМ ИМЕННО ЗАКРЫЛОСЬ — по звену, назвавшему себя победителем.
            // Отчёт человеку разный: «со склада взято 3» значит «сундук пустеет»,
            // а «сделано 3» — «ушли материалы»
            switch (итог.From)
            {
                case SupplyLink.JobDepot or SupplyLink.Home:
                    fromDepot += Math.Max(0, стало);
                    break;
                case SupplyLink.Craft:
                    crafted += Math.Max(0, стало);
                    break;
                case SupplyLink.Nearby:
                    fetched += Math.Max(0, стало);
                    break;
            }

            if (lack <= 0)
            {
                // ЗАКРЫЛОСЬ — ЗНАЧИТ ОБСТАНОВКА ДРУГАЯ. Прошлый отказ по этой
                // вещи больше не действителен, и следующая нехватка обязана
                // пойти по цепочке заново, а не упереться во вчерашнее «нет»
                Hopeless.TryAgain(need.Code, "нашлось");
                continue;
            }
            // ОТКАЗ ЦЕПОЧКИ НАЗЫВАЕТ КАЖДОЕ ЗВЕНО СВОИМИ СЛОВАМИ — и он и есть
            // ответ на «почему не собралось». Пересказывать его своими здесь
            // значило бы завести третью версию той же правды.
            // ВСЛУХ ЭТО ГОВОРИТ БЕЗНАДЁГА — один раз на причину, а не на каждый
            // заход наряда. Своего «сказать один раз» здесь нет нарочно: оно
            // живёт в Alarm, куда безнадёга и ходит. Она же и ХРАНИТ причину:
            // отсюда её берут и отчёт ниже, и строка запасов в окне управления
            Hopeless.GiveUp(need.Code, итог.Reason);
        }

        // ПРИЧИНА ЕДЕТ ВМЕСТЕ С САМОЙ НУЖДОЙ, А НЕ ОТДЕЛЬНЫМ ХВОСТОМ. Наряд
        // печатает этот отчёт одной строкой — и человек читал «запасов не
        // хватает: Axe: 0/1 (не хватает 1)», где не сказано ни чего именно не
        // хватило, ни где это берут. Подробности были, но тремя строками выше,
        // между сотней других — а в окне управления их не было вовсе.
        // Теперь их несёт сама нужда (StockNeed.Why), и потому одинаково видны
        // всем четверым читателям: чату, журналу, отчёту и окну
        var still = Missing();
        return new StockReport(still.Count == 0,
            (still.Count == 0
                ? "запасы пополнены"
                : "не хватает: " + string.Join(", ", still)) +
            (fromDepot > 0 ? $"; со склада взято {fromDepot} шт." : ""),
            still, crafted, fetched, (DateTime.UtcNow - started).TotalSeconds);
    }

    // ================= НАЧАТОЕ НЕ БРОСАЮ =================

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: МОЖНО ЛИ ДОДЕЛАТЬ ЭТО, НЕ СХОДЯ С МЕСТА.
    ///
    /// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО НАПИСАНО (журнал 16.08, 13:11:51). Бот
    /// вытесал knifeblade-peridotite, не нашёл палки — и нож остался
    /// недоделанным: «в сумке прибавилось: knifeblade-peridotite x1». Лезвие
    /// пролежало в сумке до конца вечера. Заказчик дословно: «вырезал из камня,
    /// но не скрафтил с палкой в инвентаре» и «почему он не делал крафт
    /// инструментов в простое».
    ///
    /// РАЗНИЦА, КОТОРУЮ ЭТО ПРАВИЛО И МЕРЯЕТ. Шаг «добыть» (<see cref="MakeWay.Fetch"/>)
    /// уводит бота с места и стоит минут: сходить на склад, обойти округу,
    /// сломать блок. Шаги «вытесать» и «сделать» делаются ТАМ, ГДЕ СТОИШЬ —
    /// камнетёсство кладёт заготовку под ноги, сетка 3×3 есть у игрока всегда.
    /// Значит разбор, в котором не осталось ни одного «добыть», закрывается
    /// прямо сейчас и бесплатно, — и бросать его в простое незачем.
    ///
    /// Пустой разбор сюда не годится нарочно: «шагов не осталось» означает «всё
    /// нужное уже в сумке», и доделывать там нечего.
    /// </summary>
    public static bool CanFinishInPlace(MakePlan plan) =>
        plan.Possible && plan.Steps.Count > 0 &&
        plan.Steps.All(step => step.Way != MakeWay.Fetch);

    /// <summary>
    /// ЧТО НАЧАТО И ЛЕЖИТ НЕДОДЕЛАННЫМ: нехватки, которые закрываются, не сходя
    /// с места. Живой ответ — он спрашивает сумку и реестры сервера.
    ///
    /// ВТОРОГО РАЗБОРА ТУТ НЕТ. «Сколько труда уже вложено» не считается заново
    /// и нигде не записывается: полуфабрикат в сумке ВИДЕН САМОМУ РАЗБОРУ
    /// (<see cref="Plan"/> первым делом берёт из сумки), и потому разбор
    /// начатого топора короче разбора с нуля ровно на вытесанное топорище. Вся
    /// память о начатом — это сама сумка, и второй ей быть не должно: список
    /// «что я начал», разъехавшись с сумкой, заставил бы бота доделывать то,
    /// что он уже сдал на склад.
    /// </summary>
    public IReadOnlyList<(string Want, MakePlan Plan)> StartedWork()
    {
        var найдено = new List<(string, MakePlan)>();
        if (!MayCraft)
            return найдено;

        // Справочник «что из чего» отсортирован по тому, чего в сумке больше, а
        // сумка меняется каждым делом. Держать его между вопросами — значит
        // отвечать по вчерашней сумке (та же причина, что и у ReplenishAsync)
        recipeBook.Clear();
        fetchable.Clear();
        foreach (var need in Missing())
        {
            var разбор = PlanFor(need.Code, need.Want);
            if (CanFinishInPlace(разбор))
                найдено.Add((need.Code, разбор));
        }
        return найдено;
    }

    /// <summary>
    /// ДОДЕЛАТЬ НАЧАТОЕ, НЕ СХОДЯ С МЕСТА.
    ///
    /// ЧЕМ ЭТО НЕ <see cref="ReplenishAsync"/>. Пополнение запасов — это вся
    /// цепочка снабжения целиком: сумки, склад работы, дом, крафт, поход в мир.
    /// Она уводит бота на минуты и потому зовётся ПЕРЕД РАБОТОЙ, один раз на
    /// наряд. Здесь же берутся только те нехватки, у которых не осталось ни
    /// одного шага «добыть», — то есть работа на месте и на секунды. Своей
    /// механики нет ни строчки: и разбор, и исполнение — те же самые
    /// (<see cref="MakeAsync"/>), просто спрашиваем мы их об одном.
    ///
    /// БЕЗНАДЁГА ЗДЕСЬ НЕ СПРАШИВАЕТСЯ, И ЭТО НАРОЧНО. Она бережёт от ПОХОДОВ:
    /// «за топором больше не хожу — на складе его нет». А доделать вытесанное
    /// лезвие можно не двигаясь с места, и не сделать этого из-за вчерашнего
    /// «не дойти до склада» было бы ровно тем, на что жаловался заказчик.
    /// Наоборот: получилось — говорим безнадёге отбой, обстановка изменилась.
    /// </summary>
    public async Task<StockReport> FinishStartedAsync(CancellationToken ct = default)
    {
        var начало = DateTime.UtcNow;
        var срок = начало.AddSeconds(Math.Max(1, MaxSeconds));
        int сделано = 0;
        var причины = new List<string>();

        foreach (var (want, разбор) in StartedWork())
        {
            if (ct.IsCancellationRequested || DateTime.UtcNow > срок)
                break;

            var нехватка = Check().FirstOrDefault(n =>
                string.Equals(n.Code, want, StringComparison.OrdinalIgnoreCase));
            int надо = нехватка?.Missing ?? 0;
            if (надо <= 0)
                continue;   // закрылось, пока мы доделывали соседнее

            OnLog?.Invoke($"начатое не бросаю: {want} — осталось {разбор}");
            int было = Have(want);
            var (жалоба, _) = await MakeAsync(want, надо, срок, ct);
            int стало = Have(want) - было;
            сделано += Math.Max(0, стало);

            if (стало > 0)
                Hopeless.TryAgain(want, "доделал начатое");
            else
                причины.Add($"{want}: {жалоба ?? "ничего не прибавилось"}");
        }

        var осталось = Missing();
        return new StockReport(осталось.Count == 0,
            (сделано > 0 ? $"доделал начатое: {сделано} шт." : "доделывать нечего") +
            (причины.Count > 0 ? "; " + string.Join("; ", причины) : ""),
            осталось, сделано, 0, (DateTime.UtcNow - начало).TotalSeconds);
    }

    /// <summary>
    /// СКЛАД ИЩЕТ ПО ПОДСТРОКЕ КОДА — и другого способа у него нет. Для
    /// обычного требования это ровно то, что надо. Для требования по реестру
    /// («любой меч») подстрока врёт: меч в игре называется «blade-longsword-
    /// iron», слова «sword» в коде нет вовсе, и поход на склад вышел бы пустым
    /// — с настоящей ходьбой через полкарты.
    ///
    /// Поэтому спрашиваем реестр заранее: есть ли вообще предмет с таким
    /// куском кода. Нет — на склад не идём и говорим об этом, а не топчемся.
    /// ЧЕСТНО ПРО НЕДОДЕЛАННОЕ: это заплатка, а не решение. По-хорошему складу
    /// нужна та же мерка, что и запасам (Depot.TakeAsync принимает строку);
    /// сделать это здесь нельзя — Depot ведёт другой поток.
    /// </summary>
    private bool DepotUnderstands(string want)
    {
        if (!ByRegistry(want))
            return true;
        if (ctx.World.SearchItemCodes(WithoutDomain(want), 1).Any())
            return true;
        OnLog?.Invoke($"на склад за «{want}» не иду: склад ищет по куску кода, " +
                      "а предметов с таким куском в этом мире нет — попробую сделать");
        return false;
    }

    /// <summary>
    /// ЧТО ИМЕННО ДЕЛАТЬ, чтобы закрыть потребность — конкретный код из
    /// реестра рецептов, а не наше пожелание. null — делать нечего.
    ///
    /// Зачем понадобилось. Рецепты в реестре лежат под ПОЛНЫМИ кодами
    /// («pickaxe-copper», «pickaxe-iron»), а требование пишут родом
    /// («pickaxe», «Pickaxe»). Прежний код спрашивал рецепт ровно на слово
    /// требования, не находил его никогда и молча не крафтил ничего: «крафтить
    /// кирку» стояло в настройках и не работало.
    ///
    /// Из подходящих берём ЛУЧШИЙ ПО ТИРУ (железная кирка возьмёт породу,
    /// какую медная не берёт), а при равном тире — с более коротким кодом:
    /// «pickaxe-copper» короче «prospectingpick-copper», и это ровно та
    /// разница между инструментом и щупом, которую человек имел в виду.
    /// </summary>
    public string? WhatToMake(string want)
    {
        if (ctx.Crafting is not { Ready: true } crafting)
            return null;

        // Точное имя — самый частый и самый дешёвый случай
        if (crafting.CanCraft(want, 1))
            return want;

        bool Suits(string code) =>
            MatcherOf(want) is { } match ? match(code) : InFamily(code, want);

        // Требование с реестровой меркой («любой топор») по подстроке не
        // ищется вовсе: меч в игре называется «blade-longsword-iron», и поиск
        // по слову «sword» не нашёл бы ни одного рецепта. Такие смотрим по
        // всем рецептам — мерка дешёвая, а тяжёлую проверку материалов
        // получают только подошедшие
        IEnumerable<CraftRecipe> candidates = matchers.ContainsKey(want)
            ? crafting.All
            : crafting.FindRecipes(FamilyOf(want), limit: 500);

        string? best = null;
        int bestTier = int.MinValue;
        foreach (var recipe in candidates)
        {
            if (!Suits(recipe.OutputCode) || !crafting.CanCraft(recipe.OutputCode, 1))
                continue;
            int tier = ctx.World.ToolTier(recipe.OutputCode);
            if (tier > bestTier ||
                (tier == bestTier && best != null && recipe.OutputCode.Length < best.Length))
            {
                bestTier = tier;
                best = recipe.OutputCode;
            }
        }
        return best;
    }

    // ================= КАК ЭТО ВООБЩЕ СДЕЛАТЬ =================
    // Ниже — разбор «чего не хватает и откуда это берут». Он нужен ровно там,
    // где кончается WhatToMake: тот отвечает только про то, что собирается ИЗ
    // УЖЕ ЛЕЖАЩЕГО В СУМКЕ, и на пустой сумке молчит.

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: как получить вещь, которой нет в сумке.
    ///
    /// Ни сети, ни мира, ни реестров: всё, что нужно, приходит тремя вопросами —
    /// «сколько такого в сумке», «какими рецептами это делают» и «берут ли это
    /// в мире». Поэтому правило целиком проверяется тестами, а не живым
    /// сервером.
    ///
    /// ПОРЯДОК ВНУТРИ КАЖДОГО ШАГА тот же, что у человека: сперва посмотреть в
    /// сумку, потом сделать, и только потом идти в мир. Одна и та же кучка не
    /// расписывается дважды — иначе план «топор из палки и палка на топорище»
    /// сошёлся бы на одной-единственной палке.
    ///
    /// НЕУДАВШИЙСЯ РЕЦЕПТ ОТКАТЫВАЕТ ШАГИ И РАСПИСАННЫЙ МАТЕРИАЛ, НО НЕ ПРИЧИНУ.
    /// Разница тонкая и важная. Откати мы заодно и причину — отказ назвал бы
    /// самоё вещь («не хватает axe-flint»), и человек остался бы ни с чем: он
    /// и так знает, что топора нет. Названа должна быть ПАЛКА. Зато как только
    /// хоть один рецепт сошёлся, все причины отвергнутых веток стираются: «не
    /// хватает ingot-copper» у бота с готовым каменным топором — это враньё.
    /// </summary>
    /// <param name="have">Сколько такого кода в сумке (точный код, не кусок).</param>
    /// <param name="recipesFor">Чем этот код делают (пусто — ничем).</param>
    /// <param name="canFetch">Берут ли это в мире: лежит, растёт, выпадает.</param>
    /// <param name="maxDepth">Насколько глубоко разбирать «сделанное из сделанного».</param>
    /// <param name="budget">
    /// Потолок разборов. Рецептов на сервере около тринадцати тысяч, а перебор
    /// вариантов ветвится: без потолка «сделай мне сундук» уходило бы в минуты
    /// молчания. Упёрлись в потолок — честный тупик, а не бесконечный поиск.
    /// </param>
    public static MakePlan Plan(string want, int count,
        Func<string, int> have,
        Func<string, IReadOnlyList<MakeRecipe>> recipesFor,
        Func<string, bool> canFetch,
        int maxDepth = 4, int budget = 2000)
    {
        var steps = new List<MakeStep>();
        var dead = new List<string>();
        // Сколько из сумки уже расписано под другие шаги этого же плана
        var spent = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        // Защита от круга в рецептах («доска из бруска, брусок из доски»)
        var busy = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        int left = Math.Max(1, budget);

        Need(want, Math.Max(1, count), Math.Max(1, maxDepth));

        // Один поход за палками вместо трёх: шаги «добыть» с одним кодом
        // сливаются в первый из них — он всё равно стоит раньше всех, кто эти
        // палки потратит
        var merged = new List<MakeStep>();
        foreach (var step in steps)
        {
            int same = step.Way != MakeWay.Fetch ? -1 : merged.FindIndex(m =>
                m.Way == MakeWay.Fetch &&
                string.Equals(m.Code, step.Code, StringComparison.OrdinalIgnoreCase));
            if (same >= 0)
                merged[same] = merged[same] with { Count = merged[same].Count + step.Count };
            else
                merged.Add(step);
        }

        return new MakePlan(want, merged,
            dead.Distinct(StringComparer.OrdinalIgnoreCase).ToList());

        bool Need(string code, int need, int depth)
        {
            // 1. ИЗ СУМКИ
            int free = Math.Max(0, have(code) - spent.GetValueOrDefault(code));
            int take = Math.Min(free, need);
            if (take > 0)
            {
                spent[code] = spent.GetValueOrDefault(code) + take;
                need -= take;
            }
            if (need <= 0)
                return true;

            if (--left <= 0 || depth <= 0 || !busy.Add(code))
            {
                dead.Add(code);
                return false;
            }
            int причины = dead.Count;
            try
            {
                // 2. СДЕЛАТЬ
                foreach (var recipe in recipesFor(code))
                {
                    if (recipe.OutputCount <= 0)
                        continue;
                    int times = (need + recipe.OutputCount - 1) / recipe.OutputCount;

                    var undo = Mark();
                    bool ok = true;
                    foreach (var input in recipe.Inputs)
                    {
                        int wanted = input.PerCraft * times + input.Once;
                        if (wanted <= 0 || TryAny(input.Codes, wanted, depth - 1))
                            continue;
                        ok = false;
                        break;
                    }
                    if (ok)
                    {
                        Forget(причины);
                        steps.Add(new MakeStep(recipe.Way, recipe.Output,
                            times * recipe.OutputCount));
                        return true;
                    }
                    Undo(undo);
                }

                // 3. ВЗЯТЬ В МИРЕ — последним: это долго и уводит с места
                if (canFetch(code))
                {
                    Forget(причины);
                    steps.Add(new MakeStep(MakeWay.Fetch, code, need));
                    return true;
                }

                // Ни рецептом, ни в мире. Своё имя добавляем ТОЛЬКО когда по
                // дороге вглубь никто не назвался: у топора настоящая причина —
                // палка, а «не хватает топора» человек и без нас знает
                if (dead.Count == причины)
                    dead.Add(code);
                return false;
            }
            finally { busy.Remove(code); }
        }

        // Ингредиент закрывается ЛЮБЫМ из своих кодов: «доска» в рецепте — это
        // и дуб, и берёза, и что из них есть у бота
        bool TryAny(IReadOnlyList<string> codes, int wanted, int depth)
        {
            int первый = -1;
            foreach (string variant in codes)
            {
                var undo = Mark();
                if (Need(variant, wanted, depth))
                    return true;
                // Причину оставляем от ПЕРВОГО варианта: перечислить в отказе
                // все шесть пород дерева — значит не сказать ничего
                if (первый < 0)
                    первый = dead.Count;
                else
                    Forget(первый);
                Undo(undo);
            }
            return false;
        }

        (int Steps, Dictionary<string, int> Spent) Mark() =>
            (steps.Count, new Dictionary<string, int>(spent, StringComparer.OrdinalIgnoreCase));

        void Undo((int Steps, Dictionary<string, int> Spent) mark)
        {
            steps.RemoveRange(mark.Steps, steps.Count - mark.Steps);
            spent.Clear();
            foreach (var (code, n) in mark.Spent)
                spent[code] = n;
        }

        void Forget(int from) => dead.RemoveRange(from, dead.Count - from);
    }

    /// <summary>
    /// ЧТО ПРОДЕЛАТЬ, чтобы потребность закрылась: что добыть, что вытесать,
    /// что собрать. Живой ответ — он спрашивает реестры сервера и сумку.
    ///
    /// Требование бывает ВИДОМ («Axe» — любой топор), поэтому перебираются все
    /// подходящие предметы, и берётся тот, до которого МЕНЬШЕ ШАГОВ: каменный
    /// топор из палки и камня ближе медного, которому нужно кованое топорище, а
    /// наковальни у бота нет. Порядок по тиру — только для равных: из двух
    /// одинаково близких берём тот, что берёт породу потвёрже.
    /// </summary>
    /// <param name="count">
    /// ЧТОБЫ СТАЛО СТОЛЬКО (а не «сделай ещё столько»): уже лежащее в сумке
    /// разбор засчитывает сам, и «есть 8, надо 12» — это два шага, а не
    /// двенадцать. Так спрашивают и окно, и чат, и «доделать начатое».
    /// </param>
    /// <param name="more">
    /// СЧИТАТЬ <paramref name="count"/> ПРИБАВКОЙ, А НЕ ИТОГОМ. Нужно ровно
    /// одному звонящему — звену «крафт» у снабжения, и вот почему.
    ///
    /// ЖИВАЯ ДЫРА, НАЙДЕННАЯ ПРИЁМКОЙ 22.08. Снабжение просит закрыть НЕХВАТКУ
    /// («надо 12, есть 8» → «сделай 4»), а разбор те же 4 понимал как итог — и
    /// на кандидате «ladder-wood-acacia-north», которых в сумке лежало 8,
    /// честно отвечал «уже есть»: ноль шагов, крафт не позван ни разу, звено
    /// докладывает «ничего не прибавилось», нужда уходит в безнадёгу с «больше
    /// не пробую». В окне человек видит «ladder 8/12» красным навсегда — тот
    /// самый вопрос «почему лестницы красные», только на другой половине
    /// стопки: беда просыпается, как только запаса набралось больше, чем не
    /// хватает (есть ≥ не хватает).
    ///
    /// Прибавка считается ПО КАЖДОМУ КАНДИДАТУ ОТДЕЛЬНО (<c>count + Exact</c>),
    /// а не одним числом сверху: восемь дощатых лестниц в сумке не приближают
    /// сборку палочных ни на шаг, и просить у палочной ветки «двенадцать
    /// итого» значило бы сделать восемь лишних.
    /// </param>
    public MakePlan PlanFor(string want, int count, bool more = false)
    {
        bool Suits(string code) =>
            MatcherOf(want) is { } match ? match(code) : InFamily(code, want);

        var candidates = new List<string>();
        // Требование по имени предмета («torch») — сам себе кандидат
        if (RecipesFor(want).Count > 0 || CanFetch(want))
            candidates.Add(want);
        foreach (string code in Makeable())
            if (Suits(code) && !candidates.Contains(code, StringComparer.OrdinalIgnoreCase))
                candidates.Add(code);

        // Тот же порядок, что у WhatToMake: лучший по тиру, при равном — с
        // более коротким кодом. Иначе «держать кирку» закрывалось бы щупом
        // (prospectingpick-copper — тоже tool: pickaxe)
        candidates.Sort((a, b) =>
        {
            int tier = ctx.World.ToolTier(b) - ctx.World.ToolTier(a);
            return tier != 0 ? tier
                : a.Length != b.Length ? a.Length - b.Length
                : string.CompareOrdinal(a, b);
        });

        var разборы = candidates
            .Take(Math.Max(1, MaxMakeCandidates))
            // «Ещё столько» переводится в «чтобы стало столько» ЗДЕСЬ, у самого
            // кандидата: только тут известно, сколько ИМЕННО ТАКИХ уже в сумке
            .Select(candidate => Plan(candidate, more ? count + Exact(candidate) : count,
                Exact, RecipesFor, CanFetch, MaxMakeDepth))
            .ToList();

        return Best(разборы) ?? new MakePlan(want, [], [want]);
    }

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: какой из разборов брать в работу.
    ///
    /// Сошедшийся бьёт любой несошедшийся. Из сошедшихся — тот, где МЕНЬШЕ
    /// ШАГОВ: у голого бота каменный топор в трёх шагах, а медный не выйдет
    /// вовсе. Из несошедшихся (их покажут человеку отказом) — тот, где
    /// недостающего меньше: «не хватает палки» он закроет за минуту, а «не
    /// хватает слитка, наковальни и молота» читать не станет.
    ///
    /// РАВЕНСТВО РЕШАЕТСЯ ПОРЯДКОМ ВХОДА, и порядок этот не случайный: разборы
    /// приходят лучшим по тиру вперёд. Из двух одинаково близких топоров бот
    /// возьмёт тот, что рубит быстрее.
    /// </summary>
    public static MakePlan? Best(IReadOnlyList<MakePlan> plans)
    {
        MakePlan? best = null, nearest = null;
        foreach (var plan in plans)
            if (plan.Possible)
            {
                if (best == null || plan.Steps.Count < best.Steps.Count)
                    best = plan;
            }
            else if (nearest == null || plan.DeadEnds.Count < nearest.DeadEnds.Count)
                nearest = plan;
        return best ?? nearest;
    }

    /// <summary>Разобранные рецепты по коду — на одно снаряжение, потом заново.</summary>
    private readonly Dictionary<string, IReadOnlyList<MakeRecipe>> recipeBook =
        new(StringComparer.OrdinalIgnoreCase);

    /// <summary>Сколько ИМЕННО таких в сумках (точный код, а не кусок кода).</summary>
    private int Exact(string code) =>
        ctx.Hands.CountOf(s => s.Code is { } c &&
                               string.Equals(WithoutDomain(c), WithoutDomain(code),
                                   StringComparison.OrdinalIgnoreCase));

    /// <summary>
    /// Всё, что на этом сервере вообще умеют делать: сетка и тёска.
    ///
    /// «УМЕЮТ ДЕЛАТЬ» ЗНАЧИТ «УМЕЕТ ЭТОТ БОТ», а не «есть в реестре». Разница
    /// поймана ЖИВЫМ ПРОГОНОМ 27.08, и без неё правило черты класса делало
    /// хуже, чем было. Требование «Bow» перебирает кандидатов из этого списка;
    /// bow-crude заперт чертой «bowyer», и рецептов у него для бота НОЛЬ —
    /// значит разбор объявлял его тупиком. Тупик с ОДНИМ недостающим бьёт
    /// тупик bow-simple (тоже одно — flaxfibers), а код у bow-crude короче,
    /// то есть он идёт первым и побеждает. Живой бот сказал человеку буквально:
    ///     «Bow сделать не из чего — не хватает: bow-crude (в реестре сервера
    ///      нет ни одного блока, с которого он падает)»
    /// — то есть предложил ПРИНЕСТИ ему лук вместо того, чтобы назвать льняное
    /// волокно. Кандидат, которого этот бот сделать не может ни при каких
    /// материалах, кандидатом быть не должен вовсе.
    /// </summary>
    private IEnumerable<string> Makeable()
    {
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        if (ctx.Crafting is { Ready: true } crafting)
            foreach (var recipe in crafting.All)
            {
                // Заперто чертой — для ЭТОГО бота рецепта нет (Crafting.LockedByTrait).
                // Проверка стоит ДО seen.Add нарочно: у вещи, которую делают и
                // так, и этак, второй, открытый рецепт обязан её вернуть
                if (Crafting.LockedByTrait(recipe))
                    continue;
                if (seen.Add(recipe.OutputCode))
                    yield return recipe.OutputCode;
            }
        if (ctx.Knapping is { Ready: true } knapping)
            foreach (var recipe in knapping.Recipes)
                if (!recipe.IngredientIsBlock && seen.Add(recipe.OutputCode))
                    yield return recipe.OutputCode;
    }

    /// <summary>
    /// ЧЕМ ЭТО ДЕЛАЮТ НА ЭТОМ СЕРВЕРЕ — из двух реестров сразу: сетка 3×3 и
    /// камнетёсство. Ни одного кода в нашем коде: топорище из кремня найдётся
    /// потому, что так сказал сервер.
    ///
    /// Рецепты идут в порядке «чем меньше бегать»: впереди те, на которые
    /// материал уже лежит в сумке.
    /// </summary>
    private IReadOnlyList<MakeRecipe> RecipesFor(string code)
    {
        if (recipeBook.TryGetValue(code, out var known))
            return known;

        var list = new List<MakeRecipe>();
        if (ctx.Crafting is { Ready: true } crafting)
            foreach (var recipe in crafting.RecipesFor(code))
            {
                // Сетка у игрока 3×3, и другой не бывает: рецепт под верстак
                // побольше сюда не разложить
                if (recipe.Width > Crafting.GridWidth || recipe.Height > Crafting.GridWidth)
                    continue;
                // ЧЕРТА КЛАССА ЗАКРЫВАЕТ РЕЦЕПТ ДЛЯ РАЗБОРА ТОЖЕ, и это не
                // повтор проверки, а ЕЁ ЖЕ ОДНО ПРАВИЛО (Crafting.LockedByTrait)
                // на втором пути. Пути и правда два, и они разные: сбор ищет
                // лучший рецепт по тому, что уже в сумке, а разбор строит
                // цепочку походов НАПЕРЁД. Не закрой мы разбор — бот с полной
                // честностью сходил бы за верёвкой на грубый лук (bow-crude:
                // черта «bowyer»), а сервер не принял бы сетку
                if (Crafting.LockedByTrait(recipe))
                    continue;
                if (Inputs(recipe) is not { } inputs)
                    continue;
                list.Add(new MakeRecipe(MakeWay.Grid, code, recipe.OutputQuantity, inputs));
            }

        if (ctx.Knapping is { Ready: true } knapping)
            foreach (var recipe in knapping.Recipes)
            {
                if (!string.Equals(recipe.OutputCode, code, StringComparison.OrdinalIgnoreCase) ||
                    recipe.IngredientIsBlock)
                    continue;
                // ОДИН КАМЕНЬ УХОДИТ В ДЕЛО, ЕЩЁ ОДИН ОСТАЁТСЯ В РУКЕ: с пустой
                // рукой сервер молча не считает удары, и бот «тешет» впустую
                list.Add(new MakeRecipe(MakeWay.Knap, recipe.OutputCode,
                    recipe.OutputCount, [new MakeInput(recipe.IngredientCode, 1, 1)]));
            }

        // ПРОМЫВКА ЛОТКОМ — ЧЕТВЁРТЫЙ СПОСОБ, И ОН СПРАШИВАЕТ МИР, А НЕ ТОЛЬКО
        // РЕЕСТР. Реестр отвечает «эта вещь из лотка выпадает вообще», а тут
        // нужен ответ «намыть можно ЗДЕСЬ»: без воды под ногами игра промывку
        // не считает вовсе (ingameerror-panning-notinwater), и обещать её на
        // сухом плато значило бы врать планом (закон 4). Ровно этой разницей —
        // «бывает в игре» против «есть здесь» — уже сторожит себя добыча в мире
        // (см. CanFetch → Errands.NearbyNow).
        //
        // ЛОТОК В СОСТАВЛЯЮЩИХ, А НЕ В УСЛОВИИ: он ИНСТРУМЕНТ (Once = 1, за
        // повтор не тратится), и потому разбор сам уйдёт вглубь — «лотка нет,
        // значит сделать лоток», а это бревно и любой нож. Без этого шага цепочка
        // «нет волокон → нет лотка → нечем мыть» осталась бы кольцом.
        // МЕСТО ИЩЕТСЯ ПОД ЭТУ САМУЮ ВЕЩЬ, а не «хоть какое». Здесь стояло
        // «FindSpot()» без довода, и способ заводился по КОНЪЮНКЦИИ ДВУХ
        // РАЗНЫХ ВОПРОСОВ: «волокна лотком вообще бывают» и «какой-то
        // промываемый блок есть у воды». В живом мире у воды лежит песок, а
        // волокна даёт костяная земля за четырнадцать блоков — план обещал
        // намыть, а бот уходил мыть песок (приёмка 27.08, находка 4)
        if (ctx.Panning is { Allowed: true, Ready: true } лоток &&
            лоток.KnownPans.Count > 0 &&
            лоток.WaysTo(code).Count > 0 &&
            лоток.FindSpot(code) != null)
            list.Add(new MakeRecipe(MakeWay.Pan, code, 1,
                [new MakeInput([.. лоток.KnownPans], PerCraft: 0, Once: 1)]));

        list.Sort((a, b) => Unavailable(a) - Unavailable(b));
        recipeBook[code] = list;
        return list;

        int Unavailable(MakeRecipe recipe) =>
            recipe.Inputs.Count(i => i.Codes.All(c => Exact(c) == 0));
    }

    /// <summary>
    /// Составляющие рецепта сетки, сведённые к кодам. null — среди клеток есть
    /// такая, которую бот назвать не может: врать «сделаю» про неё нельзя.
    /// </summary>
    private IReadOnlyList<MakeInput>? Inputs(CraftRecipe recipe)
    {
        var merged = new List<MakeInput>();
        foreach (var ingredient in recipe.Ingredients)
        {
            var codes = Suitable(ingredient);
            if (codes.Count == 0)
                return null;

            // Инструмент в рецепте НЕ ТРАТИТСЯ, а стирается: одного хватит на
            // все повторы. Съедаемое, наоборот, множится на число повторов
            int per = ingredient.Consumed ? ingredient.Quantity : 0;
            int once = ingredient.Consumed ? 0 : ingredient.Quantity;

            // Две клетки с одним и тем же — это одно требование на двойное
            // число, иначе «две палки» посчитались бы как «одна палка дважды»
            int same = merged.FindIndex(m =>
                m.Codes.SequenceEqual(codes, StringComparer.OrdinalIgnoreCase));
            if (same >= 0)
                merged[same] = merged[same] with
                {
                    PerCraft = merged[same].PerCraft + per,
                    Once = Math.Max(merged[same].Once, once)
                };
            else
                merged.Add(new MakeInput(codes, per, once));
        }
        return merged;
    }

    /// <summary>
    /// Какими кодами закрывается ингредиент. Конкретный код возвращается как
    /// есть — это подавляющее большинство случаев: сервер разворачивает
    /// «axehead-{material}» в отдельный рецепт на каждый материал ещё при
    /// загрузке. Маска («plank-*») и условие по меткам спрашиваются У РЕЕСТРА:
    /// свой список пород и деревьев тут был бы вторым источником правды.
    ///
    /// ЧЕСТНО ПРО ПОТОЛОК: у маски берётся не больше
    /// <see cref="MaxIngredientVariants"/> первых подошедших кодов, и просмотр
    /// реестра тоже ограничен. Значит редкий вариант («доска только из эбена»)
    /// бот может не увидеть и сказать «не из чего» там, где вариант был. Это
    /// плата за то, чтобы снаряжение не превращалось в минуту молчания.
    /// </summary>
    private IReadOnlyList<string> Suitable(CraftIngredient ingredient)
    {
        if (ingredient.Code is { Length: > 0 } exact && !exact.Contains('*'))
            return [WithoutDomain(exact)];

        string mask = ingredient.Code is { Length: > 0 } code
            ? WithoutDomain(code).Split('*')[0]
            : "";

        // ИНГРЕДИЕНТ БЕЗ КОДА — ЭТО «ЛЮБОЙ НОЖ», И ИСКАТЬ ЕГО НАДО ПО ВСЕМУ
        // РЕЕСТРУ, А НЕ В ПЕРВЫХ ПЯТИСТАХ.
        //
        // ЖИВАЯ БЕДА 27.08, ЗАКРЫВАВШАЯ ЛОТОК, А С НИМ И ЛУК. У рецепта лотка
        // (recipes/grid/tool/pan.json) вторая клетка задана НЕ кодом, а тегом:
        // «{ tags: ["tool-knife"], isTool: true }» — годится любой нож. Код у
        // такого ингредиента null, маска выходит пустой, и просмотр упирался в
        // RegistryLook: первые 512 кодов реестра, среди которых ножа нет.
        // Suitable возвращал пусто → Inputs отдавал null → рецепт выбрасывался
        // из разбора целиком → «!какдобыть pan-wooden» отвечал «в реестрах
        // сервера нет ни рецепта, ни блока, с которого он падает».
        // Это была НЕПРАВДА, и живая улика лежит рядом, в том же прогоне:
        // «!рецепт pan-wooden» → «Нашёл: pan-wooden. Для pan-wooden не хватает:
        // log-* 0/1, *:* 0/1». Рецепт был, и сбор его видел; слеп был разбор.
        //
        // ЦЕНА ПОЛНОГО ПРОСМОТРА МАЛА: ингредиентов по тегам в ванили единицы
        // (это инструменты), а разобранные рецепты лежат в recipeBook и второй
        // раз не считаются. Ограничивать здесь — значит снова потерять рецепт
        // молча, а молчание в этом проекте дороже миллисекунд (закон 4)
        // ПРЕДЕЛ РЕШАЕТ МАСКА, А НЕ КОД. Тег-ингредиент приходит с сервера НЕ
        // пустым кодом, а всеядной маской «*:*» (живой ответ бота на «!рецепт
        // pan-wooden»: «не хватает log-* 0/1, *:* 0/1»), и от неё маска выходит
        // пустой. Спроси мы про КОД — предел остался бы прежним, и лоток снова
        // пропал бы из разбора: ровно этой ошибкой первая попытка починки 27.08
        // не изменила живой ответ ни на букву
        int сколькоСмотреть = RegistryLookFor(mask);

        var found = new List<string>();
        foreach (string candidate in ctx.World.SearchItemCodes(mask, сколькоСмотреть)
                     .Concat(ctx.World.SearchBlockCodes(mask, сколькоСмотреть)))
        {
            if (!ingredient.Matches(ctx.World, candidate) ||
                found.Contains(candidate, StringComparer.OrdinalIgnoreCase))
                continue;
            found.Add(candidate);
            if (found.Count >= MaxIngredientVariants)
                break;
        }
        // Короткий код обычно и есть простой вариант: «plank-oak», а не
        // «plank-ebony», который растёт в одном краю карты
        found.Sort((a, b) => a.Length != b.Length ? a.Length - b.Length
            : string.CompareOrdinal(a, b));
        return found;
    }

    /// <summary>Сколько кодов реестра просматривать под одну маску ингредиента.</summary>
    private const int RegistryLook = 512;

    /// <summary>
    /// СКОЛЬКО КОДОВ РЕЕСТРА ПРОСМАТРИВАТЬ ПОД ЭТОТ ИНГРЕДИЕНТ. Чистое правило,
    /// потому что живьём разница видна только на редком рецепте, а сломать её
    /// можно одним словом.
    ///
    /// У ингредиента С МАСКОЙ («plank-*») просмотр ограничен: маска сама по
    /// себе отсекает лишнее, а перебирать тринадцать тысяч кодов на каждую
    /// клетку — минута молчания вместо ответа.
    ///
    /// У ингредиента ПО ТЕГУ («любой нож») отсекать нечем: сервер шлёт его
    /// всеядной маской «*:*», маска для просмотра выходит ПУСТОЙ, и предел
    /// превращается в «первые 512 кодов реестра». Ножа среди них нет.
    ///
    /// ЖИВАЯ БЕДА 27.08: рецепт лотка (pan.json — бревно плюс любой нож)
    /// выбрасывался из разбора целиком, и «!какдобыть pan-wooden» отвечал
    /// «в реестрах сервера нет ни рецепта, ни блока, с которого он падает».
    /// Рецепт был: «!рецепт pan-wooden» в том же прогоне отвечал «Для pan-wooden
    /// не хватает: log-* 0/1, *:* 0/1». А без лотка не намыть волокон, без
    /// волокон нет тетивы, без тетивы нет лука — и две волны подряд объясняли
    /// это пустым зимним миром.
    ///
    /// СПРАШИВАЕМ ИМЕННО МАСКУ, А НЕ КОД, И ЭТО НЕ ПРИДИРКА: первая попытка
    /// починки в тот же день спрашивала код — «есть ли он вообще» — и не
    /// изменила живой ответ ни на букву, потому что код у тег-ингредиента есть,
    /// он просто ничего не значит.
    /// </summary>
    public static int RegistryLookFor(string? ingredientMask) =>
        ingredientMask is { Length: > 0 } ? RegistryLook : int.MaxValue;

    /// <summary>Сколько разных кодов держать как «чем закрыть» одну клетку.</summary>
    private const int MaxIngredientVariants = 6;

    /// <summary>
    /// Можно ли это ВЗЯТЬ — не только в мире, но и В СВОЁМ СУНДУКЕ.
    ///
    /// СУНДУК ЗДЕСЬ ПОЯВИЛСЯ ВМЕСТЕ СО СВЕДЁННОЙ ЦЕПОЧКОЙ, и без него правка
    /// была бы шагом назад. Разбор «что из чего» ставит шаг «добыть» только
    /// туда, где ответ «да»; спрашивал он один лишь МИР — и ветка, чей материал
    /// лежит в описанном сундуке, объявлялась тупиком. Пока звено «крафт» у
    /// снабжения ходило мимо разбора, дыру закрывал <c>Crafting.RestockAsync</c>
    /// (он спрашивает всю цепочку); теперь мастерская одна, и знать про сундук
    /// обязана она. Это ровно та жалоба заказчика: «он знал что у него есть
    /// склад и проверил что там есть, там было все для крафта дороги, а он не
    /// стал туда возвращаться и докрафчивать».
    ///
    /// Считаем ТОЛЬКО ОПИСЬ СУНДУКОВ, без сумок: сколько лежит в сумке, разбор
    /// вычел сам, и прибавь мы её сюда — на остаток вышел бы шаг «сходи
    /// возьми», которому идти некуда.
    ///
    /// Три запрета на МИРСКУЮ половину, и все три из живых случаев:
    /// - требование по реестру («любой топор») в мире искать нечего: поручение
    ///   ищет источник по КУСКУ КОДА, а «Axe» — это вид из перечисления игры;
    /// - ИНСТРУМЕНТ в земле не растёт. Живьём на «нужна кирка» бот ушёл искать
    ///   «toolmold-blue-fired-pickaxe» — форму для отливки: кусок кода подошёл;
    /// - того, что не падает ни с одного блока реестра, не добыть в принципе, и
    ///   сказать об этом надо сразу, а не изображать поиск.
    /// Сундука эти запреты не касаются: кирку из своего ящика берут, и факел
    /// тоже — запрещено лишь искать их в земле.
    ///
    /// ЧЕТВЁРТЫЙ ЗАПРЕТ И ПЯТЫЙ ВОПРОС — ИЗ ЖИВЫХ ЖУРНАЛОВ 22.08, см.
    /// <see cref="BannedFromWorld"/> (лестница) и <see cref="Errands.NearbyNow"/>
    /// (кремнистый сланец).
    /// </summary>
    private bool CanFetch(string code)
    {
        if (fetchable.TryGetValue(code, out bool known))
            return known;
        bool вСундуке = !ByRegistry(code) && ctx.Depot is { } depot && depot.InDepot(code) > 0;
        bool вМире = !ByRegistry(code) && !BannedFromWorld(code) &&
                     ctx.World.ToolOf(code) == null &&
                     ctx.Errands is { } errands && errands.Sources(code).Length > 0 &&
                     // «БЫВАЕТ В ИГРЕ» И «ЕСТЬ ЗДЕСЬ» — РАЗНЫЕ ОТВЕТЫ, и до этой
                     // строки разбор знал только первый. Живой журнал: «чтобы
                     // получить Axe, надо: добыть stone-chert ×2 …» → «stone-chert
                     // рядом больше не нахожу», и так прогон за прогоном которую
                     // неделю, при том что вокруг лежал перидотит — топор из него
                     // ровно такой же. Спросив мир, разбор объявит кремнистую
                     // ветку тупиком и возьмёт перидотитовую
                     errands.NearbyNow(code);
        bool answer = вСундуке || вМире;
        fetchable[code] = answer;
        return answer;
    }

    /// <summary>
    /// ЭТО ЗАПРЕЩЕНО ДОБЫВАТЬ В МИРЕ — потому что так велено про ТРЕБОВАНИЕ,
    /// которое этим кодом и закрывается.
    ///
    /// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО НАПИСАНО (окно управления 22.08, «ladder
    /// 8/64» неделю подряд). Роль просит «держать 64 лестницы» с запретом
    /// добычи: <c>Require("ladder", 64, fetch: false)</c> — лестницу в мире не
    /// выламывают, это разбирать чужую шахту. Запрет лежал под именем
    /// ТРЕБОВАНИЯ («ladder»), а разбор берёт кандидатов из реестра рецептов и
    /// планирует уже КОНКРЕТНЫЙ код («ladder-wood-acacia-north»). Про него
    /// запрета не было, зато он сам с себя и падает, — и разбор выдавал
    /// «добыть ladder-wood-acacia-north ×56» одним шагом. Одним! А сделать из
    /// палок — двумя, и <see cref="Best"/> честно предпочитал короткий.
    /// Дальше цепочка упиралась в тот же запрет уже на исполнении и умирала,
    /// так ни разу и не попробовав крафт. Ровно то, что видел заказчик: восемь
    /// лестниц, красное «8/64» и ни одной сделанной.
    ///
    /// Мерка — та же, какой требование меряет сумку (<see cref="Have"/>):
    /// реестровая для инструментов, семейная для остальных. Иначе запрет и
    /// подсчёт говорили бы о разных вещах.
    /// </summary>
    private bool BannedFromWorld(string code)
    {
        foreach (string want in NoFetchSnapshot())
        {
            if (string.Equals(WithoutDomain(code), WithoutDomain(want),
                    StringComparison.OrdinalIgnoreCase))
                return true;
            if (MatcherOf(want) is { } match ? match(code) : InFamily(code, want))
                return true;
        }
        return false;
    }

    /// <summary>
    /// Ответы «где это взять» на время одного снаряжения.
    ///
    /// Не украшение: мирская половина ответа — это обход реестра блоков целиком
    /// (тринадцать тысяч записей с их выпадениями). Разбор плана спрашивает
    /// одно и то же по многу раз, перебирая отвергнутые ветки, и без памяти
    /// «снарядись» превращалось бы в секунды тишины.
    ///
    /// ЖИВЁТ РОВНО ОДНО СНАРЯЖЕНИЕ, а не до переподключения, как было. Причина
    /// в том, что ответ теперь смотрит и в ОПИСЬ СУНДУКОВ, а она меняется на
    /// каждом рейсе: запомни мы её на весь вечер — бот ходил бы за материалом в
    /// сундук, который сам же вчера и опустошил.
    /// </summary>
    private readonly Dictionary<string, bool> fetchable = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// МАСТЕРСКАЯ: СДЕЛАТЬ НЕДОСТАЮЩЕЕ, а нет материала — сперва сходить за ним.
    /// Возвращает причину отказа словами (null — сделано) и сколько всего
    /// добыто по дороге.
    ///
    /// ОТКРЫТА НАРУЖУ НАРОЧНО, И ЭТО ЗАКРЫТЫЙ ДОЛГ. Звено «крафт» у снабжения
    /// (<see cref="Supply"/>) звало <c>Crafting.CraftAsync</c> — сборку из того,
    /// что уже в сумке, — и на пустой сумке отвечало «не хватает составляющих».
    /// Разбор «что из чего», который умеет ответить, где эти составляющие
    /// взять, жил здесь и звался только отсюда. Две цепочки на одну работу
    /// разошлись в первый же вечер. Теперь мастерская одна, и звено снабжения —
    /// дверь в неё.
    ///
    /// За материалом мастерская ходит ТУДА ЖЕ, В СНАБЖЕНИЕ (см.
    /// <see cref="StepAsync"/>), так что порядок «сумки → склад работы → дом →
    /// рядом» тут не повторён ни разу.
    /// </summary>
    /// <param name="deadline">
    /// Когда бросать; по умолчанию — <see cref="MaxSeconds"/> от этой секунды.
    /// Своего срока у звонящего из снабжения нет, а работа без срока однажды
    /// станет молчанием на минуты.
    /// </param>
    public async Task<(string? Why, int Fetched)> MakeAsync(string want, int count,
        DateTime? deadline = null, CancellationToken ct = default)
    {
        // Справочник «что из чего» отсортирован по тому, чего в сумке больше, а
        // сумка меняется на каждом шаге. Держать его между заходами — значит
        // идти по вчерашней сумке; пополнение чистит его само, а звонящему
        // из снабжения чистить нечем. Память «где это взять» — по той же
        // причине: она смотрит в опись сундуков, а опись меняется рейсом
        recipeBook.Clear();
        fetchable.Clear();
        return await МастеритьAsync(want, count,
            deadline ?? DateTime.UtcNow.AddSeconds(Math.Max(1, MaxSeconds)), ct);
    }

    private async Task<(string? Why, int Fetched)> МастеритьAsync(string want, int count,
        DateTime deadline, CancellationToken ct)
    {
        // Самый частый и самый дешёвый случай: материалы уже в сумке
        if (WhatToMake(want) is { } ready && ctx.Crafting is { } crafting)
        {
            var made = await crafting.CraftAsync(ready, count, ct);
            if (made.Crafted > 0)
            {
                OnLog?.Invoke($"сделал {ready} ×{made.Crafted}");
                return (null, 0);
            }
            OnLog?.Invoke($"{ready} сразу не собрался ({made.Message}) — " +
                          "смотрю, чего именно не хватает");
        }

        // ЗВОНЯЩИЙ ПРОСИТ ПРИБАВКУ, А НЕ ИТОГ. Единственный звонящий у этой
        // мастерской — звено «крафт» снабжения, и просит оно ровно нехватку
        // (Supply: `need - было`). Пойми разбор те же числа как итог — и на
        // половине набранного запаса он ответил бы «уже есть» (см. PlanFor,
        // параметр more): бот стоял бы над красной строкой в окне и ничего не
        // делал. Быстрый путь выше говорит на том же языке: он собирает
        // ИМЕННО столько штук, сколько просят
        var plan = PlanFor(want, count, more: true);
        if (!plan.Possible)
            return (Refusal(want, plan), 0);
        if (plan.Steps.Count == 0)
            return (null, 0);

        OnLog?.Invoke($"чтобы получить {want}, надо: {plan}");
        int fetched = 0;
        foreach (var step in plan.Steps)
        {
            if (ct.IsCancellationRequested)
                return ($"{want}: работу отменили на шаге «{step}»", fetched);
            if (DateTime.UtcNow > deadline)
                return ($"{want}: время на снаряжение вышло, не сделан шаг «{step}»", fetched);

            var (why, got) = await StepAsync(step, deadline, ct);
            if (step.Way == MakeWay.Fetch)
                fetched += Math.Max(0, got);
            if (why is { Length: > 0 })
                return (why, fetched);
        }
        return (null, fetched);
    }

    /// <summary>
    /// Один шаг плана. УСПЕХ ТОЛЬКО ПО ФАКТУ: считается прибавка в сумке, а не
    /// отправленные пакеты и не «сходил и постарался».
    /// </summary>
    private async Task<(string? Why, int Got)> StepAsync(MakeStep step, DateTime deadline,
        CancellationToken ct)
    {
        int was = Exact(step.Code);
        switch (step.Way)
        {
            case MakeWay.Fetch:
                // ОДНОЙ ЦЕПОЧКОЙ, А НЕ СВОИМ ПОРЯДКОМ. Здесь стояло «сперва
                // кладовые (Supply.FromStoresAsync), потом земля (Errands)» —
                // то есть ВТОРАЯ запись того же порядка, что живёт в снабжении.
                // Расходятся такие копии молча: цепочка снабжения знает ещё и
                // «склад именно этой работы», а эта половинка — нет.
                //
                // Живой прогон 16.08, ради которого кладовые тут вообще
                // появились: «не хватает torch ×16 → добыть hay-normal-ud ×4 →
                // hay-normal-ud рядом больше не нахожу» — и так перед каждым
                // нарядом, при том что сено лежало дома. Сама трава в мире
                // кончается, а сундук — нет.
                //
                // Крафт у этого звена ВЫКЛЮЧЕН: чем делать составляющую, уже
                // решил разбор выше (он и поставил сюда шаг «добыть»), и второе
                // решение того же вопроса ходило бы по кругу.
                if (ctx.Supply is not { } снабжение)
                    return ($"{step.Code} взять негде: снабжение к боту не подключено", 0);
                // В ЗЕМЛЕ ИЩЕМ НЕ ВСЁ. Факел и кирку из своего сундука берут, а
                // копать их нельзя: живьём «нужен факел» уводил бота искать
                // настенные держатели факелов. Запрет один на весь класс
                // (BannedFromWorld) и касается он ровно мирского звена
                bool вЗемлюМожно = MayFetch && !BannedFromWorld(step.Code);
                double had = ctx.Errands?.MaxSeconds ?? 0;
                // Срок ОДИН на всё снаряжение, и поручение обязано в него
                // укладываться: иначе один поход за палками съест время,
                // отведённое на кирку, топор и нож разом
                if (ctx.Errands is { } errands)
                    errands.MaxSeconds = Math.Max(10, (deadline - DateTime.UtcNow).TotalSeconds);
                try
                {
                    await снабжение.GetAsync([(step.Code, step.Count, was)], ct: ct,
                        craft: false, nearby: вЗемлюМожно, have: Exact);
                }
                finally
                {
                    if (ctx.Errands is { } e)
                        e.MaxSeconds = had;
                }
                if (!MayFetch && Exact(step.Code) - was < step.Count)
                    return ($"за {step.Code} не иду: ходить за недостающим запрещено настройкой" +
                            WhereFrom(step.Code), Exact(step.Code) - was);
                break;

            case MakeWay.Knap:
                if (ctx.Knapping is not { Ready: true } knapping)
                    return ($"{step.Code} вытесать нечем: реестр камнетёсства не пришёл", 0);
                // Тёска даёт по одной вещи за раз — повторяем, пока не наберём
                while (Exact(step.Code) - was < step.Count &&
                       DateTime.UtcNow < deadline && !ct.IsCancellationRequested)
                {
                    var cut = await knapping.KnapAsync(step.Code, ct);
                    if (!cut.Success)
                        return ($"{step.Code} не вытесать: {cut.Message}", Exact(step.Code) - was);
                }
                break;

            case MakeWay.Pan:
                if (ctx.Panning is not { } лоток)
                    return ($"{step.Code} не намыть: лоток к боту не подключён", 0);
                if (!лоток.Allowed)
                    return ($"{step.Code} не намыть: мыть лотком запрещено ролью " +
                            "(«МытьЛоткомКогдаИначеНегде»)", 0);

                // СКОЛЬКО ПРОМЫВОК — ЧИСЛО ИЗ ТАБЛИЦЫ АССЕТА, А НЕ ИЗ ГОЛОВЫ.
                // Промывка отдаёт не больше одной вещи и чаще пустую, поэтому
                // «намыть 12 волокон» — это около ста десяти заходов кнопки.
                // Ходим ЗАХОДАМИ (роль: «ПромывокЗаЗаход»): между ними бот
                // оглядывается, ест и замечает зверя, а не стоит в воде семь
                // минут слепым
                double шанс = лоток.WaysTo(step.Code).FirstOrDefault().Chance;
                int надо = Panning.PansFor(шанс, step.Count);
                if (надо == int.MaxValue)
                    return ($"{step.Code} лотком не намыть: ни один промываемый блок " +
                            "его не отдаёт", 0);
                while (Exact(step.Code) - was < step.Count &&
                       DateTime.UtcNow < deadline && !ct.IsCancellationRequested)
                {
                    var помыл = await лоток.PanAsync(
                        Math.Max(1, Math.Min(лоток.PansPerVisit, надо)), step.Code, ct);
                    // Ни одной промывки за заход — дальше стоять незачем: причина
                    // названа внутри (нет лотка, нет воды, нет земли у воды)
                    if (помыл.Pans == 0)
                        return ($"{step.Code} не намыть: {помыл.Message}", Exact(step.Code) - was);
                }
                break;

            default:
                if (ctx.Crafting is not { Ready: true } crafting)
                    return ($"{step.Code} не собрать: реестр рецептов сетки не пришёл", 0);
                var made = await crafting.CraftAsync(step.Code, step.Count, ct);
                if (made.Crafted <= 0)
                    return ($"{step.Code} не собрать: {made.Message}", 0);
                break;
        }

        int got = Exact(step.Code) - was;
        return got >= step.Count
            ? (null, got)
            : ($"{step} — вышло {Math.Max(0, got)} из {step.Count}{WhereFrom(step.Code)}", got);
    }

    /// <summary>
    /// ОТКАЗ ОБЯЗАН НАЗВАТЬ НЕДОСТАЮЩЕЕ. Прежняя строка «сделать не из чего:
    /// подходящего рецепта нет или не хватает материалов» не годилась никуда:
    /// по ней человек не мог ни положить боту нужное, ни понять, что бот вообще
    /// умеет. Теперь называется каждый тупик и то, откуда его берут.
    ///
    /// ОТКРЫТ НАРУЖУ РАДИ «!какдобыть», И ЭТО НЕ УДОБСТВО, А ЕДИНСТВЕННОСТЬ
    /// СЛОВ. Команда печатала сам разбор (<c>MakePlan.ToString</c>), а он знает
    /// только КОДЫ: на «!какдобыть bow-crude» живой бот 27.08 ответил «негде
    /// взять bow-crude» — то есть свалил на пустой мир то, что на самом деле
    /// запрещено чертой класса. Реестр знает здесь, а не там.
    /// </summary>
    public string Refusal(string want, MakePlan plan)
    {
        // Тупик на самой вещи означает одно: рецептов на неё в реестре этого
        // сервера нет вовсе. Пересказывать это как «не хватает топора» — значит
        // сообщать человеку то, что он и так видит
        if (plan.DeadEnds.Count == 1 &&
            string.Equals(plan.DeadEnds[0], want, StringComparison.OrdinalIgnoreCase))
            // «НИ РЕЦЕПТА, НИ БЛОКА» — ПРАВДА НЕ ВСЕГДА. Рецепт бывает и есть,
            // просто заперт чертой класса: человек видит его в справочнике
            // игры, а бот отвечает «в реестрах сервера нет ни рецепта». Это не
            // мелочь, это отказ, который посылает искать несуществующее
            return ЗапертоЧертой(want) is { Length: > 0 } черта
                ? $"{want} мне не собрать: рецепт есть, но требует черту класса " +
                  $"«{черта}», а своего класса бот не знает вовсе — положите " +
                  "готовое в сумку или в сундук склада"
                // «НЕТ НИ БЛОКА» — ТОЖЕ ПРАВДА НЕ ВСЕГДА, И ЭТО ЖИВАЯ УЛИКА 27.08.
                // Прогон сборщика волны: «!какдобыть flaxfibers» отвечал «в
                // реестрах сервера нет ни рецепта, ни блока, с которого он
                // падает», а соседняя команда «!откуда flaxfibers» в том же
                // прогоне отвечала «даёт блоков 1: crop-flax-9», и «!рядом
                // crop-flax 96» находила спелый лён в живом мире. Блок был, и
                // бот про него знал; не было его РЯДОМ. Про ту же вещь внутри
                // цепочки бот при этом говорил верно («падает с crop-flax-9;
                // но НИ ОДНОГО из них нет вокруг меня») — то есть два ответа
                // одного бота про одну вещь расходились, и врал тот, который
                // спрашивают прямо
                : ctx.Errands is { } поручения && поручения.Sources(want).Length > 0
                    ? $"{want} здесь не добыть: рецепта на него в реестре сервера " +
                      $"нет вовсе{WhereFrom(want)} — положите готовое в сумку " +
                      "или в сундук склада"
                    : $"{want} на этом сервере нечем сделать и негде взять " +
                      "(в реестрах сервера нет ни рецепта, ни блока, с которого он падает) — " +
                      "положите готовое в сумку или в сундук склада";

        return $"{want} сделать не из чего — не хватает: " +
               string.Join("; ", plan.DeadEnds.Select(code => code + WhereFrom(code)));
    }

    /// <summary>
    /// Откуда это берут — по реестру сервера, чтобы отказ можно было проверить
    /// руками, а не поверить на слово.
    /// </summary>
    private string WhereFrom(string code)
    {
        // ЧЕРТА КЛАССА — ПЕРВЫМ ОТВЕТОМ, ДО ВСЯКОГО «ПАДАЕТ С». Рецепт на вещь
        // ЕСТЬ, и человек его видит в справочнике игры; сказать ему «в реестре
        // нет ни одного блока, с которого он падает» значит послать его искать
        // в мире то, что делают руками. Ровно так живой бот 27.08 ответил на
        // «!какдобыть bow-crude»
        if (ЗапертоЧертой(code) is { Length: > 0 } черта)
            return $" (рецепт на него есть, но требует черту класса «{черта}», " +
                   "а своего класса бот не знает вовсе и обещать такой сбор не станет)";

        if (ctx.Errands is not { } errands)
            return "";
        var sources = errands.Sources(code);
        if (sources.Length == 0)
            return " (в реестре сервера нет ни одного блока, с которого он падает — " +
                   "принесите сами или положите в сундук склада)";

        // «ГДЕ ЭТО БЫВАЕТ» И «ГДЕ ЭТО ЕСТЬ» — РАЗНЫЕ ОТВЕТЫ, и человеку нужен
        // второй. Прямые слова заказчика 22.08 про кремнистый сланец: «если
        // вокруг его нет, надо либо брать ДРУГУЮ породу, либо честно сказать —
        // в этой местности такого камня нет, принесите». Первое делает разбор
        // (он объявит эту ветку тупиком и возьмёт ту породу, что лежит вокруг),
        // второе говорится вот здесь
        string здесь = errands.NearbyNow(code)
            ? ""
            : "; но НИ ОДНОГО из них нет вокруг меня — в этой местности этого " +
              "не найти: принесите, положите в сундук склада или отведите меня туда, где оно есть";
        return $" (падает с {string.Join(", ", sources.Take(3))}" +
               (sources.Length > 3 ? $" и ещё {sources.Length - 3}" : "") + здесь + ")";
    }

    /// <summary>
    /// ЧЕМ ИМЕННО ЗАПЕРТ РЕЦЕПТ НА ЭТУ ВЕЩЬ — имя черты класса; пусто, когда
    /// не заперт (или рецептов нет вовсе, и это уже другой ответ).
    ///
    /// Спрашивается у одного правила на весь проект
    /// (<see cref="Crafting.LockedByTrait"/>), а не у второй его копии.
    /// </summary>
    private string ЗапертоЧертой(string code)
    {
        if (ctx.Crafting is not { Ready: true } crafting)
            return "";
        var рецепты = crafting.RecipesFor(WithoutDomain(code));
        if (рецепты.Count == 0 || !рецепты.All(Crafting.LockedByTrait))
            return "";
        return рецепты[0].RequiresTrait ?? "";
    }

    /// <summary>Одна строка для чата и панели.</summary>
    public override string ToString() =>
        Wants.Count == 0 ? "запасы не заданы" : string.Join(", ", Check());
}
