namespace VsBotKit;

/// <summary>
/// ГДЕ ПОТОЛОК НАД КЛЕТКОЙ — ОДНА МЕРКА НА ВЕСЬ ПРОЕКТ.
///
/// ЗАЧЕМ ОТДЕЛЬНЫМ ПРАВИЛОМ. Счёт потолка был выписан ТРИЖДЫ: у безголового
/// бота (<c>WorldModel.CeilingOver</c>), у него же чуть иначе для просвета над
/// ногами (<c>WorldModel.ClearanceAt</c>) и третий раз в моде
/// (<c>ModPathWorld.CeilingOver</c>), причём окно взгляда «4» было вписано
/// руками во второй раз. Док-строка мода при этом уверяла: «мерка одна на мод
/// и на бота». Это было неправдой — это были две несвязанные копии, которые
/// совпадали. Приёмка 27.08 назвала это вслух, и вот единственное место.
///
/// ЛЕСТНИЦА — НЕ ПОТОЛОК, И ЭТО ГЛАВНОЕ, ЧТО ЗДЕСЬ ЕСТЬ. Прежний счёт
/// объявлял потолком «низ первой коллизии». У лестницы игры коробка во всю
/// высоту клетки (assets/survival/blocktypes/wood/woodtyped/ladder.json:
/// <c>collisionbox { y1: 0, y2: 1, z2: 0.1875 }</c>) — тонка она по Z, а не по
/// Y, и низ у неё ровно 0. Отсюда живая беда: плывущий в затопленном колодце с
/// лестницей получал «потолок 114» там, где над ним открытое небо, предел
/// подъёма выходил НИЖЕ его собственных ног, и тело отказывалось лезть наверх
/// ложной причиной. Тот же мир в той же клетке отвечал <c>IsEnterable=True</c>.
///
/// Проект эту ловушку уже знал: в <c>AStarPathFinder</c> над веткой лестниц
/// выписано «Спрашиваем „пройти можно?“, а не „пусто?“: у лестницы сплошная
/// коллизия, и стоя у её подножия бот терял ВСЕ прыжки разом». Новый вопрос к
/// миру наступил на те же грабли — здесь он спрашивает то же самое.
/// </summary>
public static class Ceiling
{
    /// <summary>
    /// ВЫШЕ ЧЕТЫРЁХ КЛЕТОК НЕ СМОТРИМ: тело ростом 1,85, и потолок в четырёх
    /// клетках над водой уже не держит его ни при какой плавучести — а каждый
    /// лишний вопрос к модели мира это чтение чанка.
    /// </summary>
    public const int Look = 4;

    /// <summary>
    /// Низ первой коллизии выше <paramref name="from"/> в колонне
    /// (<c>double.PositiveInfinity</c> — в окне взгляда потолка нет).
    /// </summary>
    /// <param name="from">
    /// Высота, ОТ КОТОРОЙ считаем: коллизия на ней самой или ниже — это пол,
    /// а не потолок. У плывущего это пол клетки, у стоящего — высота ног.
    /// </param>
    /// <param name="firstCell">Номер клетки, с которой начинать просмотр.</param>
    /// <param name="lastCell">Номер клетки, на которой закончить (включительно).</param>
    /// <param name="collisionBottom">
    /// Низ коллизии в клетке, долей блока; 1 — из клетки ничего не свисает.
    /// </param>
    /// <param name="bodySlipsThrough">
    /// ТЕЛО ПРОХОДИТ СКВОЗЬ ЭТУ КЛЕТКУ, НЕСМОТРЯ НА КОЛЛИЗИЮ: лестница, лоза,
    /// проходимая дверь. Такая клетка макушку не держит и потолком не бывает.
    /// </param>
    public static double Above(double from, int firstCell, int lastCell,
        Func<int, float> collisionBottom, Func<int, bool> bodySlipsThrough)
    {
        for (int cy = firstCell; cy <= lastCell; cy++)
        {
            if (bodySlipsThrough(cy))
                continue;                       // лестница/дверь: тело проходит
            float bottom = collisionBottom(cy);
            if (bottom >= 1f)
                continue;                       // из этой клетки ничего не свисает
            double at = cy + bottom;
            if (at <= from + 0.0001)
                continue;                       // это пол, а не потолок
            return at;
        }
        return double.PositiveInfinity;
    }
}
