namespace VsBotKit;

/// <summary>
/// ЧЕГО НУЖДА ПРОСИТ У МИРА — заявка, с которой идут её руки.
///
/// Кода здесь нет и быть не может: нужда называется СВОЙСТВОМ («что съесть»,
/// «чем перевязаться»), а какие коды этим свойством обладают, отвечает реестр
/// сервера. Ровно так же спрашивает снабжение
/// (<see cref="Supply.ForVitalAsync"/>), и мерка тут та же самая.
/// </summary>
/// <param name="Имя">Как назвать нужду человеку: «еда», «лечебное».</param>
/// <param name="Годится">Что из реестра её закрывает.</param>
/// <param name="Сколько">Сколько штук просим за один заход.</param>
public sealed record NeedAsk(string Имя, Func<string, bool> Годится, int Сколько = 1);

/// <summary>
/// ЧЕМ КОНЧИЛСЯ ОДИН СПОСОБ.
/// </summary>
/// <param name="Сдвиг">
/// В мире что-то ПЕРЕМЕНИЛОСЬ от этой попытки — принесли сырьё, убили зверя,
/// развели костёр. Это НЕ успех: успех меряется только тем, закрыта ли нужда
/// (см. <see cref="NeedQuest.RunAsync"/>). Сдвиг нужен затем, чтобы бот
/// вернулся к делу через секунды, а не через минуты: цепочка «убил → разделал
/// → приготовил» проходится за несколько заходов, и ждать между ними полный
/// перерыв значит голодать при мясе в сумке.
/// </param>
/// <param name="Why">Что именно вышло или на чём упёрлись — словами человека.</param>
public readonly record struct NeedTry(bool Сдвиг, string Why);

/// <summary>Пройденный способ со своим словом. Пустого <paramref name="Why"/> не бывает.</summary>
public sealed record NeedStep(string Way, string Why)
{
    public override string ToString() => $"{Way}: {Why}";
}

/// <summary>
/// ЧЕМ КОНЧИЛСЯ ПОХОД ЗА НУЖДОЙ.
/// </summary>
/// <param name="Got">Нужда закрыта — ПО ФАКТУ, а не по бодрому ответу способа.</param>
/// <param name="By">Какой способ её закрыл (null — ни один).</param>
/// <param name="Moved">Хоть один способ сдвинул дело с места.</param>
/// <param name="Reason">Одна строка человеку.</param>
/// <param name="Tried">
/// Каждый пройденный способ со своим словом. Ради этого списка всё и написано:
/// человек обязан отличать «нигде нет» от «не пробовал» и знать, КАКУЮ РУЧКУ
/// повернуть, чтобы попробовали.
/// </param>
public sealed record NeedQuestReport(bool Got, string? By, bool Moved, string Reason,
    IReadOnlyList<NeedStep> Tried)
{
    public override string ToString() => Reason;
}

/// <summary>
/// ОДИН СПОСОБ СДЕЛАТЬ НУЖДУ ВЫПОЛНИМОЙ.
///
/// Способ — это ОБЪЯВЛЕНИЕ, а не ветка в лесенке условий. Новый способ (сварить
/// похлёбку, выменять у торговца, вырастить на грядке) подключается тем, что
/// его кладут в список; трогать при этом ни сам поход
/// (<see cref="NeedQuest"/>), ни соседние способы не надо.
/// </summary>
public sealed class NeedWay
{
    /// <summary>Как назвать способ человеку: «кладовые», «готовка», «охота».</summary>
    public required string Имя { get; init; }

    /// <summary>Разрешён ли способ прямо сейчас — обычно это ручка роли.</summary>
    public required Func<bool> Разрешён { get; init; }

    /// <summary>
    /// ПОЧЕМУ НЕ ВЕЛЕНО — И ЭТО ОБЯЗАНО НАЗЫВАТЬ РУЧКУ. Правило 4 проекта: отказ
    /// без имени ручки человек читает как лень бота. «Охотиться не велено» —
    /// бесполезно; «охотиться не велено (ручка „Охотиться“)» — починка в один
    /// щелчок.
    /// </summary>
    public required Func<string> ПочемуНеВелено { get; init; }

    /// <summary>Сделать. Врать про успех нельзя — его всё равно проверят по сумке.</summary>
    public required Func<NeedAsk, CancellationToken, Task<NeedTry>> Сделать { get; init; }
}

/// <summary>
/// ПОХОД ЗА НУЖДОЙ: НУЖДА, КОТОРУЮ НЕЧЕМ ЗАКРЫТЬ, ПОРОЖДАЕТ ПОДЦЕЛЬ.
///
/// ЗАЧЕМ ЭТО ЕСТЬ. Половина всякой планирующей машины (GOAP и родня) — это
/// правило «цель, которую нельзя выполнить, заменяется целью сделать её
/// выполнимой». У бота до сих пор была ровно одна такая цепочка, и написана
/// она была руками: голоден → еды в сумке нет → сходи в кладовую → обери куст.
/// Кончалась она на «дикой еды в 32 бл не видно», и бот ждал — при том что
/// умел и убивать, и разделывать, и готовить. Каждая следующая нужда
/// (лечебное, тепло, инструмент) требовала бы такой же рукописной лесенки, и
/// каждая обрывалась бы на своём «а дальше не умею».
///
/// ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО НЕТ. Здесь ОДИН цикл: пройти объявленные способы по
/// порядку и после КАЖДОГО спросить мир, закрыта ли нужда. Нет ни одной ветки
/// «если еда», ни одного кода предмета, ни одного числа. Порядок способов —
/// это и есть план, и лежит он у того, кто нужду объявил.
///
/// УСПЕХ ТОЛЬКО ПО ФАКТУ (правило 4). Способ может честно доложить «положил
/// мясо в костёр» — и это не успех; успех — когда мерка «закрыта ли нужда»
/// говорит «да». Ровно так проверяет себя костёр в <see cref="Fire"/> и еда в
/// <see cref="BehaviorEatWhenHungry"/>: смотрим в сумку, а не на свой отчёт.
///
/// НИ ОДНОГО МОЛЧАЛИВОГО ОТКАЗА. Каждый способ оставляет строку — и тот,
/// который сработал, и тот, которому не велено, и тот, который упёрся. Отказ
/// собирается из всех строк разом, как у снабжения (<see cref="Supply"/>):
/// человек читает цепочку целиком и видит, где она порвалась.
/// </summary>
public static class NeedQuest
{
    /// <summary>
    /// Пройти способы по порядку, пока нужда не закроется.
    /// </summary>
    /// <param name="ask">Чего просим.</param>
    /// <param name="ways">Способы, в том порядке, в каком их пробовать.</param>
    /// <param name="Закрыта">
    /// Спрашивается У МИРА (сумка, реестр), а не у способов. Это единственная
    /// мерка успеха на весь поход.
    /// </param>
    /// <param name="ct">Отмена: тело забрали — поход кончился, и это не отказ.</param>
    public static async Task<NeedQuestReport> RunAsync(NeedAsk ask, IReadOnlyList<NeedWay> ways,
        Func<bool> Закрыта, CancellationToken ct = default)
    {
        var шаги = new List<NeedStep>();

        // УЖЕ ЕСТЬ — И ЭТО НЕ ПОВОД КУДА-ТО ИДТИ. Между решением звать поход и
        // самим походом бот мог что-то подобрать ногами
        if (Закрыта())
            return Готово(ask, null, шаги, "это у меня уже есть");

        if (ways.Count == 0)
            // МОЛЧАТЬ НЕЛЬЗЯ. Нужда есть, закрыть нечем, а способов не объявили
            // вовсе — это поломка сборки, и звучать она обязана как поломка, а
            // не как «бот стоит»
            return Отказ(ask, шаги, false,
                $"{ask.Имя}: закрыть нечем, и ни одного способа добыть это боту не объявили");

        bool сдвинулось = false;
        foreach (var способ in ways)
        {
            if (ct.IsCancellationRequested)
            {
                шаги.Add(new NeedStep(способ.Имя, "не начинал: тело понадобилось другому делу"));
                break;
            }

            if (!способ.Разрешён())
            {
                шаги.Add(new NeedStep(способ.Имя, способ.ПочемуНеВелено()));
                continue;
            }

            NeedTry попытка;
            try
            {
                попытка = await способ.Сделать(ask, ct);
            }
            catch (OperationCanceledException)
            {
                // Тело забрали посреди способа. Это не отказ способа и не его
                // вина: причину назвал тот, кто перебил
                шаги.Add(new NeedStep(способ.Имя, "прервали: тело понадобилось другому делу"));
                break;
            }

            шаги.Add(new NeedStep(способ.Имя, попытка.Why));
            сдвинулось |= попытка.Сдвиг;

            // ВОТ ЭТА СТРОКА И ЕСТЬ ВЕСЬ МЕХАНИЗМ: спрашиваем МИР, а не способ
            if (Закрыта())
                return Готово(ask, способ.Имя, шаги, попытка.Why);
        }

        return Отказ(ask, шаги, сдвинулось,
            сдвинулось
                ? $"{ask.Имя}: пока не закрыл, но дело сдвинулось"
                : $"{ask.Имя}: закрыть нечем");
    }

    private static NeedQuestReport Готово(NeedAsk ask, string? кем, List<NeedStep> шаги, string why)
    {
        string ответ = кем == null
            ? $"{ask.Имя}: {why}"
            : $"{ask.Имя} — взял: {кем} ({why})";
        return new NeedQuestReport(true, кем, кем != null, ответ, шаги);
    }

    /// <summary>
    /// ОТКАЗ НАЗЫВАЕТ ВСЕ ОБОРВАВШИЕСЯ ЗВЕНЬЯ — до одного, теми же словами, что
    /// и снабжение. По одной строке «еды нет» нельзя понять, ходил бот куда-то
    /// или нет, и заказчик читал это как лень.
    /// </summary>
    private static NeedQuestReport Отказ(NeedAsk ask, List<NeedStep> шаги, bool сдвиг, string хвост)
    {
        string ответ = шаги.Count == 0
            ? хвост
            : $"{хвост}; пробовал так: " + string.Join(" → ", шаги.Select(s => s.ToString()));
        return new NeedQuestReport(false, null, сдвиг, ответ, шаги);
    }
}

/// <summary>
/// ОБЪЯВЛЕНИЕ НУЖДЫ: кто она, когда созрела и чем меряется её закрытие.
///
/// Всё, что нужно знать <see cref="BehaviorMeetNeed"/>, чтобы стать РУКАМИ этой
/// нужды. Следующая нужда подключается заполнением этой записи и списком
/// способов — своего класса-способности ей заводить не надо.
/// </summary>
public sealed class NeedDeclaration
{
    /// <summary>
    /// ЧЬЯ ЭТО НУЖДА — тип самой способности-нужды
    /// (<see cref="BehaviorEatWhenHungry"/>, <see cref="BehaviorHealWhenHurt"/>).
    ///
    /// Отсюда руки берут СРОЧНОСТЬ нужды (<see cref="BotBehavior.Serves"/>):
    /// бот сыт — руки весят своё скромное, бот голодает — руки весят как голод.
    /// Второго механизма наследования срочности в проекте нет и заводить его
    /// нельзя.
    /// </summary>
    public required Type Нужда { get; init; }

    /// <summary>Как назвать нужду человеку: «еда», «лечебное».</summary>
    public required string Имя { get; init; }

    /// <summary>
    /// Как назвать САМИ РУКИ в журнале и в списке важности; null — по общей
    /// таблице имён (<see cref="BehaviorWeights.NameOf(Type)"/>). Второй
    /// таблицы имён в проекте нет, поэтому здесь именно «null — общая».
    /// </summary>
    public string? Заголовок { get; init; }

    /// <summary>
    /// Нужда созрела: пора идти. Спрашивается у самой нужды.
    ///
    /// УМОЛЧАНИЕ — «НИКОГДА», И ЭТО НАРОЧНО. Незаполненное объявление обязано
    /// вести себя как отсутствующая способность, а не как вечно голодный бот.
    ///
    /// Ставится и после сборки (а не только в инициализаторе) потому, что
    /// наследник вроде <see cref="BehaviorForageWhenNoFood"/> меряет созрелость
    /// СВОЕЙ ручкой («ниже какой доли сытости идти за едой»), а тронуть свои
    /// поля до вызова базового конструктора язык не даёт.
    /// </summary>
    public Func<bool> Созрела { get; set; } = () => false;

    /// <summary>
    /// Нужду ЕСТЬ ЧЕМ ЗАКРЫТЬ прямо сейчас. Это и мерка успеха похода, и повод
    /// не начинать его вовсе: еда в сумке — забота самой еды, а не её рук.
    ///
    /// Умолчание — «уже закрыта», по той же причине: пустое объявление молчит.
    /// </summary>
    public Func<bool> Закрыта { get; set; } = () => true;

    /// <summary>Что из реестра сервера закрывает нужду.</summary>
    public Func<string, bool> Годится { get; set; } = _ => false;

    /// <summary>Сколько штук просить за один заход.</summary>
    public int Сколько { get; set; } = 1;
}

/// <summary>
/// РУКИ НУЖДЫ: СХОДИТЬ И СДЕЛАТЬ ТАК, ЧТОБЫ НУЖДУ БЫЛО ЧЕМ ЗАКРЫТЬ.
///
/// Одна способность на все нужды. Что именно она делает, решают ДВА
/// объявления: <see cref="NeedDeclaration"/> («кто я и чем меряюсь») и список
/// <see cref="Ways"/> («какими способами»). Лесенки условий внутри нет.
///
/// ВЕС БЕРЁТСЯ У НУЖДЫ, А НЕ ВЫСТАВЛЯЕТСЯ РУКАМИ. Живой случай 23.08, ради
/// которого <see cref="BotBehavior.Serves"/> и заведён: голод весит 80, но без
/// еды выбывает из очереди, а «пойти добыть еду» весило 50 — ровно как поход за
/// временной шестерёнкой; шестерёнка, начатая секундой раньше, держала тело
/// пять минут, пока бот терял здоровье. Подгонять число под каждую новую нужду
/// значило бы заводить ту же дыру заново.
///
/// ТЕЛО — РЕФЛЕКС, И ВЫШЕ НЕ ПОДНИМАЕМ. Это руки жизненной нужды, они не
/// уступают ходьбе и поручениям (живой случай 23.08: голодный бот пять минут
/// носил побрякушку для точки возрождения). Но бросить БОЙ ради похода за едой
/// — значит умереть сытым, поэтому ступень ровно та же, что у боя и у грения.
/// Берётся оно НА КАЖДЫЙ СПОСОБ ОТДЕЛЬНО — см. <see cref="ПоСпособуЗаТело"/>.
/// </summary>
public class BehaviorMeetNeed : BotBehavior
{
    private readonly BotContext ctx;
    private readonly NeedDeclaration нужда;
    private DateTime nextTry = DateTime.MinValue;

    /// <summary>
    /// СПОСОБОВ НЕ ОБЪЯВИЛИ — беда сборки, а не жизни. Говорится громко и один
    /// раз: пока сборка та же, повторять её каждые полсекунды значит залить
    /// журнал (см. <see cref="Alarm"/>).
    /// </summary>
    private readonly Alarm безСпособов;

    public BehaviorMeetNeed(BotContext ctx, NeedDeclaration нужда)
    {
        this.ctx = ctx;
        this.нужда = нужда;
        безСпособов = new Alarm(нужда.Имя);
        безСпособов.OnRaise += why => OnQuest?.Invoke(new NeedQuestReport(
            false, null, false, why, []));
        // Отказ «мне это запрещено» идёт тем же руслом, что и «способов не
        // объявили»: человек читает обе беды в одном месте и в одних словах
        выключено = new Alarm(нужда.Имя);
        выключено.OnRaise += why => OnQuest?.Invoke(new NeedQuestReport(
            false, null, false, why, []));
    }

    /// <summary>Способы в том порядке, в каком их пробовать. Порядок — это план.</summary>
    public List<NeedWay> Ways { get; } = new();

    /// <summary>
    /// Само объявление — наследнику, чтобы он дописал в него свои мерки уже
    /// после сборки (см. <see cref="NeedDeclaration.Созрела"/>).
    /// </summary>
    protected NeedDeclaration Need => нужда;

    /// <summary>Ходить за этой нуждой вообще (роль вправе запретить).</summary>
    public bool Enabled { get; set; } = true;

    /// <summary>
    /// ИМЯ РУЧКИ, КОТОРАЯ ГАСИТ ВСЮ ЦЕПОЧКУ — чтобы отказ мог её назвать.
    ///
    /// Ставит роль, когда доносит <see cref="Enabled"/>. Живой случай: человек
    /// включил «Охотиться», а бот не охотился — потому что всю нужду гасила
    /// ручка «СобиратьЕду», и молчала об этом.
    /// </summary>
    public string? Отключатель { get; set; }

    /// <summary>
    /// «ЗАПРЕЩЕНО РОЛЬЮ» — громко один раз. Причина не меняется, пока человек
    /// не повернёт ручку, и повторять её каждые полсекунды значит залить журнал.
    /// </summary>
    private readonly Alarm выключено;

    /// <summary>Пауза между заходами, когда прошлый ничего не изменил.</summary>
    public TimeSpan Cooldown { get; set; } = TimeSpan.FromMinutes(3);

    /// <summary>
    /// Через сколько секунд возвращаться, если дело СДВИНУЛОСЬ. Цепочка «убил →
    /// разделал → приготовил» проходится за несколько заходов, и полный перерыв
    /// между ними означал бы голод при мясе в сумке.
    /// </summary>
    public double RetryAfterProgressSeconds { get; set; } = 5;

    /// <summary>Чем кончился поход — обязательно вслух, целиком, со всеми звеньями.</summary>
    public event Action<NeedQuestReport>? OnQuest;

    public override Type? Serves => нужда.Нужда;

    public override string Title => нужда.Заголовок ?? base.Title;

    /// <summary>
    /// Имя для списка важности — имя самой нужды («еда», «лечебное»). Без него
    /// вторая нужда показалась бы человеку латинским «MeetNeed», а третья — тем
    /// же словом: таблица имён ключуется типом, а тип у всех нужд один.
    /// </summary>
    public override string? SelfName => нужда.Имя;

    /// <summary>Чего просим — одной заявкой, чтобы её могли задать и снаружи.</summary>
    public NeedAsk Ask => new(нужда.Имя, нужда.Годится, нужда.Сколько);

    public override async Task<bool> TickAsync(CancellationToken ct)
    {
        // «ЗАНЯТО ДВИЖЕНИЕ» ЗДЕСЬ НЕ СПРАШИВАЮТ НАРОЧНО. Живой случай 23.08:
        // бот сказал «проголодался, а еды нет» — и тут же ушёл на склад за
        // временной шестерёнкой; пока он шёл, движение было занято, и добыча
        // еды отступала на каждом тике. Занято ли тело, решает распорядитель, а
        // не способность за него
        if (!Enabled)
        {
            // ВЫКЛЮЧЕНО — ЭТО ТОЖЕ ОТКАЗ, И ОН НАЗЫВАЕТ РУЧКУ (правило 4).
            // Прежде здесь стоял голый return: человек ставил «Охотиться: да»,
            // бот не охотился, и в журнале не было ни строчки — потому что
            // гасит всю цепочку ДРУГАЯ ручка, из другого раздела окна
            выключено.Raise(Отключатель is { Length: > 0 } ручка
                ? $"закрыть нечем, но ходить за этим мне запрещено: ручка «{ручка}»"
                : "закрыть нечем, но ходить за этим мне запрещено ролью");
            return false;
        }
        выключено.Clear();
        if (DateTime.UtcNow < nextTry)
            return false;
        if (!нужда.Созрела())
            return false;

        // ЗАКРЫТЬ ЕСТЬ ЧЕМ — ЗНАЧИТ ЭТО НЕ МОЁ ДЕЛО. Еду в сумке съест сама еда
        if (нужда.Закрыта())
            return false;

        if (Ways.Count == 0)
        {
            // Приставку «еда: » ставит сама тревога (Alarm.About), второй раз
            // имя нужды здесь не повторяем
            безСпособов.Raise("закрыть нечем, и ни одного способа добыть это боту не объявили");
            return false;
        }
        безСпособов.Clear();

        // СРОК СЛЕДУЮЩЕЙ ПОПЫТКИ СТАВИМ ДО ПОХОДА, а не после: сорвавшийся
        // поход не должен зваться заново каждые полсекунды
        nextTry = DateTime.UtcNow + Cooldown;

        var отчёт = await QuestNowAsync(ct);

        // …И ПЕРЕСТАВЛЯЕМ ЕГО ОТ КОНЦА ПОХОДА. Метка выше — страховка на случай
        // броска; перерыв же обязан считаться от возвращения, а не от ухода.
        // Цепочка нужды длинная: рейс к сундуку через полкарты, до 45 с у
        // костра, до 25 с охоты. Полный неудачный проход легко перевалит за три
        // минуты — и метка, поставленная в начале, к возвращению уже в прошлом,
        // то есть перерыва нет вовсе и бот немедленно уходит на второй круг
        nextTry = DateTime.UtcNow + Cooldown;

        if (отчёт.Got || отчёт.Moved)
            nextTry = DateTime.UtcNow.AddSeconds(Math.Max(0, RetryAfterProgressSeconds));
        else if (телаНеДали)
            // ТЕЛО БЫЛО ЗАНЯТО — ЭТО НЕ «НИГДЕ НЕТ». Держать за это полный
            // перерыв значит наказать голодного за то, что он подождал конца
            // чужой стычки
            nextTry = DateTime.UtcNow.AddSeconds(Math.Max(0, RetryAfterProgressSeconds));
        return отчёт.Got || отчёт.Moved;
    }

    /// <summary>
    /// ПРОЙТИ ЦЕПОЧКУ ПРЯМО СЕЙЧАС — мимо порога нужды и мимо перерыва.
    ///
    /// Нужна человеку: команда из чата («!добудьеду») обязана показать ЖИВУЮ
    /// цепочку со всеми её отказами, а не пересказ по памяти. Тик зовёт её же —
    /// второго прохода по способам в проекте нет, иначе команда однажды
    /// показала бы не то, что бот делает на самом деле.
    /// </summary>
    public async Task<NeedQuestReport> QuestNowAsync(CancellationToken ct = default)
    {
        телаНеДали = false;
        ПередПоходом();
        try
        {
            var отчёт = await NeedQuest.RunAsync(Ask, ПоСпособуЗаТело(), нужда.Закрыта, ct);
            OnQuest?.Invoke(отчёт);
            return отчёт;
        }
        finally
        {
            ПослеПохода();
        }
    }

    /// <summary>
    /// ПЕРЕД ПЕРВЫМ СПОСОБОМ — наследнику. Тут ставят то, что живёт РОВНО ОДНУ
    /// вылазку: например, якорь «откуда я ушёл», по которому меряется, не
    /// уполз ли бот за добычей.
    /// </summary>
    protected virtual void ПередПоходом() { }

    /// <summary>
    /// ПОСЛЕ ПОСЛЕДНЕГО СПОСОБА — наследнику, и зовётся ВСЕГДА, даже если
    /// поход сорвали. Тут снимают то, что поставили перед походом: вещь,
    /// поставленную на одну вылазку и не снятую, бот унесёт с собой на всю
    /// жизнь — и будет мерить новое место старой меркой.
    /// </summary>
    protected virtual void ПослеПохода() { }

    /// <summary>Хоть одному способу не дали тела — это не отказ мира, а очередь.</summary>
    private bool телаНеДали;

    /// <summary>
    /// ТЕЛО БЕРЁТСЯ НА КАЖДЫЙ СПОСОБ ОТДЕЛЬНО И ОТПУСКАЕТСЯ МЕЖДУ НИМИ.
    ///
    /// ЭТО НЕ УКРАШЕНИЕ, А УСЛОВИЕ ЖИЗНИ БОТА. Тело здесь берут рефлексом — той
    /// же ступенью, что и самооборона, — а равный равного не перебивает
    /// (<see cref="BodyArbiter"/>: «укрытие в бурю берут тело как Reflex,
    /// замуровываются на пять минут — и голодный рефлекс, тоже Reflex, получает
    /// от них честный отказ»). Цепочка «кладовые → готовка → дикая еда → охота»
    /// целиком идёт минутами: возьми мы тело один раз на весь поход, бот все эти
    /// минуты не смог бы отбиваться.
    ///
    /// Имя владельца собирается из имени способности и имени способа — человек в
    /// журнале читает «сбор еды: охота», а не безликое «сбор еды».
    /// </summary>
    private List<NeedWay> ПоСпособуЗаТело() =>
        Ways.Select(способ => new NeedWay
        {
            Имя = способ.Имя,
            Разрешён = способ.Разрешён,
            ПочемуНеВелено = способ.ПочемуНеВелено,
            Сделать = async (ask, ct) =>
            {
                using var hold = ctx.Turn.TryTake($"{Title}: {способ.Имя}",
                    BodyArbiter.Importance.Reflex, ct);
                if (hold == null)
                {
                    телаНеДали = true;
                    // Кем именно занято тело, сказал сам распорядитель, с
                    // заглушкой повторов; второй раз повторять незачем
                    return new NeedTry(false, "тела не дали: занято другим делом");
                }
                return await способ.Сделать(ask, hold.Token);
            }
        }).ToList();
}
