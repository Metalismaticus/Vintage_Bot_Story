/// <summary>
/// ПОСТАВЩИК МОДЕЛИ (заказчик называет их «операторами»): кто продаёт думанье,
/// из какой переменной окружения бот берёт ключ и какие модели у него бывают.
///
/// ЗАЧЕМ ЭТО ДАННЫМИ, А НЕ АБЗАЦЕМ В СПРАВКЕ. Живой случай, с которого всё
/// началось: «не нашёл, где задавать данные от ИИ и поддерживаемые операторы».
/// Список, который живёт только в ИИ.md, окно управления показать не может —
/// а человек ищет его там же, где крутит остальные настройки. Раз список —
/// данные, его показывает и окно (выпадающим списком), и чат («!ии
/// поставщики»), и никто не переписывает его во второй раз своими словами.
///
/// ЗНАЧЕНИЕ КЛЮЧА ЗДЕСЬ НЕ ХРАНИТСЯ И НАРУЖУ НЕ ОТДАЁТСЯ НИКОГДА. Запись знает
/// только ИМЯ переменной окружения и умеет ответить «задана / не задана».
/// </summary>
/// <param name="Имя">Короткое имя для настроек и окна («anthropic»).</param>
/// <param name="Название">Как показать человеку («Anthropic (Claude)»).</param>
/// <param name="ПеременнаяКлюча">Откуда берётся ключ. Пусто — ключ не нужен.</param>
/// <param name="ПеременнаяАдреса">Откуда берётся адрес. Пусто — адрес свой, менять не надо.</param>
/// <param name="Модели">Примеры моделей: подсказка человеку, а не запрет.</param>
/// <param name="Что">Одна-две фразы о том, чем этот поставщик отличается.</param>
public sealed record AiProvider(
    string Имя,
    string Название,
    string ПеременнаяКлюча,
    string ПеременнаяАдреса,
    string[] Модели,
    string Что)
{
    /// <summary>
    /// Умеет ли этот бот думать таким поставщиком ПРЯМО СЕЙЧАС.
    ///
    /// Ложь тоже попадает в список нарочно: человек, который ищет в окне
    /// «Bedrock» и не находит его вовсе, решает, что не там смотрит. Увидев
    /// строку с причиной, он знает правду за одну секунду.
    /// </summary>
    public bool Умеем { get; init; } = true;

    /// <summary>Почему не умеем. Пусто — умеем.</summary>
    public string ПочемуНеУмеем { get; init; } = "";

    /// <summary>
    /// Действуют ли на него настройки роли (модель, усилие, потолок ответа).
    /// У своей нейросети, подключённой кодом, они свои — и роль об этом
    /// говорит вслух, а не делает вид, что покрутила ручку.
    /// </summary>
    public bool НастройкиДействуют { get; init; } = true;

    /// <summary>Нужен ли этому поставщику ключ из окружения.</summary>
    public bool КлючНужен => ПеременнаяКлюча.Length > 0;

    /// <summary>Нужен ли этому поставщику отдельный адрес из окружения.</summary>
    public bool АдресНужен => ПеременнаяАдреса.Length > 0;

    /// <summary>
    /// Задан ли ключ прямо сейчас. Возвращается ТОЛЬКО «да/нет»: само значение
    /// не возвращается, не печатается и никуда не записывается.
    /// </summary>
    /// <param name="окружение">Откуда читать переменные. null — настоящее окружение.</param>
    public bool КлючЗадан(Func<string, string?>? окружение = null) =>
        КлючНужен && Задана(ПеременнаяКлюча, окружение);

    /// <summary>Задан ли адрес прямо сейчас (для поставщиков, которым он нужен).</summary>
    public bool АдресЗадан(Func<string, string?>? окружение = null) =>
        АдресНужен && Задана(ПеременнаяАдреса, окружение);

    /// <summary>Как положить ключ (и адрес) — человеку в журнал и в чат.</summary>
    public string КакВключить()
    {
        if (!КлючНужен && !АдресНужен)
            return "Ключ этому поставщику не нужен.";

        var текст = new StringBuilder();
        if (КлючНужен)
            текст.Append($"Ключ кладут в переменную окружения {ПеременнаяКлюча} ДО запуска бота: ")
                 .Append($"Windows — set {ПеременнаяКлюча}=…, Linux/macOS — export {ПеременнаяКлюча}=… . ");
        if (АдресНужен)
            текст.Append($"Адрес поставщика — в переменную {ПеременнаяАдреса} тем же способом. ");
        текст.Append("В файлы бот ключ не пишет и в журнал не печатает.");
        return текст.ToString();
    }

    /// <summary>Задана ли переменная окружения. Пустое имя — не задана (а не исключение).</summary>
    private static bool Задана(string имя, Func<string, string?>? окружение)
    {
        if (имя.Length == 0)
            return false;
        var читать = окружение ?? Environment.GetEnvironmentVariable;
        return !string.IsNullOrWhiteSpace(читать(имя));
    }

    public override string ToString() => $"{Имя} — {Название}";
}

/// <summary>
/// Поставщик глазами окна управления: всё, что нужно нарисовать строку списка.
/// Ключа здесь нет и быть не может — только «задан или нет».
/// </summary>
public sealed record AiProviderState(
    string имя,
    string название,
    string что,
    string переменнаяКлюча,
    bool ключЗадан,
    string переменнаяАдреса,
    bool адресЗадан,
    string[] модели,
    bool умеем,
    string почему);

/// <summary>
/// СПИСОК ПОДДЕРЖИВАЕМЫХ ПОСТАВЩИКОВ — один на окно, чат и справку.
///
/// Список короткий не из скромности, а по факту: у бота ОДИН клиент нейросети
/// (<see cref="ClaudeClient"/>), и говорит он по протоколу Anthropic Messages.
/// Значит поддержан тот, кто отвечает по этому протоколу, — и никто больше.
/// Выдумывать сюда OpenAI или Bedrock нельзя: строка в списке не добавляет
