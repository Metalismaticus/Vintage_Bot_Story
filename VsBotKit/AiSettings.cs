    /// <summary>Все поставщики по порядку показа.</summary>
    public static IReadOnlyList<AiProvider> Все => всё;

    /// <summary>Только те, которыми бот умеет думать.</summary>
    public static IEnumerable<AiProvider> Умеем => всё.Where(п => п.Умеем);

    /// <summary>Найти поставщика по имени. null — такого нет.</summary>
    public static AiProvider? Найти(string? имя) =>
        имя is { Length: > 0 }
            ? всё.FirstOrDefault(п => string.Equals(п.Имя, имя.Trim(), StringComparison.OrdinalIgnoreCase))
            : null;

    /// <summary>Имена тех, кем думать можно, — для сообщения об ошибке.</summary>
    public static string Имена() => string.Join(", ", Умеем.Select(п => п.Имя));

    /// <summary>
    /// Список для окна управления: имя, переменная ключа, примеры моделей и
    /// «ключ задан ДА/НЕТ». Самого ключа тут нет и не появится.
    /// </summary>
    /// <param name="окружение">Откуда читать переменные. null — настоящее окружение.</param>
    public static IReadOnlyList<AiProviderState> Снимок(Func<string, string?>? окружение = null) =>
        всё.Select(п => new AiProviderState(
                п.Имя, п.Название, п.Что,
                п.ПеременнаяКлюча, п.КлючЗадан(окружение),
                п.ПеременнаяАдреса, п.АдресЗадан(окружение),
                п.Модели, п.Умеем, п.ПочемуНеУмеем))
            .ToList();
}

/// <summary>
/// НАСТРОЙКИ ИИ — ОДНО МЕСТО, где задаётся всё про нейросеть: поставщик,
/// модель, глубина раздумья, длина разговора и потолок трат.
///
/// Зачем отдельный класс. Раньше это лежало десятком свойств прямо в роли, и
/// каждое само лазило то в клиента, то в бюджет. Второй такой роли хватило бы,
/// чтобы правила разошлись копиями: где-то усилие проверяется, где-то нет.
/// Здесь механизм один, а роль — только витрина: её свойства ничего не решают,
/// они зовут этот класс (окно управления показывает свойства роли, поэтому
/// витрина нужна).
///
/// ХРАНИЛИЩА ЗДЕСЬ ТОЖЕ НЕТ. Модель, усилие и потолок живут в клиенте, лимиты
/// и цены — в бюджете; этот класс их только проверяет и доносит. Иначе «в окне
/// одно, в запросе другое» стало бы вопросом времени.
///
/// КЛЮЧ. Ни одна строка здесь не читает ЗНАЧЕНИЕ ключа: только «задана ли
/// переменная». Значение читает сам SDK — так его нельзя случайно записать в
/// пресет, в журнал или в ответ окну.
/// </summary>
public sealed class AiSettings
{
    private readonly ClaudeClient? клиент;
    private readonly LlmBudget бюджет;
    private readonly Action<string> сказать;

    // Запасные значения на случай чужой нейросети: настройки крутятся, но
    // доехать им некуда — пусть хотя бы читаются теми же, что задали
    private string модель = "";
    private string усилие = "";
    private int потолок = 8192;
    private int память = 40;

    private AiProvider поставщик;

    /// <param name="нейросеть">Чем думаем. Не <see cref="ClaudeClient"/> — значит своя, кодом.</param>
    /// <param name="бюджет">Потолок трат — тот же самый, что спрашивает роль перед ходом.</param>
    /// <param name="жалоба">Куда говорить о кривой настройке. Молчать нельзя.</param>
    public AiSettings(ILlmClient? нейросеть, LlmBudget бюджет, Action<string>? жалоба = null)
    {
        клиент = нейросеть as ClaudeClient;
        this.бюджет = бюджет;
        сказать = жалоба ?? (_ => { });
        поставщик = AiProviders.Найти(клиент != null ? AiProviders.ПоУмолчанию : AiProviders.Своя)!;
    }

    /// <summary>Кем думаем сейчас. Запись — по имени из <see cref="AiProviders"/>.</summary>
    public AiProvider Оператор => поставщик;

    /// <summary>
    /// Поставщик модели: «anthropic», «anthropic-token», «совместимый», «своя».
    ///
    /// Незнакомое или неподдержанное имя НЕ принимается: молча согласиться —
    /// значит остановить думанье и не сказать об этом ни слова.
    /// </summary>
    public string Поставщик
    {
        get => поставщик.Имя;
        set
        {
            string имя = (value ?? "").Trim();
            if (string.Equals(имя, поставщик.Имя, StringComparison.OrdinalIgnoreCase))
                return;

            var новый = AiProviders.Найти(имя);
            if (новый == null)
            {
                Пожаловаться($"поставщика «{value}» не знаю, оставил «{поставщик.Имя}». " +
                             $"Бывают: {AiProviders.Имена()}");
                return;
            }
            if (!новый.Умеем)
            {
                Пожаловаться($"поставщик «{новый.Название}» этим ботом не поддержан " +
                             $"({новый.ПочемуНеУмеем}); оставил «{поставщик.Имя}»");
                return;
            }
            // «Своя нейросеть» — это ФАКТ о том, как собрали роль, а не ручка:
            // выбрав её в окне, человек получил бы бота, который думает прежним
            // клиентом и делает вид, что сменил его
            bool этоСвоя = !новый.НастройкиДействуют;
            if (этоСвоя != (клиент == null))
            {
                Пожаловаться(клиент == null
                    ? "думает своя нейросеть, подключённая кодом: поставщика ей не выбирают"
                    : $"«{новый.Название}» задаётся не настройкой, а кодом (конструктор роли); " +
                      $"оставил «{поставщик.Имя}»");
                return;
            }

            var прежний = поставщик;
            поставщик = новый;

            // Модель подставляем ТОЛЬКО если она осталась пустой или была
            // подсказкой прежнего поставщика: вписанное человеком затирать
            // нельзя, а молча оставить чужое имя модели — значит получить отказ
            // сети на первом же ходу и гадать, почему
            if (новый.Модели.Contains(Модель))
                { }                                     // подходит, ничего не трогаем
            else if (новый.Модели.Length > 0 &&
                     (string.IsNullOrWhiteSpace(Модель) || прежний.Модели.Contains(Модель)))
                Модель = новый.Модели[0];
            else if (Модель.Length > 0)
                Пожаловаться($"модель оставил прежнюю («{Модель}») — проверьте, " +
                             $"что «{новый.Название}» её знает");

            Пожаловаться($"поставщик теперь «{новый.Название}». {новый.КакВключить()}");
        }
    }

    /// <summary>
    /// Модель нейросети. Пусто — думать нечем, и роль честно откажется.
    /// Имена смотрите у поставщика; примеры — в списке поставщиков.
    /// </summary>
    public string Модель
    {
        get => клиент?.Model ?? модель;
        set
        {
            модель = (value ?? "").Trim();
            if (клиент != null)
                клиент.Model = модель;
            else
                Пожаловаться("модель задаёт своя нейросеть — настройка роли на неё не действует");
        }
    }

    /// <summary>
    /// Сколько усилий тратить на ход: low (быстро и дёшево, боту в игре обычно
    /// хватает), medium, high, max. Незнакомое слово НЕ принимается: клиент
    /// молча превратил бы его в самое дорогое «high».
    /// </summary>
    public string Усилие
    {
        get => клиент?.Effort ?? усилие;
        set
        {
            string слово = (value ?? "").Trim().ToLowerInvariant();
            if (!ЗнакомыеУсилия.Contains(слово))
            {
                Пожаловаться($"усилие «{value}» не знаю, оставил «{Усилие}». " +
                             $"Бывает: {string.Join(", ", ЗнакомыеУсилия)}");
                return;
            }
            усилие = слово;
            if (клиент != null)
                клиент.Effort = слово;
            else
                Пожаловаться("усилие задаёт своя нейросеть — настройка роли на неё не действует");
        }
    }

    /// <summary>
    /// Потолок одного ответа в токенах. У моделей с размышлением из него
    /// тратится И раздумье, и текст: занизишь — ход оборвётся на полуслове.
    /// </summary>
    public int ПотолокОтвета
    {
        get => клиент?.MaxTokens ?? потолок;
        set
        {
            потолок = Math.Max(1, value);
            if (клиент != null)
                клиент.MaxTokens = потолок;
            else
                Пожаловаться("потолок ответа задаёт своя нейросеть — настройка роли на неё не действует");
        }
    }

    /// <summary>
    /// Сколько последних сообщений держать в разговоре. Бот живёт часами, и без
    /// ограничения история (а с ней и счёт) растёт бесконечно.
    /// </summary>
    public int ПомнитьСообщений
    {
        get => клиент?.HistoryLimit ?? память;
        set
        {
            память = Math.Max(2, value);
            if (клиент != null)
                клиент.HistoryLimit = память;
            else
                Пожаловаться("длину памяти задаёт своя нейросеть — настройка роли на неё не действует");
        }
    }

    /// <summary>Сколько обращений к нейросети разрешено за час. 0 — без лимита.</summary>
    public int ОбращенийВЧас
    {
        get => бюджет.RequestsPerHour;
        set => бюджет.RequestsPerHour = Math.Max(0, value);
    }

    /// <summary>Сколько токенов разрешено за сутки. 0 — без лимита.</summary>
    public long ТокеновВСутки
    {
        get => бюджет.TokensPerDay;
        set => бюджет.TokensPerDay = Math.Max(0, value);
    }

    /// <summary>
    /// Цена входных токенов за миллион. 0 — цену не знаем и не показываем.
    /// Тариф выдумывать нельзя: посмотрите его у поставщика и впишите сюда —
    /// тогда бот сам посчитает, во что обошёлся вечер.
    /// </summary>
    public double ЦенаВходаЗаМиллион
    {
        get => бюджет.InputPricePerMillion;
        set => бюджет.InputPricePerMillion = Math.Max(0, value);
    }

    /// <summary>Цена выходных токенов за миллион. 0 — цену не знаем и не показываем.</summary>
    public double ЦенаВыходаЗаМиллион
    {
        get => бюджет.OutputPricePerMillion;
