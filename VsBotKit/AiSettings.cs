    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: чего не хватает, чтобы обратиться к модели. Пустой
    /// список — всё на месте.
    ///
    /// Каждая беда — ОТДЕЛЬНОЙ строкой, и это не косметика. «Не могу думать»
    /// одной фразой заставляет человека гадать, что чинить: ключ, поставщика
    /// или модель. Три строки он читает и правит по одной.
    ///
    /// Ключ сюда приходит УЖЕ ответом «да/нет»: значение ключа этой функции не
    /// нужно и в неё не передаётся — тогда его нельзя случайно напечатать.
    /// </summary>
    public static IReadOnlyList<string> ЧегоНеХватает(
        string? имяПоставщика, AiProvider? поставщик, bool ключЗадан, bool адресЗадан, string? модель)
    {
        var беды = new List<string>();

        if (string.IsNullOrWhiteSpace(имяПоставщика))
        {
            беды.Add($"поставщик не выбран: настройка «Поставщик» пуста. Бывают: {AiProviders.Имена()}");
            return беды;
        }
        if (поставщик == null)
        {
            беды.Add($"поставщика «{имяПоставщика}» не знаю. Бывают: {AiProviders.Имена()}");
            return беды;
        }
        if (!поставщик.Умеем)
        {
            беды.Add($"поставщик «{поставщик.Название}» этим ботом не поддержан: {поставщик.ПочемуНеУмеем}");
            return беды;
        }
        if (!поставщик.НастройкиДействуют)
            return беды; // чужая нейросеть сама знает, чем и как ей думать

        if (поставщик.КлючНужен && !ключЗадан)
            беды.Add($"ключа нет: переменная окружения {поставщик.ПеременнаяКлюча} пуста");
        if (поставщик.АдресНужен && !адресЗадан)
            беды.Add($"адрес поставщика не задан: переменная окружения {поставщик.ПеременнаяАдреса} пуста");
        if (string.IsNullOrWhiteSpace(модель))
            беды.Add("модель не названа: настройка «Модель» пуста");

        return беды;
    }

    /// <summary>
    /// Чего не хватает прямо сейчас. Переменные окружения читаются здесь и
    /// только здесь — наружу уходит ответ «да/нет», а не значение.
    /// </summary>
    /// <param name="окружение">Откуда читать переменные. null — настоящее окружение.</param>
    public IReadOnlyList<string> ЧегоНеХватает(Func<string, string?>? окружение = null)
    {
        var беды = new List<string>(ЧегоНеХватает(поставщик.Имя, поставщик,
            поставщик.КлючЗадан(окружение), поставщик.АдресЗадан(окружение), Модель));

        // АДРЕС ОБЯЗАН ДОЕХАТЬ ДО КЛИЕНТА, а не просто лежать в переменной, —
        // и спрашиваем мы об этом САМ КЛИЕНТ, а не окружение.
        //
        // Живой случай: человек выбирает «совместимый» в окне уже на ходу, а
        // клиент читает переменную ОДИН раз, когда его создают. Переменная,
        // заданная после запуска, до него не доедет, и запросы уйдут на родной
        // адрес Anthropic — на ключе владельца. Проверка по переменной этого не
        // заметила бы: там-то адрес есть
        if (поставщик.АдресНужен && клиент is { } c && !c.OwnBaseUrl)
            беды.Add($"адрес из {поставщик.ПеременнаяАдреса} до клиента не доехал — " +
                     $"он ходит на родной адрес Anthropic ({c.BaseUrl}). Переменная " +
                     "читается один раз, когда бот поднимает клиента: задайте её ДО " +
                     "запуска бота и перезапустите его");
        return беды;
    }

    /// <summary>Готово ли всё для обращения к модели.</summary>
    public bool ГотовДумать(Func<string, string?>? окружение = null) =>
        ЧегоНеХватает(окружение).Count == 0;

    /// <summary>
    /// Чем думаем — одной строкой. Ключ сюда не попадает никогда, а вот АДРЕС
    /// попадает: «куда на самом деле уходят мои запросы» — это первый вопрос
    /// того, кто выбрал совместимого поставщика, и отвечать на него надо
    /// фактом из клиента, а не тем, что задумывалось.
    /// </summary>
    public string Чем() => клиент is { } c
        ? $"поставщик {поставщик.Название}, модель {c.Model}, усилие {c.Effort}, " +
          $"потолок ответа {c.MaxTokens} токенов, память {c.HistoryLimit} сообщений, " +
          $"адрес {c.BaseUrl}{(c.OwnBaseUrl ? "" : " (родной)")}"
        : "своя нейросеть, подключённая кодом (модель, ключ и адрес она знает сама)";

    /// <summary>Как включить думанье — подсказка того поставщика, что выбран.</summary>
    public string КакВключить() => поставщик.КакВключить();

    /// <summary>
    /// Список поставщиков словами — для чата, где выпадающего списка нет.
    /// Ключи не печатаются: только «ключ есть» или «ключа нет».
    /// </summary>
    public static string Поставщики(Func<string, string?>? окружение = null)
    {
        var текст = new StringBuilder();
        foreach (var п in AiProviders.Все)
        {
            текст.Append(текст.Length > 0 ? "\n" : "").Append(п.Имя).Append(" — ").Append(п.Название);
            if (!п.Умеем)
            {
                текст.Append(": НЕ ПОДДЕРЖАН — ").Append(п.ПочемуНеУмеем);
                continue;
            }
            текст.Append(": ");
            текст.Append(п.КлючНужен
                ? $"{п.ПеременнаяКлюча} — {(п.КлючЗадан(окружение) ? "ключ есть" : "КЛЮЧА НЕТ")}"
                : "ключ не нужен");
            if (п.АдресНужен)
                текст.Append($"; {п.ПеременнаяАдреса} — {(п.АдресЗадан(окружение) ? "адрес есть" : "АДРЕСА НЕТ")}");
            if (п.Модели.Length > 0)
                текст.Append("; модели: ").Append(string.Join(", ", п.Модели));
        }
        return текст.ToString();
    }

