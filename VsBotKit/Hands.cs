    /// <summary>
    /// Правый клик по блоку с удержанием: дверь и рычаг открываются мгновенно,
    /// а ягодный куст, костёр или лейка требуют держать кнопку — сервер меряет
    /// РЕАЛЬНОЕ время между «начал» и «отпустил» и прокручивает столько шагов,
    /// сколько мы честно насчитали.
    /// </summary>
    /// <param name="sneak">
    /// Держать Shift. Часть блоков смотрит именно на него: костёр принимает
    /// топливо и еду только в приседе, иначе клик открывает диалог.
    /// </param>
    public async Task UseBlockAsync(BlockPos pos, double seconds = 0,
        int onFace = 4, bool sneak = false, CancellationToken ct = default)
    {
        // МЁРТВЫМ РУКИ НЕ РАБОТАЮТ. Правило одно на весь проект
        // (см. SelfState.BodyIsDead), а спрашиваем его и здесь потому, что
        // удержание правой кнопки уходит СВОИМ пакетом 25, мимо Actions:
        // сервер ответил бы на него тем же noprivilege-use-playerdead
        if (ctx.Self.Dead)
        {
            OnLog?.Invoke($"по {pos} не кликну: я мёртв — сервер мёртвому " +
                          "отказывает во всём (noprivilege-use-playerdead)");
            return;
        }

        // Точку клика считаем один раз: бот на время использования стоит,
        // и настоящий клиент, не двигая мышью, шлёт ту же точку каждый кадр
        if (AimFor(pos, onFace) is not { } aim)
            return;

        // ОДНА РУКА — ОДНО ДЕЛО. Держать удар и одновременно жать «использовать»
        // живой клиент не умеет, а сервер помнит клавиши как СОСТОЯНИЕ: не
        // отпустив кнопку удара, бот открывает дверь с анимацией копания
        await ctx.Actions.ReleaseKeyAsync(Actions.KeyLeftMouse);

        if (sneak)
            await ctx.Actions.SetSneakAsync(true);
        int startTicks = BodyTicks;
        bool started = false;
        try
        {
            await SendHandBlockAsync(pos, aim, EnumHandInteractNw.StartBlockUse, 0, first: true);
            started = true;

            if (seconds > 0)
            {
                var from = DateTime.UtcNow;
                double stepAccum = 0;
                while (true)
                {
                    double left = seconds - (DateTime.UtcNow - from).TotalSeconds;
                    if (left <= 0 || ct.IsCancellationRequested)
                        break;
                    await Task.Delay((int)Math.Min(60, Math.Max(1, left * 1000)), ct).ContinueWith(_ => { });
                    double elapsed = (DateTime.UtcNow - from).TotalSeconds;
                    // Клиент шлёт пакет-шаг примерно раз в 0.15 с
                    if (elapsed - stepAccum >= 0.15)
                    {
                        stepAccum = elapsed;
                        await SendHandBlockAsync(pos, aim, EnumHandInteractNw.StepBlockUse,
                            StepsSince(startTicks), first: false);
                    }
                }
            }
        }
        finally
        {
            // «ОТПУСТИЛ» УХОДИТ ВСЕГДА, а не только в конце удачного пути:
            // начатое и не закрытое использование сервер держит открытым, и
            // бот остаётся стоять с занесённой рукой. Пара «начал-кончил» —
            // это ровно нажатие и отпускание кнопки у живого игрока
            if (started)
                await SendHandBlockAsync(pos, aim, EnumHandInteractNw.StopBlockUse,
                    seconds > 0 ? StepsSince(startTicks) : 0, first: false);
            if (sneak)
                await ctx.Actions.SetSneakAsync(false);
        }
    }

    /// <summary>
    /// Стадии взаимодействия берём ИЗ ИГРЫ (EnumHandInteractNw), а не числами.
    /// Числа стоили дорого: «шаг удержания» слался как 5, а 5 — это
    /// CancelBlockUse, то есть каждое удержание отменялось через 0.15 с
    /// (StepBlockUse = 7). Ягоды не собирались, лейка не поливала.
    /// </summary>
    private Task SendHandBlockAsync(BlockPos pos, AimPoint aim, EnumHandInteractNw stage,
        int usingCount, bool first) =>
        ctx.Bot.SendPacketAsync(new Packet_Client
        {
            Id = 25,
            HandInteraction = new Packet_ClientHandInteraction
            {
                UseType = 2,     // HeldItemInteract
                MouseButton = 2, // правая кнопка — сервер требует именно её
                EnumHandInteract = (int)stage,
                SlotId = Math.Max(0, ActiveSlot),
                X = pos.X, Y = pos.Y, Z = pos.Z,
                OnBlockFace = aim.Face,
                HitX = CollectibleNet.SerializeDoublePrecise(aim.X),
                HitY = CollectibleNet.SerializeDoublePrecise(aim.Y),
                HitZ = CollectibleNet.SerializeDoublePrecise(aim.Z),
                UsingCount = usingCount,
                FirstEvent = first ? 1 : 0
            }
        });

    /// <summary>
    /// Применить предмет, который держим в руке (еда, бинт, лейка, огниво,
    /// семена). Число шагов — настоящее: столько тиков бот реально держал
    /// кнопку. Если задан <paramref name="at"/>, предмет применяется К БЛОКУ:
    /// именно так работают огниво, лейка, мотыга и семена.
    /// </summary>
    /// <returns>
    /// Правда — применение ДОШЛО до конца тем предметом, с которого началось.
    /// Ложь — руку увели, слот опустел или тело не тикало: сервер такое
    /// применение не засчитывает, и врать об успехе нельзя.
    /// </returns>
    public async Task<bool> UseHeldAsync(double seconds, BlockPos? at = null, int onFace = 4,
        bool sneak = false, CancellationToken ct = default)
    {
        // Предмет применяют К БЛОКУ — значит есть и точка на блоке. Раньше сюда
        // писался «верх центра клетки» независимо от того, видно ли этот верх.
        // Без блока (еда, бинт) точка клика ни на что не влияет
        // Сервер берёт предмет ПО НОМЕРУ СЛОТА ИЗ ПАКЕТА и, если слот пуст,
        // молча выходит (ServerSystemInventory.HandleHandInteraction:325).
        // Такой отказ выглядит как «ничего не произошло» и стоил нам вечера
        // на мотыге и поджиге костра — теперь говорим о нём вслух
        if (Held is not { IsEmpty: false } held)
        {
            OnLog?.Invoke($"нечего применять: активный слот {ActiveSlot} пуст — " +
                          "сервер такой пакет отбрасывает молча");
            return false;
        }

        // МЁРТВЫМ РУКИ НЕ РАБОТАЮТ — то же правило, что у клика по блоку
        // (см. SelfState.BodyIsDead). Есть и бинтоваться лёжа нельзя, а
        // «применил» про мёртвого было бы обещанием успеха без факта
        if (ctx.Self.Dead)
        {
            OnLog?.Invoke($"{held.Code} не применю: я мёртв — жду возрождения");
            return false;
        }

        // Слот запоминаем СЕЙЧАС и им же отпускаем кнопку. Пакет собирался
        // по текущему активному слоту, и если за 2,5 секунды еды добыча
        // переложила в руку кирку — «отпустил» уходил с киркой, сервер молча
        // выходил, а бот рапортовал «поел». Отсюда голодная смерть с полными
        // сумками хлеба
        int slot = Math.Max(0, ActiveSlot);
        string? startedWith = held.Code;

        AimPoint aim = new(0.5, 0.5, 0.5, onFace);
        if (at is { } target)
        {
            if (AimFor(target, onFace, fallbackY: 1.0) is not { } onBlock)
            {
                OnLog?.Invoke($"не применить {held.Code} к {target}: нет прямой видимости или далеко");
                return false;
            }
            aim = onBlock;
        }

        // ВЗГЛЯД ДЕРЖИТ ДЕЛО — но только когда цель есть. Еда, бинт и питьё
        // никуда не целятся, и отнимать у бота живость на время обеда незачем:
        // человек, подошедший к жующему боту, должен видеть, что тот его заметил
        using var looking = at is { } aimed
            ? ctx.Movement.HoldAim($"применяю {held.Code} к {aimed}")
            : null;

        // КНОПКА УДАРА ОТПУСКАЕТСЯ ПЕРЕД ЕДОЙ — и это тот самый живой случай:
        // «во время копания захотел есть, и при поедании хлеба была анимация
        // копания». Тело у бота одно, и пока для сервера зажата левая кнопка
        // (он держит клавиши игрока СОСТОЯНИЕМ, см. ServerMain
        // .HandleMoveKeyChange), окружающие видят кирку, а не хлеб. Живой игрок
        // в этот миг кнопку отпускает — отпускаем и мы, кто бы её ни держал
        await ctx.Actions.ReleaseKeyAsync(Actions.KeyLeftMouse);

        if (sneak)
            await ctx.Actions.SetSneakAsync(true);
        int startTicks = BodyTicks;
        bool begun = false;
        try
        {
            await ctx.Bot.SendPacketAsync(
                HeldPacket(EnumHandInteractNw.StartHeldItemUse, 0, first: true, at, aim, slot: slot));
            begun = true;
            var started = DateTime.UtcNow;
            while (true)
            {
                double left = seconds - (DateTime.UtcNow - started).TotalSeconds;
                if (left <= 0 || ct.IsCancellationRequested)
                    break;
                await Task.Delay((int)Math.Max(1, Math.Min(100, left * 1000)), ct).ContinueWith(_ => { });
            }
            int steps = StepsSince(startTicks);
            OnLog?.Invoke($"применил {held.Code} {seconds:0.##} с, шагов {steps}" +
                          (at is { } t2 ? $" по {t2}, грань {aim.Face}" : ""));

            // Тело не тикало — сервер применение не засчитает, сколько кнопку
            // ни держи. Молчать об этом значит выдавать провал за успех
            if (steps <= 0)
            {
                OnLog?.Invoke($"{startedWith}: тело не тикало (шагов 0) — применение не засчитано");
                return false;
            }
            if (ActiveSlot != slot)
            {
                OnLog?.Invoke($"{startedWith}: руку увели во время применения " +
                              $"(слот {slot} → {ActiveSlot}) — не засчитано");
                return false;
            }
            return true;
        }
        finally
        {
            // «ОТПУСТИЛ» УХОДИТ ВСЕГДА — и на отказе, и на прерывании, и на
            // сбое. Незакрытое применение сервер считает продолжающимся: бот
            // так и стоял бы с поднесённым ко рту хлебом
            if (begun)
                await ctx.Bot.SendPacketAsync(HeldPacket(EnumHandInteractNw.StopHeldItemUse,
                    StepsSince(startTicks), first: false, at, aim, slot: slot));
            if (sneak)
                await ctx.Actions.SetSneakAsync(false);
        }
    }

    private Packet_Client HeldPacket(EnumHandInteractNw stage, int usingCount, bool first,
        BlockPos? at, AimPoint aim, long onEntityId = 0, int? slot = null) => new()
    {
        Id = 25,
        HandInteraction = new Packet_ClientHandInteraction
        {
            UseType = 2,
            MouseButton = 2,
            EnumHandInteract = (int)stage,
            // Настоящий клиент кладёт сюда номер АКТИВНОГО слота и никогда
            // не заполняет InventoryId — предмет берётся из руки
            SlotId = slot ?? Math.Max(0, ActiveSlot),
            X = at?.X ?? 0,
            Y = at?.Y ?? 0,
            Z = at?.Z ?? 0,
            OnBlockFace = aim.Face,
            HitX = CollectibleNet.SerializeDoublePrecise(aim.X),
            HitY = CollectibleNet.SerializeDoublePrecise(aim.Y),
            HitZ = CollectibleNet.SerializeDoublePrecise(aim.Z),
            OnEntityId = onEntityId,
            UsingCount = usingCount,
            FirstEvent = first ? 1 : 0
        }
    };

    /// <summary>
    /// Применить предмет из руки К СУЩЕСТВУ и держать кнопку.
    ///
    /// Так разделывают тушу ножом, так же доят и стригут. Отличие от блока —
    /// в пакете: заполняется OnEntityId, а координаты блока остаются НУЛЯМИ.
    /// Сервер разбирает это буквально: ненулевые X/Y/Z он принял бы за блок и
    /// собрал бы BlockSelection вместо EntitySelection
    /// (ServerSystemInventory.HandleHandInteraction), а нож по «блоку в нуле
    /// координат» не режет ничего.
    ///
    /// Дальность сервер проверяет сам (AntiAbuse): бить надо, стоя рядом.
    /// </summary>
    /// <param name="sneak">
    /// Держать Shift. Разделка туши в игре идёт ТОЛЬКО в приседе:
    /// ItemKnife.OnHeldInteractStart начинает резать лишь при зажатом ShiftKey,
    /// иначе возвращает «не обработано», сервер не открывает использование
    /// вовсе, и удержание кнопки уходит в пустоту. Поймано живьём: нож в руке,
    /// туша под носом, пять секунд удержания — и «разделать не вышло».
    /// </param>
    public async Task<bool> UseHeldOnEntityAsync(long entityId, double seconds,
        bool sneak = false, CancellationToken ct = default)
    {
        if (Held is not { IsEmpty: false } held)
        {
            OnLog?.Invoke($"нечего применять: активный слот {ActiveSlot} пуст");
            return false;
        }
        if (ctx.Entities.Get(entityId) is not { } target)
        {
            OnLog?.Invoke($"сущности {entityId} не вижу");
            return false;
        }
        double distance = DistanceToPoint(target.X, target.Y + 0.5, target.Z);
        if (distance > Reach)
        {
            OnLog?.Invoke($"до сущности {target.Code} {distance:0.#} бл — дальше руки ({Reach:0.#})");
            return false;
        }

        // Разделка, дойка и стрижка — прицельные дела не меньше добычи: нож
        // режет тушу, в которую смотрят. Взгляд держим всё время удержания
        using var looking = ctx.Movement.HoldAim($"применяю {held.Code} к {target.Code}");

        await ctx.Movement.FaceAsync(target.X, target.Z, ct);
        // Точка попадания — середина туловища, как у игрока, целящегося в тушу
        var aim = new AimPoint(0, 0.5, 0, 0);

        // Та же одна рука на одно дело: нож режет тушу, а не машет по ней
        await ctx.Actions.ReleaseKeyAsync(Actions.KeyLeftMouse);

        if (sneak)
            await ctx.Actions.SetSneakAsync(true);
        int startTicks = BodyTicks;
        bool begun = false;
        try
        {
            await ctx.Bot.SendPacketAsync(
                HeldPacket(EnumHandInteractNw.StartHeldItemUse, 0, first: true, null, aim, entityId));
            begun = true;
            var started = DateTime.UtcNow;
            double stepAccum = 0;
            while (true)
            {
                double left = seconds - (DateTime.UtcNow - started).TotalSeconds;
                if (left <= 0 || ct.IsCancellationRequested)
                    break;
                await Task.Delay((int)Math.Max(1, Math.Min(60, left * 1000)), ct).ContinueWith(_ => { });
                double elapsed = (DateTime.UtcNow - started).TotalSeconds;
                if (elapsed - stepAccum >= 0.15)
                {
                    stepAccum = elapsed;
                    await ctx.Bot.SendPacketAsync(HeldPacket(EnumHandInteractNw.StepHeldItemUse,
                        StepsSince(startTicks), first: false, null, aim, entityId));
                }
            }
            OnLog?.Invoke($"применил {held.Code} к {target.Code} {seconds:0.##} с, " +
                          $"шагов {StepsSince(startTicks)}");
            return true;
        }
        finally
        {
            // «Отпустил» уходит всегда: незакрытая разделка держит нож в туше
            if (begun)
                await ctx.Bot.SendPacketAsync(HeldPacket(EnumHandInteractNw.StopHeldItemUse,
                    StepsSince(startTicks), first: false, null, aim, entityId));
            if (sneak)
                await ctx.Actions.SetSneakAsync(false);
        }
    }

    /// <summary>
    /// Бросить предмет на землю: переложить его в инвентарь «под ногами».
    /// Отдельного пакета «выбросить» в игре нет — именно так это делает
    /// и живой клиент.
    /// </summary>
    /// <param name="count">Сколько штук; 0 — всю стопку.</param>
    /// <returns>Сколько штук ушло на землю (0 — не нашли или не вышло).</returns>
    public async Task<int> DropAsync(Func<string, bool> match, int count = 0,
        CancellationToken ct = default)
    {
        if (ctx.Self.FindCarried(match) is not { } found)
            return 0;
        // Инвентарь «под ногами» зовут ПОЛНЫМ именем — «ground-<uid>». Раньше
        // сюда уходило голое «ground», а сервер ищет инвентарь по точному
        // ключу (PlayerInventoryManager.GetInventory), не находил его и молча
        // отменял перенос: выбросить бот не мог НИЧЕГО и никогда
        if (ctx.Self.GroundInventoryId is not { } ground)
        {
            OnLog?.Invoke("выбросить некуда: сервер не прислал инвентарь «под ногами»");
            return 0;
        }
        int take = count > 0 ? Math.Min(count, found.Content.Count) : found.Content.Count;

        // МЕРИМ ОДНИМ И ТЕМ ЖЕ ЧИСЛОМ ДО И ПОСЛЕ. Здесь «до» бралось из ОДНОГО
        // слота (found.Content.Count), а «после» считалось СУММОЙ по всем
        // сумкам — числа несопоставимы. Живой случай: у бота два стака
        // stone-granite по 64, «!брось stone» — сервер честно выбрасывает
        // первый, сумма падает со 128 до 64, «до» равнялось 64, условие
        // «64 < 64» ложно. Бот полторы секунды ждал, писал «бросить не вышло»
        // и отвечал в чат «Нечего бросать», пока 64 камня уже лежали на земле
        string code = found.Content.Code!;
        int Carried() => ctx.Self.CarrySlots()
            .Where(s => s.Content.Code == code)
            .Sum(s => s.Content.Count);

        int before = Carried();
        await ctx.Actions.MoveItemAsync(found.InventoryId, found.Slot, ground, 0, take);

        // Проверяем по сумке: сервер мог и отказать
        var until = DateTime.UtcNow.AddSeconds(1.5);
        while (DateTime.UtcNow < until && !ct.IsCancellationRequested)
        {
            int now = Carried();
            if (now < before)
            {
                // ЗАЧЁТА ВЫБРОСА ЗДЕСЬ БОЛЬШЕ НЕТ: запас по расходу слушает
                // одну дверь — Actions.OnItemMoved, — а она лежит под самим
                // переносом строкой выше. Второй такой же зачёт рядом означал
                // бы ДВОЙНОЕ прощение убыли, то есть кредит, который молча
                // съест следующие настоящие траты
                return before - now;
            }
            await Task.Delay(100, ct).ContinueWith(_ => { });
        }
        OnLog?.Invoke($"{code} бросить не вышло — в сумке не убыло");
        return 0;
    }

    /// <summary>
    /// Съесть/применить предмет по условию: взять в руку и держать кнопку.
    /// </summary>
    /// <returns>
    /// Правда — только если применение ДОШЛО до конца. Раньше здесь стояло
    /// безусловное true за один факт взятия в руку, и «поел» в журнале ничего
    /// не значило.
    /// </returns>
    public async Task<bool> UseItemAsync(Func<SlotContent, bool> match, double seconds,
        CancellationToken ct = default)
    {
        if (await TakeToHandAsync(match, ct) is null)
            return false;
        return await UseHeldAsync(seconds, ct: ct);
    }
