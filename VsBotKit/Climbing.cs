namespace VsBotKit;

/// <summary>Чем именно бот взял высоту (или почему не взял).</summary>
public enum ClimbWay
{
    /// <summary>Уже стояли на нужной высоте.</summary>
    AlreadyThere,
    /// <summary>Дошли обычной дорогой — лестницы, уступы, прыжки.</summary>
    OnFoot,

    /// <summary>
    /// ДОСТРОИЛИ СЕБЕ ПОДЪЁМ — ступенями, лестницей или столбом; чем именно,
    /// говорит отчёт стройки, и он же ложится в <see cref="ClimbResult.Why"/>.
    ///
    /// Здесь стояло <c>Pillar</c> — «достроил столбом», — и это было не именем,
    /// а ПРИГОВОРОМ: подъём умел ровно один приём. Живой случай 29.08, 23:41:10:
    ///   «[подъём] дороги наверх нет, до цели 4 бл — поднимаюсь столбом»
    ///   «[добыча] столбиться нечем — в сумках нет блоков»
    ///   «наверх не вышло: столб вырос на 0 из 4 бл»
    /// — при двадцати четырёх лестницах в сумке (журнал 23:37:09:
    /// «ladder-stick-north ×24») и кирке pickaxe-steel в руке. Заказчик:
    /// «застрял и не стал вылезать, хотя есть лестницы с собой и кирка».
    /// </summary>
    Built,

    /// <summary>
    /// СОШЛИ ВНИЗ СВОИМ ПРИЁМОМ — ступенями, лестницей по стене или разбором
    /// породы под собой; чем именно, говорит отчёт стройки, и он же ложится
    /// в <see cref="ClimbResult.Why"/>.
    ///
    /// Здесь стояло <c>Dismantled</c> — «разобрал под собой», — и это было тем
    /// же ПРИГОВОРОМ, что и <c>Pillar</c> у подъёма строкой выше: спуск умел
    /// ровно один приём, потому что звал столб вниз напрямую
    /// (<c>Mining.PillarDownAsync</c>), минуя выбор приёма
    /// (<see cref="Scaffolding.GetDownAsync"/>).
    ///
    /// ЗАМЕР ПРИЁМКИ 01.09, ОДИН МИР, ДВА ЗОВА, ДОСЛОВНО:
    ///   «!слезь» → «вниз не вышло: спустился на 0 из 6 бл»
    ///              «[добыча] под ногами rock-granite — дальше не разобрать»
    ///   Scaffolding.GetDownAsync(6) → «вниз на 6 бл не спуститься: спрыгивать
    ///   не велено (осторожность роли), лестниц 0, готовой стены нет, порода
    ///   вокруг не берётся тем, что в руках»
    /// Первый утыкался в гранит, второй называл поимённо ВСЁ, чего не хватило.
    /// Теперь зов один, и слово про приём берётся у того, кто его выбрал:
    /// сказать «разобрал под собой» про спуск по лестнице — ровно то же
    /// враньё, что «столбом» про подъём по ступеням.
    /// </summary>
    Descended,

    /// <summary>Не вышло.</summary>
    Failed
}

/// <param name="Way">Чем взяли высоту.</param>
/// <param name="Reached">Где в итоге стоим.</param>
/// <param name="Why">
/// ЧТО ПРОИЗОШЛО — СЛОВАМИ ТОГО, КТО ЭТО СДЕЛАЛ, И ЧИСЛА ТОЖЕ ЕГО.
///
/// Рядом стояло число <c>Built</c> — «сколько блоков разобрали под собой на
/// спуске». У ПОДЪЁМА его не было нарочно: расход называет отчёт стройки
/// своими словами («вышел ступенями на 4 бл, потратив 1 бл», «построил
/// лестницу 2 бл»), а второе число рядом неминуемо разошлось бы с ним —
/// ступени бывают даровыми, а лестница тратится через одну. С тех пор как
/// спуск ходит той же дорогой (<see cref="Scaffolding.GetDownAsync"/>), свои
/// числа называет и его отчёт («повесил лестницу 3 бл, спустился на 6»), —
/// и последний читатель у <c>Built</c> пропал. Дальше он лежал бы мёртвым.
/// </param>
public record ClimbResult(bool Success, ClimbWay Way, BlockPos Reached, string Why)
{
    /// <summary>
    /// КУДА ШЛИ — ВВЕРХ ИЛИ ВНИЗ, — И ОТ ЭТОГО ИДУТ ВСЕ СЛОВА ИТОГА.
    ///
    /// ЖИВОЙ ОТВЕТ СТЕНДА ПРИЁМКИ 31.08, ДОСЛОВНО:
    ///   «!слезь на 106: НАВЕРХ не вышло: спустился на 0 из 6 бл»
    /// — а удавшийся спуск дорогой звался тем же <see cref="ClimbWay.OnFoot"/> и
    /// печатался как «ПОДНЯЛСЯ ногами до …». Человек читает прямое противоречие
    /// в обе стороны: и отказ спуска говорит про верх, и успех спуска тоже.
    /// Спуск при этом мог не сдвинуться ни на блок — и слово «поднялся» уводит
    /// чинить подъём, который тут ни при чём.
    ///
    /// Знает направление только тот, кто позвал, поэтому ставит его
    /// <see cref="Climbing.DescendToAsync"/> — ОДНИМ МЕСТОМ на все свои ветки
    /// (там же и разбор, почему одним).
    /// </summary>
    public bool Вниз { get; init; }

    /// <summary>
    /// ПРИСЛОВЬЕ ОТКАЗА ПОДЪЁМА — ОДНО И НАЗВАНО ОДИН РАЗ.
    ///
    /// Открыто нарочно: этими же словами отказывается стройка
    /// (<c>BuildClimbResult.ToString</c>), и её отчёт ложится сюда в
    /// <see cref="Why"/> целиком. Стенду нужно ровно это слово, а не его копия
    /// в кавычках: разойдись они — сторож двойного присловья зеленел бы при
    /// живой беде.
    /// </summary>
    public const string НеВышло = "наверх не вышло";

    /// <summary>
    /// ПРИСЛОВЬЕ ОТКАЗА СПУСКА. Второе слово, а не вторая механика: выбор между
    /// ними один и стоит в <see cref="Присловье"/>.
    ///
    /// Открыто по той же причине, что и <see cref="НеВышло"/>, и с той же
    /// оговоркой: этими словами отказывается СПУСК СТРОЙКИ
    /// (<c>DescendResult.ToString</c>), и его отчёт ложится сюда в
    /// <see cref="Why"/> целиком — с тех пор как «!слезь» перестал звать столб
    /// вниз в обход выбора приёма. Здесь стояло «стройка вниз не ходит, и её
    /// отчёт сюда не попадает никогда» — ровно это и было бедой: вниз у бота
    /// был один приём из четырёх.
    /// </summary>
    public const string ВнизНеВышло = "вниз не вышло";

    /// <summary>Каким присловьем отказываемся — по тому, куда шли.</summary>
    public string Присловье => Вниз ? ВнизНеВышло : НеВышло;

    /// <summary>Где мы оказались с точки зрения того, куда шли.</summary>
    private string Тут => Вниз ? "внизу" : "наверху";

    public override string ToString() => Way switch
    {
        // «УЖЕ ТУТ» НАЗЫВАЕТ РАЗНИЦУ, ЕСЛИ ОНА ЕСТЬ. Замечание приёмки 31.08:
        // «наверх 1» отвечало «уже наверху ((512016, 104, 512016))», Success =
        // True, не сойдя с места. Формально верно — блок укладывается в допуск
        // (<see cref="Climbing.HeightTolerance"/>), и на один блок живой игрок
        // всходит сам, — но человек, ПОПРОСИВШИЙ БЛОК, читает «уже наверху» и
        // не понимает, куда делась его просьба. Разницу говорит подъём
        // (Climbing.ВДопуске), здесь её только не глотают
        ClimbWay.AlreadyThere => Why.Length == 0
            ? $"уже {Тут} ({Reached})"
            : $"уже {Тут} ({Reached}): {Why}",
        ClimbWay.OnFoot => Вниз
            ? $"спустился ногами до {Reached}"
            : $"поднялся ногами до {Reached}",
        // ПРИЁМ НАЗЫВАЕТ ТОТ, КТО ЕГО ВЫБРАЛ, — И ЭТО ОДНА СТРОКА НА ОБА
        // НАПРАВЛЕНИЯ. Своих слов тут нет нарочно: сказать «столбом» про подъём
        // по лестнице (или «разобрав под собой» про спуск по ней) значит
        // соврать о том, что произошло, а выбор приёма живёт в стройке
        // (Scaffolding.GetOutAsync наверх, Scaffolding.GetDownAsync вниз).
        //
        // Двумя строками это было ровно до тех пор, пока у спуска был ОДИН
        // приём: «спустился на N бл, разобрав под собой» — слова верные, пока
        // разбор и есть весь спуск, и враньё в тот же день, когда приёмов
        // стало четыре
        ClimbWay.Built or ClimbWay.Descended => $"{Why}, стою на {Reached}",

        // ПРИСЛОВЬЕ ГОВОРИТСЯ ОДИН РАЗ — ЖИВОЙ ЧАТ 31.08, ПЕРВАЯ ЖЕ СТРОКА,
        // КОТОРУЮ ЧИТАЕТ ЧЕЛОВЕК:
        //   «наверх не вышло: наверх не вышло: до верха ещё 9 из 9 бл…;
        //    стою на (101, 111, 241)»
        // Причина не в описке, а в шве: пока подъём звал столб напрямую, в
        // Why приходила ГОЛАЯ ПРИЧИНА («столб вырос на 0 из 4 бл»), и присловье
        // было тут единственным. Теперь Why — это ОТЧЁТ СТРОЙКИ целиком
        // (Scaffolding.ClimbOutToAsync возвращает got.ToString()), а он про
        // неудачу начинается ровно теми же словами. Два присловья подряд
        // человек читает как поломку бота, а не как отказ.
        //
        // ОТБИРАТЬ СЛОВА У СТРОЙКИ НЕЛЬЗЯ: её отчёт уходит в журнал и сам по
        // себе (Scaffolding.GetOutAsync), там присловье — единственное.
        // Поэтому его говорит ТОТ, КТО ГОВОРИТ ПОСЛЕДНИМ, и только если оно
        // ещё не сказано
        _ => Why.StartsWith(Присловье, StringComparison.Ordinal)
            ? Why
            : $"{Присловье}: {Why}"
    };
}

/// <summary>
/// Взять высоту. Отдельная механика, потому что «дойти» и «забраться» —
/// разные задачи, и вторая почти всегда решается ДВУМЯ приёмами подряд:
/// сначала дорогой (лестницы, уступы, прыжки), а докуда дороги нет — стройкой
/// себе подъёма. Живой игрок так и делает, когда лестница обрывается.
///
/// Раньше это жило костылём в команде роли, и ИИ-надстройке было недоступно.
/// Теперь это механизм библиотеки: роль и нейросеть только говорят «куда»,
/// а «как» решает он сам.
///
/// ЧЕМ СТРОИТЬ — ЗДЕСЬ НЕ РЕШАЕТСЯ, И ЭТО ГЛАВНОЕ В ЭТОМ ФАЙЛЕ. Второй
/// половиной подъёма стоял голый зов столба (<c>Mining.PillarUpAsync</c>) —
/// ВТОРАЯ КОПИЯ «выбраться наверх», у которой из всего набора был один приём.
/// Настоящий набор — ступени киркой, лестница из сумки, столб из блоков, а
/// нечем столбиться — добыть материал на месте — лежит в стройке
/// (<see cref="Scaffolding.GetOutAsync"/>) и сюда не заходил НИКОГДА.
///
/// Цена этой второй копии, живой журнал 29.08, 23:41:10 (бот на дне ямы,
/// которую сам выкопал, позвали «!комне» на 4 бл выше):
///   «[подъём] дороги наверх нет, до цели 4 бл — поднимаюсь столбом»
///   «[добыча] столбиться нечем — в сумках нет блоков»
///   «наверх не вышло: столб вырос на 0 из 4 бл, стою на (60, 107, 240)»
/// В сумках при этом лежало ladder-stick-north ×24 (журнал 23:37:09), а в
/// руке была pickaxe-steel, которой бот минутой раньше ломал андезит. Ни
/// лестниц, ни кирки этот путь не спрашивал: он спрашивал только блоки под
/// ноги, а лестница под ноги не годится (Wood, Unfit) — и честно отвечал ноль.
/// Заказчик: «застрял и не стал вылезать, хотя есть лестницы с собой и кирка
/// и может выкопаться». Он прав дословно.
///
/// И ЧЕМ СЛЕЗАТЬ — ТОЖЕ НЕ ЗДЕСЬ, И ЭТО ТА ЖЕ БЕДА, НАЙДЕННАЯ ВТОРОЙ РАЗ.
/// Второй половиной СПУСКА стоял такой же голый зов столба, только вниз
/// (<c>Mining.PillarDownAsync</c>): у подъёма к этому дню было пять приёмов
/// через <see cref="Scaffolding.ClimbOutToAsync"/>, а у спуска — один.
/// Настоящий набор — спрыгнуть (его решает движение своим телом), ступени
/// вниз, лестница по стене, столб под собой — и правило выбора между ними
/// (<c>Walker.ChooseWayDown</c>) лежат в <see cref="Scaffolding.GetDownAsync"/>
/// и сюда не заходили никогда.
///
/// ЗАМЕР ПРИЁМКИ 01.09, ОДИН МИР, ДВА ЗОВА, ДОСЛОВНО:
///   «!слезь» → «вниз не вышло: спустился на 0 из 6 бл»
///              «[добыча] под ногами rock-granite — дальше не разобрать»
///   Scaffolding.GetDownAsync(6) → «вниз на 6 бл не спуститься: спрыгивать не
///   велено (осторожность роли), лестниц 0, готовой стены нет, порода вокруг
///   не берётся тем, что в руках»
/// Один и тот же бот в одном и том же мире отвечал человеку двумя разными
/// способами: первый утыкался в гранит, второй называл поимённо всё, чего не
/// хватило, — и по второму видно, нести ли лестницы или повернуть ручку.
///
/// Стройка — не чит: и блоки, и лестницы берутся из сумок и тратятся
/// по-настоящему, а ступени рубятся тем, что сейчас в руке.
/// </summary>
public class Climbing
{
    private readonly BotContext ctx;

    public Climbing(BotContext ctx) => this.ctx = ctx;

    public event Action<string>? OnLog;

    /// <summary>
    /// ИМЯ РУЧКИ РОЛИ, КОТОРУЮ НАДО ПОВЕРНУТЬ, ЧТОБЫ РАЗРЕШИТЬ ПОДЪЁМ К ЦЕЛИ.
    ///
    /// КОНСТАНТОЙ, А НЕ ГОЛОЙ СТРОКОЙ В ОТКАЗЕ, И ЭТО НЕ КРАСОТА. Библиотека
    /// про роли не знает (закон 1), поэтому имя настройки живёт тут ТЕКСТОМ, и
    /// связи с настоящим свойством роли у него нет никакой. Голая строка внутри
    /// сообщения проходила МИМО КАРАУЛА: сторож
    /// <c>ИмяРучкиВОтказеНастоящееTests</c> собирал имена по константам
    /// «Ручка…», и написанное прямо в кавычках он не видел вовсе — так эта беда
    /// и вернулась третий раз (замечание приёмки 31.08).
    ///
    /// Теперь караул читает и сами исходники: всякое имя, названное рядом со
    /// словами «ручка роли», сверяется с живым списком ручек. Мимо него уже не
    /// написать — ни строкой, ни константой.
    /// </summary>
    public const string РучкаСтолбитьсяКГостю = "СтолбитьсяКГостю";

    /// <summary>
    /// Имя ручки роли, задающей предел высоты подъёма. Константой по той же
    /// причине, что и <see cref="РучкаСтолбитьсяКГостю"/>, и под тем же
    /// караулом.
    /// </summary>
    public const string РучкаМаксимальныйСтолб = "МаксимальныйСтолб";

    /// <summary>
    /// Разрешено ли ДОСТРАИВАТЬ СЕБЕ ПОДЪЁМ, когда дороги наверх нет.
    ///
    /// Имя осталось прежним нарочно: это та же ручка роли «СтолбитьсяКГостю»,
    /// и переименовать её значило бы тихо потерять число из шести пресетов.
    /// А вот набор приёмов за ней теперь настоящий — ступени, лестница, столб
    /// (<see cref="Scaffolding.GetOutAsync"/>), — и это не расширение прав:
    /// раньше «нельзя столбиться» отнимало у бота ВСЁ, потому что столб был
    /// единственным приёмом. Чужое при этом бережёт не эта ручка, а застава
    /// (<see cref="BreakGuard"/>) и ручки «ВыбиратьсяНаверх» (рубить ли
    /// ступени) и «ДобыватьМатериалНаСтолб» (копать ли материал вокруг).
    /// </summary>
    public bool AllowPillar { get; set; } = true;

    /// <summary>
    /// Насколько высокий подъём бот согласен строить за один раз. Выше — это
    /// уже стройка, а не подъём: долго, шумно и съедает все блоки из сумок.
    /// Ручка роли «МаксимальныйСтолб» — она же ответ на «как глубоко забираться».
    /// </summary>
    public int MaxPillar { get; set; } = 24;

    /// <summary>
    /// Имя ручки роли, задающей <see cref="PillarWithin"/>. Константой по той
    /// же причине, что и <see cref="РучкаСтолбитьсяКГостю"/>, и под тем же
    /// караулом.
    /// </summary>
    public const string РучкаСтолбитьсяВРадиусе = "СтолбитьсяВРадиусе";

    /// <summary>
    /// Насколько близко к цели по горизонтали имеет смысл СТРОИТЬ ВЕРТИКАЛЬ —
    /// и вверх, и вниз. Дальше — это уже не подъём к цели, а башня посреди
    /// поля (и не спуск к цели, а колодец посреди поля).
    ///
    /// Важно, что это НЕ «строго под целью»: столб поднимает бота на нужную
    /// высоту, а последние метры он проходит поверху. Игрок делает ровно так.
    ///
    /// РУЧКА РОЛИ «СтолбитьсяВРадиусе», И ЭТО ЗАПОЗДАЛАЯ ПРАВКА. Число жило
    /// здесь заводским и не ставилось НИ ОДНОЙ ролью: в окне его не было, в
    /// пресетах не было, повернуть его человек не мог ничем — то есть по
    /// закону 1 этой настройки для хозяина бота не существовало вовсе.
    /// </summary>
    public double PillarWithin { get; set; } = 20;

    /// <summary>Считаем, что высота взята, если разница не больше этого.</summary>
    public double HeightTolerance { get; set; } = 1.5;

    /// <summary>
    /// Имя ручки роли, задающей <see cref="CanGetBackDown"/>. Константой по
    /// той же причине, что и <see cref="РучкаСтолбитьсяКГостю"/>.
    /// </summary>
    public const string РучкаСлезатьРазбираяПодСобой = "СлезатьРазбираяПодСобой";

    /// <summary>
    /// Разрешено ли слезать с того, что построил, — разбирая под собой или
    /// сходя по своей же лестнице. Пока это true, подъём обратим: поднялся —
    /// слез. Если роль это запретит, бот и подниматься не станет: подъём без
    /// спуска — ловушка, а живьём это кончилось падением насмерть.
    ///
    /// РУЧКА РОЛИ «СлезатьРазбираяПодСобой», И ЭТО ЗАПОЗДАЛАЯ ПРАВКА.
    /// Значение стояло здесь заводским и не менялось НИ ОДНОЙ ролью, то есть
    /// отказ «наверх поднимусь, а слезть будет нечем» не мог сработать
    /// никогда: свойство было всегда true. Правило описывало живую смерть и
    /// при этом молчало — закон 1.
    /// </summary>
    public bool CanGetBackDown { get; set; } = true;

    /// <summary>
    /// Добраться до точки НА ВЫСОТЕ: сначала дорогой, потом — если надо и
    /// можно — достроить себе подъём.
    /// </summary>
    /// <param name="blockCode">
    /// Чем столбиться; пусто — любым подходящим блоком из сумок. Названный
    /// блок касается ТОЛЬКО столба: ступени рубятся тем, что в руке, а
    /// лестница берётся своя — подставлять сюда её код нечего.
    /// </param>
    public async Task<ClimbResult> ClimbToAsync(BlockPos target, double maxSeconds = 180,
        CancellationToken ct = default, string blockCode = "")
    {
        if (Feet() is not { } start)
            return new ClimbResult(false, ClimbWay.Failed, new BlockPos(0, 0, 0),
                "не знаю, где стою");

        // ПРАВИЛО УСПЕХА ПОДЪЁМА — ОДНО И НАЗВАНО ОДИН РАЗ: высота сошлась И
        // стоим у цели. Спрашивается оно дважды (до дороги и после), и две
        // одинаковые строчки тут уже расходились бы врозь при первой же правке
        bool Наверху(BlockPos где) =>
            Math.Abs(где.Y - target.Y) <= HeightTolerance && Near(где, target);

        if (Наверху(start))
            return new ClimbResult(true, ClimbWay.AlreadyThere, start,
                ВДопуске(start.Y, target.Y));

        // 1. Дорогой. Она же и единственный способ, если цель НИЖЕ или в стороне
        var deadline = DateTime.UtcNow.AddSeconds(maxSeconds);
        bool arrived = await ctx.Movement.TravelToAsync(target, maxSeconds * 0.7, ct);
        if (Feet() is not { } after)
            return new ClimbResult(false, ClimbWay.Failed, start, "потерял себя в пути");

        // «ДОШЁЛ» У ДОРОГИ — ЭТО ПРО ГОРИЗОНТАЛЬ. ЗДЕСЬ СПРАШИВАЮТ ПРО ВЫСОТУ,
        // И СВЕРИТЬ ЕЁ ОБЯЗАН ПОДЪЁМ, А НЕ ПОВЕРИТЬ ЧУЖОМУ СЛОВУ.
        //
        // Здесь стояло `arrived || (высота сошлась)`, и первое слагаемое молча
        // отменяло второе. Дорога свою цель УТОЧНЯЕТ ВНИЗ — до ближайшей опоры
        // в колонне (Movement.TryTravelToAsync, NearestSupportY(up: 8, down: 8)),
        // — и делает это ПО ДЕЛУ: «встань рядом с сундуком на 112» иначе не
        // выполнимо вовсе, встать можно только на 107, и дорога об этом прямо
        // говорит («названная клетка не опора, встать можно на 107; кто мерит
        // „дошёл ли“ по НАЗВАННОЙ точке, получит расхождение в 5 бл»). Ломать
        // уточнение нельзя — беда была в том, что подъём принимал его МОЛЧА.
        //
        // ЗАМЕР ПРИЁМКИ 31.08, бот стоит на ровной земле на высоте 104:
        //   «наверх 4» → «поднялся ногами до (…, 104, …)», Success = True
        //   «наверх 8» → то же самое: 104 вместо 112
        // Цель в воздухе опорой не была; ближайшей опорой в её колонне нашлась
        // ЗЕМЛЯ ПОД САМИМ БОТОМ (четырьмя и восемью блоками ниже — обе в пределах
        // down: 8), дорога ответила «дошёл», не сделав ни шагу, а подъём объявил
        // это подъёмом. Человек просит подняться и читает «ПОДНЯЛСЯ», стоя рядом
        // с ботом, который не сошёл с места. Ровно этот урок уже был у «!иди»,
        // докладывавшего «Пришёл» по горизонтали.
        //
        // Уточнение дороги при этом целое: пока оно не больше допуска высоты,
        // сверка пропускает его сама — «встать можно на 107» и есть подъём
        // на 107. А расхождение больше допуска подъёмом не считается ничьим
        // словом
        if (ВысотуМерюСам(Наверху(after), arrived, after.Y, target.Y))
            return new ClimbResult(true, ClimbWay.OnFoot, after, "");

        // 2. Стройкой. Только вверх и только если мы уже под целью: строить
        // башню за сто блоков от неё бессмысленно
        int need = target.Y - after.Y;
        if (need <= 0)
            return new ClimbResult(false, ClimbWay.Failed, after,
                $"дороги нет, а цель не выше ({after.Y} → {target.Y}) — подъём не поможет");
        // НА ОДИН БЛОК ЖИВОЙ ИГРОК ЗАПРЫГИВАЕТ САМ — порог общий, он живёт в
        // Scaffolding.ClimbOutToAsync. Спрашиваем его тут ЗАРАНЕЕ только затем,
        // чтобы сказать вслух: молча получить от стройки «строить не стал» и
        // объявить это успехом значило бы соврать про то, что мешает. А мешает
        // не высота, а дорога — и чинить надо её
        if (need < 2)
            return new ClimbResult(false, ClimbWay.Failed, after,
                $"до цели по высоте всего {need} бл — на такое я запрыгиваю сам, " +
                "строить нечего; отсюда мешает не высота, а дорога");
        if (!AllowPillar)
            return new ClimbResult(false, ClimbWay.Failed, after,
                $"до цели ещё {need} бл вверх, а достраивать себе подъём не разрешено " +
                $"(ручка роли «{РучкаСтолбитьсяКГостю}»)");
        if (need > MaxPillar)
            return new ClimbResult(false, ClimbWay.Failed, after,
                $"до цели {need} бл вверх — это выше, чем я берусь строить ({MaxPillar}, " +
                $"ручка роли «{РучкаМаксимальныйСтолб}»)");

        double away = ВСторонеОт(after, target);
        if (away > PillarWithin)
            return new ClimbResult(false, ClimbWay.Failed, after,
                $"стою в {away:0} бл в стороне от цели — подъём выведет не туда " +
                $"(ручка роли «{РучкаСтолбитьсяВРадиусе}», сейчас {PillarWithin:0} бл)");

        // ПОДНИМАТЬСЯ ТОЛЬКО НА ТО, С ЧЕГО СЛЕЗЕМ. Столб — гладкая колонна:
        // вниз с неё ведёт единственный способ — разобрать её же. Если это
        // запрещено ролью, лезть наверх значит поставить себя в ловушку,
        // а живьём это кончилось падением насмерть
        if (!CanGetBackDown)
            return new ClimbResult(false, ClimbWay.Failed, after,
                $"наверх {need} бл я поднимусь, а слезть будет нечем — не лезу " +
                $"(ручка роли «{РучкаСлезатьРазбираяПодСобой}»)");

        // ЧЕМ ВЫБИРАТЬСЯ — СПРАШИВАЕМ ТОГО, ЧЬЁ ЭТО ДЕЛО, И РОВНО ТЕМ ЖЕ ЗОВОМ,
        // ЧТО КАРЬЕР И РУДОКОП. Своего выбора приёма здесь нет и быть не
        // должно: он один на весь проект (Scaffolding.ClimbOutToAsync — порог
        // «на один блок запрыгну сам», выбор приёма, правило успеха ПО ФАКТУ
        // ПОДЪЁМА НОГ). Разбор второй копии, которая тут стояла, — в описании
        // класса; сторож против её возвращения — ВыбираюсьИзЯмыОднимМестомTests
        double left = Math.Max(20, (deadline - DateTime.UtcNow).TotalSeconds);
        using var cts = CancellationTokenSource.CreateLinkedTokenSource(ct);
        cts.CancelAfter(TimeSpan.FromSeconds(left));
        // …И ЭТО ЛЕСА, А НЕ ДОРОГА (<see cref="ClimbKeep"/>). Здесь бот не
        // выбирается из ямы — он ДОТЯГИВАЕТСЯ ДО ЦЕЛИ В ВОЗДУХЕ, стоя на земле:
        // башню под собой он разберёт на спуске, сверху вниз, забрав блоки
        // обратно. Умолчание стройки — «дорога», и оно верно для всех прочих
        // звавших (движение из ямы, карьер, рудокоп); отличается ровно этот
        var got = await ctx.Scaffolding.ClimbOutToAsync(target.Y, Feet, cts.Token,
            бл => OnLog?.Invoke($"дороги наверх нет, до цели {бл} бл — достраиваю себе подъём"),
            blockCode, ClimbKeep.Scaffold);

        var top = Feet() ?? after;
        // Поднялись — и последние метры проходим ПОВЕРХУ. Без этого шага подъём
        // бессмыслен: бот встаёт на нужной высоте, но в стороне от цели.
        //
        // Меряем ПОДЪЁМОМ НОГ, а не расходом блоков: ступени в породе поднимают,
        // не потратив ни одного, и по расходу такой выход выглядел бы как
        // «никуда не залез»
        if (got.Up && !Near(top, target) && DateTime.UtcNow < deadline)
        {
            OnLog?.Invoke($"поднялся на {top.Y}, иду поверху к цели");
            await ctx.Movement.TravelToAsync(target,
                Math.Max(20, (deadline - DateTime.UtcNow).TotalSeconds), ct);
        }

        var end = Feet() ?? top;
        bool ok = Math.Abs(end.Y - target.Y) <= HeightTolerance;
        // СЛОВА ОТКАЗА — ЕГО СОБСТВЕННЫЕ. Стройка называет, ЧЕГО не хватило
        // («лестницей — …; столбом — годных блоков 0, а надо 4; ступенями — …»),
        // и пересказывать её своими словами значило бы потерять эти числа:
        // прежнее «столб вырос на 0 из 4 бл» человек чинить не мог ничем.
        // Пустой она тут не бывает: порог «меньше двух» отсечён выше своими
        // словами, а на всё остальное стройка отвечает отчётом
        string why = got.Why;
        // …А ЧИСЛА ПОДЪЁМА — ЕГО СОБСТВЕННЫЕ, И ИХ ДВА: СКОЛЬКО ПРОСИЛИ И
        // СКОЛЬКО ВЗЯЛ. Стройка считает от того места, где её позвали, и про
        // «просили 8» не знает ничего; отчёт без этой пары читается как жалоба
        // на запасы, а человеку надо понять, сдвинулся ли бот вообще. Считаем
        // от НАЧАЛА ЗОВА (start), а не от места после дороги: дорога тоже могла
        // поднять на пару блоков, и это тот самый подъём, о котором спрашивали.
        //
        // Ставится это ПОСЛЕ отчёта стройки нарочно: он начинается присловьем
        // отказа («наверх не вышло»), и всё, что встанет перед ним, разведёт
        // присловье надвое — живой чат 31.08 «наверх не вышло: наверх не вышло:…»
        int просили = target.Y - start.Y, взял = end.Y - start.Y;
        return new ClimbResult(ok, ok ? ClimbWay.Built : ClimbWay.Failed, end,
            ok ? why : $"{why}; просили наверх {просили} бл, поднялся на {взял} — " +
                       $"стою на {end}");
    }

    /// <summary>
    /// СПУСТИТЬСЯ к точке. Сначала дорогой; если дороги вниз нет — разобрать
    /// под собой то, по чему поднялись.
    ///
    /// Без этого «забраться» было ловушкой: бот строил под собой столб до
    /// двадцати четырёх блоков и оставался наверху навсегда — а живьём
    /// шагнул с края и разбился. Уметь подниматься и не уметь спускаться —
    /// это не умение, а способ погибнуть.
    /// </summary>
    public async Task<ClimbResult> DescendToAsync(BlockPos target, double maxSeconds = 180,
        CancellationToken ct = default)
    {
        // ВСЯКОЕ СЛОВО СПУСКА — СВЕРХУ ВНИЗ, И СТАВИТСЯ ЭТО ОДНИМ МЕСТОМ.
        // Веток отсюда выходит пять, и направление, забытое хоть в одной из
        // них, — это ровно тот отчёт, который читала приёмка: «!слезь на 106:
        // НАВЕРХ не вышло». Забыть его теперь негде: итог спуска складывается
        // только здесь
        static ClimbResult Спуск(bool ok, ClimbWay way, BlockPos где, string why) =>
            new(ok, way, где, why) { Вниз = true };

        if (Feet() is not { } start)
            return Спуск(false, ClimbWay.Failed, new BlockPos(0, 0, 0), "не знаю, где стою");

        // Цель уточняем ВНИЗ. Общее правило дороги ищет ближайшую опору в обе
        // стороны, и при спуске это выходит боком: клетка у подножия столба
        // занята самим столбом, ближайшей опорой оказывается его вершина —
        // и «спустись на 113» молча превращалось в «поднимись на 121»,
        // то есть остаться на месте
        if (!ctx.World.IsSupport(target.X, target.Y, target.Z) &&
            ctx.World.NearestSupportY(target.X, target.Y, target.Z, up: 1, down: 24) is { } below)
        {
            if (below != target.Y)
                OnLog?.Invoke($"цель спуска уточнил по высоте {target.Y} → {below}");
            target = target with { Y = below };
        }

        // ПРАВИЛО УСПЕХА СПУСКА — ОДНО И НАЗВАНО ОДИН РАЗ: стоять НЕ ВЫШЕ цели
        // И У НЕЁ ЖЕ. По высоте оно нарочно не такое, как у подъёма (там —
        // «разница не больше допуска в обе стороны»): спустившийся ниже
        // названной клетки спустился, а поднявшийся выше названной — нет.
        // Спрашивается трижды — до дороги, после дороги и после стройки, — и
        // три одинаковые строчки разошлись бы врозь при первой же правке.
        //
        // «У НЕЁ ЖЕ» ЗДЕСЬ НЕ БЫЛО ВОВСЕ, И ЭТО СТОИЛО ЛЖИ ПРО УСПЕХ. У подъёма
        // застава стоит с самого начала (Наверху = высота сошлась И Near), а
        // спуск смотрел ОДИН ТОЛЬКО Y — про X и Z в нём не было ни слова.
        // Живьём: «!слезь x y z» → бот рубил шахту там, где стоял, оказывался
        // ниже названного y за полсотни блоков от названных x z и докладывал
        // УСПЕХ. Человек читает «спустился» и идёт искать бота у себя под
        // ногами. Мерка «рядом ли» тут та же самая, что у подъёма (Near), —
        // второй её тут не заводится
        bool Внизу(BlockPos где) => где.Y <= target.Y + HeightTolerance && Near(где, target);

        if (Внизу(start))
            return Спуск(true, ClimbWay.AlreadyThere, start, ВДопуске(start.Y, target.Y));

        var deadline = DateTime.UtcNow.AddSeconds(maxSeconds);
        // «ДОШЁЛ» ДОРОГИ ЗДЕСЬ ЗНАЧИТ РОВНО ТО ЖЕ, ЧТО И У ПОДЪЁМА, — ПРО
        // ГОРИЗОНТАЛЬ. Стояло тут `if (await TravelToAsync(...)) return
        // ClimbResult(true, OnFoot, …)` — близнец той самой лжи, которую чинили
        // у «!заберись»: слово дороги объявлялось спуском, а сверка высоты
        // стояла строкой ниже, на ДРУГОЙ ветке, и до неё дело не доходило.
        //
        // ЧЕСТНО: живьём это сегодня не стреляло. Уточнение цели вниз (up: 1,
        // down: 24) стоит выше и закрывает почти всё, а дорога сквозь пол цель
        // вверх не уточняет — промах был бы ограничен целью плюс блок. Но
        // держалось это на ЧУЖОМ ИНВАРИАНТЕ: поменяют уточнение дороги — и
        // ложь про успех вернётся, уже на спуске. Теперь высоту меряет тот, кого
        // про неё спросили, и меряет ОБА раза одним правилом
        bool доложила = await ctx.Movement.TravelToAsync(target, maxSeconds * 0.6, ct);
        var stuck = Feet() ?? start;
        if (ВысотуМерюСам(Внизу(stuck), доложила, stuck.Y, target.Y))
            return Спуск(true, ClimbWay.OnFoot, stuck, "");

        int need = stuck.Y - target.Y;
        // МЕШАЕТ НЕ ВЫСОТА, А ДОРОГА — И ОБ ЭТОМ ГОВОРЯТ ВСЛУХ. Близнец той же
        // заставы у подъёма («дороги нет, а цель не выше»). Без неё спуск, до
        // цели которого осталась одна горизонталь, звал бы стройку с нулём или
        // минусом, получал бы «спускаться некуда» и выдавал это за отказ
        // спуска: человек шёл бы чинить лестницы вместо дороги
        if (need <= 0)
            return Спуск(false, ClimbWay.Failed, stuck,
                $"дороги нет, а цель не ниже ({stuck.Y} → {target.Y}) — спуск не поможет; " +
                $"до цели {ВСторонеОт(stuck, target):0} бл по полу, мешает дорога");

        // А ТУДА ЛИ Я СЛЕЗАЮ — ЗАСТАВА, КОТОРОЙ У СПУСКА НЕ БЫЛО ВОВСЕ.
        //
        // У подъёма она стоит давно и теми же словами: строить башню за сто
        // блоков от цели бессмысленно. У спуска ровно та же бессмыслица стоит
        // дороже: колодец в полсотни блоков от названной клетки бот роет НАСКВОЗЬ
        // ПОРОДУ, тратит кирку и время, а потом ещё и оказывается на дне ямы,
        // из которой надо выбираться. Живьём «!слезь x y z» кончался именно
        // этим — и докладом об успехе.
        //
        // Число здесь то же самое и берётся из того же места, что у подъёма
        // (<see cref="PillarWithin"/>): вопрос-то один — «имеет ли смысл строить
        // вертикаль отсюда». Второго числа тут не заводится
        double away = ВСторонеОт(stuck, target);
        if (away > PillarWithin)
            return Спуск(false, ClimbWay.Failed, stuck,
                $"стою в {away:0} бл в стороне от цели — слезу не туда " +
                $"(ручка роли «{РучкаСтолбитьсяВРадиусе}», сейчас {PillarWithin:0} бл)");

        OnLog?.Invoke($"дороги вниз нет ({stuck.Y} → {target.Y}), до низа {need} бл — " +
                      "слезаю сам");

        // ЧЕМ СЛЕЗАТЬ — СПРАШИВАЕМ ТОГО, ЧЬЁ ЭТО ДЕЛО, И РОВНО ТЕМ ЖЕ ЗОВОМ,
        // ЧТО ДВИЖЕНИЕ НА КРОМКЕ ОБРЫВА (Movement.GetDown → Scaffolding.GetDownAsync).
        // Своего выбора приёма здесь нет и быть не должно: он один на весь
        // проект — правило Walker.ChooseWayDown, а за ним ступени, лестница по
        // стене и столб под собой. Здесь стоял ГОЛЫЙ ЗОВ СТОЛБА, и это была
        // та же вторая копия с одним приёмом, которую проект уже ловил у
        // подъёма (разбор — в описании класса; сторож против её возвращения —
        // ВыбираюсьИзЯмыОднимМестомTests).
        //
        // Прыжок сюда не входит нарочно: он не стройка, его делает движение
        // своим телом и по своему бюджету урона — и делает ВЫШЕ, дорогой,
        // которая только что не вышла
        double left = Math.Max(20, (deadline - DateTime.UtcNow).TotalSeconds);
        using var cts = CancellationTokenSource.CreateLinkedTokenSource(ct);
        cts.CancelAfter(TimeSpan.FromSeconds(left));
        var got = await ctx.Scaffolding.GetDownAsync(need, cts.Token);

        var low = Feet() ?? stuck;
        int стройкой = stuck.Y - low.Y;
        // Спустились до цели или хотя бы ниже — дальше обычная дорога.
        // Меряем СВОЕЙ высотой, а не словом приёма: ступени сводят вниз, не
        // потратив ни блока, и по расходу такой спуск выглядел бы как «никуда
        // не слез» — тот же урок, что и у подъёма
        if (стройкой > 0 && DateTime.UtcNow < deadline)
            await ctx.Movement.TravelToAsync(target,
                Math.Max(20, (deadline - DateTime.UtcNow).TotalSeconds), ct);

        var end = Feet() ?? low;
        bool ok = Внизу(end);
        // ЧИСЛА СПУСКА — СВОИ, И ИХ ДВА: сколько просили и сколько сошёл.
        // Стройка считает от того места, где её позвали, и про «просили 6» не
        // знает ничего, а человеку надо понять, сдвинулся ли бот вообще
        int просили = start.Y - target.Y, сошёл = start.Y - end.Y;
        return Спуск(ok, ok ? ClimbWay.Descended : ClimbWay.Failed, end, ok
            // УДАЛСЯ СПУСК — СЛОВО ПРО ПРИЁМ ГОВОРИТ ТОТ, КТО ЭТОТ ПРИЁМ ВЫБРАЛ
            // («сошёл по ступеням на 6 бл, ничего не потратив»). А если стройка
            // довела не до конца и остаток добрала дорога, приписывать ей чужую
            // заслугу нельзя: тогда говорим голый факт своими числами
            ? (got.Success ? got.ToString()
                           : $"спустился на {сошёл} бл: стройка свела на {стройкой}, " +
                             "остальное дорогой")
            // ОТКАЗ — СЛОВАМИ СТРОЙКИ ЦЕЛИКОМ: она называет поимённо всё, чего
            // не хватило («спрыгивать не велено (осторожность роли), лестниц 0,
            // готовой стены нет, порода вокруг не берётся тем, что в руках»), и
            // пересказ своими словами потерял бы эти имена — прежнее «спустился
            // на 0 из 6 бл» человек чинить не мог ничем. Присловье при этом
            // говорится ОДИН раз: отчёт стройки начинается ровно им, и ToString
            // второго не приписывает
            : $"{got}; просили вниз {просили} бл, спустился на {сошёл} — стою на {end}");
    }

    /// <summary>
    /// «ДОШЁЛ» У ДОРОГИ — ЭТО ПРО ГОРИЗОНТАЛЬ. ВЫСОТУ МЕРЯЕТ ТОТ, КОГО ПРО НЕЁ
    /// СПРОСИЛИ, — И ЭТО ОДНО МЕСТО НА ПОДЪЁМ И НА СПУСК.
    ///
    /// Правило успеха у них РАЗНОЕ и живёт у каждого своё (<c>Наверху</c> и
    /// <c>Внизу</c>); общее тут другое — что чужое слово успехом не считается
    /// НИКОГДА, а если оно разошлось со своей меркой, человеку это говорят
    /// вслух. Второй копии сверки высоты тут нет нарочно: сюда приходит уже
    /// готовый свой ответ.
    ///
    /// ЗАЧЕМ ГОВОРИТЬ ВСЛУХ (закон 4). Это единственное слово, которым бот
    /// объясняет, почему не поверил дороге. Сними его — и человек читает отказ
    /// без причины: бот стоит рядом с целью, дорога молчит, а «не вышло» есть.
    /// Живой замер 31.08: «наверх 8» → бот на 104 вместо 112, дорога честно
    /// сказала «дошёл» (цель в воздухе опорой не была, ближайшей опорой в её
    /// колонне нашлась земля под самим ботом). Без этой строки человек идёт
    /// чинить дорогу, которая ни при чём.
    /// </summary>
    /// <param name="взято">
    /// СВОЙ ответ про высоту — единственный, которому верим; он и возвращается.
    /// </param>
    /// <param name="доложила">Что сказала дорога. На ответ не влияет — только на слова.</param>
    private bool ВысотуМерюСам(bool взято, bool доложила, int стою, int просили)
    {
        if (!взято && доложила)
            OnLog?.Invoke($"дорога доложила «дошёл», но это про горизонталь: " +
                          $"стою на {стою}, а просили {просили} — высоту меряю сам");
        return взято;
    }

    /// <summary>
    /// РАЗНИЦА, УКЛАДЫВАЮЩАЯСЯ В ДОПУСК, — ВСЁ РАВНО НАЗЫВАЕТСЯ ВСЛУХ.
    ///
    /// Замечание приёмки 31.08: «наверх 1» отвечало «уже наверху ((512016, 104,
    /// 512016))», Success = True, не сойдя с места. Это ВЕРНО по существу и
    /// ломать тут нечего: блок укладывается в <see cref="HeightTolerance"/>, а
    /// на блок живой игрок всходит сам — тем же порогом подъём и отказывается
    /// строить («до цели по высоте всего 1 бл — на такое я запрыгиваю сам»).
    /// Сузить допуск было бы хуже, а не лучше: им же пропускается законное
    /// уточнение цели дорогой на блок-другой, и «встань рядом с сундуком»
    /// перестало бы удаваться вовсе.
    ///
    /// Беда была не в числе, а в СЛОВЕ: человек, попросивший блок, читал «уже
    /// наверху» и не находил в ответе своей просьбы. Теперь ответ называет обе
    /// высоты и сам допуск — и человеку видно, что бот его услышал.
    /// </summary>
    private string ВДопуске(int стою, int просили) =>
        стою == просили
            ? ""
            : $"просили {просили}, стою на {стою} — разница {Math.Abs(просили - стою)} бл, " +
              $"это в пределах допуска {HeightTolerance:0.#} бл, ради неё не двигаюсь";

    private BlockPos? Feet() => ctx.Self.Position is { } p
        ? new BlockPos((int)Math.Floor(p.X), (int)Math.Floor(p.Y), (int)Math.Floor(p.Z))
        : null;

    private bool Near(BlockPos a, BlockPos b) =>
        Math.Abs(a.X - b.X) <= 2 && Math.Abs(a.Z - b.Z) <= 2;

    /// <summary>
    /// НА СКОЛЬКО БЛОКОВ Я В СТОРОНЕ ОТ ЦЕЛИ ПО ПОЛУ. Одно место на подъём и
    /// на спуск: вопрос «имеет ли смысл строить вертикаль отсюда» у них один,
    /// и две одинаковые формулы разошлись бы при первой же правке.
    /// </summary>
    private static double ВСторонеОт(BlockPos где, BlockPos цель) =>
        Math.Sqrt((где.X - цель.X) * (где.X - цель.X) +
                  (где.Z - цель.Z) * (где.Z - цель.Z));
}
