using System.Globalization;
using System.Text.Json;

using VsBotKit.Panel;

namespace VsBotKit;

/// <summary>
/// Транслокатор, увиденный ботом. Данные — из блок-сущности StaticTranslocator,
/// сервер шлёт их вместе с чанком и обновляет при изменениях, так что сеть
/// копится пассивно: где бот прошёл, там он и запомнил переходы.
/// </summary>
public sealed class TranslocatorInfo
{
    /// <summary>Клетка самого блока (пластина, на которую надо встать).</summary>
    public required BlockPos Pos { get; init; }

    /// <summary>Куда переносит. null — сервер ещё не привязал пару.</summary>
    public BlockPos? Destination { get; init; }

    /// <summary>Сколько починок сделано (нужно 4).</summary>
    public int RepairState { get; init; }

    /// <summary>Флаг canTele блок-сущности.</summary>
    public bool CanTeleport { get; init; }

    /// <summary>
    /// Починен полностью (4 взаимодействия ремонтом).
    ///
    /// ЭТО ЛУЧШЕЕ, ЧТО МЫ МОЖЕМ СКАЗАТЬ, А НЕ ИСТИНА. Само требование
    /// (RepairInteractionsRequired) сервер не шлёт и даже не сохраняет —
    /// см. оговорки в <see cref="TranslocatorRules"/>.
    /// </summary>
    public bool Repaired => RepairState >= TranslocatorRules.RepairInteractionsRequired;

    /// <summary>Готов перенести: починен, включён и знает адрес.</summary>
    public bool Working => Repaired && CanTeleport && Destination != null;

    /// <summary>
    /// Куда встать ногами: центр клетки, пластина высотой 0.125 блока.
    /// Дальше достаточно стоять и слать свою позицию — перенос серверный.
    /// </summary>
    public (double X, double Y, double Z) StandPoint => TranslocatorRules.StandPoint(Pos);

    /// <summary>
    /// КУДА ВЫБРОСИТ — не сама клетка выхода, а точка, которую сервер
    /// подставит нам в позицию. Отличие в −0,3 по X и Z и в +1 по высоте, и
    /// именно по ней проверяется «перенесло ли туда»: см.
    /// <see cref="TranslocatorRules.LandingPoint"/>.
    /// </summary>
    public (double X, double Y, double Z)? LandingPoint =>
        Destination is { } d ? TranslocatorRules.LandingPoint(d) : null;

    public override string ToString() =>
        $"{Pos} -> {(Destination is { } d ? d.ToString() : "?")}" +
        $"{(Working ? "" : Repaired ? " (спит)" : $" (сломан {RepairState}/4)")}";
}

/// <summary>
/// Карта транслокаторов: что бот видел и куда оно ведёт. Ремонтом не
/// занимается — ищет рабочий и приводит к нему (требование пользователя).
///
/// Формат данных блок-сущности (все поля уходят клиенту как есть):
/// canTele(bool), repairState(int), activated(bool), tpLocationIsOffset(bool),
/// teleX/teleY/teleZ(int) — последние только когда пара уже назначена.
/// </summary>
public class TranslocatorMap
{
    /// <summary>Имя класса блок-сущности в пакетах.</summary>
    public const string BlockEntityClass = "StaticTranslocator";

    /// <summary>
    /// Сколько починок требует ванильный транслокатор. Само число живёт в
    /// <see cref="TranslocatorRules"/> вместе с остальными фактами блок-сущности
    /// и с оговоркой, откуда мы его знаем и чего про него знать не можем.
    /// </summary>
    public const int RepairInteractionsRequired = TranslocatorRules.RepairInteractionsRequired;

    private readonly WorldModel world;

    public TranslocatorMap(WorldModel world) => this.world = world;

    /// <summary>
    /// СВОЯ ПАМЯТЬ ПАР, переживающая перезапуск. Кладётся снаружи
    /// (<see cref="VsBot"/>); null — памяти нет, и всё работает как раньше.
    ///
    /// ЗАЧЕМ ОНА ИМЕННО ЗДЕСЬ. Этот класс — единственное место, где бот вообще
    /// узнаёт адрес перехода со слов сервера (<see cref="Read"/>). Знание тут
    /// рождается — тут его и надо записывать, иначе оно уйдёт вместе с чанком:
    /// отошёл на двести блоков, сервер выгрузил чанк, и пары как не бывало.
    /// </summary>
    public TlMemory? Memory { get; set; }

    /// <summary>Все транслокаторы, которые бот когда-либо видел.</summary>
    public IEnumerable<TranslocatorInfo> All =>
        world.AllBlockEntities
            .Where(be => be.ClassName == BlockEntityClass)
            .Select(Read)
            .Where(t => t != null)!;

    /// <summary>Только рабочие: починенные, включённые и с известным адресом.</summary>
    public IEnumerable<TranslocatorInfo> Working => All.Where(t => t.Working);

    /// <summary>Транслокатор в точке или null (в т.ч. если блок сломан).</summary>
    public TranslocatorInfo? At(BlockPos pos) =>
        world.GetBlockEntity(pos) is { ClassName: BlockEntityClass } be ? Read(be) : null;

    /// <summary>
    /// Ближайший к точке рабочий транслокатор. Если задан destinationNear —
    /// ищем тот, который переносит ближе всего к нужному месту (первый шаг
    /// маршрута по сети).
    /// </summary>
    public TranslocatorInfo? Nearest(double x, double y, double z, BlockPos? destinationNear = null)
    {
        var candidates = Working.ToList();
        if (candidates.Count == 0)
            return null;

        if (destinationNear is { } goal)
        {
            // Полезен только тот, что реально сокращает путь до цели
            double current = Dist(goal, x, y, z);
            return candidates
                .Where(t => Dist(goal, t.Destination!.Value) < current)
                .OrderBy(t => Dist(goal, t.Destination!.Value) + Dist(t.Pos, x, y, z) * 0.1)
                .FirstOrDefault();
        }
        return candidates.OrderBy(t => Dist(t.Pos, x, y, z)).FirstOrDefault();
    }

    /// <summary>
    /// Дойти до транслокатора и перенестись.
    ///
    /// САМ ВХОД ЖИВЁТ В <see cref="Translocating.EnterAsync"/>, и здесь
    /// намеренно только переадресация: механика входа сложная (столкновение
    /// коробок, счётчик серверных тиков, проверка «туда ли перенесло»), и двух
    /// её списаний быть не должно. Прежняя здешняя проверка «перенос случился»
    /// сводилась к «нас куда-то унесло» и считала удачей отброс ударом.
    /// </summary>
    /// <param name="promisedExit">
    /// Что обещает КАРТА про выход этой пластины (см.
    /// <see cref="TranslocatorRouting.MapExitFor"/>). null — мнения карты нет,
    /// и сверяемся только с блок-сущностью. Пока этот довесок было некому
    /// подать, проверка «карта согласна с блоком» не срабатывала в живом боте
    /// ни разу, хотя была написана и покрыта тестом.
    /// </param>
    public static Task<SkillResult> TravelThroughAsync(BotContext ctx, TranslocatorInfo tl,
        double warmupSeconds = Translocating.DefaultPatienceSeconds,
        BlockPos? promisedExit = null,
        CancellationToken ct = default) =>
        Translocating.EnterAsync(ctx, tl.Pos, promisedExit, warmupSeconds, ct: ct);

    private static double Dist(BlockPos a, BlockPos b) => Dist(a, b.X, b.Y, b.Z);

    private static double Dist(BlockPos a, double x, double y, double z)
    {
        double dx = a.X - x, dy = a.Y - y, dz = a.Z - z;
        return Math.Sqrt(dx * dx + dy * dy + dz * dz);
    }

    private TranslocatorInfo? Read(BlockEntityInfo be)
    {
        var tree = be.Attributes;
        if (tree == null)
            return null;

        // АДРЕС ЧИТАЕМ ТАК ЖЕ, КАК ЕГО ЧИТАЕТ САМА ИГРА
        // (BlockEntityStaticTranslocator.FromTreeAttributes), а не «как
        // получится». Разниц две, и обе стоили бы дорого:
        //   • при canTele = false игра адрес НЕ БЕРЁТ вовсе, хотя в дереве он
        //     лежит: сервер пишет teleX при любом непустом tpLocation. Читая
        //     его, бот считал бы рабочим тот, что сервер держит выключенным;
        //   • (0, y, 0) у игры означает «адреса нет». Без этой оговорки бот
        //     повёл бы себя к началу координат — за полмиллиона блоков.
        var destination = TranslocatorRules.ExitBlock(
            be.Pos,
            canTeleport: tree.GetBool("canTele"),
            isOffset: tree.GetBool("tpLocationIsOffset"),
            hasAddress: tree.HasAttribute("teleX"),
            tree.GetInt("teleX"), tree.GetInt("teleY"), tree.GetInt("teleZ"));

        var это = new TranslocatorInfo
        {
            Pos = be.Pos,
            Destination = destination,
            RepairState = tree.GetInt("repairState"),
            CanTeleport = tree.GetBool("canTele")
        };

        if (Memory is { } память)
        {
            if (это.Working)
                // ЗАПОМИНАЕМ ТОЛЬКО РАБОЧИЙ (Working = починен, включён, с
                // адресом). Сломанный адрес иногда несёт, но встать на него
                // нельзя, и в сети такая пара обещала бы дорогу, которой нет:
                // бот сходил бы за тысячу блоков и упёрся в отказ «сломан 2/4».
                // Починят — увидим рабочим и запомним тогда
                память.Learn(это.Pos, это.Destination!.Value, byFeet: false);
            else
                // А ЭТО — ОПРОВЕРЖЕНИЕ, и оно надёжное. Мы держим в руках ЖИВУЮ
                // блок-сущность (без неё сюда не попасть), то есть чанк приехал
                // и сервер говорит про эту пластину прямо сейчас: сломана,
                // выключена или без адреса. Память, которая спорит с этим,
                // повела бы бота к пластине, через которую не пройти
                память.Forget(это.Pos, TranslocatorRules.Refusal(
                    TranslocatorRules.Trouble(это), это.Pos, это));
        }

        return это;
    }
}

