/// <summary>
/// ТОЧКА СЕТИ В ИГРОВЫХ КООРДИНАТАХ — тех самых, что игра показывает игроку
/// (F3, «258, 111, −260»), а не во внутренних мировых.
///
/// ПОЧЕМУ ИМЕННО ИГРОВЫЕ И ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ТИП, А НЕ <see cref="BlockPos"/>.
/// Карта сервера отдаёт координаты, УЖЕ отсчитанные от точки спавна, а бот
/// внутри живёт в мировых (середина карты — 512000). Разница между ними —
/// полмиллиона блоков: перепутай их один раз, и бот пойдёт «к транслокатору»
/// за край мира, ни разу не пожаловавшись — числа-то на вид приличные. Пока
/// точка карты и клетка мира были одним типом <see cref="BlockPos"/>, спутать
/// их можно было молча и в любой строке. Теперь нельзя: перевод только через
/// <see cref="TlMapCoords.WorldFromGame"/>, и он требует сдвиг явно.
/// </summary>
public readonly record struct TlPoint(int X, int Y, int Z)
{
    /// <summary>Как это прочитает человек: ровно то, что он видит в игре.</summary>
    public override string ToString() => $"({X}, {Y}, {Z})";

    /// <summary>Расстояние ПО ЗЕМЛЕ (без высоты), блоков.</summary>
    public double FlatDistanceTo(TlPoint other)
    {
        double dx = (double)X - other.X, dz = (double)Z - other.Z;
        return Math.Sqrt(dx * dx + dz * dz);
    }
}

/// <summary>
/// ПЕРЕВОД КООРДИНАТ: карта → игра → мир. Три системы, и путать их нельзя.
///
/// 1. КООРДИНАТЫ КАРТЫ — то, что лежит в GeoJSON: <c>[14653, 147020]</c>.
/// 2. ИГРОВЫЕ — то, что игра показывает игроку: отсчёт от точки спавна.
/// 3. МИРОВЫЕ — то, чем живёт бот внутри: спавн стоит около 512000.
///
/// ЧЕМ КАРТА ОТЛИЧАЕТСЯ ОТ ИГРЫ — ТОЛЬКО ЗНАКОМ У ВТОРОЙ ОСИ. Ось Y у карты
/// смотрит ВВЕРХ (так принято у картинок и у OpenLayers), а игровая Z растёт
/// ВНИЗ по экрану — на юг. Поэтому <c>gameZ = −mapY</c>, а X совпадает.
///
/// ОТКУДА ЭТО ИЗВЕСТНО, а не выдумано. Три независимых источника сходятся:
///   • мод заказчика (TLPath, <c>TlPathService.FromMap2D</c>) кладёт
///     <c>double x = mx, y = -my;</c> и дальше считает это HUD-координатами,
///     то есть игровыми;
///   • сама карта в скрипте кладёт <c>cy = -args.get('y')</c>, а в окошке
///     «Move to coordinates» подписывает поля «X,Z in game coordinates»
///     (разобрано в <see cref="WebMapRules"/>);
///   • её же <c>worldExtent.js</c> у TOPS: <c>origin: [-511997, 512000]</c> —
///     это МИНУС X спавна и ПЛЮС Z спавна, что и означает «по X как игра, по
///     Y с обратным знаком».
///
/// ВЫСОТА НЕ СДВИГАЕТСЯ НИКОГДА. Игра вычитает из координат игрока только
/// клетку спавна по X и Z (<see cref="VsBot.CoordOffset"/>), а Y показывает
/// абсолютный. Поэтому <c>depth1</c>/<c>depth2</c> из карты кладутся в Y как
/// есть, без единой поправки.
///
/// МНОЖИТЕЛЕЙ И ПОВОРОТОВ ЗДЕСЬ НЕТ НАРОЧНО. У мода заказчика в
/// <c>FromMap2D</c> есть ещё <c>ScaleX/ScaleY/OffsetX/OffsetY/SwapAxes/FlipX/
/// FlipY</c> — но все они по умолчанию нейтральны (1, 0, false), то есть это
/// ручки «подкрутить, если карта чужая и кривая». Заводить их у себя значило бы
/// дать человеку семь способов молча сдвинуть всю сеть; когда карта врёт, это
/// надо ЧИНИТЬ, а не компенсировать вслепую.
/// </summary>
public static class TlMapCoords
{
    /// <summary>
    /// Координаты карты → ИГРОВЫЕ. Возвращает дробные: округление — отдельный
    /// шаг, и делать его здесь значило бы прятать потерю точности.
    /// </summary>
    public static (double X, double Z) GameFromMap(double mapX, double mapY) => (mapX, -mapY);

    /// <summary>ИГРОВЫЕ → координаты карты. Обратный ход к <see cref="GameFromMap"/>.</summary>
    public static (double X, double Y) MapFromGame(double gameX, double gameZ) => (gameX, -gameZ);

    /// <summary>
    /// Точка карты (с глубиной из свойств) → игровая клетка.
    /// Округление вниз — как у игры: она берёт КЛЕТКУ, а не число с дробью.
    /// </summary>
    public static TlPoint PointFromMap(double mapX, double mapY, double depth)
    {
        var (x, z) = GameFromMap(mapX, mapY);
        return new TlPoint((int)Math.Floor(x), (int)Math.Floor(depth), (int)Math.Floor(z));
    }

    /// <summary>
    /// ИГРОВАЯ точка → клетка МИРА, которой живёт бот.
    ///
    /// Сдвиг подаётся снаружи (<see cref="VsBot.CoordOffset"/>), а не берётся
    /// сам: до входа в мир его НЕ СУЩЕСТВУЕТ — он приходит с точкой спавна
    /// пакетом. Правило, которое молча взяло бы ноль, отправило бы бота за
    /// полмиллиона блоков от цели.
    /// </summary>
    public static BlockPos WorldFromGame(TlPoint p, (int X, int Z) coordOffset)
    {
        // Складывает WorldOrigin: одно правило перевода на всю библиотеку.
        // Здесь остаётся только СМЕНА ТИПА — TlPoint (игровая) на BlockPos
        // (мировая), ради которой этот метод и существует
        var (x, y, z) = WorldOrigin.ToWorld(p.X, p.Y, p.Z, coordOffset);
        return new BlockPos(x, y, z);
    }

    /// <summary>Клетка МИРА → ИГРОВАЯ точка. Обратный ход к <see cref="WorldFromGame"/>.</summary>
    public static TlPoint GameFromWorld(BlockPos world, (int X, int Z) coordOffset)
    {
        var (x, y, z) = WorldOrigin.ToGame(world.X, world.Y, world.Z, coordOffset);
        return new TlPoint(x, y, z);
    }

    /// <summary>
    /// ПОЧЕМУ СДВИГ БРАТЬ НЕЛЬЗЯ — словами. null означает «сдвиг годный».
    ///
    /// Нулевой сдвиг — это ровно то, что отдаёт <see cref="VsBot.CoordOffset"/>,
    /// пока бот НЕ ВОШЁЛ В МИР. Взять его молча значит принять игровые
    /// координаты за мировые и повести бота в пустоту: у настоящего мира спавн
    /// стоит около 512000, и ноль там не встречается никогда.
    /// </summary>
    public static string? WhyOffsetUnusable((int X, int Z) coordOffset) =>
        coordOffset is { X: 0, Z: 0 }
            ? "сдвиг координат ещё не известен: он берётся из точки спавна, а её сервер " +
              "присылает только при входе в мир. Пока бот не вошёл, перевести адрес с карты " +
              "в клетку мира нечем — и молча взять ноль значило бы ошибиться на полмиллиона блоков"
            : null;
}

/// <summary>
/// ОДИН КОНЕЦ ПАРЫ ТРАНСЛОКАТОРОВ, как его знает карта сервера.
/// </summary>
/// <param name="At">где стоит, в ИГРОВЫХ координатах</param>
/// <param name="Label">
/// Подпись с карты (свойство <c>label</c>). Обычно пуста — на TOPS её ставят
/// руками лишь у заметных узлов. Нужна затем, чтобы маршрут называл пересадку
/// по-человечески, а не одними числами.
/// </param>
/// <param name="Tag">метка с карты (свойство <c>tag</c>) — то же назначение</param>
public readonly record struct TlStation(TlPoint At, string Label = "", string Tag = "")
{
    /// <summary>
    /// Как назвать эту пересадку человеку. Подпись есть — говорим подпись И
    /// координаты: одна подпись без адреса бесполезна тому, кто пойдёт следом.
    /// </summary>
    public string Name => Label.Length > 0 ? $"«{Label}» {At}"
        : Tag.Length > 0 ? $"[{Tag}] {At}"
        : At.ToString();

    public override string ToString() => Name;
}

/// <summary>
/// СВОЯ ЗАПОМНЕННАЯ ПАРА, УЖЕ ПЕРЕВЕДЁННАЯ В ИГРОВЫЕ КООРДИНАТЫ — то, в чём
/// сеть умеет считать.
///
/// ЗАЧЕМ ОТДЕЛЬНЫЙ ТИП, А НЕ <see cref="TlPairSeen"/> ПРЯМО. Память бота живёт
/// в МИРОВЫХ клетках (их он узнаёт первым делом, ещё до того как узнает точку
/// спавна), а сеть — в игровых. Разница между ними полмиллиона блоков, и вся
/// защита от этой ошибки держится на том, что типы РАЗНЫЕ (см. <see cref="TlPoint"/>).
/// Прими сеть мировые клетки «как есть» хоть в одном месте — и бот однажды
/// пойдёт к транслокатору за край мира, ни разу не пожаловавшись. Перевод
/// делается в одном месте: <see cref="TranslocatorRouting"/>, где живой сдвиг.
/// </summary>
/// <param name="From">Вход — игровыми координатами.</param>
/// <param name="To">Выход — игровыми координатами.</param>
/// <param name="CheckedUtc">Когда подтверждено в последний раз.</param>
/// <param name="ByFeet">Проверено ногами, а не только со слов блок-сущности.</param>
public readonly record struct TlOwnPair(TlPoint From, TlPoint To, DateTime CheckedUtc, bool ByFeet);

/// <summary>
/// ВО ЧТО СЧИТАТЬ МАРШРУТ — цены, которыми меряется «стоит ли». Это ПОЛИТИКА:
/// библиотека умеет считать граф, а сколько для НАС стоит секунда ходьбы и
/// готовы ли мы ради телепорта дать крюк — решает роль.
///
/// ПОЧЕМУ ЦЕНЫ В СЕКУНДАХ, А НЕ В БЛОКАХ. Весь смысл сети в том, что телепорт
/// проходит семь тысяч блоков мгновенно. В блоках такое ребро весит ноль, и
/// граф выбрал бы любую цепочку телепортов, даже когда пешком два шага.
/// Секунда — единственная мера, в которой ходьба и телепорт сравнимы честно.
///
/// ВСЕ ЧИСЛА ЗДЕСЬ ОТКУДА-ТО ВЗЯТЫ, И У КАЖДОГО НАПИСАНО ОТКУДА. Выдуманных
/// нет: одни сняты со сборки игры, другие — с калиброванного мода заказчика,
/// и это разные степени доверия, о чём сказано у каждого.
/// </summary>
public sealed record TlRouteSettings
{
    /// <summary>
    /// СКОЛЬКО СЕКУНД НА БЛОК ПУТИ ПО ЗЕМЛЕ.
    ///
    /// ОТКУДА 0,22. Из мода заказчика (<c>TlPathService.WalkTime</c>), где у
    /// числа стоит подпись автора: «0.22 ≈ empirically calibrated (was 0.12,
    /// ran ~1.85× too fast)» — то есть он замерил это ногами на живом сервере.
    ///
    /// ПОЧЕМУ НЕ СЧИТАЕМ ОТ СКОРОСТИ ИГРЫ. Соблазн есть:
    /// <see cref="Movement.BaseWalkSpeed"/> = 3,393 бл/с даёт 0,295 с/блок, а с
    /// бегом (×2) — 0,147. Но обе цифры соврали бы, и в РАЗНЫЕ стороны: граф
    /// меряет расстояние ПО ПРЯМОЙ, а ноги идут в обход гор, озёр и обрывов,
    /// и бежать всю дорогу никто не даёт. 0,22 — это и есть «прямая линия,
    /// пройденная по настоящей земле»; она нарочно между шагом и бегом.
    ///
    /// Число — ручка роли: у бота с другим станом скорости или на сервере с
    /// другой картой оно другое. Но менять его вслепую не надо: маршрут
    /// перестанет совпадать с тем, что бот показывает часами.
    /// </summary>
    public double WalkSecondsPerBlock { get; init; } = 0.22;

    /// <summary>
    /// Надбавка за ПОДЪЁМ: секунд на каждые 30 блоков вверх.
    /// Из того же <c>WalkTime</c> мода: <c>(dy / 30.0) * 15.0</c>.
    ///
    /// Подъём дороже спуска втрое с лишним — и это правда игры, а не причуда:
    /// вверх лезут по лестницам и уступами, вниз сходят почти даром.
    /// </summary>
    public double ClimbSecondsPer30Blocks { get; init; } = 15.0;

    /// <summary>
    /// Надбавка за СПУСК: секунд на каждые 30 блоков вниз.
    /// Из того же <c>WalkTime</c> мода: <c>(|dy| / 30.0) * 8.0</c>.
    /// </summary>
    public double DescendSecondsPer30Blocks { get; init; } = 8.0;

    /// <summary>
    /// СКОЛЬКО СТОИТ ОДНА ПЕРЕСАДКА — от «встал на пластину» до «стою на той
    /// стороне», секунд.
    ///
    /// ОТКУДА 10. Складывается из двух частей, и обе не выдуманы:
    ///   • 4,4 с — СТОЯНИЕ НА ПЛАСТИНЕ. Взято из сборки игры
    ///     (<see cref="TranslocatorNetRules.TeleportWarmupSeconds"/>), не с
    ///     потолка;
    ///   • остальное — подойти вплотную, попасть ногами на пластину, дождаться,
    ///     пока сервер догрузит чужой чанк на той стороне.
    /// Ровно 10 с на телепорт кладёт в свою оценку и мод заказчика
    /// («~10 sec per TL (approach + activation + arrival)»).
    ///
    /// ЧЕМ МЫ РАСХОДИМСЯ С МОДОМ НАРОЧНО. У него ребро-телепорт в графе весит
    /// 3,0 с, а в оценку времени идёт 10,0 с — два разных числа за одно и то же
    /// действие. Из-за этого он ИЩЕТ маршрут, считая пересадку втрое дешевле,
    /// чем потом ОБЪЯВЛЯЕТ: цепочка из шести прыжков ради экономии сотни блоков
    /// выигрывала поиск и проигрывала в жизни. У нас число ОДНО и то же и в
    /// поиске, и в ответе — иначе бот врал бы сам себе.
    /// </summary>
    public double TeleportSeconds { get; init; } = 10.0;

    /// <summary>
    /// НА СКОЛЬКО БЛОКОВ БОТ ГОТОВ ОТОЙТИ ОТ СЕТИ ПЕШКОМ, чтобы попасть на
    /// ближайший транслокатор (и так же — с последнего до цели).
    ///
    /// ОТКУДА 3000. Значение по умолчанию у мода заказчика
    /// (<c>WalkRadiusHud = 3000</c>).
    ///
    /// ЗАЧЕМ ВООБЩЕ ОГРАНИЧИВАТЬ. Не ради скорости счёта, а ради ЧЕСТНОСТИ: без
    /// предела граф соединил бы пешком любые две точки мира, и маршрут «пешком
    /// 200 000 блоков» выглядел бы как настоящий план. Дальше этого круга сеть
    /// просто не помогает, и об этом надо сказать словами.
    /// </summary>
    public double WalkRadius { get; init; } = 3000;

    /// <summary>
    /// Через сколько часов считать выгрузку карты устаревшей.
    ///
    /// ОТКУДА 24. У мода заказчика <c>TtlHours = 24</c>, и это совпадает с тем,
    /// как живёт сама карта: WebCartographer перевыгружает мир не чаще раза в
    /// сутки (у TOPS дата выгрузки прямо подписана внизу страницы).
    /// </summary>
    public double StaleAfterHours { get; init; } = 24;

    /// <summary>
    /// СКОЛЬКО СЕКУНД ДОЛЖНА ВЫИГРАТЬ СЕТЬ НА КАЖДОЙ ПЕРЕСАДКЕ, чтобы идти
    /// через неё, а не ногами.
    ///
    /// ЗАЧЕМ ЭТОТ ПОРОГ ВООБЩЕ НУЖЕН, если Дейкстра и так берёт самый быстрый
    /// путь. Потому что два его ответа стоят РАЗНОГО ДОВЕРИЯ. Пеший путь бот
    /// считает по своей же мерке и ни от кого не зависит; путь по сети —
    /// по карте, которой может быть сутки (<see cref="StaleAfterHours"/>), и
    /// каждая пересадка на нём это место, где план может оборваться:
    /// транслокатор ломают, застраивают и отбирают у него пару. Выигрыш в
    /// полминуты такого риска не стоит, выигрыш в сорок минут — стоит.
    ///
    /// ОТКУДА 15 — ЧИСЛО ВЫВЕДЕНО, А НЕ ВЫБРАНО. Это
    /// <see cref="Translocating.DefaultPatienceSeconds"/> — ровно столько бот
    /// простоит на пластине, ПРЕЖДЕ чем узнает, что карта про неё соврала.
    /// Значит одна враньём доставшаяся пересадка стоит нам не меньше этого, и
    /// меньшего выигрыша ради неё брать незачем.
    ///
    /// ЧЕСТНО: это НИЖНЯЯ оценка потери, а не полная. Настоящая больше —
    /// в неё входит и дорога к мёртвой пластине, и пересчёт маршрута. Но
    /// дорога у каждой пересадки своя, назвать её одним числом нельзя, а
    /// выдуманное «побольше для запаса» отказывало бы сети там, где она честно
    /// помогает. Нижняя граница выведена, верхняя была бы придумана.
    ///
    /// Число — ручка роли: боту, который живёт на сервере с исправной сетью,
    /// порог не нужен вовсе (0), а тому, у кого половина транслокаторов
    /// разобрана, он нужен большим.
    /// </summary>
    public double MinNetGainSecondsPerTransfer { get; init; } =
        Translocating.DefaultPatienceSeconds;

    /// <summary>
    /// Потолок на число пеших рёбер графа — сторож, а не настройка вкуса.
    ///
    /// ПРИЧИНА. Пеших рёбер растёт КВАДРАТ от числа точек в круге: у живой
    /// карты TOPS около девяти тысяч концов, и радиус, задранный до размеров
    /// мира, попросил бы сорок миллионов рёбер и съел бы память. Упёрлись в
    /// потолок — граф не молчит, а жалуется (<see cref="TlNet.Complaints"/>):
    /// урезанная сеть даёт маршрут ХУЖЕ настоящего, и знать об этом надо.
    /// </summary>
    public int MaxWalkEdges { get; init; } = 2_000_000;
}

/// <summary>
/// ЧИСЛА И ИМЕНА, КОТОРЫЕ НЕ НАШИ: их задают игра и формат карты. Ручками они
/// быть не могут — повернуть их значит разойтись с сервером.
/// </summary>
public static class TranslocatorNetRules
{
    /// <summary>
    /// Сколько секунд игра держит на пластине, прежде чем перенести.
    ///
    /// ВЗЯТО ИЗ СБОРКИ, НЕ ВЫДУМАНО: <c>BlockEntityStaticTranslocator</c>
    /// (VSSurvivalMod 1.22.6) в своём конструкторе ставит
    /// <c>TeleportWarmupSec = 4.4f</c>, а <c>BlockEntityTeleporterBase</c>
    /// переносит по условию <c>SecondsPassed &gt; TeleportWarmupSec</c>.
    /// Базовое значение у самого <c>TeleporterBase</c> — 3 с, и именно его,
    /// судя по всему, взял мод заказчика; но у СТАТИЧЕСКОГО транслокатора,
    /// то есть у того единственного, что стоит в мире и попадает на карту,
    /// оно переопределено на 4,4.
    /// </summary>
    public const double TeleportWarmupSeconds = 4.4;

    /// <summary>Путь к сети внутри карты сервера — так его выкладывает WebCartographer.</summary>
    public const string GeoJsonPath = "data/geojson/translocators.geojson";

    /// <summary>Имя файла, если сеть лежит на диске рядом с ботом.</summary>
    public const string FileName = "translocators.geojson";

    /// <summary>
    /// Сколько блоков в клетке склейки: два конца ближе этого — один и тот же
    /// транслокатор. Единица, как у мода заказчика (<c>const double Snap = 1.0</c>).
    ///
    /// Склейка нужна не от неряшливости карты, а потому, что сеть держится
    /// именно на совпадении: пока два конца — разные узлы, пересадки между
    /// ними нет, и граф рассыпается на отдельные пары.
    /// </summary>
    public const int SnapBlocks = 1;

    /// <summary>
    /// Адрес сети по адресу карты сервера. null — адрес карты негоден.
    ///
    /// Смысл в том, чтобы человек не вписывал ДВА адреса: он уже назвал карту
    /// (<see cref="PanelConfig.MapUrl"/>), а сеть лежит внутри неё на
    /// известном месте.
    /// </summary>
    public static string? GeoJsonUrl(string? mapAddress) =>
        WebMapRules.Base(mapAddress) is { } основа ? основа + GeoJsonPath : null;
}

/// <summary>
/// СЕТЬ ТРАНСЛОКАТОРОВ, ПРОЧИТАННАЯ С КАРТЫ СЕРВЕРА: точки и пары. Граф
/// строится из неё (<see cref="Route"/>), а сама она — просто данные.
///
/// ЧТО ЛЕЖИТ В GeoJSON КАРТЫ (разобрано по живому файлу
/// <c>https://map.tops.vintagestory.at/data/geojson/translocators.geojson</c>,
/// не по описанию): <c>FeatureCollection</c>, в нём <c>features</c>, у каждой
/// <c>geometry.type = "LineString"</c> с ДВУМЯ точками — это два конца ОДНОЙ
/// пары, — и <c>properties</c> с <c>depth1</c>/<c>depth2</c> (высоты этих
/// концов), <c>label</c>, <c>tag</c>.
///
/// ПОЧЕМУ ЛИНИЯ, А НЕ ДВЕ ТОЧКИ. Карта рисует пару отрезком, и это удобно нам:
/// связь «кто с кем» дана прямо, гадать по расстояниям не нужно.
///
/// ЧЕГО В КАРТЕ НЕТ И ЧЕГО ОТ НЕЁ НЕЛЬЗЯ ЖДАТЬ: починен ли транслокатор, цел
/// ли он сейчас, не разобрал ли его кто-то вчера. Карта — ВЫГРУЗКА МИРА
/// суточной давности, а не живая связь. Поэтому маршрут по ней — это план, а
/// не обещание, и <see cref="TlRoute.Tell"/> говорит об этом прямо.
/// </summary>
public sealed class TlNet
{
    private readonly List<TlStation> станции;
    private readonly List<(int A, int B)> пары;
    private readonly List<string> жалобы;

    private TlNet(List<TlStation> станции, List<(int, int)> пары, List<string> жалобы,
        string источник, DateTime? выгружено)
    {
        this.станции = станции;
        this.пары = пары;
        this.жалобы = жалобы;
        Source = источник;
        PublishedUtc = выгружено;
    }

    /// <summary>Все концы транслокаторов, по одному разу.</summary>
    public IReadOnlyList<TlStation> Stations => станции;

    /// <summary>Пары «этот переносит на тот» — номерами в <see cref="Stations"/>.</summary>
    public IReadOnlyList<(int A, int B)> Pairs => пары;

    /// <summary>Откуда взята сеть — чтобы человек знал, чему верит.</summary>
    public string Source { get; }

    /// <summary>
    /// Когда карта выгружена, если это известно (заголовок <c>Last-Modified</c>
    /// или время файла). null — неизвестно, и врать о свежести мы не станем.
    /// </summary>
    public DateTime? PublishedUtc { get; }

    /// <summary>
    /// НА ЧТО КАРТА ДАЛА ПОВОД ПОЖАЛОВАТЬСЯ: пропущенные записи, склеенные
    /// концы, отсутствующие высоты. Пусто — придраться было не к чему.
    ///
    /// Жалобы отделены от отказа НАРОЧНО. Пятьсот пар прочлось, три оказались
    /// мусором — это рабочая сеть, а не поломка; молчать же о трёх нельзя:
    /// человек должен понимать, почему бот не видит транслокатор, который он
    /// видит на карте глазами.
    /// </summary>
    public IReadOnlyList<string> Complaints => жалобы;

    /// <summary>Сеть пуста — идти по ней некуда.</summary>
    public bool Empty => пары.Count == 0;

    /// <summary>
    /// ЧТО ЗА СЕТЬ У НАС В РУКАХ — одной строкой для журнала и для человека.
    /// </summary>
    public string Tell()
    {
        string когда = PublishedUtc is { } д
            ? $", выгружена {д.ToLocalTime():dd.MM.yyyy HH:mm}"
            : ", когда выгружена — неизвестно";
        string беды = жалобы.Count > 0 ? $"; {жалобы.Count} замечан(ий) к карте" : "";
        return $"{пары.Count} пар транслокаторов, {станции.Count} концов " +
               $"(источник: {Source}{когда}){беды}";
    }

    /// <summary>
    /// НЕ УСТАРЕЛА ЛИ ВЫГРУЗКА — словами. null означает «свежая настолько,
    /// насколько мы вправе судить».
    ///
    /// ПОЧЕМУ ЭТО ВООБЩЕ ВАЖНО. Транслокатор в игре ломают, чинят и застраивают.
    /// Маршрут по вчерашней карте ведёт бота к пластине, которой может уже не
    /// быть, — и это не беда, если человек предупреждён; беда, когда бот
    /// молча уходит за десять тысяч блоков и там встаёт.
    ///
    /// Неизвестное время выгрузки — ОТДЕЛЬНЫЙ ответ, а не «наверное свежая»:
    /// «не знаю» и «свежая» человек обязан различать.
    /// </summary>
    public string? WhyStale(DateTime nowUtc, double staleAfterHours)
    {
        // ГОВОРИМ ПРО ИСТОЧНИК, А НЕ ПРО «КАРТУ». Источников теперь два: карта
        // сервера и СВОЯ ПАМЯТЬ бота (см. TlMemory). Строка «карта выгружена 30 ч
        // назад» про собственную память бота была бы просто неправдой
        if (PublishedUtc is not { } выгружено)
            return $"когда собраны эти сведения о сети ({Source}) — неизвестно, за их свежесть " +
                   "я не ручаюсь: транслокатор мог быть сломан или застроен уже после";

        var возраст = nowUtc - выгружено;
        // Часы вперёд — не «очень свежая», а разъехавшиеся часы; молчать об
        // этом нельзя, иначе «свежесть» вообще ничего не значит
        if (возраст < TimeSpan.Zero)
            return $"сведения о сети ({Source}) помечены будущим временем " +
                   $"({выгружено:dd.MM.yyyy HH:mm} UTC при текущем {nowUtc:dd.MM.yyyy HH:mm} UTC) — " +
                   "судить об их свежести нечем";

        double порог = Math.Max(0, staleAfterHours);
        return возраст.TotalHours > порог
            ? $"сведения о сети ({Source}) собраны {возраст.TotalHours:0} ч назад " +
              $"(порог {порог:0} ч) — маршрут по ним остаётся планом, а не обещанием: " +
              "часть транслокаторов могли за это время сломать или застроить"
            : null;
    }

    /// <summary>
    /// ПРОЧИТАТЬ СЕТЬ ИЗ GeoJSON. Чистое правило: строка на вход, сеть на
    /// выход, никакой сети и никакого диска.
    ///
    /// ОТКАЗ, А НЕ ПУСТАЯ СЕТЬ. Пустой граф и «карта отдала страницу ошибки»
    /// для вызывающего выглядят одинаково — оба дают «маршрута нет». Поэтому
    /// всё, что мешает прочесть карту, здесь становится ПРИЧИНОЙ словами.
    /// </summary>
    /// <param name="json">содержимое файла</param>
    /// <param name="net">разобранная сеть</param>
    /// <param name="why">почему не вышло (пусто, когда вышло)</param>
    /// <param name="source">откуда взято — попадёт в <see cref="Source"/></param>
    /// <param name="publishedUtc">когда выгружено, если известно</param>
    public static bool TryRead(string? json, out TlNet net, out string why,
        string source = "карта сервера", DateTime? publishedUtc = null)
    {
        net = Empty_(source, publishedUtc);
        why = "";

        if (json is not { Length: > 0 } || json.AsSpan().Trim().Length == 0)
        {
            why = "карта отдала пустой файл сети транслокаторов — брать маршрут неоткуда";
            return false;
        }

        JsonDocument документ;
        try
        {
            документ = JsonDocument.Parse(json);
        }
        catch (JsonException e)
        {
            // Живой случай: вместо файла приходит HTML страницы ошибки, и он
            // тоже «не пуст». Сказать «сеть пуста» было бы враньём
            why = $"файл сети транслокаторов — не JSON: {e.Message}. Похоже, по этому адресу " +
                  "лежит не сеть, а что-то другое (страница ошибки, перенаправление)";
            return false;
        }

        using (документ)
        {
            var корень = документ.RootElement;
            if (корень.ValueKind != JsonValueKind.Object)
            {
                why = "в файле сети транслокаторов на верхнем уровне не объект — это не GeoJSON";
                return false;
            }

            // Проверка типа — та же, что делает мод заказчика перед тем, как
            // положить скачанное себе: без неё в кеш попадает мусор
            if (!корень.TryGetProperty("type", out var тип) ||
                тип.ValueKind != JsonValueKind.String ||
                тип.GetString() != "FeatureCollection")
            {
                why = "файл сети транслокаторов не похож на GeoJSON: на верхнем уровне нет " +
                      "«type: FeatureCollection»";
                return false;
            }

            if (!корень.TryGetProperty("features", out var записи) ||
                записи.ValueKind != JsonValueKind.Array)
            {
                why = "в файле сети транслокаторов нет списка «features» — читать нечего";
                return false;
            }

            var список = new List<TlStation>();
            var связи = new List<(int, int)>();
            var претензии = new List<string>();
            // Склейка по КЛЕТКЕ (X, Z): именно совпадением концов держится сеть
            var поКлетке = new Dictionary<(int, int), int>();
            int пропущено = 0, безВысоты = 0, вырождено = 0;

            foreach (var запись in записи.EnumerateArray())
            {
                if (!TryPair(запись, out var a, out var b, out string подпись, out string метка,
                        out bool высотаЕсть))
                {
                    пропущено++;
                    continue;
                }
                if (!высотаЕсть)
                    безВысоты++;

                int ia = Add(список, поКлетке, a, подпись, метка);
                int ib = Add(список, поКлетке, b, подпись, метка);

                // Оба конца в одной клетке — это не пара, а точка: перенос
                // никуда. Такое в карте встречается у сломанных записей
                if (ia == ib)
                {
                    вырождено++;
                    continue;
                }
                связи.Add((ia, ib));
            }

            if (пропущено > 0)
                претензии.Add($"{пропущено} запис(ей) карты пропущено: не «LineString» с двумя " +
                              "концами или координаты не числа");
            if (вырождено > 0)
                претензии.Add($"{вырождено} пар(ы) карты ведут сами в себя (оба конца в одной " +
                              "клетке) — как переходы они бесполезны");
            if (безВысоты > 0)
                претензии.Add($"у {безВысоты} пар(ы) карта не назвала высоту (depth1/depth2) — " +
                              "взят 0, и время на подъём к ним посчитано неверно");

            if (связи.Count == 0)
            {
                why = "в файле сети транслокаторов нет ни одной годной пары: " +
                      (записи.GetArrayLength() == 0
                          ? "список «features» пуст"
                          : $"все {записи.GetArrayLength()} запис(ей) оказались негодными — " +
                            string.Join("; ", претензии));
                return false;
            }

            net = new TlNet(список, связи, претензии, source, publishedUtc);
            return true;
        }
    }

    private static TlNet Empty_(string source, DateTime? publishedUtc) =>
        new([], [], [], source, publishedUtc);

    /// <summary>Метка своих пар в сети — чтобы маршрут называл их человеку.</summary>
    public const string OwnTag = "своя память";

    /// <summary>
    /// СЕТЬ ИЗ ОДНОЙ СВОЕЙ ПАМЯТИ — когда карты сервера нет вовсе.
    ///
    /// Заказ дословно: «а если вебкарты нет у нас, то мы можем сами запоминать
    /// какие пары у тл и куда идут?». Вот это и есть тот случай.
    ///
    /// Время «выгрузки» здесь честное: САМОЕ СВЕЖЕЕ из подтверждений. По нему
    /// <see cref="WhyStale"/> и рассудит, стоит ли этой памяти верить как
    /// сегодняшней, — тем же правилом, что и карте.
    /// </summary>
    public static TlNet OfOwn(IReadOnlyCollection<TlOwnPair> own) =>
        Empty_("своя память бота", null).Plus(own);

    /// <summary>
    /// ДОБАВИТЬ К СЕТИ СВОЮ ПАМЯТЬ. Возвращает НОВУЮ сеть: прежняя не меняется —
    /// её мог взять кто-то другой, а сеть в этом файле всюду считается данными,
    /// которые не портятся под руками.
    ///
    /// СКЛЕЙКА ТА ЖЕ САМАЯ. Концы сводятся по <see cref="Клетка"/> — тем же
    /// правилом, что и при чтении карты; второго правила склейки в проекте нет
    /// и заводить его нельзя. Иначе тот же транслокатор оказался бы в сети
    /// дважды — раз с карты, раз из памяти, — и Дейкстра честно строила бы
    /// маршрут «пешком ноль блоков» между двумя его двойниками.
    ///
    /// РАСХОЖДЕНИЕ КАРТЫ И ПАМЯТИ — ЭТО ЖАЛОБА, А НЕ ОТКАЗ. Память бота свежее
    /// карты по определению (карту выгружали вчера, а бот стоял тут сегодня),
    /// поэтому побеждает память; но молчать о расхождении нельзя: человек,
    /// который смотрит на карту глазами, обязан знать, что бот видит иначе.
    /// </summary>
    public TlNet Plus(IReadOnlyCollection<TlOwnPair> own)
    {
        if (own is not { Count: > 0 })
            return this;

        var список = new List<TlStation>(станции);
        var поКлетке = new Dictionary<(int, int), int>();
        for (int i = 0; i < список.Count; i++)
            поКлетке.TryAdd(Клетка(список[i].At), i);   // первый побеждает, как при чтении карты

        var связи = new List<(int, int)>(пары);
        var уже = new HashSet<(int, int)>(связи.Select(п =>
            п.Item1 < п.Item2 ? п : (п.Item2, п.Item1)));
        var претензии = new List<string>(жалобы);

        int новых = 0, спорных = 0;
        DateTime? свежайшее = null;

        foreach (var (a, b, когда, ногами) in own)
        {
            if (PartnerOf(a) is { } поКарте && Клетка(поКарте) != Клетка(b))
            {
                спорных++;
                претензии.Add($"карта ведёт {a} в {поКарте}, а я {(ногами ? "сам прошёл" : "видел")} " +
                              $"{a} → {b}. Верю себе: карту выгружали раньше, чем я тут стоял");
            }

            int ia = Add(список, поКлетке, a, "", OwnTag);
            int ib = Add(список, поКлетке, b, "", OwnTag);
            if (ia == ib)
                continue;   // оба конца в одной клетке — это не переход

            var ключ = ia < ib ? (ia, ib) : (ib, ia);
            if (!уже.Add(ключ))
                continue;   // карта уже знает эту пару — второй раз не кладём
            связи.Add((ia, ib));
            новых++;
            if (свежайшее is not { } было || когда > было)
                свежайшее = когда;
        }

        string откуда = станции.Count == 0
            ? $"своя память бота ({новых} пар)"
            : $"{Source} + своя память бота ({новых} пар сверх карты" +
              (спорных > 0 ? $", {спорных} спорн." : "") + ")";

        return new TlNet(список, связи, претензии, откуда, PublishedUtc ?? свежайшее);
    }

    /// <summary>
    /// КЛЕТКА СКЛЕЙКИ по X и Z. Одно место на всю сеть: по нему концы
    /// сливаются при чтении карты и по нему же ищется конец в
    /// <see cref="PartnerOf"/>. Два списания разошлись бы, и «карта не знает
    /// такого транслокатора» звучало бы там, где она его знает.
    ///
    /// Деление ЦЕЛОЧИСЛЕННОЕ отбрасывает к нулю, а не вниз: у −3/2 выходит −1,
    /// у 3/2 — тоже 1, и две точки по разные стороны от нуля склеились бы в
    /// одну. Половина мира стоит в отрицательных координатах, так что это не
    /// придирка.
    /// </summary>
    private static (int X, int Z) Клетка(TlPoint точка) =>
        ((int)Math.Floor((double)точка.X / TranslocatorNetRules.SnapBlocks),
         (int)Math.Floor((double)точка.Z / TranslocatorNetRules.SnapBlocks));

    /// <summary>
    /// КУДА, ПО КАРТЕ, ВЕДЁТ ТРАНСЛОКАТОР ИЗ ЭТОЙ ТОЧКИ. null — карта такого
    /// конца не знает (его на ней нет, или пары у него нет).
    ///
    /// ЗАЧЕМ ЭТО НУЖНО ЖИВОМУ БОТУ. Мнение карты — единственное, с чем можно
    /// сверить слово блок-сущности перед тем, как встать на пластину
    /// (<see cref="TranslocatorRules.MapAgrees"/>). Расходятся они по делу:
    /// карту выгружали вчера, а пары сервер связывает на ходу, — и шаг
    /// маршрута, рассчитанный на другой выход, лучше не делать вовсе, чем
    /// сделать и уехать не туда.
    ///
    /// ВЫСОТА В ПОИСКЕ НЕ УЧАСТВУЕТ: сеть держится склейкой по клетке (X, Z),
    /// той же самой, что при чтении карты. Двух транслокаторов в одном столбце
    /// карта не различает и сама.
    /// </summary>
    public TlPoint? PartnerOf(TlPoint at)
    {
        var ключ = Клетка(at);
        int номер = -1;
        for (int i = 0; i < станции.Count; i++)
            if (Клетка(станции[i].At) == ключ)
            {
                номер = i;
                break;
            }
        if (номер < 0)
            return null;

        foreach (var (a, b) in пары)
        {
            if (a == номер)
                return станции[b].At;
            if (b == номер)
                return станции[a].At;
        }
        return null;
    }

    /// <summary>Номер конца в списке, со склейкой совпавших клеток.</summary>
    private static int Add(List<TlStation> список, Dictionary<(int, int), int> поКлетке,
        TlPoint точка, string подпись, string метка)
    {
        var ключ = Клетка(точка);
        if (поКлетке.TryGetValue(ключ, out int есть))
            return есть;

        список.Add(new TlStation(точка, подпись, метка));
        int номер = список.Count - 1;
        поКлетке[ключ] = номер;
        return номер;
    }

    /// <summary>
    /// Одна запись карты → пара концов. false — запись негодная (о ней
    /// пожалуются, но всю карту из-за неё не бросят).
    /// </summary>
    private static bool TryPair(JsonElement запись, out TlPoint a, out TlPoint b,
        out string подпись, out string метка, out bool высотаЕсть)
    {
        a = default; b = default; подпись = ""; метка = ""; высотаЕсть = false;

        if (запись.ValueKind != JsonValueKind.Object ||
            !запись.TryGetProperty("geometry", out var форма) ||
            форма.ValueKind != JsonValueKind.Object ||
            !форма.TryGetProperty("type", out var видФормы) ||
            видФормы.ValueKind != JsonValueKind.String ||
            видФормы.GetString() != "LineString" ||
            !форма.TryGetProperty("coordinates", out var точки) ||
            точки.ValueKind != JsonValueKind.Array ||
            точки.GetArrayLength() < 2)
            return false;

        // Берём ПЕРВУЮ и ПОСЛЕДНЮЮ точки, как это делает мод заказчика: линия
        // на карте может быть нарисована с изгибом, но транслокаторы — только
        // на её концах
        var первая = точки[0];
        var последняя = точки[точки.GetArrayLength() - 1];

        double h1 = 0, h2 = 0;
        if (запись.TryGetProperty("properties", out var свойства) &&
            свойства.ValueKind == JsonValueKind.Object)
        {
            bool есть1 = Number(свойства, "depth1", out h1);
            bool есть2 = Number(свойства, "depth2", out h2);
            высотаЕсть = есть1 && есть2;
            подпись = Text(свойства, "label");
            метка = Text(свойства, "tag");
        }

        if (!Pair(первая, out double x1, out double y1) || !Pair(последняя, out double x2, out double y2))
            return false;

        a = TlMapCoords.PointFromMap(x1, y1, h1);
        b = TlMapCoords.PointFromMap(x2, y2, h2);
        return true;
    }

    private static bool Pair(JsonElement точка, out double x, out double y)
    {
        x = 0; y = 0;
        return точка.ValueKind == JsonValueKind.Array &&
               точка.GetArrayLength() >= 2 &&
               точка[0].ValueKind == JsonValueKind.Number &&
               точка[1].ValueKind == JsonValueKind.Number &&
               точка[0].TryGetDouble(out x) &&
               точка[1].TryGetDouble(out y) &&
               double.IsFinite(x) && double.IsFinite(y);
    }

    private static bool Number(JsonElement свойства, string имя, out double значение)
    {
        значение = 0;
        return свойства.TryGetProperty(имя, out var поле) &&
               поле.ValueKind == JsonValueKind.Number &&
               поле.TryGetDouble(out значение) &&
               double.IsFinite(значение);
    }

    private static string Text(JsonElement свойства, string имя) =>
        свойства.TryGetProperty(имя, out var поле) && поле.ValueKind == JsonValueKind.String
            ? поле.GetString()?.Trim() ?? ""
            : "";

