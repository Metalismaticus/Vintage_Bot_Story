    /// <summary>
    /// СКОЛЬКО СЕКУНД ИДТИ ПЕШКОМ ИЗ ОДНОЙ ТОЧКИ В ДРУГУЮ — по прямой, с
    /// поправкой на высоту.
    ///
    /// Правило взято у мода заказчика (<c>TlPathService.WalkTime</c>) целиком,
    /// включая деление высоты на 30: подъём и спуск там считаются «за каждые
    /// 30 блоков», и менять это значило бы разойтись с числом 0,22, которое
    /// вместе с ним и калибровали.
    ///
    /// ЧЕГО ЭТО ПРАВИЛО НЕ ЗНАЕТ И НЕ ОБЕЩАЕТ: гор, воды, обрывов и заборов.
    /// Это оценка ПО ПРЯМОЙ. Настоящий путь ищет <see cref="AStarPathFinder"/>,
    /// и он же скажет, что дороги нет. Здесь считается только «во что примерно
    /// обойдётся» — чтобы выбрать между телепортом и ногами.
    /// </summary>
    public static double WalkSeconds(TlPoint a, TlPoint b, TlRouteSettings settings) =>
        WalkSeconds(a.FlatDistanceTo(b), (double)b.Y - a.Y, settings);

    /// <summary>
    /// ТО ЖЕ ПРАВИЛО, НО ЯДРОМ: расстояние по земле и перепад высоты на вход.
    ///
    /// ПОЧЕМУ ОНО ВЫНЕСЕНО ОТДЕЛЬНО. Ту же цену дороги спрашивает не только
    /// граф сети, но и выбор «ногами или через сеть»
    /// (<see cref="TrekRules.WalkSecondsBetween"/>), а тот считает КЛЕТКАМИ
    /// МИРА и работает, даже когда сети нет вовсе. Спиши мы формулу второй раз
    /// — и «пешком около 87 мин» в сравнении разошлось бы с «пешком около
    /// 87 мин» внутри маршрута ровно тогда, когда человек по ним что-то решает.
    ///
    /// Сдвиг координат правилу не нужен: в него входят только РАЗНОСТИ, а они
    /// у мировых клеток и у игровых одни и те же.
    /// </summary>
    public static double WalkSeconds(double flatBlocks, double climbBlocks,
        TlRouteSettings settings)
    {
        double поЗемле = Math.Max(0, flatBlocks) * settings.WalkSecondsPerBlock;
        return поЗемле + (climbBlocks > 0
            ? climbBlocks / 30.0 * settings.ClimbSecondsPer30Blocks
            : -climbBlocks / 30.0 * settings.DescendSecondsPer30Blocks);
    }

    /// <summary>
    /// МАРШРУТ ИЗ ТОЧКИ В ТОЧКУ. Обе — в ИГРОВЫХ координатах (см.
    /// <see cref="TlPoint"/>).
    ///
    /// ОТКАЗА «МАРШРУТА НЕТ» ЗДЕСЬ НЕ БЫВАЕТ, И ЭТО НАРОЧНО. Ногами можно
    /// дойти всегда, поэтому пеший путь напрямую в графе есть ВСЕГДА — даже
    /// когда он длиной в полмира. Иначе вышло бы худшее из возможных: сеть не
    /// помогла, а бот отвечает «не могу», хотя цель в двухстах блоках за
    /// границей круга <see cref="TlRouteSettings.WalkRadius"/>. Если сеть
    /// оказалась бесполезна, маршрут скажет это словами
    /// (<see cref="TlRoute.Tell"/>), а не промолчит.
    ///
    /// ПОЧЕМУ ДЕЙКСТРА, А НЕ A*. Ребро-телепорт стоит 10 секунд и проходит
    /// семь тысяч блоков: любая оценка «сколько осталось по прямой» для него
    /// врёт в разы и перестаёт быть допустимой, а с недопустимой оценкой A*
    /// перестаёт находить лучший путь. Дейкстра ничего не предполагает.
    /// </summary>
    /// <param name="from">откуда (обычно — где стоит бот)</param>
    /// <param name="to">куда</param>
    /// <param name="settings">цены — политика роли</param>
    /// <param name="nowUtc">
    /// Часы, если хотим проверить свежесть карты. null — не проверять. Часы
    /// подаются СНАРУЖИ, чтобы правило осталось чистым: иначе один и тот же
    /// мир давал бы разный ответ и его нельзя было бы положить в тест.
    /// </param>
    /// <param name="avoid">
    /// ПАРЫ, КОТОРЫЕ ОБХОДИМ СТОРОНОЙ: концы, о которых бот УЖЕ УЗНАЛ ДЕЛОМ,
    /// что через них не пройти (сломан, не запитан, к нему нет дороги).
    ///
    /// ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ У ТОГО, КТО ИДЁТ. Наткнувшись на мёртвую пластину,
    /// бот пересчитывает маршрут — и без этого списка Дейкстра честно отдаёт
    /// ТОТ ЖЕ САМЫЙ путь через ту же мёртвую пластину: по карте он по-прежнему
    /// лучший. Вышел бы круг — сходил, уткнулся, пересчитал, сходил снова.
    /// Карта суточной давности не знает, что там сломано; бот, один раз это
    /// увидевший, знает, и его знание обязано попасть в счёт.
    ///
    /// ПЕШКОМ через такую точку ходить не запрещаем: сломан транслокатор, а не
    /// земля под ним.
    /// </param>
    public TlRoute Route(TlPoint from, TlPoint to, TlRouteSettings? settings = null,
        DateTime? nowUtc = null, IReadOnlyCollection<TlPoint>? avoid = null)
    {
        var цены = settings ?? new TlRouteSettings();
        var оговорки = new List<string>();
        // Обходим по КЛЕТКЕ склейки — той же самой, что держит всю сеть: один и
        // тот же транслокатор встречается на карте концом разных записей, и
        // сравнение точка-в-точку пропустило бы его двойников
        var обход = avoid is { Count: > 0 }
            ? new HashSet<(int, int)>(avoid.Select(Клетка))
            : null;

        if (nowUtc is { } часы && WhyStale(часы, цены.StaleAfterHours) is { } старьё)
            оговорки.Add(старьё);
        оговорки.AddRange(жалобы);

        // Цель под ногами. Без этой строки вышел бы шаг длиной ноль блоков за
        // ноль секунд — формально верный, а на деле «иди никуда»: тот, кто
        // пойдёт по шагам, честно попытался бы его сделать
        if (from == to)
            return new TlRoute([], Tell(), оговорки, null);

        // ── Узлы: все концы сети плюс «откуда» и «куда» ──────────────────
        int всего = станции.Count;
        int старт = всего, финиш = всего + 1;
        var точки = new TlPoint[всего + 2];
        for (int i = 0; i < всего; i++)
            точки[i] = станции[i].At;
        точки[старт] = from;
        точки[финиш] = to;

        var рёбра = new List<(int To, double Seconds, bool ByTeleport)>[всего + 2];
        for (int i = 0; i < рёбра.Length; i++)
            рёбра[i] = [];

        void Ребро(int a, int b, double секунды, bool телепорт)
        {
            if (a == b)
                return;
            рёбра[a].Add((b, секунды, телепорт));
            рёбра[b].Add((a, секунды, телепорт));
        }

        // ── Рёбра-телепорты: даром по расстоянию, платно по времени ───────
        int обойдено = 0;
        foreach (var (a, b) in пары)
        {
            // МЁРТВУЮ ПАРУ В ГРАФ НЕ КЛАДЁМ ВОВСЕ. Не «дороже», а именно нет:
            // назначь мы ей большую цену, Дейкстра всё равно взяла бы её, когда
            // другого пути нет, — и бот пошёл бы во второй раз туда, где уже
            // стоял перед сломанной пластиной
            if (обход != null &&
                (обход.Contains(Клетка(станции[a].At)) || обход.Contains(Клетка(станции[b].At))))
            {
                обойдено++;
                continue;
            }
            Ребро(a, b, цены.TeleportSeconds, true);
        }

        // Молчать об обходе нельзя: маршрут стал длиннее не потому, что сеть
        // плоха, а потому, что бот своими ногами убедился в обратном
        if (обойдено > 0)
            оговорки.Add($"{обойдено} пар(ы) обхожу стороной: на них я уже натыкался — " +
                         "по карте они есть, а на деле через них не пройти");

        // ── Рёбра пешком: только внутри круга (см. WalkRadius) ────────────
        double радиус = Math.Max(0, цены.WalkRadius);
        int пеших = 0;
        bool потолок = false;

        // Сетка клеток размером в радиус: два конца ближе радиуса лежат либо в
        // одной клетке, либо в соседней, поэтому хватает обхода 3×3. Без неё
        // это перебор всех пар — сорок миллионов проверок на живой карте
        // Потолок на сторону клетки — сторож от переполнения: радиус приходит
        // ручкой роли, а «пусть ходит куда угодно, 1e10» превратило бы int в
        // отрицательное число и разложило бы всю сетку. Мир Vintage Story
        // шире двух миллионов блоков не бывает
        int сторона = (int)Math.Clamp(Math.Ceiling(радиус), 1, 4_000_000);
        var сетка = new Dictionary<(int, int), List<int>>();
        // Имя своё, не «Клетка»: ячейка ЭТОЙ сетки — размером в радиус ходьбы,
        // а клетка склейки сети — в один блок; путать их нельзя
        (int, int) ЯчейкаСетки(TlPoint p) =>
            ((int)Math.Floor((double)p.X / сторона), (int)Math.Floor((double)p.Z / сторона));

        for (int i = 0; i < всего; i++)
        {
            var к = ЯчейкаСетки(точки[i]);
            if (!сетка.TryGetValue(к, out var свои))
                сетка[к] = свои = [];
            свои.Add(i);
        }

        IEnumerable<int> Рядом(TlPoint p)
        {
            var (cx, cz) = ЯчейкаСетки(p);
            for (int dx = -1; dx <= 1; dx++)
                for (int dz = -1; dz <= 1; dz++)
                    if (сетка.TryGetValue((cx + dx, cz + dz), out var свои))
                        foreach (int i in свои)
                            yield return i;
        }

        for (int i = 0; i < всего && !потолок; i++)
            foreach (int j in Рядом(точки[i]))
            {
                // j <= i — эту пару уже видели с другой стороны
                if (j <= i)
                    continue;
                if (точки[i].FlatDistanceTo(точки[j]) > радиус)
                    continue;
                if (пеших >= цены.MaxWalkEdges)
                {
                    потолок = true;
                    break;
                }
                Ребро(i, j, WalkSeconds(точки[i], точки[j], цены), false);
                пеших++;
            }

        if (потолок)
            оговорки.Add($"пеших связей в сети больше потолка ({цены.MaxWalkEdges}) — часть " +
                         "их отброшена, и найденный маршрут может оказаться хуже настоящего. " +
                         "Уменьшите «как далеко отходить от сети»");

        // Концы маршрута цепляем к сети тем же кругом
        foreach (int i in Рядом(from))
            if (точки[i].FlatDistanceTo(from) <= радиус)
                Ребро(старт, i, WalkSeconds(from, точки[i], цены), false);
        foreach (int i in Рядом(to))
            if (точки[i].FlatDistanceTo(to) <= радиус)
                Ребро(финиш, i, WalkSeconds(to, точки[i], цены), false);

        // ПЕШКОМ НАПРЯМУЮ — ВСЕГДА. Причина см. в описании метода
        Ребро(старт, финиш, WalkSeconds(from, to, цены), false);

        // ── Дейкстра ─────────────────────────────────────────────────────
        int n = точки.Length;
        var цена = new double[n];
        var откуда = new int[n];
        var какПришли = new bool[n];
        Array.Fill(цена, double.PositiveInfinity);
        Array.Fill(откуда, -1);
        цена[старт] = 0;

        var очередь = new PriorityQueue<int, double>();
        очередь.Enqueue(старт, 0);
        var готово = new bool[n];

        while (очередь.TryDequeue(out int v, out double d))
        {
            if (готово[v])
                continue;
            готово[v] = true;
            if (v == финиш)
                break;
            // Устаревшая запись в очереди: до этого узла уже дошли дешевле
            if (d > цена[v])
                continue;

            foreach (var (куда, секунды, телепорт) in рёбра[v])
            {
                double новая = цена[v] + секунды;
                if (новая >= цена[куда])
                    continue;
                цена[куда] = новая;
                откуда[куда] = v;
                какПришли[куда] = телепорт;
                очередь.Enqueue(куда, новая);
            }
        }

        // Прямое ребро есть всегда, поэтому сюда не попасть; но молча
        // рассыпаться при пустой сети всё равно нельзя
        if (double.IsPositiveInfinity(цена[финиш]))
            return new TlRoute([], Tell(), оговорки,
                "маршрута нет: в сети не нашлось ни одного пути, даже пешком напрямую");

        var порядок = new List<int>();
        for (int узел = финиш; узел != -1; узел = откуда[узел])
            порядок.Add(узел);
        порядок.Reverse();

        TlStation Станция(int узел) => узел < всего
            ? станции[узел]
            : new TlStation(точки[узел]);

        var шаги = new List<TlLeg>(порядок.Count - 1);
        for (int i = 0; i + 1 < порядок.Count; i++)
        {
            int a = порядок[i], b = порядок[i + 1];
            bool телепорт = какПришли[b];
            шаги.Add(new TlLeg(телепорт, Станция(a), Станция(b),
                телепорт ? цены.TeleportSeconds : WalkSeconds(точки[a], точки[b], цены),
                телепорт ? 0 : точки[a].FlatDistanceTo(точки[b])));
        }

        return new TlRoute(шаги, Tell(), оговорки, null);
    }
}

/// <summary>
/// ОДИН ШАГ МАРШРУТА: либо пешком, либо через транслокатор.
/// </summary>
/// <param name="ByTeleport">true — это прыжок через пару транслокаторов</param>
/// <param name="From">откуда</param>
/// <param name="To">куда</param>
/// <param name="Seconds">во что обойдётся по оценке</param>
/// <param name="Blocks">
/// Сколько блоков идти ногами. У прыжка — 0, и это не описка: расстояние в
/// блоках он не преодолевает, а перескакивает. Сложи мы его в общий счёт
/// «пешком», и ответ «пешком 7500 бл» получился бы там, где бот прошёл двести.
/// </param>
public readonly record struct TlLeg(bool ByTeleport, TlStation From, TlStation To,
    double Seconds, double Blocks)
{
    public override string ToString() => ByTeleport
        ? $"транслокатор {From.Name} → {To.Name}"
        : $"пешком {Blocks:0} бл {From.At} → {To.At}";
}

/// <summary>
/// МАРШРУТ, КОТОРЫЙ УМЕЕТ РАССКАЗАТЬ О СЕБЕ СЛОВАМИ.
///
/// ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ У ТОГО, КТО ПОКАЖЕТ. Требование заказчика дословно:
/// маршрут обязан говорить «через 3 телепорта, пешком 240 бл, около 4 мин» и
/// называть каждый пересадочный узел. Собери эту строку вызывающий, и у окна
/// управления, у чата и у журнала вышло бы три разных ответа про один и тот же
/// путь — а расходятся они ровно тогда, когда человек по ним что-то решает.
/// </summary>
/// <param name="Legs">шаги по порядку; пусто — идти некуда</param>
/// <param name="NetSummary">что за сеть считала этот путь</param>
/// <param name="Caveats">оговорки: устаревшая карта, замечания к ней, урезанный граф</param>
/// <param name="Why">почему маршрута нет; null — маршрут есть</param>
public sealed record TlRoute(IReadOnlyList<TlLeg> Legs, string NetSummary,
    IReadOnlyList<string> Caveats, string? Why)
{
    /// <summary>
    /// ОТВЕТ ЕСТЬ. Не «есть куда шагнуть»: цель под ногами — это тоже ответ, и
    /// притом успешный.
    ///
    /// ПОЧЕМУ ЭТО ВАЖНО ИМЕННО ТАК. Тот, кто пойдёт по маршруту, пишет
    /// <c>if (!route.Found) отказ</c>. Считай мы «уже на месте» ненайденным, и
    /// бот, стоящий ровно на цели, доложил бы, что дойти не может, — худший
    /// вид вранья, потому что он звучит как поломка.
    /// </summary>
    public bool Found => Why is null;

    /// <summary>Идти никуда не надо: цель там же, где бот.</summary>
    public bool NothingToDo => Why is null && Legs.Count == 0;

    /// <summary>Сколько раз пересаживаться.</summary>
    public int TeleportCount => Legs.Count(l => l.ByTeleport);

    /// <summary>Сколько блоков идти ногами всего.</summary>
    public double WalkBlocks => Legs.Where(l => !l.ByTeleport).Sum(l => l.Blocks);

    /// <summary>Во сколько секунд обойдётся весь путь по оценке.</summary>
    public double Seconds => Legs.Sum(l => l.Seconds);

    /// <summary>
    /// ПЕРЕСАДКИ — только прыжки, без промежуточных пеших точек.
    ///
    /// Мод заказчика делает то же самое отдельным проходом (<c>CleanPath</c>):
    /// узел, через который просто прошли ногами, пересадкой не является, и
    /// называть его человеку — сбивать с толку.
    /// </summary>
    public IReadOnlyList<TlLeg> Transfers => Legs.Where(l => l.ByTeleport).ToList();

    /// <summary>
    /// ОДНОЙ СТРОКОЙ: «через 3 транслокатора, пешком 240 бл, около 4 мин».
    /// </summary>
    public string Tell()
    {
        if (Why is { } нет)
            return нет;
        if (Legs.Count == 0)
            return "идти никуда не надо: цель там же, где я";

        string хвост = Caveats.Count > 0 ? ". " + string.Join(". ", Caveats) : "";

        // Сеть не пригодилась — сказать об этом ПРЯМО. Молчаливое «пешком 9000
        // бл» человек прочтёт как «бот не нашёл транслокаторы», а он их нашёл
        // и отверг: они не по пути
        return TeleportCount == 0
            ? $"пешком напрямую {WalkBlocks:0} бл, {About(Seconds)} — " +
              $"сеть транслокаторов тут не помогает{хвост}"
            : $"через {TeleportCount} {Пересадок(TeleportCount)}, пешком {WalkBlocks:0} бл, " +
              $"{About(Seconds)}{хвост}";
    }

    /// <summary>
    /// ПОДРОБНО: строка про весь путь и по строке на каждую пересадку.
    /// Именно это читает человек, когда решает, отпускать ли бота.
    /// </summary>
    public string TellSteps()
    {
        var строки = new List<string> { Tell() };
        if (Legs.Count == 0)
            return string.Join(Environment.NewLine, строки);

        int номер = 0;
        foreach (var шаг in Legs)
            if (шаг.ByTeleport)
                строки.Add($"  пересадка {++номер}: {шаг.From.Name} → {шаг.To.Name}");
            else if (шаг.Blocks >= 1)
                строки.Add($"  пешком {шаг.Blocks:0} бл до {шаг.To.Name}");

        строки.Add($"  сеть: {NetSummary}");
        return string.Join(Environment.NewLine, строки);
    }

    public override string ToString() => Tell();

    /// <summary>
    /// «около 4 мин». Точность нарочно грубая: это ОЦЕНКА по прямой, и
    /// «4 мин 17 с» врало бы точностью, которой у неё нет.
    /// </summary>
    public static string About(double seconds)
    {
        if (seconds < 90)
            return $"около {Math.Max(1, Math.Round(seconds)).ToString("0", CultureInfo.InvariantCulture)} с";
        double минут = seconds / 60.0;
        if (минут < 60)
            return $"около {минут.ToString("0", CultureInfo.InvariantCulture)} мин";
        int часов = (int)(минут / 60);
        int остаток = (int)Math.Round(минут - часов * 60);
        // 60 минут в остатке — это «1 ч 60 мин»: считаем часы заново
        if (остаток == 60)
        {
            часов++;
            остаток = 0;
        }
        return остаток == 0 ? $"около {часов} ч" : $"около {часов} ч {остаток} мин";
    }

    /// <summary>
    /// «транслокатор / транслокатора / транслокаторов» по числу. Наружу оно
    /// нужно затем, что о тех же пересадках говорит и выбор пути
    /// (<see cref="TrekChoice"/>), а два списания русского счёта разъезжаются
    /// на первом же «11 транслокатора».
    /// </summary>
    public static string Пересадок(int сколько)
    {
        int сотня = сколько % 100, десяток = сколько % 10;
        if (сотня is >= 11 and <= 14)
            return "транслокаторов";
        return десяток switch
        {
            1 => "транслокатор",
            2 or 3 or 4 => "транслокатора",
            _ => "транслокаторов"
        };
    }
}

// ═══════════════════════════════════════════════════════════════════════════
//  ТОЧКА НА КАРТЕ — И БОТ САМ РЕШАЕТ, КАК ТУДА ПОПАСТЬ
//
//  Заказ дословно: «хочу по веб админке на карте давать точку куда ему бежать,
//  и он уже думал, через телепорты или пешком и шел».
//
//  Всё, что ниже, — ЧИСТЫЕ ПРАВИЛА: числа на вход, решение и слова на выход.
//  Ни ног, ни сети, ни часов. Ходить по выбранному плану — дело <see cref="Trek"/>.
// ═══════════════════════════════════════════════════════════════════════════

/// <summary>
/// РЕШЕНИЕ «НОГАМИ ИЛИ ЧЕРЕЗ СЕТЬ» — С ОБЕИМИ ОЦЕНКАМИ, А НЕ ОДНИМ ОТВЕТОМ.
///
/// ПОЧЕМУ ОБЕ ОЦЕНКИ ВСЕГДА НА РУКАХ. Человек, отпускающий бота на сорок минут,
/// решает не за него, а вместе с ним: «87 минут пешком против 47 через сеть» —
/// это разговор, а «иду через сеть» — приказ, в котором нечего проверить.
/// Спрятанное сравнение к тому же нельзя поймать за руку: разойдись оценка
/// ходьбы с той, по которой считался граф, и никто бы этого не увидел.
/// </summary>
/// <param name="ByNet">идти через сеть транслокаторов</param>
/// <param name="WalkSeconds">во сколько секунд обойдётся дорога ПЕШКОМ НАПРЯМУЮ</param>
/// <param name="NetSeconds">во сколько — через сеть (равно ходьбе, когда сеть не помогает)</param>
/// <param name="Transfers">сколько пересадок в сетевом пути</param>
/// <param name="Gain">на сколько секунд сеть быстрее ходьбы (может быть и ноль)</param>
/// <param name="NeedGain">какой выигрыш требовался, чтобы сеть того стоила</param>
/// <param name="Why">то самое сравнение словами — для человека и для журнала</param>
public readonly record struct TrekChoice(bool ByNet, double WalkSeconds, double NetSeconds,
    int Transfers, double Gain, double NeedGain, string Why)
{
    public override string ToString() => Why;
}

/// <summary>
/// ПРАВИЛА ПОХОДА К ТОЧКЕ: чем меряем, что выбираем и что делаем, наткнувшись
/// на беду. Всё чистое и всё в тестах — потому что руками этого не проверить:
/// живой поход длится сорок минут и требует сервера.
/// </summary>
public static class TrekRules
{
    /// <summary>
    /// ЦЕНА ДОРОГИ МЕЖДУ КЛЕТКАМИ МИРА — той же меркой, что и внутри графа
    /// (<see cref="TlNet.WalkSeconds(double, double, TlRouteSettings)"/>).
    ///
    /// Своей формулы здесь нет НАРОЧНО. Сравнение «ногами против сети» имеет
    /// смысл, только если обе оценки считаны одним и тем же: спиши мы ходьбу
    /// второй раз, и порог «стоит ли сеть захода» сторожил бы разницу двух
    /// разных мерок, а не разницу двух дорог.
    /// </summary>
    public static double WalkSecondsBetween(BlockPos from, BlockPos to, TlRouteSettings settings)
    {
        double dx = (double)to.X - from.X, dz = (double)to.Z - from.Z;
        return TlNet.WalkSeconds(Math.Sqrt(dx * dx + dz * dz), (double)to.Y - from.Y, settings);
    }

    /// <summary>
    /// ВЫБОР С ЧИСЛАМИ. Сравниваются ОДНОЙ меркой — секундами: в блоках
    /// телепорт весит ноль, и любая цепочка прыжков «выигрывала» бы у двух
    /// шагов пешком.
    ///
    /// ПОРОГ (<see cref="TlRouteSettings.MinNetGainSecondsPerTransfer"/>) стоит
    /// на каждой пересадке, а не на всём пути: рискует план ровно в местах
    /// пересадок, и шесть прыжков ради минуты выигрыша — это шесть мест, где
    /// суточной давности карта может соврать.
    /// </summary>
    /// <param name="walkSeconds">оценка «пешком напрямую»</param>
    /// <param name="route">
    /// Маршрут по сети. null — сети нет вовсе; тогда выбора не было, и это
    /// говорится прямо, вместе с причиной <paramref name="netWhy"/>.
    /// </param>
    /// <param name="settings">цены и порог — политика роли</param>
    /// <param name="netWhy">почему сети нет (пусто — она есть)</param>
    public static TrekChoice Choose(double walkSeconds, TlRoute? route,
        TlRouteSettings settings, string netWhy = "")
    {
        string пешком = TlRoute.About(walkSeconds);

        // 1. СЕТИ НЕТ ВОВСЕ. Это не отказ идти: ногами дойти можно всегда, а
        //    вот молчать о том, что сравнивать было не с чем, нельзя — иначе
        //    «иду пешком» человек прочтёт как «сеть проверена и не помогла»
        if (route is not { Found: true } путь)
            return new TrekChoice(false, walkSeconds, walkSeconds, 0, 0, 0,
                $"пешком напрямую {пешком}; через сеть посчитать не вышло" +
                (netWhy.Length > 0 ? $": {netWhy}" : "") + " — иду ногами");

        int пересадок = путь.TeleportCount;
        double сетью = путь.Seconds;

        // 2. СЕТЬ И САМА НЕ ПОМОГЛА: Дейкстра выбрала прямой пеший путь.
        //    Сказать это прямо — иначе человек решит, что бот транслокаторов
        //    не нашёл, а он их нашёл и отверг
        if (пересадок == 0)
            return new TrekChoice(false, walkSeconds, сетью, 0, 0, 0,
                $"пешком напрямую {пешком} — сеть транслокаторов тут не помогает: " +
                "ни один переход не по пути");

        double выигрыш = walkSeconds - сетью;
        double надо = Math.Max(0, settings.MinNetGainSecondsPerTransfer) * пересадок;
        // Ноль выигрыша при нулевом пороге — это «одно и то же время»; в таком
        // случае идём ногами: пеший путь ни от какой карты не зависит
        bool через = выигрыш > 0 && выигрыш >= надо;

        string обе = $"пешком напрямую {пешком}, через сеть {TlRoute.About(сетью)} " +
                     $"({пересадок} {TlRoute.Пересадок(пересадок)})";

        return new TrekChoice(через, walkSeconds, сетью, пересадок, выигрыш, надо,
            через
                ? $"{обе} — иду через сеть: выигрыш {TlRoute.About(выигрыш)}" +
                  (надо > 0 ? $", а хватило бы {TlRoute.About(надо)}" : "")
                : $"{обе} — иду ногами: сеть выигрывает всего {TlRoute.About(Math.Max(0, выигрыш))}, " +
                  $"а ради {пересадок} {TlRoute.Пересадок(пересадок)} нужно хотя бы " +
                  $"{TlRoute.About(надо)}: карту выгружали когда-то, и каждая пересадка — " +
                  "место, где план может оборваться");
    }

    /// <summary>
    /// ВДВОЕ БОЛЬШЕ ОЦЕНКИ — вот сколько времени даётся на один пеший шаг.
    ///
    /// ОТКУДА ЗАПАС. Оценка меряет расстояние ПО ПРЯМОЙ, а число 0,22 с/бл
    /// (<see cref="TlRouteSettings.WalkSecondsPerBlock"/>) замерено ногами на
    /// живом сервере и обычный обход уже включает. Чего оно не включает — озера
    /// поперёк дороги и обрыва: вдвое — это запас ровно на один такой крюк.
    ///
    /// ПОЧЕМУ НЕ БОЛЬШЕ. Срок здесь не приговор: не уложились — шаг честно
    /// доложит «не дошёл», и поход пересчитает маршрут
    /// (<see cref="AfterTrouble"/>), а не встанет. А вот раздутый впятеро срок
    /// заставил бы бота полчаса биться в стену молча.
    /// </summary>
    public const double LegBudgetFactor = 2.0;

    /// <summary>
    /// Меньше этого на шаг не даём, сколько бы ни насчитала оценка. Двадцать
    /// блоков по прямой — это четыре секунды по числу и минута в жизни, если
    /// между ними чужой дом, который надо обойти.
    /// </summary>
    public const double MinLegSeconds = 60;

    /// <summary>Сколько секунд дать телу на один шаг маршрута.</summary>
    public static double LegBudgetSeconds(double estimateSeconds) =>
        Math.Max(MinLegSeconds, Math.Max(0, estimateSeconds) * LegBudgetFactor);

    /// <summary>
    /// ШАГ ВНУТРИ ЧУЖОГО СРОКА: у похода, начатого не с карты, а обычной
    /// дорогой, есть свой предел — тот самый maxSeconds, который назвала роль
    /// или задача.
    ///
    /// ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ ПРАВИЛОМ. Шаг маршрута считает себе срок сам
    /// (<see cref="LegBudgetSeconds"/>), и он вполне может оказаться длиннее
    /// всего, что дали походу. Без этой обрезки задача, которой отвели минуту,
    /// молча висела бы шесть: первый же пеший шаг взял бы себе минимум в 60 с
    /// и не спросил бы ни у кого. А тот, кто мерит «дошёл ли» по своему
    /// секундомеру, решил бы, что бот пропал.
    ///
    /// НОЛЬ — ЭТО ЧЕСТНОЕ «ВРЕМЯ ВЫШЛО», а не «иди сколько хочешь»: шаг с
    /// нулевым сроком обязан сразу доложить неудачу, а не выйти в дорогу без
    /// предела.
    /// </summary>
    /// <param name="legBudget">сколько шаг попросил бы себе сам</param>
    /// <param name="secondsLeft">сколько осталось у всего похода</param>
    public static double LegSecondsWithin(double legBudget, double secondsLeft) =>
        secondsLeft <= 0 ? 0 : Math.Min(Math.Max(0, legBudget), secondsLeft);

    /// <summary>
    /// С КАКОЙ ДАЛЬНОСТИ ИСКАТЬ ПЕРЕХОД, ЕСЛИ РОЛЬ НЕ СКАЗАЛА ИНАЧЕ, блоков по
    /// прямой. Само решение — политика роли (ручка «ИскатьТранслокаторОтБлоков»);
    /// здесь только то число, с которого ей разумно начать, — по образцу
    /// остальных цен маршрута (<see cref="TlRouteSettings"/>).
    ///
    /// ПОЧЕМУ ТРИСТА. Всё хозяйство одного человека — дом, склад, забой,
    /// стройка — умещается в сотню блоков: там переход и не нужен, и спрашивать
    /// про него на каждый шаг к сундуку было бы работой впустую. Триста блоков
    /// по прямой — это уже минута бега (0,22 с/бл), то есть та дорога, ради
    /// которой сеть и заводили. А отсекать бесполезные пересадки — не дело
    /// этого числа: для этого есть выигрыш на пересадку
    /// (<see cref="TlRouteSettings.MinNetGainSecondsPerTransfer"/>).
    /// </summary>
    public const double AskNetFromBlocks = 300;

    /// <summary>
    /// СПРАШИВАТЬ ЛИ СЕТЬ ПЕРЕД ОБЫЧНОЙ ДОРОГОЙ.
    ///
    /// ЖИВАЯ ЖАЛОБА ЗАКАЗЧИКА (01.09): «мы же записываем в нашу постоянную
    /// память пары тл? а то бот побежал вместо тл». Пары и правда писались
    /// (<see cref="TlMemory"/>), маршрут по сети считался
    /// (<see cref="TlNet.Route"/>), поход по нему умел ходить
    /// (<see cref="Trek"/>) — а спрашивали всё это РОВНО В ОДНОМ месте: щелчок
    /// по карте в окне управления. Задача, склад, дом, работа, спасение — все
    /// звали ноги напрямую (<c>Movement.TravelToAsync</c>), а ноги про переходы
    /// не знают ничего и знать не должны: они ходят по клеткам, а пара — это
    /// прыжок между далёкими местами.
    ///
    /// ПОЧЕМУ ПОРОГ ВООБЩЕ НУЖЕН. Ноги зовут ОЧЕНЬ часто: подойти к сундуку,
    /// шагнуть к двери, встать на соседнюю клетку. Считать ради трёх шагов
    /// Дейкстру по всем станциям карты — работа впустую, а строка «пешком
    /// напрямую 2 бл; сеть тут не помогает» на каждый шаг превращает журнал в
    /// шум, в котором тонет настоящая беда.
    ///
    /// НОЛЬ И МЕНЬШЕ — ВЫКЛЮЧАТЕЛЬ: «сеть не спрашивать вовсе». Так человек
    /// говорит «на этом сервере переходов нет» или «ходи ногами, я разбираюсь».
    ///
    /// ГОВОРИТЬ ЛИ ЭТО ВСЛУХ — РЕШАЕТ ТО ЖЕ ПРАВИЛО, И ЭТО НЕ ПРИДИРКА.
    /// Молчать про выключенный порог нельзя: человек, спросивший «а почему он
    /// побежал вместо тл», обязан прочесть ответ. Но говорить про «цель ближе
    /// порога» — значит сыпать строку на каждый шаг к сундуку, а живой случай с
    /// тридцатью одинаковыми строками в этом проекте уже был
    /// (<see cref="LogRepeats.NewsOf"/>). Разница между этими двумя случаями
    /// ровно одна: ближняя цель — это настройка, работающая ровно так, как её
    /// задали, а нулевой порог — это отказ от целой затеи, и он новость.
    /// Держать эту разницу отдельным «если» у зовущего значило бы завести
    /// вторую копию того же правила.
    /// </summary>
    /// <param name="straightBlocks">сколько до цели по прямой</param>
    /// <param name="fromBlocks">с какой дальности искать переход — ручка роли</param>
    /// <seealso cref="AskNetFromBlocks"/>
    public static (bool Ask, bool Tell, string Why) WorthAskingNet(double straightBlocks,
        double fromBlocks)
    {
        if (fromBlocks <= 0)
            return (false, true, "сеть переходов перед дорогой не спрашиваю вовсе: порог " +
                                 "«искать транслокатор от» стоит на нуле — так велела роль");
        if (straightBlocks < fromBlocks)
            return (false, false, $"до цели {straightBlocks:0} бл по прямой, а транслокаторы " +
                                  $"ищу от {fromBlocks:0} бл — иду ногами");
        return (true, true, $"до цели {straightBlocks:0} бл по прямой — это дальше " +
                            $"{fromBlocks:0} бл: смотрю, не быстрее ли через транслокаторы");
    }

    /// <summary>
    /// НАТКНУЛИСЬ НА БЕДУ — ПЕРЕСЧИТЫВАТЬ ИЛИ БРОСАТЬ.
    ///
    /// ПРАВИЛО ОДНО И ПРОСТОЕ: пересчёт имеет смысл, только если у бота
    /// появились НОВЫЕ СВЕДЕНИЯ. Мёртвая пластина — это сведения: её кладут в
    /// обход (<see cref="TlNet.Route"/>), и следующий маршрут пойдёт другим
    /// путём. Пеший провал НАПРЯМУЮ сведений не даёт: маршрут тот же самый, и
    /// второй заход прошёл бы тем же местом — это круг, а не упорство.
    ///
    /// ПОТОЛОК ПЕРЕСЧЁТОВ — по той же причине, по какой у возврата к
    /// прерванному три попытки (<see cref="Resume.MaxReturns"/>): один-два раза
    /// подряд бывает и по случайности, а вот три подряд означают, что дороги
    /// туда сейчас нет, и молчаливое верчение по кругу человек читает точно так
    /// же, как мёртвого бота, только оно ещё и жрёт время.
    /// </summary>
    /// <param name="haveNewFacts">
    /// Узнали ли что-то новое: мёртвый транслокатор, недостижимая пластина.
    /// false — беда ничего не добавила к тому, что бот и так знал.
    /// </param>
    /// <param name="replansUsed">сколько пересчётов уже сделано за этот поход</param>
    /// <param name="maxReplans">потолок пересчётов</param>
    public static (bool Replan, string Say) AfterTrouble(bool haveNewFacts,
        int replansUsed, int maxReplans)
    {
        if (!haveNewFacts)
            return (false, "пересчитывать нечего: нового я тут не узнал, и второй заход " +
                           "прошёл бы тем же местом");
        if (replansUsed >= Math.Max(0, maxReplans))
            return (false, $"пересчитывал маршрут {replansUsed} раз(а) — и каждый раз " +
                           "упираюсь. Дальше не пойду: это уже круг, а не дорога");
        return (true, $"считаю маршрут заново, обходя то, на чём споткнулся " +
                      $"(пересчёт {replansUsed + 1} из {Math.Max(0, maxReplans)})");
    }

    /// <summary>
    /// НЕУДАВШИЙСЯ ШАГ — ЭТО СВЕДЕНИЯ О ДОРОГЕ ИЛИ НЕТ.
    ///
    /// Отвечает сразу на оба вопроса, потому что ответ у них ОДИН: вычёркивать
    /// ли пластину из сети на этот поход (<see cref="TlNet.Route"/>, довод
    /// avoid) и пересчитывать ли маршрут (<see cref="AfterTrouble"/>). Развести
    /// их — значит завести второе место, где можно забыть про отмену.
    ///
    /// ПРЕРВАЛИ — ЗНАЧИТ ПЛАСТИНА НИ ПРИ ЧЁМ, и это главное здесь. Шаг бросают
    /// не только беды дороги: рефлекс жизни забирает тело поесть или отбиться,
    /// человек говорит «стоп». Наружу и то и другое выходит одинаково —
    /// EnterAsync при отменённом токене отвечает «перенос … прерван», а ноги
    /// просто false, — и пока эти два случая были одним, исправный транслокатор
    /// вычёркивался из СЕТИ ЦЕЛИКОМ по чужой воле. Живой случай: поход через
    /// полсети, на втором шаге бот пошёл есть; вернувшись, он считал дорогу
    /// заново уже без того перехода, хотя с переходом всё было в порядке. Два-три
    /// перебоя за сорокаминутный поход — и половина сети вычеркнута, а в журнале
    /// это читается как «карта соврала».
    ///
    /// ЧЕСТНО ПРО ВТОРУЮ СТОРОНУ ОШИБКИ: если пластина и вправду мертва, а нас
    /// в тот же миг ещё и прервали, она останется в сети — и следующий заход
    /// споткнётся о неё снова и вычеркнет уже без помех. Это дешевле обратного:
    /// потерять один шаг лучше, чем потерять половину сети.
    /// </summary>
    /// <param name="cancelled">тело отобрали (рефлекс жизни, «стоп») — шаг оборван чужой волей</param>
    /// <param name="aboutPlate">
    /// Шаг был ПРО ПЛАСТИНУ: сама пересадка или подход к транслокатору. false —
    /// шаг вёл в промежуточную точку, и его провал ничего не добавляет к тому,
    /// что бот и так знал: маршрут тот же, второй заход прошёл бы тем же местом.
    /// </param>
    public static bool LegFailureIsAboutTheRoad(bool cancelled, bool aboutPlate) =>
        !cancelled && aboutPlate;

    /// <summary>
    /// ШАГ МАРШРУТА СЛОВАМИ: «шаг 2 из 5: пешком 240 бл до «Рынок» (…)».
    ///
    /// Доклад по ходу — не украшение. Поход через полмира идёт сорок минут, и
    /// всё это время человек в окне видит только журнал; молчащий бот и
    /// зависший бот оттуда выглядят одинаково.
    /// </summary>
    public static string SayLeg(int number, int total, TlLeg leg) =>
        $"шаг {number} из {total}: " + (leg.ByTeleport
            ? $"пересадка {leg.From.Name} → {leg.To.Name} " +
              $"(на пластине стоять {TranslocatorRules.RealWarmupSeconds:0.##} с)"
            : $"пешком {leg.Blocks:0} бл до {leg.To.Name}, {TlRoute.About(leg.Seconds)}");
}

/// <summary>
/// ПЛАН ПОХОДА: куда, каким путём и во что это обойдётся — всё ДО первого шага.
///
/// ЗАЧЕМ ПЛАН ОТДЕЛЬНО ОТ ПОХОДА. Щелчок по карте в окне управления не должен
/// уводить бота за десять тысяч блоков: человеку сперва показывают, что он
/// выбрал и во что это встанет, и только потом он подтверждает. Тот же план
/// уходит в журнал перед выходом — чтобы «почему он поплёлся пешком» можно
/// было прочесть, а не гадать.
/// </summary>
/// <param name="From">откуда считали — клеткой МИРА (обычно там, где бот стоит)</param>
/// <param name="Goal">куда идём — клеткой МИРА, которой живёт бот</param>
/// <param name="Choice">решение с обеими оценками</param>
/// <param name="Route">маршрут по сети; null — сети не было</param>
/// <param name="NetWhy">почему сети нет (пусто — она есть)</param>
public sealed record TrekPlan(BlockPos From, BlockPos Goal, TrekChoice Choice,
    TlRoute? Route, string NetWhy)
{
    /// <summary>
    /// Идти некуда: цель ровно там, где бот. Отдельный ответ, а не «маршрут в
    /// ноль шагов»: тот, кто пойдёт по шагам, честно попытался бы сделать шаг
    /// длиной ноль — и доложил бы неудачу, стоя на цели.
    /// </summary>
    public bool NothingToDo => From == Goal;

    /// <summary>Идём через сеть — значит есть и шаги, по которым идти.</summary>
    public bool ByNet => Choice.ByNet && Route is { Found: true, Legs.Count: > 0 };

    /// <summary>Шаги маршрута; пусто — идём напрямую ногами.</summary>
    public IReadOnlyList<TlLeg> Legs => ByNet ? Route!.Legs : [];

    /// <summary>Оговорки маршрута: устаревшая карта, замечания к ней, обойдённые пары.</summary>
    public IReadOnlyList<string> Caveats => Route?.Caveats ?? [];

    /// <summary>ОДНОЙ СТРОКОЙ: обе оценки и выбор.</summary>
    public string Tell()
    {
        if (NothingToDo)
            return "идти никуда не надо: цель там же, где я";
        string хвост = Caveats.Count > 0 ? ". " + string.Join(". ", Caveats) : "";
        return Choice.Why + хвост;
    }

    /// <summary>
    /// ПОДРОБНО: сравнение, каждый шаг и что за сеть считала. Именно это читает
    /// человек, решая, отпускать ли бота.
    /// </summary>
    public string TellSteps()
    {
        var строки = new List<string> { Tell() };
        if (NothingToDo)
            return строки[0];

        if (ByNet)
        {
            int номер = 0;
            foreach (var шаг in Legs)
                строки.Add("  " + TrekRules.SayLeg(++номер, Legs.Count, шаг));
        }
        else
            // Клетку печатает сам BlockPos — числа игровые (WorldOrigin).
            // Оговорка «координаты мировые» отсюда УБРАНА вместе с причиной:
            // пока она стояла, человек читал в отчёте о походе адрес, которого
            // нет у него на экране, и оговорка лишь честно об этом сообщала
            строки.Add($"  пешком напрямую до {Goal} (дорогу ищут ноги, а не карта)");

        if (Route is { } маршрут)
            строки.Add($"  сеть: {маршрут.NetSummary}");
        else if (NetWhy.Length > 0)
            строки.Add($"  сеть: {NetWhy}");
        return string.Join(Environment.NewLine, строки);
    }

    public override string ToString() => Tell();
}

/// <summary>
/// ЧТО БОТ ЗНАЕТ О СЕТИ ПРЯМО СЕЙЧАС. Сеть отдельно от причины НАРОЧНО: «ещё
/// читаю» и «карта не ответила» человек обязан различать.
/// </summary>
public readonly record struct TlNetLook(TlNet? Net, string Why)
{
    /// <summary>Сеть на руках — можно считать маршрут.</summary>
    public bool Ready => Net is not null;
}

/// <summary>
/// ОТКУДА БЕРЁТСЯ СЕТЬ: файл рядом с ботом или адрес карты сервера. Здесь и
/// только здесь у этой части есть диск и сеть — всё остальное выше по файлу
/// чистые правила, и это разделение держит их в тестах.
///
/// ПОРЯДОК ТАКОЙ И ВОТ ПОЧЕМУ. Сперва файл: он уже на диске, читается мгновенно
/// и работает без интернета — а боты живут на серверах, где выход наружу могут
/// и закрыть. Карта спрашивается, только когда файла нет или он протух
/// (<see cref="TlRouteSettings.StaleAfterHours"/>), и ответ кладётся в тот же
/// файл: назавтра он снова годится без сети.
///
/// ПОЧЕМУ НИКОГДА НЕ ЖДЁМ СЕТЬ В ОТВЕТЕ. Ровно та же причина, что у
/// <see cref="WebMapSource"/>: одна залипшая чужая машина заморозила бы того,
/// кто спросил маршрут. Поэтому ходим ФОНОМ, а отвечаем сразу — честным «ещё
/// читаю».
/// </summary>
public sealed class TranslocatorNetSource : IDisposable
{
    private readonly HttpClient http;
    private readonly bool своийHttp;
    private readonly Lock замок = new();

    private TlNet? сеть;
    private string почему = "";
    private bool спрашиваем;
    private string спрошенныйАдрес = "";
    private DateTime следующаяПопытка = DateTime.MinValue;

    /// <summary>
    /// Адрес карты сервера — ТОТ ЖЕ, что у окна управления
    /// (<see cref="PanelConfig.MapUrl"/>). Сеть лежит внутри неё на известном
    /// месте, и второй адрес человеку вписывать незачем
    /// (<see cref="TranslocatorNetRules.GeoJsonUrl"/>).
    /// </summary>
    public string? MapAddress { get; set; }

    /// <summary>
    /// Файл сети на диске. Он же кеш скачанного. Пусто — файлом не пользуемся.
    /// </summary>
    public string? FilePath { get; set; }

    /// <summary>Через сколько часов идти за картой заново.</summary>
    public double StaleAfterHours { get; set; } = new TlRouteSettings().StaleAfterHours;

    /// <summary>Через сколько пробовать снова после неудачи.</summary>
    public TimeSpan RetryAfter { get; set; } = TimeSpan.FromMinutes(5);

    /// <summary>Часы — подменяются в тестах, чтобы не ждать по-настоящему.</summary>
    public Func<DateTime> Now { get; set; } = () => DateTime.UtcNow;

    /// <summary>Куда сказать вслух. Молчать о неудаче нельзя.</summary>
    public event Action<string>? OnLog;

    public TranslocatorNetSource(HttpClient? client = null)
    {
        своийHttp = client is null;
        http = client ?? new HttpClient { Timeout = TimeSpan.FromSeconds(60) };
    }

    /// <summary>
    /// ПОЧЕМУ СЕТИ НЕТ И БЫТЬ НЕ МОЖЕТ — чистое правило. null означает «есть
    /// откуда читать».
    ///
    /// Это и есть требование «нет адреса и нет файла — честный отказ, а не
    /// пустой граф»: пустой граф молча ответил бы «пешком напрямую 9000 бл» и
    /// выглядел бы как работа.
    /// </summary>
    public static string? WhyNoNet(string? mapAddress, string? filePath, bool fileExists)
    {
        bool адресГоден = TranslocatorNetRules.GeoJsonUrl(mapAddress) is not null;
        bool файлЕсть = filePath is { Length: > 0 } && fileExists;

        if (адресГоден || файлЕсть)
            return null;

        if (mapAddress is { Length: > 0 } кривой && кривой.Trim().Length > 0)
            return $"адрес карты сервера не понят: «{кривой.Trim()}», а файла сети " +
                   (filePath is { Length: > 0 } ф ? $"«{ф}» " : "") +
                   "рядом с ботом нет. Маршрутов по транслокаторам не будет — и это отказ, " +
                   "а не пустая сеть: с пустой я бы молча повёл вас пешком через полмира";

        return "сети транслокаторов взять неоткуда: адрес карты сервера не задан, файла " +
               (filePath is { Length: > 0 } п ? $"«{п}» " : $"«{TranslocatorNetRules.FileName}» ") +
               "рядом с ботом тоже нет. Впишите адрес карты (тот же, что у окна управления, " +
               "например «https://map.tops.vintagestory.at/») — или положите рядом файл " +
               $"«{TranslocatorNetRules.FileName}», выгруженный с неё";
    }

    /// <summary>
    /// ЧТО ЕСТЬ ПРЯМО СЕЙЧАС. Сети не ждёт никогда.
    /// </summary>
    /// <param name="ask">
    /// Можно ли ходить в интернет. false — только сказать, что известно.
    /// Нужен затем же, зачем и у карты в окне: стучаться на чужой сервер там,
    /// где об этом не просили, — лишняя работа и лишний шум.
    /// </param>
    public TlNetLook Look(bool ask = true)
    {
        if (WhyNoNet(MapAddress, FilePath, FileExists()) is { } нет)
            return new TlNetLook(null, нет);

        lock (замок)
        {
            string адрес = TranslocatorNetRules.GeoJsonUrl(MapAddress) ?? "";

            // Адрес сменили — прежняя сеть от ДРУГОЙ карты, и держаться за неё
            // значило бы вести бота по чужому миру
            if (адрес != спрошенныйАдрес)
            {
                спрошенныйАдрес = адрес;
                сеть = null;
                почему = "";
                следующаяПопытка = DateTime.MinValue;
            }

            if (сеть is null && ReadFile() is { } изФайла)
            {
                сеть = изФайла;
                почему = "";
            }

            bool протухла = сеть?.WhyStale(Now(), StaleAfterHours) is not null;

            if (сеть is { } готовая && !протухла)
                return new TlNetLook(готовая, "");

            if (адрес.Length == 0)
                return сеть is { } старая
                    ? new TlNetLook(старая, "")   // обновить неоткуда — работаем тем, что есть
                    : new TlNetLook(null, почему.Length > 0 ? почему : "файл сети прочитать не вышло");

            if (!ask)
                return new TlNetLook(сеть, сеть is null
                    ? "за сетью транслокаторов бот не ходил: ходить в сеть не велено"
                    : "");

            if (!спрашиваем && Now() >= следующаяПопытка)
            {
                спрашиваем = true;
                _ = Task.Run(() => AskAsync(адрес));
            }

            // Протухшая сеть лучше никакой: маршрут по ней честно скажет о
            // своём возрасте (см. TlNet.WhyStale), а отказ не сказал бы ничего
            return new TlNetLook(сеть, сеть is not null
                ? ""
                : почему.Length > 0 ? почему : "читаю сеть транслокаторов с карты сервера…");
        }
    }

    private bool FileExists()
    {
        try
        {
            return FilePath is { Length: > 0 } путь && File.Exists(путь);
        }
        catch
        {
            // Путь может быть негодным (кривые знаки, нет прав) — это «файла
            // нет», а не повод рассыпаться
            return false;
        }
    }

    /// <summary>Прочесть файл, если он есть. Время файла — это и есть срок выгрузки.</summary>
    private TlNet? ReadFile()
    {
        if (FilePath is not { Length: > 0 } путь)
            return null;
        try
        {
            if (!File.Exists(путь))
                return null;
            string текст = File.ReadAllText(путь);
            if (TlNet.TryRead(текст, out var прочитано, out string нет,
                    $"файл {путь}", File.GetLastWriteTimeUtc(путь)))
                return прочитано;

            почему = $"файл сети «{путь}»: {нет}";
            OnLog?.Invoke(почему);
            return null;
        }
        catch (Exception e)
        {
            почему = $"файл сети «{путь}» не прочитать: {e.Message}";
            OnLog?.Invoke(почему);
            return null;
        }
    }

    /// <summary>Сходить за сетью на карту. Всё, что пошло не так, становится словами.</summary>
    private async Task AskAsync(string адрес)
    {
        string? тело = null;
        DateTime? выгружено = null;
        string беда = "";
        try
        {
            using var ответ = await http.GetAsync(адрес);
            if (!ответ.IsSuccessStatusCode)
                беда = $"карта сервера ответила {(int)ответ.StatusCode} на {адрес} — " +
                       "сети транслокаторов оттуда не взять";
            else
            {
                тело = await ответ.Content.ReadAsStringAsync();
                // Когда мир выгружали — говорит сам сервер. Своё «сейчас»
                // поставить было бы враньём: файл может быть недельной давности
                выгружено = ответ.Content.Headers.LastModified?.UtcDateTime;
            }
        }
        catch (Exception e)
        {
            беда = $"карта сервера не ответила на {адрес}: {e.Message}. " +
                   "Маршрутов по транслокаторам не будет, пока она молчит";
        }

        lock (замок)
        {
            спрашиваем = false;

            // Пока ходили, адрес могли сменить — ответ уже не про эту карту
            if (адрес != спрошенныйАдрес)
                return;

            if (беда.Length > 0)
            {
                почему = беда;
                следующаяПопытка = Now() + RetryAfter;
                OnLog?.Invoke(беда);
                return;
            }

            if (!TlNet.TryRead(тело, out var прочитано, out string нет, адрес, выгружено))
            {
                почему = $"карта сервера {адрес}: {нет}";
                следующаяПопытка = Now() + RetryAfter;
                OnLog?.Invoke(почему);
                return;
            }

            сеть = прочитано;
            почему = "";

            // СХОДИЛИ УДАЧНО — ЗНАЧИТ СЛЕДУЮЩИЙ РАЗ НЕ РАНЬШЕ СРОКА. Раньше
            // срок ставился ТОЛЬКО ПОСЛЕ НЕУДАЧИ, а после удачи оставался
            // нулём, и повторный поход сдерживало одно лишь «сеть свежая».
            //
            // ЧТО ЭТО ЛОМАЛО. Свежесть считается по времени выгрузки, а его
            // даёт заголовок Last-Modified — которого у карты может и не быть
            // (так отвечает всякий посредник и всякая карта, отдающая файл не
            // с диска). Тогда WhyStale честно говорит «когда собраны —
            // неизвестно», сеть НАВСЕГДА числится протухшей, и каждый вопрос о
            // ней слал новый запрос: на сотню вопросов — сто два похода на
            // чужую машину и столько же переписываний файла под ногами
            // (стенд TrekOnTheRoadTests.Приехавшую_сеть_бот_не_качает_заново…).
            // Дальняя дорога спрашивает сеть на каждом шаге, так что живьём
            // это било бы по карте сервера сотнями запросов на один поход.
            //
            // «Не знаю, свежая ли» — это причина СКАЗАТЬ человеку (и WhyStale
            // говорит), а не причина качать без конца: второй заход через
            // секунду принесёт ровно тот же файл.
            следующаяПопытка = Now() + СрокДоСледующегоПохода();

            OnLog?.Invoke($"сеть транслокаторов прочитана: {прочитано.Tell()}");
            foreach (string замечание in прочитано.Complaints)
                OnLog?.Invoke($"сеть транслокаторов: {замечание}");

            SaveFile(тело!);
        }
    }

    /// <summary>
    /// ЧЕРЕЗ СКОЛЬКО ИДТИ НА КАРТУ СНОВА ПОСЛЕ УДАЧНОЙ ВЫГРУЗКИ.
    ///
    /// Это <see cref="StaleAfterHours"/> — тот самый срок, после которого
    /// выгрузка считается устаревшей; раньше него новая ходка бессмысленна,
    /// карта всё равно перевыгружается не чаще раза в сутки.
    ///
    /// Пол в <see cref="RetryAfter"/> нужен для нуля и прочих малых значений
    /// ручки: «считать устаревшим сразу» — это про доверие к сведениям, а не
    /// разрешение долбить чужую машину без передышки.
    /// </summary>
    private TimeSpan СрокДоСледующегоПохода()
    {
        var срок = TimeSpan.FromHours(Math.Max(0, StaleAfterHours));
        return срок < RetryAfter ? RetryAfter : срок;
    }

    /// <summary>
    /// Положить скачанное в файл, чтобы завтра обойтись без сети. Не вышло —
    /// не беда для маршрута, но сказать надо: иначе бот молча ходит в интернет
    /// на каждый запуск.
    /// </summary>
    private void SaveFile(string тело)
    {
        if (FilePath is not { Length: > 0 } путь)
            return;
        try
        {
            if (Path.GetDirectoryName(путь) is { Length: > 0 } папка && !Directory.Exists(папка))
                Directory.CreateDirectory(папка);

            // СНАЧАЛА ВО ВРЕМЕННЫЙ, ПОТОМ ПОДМЕНОЙ — той же осторожностью, что
            // книга встреч, память пар и задачи (Meetings, TlMemory, Jobs).
            // Здесь это было единственное место во всей библиотеке, где текст
            // лился прямо в живой файл, и стоило это двух бед сразу:
            //   • пока идёт запись, файл НЕ ОТДАЁТСЯ на чтение — Windows
            //     отвечает «файл занят другим процессом» и человеку, и второму
            //     боту, и следующему запуску;
            //   • оборвись запись посередине (питание, убитый процесс) — рядом
            //     с ботом оставался бы обрубок geojson вместо вчерашней целой
            //     сети, и назавтра пришлось бы снова идти в интернет.
            // Подмена же — один шаг: файл либо прежний, либо новый целиком.
            string временный = путь + ".tmp";
            File.WriteAllText(временный, тело);
            File.Move(временный, путь, overwrite: true);
        }
        catch (Exception e)
        {
            // За собой прибрать: недописанный «.tmp» рядом с ботом — мусор,
            // который человек примет за сеть и станет искать, почему она пуста
            try { File.Delete(путь + ".tmp"); } catch { /* и убрать не вышло — не беда */ }

            OnLog?.Invoke($"сеть транслокаторов скачана, но в файл «{путь}» не легла: " +
                          $"{e.Message}. Завтра придётся снова идти в интернет");
        }
    }

    public void Dispose()
    {
        if (своийHttp)
            http.Dispose();
    }
}

/// <summary>
/// СЕТЬ ТРАНСЛОКАТОРОВ, ПОДКЛЮЧЁННАЯ К ЖИВОМУ БОТУ — тот самый шов, которого
/// не хватало: чистые правила выше умели считать маршрут, но спросить их было
/// НЕОТКУДА. Ни команды, ни вызова из роли не существовало, и человек,
/// вписавший адрес карты, получал работающую картинку — и ни одного маршрута,
/// без единого слова о том, почему.
///
/// ЧТО ЗДЕСЬ ДЕЛАЕТСЯ И ЧЕГО НЕ ДЕЛАЕТСЯ. Здесь — только перевод координат и
/// честные отказы словами. Цены (<see cref="Settings"/>) и адреса
/// (<see cref="Source"/>) сюда КЛАДЁТ РОЛЬ: по закону проекта адреса и пороги —
/// это политика, а не механизм. Своих чисел у этого класса нет ни одного.
///
/// ТРИ СИСТЕМЫ КООРДИНАТ СХОДЯТСЯ ИМЕННО ТУТ (см. <see cref="TlMapCoords"/>):
/// снаружи спрашивают КЛЕТКАМИ МИРА, которыми живёт бот, сеть считает в
/// ИГРОВЫХ, а карта отдаёт свои. Сдвиг берётся живым (<see cref="VsBot.CoordOffset"/>):
/// до входа в мир его не существует вовсе, и молча взятый ноль отправил бы бота
/// за полмиллиона блоков.
/// </summary>
public sealed class TranslocatorRouting : IDisposable
{
    private readonly Func<(int X, int Z)> сдвиг;

    /// <param name="coordOffset">
    /// Живой сдвиг «игровые ↔ мировые» — <see cref="VsBot.CoordOffset"/>.
    /// Функцией, а не числом: до входа в мир сдвига нет, а бот создаётся раньше.
    /// </param>
    public TranslocatorRouting(Func<(int X, int Z)> coordOffset, HttpClient? client = null)
    {
        сдвиг = coordOffset;
        Source = new TranslocatorNetSource(client);
        Source.OnLog += m => OnLog?.Invoke(m);
    }

    /// <summary>Откуда берётся сеть: файл рядом с ботом и/или карта сервера.</summary>
    public TranslocatorNetSource Source { get; }

    /// <summary>
    /// СВОЯ ПАМЯТЬ ПАР — второй источник знания о сети, и единственный, когда
    /// карты сервера нет вовсе (заказ 17.08: «а если вебкарты нет у нас, то мы
    /// можем сами запоминать какие пары у тл и куда идут?»).
    ///
    /// Кладётся снаружи (<see cref="VsBot"/>), потому что живёт дольше сеанса:
    /// у неё файл на диске. null — памяти нет, всё как раньше.
    /// </summary>
    public TlMemory? Memory { get; set; }

    /// <summary>
    /// ЦЕНЫ МАРШРУТА — политика роли. Запись целиком новым набором нарочно:
    /// <see cref="TlRouteSettings"/> — запись с init-свойствами, и «повернуть
    /// одну ручку» в ней нельзя, зато нельзя и забыть донести остальные.
    /// </summary>
    public TlRouteSettings Settings { get; set; } = new();

    /// <summary>Часы — подменяются в тестах, чтобы свежесть карты была проверяемой.</summary>
    public Func<DateTime> Now { get; set; } = () => DateTime.UtcNow;

    /// <summary>Куда сказать вслух. Молчать о неудаче нельзя.</summary>
    public event Action<string>? OnLog;

    /// <summary>
    /// МАРШРУТ МЕЖДУ КЛЕТКАМИ МИРА. Отказ — всегда словами и с причиной:
    /// «сети взять неоткуда», «ещё читаю», «сдвиг не известен». Пустого
    /// маршрута без объяснения отсюда не выходит никогда.
    /// </summary>
    /// <param name="ask">можно ли ходить за картой в интернет прямо сейчас</param>
    /// <param name="avoid">
    /// Концы, которые бот уже проверил ногами и нашёл негодными (см.
    /// <see cref="TlNet.Route"/>). Точки — в ИГРОВЫХ координатах: так их видит
    /// сеть, и так же их отдаёт <see cref="GameOf"/>.
    /// </param>
    public TlRoute RouteBetween(BlockPos fromWorld, BlockPos toWorld, bool ask = true,
        IReadOnlyCollection<TlPoint>? avoid = null)
    {
        if (TlMapCoords.WhyOffsetUnusable(сдвиг()) is { } нетСдвига)
            return new TlRoute([], "сеть не спрашивали", [], нетСдвига);

        var (сеть, почему) = Сеть(ask);
        if (сеть is null)
            return new TlRoute([], "сети нет", [],
                почему.Length > 0 ? почему : "сети транслокаторов у меня нет");

        var о = сдвиг();
        return сеть.Route(TlMapCoords.GameFromWorld(fromWorld, о),
            TlMapCoords.GameFromWorld(toWorld, о), Settings, Now(), avoid);
    }

    /// <summary>
    /// СЕТЬ, В КОТОРОЙ УЖЕ СЛОЖЕНЫ ОБА ИСТОЧНИКА: карта сервера и своя память.
    /// Одно место на всех, кто сеть спрашивает (маршрут, мнение о пластине,
    /// рассказ человеку), — иначе один из троих однажды остался бы без своей
    /// памяти, причём молча.
    ///
    /// ПЕРЕВОД КООРДИНАТ ТОЖЕ ЗДЕСЬ, И ТОЛЬКО ЗДЕСЬ. Память бота — мировые
    /// клетки, сеть — игровые точки (см. <see cref="TlOwnPair"/>).
    ///
    /// ОТКАЗ ОСТАЁТСЯ ОТКАЗОМ. Нет ни карты, ни памяти — возвращаем null и
    /// причину словами: пустая сеть молча ответила бы «пешком через полмира» и
    /// выглядела бы как работа (та же оговорка у
    /// <see cref="TranslocatorNetSource.WhyNoNet"/>).
    /// </summary>
    private (TlNet? Net, string Why) Сеть(bool ask)
    {
        var своё = Своё();
        var взгляд = Source.Look(ask);

        if (взгляд.Net is { } карта)
            return (своё.Count > 0 ? карта.Plus(своё) : карта, "");

        if (своё.Count > 0)
            return (TlNet.OfOwn(своё), "");

        return (null, взгляд.Why);
    }

    /// <summary>Своя память в игровых координатах. Пусто — памяти нет или она пуста.</summary>
    private List<TlOwnPair> Своё()
    {
        if (Memory is not { Count: > 0 } память)
            return [];
        var о = сдвиг();
        var список = new List<TlOwnPair>(память.Count);
        foreach (var п in память.All)
            список.Add(new TlOwnPair(
                TlMapCoords.GameFromWorld(п.From, о),
                TlMapCoords.GameFromWorld(п.To, о),
                п.CheckedUtc, п.ByFeet));
        return список;
    }

    /// <summary>
    /// ПЛАН ПОХОДА К ТОЧКЕ: сравнить ноги и сеть ОДНОЙ меркой и назвать обе
    /// оценки. Ни шагу при этом не делается — это то, что окно управления
    /// показывает человеку ДО подтверждения.
    ///
    /// ПОЧЕМУ ОТКАЗА ОТСЮДА НЕ БЫВАЕТ. Ногами дойти можно всегда, поэтому
    /// «сети нет», «карта молчит» и «сдвиг не известен» — это не отказ идти, а
    /// причина, по которой сравнивать было не с чем; она уходит в
    /// <see cref="TrekPlan.NetWhy"/> и говорится вслух. Молчаливое «иду пешком»
    /// человек прочёл бы как «сеть проверена и не помогла».
    /// </summary>
    public TrekPlan PlanTo(BlockPos fromWorld, BlockPos toWorld, bool ask = true,
        IReadOnlyCollection<TlPoint>? avoid = null)
    {
        // Цена ходьбы считается ВСЕГДА и своим правилом: она не зависит ни от
        // карты, ни от сдвига координат — только от того, где бот и куда зовут
        double пешком = TrekRules.WalkSecondsBetween(fromWorld, toWorld, Settings);

        var маршрут = RouteBetween(fromWorld, toWorld, ask, avoid);
        bool есть = маршрут.Found;
        return new TrekPlan(fromWorld, toWorld,
            TrekRules.Choose(пешком, есть ? маршрут : null, Settings, маршрут.Why ?? ""),
            есть ? маршрут : null,
            есть ? "" : маршрут.Why ?? "");
    }

    /// <summary>
    /// ИГРОВАЯ точка сети → клетка МИРА. null — сдвиг ещё не известен (бот не
