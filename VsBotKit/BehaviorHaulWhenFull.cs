namespace VsBotKit;

/// <summary>
/// СУМКИ ПОЛНЫ — САМ ИДУ НА СКЛАД.
///
/// ЖИВАЯ ЖАЛОБА, РАДИ КОТОРОЙ ЭТО НАПИСАНО, слово в слово: «не могу найти
/// команду разгрузиться в отмеченный склад, инвентарь у бота полный и он не
/// идет». Команду с тех пор завели («!разгрузка»), а вот САМ бот на склад не
/// собирался никогда. Всё для этого в боте лежало и молчало: порог
/// (<see cref="Depot.HaulWhenFreeSlots"/>) и вопрос «пора ли»
/// (<see cref="Depot.TimeToHaul"/>) спрашивал ровно один наряд за рудой
/// (<see cref="MiningOrder"/>). Карьер, штольня и просто живущий бот стояли с
/// полной сумкой и ломали породу в никуда: выломанное падает на землю и там
/// же остаётся.
///
/// ---------------------------------------------------------------------
/// ГДЕ ЕЁ МЕСТО В ВЕСАХ И ПОЧЕМУ ИМЕННО ТАМ
///
/// Вес — <see cref="BehaviorWeights.Work"/> (дело роли), а НЕ рефлекс
/// выживания. Разгрузка ничего не спасает: полная сумка — это про потерянную
/// добычу, а не про здоровье. Стоя выше еды или лечения, рейс на склад увёл бы
/// голодного бота за триста блоков — ровно та беда, из-за которой у еды,
/// лечения и возрождения появился ПОЛ (см. <see cref="BehaviorWeights"/>).
/// Потолок ей достаётся сам собой: всё, что по умолчанию ниже
/// <see cref="BehaviorWeights.LifeFloor"/>, выше него и не поднимается, —
/// поэтому «разгрузка 99» в панели работу над едой не поставит.
///
/// Внутри своего веса она стоит ПОСЛЕ подбора своей добычи и ПЕРЕД сбором
/// ягод: сперва поднять с земли то, что сам же выломал (иначе оно так и
/// останется лежать), потом отнести всё разом, а за ягодами идти уже потом —
/// в полную сумку они всё равно не влезут.
///
/// ---------------------------------------------------------------------
/// ПОЧЕМУ БОТ НЕ БРОСАЕТ ДЕЛО НА ПЕРВОМ ЖЕ ЗАНЯТОМ СЛОТЕ
///
/// Мерка одна и живёт в складе: свободных мест осталось не больше порога
/// (по умолчанию 3 из 32). До порога никто никого не трогает — карьер копает,
/// дорога мостится. Второе условие — <see cref="CargoSlots"/>: сумка, забитая
/// СВОИМ (кирка, факелы, еда), поводом для рейса не считается. Без этого
/// выходил вечный круг: бот с полным набором инструментов видит «мест 2 из 32»,
/// идёт на склад, склад честно отвечает «в сумке только своё — нести нечего»,
/// и всё сначала — дважды в секунду, каждый раз отбирая тело у работы.
///
/// ---------------------------------------------------------------------
/// ЧЬИМ ТЕЛОМ ИДЁМ И ПОЧЕМУ ЭТО НЕ «Я ВАЖНЕЕ ВСЕХ»
///
/// Тело берётся важностью <see cref="BodyArbiter.Importance.Reflex"/>, и это
/// не оценка себя, а ЕДИНСТВЕННОЕ ЧТЕНИЕ ПЕРЕХВАТА, при котором прерванная
/// работа возвращается. Распорядитель тела различает всего два случая
/// (<see cref="BodyArbiter.Preemption"/>): перехватил рефлекс — «помеха
/// временная, цель прежняя, тело вернут» (<see cref="BodyArbiter.Ending.Preempted"/>,
/// и <see cref="Resume"/> доводит работу до конца); перехватило что угодно
/// ниже — «боту велели заняться другим», и к карьеру он не вернётся. Разгрузка
/// — ровно первый случай: цель не менялась, бот уходит на пять минут и
/// возвращается в тот же забой (<see cref="Depot.ReturnToFace"/>). Возьми она
/// тело как «дело роли», карьер после рейса умирал бы навсегда — та самая яма
/// «скопал часть сверху и не стал углубляться».
///
/// ЦЕНА ЭТОГО РЕШЕНИЯ НАЗЫВАЕТСЯ ВСЛУХ: равный равного не перебивает, значит
/// БОЙ во время рейса получил бы отказ. Платим не молчанием, а уступкой —
/// <see cref="GiveWay"/>: боту сказали «телом распоряжается разгрузка» —
/// рейс сходит с тела сам и вернётся к нему после стычки. Связывает это
/// пресет выживания (там и живёт «кто важнее»), а не эта способность.
///
/// ---------------------------------------------------------------------
/// ПОЧЕМУ РЕЙС ИДЁТ СВОИМ ХОДОМ, А НЕ ВНУТРИ ТИКА
///
/// Планировщик способностей обходит их ПО ОЧЕРЕДИ и ждёт каждую
/// (<see cref="BehaviorRunner.StartAsync"/>). Рейс на склад — это минуты
/// ходьбы; сделай мы его прямо в тике, эти минуты не тикали бы ни еда, ни
/// лечение, ни бой. Бот, умерший от голода с хлебом в кармане, у этого
/// заказчика уже был, и повторить его в новом месте нельзя. Поэтому тик
/// только ЗАВОДИТ рейс и тут же отпускает очередь, а рейс живёт своей задачей
/// и слушается трёх отмен разом: своего владения телом (его погасит дело
/// жизни), уступки бою и общей отмены бота.
/// </summary>
public class BehaviorHaulWhenFull : BotBehavior
{
    private readonly BotContext ctx;

    public BehaviorHaulWhenFull(BotContext ctx) => this.ctx = ctx;

    /// <summary>
    /// Как рейс зовётся в очереди на тело — и по этому же имени его узнаёт
    /// <see cref="GiveWay"/>. Имя одно на оба случая нарочно: разъедься они,
    /// бот уступал бы тело не тому и молча.
    /// </summary>
    public const string Owner = "разгрузка";

    /// <summary>
    /// Ходить ли на склад самому. ВЫКЛЮЧЕНО по умолчанию: решает роль. Бот без
    /// склада от этой способности ничего не получит, а лавочнику посреди
    /// торговли уходить к сундукам незачем.
    /// </summary>
    public bool Enabled { get; set; }

    /// <summary>
    /// Через сколько секунд пробовать снова, если рейс не удался (сундук полон,
    /// до склада не дойти, в точке склада не хранилище).
    ///
    /// Пауза здесь обязательна. Неудача не проходит сама: сумка как была полной,
    /// так и осталась, и без паузы бот отбирал бы тело у работы каждый тик,
    /// уходил бы к тому же полному сундуку — и <see cref="Resume"/> бросил бы
    /// карьер уже на третьем таком возврате как безнадёжный.
    /// </summary>
    public double RetrySeconds { get; set; } = 60;

    /// <summary>
    /// Через сколько секунд возвращаться к рейсу, уступив тело более важному
    /// (бой, еда, лечение). Счёт на секунды, а не на минуты: стычка кончается
    /// быстро, а сумка всё это время полна.
    /// </summary>
    public double YieldSeconds { get; set; } = 5;

    /// <summary>
    /// СКОЛЬКО ДАТЬ РАБОТЕ СХОДИТЬ НА СКЛАД САМОЙ, прежде чем отбирать у неё
    /// тело. Считается с той секунды, как сумка набралась до порога.
    ///
    /// Наряд за рудой носит груз сам — спрашивает склад на каждом круге. Отбери
    /// у него тело раньше, чем он до этого вопроса дойдёт, и «!добудь медь 20»
    /// кончится словом «отменено»: наряд на возврат не заведён. Полминуты —
    /// это круг наряда и заведомо меньше, чем карьеру нужно, чтобы от порога
    /// добить сумку начисто (одна стопка камня — 64 удара).
    ///
    /// Тело СВОБОДНО — этот срок не ждут вовсе: прерывать некого.
    /// </summary>
    /// По умолчанию НОЛЬ — поблажки нет. Заказчик просил ровно обратного:
    /// «инвентарь у бота полный и он не идет». Работа, которая сама сходит на
    /// склад, есть не у всех, а ждать тридцать секунд с полной сумкой значит
    /// ронять добычу на землю. Кому поблажка нужна — крутит ручку.
    public double GraceSeconds { get; set; }

    /// <summary>С какого мига сумка полна. null — не полна.</summary>
    private DateTime? полнаС;

    /// <summary>
    /// БЕДА, О КОТОРОЙ ГОВОРЯТ ГРОМКО И ОДИН РАЗ: нести некуда, сундук полон,
    /// телом распоряжается кто-то важнее. Своего «сказать один раз» здесь нет
    /// и не будет — <see cref="Alarm"/> для того и написан.
    /// </summary>
    public Alarm Trouble { get; } = new("разгрузка");

    /// <summary>Пошёл на склад (сколько мест оставалось в сумке).</summary>
    public event Action<int>? OnGoing;

    /// <summary>Рейс кончился — с тем, чем кончился. Отчёт склада как есть.</summary>
    public event Action<HaulReport>? OnHauled;

    /// <summary>Рейс уступил тело: кому именно, решает не эта способность.</summary>
    public event Action? OnGaveWay;

    private Task? trip;
    private CancellationTokenSource? tripStop;
    private DateTime nextTry = DateTime.MinValue;

    /// <summary>Рейс идёт прямо сейчас.</summary>
    public bool Hauling => trip is { IsCompleted: false };

    /// <summary>
    /// Сам рейс — задачей. Отдан наружу затем, что рейс живёт ВНЕ тика (см.
    /// разбор у класса), и дождаться его иначе нечем: ни стенд, ни роль не
    /// смогли бы отличить «рейс идёт» от «рейс кончился и ничего не сказал».
    /// </summary>
    public Task? Trip => trip;

    // ---------------- чистые правила ----------------

    /// <summary>
    /// ПОРА ЛИ НА СКЛАД. Чистое правило: всё, что оно спрашивает у мира, подано
    /// сюда числами.
    ///
    /// Порог — не наш, он общий и живёт в складе (<see cref="Depot.BagIsFull"/>):
    /// иначе «когда сумка полна» означало бы у наряда одно, а у этой
    /// способности другое.
    ///
    /// А вот <paramref name="cargoSlots"/> — наше и здесь важнее порога. Полная
    /// сумка ИНСТРУМЕНТОВ И ЕДЫ на склад не носится: рейс кончился бы отказом
    /// «в сумке только своё — нести нечего», и так каждый тик.
    /// </summary>
    /// <param name="freeSlots">свободных мест в сумках</param>
    /// <param name="haulWhenFreeSlots">порог склада: при скольких местах пора</param>
    /// <param name="cargoSlots">сколько слотов занято грузом, а не своим</param>
    public static bool TimeToGo(int freeSlots, int haulWhenFreeSlots, int cargoSlots) =>
        cargoSlots > 0 && Depot.BagIsFull(freeSlots, haulWhenFreeSlots);

    /// <summary>
    /// СТОИТ ЛИ ПРЕРЫВАТЬ РАДИ СКЛАДА. Чистое правило: null — можно идти, иначе
    /// причина человеческими словами (её и скажет тревога — один раз).
    ///
    /// РЕФЛЕКС И ДЕЛО ЖИЗНИ (бой, побег, укрытие, обед) не трогаем вовсе.
    /// Распорядитель тела и так откажет равному, но спросить надо ДО отказа:
    /// иначе журнал заливает «разгрузка не берёт тело: занято боем» дважды в
    /// секунду, а в этом шуме заказчик уже однажды не разглядел настоящей беды.
    ///
    /// ЧУЖОЙ РЕЙС. Человек сказал «!разгрузка» руками; второй такой же рейс
    /// поверх первого не затевается, сколько бы ни было в сумке.
    ///
    /// РАБОТЕ ДАЁМ СХОДИТЬ САМОЙ. Работу роли и приказ человека прерывать
    /// можно, но НЕ В ТУ ЖЕ СЕКУНДУ, как сумка набралась: наряд за рудой
    /// (<see cref="MiningOrder"/>) носит груз на склад САМ — спрашивает
    /// <see cref="Depot.TimeToHaul"/> на каждом круге и ходит сам. Отбери у
    /// него тело раньше, чем он дойдёт до этого вопроса, — и «!добудь медь 20»
    /// кончится словом «отменено» вместо двадцати меди: наряд на возврат не
    /// заведён и второй раз сам не начнётся.
    ///
    /// Поэтому мерка времени, а не имени: список «кто носит сам» пришлось бы
    /// пополнять при каждой новой работе и однажды забыть. Сумка полна дольше
    /// отведённого, а тело всё ещё у работы — значит сама она не сходит, и
    /// дальше копать в полную сумку значит ронять добычу на землю. Карьеру этот
    /// срок не мешает: от порога до забитой начисто сумки он копает минуты
    /// (одна стопка камня — это 64 удара), и прерванный карьер вернётся сам.
    /// </summary>
    /// <param name="busyOwner">чем занято тело (пусто — тело свободно)</param>
    /// <param name="busyWith">насколько важно нынешнее занятие</param>
    /// <param name="fullSeconds">сколько секунд сумка уже полна</param>
    /// <param name="graceSeconds">сколько времени дать работе сходить на склад самой</param>
    public static string? WhyNotNow(string busyOwner, BodyArbiter.Importance? busyWith,
        double fullSeconds, double graceSeconds)
    {
        if (busyOwner.Contains(Owner, StringComparison.OrdinalIgnoreCase))
            return $"рейс на склад уже идёт («{busyOwner}») — второго не затеваю";
        if (busyWith is not { } level)
            return null;   // тело свободно — прерывать нечего и ждать нечего
        if (level >= BodyArbiter.Importance.Reflex)
            return $"сумки полны, а телом сейчас распоряжается «{busyOwner}» — " +
                   "пойду на склад, как освободится";
        if (fullSeconds < graceSeconds)
            return $"сумки полны, а телом занято «{busyOwner}» — даю ему " +
                   $"{graceSeconds - fullSeconds:0} с сходить на склад самому";
        return null;
    }

    /// <summary>
    /// СКОЛЬКО ЖДАТЬ ПЕРЕД СЛЕДУЮЩЕЙ ПОПЫТКОЙ — чистое правило.
    ///
    /// Разгрузился — ждать нечего: сумка пуста, и порог сам больше не сработает.
    /// Уступили тело — пауза короткая, стычка или обед кончаются быстро.
    /// Всё остальное (нести некуда, сундук полон, не дойти, вышло время) само
    /// не проходит: сюда нужна долгая пауза, иначе бот ходит к тому же полному
    /// сундуку каждые несколько секунд и отбирает тело у работы.
    /// </summary>
    public static double PauseAfter(HaulStop stop, double retrySeconds, double yieldSeconds) =>
        stop switch
        {
            HaulStop.Done => 0,
            HaulStop.Cancelled => yieldSeconds,
            _ => retrySeconds
        };

    // ---------------- сам ход ----------------

    /// <summary>
    /// Сколько слотов занято ГРУЗОМ — тем, что на складе и оставляют. Что
    /// считать грузом, решает склад (<see cref="Depot.Cargo(string)"/>):
    /// правило про кирку, факелы, еду и про ИЗЛИШЕК запаса в боте одно, и
    /// второй его копии здесь нет.
    ///
    /// СПРАШИВАЕМ ЧИСЛО, А НЕ «ЧЬЁ ЭТО», И ЭТО НЕ МЕЛОЧЬ. Пока здесь стояло
    /// «не своё» (Keep), сумка, набитая лишними стрелами, грузом не считалась
    /// вовсе — рейс не начинался, и починка излишка в самом складе не значила
    /// бы ничего: правило верное, а спросить его некому.
    /// </summary>
    public int CargoSlots(Depot depot) => ctx.Self.CarrySlots()
        .Count(s => !s.Content.IsEmpty && s.Content.Code is { } code && depot.Cargo(code) > 0);

    public override Task<bool> TickAsync(CancellationToken ct)
    {
        if (!Enabled || ctx.Depot is not { } depot)
            return Task.FromResult(false);

        // Рейс уже идёт своим ходом — очередь способностей не держим: пока бот
        // шагает к сундуку, ему по-прежнему надо есть, лечиться и отбиваться
        if (Hauling || DateTime.UtcNow < nextTry)
            return Task.FromResult(false);

        // 1. ПОРА ЛИ
        if (!TimeToGo(ctx.Self.FreeCarrySlots(), depot.HaulWhenFreeSlots, CargoSlots(depot)))
            return Task.FromResult(false);

        // 2. ЕСТЬ ЛИ КУДА. Спрашиваем сам склад — он же и жалуется, ОДИН раз на
        // положение («сумка полна, а нести некуда: склад не задан…»). Своей
        // второй жалобы здесь нет нарочно: две строки об одном и том же читаются
        // как две разные беды
        if (!depot.TimeToHaul())
        {
            // Сумка разгрузилась (сама или чужими руками) — счёт «сколько уже
            // полна» начинается заново, иначе поблажка работе выдаётся один раз
            // за всю смену и больше никогда
            полнаС = null;
            return Task.FromResult(false);
        }

        // С КАКОГО МОМЕНТА ПОЛНА. Нужно поблажке: работе дают GraceSeconds
        // сходить на склад самой, и отсчитывать их надо от того мига, когда
        // сумка набилась, а не от каждого тика
        полнаС ??= DateTime.UtcNow;

        // 3. СТОИТ ЛИ ПРЕРЫВАТЬ
        if (WhyNotNow(ctx.Turn.Busy, ctx.Turn.BusyWith,
                (DateTime.UtcNow - полнаС.Value).TotalSeconds, GraceSeconds) is { } wait)
        {
            Trouble.Raise(wait);
            return Task.FromResult(false);
        }

        var hold = ctx.Turn.TryTake(Owner, BodyArbiter.Importance.Reflex, ct);
        if (hold == null)
        {
            // Отказ распорядитель уже сказал вслух сам. Нам остаётся не долбить
            // его в следующий тик
            nextTry = DateTime.UtcNow.AddSeconds(YieldSeconds);
            return Task.FromResult(false);
        }

        OnGoing?.Invoke(ctx.Self.FreeCarrySlots());
        var stop = new CancellationTokenSource();
        tripStop = stop;
        trip = RunTripAsync(depot, hold, stop, ct);
        return Task.FromResult(true);
    }

    /// <summary>
    /// Рейс: сходить, сложить, вернуться в забой. Своей механики тут нет —
    /// весь рейс делает склад (<see cref="Depot.HaulAsync"/>), здесь только
    /// владение телом, три отмены и честный конец.
    /// </summary>
    private async Task RunTripAsync(Depot depot, BodyArbiter.Hold hold,
        CancellationTokenSource stop, CancellationToken outer)
    {
        HaulReport? report = null;
        try
        {
            using (hold)
            using (stop)
            using (var linked = CancellationTokenSource.CreateLinkedTokenSource(
                       hold.Token, stop.Token, outer))
            {
                report = await depot.HaulAsync(linked.Token);
            }
        }
        catch (OperationCanceledException)
        {
            // Рейс оборвали: дело жизни забрало тело, уступили бою, человек
            // сказал «стоп». Это не беда и не успех — вернёмся через паузу
        }
        catch (Exception ex)
        {
            // Задача живёт ВНЕ тика, и раннер её ошибку не увидит и не покажет.
            // Молчаливо погасший рейс со стороны неотличим от бота, который
            // «просто не идёт», — а именно с этой жалобы всё и началось
            Trouble.Raise($"рейс сорвался: {ex.Message}");
            nextTry = DateTime.UtcNow.AddSeconds(RetrySeconds);
            tripStop = null;
            return;
        }

        tripStop = null;
        if (report is not { } done)
        {
            nextTry = DateTime.UtcNow.AddSeconds(YieldSeconds);
            return;
        }

        OnHauled?.Invoke(done);
        nextTry = DateTime.UtcNow.AddSeconds(PauseAfter(done.Stop, RetrySeconds, YieldSeconds));
        if (done.Success)
            Trouble.Clear($"разгрузился, мест в сумке {done.FreeSlotsAfter}");
        else if (done.Stop != HaulStop.Cancelled)
            // Про отмену не тревожим: тело забрал кто-то важнее, и он про себя
            // уже сказал
            Trouble.Raise(done.Reason);
    }

    /// <summary>
    /// УСТУПИТЬ ТЕЛО: рейс сходит с него сам и вернётся после.
    ///
    /// Зачем это нужно. Рейс держит тело как рефлекс (иначе прерванный карьер
    /// не вернулся бы — см. разбор у класса), а равный равного не перебивает:
    /// бой, попросив тело посреди рейса, получил бы честный отказ и всю дорогу
    /// до сундука бот стоял бы под ударами. Отказывать бою нельзя, а понизить
    /// важность рейса — значит потерять возврат к работе. Поэтому уступаем
    /// сами, по просьбе.
    ///
    /// <paramref name="holder"/> — имя того, кто СЕЙЧАС держит тело (именно его
    /// и называет бой в своём «телом распоряжается …»). Чужое владение не наше
    /// дело: возвращаем false и ничего не трогаем.
    /// </summary>
    public bool GiveWay(string holder)
    {
        if (!Hauling || !string.Equals(holder, Owner, StringComparison.OrdinalIgnoreCase))
            return false;
        try
        {
            tripStop?.Cancel();
        }
        catch (ObjectDisposedException)
        {
            // Рейс кончился сам между проверкой и отменой — уступать нечего
            return false;
        }
        nextTry = DateTime.UtcNow.AddSeconds(YieldSeconds);
        OnGaveWay?.Invoke();
        return true;
    }
