using System.Collections;
using System.Diagnostics;
using System.Reflection;

namespace VsBotKit;

/// <summary>
/// ОБХОД ВСЕХ ПОЛЕЙ БОТА — механический снимок состояния вместо рукописного
/// списка полей.
///
/// ЖИВАЯ ПРИЧИНА, ПО КОТОРОЙ ЗАВЕДЁН ИМЕННО ОБХОД, А НЕ СПИСОК. Заказчик
/// 23.08: «хочется смену настроек и роли без перезапуска». Снять роль значит
/// вернуть боту всё, что она раздала: пороги (в одном <c>Movement</c> их 68,
/// всего по библиотеке под тысячу), подписки на события, добавленные
/// способности, команды и навыки. Рукописный список этих мест разошёлся бы с
/// кодом в первый же месяц и разошёлся бы МОЛЧА: забытое поле не падает и не
/// жалуется, оно просто оставляет стражника с дерзкой ходьбой копателя.
/// Поэтому «что раздала роль» здесь никто не перечисляет — это РАЗНИЦА
/// снимков, снятых до и после <see cref="BotRole.Configure"/>.
///
/// ЧТО ИМЕННО ОБХОДИТСЯ. Поля (а не свойства): у свойства с автоматическим
/// хранением поле и есть единственное место, где живёт значение, а приватные
/// реестры (словарь команд <c>ChatCommands.commands</c>, словарь навыков
/// <c>SkillRunner.skills</c>) свойствами наружу не выведены вовсе — списком по
/// свойствам их было бы не снять. Заодно поле обходит и СВОЙСТВО С УМНЫМ
/// СЕТТЕРОМ: <c>Movement.Caution</c> при записи раскладывается ещё на десяток
/// полей, и вернуть его вызовом сеттера значило бы гадать, что он делает.
///
/// ГДЕ ОБХОД ОСТАНАВЛИВАЕТСЯ И ПОЧЕМУ ГОВОРИТ ОБ ЭТОМ ВСЛУХ:
///   • в чужие типы (типы игры, типы платформы) не заходим — там реестры на
///     десятки тысяч записей, и роль их всё равно не трогает;
///   • собрание больше <see cref="ПределСобрания"/> записей не переписываем, а
///     запоминаем только счёт: это карта мира и список существ, их роль тоже
///     не трогает. Если такое собрание всё-таки изменится — обход НАЗОВЁТ его
///     в жалобах, а не промолчит;
///   • на <see cref="ПределОбъектов"/> обход обрывается и жалуется.
/// </summary>
public sealed class ОбходПолей
{
    /// <summary>
    /// Собрание длиннее — не переписываем, помним только счёт. 256 взято по
    /// самому большому собранию, которое роль вправду раздаёт: способностей
    /// выживания 24, команд чата около 30, навыков полтора десятка. Всё, что
    /// длиннее, — это уже мир, существа и реестры игры.
    /// </summary>
    public const int ПределСобрания = 256;

    /// <summary>Столько объектов — и хватит: дальше обход честно обрывается.</summary>
    public const int ПределОбъектов = 20_000;

    private readonly Dictionary<string, Ячейка> ячейки = new(StringComparer.Ordinal);
    private readonly HashSet<object> видели = new(ReferenceEqualityComparer.Instance);
    private readonly List<string> заметки = [];
    private readonly HashSet<Assembly> свои = [];

    private ОбходПолей() { }

    /// <summary>Что обход снять не смог — словами и по именам.</summary>
    public IReadOnlyList<string> Заметки => заметки;

    /// <summary>Сколько полей снято — числом, для журнала и стендов.</summary>
    public int Снято => ячейки.Count;

    /// <summary>Снятые поля: путь → ячейка.</summary>
    internal IReadOnlyDictionary<string, Ячейка> Ячейки => ячейки;

    /// <summary>
    /// Снять весь бот. <paramref name="мимо"/> — объекты, внутрь которых не
    /// заходим: сама роль сюда и попадает. Роль после смены выбрасывают
    /// целиком, её поля возвращать некуда, а вот перепутать поле роли с полем
    /// механизма — прямой путь к «отката нет, а отчёт зелёный».
    /// </summary>
    public static ОбходПолей Снять(VsBot бот, params object?[] мимо)
    {
        var обход = new ОбходПолей();
        обход.свои.Add(typeof(VsBot).Assembly);
        // Своя роль заказчика лежит отдельной сборкой (Roles.ПапкаРолей), и её
        // способности — такие же механизмы, как наши. Не пустить обход в её
        // сборку значило бы не снимать след ровно у тех ролей, ради которых
        // папка и заведена
        if (бот.Role is { } роль)
            обход.свои.Add(роль.GetType().Assembly);
        foreach (object? м in мимо)
            if (м is not null)
                обход.видели.Add(м);
        обход.Пройти(бот);
        return обход;
    }

    /// <summary>
    /// ОПИСЬ — тот же снимок, но словами и сравнимый с другим снимком.
    ///
    /// Нужна ровно для одной проверки, и проверка эта главная: снять роль,
    /// накатить её же заново — и описи обязаны совпасть ДО ЕДИНОЙ СТРОКИ.
    /// Сравнивать сами объекты нельзя: способности после пересборки — ДРУГИЕ
    /// объекты того же вида, и равенство по ссылке сказало бы «не совпало»
    /// там, где всё правильно. Поэтому здесь всё сводится к тексту: у объекта —
    /// вид, у делегата — имена методов, у собрания — содержимое.
    ///
    /// МОМЕНТЫ ВРЕМЕНИ НЕ СРАВНИВАЮТСЯ. <c>DateTime</c> в полях механизмов —
    /// это «когда я последний раз пробовал», и он по определению разный у двух
    /// прогонов. Сравнивай мы его — опись краснела бы всегда и потому не
    /// значила бы ничего.
    /// </summary>
    public SortedDictionary<string, string> Опись()
    {
        var опись = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var (путь, я) in ячейки)
            опись[путь] = я.Словами();
        return опись;
    }

    /// <summary>
    /// ПЕРЕЧИТАТЬ ТЕ ЖЕ САМЫЕ ПОЛЯ, не обходя граф заново.
    ///
    /// Нужно на каждый поворот ручки в окне, и потому обязано быть дешёвым:
    /// хозяин объекта и <see cref="FieldInfo"/> уже найдены обходом, остаётся
    /// прочитать значения. Полный обход тут был бы платой в десятки
    /// миллисекунд за каждый щелчок мышью — а пресет крутит ручки пачкой, по
    /// сотне за раз.
    ///
    /// Полей, РОЖДЁННЫХ ролью (у её же способностей), здесь нет нарочно:
    /// способности роли снимаются целиком, вместе с объектами, и возвращать в
    /// них нечего.
    /// </summary>
    internal Dictionary<string, Ячейка> Перечитать()
    {
        var свежие = new Dictionary<string, Ячейка>(ячейки.Count, StringComparer.Ordinal);
        foreach (var (путь, старая) in ячейки)
        {
            object? значение;
            try { значение = старая.Поле.GetValue(старая.Владелец); }
            catch (Exception e)
            {
                // МОЛЧА ПРОПУСТИТЬ НЕЛЬЗЯ. Не прочитанное поле выпадает из
                // свежего снимка, а значит и из следа: роль его тронула, а
                // откат про него не узнает. Соседний обход (Пройти) такой
                // отказ записывает, а здесь он был проглочен — то есть
                // «поле роли не вернулось, а НеВернулось пусто»
                заметки.Add($"{путь}: перечитать не удалось ({e.GetType().Name})");
                continue;
            }
            var я = new Ячейка(путь, старая.Владелец, старая.Поле, значение);
            if (значение is not null && !Наш(значение.GetType()) && !Игровое(значение.GetType()))
                СнятьСобрание(я, значение, очередь: null);
            свежие[путь] = я;
        }
        return свежие;
    }

    private void Пройти(object корень)
    {
        var очередь = new Queue<(object Кто, string Путь)>();
        видели.Add(корень);
        очередь.Enqueue((корень, ""));

        while (очередь.Count > 0)
        {
            var (кто, где) = очередь.Dequeue();
            if (видели.Count > ПределОбъектов)
            {
                заметки.Add($"обход оборван на {ПределОбъектов} объектах — дальше «{где}» не снято");
                return;
            }

            foreach (var поле in ПоляТипа(кто.GetType()))
            {
                object? значение;
                try { значение = поле.GetValue(кто); }
                catch (Exception e)
                {
                    заметки.Add($"{где}.{ИмяПоля(поле)}: не прочиталось ({e.GetType().Name})");
                    continue;
                }

                string путьПоля = где.Length == 0 ? ИмяПоля(поле) : $"{где}.{ИмяПоля(поле)}";
                var я = new Ячейка(путьПоля, кто, поле, значение);
                ячейки[путьПоля] = я;

                if (значение is null)
                    continue;

                // СНАЧАЛА наши типы, и только потом собрания: наш тип может
                // быть перечислимым (реестр с удобным foreach), и перебрать его
                // вместо разбора по полям значило бы не снять его порогов
                if (Наш(значение.GetType()))
                {
                    if (видели.Add(значение))
                        очередь.Enqueue((значение, путьПоля));
                    continue;
                }

                // ЖИВОЕ СОСТОЯНИЕ ИГРЫ ОБХОД НЕ СНИМАЕТ (см. Игровое): роль его
                // не раздаёт, вернуть его нельзя, и жаловаться на него — врать
                if (Игровое(значение.GetType()))
                    continue;

                СнятьСобрание(я, значение, очередь);
            }
        }
    }

    /// <param name="очередь">
    /// Куда складывать наши объекты, найденные внутри собрания. null — идёт
    /// перечитывание уже пройденного графа, и заходить внутрь заново незачем.
    /// </param>
    private void СнятьСобрание(Ячейка я, object значение, Queue<(object, string)>? очередь)
    {
        // Массив — лист, а не собрание. Роль массивов не мутирует; заменит весь
        // массив — это увидится как смена значения самого поля
        if (значение is Array or string)
            return;

        if (значение is IDictionary словарь)
        {
            if (словарь.Count > ПределСобрания)
            {
                я.Велико = словарь.Count;
                return;
            }
            я.Словарь = [];
            foreach (DictionaryEntry пара in словарь)
            {
                я.Словарь.Add(new KeyValuePair<object, object?>(пара.Key, пара.Value));
                if (очередь is not null && пара.Value is { } v && Наш(v.GetType()) && видели.Add(v))
                    очередь.Enqueue((v, $"{я.Путь}[{пара.Key}]"));
            }
            return;
        }

        if (значение is not IEnumerable перечислимое || Наш(значение.GetType()))
            return;

        // СЧЁТ БЕРЁТСЯ НАСТОЯЩИЙ, А НЕ «ПРЕДЕЛ ПЛЮС ОДИН». Обрыв прямо в
        // накоплении писал в Велико ровно 257 ЛЮБОМУ длинному собранию, и
        // сверка «было 257, стало 257» не могла отличиться никогда: словарь
        // говорок на 7437 записей и список на 404 выглядели одинаково. То есть
        // обещание док-строки «обход НАЗОВЁТ такое собрание в жалобах» было
        // враньём для всего, что не словарь. У ICollection счёт спрашивается
        // даром, у прочего перечислимого он считается целиком — это дороже,
        // но платится только за собрания длиннее предела
        if (значение is ICollection сразу)
        {
            if (сразу.Count > ПределСобрания)
            {
                я.Велико = сразу.Count;
                return;
            }
        }

        var предметы = new List<object?>();
        int всего = 0;
        foreach (object? предмет in перечислимое)
        {
            всего++;
            if (всего <= ПределСобрания)
                предметы.Add(предмет);
        }
        if (всего > ПределСобрания)
        {
            я.Велико = всего;
            return;
        }
        я.Список = предметы;

        if (очередь is null)
            return;
        for (int i = 0; i < предметы.Count; i++)
            if (предметы[i] is { } v && Наш(v.GetType()) && видели.Add(v))
                очередь.Enqueue((v, $"{я.Путь}[{i}]"));
    }

    /// <summary>
    /// Наш ли это тип — то есть механизм бота, внутрь которого надо зайти.
    ///
    /// ОБХОД НЕ ОБХОДИТ САМ СЕБЯ. След роли живёт полем бота и держит внутри
    /// снимок всех его полей и список всех виденных объектов; зайди обход
    /// туда — он снял бы собственную бухгалтерию, и любые две описи разошлись
    /// бы на ней, а не на боте. Это единственное исключение, и оно про
    /// инструмент, а не про бота.
    /// </summary>
    /// <summary>
    /// ЭТО ЖИВОЕ СОСТОЯНИЕ ИГРЫ, А НЕ НАСТРОЙКА РОЛИ.
    ///
    /// ЖИВОЙ СЛУЧАЙ 26.08, СЛОВА ЗАКАЗЧИКА: «полубот — что за хрень, я хочу без
    /// перезапуска сервера менять пресеты ботов». Он был прав дважды: и в том,
    /// что хочет, и в том, что это «хрень». На КАЖДУЮ смену пресета окно
    /// пугало его строкой «ПРЕЖНЯЯ РОЛЬ ВЕРНУЛАСЬ НЕ ВСЯ — бот сейчас полубот,
    /// перезапустите его», а роль при этом менялась ВЕРНО. Вот из чего состояла
    /// вся жалоба, дословно из живого прогона:
    ///
    ///   Body.physics.entity.WatchedAttributes: не вернулось
    ///       (MissingMethodException: 'SyncedTreeAttribute.Add/Enqueue/Push')
    ///   Entities.entities[894362].WatchedAttributes: не вернулось (то же)
    ///   Stability.rules.config: не вернулось (TreeAttribute...)
    ///
    /// Это свойства ИГРОВОЙ сущности бота, свойства ЧУЖИХ МОБОВ вокруг и
    /// настройка самой игры. Роль их не трогает и тронуть не может: их пишет
    /// сервер. Обход же видел «это перечислимое» (дерево атрибутов игры и
    /// правда IEnumerable), снимал его как обычное собрание — а вернуть не мог,
    /// потому что у игрового дерева нет Add/Enqueue/Push.
    ///
    /// ГРАНИЦА ПРОХОДИТ ЗДЕСЬ. Откат отвечает за то, что раздаёт РОЛЬ. Живой
    /// мир — не её вотчина: возвращать чужому мобу его прошлые свойства не
    /// только невозможно, но и НЕВЕРНО, а пугать этим человека — вдвойне.
    /// </summary>
    private static bool Игровое(Type тип) =>
        тип.Namespace?.StartsWith("Vintagestory", StringComparison.Ordinal) == true ||
        тип.Assembly.GetName().Name?.StartsWith("Vintagestory", StringComparison.Ordinal) == true;

    private bool Наш(Type тип) =>
        !тип.IsValueType && тип != typeof(string) && !typeof(Delegate).IsAssignableFrom(тип)
        && тип != typeof(СледРоли) && тип != typeof(ОбходПолей)
        && свои.Contains(тип.Assembly);

    private static IEnumerable<FieldInfo> ПоляТипа(Type тип)
    {
        for (Type? t = тип; t != null && t != typeof(object); t = t.BaseType)
            foreach (var f in t.GetFields(BindingFlags.Instance | BindingFlags.Public
                                          | BindingFlags.NonPublic | BindingFlags.DeclaredOnly))
                yield return f;
    }

    /// <summary>
    /// Имя поля человеку: у автоматического свойства оно выглядит как
    /// «&lt;Caution&gt;k__BackingField», и в жалобе такое имя ничего не
    /// объясняет, а отказ обязан называть ручку узнаваемо.
    /// </summary>
    internal static string ИмяПоля(FieldInfo поле)
    {
        string имя = поле.Name;
        int конец = имя.IndexOf('>');
        return имя.Length > 0 && имя[0] == '<' && конец > 1 ? имя[1..конец] : имя;
    }

    /// <summary>Одно снятое поле: где живёт, что в нём было, что в нём лежит собранием.</summary>
    internal sealed class Ячейка(string путь, object владелец, FieldInfo поле, object? значение)
    {
        public string Путь { get; } = путь;
        public object Владелец { get; } = владелец;
        public FieldInfo Поле { get; } = поле;
        public object? Значение { get; } = значение;

        /// <summary>Содержимое списка (или иного перечислимого), если снято.</summary>
        public List<object?>? Список { get; set; }

        /// <summary>Содержимое словаря, если снято.</summary>
        public List<KeyValuePair<object, object?>>? Словарь { get; set; }

        /// <summary>Собрание длиннее предела: помним только счёт.</summary>
        public int? Велико { get; set; }

        public string Словами()
        {
            if (Велико is { } сколько)
                return $"собрание[{сколько}] — длиннее предела, содержимое не снято";
            if (Словарь is { } с)
                return "словарь{" + string.Join("; ", с
                    .Select(п => $"{п.Key}={Кратко(п.Value)}")
                    .OrderBy(строка => строка, StringComparer.Ordinal)) + "}";
            if (Список is { } л)
                return "список[" + string.Join("; ", л.Select(Кратко)) + "]";
            return Кратко(Значение);
        }

        private static string Кратко(object? что) => что switch
        {
            null => "нет",
            // Момент времени — это «когда я последний раз пробовал», у двух
            // прогонов он разный всегда. Сравнивать его значит красить опись
            // впустую и приучать не верить ей вовсе
            DateTime or DateTimeOffset => "<момент>",
            string s => $"\"{s}\"",
            bool b => b ? "да" : "нет",
            Delegate d => "слушатели: " + string.Join(", ", d.GetInvocationList()
                .Select(x => $"{x.Method.DeclaringType?.Name}.{x.Method.Name}")),
            Enum e => e.ToString(),
            IFormattable f => f.ToString(null, System.Globalization.CultureInfo.InvariantCulture),
            _ => $"<{что.GetType().Name}>",
        };
    }
}

/// <summary>
/// СЛЕД РОЛИ: всё, что роль сделала с ботом, — по нему её и снимают.
///
/// ПОЧЕМУ СЛЕД СЧИТАЕТСЯ РАЗНИЦЕЙ ВОКРУГ <c>Configure</c>, А НЕ «ОТ ЗАВОДА».
/// Заводской снимок «как было при рождении бота» вернул бы заодно и то, что
/// поставила ПРОГРАММА после выбора роли: центр берегов памяти, записывающего
/// ручки, отладочные команды, — а главное, выкинул бы подписчиков, которых
/// завело окно управления (журнал окна живёт подпиской на <c>bot.OnLog</c>).
/// Окно замолчало бы после первой же смены роли, и молчало бы молча. Разница
/// вокруг <c>Configure</c> называет ровно то, что тронула роль, и ничего сверх.
///
/// СЛЕД ПИШЕТСЯ ВСЮ ЖИЗНЬ РОЛИ, А НЕ ТОЛЬКО ПРИ СБОРКЕ (см.
/// <see cref="Дописать"/>): ручку крутят в окне уже в мире, и повёрнутое после
/// сборки — такой же след.
///
/// ТРИ ВИДА СЛЕДА И ТРИ РАЗНЫХ ОТКАТА — потому что порог и подписка отменяются
/// по-разному:
///   • ПОРОГ (обычное поле) возвращается ЦЕЛИКОМ к тому, что было до роли.
///     Именно целиком: ручку могли повернуть в окне уже после сборки, и
///     «вернуть, только если значение всё ещё то, что поставила роль» оставило
///     бы новой роли чужой порог — того самого полубота;
///   • ПОДПИСКА (делегат) вычитается ПОИМЕННО: у события к этому времени есть
///     и чужие слушатели (окно, журнал, аккаунт), и стереть событие целиком
///     значит оглушить их всех;
///   • СОБРАНИЕ (список способностей, словари команд и навыков, требования
///     запаса) возвращается к прежнему содержимому, но добавленное ПОЗЖЕ и не
///     ролью — сохраняется: отладочные команды ставит программа, а не роль.
/// </summary>
public sealed class СледРоли
{
    private readonly List<Откат> порядок = [];
    private readonly Dictionary<string, Откат> поПути = new(StringComparer.Ordinal);
    private readonly List<string> жалобы = [];
    private ОбходПолей доРоли = null!;
    private bool пишем;

    private СледРоли() { }

    /// <summary>Сколько мест роль тронула.</summary>
    public int Тронуто => порядок.Count;

    /// <summary>Что снять не удалось — по именам, без «что-то пошло не так».</summary>
    public IReadOnlyList<string> Жалобы => жалобы;

    /// <summary>Сколько заняло снятие следа при сборке — для журнала, честно.</summary>
    public TimeSpan Заняло { get; private set; }

    /// <summary>Пути, которые роль тронула, — для журнала и для стендов.</summary>
    public IReadOnlyList<string> Места => порядок.Select(о => о.Путь).ToList();

    /// <summary>
    /// Записать след: снимок до, настройка, перечитывание, разница.
    /// <paramref name="настроить"/> — это и есть <c>role.Configure(bot)</c>:
    /// зовём его ЗДЕСЬ, между двумя снимками, чтобы «что сделала роль» было
    /// фактом обхода, а не обещанием роли.
    /// </summary>
    public static СледРоли Записать(VsBot бот, BotRole роль, Action настроить)
    {
        var часы = Stopwatch.StartNew();
        var след = new СледРоли { пишем = true };
        след.доРоли = ОбходПолей.Снять(бот, роль);
        след.жалобы.AddRange(след.доРоли.Заметки);
        try
        {
            настроить();
            след.Сверить(след.доРоли.Ячейки, след.доРоли.Перечитать());
        }
        finally
        {
            след.пишем = false;
        }
        след.Заняло = часы.Elapsed;
        return след;
    }

    /// <summary>
    /// ДОПИСАТЬ СЛЕД: ручку роли повернули уже ПОСЛЕ сборки — и это надо снять
    /// тоже.
    ///
    /// ЖИВОЙ СЛУЧАЙ, БЕЗ КОТОРОГО СБРОС БЫЛ БЫ ДЫРЯВЫМ И ДЫРЯВЫМ МОЛЧА.
    /// «Дальность руды сквозь стены» у копателя с завода равна заводской
    /// дальности механизма — значит <c>Configure</c> её НЕ МЕНЯЕТ, и в разнице
    /// вокруг сборки её нет вовсе. Заказчик крутит её в окне на 200, меняет
    /// роль на стражника — и стражник остаётся с читерским зрением на 200
    /// блоков, которого у него нет даже ручки, чтобы выключить.
    ///
    /// Дверь у поворота ручки одна (<see cref="RoleKnobs.Apply(BotRole, string,
    /// System.Text.Json.JsonElement)"/>), через неё же идёт и запись — второго
    /// места, где можно забыть, тут не заводится.
    ///
    /// Вложенный поворот (пресет крутит ручки пачкой, <see cref="RoleKnobs.
    /// ApplyAll(BotRole, System.Text.Json.JsonElement, out List{string})"/>)
    /// пишется ОДНОЙ записью: иначе сотня ручек стоила бы сотни перечитываний
    /// подряд.
    /// </summary>
    internal void Дописать(Action действие)
    {
        if (пишем)
        {
            действие();
            return;
        }
        пишем = true;
        try
        {
            var до = доРоли.Перечитать();
            действие();
            Сверить(до, доРоли.Перечитать());
        }
        finally
        {
            пишем = false;
        }
    }

    private void Сверить(IReadOnlyDictionary<string, ОбходПолей.Ячейка> до,
                         IReadOnlyDictionary<string, ОбходПолей.Ячейка> после)
    {
        foreach (var (путь, было) in до)
        {
            if (!после.TryGetValue(путь, out var стало))
            {
                // ПУТИ ИСЧЕЗАЮТ ТОЛЬКО ОДНИМ СПОСОБОМ: перечитывание идёт по
                // тем же самым ячейкам, и ключ пропадает, лишь когда поле не
                // прочиталось. Промолчать тут значило бы «роль тронула, откат
                // не вернул, а НеВернулось пусто» — тихая ложь про полубота
                жалобы.Add($"{путь}: перечитать не удалось — вернуть нечем");
                continue;
            }

            if (было.Велико is { } скольким && стало.Велико is { } сколько && скольким != сколько)
            {
                жалобы.Add($"{путь}: собрание из {скольким} стало {сколько} — " +
                           "длиннее предела, вернуть нечем");
                continue;
            }

            // ПОДПИСКИ. Сравниваем списки слушателей, а не сами делегаты:
            // «событие изменилось» без имён не даёт снять ничего
            if (было.Значение is Delegate or null && стало.Значение is Delegate новое)
            {
                var прежние = (было.Значение as Delegate)?.GetInvocationList() ?? [];
                var теперь = новое.GetInvocationList();
                var добавленные = теперь.Where(д => !прежние.Contains(д)).ToList();
                var убранные = прежние.Where(д => !теперь.Contains(д)).ToList();
                if (добавленные.Count == 0 && убранные.Count == 0)
                    continue;
                var подписка = Завести(путь, было);
                (подписка.Добавленные ??= []).AddRange(добавленные);
                (подписка.Убранные ??= []).AddRange(убранные);
                continue;
            }

            if (!Одно(было.Значение, стало.Значение))
            {
                // ПОРОГ ВОЗВРАЩАЕТСЯ ЦЕЛИКОМ И ТОЛЬКО К ПЕРВОМУ ЗНАЧЕНИЮ. Знаем
                // путь — значит заводское уже записано; перезаписать его
                // нынешним (то есть значением уходящей роли) и означало бы
                // оставить новой роли чужой порог
                if (!поПути.ContainsKey(путь))
                {
                    var порог = Завести(путь, было);
                    порог.Значение = было.Значение;
                    порог.Вернуть = true;
                }
                continue;
            }

            // Поле не менялось, а вот СОДЕРЖИМОЕ собрания за ним — могло
            if (поПути.TryGetValue(путь, out var прежний) && прежний.Вернуть)
                continue;   // вернём объект целиком — содержимое считать незачем

            if (было.Словарь is { } словарьБыл && стало.Словарь is { } словарьСтал
                && !ОдинСловарь(словарьБыл, словарьСтал))
            {
                var собрание = Завести(путь, было);
                собрание.СловарьБыло ??= словарьБыл;
                собрание.СловарьСтало = словарьСтал;
            }
            else if (было.Список is { } списокБыл && стало.Список is { } списокСтал
                     && !ОдинСписок(списокБыл, списокСтал))
            {
                var собрание = Завести(путь, было);
                собрание.СписокБыло ??= списокБыл;
                собрание.СписокСтало = списокСтал;
            }
        }
    }

    private Откат Завести(string путь, ОбходПолей.Ячейка было)
    {
        if (поПути.TryGetValue(путь, out var есть))
            return есть;
        var новый = new Откат(путь, было.Владелец, было.Поле);
        поПути[путь] = новый;
        порядок.Add(новый);
        return новый;
    }

    /// <summary>
    /// Снять роль: вернуть всё, что она тронула. Возвращает жалобы — то, что
    /// вернуть НЕ удалось. Пустой список значит «вернулось всё», и только это
    /// даёт право сказать, что полубота не получилось.
    /// </summary>
    public IReadOnlyList<string> Откатить()
    {
        var беды = new List<string>(жалобы);
        // Задом наперёд: если роль сперва заменила объект, а потом правила его
        // поля, вернуть надо сначала поля, а уж потом сам объект
        for (int i = порядок.Count - 1; i >= 0; i--)
        {
            var о = порядок[i];
            try { Вернуть(о); }
            catch (Exception e) { беды.Add($"{о.Путь}: не вернулось ({e.GetType().Name}: {e.Message})"); }
        }
        return беды;
    }

    private static void Вернуть(Откат о)
    {
        if (о.Вернуть)
        {
            о.Поле.SetValue(о.Владелец, о.Значение);
            return;
        }

        if (о.Добавленные is not null || о.Убранные is not null)
        {
            var текущее = о.Поле.GetValue(о.Владелец) as Delegate;
            foreach (var д in о.Добавленные ?? [])
                текущее = Delegate.Remove(текущее, д);
            foreach (var д in о.Убранные ?? [])
                текущее = Delegate.Combine(текущее, д);
            о.Поле.SetValue(о.Владелец, текущее);
            return;
        }

        if (о.СловарьБыло is { } словарьБыло)
        {
            var живой = (IDictionary)о.Поле.GetValue(о.Владелец)!;
            var поКлючу = словарьБыло.ToDictionary(п => п.Key, п => п.Value);
            foreach (var п in о.СловарьСтало ?? [])
                if (!поКлючу.ContainsKey(п.Key) && живой.Contains(п.Key))
                    живой.Remove(п.Key);
            foreach (var п in словарьБыло)
                живой[п.Key] = п.Value;
            return;
        }

        if (о.СписокБыло is { } списокБыло)
        {
            object живое = о.Поле.GetValue(о.Владелец)!;
            // СОБРАНИЯ У НАС РАЗНЫЕ, И КЛАСТЬ В НИХ НАДО ПО-РАЗНОМУ: список
            // способностей — List, требования без доставки — HashSet, память
            // последних слов — Queue. Приведение к одному IList роняло откат на
            // очереди, и роль оставалась снятой наполовину
            var очистить = живое.GetType().GetMethod("Clear", Type.EmptyTypes)
                ?? throw new MissingMethodException(живое.GetType().Name, "Clear");
            var положить = ПоложитьВ(живое.GetType())
                ?? throw new MissingMethodException(живое.GetType().Name, "Add/Enqueue/Push");

            // Позже и НЕ РОЛЬЮ добавленное остаётся: отладочные команды ставит
            // программа, и смена роли их убивать не вправе
            var стало = о.СписокСтало ?? [];
            var поздние = ((IEnumerable)живое).Cast<object?>()
                .Where(x => !Есть(списокБыло, x) && !Есть(стало, x))
                .ToList();
            очистить.Invoke(живое, null);
            foreach (object? x in списокБыло)
                положить.Invoke(живое, [x]);
            foreach (object? x in поздние)
                положить.Invoke(живое, [x]);
        }
    }

    /// <summary>Чем в это собрание кладут: Add, Enqueue или Push.</summary>
    private static MethodInfo? ПоложитьВ(Type тип) =>
        тип.GetMethods(BindingFlags.Instance | BindingFlags.Public)
            .FirstOrDefault(м => м.GetParameters().Length == 1
                                 && м.Name is "Add" or "Enqueue" or "Push");

    private static bool Есть(List<object?> где, object? что) =>
        где.Any(x => ReferenceEquals(x, что) || Equals(x, что));

    private static bool Одно(object? а, object? б) =>
        ReferenceEquals(а, б) || (а is not null && б is not null && а.Equals(б));

    private static bool ОдинСписок(List<object?> а, List<object?> б) =>
        а.Count == б.Count && а.Zip(б).All(п => Одно(п.First, п.Second));

    private static bool ОдинСловарь(List<KeyValuePair<object, object?>> а,
                                    List<KeyValuePair<object, object?>> б)
    {
        if (а.Count != б.Count)
            return false;
        var поКлючу = б.ToDictionary(п => п.Key, п => п.Value);
        return а.All(п => поКлючу.TryGetValue(п.Key, out object? v) && Одно(п.Value, v));
    }

    /// <summary>Одно место, куда роль влезла, и всё, чем это отменяют.</summary>
    private sealed class Откат(string путь, object владелец, FieldInfo поле)
    {
        public string Путь { get; } = путь;
        public object Владелец { get; } = владелец;
        public FieldInfo Поле { get; } = поле;
        public object? Значение { get; set; }
        public bool Вернуть { get; set; }
        public List<Delegate>? Добавленные { get; set; }
        public List<Delegate>? Убранные { get; set; }
        public List<KeyValuePair<object, object?>>? СловарьБыло { get; set; }
        public List<KeyValuePair<object, object?>>? СловарьСтало { get; set; }
        public List<object?>? СписокБыло { get; set; }
        public List<object?>? СписокСтало { get; set; }
    }
}

/// <summary>
/// ЧЕМ КОНЧИЛАСЬ СМЕНА РОЛИ — фактом, а не «применено».
///
/// Три части нарочно врозь: «что бросили» человек читает как потерю и обязан
/// увидеть её ПО ИМЕНИ («карьер отменён»), «что не вернулось» — это отказ, а
/// «что всё равно остаётся при запуске» — не отказ вовсе, а честная граница.
/// Слепи мы их в одну строку — заказчик перестал бы отличать беду от границы.
/// </summary>
/// <param name="Было">Кем бот был. null — роли не было вовсе.</param>
/// <param name="Стало">Кем стал.</param>
/// <param name="Брошено">Что честно остановлено: навык, работа, держатель тела.</param>
/// <param name="НеВернулось">Что откат вернуть не смог. Пусто — вернулось всё.</param>
/// <param name="Тронуто">Сколько мест держала прежняя роль.</param>
/// <param name="Заняло">Сколько заняла смена.</param>
public sealed record СменаРоли(
    string? Было,
    string Стало,
    IReadOnlyList<string> Брошено,
    IReadOnlyList<string> НеВернулось,
    int Тронуто,
    TimeSpan Заняло)
{
    /// <summary>Смена удалась ЦЕЛИКОМ: вернулось всё, что держала прежняя роль.</summary>
    public bool Целиком => НеВернулось.Count == 0;

    /// <summary>
    /// ЧЕГО СМЕНА РОЛИ НА ХОДУ НЕ ДЕЛАЕТ — назвать ПОИМЕННО, а не отделаться
    /// общим «перезапустите бота».
    ///
    /// ЗАЧЕМ ЭТО ОТДЕЛЬНОЕ ЧИСТОЕ ПРАВИЛО. Окно на КАЖДЫЙ поворот ЛЮБОЙ ручки
    /// отвечало «часть настроек подействует после перезапуска бота», ни разу не
    /// назвав, какая именно. Человеку, которому после каждого щелчка говорят
    /// про перезапуск, ничего не остаётся, кроме как повторить это заказом:
    /// «хочется смену настроек и роли без перезапуска». Общее предупреждение
    /// вместо имени — это и есть то, что довело до заказа, и повторять его
    /// новой строкой нельзя.
    ///
    /// Пусто — значит перезапускать НЕЧЕГО, и это тоже надо уметь сказать.
    /// </summary>
    /// <param name="пресетПроситОтладку">
    /// Новый готовый бот просит отладочные команды («!часы», «!копай»), а бот
    /// поднят без них: команды ставит запуск один раз, до выбора роли.
    /// </param>
    /// <param name="словоПриВходе">
    /// Новый готовый бот просит сказать что-то при входе в мир. Вход уже был —
    /// сказано не будет.
    /// </param>
    /// <param name="вМиру">Бот сейчас в мире.</param>
    /// <param name="почемуНеЗапомнится">
    /// <see cref="BotConfig.ПочемуНеЗапомнится"/>: строка запуска сильнее файла
    /// настроек. Это НЕ про сегодня, а про следующий запуск, и путать эти два
    /// «перезапустите» нельзя.
    /// </param>
    public static IReadOnlyList<string> ЧегоСменаНеДелает(
        bool пресетПроситОтладку, IReadOnlyList<string> словоПриВходе, bool вМиру,
        string? почемуНеЗапомнится)
    {
        var строки = new List<string>();
        if (пресетПроситОтладку)
            строки.Add("отладочные команды («!часы», «!копай», «!еда») этот готовый бот просит, " +
                       "а ставит их запуск один раз, до выбора роли — они появятся только " +
                       "при следующем запуске бота");
        if (словоПриВходе.Count > 0 && вМиру)
            строки.Add($"сказать при входе в мир («{string.Join("; ", словоПриВходе)}») " +
                       "уже не выйдет: вход был раньше смены роли");
        if (почемуНеЗапомнится is { Length: > 0 })
            строки.Add(почемуНеЗапомнится);
        return строки;
    }

    /// <summary>
    /// Строки для журнала и для окна. Окно журнал показывает, поэтому это и
    /// есть ответ заказчику: другого пути от бота к окну у смены роли нет.
    /// </summary>
    public IReadOnlyList<string> Словами()
    {
        var строки = new List<string>
        {
            Было is null
                ? $"роль: {Стало}"
                : $"роль сменилась на ходу: {Было} → {Стало} " +
                  $"(снято мест: {Тронуто}, заняло {Заняло.TotalMilliseconds:0} мс)",
        };
        foreach (string брошено in Брошено)
            строки.Add($"смена роли остановила: {брошено}");
        foreach (string беда in НеВернулось)
            строки.Add($"смена роли НЕ вернула: {беда}");
        if (!Целиком)
            строки.Add("прежняя роль вернулась не вся — бот сейчас полубот; " +
                       "перезапустите его, чтобы он поднялся чистым");
        return строки;
    }
}
