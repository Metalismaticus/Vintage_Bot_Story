using System.Reflection;
using System.Text.Json;

namespace VsBotKit;

/// <summary>Роль в каталоге: как зовут, что делает, как создать.</summary>
/// <param name="Id">Короткое имя для настроек и панели («digger», «trader»).</param>
/// <param name="Title">Как показывать человеку («Копатель»).</param>
/// <param name="About">Одна-две фразы о том, чем бот будет заниматься.</param>
/// <param name="Create">Как сделать роль. Каждый вызов даёт новую — роль хранит состояние.</param>
public sealed record RoleEntry(string Id, string Title, string About, Func<BotRole> Create)
{
    /// <summary>
    /// Что должно быть готово, чтобы роль работала: размеченный магазин, дом,
    /// кирка. Панель показывает это рядом с ролью, чтобы человек не гадал,
    /// почему бот «ничего не делает».
    /// </summary>
    public string[] Needs { get; init; } = [];

    /// <summary>
    /// ОТКУДА ЭТА РОЛЬ ВЗЯЛАСЬ. Пусто — приехала с программой (её положило в
    /// каталог само приложение). Иначе — путь к файлу, из которого её
    /// подобрали (<see cref="RoleCatalog.AddFromFolder"/>).
    ///
    /// Наружу это идёт затем, что «своя роль» и «наша роль» ведут себя
    /// одинаково ровно до первой беды: обновление программы заменит НАШИ
    /// файлы и не тронет чужой, а сломанная своя роль выглядит как сломанный
    /// бот. Человек должен видеть, чей это код, не гадая.
    /// </summary>
    public string Source { get; init; } = "";

    public override string ToString() => $"{Id} — {Title}";
}

/// <summary>
/// ЛИЦО РОЛИ: что человек должен знать о ней, ещё НЕ выбрав её.
///
/// ЖИВАЯ ПРОСЬБА ЗАКАЗЧИКА, ради которой заведено: «Не понимаю как выбор роли
/// на что-то влияет, я же думал там будут готовые пресеты, свои настройки,
/// допустим у ии появится токен и т.д. у продавца тоже будут свои». Разница
/// между ролями была настоящей (у копателя 94 своих настройки, у продавца две,
/// у ИИ — свои поставщик и модель), но УВИДЕТЬ её было можно ровно одним
/// способом: перезапустить бота другой ролью и сравнить два окна по памяти.
/// Список ролей при этом стоял в окне без единого числа — три строки описания
/// и ни одной приметы того, чем они отличаются.
/// </summary>
/// <param name="Id">Имя роли для настроек и пресетов.</param>
/// <param name="Title">Как показывать человеку.</param>
/// <param name="Knobs">Все настройки роли по именам.</param>
/// <param name="Own">
/// Настройки, которых нет НИ У ОДНОЙ другой роли каталога, — то самое «своё».
/// </param>
/// <param name="Why">
/// Почему роль не удалось создать и её настройки неизвестны. Пусто — всё вышло.
/// Молчать тут нельзя: пустой список «своего» у живой роли и у несозданной
/// выглядит одинаково, а значит одно из двух было бы враньём.
/// </param>
public sealed record RoleFace(string Id, string Title,
    IReadOnlyList<string> Knobs, IReadOnlyList<string> Own, string Why);

/// <summary>
/// КАТАЛОГ РОЛЕЙ: какие роли вообще бывают у этого бота.
///
/// Зачем. Выбор роли жил цепочкой «если аргумент такой — эта роль, иначе та»
/// в запускающем файле. Пока ролей единицы, это терпимо; но панели настроек надо
/// ПОКАЗАТЬ список ролей, а нейросети — выбрать роль по имени, и каждый из них
/// заводил бы себе вторую такую же цепочку. Здесь список один.
///
/// Каталог — механизм. Какие роли в него положить, решает приложение: сама
/// библиотека ролей не знает и знать не должна.
/// </summary>
public sealed class RoleCatalog
{
    private readonly Dictionary<string, RoleEntry> roles = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>Добавить роль в каталог.</summary>
    public RoleCatalog Add(string id, string title, string about, Func<BotRole> create,
        params string[] needs)
    {
        roles[id] = new RoleEntry(id, title, about, create) { Needs = needs };
        лица = null;   // список ролей изменился — посчитанное «своё» устарело
        return this;
    }

    /// <summary>Все роли по порядку добавления.</summary>
    public IReadOnlyList<RoleEntry> All => roles.Values.ToList();

    /// <summary>Найти роль по имени. null — такой нет.</summary>
    public RoleEntry? Find(string? id) =>
        id is { Length: > 0 } && roles.TryGetValue(id, out var e) ? e : null;

    /// <summary>Есть ли такая роль.</summary>
    public bool Has(string? id) => Find(id) != null;

    /// <summary>Список имён для сообщения об ошибке: «есть такие роли: …».</summary>
    public string Names() => string.Join(", ", roles.Keys);

    // ------------------------------------------------------------------
    //  СВОИ РОЛИ ИЗ ПАПКИ РЯДОМ С ПРОГРАММОЙ
    // ------------------------------------------------------------------

    private readonly List<string> заметки = [];

    /// <summary>
    /// ЧТО СЛУЧИЛОСЬ, ПОКА СОБИРАЛСЯ КАТАЛОГ, — строками для человека.
    ///
    /// Пусто — рассказывать нечего. Всё, что здесь появляется, обязано быть
    /// сказано вслух: «нашёл свою роль», «файл не открылся», «имя занято».
    /// Молча пропущенная роль — это бот, который поднялся не тем, кем его
    /// просили, и об этом никто не узнал.
    /// </summary>
    public IReadOnlyList<string> Notes => заметки;

    /// <summary>
    /// НЕСКОЛЬКО МЕСТ СРАЗУ, и одна и та же папка не называется дважды.
    ///
    /// Мест правда несколько: рядом с программой (там же, где <c>presets</c>),
    /// в папке состояния (контейнер, где рядом с программой писать нельзя) и
    /// рядом с проектом, когда бот запущен из папки сборки — та стирается
    /// пересборкой вместе со всем, что в неё положили. При обычной установке
    /// первые две совпадают, и без этой сверки человек читал бы в журнале один
    /// и тот же путь дважды, будто бот смотрит в два разных места.
    ///
    /// Берём из ВСЕХ папок, а не из первой найденной: свои роли — это не одна
    /// коллекция, а отдельные файлы, и «нашли в одном месте — второе не
    /// смотрим» молча спрятало бы половину.
    /// </summary>
    public int AddFromFolders(params string?[] folders)
    {
        var названные = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        int всего = 0;
        foreach (string? папка in folders)
        {
            if (папка is not { Length: > 0 })
                continue;
            string ключ;
            try
            {
                ключ = Path.TrimEndingDirectorySeparator(Path.GetFullPath(папка));
            }
            catch
            {
                ключ = папка;
            }
            if (названные.Add(ключ))
                всего += AddFromFolder(папка);
        }
        return всего;
    }

    /// <summary>
    /// СВОИ РОЛИ ИЗ ПАПКИ: подобрать все <c>*.dll</c>, что лежат рядом, и
    /// взять из них классы-наследники <see cref="BotRole"/>.
    ///
    /// ЗАЧЕМ ЭТО ПОЯВИЛОСЬ. Заказчик просил «возможность написать код роли и
    /// закинуть в файлы». До этого «своя роль» значила: положить <c>.cs</c> в
    /// исходники приложения, дописать строку в его каталог и ПЕРЕСОБРАТЬ
    /// программу — то есть быть владельцем этих исходников и держать у себя
    /// .NET SDK и установленную игру. Раздаётся же бот одним самодостаточным
    /// файлом, и «закинуть рядом» в нём не работало вовсе.
    ///
    /// ПОЧЕМУ ИМЕННО СОБРАННЫЙ ФАЙЛ, А НЕ ИСХОДНИК. Собрать <c>.cs</c> на
    /// стороне бота нечем: компилятора внутри нет, а тащить его туда — это
    /// десятки мегабайт ради того, что человек и так делает у себя одной
    /// командой <c>dotnet build</c>. Честнее сказать это прямо, чем сделать
    /// вид, что бот «понимает исходники».
    ///
    /// ЧЕГО ЭТО НЕ ДЕЛАЕТ И ЧЕМ ОПАСНО. Взятый файл — это КОД, который пойдёт
    /// в том же процессе, что и бот: он может всё то же, что и сам бот.
    /// Песочницы здесь нет и быть не может (.NET её не даёт), поэтому правило
    /// одно и оно человеческое: класть в эту папку только то, что вы собрали
    /// сами. Каждый взятый файл называется вслух — см. <see cref="Notes"/>.
    /// </summary>
    /// <param name="folder">Папка со своими ролями (её может и не быть).</param>
    /// <returns>Сколько ролей добавлено.</returns>
    public int AddFromFolder(string folder)
    {
        string путь;
        try
        {
            путь = Path.GetFullPath(folder);
        }
        catch (Exception e)
        {
            заметки.Add($"папку своих ролей «{folder}» не понял: {e.Message}");
            return 0;
        }

        if (!Directory.Exists(путь))
            // Молчим НАРОЧНО: у большинства хозяев бота этой папки нет вовсе,
            // и строка «папки нет» в каждом запуске была бы шумом про норму
            return 0;

        string[] файлы;
        try
        {
            файлы = Directory.GetFiles(путь, "*.dll").Order().ToArray();
        }
        catch (Exception e)
        {
            заметки.Add($"папку своих ролей «{путь}» не прочитал: {e.Message}");
            return 0;
        }

        if (файлы.Length == 0)
        {
            заметки.Add($"папка своих ролей «{путь}» пуста — своих ролей не нашёл");
            return 0;
        }

        int всего = 0;
        foreach (string файл in файлы)
            всего += AddFromFile(файл);
        return всего;
    }

    /// <summary>
    /// Взять роли из одного собранного файла. Отдельно от папки затем, что это
    /// та самая единица, о которой человек думает («положил файл — получил
    /// роль»), и проверять её надо тоже поштучно.
    /// </summary>
    public int AddFromFile(string file)
    {
        string имяФайла = Path.GetFileName(file);
        Assembly сборка;
        try
        {
            // LoadFrom, а не LoadFile: зависимости (сам VsBotKit) обязаны
            // разрешиться в ту же сборку, что уже поднята у бота. Иначе
            // «BotRole» чужого файла оказался бы ДРУГИМ типом с тем же именем,
            // и роль честно не подошла бы ни под одну проверку
            сборка = Assembly.LoadFrom(Path.GetFullPath(file));
        }
        catch (Exception e)
        {
            заметки.Add($"свою роль из «{имяФайла}» взять не вышло: {e.Message}");
            return 0;
        }

        // ФАЙЛ МОГ И НЕ ОТКРЫТЬСЯ — .NET отдаёт УЖЕ ПОДНЯТУЮ сборку, если её
        // имя и версия совпали с нашей. Так бывает, когда рядом со своей ролью
        // положили копию библиотеки бота или самой программы: роли возьмутся,
        // но НЕ ИЗ ЭТОГО ФАЙЛА, и правка в нём ничего не изменит. Молчать об
        // этом нельзя — человек правил бы файл и не понимал, почему без толку
        try
        {
            if (сборка.Location is { Length: > 0 } откуда &&
                !string.Equals(Path.GetFullPath(откуда), Path.GetFullPath(file),
                    StringComparison.OrdinalIgnoreCase))
                заметки.Add($"файл «{имяФайла}»: под этим же именем в боте уже поднята " +
                            $"сборка «{откуда}» — роли беру ИЗ НЕЁ, а не из вашего файла. " +
                            "Кладите в папку только свою роль, без копий библиотеки бота");
        }
        catch
        {
            // Сборка без файла на диске (собрана в памяти) — сверять не с чем
        }

        int взято = 0;
        foreach (var тип in ТипыИз(сборка, имяФайла))
        {
            if (WhyNotARole(тип) is { } почему)
            {
                // Молчим о ЧУЖИХ классах: в любом файле их сотни, и жалоба на
                // каждый утопила бы единственную важную строку. Говорим только
                // о том, что похоже на роль, но ею не стало
                if (typeof(BotRole).IsAssignableFrom(тип))
                    заметки.Add($"класс «{тип.Name}» из «{имяФайла}» ролью не стал: {почему}");
                continue;
            }

            BotRole образец;
            try
            {
                образец = (BotRole)Activator.CreateInstance(тип)!;
            }
            catch (Exception e)
            {
                заметки.Add($"роль «{тип.Name}» из «{имяФайла}» не создалась: {e.Message}");
                continue;
            }

            string id = IdOf(тип);
            if (roles.TryGetValue(id, out var занято))
            {
                заметки.Add($"роль «{тип.Name}» из «{имяФайла}» не взял: имя «{id}» уже " +
                            $"занято ролью «{занято.Title}». Переименуйте класс — имя роли " +
                            "берётся от него");
                continue;
            }

            // ИМЯ РОЛИ ДЛЯ ЧЕЛОВЕКА ГОВОРИТ САМА РОЛЬ, и это не мелочь: окно
            // снимает пресет с живой роли, отыскивая её в каталоге по
            // совпадению Title и BotRole.Name (см. ControlPanel.SavePreset).
            // Придумай мы название здесь — снятый пресет получил бы чужое имя
            // роли и при следующем запуске поднял бы другого бота, молча
            roles[id] = new RoleEntry(id, образец.Name,
                $"своя роль из файла «{имяФайла}»", () => (BotRole)Activator.CreateInstance(тип)!)
            {
                Source = Path.GetFullPath(file)
            };
            лица = null;   // список ролей изменился — посчитанное «своё» устарело
            заметки.Add($"своя роль «{id}» ({образец.Name}) из «{имяФайла}»");
            взято++;
        }
        return взято;
    }

    /// <summary>
    /// Типы из сборки, не роняя бота на первом же, чью зависимость не найти.
    ///
    /// <see cref="ReflectionTypeLoadException"/> здесь не беда, а обычное дело:
    /// в чужом файле бывают классы, тянущие пакеты, которых у нас нет. Игра
    /// продолжается с теми типами, что загрузились, а о потерянных говорится
    /// вслух — иначе роль «пропала» бы без единого слова.
    /// </summary>
    private IEnumerable<Type> ТипыИз(Assembly сборка, string имяФайла)
    {
        try
        {
            return сборка.GetTypes();
        }
        catch (ReflectionTypeLoadException e)
        {
            заметки.Add($"в «{имяФайла}» часть классов не загрузилась " +
                        $"({e.LoaderExceptions.Length} шт.): " +
                        string.Join("; ", e.LoaderExceptions
                            .Where(x => x != null).Select(x => x!.Message).Distinct().Take(3)));
            return e.Types.Where(t => t != null).Select(t => t!);
        }
        catch (Exception e)
        {
            заметки.Add($"классы из «{имяФайла}» прочитать не вышло: {e.Message}");
            return [];
        }
    }

    /// <summary>
    /// ПОЧЕМУ ЭТОТ КЛАСС НЕ РОЛЬ. null — роль, брать можно.
    ///
    /// Чистое правило: ни файлов, ни бота — потому и проверяется стендом.
    /// Каждая причина названа словами, которые человек прочтёт у себя в
    /// журнале: «класс не публичный» лечится одним словом в его же коде, а
    /// молчаливый пропуск лечится вечером догадок.
    /// </summary>
    public static string? WhyNotARole(Type? type)
    {
        if (type == null)
            return "класса нет";
        if (!typeof(BotRole).IsAssignableFrom(type))
            return $"он не наследник {nameof(BotRole)}";
        if (type == typeof(BotRole))
            return "это сам BotRole, а не роль";
        if (type.IsAbstract)
            return "класс абстрактный — создать его нечем";
        if (!type.IsPublic && !type.IsNestedPublic)
            return "класс не публичный — снаружи его не создать";
        if (type.IsGenericTypeDefinition)
            return "класс с параметром типа — какой именно роли он равен, сказать нельзя";
        if (type.GetConstructor(Type.EmptyTypes) == null)
            return "у класса нет конструктора без аргументов — бот не знает, что ему передать";
        return null;
    }

    /// <summary>
    /// Имя роли для настроек и пресетов — от имени класса, приведённого к
    /// нижнему регистру. Своего слова у каталога тут нет нарочно: человек
    /// назвал класс сам, и это единственное имя, которое он про свою роль знает.
    /// </summary>
    public static string IdOf(Type type) => type.Name.ToLowerInvariant();

    // ------------------------------------------------------------------
    //  ЧЕМ РОЛИ ОТЛИЧАЮТСЯ ДРУГ ОТ ДРУГА
    // ------------------------------------------------------------------

    private IReadOnlyList<RoleFace>? лица;

    /// <summary>
    /// ЧЕМ КАЖДАЯ РОЛЬ ОТЛИЧАЕТСЯ ОТ ОСТАЛЬНЫХ — списком, до всякого выбора.
    ///
    /// Считается ОДИН раз на СОБРАННЫЙ каталог: имена настроек у роли от
    /// запуска к запуску не меняются (они заданы её классом), а создание роли
    /// стоит конструктора — у роли на нейросети это ещё и клиент SDK. Добавили
    /// роль после — посчитанное забывается: «своё» есть свойство ВСЕГО набора,
    /// и четвёртая роль способна отобрать «своё» у первой.
    /// </summary>
    public IReadOnlyList<RoleFace> Faces() => лица ??= СобратьЛица();

    private IReadOnlyList<RoleFace> СобратьЛица()
    {
        var ручки = new Dictionary<string, IReadOnlyList<string>>(StringComparer.OrdinalIgnoreCase);
        var беды = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);

        foreach (var роль in All)
        {
            try
            {
                ручки[роль.Id] = RoleKnobs.Of(роль.Create()).Select(k => k.Name).ToList();
                беды[роль.Id] = "";
            }
            catch (Exception e)
            {
                // Роль не создалась — честно об этом и говорим. Пустой список
                // «своего» у живой роли и у несозданной выглядит одинаково,
                // и без этой строки одно из двух было бы враньём
                ручки[роль.Id] = [];
                беды[роль.Id] = $"роль не создалась: {e.Message}";
            }
        }

        return All.Select(р => new RoleFace(р.Id, р.Title,
            ручки[р.Id], OnlyHere(р.Id, ручки), беды[р.Id])).ToList();
    }

    /// <summary>
    /// ЧТО У ЭТОЙ РОЛИ СВОЁ: настройки, которых нет ни у одной другой роли
    /// каталога.
    ///
    /// ПОЧЕМУ СРАВНЕНИЕМ, А НЕ «ГДЕ ОБЪЯВЛЕНА». Спросить у свойства, каким
    /// классом оно объявлено, легко — и ответ был бы неверным: роль, собранная
    /// на основе копателя, объявит его настройки не у себя, а человеку они
    /// всё равно «копательские». «Своё» — это то, чего у соседей нет, и никакая
    /// родословная этого не решает.
    ///
    /// Чистое правило: ни ролей, ни отражения — только имена. Потому и
    /// проверяется стендом.
    /// </summary>
    /// <param name="me">Имя роли, про которую спрашивают.</param>
    /// <param name="byRole">Имена настроек каждой роли каталога.</param>
    public static IReadOnlyList<string> OnlyHere(
        string me, IReadOnlyDictionary<string, IReadOnlyList<string>> byRole)
    {
        if (!byRole.TryGetValue(me, out var мои))
            return [];
        var чужие = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var (имя, список) in byRole)
            if (!string.Equals(имя, me, StringComparison.OrdinalIgnoreCase))
                foreach (string ручка in список)
                    чужие.Add(ручка);
        return мои.Where(р => !чужие.Contains(р)).ToList();
    }
}

/// <summary>
/// КАК ЭТА РУЧКА ЗВАЛАСЬ РАНЬШЕ — чтобы переименование не съело чужой пресет.
///
/// ЖИВАЯ БЕДА, РАДИ КОТОРОЙ ЗАВЕДЕНО. Пресет — это ТЕКСТ с именами ручек, и
/// лежит он не только у нас: своя папка пресетов есть у каждого хозяина бота
/// (<see cref="PresetLibrary.Directory"/>), и своё там СТАРШЕ приехавшего с
/// программой. Переименуй мы ручку молча — файл человека остался бы со старым
/// словом, настройка перестала бы применяться, и бот всю ночь работал бы на
/// заводском значении. Для «Смелости» выживальщика это ровно «не прыгать
/// вовсе» (0) против «прыгать и платить здоровьем» — разбитый бот на дне
/// карьера вместо обхода.
///
/// ПОЧЕМУ НЕ МОЛЧА И НЕ НАВСЕГДА. Старое имя понимается, но о нём ГОВОРЯТ
/// вслух — <see cref="RoleKnobs.ApplyAll(BotRole, System.Text.Json.JsonElement,
/// out List{string}, out List{string})"/> отдаёт такие строки отдельным
/// списком, а не вместе с жалобами: жалоба означает «настройка НЕ
/// подействовала», и складывать сюда же «подействовала, но зовётся иначе»
/// значило бы врать в обе стороны разом.
///
/// ЧЕГО ЭТА МЕТКА НЕ ДЕЛАЕТ. Она не переносит имя между РОЛЯМИ: метка живёт на
/// СВОЙСТВЕ, и старое имя понимает только та роль, у которой оно было. Роль, у
/// которой такого имени не бывало, даёт честный отказ «у роли „X“ нет настройки
/// „Y“» вместо тихого применения чужого числа.
///
/// А ЕСЛИ ОДНО И ТО ЖЕ СЛОВО БЫЛО У ДВУХ РОЛЕЙ — каждая заводит СВОЮ метку и
/// понимает его ПО-СВОЕМУ, и это не двусмысленность. Живой случай: «Смелость»
/// была у выживальщика (ступень 0/1/2) и у продавца (хп урона за спрыгивание);
/// каждому она возвращает ЕГО ЖЕ старое число, потому что пресет НАЗЫВАЕТ СВОЮ
/// РОЛЬ и <see cref="PresetLibrary.Build"/> крутит ручки у названной роли —
/// файл выживальщика поднимает выживальщика. Перепутать смыслы может только
/// человек, переложивший строку руками, и об этом ему будет сказано вслух:
/// причина из <see cref="Why"/> обязана называть ЕДИНИЦЫ, а не одно лишь новое
/// имя. Ради этого <see cref="Why"/> и заведён.
/// </summary>
[AttributeUsage(AttributeTargets.Property, AllowMultiple = true, Inherited = true)]
public sealed class KnobWasNamedAttribute(string was) : Attribute
{
    /// <summary>Прежнее имя ручки, как оно написано в уже созданных пресетах.</summary>
    public string Was { get; } = was;

    /// <summary>Почему переименовали — эту причину человек и прочтёт в журнале.</summary>
    public string Why { get; set; } = "";
}

/// <summary>Настраиваемая ручка роли: что можно покрутить снаружи.</summary>
/// <param name="Name">Имя свойства как оно написано в роли («СмелостьВПути»).</param>
/// <param name="Kind">Простое имя типа для панели: «флаг», «число», «строка», «клетка».</param>
/// <param name="Value">Что стоит сейчас.</param>
public sealed record RoleKnob(string Name, string Kind, object? Value)
{
    public override string ToString() => $"{Name} = {Value ?? "не задано"} ({Kind})";
}

/// <summary>
/// РУЧКИ РОЛИ — читать и крутить настройки роли, не зная её типа.
///
/// Зачем это нужно. Настройки у ролей свои и называются по-человечески:
/// «СмелостьВПути», «СобиратьЕду», «МаксимальныйСтолб», «Дом». Панель, пресет и
/// чат должны уметь показать их и поменять — но ни один из троих не должен
/// знать про конкретную роль. Иначе каждая новая роль требовала бы правок в
/// трёх местах, и они бы разъезжались.
///
/// Правило простое: ручка — это ПУБЛИЧНОЕ свойство роли, которое можно
/// записать. Всё остальное роль держит при себе.
/// </summary>
public static class RoleKnobs
{
    /// <summary>Как назвать тип по-человечески — это увидит человек в панели.</summary>
    public static string KindOf(Type t)
    {
        t = Nullable.GetUnderlyingType(t) ?? t;
        if (t == typeof(bool)) return "флаг";
        if (t == typeof(string)) return "строка";
        // Обе клетки — и мировая, и игровая — для человека одно и то же: три
        // числа. Разными их держит ТИП, а не вид в панели: игровые координаты
        // (258, 111, -260) и мировые (512258, 111, 511740) перепутать нельзя,
        // и живьём это уже стоило заказчику склада «за полмиллиона блоков»
        if (t == typeof(BlockPos) || t == typeof(GamePos)) return "клетка";
        if (t.IsEnum) return "выбор";
        if (t == typeof(int) || t == typeof(long)) return "целое";
        if (t == typeof(double) || t == typeof(float)) return "число";
        return t.Name;
    }

    /// <summary>
    /// МЕРИТСЯ ЛИ ЭТА РУЧКА ВООБЩЕ. Меру («секунды», «блоки») имеет только
    /// ЧИСЛО; у клетки, галочки, строки и выбора её не бывает — как не бывает
    /// «трёх координат в секундах» и «галочки в блоках».
    ///
    /// СПРАШИВАЕТСЯ ЗДЕСЬ, А НЕ В ПАНЕЛИ, потому что слова видов родились
    /// строчкой выше, в <see cref="KindOf"/>: разъедься эти два места — и
    /// панель молча начала бы мерить то, чего не меряют.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ради которого правило записано в код, а не в дисциплину
    /// пишущих. Под полем «Склад» — под ТРЕМЯ КООРДИНАТАМИ — у стражника,
    /// продавца, ИИ и выживальщика стояла подпись «секунды»: в док-строке
    /// «Склада» перечислены соседние ручки, «(СкладНеДальшеЧем, СекундНаРейс,
    /// опись)», и искатель меры принял «, секунднарейс» за «, секунд». Это та
    /// самая путаница, за которую заказчик уже заплатил складом «за полмиллиона
    /// блоков»: человек читает подпись под полем и вписывает в него числа с
    /// экрана игры. Переписать одну док-строку значило бы ждать, пока кто-нибудь
    /// напишет «, секунд…» в следующем описании клетки.
    /// </summary>
    public static bool Меряется(string? вид) => вид is "целое" or "число";

    /// <summary>
    /// ИЗ ЧЕГО ВЫБИРАТЬ, если ручка — «выбор». Пусто — выбирать не из чего,
    /// и окно покажет обычное поле.
    ///
    /// ЖИВАЯ БЕДА, РАДИ КОТОРОЙ ЗАВЕДЕНО. Заказчик 16.08: «не идет домой при
    /// бездействии, настройку вроде включил». Включать там было нечего: «БезДела»
    /// — перечисление, а окно показывало его ПУСТОЙ СТРОКОЙ ВВОДА, куда слово
    /// («Домой», «Бродить», «Выйти») надо было угадать и набрать вслепую. В
    /// журнале за все прогоны стоит одно и то же «без дела 60 с — стою, так
    /// настроено»: набранное либо не набиралось вовсе, либо отвергалось
    /// Enum.Parse. Список из четырёх слов человек не угадывает — он его видит.
    ///
    /// То же самое окно уже умело для поставщика нейросети, но умело ПО ИМЕНИ
    /// ручки («Поставщик»), то есть ровно для одной. Здесь это правило типа, и
    /// оно одно на все перечисления библиотеки — «Мстить», «БезДела» и те, что
    /// заведут после нас.
    /// </summary>
    public static IReadOnlyList<string> ChoicesOf(Type? type)
    {
        if (type == null)
            return [];
        Type t = Nullable.GetUnderlyingType(type) ?? type;
        return t.IsEnum ? Enum.GetNames(t) : [];
    }

    /// <summary>
    /// КАК ЗОВЁТСЯ РУЧКА, КОТОРОЙ КРУТИТСЯ ВОТ ЭТО. null — у роли такой нет.
    ///
    /// ЖИВАЯ ПРОСЬБА ЗАКАЗЧИКА: «лучше отображать в вебформе тоже, придумай
    /// красиво в конструкторе задачи» — а вместе с разбором заказа человеку
    /// нужна рядом и та ручка, которой этот разбор меняется
    /// («ВЧёмСчитатьМеталл»: считать слитками или штуками).
    ///
    /// СПРАШИВАЕМ ПО ТИПУ, А НЕ ПО ИМЕНИ, и это не изящество. Имя ручки —
    /// ПОЛИТИКА РОЛИ: копатель зовёт её «ВЧёмСчитатьМеталл», другая роль назовёт
    /// иначе или не заведёт вовсе. Напиши окно это имя у себя — оно решало бы за
    /// роль, как ей называть свои настройки (правило 1), и молча перестало бы
    /// работать в тот день, когда ручку переименуют. Тип же (MetalCount)
    /// принадлежит библиотеке и сменить его молча нельзя.
    ///
    /// Ручек одного типа у роли может оказаться и две — тогда честно НИ ОДНОЙ:
    /// угадывать, какую из них человек имел в виду, значит крутить не ту.
    /// </summary>
    public static string? NameOfType(BotRole? role, Type type)
    {
        if (role == null)
            return null;
        var подходят = Writable(role)
            .Where(p => (Nullable.GetUnderlyingType(p.PropertyType) ?? p.PropertyType) == type)
            .Select(p => p.Name)
            .ToList();
        return подходят.Count == 1 ? подходят[0] : null;
    }

    private static IEnumerable<PropertyInfo> Writable(BotRole role) =>
        role.GetType()
            .GetProperties(BindingFlags.Public | BindingFlags.Instance)
            .Where(p => p.CanRead && p.CanWrite && p.GetIndexParameters().Length == 0);

    /// <summary>
    /// Есть ли у роли такая ручка. Регистр не важен — как и при повороте.
    ///
    /// Спрашивают этим КОМАНДЫ ЧАТА, и вот зачем. Команда «!месть догнать 40»
    /// и ручка роли «Мстить» правят ОДНО И ТО ЖЕ число в способности, но живут
    /// врозь: ручка доносится заново на каждый поворот ЛЮБОЙ соседней ручки, и
    /// сказанное в чат стиралось следующим же движением ползунка — МОЛЧА.
    /// Теперь команда сперва спрашивает, есть ли у роли эта ручка: есть —
    /// пишет в неё (тогда сказанное переживёт и панель покажет то же самое),
    /// нет — правит способность и ЧЕСТНО ГОВОРИТ, что это до первой настройки.
    /// </summary>
    public static bool Has(BotRole? role, string? name) =>
        role != null && name is { Length: > 0 } &&
        Writable(role).Any(p => string.Equals(p.Name, name, StringComparison.OrdinalIgnoreCase));

    /// <summary>
    /// СЛОВА, ПО КОТОРЫМ ИМЯ ЧИТАЕТСЯ КАК СЕКРЕТ. Список один на весь проект
    /// нарочно: разойдись он на два, второй однажды отстанет — и ровно та
    /// ручка, ради которой закон писан, проедет мимо.
    ///
    /// Оба языка здесь не для красоты: имена ручек в этом проекте русские
    /// («ПарольПрокси»), а имена в чужих ролях и в чужих сборках — английские
    /// («ApiToken»). Пропусти мы половину — закон держал бы половину.
    /// </summary>
    private static readonly string[] СловаСекретов =
    [
        "ключ", "key", "токен", "token", "пароль", "password", "passwd",
        "секрет", "secret", "credential"
    ];

    /// <summary>
    /// ПОХОЖЕ ЛИ ИМЯ НАСТРОЙКИ НА СЕКРЕТ — чистое правило, потому и
    /// проверяется стендом без бота и без файлов.
    ///
    /// ЗАЧЕМ ЭТО ПРАВИЛО ВООБЩЕ ЕСТЬ. Ручка роли — это не просто поле в окне.
    /// Она уходит ДВУМЯ дорогами сразу, и обе — наружу: <see
    /// cref="PresetLibrary.Capture"/> кладёт ВСЕ ручки в файл готового бота
    /// (файлами обмениваются, их прикладывают к письмам и кладут в git), а
    /// панель отдаёт их же значения в браузер. Поэтому секрету — ключу
    /// нейросети, паролю прокси, токену — ручкой роли быть нельзя НИКОГДА:
    /// он живёт в переменной окружения, а окно показывает только «задан или
    /// нет» (<see cref="AiSettings"/>, <see cref="Panel.PanelSettings.Public"/>).
    ///
    /// ПОЧЕМУ ЗАПРЕТ, А НЕ ПРЯТАНЬЕ ЗНАЧЕНИЯ. Спрятать значение на выходе
    /// значило бы завести ВТОРОЙ механизм секретов рядом с первым и молча
    /// оставить человеку ручку, в которую он вписывает пароль, думая, что
    /// тот куда-то доедет. Честнее не дать такой ручке появиться: беда
    /// ловится на стенде, у автора роли, а не на чужом диске.
    ///
    /// ПОЧЕМУ СПРАШИВАЕТСЯ ЕЩЁ И ВИД РУЧКИ. Секрет — это ТЕКСТ; числом,
    /// флагом, клеткой или выбором из списка доступ не выдают. А слово
    /// «токен» в этом проекте живёт ДВУМЯ жизнями: у нейросети токен — это
    /// единица счёта, и ручка «ТокеновВСутки» (целое) — потолок трат, а не
    /// пропуск. Правило, не знающее вида, объявило бы секретом денежный
    /// лимит — и его бы ослабили, выкинув «токен» из слов; тогда настоящий
    /// «ТокенДоступа» проехал бы мимо. Вид ручки разводит эти два случая
    /// честно, не трогая список слов.
    /// </summary>
    /// <param name="name">Имя настройки роли.</param>
    /// <param name="kind">
    /// Вид ручки, как его называет <see cref="KindOf"/> («строка», «целое»…).
    /// Не сказан — судим по одному имени: так спрашивает чистое правило.
    /// </param>
    public static bool LooksSecret(string? name, string? kind = null) =>
        name is { Length: > 0 } &&
        (kind is null || kind == "строка") &&
        СловаСекретов.Any(с => name.Contains(с, StringComparison.OrdinalIgnoreCase));

    /// <summary>
    /// ЧТО СКАЗАТЬ ЧЕЛОВЕКУ, КОГДА ОДНО И ТО ЖЕ ЧИСЛО ПРАВЯТ ИЗ ДВУХ МЕСТ —
    /// чистое правило, без бота и без ролей, потому его и можно проверить.
    ///
    /// СТАРШЕ — НАСТРОЙКА РОЛИ, и вот почему. Её видно в окне управления, она
    /// уходит в пресет и переживает перезапуск; слово, сказанное в чат, не
    /// видно нигде. А главное — роль доносит СВОИ ручки до способностей заново
    /// на каждый поворот ЛЮБОЙ соседней ручки, так что сказанное мимо неё
    /// стиралось следующим же движением ползунка. МОЛЧА, и это худшее.
    ///
    /// Поэтому ответов ровно три, и молчаливого среди них нет:
    ///   • ручка у роли есть и повернулась — сказанное записано и переживёт;
    ///   • ручка есть, но повернуть не вышло — названа причина, и способность
    ///     НЕ тронута (иначе окно показывало бы одно, а бот делал другое);
    ///   • ручки у роли нет — правка легла прямо в способность, и сказано, чего
    ///     ей недостаёт.
    ///
    /// ТРЕТИЙ ОТВЕТ НЕ ПУГАЕТ ЗРЯ, и это важно. Раз ручки нет, то и стирать
    /// сказанное некому: роль доносит только СВОИ ручки. Значит правда тут не
    /// «пропадёт через минуту», а «нигде не записано»: в окне её не видно, в
    /// пресет она не уйдёт и перезапуска не переживёт. Обещать «до следующей
    /// настройки роли» в этом случае было бы такой же неправдой, как молчать.
    /// </summary>
    /// <param name="knob">Имя ручки роли («Мстить»).</param>
    /// <param name="roleName">Как зовут роль — для честного «у роли „X“ нет».</param>
    /// <param name="hasKnob">Есть ли у роли такая ручка.</param>
    /// <param name="complaint">Жалоба поворота или null, если всё вышло.</param>
    public static string SayWhoKeeps(string knob, string? roleName, bool hasKnob, string? complaint)
    {
        if (!hasKnob)
            return $" Поправил на живую: у роли «{roleName ?? "без роли"}» настройки " +
                   $"«{knob}» нет, поэтому в окне управления этого не видно, в пресет оно " +
                   "не уйдёт и перезапуска не переживёт.";
        return complaint != null
            ? $" Настройку роли «{knob}» повернуть не вышло: {complaint}. Способность не " +
              "трогал — иначе окно показывало бы одно, а бот делал другое."
            : $" Записал в настройку роли «{knob}»: это видно в окне управления и " +
              "переживёт следующую настройку роли.";
    }

    /// <summary>
    /// Повернуть ручку ГОТОВЫМ ЗНАЧЕНИЕМ, а не разобранным из JSON. Возвращает
    /// жалобу или null, если всё вышло.
    ///
    /// Нужно тому, кто зовёт из кода (команда чата, навык): у него на руках уже
    /// число, флаг или значение перечисления, и городить ради него JSON —
    /// значит городить второй разбор. Внутри — ТОТ ЖЕ <see cref="Apply(BotRole,
    /// string, JsonElement)"/>: правила преобразования, жалобы и донесение до
    /// механизма (OnKnobsChanged) обязаны быть одни и те же, откуда бы ручку ни
    /// повернули.
    /// </summary>
    public static string? Set(BotRole role, string name, object? value)
    {
        try
        {
            // Через JSON нарочно: у перечислений на этом пути работает их
            // собственный преобразователь (RevengePolicy пишется словом
            // «Догонять», а не номером), и второй такой таблицы заводить негде
            return Apply(role, name, JsonSerializer.SerializeToElement(value));
        }
        catch (Exception e)
        {
            return $"настройка «{name}»: {e.Message}";
        }
    }

    /// <summary>
    /// КАКОГО ТИПА ЭТА РУЧКА. null — сказать нечего, и врать не будем.
    ///
    /// Нужен там, где вида («клетка») мало: игровые координаты (258, 111, −260)
    /// и мировые (512258, 111, 511740) — это одно и то же место, но разными
    /// числами, а вид у них ОДИН. Живьём это уже стоило заказчику склада «за
    /// полмиллиона блоков», поэтому спрашивающих двое (подпись в окне и память
    /// мест), а правило — одно, вот это.
    /// </summary>
    public static Type? TypeOf(BotRole role, string name)
    {
        try
        {
            return role.GetType().GetProperty(name,
                BindingFlags.Public | BindingFlags.Instance | BindingFlags.IgnoreCase)?.PropertyType;
        }
        catch (AmbiguousMatchException)
        {
            // Две ручки, различающиеся только регистром: сказать, в каких
            // координатах, честно нельзя — и мы не говорим
            return null;
        }
    }

    /// <summary>Что у этой роли можно покрутить и что стоит сейчас.</summary>
    public static IReadOnlyList<RoleKnob> Of(BotRole role) =>
        Writable(role)
            .Select(p => new RoleKnob(p.Name, KindOf(p.PropertyType), Read(role, p)))
            .ToList();

    private static object? Read(BotRole role, PropertyInfo p)
    {
        try
        {
            object? value = p.GetValue(role);
            // Клетку отдаём тремя числами: так её понимает и панель, и файл
            return value switch
            {
                BlockPos pos => new { x = pos.X, y = pos.Y, z = pos.Z },
                GamePos game => new { x = game.X, y = game.Y, z = game.Z },
                _ => value
            };
        }
        catch
        {
            return null;
        }
    }

    /// <summary>
    /// Повернуть одну ручку. Возвращает жалобу или null, если всё вышло.
    ///
    /// Жалоба, а не исключение: настроек в пресете бывает десяток, и из-за
    /// одной опечатки нельзя терять остальные девять. Но и молчать нельзя —
    /// иначе бот всю ночь работает не так, как написано в файле.
    /// </summary>
    public static string? Apply(BotRole role, string name, JsonElement value) =>
        Apply(role, name, value, out _);

    /// <summary>
    /// То же самое, но с ответом о ПЕРЕИМЕНОВАНИИ: <paramref name="renamed"/> —
    /// строка «настройка звалась так, а зовётся эдак» или null, если имя
    /// нынешнее.
    ///
    /// Отдельно от жалобы НАРОЧНО. Жалоба значит «настройка не подействовала», и
    /// тот, кто её печатает, говорит «отвергнуто» (см. PresetLibrary.Build).
    /// Переименованная ручка ПОДЕЙСТВОВАЛА — назвать это отказом было бы враньём,
    /// а промолчать значило бы оставить человека со старым словом в файле до
    /// того дня, когда мы перестанем его понимать.
    /// </summary>
    public static string? Apply(BotRole role, string name, JsonElement value, out string? renamed)
    {
        renamed = null;
        var p = Writable(role).FirstOrDefault(
            x => string.Equals(x.Name, name, StringComparison.OrdinalIgnoreCase));

        // ПРЯМОЕ ИМЯ ВСЕГДА СТАРШЕ СТАРОГО, и порядок этих двух поисков — не
        // вкус: доведись когда-нибудь освободившемуся старому имени достаться
        // другой ручке, живая настройка обязана победить свою же историю
        if (p == null)
            foreach (var x in Writable(role))
                if (WasNamed(x, name) is { } метка)
                {
                    p = x;
                    renamed = $"настройка «{name}» теперь зовётся «{x.Name}»" +
                              (метка.Why.Length > 0 ? $" ({метка.Why})" : "") +
                              ". Значение применено по старому имени; поправьте его в пресете, " +
                              "пока старое ещё понимается";
                    break;
                }

        if (p == null)
            return $"у роли «{role.Name}» нет настройки «{name}»";

        try
        {
            object? parsed = Convert(p.PropertyType, value);
            if (parsed == null && Nullable.GetUnderlyingType(p.PropertyType) == null &&
                p.PropertyType.IsValueType)
            {
                // «Переименована» значит «ПРИМЕНЕНА под старым именем». Не
                // подействовала — значит и говорить не о чем, иначе журнал
                // отчитается о новом имени той настройки, которой в боте нет
                renamed = null;
                return $"настройке «{name}» нужно значение типа {KindOf(p.PropertyType)}";
            }
            p.SetValue(role, parsed);
            // ЗА ЭТИМ ЗНАЧЕНИЕМ ТЕПЕРЬ СТОИТ ЧЕЛОВЕК, А НЕ ДОГАДКА БОТА.
            // Сюда сходятся ВСЕ повороты — окно, пресет, слово в чат, — и
            // другого места, где пометку можно снять честно, нет. Не снимай мы
            // её здесь, и заданный руками склад тоже перестал бы попадать в
            // файл: то есть вернулась бы вторая половина жалобы «запоминание
            // не работает у дома и склада» (разбор — BotRole.ПометитьДогадку)
            role.ПометитьДогадку(p.Name, догадка: false);
            // Значение легло в роль — теперь оно обязано доехать до механизма.
            // Пока этого вызова не было, повёрнутое ПОСЛЕ сборки роли (а панель
            // крутит ручки именно так, уже в мире) не действовало вовсе
            ДонестиИЗапомнить(role);
            return null;
        }
        catch (Exception e)
        {
            renamed = null;
            return $"настройка «{name}»: {e.Message}";
        }
    }

    /// <summary>
    /// ДОНЕСТИ ПОВЁРНУТОЕ ДО МЕХАНИЗМА — И ЗАПОМНИТЬ, ЧТО ИМЕННО ТРОНУЛОСЬ.
    ///
    /// Донесение и запись в след роли — ОДНО действие, и разделять их нельзя.
    /// Роль живёт до первой смены роли, а всё, что она тронула, при смене
    /// возвращается механически (<see cref="СледРоли"/>). След снимается
    /// разницей вокруг сборки роли, и поворот ручки ПОСЛЕ сборки в эту разницу
    /// не попадает: ручка, чьё заводское значение совпадает с заводским
    /// значением механизма, при сборке ничего не меняет — а повёрнутая в окне
    /// меняет, и меняет навсегда. Так читерское зрение копателя и переехало бы
    /// на стражника, у которого такой ручки нет вовсе.
    ///
    /// Место одно, потому что дверь одна: сюда сходятся и окно
    /// (<c>ControlPanel.SetKnob</c>), и пресет (<see cref="ApplyAll(BotRole,
    /// JsonElement, out List{string})"/>), и слово в чате.
    /// </summary>
    private static void ДонестиИЗапомнить(BotRole role)
    {
        if (role.Хозяин is { } бот)
            бот.ЗаписатьВСлед(role.OnKnobsChanged);
        else
            role.OnKnobsChanged();   // роль ещё не на боте: пресет крутит её до UseRole
    }

    /// <summary>
    /// Звалась ли эта ручка когда-то так. Метка на свойстве — единственное
    /// место, где живёт история имени: таблица «старое → новое» в панели или в
    /// пресетах была бы вторым таким местом и однажды отстала бы от кода.
    /// </summary>
    private static KnobWasNamedAttribute? WasNamed(PropertyInfo p, string name) =>
        p.GetCustomAttributes<KnobWasNamedAttribute>(inherit: true)
            .FirstOrDefault(a => string.Equals(a.Was, name, StringComparison.OrdinalIgnoreCase));

    /// <summary>
    /// Как ручки этой роли звались раньше: «старое имя → нынешнее».
    ///
    /// Нужно проверкам: старое имя, совпавшее с ЖИВОЙ ручкой той же роли, — это
    /// не переименование, а ловушка (одно слово, два хозяина), и поймать её надо
    /// на стенде, а не в чужом пресете.
    /// </summary>
    public static IReadOnlyList<(string Was, string Now)> Renames(BotRole role) =>
        Writable(role)
            .SelectMany(p => p.GetCustomAttributes<KnobWasNamedAttribute>(inherit: true)
                .Select(a => (a.Was, Now: p.Name)))
            .ToList();

    private static object? Convert(Type target, JsonElement value)
    {
        Type t = Nullable.GetUnderlyingType(target) ?? target;

        if (value.ValueKind == JsonValueKind.Null)
            return null;

        if (t == typeof(bool))
            return value.ValueKind switch
            {
                JsonValueKind.True => true,
                JsonValueKind.False => false,
                JsonValueKind.String => bool.Parse(value.GetString()!),
                JsonValueKind.Number => value.GetDouble() != 0,
                _ => throw new FormatException("нужно да или нет")
            };

        if (t == typeof(string))
            return value.ValueKind == JsonValueKind.String ? value.GetString() : value.ToString();

        if (t == typeof(int)) return value.ValueKind == JsonValueKind.String
            ? int.Parse(value.GetString()!) : value.GetInt32();
        if (t == typeof(long)) return value.GetInt64();
        if (t == typeof(double)) return value.ValueKind == JsonValueKind.String
            ? double.Parse(value.GetString()!) : value.GetDouble();
        if (t == typeof(float)) return (float)value.GetDouble();

        if (t.IsEnum)
            return Enum.Parse(t, value.GetString() ?? value.ToString(), ignoreCase: true);

        if (t == typeof(BlockPos) || t == typeof(GamePos))
        {
            if (value.ValueKind != JsonValueKind.Object)
                throw new FormatException("клетка задаётся как {\"x\": …, \"y\": …, \"z\": …}");
            int Get(string n) => value.TryGetProperty(n, out var v) && v.TryGetInt32(out int i)
                ? i
                : throw new FormatException($"в клетке не хватает «{n}»");
            return t == typeof(GamePos)
                ? new GamePos(Get("x"), Get("y"), Get("z"))
                : new BlockPos(Get("x"), Get("y"), Get("z"));
        }

        throw new FormatException($"такие настройки бот менять не умеет ({t.Name})");
    }

    /// <summary>
    /// Повернуть все ручки из раздела настроек. Возвращает, сколько получилось;
    /// все жалобы складываются в <paramref name="problems"/>.
    /// </summary>
    public static int ApplyAll(BotRole role, JsonElement settings, out List<string> problems) =>
        ApplyAll(role, settings, out problems, out _);

    /// <summary>
    /// То же самое, но старые имена ручек отдаются ОТДЕЛЬНЫМ списком
    /// (<paramref name="renamed"/>), а не вместе с жалобами.
    ///
    /// Два списка, а не один, потому что слова у них разные и оба нужны:
    /// жалоба — «настройка НЕ подействовала, разбирайтесь»; переименование —
    /// «подействовала, но в файле старое слово, поправьте на досуге». Сложи их
    /// в кучу — и тот, кто печатает «отвергнуто N», соврёт человеку про
    /// работающую настройку.
    /// </summary>
    public static int ApplyAll(BotRole role, JsonElement settings,
        out List<string> problems, out List<string> renamed)
    {
        problems = [];
        renamed = [];
        if (settings.ValueKind != JsonValueKind.Object)
            return 0;

        int applied = 0;
        var проблемы = problems;
        var переименованные = renamed;

        // ПАЧКА ПИШЕТСЯ В СЛЕД РОЛИ ОДНОЙ ЗАПИСЬЮ. Пресет крутит по сотне ручек
        // за раз, а каждая запись в след — это перечитывание полей бота; сотня
        // перечитываний подряд превратила бы «применить готового бота» в
        // секунды ожидания на ровном месте. Внутри Apply вложенная запись
        // распознаётся и не заводится (СледРоли.Дописать)
        void Пачкой()
        {
            foreach (var field in settings.EnumerateObject())
            {
                string? complaint = Apply(role, field.Name, field.Value, out string? старое);
                if (старое != null)
                    переименованные.Add(старое);
                if (complaint == null)
                    applied++;
                else
                    проблемы.Add(complaint);
            }
        }

        if (role.Хозяин is { } бот)
            бот.ЗаписатьВСлед(Пачкой);
        else
            Пачкой();
        return applied;
    }
