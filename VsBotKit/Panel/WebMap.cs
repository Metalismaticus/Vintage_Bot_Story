using System.Globalization;
using System.Text.RegularExpressions;

namespace VsBotKit.Panel;

/// <summary>
/// СЕТКА ПЛИТОК ВЕБ-КАРТЫ СЕРВЕРА — то, что карта сама про себя рассказывает
/// файлом <c>worldExtent.js</c>.
///
/// ОТКУДА ЭТИ ПОЛЯ. Карта сервера (мод WebCartographer, см.
/// <see cref="WebMapRules"/>) выкладывает рядом со страницей файл вида:
/// <code>
/// var vsWorldGrid = new ol.tilegrid.TileGrid({
///     extent: [-1024000,-1024000,1024000,1024000],
///     origin: [-511997,512000],
///     resolutions: [512,256,128,64,32,16,8,4,2,1],
///     tileSize: [256, 256]
/// });
/// </code>
/// Ничего из этого мы не выдумываем и не подставляем «по умолчанию»: у каждого
/// мира свой спавн и свои уровни, и угаданное число сдвинуло бы всю картинку.
/// Нет файла — нет и подложки (см. <see cref="WebMapSource"/>).
/// </summary>
/// <param name="OriginX">
/// Левый край сетки в координатах карты. Он равен МИНУС X спавна: карта
/// вычитает спавн так же, как игра, поэтому её координаты — ИГРОВЫЕ.
/// </param>
/// <param name="OriginY">
/// Верхний край сетки в координатах карты. Ось Y у карты смотрит ВВЕРХ, а
/// игровая Z — вниз по экрану, поэтому mapY = −gameZ (см. <see cref="WebMapRules"/>).
/// </param>
/// <param name="Resolutions">
/// Сколько игровых блоков в одном пикселе на каждом уровне. Номер уровня —
/// это и есть номер в этом списке: он же стоит в адресе плитки.
/// </param>
/// <param name="TileWidth">ширина плитки в пикселях (у WebCartographer 256)</param>
/// <param name="TileHeight">высота плитки в пикселях</param>
public readonly record struct WebMapGrid(
    double OriginX, double OriginY, IReadOnlyList<double> Resolutions,
    int TileWidth, int TileHeight)
{
    /// <summary>Сколько уровней у этой карты (самый подробный — последний).</summary>
    public int Levels => Resolutions.Count;

    public override string ToString() =>
        $"начало ({OriginX}, {OriginY}), уровней {Levels}, плитка {TileWidth}×{TileHeight}";
}

/// <summary>
/// Одна плитка карты сервера — В ИГРОВЫХ КООРДИНАТАХ, а не в долях окна.
///
/// ПОЧЕМУ ИМЕННО В ИГРОВЫХ, И ПОЧЕМУ ЭТО НЕ МЕЛОЧЬ. Живой прогон 15.08:
/// «карта не отображается нормально, которая с вебсайта другого, полэкрана
/// только». На снимке видно главное: метки бота и склада стоят по всей высоте
/// окна, а картинки карты — только в его части.
///
/// Разбор: место плитки раньше приходило ДОЛЕЙ ОКНА, а окно едет за ботом.
/// Бот шагнул — доли у ВСЕХ плиток стали другими, страница сочла подложку
/// сменившейся и собрала слой заново. Пересобранный слой — это новые картинки
/// для браузера: те, что ещё качались, обрывались на полпути и начинали
/// сначала. У карты сервера плитка весит под сотню килобайт, а окно
/// опрашивается раз в три секунды, — и пока бот копает дорогу, НИ ОДНА плитка
/// докачаться не успевает. Отсюда и «полэкрана»: успели те, что поближе.
///
/// Игровые координаты этого не знают вовсе: у плитки они те же и на первом
/// шаге, и на сотом. Едет теперь ОКНО (viewBox), а картинки стоят на месте —
/// как им и положено, они же про место в мире, а не про наш взгляд на него.
/// </summary>
/// <param name="Level">номер уровня — он же папка в адресе плитки</param>
/// <param name="Col">номер плитки поперёк (первое число в имени файла)</param>
/// <param name="Row">номер плитки вниз (второе число в имени файла)</param>
/// <param name="Url">готовый адрес картинки</param>
/// <param name="GameX">игровой X левого края плитки</param>
/// <param name="GameZ">
/// игровой Z ВЕРХНЕГО края плитки. Именно Z, а не высота: на карте вниз по
/// экрану идёт Z, и перепутать её с Y — та самая ошибка, из-за которой карта
/// молча показывает не то место.
/// </param>
/// <param name="GameW">ширина плитки в игровых блоках</param>
/// <param name="GameH">высота плитки в игровых блоках (по оси Z)</param>
public readonly record struct WebMapTile(int Level, int Col, int Row, string Url,
    double GameX, double GameZ, double GameW, double GameH);

/// <summary>
/// РЕШЁТКА ПЛИТОК ПОД ОКНОМ — номера столбцов и строк, накрывающие окно от края
/// до края. Границы ВКЛЮЧАЮЩИЕ с обеих сторон.
///
/// Заведено затем, чтобы номера считались в одном месте
/// (<see cref="WebMapRules.Lattice"/>), а <see cref="WebMapRules.Tiles"/> и
/// замер покрытия <see cref="WebMapRules.Cover"/> оба спрашивали ЕЁ. Разойдись
/// эти два счёта — замер бодро подтверждал бы «накрыто целиком» о подложке с
/// белой полосой у кромки, а именно на это заказчик и жалуется.
/// </summary>
/// <param name="Level">уровень, для которого посчитана решётка (уже прижатый к списку)</param>
/// <param name="StepX">сколько игровых блоков в плитке поперёк</param>
/// <param name="StepZ">сколько игровых блоков в плитке вниз (по оси Z)</param>
public readonly record struct WebMapLattice(int Level, int ColFrom, int ColTo,
    int RowFrom, int RowTo, double StepX, double StepZ);

/// <summary>
/// ЗАМЕР ПОКРЫТИЯ ПОДЛОЖКИ: сколько клеток решётки накрывают окно и сколько из
/// них вправду попало в запрос.
///
/// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЭТО ЕСТЬ. Заказчик 16.08 дословно: «карта не на
/// всю зону». Ему дважды докладывали «готово», и дважды живьём было сломано —
/// поэтому здесь не слова, а число, и оно уходит и в окно, и в тест.
/// </summary>
/// <param name="Need">клеток решётки под окном — столько картинок нужно, чтобы накрыть его целиком</param>
/// <param name="Asked">сколько из них вправду запрошено у карты сервера</param>
/// <param name="Beyond">
/// Сколько из них лежат за краем выгруженного мира (отрицательный номер). Это
/// НЕ недостача: картинки там нет и быть не может, и просить её значило бы
/// стучаться к чужому серверу заведомо зря.
/// </param>
public readonly record struct WebMapCover(long Need, long Asked, long Beyond)
{
    /// <summary>
    /// Сколько клеток окна остались без картинки НЕ ПО ВИНЕ ВЫГРУЗКИ. Больше
    /// нуля — это и есть «карта не на всю зону», и об этом говорится вслух.
    /// </summary>
    public long Missing => Math.Max(0, Need - Asked - Beyond);

    /// <summary>Подложка накрывает окно целиком.</summary>
    public bool Whole => Need > 0 && Missing == 0;

    public override string ToString() =>
        $"надо {Need}, запрошено {Asked}, за краем мира {Beyond}, не хватает {Missing}";
}

/// <summary>
/// КАРТА СЕРВЕРА ПОД НАШИМИ ТОЧКАМИ: чистые правила про то, как её адрес
/// превратить в подложку и в ссылку.
///
/// ЗАКАЗ ЗАКАЗЧИКА ДОСЛОВНО: «под вебкартой я имел ввиду поддержку карты по
/// типу https://map.tops.vintagestory.at/?x=0&amp;y=0&amp;zoom=5». То есть не
/// нашу самодельную картинку, а КАРТУ САМОГО СЕРВЕРА, и на ней — метку бота.
///
/// ЧТО ЭТО ЗА КАРТА (разобрано по самой карте и по её исходникам, не выдумано):
///   • мод <b>WebCartographer</b> (Th3Dilli, Zadak, Drakker),
///     https://gitlab.com/th3dilli_vintagestory/WebCartographer — он выгружает
///     из сохранёнки мира готовый набор картинок и статическую страницу;
///   • страницу рисует OpenLayers (<c>lib/ol.js</c>), плитки лежат по адресу
///     <c>&lt;карта&gt;/data/world/&lt;уровень&gt;/&lt;столбец&gt;_&lt;строка&gt;.png</c>,
///     256×256 пикселей;
///   • сетку уровней карта публикует сама файлом <c>worldExtent.js</c>
///     (см. <see cref="WebMapGrid"/>);
///   • адрес вида <c>?x=…&amp;y=…&amp;zoom=…</c> принимает ИГРОВЫЕ координаты:
///     сама карта в окошке «Move to coordinates» пишет «X,Z in game
///     coordinates: 2050,6900», а её скрипт кладёт <c>cy = -args.get('y')</c>,
///     то есть <c>y</c> в адресе — это игровая Z.
///
/// ПОЛОЖЕНИЯ ЖИВЫХ ИГРОКОВ КАРТА НЕ ОТДАЁТ. Это выгрузка мира, а не живая
/// связь: у TOPS внизу страницы прямо написана дата последней выгрузки. Живые
/// точки умеет отдельный мод WebCartographerSync — он поднимает СВОЮ дверь на
/// сервере игры (порт игры + 1) и в состав карты не входит; на странице мода
/// сказано, что для WebCartographer это пока не работает. Поэтому чужих
/// игроков панель на карте не показывает и показывать не может — а наш бот
/// рисуется нашими же координатами, которые мы и так знаем.
///
/// ПОЧЕМУ ПЛИТКИ, А НЕ ЧУЖАЯ БИБЛИОТЕКА. Панель обязана работать на машине без
/// выхода в сеть (там и живут боты), и загружать к себе <c>ol.js</c> с карты
/// нельзя: без сети страница не открылась бы вовсе. Картинку же браузер тянет
/// сам, а не тянется — не вышло, подложки просто нет, и об этом сказано
/// словами.
///
/// ПОЧЕМУ <c>worldExtent.js</c> ЧИТАЕТ БОТ, А НЕ СТРАНИЦА. Это чужой адрес:
/// <c>fetch</c> к нему из браузера упёрся бы в CORS, а картинке (<c>img</c>)
/// CORS не нужен. Поэтому сетку спрашивает бот (<see cref="WebMapSource"/>), а
/// браузер тянет только картинки.
/// </summary>
public static partial class WebMapRules
{
    /// <summary>
    /// Папка с картинками мира внутри карты. Имя не наше: так его пишет сам
    /// WebCartographer (<c>let dataFolder = 'data'</c> в его странице).
    /// </summary>
    public const string DataFolder = "data";

    /// <summary>Имя файла, которым карта рассказывает о своей сетке.</summary>
    public const string ExtentFile = "worldExtent.js";

    /// <summary>
    /// Сколько плиток пускать в один ряд подложки.
    ///
    /// ПРИЧИНА ЧИСЛА. Каждая плитка — отдельный запрос браузера к чужому
    /// серверу, и окно панели перерисовывается каждые несколько секунд. Восемь
    /// на восемь — это 64 картинки, которые браузер закеширует и больше не
    /// попросит; сотня уровнем подробнее превратила бы вкладку в обстрел
    /// чужого сервера запросами.
    /// </summary>
    public const int MaxTilesAcross = 8;

    /// <summary>
    /// Потолок числа плиток на одну подложку — сторож на случай кривой сетки в
    /// <c>worldExtent.js</c> (разрешение 0, отрицательный размер плитки).
    /// Ошибиться тут значит попросить у браузера миллион картинок.
    /// </summary>
    public const int MaxTiles = 400;

    /// <summary>
    /// Сколько блоков в пикселе на САМОМ КРУПНОМ шаге просмотрщика карты
    /// (уровень 0). Число не наше: так оно записано в самой карте
    /// (<c>html/js/map/mapView.js</c>, <c>resolutions: [256, 128, 64, …]</c>),
    /// и дальше уровни делятся пополам.
    ///
    /// СВЕРЕНО ЗАНОВО 16.08 по исходникам мода
    /// (WebCartographer, <c>WebCartographer/html/js/map/mapView.js</c>):
    /// <c>resolutions: [256, 128, 64, 32, 16, 8, 4, 2, 1, 0.5, 0.25, 0.125]</c>
    /// — ровно двенадцать шагов, верхний 256. Значит, уровень плиток «1 блок в
    /// точке» открывается ссылкой с <c>zoom=8</c>, и это то, что мы и шлём.
    ///
    /// ЗАЧЕМ ЭТО ЗДЕСЬ. У выгрузки мира свой список уровней (у TOPS он
    /// начинается с 512), и номер уровня плитки НЕ РАВЕН числу <c>zoom</c> в
    /// адресе карты. Ссылка «открыть это место на карте сервера» обязана
    /// пересчитать одно в другое, иначе она открывалась бы не в том масштабе.
    /// </summary>
    public const double ViewerTopResolution = 256;

    /// <summary>Сколько шагов масштаба знает просмотрщик карты (0..11).</summary>
    public const int ViewerMaxZoom = 11;

    /// <summary>
    /// ПОЧЕМУ КАРТЫ СЕРВЕРА НЕТ — словами. null означает «адрес годный».
    ///
    /// Пустой адрес — не беда и не поломка: карта сервера есть не у всех, и
    /// без неё панель работает ровно как раньше. А вот адрес, набранный с
    /// опиской, обязан сказать об этом вслух: молча пустая подложка
    /// неотличима от «сервер не ответил».
    /// </summary>
    public static string? WhyNoWebMap(string? address)
    {
        if (address is not { Length: > 0 } || address.Trim().Length == 0)
            return "карта сервера не задана — панель рисует только то, что знает сам бот. " +
                   "Если у вашего сервера есть веб-карта (мод WebCartographer, страница " +
                   "вроде «https://map.tops.vintagestory.at/»), впишите её адрес здесь или " +
                   "«panel.mapUrl» в bot.json (флаг запуска --map-url) — и та же самая карта " +
                   "станет подложкой под точками бота";

        return Base(address) is null
            ? $"адрес карты сервера не понят: «{address.Trim()}». Нужен адрес страницы карты " +
              "целиком, по http или https, например «https://map.tops.vintagestory.at/». " +
              "Ни ключей, ни паролей в него не подставляется — бот только читает оттуда " +
              "картинки"
            : null;
    }

    /// <summary>
    /// АДРЕС КАРТЫ, ПРИВЕДЁННЫЙ К ОДНОМУ ВИДУ: «https://дом/путь/» с косой на
    /// конце и без «?x=0&amp;y=0&amp;zoom=5». null — адрес не годится.
    ///
    /// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЭТО ЕСТЬ. Человек копирует адрес из
    /// браузера — а там он ровно с хвостом «?x=0&amp;y=0&amp;zoom=5», как в
    /// заказе. Приклей мы к такому «data/world/…», и вышло бы
    /// «…?x=0&amp;y=0&amp;zoom=5data/world/…» — ни одной картинки.
    ///
    /// Схему требуем http или https и никакую другую: «file://» увёл бы бота
    /// читать диск, а не карту.
    /// </summary>
    public static string? Base(string? address)
    {
        if (address is not { Length: > 0 })
            return null;
        string текст = address.Trim();
        if (текст.Length == 0)
            return null;

        // Человек пишет «map.tops.vintagestory.at» без схемы — это тот же
        // адрес, и отказывать в нём было бы придиркой. Схему добавляем
        // безопасную: карта у всех на https
        if (!текст.Contains("://", StringComparison.Ordinal))
            текст = "https://" + текст;

        if (!Uri.TryCreate(текст, UriKind.Absolute, out var uri))
            return null;
        if (uri.Scheme != Uri.UriSchemeHttp && uri.Scheme != Uri.UriSchemeHttps)
            return null;
        if (uri.Host.Length == 0)
            return null;

        // Хвост «?x=…» и «#…» отбрасываем: это положение чужого взгляда на
        // карте, а не адрес самой карты
        string путь = uri.AbsolutePath;
        // «/index.html» — тоже страница карты; папка у неё та же
        int косая = путь.LastIndexOf('/');
        if (косая >= 0 && путь[(косая + 1)..].Contains('.'))
            путь = путь[..(косая + 1)];
        if (!путь.EndsWith('/'))
            путь += "/";

        return $"{uri.Scheme}://{uri.Authority}{путь}";
    }

    /// <summary>Адрес файла, которым карта рассказывает о своей сетке.</summary>
    public static string ExtentUrl(string @base) => @base + ExtentFile;

    /// <summary>
    /// Адрес одной картинки мира. Вид адреса не наш: так его собирает сама
    /// карта (<c>dataFolder + '/world/{z}/{x}_{y}.png'</c>).
    /// </summary>
    public static string TileUrl(string @base, int level, int col, int row) =>
        $"{@base}{DataFolder}/world/{level}/{col}_{row}.png";

    /// <summary>
    /// ССЫЛКА «ОТКРЫТЬ ЭТО МЕСТО НА КАРТЕ СЕРВЕРА».
    ///
    /// Координаты в неё идут ИГРОВЫЕ и без пересчёта: карта считает их так же,
    /// как игра (см. <see cref="WebMapRules"/>). Знак у Z не меняем — карта
    /// сама кладёт <c>cy = -y</c>.
    /// </summary>
    public static string Link(string @base, int gameX, int gameZ, int viewZoom) =>
        $"{@base}?x={gameX.ToString(CultureInfo.InvariantCulture)}" +
        $"&y={gameZ.ToString(CultureInfo.InvariantCulture)}" +
        $"&zoom={Math.Clamp(viewZoom, 0, ViewerMaxZoom).ToString(CultureInfo.InvariantCulture)}";

    /// <summary>
    /// Шаг масштаба ПРОСМОТРЩИКА по номеру уровня плиток. Зачем перевод —
    /// см. <see cref="ViewerTopResolution"/>.
    /// </summary>
    public static int ViewZoom(WebMapGrid grid, int level)
    {
        if (grid.Levels == 0)
            return 0;
        double res = grid.Resolutions[Math.Clamp(level, 0, grid.Levels - 1)];
        if (res <= 0)
            return 0;
        return (int)Math.Clamp(Math.Round(Math.Log2(ViewerTopResolution / res)), 0, ViewerMaxZoom);
    }

    /// <summary>
    /// Потолок «сколько точек картинки мы вообще согласны просить у чужой
    /// карты поперёк окна».
    ///
    /// ПРИЧИНА ЧИСЛА. Уровень подбирается под РАЗМЕР КАРТИНКИ НА ЭКРАНЕ
    /// (<see cref="LevelForScreen"/>), а размер этот приходит от браузера и
    /// умножается на плотность его точек: на экране 4K с двойной плотностью
    /// вышло бы под четыре тысячи точек, то есть шестнадцать плиток поперёк и
    /// две с половиной сотни картинок на одну перерисовку. Разницы между
    /// 2048 и 4096 точками глаз на карте леса не увидит, а чужой сервер
    /// разницу в запросах почувствует.
    /// </summary>
    public const int MaxScreenPixels = 2048;

    /// <summary>
    /// Сколько плиток поперёк разрешено, когда уровень выбирается под экран.
    ///
    /// Больше <see cref="MaxTilesAcross"/> нарочно: при 2048 точках экрана
    /// честный уровень «одна точка = один блок» требует девяти плиток, и
    /// упрись мы в восемь — пришлось бы взять уровень вдвое крупнее и
    /// растянуть его. Ровно это заказчик и назвал «плохое качество карты».
    /// </summary>
    public const int ScreenTilesAcross = 10;

    /// <summary>
    /// КАКОЙ УРОВЕНЬ КАРТИНОК БРАТЬ ПОД ОКНО, ЗНАЯ РАЗМЕР КАРТИНКИ НА ЭКРАНЕ.
    ///
    /// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЭТО ЕСТЬ. Заказчик 16.08: «плохое качество
    /// карты, проверь точно ли ты выводишь масштаб карты». Проверено: старое
    /// правило <see cref="LevelFor"/> считает ТОЛЬКО плитки и НЕ ЗНАЕТ, во
    /// сколько точек экрана эта картинка развернётся. Оттого два перекоса
    /// сразу:
    ///   • окно 2048 блоков на экране с двойной плотностью точек — нужен
    ///     уровень «1 блок в точке», а потолок в восемь плиток поперёк отдаёт
    ///     уровень «2 блока в точке», и браузер растягивает его вдвое. Это и
    ///     есть размытая карта;
    ///   • окно 64 блока — берётся самый подробный уровень, и он всё равно
    ///     растягивается в шестнадцать раз, потому что подробнее «одного блока
    ///     в точке» у выгрузки мира НЕТ. Тут виновата не карта, а масштаб, и
    ///     сказать об этом надо словами (<see cref="MapZoomRules.WebMapWords"/>).
    ///
    /// ПРАВИЛО ЦЕЛИКОМ: нужное разрешение — это <c>сторона / точки экрана</c>
    /// блоков в точке. Берём САМЫЙ КРУПНЫЙ уровень, который не хуже нужного
    /// (то есть не придётся растягивать), и, если он просит слишком много
    /// плиток, отступаем на уровень крупнее. Просить уровень подробнее
    /// нужного бессмысленно: лишние точки картинки экран всё равно выбросит,
    /// а чужому серверу это лишние запросы.
    /// </summary>
    /// <param name="grid">сетка карты сервера</param>
    /// <param name="span">сторона окна в игровых блоках</param>
    /// <param name="screenPixels">
    /// Во сколько точек картинка развернётся на экране. 0 и меньше — браузер
    /// не сказал (старая страница, ещё не мерила), и тогда решает старое
    /// правило <see cref="LevelFor"/>: гадать размер экрана за браузер нельзя.
    /// </param>
    /// <param name="maxAcross">потолок плиток поперёк</param>
    public static int LevelForScreen(WebMapGrid grid, int span, int screenPixels,
        int maxAcross = ScreenTilesAcross)
    {
        if (grid.Levels == 0)
            return 0;
        if (screenPixels <= 0 || span <= 0)
            return LevelFor(grid, span);

        // Больше MaxScreenPixels не просим — см. причину у самой постоянной
        double точки = Math.Min(screenPixels, MaxScreenPixels);
        double нужно = span / точки;                 // блоков в одной точке экрана

        // Уровни идут от крупного к подробному, номер уровня — номер в списке.
        // Берём первый, который уже не грубее нужного
        int уровень = grid.Levels - 1;
        for (int i = 0; i < grid.Levels; i++)
        {
            double res = grid.Resolutions[i];
            if (res > 0 && res <= нужно)
            {
                уровень = i;
                break;
            }
        }

        // Слишком много плиток — отступаем на уровень крупнее. Лучше картинка
        // помягче, чем сотня запросов к чужому серверу на каждый шаг бота
        int потолок = Math.Max(1, maxAcross);
        while (уровень > 0)
        {
            double плитка = grid.Resolutions[уровень] * grid.TileWidth;
            if (плитка > 0 && Math.Ceiling(span / плитка) + 1 <= потолок)
                break;
            уровень--;
        }
        return уровень;
    }

    /// <summary>
    /// КАКОЙ УРОВЕНЬ КАРТИНОК БРАТЬ ПОД ОКНО ШИРИНОЙ <paramref name="span"/>
    /// блоков: самый подробный из тех, что укладываются в
    /// <paramref name="maxAcross"/> плиток поперёк.
    ///
    /// Идём от подробного к крупному, а не наоборот, потому что человек
    /// открывает карту, чтобы РАЗГЛЯДЕТЬ место: крупный уровень читается как
    /// «карта размылась».
    ///
    /// ЭТО ЗАПАСНОЕ ПРАВИЛО. Пока браузер не сказал, во сколько точек он
    /// развернёт картинку, судить о резкости не по чему, и остаётся считать
    /// плитки. Знает размер — решает <see cref="LevelForScreen"/>.
    /// </summary>
    public static int LevelFor(WebMapGrid grid, int span, int maxAcross = MaxTilesAcross)
    {
        if (grid.Levels == 0)
            return 0;
        int потолок = Math.Max(1, maxAcross);
        for (int уровень = grid.Levels - 1; уровень > 0; уровень--)
        {
            double плитка = grid.Resolutions[уровень] * grid.TileWidth;
            if (плитка <= 0)
                continue;
            // «+1»: окно почти никогда не начинается ровно на краю плитки, и
            // одна лишняя нужна с каждой стороны
            if (Math.Ceiling(span / плитка) + 1 <= потолок)
                return уровень;
        }
        return 0;
    }

    /// <summary>
    /// РЕШЁТКА ПЛИТОК ПОД ОКНОМ: какие номера столбцов и строк накрывают окно
    /// от края до края. false — сетка негодная (нулевое разрешение, пустой
    /// список уровней) или окно вырождено; рисовать нечего.
    ///
    /// ПОЧЕМУ ЭТО ОТДЕЛЬНЫМ ПРАВИЛОМ, А НЕ ЧЕТЫРЬМЯ СТРОЧКАМИ ВНУТРИ
    /// <see cref="Tiles"/>. Заказчик 16.08 сказал дословно «карта не на всю
    /// зону» и на слово «починено» больше не верит — нужен ЗАМЕР
    /// (<see cref="Cover"/>): накрыли плитки область целиком или у края
    /// осталась дыра. Считай замер свои номера сам — он проверял бы сам себя, и
    /// разойдись два счёта, панель бодро сообщала бы «накрыто целиком» о карте
    /// с белой полосой. Поэтому номера считаются ЗДЕСЬ И ТОЛЬКО ЗДЕСЬ, а Tiles
    /// и замер оба спрашивают эту решётку.
    ///
    /// ПОЧЕМУ floor У ОБОИХ КРАЁВ, А НЕ ceil У ДАЛЬНЕГО. Плитка накрывает
    /// полуинтервал [начало; начало+шаг). Клетка ближнего края окна — это
    /// floor(мин), клетка дальнего края — floor(макс), и она нужна целиком:
    /// возьми мы ceil, последний столбец выпал бы, и у правой кромки была бы
    /// ровно та белая полоса, о которой речь. Когда дальний край попадает
    /// ровно на стык плиток, лишний столбец нулевой ширины — не беда: одна
    /// картинка про запас дешевле дыры.
    /// </summary>
    public static bool Lattice(WebMapGrid grid, MapFrame frame, int level,
        out WebMapLattice lattice)
    {
        lattice = default;
        if (grid.Levels == 0 || frame.Span <= 0 || grid.TileWidth <= 0 || grid.TileHeight <= 0)
            return false;

        level = Math.Clamp(level, 0, grid.Levels - 1);
        double res = grid.Resolutions[level];
        if (res <= 0 || double.IsNaN(res) || double.IsInfinity(res))
            return false;

        double шагX = res * grid.TileWidth;      // сколько игровых блоков в плитке поперёк
        double шагZ = res * grid.TileHeight;

        // Координаты карты: mapX = игровой X, mapY = −игровой Z (ось Y у карты
        // смотрит вверх, а Z в игре — вниз по экрану)
        if (!Номер((frame.MinX - grid.OriginX) / шагX, out int столбецОт) ||
            !Номер((frame.MaxX - grid.OriginX) / шагX, out int столбецДо) ||
            !Номер((grid.OriginY + frame.MinZ) / шагZ, out int строкаОт) ||
            !Номер((grid.OriginY + frame.MaxZ) / шагZ, out int строкаДо))
            return false;

        lattice = new WebMapLattice(level, столбецОт, столбецДо, строкаОт, строкаДо, шагX, шагZ);
        return true;
    }

    /// <summary>
    /// Номер плитки из доли. Вылез за int — отказ, а не срезанное число:
    /// у крошечного разрешения в кривом <c>worldExtent.js</c> номер выходит за
    /// миллиарды, и молча обёрнутый int показал бы картинки с другого конца
    /// мира как ни в чём не бывало.
    /// </summary>
    private static bool Номер(double x, out int номер)
    {
        номер = 0;
        double п = Math.Floor(x);
        if (double.IsNaN(п) || п < int.MinValue || п > int.MaxValue)
            return false;
        номер = (int)п;
        return true;
    }

    /// <summary>
    /// ПЛИТКИ ПОД ОКНО КАРТЫ. Пусто — сетка негодная или окно целиком за краем
    /// выгруженного мира.
    ///
    /// Отрицательные номера плиток НЕ ЗАПРАШИВАЕМ: у выгрузки они начинаются с
    /// нуля, и просить их значило бы стучаться к чужому серверу заведомо зря.
    /// </summary>
    public static IReadOnlyList<WebMapTile> Tiles(WebMapGrid grid, MapFrame frame,
        int level, string @base)
    {
        if (!Lattice(grid, frame, level, out var решётка))
            return [];

        var плитки = new List<WebMapTile>();
        for (int строка = решётка.RowFrom; строка <= решётка.RowTo; строка++)
        {
            // Ряды и столбцы у выгрузки начинаются с нуля: отрицательного
            // адреса на сервере карты не существует вовсе. Просить их — значит
            // тратить потолок MaxTiles на заведомо мёртвые запросы и получать
            // «картинок пришло 0 из N» у края мира
            if (строка < 0)
                continue;
            for (int столбец = решётка.ColFrom; столбец <= решётка.ColTo; столбец++)
            {
                if (столбец < 0)
                    continue;
                // Потолок — сторож от кривой сетки, и он ОБРЕЗАЕТ подложку.
                // Молчать об этом нельзя: обрезанная подложка и есть «карта не
                // на всю зону». Замер Cover считает то же самое и называет
                // недостачу числом (см. CoverWords)
                if (плитки.Count >= MaxTiles)
                    return плитки;

                // Левый верхний угол плитки, назад в игровые координаты. Так
                // он и уходит наружу: доля окна устарела бы на первом же шаге
                // бота (см. WebMapTile)
                double x0 = grid.OriginX + столбец * решётка.StepX;
                double z0 = строка * решётка.StepZ - grid.OriginY;

                плитки.Add(new WebMapTile(решётка.Level, столбец, строка,
                    TileUrl(@base, решётка.Level, столбец, строка),
                    x0, z0, решётка.StepX, решётка.StepZ));
            }
        }
        return плитки;
    }

    /// <summary>
    /// ЗАМЕР ПОКРЫТИЯ: НАКРЫЛИ ЛИ ЗАПРОШЕННЫЕ ПЛИТКИ ВСЮ ОБЛАСТЬ ОКНА.
    ///
    /// ЗАКАЗ ЗАКАЗЧИКА ДОСЛОВНО (16.08): «карта не на всю зону». Ему дважды
    /// докладывали «готово», и дважды живьём было сломано, поэтому отчёт словами
    /// больше не считается ответом: считается ЧИСЛО — сколько клеток решётки
    /// накрывают окно, сколько из них вправду попало в запрос и сколько лежит за
    /// краем выгруженного мира, где картинки нет и быть не может.
    ///
    /// Число это идёт и в окно (<c>вебкарта.покрытие</c>), а не только в тест:
    /// человек, увидевший белую полосу у кромки, обязан прочесть, чья это беда —
    /// наша (не попросили) или самой выгрузки (там мир не бывал).
    /// </summary>
    public static WebMapCover Cover(WebMapGrid grid, MapFrame frame, int level,
        IReadOnlyList<WebMapTile> tiles)
    {
        if (!Lattice(grid, frame, level, out var решётка))
            return default;

        long столбцов = (long)решётка.ColTo - решётка.ColFrom + 1;
        long строк = (long)решётка.RowTo - решётка.RowFrom + 1;
        if (столбцов <= 0 || строк <= 0)
            return default;

        // Клетки с отрицательным номером считаем арифметикой, а не обходом:
        // у кривой сетки решётка бывает в миллиарды клеток, и перебор её
        // повесил бы окно управления ради одного числа
        long левее = Math.Clamp(-(long)решётка.ColFrom, 0, столбцов);
        long выше = Math.Clamp(-(long)решётка.RowFrom, 0, строк);
        long заКраем = левее * строк + выше * столбцов - левее * выше;

        // Запрошенным считаем только то, что вправду лежит в этой решётке и на
        // этом уровне: чужая плитка соседнего уровня накрывает то же место
        // картинкой другого масштаба, и зачесть её значило бы соврать в замере
        var есть = new HashSet<(int, int)>();
        foreach (var п in tiles)
            if (п.Level == решётка.Level &&
                п.Col >= решётка.ColFrom && п.Col <= решётка.ColTo &&
                п.Row >= решётка.RowFrom && п.Row <= решётка.RowTo)
                есть.Add((п.Col, п.Row));

        return new WebMapCover(столбцов * строк, есть.Count, заКраем);
    }

    /// <summary>
    /// ЗАМЕР ПОКРЫТИЯ СЛОВАМИ. Пусто — сетки нет и мерить нечего.
    ///
    /// Говорится это ВСЕГДА, а не только при беде: «накрыто целиком» — тот самый
    /// ответ, которого заказчик и ждёт от жалобы «карта не на всю зону», и
    /// молчаливая полная подложка от молчаливой дырявой неотличима.
    /// </summary>
    public static string CoverWords(WebMapCover cover)
    {
        if (cover.Need <= 0)
            return "";

        // Склоняет числа тот же счёт, что и остальные строки под картой
        // (MapZoomRules.Plural): «4 плиток» рядом с «2 блока в точке» выглядело
        // бы написанным наспех, а объяснению сейчас надо верить
        string надо = MapZoomRules.Plural(cover.Need, "клетки", "клеток", "клеток");
        string взято = MapZoomRules.Plural(cover.Asked, "плитка", "плитки", "плиток");

        if (cover.Missing > 0)
            return $"ПОДЛОЖКА НАКРЫВАЕТ НЕ ВСЁ ОКНО: под ним {надо}, попросить удалось " +
                   $"{cover.Asked}, не хватает {cover.Missing}. " +
                   $"Больше {MaxTiles} картинок разом бот у чужой карты не просит — " +
                   "отдалите окно или сузьте его, и подложка сойдётся.";

        return cover.Beyond > 0
            ? $"Подложка накрывает окно целиком: {взято} из {надо}; остальные {cover.Beyond} " +
              "лежат за краем выгруженного мира, картинок там нет и быть не может."
            : $"Подложка накрывает окно целиком: {взято}, дыр по краям нет.";
    }

    /// <summary>
    /// РАЗБОР <c>worldExtent.js</c>. Это не JSON, а строчка кода на JavaScript,
    /// поэтому берём из неё ровно три числа-набора и ничего не исполняем.
    ///
    /// НИ ОДНОГО ЗНАЧЕНИЯ ПО УМОЛЧАНИЮ ЗДЕСЬ НЕТ. Не нашлось начало сетки или
    /// уровни — это отказ с причиной, а не «поставим 256 и как-нибудь
    /// нарисуем»: подставленное число сдвинуло бы подложку под точками бота, и
    /// человек читал бы место склада по чужой картинке.
    /// </summary>
    /// <param name="js">содержимое файла</param>
    /// <param name="grid">разобранная сетка</param>
    /// <param name="why">почему не вышло (пусто, когда вышло)</param>
    public static bool TryParse(string? js, out WebMapGrid grid, out string why)
    {
        grid = default;
        why = "";

        if (js is not { Length: > 0 })
        {
            why = $"карта отдала пустой {ExtentFile} — сетку уровней взять неоткуда";
            return false;
        }

        // Потолок на разбор: по этому адресу может лежать что угодно, вплоть до
        // страницы ошибки на много мегабайт, и гонять по ней поиск незачем
        string текст = js.Length > 64 * 1024 ? js[..(64 * 1024)] : js;

        var начало = OriginPattern().Match(текст);
        if (!начало.Success ||
            !Number(начало.Groups[1].Value, out double ox) ||
            !Number(начало.Groups[2].Value, out double oy))
        {
            why = $"в {ExtentFile} не нашлось «origin» — без начала сетки картинки легли бы " +
                  "не туда, а карта со сдвигом хуже, чем никакой";
            return false;
        }

        var уровни = ResolutionsPattern().Match(текст);
        if (!уровни.Success)
        {
            why = $"в {ExtentFile} не нашлось «resolutions» — неизвестно, сколько блоков " +
                  "в пикселе на каждом шаге";
            return false;
        }

        var список = new List<double>();
        foreach (string кусок in уровни.Groups[1].Value.Split(',',
                     StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            if (!Number(кусок, out double r) || r <= 0)
            {
                why = $"в {ExtentFile} среди «resolutions» стоит негодное число «{кусок}»";
                return false;
            }
            список.Add(r);
        }
        if (список.Count == 0)
        {
            why = $"в {ExtentFile} список «resolutions» пуст";
            return false;
        }

        // Размер плитки карта пишет и парой, и одним числом — оба вида законны
        int ширина = 256, высота = 256;
        var плитка = TileSizePattern().Match(текст);
        if (плитка.Success)
        {
            string первое = плитка.Groups[1].Success ? плитка.Groups[1].Value : плитка.Groups[3].Value;
            string второе = плитка.Groups[2].Success ? плитка.Groups[2].Value : первое;
            if (!int.TryParse(первое, NumberStyles.Integer, CultureInfo.InvariantCulture, out ширина) ||
                !int.TryParse(второе, NumberStyles.Integer, CultureInfo.InvariantCulture, out высота) ||
                ширина <= 0 || высота <= 0)
            {
                why = $"в {ExtentFile} негодный «tileSize»";
                return false;
            }
        }

        grid = new WebMapGrid(ox, oy, список, ширина, высота);
        return true;
    }

    /// <summary>Число из файла карты. Точка десятичная всегда — это JavaScript.</summary>
    private static bool Number(string text, out double value) =>
        double.TryParse(text.Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out value);

    [GeneratedRegex(@"origin\s*:\s*\[\s*(-?[0-9.eE+]+)\s*,\s*(-?[0-9.eE+]+)\s*\]")]
    private static partial Regex OriginPattern();

    [GeneratedRegex(@"resolutions\s*:\s*\[([^\]]{0,4096})\]")]
    private static partial Regex ResolutionsPattern();

    [GeneratedRegex(@"tileSize\s*:\s*(?:\[\s*([0-9]{1,6})\s*(?:,\s*([0-9]{1,6})\s*)?\]|([0-9]{1,6}))")]
    private static partial Regex TileSizePattern();
}

/// <summary>
/// КУДА ЧЕЛОВЕК СМОТРИТ РУКАМИ: сторона окна и его середина. Всё пустое —
/// не трогал, и окно подбирается само.
///
/// ЗАЧЕМ ОДНИМ ТИПОМ, А НЕ ДВУМЯ ЧИСЛАМИ ПОРОЗНЬ. Масштаб и середина —
/// одно решение человека, и живут они одинаково: их знает только открытая
/// вкладка, они не пишутся в настройки (взгляд у каждой вкладки свой) и
/// сбрасываются одной кнопкой «Всё в окне». Разложи их по разным местам —
/// «отдалить» после того, как карту утянули в сторону, вернуло бы окно к боту,
/// и сдвиг терялся бы молча.
/// </summary>
/// <param name="Span">сторона окна в блоках; null — масштаб не трогали</param>
/// <param name="Center">
/// Середина окна в ИГРОВЫХ координатах; null — карту не двигали, и окно едет за
/// ботом, как раньше.
/// </param>
public readonly record struct MapLook(int? Span, MapPick? Center)
{
    /// <summary>Человек не трогал ни масштаб, ни положение карты.</summary>
    public bool Untouched => Span is null && Center is null;

    /// <summary>Взгляд, который человек не трогал: окно подбирается само.</summary>
    public static MapLook Auto => default;

    public override string ToString() =>
        Untouched ? "окно само"
                  : $"сторона {(Span?.ToString() ?? "сама")}, середина {(Center?.ToString() ?? "у бота")}";
}

/// <summary>
/// МАСШТАБ КАРТЫ В ОКНЕ УПРАВЛЕНИЯ: приблизить, отдалить и сказать вслух,
/// насколько крупно человек сейчас смотрит.
///
/// ЗАКАЗ ЗАКАЗЧИКА ДОСЛОВНО (16.08): «плохое качество карты, проверь точно ли
/// ты выводишь масштаб карты, неплохо было бы и нам его добавить на нашу».
///
/// ПОЧЕМУ ЭТО ПРАВИЛО, А НЕ ДЕСЯТЬ СТРОК В БРАУЗЕРЕ. Масштаб решает три вещи
/// разом: какое окно мира показать, какой уровень картинок попросить у чужой
/// карты (<see cref="WebMapRules.LevelForScreen"/>) и куда лягут ТОЧКИ БОТА.
/// Стоит этим трём разъехаться — и выходит то, что заказчик уже видел в живом
/// прогоне 15.08: «карта не отображается нормально… полэкрана только», метки
/// сами по себе, картинка сама по себе. В браузере такое видно только глазами
/// и только задним числом; здесь это сторожит тест.
///
/// ТОЧКИ НЕ ДВИГАЮТСЯ НИ ПРИ КАКОМ МАСШТАБЕ, и это не пожелание, а устройство:
/// доля каждой точки считается <see cref="PanelMapRules.Fraction"/> от ТОГО ЖЕ
/// окна, которое ушло в подложку. Страница не пересчитывает ничего сама —
/// поменялся масштаб, она заново спрашивает бота и рисует пришедшее целиком.
/// </summary>
public static class MapZoomRules
{
    /// <summary>
    /// СТУПЕНИ МАСШТАБА — стороны окна в блоках, от самой тесной до самой
    /// широкой, вдвое каждая.
    ///
    /// Границы не свои: это <see cref="PanelMapRules.MinSpan"/> и
    /// <see cref="PanelMapRules.MaxSpan"/>, те же, в которые упирается
    /// автоподбор окна. Заведи мы здесь второй список чисел — карта на кнопке
    /// «отдалить» показывала бы не то, что она же показывает сама.
    ///
    /// Вдвое, а не «на сколько-нибудь»: у карты сервера уровни тоже идут
    /// вдвое, и на ступенях, кратных её уровням, картинка ложится точка в
    /// точку, без растягивания.
    /// </summary>
    public static IReadOnlyList<int> Spans { get; } = Ladder();

    private static int[] Ladder()
    {
        var список = new List<int>();
        for (int с = PanelMapRules.MinSpan; с <= PanelMapRules.MaxSpan; с *= 2)
            список.Add(с);
        // Крайняя ступень обязана быть ровно MaxSpan: иначе «отдалить до упора»
        // показывало бы не то же самое, что автоподбор при дальней точке
        if (список.Count == 0 || список[^1] != PanelMapRules.MaxSpan)
            список.Add(PanelMapRules.MaxSpan);
        return [.. список];
    }

    /// <summary>Сколько всего ступеней.</summary>
    public static int Steps => Spans.Count;

    /// <summary>
    /// НОМЕР БЛИЖАЙШЕЙ СТУПЕНИ к стороне <paramref name="span"/>.
    ///
    /// «Ближайшая» считается по отношению, а не по разности: от 64 до 128
    /// разница 64 блока, а от 1024 до 2048 — тысяча, и по разности любое
    /// широкое окно липло бы к самой широкой ступени.
    /// </summary>
    public static int Step(int span)
    {
        if (span <= 0)
            return 0;
        int лучший = 0;
        double лучшее = double.MaxValue;
        for (int i = 0; i < Spans.Count; i++)
        {
            double о = (double)Math.Max(span, Spans[i]) / Math.Min(span, Spans[i]);
            if (о < лучшее)
            {
                лучшее = о;
                лучший = i;
            }
        }
        return лучший;
    }

    /// <summary>Сторона окна по номеру ступени; номер вне списка прижимается к краю.</summary>
    public static int SpanOf(int step) => Spans[Math.Clamp(step, 0, Spans.Count - 1)];

    /// <summary>
    /// СТОРОНА ОКНА ПОСЛЕ «ПРИБЛИЗИТЬ» (<paramref name="delta"/> &lt; 0) ИЛИ
    /// «ОТДАЛИТЬ» (&gt; 0).
    ///
    /// Приблизить — это МЕНЬШЕ блоков в окне, поэтому знак и выглядит наоборот.
    /// Взято от колеса мыши: вверх (deltaY &lt; 0) во всех картах мира — это
    /// приблизить, и делать по-своему значило бы удивлять человека.
    /// </summary>
    public static int Zoom(int span, int delta) => SpanOf(Step(span) + delta);

    /// <summary>
    /// Насколько окон разом позволено утянуть карту одним движением.
    ///
    /// ЭТО СТОРОЖ, А НЕ ОГРАНИЧЕНИЕ ДЛЯ РУКИ. Мышью больше одного-двух окон за
    /// жест не утянешь физически (курсор упирается в экран), а вот строку
    /// запроса набирает кто угодно: доля в миллиард увела бы середину окна за
    /// край int, и карта показала бы другой конец мира вместо отказа.
    /// </summary>
    public const double MaxDragWindows = 8;

    /// <summary>
    /// СЕРЕДИНА ОКНА, ПРИЖАТАЯ К БЕЗОПАСНОМУ КРАЮ.
    ///
    /// Края окна считаются как <c>середина ± сторона/2</c>, и у середины возле
    /// края int это переполнение: <see cref="MapFrame.MinX"/> обернулся бы в
    /// плюс, окно вывернулось бы наизнанку, а подложка легла бы к нему в тон —
    /// то есть карта показала бы не то место, ничего об этом не сказав.
    /// </summary>
    public static int SafeCenter(double coord)
    {
        if (double.IsNaN(coord))
            return 0;
        double край = (double)int.MaxValue - PanelMapRules.MaxSpan;
        return (int)Math.Round(Math.Clamp(coord, -край, край));
    }

    /// <summary>
    /// ОКНО ПРИ МАСШТАБЕ И СЕРЕДИНЕ, ЗАДАННЫХ РУКАМИ. Ничего не трогали
    /// (<see cref="MapLook.Untouched"/>) — окно остаётся тем, что подобралось
    /// само (<see cref="PanelMapRules.Frame"/>).
    ///
    /// СЕРЕДИНУ ДЕРЖИТ ЧЕЛОВЕК, ЕСЛИ ОН ЕЁ НАЗВАЛ, И ЯКОРЬ — ЕСЛИ НЕТ.
    /// Заказ 16.08 дословно: «карте добавить возможность двигать ее курсором как
    /// любую другую карту». Утянув карту в сторону, человек смотрит НЕ на бота —
    /// и окно, которое на следующем же опросе прыгнуло бы назад к боту, ровно
    /// это «двигать» и отменяет: бот идёт, опрос раз в три секунды, и карта
    /// вырывалась бы из рук. Поэтому названная середина сильнее якоря.
    ///
    /// Не названа — середина у якоря, то есть у бота: приблизив карту, человек
    /// смотрит на него, а середина автоокна стоит посреди ВСЕХ точек, и на
    /// тесной ступени бот уехал бы за край собственной карты из-за одной старой
    /// записи о руде на другом конце мира. Бота в мире нет — держимся прежней
    /// середины: другой у нас нет.
    /// </summary>
    public static MapFrame Frame(MapFrame auto, MapMark? anchor, MapLook look)
    {
        if (look.Untouched)
            return auto;

        // Масштаб не назвали, а карту подвинули — сторона остаётся та, на
        // которой человек и тянул: менять её вместе со сдвигом значило бы
        // дёргать карту из-под руки
        int сторона = look.Span is { } просят ? SpanOf(Step(просят)) : auto.Span;

        if (look.Center is { } его)
            return new MapFrame(SafeCenter(его.X), SafeCenter(его.Z), сторона);
        return new MapFrame(anchor?.X ?? auto.CenterX, anchor?.Z ?? auto.CenterZ, сторона);
    }

    /// <summary>
    /// ОКНО ПРИ ЗАДАННОМ РУКАМИ ТОЛЬКО МАСШТАБЕ — прежний вид правила, когда
    /// карту ещё не умели двигать.
    /// </summary>
    public static MapFrame Frame(MapFrame auto, MapMark? anchor, int? span) =>
        Frame(auto, anchor, new MapLook(span, null));

    /// <summary>
    /// КАРТУ ПОТЯНУЛИ КУРСОРОМ → КУДА ПЕРЕЕХАЛА СЕРЕДИНА ОКНА.
    ///
    /// ЗАКАЗ ЗАКАЗЧИКА ДОСЛОВНО (16.08): «карте добавить возможность двигать ее
    /// курсором как любую другую карту».
    ///
    /// ПОЧЕМУ ЭТО СЧИТАЕТ БОТ, А НЕ СТРАНИЦА, И ПОЧЕМУ ДОЛЯМИ. Долями окна
    /// разговаривает вся карта: ими приходит щелчок (<see cref="MapPickRules.At"/>),
    /// ими же уходят места точек (<see cref="PanelMapRules.Fraction"/>). Браузер
    /// знает про свои пиксели и больше ни про что; переводить их в блоки — то
    /// самое место, где ось Z путают с высотой, и цена ошибки здесь та же, что
    /// у щелчка: карта уезжает не туда, а выглядит исправной.
    ///
    /// ЗНАК ОБРАТНЫЙ, И ЭТО НЕ ОПИСКА. Утянули картинку ВПРАВО — значит смотреть
    /// стали ЛЕВЕЕ, окно уехало в минус по X. Так ведёт себя любая карта в мире,
    /// и сделать наоборот значило бы удивить человека на первом же движении.
    /// </summary>
    /// <param name="frame">окно, ПО КОТОРОМУ тянули (доли считаны от него)</param>
    /// <param name="dragFracX">на какую долю ширины окна утянули вправо</param>
    /// <param name="dragFracZ">на какую долю высоты окна утянули вниз</param>
    public static MapPick Pan(MapFrame frame, double dragFracX, double dragFracZ)
    {
        if (frame.Span <= 0 || !double.IsFinite(dragFracX) || !double.IsFinite(dragFracZ))
            return new MapPick(frame.CenterX, frame.CenterZ);

        double долейX = Math.Clamp(dragFracX, -MaxDragWindows, MaxDragWindows);
        double долейZ = Math.Clamp(dragFracZ, -MaxDragWindows, MaxDragWindows);

        return new MapPick(
            SafeCenter(frame.CenterX - долейX * frame.Span),
            SafeCenter(frame.CenterZ - долейZ * frame.Span));
    }

    /// <summary>
    /// ЧТО СКАЗАТЬ ПРО ОКНО, КОТОРОЕ ЧЕЛОВЕК ДЕРЖИТ РУКАМИ. Пусто — окно
    /// подбирается само, и говорить нечего.
    ///
    /// Молчать нельзя: утянув карту от бота, человек через минуту видит, что
    /// метки бота на ней нет, — и это неотличимо от «бот пропал». Надо сказать
    /// прямо: карта стоит там, где вы её поставили, и вернуть её одной кнопкой.
    /// </summary>
    public static string HeldWords(MapLook look) => look.Center is not null
        ? "Окно вы держите руками: за ботом оно больше не едет. Вернуть слежение — «Всё в окне»."
        : look.Span is not null
            ? "Масштаб задан руками; окно держится бота. Вернуть подбор под все точки — «Всё в окне»."
            : "";

    /// <summary>
    /// НАСКОЛЬКО КРУПНО ЧЕЛОВЕК СМОТРИТ — словами.
    ///
    /// Молчать об этом нельзя ровно по той же причине, по какой подписаны оси:
    /// «плохое качество» и «слишком крупный масштаб» с виду одно и то же, и
    /// без числа человек чинит карту вместо того, чтобы отдалить её.
    /// </summary>
    /// <param name="span">сторона окна в блоках</param>
    /// <param name="screenPixels">во сколько точек экрана окно развернулось (0 — браузер не сказал)</param>
    public static string Words(int span, int screenPixels)
    {
        if (span <= 0)
            return "";
        if (screenPixels <= 0)
            return $"Сторона окна {span} бл.";
        // Сторону окна называет тот, кто рисует оси, — повторять её здесь
        // значило бы говорить одно и то же дважды в одной строке
        double наБлок = (double)screenPixels / span;
        return наБлок >= 1
            ? $"Один блок занимает {Plural(наБлок, "точку", "точки", "точек")} экрана."
            : $"В одной точке экрана {Plural(1 / наБлок, "блок", "блока", "блоков")}.";
    }

    /// <summary>
    /// САМАЯ ТЕСНАЯ СТУПЕНЬ, НА КОТОРОЙ КАРТИНКУ СЕРВЕРА ЕЩЁ НЕ РАСТЯГИВАЕТ.
    /// 0 — такой ступени нет вовсе.
    ///
    /// Подробнее самого подробного уровня у выгрузки мира ничего нет: у карты
    /// TOPS это «один блок в точке». Значит, окно уже, чем экран в точках,
    /// растягивается ВСЕГДА — и это не поломка, а предел самой карты. Число
    /// нужно затем, чтобы сказать человеку не «извините», а «отдалите до
    /// 1024 бл, и станет резко».
    ///
    /// НОЛЬ — ТОЖЕ ЧЕСТНЫЙ ОТВЕТ. На очень широком и плотном экране резкой не
    /// станет ни одна ступень: даже самая широкая даёт меньше точек, чем экран.
    /// Посоветовать в этом случае «отдалите до 2048» значило бы пообещать то,
    /// чего не будет, — и человек жал бы кнопку, не понимая, почему не помогло.
    ///
    /// Точки экрана берутся НАСТОЯЩИЕ, без потолка
    /// <see cref="WebMapRules.MaxScreenPixels"/>: потолок решает, сколько
    /// просить у чужого сервера, а растягивает браузер по-настоящему.
    /// </summary>
    public static int SharpSpan(WebMapGrid grid, int screenPixels)
    {
        if (grid.Levels == 0 || screenPixels <= 0)
            return SpanOf(Steps - 1);
        double мельче = grid.Resolutions[^1];
        if (мельче <= 0 || double.IsNaN(мельче) || double.IsInfinity(мельче))
            return SpanOf(Steps - 1);
        double надо = screenPixels * мельче;
        for (int i = 0; i < Spans.Count; i++)
            if (Spans[i] >= надо)
                return Spans[i];
        return 0;
    }

    /// <summary>
    /// ВО СКОЛЬКО РАЗ БРАУЗЕР РАСТЯГИВАЕТ КАРТИНКУ КАРТЫ. 0 — считать нечем
    /// (нет сетки, нет окна или браузер не сказал своего размера).
    ///
    /// Больше единицы — картинку растягивают, и она выглядит мягкой. Меньше —
    /// наоборот, сжимают: точек в ней больше, чем у экрана.
    ///
    /// ЭТО ЧИСЛО НУЖНО НЕ ТОЛЬКО ДЛЯ СЛОВ. По нему страница выбирает, КАК
    /// браузеру сглаживать картинку: растянутую честнее показывать точками
    /// (каждый блок своим цветом), а сжатую — наоборот, только сглаживанием,
    /// иначе браузер выбрасывает лишние точки и ровный лес идёт рябью.
    /// Считается ЗДЕСЬ, а не в браузере, чтобы у слов и у показа было одно и
    /// то же число: разойдись они — панель говорила бы «растянуто вдвое» на
    /// картинке, которую она же сглаживает как сжатую.
    ///
    /// Точки экрана берутся НАСТОЯЩИЕ, без потолка
    /// <see cref="WebMapRules.MaxScreenPixels"/>: потолок решает, сколько
    /// просить у чужого сервера, а растягивает браузер по-настоящему, и
    /// приуменьшить это значило бы соврать о том, что человек видит глазами.
    /// </summary>
    /// <param name="grid">сетка карты сервера</param>
    /// <param name="level">взятый уровень</param>
    /// <param name="span">сторона окна в блоках</param>
    /// <param name="screenPixels">во сколько точек экрана окно развернулось</param>
    public static double Stretch(WebMapGrid grid, int level, int span, int screenPixels)
    {
        if (grid.Levels == 0 || span <= 0 || screenPixels <= 0)
            return 0;
        double res = grid.Resolutions[Math.Clamp(level, 0, grid.Levels - 1)];
        if (res <= 0 || double.IsNaN(res) || double.IsInfinity(res))
            return 0;
        double точекКартинки = span / res;
        return точекКартинки > 0 ? screenPixels / точекКартинки : 0;
    }

    /// <summary>
    /// ЧТО СЕЙЧАС С КАЧЕСТВОМ ПОДЛОЖКИ — словами и по факту.
    ///
    /// ЗАЧЕМ. Заказчик написал «плохое качество карты», и правильный ответ на
    /// это — не молчаливая картинка, а число: какой уровень взят, сколько в
    /// нём блоков на точку и во сколько раз браузер его растянул. Тогда видно
    /// сразу, чья это беда: наша (взяли не тот уровень) или самой выгрузки
    /// мира (подробнее у неё нет).
    /// </summary>
    /// <inheritdoc cref="Stretch" path="/param"/>
    public static string WebMapWords(WebMapGrid grid, int level, int span, int screenPixels)
    {
        if (grid.Levels == 0 || span <= 0)
            return "";
        double res = grid.Resolutions[Math.Clamp(level, 0, grid.Levels - 1)];
        if (res <= 0 || double.IsNaN(res) || double.IsInfinity(res))
            return "";

        int взят = Math.Clamp(level, 0, grid.Levels - 1);
        bool предел = взят >= grid.Levels - 1;
        string начало = $"Картинки карты сервера взяты уровнем {взят} из {grid.Levels - 1}" +
                        (предел ? " (подробнее у неё нет)" : "") +
                        $": {Plural(res, "блок", "блока", "блоков")} в точке картинки.";

        // Растяжение считает Stretch — второго счёта здесь быть не должно:
        // по этому же числу страница выбирает сглаживание, и разойдись они —
        // слова спорили бы с картинкой
        double растяжение = Stretch(grid, взят, span, screenPixels);
        if (растяжение <= 0)
            return начало;

        if (растяжение <= 1.05)
            return начало + " Растягивать её не приходится — это её родная резкость.";

        начало += $" Браузер растягивает её в {Plural(растяжение, "раз", "раза", "раз")} — " +
                  "оттого карта и выглядит мягкой.";
        if (!предел)
            return начало + " Уровень подробнее нарочно не взят: это сотни картинок " +
                            "с чужого сервера на каждую перерисовку окна.";

        int резкая = SharpSpan(grid, screenPixels);
        return начало + (резкая > 0
            ? $" Нужна резкая картинка — отдалите до {резкая} бл."
            : $" Резкой она на вашем экране не станет ни на одной ступени: даже самая " +
              $"широкая ({SpanOf(Steps - 1)} бл) даёт меньше точек, чем у экрана. " +
              "Это предел самой выгрузки мира, а не окна.");
    }

    /// <summary>
    /// Число человеку: без хвоста у целых, с одним знаком после запятой у
    /// прочих. Запятая, а не точка, нарочно — окно говорит по-русски, а
    /// «1.6» посреди русской фразы читается как опечатка.
    /// </summary>
    private static string Число(double x)
    {
        double о = Math.Round(x, 1, MidpointRounding.AwayFromZero);
        if (Math.Abs(о - Math.Round(о)) < 0.05)
            return ((long)Math.Round(о)).ToString(CultureInfo.InvariantCulture);
        return о.ToString("0.0", CultureInfo.InvariantCulture).Replace('.', ',');
    }

    /// <summary>
    /// ЧИСЛО СО СЛОВОМ В ПРАВИЛЬНОМ ПАДЕЖЕ: «1 блок», «2 блока», «5 блоков»,
    /// «1,5 блока».
    ///
    /// ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ «блока(ов)». Эти строки читает заказчик, и читает
    /// он их ровно в тот миг, когда уже недоволен видом карты. «Растягивает в
    /// 2 раз(а)» посреди объяснения выглядит как недоделка — а объяснению
    /// сейчас надо верить. Правило русское и обычное: 11–14 всегда «блоков»,
    /// иначе по последней цифре; у дробного числа — родительный единственного
    /// («1,5 блока»), как и говорят по-русски.
    ///
    /// НАРУЖУ ОТКРЫТО НАРОЧНО. Замер покрытия (<see cref="WebMapRules.CoverWords"/>)
    /// считает плитки и клетки и говорит о них тому же человеку в той же строке
    /// под картой. Заведи он своё склонение — «4 плиток» стояло бы рядом с
    /// «2 блока в точке», и объяснение, которому надо верить, выглядело бы
    /// написанным наспех.
    /// </summary>
    public static string Plural(double x, string один, string два, string много)
    {
        string число = Число(x);
        double о = Math.Round(x, 1, MidpointRounding.AwayFromZero);
        bool целое = Math.Abs(о - Math.Round(о)) < 0.05;
        if (!целое)
            return $"{число} {два}";

        long n = Math.Abs((long)Math.Round(о));
        if (n % 100 is >= 11 and <= 14)
            return $"{число} {много}";
        return $"{число} " + (n % 10) switch
        {
            1 => один,
            2 or 3 or 4 => два,
            _ => много
        };
    }
}

