/// <summary>
/// ЩЕЛЧОК ПО КАРТЕ → ТОЧКА МИРА: чистое правило, обратное
/// <see cref="PanelMapRules.Fraction"/>.
///
/// ЗАКАЗ ЗАКАЗЧИКА ДОСЛОВНО: «хочу по веб админке на карте давать точку куда
/// ему бежать, и он уже думал, через телепорты или пешком и шел».
///
/// ПОЧЕМУ ЭТО СЧИТАЕТ БОТ, А НЕ СТРАНИЦА. По той же причине, по какой доли
/// точек считает он же: перепутать здесь ось Z с высотой проще всего, а стоит
/// это бота, ушедшего не туда, куда ткнули пальцем. В браузере такую ошибку
/// видно только глазами и только задним числом; здесь её сторожит тест —
/// и сторожит он именно КРУГОВОЙ ХОД: доля точки, посчитанная
/// <see cref="PanelMapRules.Fraction"/>, обязана вернуть ту же самую клетку.
/// Два конца одного перевода живут в разных файлах, и без этой сверки они
/// разъехались бы молча.
///
/// ВЫСОТЫ У ЩЕЛЧКА НЕТ И БЫТЬ НЕ МОЖЕТ — см. <see cref="NoHeightWhy"/>.
/// </summary>
public static class MapPickRules
{
    /// <summary>
    /// Крошечная поправка при переводе доли обратно в клетку.
    ///
    /// ЭТО НЕ ПОДГОНКА, А ЛЕЧЕНИЕ ДВОИЧНОЙ ДРОБИ: у доли 3/7, умноженной назад
    /// на 7, выходит 2,9999999999999996, и без поправки щелчок ровно по точке
    /// уезжал бы на клетку влево. Одна миллиардная блока меньше любой мыслимой
    /// точности мыши, так что честному щелчку она помешать не может.
    /// </summary>
    public const double CellEpsilon = 1e-9;

    /// <summary>
    /// ПОЧЕМУ ВЫСОТУ У ЩЕЛЧКА СПРАШИВАЮТ ОТДЕЛЬНО. Карта — вид сверху: в ней
    /// есть X и Z и нет Y. Подставить свою высоту молча нельзя — на дне ущелья
    /// и на вершине горы это разные места, и «иду к (2050, 111, 6900)» звучало
    /// бы как точный адрес, будучи догадкой. Поэтому высоту либо называет
    /// человек, либо берётся ЕГО ЖЕ БОТА нынешняя — и об этом говорится вслух.
    /// </summary>
    public const string NoHeightWhy =
        "у карты нет высоты: она вид сверху, в ней только X и Z. Высоту я беру ту, " +
        "на которой стою сам, а на месте уточняю по земле — если цель в ущелье или " +
        "на горе, впишите её высоту сами";

    /// <summary>
    /// НАСКОЛЬКО МЫШИ ПОЗВОЛЕНО ДРОГНУТЬ, ЧТОБЫ ЩЕЛЧОК ОСТАЛСЯ ЩЕЛЧКОМ, — в
    /// точках экрана.
    ///
    /// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЭТО ЕСТЬ. С этой волны карту двигают
    /// курсором (заказ 16.08: «двигать ее курсором как любую другую карту»), а
    /// щелчок по карте с прошлой волны ВЫБИРАЕТ ТОЧКУ, куда бот пойдёт.
    /// Значит, каждое перетаскивание кончается отпусканием кнопки — то есть
    /// щелчком, — и без этого порога человек, подвинувший карту, каждый раз
    /// получал бы выбранную цель там, где отпустил руку.
    ///
    /// Число — обычный порог дрожания руки (у Windows он тоже около четырёх
    /// точек, SM_CXDRAG): меньше него мышь ёрзает при простом нажатии.
    /// </summary>
    public const double DragSlopPixels = 4;

    /// <summary>
    /// ЭТО БЫЛА ПРОТЯЖКА, А НЕ ЩЕЛЧОК? Расстояние — в точках экрана, то есть в
    /// том, чем меряет браузер.
    ///
    /// Правило живёт здесь, рядом с переводом щелчка в точку мира, нарочно:
    /// решают они одно и то же — считать ли отпускание кнопки приказом выбрать
    /// место в мире.
    /// </summary>
    public static bool WasDrag(double dx, double dy)
    {
        if (!double.IsFinite(dx) || !double.IsFinite(dy))
            return true;    // не поняли движения — считаем протяжкой: промолчать безопаснее, чем увести бота
        return dx * dx + dy * dy > DragSlopPixels * DragSlopPixels;
    }

    /// <summary>
    /// КУДА ТКНУЛИ. Доли — от левого и от ВЕРХНЕГО края квадрата карты, от 0 до
    /// 1 (так их и отдаёт браузер: <c>event.offsetX / ширина</c>).
    ///
    /// null означает «мимо карты»: доля вне 0…1 или окно вырождено. Молча
    /// подтягивать такой щелчок к краю нельзя — человек ткнул мимо, а бот
    /// пошёл бы в угол карты как ни в чём не бывало.
    /// </summary>
    public static MapPick? At(MapFrame frame, double fracX, double fracZ)
    {
        if (frame.Span <= 0 ||
            !double.IsFinite(fracX) || !double.IsFinite(fracZ) ||
            fracX < 0 || fracX > 1 || fracZ < 0 || fracZ > 1)
            return null;

        return new MapPick(
            frame.MinX + (int)Math.Floor(fracX * frame.Span + CellEpsilon),
            frame.MinZ + (int)Math.Floor(fracZ * frame.Span + CellEpsilon));
    }
}

/// <summary>Чем человек показал место на карте.</summary>
public enum MapDrawKind
{
    /// <summary>Одна клетка — щелчок.</summary>
    Point,

    /// <summary>Обведённая область — «копай вот тут».</summary>
    Area,

    /// <summary>Отрезок из угла в угол — «веди отсюда сюда».</summary>
    Line
}

/// <summary>
/// НАРИСОВАННОЕ НА КАРТЕ — в ИГРОВЫХ координатах.
///
/// Обе клетки настоящие: их посчитал <see cref="MapPickRules.At"/> — тот же
/// перевод доли в клетку, каким живёт обычный щелчок. Второго перевода тут нет.
/// </summary>
/// <param name="Kind">точка, область или отрезок</param>
/// <param name="X1">игровой X первого конца (у точки — он же единственный)</param>
/// <param name="Z1">игровой Z первого конца</param>
/// <param name="X2">игровой X второго конца</param>
/// <param name="Z2">игровой Z второго конца</param>
public readonly record struct MapDrawn(MapDrawKind Kind, int X1, int Z1, int X2, int Z2)
{
    /// <summary>Точка: оба конца — одна и та же клетка.</summary>
    public static MapDrawn Point(int x, int z) => new(MapDrawKind.Point, x, z, x, z);

    public int MinX => Math.Min(X1, X2);
    public int MaxX => Math.Max(X1, X2);
    public int MinZ => Math.Min(Z1, Z2);
    public int MaxZ => Math.Max(Z1, Z2);

    /// <summary>
    /// Середина обведённого — в long, потому что края карты Vintage Story
    /// расходятся на миллион блоков и сумма двух X в int переполняется.
    /// </summary>
    public int CenterX => (int)(((long)MinX + MaxX) / 2);

    /// <inheritdoc cref="CenterX"/>
    public int CenterZ => (int)(((long)MinZ + MaxZ) / 2);

    /// <summary>
    /// Сторона обведённого квадрата В КЛЕТКАХ, а не в блоках расстояния.
    ///
    /// Отсюда «+1»: человек обвёл клетки с 10-й по 20-ю — это ОДИННАДЦАТЬ
    /// клеток, и карьер стороной 10 оставил бы ряд необработанным. Карьер меряет
    /// себя именно клетками («сторона карьера в блоках» — это число клеток
    /// в ряду), поэтому и здесь клетки.
    ///
    /// Берётся БОЛЬШАЯ из двух сторон: у карьера яма квадратная, и вписать
    /// в обведённое надо всё, что обвели, а не половину.
    /// </summary>
    public int Side => (int)Math.Max((long)MaxX - MinX, (long)MaxZ - MinZ) + 1;

    /// <summary>Радиус от середины до края обведённого, в клетках.</summary>
    public int Radius => Math.Max(1, Side / 2);

    /// <summary>Длина отрезка в блоках — ею меряют дорогу и штольню.</summary>
    public int Length => (int)Math.Round(
        Math.Sqrt(Math.Pow((double)X2 - X1, 2) + Math.Pow((double)Z2 - Z1, 2)));

    public override string ToString() => Kind switch
    {
        MapDrawKind.Point => $"точка ({X1}, ?, {Z1})",
        MapDrawKind.Area => $"область {Side}×{Side} вокруг ({CenterX}, ?, {CenterZ})",
        _ => $"отрезок ({X1}, ?, {Z1}) → ({X2}, ?, {Z2}), {Length} бл"
    };
}

/// <summary>
/// Одно поле задачи, заполненное нарисованным на карте.
/// </summary>
/// <param name="Name">имя поля вида работы — то самое, что стоит в его описании</param>
/// <param name="Kind">вид поля из <see cref="WorkFieldKinds"/>: клетка или целое</param>
/// <param name="X">игровой X (только у клетки)</param>
/// <param name="Y">
/// Высота (только у клетки). Своей высоты у карты нет вовсе
/// (<see cref="MapPickRules.NoHeightWhy"/>), и она приезжает сюда снаружи —
/// названная человеком или взятая у бота. Но НЕСТИ ЕЁ ОБЯЗАНО ЭТО ЖЕ ПОЛЕ:
/// конструктор задач считает точку без высоты недозаполненной и жалуется на
/// неё словами, а человек в это время видит два числа из трёх и не понимает,
/// чего от него хотят.
/// </param>
/// <param name="Z">игровой Z (только у клетки)</param>
/// <param name="Number">число (только у целого)</param>
public readonly record struct MapDrawField(string Name, string Kind, int X, int Y, int Z, int Number)
{
    public static MapDrawField Cell(string name, int x, int y, int z) =>
        new(name, WorkFieldKinds.Cell, x, y, z, 0);

    public static MapDrawField Int(string name, int number) =>
        new(name, WorkFieldKinds.Int, 0, 0, 0, number);

    public override string ToString() => Kind == WorkFieldKinds.Cell
        ? $"{Name} = ({X}, {Y}, {Z})"
        : $"{Name} = {Number}";
}

/// <summary>
/// Что нарисованное даёт этому виду работы.
/// </summary>
/// <param name="Fields">какие поля заполнить и чем</param>
/// <param name="StillNeeded">
/// Обязательные поля вида, которых нарисованное НЕ заполняет: их человек
/// дозаполнит руками. Молчать о них нельзя — иначе задача уедет в очередь
/// недоделанной и откажется через сорок минут.
/// </param>
/// <param name="Why">Почему не вышло ничего (пусто — вышло).</param>
public sealed record MapDrawFill(
    IReadOnlyList<MapDrawField> Fields,
    IReadOnlyList<string> StillNeeded,
    string Why)
{
    /// <summary>Нарисованное этому виду работы годится.</summary>
    public bool Any => Fields.Count > 0;
}

/// <summary>
/// НАРИСОВАННОЕ НА КАРТЕ → ПОЛЯ ТОЙ ЖЕ САМОЙ ЗАДАЧИ.
///
/// ЗАКАЗ ЗАКАЗЧИКА ДОСЛОВНО: «карту вкладку объедини с задачами и добавим
/// добавление задач с карты, чтобы можно было нарисовать где копать к примеру,
/// звучит интересно, но придумай как сделать удобно».
///
/// ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: ВТОРОГО ОПИСАНИЯ КОМАНД ЗДЕСЬ НЕТ. Ни одного
/// имени вида работы, ни одного имени навыка. Правило смотрит только на ПОЛЯ,
/// которые вид работы объявил о себе сам (<see cref="WorkKind.Fields"/>), и на
/// имена этих полей — те самые общие константы <see cref="WorkFields"/>,
/// которыми роль их и называет. Заведи роль новую работу с «стартом» и
/// «концом» — она станет рисоваться отрезком без единой правки здесь; а
/// сочини правило свой список работ — он разошёлся бы с ролью в первый же день,
/// и человек рисовал бы область, а бот получал бы задачу с пустым центром.
///
/// ПОЧЕМУ ЭТО ЧИСТОЕ ПРАВИЛО, А НЕ ДЕСЯТЬ СТРОК В БРАУЗЕРЕ. Здесь живёт перевод
/// «обвёл клетки → сторона карьера» и «протянул отрезок → откуда и куда». Оба
/// ошибаются молча: карьер выйдет на клетку уже обведённого, дорога пойдёт
/// задом наперёд, — и увидеть это можно только через сорок минут работы бота.
/// В браузере такое не проверить ничем, кроме глаз; здесь это сторожит тест.
///
/// ВЫСОТЫ У НАРИСОВАННОГО НЕТ. Карта — вид сверху
/// (<see cref="MapPickRules.NoHeightWhy"/>), и клетка едет сюда уже с той
/// высотой, которую назвал человек или подставил бот; своей высоты правило не
/// выдумывает.
/// </summary>
public static class MapDrawRules
{
    /// <summary>Поля-МЕСТА, которые нарисованное вправе заполнять.</summary>
    /// <remarks>
    /// Список закрыт нарочно. «Сдавать» и «брать» — тоже клетки, но это
    /// СУНДУКИ: попасть в сундук серединой обведённой области нельзя, а
    /// подставленный наугад сундук — это груз, уехавший неизвестно куда.
    /// На сундук показывают точно, отдельным полем.
    /// </remarks>
    public static readonly string[] PlaceFields = [WorkFields.Start, WorkFields.End];

    /// <summary>Поля-РАЗМЕРЫ, которые нарисованное вправе заполнять.</summary>
    public static readonly string[] SizeFields = [WorkFields.Width, WorkFields.Radius];

    /// <summary>
    /// ЧТО НАРИСОВАННОЕ ДАЁТ ЭТОМУ ВИДУ РАБОТЫ.
    ///
    /// <paramref name="y"/> — высота, которую назвал человек (или подставил
    /// бот): у карты её нет вовсе, а класть в поле «клетка» точку без высоты
    /// нельзя — конструктор задач считает такую точку недозаполненной.
    /// </summary>
    public static MapDrawFill Fill(IReadOnlyList<WorkField> fields, MapDrawn drawn, int y)
    {
        // СПИСКИ ЗАКРЫТЫ КОДОМ, А НЕ ОБЕЩАНИЕМ. Отбор идёт ЧЕРЕЗ них: иначе
        // «сдавать» и «брать» (тоже клетки!) однажды попали бы под руку
        // нарисованному, и груз уехал бы в сундук, которого человек не называл
        var места = fields.Where(f => f.Kind == WorkFieldKinds.Cell &&
            PlaceFields.Contains(f.Name, StringComparer.OrdinalIgnoreCase)).ToList();
        var размеры = fields.Where(f => f.Kind == WorkFieldKinds.Int &&
            SizeFields.Contains(f.Name, StringComparer.OrdinalIgnoreCase)).ToList();

        WorkField? Место(string имя) => места.FirstOrDefault(f =>
            string.Equals(f.Name, имя, StringComparison.OrdinalIgnoreCase));
        WorkField? Размер(string имя) => размеры.FirstOrDefault(f =>
            string.Equals(f.Name, имя, StringComparison.OrdinalIgnoreCase));

        var старт = Место(WorkFields.Start);
        var конец = Место(WorkFields.End);
        var ширина = Размер(WorkFields.Width);
        var радиус = Размер(WorkFields.Radius);

        var вышло = new List<MapDrawField>();
        string почему = "";

        switch (drawn.Kind)
        {
            case MapDrawKind.Point:
                // ТОЧКА ИДЁТ ТУДА, БЕЗ ЧЕГО ДЕЛО НЕ ПОЙДЁТ. У штольни
                // обязателен «конец» («куда вести ход»), а «старт» — это
                // необязательное устье, и класть щелчок в устье значило бы
                // оставить задачу без цели: человек ткнул, куда копать, а бот
                // отказался бы словами «не задано поле конец»
                var одно = ЕдинственноеОбязательное(старт, конец);
                var цель = одно ?? старт ?? конец;
                if (цель is null)
                {
                    почему = "этому делу точка на карте не нужна: у него нет полей «" +
                             $"{WorkFields.Start}» и «{WorkFields.End}»";
                    break;
                }
                вышло.Add(MapDrawField.Cell(цель.Name, drawn.X1, y, drawn.Z1));
                break;

            case MapDrawKind.Line:
                // ОТРЕЗОК — ЭТО ПАРА ТОЧЕК, и класть его в одну нельзя: человек
                // показал направление, а половина направления — это уже
                // догадка о том, куда вести дорогу
                if (старт is null || конец is null)
                {
                    почему = $"отрезок ложится в пару полей «{WorkFields.Start}» и " +
                             $"«{WorkFields.End}», а у этого дела их нет — " +
                             "покажите одну точку";
                    break;
                }
                вышло.Add(MapDrawField.Cell(старт.Name, drawn.X1, y, drawn.Z1));
                вышло.Add(MapDrawField.Cell(конец.Name, drawn.X2, y, drawn.Z2));
                break;

            default:
                // ОБЛАСТЬ — ЭТО ОДНО МЕСТО ПЛЮС РАЗМЕР. Ровно то, чего просил
                // заказчик: «нарисовать где копать». Куда именно ляжет размер,
                // решает вид работы своим полем: у карьера это «ширина»
                // (сторона ямы), у наряда и разведки — «радиус» поиска.
                //
                // ДЕЛУ С ДВУМЯ МЕСТАМИ ОБВЕДЁННОЕ НЕ ГОДИТСЯ, и молча взять из
                // него половину нельзя. Имён работ правило по-прежнему не
                // знает — оно смотрит на то, что дело объявило о себе само:
                // объявлены ОБА места («старт» и «конец») — значит, дело
                // задаётся отрезком, а не пятном. Иначе выходило вот что:
                //   • у дороги «ширина» — это ширина ПОЛОТНА поперёк отрезка
                //     (поле так и объявлено: «1..9», см. RoadPlan.MaxWidth), а
                //     сюда легла бы сторона обведённого: обвёл 61 клетку —
                //     получил «ширина = 61», и бот молча урезал бы её до 9;
                //   • у штольни «старт» — это УСТЬЕ, а не «куда вести ход», и
                //     середина обведённого (человек показал ею, КУДА копать)
                //     легла бы в устье, оставив обязательный «конец» пустым, —
                //     ровно та беда, ради которой одиночная точка и выбирает
                //     единственное ОБЯЗАТЕЛЬНОЕ поле (см. выше)
                if (старт is not null && конец is not null)
                {
                    почему = $"у этого дела ДВА места («{WorkFields.Start}» и " +
                             $"«{WorkFields.End}») — обведённой областью их не задать, " +
                             "проведите отрезок";
                    break;
                }
                if (старт is null)
                {
                    почему = $"у этого дела нет поля «{WorkFields.Start}» — " +
                             "обведённой области его не задать";
                    break;
                }
                вышло.Add(MapDrawField.Cell(старт.Name, drawn.CenterX, y, drawn.CenterZ));
                if (ширина is not null)
                    вышло.Add(MapDrawField.Int(ширина.Name, drawn.Side));
                else if (радиус is not null)
                    вышло.Add(MapDrawField.Int(радиус.Name, drawn.Radius));
                break;
        }

        // ЧЕГО НАРИСОВАННОЕ НЕ ДАЁТ — НАЗЫВАЕМ ПОИМЁННО. Иначе человек обвёл
        // область под наряд, увидел заполненные поля и отправил задачу без
        // «что» и «сколько»: бот отказался бы уже в очереди
        var заполнено = вышло.Select(п => п.Name).ToHashSet(StringComparer.OrdinalIgnoreCase);
        var надо = вышло.Count == 0
            ? []
            : fields.Where(f => f.Required && !заполнено.Contains(f.Name))
                    .Select(f => f.Name).ToList();

        return new MapDrawFill(вышло, надо, почему);
    }

    /// <summary>
    /// Единственное ОБЯЗАТЕЛЬНОЕ поле-место вида работы. null — их ноль или
    /// больше одного, и выбирать за человека нечего.
    /// </summary>
    private static WorkField? ЕдинственноеОбязательное(WorkField? start, WorkField? end)
    {
        WorkField? один = null;
        foreach (var f in new[] { start, end })
        {
            if (f is not { Required: true })
                continue;
            if (один != null)
                return null;    // обязательны оба (дорога) — точкой их не задать
            один = f;
        }
        return один;
    }
}

/// <summary>
/// ЧТО ПАНЕЛЬ ЗНАЕТ О КАРТЕ СЕРВЕРА ПРЯМО СЕЙЧАС.
/// </summary>
/// <param name="Address">адрес, приведённый к одному виду (пусто — не задан или негоден)</param>
/// <param name="Grid">сетка, если карта уже ответила</param>
/// <param name="Why">
/// Почему подложки нет. Пусто — она есть. Отдельно от <paramref name="Grid"/>
/// нарочно: «ещё спрашиваю» и «сервер не ответил» человек обязан различать.
/// </param>
public readonly record struct WebMapLook(string Address, WebMapGrid? Grid, string Why)
{
    /// <summary>Можно рисовать подложку.</summary>
    public bool Ready => Grid is not null;
}

/// <summary>
/// СПРАШИВАЕТ У КАРТЫ СЕРВЕРА ЕЁ СЕТКУ — один раз и в стороне от опроса
/// страницы.
///
/// ПОЧЕМУ НЕ ПРЯМО В ОТВЕТЕ ПАНЕЛИ. Страница опрашивает бота каждые несколько
/// секунд, а карта — чужой сервер в интернете. Сходи мы за ней прямо в
/// обработчике, и одна залипшая чужая машина заморозила бы всё окно
/// управления: человек жал бы «стоп» боту и не понимал, почему панель молчит.
/// Поэтому спрашиваем ФОНОМ, а ответ панели отдаём сразу — с честным «ещё
/// спрашиваю».
///
/// ПОЧЕМУ ОДИН РАЗ. worldExtent.js меняется только при новой выгрузке мира, то
/// есть раз в сутки в лучшем случае. Дёргать его на каждый опрос страницы —
/// это обстрел чужого сервера ради числа, которое не менялось.
/// </summary>
public sealed class WebMapSource : IDisposable
{
    private readonly HttpClient http;
    private readonly bool ownsHttp;
    private readonly Lock замок = new();

    private string адрес = "";
    private WebMapGrid? сетка;
    private string почему = "";
    private bool спрашиваем;
    private DateTime следующаяПопытка = DateTime.MinValue;

    /// <summary>Через сколько пробовать снова после неудачи.</summary>
    public TimeSpan RetryAfter { get; set; } = TimeSpan.FromMinutes(5);

    /// <summary>Часы — подменяются в тестах, чтобы не ждать пять минут по-настоящему.</summary>
    public Func<DateTime> Now { get; set; } = () => DateTime.UtcNow;

    /// <summary>Куда сказать вслух. Молчать о неудаче нельзя.</summary>
    public event Action<string>? OnLog;

    public WebMapSource(HttpClient? client = null)
    {
        ownsHttp = client is null;
        // Короткий срок нарочно: это украшение вкладки, а не работа бота, и
        // ждать чужой сервер минуту незачем
        http = client ?? new HttpClient { Timeout = TimeSpan.FromSeconds(15) };
    }

    /// <summary>
    /// ЧТО ЕСТЬ ПРЯМО СЕЙЧАС. Не ждёт сети никогда: не спрошено — заводит
    /// фоновый заход и отвечает «спрашиваю».
    /// </summary>
    /// <param name="address">адрес карты сервера (<see cref="PanelConfig.MapUrl"/>)</param>
    /// <param name="ask">
    /// Можно ли ходить в сеть. false — только сказать, что известно, и НИКУДА
    /// не ходить.
    ///
    /// ЗАЧЕМ ЭТО ЕСТЬ. Карта в окне выключена по умолчанию именно затем, чтобы
    /// бот не делал лишней работы там, где на окно неделями никто не смотрит.
    /// Ходить при этом на чужую машину за сеткой уровней — ровно та лишняя
    /// работа, от которой выключатель и сторожит; вдобавок это стук в чужой
    /// сервер, о котором человек не просил.
    /// </param>
    public WebMapLook Look(string? address, bool ask = true)
    {
        if (WebMapRules.WhyNoWebMap(address) is { } нет)
            return new WebMapLook("", null, нет);

        string основа = WebMapRules.Base(address)!;

        lock (замок)
        {
            // Адрес поменяли — старая сетка чужая, и держаться за неё значило
            // бы подложить под точки картинки другого мира
            if (основа != адрес)
            {
                адрес = основа;
                сетка = null;
                почему = "";
                следующаяПопытка = DateTime.MinValue;
            }

            if (сетка is { } готовая)
                return new WebMapLook(адрес, готовая, "");

            // Ходить не велено — говорим, что известно, и никуда не идём
            if (!ask)
                return new WebMapLook(адрес, null, почему.Length > 0
                    ? почему
                    : "за сеткой уровней этой карты бот не ходил: карта в окне выключена, " +
                      "и стучаться на чужой сервер, пока на неё никто не смотрит, незачем");

            if (!спрашиваем && Now() >= следующаяПопытка)
            {
                спрашиваем = true;
                _ = Task.Run(() => AskAsync(основа));
            }

            return new WebMapLook(адрес, null,
                почему.Length > 0 ? почему : "спрашиваю у карты сервера её сетку уровней…");
        }
    }

    /// <summary>Сходить за файлом. Всё, что пошло не так, становится словами.</summary>
    private async Task AskAsync(string основа)
    {
        string ссылка = WebMapRules.ExtentUrl(основа);
        string? тело = null;
        string беда = "";
        try
        {
            тело = await http.GetStringAsync(ссылка);
        }
        catch (Exception e)
        {
            беда = $"карта сервера не ответила на {ссылка}: {e.Message}. Подложки не будет — " +
                   "точки бота панель покажет своей сеткой, как раньше";
        }

        lock (замок)
        {
            спрашиваем = false;

            // Пока ходили, адрес могли сменить — тогда ответ уже не про эту карту
            if (основа != адрес)
                return;

            if (беда.Length > 0)
            {
                почему = беда;
                следующаяПопытка = Now() + RetryAfter;
                OnLog?.Invoke(беда);
                return;
            }

            if (WebMapRules.TryParse(тело, out var разобрано, out string нет))
            {
                сетка = разобрано;
                почему = "";
                OnLog?.Invoke($"карта сервера подключена: {основа} ({разобрано})");
                return;
            }

            почему = нет;
            следующаяПопытка = Now() + RetryAfter;
            OnLog?.Invoke($"карта сервера {основа}: {нет}");
        }
    }

    public void Dispose()
    {
        if (ownsHttp)
            http.Dispose();
    }
}
