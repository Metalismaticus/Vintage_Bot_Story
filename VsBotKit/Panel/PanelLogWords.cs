using System.Text;

namespace VsBotKit.Panel;

/// <summary>
/// ЖИРНЫМ — КЛЮЧЕВОЕ В СТРОКЕ ЖУРНАЛА, чтобы её можно было прочесть глазом, а
/// не разобрать.
///
/// ЗАКАЗ ДОСЛОВНО: «добавить нужно жирным выделение ключевым словам в логах для
/// лёгкого чтения». Живой журнал 20.08 — это три с половиной тысячи строк
/// одинаковым серым моноширинным текстом, где строка «[навык дорога] не вышло:
/// …» ничем не отличается от «[руки] убрал stonepath-free в сумку». Глаз по
/// такому не скользит, а читает подряд.
///
/// ЧТО ВЫДЕЛЯЕТСЯ — РОВНО ДВА МЕСТА В СТРОКЕ, И ЭТО НАРОЧНО:
///   1) ИМЯ РАБОТЫ в квадратных скобках — «[дорога]», «[движение]», «[склад]».
///      Это левый столбец журнала: по нему глаз находит нужное дело, не читая
///      строк. В живом журнале таких имён сорок, и одно из них стоит почти в
///      каждой строке;
///   2) ГЛАВНОЕ СЛОВО СТРОКИ — одно: смерть и урон, если они есть; иначе
///      отказ; иначе находка. Порядок именно такой, потому что читают журнал
///      после беды, а не до неё: «умер» обязано победить «взял», даже если
///      стоит в строке позже.
/// Третьего жирного места нет НАРОЧНО. Заказчик сказал прямо: «не переусердствуй:
/// если жирным будет половина строки, это ничего не даст». Половина жирного —
/// это ровно то же самое, что ничего.
///
/// ПОЧЕМУ ЭТО МЕХАНИЗМ, А НЕ РУЧКА РОЛИ. Ручками роли делаются числа и пороги —
/// то, что человек крутит под свой мир. Здесь чисел нет вовсе: список слов —
/// это язык самого бота, тот же для копателя, жителя и продавца. Ручка «какие
/// слова считать важными» была бы полем, которое никто никогда не откроет.
///
/// РАЗМЕТКА СЕРВЕРА В ЖУРНАЛ НЕ ПУСКАЕТСЯ. Игра шлёт строки чата со своей
/// разметкой — в журнале заказчика это видно дословно:
///     [чат:0] &lt;strong&gt;сосед:&lt;/strong&gt; Мощу дорогу
/// Имя говорящего мы выделяем сами, а ВСЁ остальное, что прислал сервер,
/// экранируется как обычный текст. Иначе всякий, кто напишет в общий чат
/// «&lt;img onerror=…&gt;», писал бы не в чат, а в окно управления хозяина.
/// </summary>
public static class PanelLogWords
{
    /// <summary>
    /// СЛОВА ПРО СМЕРТЬ И УРОН. Первые в очереди: журнал открывают, когда
    /// что-то случилось, и «умер на 61, 112, 257» человек обязан увидеть, не
    /// вчитываясь. «Потеряно … хп» — это слово самого сервера (группа чата −5),
    /// поэтому оно стоит здесь как есть.
    /// </summary>
    public static readonly string[] Беда =
    [
        "ОТКАЗ СЕРВЕРА", "Потеряно", "умер", "погиб", "убит", "смерть", "сломал",
    ];

    /// <summary>
    /// СЛОВА ПРО ОТКАЗ. Ради них журнал и читают чаще всего: бот честно
    /// называет, чего он НЕ сделал, и эта половина строки должна бросаться в
    /// глаза раньше, чем половина про сделанное.
    /// </summary>
    public static readonly string[] Отказ =
    [
        "не вышло", "не смог", "не дошёл", "не дотянулся", "не пойду", "не хватает",
        "не нашёл", "не могу", "не буду", "не начать", "не добыть", "нечем",
        "сдаюсь", "застрял", "бросил", "отказ", "молчу", "не знаю",
    ];

    /// <summary>
    /// СЛОВА ПРО НАЙДЕННОЕ И СДЕЛАННОЕ. Последние в очереди — но нужные:
    /// по ним видно, что бот вообще работает, а не топчется.
    /// </summary>
    public static readonly string[] Находка =
    [
        "нашёл", "подобрал", "добыл", "замостил", "сделал", "взял", "положил",
        "отметил", "запомнил", "готово",
    ];

    /// <summary>
    /// ИМЯ РАБОТЫ: «[дорога]» в начале строки. Ищем ПЕРВЫЕ скобки и только
    /// рядом с началом — скобки встречаются и в середине строки («(моб)»,
    /// «(512052, 111, 512255)»), а имя работы стоит сразу за временем.
    ///
    /// Время панель ставит сама («00:01:30 [дорога] …»), поэтому смотрим не
    /// строго в нулевой позиции, а в начале строки.
    /// </summary>
    /// <returns>Где стоит «[…]» — или null, если имени работы в строке нет.</returns>
    public static (int Start, int Length)? Работа(string line)
    {
        int начало = line.IndexOf('[');
        // «Начало строки» — это время и пробел, дальше имени работы уже не
        // бывает. Без этого предела жирным становилось бы «[дорога]» посреди
        // пересказа чужой строки в «промолчал о повторах: …»
        if (начало < 0 || начало > 12)
            return null;
        int конец = line.IndexOf(']', начало + 1);
        if (конец < 0)
            return null;
        return (начало, конец - начало + 1);
    }

    /// <summary>
    /// ГЛАВНОЕ СЛОВО СТРОКИ — одно на строку.
    ///
    /// Группы разбираются по старшинству (беда → отказ → находка), а ВНУТРИ
    /// группы берётся самое раннее вхождение: в строке «сделал 1 × … ; дальше
    /// не вышло» человеку нужно «не вышло», а не «сделал», — поэтому отказ и
    /// стоит выше находки, хотя в строке он позже.
    /// </summary>
    /// <param name="line">Строка журнала целиком.</param>
    /// <param name="from">С какого места искать (после имени работы).</param>
    public static (int Start, int Length)? Главное(string line, int from = 0)
    {
        foreach (var группа in new[] { Беда, Отказ, Находка })
        {
            (int Start, int Length)? лучшее = null;
            foreach (string слово in группа)
            {
                int i = line.IndexOf(слово, Math.Min(from, line.Length),
                    StringComparison.OrdinalIgnoreCase);
                if (i < 0)
                    continue;
                // Раньше по строке — или то же место, но слово длиннее:
                // «не вышло» важнее, чем «не» внутри него
                if (лучшее is null || i < лучшее.Value.Start ||
                    (i == лучшее.Value.Start && слово.Length > лучшее.Value.Length))
                    лучшее = (i, слово.Length);
            }
            if (лучшее is { } нашли)
                return ДоКонцаМеры(line, нашли);
        }
        return null;
    }

    /// <summary>
    /// «Потеряно» без числа — половина новости. Живая строка: «Потеряно 2,5 хп
    /// дрифтер (моб)»; важно тут именно 2,5, а не слово «потеряно». Поэтому
    /// найденное слово дотягивается до конца меры, если сразу за ним стоит
    /// число с единицей.
    /// </summary>
    private static (int Start, int Length) ДоКонцаМеры(string line, (int Start, int Length) слово)
    {
        int i = слово.Start + слово.Length;
        if (i >= line.Length || line[i] != ' ')
            return слово;
        int ц = i + 1;
        while (ц < line.Length && (char.IsDigit(line[ц]) || line[ц] is ',' or '.'))
            ц++;
        if (ц == i + 1)                       // числа за словом нет
            return слово;
        int е = ц;
        if (е < line.Length && line[е] == ' ')
            е++;
        while (е < line.Length && char.IsLetter(line[е]))
            е++;
        return (слово.Start, е - слово.Start);
    }

    /// <summary>
    /// СТРОКА ЖУРНАЛА КАК HTML: всё чужое экранировано, ключевое — в &lt;b&gt;.
    ///
    /// Экранирование и разметка делаются ЗА ОДИН ПРОХОД нарочно: сначала
    /// экранировать, а потом искать слова — значит искать их в тексте, где
    /// «&lt;» уже стало «&amp;lt;», и попадать разметкой в середину мнемоники.
    /// </summary>
    public static string Html(string? line)
    {
        string текст = line ?? "";
        var работа = Работа(текст);
        var главное = Главное(текст, работа is { } р ? р.Start + р.Length : 0);

        var вывод = new StringBuilder(текст.Length + 32);
        int i = 0;
        while (i < текст.Length)
        {
            if (ИмяГоворящего(текст, i) is { } имя)
            {
                вывод.Append("<b>").Append(Экранировать(имя.Text)).Append("</b>");
                i = имя.After;
                continue;
            }
            if (работа is { } р2 && i == р2.Start)
            {
                вывод.Append("<b>").Append(Экранировать(текст.Substring(i, р2.Length))).Append("</b>");
                i += р2.Length;
                continue;
            }
            if (главное is { } г && i == г.Start)
            {
                вывод.Append("<b>").Append(Экранировать(текст.Substring(i, г.Length))).Append("</b>");
                i += г.Length;
                continue;
            }
            Экранировать(текст[i], вывод);
            i++;
        }
        return вывод.ToString();
    }

    private const string Открыть = "<strong>";
    private const string Закрыть = "</strong>";

    /// <summary>
    /// ИМЯ ГОВОРЯЩЕГО в строке чата. Игра шлёт его в своей разметке
    /// («&lt;strong&gt;сосед:&lt;/strong&gt;»), и в журнале заказчика она
    /// видна дословно — тегами.
    ///
    /// Признаём РОВНО эту пару тегов и ровно тогда, когда между ними нет ни
    /// одной угловой скобки. Внутренность всё равно экранируется: имя игрока
    /// приходит с сервера, а значит, его пишет чужой человек, и «имя» вида
    /// «&lt;img onerror=…&gt;» разметкой стать не должно ни при каких условиях.
    /// </summary>
    private static (string Text, int After)? ИмяГоворящего(string line, int i)
    {
        if (string.CompareOrdinal(line, i, Открыть, 0, Открыть.Length) != 0)
            return null;
        int начало = i + Открыть.Length;
        int конец = line.IndexOf(Закрыть, начало, StringComparison.Ordinal);
        if (конец < 0)
            return null;
        string внутри = line[начало..конец];
        if (внутри.Contains('<') || внутри.Contains('>'))
            return null;
        return (внутри, конец + Закрыть.Length);
    }

    /// <summary>Текст, безопасный для вставки в страницу.</summary>
    public static string Экранировать(string text)
    {
        var б = new StringBuilder(text.Length);
        foreach (char c in text)
            Экранировать(c, б);
        return б.ToString();
    }

    private static void Экранировать(char c, StringBuilder куда)
    {
        switch (c)
        {
            case '&': куда.Append("&amp;"); break;
            case '<': куда.Append("&lt;"); break;
            case '>': куда.Append("&gt;"); break;
            case '"': куда.Append("&quot;"); break;
            default: куда.Append(c); break;
        }
    }
}
