namespace VsBotKit.Panel;

/// <summary>Что за точка стоит на карте. Вид решает и цвет, и порядок показа.</summary>
public enum MapMarkKind
{
    /// <summary>Сам бот — то, ради чего заказчик карту и просил.</summary>
    Bot,

    /// <summary>Дом (<see cref="Shelter.Home"/>). Он у бота один.</summary>
    Home,

    /// <summary>
    /// ПОСТ — где боту велено стоять (<see cref="BehaviorHoldPost.Post"/>).
    ///
    /// ОТДЕЛЬНЫМ ВИДОМ, А НЕ ВТОРЫМ ДОМОМ. Дом — это «куда прятаться в бурю и
    /// где возрождаться», пост — «где стоять»; у стражника это РАЗНЫЕ точки, и
    /// нарисуй мы их одним значком, человек не смог бы понять, которая из них
    /// куда. Пока вида не было, пост на карте не рисовался ВООБЩЕ, а пресет
    /// при этом рекламировал «задайте щелчком по карте»: поставить можно,
    /// увидеть нельзя.
    /// </summary>
    Post,

    /// <summary>Сундук склада (<see cref="Depot.Chests"/>).</summary>
    Depot,

    /// <summary>Запомненная клетка руды или породы (<see cref="ResourceMemory"/>).</summary>
    Resource,

    /// <summary>
    /// Место встречи с ЖИВЫМ ЧЕЛОВЕКОМ. Показывается только по отдельному
    /// явному включению и несёт ровно два сведения — имя и место. Почему так
    /// строго — см. <see cref="PanelMapRules"/> и <see cref="Meeting"/>.
    /// </summary>
    Meeting
}

/// <summary>
/// Одна точка карты.
/// </summary>
/// <param name="Kind">чем эта точка является</param>
/// <param name="Title">как её назвать человеку</param>
/// <param name="Note">
/// Подробность одной строкой: «медь, 40 мин назад», «сундук склада». Пусто —
/// сказать нечего, и придумывать нечего не надо.
/// </param>
/// <param name="X">игровые координаты — те самые, что человек видит в игре</param>
/// <param name="Y">высота (у игры она не сдвигается)</param>
/// <param name="Z">игровые координаты</param>
public readonly record struct MapMark(MapMarkKind Kind, string Title, string Note,
    int X, int Y, int Z)
{
    public override string ToString() =>
        $"{Title} ({X}, {Y}, {Z})" + (Note.Length > 0 ? $" — {Note}" : "");
}

/// <summary>
/// ОКНО КАРТЫ: квадрат игрового мира, который рисуется на странице.
///
/// Квадрат, а не прямоугольник, нарочно: у прямоугольника шаг по X и по Z
/// разный, и одинаковое расстояние в блоках выглядело бы разным на экране —
/// то есть карта врала бы о том, что дальше, а что ближе.
/// </summary>
/// <param name="CenterX">середина окна по игровому X</param>
/// <param name="CenterZ">середина окна по игровому Z</param>
/// <param name="Span">сторона квадрата в блоках</param>
public readonly record struct MapFrame(int CenterX, int CenterZ, int Span)
{
    /// <summary>Левый край по X (меньшее значение).</summary>
    public int MinX => CenterX - Span / 2;

    /// <summary>Верхний край по Z (меньшее значение).</summary>
    public int MinZ => CenterZ - Span / 2;

    public int MaxX => MinX + Span;
    public int MaxZ => MinZ + Span;

    /// <summary>Точка внутри окна (края считаются внутри).</summary>
    public bool Holds(MapMark m) => m.X >= MinX && m.X <= MaxX && m.Z >= MinZ && m.Z <= MaxZ;

    public override string ToString() =>
        $"квадрат {Span} бл вокруг ({CenterX}, {CenterZ})";
}

/// <summary>
/// КАРТА В ОКНЕ УПРАВЛЕНИЯ: чистые правила про то, что на ней рисуется и в
/// каких границах.
///
/// ЗАКАЗ ЗАКАЗЧИКА, ради которого это есть: «хочу вывод положения игрока на
/// вебкарте, но как доп настройка». Карта показывает бота, дом, склад и
/// запомненные места — то, что бот УЖЕ знает. Новых механик под карту не
/// заводится: своей памяти у неё нет, она только раскладывает по клеточкам
/// чужое (<see cref="Shelter.Home"/>, <see cref="Depot.Chests"/>,
/// <see cref="ResourceMemory"/>).
///
/// ПОЧЕМУ ЭТО ОТДЕЛЬНОЕ ЧИСТОЕ ПРАВИЛО, а не десять строк в разметке страницы.
/// Границы окна, потолок числа точек и отказы («карта выключена», «координаты
/// назвать нечем») — решения, которые видно только глазами, если они живут в
/// браузере. Здесь их проверяет тест, а цена ошибки — карта, которая молча
/// показывает не то место.
///
/// КООРДИНАТЫ ТУТ ТОЛЬКО ИГРОВЫЕ. Внутри бот живёт в мировых (там середина
/// карты — 512000), и человек этих чисел никогда не видел. В журнале бот уже
/// говорит игровыми — покажи карта мировые, и одно и то же место называлось бы
/// двумя разными наборами чисел. Перевод делает тот, кто собирает точки
/// (<see cref="GameCoords.GameOf"/>), — второго перевода здесь нет.
///
/// ЧАСТНАЯ ЖИЗНЬ. Про живых людей карта показывает ровно два сведения — ИМЯ и
/// МЕСТО последней встречи, и только когда это включено отдельно и явно
/// (<see cref="PanelConfig.MapPeople"/>, по умолчанию выключено). Ни времени
/// встречи, ни счёта встреч, ни того, здоровался ли бот, наружу не уходит:
/// книга встреч — записи о человеке, который о них не знает и согласия не
/// давал (см. <see cref="Meeting"/>). Карта живёт на петле, за дверью панели,
/// и никуда ничего не отправляет.
/// </summary>
public static class PanelMapRules
{
    /// <summary>
    /// Самое тесное окно карты. Один бот посреди пустого мира не должен
    /// раздувать одну клетку на весь экран: масштаб «одна клетка = экран»
    /// показывает не место, а точку.
    /// </summary>
    public const int MinSpan = 64;

    /// <summary>
    /// Самое широкое окно карты.
    ///
    /// Нужно затем, что одна дальняя точка портит всю картинку: встреча за
    /// три тысячи блоков сжимает дом, склад и бота в одну песчинку в углу.
    /// Дальше этого карта не растягивается, а честно говорит, сколько точек
    /// осталось за краем.
    /// </summary>
    public const int MaxSpan = 2048;

    /// <summary>
    /// Свободное место по краям, чтобы точка на самой границе не оказалась
    /// наполовину срезанной рамкой.
    /// </summary>
    public const int Padding = 8;

    /// <summary>
    /// Сколько запомненных клеток руды пускать на карту.
    ///
    /// Память держит до 4096 клеток (<see cref="ResourceMemory.Capacity"/>), и
    /// отдавать их окну все — это и есть та «лишняя работа», из-за которой
    /// карта выключена по умолчанию: их надо перевести в игровые координаты,
    /// сложить в JSON и нарисовать, и всё это по десять раз в минуту. Человеку
    /// нужны ближние; дальние он всё равно не различит.
    /// </summary>
    public const int ResourceCap = 200;

    /// <summary>
    /// Сколько мест встреч пускать на карту. Меньше руды нарочно: это записи
    /// о живых людях, и чем их меньше видно разом, тем лучше.
    /// </summary>
    public const int MeetingCap = 50;

    /// <summary>
    /// Те же потолки, но при включённом СЕРВЕРНОМ РЕЖИМЕ
    /// (<see cref="ServerModeConfig"/>). Он затем и есть, чтобы бот «не
    /// отжирал лишнего по оперативке», и карта под ним обязана считаться с
    /// этим, а не делать вид, что режима нет.
    /// </summary>
    public const int ServerResourceCap = 40;

    /// <inheritdoc cref="ServerResourceCap"/>
    public const int ServerMeetingCap = 10;

    /// <summary>Потолок клеток руды, который действует сейчас.</summary>
    public static int ResourceCapFor(bool serverMode) =>
        serverMode ? ServerResourceCap : ResourceCap;

    /// <summary>Потолок мест встреч, который действует сейчас.</summary>
    public static int MeetingCapFor(bool serverMode) =>
        serverMode ? ServerMeetingCap : MeetingCap;

    /// <summary>
    /// ПОЧЕМУ КАРТЫ НЕТ — словами человеку. null означает «карту рисовать
    /// можно».
    ///
    /// Молчаливая пустая вкладка тут была бы худшим исходом: «карта выключена»
    /// и «бот нигде не был» со стороны неотличимы, и человек полез бы чинить
    /// то, что не сломано.
    /// </summary>
    /// <param name="mapOn">включена ли карта (<see cref="PanelConfig.Map"/>)</param>
    /// <param name="coordsKnown">пришёл ли сдвиг спавна (<see cref="GameCoords.CoordsKnown"/>)</param>
    /// <param name="serverMode">
    /// Включён ли серверный режим (<see cref="ServerModeConfig.Use"/>). На отказ
    /// он не влияет — влияет на ПРИЧИНУ: человеку, который сам велел боту не
    /// отжирать лишнего, надо назвать эту же причину его словами.
    /// </param>
    public static string? WhyNoMap(bool mapOn, bool coordsKnown, bool serverMode = false)
    {
        if (!mapOn)
            return (serverMode
                       ? "карта выключена, и это ровно то, о чём просит включённый вами " +
                         "серверный режим: он затем и есть, чтобы бот не отжирал лишнего. "
                       : "карта выключена. Она выключена по умолчанию нарочно: бот чаще " +
                         "всего живёт на сервере, где окно неделями никто не открывает. ") +
                   "Карта на каждый опрос страницы перебирает память руды, склад и " +
                   "встречи — это лишняя работа и лишняя память там, где на неё никто " +
                   "не смотрит. Включить: кнопкой здесь же или «panel.map: true» " +
                   "в bot.json (флаг запуска --map)";

        if (!coordsKnown)
            return "карту нарисовать нечем: сдвиг точки спавна приходит только после входа " +
                   "в мир, а без него игровые координаты назвать нельзя. Мировые показывать " +
                   "не буду — они отличаются от игровых на полмиллиона блоков, и это те " +
                   "самые числа, на которых теряют склад";

        return null;
    }

    /// <summary>
    /// ЧЕМ КАРТА ОБХОДИТСЯ ПРИ ВКЛЮЧЁННОМ СЕРВЕРНОМ РЕЖИМЕ — словами. Пусто,
    /// когда режим выключен и урезать нечего.
    ///
    /// Молчать об урезании нельзя: человек, у которого бот помнит тысячу
    /// клеток руды, увидел бы на карте сорок и решил, что память потерялась.
    /// </summary>
    public static string ServerModeNote(bool serverMode) => serverMode
        ? $"Серверный режим включён, а карта работает на каждый опрос страницы — " +
          $"поэтому её потолки урезаны: клеток руды не больше {ServerResourceCap} " +
          $"(обычно {ResourceCap}), мест встреч не больше {ServerMeetingCap} " +
          $"(обычно {MeetingCap}). Память бота при этом целая — урезан только показ."
        : "";

    /// <summary>
    /// ПОЧЕМУ НЕТ ЛЮДЕЙ НА КАРТЕ. null — показывать можно.
    ///
    /// Отдельно от <see cref="WhyNoMap"/>, потому что это отдельное решение:
    /// карту включают ради себя, а людей на ней — ради чужих имён.
    /// </summary>
    public static string? WhyNoPeople(bool peopleOn) => peopleOn
        ? null
        : "мест встреч на карте нет: их показ выключен отдельно и по умолчанию. " +
          "Книга встреч — записи о живых людях, которые о них не знают и согласия " +
          "не давали, поэтому наружу она не отдаётся. Включённая, карта показывает " +
          "только имя и место последней встречи — ни времени, ни счёта встреч, " +
          "ни приветствий. Включить: «panel.mapPeople: true» в bot.json";

    /// <summary>
    /// ГРАНИЦЫ ОКНА: квадрат, в который поместилось бы всё.
    ///
    /// Правило целиком:
    ///   • точек нет — отдаём самый тесный квадрат вокруг нуля; рисовать нечего,
    ///     и об этом говорит тот, кто звал, а не рамка;
    ///   • иначе берём охват всех точек, добавляем поля и округляем до квадрата;
    ///   • слишком широко (одна точка за три тысячи блоков) — упираемся в
    ///     <see cref="MaxSpan"/> и центрируемся на ЯКОРЕ, а не на середине
    ///     охвата: якорь — это бот, и потерять из виду его карте нельзя.
    /// </summary>
    /// <param name="marks">все точки, которые хотелось бы показать</param>
    /// <param name="anchor">
    /// Точка, которую нельзя терять при переполнении (обычно бот). null —
    /// центрируемся по середине охвата.
    /// </param>
    public static MapFrame Frame(IReadOnlyList<MapMark> marks, MapMark? anchor = null)
    {
        if (marks.Count == 0)
            return new MapFrame(anchor?.X ?? 0, anchor?.Z ?? 0, MinSpan);

        int minX = int.MaxValue, maxX = int.MinValue;
        int minZ = int.MaxValue, maxZ = int.MinValue;
        foreach (var m in marks)
        {
            if (m.X < minX) minX = m.X;
            if (m.X > maxX) maxX = m.X;
            if (m.Z < minZ) minZ = m.Z;
            if (m.Z > maxZ) maxZ = m.Z;
        }

        // Охват считаем в long: две точки по краям карты Vintage Story
        // расходятся на миллион блоков, и в int разность переполнилась бы
        long width = (long)maxX - minX;
        long height = (long)maxZ - minZ;
        long need = Math.Max(width, height) + 2L * Padding;

        int span = (int)Math.Clamp(need, MinSpan, MaxSpan);

        // Не влезло — держимся за якорь. Иначе бот уезжал бы за край
        // собственной карты из-за одной старой записи на другом конце мира
        if (need > MaxSpan && anchor is { } a)
            return new MapFrame(a.X, a.Z, span);

        // Середина охвата — среднее краёв, тоже в long: (minX + maxX) в int
        // переполняется на тех же дальних точках
        int centerX = (int)(((long)minX + maxX) / 2);
        int centerZ = (int)(((long)minZ + maxZ) / 2);
        return new MapFrame(centerX, centerZ, span);
    }

    /// <summary>Сколько точек не поместилось в окно — их человеку надо назвать числом.</summary>
    public static int Outside(IReadOnlyList<MapMark> marks, MapFrame frame)
    {
        int n = 0;
        foreach (var m in marks)
            if (!frame.Holds(m))
                n++;
        return n;
    }

    /// <summary>
    /// Место точки внутри окна долей от 0 до 1 — то, чем страница умножает
    /// ширину картинки.
    ///
    /// Считается ЗДЕСЬ, а не в браузере, ровно по одной причине: на этой доле
    /// проще всего перепутать ось Z с осью Y и получить карту, где склад стоит
    /// не там, где он есть. Вышедшее за края не подрезаем — подрезать решает
    /// тот, кто рисует, а врать о положении правило не вправе.
    /// </summary>
    public static double Fraction(int coord, int min, int span) =>
        span <= 0 ? 0.5 : (coord - (double)min) / span;

    /// <summary>
    /// Сколько блоков в одном делении сетки, чтобы делений вышло около десяти.
    ///
    /// Круглый шаг (10, 25, 50, 100, 250…) нужен затем, что подпись «через
    /// каждые 137 блоков» человеку не говорит ничего, а «каждые 100» —
    /// говорит сразу.
    /// </summary>
    public static int GridStep(int span)
    {
        if (span <= 0)
            return 1;
        int[] steps = [1, 2, 5, 10, 25, 50, 100, 250, 500, 1000];
        foreach (int step in steps)
            if (span / step <= 10)
                return step;
        return steps[^1];
    }
}
