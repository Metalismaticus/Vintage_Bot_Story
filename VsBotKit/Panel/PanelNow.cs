namespace VsBotKit.Panel;

/// <summary>Откуда взялось то, чем бот занят прямо сейчас.</summary>
public enum NowFrom
{
    /// <summary>Свободен: тело никто не держит и долгого дела нет.</summary>
    Idle,

    /// <summary>Это задача из очереди — она же стоит в списке ниже со своим номером.</summary>
    Queue,

    /// <summary>
    /// ДЕЛО НЕ ИЗ ОЧЕРЕДИ: приказ из чата, кнопка панели, рефлекс выживания,
    /// собственный наряд роли. Ради этого случая всё и написано — см.
    /// <see cref="PanelNow"/>.
    /// </summary>
    Outside
}

/// <summary>
/// ЧЕМ БОТ ЗАНЯТ ПРЯМО СЕЙЧАС — так, как это показывает вкладка «Задачи».
/// </summary>
/// <param name="From">откуда дело взялось</param>
/// <param name="Title">
/// Название дела. Берётся у ОЧЕРЕДИ НА ТЕЛО (<see cref="BodyArbiter.Busy"/>) —
/// той самой строкой, что стоит в шапке окна («занят: команда добудь»).
/// Своего названия панель не придумывает: два имени у одного дела означали бы,
/// что человек в шапке и в списке видит разное и не может их сопоставить.
/// </param>
/// <param name="Skill">какой навык при этом крутится (пусто — никакой)</param>
/// <param name="Number">номер задачи в очереди; 0 — дело не из очереди</param>
/// <param name="Id">имя задачи в очереди; пусто — дело не из очереди</param>
/// <param name="Reason">объяснение человеку одной строкой</param>
public sealed record PanelNow(NowFrom From, string Title, string Skill,
    int Number, string Id, string Reason)
{
    /// <summary>Есть чем занят. false — бот свободен.</summary>
    public bool Any => From != NowFrom.Idle;

    public override string ToString() => Reason;
}

/// <summary>
/// ТЕКУЩАЯ ЗАДАЧА ПЕРВОЙ СТРОКОЙ ОЧЕРЕДИ.
///
/// ОШИБКА ЗАКАЗЧИКА, ради которой это заведено (записана 09.08): «в активных
/// задачах сейчас не показывается текущая задача, а это ошибка».
///
/// Что было. Шапка окна честно писала «занят: команда добудь» — её она берёт у
/// очереди на тело (<see cref="BodyArbiter.Busy"/>). А вкладка «Задачи» рисует
/// СПИСОК ОЧЕРЕДИ (<see cref="WorkPlan"/>) и отмечает в нём «идёт» только ту
/// строку, которую пустил бегун. Приказ из чата, кнопка панели, наряд роли и
/// рефлекс выживания в очереди не лежат — и вкладка про них молчала. Человек
/// видел занятого бота и пустой список активных задач.
///
/// ПОЧЕМУ ЭТО ОТДЕЛЬНОЕ ЧИСТОЕ ПРАВИЛО, а не три строчки в разметке страницы.
/// Тут сходятся два разных источника — очередь на тело и бегун очереди, — и
/// сводить их надо ОДИН раз. Свести их в браузере значило бы, что правило
/// живёт в языке, которого не проверить тестом, а цена ошибки — снова пустая
/// вкладка при занятом боте.
/// </summary>
public static class PanelNowLine
{
    /// <summary>
    /// Свести шапку и очередь в одну строку «сейчас».
    ///
    /// Порядок ответов:
    ///   1) бегун ведёт задачу — она и есть текущая, называем её тем же именем,
    ///      что и очередь на тело, а номер даём из очереди;
    ///   2) тело занято, а бегун свободен — дело пришло со стороны; ЭТО И ЕСТЬ
    ///      пропавший случай;
    ///   3) тело свободно, но долгий навык крутится — так бывает у дел, которые
    ///      тела не берут (разбор сумки, разговор); молчать о них тоже нельзя;
    ///   4) всё пусто — так и говорим.
    /// </summary>
    /// <param name="bodyBusy">чем занята очередь на тело (BodyArbiter.Busy)</param>
    /// <param name="skill">какой навык крутится (SkillRunner.CurrentSkill)</param>
    /// <param name="queueJobName">имя задачи, которую ведёт бегун (пусто — не ведёт)</param>
    /// <param name="queueJobId">её ключ в очереди</param>
    /// <param name="queueNumber">её номер в очереди, с единицы</param>
    public static PanelNow Of(string? bodyBusy, string? skill,
        string? queueJobName = null, string? queueJobId = null, int queueNumber = 0)
    {
        string body = (bodyBusy ?? "").Trim();
        string what = (skill ?? "").Trim();
        string job = (queueJobName ?? "").Trim();
        string id = (queueJobId ?? "").Trim();

        if (job.Length > 0)
            return new PanelNow(NowFrom.Queue,
                // Название БЕРЁМ У ТЕЛА, когда оно есть: в шапке человек читает
                // именно его. Тела может и не быть (бегун только начал, дело
                // ещё не взяло тело) — тогда называем задачу её собственным
                // именем, а не придумываем третье
                body.Length > 0 ? body : job, what, queueNumber, id,
                $"идёт задача очереди «{job}»" +
                (queueNumber > 0 ? $" (она {queueNumber}-я по счёту)" : "") +
                (what.Length > 0 ? $", навык «{what}»" : ""));

        if (body.Length > 0)
            return new PanelNow(NowFrom.Outside, body, what, 0, "",
                $"бот занят делом «{body}»" +
                (what.Length > 0 ? $" (навык «{what}»)" : "") +
                " — оно пришло не из очереди: приказ из чата, кнопка окна, " +
                "наряд роли или спасение. В списке ниже его нет и не будет, " +
                "останавливают такое кнопкой «Остановить»");

        if (what.Length > 0)
            return new PanelNow(NowFrom.Outside, $"навык {what}", what, 0, "",
                $"идёт навык «{what}», но тела он не держит — очередь на тело " +
                "свободна, и перебить его нечем");

        return new PanelNow(NowFrom.Idle, "", "", 0, "",
            "бот ничем не занят — очередь можно пускать");
    }
}
