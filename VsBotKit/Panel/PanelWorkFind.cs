namespace VsBotKit.Panel;

/// <summary>
/// НАЙТИ РАБОТУ ПО ТОМУ СЛОВУ, КОТОРОЕ ЧЕЛОВЕК НАБРАЛ.
///
/// ЖИВОЙ ПРОГОН 15.08, ДОСЛОВНО: «команду копания тоннеля в вебформе не могу
/// найти». Она там БЫЛА — третьей строкой в списке видов работ. Но зовётся она
/// «Штольня до точки», а человек искал ТОННЕЛЬ, и список из шестнадцати
/// названий свёрнут в одну строчку выбора: пока не раскроешь и не прочтёшь всё
/// подряд, «штольни» не увидишь. Вот и вышло, что умение у бота есть, а
/// поручить его нечем — ровно та беда, от которой меню и заводили.
///
/// ПОЧЕМУ ЭТО ОТДЕЛЬНОЕ ЧИСТОЕ ПРАВИЛО, А НЕ ДЕСЯТЬ СТРОК В РАЗМЕТКЕ. Слова,
/// которыми человек ищет работу, — это его язык, а не язык механизма. Ошибка
/// здесь не рушит ничего громко: она просто ПРЯЧЕТ умение, и человек уходит
/// уверенный, что бот так не умеет. Такое ловится только стендом, поэтому
/// таблица слов и поиск по ней лежат отдельно и закрыты тестом.
///
/// ЧЕГО ЗДЕСЬ НЕТ. Здесь нет знания о том, что бот умеет: ни одного имени
/// навыка, ни одного вида работы. Меню составляет механизм
/// (<see cref="WorkMenu"/>), роль называет свои работы сама, а это правило
/// только сверяет НАБРАННОЕ СЛОВО с тем, что бот про работу уже сказал —
/// названием, описанием и именем навыка. Заведи роль новую работу — она
/// найдётся и без правки этой таблицы; таблица нужна лишь там, где
/// человеческое слово и слово бота РАЗНЫЕ.
/// </summary>
public static class PanelWorkFind
{
    /// <summary>
    /// СЛОВА ЧЕЛОВЕКА → СЛОВА БОТА. Слева то, что набирают; справа то, что
    /// вправду стоит в названиях и описаниях работ.
    ///
    /// Каждая строка здесь стоит за случаем, когда человек искал не тем словом,
    /// каким работа названа. Первая — заказчикова, дословно из живого прогона.
    /// Сравнение идёт по НАЧАЛУ слова («тоннел» ловит и «тоннель», и
    /// «тоннеля»), поэтому окончания не перечисляем.
    /// </summary>
    public static readonly IReadOnlyList<(string Набрал, string[] Значит)> Слова =
    [
        // «команду копания тоннеля в вебформе не могу найти» — а работа зовётся
        // «Штольня до точки»
        ("тоннел", ["штольн", "ход", "прокоп"]),
        ("туннел", ["штольн", "ход", "прокоп"]),
        ("штольн", ["штольн"]),
        ("шахт", ["штольн", "карьер", "разведк"]),
        ("прокоп", ["штольн", "ход"]),
        // Карьер человек чаще называет ямой или котлованом
        ("ям", ["карьер"]),
        ("котлован", ["карьер"]),
        ("копа", ["карьер", "штольн", "разведк", "ход"]),
        ("выкопа", ["карьер", "штольн"]),
        // «принеси меди» — это наряд, а слова «наряд» человек не набирает
        ("принес", ["наряд", "принест"]),
        ("добы", ["наряд", "руд", "принест"]),
        ("руд", ["наряд", "руд", "разведк"]),
        ("металл", ["наряд", "руд", "разведк"]),
        // Дорога и мощение
        ("мост", ["дорог", "полотн"]),
        ("мощ", ["дорог", "полотн"]),
        ("трасс", ["дорог"]),
        ("путь", ["дорог"]),
        // Еда, склад, снаряжение
        ("ед", ["сбор", "ягод", "гриб"]),
        ("ягод", ["сбор"]),
        ("гриб", ["сбор"]),
        ("сундук", ["склад", "разгрузк", "сдавать"]),
        ("склад", ["склад", "разгрузк"]),
        ("разгруз", ["разгрузк", "склад"]),
        ("кирк", ["снаряжен", "кирк"]),
        ("факел", ["снаряжен", "факел"]),
        ("инструмент", ["снаряжен", "кирк"]),
        ("развед", ["разведк", "штрек"])
    ];

    /// <summary>
    /// Подходит ли работа под набранное. Пустой запрос подходит ВСЕМУ: пустое
    /// поле поиска не должно прятать список — человек тогда решит, что работ
    /// нет вовсе.
    /// </summary>
    /// <param name="title">название работы, как её показывают</param>
    /// <param name="about">что бот про неё говорит</param>
    /// <param name="skill">имя навыка</param>
    /// <param name="query">что набрали в поиске</param>
    public static bool Matches(string? title, string? about, string? skill, string? query)
    {
        string набрано = Normalize(query);
        if (набрано.Length == 0)
            return true;

        string[] стог = Normalize($"{title} {about} {skill}")
            .Split(' ', StringSplitOptions.RemoveEmptyEntries);

        // Сперва прямое совпадение: человек набрал слово бота — и хватит
        foreach (string кусок in набрано.Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            if (ЕстьСлово(стог, кусок))
                continue;
            if (!ЧерезСловарь(стог, кусок))
                return false;   // хоть одно слово не нашлось — это не та работа
        }
        return true;
    }

    /// <summary>
    /// Начинается ли хоть одно слово бота на этот кусок.
    ///
    /// ИМЕННО СЛОВО, А НЕ ЛЮБОЕ МЕСТО В СТРОКЕ, и это не придирка: у карьера в
    /// описании стоит «выходит целыми блоками», и поиск по любому месту находил
    /// в нём «ход» — а значит, на слово «тоннель» человеку предлагался карьер.
    /// Подсказка, зовущая не туда, хуже отсутствия подсказки.
    /// </summary>
    private static bool ЕстьСлово(string[] стог, string кусок)
    {
        foreach (string слово in стог)
            if (слово.StartsWith(кусок, StringComparison.Ordinal))
                return true;
        return false;
    }

    /// <summary>
    /// Нашлось ли слово через таблицу «слова человека → слова бота».
    /// </summary>
    private static bool ЧерезСловарь(string[] стог, string кусок)
    {
        foreach (var (набрал, значит) in Слова)
        {
            // Сверяем по началу в обе стороны: «тон» должно ловить «тоннель»
            // (человек ещё дописывает), а «тоннеля» — строку «тоннел»
            if (!кусок.StartsWith(набрал, StringComparison.Ordinal) &&
                !набрал.StartsWith(кусок, StringComparison.Ordinal))
                continue;
            foreach (string слово in значит)
                if (ЕстьСлово(стог, слово))
                    return true;
        }
        return false;
    }

    /// <summary>
    /// Строка к одному виду: строчные буквы, «ё» как «е», лишние пробелы прочь.
    /// Без «ё» нельзя: половина людей набирает «еда» и «елка» без точек, и
    /// поиск молча не находил бы то, что лежит на виду.
    /// </summary>
    public static string Normalize(string? text) =>
        string.Join(' ', (text ?? "").ToLowerInvariant().Replace('ё', 'е')
            .Split([' ', '\t', '\n', '\r', ',', ';', '.', '(', ')', '«', '»', '"', ':', '—', '-'],
                StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries));
}
