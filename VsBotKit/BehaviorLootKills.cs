namespace VsBotKit;

/// <summary>
/// ЧТО БОТ СОБИРАЕТСЯ СДЕЛАТЬ С НАЙДЕННЫМ ТЕЛОМ.
///
/// Три дела здесь нарочно разведены, потому что в игре это ТРИ РАЗНЫХ
/// МЕХАНИЗМА: вещи с земли подбираются ногами, туша вскрывается ножом, а
/// вскрытая туша открывается как сундук. Одним «да/нет» их не описать: с рыбы
/// падает на землю филе И её же можно разделать, с саранчи падает всё и резать
/// нечего, а с дрифтера на землю не падает ничего вовсе.
/// </summary>
/// <param name="ПометитьМесто">
/// Сказать подбору «здесь упало»: за выпавшим на землю сходит он же, что и
/// после кирки, — второго подбора в проекте нет и не будет.
/// </param>
/// <param name="Разделать">Взять нож и вскрыть тушу.</param>
/// <param name="Забрать">Открыть уже вскрытую тушу и вынуть добычу.</param>
/// <param name="Почему">Человеческая причина — она и уходит в журнал.</param>
public readonly record struct KillLootChoice(bool ПометитьМесто, bool Разделать,
    bool Забрать, string Почему)
{
    /// <summary>С этим телом делать нечего.</summary>
    public bool Ничего => !ПометитьМесто && !Разделать && !Забрать;
}

/// <summary>
/// ЧИСТОЕ ПРАВИЛО «ЧТО ДЕЛАТЬ С УБИТЫМ» — одно на всех, без мира и без бота.
///
/// Живёт отдельной функцией нарочно: пока такой ответ складывался лесенкой
/// условий внутри способности, спросить его было нельзя ни человеку, ни
/// проверке — а он и есть всё поведение бота после боя.
/// </summary>
public static class KillLootRules
{
    /// <summary>
    /// ДОКУДА ИДТИ ЗА ДОБЫЧЕЙ ИМЕННО СЕЙЧАС — вопрос НЕ к голому расстоянию.
    ///
    /// ЖИВАЯ ЖАЛОБА ЗАКАЗЧИКА: бот две минуты стоял без единого дела, а вокруг
    /// лежали его же туши, и он про каждую сказал:
    ///   «до тела 14,8 бл, а дальше 8 я за добычей не хожу»
    ///   «до тела 10,2 бл, а дальше 8 я за добычей не хожу»
    /// Десять шагов до собственной добычи — и простой. Это не бережливость.
    ///
    /// ЧТО ЭТА РУЧКА БЕРЕЖЁТ НА САМОМ ДЕЛЕ — РАБОТУ, А НЕ НОГИ. Она и заведена
    /// была словами про работу: «сторожу у прилавка и пять блоков в сторону
    /// дороги, а охотнику и полсотни мало». Цена похода за тушей — это
    /// брошенный карьер, оставленный пост, недоведённая дорога; когда бросать
    /// нечего, цены нет, а значит нет и причины стоять. Голое расстояние ценой
    /// не было никогда: ходьба бота не стоит ничего, пока ему нечем заняться.
    ///
    /// ЧИСЛО РУЧКИ НЕ ТРОНУТО, И ТРОГАТЬ ЕГО НЕЛЬЗЯ (политика, хозяин один).
    /// Меняется не оно, а ВОПРОС, на который оно отвечает: «дальше скольких
    /// блоков я не брошу ради туши свою работу». Занят — предел ровно тот, что
    /// задал хозяин. Свободен — иду за тем, что вижу, и бесконечности тут не
    /// заводится: дальше своего осмотра бот туш не замечает вовсе.
    ///
    /// И РАЗ ВОПРОС ЗДЕСЬ «ЗАНЯТО ЛИ ТЕЛО», ТО ЗАНЯТОСТЬ ОБЯЗАНА БЫТЬ ПРАВДОЙ.
    /// Эта жалоба вернулась дословно, когда очередь задач стала брать тело НА
    /// ВСЮ ЗАДАЧУ: «занято» становилось ВСЕГДА — и пока бот шёл, и пока стоял,
    /// — а предел падал вдвое на всё это время. Чинилось не здесь: очередь
    /// берёт тело на поход (<c>WorkRunner.Legs</c>), и «занят» снова значит
    /// «и вправду занят». Правило же остаётся прежним, и трогать его не за что.
    ///
    /// ПОЧЕМУ ИМЕННО «ЗАНЯТО ЛИ ТЕЛО», А НЕ «ВАЖНО ЛИ ЗАНЯТИЕ». Разделка стоит
    /// на ступени <c>Urgent</c> и перебивает почти всё (туша сгниёт, камень
    /// нет) — спроси мы «важнее ли моё дело», ответ был бы «нет» почти всегда,
    /// и предел не работал бы ни при какой работе. А занятое тело — это ровно
    /// то, что поход за тушей у бота отнимет, и другого имени у этой цены нет.
    /// </summary>
    /// <param name="дальшеНеХодим">Ручка роли, блоков. Ноль — предела нет.</param>
    /// <param name="видноНеДальше">
    /// Докуда бот вообще замечает туши (у способности это осмотр вдвое шире
    /// предела похода). Своего числа здесь нет нарочно: идти за тем, чего не
    /// видел, бот не может, и это и есть естественный потолок свободного.
    /// </param>
    /// <param name="занятДелом">
    /// Чем занято тело прямо сейчас (пусто — ничем). Имя уходит в причину как
    /// есть: человек должен прочитать, ЧТО именно бот сберёг.
    /// </param>
    public static (double Предел, string Почему) HowFarToGo(
        double дальшеНеХодим, double видноНеДальше, string занятДелом)
    {
        if (дальшеНеХодим <= 0)
            return (0, "предела за добычей мне не задано");
        if (занятДелом.Length > 0)
            return (дальшеНеХодим,
                $"я занят делом «{занятДелом}», и дальше {дальшеНеХодим:0} бл его ради туши не бросаю");
        double свободному = Math.Max(дальшеНеХодим, видноНеДальше);
        return (свободному,
            $"дел у меня сейчас нет, а {дальшеНеХодим:0} бл — это предел брошенной работы, " +
            $"не моих ног: иду за всем, что вижу ({свободному:0} бл)");
    }

    /// <param name="подбирать">Ручка роли: подбирать ли выпавшее из убитых.</param>
    /// <param name="разделывать">Ручка роли: разделывать ли туши.</param>
    /// <param name="разделываема">
    /// Игра даёт эту тварь разделать (см. <see cref="Butchering.CanBeButchered"/>).
    /// </param>
    /// <param name="ужеРазделана">Флаг «harvested» от сервера.</param>
    /// <param name="естьЧтоЗабрать">
    /// В ТУШЕ ЕЩЁ ЧТО-ТО ЛЕЖИТ (<see cref="Butchering.HasLoot"/>). Спрашивается
    /// у разделки, своей мерки здесь нет: две мерки уже разъезжались, и живой
    /// журнал 19.08 в 18:33:51 сказал за одну секунду «туша уже вскрыта —
    /// забираю добычу», «иду разделывать: туш 1, ближайшая в 1,1 бл» и «туш в
    /// радиусе 12 бл не нашёл». Опись не пришла — считаем «есть»: соврать «там
    /// пусто», не заглянув, значит бросить добычу.
    /// </param>
    /// <param name="естьНож">Нож лежит в сумках.</param>
    /// <param name="доТела">Сколько до тела блоков.</param>
    /// <param name="дальшеНеХодим">
    /// За добычей с убитых дальше этого не ходим, блоков. Ноль — предела нет.
    ///
    /// ЭТО ПРЕДЕЛ, ДЕЙСТВУЮЩИЙ СЕЙЧАС, а не голое число ручки: считает его
    /// <see cref="HowFarToGo"/>, и зависит он от того, есть ли у бота работа,
    /// которую поход за тушей бросит.
    /// </param>
    public static KillLootChoice Decide(bool подбирать, bool разделывать,
        bool разделываема, bool ужеРазделана, bool естьЧтоЗабрать, bool естьНож,
        double доТела, double дальшеНеХодим)
    {
        if (!подбирать && !разделывать)
            return new KillLootChoice(false, false, false,
                "и подбор с убитых, и разделка выключены настройкой");

        // СТОИТ ЛИ ОВЧИНКА ВЫДЕЛКИ — мерит роль, а не библиотека: сторожу у
        // прилавка и пять блоков в сторону дороги, а охотнику и полсотни мало.
        // Само правило ОДНО на всю добычу и живёт у подбора
        // (<see cref="Pickup.TooFarToGo"/>): здесь была его первая копия, а
        // вторая заводилась для помеченных мест — с теми же числами и другими
        // словами
        if (Pickup.TooFarToGo("тела", доТела, дальшеНеХодим) is { } далеко)
            return new KillLootChoice(false, false, false, далеко);

        // ВЫПАВШЕЕ НА ЗЕМЛЮ БЫВАЕТ И У РАЗДЕЛЫВАЕМЫХ. У рыбы в описании
        // сущности есть и drops (филе падает на землю), и harvestable — если
        // помечать место только неразделываемым, филе так и останется лежать
        bool пометить = подбирать;

        if (!разделывать)
            return new KillLootChoice(пометить, false, false,
                "разделка выключена — беру только то, что упало на землю");

        if (!разделываема)
            return new KillLootChoice(пометить, false, false,
                "разделывать нечего: что с него причиталось, выпало на землю");

        if (ужеРазделана)
            return естьЧтоЗабрать
                ? new KillLootChoice(пометить, false, true,
                    "туша уже вскрыта — забираю добычу")
                // ПУСТАЯ ВСКРЫТАЯ ТУША — НЕ ПОВОД ИДТИ. Она лежит ещё
                // несколько игровых часов (EntityBehaviorDeadDecay), и без
                // этой развилки бот объявлял поход к ней каждый заход, а обход
                // тут же отвечал «туш не нашёл» — то самое враньё 19.08
                : new KillLootChoice(пометить, false, false,
                    "туша вскрыта и пуста — забирать нечего");

        if (!естьНож)
            // ТА ЖЕ СТРОКА, ЧТО У ОБХОДА, И ЭТО НЕ УКРАШЕНИЕ. Здесь стоял
            // голый отказ «ножа нет», и человек, видящий в сумке «Лезвие
            // ножа», читал его как враньё — ровно то, ради чего разделку и
            // переводили с букв кода на реестр игры
            return new KillLootChoice(пометить, false, false, Butchering.НечемРезать());

        return new KillLootChoice(пометить, true, true, "разделываю и забираю");
    }
}

/// <summary>
/// «УБИЛ — ЗАБЕРИ»: добыча с убитых.
///
/// ЗАЧЕМ ЗАВЕДЕНА. Прямые слова заказчика: «Нужно подбирать выпавшие вещи из
/// мобов и разделывать их (отдельная настройка)». В живом журнале 16.08 это
/// видно во всей красе — двенадцать строк «drifter-normal повержен» за смену
/// и НИ ОДНОЙ строки о добыче: бот убивал и уходил. Половины механизмов при
/// этом давно были на месте (подбор с земли, разделка ножом, бой) — не было
/// того, кто скажет им «а теперь забери».
///
/// ЧТО ЗДЕСЬ СВОЕГО, А ЧТО ЧУЖОЕ. Своего — ровно одно: ЗАМЕТИТЬ СВЕЖЕЕ ТЕЛО.
/// Дальше способность только раздаёт работу тем, кто её умеет:
/// <list type="bullet">
/// <item>выпавшее на землю — пометкой места (<see cref="Pickup.Note"/>), и за
/// ним сходит тот же подбор, что и после кирки. Второго подбора здесь нет
/// нарочно: одна механика живёт в одном месте;</item>
/// <item>туша — <see cref="Butchering"/>: нож, удержание кнопки, флаг
/// «harvested» от сервера и перенос из туши общим слоем хранилищ.</item>
/// </list>
///
/// ЧЬИМ ТЕЛОМ ИДЁТ РАЗДЕЛКА — И ПОЧЕМУ ЭТО ПЕРЕПИСАНО 29.08.
///
/// Здесь стояло: тело берётся обычной важностью (Routine), «посреди карьера
/// разделка НЕ НАЧНЁТСЯ, и это правильно: бросать наряд ради шкуры нельзя».
/// Плата была названа честно тут же — и она оказалась не платой, а бедой.
/// Живые слова заказчика 28.08: «трупы остаются с вещами и не исчезают».
/// Карьер держит тело как Command(10), разделка просила его как Routine(0),
/// меньший не перебивает — и разделка ЖДАЛА все три игровых часа, которые
/// отведены туше дрифтера (deaddecay, hoursToDecay: 3; при обычной скорости
/// времени это шесть реальных минут). Туша пропадала вместе с добычей: на
/// землю из неё не выпадает ничего.
///
/// РЕШЕНИЕ ХОЗЯИНА: РАЗДЕЛКА ПЕРЕБИВАЕТ РАБОТУ. Причина простая и проверяемая
/// — камень никуда не денется, а туша сгниёт. Ручка роли
/// («РазделкаПеребиваетРаботу») заводским значением стоит именно так, и её
/// можно перевернуть; сама способность берёт тело важностью
/// <see cref="BodyArbiter.Importance.Urgent"/> (см. <see cref="Level"/>).
///
/// ЧЕГО ЭТО НЕ ДЕЛАЕТ, И ЭТО ГЛАВНОЕ. Urgent стоит ВЫШЕ приказа, но НИЖЕ
/// рефлекса и дела жизни: бой, побег, укрытие, еда и лечение перебивают
/// разделку в ту же секунду — в том числе событием
/// (<see cref="BodyArbiter.MakeWay"/>), не дожидаясь своей очереди в обходе
/// способностей. Бот, погибший над тушей, был бы ценой куда дороже шкуры, и
/// такой размен здесь запрещён устройством, а не оговоркой.
///
/// СРОК СПРАШИВАЕТСЯ У ИГРЫ, а не выдумывается: сколько туше осталось лежать,
/// считает <see cref="Butchering.СрокТуши"/> по часу смерти от сервера и по
/// <c>hoursToDecay</c> из описания сущности. Поэтому и отказ, и размен звучат
/// числом — «туша сгниёт через 5,4 мин», — а не общими словами.
///
/// Числа и «стоит ли овчинка выделки» — ручки роли (LivingRole:
/// «ПодбиратьДобычуСУбитых», «РазделыватьТуши», «ЗаДобычейСУбитыхНеДальше»,
/// «РазделкаПеребиваетРаботу»).
/// </summary>
public class BehaviorLootKills : BotBehavior
{
    private readonly BotContext ctx;
    private readonly Butchering butchering;

    /// <summary>
    /// Места, помеченные для подбора: тело → когда пометили. Пометка обязана
    /// лечь РОВНО ОДИН РАЗ, иначе бот будет гонять подбор к одной и той же
    /// луже крови до самого распада туши.
    /// </summary>
    private readonly Dictionary<long, DateTime> noted = [];

    /// <summary>
    /// Что мы уже сказали про это тело. Повторять одно и то же нельзя, а вот
    /// ПЕРЕМЕНИВШЕЕСЯ сказать надо сразу — это то же правило, по которому бот
    /// говорит про разломы. Живой случай прямо здесь: тело за пределом
    /// («далеко, не хожу») перестаёт быть далёким, как только бот к нему
    /// подошёл, и молчать об этом значило бы забыть его навсегда.
    /// </summary>
    private readonly Dictionary<long, (DateTime When, string Said)> told = [];

    /// <summary>
    /// Туши, с которых заход ничего не дал, и почему. Сюда же уходит и «до тела
    /// далеко, не пойду».
    ///
    /// СЧЁТ НЕ СВОЙ, И ЭТО ГЛАВНОЕ. Пояснение к <see cref="RetryFailedSeconds"/>
    /// прямо признавалось копией: «та же мерка, что у подбора». Копией оно и
    /// было — третьей по счёту в дереве. Теперь у правила «раз не вышло, не
    /// долби каждый раз, но и не забывай навсегда» один дом
    /// (<see cref="Hopeless{TKey}"/>), а потребителей трое: снабжение (ключ —
    /// код вещи), подбор с земли и эта разделка.
    ///
    /// КЛЮЧ — «КОД #НОМЕР», А НЕ ГОЛЫЙ НОМЕР. Ключ уходит в строку вслух
    /// (<see cref="Alarm.About"/>), и «4318: до тела 23,5 бл» человеку не
    /// говорит ничего, а «drifter-normal #4318» говорит всё. Номер в ключе
    /// остаётся: двух дрифтеров рядом различает только он.
    /// </summary>
    private readonly Hopeless failed = new();

    /// <summary>
    /// ТУШИ ЗА ПРЕДЕЛОМ ПОХОДА: про какую мы уже сказали «далеко, не иду».
    ///
    /// ПОЧЕМУ ОТДЕЛЬНО ОТ <see cref="failed"/>, А НЕ ТЕМ ЖЕ СЧЁТОМ. Механизм тот
    /// же (<see cref="VsBotKit.Hopeless{TKey}"/>) и заведён он именно для таких
    /// случаев, а вот ВОПРОСЫ разные, и сроки у них разные. «Заход ничего не
    /// дал» проходит само собой по времени (яму засыпали, нож нашёлся) —
    /// поэтому там срок. «Тело далеко» проходит РОВНО ОДНИМ СПОСОБОМ: бот
    /// подошёл ближе, — и тогда отбой обязан прозвучать сразу, а не через две
    /// минуты.
    ///
    /// Сведи их в один счёт — и «подошёл ближе» стирало бы память о туше, до
    /// которой не дойти, на каждом такте: бот ходил бы к ней кругами до самого
    /// распада. Ровно это и вылезло красным на стенде, когда счёт был один.
    /// </summary>
    private readonly Hopeless далёкие = new();

    private DateTime nextTry = DateTime.MinValue;
    private readonly LogRepeats quiet = new();

    public BehaviorLootKills(BotContext ctx, Butchering butchering)
    {
        this.ctx = ctx;
        this.butchering = butchering;
        // У механизма своё умолчание (десять минут — мерка снабжения), а туша
        // распадается за три игровых часа: свой срок ставим сразу
        failed.TryAgainAfter = TimeSpan.FromSeconds(retryFailedSeconds);
        далёкие.TryAgainAfter = TimeSpan.FromSeconds(retryFailedSeconds);
        // ОТКАЗ БЕЗНАДЁГИ БЫЛ НЕМЫМ: на failed.OnSay не подписывался никто, и
        // «к этой туше больше не иду» не доходило до человека ни разу
        failed.OnSay += why => OnRefused?.Invoke(why);
        далёкие.OnSay += why => OnRefused?.Invoke(why);
    }

    /// <summary>Подбирать выпавшее из убитых (решение роли).</summary>
    public bool PickUpDrops { get; set; } = true;

    /// <summary>Разделывать туши ножом и забирать из них добычу (решение роли).</summary>
    public bool Butcher { get; set; } = true;

    /// <summary>
    /// Дальше этого за добычей с убитых не ходить, блоков (0 — предела нет).
    ///
    /// ЧТО ИМЕННО МЕРИТ ЭТО ЧИСЛО — не ноги, а РАБОТУ, которую поход за тушей
    /// бросит: разбор и живая жалоба у <see cref="KillLootRules.HowFarToGo"/>.
    /// Свободному телу оно хода не запрещает.
    /// </summary>
    public double Radius { get; set; } = 12;

    /// <summary>
    /// ПЕРЕБИВАТЬ ЛИ РАБОТУ РАДИ РАЗДЕЛКИ (решение роли).
    ///
    /// Включено — потому что так решил хозяин бота, и решение у него простое:
    /// камень никуда не денется, а туша сгниёт. Выключено — разделка становится
    /// обычным делом роли и честно ждёт, пока освободится тело; сколько при
    /// этом осталось туше, бот всё равно скажет вслух.
    /// </summary>
    public bool PreemptWork { get; set; } = true;

    /// <summary>
    /// КАКОЙ ВАЖНОСТЬЮ БЕРЁТСЯ ТЕЛО — одна строка на всю способность, и второй
    /// нет нарочно: спрашивают её двое (сам захват и предсказание «перебьём ли
    /// кого-то»), и разъедься они, бот объявлял бы размен, которого не было.
    ///
    /// <see cref="BodyArbiter.Importance.Urgent"/> — выше приказа (карьер,
    /// дорога, «!иди»), ниже рефлекса (бой, побег) и дела жизни (еда, лечение).
    /// Разбор, почему не Reflex и почему не Command, — у самой ступени.
    /// </summary>
    public BodyArbiter.Importance Level => PreemptWork
        ? BodyArbiter.Importance.Urgent
        : BodyArbiter.Importance.Routine;

    /// <summary>
    /// Пауза между заходами. Без неё способность лезет за телом каждые полтакта
    /// и мешает и себе, и соседям.
    /// </summary>
    public double CooldownSeconds { get; set; } = 3;

    /// <summary>
    /// Сколько молчать, когда заход НИЧЕГО не дал. Отказ («ножа нет») обязан
    /// прозвучать, но раз в полминуты, а не дважды в секунду: именно такими
    /// повторами журнал заказчика и заливало.
    /// </summary>
    public double RetryAfterNothingSeconds { get; set; } = 30;

    /// <summary>
    /// Через сколько секунд снова пробовать тушу, с которой ничего не вышло.
    /// Две минуты — та же мерка, что у подбора (<see cref="Pickup.RetryFailedSeconds"/>):
    /// мир меняется, но не каждые полминуты. Ноль — не помнить неудач вовсе.
    ///
    /// Мерка та же, а СЧЁТ теперь общий: оба числа доводятся до одного механизма
    /// <see cref="Hopeless{TKey}"/>, и разъехаться им больше нечем.
    /// </summary>
    public double RetryFailedSeconds
    {
        get => retryFailedSeconds;
        set
        {
            retryFailedSeconds = value;
            failed.TryAgainAfter = TimeSpan.FromSeconds(Math.Max(0, value));
            далёкие.TryAgainAfter = TimeSpan.FromSeconds(Math.Max(0, value));
        }
    }

    private double retryFailedSeconds = 120;

    /// <summary>Через сколько минут забывать разобранное тело (память не резиновая).</summary>
    public double ForgetBodiesMinutes { get; set; } = 20;

    /// <summary>Решение по одному телу: код твари и что с ней делаем.</summary>
    public event Action<string, KillLootChoice>? OnBody;

    /// <summary>
    /// ПОШЁЛ К ТУШАМ: сколько их и как далеко ближайшая. Говорится ДО первого
    /// шага и КАЖДЫЙ раз — в отличие от <see cref="OnBody"/>, который молчит,
    /// пока решение по телу не переменилось.
    ///
    /// Молчаливый уход и есть та беда, на которую жаловался человек: «я дома», а
    /// через три секунды бот за одиннадцать блоков и ни строчки о том, зачем
    /// (журнал 18.08, 00:17:36 → 00:17:39).
    /// </summary>
    public event Action<int, double>? OnGoing;

    /// <summary>Чем кончился обход туш.</summary>
    public event Action<ButcherReport>? OnButchered;

    /// <summary>Отказ, который надо назвать вслух (тело занято, ножа нет).</summary>
    public event Action<string>? OnRefused;

    /// <summary>
    /// БРОСИЛ РАБОТУ РАДИ ТУШИ — и сказал, чью и почему.
    ///
    /// Отдельно от <see cref="OnRefused"/> нарочно: это не отказ, а РАЗМЕН, и
    /// человеку он читается наоборот. Распорядитель тела печатает своё
    /// «„разделка“ важнее — прерываю „команда карьер“», но в нём нет главного —
    /// СКОЛЬКО ОСТАЛОСЬ ТУШЕ. Без этого числа размен выглядит капризом; с ним
    /// он и есть тот расчёт, ради которого ступень заводилась.
    /// </summary>
    public event Action<string>? OnPreempted;

    public override async Task<bool> TickAsync(CancellationToken ct)
    {
        if (!PickUpDrops && !Butcher)
            return false;
        if (DateTime.UtcNow < nextTry)
            return false;
        if (ctx.Self.Position is not { } me)
            return false;
        // Мёртвый не подбирает и не режет: сервер не отдаёт вещи мёртвым
        // (то же условие, что и у подбора с земли)
        if (ctx.Self.Health is { } hp && hp <= 0)
            return false;

        // Осматриваем ШИРЕ предела похода: тело в двадцати блоках мы видим и
        // обязаны сказать о нём «далеко», а не делать вид, что его нет
        double look = Radius > 0 ? Radius * 2 : 32;

        // ДОКУДА ХОДИМ ЗА ДОБЫЧЕЙ ИМЕННО СЕЙЧАС. Спрашиваем ОДИН РАЗ НА ОБХОД
        // и одним правилом на оба вопроса — и «стоит ли говорить „далеко“», и
        // «что делать с телом» (<see cref="KillLootRules.Decide"/>). Разъедься
        // они, и бот объявлял бы поход к туше, которую сам же считает далёкой:
        // ровно так и жил этот файл, пока предел был записан в двух местах
        var (предел, почемуПредел) = KillLootRules.HowFarToGo(Radius, look, ctx.Turn.Busy);
        var кандидаты = new List<string>();
        double ближайшая = double.PositiveInfinity;
        // САМА БЛИЖАЙШАЯ ТУША, А НЕ ТОЛЬКО РАССТОЯНИЕ ДО НЕЁ: у неё спрашивают
        // срок распада, и спрашивают ИМЕННО У БЛИЖАЙШЕЙ — к ней бот и пойдёт
        EntityInfo? ближняя = null;
        foreach (var body in ctx.Entities.Nearby(me.X, me.Y, me.Z, look).ToList())
        {
            if (!butchering.IsCarcass(body))
                continue;

            string ключ = Ключ(body);

            // ДАЛЕКО — ЭТО ОДНА НОВОСТЬ, А НЕ ДВАДЦАТЬ В СЕКУНДУ.
            //
            // Живой случай (журнал 17.08, 23:48:05–23:48:12): восемнадцать строк
            // за семь секунд про две туши —
            //   до тела 13,8 бл … до тела 12,1 бл … до тела 14,3 бл …
            // Отказ был честный, а вот «уже говорил» — сломано: сравнивалась
            // ГОТОВАЯ СТРОКА, а в ней тикает расстояние. Бот шевельнулся на
            // десять сантиметров — и строка «другая», значит новость. Тем же
            // концом эта беда бьёт и по Alarm внутри Hopeless: спрашивать надо
            // не «та же ли строка», а «сдались ли мы уже про это тело» —
            // то есть Given ДО GiveUp
            if (Pickup.TooFarToGo("тела", body.DistanceTo(me.X, me.Y, me.Z), предел)
                is { } далеко)
            {
                if (!далёкие.Given(ключ))
                    далёкие.GiveUp(ключ, $"{далеко} — {почемуПредел}");
                continue;
            }
            // Подошли ближе — отбой вслух: молчаливое возвращение к туше, от
            // которой только что отказались, человек читает как метание
            далёкие.TryAgain(ключ, "подошёл ближе — за добычей иду");

            var выбор = KillLootRules.Decide(
                подбирать: PickUpDrops,
                разделывать: Butcher,
                разделываема: Butchering.CanBeButchered(body),
                ужеРазделана: Butchering.IsHarvested(body),
                // МЕРКА «ЕСТЬ ЛИ ЗА ЧЕМ ИДТИ» — ОДНА И ЖИВЁТ У РАЗДЕЛКИ.
                // Своей здесь нет нарочно: пока их было две, обход туш
                // отвечал «не нашёл» на тушу, к которой эта же способность
                // секундой раньше объявила поход (журнал 19.08, 18:33:51)
                естьЧтоЗабрать: butchering.HasLoot(body),
                естьНож: butchering.HasKnife,
                доТела: body.DistanceTo(me.X, me.Y, me.Z),
                // ТОТ ЖЕ ПРЕДЕЛ, ЧТО И У ОТКАЗА ВЫШЕ, а не голая ручка:
                // считает его KillLootRules.HowFarToGo один раз на обход
                дальшеНеХодим: предел);

            // ПЕРЕМЕНИЛОСЬ — СКАЗАЛИ, а одно и то же дважды не повторяем
            if (!told.TryGetValue(body.Id, out var было) || было.Said != выбор.Почему)
            {
                told[body.Id] = (DateTime.UtcNow, выбор.Почему);
                OnBody?.Invoke(body.Code, выбор);
            }

            // МЕСТО ПОМЕЧАЕМ РОВНО ОДИН РАЗ — и не «когда впервые увидели», а
            // КОГДА РЕШИЛИ ЗА НИМ ИДТИ. Разница живая: тело, впервые увиденное
            // за пределом похода, при первой же встрече не помечается, и
            // пометить его надо, когда бот к нему подойдёт
            if (выбор.ПометитьМесто && !noted.ContainsKey(body.Id))
            {
                noted[body.Id] = DateTime.UtcNow;
                ctx.Pickup.Note(new BlockPos((int)Math.Floor(body.X),
                    (int)Math.Floor(body.Y), (int)Math.Floor(body.Z)));
            }

            // А вот резать можно и не в первый тик: нож мог найтись позже,
            // и туша ждёт нас до самого распада. Кроме той, на которой мы уже
            // обожглись: к туше за стеной или в яме бот иначе ходил бы каждые
            // полминуты до самого её распада — ровно та беготня, от которой
            // подбор бережётся своей памятью о неудачах (Pickup.GaveUpOn)
            if ((выбор.Разделать || выбор.Забрать) && !ГиблоеДело(ключ))
            {
                кандидаты.Add(ключ);
                double бл = body.DistanceTo(me.X, me.Y, me.Z);
                if (бл < ближайшая)
                {
                    ближайшая = бл;
                    ближняя = body;
                }
            }
        }
        ForgetOldBodies();

        if (кандидаты.Count == 0)
            return false;

        nextTry = DateTime.UtcNow.AddSeconds(CooldownSeconds);

        // СКОЛЬКО ОСТАЛОСЬ ТУШЕ — СПРАШИВАЕМ ДО ЗАХВАТА ТЕЛА, потому что число
        // это нужно ОБОИМ исходам: и размену («бросаю копать»), и отказу
        // («жду»). Спрашиваем у разделки — своей мерки распада здесь нет
        string срок = ближняя is { } тело ? butchering.СрокТуши(тело) : "";

        // КОГО ПЕРЕБИВАЕМ — ЗАПОМИНАЕМ ЗАРАНЕЕ: после удачного захвата тело уже
        // наше, и спросить «а кто держал его секунду назад» будет не у кого
        string держал = ctx.Turn.Busy;
        bool перебиваем = держал.Length > 0 && ctx.Turn.BusyWith is { } чем && Level > чем;

        using var hold = ctx.Turn.TryTake("разделка", Level, ct);
        if (hold == null)
        {
            // Молчать нельзя: со стороны это «бот прошёл мимо туши». Но и
            // повторять каждые три секунды нельзя — туша ждёт часами.
            //
            // СРОК НАЗЫВАЕТСЯ И В ОТКАЗЕ, а не только в размене. Без него
            // человек читает «разделка ждёт» как «подождёт и сделает», а туша
            // ждать не умеет: пропав, она унесёт добычу с собой. Это же число —
            // единственный честный способ показать цену выключенной ручки
            // «РазделкаПеребиваетРаботу»
            Say($"туши рядом есть, а тело занято делом «{ctx.Turn.Busy}» — разделка ждёт" +
                (срок.Length > 0 ? $"; {срок}" : ""));
            nextTry = DateTime.UtcNow.AddSeconds(RetryAfterNothingSeconds);
            return false;
        }

        // БРОСИЛИ ЧУЖУЮ РАБОТУ — СКАЗАЛИ, ЧЬЮ И ПОЧЕМУ. Распорядитель тела
        // напечатал своё «„разделка“ важнее — прерываю „команда карьер“», но
        // ПОЧЕМУ важнее, знает только эта способность: у неё на руках срок
        if (перебиваем)
            OnPreempted?.Invoke($"бросаю «{держал}»: {(срок.Length > 0 ? срок : "туша ждать не может")}" +
                                " — камень никуда не денется, а туша пропадёт вместе с добычей");

        // КУДА И ЗАЧЕМ УШЁЛ — ДО ПЕРВОГО ШАГА И КАЖДЫЙ РАЗ.
        //
        // Живой случай (журнал 18.08), дословно:
        //   00:17:36 [укрытие] дома, дверь (512061, 112, 512252) закрыта
        //   00:17:36 я дома
        //   00:17:39 [движение] дорога: 2 точек до (512064, 112, 512244)
        // Через три секунды после «я дома» бот ушёл за одиннадцать блоков — к
        // туше дрифтера на (512064, 111, 512243), и понять это по журналу можно
        // было только сверив координаты руками. Сама-то способность про эту
        // тушу уже говорила («разделываю и забираю», 00:17:16), но повтор она
        // глушит по неизменившейся причине — и УХОД выходил немым
        OnGoing?.Invoke(кандидаты.Count, double.IsInfinity(ближайшая) ? 0 : ближайшая);

        // ОБХОД ИДЁТ ДО ТОГО ЖЕ ПРЕДЕЛА, ЧТО И РЕШЕНИЕ ПО ТЕЛУ. Здесь стояла
        // голая ручка, и с ней починка была бы обманом: бот объявлял бы поход
        // к туше в 14,8 бл и тут же искал её в восьми — то самое «объявил
        // поход и не нашёл», на которое жаловался журнал 19.08
        var report = await butchering.ButcherNearbyAsync(
            предел > 0 ? предел : 32, hold.Token);
        OnButchered?.Invoke(report);
        if (!report.Any)
        {
            // Заход впустую (не дойти, туша пуста) — не долбиться в него
            // каждые три секунды и не возвращаться к этим тушам ещё две минуты
            nextTry = DateTime.UtcNow.AddSeconds(RetryAfterNothingSeconds);
            foreach (string ключ in кандидаты)
                failed.GiveUp(ключ, report.Why.Length > 0 ? report.Why : "заход ничего не дал");
        }
        return report.Any;
    }

    /// <summary>
    /// ЧЕМ ЭТА ТУША ЗОВЁТСЯ В ОТКАЗЕ. Код без номера слил бы двух дрифтеров
    /// рядом в один, номер без кода ничего не говорит человеку — а ключ уходит
    /// в строку вслух как есть.
    /// </summary>
    private static string Ключ(EntityInfo body) => $"{body.Code} #{body.Id}";

    /// <summary>
    /// На этой туше мы уже обожглись и пока к ней не идём. Мир меняется —
    /// яму могли засыпать, — но не каждые полминуты.
    /// </summary>
    private bool ГиблоеДело(string ключ) => failed.Given(ключ);

    /// <summary>Сказать один раз, а повторы посчитать (см. <see cref="LogRepeats"/>).</summary>
    private void Say(string message)
    {
        if (quiet.Say(message, DateTime.UtcNow) is { } line)
            OnRefused?.Invoke(line);
    }

    /// <summary>
    /// Забыть давние тела. Туша распадается сама (у дрифтера — три игровых
    /// часа), и держать её id вечно значит копить память ни о чём.
    /// </summary>
    private void ForgetOldBodies()
    {
        // Про «гиблые» тела здесь не сказано ни слова нарочно: их выметает сам
        // механизм безнадёги (Hopeless.Remember), и второй мерки забывания у
        // них быть не должно — иначе туша, которой ещё рано на вторую попытку,
        // молча вернулась бы в обход
        if (noted.Count < 64 && told.Count < 64)
            return;
        var порог = DateTime.UtcNow.AddMinutes(-Math.Max(1, ForgetBodiesMinutes));
        foreach (long id in noted.Where(p => p.Value < порог).Select(p => p.Key).ToList())
            noted.Remove(id);
        foreach (long id in told.Where(p => p.Value.When < порог).Select(p => p.Key).ToList())
            told.Remove(id);
    }
}
