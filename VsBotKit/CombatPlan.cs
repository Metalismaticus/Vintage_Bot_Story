namespace VsBotKit;

/// <summary>
/// ЧТО МЕЖДУ НАМИ — преграда или ничего.
///
/// Дословно от заказчика: «не лезть в бой если ты в доме с закрытой дверью
/// (вас разделяет дверь или блоки), ты спрятался от шторма и вас разделяют
/// блоки или дверь — должно быть так».
///
/// ЧЕМ ЭТО ПОДТВЕРЖДЕНО В САМОЙ ИГРЕ (сборки 1.22.6, не выдумка):
///   • тварь бьёт только по прямой видимости. И ближний бой, и стрельба
///     проходят через AiTaskBaseTargetable.hasDirectContact, а он пускает
///     World.RayTraceForSelection из глаз твари в бота и требует, чтобы луч
///     НИ ВО ЧТО не упёрся (blockSel == null). Стена или закрытая дверь между
///     нами — и тварь не достанет бота ничем;
///   • СЕРВЕР ЖЕ САМ такого луча по игроку НЕ проверяет:
///     ServerSystemEntitySimulation.HandleEntityInteraction (пакет 17) меряет
///     только расстояние до бокса и права. То есть удар сквозь стену сервер
///     ЗАСЧИТАЕТ — но живой игрок так не может, и это ровно тот чит, которого
///     в проекте быть не должно.
/// </summary>
public enum CombatBarrier
{
    /// <summary>Между нами ничего: он достанет меня, я достану его.</summary>
    None,

    /// <summary>
    /// Закрытая дверь. Особый вид преграды: бот её открывать УМЕЕТ, а тварь —
    /// нет. В игре дверь поворачивает BEBehaviorDoor.ToggleDoorState(IPlayer
    /// byPlayer, …) — только игрок; ни одной задачи ИИ, которая открывала бы
    /// или ломала дверь, в VSEssentials и VSSurvivalMod нет, а путь тварям
    /// считает Vintagestory.Essentials.AStar по коллизиям и про двери не знает
    /// вовсе. Значит закрытая дверь для твари — глухая стена.
    /// </summary>
    Door,

    /// <summary>Блоки: стена, земля, потолок, заложенный проход.</summary>
    Blocks
}

/// <summary>Что бот делает с этим противником прямо сейчас.</summary>
public enum CombatChoice
{
    /// <summary>Драться: подойти, если надо, и бить.</summary>
    Fight,

    /// <summary>Уходить: оторваться на безопасное расстояние.</summary>
    Flee,

    /// <summary>Заложить проход блоком — когда оторваться не выйдет.</summary>
    Seal,

    /// <summary>Не связываться: заниматься своим делом.</summary>
    Ignore,

    /// <summary>
    /// Загнан: ни уйти, ни закрыться, а драться не вытяну — но и стоять
    /// нельзя. Дерусь тем, что есть, и говорю об этом вслух.
    /// </summary>
    Cornered
}

/// <summary>
/// ЧЕМ КОНЧИЛАСЬ СТЫЧКА. Три разных исхода, и путать их нельзя: «повержен» —
/// это заявка на победу, и она обязана опираться на факт от сервера.
/// </summary>
public enum CombatEnd
{
    /// <summary>Сервер прислал его здоровье, и оно упало до нуля.</summary>
    Defeated,

    /// <summary>Живой и целый, но бой кончился: ушёл за предел, вышло время.</summary>
    LeftFight,

    /// <summary>
    /// Пропал из мира, не показав нуля: вышел из прогруженных чанков, или мы
    /// сами переподключились. Это НЕ победа.
    /// </summary>
    Vanished
}

/// <summary>
/// КОГО ВООБЩЕ МОЖНО БИТЬ И КОГДА ОН ПОВЕРЖЕН — чистые правила боя.
///
/// ЖИВОЙ СЛУЧАЙ, ради которого этот класс появился (журнал 17.08,
/// 23:49:47 → 23:51:14). Полторы минуты подряд, дважды в секунду:
///   отбиваюсь от bowtornprojectile / bowtornprojectile повержен
/// Сто восемьдесят пар, и обе строки в одну и ту же миллисекунду — то есть
/// бот НИ РАЗУ не замахнулся, а «победу» доложил сто восемьдесят раз.
/// bowtornprojectile — это стрела боуторна, воткнутая в стену; в оценке боя
/// так и записано: «5,1 против 0 бл/с».
///
/// ЛОМАЛОСЬ ЗДЕСЬ ДВЕ ВЕЩИ СРАЗУ, и обе — из-за отсутствующего здоровья.
/// Сервер шлёт дерево «health» только тем, у кого есть поведение health
/// (<c>EntityBehaviorHealth</c> кладёт его в WatchedAttributes); у стрелы,
/// у лежащей вещи, у падающего блока его нет вовсе. А в бою на этот
/// НЕИЗВЕСТНЫЙ ответ отвечали ТРЕМЯ РАЗНЫМИ догадками:
///   • отбор целей: <c>(e.Health ?? 1) &gt; 0</c> — «нет здоровья, значит жив»;
///   • цикл боя:    <c>(live.Health ?? 0) &lt;= 0</c> — «нет здоровья, значит убит»;
///   • счёт боя:    <c>enemy.Health ?? 12</c> — «нет здоровья, значит двенадцать».
/// Первая брала стрелу в бой, вторая тут же объявляла её поверженной, и так
/// по кругу, пока стрела не исчезла сама (у снаряда в игре
/// <c>despawn minSeconds: 120</c> — ровно те полторы минуты).
///
/// ОТСЮДА И ПРАВИЛА. Оба спрашивают ФАКТ ОТ СЕРВЕРА и не гадают:
/// живое — то, чему сервер прислал здоровье и чей тип он не объявил неживым;
/// повержен — только тот, чьё присланное здоровье упало до нуля.
/// </summary>
public static class CombatTargets
{
    /// <summary>
    /// МОЖНО ЛИ ЭТО БИТЬ ВООБЩЕ.
    ///
    /// Два вопроса к серверу, и ни одного к себе:
    /// <list type="number">
    /// <item>тип объявлен НЕЖИВЫМ (тег <c>inanimate</c> в реестре типов, см.
    /// <see cref="EntityTypes"/>) — стрела, копьё, вещь на земле, падающий
    /// блок, лодка, манекен, соломенное чучело. Живой игрок такое даже
    /// НАВЕСТИ не может: и выбор цели мышью
    /// (<c>SystemMouseInWorldInteractions</c>), и серверный отбор
    /// (<c>ServerSystemEntitySimulation</c>) фильтруют по
    /// <c>Entity.IsInteractable</c>, а у <c>EntityProjectileBase</c> он
    /// намертво false. Бить снаряд — то, чего живой игрок не может;</item>
    /// <item>здоровья сервер не прислал вовсе — значит бить нечего: урон в
    /// игре считает поведение health, и без него удар не сделает ничего.
    /// Это и запасной ответ на случай, когда реестр ещё не пришёл или тип в
    /// нём незнаком (модовая тварь): молчаливого «наверное, живой» тут быть
    /// не должно.</item>
    /// </list>
    ///
    /// Соломенное чучело показывает, почему нужны ОБА вопроса: здоровье у
    /// него есть (health 100/100 в strawdummy.json), а тег «inanimate» стоит.
    /// </summary>
    /// <param name="inanimate">сервер объявил тип неживым (реестр типов)</param>
    /// <param name="health">здоровье, ПРИСЛАННОЕ сервером; null — не прислано</param>
    public static bool CanBeFought(bool inanimate, float? health) =>
        !inanimate && health is { } hp && hp > 0;

    /// <summary>
    /// ПОВЕРЖЕН — ТОЛЬКО ПО ФАКТУ ОТ СЕРВЕРА (правило 4 проекта).
    ///
    /// Не «исчез из мира» и не «здоровья не видно»: сущность пропадает и
    /// когда просто вышла из прогруженных чанков, а после переподключения
    /// пропадают разом все (<see cref="EntityModel.Reset"/>). Победа — это
    /// присланное сервером здоровье, упавшее до нуля; убитый зверь в игре
    /// лежит трупом ещё несколько часов (<c>EntityBehaviorDeadDecay</c>),
    /// так что нуль приходит и виден.
    /// </summary>
    public static bool Defeated(float? health) => health is { } hp && hp <= 0;

    /// <summary>
    /// КОГО БИТЬ В ОТВЕТ — ТОЛЬКО ТОГО, КОГО НАЗВАЛ СЕРВЕР. ПОДМЕНА ЗАПРЕЩЕНА.
    ///
    /// ЖИВОЙ СЛУЧАЙ (журнал 19.08, 01:38:59):
    ///   сервер говорит, ударил «поверхностный шивер», а рядом такого нет —
    ///   беру bowtorn-surface
    ///   меня ударил bowtorn-surface — иду разбираться   (и ещё дважды)
    /// Боуторн бота не трогал: сервер прямо назвал шивера. Прежний отбор,
    /// не найдя названного, брал ПЕРВОГО ВРАЖДЕБНОГО ПОД РУКОЙ — и бот шёл
    /// драться с тем, кто оказался перед носом. Сам код при этом писал в
    /// комментарии «это и есть „бью не того“» и делал ровно это.
    ///
    /// ИМЯ — ЭТО ФАКТ. Сервер шлёт его в сообщение об уроне и собирает тем же
    /// <c>Entity.GetPrefixAndCreatureName</c>, каким подписывает тварь живому
    /// игроку. Раз факт есть, догадке места нет: названного нет рядом — значит
    /// обидчика в досягаемости НЕТ, и мстить некому. Ближайший враждебный сам
    /// подойдёт и ударит — вот тогда сервер назовёт уже его.
    ///
    /// БЕЗЫМЯННЫЙ УДАР — ДРУГОЕ ДЕЛО: сервер не назвал никого (взрыв, ловушка,
    /// неразобранная строка), опровергать нечего, и ближайший враждебный —
    /// единственное, что вообще известно. Это не подмена названного.
    /// </summary>
    /// <param name="named">
    /// Имя обидчика словами сервера; пусто — сервер никого не назвал.
    /// </param>
    /// <param name="nearbyNames">
    /// Имена враждебных рядом ТЕМИ ЖЕ СЛОВАМИ, ближний первым.
    /// </param>
    /// <returns>Номер выбранного в списке; null — бить в ответ некого.</returns>
    public static int? WhoToFight(string? named, IReadOnlyList<string> nearbyNames)
    {
        if (nearbyNames.Count == 0)
            return null;
        if (named is not { Length: > 0 })
            return 0;
        for (int i = 0; i < nearbyNames.Count; i++)
            if (string.Equals(nearbyNames[i], named, StringComparison.OrdinalIgnoreCase))
                return i;
        return null;
    }
}

/// <summary>
/// ЧТО СЧИТАТЬ ОРУЖИЕМ — ОДНА МЕРКА НА ВСЕХ, КТО ЕЁ СПРАШИВАЕТ.
///
/// ЗАЧЕМ ЭТОТ КЛАСС ПОЯВИЛСЯ. Мерка нужна двоим: самообороне («драться или
/// бежать безоружным») и сбору оружия к ночи («что брать в руку»). Числа и
/// формула были СПИСАНЫ ДВАЖДЫ — по копии у каждой способности, с одинаковыми
/// умолчаниями 1,5 и 0,5. Команда «!бой 3» правила ровно одну копию и отвечала
/// человеку «оружием считаю от 3 урона» без всяких оговорок; к темноте вторая
/// копия (порог у неё так и оставался 1,5) брала в руку предмет с ценностью 2,
/// а самооборона тот же предмет оружием не считала и командовала убегать.
/// Человек был уверен, что настроил порог; настроил он половину.
///
/// Теперь мерка одна и живёт у бота (<see cref="BotContext.Weapons"/>): у
/// способностей остались только двери к ней, и повернуть её можно откуда угодно
/// — обе стороны увидят одно и то же число.
/// </summary>
public sealed class WeaponStandard
{
    /// <summary>
    /// Ниже этой боевой ценности предмет оружием не считается.
    ///
    /// Без порога «лучшим оружием» оказывались лён и семена: голый урон есть
    /// почти у всего, и бот брал в руку первый попавшийся хлам. Полтора — заметно
    /// выше кулака и ниже любого настоящего оружия.
    /// </summary>
    public const float DefaultMinPower = 1.5f;

    /// <summary>
    /// Во сколько раз инструмент хуже настоящего оружия. Кирка и лопата
    /// формально наносят урон, но идти с ними на дрифтера — не бой, а смерть.
    /// </summary>
    public const float DefaultToolFactor = 0.5f;

    /// <summary>С какого урона предмет считается оружием (кулак заметно слабее).</summary>
    public float MinPower { get; set; } = DefaultMinPower;

    /// <summary>Во сколько раз инструмент дешевле настоящего оружия.</summary>
    public float ToolFactor { get; set; } = DefaultToolFactor;

    /// <summary>
    /// БОЕВАЯ ЦЕННОСТЬ ПРЕДМЕТА: урон из реестра игры, у инструмента — режется.
    /// Формула была списана дважды и оба раза одинаково; одна копия и нужна.
    /// </summary>
    public float PowerOf(WorldModel world, string code)
    {
        float power = world.GetAttackPowerByCode(code);
        return world.GetToolTypeByCode(code) != null ? power * ToolFactor : power;
    }

    /// <summary>Оружие ли это по нынешней мерке.</summary>
    public bool IsWeapon(float power) => power >= MinPower;

    /// <summary>
    /// ЛУЧШЕЕ ОРУЖИЕ В СУМКАХ — ОДИН ОБХОД НА ВЕСЬ ПРОЕКТ.
    ///
    /// Был списан дважды слово в слово: сбор оружия к ночи
    /// (<c>BehaviorWeaponAtNight</c>) и охота (<c>Hunting</c>). Формула
    /// ценности у обоих бралась отсюда, а вот САМ ОБХОД — свой, и это ровно
    /// та трещина, о которой предупреждает правило 2: научи выбор пропускать
    /// щит или лук без стрел — и починят один список из двух, а второй молча
    /// продолжит тянуть в руку не то.
    ///
    /// Одежда и курсор пропускаются: в «character» лежит надетое (снимать с
    /// себя броню ради удара незачем), в «mouse» — то, что бот держит мышью
    /// посреди перекладки, и трогать это в другом деле нельзя.
    /// </summary>
    /// <param name="world">Реестр игры — оттуда урон и тип инструмента.</param>
    /// <param name="inventories">Свои описи (<c>SelfState.OwnInventories</c>).</param>
    public (string? Code, float Power) BestInBags(WorldModel world,
        IEnumerable<KeyValuePair<string, SlotContent[]>> inventories)
    {
        string? best = null;
        float bestPower = 0;
        foreach (var (invId, slots) in inventories)
        {
            if (invId.StartsWith("character", StringComparison.Ordinal) ||
                invId.StartsWith("mouse", StringComparison.Ordinal))
                continue;
            foreach (var slot in slots)
            {
                if (slot.Code is not { } code)
                    continue;
                float power = PowerOf(world, code);
                if (power > bestPower)
                {
                    bestPower = power;
                    best = code;
                }
            }
        }
        return (best, bestPower);
    }
}

/// <summary>
/// ЧТО БОТ ЗНАЕТ О СТЫЧКЕ, ЧИСЛАМИ. Все поля — либо факт от сервера, либо
/// собственный замер; выдуманных значений здесь нет, а чего не знаем — то
/// null, и оценка об этом честно скажет.
/// </summary>
public sealed record CombatFacts
{
    /// <summary>Сколько блоков до противника.</summary>
    public required double Gap { get; init; }

    /// <summary>Дальность своего удара, бл.</summary>
    public double Reach { get; init; } = 2.3;

    /// <summary>Своя скорость бегом, бл/с (игра + свои статы, см. Movement.WalkSpeed).</summary>
    public double MySpeed { get; init; } = 6.7;

    /// <summary>
    /// Его скорость, бл/с. Либо ЗАМЕР по присланным положениям
    /// (<see cref="CombatPace"/>), либо ОБЪЯВЛЕННОЕ игрой в описании твари
    /// (<see cref="CreatureSpeeds"/>). null — ни того, ни другого: такого кода
    /// в ассетах нет, а сам он с места не двинулся.
    /// </summary>
    public double? HisSpeed { get; init; }

    /// <summary>
    /// Скорость именно ЗАМЕРЕНА, а не взята из описания твари. Нужен для
    /// честной строки в журнале: человек должен видеть, где число своё, а где
    /// обещанное игрой (у замера бывает и «он стоял», у описания — «так
    /// написано, но по снегу он медленнее»).
    /// </summary>
    public bool HisSpeedMeasured { get; init; }

    /// <summary>Откуда взялось число скорости — одними словами во всех ответах.</summary>
    public string SpeedSource => HisSpeedMeasured ? "замер" : "по описанию твари";

    /// <summary>Сколько у меня здоровья сейчас.</summary>
    public required double MyHealth { get; init; }

    /// <summary>Мой урон за удар (боевая ценность того, что в руках).</summary>
    public double MyHit { get; init; }

    /// <summary>Пауза между моими ударами, с.</summary>
    public double MySwingSeconds { get; init; } = 0.9;

    // ---- ЛУК: ВТОРОЕ СРЕДСТВО, О КОТОРОМ СЧЁТ НЕ ЗНАЛ ВОВСЕ ----
    //
    // ЖИВОЙ СЛУЧАЙ, из-за которого эти пять полей появились (щуп 26.08). Бот с
    // луком и восемью стрелами, без меча, говорит про дрифтера в пятнадцати
    // блоках дословно:
    //
    //   ПЛАН: Ignore — … дерусь не выйдет — драться нечем: годного оружия нет,
    //   а кулаками это не бой, а смерть
    //
    // Мерка оружия (WeaponStandard) считает УДАР РУКОЙ, и у лука в ассетах
    // 1.22.7 поля attackpower нет вовсе — то есть по ней лук ровно так же слаб,
    // как кулак (CollectibleObject.AttackPower = 0,5). Оттого весь дальний бой
    // был мёртв: бот с луком считал себя безоружным, выбирал «убегаю» или «не
    // связываюсь» и в цикл стычки, где живёт лук, НЕ ВХОДИЛ НИ РАЗУ.
    //
    // ПОЧЕМУ ЭТО НЕ «ЕЩЁ ОДНА ЦЕННОСТЬ ОРУЖИЯ», А ОТДЕЛЬНЫЕ ПОЛЯ. Лук — это
    // другой способ, а не другое оружие: у него своя дальность (ближе
    // «СтрелятьНеБлижеЧем» он молчит, дальше «СтрелятьНеДальше» тоже), свои
    // промахи и конечные стрелы. Сложить его с мечом в одно число значило бы
    // соврать в обе стороны сразу.

    /// <summary>
    /// УРОН ОДНОГО ПОПАДАНИЯ СТРЕЛОЙ, хп: лук плюс стрела по реестру сервера
    /// (<c>ItemBow.OnHeldInteractStop</c> складывает их <c>attributes.damage</c>).
    /// Ноль — стрелять нечем или роль сняла ручку «СтрелятьИзЛука».
    /// </summary>
    public double ShotHit { get; init; }

    /// <summary>
    /// Сколько секунд занимает ОДИН выстрел целиком: натяг плюс пауза между
    /// выстрелами (ручки «ТянутьТетивуСекунд» и пауза лучника). Это замер
    /// собственного цикла, а не решение.
    /// </summary>
    public double ShotSeconds { get; init; } = 2.1;

    /// <summary>
    /// ДОЛЯ ПОПАДАНИЯ по ЭТОЙ цели с ЭТОГО расстояния
    /// (<see cref="Archery.HitChance"/>, считает её лук и только лук).
    /// Отрицательная — размер цели реестр не назвал, считать было нечем.
    ///
    /// БЕЗ НЕЁ СЧЁТ БЫЛ БЫ ВРАНЬЁМ В ОПАСНУЮ СТОРОНУ: «лук бьёт по 2,75» и
    /// «лук бьёт по 2,75 в одном случае из пяти» — это «свалю за 15 с» против
    /// «свалю за 75 с», то есть разница между боем и смертью по расчёту.
    /// </summary>
    public double ShotChance { get; init; } = -1;

    /// <summary>Сколько стрел в сумках. Ноль — лук молчит, и это честный отказ.</summary>
    public int Arrows { get; init; }

    /// <summary>Ближе этого лук не стреляет — ручка роли «СтрелятьНеБлижеЧем».</summary>
    public double ShootMinRange { get; init; }

    /// <summary>Дальше этого лук не стреляет — ручка роли «СтрелятьНеДальше».</summary>
    public double ShootMaxRange { get; init; }

    /// <summary>
    /// С КАКОЙ ДОЛИ ПОПАДАНИЯ ЛУК ВООБЩЕ БЕРЁТСЯ ЗА ВЫСТРЕЛ — ручка роли
    /// «СтрелятьПриШансеНеНиже». Число тут не ради красоты счёта: до 27.08
    /// порог знал только сам лук, и счёт боя обещал урон от выстрелов,
    /// которые лук отказывался делать (см. <see cref="ShotChanceEnough"/>).
    /// </summary>
    public double MinShotChance { get; init; }

    /// <summary>
    /// ЕСТЬ ЛИ ЧЕМ БИТЬ ВБЛИЗИ — та же мерка оружия, какой её меряет бой
    /// (<c>Weapons.IsWeapon</c>), а не «MyHit больше нуля». Разница живая:
    /// кирка в руках урон даёт, оружием не считается, и лук в такой руке —
    /// по-прежнему единственное, чем бот и правда дерётся.
    /// </summary>
    public bool HaveMelee { get; init; }

    /// <summary>
    /// ЭТОГО ВРАГА ЛУЧШЕ БИТЬ ИЗДАЛИ: он сам почти не бьёт, зато СОЗЫВАЕТ
    /// ДРУГИХ, когда рядом шумят. В игре 1.22.7 это колокол — см.
    /// <see cref="CombatDanger.CallsForHelp"/>, там же разбор задачи
    /// <c>AiTaskBellAlarm</c> и все её числа.
    /// </summary>
    public bool SummonsHelp { get; init; }

    /// <summary>
    /// Его удар по мне, хп. Это либо ЗАМЕР из журнала урона сервера, либо (пока
    /// замера нет) запас, который выставила способность. Нулём его считать
    /// нельзя ни при каких условиях: это объявило бы любой бой бесплатным.
    /// </summary>
    public double? HisHit { get; init; }

    /// <summary>
    /// Удар именно ЗАМЕРЕН, а не взят запасом. Нужен только для честной строки
    /// в журнале: человек должен видеть, где число настоящее.
    /// </summary>
    public bool HisHitMeasured { get; init; }

    /// <summary>
    /// Он бьёт меня ПРЯМО СЕЙЧАС (последний удар — от него и недавно).
    ///
    /// Без этого поля бегство упиралось в порог расстояния: боуторн стреляет с
    /// двадцати блоков, а «ближе восьми не подходил — бежать не от чего». Ровно
    /// про это заказчик и написал: «когда нас бьет боуторн, мы можем должны
    /// идти его убивать или прятаться».
    /// </summary>
    public bool UnderFire { get; init; }

    /// <summary>Как часто он бьёт, с (замер или разумный запас).</summary>
    public double HisHitSeconds { get; init; } = 1.5;

    /// <summary>Сколько у него осталось здоровья (сервер шлёт его открыто).</summary>
    public double HisHealth { get; init; } = 12;

    /// <summary>Есть ли до него дорога. false — гнаться значит биться в стену.</summary>
    public bool Reachable { get; init; } = true;

    /// <summary>
    /// ЕСТЬ ЛИ ДОРОГА У НЕГО — КО МНЕ. Считает её тот же поиск пути, только
    /// закрытая дверь в нём глухая стена, как и для твари
    /// (см. <see cref="CreatureReach"/>). true — «дойдёт» И «не знаю»: врать
    /// себе, что за стеной безопасно, нельзя ни при каком незнании.
    ///
    /// ЭТО НЕ ТО ЖЕ САМОЕ, ЧТО <see cref="Reachable"/>, и разница живая. Тот
    /// вопрос про МОИ ноги: дверь бот открывает сам, поэтому дорога к твари у
    /// него есть почти всегда — и он к ней шёл. Этот вопрос про ЕГО ноги, и
    /// ровно про него написал заказчик: «не имеет смысл агриться на врагов за
    /// стенами дома, если двери закрыты».
    ///
    /// ПОЧЕМУ ОДНОЙ ПРЕГРАДЫ (<see cref="Barrier"/>) НЕ ХВАТИЛО. Преграда —
    /// это ЛУЧ, а сквозь окно луч проходит: тварь снаружи видна, преграды
    /// «нет», и по числам выходило «дерусь». Живьём это и было «бежит в окно и
    /// дерётся попой».
    /// </summary>
    public bool HeReachesMe { get; init; } = true;

    /// <summary>
    /// МЕНЯ БЬЮТ ПРЯМО СЕЙЧАС — КТО БЫ ЭТО НИ БЫЛ.
    ///
    /// ЧЕМ ОТЛИЧАЕТСЯ ОТ <see cref="UnderFire"/> И ЗАЧЕМ ЗАВЕДЕНО ОТДЕЛЬНО.
    /// Там условие «бьёт ИМЕННО ОН»: обидчика надо было сперва опознать
    /// (<c>BehaviorAttackHostiles.FindAttacker</c>), а он вправе вернуть null —
    /// урон пришёл, а по имени и радиусу никого не нашлось. Тогда получалось
    /// худшее из возможного: бота бьют, а «он до меня не дойдёт» держится, и
    /// бой, бегство, заклад и «загнан» все отвечают «нет пути». Броня при этом
    /// надевается (она смотрит на сам факт урона), а драться бот отказывается.
    ///
    /// Расчёт «дороги ко мне у него нет» отменяет ФАКТ, а факт здесь один:
    /// по мне попадают. Кто именно — для этой отмены неважно.
    /// </summary>
    public bool ЯПодУдаром { get; init; }

    /// <summary>
    /// СТРЕЛЯТЬ ЛИ В ТОГО, КОМУ ДО МЕНЯ НЕ ДОЙТИ. Ручка роли
    /// «СтрелятьВТехКтоДоМеняНеДойдёт»; заводское — НЕТ.
    ///
    /// ПОЧЕМУ ЗАВОДСКОЕ «НЕТ» И ПОЧЕМУ ЭТО РУЧКА, А НЕ РЕШЕНИЕ БИБЛИОТЕКИ.
    /// Заказчик написал: «не имеет смысл агриться на врагов за стенами дома,
    /// если двери закрыты». Пока этой ручки не было, выходило наоборот:
    /// <see cref="ShotStillPasses"/> отпирал бой, оценка боя при недостижимом
    /// враге давала цену 0 и оценку 100, «занимаюсь своим» давало ровно те же
    /// 100 — а при равных побеждает первый по порядку, то есть ДРАКА. Бот с
    /// луком бросал дело, забирал тело рефлексом и обстреливал каждого
    /// видимого в окно дрифтера. Ровно та жалоба, которую чинили.
    ///
    /// Кому это нужно наоборот — стражнику на стене, — тот ручку и повернёт.
    /// </summary>
    public bool ShootUnreachable { get; init; }

    /// <summary>
    /// ЧТО МЕЖДУ НАМИ: дверь, блоки или ничего (см. <see cref="CombatBarrier"/>).
    /// Замер лучом из глаз, а не догадка; «не знаю» здесь значит None —
    /// придумывать преграду, которой не видел, нельзя.
    /// </summary>
    public CombatBarrier Barrier { get; init; } = CombatBarrier.None;

    /// <summary>
    /// Я НАРОЧНО СПРЯТАЛСЯ, и укрытие ещё держится (см. <see cref="Shelter.Hidden"/>):
    /// либо замурован блоками, либо ушёл под крышу и закрыл за собой дверь.
    ///
    /// Отдельным фактом от <see cref="Barrier"/>, потому что это разные вещи:
    /// преграда — про мир, укрытие — про СОБСТВЕННОЕ РЕШЕНИЕ бота. Заказчик про
    /// это и написал: выйти из укрытия ради драки — значит отменить своё же
    /// решение спрятаться.
    /// </summary>
    public bool Hiding { get; init; }

    /// <summary>Преграда есть — про мир, а не про решения бота.</summary>
    public bool Separated => Barrier != CombatBarrier.None;

    /// <summary>
    /// УКРЫТИЕ ДЕРЖИТ — и это САМОСТОЯТЕЛЬНАЯ причина не лезть в бой, наравне
    /// с преградой.
    ///
    /// ПОЧЕМУ ОДНОГО <see cref="Separated"/> НЕ ХВАТИЛО. Преграду бот меряет
    /// лучом, а луч отвечает про ЭТУ секунду и про ЭТУ точку: тварь сместилась
    /// на шаг и заглянула в дверной проём наискосок, реестр блоков ещё не
    /// пришёл (тогда преграды честно «не видно»), в стене укрытия щель в один
    /// блок — и Barrier становится None. По числам это «преграды нет, дерусь»,
    /// а на деле бот РАЗБИРАЕТ СВОЁ ЖЕ УКРЫТИЕ и выходит под бурю. Ровно это
    /// заказчик и запретил: «ты спрятался от шторма … — должно быть так».
    ///
    /// ЧЕМ УКРЫТИЕ ПЕРЕСТАЁТ ДЕРЖАТЬ — двумя честными признаками, и оба про
    /// то, что он МЕНЯ УЖЕ ДОСТАЁТ (значит прятаться больше не от чего):
    ///   • он бьёт меня прямо сейчас (<see cref="UnderFire"/>) — сквозь стену
    ///     твари в игре не бьют (hasDirectContact), значит укрытия больше нет;
    ///   • он вплотную и между нами ничего — то есть он ВНУТРИ со мной.
    /// В обоих случаях бой идёт как прежде, со всеми числами.
    /// </summary>
    public bool Sheltered => Hiding && !UnderFire &&
        !(Barrier == CombatBarrier.None && Gap <= Reach + CombatPlan.MeleeSlack);

    /// <summary>
    /// ОН ДО МЕНЯ НЕ ДОБЕРЁТСЯ — и это самостоятельная причина не связываться,
    /// наравне с преградой и укрытием.
    ///
    /// ГРАНИЦА ЗДЕСЬ ОДНА, И ОНА ИЗ ФАКТА ОТ СЕРВЕРА: МЕНЯ БЬЮТ. Раз по мне
    /// попадают — кто-то дошёл, и никакой расчёт этого не отменяет: дверь мог
    /// открыть живой игрок, тварь могла оказаться летающей, поиск мог упереться
    /// в свой потолок.
    ///
    /// СПРАШИВАЕТСЯ И «БЬЁТ ИМЕННО ОН» (<see cref="UnderFire"/>), И ПРОСТО
    /// «МЕНЯ БЬЮТ» (<see cref="ЯПодУдаром"/>), и второе тут главное: опознание
    /// обидчика вправе не удаться, а бот, которого бьют неизвестно кто, обязан
    /// перестать верить расчёту тем более. Пока стояло одно первое, бота могли
    /// избивать, а он отвечал «занимаюсь своим».
    ///
    /// ОТВЕТ ЖИВЁТ РОВНО ДО СЛЕДУЮЩЕГО ОПРОСА (полторы секунды): дорогу
    /// пересчитывают заново, и открытая дверь возвращает бой сама собой.
    /// </summary>
    public bool Unreachable => !HeReachesMe && !UnderFire && !ЯПодУдаром;

    /// <summary>
    /// ОТВЕЧАТЬ НЕ НА ЧТО: между нами преграда, меня держит своё укрытие или он
    /// до меня не доберётся. Один вопрос на все пять оценок — чтобы завтра
    /// кто-нибудь не научил четыре из них новому правилу, а пятую забыл.
    /// </summary>
    public bool Blocked => Separated || Sheltered || Unreachable;

    /// <summary>
    /// ...А ВОТ СТРЕЛА ВСЁ РАВНО ПРОХОДИТ — И ЭТО РЕШЕНИЕ РОЛИ, А НЕ БИБЛИОТЕКИ.
    ///
    /// Живой игрок из окна по тому, кто снаружи, стрелять МОЖЕТ — тут разницы
    /// с законом 5 нет. Но «может» и «стоит ли» — разные вопросы, и второй
    /// решает <see cref="ShootUnreachable"/> (ручка «СтрелятьВТехКтоДоМеняНе
    /// Дойдёт», заводское «нет»): заказчик просил НЕ агриться на тех, кто за
    /// стеной. Пока ручки не было, бот с луком бросал работу ради каждого
    /// видимого в окно дрифтера — и это была та же жалоба, только сбоку.
    ///
    /// Сама возможность выстрела держится на том же луче:
    /// <see cref="Separated"/> — луч упёрся, сквозь него не стреляет никто (и
    /// сам лук об этом уже отказывается: «между нами debarkedlog-oak-ud»);
    /// <see cref="Unreachable"/> — луч ЧИСТ, не проходят только ноги.
    ///
    /// Своё укрытие сюда не входит нарочно: <see cref="Sheltered"/> — это
    /// решение спрятаться, а не свойство мира, и стрельбой из укрытия бот его
    /// не отменяет только на вид. Тут ничего не меняем.
    /// </summary>
    public bool ShotStillPasses =>
        ShootUnreachable && Unreachable && !Separated && !Sheltered && CanShoot;

    /// <summary>
    /// ПОЧЕМУ Я НЕ ЛЕЗУ, одними и теми же словами во всех ответах.
    ///
    /// Строка одна на пятерых нарочно: пока у каждого ответа была бы своя,
    /// однажды одна из них разошлась бы с остальными, и человек прочёл бы в
    /// журнале два разных объяснения одного и того же отказа.
    /// </summary>
    public string WhyNotEngage() => Sheltered
        ? Barrier switch
        {
            CombatBarrier.Door =>
                "я нарочно спрятался, и укрытие держится: нас разделяет закрытая дверь — " +
                "выйти за ней ради драки значит отменить своё же решение спрятаться " +
                "(сам он её не откроет: двери в игре открывает только игрок)",
            CombatBarrier.Blocks =>
                "я нарочно спрятался, и укрытие держится: нас разделяют блоки — " +
                "разбирать своё же укрытие ради драки значит отменить решение спрятаться",
            // Преграды луч не увидел, а укрытие держится: он в стольких-то
            // блоках, не бьёт и не вплотную — значит до меня не дотягивается
            _ => $"я нарочно спрятался, и укрытие держится: он в {Gap:0.#} бл, меня не достаёт " +
                 "и внутрь не влез — выйти к нему значит отменить своё же решение спрятаться"
        }
        : Barrier == CombatBarrier.Door
            ? "нас разделяет закрытая дверь: сам он её не откроет (двери в игре открывает " +
              "только игрок), а я не пойду открывать её ради драки"
            : Separated
                ? "нас разделяет преграда: он до меня не достанет (твари в игре бьют только " +
                  "по прямой видимости), а бить сквозь неё — чит"
                // ВИДЕТЬ — НЕ ЗНАЧИТ ДОСТАВАТЬ. Луч чист (окно, щель, обрыв), а
                // дороги ко мне у него нет: ни одна тварь в игре не откроет
                // дверь и не влезет по лестнице. Слова разные нарочно — человек
                // должен отличать «между нами стена» от «он до меня не дойдёт»
                : $"он в {Gap:0.#} бл и на виду, а дороги ко мне у него нет: тварь дверь не " +
                  "откроет и наверх не залезет. Идти к нему через полдома — это не оборона";

    /// <summary>Сколько сторон вокруг ног открыто — есть ли куда отойти.</summary>
    public int EscapeRoutes { get; init; } = 4;

    /// <summary>Есть чем заложить проход.</summary>
    public bool CanSeal { get; init; }

    /// <summary>При скольких открытых сторонах закладываться ещё имеет смысл.</summary>
    public int SealMaxOpenSides { get; init; } = 2;

    /// <summary>Ближе этого бегство вообще начинается.</summary>
    public double FleeStart { get; init; } = 8;

    /// <summary>На сколько надо оторваться, чтобы считать себя ушедшим.</summary>
    public double EscapeDistance { get; init; } = 18;

    /// <summary>Дальше этого не связываемся вовсе.</summary>
    public double EngageLimit { get; init; } = 14;

    /// <summary>
    /// ДАЛЬШЕ ЭТОГО НЕ ХОДИМ НОГАМИ — предел ОБОРОНЫ, а не стрельбы.
    ///
    /// ЗАЧЕМ ОТДЕЛЬНОЕ ЧИСЛО. <see cref="EngageLimit"/> вырос вместе с кругом
    /// встречи: пока лук при себе, врага берут в бой с «СтрелятьНеДальше»
    /// (24 бл), и предел обязан был вырасти следом — иначе счёт отвечал бы
    /// «это уже охота» ровно про того врага, ради которого круг и расширен.
    /// Но у этого роста было ТИХОЕ ПОСЛЕДСТВИЕ: стоило луку отказаться (порог
    /// доли, кончились стрелы), и управление падало в погоню НОГАМИ — с тех
    /// двадцати четырёх блоков, откуда до 26.08 бот врага вообще не видел, при
    /// том что строкой ниже в его же коде написано «мы обороняемся, а не
    /// охотимся». Стрелять с двадцати — оборона; идти двадцать блоков бить
    /// кулаком — охота, и решать это должны разные числа.
    /// </summary>
    public double FootChaseLimit { get; init; } = 14;

    /// <summary>Сколько секунд роль отпускает на погоню.</summary>
    public double MaxChaseSeconds { get; init; } = 25;

    /// <summary>Сколько секунд роль отпускает на побег.</summary>
    public double MaxFleeSeconds { get; init; } = 20;

    // ---- ЦЕНЫ ОТВЕТОВ: чем роль дорожит сверх собственного здоровья ----
    //
    // ПОЧЕМУ ЭТО ПОЛЯ, А НЕ ЧИСЛА В СЧЁТЕ. Мерка «потерянное здоровье» одна на
    // все четыре ответа и считается механикой (сколько хп снимут за столько-то
    // секунд). А вот НАСКОЛЬКО дорого бросить дело, замуроваться или потерпеть
    // — это решение РОЛИ, и оно у ролей разное: сторожу у ворот уход стоит
    // почти всего, рудокопу в штреке — половины рейса, а продавцу за прилавком
    // не стоит почти ничего. Пока эти числа были const внутри библиотеки,
    // повернуть их было нечем ни из роли, ни из панели.

    /// <summary>
    /// ЦЕНА УХОДА СВЕРХ ПОТЕРЯННОГО ЗДОРОВЬЯ, в тех же хп.
    /// Умолчание — <see cref="CombatPlan.DefaultFleePrice"/>, ставит роль.
    /// </summary>
    public double FleePrice { get; init; } = CombatPlan.DefaultFleePrice;

    /// <summary>
    /// Надбавка к цене закладывания, хп. Умолчание —
    /// <see cref="CombatPlan.DefaultSealPrice"/>, ставит роль.
    /// </summary>
    public double SealPrice { get; init; } = CombatPlan.DefaultSealPrice;

    /// <summary>
    /// Сколько секунд бот согласен ТЕРПЕТЬ удары, продолжая своё дело.
    /// Умолчание — <see cref="CombatPlan.DefaultIgnoreSeconds"/>, ставит роль.
    /// </summary>
    public double IgnoreSeconds { get; init; } = CombatPlan.DefaultIgnoreSeconds;

    /// <summary>
    /// СКОЛЬКО СЕКУНД Я УЖЕ ТЕРПЛЮ — замер, а не решение.
    ///
    /// ЖИВОЙ СЛУЧАЙ (журнал 19.08). Одна и та же строка, четырежды за минуту:
    /// «не связываюсь: если не трогать, за 10 с снимет около 10,1 хп». Каждые
    /// полсекунды бот выдавал себе полные десять секунд терпения заново — и
    /// терпел, пока его били, сколько угодно долго. Терпение обязано
    /// РАСХОДОВАТЬСЯ: отпущенные ролью секунды считаются от начала избиения, а
    /// не от нынешнего хода. Кончились — «занимаюсь своим» перестаёт быть
    /// ответом, и слово переходит к остальным.
    /// </summary>
    public double EnduredSeconds { get; init; }

    /// <summary>
    /// Уйти — значит уйти дальше хотя бы на столько блоков. Умолчание —
    /// <see cref="CombatPlan.DefaultFleeGainAtLeast"/>, ставит роль.
    /// </summary>
    public double FleeGainAtLeast { get; init; } = CombatPlan.DefaultFleeGainAtLeast;

    /// <summary>
    /// Роль уже велела отступать: здоровья меньше своего порога
    /// (RetreatHealthFraction), и размен ударов запрещён, чем бы он ни
    /// считался по числам. Отдельным полем, а не «мало здоровья», потому что
    /// порог этот — решение РОЛИ: сторожу он один, охотнику другой.
    /// </summary>
    public bool Retreating { get; init; }

    /// <summary>Мой урон в секунду РУКОЙ.</summary>
    public double MyDps => MyHit / Math.Max(0.1, MySwingSeconds);

    /// <summary>
    /// ЛУК СО СТРЕЛАМИ ПРИ МНЕ — без всякого разговора о дистанции.
    /// Отдельным вопросом затем, что «отойти и стрелять» спрашивает именно
    /// это: он подошёл БЛИЖЕ, чем позволено стрелять, а лук от этого никуда
    /// не делся.
    /// </summary>
    public bool BowReady => ShotHit > 0 && Arrows > 0;

    /// <summary>
    /// ОН В ПОЯСЕ ДАЛЬНОСТИ, ОТПУЩЕННОМ РОЛЬЮ. Чистое правило, чтобы у
    /// подготовки фактов и у счёта вариантов не было двух копий этого
    /// условия: до 27.08 их и было две — одна здесь, вторая переписана рукой
    /// в <c>BehaviorAttackHostiles.Facts</c>, чтобы не звать наводку зря.
    /// Поправь одну — вторая отстанет молча (закон 2).
    /// </summary>
    public static bool InShootingBand(double shotHit, int arrows, double gap,
                                      double min, double max) =>
        shotHit > 0 && arrows > 0 && gap >= min && gap <= max;

    /// <summary>
    /// ДОЛЯ ПОПАДАНИЯ УСТРАИВАЕТ (или её вовсе нечем посчитать).
    ///
    /// ПОЧЕМУ ЭТО ВХОДИТ В «МОГУ СТРЕЛЯТЬ». Порог держит ручка
    /// «СтрелятьПриШансеНеНиже», и спрашивал его ТОЛЬКО сам лук, а счёт боя —
    /// нет. Живьём 26.08 это давало два ответа про один и тот же тик:
    /// «ПЛАН: Fight — беру его стрелой с 12 бл … свалю за 5,4 с (оценка 98)» и
    /// тут же «не стреляю … ручка „СтрелятьПриШансеНеНиже“ просит 0,99.
    /// Подойду ближе». То есть счёт клал в урон выстрелы, которых лук делать
    /// не станет, и обещал человеку число, которого не будет.
    ///
    /// МИНУС — «РАЗМЕРА ЦЕЛИ РЕЕСТР НЕ НАЗВАЛ»: тогда порог не спрашивает и
    /// сам лук (Archery.WhyNotShoot), и отказываться от стрельбы из-за
    /// непришедшего реестра значило бы вернуть ту самую беду.
    /// </summary>
    public bool ShotChanceEnough =>
        ShotChance < 0 || ShotIsLastResort || ShotChance >= MinShotChance;

    /// <summary>
    /// СТРЕЛА — ПОСЛЕДНЕЕ, ЧТО ОСТАЛОСЬ, И ТОГДА ПОРОГ ДОЛИ НЕ СПРАШИВАЕТСЯ.
    ///
    /// Решение ТО ЖЕ САМОЕ, что принимает сам лук (<see cref="Archery.LastResort"/>),
    /// и по тем же доводам: бить вблизи нечем, либо подходить нельзя. Без этой
    /// строки порог, попав в счёт боя, УБИЛ БЫ ветку «стреляю всё равно: больше
    /// нечем»: счёт отвечал бы «драться нечем; и стрелой не достану — порог
    /// просит 0,99» → Ignore, цикл боя не запускался бы вовсе, и до лука дело
    /// снова не доходило. Ровно так и покраснел живой стенд
    /// ЛукИЩитTests.ЖИВОЙ_ПУТЬ_порог_доли_спрашивается_а_без_меча_бот_ВСЁ_РАВНО_СТРЕЛЯЕТ.
    ///
    /// ТРЕТЬЕГО ДОВОДА ЛУКА («загнан») ЗДЕСЬ НЕТ НАРОЧНО: «загнан» — это уже
    /// ОТВЕТ счёта, и спрашивать его при подготовке доводов значило бы считать
    /// решение через самого себя. Счёт от этого строже лука, а не мягче: лук
    /// выстрелит и там, где счёт разрешил, и там, где загнан, — молчащего лука
    /// при говорящем счёте не выйдет ни в одном случае.
    /// </summary>
    public bool ShotIsLastResort => !HaveMelee || KeepingDistance;

    /// <summary>
    /// ПЯЧУСЬ И СТРЕЛЯЮ — три условия, и каждое проверяется, а не
    /// предполагается: я знаю его скорость, я быстрее него, и вокруг ног есть
    /// куда пятиться. Одно место на весь счёт: спрашивают отсюда и цена боя
    /// (<see cref="CombatPlan.RateFight"/>), и снятие порога доли.
    /// </summary>
    public bool KeepingDistance => SummonsHelp && EscapeRoutes > 0 &&
                                   HisSpeed is { } его && MySpeed > его + 0.01;

    /// <summary>
    /// СТРЕЛА ДОСТАЁТ ЕГО ПРЯМО ОТСЮДА, И ЛУК СОГЛАСЕН ЕЁ ПУСТИТЬ. Один вопрос
    /// на все ответы — чтобы завтра ни одна оценка не завела своего.
    /// </summary>
    public bool CanShoot =>
        InShootingBand(ShotHit, Arrows, Gap, ShootMinRange, ShootMaxRange) && ShotChanceEnough;

    /// <summary>
    /// Мой урон в секунду СТРЕЛАМИ, уже с поправкой на промахи. Ноль — стрела
    /// отсюда не идёт (см. <see cref="CanShoot"/>).
    ///
    /// ДОЛЯ НЕИЗВЕСТНА (минус) — СЧИТАЕМ ПО ПОПАДАНИЯМ, и это сказано вслух в
    /// объяснении оценки. Придумать за сервер ширину твари нельзя, а отказаться
    /// от лука на всю сессию из-за непришедшего реестра — значит вернуть ровно
    /// ту беду, ради которой всё это и чинится.
    /// </summary>
    public double ShotDps => CanShoot ? ShotDpsAnywhere : 0;

    /// <summary>
    /// УРОН В СЕКУНДУ СТРЕЛАМИ, ЕСЛИ ВСТАТЬ ТУДА, ОТКУДА ОНИ ИДУТ.
    ///
    /// Нужен ровно одному случаю — «пячусь и стреляю»: он подошёл ближе
    /// «СтрелятьНеБлижеЧем», стрелять отсюда нельзя, но два шага назад это
    /// чинят. Доля попадания при этом снята С НЫНЕШНЕЙ дистанции, то есть с
    /// более близкой, чем будет после отхода, — а разброс лука угловой, и
    /// вблизи попадать легче. Значит число слегка ОПТИМИСТИЧНО, и это сказано
    /// вслух; цены боя оно не меняет (в той ветке размена нет вовсе, цена 0),
    /// а решение пересчитывается каждый тик заново.
    /// </summary>
    public double ShotDpsAnywhere =>
        ShotHit * (ShotChance < 0 ? 1 : ShotChance) / Math.Max(0.1, ShotSeconds);

    /// <summary>
    /// ЧЕМ Я ВОЗЬМУ ЕГО В ЭТОЙ СТЫЧКЕ — лучшим из того, что и правда пойдёт в
    /// ход. Не сумма: стрелять и махать одновременно нельзя.
    /// </summary>
    public double BestDps => Math.Max(MyDps, ShotDps);

    /// <summary>
    /// ПОЧЕМУ ЛУК ЗДЕСЬ НЕ ОТВЕТ — СЛОВАМИ И С ИМЕНЕМ РУЧКИ. Пусто — отвечает.
    ///
    /// Слова нарочно те же, что у самого лука (<see cref="Archery.WhyNotShoot"/>):
    /// два разных объяснения одного отказа — это то, из-за чего человек чинит
    /// не ту ручку.
    /// </summary>
    public string WhyNoShot() =>
        ShotHit <= 0
            ? Arrows > 0
                ? "лука нет ни в руках, ни в сумках"
                : "стрелять нечем: ни лука, ни стрел"
        : Arrows <= 0
            ? "стрелы кончились (запас держит ручка «ЗапасПоРасходу», строка «arrow к bow»)"
        : Gap < ShootMinRange
            ? $"он в {Gap:0.#} бл — ближе ручки «СтрелятьНеБлижеЧем» ({ShootMinRange:0.#})"
        : Gap > ShootMaxRange
            ? $"до него {Gap:0.#} бл — дальше ручки «СтрелятьНеДальше» ({ShootMaxRange:0.#})"
        : !ShotChanceEnough
            // ТОТ ЖЕ ОТКАЗ, ЧТО У САМОГО ЛУКА, И ТЕМИ ЖЕ СЛОВАМИ. Пока его тут
            // не было, счёт молчал о причине, которую лук называет вслух, —
            // человек читал «беру его стрелой» и тут же «не стреляю … порог
            // просит 0,99», и чинил не ту ручку
            ? $"попаду только {Archery.OddsInWords(ShotChance)}, а ручка " +
              $"«СтрелятьПриШансеНеНиже» просит {MinShotChance:0.##}"
        : "";

    /// <summary>Его урон в секунду по замеру (0 — замера нет).</summary>
    public double HisDps => (HisHit ?? 0) / Math.Max(0.1, HisHitSeconds);
}

/// <summary>
/// ЧЕМ ОПАСЕН ВРАГ СВЕРХ СВОЕГО УДАРА — ЧИСТОЕ ПРАВИЛО, ОДНО НА ПРОЕКТ.
///
/// Заказчик дословно: «луком предпочтительно, если есть, с далека убивать
/// колокола». ПОЧЕМУ издалека — спрошено у самой игры, а не придумано.
///
/// ЧТО ДЕЛАЕТ КОЛОКОЛ (ilspycmd по VSSurvivalMod.dll 1.22.7,
/// <c>AiTaskBellAlarm</c>, и assets/survival/entities/lore/bell.json):
/// <list type="bullet">
/// <item>СВОЕГО УДАРА У НЕГО НЕТ ВОВСЕ. В списке его задач нет ни
/// <c>meleeattack</c>, ни <c>seekentity</c> — только тревога, «слушаю»,
/// «прячусь» и «брожу». Стоять рядом с ним не больно ни секунды;</item>
/// <item>ЗАТО ОН ЗОВЁТ ДРУГИХ. <c>ContinueExecute</c> каждые 1…5 с
/// (<c>spawnIntervalMsMin/Max</c>) вызывает <c>trySpawnCreatures</c> на
/// <c>spawnMaxQuantity</c> = 6 голов в радиусе <c>spawnRange</c> = 12 бл, и
/// зовёт он не мелочь: drifter-deep, drifter-tainted (дважды),
/// drifter-corrupt, shiver-deep, bowtorn-deep, locust-corrupt;</item>
/// <item>А СЛЫШИТ ОН ШУМ. <c>ShouldExecute</c> берёт <c>seekingRange</c> = 15,
/// умножает на 1,25, пока идёт задача «слушаю», и делит на 3 в остальное
/// время; дальше смотрит на управление игроком. ДВИЖУЩЕГОСЯ (идёт, прыгает,
/// машет рукой, что-то использует — а натяг лука это тоже
/// <c>HandUse</c>) он засекает на всём этом расстоянии, крадущегося — с 3…6 бл,
/// а стоящего смирно — только с 2…3 бл. Отпускает он цель, отошедшую дальше
/// <c>seekingRange + 5</c> = 20 бл.</item>
/// </list>
/// Отсюда и правило: подойти к колоколу на длину руки — значит НАЧАТЬ БОЙ СО
/// ВСЕМИ, кого он успеет созвать, пока его валишь; сотня его хп при этом
/// набегает секунд за тридцать даже хорошим мечом.
///
/// ПРИЗНАК — ИЗ РЕЕСТРА СЕРВЕРА, А НЕ СПИСОК ИМЁН (правило 6 проекта).
/// Спрашивается КЛАСС СУЩНОСТИ: сервер шлёт его в том же пакете реестра, что и
/// теги с атрибутами (<see cref="EntityTypeInfo.Class"/>), и <c>EntityBell</c>
/// — это класс САМОЙ ИГРЫ, заведённый ровно под сирену: всё, что он делает, —
/// гоняет звук тревоги пакетами 1025/1026. Модовый колокол, объявленный этим
/// классом, попадёт сюда сам; переименуй мод сущность как угодно — правило не
/// сломается, потому что имени оно не спрашивает.
///
/// ЧЕГО СЕРВЕР НЕ ШЛЁТ, И Я ГОВОРЮ ЭТО ВСЛУХ: настройки поведений
/// (<c>seekingRange</c>, <c>spawnRange</c>, список созываемых) в реестр НЕ
/// ВХОДЯТ — спросить их у сервера нечем. Поэтому числа выше стоят в этом
/// объяснении, а не в коде: решение здесь принимается по признаку «зовёт
/// подмогу», а не по подсчёту его радиусов.
///
/// ЧЕСТНО И ПРО ВТОРОЙ КОЛОКОЛ. Тот же класс носит <c>bellmini</c> — спутник
/// селянина Тобиаса: у него НЕТ задачи <c>bellalarm</c> вовсе, он убегает при
/// ударе и в hostile-группе спавна не значится. Правило назовёт и его «лучше
/// издали», и это не беда: издали — не значит «бей», это значит «не подходи».
/// </summary>
public static class CombatDanger
{
    /// <summary>Класс игры, заведённый под сирену тревоги.</summary>
    public const string BellClass = "EntityBell";

    /// <summary>
    /// Этот зовёт подмогу, когда слышит рядом живого. <paramref name="entityClass"/>
    /// — класс из реестра сервера (<see cref="EntityTypeInfo.Class"/>), пусто —
    /// реестр ещё не пришёл, и тогда ответ «не знаю» = false: выдумывать за
    /// сервер нельзя ни в одну сторону.
    /// </summary>
    public static bool CallsForHelp(string? entityClass) =>
        string.Equals(entityClass, BellClass, StringComparison.Ordinal);
}

/// <summary>
/// С КАКОГО РАССТОЯНИЯ БОТ ВСТРЕЧАЕТ ВРАГА — ЧИСТОЕ ПРАВИЛО, ОДНО НА ВЕСЬ БОЙ.
///
/// ЖАЛОБА ЗАКАЗЧИКА ДОСЛОВНО: «На дальних мобов снова не агрится, просто броню
/// надевает, а нужно сделать интеллектуально: допустим если есть лук, то
/// логично расстрелять моба».
///
/// ЧТО БЫЛО. Два числа спорили молча и оба проигрывали. Оборонительный радиус
/// «ВступатьВБойСРасстояния» = 4 бл, а лук стреляет с 5 до 24
/// («СтрелятьНеБлижеЧем» / «СтрелятьНеДальше»). Пока цель выбиралась в четырёх
/// блоках, лук не спрашивался НИ РАЗУ: к тому мигу, как враг попадал в список,
/// он был уже ближе, чем позволено стрелять. Бот честно писал об этом в журнал
/// («лук в обычной стычке молчит») — и всё равно стоял в броне, ничего не делая.
///
/// КТО КОГО СЛУШАЕТ — ОТВЕТ. Ни то, ни другое: слушают ТО, ЧЕМ БУДУТ БИТЬ.
/// Есть лук и стрелы — врага встречают на дальности выстрела, потому что бить
/// его начнут оттуда. Нет лука — остаётся оборонительный радиус роли, потому
/// что бить придётся руками, а сколько шагов отойти от своего дела ради драки,
/// решает человек (та же ручка «ВступатьВБойСРасстояния», она теперь есть во
/// всех пресетах).
///
/// ВТОРОГО СПОСОБА БИТЬ ДАЛЬНИХ ЗДЕСЬ НЕ ЗАВЕДЕНО. Без лука бот сходится
/// ногами ровно так, как сходился всегда: погоня внутри стычки
/// (<c>Movement.PursueAsync</c>) и месть обидчику в радиусе «РадиусМести».
/// </summary>
public static class CombatReach
{
    /// <summary>
    /// С какого расстояния встречать врага.
    /// </summary>
    /// <param name="defendRadius">Ручка роли «ВступатьВБойСРасстояния».</param>
    /// <param name="bowReady">
    /// Лук и стрелы при себе, и роль разрешила стрелять («СтрелятьИзЛука»).
    /// </param>
    /// <param name="shootMaxRange">Ручка роли «СтрелятьНеДальше».</param>
    /// <param name="meetWithBow">
    /// Ручка роли «ВстречатьЛукомИздалека». Снята — лук молчит в обороне, как
    /// до 26.08: бот подпускает врага на оборонительный радиус.
    /// </param>
    public static double MeetFrom(double defendRadius, bool bowReady,
        double shootMaxRange, bool meetWithBow = true) =>
        bowReady && meetWithBow
            ? Math.Max(Math.Max(0, defendRadius), Math.Max(0, shootMaxRange))
            : Math.Max(0, defendRadius);
}

/// <summary>Оценка ОДНОГО варианта: число и объяснение с числами.</summary>
/// <param name="Score">Больше — лучше. <see cref="CombatPlan.NoWay"/> — не вариант вовсе.</param>
/// <param name="Why">Почему столько — словами и цифрами, для журнала.</param>
public sealed record CombatRating(int Score, string Why)
{
    public bool Usable => Score > CombatPlan.NoWay;
}

/// <summary>Выбранный вариант с его оценкой и объяснением.</summary>
public sealed record CombatDecision(CombatChoice Choice, int Score, string Why)
{
    public override string ToString() => $"{Name(Choice)}: {Why}";

    /// <summary>Название варианта по-русски — для журнала.</summary>
    public static string Name(CombatChoice c) => c switch
    {
        CombatChoice.Fight => "дерусь",
        CombatChoice.Flee => "ухожу",
        CombatChoice.Seal => "закладываюсь",
        CombatChoice.Ignore => "не связываюсь",
        _ => "загнан"
    };
}

/// <summary>
/// ЧТО ДЕЛАТЬ С ПРОТИВНИКОМ — ВЫБОР С ЧИСЛАМИ, СЧИТАННЫЙ ДО ПЕРВОГО ШАГА.
///
/// ЗАЧЕМ. Дословно от заказчика: «когда нас бьет боуторн, мы можем должны идти
/// его убивать или прятаться, а не просто бегать в боевом режиме и умирать» и
/// «боевой режим просто может бежать в стену». Прежний бой решал условиями по
/// очереди: мало здоровья — беги; нет оружия — беги; иначе — гонись. Ни одно из
/// этих «иначе» не спрашивало, ДОГОНЮ ЛИ, ВЫЖИВУ ЛИ и ЕСТЬ ЛИ КУДА ОТОЙТИ, — и
/// живьём это вышло семнадцатью строками «тупик (512048, 93, 512264) …
/// запомнил, буду обходить» подряд: погоня упёрлась в стену и продолжала
/// упираться.
///
/// Образец счёта взят из проекта же — <see cref="Tunnel.RateStepSide"/> и
/// <see cref="Tunnel.PickStepSide"/>: каждый вариант получает ЧИСЛО по одной
/// общей мерке, лучший берётся максимумом, а когда не годится ни один — вслух
/// называется ближайшая помеха, а не «не смог».
///
/// МЕРКА ЗДЕСЬ — ПОТЕРЯННОЕ ЗДОРОВЬЕ. Она единственная общая для всех четырёх
/// ответов: и «сколько снимет, пока я его свалю», и «сколько снимет, пока я
/// отрываюсь», и «сколько снимет, если я просто продолжу работать». Оценка =
/// 100 минус эти хп, чтобы «больше» значило «лучше».
///
/// ГЛАВНОЕ ПРАВИЛО, ОДНО НА ВСЕ ВАРИАНТЫ: вариант, который стоит БОЛЬШЕ хп,
/// чем у бота есть, — это не выбор, а смерть, и он отбрасывается. Именно его
/// не хватало: бот честно «выбирал» бой, в котором умирал.
///
/// ЧТО ЗДЕСЬ МЕХАНИКА, А ЧТО ПОЛИТИКА. Механика — сам счёт: догоню ли по
/// скоростям, сколько снимут за столько-то секунд, сколько времени уходит на
/// разворот и на установку блока (<see cref="FleeExposureSeconds"/>,
/// <see cref="SealSeconds"/>, <see cref="MeleeSlack"/>). Политика — ЦЕНЫ: во
/// сколько хп бот оценивает брошенное дело, запертость за блоком и терпение
/// под ударами. Они приходят полями <see cref="CombatFacts"/>, их ставит РОЛЬ,
/// а здесь лежат только умолчания (Default…): у сторожа, рудокопа и продавца
/// эти числа разные, и «зашить» их одним набором значило бы решить за все роли
/// сразу.
/// </summary>
public static class CombatPlan
{
    /// <summary>Оценка варианта, который не годится вовсе.</summary>
    public const int NoWay = -1000;

    /// <summary>
    /// СКОЛЬКО СЕКУНД ТЕРПЕТЬ УДАРЫ, ЗАНИМАЯСЬ СВОИМ, — по умолчанию.
    ///
    /// Три-четыре удара по кулдауну: ровно столько бот и стоял под боуторном в
    /// журнале заказчика, прежде чем что-то предпринять. Число разумное, но
    /// решение это РОЛЕВОЕ — сторож потерпит дольше рудокопа, — поэтому здесь
    /// только умолчание, а живёт оно в <see cref="CombatFacts.IgnoreSeconds"/>.
    /// </summary>
    public const double DefaultIgnoreSeconds = 10;

    /// <summary>
    /// МЕХАНИКА, А НЕ ПОЛИТИКА: сколько секунд он успевает бить, пока бот
    /// разворачивается и выходит из его досягаемости. Мы уже знаем, что мы
    /// быстрее (иначе побега нет), так что дальше он не достаёт — но раз-другой
    /// на развороте достаёт всегда. Это замер разворота, а не чьё-то решение,
    /// и ролью не крутится.
    /// </summary>
    public const double FleeExposureSeconds = 2;

    /// <summary>
    /// МЕХАНИКА: сколько секунд занимает заложить проход (два блока, низ и
    /// верх). Это время установки блоков в игре, а не мнение роли.
    /// </summary>
    public const double SealSeconds = 2.5;

    /// <summary>
    /// ЦЕНА УХОДА СВЕРХ ПОТЕРЯННОГО ЗДОРОВЬЯ, в тех же хп, — по умолчанию.
    ///
    /// Без неё побег почти всегда дешевле боя (уходя, под ударом стоишь пару
    /// секунд, а размен идёт секунд пять), и получается ровно та жалоба, с
    /// которой всё началось: «а не просто бегать в боевом режиме и умирать».
    /// Уход стоит не только здоровья: бот бросает дело, теряет место и всё
    /// равно встретит эту тварь снова. Восемь хп — это «дерусь, если бой
    /// обойдётся дешевле, чем в восемь хп сверх побега».
    ///
    /// НАСКОЛЬКО дорого бросить дело — решает роль
    /// (<see cref="CombatFacts.FleePrice"/>): у сторожа у ворот и у продавца за
    /// прилавком это разные числа. Здесь только разумное умолчание.
    /// </summary>
    public const double DefaultFleePrice = 8;

    /// <summary>
    /// Надбавка к цене закладывания — по умолчанию больше, чем у ухода: за
    /// блоком бот цел, но заперт, и выбираться оттуда придётся отдельно. При
    /// прочих равных уйти ногами лучше, чем замуроваться. Крутится ролью
    /// (<see cref="CombatFacts.SealPrice"/>): рудокопу в штреке камень и стена
    /// привычны, а продавцу замуровываться в лавке незачем вовсе.
    /// </summary>
    public const double DefaultSealPrice = 12;

    /// <summary>
    /// Уйти — значит УЙТИ ДАЛЬШЕ хотя бы на столько блоков, по умолчанию.
    /// Иначе стрелок, который бьёт с двадцати блоков (а порог отрыва —
    /// восемнадцать), даёт «бежать ноль блоков» и побег выходит бесплатным на
    /// бумаге. Крутится ролью (<see cref="CombatFacts.FleeGainAtLeast"/>).
    /// </summary>
    public const double DefaultFleeGainAtLeast = 6;

    /// <summary>
    /// МЕХАНИКА: насколько дальше досягаемости он ещё считается «вплотную».
    /// Это допуск на длину руки и дрожание координат, а не решение роли.
    /// </summary>
    public const double MeleeSlack = 1.0;

    /// <summary>
    /// ДРАТЬСЯ. Здесь и только здесь считается «догоню ли» и «выживу ли».
    /// </summary>
    public static CombatRating RateFight(CombatFacts f)
    {
        // ПРЕГРАДА И УКРЫТИЕ — ПЕРВЫМ ВОПРОСОМ, ДО ВСЕХ ЧИСЕЛ. Оружие, здоровье
        // и скорости не значат ничего, пока между нами стена или закрытая дверь
        // (сквозь них драки не бывает — бывает только чит, см. CombatBarrier) и
        // пока держится укрытие, в которое бот залез НАРОЧНО (см. Sheltered):
        // выйти из него ради драки — значит отменить собственное решение
        //
        // ОДНО ИСКЛЮЧЕНИЕ, И ОНО ПОД РУЧКОЙ РОЛИ «СтрелятьВТехКтоДоМеняНеДойдёт»
        // (заводское — НЕТ, см. CombatFacts.ShootUnreachable). Когда мешают
        // только ЕГО ноги (Unreachable), луч чист, лук достаёт И роль это
        // позволила, — выстрел проходит. Ниже он и уйдёт в ветку «беру его
        // стрелой»: сходиться там не надо, а значит и решение это не про подход
        //
        // «ДАЛЬШЕ ДЛИНЫ РУКИ» здесь обязательно: ближе неё выстрела не бывает
        // вовсе, а махать рукой сквозь окно в того, до кого нет дороги, — это
        // ровно то самое «дерётся попой», которое и чиним
        if (f.Blocked && !(f.ShotStillPasses && f.Gap > f.Reach))
            return new CombatRating(NoWay, f.WhyNotEngage());
        // ЧЕМ БИТЬ — СПРАШИВАЕМ ОБА СРЕДСТВА СРАЗУ. Пока здесь стояло одно
        // «MyDps <= 0», бот с луком и восемью стрелами объявлял себя безоружным
        // (у лука в ассетах игры нет attackpower вовсе) — и весь дальний бой был
        // мёртв. Отказ теперь называет ОБЕ причины: и про руку, и про лук с
        // именем ручки, которую надо повернуть
        if (f.BestDps <= 0)
            return new CombatRating(NoWay,
                "драться нечем: годного оружия нет, а кулаками это не бой, а смерть" +
                (f.WhyNoShot() is { Length: > 0 } лук ? $"; и стрелой не достану — {лук}" : ""));
        if (f.Retreating)
            return new CombatRating(NoWay,
                $"роль велела отступать (у меня {f.MyHealth:0.#} хп) — размен запрещён");
        if (f.Gap > f.EngageLimit)
            return new CombatRating(NoWay,
                $"до него {f.Gap:0.#} бл — дальше предела {f.EngageLimit:0.#} бл, это уже охота, а не оборона");

        double closeSeconds = 0;
        string approach = "он вплотную";
        // СХОДИТЬСЯ НАДО НЕ ВСЕГДА. Стрела достаёт его прямо отсюда — значит и
        // «догоню ли», и «есть ли дорога» к делу не относятся: бить я начну, не
        // сходя с места, а сойдётся он сам. Ровно об этом заказчик и просил:
        // «если есть лук, то логично расстрелять моба»
        if (f.Gap > f.Reach && f.CanShoot)
        {
            approach = $"беру его стрелой с {f.Gap:0.#} бл — сходиться незачем" +
                       (f.ShotChance >= 0
                           ? $" (попаду {Archery.OddsInWords(f.ShotChance)}, стрел {f.Arrows})"
                           : $" (размера его реестр не назвал, долю попадания считать нечем — " +
                             $"стрел {f.Arrows})") +
                       (f.SummonsHelp
                           ? "; и подходить к нему нельзя: он созовёт подмогу"
                           : "");
        }
        else if (f.Gap > f.Reach)
        {
            // ЖИВОЙ СЛУЧАЙ: погоня без дороги. Семнадцать строк «тупик …»
            // подряд — это ровно попытка догнать того, до кого хода нет
            if (!f.Reachable)
                return new CombatRating(NoWay,
                    $"до него {f.Gap:0.#} бл, а дороги туда нет — гнаться значит биться в стену");
            // НОГАМИ — НЕ ДАЛЬШЕ ПРЕДЕЛА ОБОРОНЫ. Общий предел
            // (EngageLimit) вырос вместе с кругом встречи, потому что стрелять
            // с двадцати блоков — законная оборона. Идти туда пешком — уже
            // охота, и до 27.08 бот шёл: стоило луку отказаться (порог доли,
            // кончились стрелы), и управление падало сюда с той же дальности
            if (f.Gap > f.FootChaseLimit)
                return new CombatRating(NoWay,
                    $"до него {f.Gap:0.#} бл, а стрелой не достану ({f.WhyNoShot()}); " +
                    $"идти к нему ногами дальше {f.FootChaseLimit:0.#} бл — это охота, а не оборона");
            // СКОРОСТИ НЕТ НИ ЗАМЕРОМ, НИ ИЗ ОПИСАНИЯ ТВАРИ. Такое остаётся
            // только для тех, кого нет в ассетах установленной игры (мод, чужой
            // сервер): выдумывать за них число нельзя, и гнаться вслепую тоже
            if (f.HisSpeed is not { } his)
                return new CombatRating(NoWay,
                    "скорости его не знаю: ни замера, ни описания твари в ассетах игры — " +
                    "гнаться вслепую не буду");
            if (f.MySpeed <= his + 0.01)
                return new CombatRating(NoWay,
                    $"не догоню: моя скорость {f.MySpeed:0.#} бл/с против его {his:0.#} ({f.SpeedSource})");
            closeSeconds = (f.Gap - f.Reach) / (f.MySpeed - his);
            if (closeSeconds > f.MaxChaseSeconds)
                return new CombatRating(NoWay,
                    $"догонять его {closeSeconds:0.#} с — дольше отпущенных {f.MaxChaseSeconds:0.#} с");
            approach = $"догоню за {closeSeconds:0.#} с ({f.MySpeed:0.#} против {his:0.#} бл/с, {f.SpeedSource})";
        }

        // ВАЛИТЬ БУДУ ЛУЧШИМ ИЗ СВОИХ СРЕДСТВ. У стрел в этом числе уже учтены
        // промахи (ShotDps), иначе крудовый лук на двадцати блоках обещал бы
        // свалить медведя за десять секунд.
        //
        // ФОРА СТРЕЛКА — ЭТО НЕ ПОДАРОК СЕБЕ, А ТА ЖЕ АРИФМЕТИКА, ЧТО И
        // «ДОГОНЮ ЛИ», ТОЛЬКО НАОБОРОТ. Пока он идёт ко мне свои пятнадцать
        // блоков, он меня не достаёт (твари бьют только вплотную и только по
        // прямой видимости), а я стреляю. Без этого счёта бой из лука был бы
        // ЗАПРЕЩЁН арифметикой: колокол в ста хп «снимал» бы двести пятьдесят
        // хп запасом за те две минуты, что его валят стрелами, — притом что
        // своего удара у него нет вовсе и с места он почти не сходит.
        //
        // ФОРУ СЕБЕ НЕ ВЫДУМЫВАЕМ: скорости его не знаю — форы нет.
        double killSeconds, cost;

        // ТРИ УСЛОВИЯ ОТХОДА живут одним местом (CombatFacts.KeepingDistance):
        // от них зависит не только цена боя, но и сама возможность вести
        // дальний бой в упор (см. отойдяСмогу) и снятие порога доли попадания
        bool держуДистанцию = f.KeepingDistance;

        // ОТОЙТИ И СТРЕЛЯТЬ — ВЕТКА, КОТОРАЯ ДО 27.08 БЫЛА НЕДОСТИЖИМА РОВНО
        // ТАМ, РАДИ ЧЕГО ЗАВЕДЕНА.
        //
        // Пока условием стояло одно лишь CanShoot, при Gap < «СтрелятьНеБлижеЧем»
        // вся дальняя ветка пропускалась — а вместе с ней и «пячусь». Сто хп
        // колокола считались тогда полным разменом вплотную, и ответ выходил
        // «не вытяну» → бегство. Живой щуп приёмки: колокол в 3,5 бл, лук, 64
        // стрелы и меч при себе — «ПЛАН: Flee — оторвусь за 2,7 с». Бот убегал
        // от того, кто его не бьёт, вместо того чтобы отойти на два блока и
        // расстрелять. Ровно об этом заказчик и просил: «луком предпочтительно,
        // если есть, с далека убивать колокола».
        bool отойдяСмогу = держуДистанцию && f.BowReady && f.ShotChanceEnough &&
                           f.Gap < f.ShootMinRange && f.ShootMinRange <= f.ShootMaxRange;

        if ((f.CanShoot && f.Gap > f.Reach) || отойдяСмогу)
        {
            double fora = f.HisSpeed is { } подходит && подходит > 0.01
                ? Math.Max(0, (f.Gap - f.Reach) / подходит)
                : 0;
            // Урон стрелами берём «откуда стрелять можно»: в ветке отхода
            // стрелять отсюда нельзя по определению, а через два шага — можно
            double лукДпс = отойдяСмогу ? f.ShotDpsAnywhere : f.ShotDps;
            double стрелами = f.HisHealth / Math.Max(1e-9, лукДпс);
            // ДЕРЖУ ДИСТАНЦИЮ — ЭТО НЕ «СТОЮ И СТРЕЛЯЮ», А НЕПРЕРЫВНЫЙ ОТХОД.
            //
            // Ради колокола (см. CombatDanger.CallsForHelp) и только по его же
            // условиям: подходить к нему нельзя, а сто хп простым луком с
            // одного захода не снять. Живой лучник в таком случае пятится, и
            // бот пятится тем же приёмом, каким отскакивает после удара
            // (StepBackAsync). Тогда размена вплотную не бывает вовсе, и цена
            // боя честно нулевая.
            //
            // «Держу дистанцию» без запаса скорости было бы обещанием, которого
            // ноги не выполнят, — поэтому три условия проверены выше, до развилки.
            // ОН ДО МЕНЯ НЕ ДОЙДЁТ — ЗНАЧИТ РАЗМЕНА НЕ БУДЕТ ВОВСЕ, и цена боя
            // честно нулевая. Без этой ветки счёт валился в «добиваю рукой»
            // ниже и обещал размен вплотную с тем, кто вплотную не окажется:
            // выходило «не вытяну» — то есть бот отказывался стрелять из окна
            // по дрифтеру, который и подойти-то не может
            if (f.Unreachable)
            {
                killSeconds = стрелами;
                cost = 0;
                approach += $"; дороги ко мне у него нет — размена не будет, " +
                            $"стреляю с {f.Gap:0.#} бл";
            }
            else if (держуДистанцию)
            {
                killSeconds = стрелами;
                cost = 0;
                approach += отойдяСмогу
                    ? $"; он в {f.Gap:0.#} бл — ближе, чем стреляю ({f.ShootMinRange:0.#}); " +
                      $"отхожу и бью стрелой ({f.MySpeed:0.#} против {f.HisSpeed:0.#} бл/с, " +
                      $"{f.SpeedSource})"
                    : $"; вплотную не подпущу — пячусь ({f.MySpeed:0.#} против " +
                      $"{f.HisSpeed:0.#} бл/с, {f.SpeedSource})";
            }
            else if (стрелами <= fora)
            {
                // Он не дойдёт: свалю раньше, чем он окажется на длине руки
                killSeconds = стрелами;
                cost = 0;
            }
            else
            {
                // ДОБИВАЮ РУКОЙ, А НЕ ЛУКОМ — И ЭТО НЕ ПРИДИРКА.
                //
                // Эта ветка начинается ровно тогда, когда он ДОШЁЛ до меня на
                // длину руки (Reach 2,3), то есть встал БЛИЖЕ «СтрелятьНеБлижеЧем»
                // (5), где лук молчит по определению. Здесь стоял BestDps, и он
                // подставлял в добивание урон выстрела, которого в этой фазе не
                // будет. Живой щуп приёмки: дрифтер 12 бл, лук 2,75×0,7, кулак
                // 0,5, 30 хп → «потеряю около 28,3 из 30 (оценка 72)» = дерусь;
                // честный счёт кулаком — 46,7 из 30, то есть «не вытяну».
                // РЕШЕНИЕ ПЕРЕВОРАЧИВАЛОСЬ, и человеку называлось лживое число.
                double осталось = Math.Max(0, f.HisHealth - лукДпс * fora);

                // ВПЛОТНУЮ У МЕНЯ НЕТ НИЧЕГО — И ЭТО НАДО СКАЗАТЬ, А НЕ
                // ПРЯТАТЬ ЗА УРОНОМ ЛУКА. Ровно тот случай, что открыла эта
                // волна: лук в хотбаре, меча нет — FindBestWeapon даёт 0.
                if (f.MyDps <= 0)
                    return new CombatRating(NoWay,
                        $"стрелой сниму {Math.Max(0, f.HisHealth - осталось):0.#} из " +
                        $"{f.HisHealth:0.#} хп, пока он идёт, а вплотную бить нечем: " +
                        "годного оружия нет, кулаками это не бой, а смерть");

                double добить = осталось / f.MyDps;
                killSeconds = fora + добить;
                cost = f.HisDps * добить;
            }
        }
        else
        {
            killSeconds = f.HisHealth / f.BestDps;
            // Пока догоняем, он нас не достаёт: либо убегает, либо ещё не дошёл.
            // Считаем размен — то, что начнётся, когда сойдёмся вплотную
            cost = f.HisDps * killSeconds;
        }
        if (cost >= f.MyHealth)
            return new CombatRating(NoWay,
                $"не вытяну: валить его {killSeconds:0.#} с, он за это время снимет " +
                $"{cost:0.#} хп, а у меня {f.MyHealth:0.#}");

        int score = 100 - (int)Math.Round(cost);
        string price = f.HisHit is { } hit
            ? $"он бьёт по {hit:0.##} хп ({(f.HisHitMeasured ? "замер" : "запас, ни разу не задевал")}) " +
              $"— потеряю около {cost:0.#}"
            : $"цену его удара не знаю — потеряю около {cost:0.#}";
        return new CombatRating(score,
            $"{approach}; свалю за {killSeconds:0.#} с, {price} из {f.MyHealth:0.#} (оценка {score})");
    }

    /// <summary>УХОДИТЬ. «Оторвусь ли» — тот же счёт скоростей, только наоборот.</summary>
    public static CombatRating RateFlee(CombatFacts f)
    {
        // БЕЖАТЬ ИЗ-ЗА СТЕНЫ НЕ ОТ КОГО, и это не мелочь. Без этой строки
        // получалось наоборот: бой сквозь преграду запрещён, значит остаётся
        // бегство — и бот, сидящий дома за закрытой дверью, ВЫХОДИЛ бы наружу
        // «отрываться» от твари, которая до него и так не дотягивается.
        // Из своего укрытия бегство — то же самое: выход наружу
        if (f.Blocked)
            return new CombatRating(NoWay, "бежать не от кого: " + f.WhyNotEngage());
        // ДВА РАЗНЫХ ПОРОГА, как и в FleeRules.Decide: срываться с места
        // из-за дрифтера на другом конце пещеры — это те самые семьдесят
        // строк «убегаю» за полминуты. Но если он БЬЁТ (стрелок с двадцати
        // блоков), расстояние ничего не значит — бежать надо
        if (f.Gap > f.FleeStart && !f.UnderFire)
            return new CombatRating(NoWay,
                $"он в {f.Gap:0.#} бл, ближе {f.FleeStart:0.#} не подходил и не бьёт — бежать не от чего");
        if (f.EscapeRoutes <= 0)
            return new CombatRating(NoWay, "бежать некуда: вокруг ног нет ни одной открытой стороны");
        // ЗА ОТРЫВ НЕ РУЧАЮСЬ — НО МЕНЯ БЬЮТ, И СТОЯТЬ ХУЖЕ.
        //
        // Здесь и был тупик по устройству (журнал 19.08): бот не знал, оторвётся
        // ли, а узнать это, стоя под ударами, невозможно. Живой игрок в такую
        // минуту не стоит: он уходит, не зная наверняка, — и уходит не зря даже
        // от того, кто быстрее. Тварь бьёт ТОЛЬКО по прямой видимости
        // (AiTaskBaseTargetable.hasDirectContact), значит любой угол, косяк и
        // склон разрывают удар, а не только чистый отрыв по скорости.
        //
        // Оценка нарочно худшая из годных: этот ответ берут, только когда не
        // годится ни один другой, — но БЕРУТ, а не отказываются от всего сразу.
        // И только под ударами: срываться с места от того, кто нас не трогает,
        // — это те самые семьдесят строк «убегаю» за полминуты.
        //
        // ЧЕГО СЮДА НЕ ПОПАДАЕТ: случаи, когда уход ЗАВЕДОМО не по карману
        // (цена больше здоровья) — это не «не ручаюсь», а «знаю, что убьёт»,
        // и там честнее «загнан».
        CombatRating НеРучаюсь(string why) => f.UnderFire
            ? new CombatRating(NoWay + 1, why +
                ", но меня бьют, а стоять под ударами хуже: ухожу вслепую — хотя бы разорву " +
                "прямую видимость (сквозь стену твари в игре не бьют)")
            : new CombatRating(NoWay, why + ", и он меня не бьёт — срываться с места незачем");

        if (f.HisSpeed is not { } his)
            return НеРучаюсь("скорости его не знаю: ни замера, ни описания твари в ассетах игры");
        if (f.MySpeed <= his + 0.01)
            return НеРучаюсь(
                $"не оторвусь: моя скорость {f.MySpeed:0.#} бл/с против его {his:0.#} ({f.SpeedSource})");

        double need = Math.Max(f.FleeGainAtLeast, f.EscapeDistance - f.Gap);
        double breakSeconds = need / (f.MySpeed - his);
        if (breakSeconds > f.MaxFleeSeconds)
            return НеРучаюсь(
                $"отрываться {breakSeconds:0.#} с — дольше отпущенных {f.MaxFleeSeconds:0.#} с");

        double cost = f.HisDps * Math.Min(breakSeconds, FleeExposureSeconds) + f.FleePrice;
        if (cost >= f.MyHealth)
            return new CombatRating(NoWay,
                $"даже уход стоит {cost:0.#} хп, а у меня {f.MyHealth:0.#}");

        int score = 100 - (int)Math.Round(cost);
        return new CombatRating(score,
            $"оторвусь за {breakSeconds:0.#} с ({f.MySpeed:0.#} против {his:0.#} бл/с, {f.SpeedSource}), " +
            $"уход обойдётся около {cost:0.#} хп (оценка {score})");
    }

    /// <summary>ЗАЛОЖИТЬСЯ. Годится только там, где проход один-два.</summary>
    public static CombatRating RateSeal(CombatFacts f)
    {
        // Закладывать проход, когда он и так закрыт, — тратить камень впустую
        if (f.Blocked)
            return new CombatRating(NoWay, "закладываться не от кого: " + f.WhyNotEngage());
        if (!f.CanSeal)
            return new CombatRating(NoWay, "закладываться нечем: подходящего блока в сумке нет");
        if (f.Gap > f.FleeStart && !f.UnderFire)
            return new CombatRating(NoWay,
                $"он в {f.Gap:0.#} бл и не бьёт — закладываться не от кого");
        if (f.EscapeRoutes > f.SealMaxOpenSides)
            return new CombatRating(NoWay,
                $"здесь открыто сторон: {f.EscapeRoutes} (больше {f.SealMaxOpenSides}) — обойдёт за полсекунды");

        double cost = f.HisDps * SealSeconds + f.SealPrice;
        if (cost >= f.MyHealth)
            return new CombatRating(NoWay,
                $"закладываться {SealSeconds:0.#} с — стоит {cost:0.#} хп, а у меня {f.MyHealth:0.#}");

        int score = 100 - (int)Math.Round(cost);
        return new CombatRating(score,
            $"проход узкий (открыто сторон: {f.EscapeRoutes}) — закроюсь блоком за {SealSeconds:0.#} с, " +
            $"потеряю около {cost:0.#} хп (оценка {score})");
    }

    /// <summary>
    /// НЕ СВЯЗЫВАТЬСЯ. Это полноценный вариант со своей ценой, а не «ничего
    /// не делать»: стоять под ударами тоже стоит здоровья, и когда эта цена
    /// выше собственного запаса — вариант отпадает, как и всякий смертельный.
    /// </summary>
    public static CombatRating RateIgnore(CombatFacts f)
    {
        // ПРЕГРАДА ДЕЛАЕТ ЭТОТ ОТВЕТ БЕСПЛАТНЫМ, и это факт игры, а не поблажка:
        // тварь бьёт только по прямой видимости (hasDirectContact), значит из-за
        // стены она не снимет ни хп. Цена ноль — оценка 100, и никакой другой
        // ответ её не перебьёт: и бой, и уход, и заклад стоят чего-нибудь.
        //
        // Своё укрытие считается здесь так же и по той же причине: пока оно
        // держится, он до бота не дотягивается. А перестанет держать —
        // Sheltered погаснет в ту же секунду (он ударил или влез внутрь), и
        // цена этого ответа станет обычной, со всеми числами
        if (f.Blocked)
            return new CombatRating(100, f.WhyNotEngage() + " — занимаюсь своим (оценка 100)");
        if (f.Gap > f.EngageLimit)
            return new CombatRating(100,
                $"он в {f.Gap:0.#} бл — дальше предела {f.EngageLimit:0.#}, занимаюсь своим (оценка 100)");
        if (f.HisDps <= 0)
            return new CombatRating(100,
                $"он в {f.Gap:0.#} бл и бить меня нечем — пока не мешает (оценка 100)");

        // ТЕРПЕНИЕ РАСХОДУЕТСЯ. Отпущенные ролью секунды считаются от НАЧАЛА
        // избиения (см. CombatFacts.EnduredSeconds), а не выдаются заново на
        // каждом ходу: без этого «не связываюсь» оставалось самым дешёвым
        // ответом сколь угодно долго, и бот честно давал себя забить, повторяя
        // одну и ту же строку. Кончилось терпение — слово переходит к драке,
        // уходу и закладыванию, а если и они откажут, останется «загнан»
        if (f.UnderFire && f.EnduredSeconds >= f.IgnoreSeconds)
            return new CombatRating(NoWay,
                $"терплю уже {f.EnduredSeconds:0.#} с из отпущенных {f.IgnoreSeconds:0.#} — " +
                "это больше не «занимаюсь своим», это «стою под ударами»");

        // СКИДКИ ЗА «Я ЖЕ БЫСТРЕЕ, РАЗОЙДЁМСЯ» ЗДЕСЬ НАРОЧНО НЕТ. Быстрее —
        // это когда БЕЖИШЬ; а «не связываться» значит заниматься своим делом
        // стоя на месте, и тварь дойдёт до бота сама
        double cost = f.HisDps * f.IgnoreSeconds;
        if (cost >= f.MyHealth)
            return new CombatRating(NoWay,
                $"стоять под ударами — это смерть: он снимет {cost:0.#} хп за {f.IgnoreSeconds:0.#} с, " +
                $"а у меня {f.MyHealth:0.#}");

        int score = 100 - (int)Math.Round(cost);
        return new CombatRating(score,
            $"если не трогать, за {f.IgnoreSeconds:0.#} с снимет около {cost:0.#} хп (оценка {score})");
    }

    /// <summary>
    /// ЗАГНАН. Крайняя мера, и оценка у неё нарочно хуже любого настоящего
    /// варианта: её берут, только когда не годится ни один другой. Здесь нет
    /// проверки «вытяну ли» — стоять лбом к стене под ударами хуже любого боя.
    /// </summary>
    public static CombatRating RateCornered(CombatFacts f)
    {
        // ЗАГНАННОСТЬ ЧЕРЕЗ СТЕНУ НЕ СЧИТАЕТСЯ. Тварь может стоять вплотную к
        // двери — по расстоянию это «вплотную», а по делу нас разделяет дверь,
        // и махать в неё от отчаяния незачем. Без этой строки крайняя мера
        // сработала бы там, где бот в полной безопасности. Замурованный в
        // собственном укрытии бот не «загнан», а спрятан — это разные вещи
        if (f.Blocked)
            return new CombatRating(NoWay, "драться от отчаяния не с кем: " + f.WhyNotEngage());
        if (f.Gap > f.Reach + MeleeSlack)
            return new CombatRating(NoWay,
                $"он в {f.Gap:0.#} бл — не вплотную, драться от отчаяния рано");
        return new CombatRating(NoWay + 1,
            $"он в {f.Gap:0.#} бл, у меня {f.MyHealth:0.#} хп, отходов {f.EscapeRoutes} — " +
            "ни уйти, ни закрыться, ни вытянуть размен: дерусь тем, что есть");
    }

    /// <summary>Порядок разбора и он же порядок при равных оценках.</summary>
    private static readonly CombatChoice[] Order =
        [CombatChoice.Fight, CombatChoice.Flee, CombatChoice.Seal,
         CombatChoice.Ignore, CombatChoice.Cornered];

    /// <summary>Оценить один названный вариант.</summary>
    public static CombatRating Rate(CombatChoice choice, CombatFacts f) => choice switch
    {
        CombatChoice.Fight => RateFight(f),
        CombatChoice.Flee => RateFlee(f),
        CombatChoice.Seal => RateSeal(f),
        CombatChoice.Ignore => RateIgnore(f),
        _ => RateCornered(f)
    };

    /// <summary>
    /// ЛУЧШИЙ ВАРИАНТ ИЗ ВСЕХ — оценили каждый, взяли максимум. При равных
    /// побеждает первый по <see cref="Order"/>, чтобы ответ не зависел от
    /// прогона: дёрганье между двумя одинаковыми решениями живьём выглядит
    /// как «бот мечется».
    /// </summary>
    public static CombatDecision Pick(CombatFacts f)
    {
        var rated = new Dictionary<CombatChoice, CombatRating>();
        CombatChoice best = CombatChoice.Ignore;
        CombatRating? bestRating = null;
        foreach (var choice in Order)
        {
            var rating = Rate(choice, f);
            rated[choice] = rating;
            if (!rating.Usable)
                continue;
            if (bestRating == null || rating.Score > bestRating.Score)
            {
                best = choice;
                bestRating = rating;
            }
        }

        // НЕ ГОДИТСЯ НИ ОДИН. Молчать нельзя: человек должен прочитать, обо
        // что споткнулись все ответы сразу
        if (bestRating == null)
            return new CombatDecision(CombatChoice.Ignore, NoWay, WhyNothing(rated));

        // «НЕ СВЯЗЫВАЮСЬ» ОБЯЗАНО ОБЪЯСНИТЬ, ПОЧЕМУ НЕ СВЯЗЫВАЕТСЯ.
        //
        // Именно этого не хватало живьём. Заказчик: «Не догоняем — честный
        // отказ, а не 17 строк „тупик"». Отказ есть, но он лежал внутри
        // отброшенного варианта, и в журнал попадало безмятежное «занимаюсь
        // своим» — при том что бот только что решил не гнаться из-за стены
        //
        // ПРЕГРАДА И УКРЫТИЕ — ИСКЛЮЧЕНИЕ, И ВОТ ПОЧЕМУ. Когда нас разделяет
        // стена или дверь либо держится своё укрытие, все четыре отказа — ОДИН
        // И ТОТ ЖЕ отказ (см. WhyNotEngage), и перечисление превратило бы одну
        // ясную строку в четыре одинаковых. Это ровно тот шум, из-за которого
        // в журнале заказчика не было видно беды
        string why = bestRating.Why;
        if (best == CombatChoice.Ignore && !f.Blocked)
        {
            var refused = new List<string>();
            foreach (var c in new[] { CombatChoice.Fight, CombatChoice.Flee, CombatChoice.Seal })
                if (!rated[c].Usable)
                    refused.Add($"{CombatDecision.Name(c)} не выйдет — {rated[c].Why}");
            if (refused.Count > 0)
                why += "; " + string.Join("; ", refused);
        }
        return new CombatDecision(best, bestRating.Score, why);
    }

    /// <summary>
    /// ПОЧЕМУ НЕ ВЫШЛО НИЧЕГО — называем помехи по всем вариантам сразу.
    /// «Не смог» без разбора в журнале не читается никак, а чинить надо ровно
    /// то, обо что споткнулись.
    /// </summary>
    public static string WhyNothing(CombatFacts f) =>
        WhyNothing(Order.ToDictionary(c => c, c => Rate(c, f)));

    private static string WhyNothing(IReadOnlyDictionary<CombatChoice, CombatRating> rated) =>
        "делать нечего и вот почему: " + string.Join("; ",
            Order.Select(c => $"{CombatDecision.Name(c)} — {rated[c].Why}"));

    /// <summary>
    /// Все варианты с оценками — для панели и разбора живого случая. Человек
    /// должен ВИДЕТЬ, из чего бот выбирал, а не только что он выбрал.
    /// </summary>
    public static IReadOnlyList<(CombatChoice Choice, CombatRating Rating)> Report(CombatFacts f) =>
        Order.Select(c => (c, Rate(c, f))).ToList();
}

/// <summary>Что значит полученный удар для решения «лезть ли в бой».</summary>
public enum FightEntry
{
    /// <summary>Живой противник ударил заметно — есть с кем драться.</summary>
    FightBack,

    /// <summary>Живой противник задел, но это царапина — не повод бросать дело.</summary>
    Scratch,

    /// <summary>Голод, падение, холод — отбиваться не от кого.</summary>
    NotAFight,

    /// <summary>Сервер причину не назвал (или мы её не прочли) — гадать не будем.</summary>
    Unknown
}

/// <summary>
/// ВХОД В БОЙ — ЧИСТОЕ ПРАВИЛО НА ДВУХ ЧИСЛАХ И ОДНОМ ФАКТЕ.
///
/// Живой случай целиком: «[чат:-5] Потеряно 0,03 хп дрифтер (моб) → вход в бой»
/// и рядом «Потеряно 1,07 хп от gravity», «Потеряно 0,13 хп от hunger» — тем же
/// путём. Заказчик: «рандомно включается, нужно разграничить причины».
///
/// Разграничение здесь ровно одно и очень простое:
///   1. Ударил ЖИВОЙ противник? Нет — это не бой, чем бы ни было (голод,
///      падение, холод). Отбиваться не от кого, и ход надо отдать еде и одежде.
///   2. Ударил заметно? Три сотых хп — не нападение, а щекотка: самый слабый
///      дрифтер бьёт на 2,5 хп. Порог — настройкой, потому что у брони бота
///      и у модовых тварей числа свои.
/// </summary>
public static class CombatEntry
{
    /// <summary>Разобрать один удар: лезть ли из-за него в бой.</summary>
    public static FightEntry Judge(DamageHit? hit, double minToFight)
    {
        if (hit == null || hit.From == DamageFrom.Unknown)
            return FightEntry.Unknown;
        if (!hit.ByLiving)
            return FightEntry.NotAFight;
        return hit.Amount >= minToFight ? FightEntry.FightBack : FightEntry.Scratch;
    }

    /// <summary>Одна строка для журнала — с причиной и числами, а не «получил урон».</summary>
    public static string Say(FightEntry verdict, DamageHit hit, double minToFight) => verdict switch
    {
        FightEntry.FightBack => $"меня ударили: {hit} — разбираюсь",
        FightEntry.Scratch =>
            $"царапина: {hit}, меньше порога {minToFight:0.##} хп — в бой из-за неё не лезу",
        FightEntry.NotAFight =>
            $"это не нападение: {hit} — отбиваться не от кого",
        _ => $"урон есть, а причину сервер не назвал ({hit.Raw}) — в бой не лезу"
    };
}
