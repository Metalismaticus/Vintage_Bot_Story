namespace VsBotKit;

/// <summary>
/// ЗАЧЕМ БОТ ОТКРЫЛ РОТ. Не «что он сказал», а «по какому поводу» — от этого и
/// зависит, уходит ли строка в игровой чат при радиотишине.
///
/// Разделение НЕ придумано, а взято из прямого вопроса заказчика 16.08:
/// «чтобы бот казался настоящим и принимал команды только через вебформу и
/// ничего в чат не писал по своим задачам». Ключевое слово там — «по своим
/// задачам»: отчёты о наряде глушить надо, а приветствие и ответ на прямое
/// обращение — ни в коем случае. Молчащий в ответ на «привет» бот выглядит не
/// живее, а мертвее — и это ровно противоположно тому, чего просили.
/// </summary>
public enum SayReason
{
    /// <summary>
    /// СКАЗАТЬ ВЕЛЕЛИ ПРЯМО, этой самой строкой: кнопка «сказать» в окне
    /// управления, строка в консоли хозяина, ответ нейросети. Заводское
    /// значение у всех дверей нарочно: строку, которую человек написал сам,
    /// глушить нельзя ни при какой настройке — он нажал и ждёт её в чате.
    /// </summary>
    Приказ,

    /// <summary>
    /// КОМАНДА СЕРВЕРУ, а не речь: «/emote wave», «/tp», «/gamemode». Ставится
    /// не рукой, а по первому символу (см. <see cref="BotVoice.IsServerCommand"/>):
    /// префикс «/» — это правило самой игры
    /// (<c>ChatCommandApi.ServerCommandPrefix</c>, VintagestoryLib 1.22.6),
    /// а не наша договорённость. Глуши мы её — приветственный ЖЕСТ перестал бы
    /// работать вместе со словами, хотя жест никто выключать не просил.
    /// </summary>
    Служебное,

    /// <summary>
    /// ОТВЕТ ЧЕЛОВЕКУ, КОТОРЫЙ САМ ОБРАТИЛСЯ В ЧАТ. Не глушится никогда:
    /// человек написал боту и ждёт ответа, а тишина в ответ — это и есть
    /// «сломанный бот» в глазах любого, кто подошёл. Сюда же попадает честный
    /// отказ «управление из чата закрыто».
    /// </summary>
    Ответ,

    /// <summary>
    /// ЗДРАВСТВУЙ И ПРОЩАЙ. Не глушится: у приветствия и прощания уже есть
    /// СВОИ ручки роли («Здороваться», «МахатьИгрокам»,
    /// «ПрощатьсяПередУходом»), и вторая ручка, гасящая то же самое, была бы
    /// второй копией одной механики — а её потом ищут по всей панели.
    /// </summary>
    Вежливость,

    /// <summary>
    /// БОТ ГОВОРИТ ПО СВОЕМУ ПОЧИНУ О СВОИХ ДЕЛАХ: «Мощу дорогу. „!стоп“ —
    /// прервать», «дорога 1 рядов из 38, замощено 1 кл. из 114…». Ровно эти
    /// строки заказчик и видел в живом журнале 16.08 при наряде, отданном из
    /// окна управления. ЭТО И ГЛУШИТ РАДИОТИШИНА — и только это.
    /// </summary>
    Отчёт,

    /// <summary>
    /// ОТВЕТ НА КОМАНДУ, ПОЗВАННУЮ МИМО ЧАТА: окно управления, стенд, консоль
    /// хозяина. В чат такая строка при радиотишине НЕ идёт — в чате её никто не
    /// ждал; но в журнал она обязана лечь ЦЕЛИКОМ, потому что больше её туда не
    /// пишет никто.
    ///
    /// ЖИВАЯ ЛОЖЬ, РАДИ КОТОРОЙ ЗАВЕДЕНО (прогон 27.08, out/разведка-лук4).
    /// Ответ «!рядом water 48» ушёл укороченным с хвостом «…(целиком — в журнале
    /// и окне управления)», а в журнале лежала ровно та же обрезанная строка:
    /// длинный ответ шёл поводом <see cref="Отчёт"/>, а тот нарочно НЕ пишет
    /// целое — считается, что работа уже написала его сама. Ответ команды не
    /// пишет никто, и хвост обещал читателю несуществующее. Разведка мира два
    /// раза подряд теряла список найденного, и найденное приходилось искать
    /// заново.
    ///
    /// Тем и отличается от <see cref="Ответ"/>: тот — человеку В ЧАТ и не
    /// глушится никогда; этот — человеку В ОКНО и глушится, как отчёт.
    /// </summary>
    ОтветМимоЧата
}

/// <summary>
/// ГОЛОС БОТА: одни ворота на весь исходящий игровой чат.
///
/// ЗАЧЕМ ЭТОТ КЛАСС ПОЯВИЛСЯ. Прямой вопрос заказчика 16.08: «настройка
/// „КомандыИзЧата“ … дает радиотишину? чтобы бот казался настоящим и принимал
/// команды только через вебформу и ничего в чат не писал по своим задачам?».
/// Ответ по коду — НЕТ: <see cref="ChatCommands.AcceptFromChat"/> стоит на
/// разборе ВХОДЯЩЕЙ строки и про рот бота не знает вовсе. Говорить боту она не
/// мешала никак: в журнале того же прогона он писал в чат «Мощу дорогу…» и
/// полный отчёт о наряде, отданном из окна управления, — потому что ответы
/// команды уходят в чат независимо от того, откуда команду позвали.
///
/// ПОЧЕМУ ВОРОТА ЗДЕСЬ, А НЕ У КАЖДОГО ГОВОРЯЩЕГО. Дверь в чат у бота ровно
/// одна — <see cref="BotClient.SendChatAsync"/>: через неё идут и ответы
/// команд, и приветствия, и «/emote», и строка из окна «сказать». Поставь
/// проверку у говорящих — их семь, и восьмой её забудет; а забытая проверка в
/// этом деле означает, что бот выдал себя одной строкой.
///
/// НИКОГДА МОЛЧАНИЕ. Проглоченная строка не исчезает: она уходит в журнал
/// хозяина с пометкой «[молчу]». Иначе радиотишина стала бы способом ПОТЕРЯТЬ
/// отчёт о наряде, а не спрятать его от чужих глаз.
/// </summary>
public sealed class BotVoice
{
    /// <summary>
    /// ПИСАТЬ ЛИ В ЧАТ О СВОИХ ДЕЛАХ. Заводское «да» — так бот вёл себя всегда,
    /// и молча отнимать у человека отчёты в чате нельзя. «Нет» — радиотишина:
    /// в чат не уходит ни одна строка, которую бот сочинил сам.
    ///
    /// Механизм, а не политика: ЧТО считать своим делом, решает
    /// <see cref="SayReason"/>, а СТОИТ ЛИ молчать — роль
    /// (LivingRole.ПисатьВЧатОСвоихДелах).
    /// </summary>
    public bool ReportWork { get; set; } = true;

    /// <summary>
    /// Строку проглотила радиотишина. Слушает журнал: молчания без следа быть
    /// не должно.
    /// </summary>
    public event Action<string>? OnHushed;

    /// <summary>
    /// КОМАНДА СЕРВЕРУ ЛИ ЭТО. Правило игры, а не наше: серверные команды
    /// начинаются с «/» (<c>Vintagestory.Common.ChatCommandApi.ServerCommandPrefix
    /// = "/"</c>, сверено по VintagestoryLib 1.22.6). Клиентский префикс «.»
    /// сюда не входит намеренно: клиента у бота нет, и такая строка ушла бы на
    /// сервер обычной репликой.
    ///
    /// Чистая функция: ошибись здесь — и радиотишина проглотит «/emote wave»,
    /// то есть сломает приветственный жест, о котором никто не просил.
    /// </summary>
    public static bool IsServerCommand(string? message) =>
        message is { Length: > 0 } && message.TrimStart().StartsWith('/');

    /// <summary>
    /// УЙДЁТ ЛИ СТРОКА В ЧАТ. Всё правило целиком, одной чистой функцией —
    /// поэтому оно и закрыто тестом: живьём проверять «промолчал ли бот на
    /// людном сервере» нечем.
    /// </summary>
    public static bool Speaks(SayReason reason, bool reportWork) =>
        (reason != SayReason.Отчёт && reason != SayReason.ОтветМимоЧата) || reportWork;

    /// <summary>
    /// ПО КАКОМУ ПОВОДУ ЭТО СКАЗАНО НА САМОМ ДЕЛЕ. Названный повод уточняется
    /// по самой строке: «/emote wave», отданное как отчёт, всё равно остаётся
    /// командой серверу, а не речью.
    /// </summary>
    public static SayReason ReasonOf(string? message, SayReason told) =>
        IsServerCommand(message) ? SayReason.Служебное : told;

    /// <summary>
    /// Пропустить ли эту строку в чат. Единственное место, где решение
    /// принимается; проглоченное уходит в <see cref="OnHushed"/>.
    /// </summary>
    public bool Allows(string? message, SayReason told)
    {
        var повод = ReasonOf(message, told);
        if (Speaks(повод, ReportWork))
            return true;
        OnHushed?.Invoke($"[молчу] в чат не пишу о своих делах (радиотишина): {message}");
        return false;
    }

    // ======================= ДЛИНА СТРОКИ В ЧАТЕ =======================

    /// <summary>
    /// СКОЛЬКО БУКВ ПУСКАТЬ В ЧАТ ОДНОЙ СТРОКОЙ. Ноль и меньше — не резать
    /// вовсе (так бот и говорил до сих пор).
    ///
    /// Механизм, а не политика: СКОЛЬКО именно — решает роль
    /// (LivingRole.ДлинаСтрокиВЧате), потому что зависит это от чата у человека
    /// на экране, а не от игры. В сборках игры предела длины реплики нет —
    /// искали: ни <c>Packet_ChatLine</c>, ни разбор чата на сервере её не режут.
    /// Значит, число здесь человеческое, и придумывать его за человека нельзя.
    /// </summary>
    public int MaxChatLength { get; set; }

    /// <summary>
    /// Строку укоротили для чата. Слушает журнал: в журнал уходит ЦЕЛАЯ строка,
    /// иначе укорачивание стало бы способом потерять отчёт, а не сократить его.
    /// </summary>
    public event Action<string>? OnShortened;

    /// <summary>Куда отсылать за подробностями. Отдельно — чтобы искать в одном месте.</summary>
    public const string WhereTheRestIs = "…(целиком — в журнале и окне управления)";

    /// <summary>
    /// КОРОТКАЯ СТРОКА ДЛЯ ЧАТА из длинного отчёта.
    ///
    /// ЖИВОЙ СЛУЧАЙ (журнал заказчика 20.08, 00:01:30). В общий чат ушёл ВЕСЬ
    /// отчёт о дороге — 700 с лишним букв: ряды, клетки, коды блоков, две
    /// клетки координатами, две ручки роли по имени и разбор нехватки камня.
    /// Слова заказчика: «в игре это простыня на пять строк». Отчёт этот верный
    /// и нужный — но нужен он в журнале и окне, а в чате от него не остаётся
    /// даже начала: пять строк уезжают вверх быстрее, чем их прочтут.
    ///
    /// РЕЖЕМ ПО ГРАНИЦЕ МЫСЛИ, А НЕ ПО БУКВЕ. Отчёты у бота собраны из кусков
    /// через «; » — ровно так их и разбирает человек. Обрыв посреди слова
    /// («не хватает stone-perido») читается как поломка, а не как краткость.
    /// Если первый же кусок длиннее предела — тогда режем по слову, и только
    /// если и слова нет — по букве: соврать «строка кончилась» нельзя нигде.
    ///
    /// И ВСЕГДА ГОВОРИМ, ЧТО УКОРОТИЛИ. Без хвоста
    /// <see cref="WhereTheRestIs"/> короткая строка неотличима от полного
    /// ответа, и человек решит, что бот не назвал причину, — а бот назвал.
    /// Предел меньше самого хвоста — тогда в чат уходит ОДИН хвост: сказать
    /// «смотрите журнал» и ничего больше честнее, чем выдать огрызок в три
    /// буквы за ответ. Целая строка при этом в журнале, как и всегда.
    /// </summary>
    /// <param name="message">Что бот собрался сказать.</param>
    /// <param name="maxLength">Предел букв; ноль и меньше — не резать.</param>
    public static string Shorten(string? message, int maxLength)
    {
        string текст = message ?? "";
        if (maxLength <= 0 || текст.Length <= maxLength)
            return текст;

        // Команду серверу не режем НИКОГДА: «/tp =512061 =112 =512257» —
        // это действие, и обрубок его не выполнит, а исказит
        if (IsServerCommand(текст))
            return текст;

        int место = Math.Max(0, maxLength - WhereTheRestIs.Length);
        // Граница мысли: последняя точка с запятой, уместившаяся в предел
        int граница = текст.LastIndexOf("; ", Math.Min(место, текст.Length - 1),
            StringComparison.Ordinal);
        if (граница <= 0)
            граница = текст.LastIndexOf(' ', Math.Min(место, текст.Length - 1));
        if (граница <= 0)
            граница = место;                 // ни точки с запятой, ни пробела
        return текст[..граница].TrimEnd(' ', ';', ',') + WhereTheRestIs;
    }

    /// <summary>
    /// СЛЕД УКОРАЧИВАНИЯ В ЖУРНАЛЕ — и целая строка при нём ровно тогда, когда
    /// её больше негде взять.
    ///
    /// ЖИВОЙ СЛУЧАЙ 22.08, 17:18:35 — тот самый, ради которого правило и
    /// заведено. Отказ дороги стоял в журнале четырьмя строками, и самой
    /// длинной из них была строка «[коротко в чат]»: она несла И короткую
    /// строку, И весь отчёт целиком — третьим экземпляром за ту же
    /// миллисекунду. Заказчик просил короткую строку в чат, получил её — и
    /// журнал стал хуже прежнего.
    ///
    /// РАЗНИЦУ ДЕЛАЕТ ПОВОД, А НЕ ДЛИНА. <see cref="SayReason.Отчёт"/> — это
    /// бот рассказывает о СВОЕЙ работе, а свой отчёт работа уже написала в
    /// журнал сама и целиком (у каждого job'а в конце
    /// <c>OnLog(report.ToString())</c>). Здесь он был бы вторым экземпляром, и
    /// достаточно отметки: строку укоротили, вот насколько.
    ///
    /// А ВОТ ОТВЕТ ЧЕЛОВЕКУ («!помощь», «!запасы») не пишет в журнал НИКТО,
    /// кроме этой строки. Выброси мы целый текст и здесь — хвост
    /// <see cref="WhereTheRestIs"/> стал бы враньём: он обещает, что целое
    /// лежит в журнале.
    ///
    /// И ОТВЕТ ИЗ ОКНА — ТОЖЕ ОТВЕТ (<see cref="SayReason.ОтветМимоЧата"/>).
    /// До 27.08 такого повода не было вовсе, и ответы команд, позванных стендом
    /// и окном управления, шли поводом «Отчёт»: хвост обещал журнал, а в журнале
    /// лежала та же обрезанная строка. Улика — out/разведка-лук4: «Нашёл: air
    /// (−16, 115, −65); … …(целиком — в журнале и окне управления)», и рядом
    /// «[коротко в чат] отчёт работы (257 букв) укоротил до 213: целиком его
    /// пишет в журнал сама работа». Работа его не писала: работы не было, была
    /// команда.
    ///
    /// Чистая функция: живьём разницу между поводами видно только на настоящем
    /// сервере с настоящим человеком в чате.
    /// </summary>
    public static string ShortenNote(string shortened, string full, SayReason reason) =>
        reason == SayReason.Отчёт
            ? $"[коротко в чат] отчёт работы ({full.Length} букв) укоротил до " +
              $"{shortened.Length}: целиком его пишет в журнал сама работа"
            : $"[коротко в чат] сказал «{shortened}»; целиком: {full}";

    /// <summary>
    /// Строка для чата — уже укороченная, если надо. След укорачивания уходит
    /// журналу через <see cref="OnShortened"/> (см. <see cref="ShortenNote"/>).
    /// </summary>
    /// <param name="reason">
    /// По какому поводу это сказано. От повода зависит, нужен ли журналу целый
    /// текст: свой отчёт работа туда уже написала, а ответ человеку — нет.
    /// БЕЗ УМОЛЧАНИЯ НАРОЧНО: забытый повод означал бы отчёт в журнале вторым
    /// экземпляром — ровно то, из-за чего правило и заведено. Пусть об этом
    /// спорит компилятор, а не приёмка.
    /// </param>
    public string ForChat(string message, SayReason reason)
    {
        string коротко = Shorten(message, MaxChatLength);
        if (!ReferenceEquals(коротко, message) && коротко != message)
            OnShortened?.Invoke(ShortenNote(коротко, message, reason));
        return коротко;
    }
}
