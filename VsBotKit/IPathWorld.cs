namespace VsBotKit;

/// <summary>
/// Всё, что поиск пути спрашивает у мира. РОВНО пятнадцать вопросов — и ни
/// одного про сеть, пакеты, предметы, рецепты или инвентари.
///
/// Зачем этот шов. До него планировщик принимал <see cref="WorldModel"/>
/// целиком — тысяча триста строк, где разбор пакетов соседствует с реестром
/// брони и питательностью еды. Из-за этого:
/// <list type="bullet">
/// <item>его нельзя было проверить отдельно от сетевой модели;</item>
/// <item>чужую реализацию поиска подставить было некуда — она тянула бы
/// на себя весь класс;</item>
/// <item>и главное: логику нельзя было переиспользовать в клиентском МОДЕ,
/// где мир спрашивают у самой игры, а не собирают из пакетов.</item>
/// </list>
///
/// Теперь мод отвечает на те же пятнадцать вопросов через игровой доступ к
/// блокам — и получает ровно тот же поиск пути, что и безголовый бот.
/// Один алгоритм, две жизни.
/// </summary>
public interface IPathWorld
{
    /// <summary>Стоять в этой клетке можно: под ногами опора, телу есть место.</summary>
    bool IsStandable(int x, int y, int z);

    /// <summary>
    /// ТОЧНАЯ ВЫСОТА НОГ, ЕСЛИ СТОЯТЬ В ЭТОЙ КЛЕТКЕ, в блоках: на полном кубе
    /// снизу — ровно граница клетки, на тонком блоке В САМОЙ клетке (плита,
    /// дорожная плита, пластина) — его верх.
    ///
    /// ЗАЧЕМ ЭТО ПОИСКУ ПУТИ. Живой случай 26.08: подъём на клетку выше решался
    /// ПО НОМЕРУ КЛЕТКИ и всегда считался шагом. Но одна клетка по номеру —
    /// это что угодно по высоте: с плиты на плиту 0,5 (шаг берёт), а с дорожной
    /// плиты (верх 0,9375) на целый блок — 1,06, и шага в 0,6 не хватает.
    /// Бот двенадцать раз упирался и записывал проходимые клетки в тупики.
    /// Теперь высота меряется в блоках, и мерку даёт мир.
    /// </summary>
    double FeetY(int x, int y, int z);

    /// <summary>Войти телом можно: проходимо, лестница или открываемая дверь.</summary>
    bool IsEnterable(int x, int y, int z);

    /// <summary>Клетка не мешает пройти (тонкая трава, ковёр, воздух).</summary>
    bool IsPassable(int x, int y, int z);

    /// <summary>Блок целиком перекрывает клетку.</summary>
    bool IsSolid(int x, int y, int z);

    /// <summary>На это можно опереться: пол, вода или лестница.</summary>
    bool IsSupport(int x, int y, int z);

    /// <summary>Держаться за лестницу в этой клетке (считая уровень головы).</summary>
    bool CanHangAt(int x, int y, int z);

    /// <summary>Лестница как таковая.</summary>
    bool IsClimbable(int x, int y, int z);

    /// <summary>Вода, в которой плывут.</summary>
    bool IsWater(int x, int y, int z);

    /// <summary>Поверхность воды: плыть можно, голова над водой.</summary>
    bool IsWaterSurface(int x, int y, int z);

    /// <summary>
    /// СКОЛЬКО НАЛИТО В КЛЕТКУ, доля 0…1 (<c>Block.LiquidLevel</c> игры, делённый
    /// на восемь). Не жидкость — ноль.
    ///
    /// ЗАЧЕМ ЭТОТ ВОПРОС ПОЯВИЛСЯ СЕМНАДЦАТЫМ. По уровню заполнения игра считает
    /// ДВЕ разные вещи, и обе решают, выйдет ли тело из воды на берег:
    /// плавучесть (<c>PModuleInLiquid.HandleSwimming</c> берёт LiquidLevel/8) и
    /// поблажку «упёрся в стену — ползи вверх», которая требует ровно полной
    /// воды, <c>LiquidLevel &gt;= 7</c>. Замер на живых модулях игры показал
    /// разницу в целую клетку: из пруда 7/8 тело выходит на кромку, а из такого
    /// же пруда 6/8 — нет. Пока вопроса не было, поиск пути мерил выход
    /// выдуманной ручкой «на клетку вверх можно» и обещал невозможное.
    /// </summary>
    double LiquidFill(int x, int y, int z);

    /// <summary>
    /// ГДЕ ПОТОЛОК НАД ЭТОЙ КЛЕТКОЙ, блоков: высота низа первой коллизии выше
    /// её пола. <c>double.PositiveInfinity</c> — потолка в окне взгляда нет.
    ///
    /// ЗАЧЕМ ЭТОТ ВОПРОС ПОЯВИЛСЯ ШЕСТНАДЦАТЫМ. Живая беда 27.08: бот в
    /// затопленном ходе (пол 113, вода в 113 и 114, кирпичный потолок в 115)
    /// одиннадцать опытов подряд не мог выйти на кромку 114,0 — и стоял ровно
    /// на 113,15, то есть 115,0 − 1,85: ВИСЕЛ МАКУШКОЙ В ПОТОЛКЕ. Плавучесть
    /// выше не поднимает, прыжка у плывущего нет вовсе
    /// (<c>PModuleOnGround.Applicable</c> — «OnGround &amp;&amp; !Swimming»), а
    /// всход берёт свои 0,6 от ног. Пока этого вопроса не было, поиск пути
    /// раздавал выход из воды по одному лишь «на кромке можно стоять» — и звал
    /// туда, куда телу не подняться.
    /// </summary>
    double CeilingOver(int x, int y, int z);

    /// <summary>
    /// ЧЕМ КЛЕТКА ВРЕДИТ ТОМУ, КТО В НЕЙ ОКАЗАЛСЯ: лава, кипяток, огонь,
    /// горящий костёр, шипы. Что именно считать вредом, решает одно правило на
    /// весь проект — <see cref="HarmRules.HarmOf"/>, и решает по реестру игры.
    ///
    /// СПРАШИВАЮТ ЭТО ДВУМЯ ИМЕНАМИ, и разница между ними важная:
    /// <see cref="HarmRules.HurtsToEnter"/> — «сюда не вставать заранее» (любой
    /// вред, им живут маршрут и выбор места), <see cref="HarmRules.HurtsToStandIn"/>
    /// — «отсюда уходить прямо сейчас» (жжёт стоящего смирно). Оба — тонкая
    /// обёртка над этим одним вопросом, второго правила нет.
    ///
    /// Здесь стояло «IsDangerousLiquid», и оно знало ровно про слой жидкости:
    /// маршрут через собственный костёр строился беспрепятственно.
    /// </summary>
    CellHarm HarmAt(int x, int y, int z);

    /// <summary>Дверь.</summary>
    bool IsDoor(int x, int y, int z);

    /// <summary>Дверь открыта.</summary>
    bool IsDoorOpen(int x, int y, int z);

    /// <summary>Дорога или тропа: по ней ходят охотнее.</summary>
    bool IsRoadLike(int x, int y, int z);

    /// <summary>
    /// Множитель скорости ходьбы для того, кто СТОИТ В ЭТОЙ КЛЕТКЕ.
    ///
    /// Вопрос нарочно про клетку ног, а не про блок под ней: игра берёт ДВА
    /// блока — тот, что под ногами, и тот, в котором ноги стоят, — и слой снега
    /// виден только во втором (см. WorldModel.StandingWalkSpeed). Пока спрос был
    /// «блок под клеткой», занесённая снегом каменная тропа числилась у дороги
    /// самой быстрой землёй, а тело шло по ней медленнее всего.
    /// </summary>
    float StandingWalkSpeed(int x, int y, int z);

    /// <summary>Ближайший уровень с опорой в окне; null — опоры нет.</summary>
    int? FindSupportY(int x, int startY, int z, int up = 1, int down = 3);
}
