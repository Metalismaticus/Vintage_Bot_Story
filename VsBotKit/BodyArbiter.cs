namespace VsBotKit;

/// <summary>
/// Кто прямо сейчас распоряжается телом.
///
/// Тело у бота ОДНО, а желающих двигать им несколько: долгая задача (сходить,
/// сложить костёр, вспахать поле), рефлекс выживания (бежать от дрифтера,
/// драться, лечиться) и команда из чата. Без разбора очереди получается то,
/// что поймано живьём: рефлекс уводит бота от дрифтера, а задача готовки
/// продолжает тыкать в костёр — с двадцати пяти блоков, честно докладывая
/// «не дотянуться» двадцать раз подряд.
///
/// Правило простое: тело берут во владение, у владения есть важность, и более
/// важный владелец ПЕРЕБИВАЕТ менее важного — у того сразу срабатывает отмена,
/// и он прекращает работу сам. Равный по важности не перебивает: две команды
/// подряд не толкаются, вторая просто ждёт своей очереди или уходит ни с чем.
///
/// ВЫШЕ ВСЕХ СТОИТ ЖИЗНЬ (<see cref="Importance.Vital"/>): поесть, полечиться,
/// выбраться из воды. Эта ступень появилась не для красоты — «равный не
/// перебивает» стоило заказчику бота, который рыл карьер и умирал от голода с
/// хлебом в кармане. Важности этой ступени НЕТ настройки и быть не должно:
/// иначе «копать» можно было бы поставить выше «есть».
///
/// ГРАНИЦА С ПЛАНИРОВЩИКОМ, и её нельзя стирать. Появился револьверный цикл
/// (<see cref="Revolver"/>): он смотрит вперёд и решает, ЧТО БОТ СДЕЛАЕТ
/// ДАЛЬШЕ — например, поесть у порога, потому что в пути проголодается.
/// Распорядитель тела не знает о нём ничего и знать не должен: он отвечает на
/// совсем другой вопрос — КТО РАСПОРЯЖАЕТСЯ ТЕЛОМ ПРЯМО СЕЙЧАС. Планировщик
/// может ошибиться в сроке, не успеть, не угадать; право рефлекса перебить
/// работу от этого не убавляется НИ НА ВОЛОС. Соблазн «раз мы теперь планируем,
/// пусть план и решает, кому дать тело» здесь назван нарочно, чтобы его не
/// приняли за упущение: планом нельзя отменить голод, бой и воду в лёгких.
///
/// ДРОЖЬ ВЫБОРА, И ПОЧЕМУ У ГОЛОГО СРАВНЕНИЯ ВАЖНОСТЕЙ ЕЁ НЕ ИЗБЕЖАТЬ. Жалоба
/// заказчика 30.08 дословно: «он бегал вперед назад с резкими разворотами как
/// сумасшедший». В журнале это шесть смен хозяина тела за четырнадцать секунд —
/// по одной каждые две с небольшим секунды, и КАЖДАЯ ВЫБРАНА ВЕРНО: бот и
/// правда был голоден, сумки и правда были полны. Неверна была не одна из них,
/// а их череда: у смены хозяина есть цена — разворот на месте и марш к новой
/// цели, — и голое «важнее — значит забираю» этой цены не видит вовсе.
/// Лечится это <see cref="SettleSeconds"/>: см. разбор там.
///
/// И ВТОРАЯ ПОЛОВИНА ТОЙ ЖЕ БЕДЫ — ЩЕЛЬ МЕЖДУ ЗАХОДАМИ. Перебитая работа тело
/// отдаёт и просит заново (<see cref="Resume"/>), и в этот промежуток оно
/// формально НИЧЬЁ. В живом журнале в эту щель дважды влезало хозяйственное
/// дело — сборы и подбор своей добычи, — а вернувшаяся дорога отбирала тело
/// обратно: ещё один разворот на месте. Поэтому «свободно» и «ничьё» здесь
/// разведены: <see cref="ReserveLeft"/>, та же ручка и те же секунды.
///
/// В ЭТУ ЖЕ ЩЕЛЬ ОДНАЖДЫ ПРОВАЛИЛОСЬ СПАСЕНИЕ, И ЭТО БЫЛО ХУЖЕ ВСЕГО.
/// <see cref="MakeWay"/> тело только ОСВОБОЖДАЛА, а не ОТДАВАЛА рефлексу, ради
/// которого чистили, — и перебитая работа успевала забрать его назад ПЕРВОЙ:
/// возврат ждёт секунду, а ход рефлекса приходит через 1,2 с. Со второй
/// секунды у работы была уже СВЕЖАЯ ВЫДЕРЖКА против того самого боя, для
/// которого дорогу и расчищали, — то есть выдержка ЗАДЕРЖИВАЛА СПАСЕНИЕ. Кому
/// достанется тело, решала гонка «кто первый успел», и это неверно само по
/// себе. Теперь расчищенное тело ДЕРЖИТСЯ ЗА ТЕМ, РАДИ КОГО ЧИСТИЛИ
/// (<see cref="Claim"/>, поле cleared), тем же правилом и той же ручкой.
///
/// И ДЕРЖИТСЯ ОНО РОВНО ДО ЕГО ХОДА, А НЕ ПЯТЬ СЕКУНД (<see cref="WayDone"/>).
/// Эта половина стоила отдельной починки: застава пережидала и бой, и «не
/// связываюсь», и отсутствие врага — то есть все случаи, когда спасение за
/// телом так и не пришло, — и всё это время отказывала карьеру, дороге,
/// разделке и приказу человека из чата. Избитый бот замирал.
/// </summary>
public sealed class BodyArbiter
{
    /// <summary>Насколько важно занятие. Больше — важнее.</summary>
    public enum Importance
    {
        /// <summary>Фоновое дело роли: торговля, обход грядок, стройка.</summary>
        Routine = 0,

        /// <summary>Приказ из чата: человек ждёт ответа.</summary>
        Command = 10,

        /// <summary>
        /// СРОЧНОЕ ДЕЛО РОЛИ: то, чей ПРЕДМЕТ ИСЧЕЗНЕТ САМ, пока бот занят
        /// другим. Не спасение — камень, руда и грядка подождут сколько угодно,
        /// а вот туша нет.
        ///
        /// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО СТУПЕНЬ ЗАВЕДЕНА. Заказчик 28.08:
        /// «трупы остаются с вещами и не исчезают». Разделка брала тело как
        /// <see cref="Routine"/>, карьер — как <see cref="Command"/>; равный не
        /// перебивает, меньший тем более, и пока карьер копал свои семьсот
        /// клеток, разделка ЖДАЛА. Туша дрифтера живёт три игровых часа
        /// (deaddecay, hoursToDecay: 3 в lore/drifter.json) — при обычной
        /// скорости времени это шесть реальных минут, — и пропадает ВМЕСТЕ с
        /// добычей: на землю из неё не выпадает ничего.
        ///
        /// ПОЧЕМУ ОТДЕЛЬНАЯ СТУПЕНЬ, А НЕ <see cref="Reflex"/>. Взять тело
        /// рефлексом было бы проще всего, и это ровно то, чем нельзя платить:
        /// рефлекс рефлекса не перебивает, а значит бой, побег и укрытие
        /// получили бы над тушей ЧЕСТНЫЙ ОТКАЗ — бот дорезал бы шкуру, пока
        /// его бьют. Ниже рефлекса стоять обязано ВСЁ, что не спасает жизнь.
        ///
        /// ПОЧЕМУ НЕ ПРОСТО ПОДНЯТЬ РАЗДЕЛКУ ДО <see cref="Command"/>. Равный
        /// не перебивает: карьер, начатый командой из чата, так и держал бы
        /// тело. А главное — <see cref="Preemption"/> прочитал бы такой
        /// перехват как СМЕНУ ЦЕЛИ, и прерванный карьер не вернулся бы никогда
        /// (та самая яма «скопал часть сверху и не стал углубляться»).
        /// </summary>
        Urgent = 15,

        /// <summary>Выживание: бой, побег, укрытие в бурю.</summary>
        Reflex = 20,

        /// <summary>
        /// ЖИЗНЬ: поесть, полечиться, выбраться из воды и лавы. ВЫШЕ ВСЕГО, и
        /// вот почему это отдельная ступень, а не тот же <see cref="Reflex"/>.
        ///
        /// Равный равного не перебивает — это правило спасает от толкотни, но
        /// оно же убивало бота. Живой случай (журнал карьера, минута подряд):
        /// «Потеряно 0,13 хп от hunger» каждые шесть секунд, хлеб в кармане, а
        /// тело держит долгая работа. И тот же капкан со второй стороны: бой и
        /// укрытие в бурю берут тело как Reflex, замуровываются на пять минут —
        /// и голодный рефлекс, тоже Reflex, получает от них честный отказ.
        ///
        /// Живой игрок в такой миг бросает кирку и жуёт, даже если рядом
        /// дрифтер. Поэтому ступень отдельная: голод, лечение и спасение из
        /// воды перебивают ВСЁ, включая другие рефлексы. Смерть от голода при
        /// наличии еды недопустима ни при какой настройке.
        /// </summary>
        Vital = 30
    }

    /// <summary>
    /// Чем кончилось владение телом — и, главное, СТОИТ ЛИ ВЕРНУТЬСЯ К ДЕЛУ.
    ///
    /// Живой случай (журнал 21:37-21:39). Заказчик дал «!карьер 7 15» — 720
    /// клеток. Через полторы минуты рядом упала еда, рефлекс забрал тело:
    /// «поднять еду» важнее — прерываю «команда карьер». Карьер честно встал на
    /// 67-й клетке и УМЕР НАВСЕГДА. Человек увидел это так: «дал задачу карьера,
    /// а он скопал только часть сверху и не стал углубляться по заданию».
    ///
    /// Прерывание было правильным (голодный бот важнее ямы), неправильным было
    /// беспамятство: никто не помнил, ЧТО прервали. А отличать причины обрыва
    /// было НЕЧЕМ — и «спасаюсь», и «человек сказал стоп», и «бот умер»
    /// одинаково ставили один флаг Interrupted. Вернуться после первого —
    /// правильно; после двух других — значит не слушаться человека и работать
    /// мёртвым. Отсюда три разных конца вместо одного «прервали».
    /// </summary>
    public enum Ending
    {
        /// <summary>Дело идёт или закончилось само.</summary>
        None = 0,

        /// <summary>
        /// Тело забрал РЕФЛЕКС ВЫЖИВАНИЯ: поесть, отбиться, спастись. Цель не
        /// менялась, помеха временная — работу надо доделать.
        /// </summary>
        Preempted,

        /// <summary>
        /// Тело забрала не спасающая, а обычная задача: человек дал новый
        /// приказ. ЦЕЛЬ СМЕНИЛАСЬ — к старой возвращаться нельзя, иначе бот
        /// после «!иди домой» молча уйдёт обратно в карьер.
        /// </summary>
        Retargeted,

        /// <summary>
        /// Дело оборвали насмерть: «стоп» от человека, смерть, выход из мира.
        /// Возврат тут — прямое неподчинение.
        /// </summary>
        Halted
    }

    /// <summary>
    /// Как читать перехват тела: временная помеха это или новая цель.
    ///
    /// ЧИСТОЕ ПРАВИЛО, и вся политика возврата стоит на нём. Мерка одна:
    /// НОВУЮ ЦЕЛЬ БОТУ СТАВИТ ТОЛЬКО ЧЕЛОВЕК. Приказ из чата
    /// (<see cref="Importance.Command"/>) и всё, что ниже, — это «займись
    /// другим», к старому возвращаться нельзя. Всё, что выше приказа, тело
    /// ЗАНИМАЕТ НЕНАДОЛГО и отдаёт само: рефлекс спасает, дело жизни кормит и
    /// лечит, срочное дело роли (<see cref="Importance.Urgent"/>) успевает
    /// к тому, что вот-вот пропадёт. Цель при этом не менялась ни разу.
    ///
    /// МЕРКА ЗДЕСЬ СТОЯЛА КАК «рефлекс и выше», и до появления
    /// <see cref="Importance.Urgent"/> это было ТО ЖЕ САМОЕ число: между
    /// приказом и рефлексом не было ничего. Разъехались они ровно тогда, когда
    /// между ними встала разделка, — и «выше приказа» оказалось настоящим
    /// именем правила, а «рефлекс и выше» лишь совпадением. Опустить порог до
    /// приказа включительно нельзя: тогда «!иди домой» посреди карьера читался
    /// бы как временная помеха, и бот молча ушёл бы копать обратно.
    /// </summary>
    public static Ending Preemption(Importance by) =>
        by > Importance.Command ? Ending.Preempted : Ending.Retargeted;

    private readonly object gate = new();
    private Hold? current;
    private long era;

    /// <summary>
    /// СЧЁТ СМЕН ХОЗЯИНА ТЕЛА: сколько раз с начала жизни бота менялся ответ на
    /// вопрос «кто распоряжается телом». Число само по себе ничего не значит —
    /// значит только то, ОСТАЛОСЬ ЛИ ОНО ПРЕЖНИМ.
    ///
    /// ЗАЧЕМ ЗАВЕДЕНО, И ЭТО ЖИВАЯ ЖАЛОБА 01.09: «бежит и иногда крутится,
    /// смотрится неестественно». В журнале это три похода, дерущихся за ходьбу
    /// одновременно:
    ///   23:06:27 за тело дерутся двое: «дорога до (62,112,254)» и «дорога до (-11,114,261)»
    ///   23:06:46 за тело дерутся двое: «дорога до (-11,114,261)» и «дорога до (62,112,254)»
    ///   23:06:54 за тело дерутся двое: «дорога до (-7390,39,1978)» и «дорога до (62,112,254)»
    /// Каждый строил маршрут в свою сторону, ходьба доставалась то одному, то
    /// другому — и бот на каждой смене разворачивался на месте.
    ///
    /// ПРИЧИНА БЫЛА В УСТРОЙСТВЕ, А НЕ В ЧИСЛАХ: РАСПОРЯДИТЕЛЕЙ БЫЛО ДВА.
    /// Здешний решал, кто держит ТЕЛО; а у движения была СВОЯ собственность на
    /// ХОДЬБУ (<c>Movement.TakeBody</c>) со своим счётом перехватов, и про
    /// здешнего она не знала ничего. Поход, начатый под владением, продолжал
    /// шагать и ПОСЛЕ того, как владение у него отняли: живьём это «!иди»,
    /// который берёт тело командой, а дорогу зовёт без токена владения, —
    /// перебитый рефлексом, он терял тело и всё равно топал свои пять минут.
    ///
    /// СВЕДЕНО В ОДНО ЭТИМ ЧИСЛОМ. Ходьба больше не решает, чья она: поход
    /// действителен, пока цело то владение, при котором он затеян, — а «цело»
    /// и значит «число не изменилось». Читает его единственная дверь во всю
    /// ходьбу (<c>Movement.WithSelfRestartAsync</c>), второго списка «кто кого
    /// перебивает» у движения больше нет.
    ///
    /// МЕНЯЕТСЯ ОНО РОВНО ТОГДА, КОГДА МЕНЯЕТСЯ ХОЗЯИН: тело взяли, отпустили,
    /// перебили, расчистили под спасение, — и ещё на <see cref="Interrupt"/>,
    /// даже если тело было свободно. Последнее не мелочь: «стоп», смерть и
    /// выход из мира отменяют ВСЁ ЗАДУМАННОЕ, и ходьба, которую никто не брал
    /// во владение, тоже задумана до них.
    /// </summary>
    public long Era
    {
        get { lock (gate) { Living(); return era; } }
    }

    /// <summary>
    /// СМЕНИТЬ ХОЗЯИНА ТЕЛА — единственное место, где это поле пишется, чтобы
    /// счёт смен (<see cref="Era"/>) нельзя было обойти мимо. Вызывать только
    /// под gate.
    /// </summary>
    private void Own(Hold? who)
    {
        if (ReferenceEquals(current, who))
            return;
        current = who;
        era++;
    }

    /// <summary>
    /// Живой хозяин тела. ВЛАДЕНИЕ С ПОГАШЕННЫМ ТОКЕНОМ ЗДЕСЬ НЕ СЧИТАЕТСЯ.
    ///
    /// Живой случай (журнал 23:50:37-23:51:05): рефлекс бегства забирал тело у
    /// дальней дороги, через полсекунды отпускал, а перебитый поход ещё
    /// доигрывал свой круг — ждал ответа сервера, досчитывал маршрут — и всё
    /// это время формально ДЕРЖАЛ владение. Роль пробовала пойти снова и
    /// получала «занято» от дела, которое само уже кончилось. Со стороны это
    /// ровно то, на что жаловался заказчик: бот не идёт и не дерётся.
    ///
    /// Считать хозяином только «перебитого» мало. Владение гаснет и СНАРУЖИ:
    /// роль перезапускает свой наряд, команда из чата отменяется, бот выходит
    /// из мира — токен вызывающего погас, а Interrupted у владения так и
    /// осталось false. Такой мертвец не отпустит тело никогда (Dispose зовёт
    /// тот, кого уже отменили), и все следующие «взять тело» получают отказ от
    /// призрака. Поэтому мерка одна: жив тот, у кого токен ещё горит.
    ///
    /// Вызывать только под gate.
    /// </summary>
    private Hold? Living()
    {
        if (current is { Alive: false })
            Own(null);
        return current;
    }

    /// <summary>Чем бот занят (пусто — ничем).</summary>
    public string Busy
    {
        get { lock (gate) return Living()?.Owner ?? ""; }
    }

    /// <summary>
    /// Живое владение телом целиком, а не только его имя (null — тело свободно).
    ///
    /// Зачем наружу. Долгая работа обычно идёт ПОД чужим владением: команда из
    /// чата взяла тело как «команда карьер», а копает потом карьер, у которого
    /// на руках только токен отмены. Когда токен гаснет, по нему не понять,
    /// что случилось: спас ли бота рефлекс, сказал ли человек «стоп», умер ли
    /// бот. Спросить об этом можно только у самого владения — отсюда и доступ.
    /// Брать тело этим НЕЛЬЗЯ: для этого есть TryTake.
    /// </summary>
    public Hold? Current
    {
        get { lock (gate) return Living(); }
    }

    /// <summary>Насколько важно нынешнее занятие.</summary>
    public Importance? BusyWith
    {
        get { lock (gate) return Living()?.Level; }
    }

    public event Action<string>? OnLog;

    /// <summary>
    /// ВЫДЕРЖКА НАЧАТОГО ДЕЛА: сколько секунд у хозяина тела есть ПРЕИМУЩЕСТВО
    /// перед тем, кто просто важнее. Ноль — как было, перехват в ту же секунду.
    ///
    /// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЗАВЕДЕНА (журнал 30.08, 23:37:03-23:37:17):
    ///   «поднять еду» важнее — прерываю «дорога»
    ///   «поесть redmeat-cooked» важнее — прерываю «дорога»
    ///   «дорога» важнее — прерываю «своя добыча»
    ///   «разгрузка» важнее — прерываю «дорога»
    ///   «поесть redmeat-cooked» важнее — прерываю «разгрузка»
    ///   «разгрузка» важнее — прерываю «дорога»
    /// Шесть смен хозяина за четырнадцать секунд, и работы за это время —
    /// «дорога 0 рядов из 21, выкопано 8 кл. выемки; 107 с». Заказчик увидел
    /// это как «бегал вперед назад с резкими разворотами как сумасшедший».
    ///
    /// ЭТО ИЗВЕСТНАЯ БЕДА ПОЛЕЗНОСТНЫХ СИСТЕМ — ДРОЖЬ ВЫБОРА, и лечится она
    /// гистерезисом: у того, кто уже работает, есть фора, и претендент обязан
    /// либо быть заметно важнее, либо дождаться окна. Окно здесь — это и есть
    /// выдержка: она открывается, как только дело проработало свои секунды.
    ///
    /// ПОЧЕМУ ВЫДЕРЖКА ВРЕМЕНЕМ, А НЕ «БЫТЬ НА ДВЕ СТУПЕНИ ВЫШЕ». Ступени у нас
    /// дискретные (0, 10, 15, 20, 30), «чуть выше» между ними не бывает вовсе, и
    /// мерить фору ими значило бы сказать «бой не перебьёт дорогу, потому что он
    /// всего на две ступени выше». Цена смены хозяина измеряется не ступенями, а
    /// разворотом и маршем — то есть СЕКУНДАМИ, и фора меряется тем же.
    ///
    /// ЗДЕСЬ НОЛЬ, И ЭТО НЕ ЗАБЫТОЕ ЧИСЛО, А ГРАНИЦА МЕХАНИЗМА И ПОЛИТИКИ.
    /// Сколько секунд стоит смена хозяина ИМЕННО У ЭТОГО бота — решает роль, и
    /// решает вслух: <c>LivingRole.ВыдержкаНачатогоДелаСекунд</c>, пять секунд
    /// по умолчанию и в каждом пресете. Число там взято из тех же шести строк
    /// журнала: перехваты шли в среднем раз в 2,3 с, а самый долгий промежуток
    /// между ними — пять секунд (23:37:12 → 23:37:17); выдержка короче пяти не
    /// поймала бы и этой пары, то есть не поймала бы ничего.
    ///
    /// ОДНО ЧИСЛО НА ДВЕ ПОЛОВИНЫ. Эти же секунды держат тело за перебитым
    /// делом, пока оно возвращается (<see cref="ReserveLeft"/>): это не вторая
    /// ручка, а тот же самый ответ на тот же вопрос — сколько времени начатая
    /// работа считается хозяйкой тела. Заведи мы вторую, они разошлись бы в
    /// первый же день, и человек не знал бы, какую крутить.
    /// </summary>
    public double SettleSeconds { get; set; }

    /// <summary>
    /// Имя ручки выдержки ЧЕЛОВЕЧЕСКИМИ словами — уходит прямо в отказ. Без
    /// него человек читает «подожди 4 с» и не знает, где это убавить.
    /// </summary>
    public string SettleKnob { get; set; } = nameof(SettleSeconds);

    /// <summary>
    /// СКОЛЬКО ЕЩЁ СЕКУНД ПРЕТЕНДЕНТУ ЖДАТЬ. Чистое правило: всё, что оно
    /// спрашивает у мира, подано сюда числами. 0 — брать можно сейчас.
    ///
    /// ЖИЗНЬ НЕ ЖДЁТ НИКОГДА, И ЭТО ПЕРВОЕ ПРАВИЛО ЗДЕСЬ. Цена ошибки в другую
    /// сторону — труп: вылечить дрожь и получить мёртвого бота хуже, чем не
    /// лечить. <see cref="Importance.Vital"/> — это огонь и вода
    /// (<c>BehaviorLeaveHarm</c>), голод и лечение (<see cref="TakeForLife"/>);
    /// они режут в ту же секунду при любой выдержке. Смерть, «стоп» от человека
    /// и выход из мира сюда не приходят вовсе — они идут через
    /// <see cref="Interrupt"/>, и эта дверь выдержки не знает.
    ///
    /// СПАСЕНИЕ НЕ ЖДЁТ ВОВСЕ, И ХОДИТ ОНО ЗДЕСЬ НЕ ЧЕРЕЗ ЭТО ПРАВИЛО. У него
    /// своя дверь — <see cref="TakeForRescue"/>, а под ней <see cref="MakeWay"/>:
    /// она расчищает тело и держит его за тем, ради кого чистили. Ею ходят все
    /// четверо — бой (<c>WakeForFight</c> зовёт расчистку на каждом ударе не
    /// слабее <c>MinHurtToFight</c>), укрытие в бурю, уход от нестабильности и
    /// грение.
    ///
    /// ЗДЕСЬ СТОЯЛО, ЧТО ВЫДЕРЖКУ ПЛАТИТ «ровно один случай: бой, который бот
    /// затевает сам». ЭТО БЫЛО НЕПРАВДОЙ, и приёмка доказала это стендом:
    /// двери <see cref="MakeWay"/> у трёх спасений не было вовсе, и все три
    /// получали от начатой секунду назад дороги честный отказ — «укрытие в
    /// бурю», «уйти от нестабильности» и «греться» уходили молчать до
    /// следующего тика, пока бот мёрз, тонул в нестабильности и стоял под
    /// бурей. Дверь им заведена, а строка эта переписана: врать про то, кто
    /// платит выдержку, опаснее, чем брать её лишний раз.
    ///
    /// ПЛАТИТ ЕЁ, ЗНАЧИТ, ТОТ, КТО ТЕЛО ПРОСТО ХОЧЕТ, А НЕ СПАСАЕТ: рейс на
    /// склад («разгрузка»), подбор упавшей еды, разделка туши — все они той же
    /// ступени <see cref="Importance.Reflex"/> или ниже, и ради них выдержка и
    /// заведена. Платит и бой, который бот ЗАТЕВАЕТ САМ, ещё не будучи битым:
    /// такой бот может пропустить первый удар — и он же тут же расчистит себе
    /// дорогу. Живой игрок, заметив дрифтера за двадцать блоков, тоже сперва
    /// дорубает свой удар киркой. Царапина (<c>FightEntry.Scratch</c>) дороги
    /// не расчищает и раньше — это не наша перемена.
    ///
    /// ФОНОВОМУ ДЕЛУ ФОРЫ НЕТ. <see cref="Importance.Routine"/> — это подбор
    /// своей добычи, прогулка, «снарядиться»: рвутся без потерь и возвращаются
    /// своим же тиком через секунду. Дай им фору — и приказ человека («дорога»,
    /// «карьер») получал бы отказ ради прогулки, а начало работы в этом проекте
    /// спрашивает тело ОДИН раз, без ожидания (<c>Resume.RunAsync</c>, первый
    /// заход). Выдержка защищает начатую РАБОТУ от дрожи, а не любое занятие от
    /// любого претендента.
    ///
    /// ПЛАТЯТ, ЗНАЧИТ, ВСЕ, КРОМЕ ЖИЗНИ, — и разгрузка тоже, ради неё всё и
    /// затевалось: в живом журнале рейс на склад дважды за четырнадцать секунд
    /// отобрал тело у дороги, начатой секунду назад.
    /// </summary>
    /// <param name="claimant">важность претендента</param>
    /// <param name="holder">важность нынешнего хозяина тела</param>
    /// <param name="heldSeconds">сколько секунд хозяин уже держит тело</param>
    /// <param name="settleSeconds">выдержка (<see cref="SettleSeconds"/>)</param>
    public static double SettleLeft(Importance claimant, Importance holder,
        double heldSeconds, double settleSeconds)
    {
        if (settleSeconds <= 0)
            return 0;
        // Жизнь не ждёт — см. разбор выше
        if (claimant >= Importance.Vital)
            return 0;
        // Фоновому делу форы нет
        if (holder <= Importance.Routine)
            return 0;
        // Претендент и так не сильнее: ему откажут по важности, и выдержке тут
        // сказать нечего. Считать её здесь значило бы объявить причиной отказа
        // выдержку там, где дело в самой важности, — и человек крутил бы не ту
        // ручку
        if (claimant <= holder)
            return 0;
        double left = settleSeconds - heldSeconds;
        return left > 0 ? left : 0;
    }

    /// <summary>
    /// СКОЛЬКО ЕЩЁ СЕКУНД ТЕЛО ДЕРЖИТСЯ ЗА ТЕМ, КТО ЕГО СЕЙЧАС НЕ ДЕРЖИТ.
    /// Чистое правило: всё подано числами. 0 — тело ничьё.
    ///
    /// СУДИТ ОНО ОБА ПРОМЕЖУТКА, И ЭТО ОДИН И ТОТ ЖЕ ВОПРОС (см.
    /// <see cref="Claim"/>): тело держится либо за ПЕРЕБИТЫМ ДЕЛОМ, которое
    /// возвращается, либо за СПАСЕНИЕМ, ради которого его расчистили
    /// (<see cref="MakeWay"/>) и которое возьмёт его ближайшим ходом. Меняется
    /// только то, чья важность подана в <paramref name="reserved"/>; правило,
    /// секунды и ручка — одни.
    ///
    /// ЭТО ВТОРАЯ ПОЛОВИНА ОДНОЙ И ТОЙ ЖЕ ВЫДЕРЖКИ, А НЕ ВТОРОЙ МЕХАНИЗМ, и
    /// сказано это нарочно. <see cref="SettleLeft"/> держит тело за делом, ПОКА
    /// оно работает; здесь — те же секунды и та же ручка, но в промежутке между
    /// заходами, когда дело тело уже отдало, а вернуться ещё не успело
    /// (<see cref="Resume"/> ждёт <c>PauseSeconds</c>, потом просит тело
    /// заново). Ноль в ручке гасит обе половины разом.
    ///
    /// ЗАЧЕМ ВООБЩЕ ЩЕЛЬ ЗАКРЫВАТЬ. Живой журнал 30.08, дословно:
    ///   23:36:17 [снаряжение] не хватает: ladder: 24/64 …
    ///   23:36:18 возвращаюсь на дорогу … (заход 3)
    ///   23:37:09 «дорога» важнее — прерываю «своя добыча»
    /// Между заходами дороги тело было НИЧЬЁ, и в эту щель дважды влезло
    /// хозяйственное дело: сборы («снарядиться» — оно же за десять минут до
    /// того накрафтило те самые 24 лестницы) и подбор своей добычи. Дорога,
    /// вернувшись, отбирала тело обратно — вот и лишний разворот на месте,
    /// которого никто не заказывал. «Тело свободно» и «делать нечего» — разные
    /// вещи, и путать их нельзя.
    ///
    /// РАВНЫЙ И БОЛЕЕ ВАЖНЫЙ БЕРУТ СРАЗУ, И ЭТО ГЛАВНОЕ ПРАВИЛО ЗДЕСЬ. Бронь
    /// отказывает только тем, кто НИЖЕ перебитого: рефлекс, дело жизни и
    /// срочное дело роли выше приказа по построению, а новый приказ человека
    /// («!иди домой» посреди дороги) равен ему — и слушаться человека бот
    /// обязан немедленно. Цена ошибки в другую сторону — труп и неподчинение.
    /// </summary>
    /// <param name="claimant">важность претендента</param>
    /// <param name="reserved">
    /// важность того, за кем держится тело: перебитого дела, которое
    /// возвращается, или спасения, ради которого тело расчистили
    /// </param>
    /// <param name="sinceSeconds">
    /// сколько секунд тело держится за ним: с мига, как оно освободилось, или
    /// с мига расчистки
    /// </param>
    /// <param name="settleSeconds">выдержка (<see cref="SettleSeconds"/>)</param>
    public static double ReserveLeft(Importance claimant, Importance reserved,
        double sinceSeconds, double settleSeconds)
    {
        if (settleSeconds <= 0)
            return 0;
        // Равный и более важный — сразу: см. разбор выше
        if (claimant >= reserved)
            return 0;
        double left = settleSeconds - sinceSeconds;
        return left > 0 ? left : 0;
    }

    /// <summary>
    /// ЗА КЕМ ДЕРЖИТСЯ ТЕЛО, ПОКА ЕГО НИКТО НЕ ДЕРЖИТ. Одна запись на оба
    /// случая нарочно: вопрос у них один — чьё тело в этот промежуток, — и
    /// правило одно (<see cref="ReserveLeft"/>), и ручка одна
    /// (<see cref="SettleSeconds"/>).
    ///
    /// Случая ровно два, и они зеркальны:
    ///   • ПЕРЕБИТОЕ ДЕЛО (<see cref="reserved"/>) — тело уже отдало и сейчас
    ///     вернётся за ним (<see cref="Resume"/> ждёт паузу и просит заново);
    ///   • СПАСЕНИЕ, РАДИ КОТОРОГО ТЕЛО РАСЧИСТИЛИ (<see cref="cleared"/>) — оно
    ///     тело ещё не взяло и возьмёт своим ближайшим ходом.
    /// Заведи мы им два разных правила, они разошлись бы в первый же день.
    /// </summary>
    /// <param name="What">чьё: имя перебитого дела или повод расчистки</param>
    /// <param name="Level">насколько оно важно</param>
    /// <param name="Since">с какого мига идёт счёт</param>
    private sealed record Claim(string What, Importance Level, DateTime Since);

    /// <summary>За кем держится тело между заходами (null — ни за кем).</summary>
    private Claim? reserved;

    /// <summary>
    /// ПОД КАКОЕ СПАСЕНИЕ РАСЧИЩЕНО ТЕЛО (null — ни под какое).
    ///
    /// ЖИВАЯ БЕДА, РАДИ КОТОРОЙ ЗАВЕДЕНО, — та самая, что описана у класса.
    /// <see cref="MakeWay"/> тело ОСВОБОЖДАЛА и на этом кончалась, а дальше шла
    /// гонка: возврат перебитой работы ждёт секунду (<c>Resume.PauseSeconds</c>)
    /// и просит тело, а ход рефлекса приходит через 1,2 с — цикл способностей
    /// тикает раз в 400 мс и ЖДЁТ каждую. Работа успевала первой, и с этого
    /// мига у неё была СВЕЖАЯ ВЫДЕРЖКА против того самого боя, ради которого
    /// дорогу и расчистили. Стенд приёмки напечатал это дословно: «дорога
    /// вернулась: True» → «бой взял тело: False; занято: дорога».
    ///
    /// Поэтому расчистка теперь не только освобождает, но и ДЕРЖИТ: пока
    /// спасение не пришло за телом, тело не достаётся никому ниже его — ни
    /// вернувшейся работе, ни хозяйству, ни новому приказу из чата. Выше —
    /// достаётся: жизнь (еда, лечение, выход из огня и воды) не ждёт никогда и
    /// ни за чем.
    ///
    /// А ЖИВЁТ ОНА РОВНО ДО ХОДА СПАСЕНИЯ (<see cref="WayDone"/>), а не свои
    /// пять секунд, и это вторая правка приёмки — за первую же и заплаченная.
    /// «Держит, пока спасение не пришло» кончалось только приходом; не пришло —
    /// и застава стояла всю выдержку, отказывая карьеру, дороге, разделке и
    /// приказу человека. Замер: роль взяла тело 0 раз из 40. Полный разбор и
    /// живые числа — у <see cref="WayDone"/>.
    /// </summary>
    private Claim? cleared;

    /// <summary>
    /// ЗАПОМНИТЬ, ЧТО ПЕРЕБИТОЕ ДЕЛО ВЕРНЁТСЯ, и до его возвращения не отдавать
    /// тело тем, кто ниже. Зовётся из обоих мест, где дело перебивают ради
    /// более важного: и когда тело забирают (<see cref="TryTake"/>), и когда
    /// расчищают дорогу удару (<see cref="MakeWay"/>). Второго списка «кого
    /// ждать» нет: ждём ровно того, кого сами же и перебили.
    ///
    /// БРОНЬ СТАВИТСЯ ТОЛЬКО НА <see cref="Ending.Preempted"/> — то есть на то,
    /// что и вправду возвращается (<see cref="Preemption"/>). Новую цель от
    /// человека держать нечего: к старой работе бот не пойдёт вовсе.
    ///
    /// Вызывать только под gate.
    /// </summary>
    private void Reserve(Hold busy, Ending how)
    {
        if (how != Ending.Preempted)
        {
            Forget();
            return;
        }
        reserved = new Claim(busy.Owner, busy.Level, DateTime.UtcNow);
    }

    /// <summary>Брони больше нет. Вызывать только под gate.</summary>
    private void Forget() => reserved = null;

    /// <summary>
    /// Взять тело. Возвращает владение (его надо освободить) или null, если
    /// тело занято не менее важным делом, у занятого ещё не вышла выдержка
    /// (<see cref="SettleSeconds"/>) ИЛИ тело держится за перебитым делом,
    /// которое сейчас вернётся (<see cref="ReserveLeft"/>).
    ///
    /// <paramref name="ct"/> — отмена вызывающего; она связывается с отменой
    /// владения, поэтому внутри задачи достаточно следить за одним токеном.
    /// </summary>
    public Hold? TryTake(string owner, Importance level, CancellationToken ct = default)
    {
        lock (gate)
        {
            // ОТМЕНЁННЫЙ ВЫЗЫВАЮЩИЙ ТЕЛУ НЕ ХОЗЯИН. Иначе выходит вот что: он
            // берёт владение, по дороге перебивает живое дело — и тут же
            // умирает сам, потому что его токен погас ещё до захода. Тело
            // остаётся ничьим, а прерванный поход уже не вернуть
            if (ct.IsCancellationRequested)
            {
                Refused(level, $"«{owner}» не берёт тело: его самого уже отменили");
                return null;
            }

            if (Living() is { } busy)
            {
                if (level <= busy.Level)
                {
                    Refused(level, $"«{owner}» не берёт тело: занято «{busy.Owner}»");
                    return null;
                }
                // ВЫДЕРЖКА НАЧАТОГО ДЕЛА. Стояло голое «важнее — значит забираю»,
                // и дело, начатое полторы секунды назад, отбиралось мгновенно;
                // разбор живого случая — у SettleSeconds. Настоящая беда сюда
                // не попадает вовсе (правило SettleLeft)
                double wait = SettleLeft(level, busy.Level, busy.HeldSeconds, SettleSeconds);
                if (wait > 0)
                {
                    Refused(level,
                        $"«{owner}» не берёт тело: «{busy.Owner}» взялось " +
                        $"{busy.HeldSeconds:0.#} с назад, даю ему доработать ещё {wait:0.#} с " +
                        $"(ручка «{SettleKnob}») — иначе бот только разворачивается на месте",
                        // Повод устойчив, а секунды в строке убывают на каждой
                        // попытке — см. разбор у Refused
                        $"выдержка|{owner}|{busy.Owner}");
                    return null;
                }
                OnLog?.Invoke($"«{owner}» важнее — прерываю «{busy.Owner}»");
                // ЗАПОМИНАЕМ, КТО ПЕРЕБИЛ, а не только то, что перебили: по
                // одному лишь флагу «прервали» перебитый не отличит рефлекс,
                // который вернёт тело через минуту, от нового приказа человека
                var how = Preemption(level);
                busy.Interrupt(how, owner);
                // …и держим тело за перебитым, пока он возвращается
                Reserve(busy, how);
            }
            else
            {
                // РАСЧИЩЕННОЕ ТЕЛО ДОСТАЁТСЯ ТОМУ, РАДИ КОГО ЧИСТИЛИ, — и эта
                // ветка стоит ПЕРЕД бронью нарочно. Именно здесь и была та
                // беда: перебитая работа возвращалась первой и встречала
                // спасение свежей выдержкой. Разбор — у поля cleared
                if (cleared is { } way)
                {
                    double чисто = ReserveLeft(level, way.Level,
                        (DateTime.UtcNow - way.Since).TotalSeconds, SettleSeconds);
                    if (чисто > 0)
                    {
                        Refused(level,
                            $"«{owner}» не берёт тело: его расчистили под «{way.What}» " +
                            $"и держат за спасением ещё {чисто:0.#} с (ручка «{SettleKnob}»)",
                            // Повод устойчив, секунды в строке убывают — см. Refused
                            $"расчистка|{owner}");
                        return null;
                    }
                    // Либо это оно и есть (не ниже расчистки — спасение или
                    // жизнь), либо спасение так и не пришло за отпущенный срок.
                    // В обоих случаях расчистка отработала: держать тело дальше
                    // значило бы морозить бота ради того, кто не пришёл
                    cleared = null;
                }

                // ТЕЛО СВОБОДНО, НО НЕ НИЧЬЁ: между заходами оно держится за
                // перебитым делом. Разбор живого случая — у ReserveLeft
                if (reserved is { } back && owner != back.What)
                {
                    double держим = ReserveLeft(level, back.Level,
                        (DateTime.UtcNow - back.Since).TotalSeconds, SettleSeconds);
                    if (держим > 0)
                    {
                        Refused(level,
                            $"«{owner}» не берёт тело: его ещё {держим:0.#} с держит за собой " +
                            $"перебитое «{back.What}» — оно возвращается " +
                            $"(ручка «{SettleKnob}»)",
                            // Повод устойчив, секунды в строке убывают — см. Refused
                            $"бронь|{owner}|{back.What}");
                        return null;
                    }
                    // БРОНЬ СНИМАЕТ ТОЛЬКО ВЫШЕДШИЙ СРОК, А НЕ ПРОШЕДШИЙ МИМО.
                    //
                    // Здесь стояло голое «Forget()» на всякий ноль, и это была
                    // тихая дыра. Ноль ReserveLeft отдаёт ДВУМЯ разными
                    // способами: и когда срок брони вышел, и когда претендент
                    // просто ВАЖНЕЕ перебитого. Во втором случае бронь стиралась
                    // первым же рефлексом, взявшим тело поверх неё, — а рефлекс
                    // держит тело минутами (рейс на склад — это минуты ходьбы),
                    // и щель ПОСЛЕ него открывалась настежь. То есть ровно та
                    // щель, ради которой бронь и заведена. Строкой ниже это уже
                    // было сказано словами («чужой её не снимает нарочно»), а
                    // делалось наоборот; поймано стендом расчистки, где бой
                    // проходит мимо брони по дороге к телу
                    if ((DateTime.UtcNow - back.Since).TotalSeconds >= SettleSeconds)
                        Forget();
                }
            }
            // ЗАБРОНИРОВАВШИЙ ВЕРНУЛСЯ — бронь отработала и снимается. Чужой её
            // не снимает нарочно: рефлекс, взявший тело поверх брони, отпустит
            // его через минуту, и щель откроется снова — а ждут в ней всё того
            // же перебитого
            if (reserved is { } mine && owner == mine.What)
                Forget();
            var hold = new Hold(this, owner, level, ct);
            Own(hold);
            return hold;
        }
    }

    /// <summary>
    /// Прервать нынешнее дело, кто бы им ни занимался.
    ///
    /// Зачем это нужно отдельно от «взять тело». Смерть не заинтересована в
    /// теле — ей нечего с ним делать, — но и позволить прежнему делу тянуться
    /// нельзя: мёртвому сервер отказывает во всём, и команда, начатая при
    /// жизни, продолжала крутиться вхолостую, держа тело за собой. В окне
    /// управления это выглядело как «занят: команда добудь» навсегда, а в
    /// игре — как залипший бот.
    ///
    /// Возвращает имя прерванного дела (пусто — бот и так был свободен).
    /// </summary>
    public string Interrupt(string why)
    {
        lock (gate)
        {
            // БРОНЬ СНИМАЕТСЯ ДАЖЕ У СВОБОДНОГО ТЕЛА, и это не мелочь: «стоп»
            // от человека приходит и МЕЖДУ заходами, когда работа тела не
            // держит вовсе, а вернуться собиралась. Стой это ниже, за проверкой
            // «есть ли хозяин», — и бот после «стоп» ещё несколько секунд молча
            // отказывал бы живым делам ради покойника (та же причина, по
            // которой у возврата есть собственный выключатель Resume.StopAll)
            Forget();
            // И РАСЧИСТКА СНИМАЕТСЯ ТОЖЕ, по той же причине. «Стоп», смерть и
            // выход из мира отменяют и спасение: мёртвый не дерётся и не
            // греется, а держать за ним расчищенное тело значит молча отказывать
            // живым делам ради покойника. Понадобится снова — новый удар
            // расчистит дорогу заново, ждать этого секунды
            cleared = null;
            // И СЧЁТ СМЕН ХОЗЯИНА ИДЁТ ДАЖЕ У СВОБОДНОГО ТЕЛА — по той же
            // причине, по какой снимаются бронь и расчистка, и это ЖИВАЯ ЖАЛОБА
            // 01.09: «погиб, возрождаюсь» в 23:05:33, сервер перебросил бота на
            // 385 блоков — а задуманное ДО смерти пережило переброс, и через
            // пятнадцать секунд бот строил маршрут в другой конец мира на семь
            // с половиной тысяч блоков. Ходьба, которую никто не брал во
            // владение, при пустом теле не заметила бы смерти вовсе: тут менять
            // было бы нечего. «Стоп», смерть и выход из мира отменяют ВСЁ
            // ЗАДУМАННОЕ, а не только то, что успело взять тело
            era++;
            if (Living() is not { } busy)
                return "";
            OnLog?.Invoke($"прерываю «{busy.Owner}»: {why}");
            // НАСМЕРТЬ. Сюда приходят «стоп» от человека, смерть и выход из
            // мира — то есть случаи, когда возвращаться к делу нельзя вовсе
            busy.Interrupt(Ending.Halted, why);
            // И ОТПУСКАЕМ ТЕЛО ТУТ ЖЕ, не дожидаясь, пока перебитый очнётся.
            // Иначе выходит наполовину: смерть прервала «команду добудь», а
            // окно управления до самого её конца показывает «занят: команда
            // добудь» — и возрождённому боту нечем взяться за дело. Опоздавший
            // Dispose ничего не сломает: он отпускает тело только если оно
            // всё ещё за ним (сверка по ссылке в Release)
            Own(null);
            return busy.Owner;
        }
    }

    /// <summary>
    /// РАСЧИСТИТЬ ДОРОГУ ТОМУ, КТО ВАЖНЕЕ, — НЕ ДОЖИДАЯСЬ ЕГО ХОДА.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ради которого этот вход заведён (журнал 19.08, одиннадцать
    /// секунд):
    ///   18:33:54 без дела — иду домой (61, 112, 257)
    ///   18:34:05 [чат:-5] Потеряно 2,5 хп дрифтер (моб)
    ///   … ещё пять таких же …
    ///   18:34:16 погиб, возрождаюсь
    /// Ни одной строки про бой. И вот почему: цикл способностей обходит их ПО
    /// ОЧЕРЕДИ и ЖДЁТ каждую (<c>await behavior.TickAsync</c>), а дорога домой
    /// уходит в один заход на двадцать секунд (<c>BehaviorIdle.HomeSeconds</c>).
    /// Все эти двадцать секунд бой не тикал ВООБЩЕ — то есть даже не спрашивал
    /// тела. Правило «рефлекс перебивает работу» было цело, спросить его было
    /// некому. Видно это и по журналу: шесть строк «меня ударили» напечатались
    /// разом в 18:34:26.848 — первым тиком боя за двадцать две секунды, уже
    /// после смерти и возрождения.
    ///
    /// Поэтому расчистка живёт ЗДЕСЬ, у распорядителя, и зовётся СОБЫТИЕМ (удар
    /// от сервера), а не ходом способности: тот, кто держит тело менее важным
    /// делом, обязан остановиться в ту же секунду, а не в свою очередь.
    ///
    /// Прерывание считается ПЕРЕХВАТОМ, а не смертью дела: рефлекс отпустит
    /// тело, и прерванное надо доделать (<see cref="Preemption"/>). Равного и
    /// более важного не трогаем — это то же правило, что и в
    /// <see cref="TryTake"/>, второго списка «кто кого» здесь нет.
    ///
    /// РАСЧИСТИТЬ — ЗНАЧИТ ОТДАТЬ, А НЕ ПРОСТО ОСВОБОДИТЬ, и это правка приёмки.
    /// Здесь стояло одно освобождение, и тело доставалось не тому, ради кого
    /// чистили, а тому, кто первым спросил: перебитая работа возвращается через
    /// секунду, а ход рефлекса приходит через 1,2 с. Полный разбор живого
    /// случая и стенда приёмки — у поля cleared.
    ///
    /// Возвращает имя прерванного дела (пусто — никого не тронули).
    /// </summary>
    public string MakeWay(Importance level, string why)
    {
        lock (gate)
        {
            // ТЕЛО С ЭТОЙ СЕКУНДЫ ДЕРЖИТСЯ ЗА ТЕМ, РАДИ КОГО ЕГО ЧИСТЯТ, — вот
            // главная строка всего входа, и стоит она ПЕРВОЙ, до всякого «а
            // есть ли кого прерывать».
            //
            // СТАВИМ ДАЖЕ ТОГДА, КОГДА ПЕРЕБИВАТЬ НЕКОГО, и это не небрежность.
            // Тело бывает свободно и в самый миг удара — перебитая работа как
            // раз идёт назад и возьмёт его через полсекунды; бывает и занято
            // равным или более важным делом — бот жуёт или уже дерётся. Чистить
            // в обоих случаях нечего, а спасение всё равно ждёт своего хода, и
            // тело обязано достаться ЕМУ, а не тому, кто просто успел первым.
            //
            // СРОК ЕЙ — НЕ СЕКУНДЫ, А ХОД СПАСЕНИЯ (WayDone): кончается она тем
            // ходом, ради которого её ставили, — взял он тело или не взял.
            // Секунды остались страховкой на случай, когда хода не будет вовсе
            cleared = new Claim(why.Length > 0 ? why : "спасение", level, DateTime.UtcNow);

            if (Living() is not { } busy || level <= busy.Level)
                return "";
            OnLog?.Invoke($"{why} — прерываю «{busy.Owner}», дальше не жду своей очереди");
            var how = Preemption(level);
            busy.Interrupt(how, why);
            // …и держим тело за перебитым, пока он возвращается: расчистка
            // отдаёт тело в ту же секунду, и без брони в эту щель влезло бы
            // хозяйственное дело (разбор — у ReserveLeft)
            Reserve(busy, how);
            // ТЕЛО ОТПУСКАЕМ СРАЗУ, как и при обрыве насмерть: перебитый ещё
            // доигрывает свой круг (ждёт ответа сервера, досчитывает маршрут), а
            // спасаться надо сейчас. Опоздавший Dispose ничего не сломает —
            // он отпускает тело, только если оно всё ещё за ним (см. Release)
            Own(null);
            return busy.Owner;
        }
    }

    /// <summary>
    /// ХОД ТОГО, РАДИ КОГО ЧИСТИЛИ, СОСТОЯЛСЯ — И РАСЧИСТКА ЭТИМ КОНЧАЕТСЯ,
    /// взял он тело или не взял.
    ///
    /// ЧЕМ БЫЛА РАСЧИСТКА БЕЗ ЭТОЙ ДВЕРИ. <see cref="MakeWay"/> ставила её на
    /// КАЖДЫЙ удар, а снималась она в одном-единственном месте — в ветке «тело
    /// свободно» у <see cref="TryTake"/>, то есть только когда спасение за
    /// телом и вправду приходило. Не приходило оно в четырёх случаях, и все
    /// четыре обычные: бой УЖЕ держит тело (удары по ходу стычки), бой решил
    /// «не связываюсь», бой пережидает бегство и врага не видно вовсе. Тогда
    /// застава стояла ПОЛНУЮ выдержку (в пресете — пять секунд) и отказывала
    /// всему, что ниже рефлекса.
    ///
    /// ЗАМЕР ЖИВЬЁМ, на настоящем распорядителе и настоящей способности боя:
    /// после стычки работа простояла 5,0 с; под ударами раз в полторы секунды
    /// при «не связываюсь» — двадцать секунд, и роль взяла тело 0 РАЗ ИЗ 40.
    /// Отказ получали карьер, дорога, разделка туши и — хуже всего — ПРИКАЗ
    /// ЧЕЛОВЕКА ИЗ ЧАТА: «„!иди домой“ не берёт тело: его расчистили под „меня
    /// бьют (дрифтер 2,5 хп)“». Жизнь при этом резала (с голоду бот не умрёт),
    /// а вот уйти от дрифтера по слову хозяина бот не мог.
    ///
    /// ПРИЧИНА, А НЕ СЛЕДСТВИЕ. Расчистка — это «освободи тело ДЛЯ ВОТ ЭТОГО
    /// дела», и жила она своей жизнью: не знала, состоялось ли то, ради чего её
    /// ставили. Значит и кончаться она обязана ТОГДА ЖЕ, когда это решилось, —
    /// а решается это ровно на ходу спасения. Ход пришёл, спасение тело взяло —
    /// расчистку снимает сам <see cref="TryTake"/>; ход пришёл, а спасение тела
    /// НЕ ВЗЯЛО (не захотело, не смогло, передумало) — снимает эта дверь. Ждать
    /// после этого нечего и некого.
    ///
    /// ЧЕГО ЭТО НЕ ЛОМАЕТ. Спасение по-прежнему не ждёт: пока ход спасения НЕ
    /// ПРИШЁЛ — а это и есть тот случай, ради которого расчистка заведена (цикл
    /// способностей ЖДЁТ каждую, и дорога домой уходит в один заход на двадцать
    /// секунд), — застава стоит как стояла, и вернувшаяся работа тела не
    /// отберёт.
    ///
    /// ЦЕНУ НАЗЫВАЮ ВСЛУХ, она есть. Ход спасения идёт своим потоком, а удар
    /// приходит чужим — сетевым; удар, пришедший в САМОМ КОНЦЕ хода, этот ход
    /// уже не увидит, а расчистку его снимет. Тогда застава живёт не до
    /// следующего хода, а на один тик меньше (400 мс), и вернувшаяся работа
    /// успела бы влезть — только ей на возврат нужна целая секунда
    /// (<c>Resume.PauseSeconds</c>), а следующий удар ставит расчистку заново
    /// через полторы. Мерить конец хода не временем, а «удар был раньше начала
    /// хода», я нарочно НЕ стал: тогда удары ПО ХОДУ СТЫЧКИ (а их большинство)
    /// не снимались бы вовсе — то есть вернулся бы ровно тот случай, ради
    /// которого всё это и чинится.
    ///
    /// А ЧЕМ ЭТА ЦЕНА ОГРАНИЧЕНА — ПИШУ ЗДЕСЬ, ПОТОМУ ЧТО В САМИХ ЧИСЛАХ ЭТОГО
    /// НЕ ВИДНО НИ ОДНОМУ ЧИТАЮЩЕМУ. Всё «успела бы влезть, да не успевает»
    /// держится на ОДНОМ сравнении двух чисел из разных файлов: пауза возврата
    /// (<c>Resume.PauseSeconds</c>, 1 с) БОЛЬШЕ хода способностей
    /// (<c>BehaviorRunner.TickMs</c>, 400 мс). Пока это так, в расчищенное тело
    /// первым приходит спасение, а не работа, и цена ограничена одним тиком.
    ///
    /// ОПУСТЯТ ПАУЗУ НИЖЕ ТИКА — И СТУПОР ВЕРНЁТСЯ ЦЕЛИКОМ. Опустить есть чем:
    /// это ручка человека («ПаузаПередВозвратом» у копателя, и берётся она как
    /// <c>Math.Max(0, …)</c> — ноль разрешён). Тогда перебитая работа берёт
    /// тело первой, а ближайший ход боя встречает СВЕЖЕЕ дело и платит ему
    /// полную выдержку: <c>SettleLeft(Reflex, Command, 0, 5)</c> = 5 с — тот
    /// самый отказ «„!иди домой“ не берёт тело», ради которого эта дверь и
    /// заведена. Фоновое дело (<see cref="Importance.Routine"/>) этой цены не
    /// создаёт — ему форы нет вовсе (см. <see cref="SettleLeft"/>); беда только
    /// у приказа из чата и у срочного дела роли.
    ///
    /// Сторожит связь <c>СпасениеНеЖдётTests</c>: там оба числа берутся живыми
    /// (не литералами) и там же показано на настоящем распорядителе, что даёт
    /// пауза короче тика.
    ///
    /// ЗДЕСЬ МОЛЧА, И ЭТО НЕ УМОЛЧАННЫЙ ОТКАЗ. Никому ни в чём не отказано —
    /// наоборот, тело отпущено; а своё решение («не связываюсь», «врага не
    /// видно») спасение говорит само и своими словами. Печатать это дважды в
    /// секунду значило бы залить журнал ровно тем шумом, от которого в
    /// <see cref="Refused"/> заведена заглушка.
    ///
    /// Снимает расчистку не выше поданной ступени: ход рефлекса не отменяет
    /// того, что чистили ради жизни. Возвращает true, если сняли.
    /// </summary>
    /// <param name="level">чей ход состоялся</param>
    public bool WayDone(Importance level)
    {
        lock (gate)
        {
            if (cleared is not { } way || way.Level > level)
                return false;
            cleared = null;
            return true;
        }
    }

    /// <summary>
    /// ВЗЯТЬ ТЕЛО РАДИ ЖИЗНИ: поесть, полечиться, выбраться из воды. Отдельный
    /// вход нарочно — чтобы в способности стояло не число и не название
    /// ступени, а прямо сказанное «это ради жизни», и чтобы такую строку
    /// нельзя было случайно понизить до рефлекса при правке соседнего кода.
    ///
    /// Отказать этому может только другое такое же дело жизни (лечение против
    /// еды) — и об отказе будет сказано вслух, см. <see cref="OnVitalRefused"/>.
    /// </summary>
    public Hold? TakeForLife(string owner, CancellationToken ct = default) =>
        TryTake(owner, Importance.Vital, ct);

    /// <summary>
    /// ВЗЯТЬ ТЕЛО РАДИ СПАСЕНИЯ: укрыться в бурю, уйти от нестабильности,
    /// согреться, драться. Расчищает себе дорогу и тут же её занимает —
    /// выдержку начатого дела (<see cref="SettleSeconds"/>) спасение не платит
    /// НИКОГДА.
    ///
    /// ЖИВАЯ БЕДА, РАДИ КОТОРОЙ ЗАВЕДЕНО. Дверь <see cref="MakeWay"/> была
    /// только у боя, и то лишь потому, что удар приходит СОБЫТИЕМ. У трёх
    /// остальных спасений двери не было вовсе, и они ходили голым
    /// <see cref="TryTake"/> ступенью <see cref="Importance.Reflex"/> — то есть
    /// получали от дороги, начатой секунду назад, честный отказ и уходили
    /// молчать до следующего тика. Стенд приёмки напечатал по <c>null</c> на
    /// всех четверых: «укрытие в бурю», «уйти от нестабильности», «греться» и
    /// сам бой. Бот в это время мёрз, стоял под бурей и осыпался вместе с
    /// нестабильным блоком.
    ///
    /// ПОЧЕМУ НЕ ПОДНЯТЬ ИХ ДО <see cref="Importance.Vital"/>. Жизнь перебивает
    /// ВСЁ, включая бой, — а бросать драку ради похода к костру значит умереть
    /// согретым (разбор — в <c>Cold</c>). Ступень у спасения верная, неверна
    /// была дверь.
    ///
    /// ПОЧЕМУ ЭТО НЕ «СПИСОК ИСКЛЮЧЕНИЙ ИЗ ВЫДЕРЖКИ». Дверь ОДНА и делает одно:
    /// расчищает тело и занимает его. Кто в неё входит — политика способности, и
    /// каждая говорит это у себя вслух. Рейс на склад («разгрузка»), подбор
    /// упавшей еды и разделка туши в неё не входят НАРОЧНО: они той же ступени
    /// или ниже, но это хозяйство, а не спасение, — и держит их выдержка ради
    /// того самого «бегал вперёд-назад с резкими разворотами».
    /// </summary>
    /// <param name="owner">чем бот занят: уйдёт в журнал и в окно управления</param>
    /// <param name="why">почему это спасение: уйдёт в строку расчистки</param>
    public Hold? TakeForRescue(string owner, string why, CancellationToken ct = default)
    {
        // ПОД ОДНИМ ЗАМКОМ: между расчисткой и взятием не должно помещаться
        // ничего, иначе мы расчистили бы дорогу чужому. Замок повторный —
        // обе двери внутри берут его же
        lock (gate)
        {
            // ОТМЕНЁННЫЙ НИКОМУ ДОРОГИ НЕ ЧИСТИТ: иначе он перебьёт живую
            // работу и тут же умрёт сам, а тело останется ничьим. Та же
            // причина, что и в первой строке TryTake; отказ скажет она же,
            // своими словами, чтобы двух разных отказов на один случай не было
            if (!ct.IsCancellationRequested)
                MakeWay(Importance.Reflex, why);
            var hold = TryTake(owner, Importance.Reflex, ct);
            // ХОД СПАСЕНИЯ ЗДЕСЬ ВЕСЬ ЦЕЛИКОМ: расчистили и тут же спросили.
            // Не дали (тело у равного или более важного — бот уже дерётся или
            // ест) — значит расчистка своё отслужила ПРЯМО СЕЙЧАС, и висеть ей
            // выдержку не за чем: греться попросит снова следующим тиком.
            // Иначе выходило вот что: «греться» чистит дорогу, тела не получает
            // (его держит бой), уходит — а застава остаётся и после боя ещё
            // пять секунд отказывает карьеру и приказу из чата. Разбор
            // целиком — у WayDone
            if (hold == null)
                WayDone(Importance.Reflex);
            return hold;
        }
    }

    /// <summary>
    /// Взять тело и подождать, пока освободится, если занято. Для команд из
    /// чата: человек написал «иди туда» — пусть дождётся своей очереди.
    /// </summary>
    public async Task<Hold?> TakeAsync(string owner, Importance level,
        double waitSeconds = 10, CancellationToken ct = default)
    {
        var deadline = DateTime.UtcNow.AddSeconds(waitSeconds);
        while (!ct.IsCancellationRequested)
        {
            if (TryTake(owner, level, ct) is { } hold)
                return hold;
            if (DateTime.UtcNow >= deadline)
                return null;
            await Task.Delay(200, ct).ContinueWith(_ => { });
        }
        return null;
    }

    private void Release(Hold hold)
    {
        lock (gate)
            if (ReferenceEquals(current, hold))
            {
                Own(null);
                // СЧЁТ БРОНИ ИДЁТ С ТОГО МИГА, КАК ТЕЛО СТАЛО СВОБОДНЫМ, а не с
                // мига перехвата, и это не мелочь: рефлекс держит тело минутами
                // (рейс на склад — это минуты ходьбы), и отсчитай мы бронь от
                // перехвата, к концу рейса от неё не осталось бы ни секунды —
                // то есть щель между заходами не закрылась бы вовсе
                if (reserved is { } back)
                    reserved = back with { Since = DateTime.UtcNow };
            }
    }

    /// <summary>
    /// Сколько секунд молчать про ПОВТОРНЫЙ такой же отказ.
    ///
    /// Способности тикают дважды в секунду, и «бой не берёт тело: занято
    /// укрытием» без этой заглушки даёт сотню одинаковых строк в минуту —
    /// ровно тот шум, за которым заказчик не увидел настоящей беды.
    /// </summary>
    public double QuietRefusalSeconds { get; set; } = 3;

    private string lastRefusal = "";
    private DateTime lastRefusalAt = DateTime.MinValue;

    /// <summary>
    /// ТЕЛА НЕ ДАЛИ ДЕЛУ ЖИЗНИ. Отдельное событие, потому что это не «занято,
    /// зайду позже», а «бот сейчас теряет здоровье и ничего не может сделать».
    /// Такое обязано дойти до роли и до человека, а не осесть в общем журнале
    /// между сотней строк про подбор камней.
    /// </summary>
    public event Action<string>? OnVitalRefused;

    /// <summary>
    /// Отказ вслух. Обычный — один раз в <see cref="QuietRefusalSeconds"/>
    /// (иначе «бой не берёт тело: занято укрытием» даёт сотню одинаковых строк
    /// в минуту). Отказ ДЕЛУ ЖИЗНИ — всегда и громко: молчаливый «null» из
    /// TryTake это то, из-за чего бот умирал, «стоя и ничего не делая».
    /// Вызывать только под gate.
    /// </summary>
    /// <param name="повод">
    /// УСТОЙЧИВЫЙ ПОВОД, по которому заглушка узнаёт повтор, — отдельно от
    /// строки, и это не украшение. В отказе по выдержке стоят СЕКУНДЫ, и они
    /// убывают на каждой попытке: <c>TakeAsync</c> спрашивает тело пять раз в
    /// секунду, а строка каждый раз отличается последней цифрой — то есть
    /// заглушка не сработала бы НИ РАЗУ. Ровно тот шум, за которым заказчик
    /// однажды не разглядел настоящей беды; так же от него лечились тревоги
    /// (<see cref="Alarm"/>: «повод, а не готовая строка»). Не сказан — поводом
    /// служит сама строка, как было.
    /// </param>
    private void Refused(Importance level, string line, string? повод = null)
    {
        if (level >= Importance.Vital)
        {
            // Заглушку тут не ставим НАРОЧНО: голодному нечего терпеть, а
            // повторов немного — дела жизни отказывают друг другу редко
            OnLog?.Invoke(line);
            OnVitalRefused?.Invoke(line);
            return;
        }
        string key = повод ?? line;
        if (key == lastRefusal &&
            DateTime.UtcNow - lastRefusalAt < TimeSpan.FromSeconds(QuietRefusalSeconds))
            return;
        lastRefusal = key;
        lastRefusalAt = DateTime.UtcNow;
        OnLog?.Invoke(line);
    }

    /// <summary>
    /// Владение телом. Пока живо — бот занят этим делом. Токен гаснет, когда
    /// дело перебили: продолжать работу после этого — врать о том, где бот.
    /// </summary>
    public sealed class Hold : IDisposable
    {
        private readonly BodyArbiter arbiter;
        private readonly CancellationTokenSource cts;
        private readonly CancellationTokenRegistration link;

        /// <summary>
        /// Конец дела записывают двое и без общей очереди: распорядитель (под
        /// своим замком) и отмена чужого токена (из callback-а системы).
        /// Без этого замка они могли записать причину вперемешку.
        /// </summary>
        private readonly object endGate = new();

        internal Hold(BodyArbiter arbiter, string owner, Importance level, CancellationToken outer)
        {
            this.arbiter = arbiter;
            Owner = owner;
            Level = level;
            cts = new CancellationTokenSource();
            // Регистрация ведёт на САМО ВЛАДЕНИЕ, а не сразу на токен: отмена
            // снаружи (роль перезапустила наряд, человек нажал «стоп», бот
            // вышел из мира) — тоже конец делу, и его причину надо записать.
            // Раньше такое владение гасло молча, и перебитый не мог отличить
            // «меня отменил хозяин» от «я доработал сам»
            link = outer.CanBeCanceled
                ? outer.Register(static s => ((Hold)s!).EndFromOutside(), this)
                : default;
        }

        public string Owner { get; }
        public Importance Level { get; }

        /// <summary>Когда это дело взяло тело — начало отсчёта выдержки.</summary>
        public DateTime TakenAt { get; } = DateTime.UtcNow;

        /// <summary>
        /// Сколько секунд дело уже держит тело. По этому числу
        /// <see cref="SettleLeft"/> и решает, вышла ли выдержка.
        /// </summary>
        public double HeldSeconds => (DateTime.UtcNow - TakenAt).TotalSeconds;

        /// <summary>Отменяется, когда дело перебили или владение отпустили.</summary>
        public CancellationToken Token => cts.Token;

        /// <summary>
        /// Чем кончилось дело: доработало само, его перебил рефлекс, сменилась
        /// цель или его оборвали насмерть. По этому и решают, возвращаться ли
        /// (см. <see cref="Resume"/>).
        /// </summary>
        public Ending End { get; private set; }

        /// <summary>Кто оборвал дело: имя перехватившего или названная причина.</summary>
        public string EndedBy { get; private set; } = "";

        /// <summary>
        /// Дело перебили. Оставлено как было: на этот флаг смотрят команды чата
        /// («Бросил дело: понадобилось спасаться»), и переучивать их незачем —
        /// подробности спрашивают у <see cref="End"/>.
        /// </summary>
        public bool Interrupted => End != Ending.None;

        /// <summary>
        /// Владение ещё живо: токен горит. Погас — телом распоряжается уже
        /// не этот хозяин, кто бы его ни погасил (перебили, отменили снаружи,
        /// отпустили). См. разбор в Living().
        /// </summary>
        public bool Alive => !cts.IsCancellationRequested;

        internal void Interrupt(Ending how, string by)
        {
            // ПЕРВАЯ причина и есть настоящая: если следом за рефлексом придёт
            // ещё и «стоп», дело всё равно оборвал не рефлекс — но перебили
            // его именно тогда, когда перебили, и переписывать это задним
            // числом значит врать в отчёте
            lock (endGate)
                if (End == Ending.None)
                {
                    End = how;
                    EndedBy = by;
                }
            cts.Cancel();
        }

        /// <summary>Токен вызывающего погас: дело оборвали снаружи, не через нас.</summary>
        private void EndFromOutside()
        {
            Interrupt(Ending.Halted, "отменено снаружи");
        }

        public void Dispose()
        {
            arbiter.Release(this);
            // СНАЧАЛА снимаем подписку на чужой токен, потом гасим свой: иначе
            // обычное завершение дела (Dispose гасит cts) выглядело бы для
            // подписки как отмена снаружи, и всякая доделанная работа
            // записывалась бы в оборванные
            link.Dispose();
            if (!cts.IsCancellationRequested)
                cts.Cancel();
            cts.Dispose();
        }
    }
}
