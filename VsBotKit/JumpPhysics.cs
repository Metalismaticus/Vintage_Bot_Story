namespace VsBotKit;

/// <summary>
/// ЧТО ТЕЛО МОЖЕТ В ПРЫЖКЕ — ОДНА ПРАВДА ДЛЯ ВСЕХ.
///
/// До этого дальность прыжка жила в трёх местах: константа в настройках пути,
/// формула в планировщике и другая формула в реактивном прыжке. Они разошлись,
/// и получилось худшее из двух: планировщик закладывал прыжки, которых тело не
/// вытягивает, а после починки — наоборот, запрещал прыжки, которые тело берёт
/// шутя. Заказчик увидел это как «бот стал бояться перепрыгивать».
///
/// ЧИСЛА ЗДЕСЬ ЗАМЕРЕНЫ ТЕЛОМ, А НЕ ПОСЧИТАНЫ НА БУМАГЕ, и это не педантизм.
/// Бумажный счёт тут уже подвёл дважды: время полёта было записано 0,72 с
/// (тело держится 0,683), а полёт с места — 2,77 бл (тело пролетает 2,51).
/// Обе ошибки в опасную сторону: бот обещал себе больше, чем может, и прыгал
/// в щель, которую не берёт. Замер делает <c>PlayerPhysicsFactsTests</c>: он
/// крутит НАСТОЯЩИЕ модули игры (PModuleOnGround, PModuleGravity,
/// PModuleMotionDrag, PModulePlayerInAir) и смотрит, куда приехало тело.
/// Разъедется игра с этими числами — покраснеет он, а не заказчик.
///
/// ОТКУДА ЭТО В САМОЙ ИГРЕ (ilspycmd, 1.22.7): толчок
/// <c>PModuleOnGround.DoApply</c> ставит <c>Motion.Y = BaseJumpForce/60</c>
/// (BaseJumpForce = 8.2f), дальше каждый тик 1/60 с работают
/// <c>PModuleGravity</c> (GravityPerSecond = 0.37f) и
/// <c>PModuleMotionDrag</c> (AirDragAlways = 0.983f).
///
/// Файл нарочно ничего не знает ни про сеть, ни про мир: его линкует в себя
/// клиентский МОД (как <see cref="BodySize"/> и <see cref="BlockPos"/>),
/// а мод считает маршрут тем же кодом, что и безголовый бот.
/// </summary>
public static class JumpPhysics
{
    /// <summary>
    /// Время в воздухе при удержании прыжка, секунд: от отрыва до возвращения
    /// на свой уровень. ЗАМЕР: 0,683 с (41 тик по 1/60). Записанные раньше
    /// 0,72 с были посчитаны на бумаге и завышали полёт на 5 %.
    /// </summary>
    public const double AirTime = 0.683;

    /// <summary>
    /// ПОДЪЁМ НОГ В ВЫСШЕЙ ТОЧКЕ ПРЫЖКА, блоков. ЗАМЕР: 1,2696.
    ///
    /// ЭТО ТО САМОЕ ЧИСЛО, НА КОТОРОМ ЗАКАЗЧИК ПОЙМАЛ ПРОЕКТ. В отказе бот
    /// говорил «прыжком РОВНО 1 бл» (журнал 19.08, 36 раз подряд), а здесь уже
    /// стояло 1,27 — два ответа об одной величине. Слова заказчика: «разве у
    /// героя прыжок ровно 1? мне казалось на снег запрыгивает?». Запрыгивает:
    /// сугроб (snowlayer-5…7) поднимает опору на 1,25, и апекс это берёт.
    /// Целые клетки, которыми ходит планировщик, отсюда ВЫВОДЯТСЯ
    /// (<see cref="Walker.JumpUp"/>), а не пишутся вторым числом.
    /// </summary>
    public const double ApexRise = 1.2696;

    /// <summary>
    /// СКОЛЬКО ЦЕЛЫХ КЛЕТОК БЕРЁТСЯ ПРЫЖКОМ ВВЕРХ — мерка тех, кто ходит по
    /// клеткам, а не по высотам (поиск пути и планировщик).
    ///
    /// ЛЕЖИТ ЗДЕСЬ, А НЕ У ХОДЬБЫ, ПО ЖИВОЙ ПРИЧИНЕ. Это же число было выписано
    /// ТРИЖДЫ: <c>Walker.JumpUp</c> выводил его из апекса, а
    /// <c>PathOptions.MaxJumpUp</c> и <c>PathOptions.MaxStepUp</c> держали
    /// голые единицы с подписью «прыжок поднимает тело на 1,27». Три записи об
    /// одной величине — три шанса разойтись, и один раз проект уже разошёлся
    /// ровно так: «прыжком ровно 1 бл» в отказе против апекса 1,27 в починке.
    /// Урежь кто-нибудь апекс — поиск пути перестанет закладывать подъёмы САМ,
    /// без второй правки в другом файле.
    ///
    /// В <see cref="JumpPhysics"/>, а не в <c>Walker</c>, потому что клиентский
    /// МОД линкует этот файл и <c>PathOptions</c>, а <c>Walker</c> — нет: живи
    /// число там, мод считал бы маршрут своей копией единицы.
    /// </summary>
    public static readonly int CellsUp = (int)Math.Floor(ApexRise);

    /// <summary>
    /// ДАРОВОЙ ПОДЪЁМ ОБРАТНО, клеток: столько тело возьмёт САМО, без лестниц,
    /// блоков и кирки. На суше это прыжок (<see cref="CellsUp"/>); В ВОДЕ ЭТО
    /// НОЛЬ — у плывущего прыжка нет ВОВСЕ.
    ///
    /// Число игры, не наше: <c>PModuleOnGround.Applicable</c> в
    /// VintagestoryLib 1.22.7 — это <c>entity.OnGround &amp;&amp;
    /// !entity.Swimming</c>. Модуль, который вообще читает кнопку прыжка,
    /// плывущему не применяется.
    ///
    /// ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ ПРАВИЛОМ. Вопрос «а выберусь ли я обратно»
    /// (<see cref="Walker.WayBackFromBelow"/>) брал даровой подъём как
    /// <see cref="CellsUp"/> всегда — то есть спуск в ЗАТОПЛЕННУЮ яму обещал
    /// себе прыжок наружу, которого не будет. Приёмка 27.08 назвала это вслух:
    /// «свой же факт не донесён до второго потребителя». Вот он донесён.
    /// </summary>
    public static int FreeRiseBack(bool swimming) => swimming ? 0 : CellsUp;

    /// <summary>
    /// ЧЕМ БЕРЁТСЯ ПОДЪЁМ НА СТОЛЬКО БЛОКОВ: шагом, прыжком или никак.
    ///
    /// ЖИВОЙ СЛУЧАЙ 26.08, ВОСПРОИЗВЕДЁН ДВАЖДЫ. За четыре минуты прогона бот
    /// двенадцать раз упёрся и записал тринадцать клеток в тупики, прыгнув при
    /// этом всего шесть раз. Журнал:
    ///     тупик (46, 110, 234) и (46, 111, 234) (стою в (46, 110, 235))
    ///     упёрся на точке 2/4 (46, 111, 234), стою (46,5, 109,9, 235,3)
    ///     (46, 110, 234): тело не вошло сюда 2 раза подряд — веду маршрут мимо
    ///
    /// ПРИЧИНА. Поиск пути решал «ступенька это или нет» ПО НОМЕРУ КЛЕТКИ:
    /// клетка выше на одну — значит шаг, и шагу присваивался StepKind.Walk. А
    /// тело для Walk прыжок не жмёт НИКОГДА (Movement: «step.IsJump ||
    /// NeedsJumpTo», а второе отвечает только про яму впереди и для соседней
    /// клетки выходит сразу).
    ///
    /// Между тем одна клетка по номеру — это ЧТО УГОДНО по высоте: с плиты на
    /// плиту 0,5 (шаг берёт), а с дорожной плиты (верх 0,9375) на целый блок —
    /// 1,06, и шага в 0,6 тут не хватает. Ровно на этом бот и стоял: ноги на
    /// 109,9, цель на 111.
    ///
    /// ПОЭТОМУ МЕРА — БЛОКИ, А НЕ КЛЕТКИ, и обе границы взяты из игры:
    /// <see cref="BodySize.StepUp"/> = 0,6 (EntityBehaviorControlledPhysics)
    /// и <see cref="ApexRise"/> = 1,27 (замер телом на игровой физике).
    /// </summary>
    public static RiseKind KindOfRise(double rise) =>
        rise <= BodySize.StepUp ? RiseKind.Step
        : rise <= ApexRise ? RiseKind.Jump
        : RiseKind.TooHigh;

    /// <summary>
    /// Какая доля дальности остаётся, если приземляться НА БЛОК ВЫШЕ.
    ///
    /// Откуда число. Полёт — парабола с вершиной <see cref="ApexRise"/>. Тело
    /// выше одного блока лишь на части пути: h(τ) = 4·ApexRise·τ·(1−τ), где
    /// τ — доля полёта. Решая h(τ) = 1, получаем τ = (1 + √(1 − 1/ApexRise))/2 —
    /// дальше тело уже ниже уступа и попросту в него упрётся.
    ///
    /// СЧИТАЕТСЯ, А НЕ ЗАПИСАНО ЧИСЛОМ, И ЭТО НЕ ПЕДАНТИЗМ. Здесь стояло
    /// «= 0.73» с этим самым выводом в подписи — то есть ПЕРЕСКАЗ расчёта
    /// рядом с расчётом, вторая запись величины, зависящей от апекса. Ровно
    /// такой пересказ уже отстал однажды: «прыжком ровно 1 бл» пережил
    /// замеренные 1,27, а «полёт 2,77» пережил замеренные 2,507. Урежь
    /// кто-нибудь апекс — доля поедет за ним САМА, без второй правки.
    /// (На сегодняшнем апексе выходит 0,7304 — прежние 0,73 и были верны,
    /// но верны они были вручную.)
    ///
    /// НОЛЬ ПРИ АПЕКСЕ НИЖЕ БЛОКА — не заглушка, а тот же расчёт до конца:
    /// корень там мнимый именно потому, что тело НЕ ПОДНИМАЕТСЯ на блок ни
    /// в какой миг полёта, и доля дальности «на блок выше» честно нулевая.
    /// Без этой ветки вышло бы NaN, а NaN тихо запрещает прыжок сравнением,
    /// и человек читал бы отказ, не понимая, откуда он.
    /// </summary>
    public static readonly double UpwardReachFraction =
        ApexRise <= 1 ? 0 : (1 + Math.Sqrt(1 - 1 / ApexRise)) / 2;

    /// <summary>
    /// УСТАНОВИВШАЯСЯ СКОРОСТЬ ШАГА на ровной земле при walkspeed = 1, бл/с.
    /// ЗАМЕР: 3,393 (за секунду тело проходит ровно столько).
    ///
    /// ЛЕЖИТ ЗДЕСЬ, А НЕ В ДВИЖЕНИИ, ПО ОДНОЙ ПРИЧИНЕ: дальность прыжка —
    /// это скорость, помноженная на время полёта, и обе половины обязаны быть
    /// одним числом на весь проект. <c>Movement.BaseWalkSpeed</c> теперь
    /// ссылается сюда, а не держит свою копию. Мод линкует этот файл — значит
    /// и он меряет прыжок той же скоростью, что и безголовый бот.
    /// </summary>
    public const double WalkSpeed = 3.393;

    /// <summary>
    /// Во сколько раз бег быстрее шага. Число игры:
    /// <c>GlobalConstants.SprintSpeedMultiplier = 2.0</c> (VintagestoryAPI 1.22.7),
    /// и оно же проверяется замером (бег ровно вдвое быстрее шага).
    /// </summary>
    public const double SprintMultiplier = 2.0;

    /// <summary>Скорость полного бега по ровной земле, бл/с.</summary>
    public const double SprintSpeed = WalkSpeed * SprintMultiplier;

    /// <summary>
    /// Полёт прыжка С МЕСТА, блоков. ЗАМЕР: 2,507 (раньше стояло 2,77 —
    /// завышение на четверть блока, то есть обещанный себе недолёт).
    /// Не ноль потому, что в полёте тело всё-таки разгоняется:
    /// <c>PModulePlayerInAir</c> добавляет ход, пока держат клавишу прыжка.
    /// </summary>
    public const double StandingFlight = 2.507;

    /// <summary>Полёт прыжка с полного разбега, блоков. ЗАМЕР: 4,848.</summary>
    public const double RunningFlight = 4.848;

    /// <summary>
    /// Свес хитбокса: по столько блоков добавляется на взлёте и на посадке.
    /// Это ПОЛОВИНА ШИРИНЫ ТЕЛА (<see cref="BodySize.HalfWidth"/>), а не своё
    /// число: ширина тела в проекте одна, и меряют ею и прыжок, и проход по
    /// прямой, и попадание на пластину транслокатора.
    /// </summary>
    public const double HitboxOverhang = BodySize.HalfWidth;

    /// <summary>
    /// Сколько блоков разбега нужно до полной скорости. Разгон занимает около
    /// 0.2 с — это полтора блока. Одной клетки сзади НЕ хватает.
    /// </summary>
    public const double RunUpToFullSpeed = 1.5;

    // ---------------- за что тело цепляется в высшей точке ----------------

    /// <summary>
    /// ДОКУДА ДОСТАЁТ ТЕЛО В ВЫСШЕЙ ТОЧКЕ ПРЫЖКА, блоков: ноги поднимаются на
    /// <see cref="ApexRise"/>, а сверху к ним прибавляется рост
    /// (<see cref="BodySize.Height"/>). За висячую лестницу цепляются ТЕЛОМ, а
    /// не ногами, — поэтому мерка тут рост, а не апекс.
    /// </summary>
    public static double ReachUp => ApexRise + BodySize.Height;

    /// <summary>
    /// Самая высокая ступень висячей лестницы, за которую ещё зацепишься
    /// прыжком, клеток над клеткой ног. Из <see cref="ReachUp"/>.
    /// </summary>
    public static int HighestRung => (int)ReachUp;

    /// <summary>
    /// Где окажутся ноги после зацепа. Тело висит, КАСАЯСЬ нижней ступени,
    /// значит ноги встают на клетку ниже неё: зацепившись за ступень в трёх
    /// блоках над полом, бот поднимается на два.
    /// </summary>
    /// <param name="feetY">Клетка ног перед прыжком.</param>
    /// <param name="rungAbove">На сколько блоков выше висит нижняя ступень.</param>
    public static int FeetAfterGrab(int feetY, int rungAbove) =>
        feetY + Math.Max(0, rungAbove - 1);

    /// <summary>
    /// На сколько клеток вверх прыжок к висячей лестнице поднимает НОГИ —
    /// столько поиск пути и вправе закладывать.
    ///
    /// СВОЕГО ЧИСЛА У ПОИСКА ПУТИ БОЛЬШЕ НЕТ: там стояла двойка с подписью
    /// «ноги поднимаются на 1.27, тело достаёт до 3.12, значит рунг не выше 3,
    /// а ноги на 2». Подпись — пересказ ЭТОГО расчёта, и пересказ рано или
    /// поздно отстаёт от расчёта: так уже отстало «прыжком ровно 1 бл».
    /// </summary>
    public static int LadderMountCells => FeetAfterGrab(0, HighestRung);

    /// <summary>
    /// КАКАЯ СКОРОСТЬ БУДЕТ К МОМЕНТУ ОТРЫВА при таком разбеге, бл/с.
    /// Разгон линеен по пройденному пути до <see cref="RunUpToFullSpeed"/>.
    /// </summary>
    public static double SpeedAfterRunUp(double runUpBlocks) =>
        SprintSpeed * Math.Clamp(runUpBlocks / RunUpToFullSpeed, 0, 1);

    /// <summary>
    /// ПОЛЁТ ПО СКОРОСТИ ОТРЫВА — ЕДИНСТВЕННАЯ ФОРМУЛА ДАЛЬНОСТИ В ПРОЕКТЕ.
    ///
    /// Здесь их было ДВЕ: планировщик считал полёт по разбегу линейной
    /// прикидкой между двумя замерами, а реактивный прыжок у обрыва — своей
    /// «скорость × время полёта». Второе занижало на 0,2 бл, и два ответа об
    /// одном прыжке расходились ровно там, где расхождение и опасно: у края.
    /// Теперь по разбегу считается ТА ЖЕ функция, через
    /// <see cref="SpeedAfterRunUp"/>.
    ///
    /// «Скорость × время» тут не годится буквально: оторвавшись от земли, тело
    /// теряет её сопротивление (groundDragFactor 0,3) и в полёте немного
    /// РАЗГОНЯЕТСЯ — на полном бегу выходит 7,1 бл/с вместо 6,79. Поэтому
    /// прямая проведена по двум замерам, а не по бумажной формуле.
    /// </summary>
    public static double FlightAtSpeed(double blocksPerSecond) =>
        StandingFlight + (RunningFlight - StandingFlight) *
        Math.Clamp(blocksPerSecond / SprintSpeed, 0, 1);

    /// <summary>Полёт при таком разбеге (блоков разбега → блоков полёта).</summary>
    public static double FlightWithRunUp(double runUpBlocks) =>
        FlightAtSpeed(SpeedAfterRunUp(runUpBlocks));

    /// <summary>
    /// До какой клетки бот дотягивается прыжком при таком разбеге. Считается
    /// в клетках от точки отрыва: 3.11 означает «клетка №3 берётся, №4 нет».
    /// </summary>
    public static double ReachWithRunUp(double runUpBlocks) =>
        FlightWithRunUp(runUpBlocks) + 2 * HitboxOverhang;

    /// <summary>
    /// То же самое, но по НАСТОЯЩЕЙ скорости тела — так считает реактивный
    /// прыжок у обрыва, которому разбег гадать не нужно: он уже бежит.
    /// </summary>
    public static double ReachAtSpeed(double blocksPerSecond) =>
        FlightAtSpeed(blocksPerSecond) + 2 * HitboxOverhang;

    /// <summary>
    /// Запас прыжка: на сколько блоков дальше цели бот долетел бы. Больше нуля —
    /// перелетит, меньше — не долетит. Это и есть мера риска: прыжок с запасом
    /// в два блока не «рискованный над пропастью», он просто прыжок.
    /// </summary>
    public static double Margin(double reach, double distance) => reach - distance;

    /// <summary>
    /// Вероятность промахнуться при таком запасе. При запасе от
    /// <paramref name="safeMargin"/> и выше промаха нет вовсе: тело летит по
    /// физике игры, а не по удаче. Ближе к пределу — риск растёт до половины.
    /// </summary>
    public static double MissChance(double margin, double safeMargin)
    {
        if (margin >= safeMargin)
            return 0;
        if (margin <= 0)
            return 1;
        return 0.5 * (1 - margin / safeMargin);
    }

    /// <summary>Урон от падения после прыжка: высота считается от апекса.</summary>
    public static double FallDamageAfterJump(double pitDepth) =>
        AStarPathFinder.EstimateFallDamage(pitDepth + ApexRise);

    /// <summary>
    /// ПОМОЖЕТ ЛИ ПРЫЖОК, КОГДА ИГРОВАЯ ПРОБА ШАГА ОТКАЗАЛА ПО ПОТОЛКУ.
    ///
    /// ЖИВОЙ СЛУЧАЙ (стенд 26.08, дверной проём заказчика (62, 112, 252) и
    /// точно такой же в (512032, 110, 512010)). Порог занесло снежным слоем
    /// (коробка 0,125 — снежные слои 2…4 в ассетах 1.22.7; старый щуп печатал её
    /// округлённо, «0,13»), а притолока проёма стоит ровно в 2,0 над полом.
    /// Игра поднимает тело на «верх препятствия + 0,03» и требует, чтобы на
    /// этой высоте тело ни во что не упиралось: 0,125 + 0,03 + 1,85 = 2,005
    /// против 2,0 — отказ на ПЯТЬ ТЫСЯЧНЫХ блока. Шага нет, снег гасит ось
    /// начисто, и бот стоит в проёме, не выходя ни вперёд, ни назад.
    ///
    /// А ПРЫЖОК ТАМ РАБОТАЕТ, и это не хитрость, а обычное движение живого
    /// игрока: потолок подрезает прыжок ровно на просвет над головой
    /// (2,0 − 1,85 = 0,15), но 0,15 больше, чем 0,125, — ноги оказываются выше
    /// снега, ось освобождается, и тело выходит. Никакого запаса игры к
    /// препятствию прибавлять не надо: прыжок не «пробует поместиться»,
    /// он просто поднимает.
    ///
    /// ГРАНИЦА ЗДЕСЬ НЕ ВКУСОВАЯ, И РУЧКИ У НЕЁ НЕТ НАРОЧНО: оба числа
    /// измеренные, и оба меряет ИГРА. Подъём называет проба шага
    /// (<c>GamePlayerPhysics.StepDeniedOverhead</c>), просвет над головой —
    /// игровой <c>CollisionTester</c>, поднимающий то самое тело на месте
    /// (<c>GamePlayerPhysics.StepDeniedHeadroom</c>). Крутить тут нечего.
    ///
    /// Сугроб в 0,25 под тем же потолком прыжком НЕ БЕРЁТСЯ, и это правило
    /// обязано сказать «нет»: тело на нём и стоять-то не сможет (2,0 − 0,25 =
    /// 1,75 при росте 1,85). Такой проём чистят, а не перепрыгивают —
    /// этим занят приём «смахнуть мелочь с дороги» (<c>WalkTry.Sweep</c>).
    ///
    /// О ДВУХ ВЕТКАХ, ДО КОТОРЫХ СЕГОДНЯШНИЙ ЖИВОЙ ПУТЬ НЕ ДОХОДИТ (сказано
    /// вслух по разбору приёмки, а не спрятано). Единственный, кто зовёт это
    /// правило, — <c>Movement.CanHopObstacle</c>, и он приносит подъём, уже
    /// отобранный игрой: <c>FindSteppableCollisionBox</c> берёт ступеньки
    /// строго в (0; <c>StepHeight</c>=0,6], а апекс прыжка 1,27. Значит ни
    /// «шаг не отказывал», ни «выше прыжка» оттуда не приходят никогда.
    /// Ветки всё же стоят: правило открытое и чистое, отвечать мусором на
    /// мусор оно не вправе. Тесты на них сторожат САМО ПРАВИЛО, и выдавать их
    /// за проверку живого случая нельзя — там их и нет.
    /// </summary>
    /// <param name="rise">Высота препятствия над ногами, блоков (ответ игры).</param>
    /// <param name="headroom">Просвет над головой прямо сейчас, блоков (ответ игры).</param>
    public static (bool Hop, string Why) HopWhenStepDenied(double rise, double headroom)
    {
        if (rise <= 0)
            return (false, "шаг не отказывал — прыгать не с чего");
        if (rise > ApexRise)
            return (false, $"передо мной {rise:0.###} бл — выше прыжка ({ApexRise:0.##} бл)");
        if (headroom > rise)
            return (true, $"шаг не влез под потолок, а прыжок влезет: препятствие " +
                          $"{rise:0.###} бл, над головой {headroom:0.###} бл");
        return (false, $"под потолком не подняться: препятствие {rise:0.###} бл, " +
                       $"а над головой всего {headroom:0.###} бл — тут не прыгать надо, " +
                       "а убирать помеху");
    }

    // ---------------- вплавь: прыжка нет вовсе ----------------

    /// <summary>
    /// ГЛУБИНА ПОСАДКИ ПЛЫВУЩЕГО, блоков: <c>Entity.SwimmingOffsetY</c> игры —
    /// «SelectionBox.Y1 + SelectionBox.Y2 · 0,66» (VintagestoryAPI 1.22.7), у
    /// игрока это 0 + 1,85·0,66 = 1,221. Именно на этой высоте игра щупает
    /// клетку, решая «плывёт или идёт вброд», и от неё же считает плавучесть.
    ///
    /// Число одно на проект: <c>WorldModel.SwimmingOffsetY</c> ссылается СЮДА,
    /// а не держит свою копию, — этот файл линкует в себя клиентский мод, и
    /// вторая запись величины разъехалась бы, как уже разъезжался апекс.
    /// </summary>
    public static readonly double SwimmingOffsetY = BodySize.Height * 0.66;

    /// <summary>
    /// ЛИНИЯ ВОДЫ ПО СЧЁТУ САМОЙ ИГРЫ, блоков. Это НЕ поверхность водоёма:
    /// игра складывает своё число из трёх клеток и НЕ смотрит, сколько налито
    /// в те две, что выше, — каждая жидкая клетка над клеткой ног прибавляет
    /// ровно 1,125 (<c>PModuleInLiquid.HandleSwimming</c>, VintagestoryAPI
    /// 1.22.7, дословно):
    /// <code>
    ///   num = Clamp((int)Y + LiquidLevel/8
    ///               + (выше жидкость ? 1.125f : 0)
    ///               + (ещё выше жидкость ? 1.125f : 0)
    ///               − Y − SwimmingOffsetY, 0, 1)
    /// </code>
    /// Отсюда и странность, которую нельзя «упростить до поверхности»: в пруду
    /// с настоящей поверхностью 110,875 линия воды у клетки ног равна 111,0.
    /// </summary>
    /// <param name="feetCellY">Номер клетки, в которой НОГИ.</param>
    /// <param name="fillAtFeet">Заполнение клетки ног жидкостью, доля 0…1.</param>
    /// <param name="liquidAbove">Клетка над ногами — жидкость.</param>
    /// <param name="liquidTwoAbove">И следующая за ней — тоже.</param>
    public static double WaterLine(int feetCellY, double fillAtFeet,
                                   bool liquidAbove, bool liquidTwoAbove) =>
        feetCellY + fillAtFeet + (liquidAbove ? 1.125 : 0) + (liquidTwoAbove ? 1.125 : 0);

    /// <summary>
    /// НЕДОБОР ПЛЫВУЩЕГО ДО ЛИНИИ ВОДЫ НА ХОДУ, блоков. ВЫВЕДЕНО, А НЕ ПОДОБРАНО.
    ///
    /// <c>PModulePlayerInLiquid.HandleSwimming</c> толкает вверх только
    /// «if (num &gt; 0.1f || !controls.TriesToMove)», а само num — это
    /// «min(1, сырое + 0.075f)». Идущий (TriesToMove) толкается, пока
    /// сырое &gt; 0,1 − 0,075, то есть подъём прекращается на сырое = 0,025.
    /// Сырое — это и есть «сколько ещё не добрали до линии воды».
    ///
    /// ЗАМЕРЕНО ПРЯМО, А НЕ ПЕРЕСКАЗАНО (<c>Гребок_вверх_гаснет_ровно_на_этом_недоборе</c>
    /// в <c>ВыходИзОткрытойВодыЗамерTests</c>): двоичным поиском по высоте тела
    /// ищется та высота, на которой ИДУЩИЙ в воде ещё получает гребок вверх
    /// (motion.Y растёт за один тик), и на полблока выше — уже нет. Граница
    /// сходится с этим числом до тысячной.
    ///
    /// ЗДЕСЬ СТОЯЛА ССЫЛКА НА ОПЫТ, КОТОРОГО НЕ БЫЛО. Подпись обещала «замер:
    /// тело на ходу поднималось до 109,7954» — такого опыта в наборе не
    /// существовало вовсе, а число жило только в прозе. Приёмка 27.08 поймала
    /// это подменой: <c>SwimPushCutoff</c> можно было поставить и 0,10 (это
    /// буквальный литерал игры, самая вероятная ошибка вывода), и 0,0 — все
    /// 4954 стенда оставались зелёными. Теперь число держит опыт.
    /// </summary>
    /// <remarks>
    /// ЧИСЛО НАРОЧНО НЕ <c>const</c>: константа времени компиляции ВПЕЧАТЫВАЕТСЯ
    /// в чужую сборку, и стенд, собранный вчера, продолжает мерить вчерашним
    /// числом. Поймано при проверке подменой 27.08 — я подвинул это число, а
    /// стенд остался зелёным, потому что старое значение было впечатано в
    /// VsBotKit.Tests.dll.
    /// </remarks>
    public static readonly double SwimPushCutoff = 0.025;

    /// <summary>
    /// НЕДОБОР ПЛЫВУЩЕГО, ЗАМЕРШЕГО НА МЕСТЕ, блоков. ТОЖЕ ВЫВЕДЕНО.
    ///
    /// Стоящий не «TriesToMove», и тогда у него РАБОТАЕТ ТЯЖЕСТЬ:
    /// <c>PModuleGravity.DoApply</c> вычитает её всякий раз, когда неверно
    /// «Swimming &amp;&amp; TriesToMove &amp;&amp; Alive», причём в жидкости
    /// втрое слабее — множитель «entity.FeetInLiquid ? 0.33f : 1f». За тик это
    ///     0,37 (GravityPerSecond) · 0,33 · 1/60 = 0,002035 бл,
    /// а гребок вверх даёт «0.005f · num · dt · 60f» = 0,005·num. Равенство
    /// даёт num = 0,407, и за вычетом всё тех же 0,075 — сырое = 0,332.
    ///
    /// СХОДИТСЯ ДВАЖДЫ, И ОБА РАЗА ДО ТРЁХ ЗНАКОВ. Стенд на игровой физике: при
    /// линии воды 111,0 тело замирает на 109,447 = 111,0 − 1,221 − 0,332.
    /// ЖИВОЙ МИР ЗАКАЗЧИКА (прогон 27.08, out/вода-ДО): бот стоит в море
    /// «позиция (32, 114,3, 9), плыву», а колонна там — saltwater-d-6 в 114 и
    /// saltwater-d-7 в 115, то есть линия воды 114 + 0,75 + 1,125 = 115,875,
    /// и счёт даёт 115,875 − 1,553 = 114,322.
    /// </summary>
    /// <remarks>Не <c>const</c> по той же причине, что и
    /// <see cref="SwimPushCutoff"/>: константа впечатывается в чужую сборку.</remarks>
    public static readonly double SwimRestOffset = 0.332;

    /// <summary>
    /// ГДЕ ДЕРЖАТСЯ НОГИ ПЛЫВУЩЕГО НА ХОДУ (по ней и решает маршрут: бот в пути
    /// именно что идёт, а не замирает).
    /// </summary>
    public static double AfloatInOpenWater(double waterLine) =>
        waterLine - SwimmingOffsetY - SwimPushCutoff;

    /// <summary>Где держатся ноги плывущего, замершего на месте.</summary>
    public static double AfloatAtRest(double waterLine) =>
        waterLine - SwimmingOffsetY - SwimRestOffset;

    /// <summary>
    /// ДОКУДА ПОДНИМУТСЯ НОГИ ИЗ ОТКРЫТОЙ ВОДЫ — ДВУМЯ РАЗНЫМИ СРЕДСТВАМИ ИГРЫ,
    /// и второе из них было пропущено проектом до 27.08 целиком.
    ///
    /// <list type="number">
    /// <item>ПЛАВУЧЕСТЬ: ноги висят на <see cref="AfloatInOpenWater"/>, и от них
    /// берётся обычный всход <see cref="BodySize.StepUp"/> — он работает и
    /// вплавь (<c>HandleSteppingOnBlocks</c> отказывает лишь тому, кто НИ на
    /// земле, НИ вплавь);</item>
    /// <item>ВЫЛАЗ ПО СТЕНКЕ. У игры есть отдельная поблажка ровно на этот
    /// случай, и держится она на УРОВНЕ ЖИДКОСТИ. Дословно
    /// (<c>EntityBehaviorControlledPhysics.ApplyTests</c>, VSEssentials 1.22.7):
    /// <code>
    ///   if (CollidedHorizontally &amp;&amp; !IsClimbing &amp;&amp; !IsStepping &amp;&amp; Habitat != Underwater)
    ///     if (LiquidLevel(x, (int)(Y+0.5), z) >= 7 || LiquidLevel(x, (int)Y, z) >= 7
    ///         || LiquidLevel(x, (int)(Y−0.05), z) >= 7)
    ///     { motion.Y += 0.2 * dt;  controls.IsStepping = true; }
    /// </code>
    /// То есть упёршийся в стену, стоя в ПОЛНОЙ воде (7/8), сам ползёт вверх,
    /// пока полная вода не кончится, — и поднимается до ВЕРХА последней полной
    /// клетки. В неполной воде этой поблажки нет ВООБЩЕ.</item>
    /// </list>
    ///
    /// ЗАМЕР ПОДТВЕРЖДАЕТ ОБЕ ВЕТКИ И РАЗНИЦУ МЕЖДУ НИМИ
    /// (<c>ВыходИзОткрытойВодыЗамерTests</c>, 22 опыта на живых модулях игры):
    /// из пруда 7/8 с поверхностью 110,875 тело выходит на кромку 111,5 и не
    /// выходит на 112,0 — счёт даёт ровно 111,0 + 0,6 = 111,6; а из такого же
    /// пруда 6/8 с поверхностью 110,75 оно не выходит уже на 111,0, и счёт даёт
    /// 109,504 + 0,6 = 110,104. Одна вода, одна кромка, разный ответ — и
    /// решает его уровень заполнения, а не глубина и не поверхность.
    /// </summary>
    /// <param name="waterLine">Линия воды у клетки ног (<see cref="WaterLine"/>).</param>
    /// <param name="topFullWater">
    /// Верх последней ПОЛНОЙ клетки воды над телом; <c>double.NegativeInfinity</c>,
    /// если полной воды тут нет — тогда вылаза по стенке не будет.
    /// </param>
    public static double ReachFromOpenWater(double waterLine, double topFullWater) =>
        Math.Max(AfloatInOpenWater(waterLine), topFullWater) + BodySize.StepUp;

    /// <summary>
    /// НОГИ В ЖИДКОСТИ ИЛИ НЕТ — ОДНО ПРАВИЛО НА ВЕСЬ ПРОЕКТ, И ЭТО ПРАВИЛО ИГРЫ.
    ///
    /// Дословно <c>EntityBehaviorControlledPhysics.ApplyTests</c> (VSEssentials
    /// 1.22.7, ilspycmd 27.08):
    /// <code>
    ///   if (feetBlock.IsLiquid())
    ///     entity.FeetInLiquid =
    ///       (float)(feetBlock.LiquidLevel + (aboveBlock.LiquidLevel > 0 ? 1 : 0)) / 8f
    ///       >= pos.Y - (int)pos.Y;
    /// </code>
    /// Прибавка за жидкость сверху идёт К УРОВНЮ (одна восьмая), а не к доле —
    /// это легко прочесть наоборот, и тогда правило начнёт разрешать промывку
    /// стоя по щиколотку.
    ///
    /// ЗАЧЕМ ОДНИМ МЕСТОМ. По этому вопросу игра решает, считать ли промывку
    /// лотком (<c>ingameerror-panning-notinwater</c>), и по нему же живое тело
    /// ставит свой флаг. Копий было две, и вторая (в <c>Panning</c>) звучала
    /// «в клетке ног есть вода» — то есть отвечала «да» там, где живой игрок
    /// промыть не может (закон 5).
    /// </summary>
    /// <param name="feetY">Высота ног тела (дробная).</param>
    /// <param name="fillAtFeet">Заполнение клетки ног, доля 0…1.</param>
    /// <param name="liquidAbove">Над клеткой ног — тоже жидкость.</param>
    public static bool FeetInLiquid(double feetY, double fillAtFeet, bool liquidAbove) =>
        fillAtFeet > 0 &&
        fillAtFeet + (liquidAbove ? 1 / 8.0 : 0) >= feetY - Math.Floor(feetY);

    /// <summary>
    /// ГДЕ ИГРА ЩУПАЕТ ВОДУ ДЛЯ ВЫЛАЗА ПО СТЕНКЕ — три высоты ОТНОСИТЕЛЬНО НОГ,
    /// дословно из <c>EntityBehaviorControlledPhysics.ApplyTests</c> (VSEssentials
    /// 1.22.7, сверено ilspycmd 27.08):
    /// <code>
    ///   GetBlockRaw(x, (int)(pos.InternalY + 0.5), z, 2).LiquidLevel >= 7 ||
    ///   GetBlockRaw(x, (int)pos.InternalY,        z, 2).LiquidLevel >= 7 ||
    ///   GetBlockRaw(x, (int)(pos.InternalY - 0.05), z, 2).LiquidLevel >= 7
    /// </code>
    ///
    /// ПОЧЕМУ ЭТО ВАЖНО, А НЕ ПЕДАНТИЗМ. Проект переводил поблажку как «клетка,
    /// В КОТОРОЙ НОГИ, полна» — и терял верхний щуп «+0,5», который смотрит на
    /// клетку ВЫШЕ ног. В море заказчика (прочие клетки 6/8, ВЕРХНЯЯ 7/8) ноги
    /// висят на 114,63 в клетке 114 (6/8), а щуп «+0,5» попадает в клетку 115
    /// (7/8) — игра вылаз РАЗРЕШАЕТ, тело выходит, а правило отказывало.
    /// Именно на этом расходились два конца: поиск пути спрашивал клетку 115 и
    /// разрешал, тело спрашивало клетку 114 и запрещало. Теперь оба спрашивают
    /// по ВЫСОТЕ НОГ, и клетка, от которой задан вопрос, ответа не меняет.
    /// </summary>
    public static readonly double[] WallCrawlProbes = [0.5, 0.0, -0.05];

    /// <summary>
    /// ДОКУДА ПОДНИМУТСЯ НОГИ ПЛЫВУЩЕГО — ОДИН СЧЁТ, ОДНО МЕСТО.
    ///
    /// ЗАКОН 2, НАХОДКА ПРИЁМКИ 27.08. Этот <c>Math.Min</c> стоял ДВАЖДЫ: здесь
    /// (внутри <see cref="LeaveWater"/>) и в <c>Buoyancy.ReachOutOfWater</c>.
    /// Одна формула, два тела: поиск пути резал клетки вторым, а отказ вслух
    /// объяснялся первым. Разъехались бы молча — и планировщик снова водил бы
    /// туда, откуда тело разворачивается.
    /// </summary>
    /// <param name="waterLine">Линия воды у клетки, где тело плывёт.</param>
    /// <param name="topFullWater">Верх вылаза по стенке; −∞ — вылаза нет.</param>
    /// <param name="ceilingY">Низ потолка над водой; +∞ — открытое небо.</param>
    public static double ReachOutOfWater(double waterLine, double topFullWater, double ceilingY) =>
        double.IsPositiveInfinity(ceilingY)
            ? ReachFromOpenWater(waterLine, topFullWater)
            : Math.Min(ReachFromOpenWater(waterLine, topFullWater), ReachUnderCeiling(ceilingY));

    /// <summary>
    /// ДОКУДА ПОДНИМУТСЯ НОГИ ПЛЫВУЩЕГО, КОГДА ВСТАВАТЬ НЕ НА ЧТО — то есть при
    /// ВСПЛЫТИИ В ВОДУ, а не при выходе на кромку. Это ЧИСТАЯ ПЛАВУЧЕСТЬ: ни
    /// всхода, ни вылаза по стенке.
    ///
    /// ПОЧЕМУ ОТДЕЛЬНОЕ ЧИСЛО, А НЕ <see cref="ReachOutOfWater"/>. Оба игровых
    /// средства подъёма требуют, ВО ЧТО УПЕРЕТЬСЯ:
    /// <list type="bullet">
    /// <item>всход <see cref="BodySize.StepUp"/> — <c>HandleSteppingOnBlocks</c>
    /// ищет коробку столкновений, НА КОТОРУЮ всходят (<c>FindSteppableCollisionBox</c>);
    /// в открытой воде её нет вовсе;</item>
    /// <item>вылаз по стенке — <c>ApplyTests</c> требует <c>CollidedHorizontally</c>,
    /// то есть тело должно упереться в стену.</item>
    /// </list>
    /// Всплытие в соседнюю клетку воды не даёт ни того, ни другого, и полблока
    /// всхода там были ПОДАРЕНЫ. Цена подарка известна поимённо: улика
    /// «упёрся на точке 4/29 (32, 115, 9)» из живого прогона заказчика. Клетка
    /// (32,115,9) — вода, ноги тела держатся на 114,63 и в клетку 115 не
    /// попадают НИКОГДА, а поиск пути строил по ней целый плывущий отрезок,
    /// потому что 115 ≤ 114,63 + 0,6. Ровно тот же грех, что у снесённой
    /// <c>MaxWaterExitHeight</c>: полблока без источника.
    /// </summary>
    /// <param name="waterLine">Линия воды у клетки, где тело плывёт.</param>
    /// <param name="ceilingY">Низ потолка над водой; +∞ — открытое небо.</param>
    public static double AfloatReach(double waterLine, double ceilingY) =>
        double.IsPositiveInfinity(ceilingY)
            ? AfloatInOpenWater(waterLine)
            : Math.Min(AfloatInOpenWater(waterLine), AfloatUnderCeiling(ceilingY));

    /// <summary>Полная клетка жидкости у игры — <c>LiquidLevel &gt;= 7</c> из восьми.</summary>
    /// <remarks>Не <c>const</c> по той же причине, что и
    /// <see cref="SwimPushCutoff"/>: константа впечатывается в чужую сборку.</remarks>
    public static readonly double FullLiquid = 7 / 8.0;

    /// <summary>
    /// ВЫЙДЕТ ЛИ ПЛЫВУЩИЙ НА КРОМКУ — ОДИН ВОПРОС НА ОБА КОНЦА (поиск пути и
    /// живое тело), и обе заставы разом: потолок сверху и плавучесть снизу.
    ///
    /// ЧТО ЗДЕСЬ ЗАМЕНИЛО ВЫДУМАННОЕ ЧИСЛО. До 27.08 выход из воды мерился
    /// ручкой <c>PathOptions.MaxWaterExitHeight = 1</c> — «на клетку вверх
    /// можно», — и у этой единицы НЕ БЫЛО ИСТОЧНИКА: так и стояло в её же
    /// подписи, «осторожное умолчание без источника». Она врала в обе стороны:
    /// обещала выход на кромку в клетку из НЕПОЛНОЙ воды (замер: не выходит) и
    /// обещала его же там, где под кромкой нет полной воды вовсе — например у
    /// кирпичной стены дома заказчика, встающей из моря saltwater-d-6.
    /// </summary>
    /// <param name="ledgeFeetY">Высота ног на кромке, куда зовёт маршрут.</param>
    /// <param name="waterLine">Линия воды у клетки, где тело плывёт.</param>
    /// <param name="topFullWater">Верх последней полной клетки воды над телом.</param>
    /// <param name="ceilingY">Низ потолка над водой; +∞ — открытое небо.</param>
    public static (bool Out, string Why) LeaveWater(
        double ledgeFeetY, double waterLine, double topFullWater, double ceilingY)
    {
        double плавучесть = ReachFromOpenWater(waterLine, topFullWater);
        double потолок = double.IsPositiveInfinity(ceilingY)
            ? double.PositiveInfinity
            : ReachUnderCeiling(ceilingY);
        // Считает ОДНА функция на весь проект — см. ReachOutOfWater: этот
        // Math.Min стоял и здесь, и в Buoyancy, и они разъехались бы молча
        double предел = ReachOutOfWater(waterLine, topFullWater, ceilingY);
        if (ledgeFeetY <= предел)
            return (true, "");
        if (потолок < плавучесть)
            return (false,
                $"из-под потолка {ceilingY:0.##} не выбраться: макушка держит ноги на " +
                $"{AfloatUnderCeiling(ceilingY):0.##}, шагом вплавь берётся {BodySize.StepUp:0.##} бл " +
                $"(прыжка у плывущего нет вовсе), а кромка на {ledgeFeetY:0.##} — " +
                $"выше на {ledgeFeetY - предел:0.##} бл");
        return (false,
            $"вплавь на кромку {ledgeFeetY:0.##} не подняться: вода держит ноги на " +
            $"{AfloatInOpenWater(waterLine):0.##}" +
            (double.IsNegativeInfinity(topFullWater)
                ? " (вверх по стенке тут не выползти — вода неполная)"
                : $", по стенке в полной воде выползаю до {topFullWater:0.##}") +
            $", и всход даёт ещё {BodySize.StepUp:0.##} бл — не хватает " +
            $"{ledgeFeetY - предел:0.##} бл");
    }

    /// <summary>
    /// ГДЕ ОКАЖУТСЯ НОГИ ПЛЫВУЩЕГО, КОГДА НАД ВОДОЙ ПОТОЛОК: макушка упирается
    /// в него, и выше тело не поднимет ни плавучесть, ни разгон.
    /// </summary>
    /// <param name="ceilingY">Высота низа потолка, блоков.</param>
    public static double AfloatUnderCeiling(double ceilingY) => ceilingY - BodySize.Height;

    /// <summary>
    /// ДОКУДА ИЗ-ПОД ТАКОГО ПОТОЛКА ВООБЩЕ МОГУТ ПОДНЯТЬСЯ НОГИ, блоков:
    /// висящая в перекрытии макушка плюс всход. Выше не поднимает НИЧТО —
    /// ни плавучесть, ни разгон, ни прыжок (у плывущего его нет, а идущему
    /// вброд потолок подрезает подъём ровно так же).
    ///
    /// ОДНО ЧИСЛО НА ДВА КОНЦА: по нему поиск пути отсекает клетки
    /// (<c>AStarPathFinder</c>), им же тело объясняет отказ вслух
    /// (<see cref="LeaveWater"/>). Разойдись они — планировщик
    /// снова водил бы туда, откуда тело разворачивается.
    /// </summary>
    public static double ReachUnderCeiling(double ceilingY) =>
        AfloatUnderCeiling(ceilingY) + BodySize.StepUp;

    // ЧЕГО ЗДЕСЬ БОЛЬШЕ НЕТ: ОТДЕЛЬНОГО ПРАВИЛА «LeaveWaterUnderCeiling».
    //
    // Оно спрашивало только про потолок, и подпись у него честно говорила:
    // «ЭТО ПРАВИЛО НЕ ЗАПРЕЩАЕТ ОТКРЫТУЮ ВОДУ». Ровно эта дыра и оказалась
    // следующей бедой воды: под открытым небом тело не спрашивало НИЧЕГО, и
    // выход решала выдуманная единица MaxWaterExitHeight. Двух правил про один
    // и тот же подъём теперь нет — есть одно, <see cref="LeaveWater"/>, и обе
    // заставы в нём считаются разом: потолок сверху, плавучесть снизу.

    /// <summary>
    /// ДОКУДА ПОДНИМУТ НОГИ ИДУЩЕГО ВБРОД, блоков. ЭТО ДРУГОЕ ЧИСЛО, ЧЕМ У
    /// ПЛЫВУЩЕГО, И ПУТАТЬ ИХ БЫЛО ЖИВОЙ ОШИБКОЙ.
    ///
    /// ПРИЁМКА 27.08, НАХОДКА 2. Тело спрашивало <see cref="ReachUnderCeiling"/>
    /// и вплавь, И ВБРОД — то есть меряло идущего по дну меркой висящего в
    /// потолке. Но вброд тело стоит НОГАМИ НА ДНЕ, и прыжок у него ЕСТЬ:
    /// <c>PModuleOnGround.Applicable</c> = «OnGround &amp;&amp; !Swimming», а вброд
    /// <c>Swimming</c> ложь. Бот в ручье или в луже собственного подвала
    /// получал отказ «из-под потолка не выбраться» на законный подъём — и
    /// вместе с отказом <c>MarkUnreachableLeg</c>, то есть ОТРАВЛЕНИЕ клетки
    /// маршрута: потом туда не было ходу и с другой стороны.
    ///
    /// ЧТО МЕРЯЕТСЯ ЗДЕСЬ. Ноги на дне (<paramref name="feetY"/>) поднимаются
    /// либо всходом (<see cref="BodySize.StepUp"/>), либо прыжком до
    /// <see cref="ApexRise"/> — а потолок режет прыжок сверху, потому что
    /// макушка упирается в него ровно так же: выше <c>потолок − рост</c> ноги
    /// не поднимет ничто. Всход берётся ВСЕГДА: он работает и упершись
    /// макушкой (<c>HandleSteppingOnBlocks</c> смотрит только на опору под
    /// ногами), поэтому он под минимум не попадает.
    ///
    /// СКАЗАНО ВСЛУХ: прыжок ВБРОД замерен телом на игровой физике и даёт
    /// апекс 1,2483 против 1,2696 на суше — вода сопротивляется. Здесь стоит
    /// сухой <see cref="ApexRise"/>, то есть правило на 0,02 бл щедрее правды.
    /// Не подгоняю числом: второе число апекса нигде не измерено правилом, а
    /// выдумывать его — это закон 6. Цена завышения — редкий отказ тела уже
    /// на месте вместо отказа в плане.
    /// </summary>
    /// <param name="feetY">Высота ног на дне, где тело стоит сейчас.</param>
    /// <param name="ceilingY">Низ потолка над водой.</param>
    public static double ReachWadingUnderCeiling(double feetY, double ceilingY) =>
        Math.Max(feetY + BodySize.StepUp,
                 Math.Min(feetY + ApexRise, AfloatUnderCeiling(ceilingY)));

    /// <summary>
    /// ВЫЙДЕТ ЛИ НА КРОМКУ ИДУЩИЙ ВБРОД. Тот же вопрос, что и у плывущего
    /// (<see cref="LeaveWater"/>), но меркой идущего по дну —
    /// см. <see cref="ReachWadingUnderCeiling"/>, там же и живая цена путаницы.
    /// </summary>
    public static (bool Out, string Why) LeaveWaterWading(
        double ledgeFeetY, double feetY, double ceilingY)
    {
        double reach = ReachWadingUnderCeiling(feetY, ceilingY);
        if (ledgeFeetY <= reach)
            return (true, "");
        return (false,
            $"вброд из-под потолка {ceilingY:0.##} не подняться: ноги на " +
            $"{feetY:0.##}, прыжок макушкой упирается в потолок и выше " +
            $"{reach:0.##} их не поднимет, а кромка на {ledgeFeetY:0.##} — " +
            $"выше на {ledgeFeetY - reach:0.##} бл");
    }
}
/// <summary>
/// Чем берётся подъём: шагом, прыжком или ничем из того, что бот умеет сам
/// (тогда нужна стройка — столб, ступени, лестница).
/// </summary>
public enum RiseKind
{
    /// <summary>Всходим не отрываясь от земли (не выше StepUp).</summary>
    Step,
    /// <summary>Берётся прыжком (не выше апекса).</summary>
    Jump,
    /// <summary>Своими силами не подняться.</summary>
    TooHigh
}
