namespace VsBotKit;

/// <summary>
/// ЗАЧЕМ БОТ ЗАМАХНУЛСЯ. От этого зависит строгость заставы, и различие тут
/// не наше, а заказчика: «ломать крайняя мера же».
/// </summary>
public enum BreakWhy
{
    /// <summary>
    /// РАДИ ПРОХОДА: блоки на столб, ступени наверх, пробитый потолок,
    /// разобранный пол на спуске, расчистка помехи с дороги. Ничего этого
    /// человек не заказывал — бот сам решил, что иначе не пройдёт, и ровно
    /// здесь он трижды выламывал дом.
    /// </summary>
    Way,

    /// <summary>
    /// ПО ДЕЛУ, КОТОРОЕ НАЗНАЧИЛ ЧЕЛОВЕК: дорога, карьер, руда, лес, грядка,
    /// костёр, укрытие. Место и работу назвал он сам, и «не понял, чей это
    /// ствол» посреди лесоповала означало бы невыполненный наряд на ровном
    /// месте. Чужая постройка и заявка сервера не ломаются и тут.
    /// </summary>
    Work
}

/// <summary>
/// ЗАСТАВА МОЛОТКА: ЕДИНСТВЕННЫЙ ОТВЕТ НА ВОПРОС «МОЖНО ЛИ ЭТО ЛОМАТЬ».
///
/// ПОЧЕМУ ОНА ЗАВЕДЕНА ОТДЕЛЬНО. Дорог к молотку в проекте было шесть, а
/// застава стояла на четырёх: проходка и ступени (Tunnel.ClearAsync),
/// смахивание мелочи, пол при спуске, потолок при столбе и добыча блоков на
/// столб спрашивали <c>Tunnel.MayBreak</c>, а дорога, карьер, руда, костёр,
/// грядка, укрытие и поручения били <see cref="Mining.BreakAsync"/> НАПРЯМУЮ,
/// не спросив никого. Три раза подряд заказчик писал одно и то же — «зачем
/// ломать, если был путь» — и три раза чинили одну из дорог.
///
/// ТЕПЕРЬ ДОРОГА ОДНА: застава стоит В САМОМ <see cref="Mining.BreakAsync"/>,
/// то есть в единственном месте проекта, где бот бьёт по блоку. Обойти её
/// нельзя ничем, и второй заставы заводить не надо: те шестеро, что
/// спрашивали заранее, спрашивают ЕЁ ЖЕ — чтобы не идти к блоку зря и чтобы
/// отказ прозвучал до похода, а не после.
///
/// ЗДЕСЬ ТОЛЬКО СБОР ФАКТОВ. Решает <see cref="BlockOwners"/>, и каждый факт
/// настоящий, ни одного выдуманного списка кодов (правило 6):
///   • «сам положил» — своя память временных лесов (<see cref="TempBlocks"/>);
///   • «чужое место» — заявки сервера и приметы (<see cref="Claims"/>);
///   • «двор хозяина» — дом и склад, отмеченные им в окне управления;
///   • «это делают руками» — есть ли РЕЦЕПТ СЕТКИ в реестре сервера;
///   • материал и вкладка «terrain» — реестр блоков сервера;
///   • «мусор» — <c>Block.Replaceable</c> оттуда же;
///   • блок-сущности вокруг (сундук, дверь, табличка, кровать) — сам мир.
/// </summary>
public sealed class BreakGuard
{
    private readonly BotContext ctx;

    public BreakGuard(BotContext ctx) => this.ctx = ctx;

    /// <summary>
    /// ИМЯ РУЧКИ, КОТОРУЮ НАДО ПОВЕРНУТЬ, ЧТОБЫ СНЯТЬ ОХРАНУ ДВОРА.
    ///
    /// СТРОКОЙ, А НЕ ЧЕРЕЗ <c>nameof</c>, ПОТОМУ ЧТО БИБЛИОТЕКА ПРО РОЛИ НЕ
    /// ЗНАЕТ (закон 1): <see cref="LivingRole"/> живёт тут же, но застава
    /// одинаково служит и чужой роли, написанной хозяином бота. Связи с
    /// настоящим свойством у строки нет никакой — потому её и стережёт отдельный
    /// караул <c>ИмяРучкиВОтказеНастоящееTests</c>, который сверяет каждое такое
    /// имя с ЖИВЫМ списком ручек всех ролей.
    ///
    /// ДОЛГ ЗАКРЫТ 31.08: ручка <see cref="LivingRole.ДомИСкладБерегуВРадиусе"/>
    /// заведена, донесена до <see cref="KeepRadius"/> и названа во всех шести
    /// пресетах. До того отказ «радиус задаёт настройка „ДомИСкладБерегуВРадиусе“»
    /// посылал человека к настройке, которой он в окне не находил.
    /// </summary>
    public const string РучкаБерегуДомИСклад = "ДомИСкладБерегуВРадиусе";

    /// <summary>
    /// Ломать ли чужую постройку БЕЗ заявки ради выхода. Механизм, решает роль
    /// (ручка «ЛоматьЧужоеРадиВыхода»). Заводское — не ломать.
    /// </summary>
    public bool BreakForeignToGetOut { get; set; }

    /// <summary>
    /// В скольких блоках вокруг искать приметы постройки — сундуки, двери,
    /// таблички, кровати, печи. Меньше — бот полезет сквозь стену сарая;
    /// больше — откажется копать руду под чужим погребом.
    ///
    /// ЧИСЛО ЗДЕСЬ НЕ СВОЁ: его называет роль ручкой
    /// «ПриметыПостройкиИскатьВРадиусе» и доносит через <c>Tunnel</c>.
    /// Заводские три стоят и тут — стендам и чужому коду, которые роль не
    /// собирают.
    /// </summary>
    public int BuiltAroundRadius { get; set; } = 3;

    /// <summary>
    /// НАСКОЛЬКО ВОКРУГ ОТМЕЧЕННЫХ ДОМА И СКЛАДА НИЧЕГО НЕ ТРОГАТЬ.
    ///
    /// Шесть — это его дом: отметки (62, 122, 255) и (62, 112, 255), дверь в
    /// (61, 112, 252), то есть три блока от складской отметки. Куб со стороной
    /// 12 накрывает и стену, и пол, в которые бот бил 23.08. Ноль — «беречь
    /// только по прочим приметам», законный выбор человека, который поставил
    /// отметку посреди карьера.
    ///
    /// Ручка роли — см. <see cref="РучкаБерегуДомИСклад"/>.
    /// </summary>
    public int KeepRadius { get; set; } = 6;

    /// <summary>
    /// МОЖНО ЛИ СЛОМАТЬ ЭТУ КЛЕТКУ — вопрос мира и памяти, ответ правила.
    /// Второй копии решения тут нет нарочно: всё, что ниже, — сбор фактов.
    /// </summary>
    public (bool May, string Why) MayBreak(BlockPos cell, BreakWhy why = BreakWhy.Work)
    {
        string code = ctx.World.GetBlockCode(cell) ?? "";
        var place = ctx.Claims?.Inside(cell);
        var (who, whose) = BlockOwners.Whose(
            code,
            ctx.Temp?.Mine(cell) == true,
            place?.Why ?? "",
            ctx.World.MaterialOf(code),
            TerrainByGame(code),
            BuiltThingsAround(cell),
            MadeByHand(code));
        return BlockOwners.MayBreak(who, whose, why, BreakForeignToGetOut,
            place?.Kind == ForeignKind.Claim, OwnersPlace(cell), Litter(cell));
    }

    /// <summary>
    /// Игра сама объявляет этот блок частью нетронутого мира — по вкладке
    /// творческого инвентаря из реестра сервера. Реестр ещё не пришёл — не
    /// объявляет ничего, и правило решит по материалу.
    /// </summary>
    private bool TerrainByGame(string code) =>
        ctx.World.GetGameBlockByCode(code) is { BlockId: > 0 } block &&
        block.CreativeInventoryTabs?.Contains(BlockOwners.TerrainTab) == true;

    /// <summary>
    /// ИГРА САМА ГОВОРИТ, ЧТО ТАКОЕ ДЕЛАЮТ РУКАМИ: у блока есть рецепт сетки.
    ///
    /// Спрашиваем реестр рецептов, который прислал сервер (12 995 штук на мире
    /// заказчика, <see cref="Crafting.RecipesFor"/>), а не список кодов: это и
    /// есть та самая разница, на которой проект горел трижды. Реестр не пришёл
    /// — ответа нет, и правило решает по прочим приметам, как решало раньше.
    /// </summary>
    private bool MadeByHand(string code) =>
        code.Length > 0 && ctx.Crafting is { Ready: true } crafting &&
        crafting.RecipesFor(code).Count > 0;

    /// <summary>
    /// Игра сама зовёт этот блок заменяемым: любой поставленный блок его
    /// затирает. Так помечены снег, трава, цветы — то, что живой игрок сметает
    /// не глядя и что не бывает ничьей постройкой.
    /// </summary>
    private bool Litter(BlockPos cell) =>
        ctx.World.ReplaceableOf(cell.X, cell.Y, cell.Z) >= WorldModel.ReplacedByPlacing;

    /// <summary>
    /// Сколько вокруг клетки поставленных человеком вещей — дверей, сундуков,
    /// табличек, кроватей, печей. В породе такого не бывает.
    ///
    /// СПРАШИВАЕМ РЕЕСТР ИГРЫ, А НЕ СПИСОК ПРИСЛАННЫХ БЛОК-СУЩНОСТЕЙ, И ЭТО
    /// НАХОДКА СТЕНДА, А НЕ ВКУС. Здесь стоял <c>BlockEntitiesIn</c>, и он
    /// давал ноль ровно там, где нужен был ответ: список присланных
    /// блок-сущностей приходит с чанком ОТДЕЛЬНО от блоков и вдобавок нарочно
    /// просеивается честным зрением (читать надпись сквозь стену живой игрок
    /// не может). В живом случае 23.08 бот стоял В ДВЕРЯХ дома заказчика — и
    /// двери этой застава не видела, а стену выломала.
    ///
    /// Подглядыванием это не стало: спрашивается ТИП блока, а код блока бот
    /// читает и так. «Дверь ли передо мной» видно с порога.
    /// </summary>
    private int BuiltThingsAround(BlockPos cell)
    {
        int r = Math.Max(0, BuiltAroundRadius);
        return ctx.World.PlacedThingsIn(
            new BlockPos(cell.X - r, cell.Y - r, cell.Z - r),
            new BlockPos(cell.X + r, cell.Y + r, cell.Z + r));
    }

    /// <summary>
    /// ОТМЕТКИ ХОЗЯИНА — ДОМ И СКЛАД. Берём их там, куда их и доносит роль:
    /// <see cref="Depot.Home"/> (та же клетка, что у <c>Shelter.Home</c>, —
    /// см. <c>LivingRole.ОтнестиДомБоту</c>) и <see cref="Depot.Chests"/> (точка
    /// склада из окна управления). Своего понятия «дом» здесь не заводится:
    /// второе такое понятие и означало бы, что отметка в окне бережёт не всё.
    /// </summary>
    private string OwnersPlace(BlockPos cell) =>
        BlockOwners.OwnersPlace(Marks(), cell.X, cell.Y, cell.Z, KeepRadius);

    private IEnumerable<(string Name, int X, int Y, int Z)> Marks()
    {
        if (ctx.Depot is not { } depot)
            yield break;
        if (depot.Home is { } home)
            yield return ("дом", home.X, home.Y, home.Z);
        foreach (var chest in depot.Chests)
            yield return ("склад", chest.X, chest.Y, chest.Z);
    }
}
