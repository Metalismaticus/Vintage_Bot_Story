namespace VsBotKit;

/// <summary>
/// «Не оставляй своё добро на земле».
///
/// Бот ломает блок — добыча падает на землю отдельной вещью и лежит, пока по
/// ней не пройти ногами. Живьём это выглядело так: отправил копать карьер,
/// бот честно сломал девять клеток и вернулся с пустыми руками, а в отчёте
/// стояло «получено: ничего».
///
/// Способность разбирает пометки, которые оставляет <see cref="Mining"/>:
/// сломали — запомнили место, освободилось тело — сходили и подобрали.
/// Она НАМЕРЕННО обычной важности: голод, бой и холод её перебивают, и это
/// правильно — добыча полежит, а бот нет.
///
/// Роль решает только «когда и что»: радиус, время, брать ли чужое, что
/// пропускать. Механика — в <see cref="Pickup"/>, здесь её нет.
/// </summary>
public class BehaviorPickUpDrops : BotBehavior
{
    private readonly BotContext ctx;
    private DateTime nextTry = DateTime.MinValue;

    public BehaviorPickUpDrops(BotContext ctx)
    {
        this.ctx = ctx;
        // Отказ и отбой безнадёги говорят ТЕМ ЖЕ голосом, что и прочие отказы
        // подбора: второго события «бот не пошёл» здесь заводить незачем
        Далеко.OnSay += why => OnRefused?.Invoke(why);
    }

    /// <summary>Подбирать вообще: роль может выключить (лавочнику это ни к чему).</summary>
    public bool On { get; set; } = true;

    /// <summary>Как далеко отходить за своей добычей.</summary>
    public double Radius { get; set; } = 8;

    /// <summary>
    /// ДАЛЬШЕ ЭТОГО ЗА ПОМЕЧЕННЫМ МЕСТОМ НЕ ХОДИТЬ, блоков (0 — предела нет).
    /// Решает роль (ручка «ЗаСвоейДобычейНеДальше»).
    ///
    /// ЗАЧЕМ ЗАВЕДЕНО — заказ человека, дословно: «после бегает домой (установка
    /// в безделье дом), но возвращается, но зачем непонятно, баг». Живой случай
    /// (журнал 17.08, 23:54–23:57) выглядел так, трижды подряд:
    ///   23:54:53 [укрытие] дома, дверь (512061, 112, 512252) закрыта
    ///   23:54:53 я дома
    ///   23:54:54 [движение] дорога: 4 точек до (512042, 110, 512237)
    ///   23:54:59 [движение] точки кончились, а по высоте не дошёл
    /// Секунда между «я дома» и уходом за двадцать шесть блоков — и ни слова о
    /// том, куда и зачем.
    ///
    /// Уводили бота ПОМЕТКИ: дорога наломала клеток на своём конце, каждая
    /// сломанная клетка легла пометкой (<see cref="Pickup.Note"/>), а
    /// <see cref="Pickup.CollectAroundAsync"/> идёт к пометке БЕЗ ВСЯКОГО
    /// ПРЕДЕЛА — <see cref="Radius"/> мерит осмотр ВОКРУГ места, а не дорогу к
    /// нему. Пометок копится до 64, разбираются они по одной, и каждая стоила
    /// похода через полкарты; вернувшись, бот снова бездельничал минуту, снова
    /// шёл домой — и так весь вечер.
    ///
    /// Шестнадцать блоков — вдвое больше осмотра: своё, выломанное только что,
    /// лежит рядом, а за дальним придёт наряд или разгрузка, у которых на это
    /// есть маршрут и время.
    /// </summary>
    public double WalkLimit { get; set; } = 16;

    /// <summary>Сколько времени отводить на один заход.</summary>
    public double MaxSeconds { get; set; } = 25;

    /// <summary>Пауза между заходами: иначе бот мельтешит вместо дела.</summary>
    public double CooldownSeconds { get; set; } = 3;

    /// <summary>
    /// Брать только своё: помеченные места и выпавшее из нас. Чужое
    /// брошенное — не наше дело, пока роль не разрешит.
    /// </summary>
    public bool OnlyOwnHarvest { get; set; } = true;

    /// <summary>Чего не подбирать (коды или части кодов) — булыжник, грязь, гниль.</summary>
    public List<string> Ignore { get; } = [];

    /// <summary>Что вообще брать; null — всё, кроме <see cref="Ignore"/>.</summary>
    public Func<string, bool>? Accept { get; set; }

    /// <summary>Сходили за добычей (итог подбора).</summary>
    public event Action<PickupResult>? OnCollected;

    /// <summary>
    /// ПОШЁЛ ЗА СВОЕЙ ДОБЫЧЕЙ — куда и сколько до неё. Говорится ДО первого шага
    /// и всегда.
    ///
    /// Молчаливый уход и есть та беда, на которую жаловался человек: «я дома», а
    /// через секунду бот за тридцать блоков и ни строчки о том, зачем. Кто увёл
    /// — было видно только по координатам цели в строке движения, и разбирать
    /// это приходилось по журналу вручную.
    /// </summary>
    public event Action<BlockPos, double>? OnGoing;

    /// <summary>Не пошёл за добычей — с причиной (далеко, тела не дали).</summary>
    public event Action<string>? OnRefused;

    /// <summary>
    /// ЗА КАКИМИ ПОМЕТКАМИ БОЛЬШЕ НЕ ХОДИМ, ПОКА НЕ ПОДОЙДЁМ БЛИЖЕ.
    ///
    /// Механизм общий (<see cref="VsBotKit.Hopeless{TKey}"/>), своего счётчика
    /// здесь нет: он сказал бы «до места 30 бл, а дальше 16 я не хожу» каждые
    /// три секунды — ровно тот шум, от которого в этом проекте уже лечили и
    /// голод, и разломы, и тушу дрифтера.
    /// </summary>
    public Hopeless<BlockPos> Далеко { get; } = new("за добычей не иду");

    public override async Task<bool> TickAsync(CancellationToken ct)
    {
        if (!On || ctx.Pickup is not { } pickup)
            return false;
        if (DateTime.UtcNow < nextTry)
            return false;

        // Мёртвый не подбирает — это правило самой игры, а не наша
        // осторожность: сервер не отдаёт вещи мёртвым
        if (ctx.Self.Health is { } hp && hp <= 0)
            return false;

        // Есть ли ради чего идти: либо помеченное место, либо вещь на виду
        var seen = pickup.Around(Radius, Want).Where(d => !OnlyOwnHarvest || d.Mine || pickup.HasNotes).ToList();
        if (seen.Count == 0 && !pickup.HasNotes)
            return false;

        nextTry = DateTime.UtcNow.AddSeconds(CooldownSeconds);

        PickupResult got;
        if (seen.Count > 0)
        {
            got = await pickup.CollectAsync(Radius, Want, onlyMine: false,
                maxSeconds: MaxSeconds, ct: ct, owner: "своя добыча");
        }
        else if (pickup.NextNote() is { } spot)
        {
            // ДАЛЕКО — НЕ ИДУ, И ГОВОРЮ ОБ ЭТОМ. Здесь предела не было вовсе:
            // Radius мерит осмотр ВОКРУГ места, а дорога К НЕМУ не мерилась
            // ничем, и пометка на другом конце дороги уводила бота из дома
            // сразу после «я дома» (разбор с журналом — у WalkLimit).
            // Пометку НЕ ЗАБЫВАЕМ: бот к ней ещё вернётся работой, и тогда
            // выпавшее подберётся само
            double далеко = ctx.Self.Position is { } где
                ? Depot.Apart(spot, new BlockPos((int)Math.Floor(где.X),
                                                 (int)Math.Floor(где.Y), (int)Math.Floor(где.Z)))
                : 0;   // где стою — не знаю; не отказывать же из-за этого
            if (Pickup.TooFarToGo("помеченного места", далеко, WalkLimit) is { } почему)
            {
                // Спрашиваем «сдались ли уже» ДО того, как сдаться: расстояние в
                // строке тикает на каждом шаге, и Alarm внутри безнадёги принял
                // бы «26,3 бл» за новость после «26,1 бл» — ровно тем эта же
                // беда и вылезла у добычи с убитых (восемнадцать строк за семь
                // секунд, журнал 17.08)
                if (!Далеко.Given(spot))
                    Далеко.GiveUp(spot, почему + " — пометку держу, подберу, когда окажусь рядом");
                return false;
            }
            // Подошли ближе — отбой вслух: иначе человек не поймёт, почему бот
            // «вдруг» пошёл за тем, за чем только что отказывался
            Далеко.TryAgain(spot, "оказался рядом — иду за добычей");

            OnGoing?.Invoke(spot, далеко);
            got = await pickup.CollectAroundAsync(spot, Radius, Want,
                maxSeconds: MaxSeconds, ct: ct, owner: "своя добыча");
            // Место разобрано (или там уже пусто) — не возвращаться к нему.
            // А НЕ ДОШЛИ ВОВСЕ — ПОМЕТКА ОСТАЁТСЯ: судит об этом сам подбор
            // (Pickup.PlaceHandled), потому что пометки — его имущество, и
            // потому что живьём безусловное забывание выедало память о
            // сломанных блоках, пока тело держал наряд
            if (Pickup.PlaceHandled(got.Stop))
                pickup.ForgetNote(spot);
        }
        else
        {
            return false;
        }

        if (got.Items > 0 || got.Stop == PickupStop.BagsFull)
            OnCollected?.Invoke(got);
        // Сумки полны — ходить дальше бессмысленно, пусть роль разгружает
        if (got.Stop == PickupStop.BagsFull)
            nextTry = DateTime.UtcNow.AddSeconds(Math.Max(CooldownSeconds, 20));
        return got.Items > 0;
    }

    /// <summary>
    /// БЕРЁМ ЛИ МЫ ЭТО — вся политика роли одной чистой функцией: сперва запрет
    /// (<see cref="Ignore"/>), потом разрешение (<see cref="Accept"/>), а по
    /// умолчанию берём всё.
    ///
    /// Спрашивать её вправе и снаружи, и это не украшение: приёмка вырезала
    /// строку с <see cref="Ignore"/> целиком, и ни один из 1395 тестов не упал —
    /// проверка «роль может запретить ненужное» на деле лишь клала слово
    /// в список и тут же читала его оттуда же. Пока правило нельзя спросить,
    /// его нельзя и проверить.
    /// </summary>
    public bool Want(string code)
    {
        if (Ignore.Any(i => code.Contains(i, StringComparison.OrdinalIgnoreCase)))
            return false;
        return Accept?.Invoke(code) ?? true;
    }
}
