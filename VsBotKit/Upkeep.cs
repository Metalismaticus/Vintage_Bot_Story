namespace VsBotKit;

/// <summary>
/// ОДНА ПАРА «ЧЕМ ПОЛЬЗУЮСЬ → ЧТО НА ЭТО ТРАЧУ».
/// </summary>
/// <param name="Spend">
/// Род расходника: «arrow», «torch», «bandage». Род, а не полный код: в игре
/// стрела бывает четырнадцати материалов (arrow-crude … arrow-steel), и просить
/// их по одному значило бы завести список, которого нам никто не давал.
/// </param>
/// <param name="Consumer">
/// Род того, ЧЕМ это тратят: «bow». Пусто — повода-предмета нет, и единственным
/// поводом остаётся сам расход.
///
/// ЗАЧЕМ ОН ВООБЩЕ НУЖЕН — РАДИ ХОЛОДНОГО СТАРТА. Пока бот не выстрелил ни
/// разу, расход равен нулю, и по одному расходу стрелы не понадобились бы
/// никогда: чтобы начать тратить, их надо сперва иметь. Лук в сумке — это и
/// есть то, что живой игрок видит на своём поясе, когда решает «надо бы
/// стрел».
/// </param>
public sealed record UpkeepPair(string Spend, string Consumer)
{
    public override string ToString() =>
        Consumer.Length > 0 ? $"{Spend} к {Consumer}" : Spend;
}

/// <summary>
/// ЧТО РЕШЕНО ДЕРЖАТЬ ПРЯМО СЕЙЧАС И ПОЧЕМУ ИМЕННО СТОЛЬКО.
///
/// «Почему» здесь — не про то, почему НЕ ХВАТАЕТ (это знает безнадёга запасов,
/// см. <see cref="StockNeed.Why"/>), а про то, откуда взялось САМО ЧИСЛО. Две
/// разные правды, и путать их нельзя: человек, увидевший «arrow: 3/20»,
/// спрашивает и «почему двадцать», и «почему только три».
/// </summary>
public sealed record UpkeepWant(string Code, int Want, int Spent, bool ConsumerAtHand, string Why)
{
    public override string ToString() => $"{Code} ×{Want}: {Why}";
}

/// <summary>
/// ЧЕМ ПОЛЬЗУЮСЬ — ТО И ДЕРЖУ ПРО ЗАПАС.
///
/// ЗАКАЗ 26.08, СЛОВА ЗАКАЗЧИКА ДОСЛОВНО: «также больше бы логики, чтобы бот
/// сам понимал чего ему не достает и крафтил, например стрелы».
///
/// ЧЕГО НЕ ХВАТАЛО. Список требований (<see cref="Stock.Wants"/>) был
/// НЕПОДВИЖНЫМ: роль один раз говорила «держи 64 лестницы, 16 факелов», и
/// дальше это число не зависело ни от чего. Для кирки так и надо — она одна и
/// не кончается. Для расходника это неправда в обе стороны сразу: бот, который
/// ни разу не стрелял, таскает стопку стрел «на всякий случай» (заказчик уже
/// жаловался на метания за припасами), а бот, который отстреливает по сорок
/// штук за вылазку, ходит с шестнадцатью и встаёт посреди охоты.
///
/// ПРАВИЛО ОБЩЕЕ, А НЕ ПРО СТРЕЛЫ. Пара «потребитель → расходник» задаётся
/// ролью строкой: стрелы к луку, факелы к тьме, бинты к ранам, лестницы к
/// спуску. Стрелы — ПЕРВЫЙ потребитель правила, а не единственный, и ничего
/// про стрелы в этом файле не написано.
///
/// КАК МЕРЯЕТСЯ РАСХОД — ПО СУМКЕ, А НЕ ПО ДОКЛАДАМ СПОСОБНОСТЕЙ. Это нарочно
/// и это главное решение здесь. Доклад («я выстрелил») пришлось бы заводить в
/// каждой способности отдельно, и каждая новая забывала бы о нём — ровно так в
/// этом проекте трижды находилось правило, которое верное, а спросить его
/// некому. Убыль в сумке видна ОДНА НА ВСЕХ: и выстрел, и поставленный факел,
/// и наложенный бинт, и повешенная лестница выглядят одинаково.
///
/// ЧТО УБЫЛЬЮ НЕ СЧИТАЕТСЯ, И ЭТО НЕ МЕЛОЧЬ. Сумка худеет ещё от двух вещей, и
/// обе к расходу отношения не имеют:
///   • вещь ПЕРЕЛОЖЕНА наружу — в сундук, на прилавок, на землю, в костёр:
///     оттуда же её и заберут;
///   • умер — вещи остались на месте смерти, сумка обнулилась целиком.
/// Смерть сбрасывает отсчёт целиком, а переносы зачитываются ОДНОЙ ДВЕРЬЮ —
/// <c>Actions.OnItemMoved</c>. Не сделай мы этого, один рейс на склад
/// прочитался бы как «истратил стопку стрел», и бот пошёл бы делать ещё
/// стопку — то самое метание, ради устранения которого всё и писалось.
///
/// ПОЧЕМУ ДВЕРЬ ОДНА, А НЕ ПО ВЫЗОВУ НА КАЖДЫЙ ПЕРЕНОС. Приёмка проверила
/// подменой: первая сдача зачитывала перенос ДВУМЯ вызовами руками (укладка в
/// хранилище и выброс), объявив, что дверей всего три. Дверей оказалось СЕМЬ —
/// добавились «!брось» и кнопка окна, перекладка в чужой сундук, выкладка
/// товара лавочником, закладка в костёр и материал в сетку крафта, — и каждая
/// незакрытая читалась как расход. Восьмую забыли бы точно так же. Все они без
/// исключения ходят через <c>Actions.MoveItemAsync</c>, и подписка стоит там.
///
/// СЕТКА КРАФТА ЗАЧЁТОМ НЕ СЧИТАЕТСЯ НАРОЧНО, и это не недосмотр: материал,
/// ушедший в крафт, ИСТРАЧЕН по-настоящему — палки, из которых собрали лестницу,
/// назад не вернутся. Своя опись бота (та, что кончается на его uid) остаётся
/// «своей», кроме земли под ногами: туда вещи и выбрасывают.
///
/// Класс — МЕХАНИЗМ. Что и подо что держать, на сколько минут расхода и сколько
/// держать до первого расхода — ручки роли («ЗапасПоРасходу»,
/// «ЗапасНаМинутРасхода», «ЗапасНаПервыйРаз»). Где брать недостающее, здесь не
/// решается ни одним словом: это <see cref="Supply"/>, и второй такой цепочки в
/// проекте нет.
/// </summary>
public class Upkeep
{
    private readonly BotContext ctx;

    public Upkeep(BotContext ctx)
    {
        this.ctx = ctx;

        // ТРЕБОВАНИЯ ПОДНОВЛЯЮТСЯ ПЕРЕД КАЖДЫМ ОПРОСОМ ЗАПАСОВ, а не по
        // таймеру. Причина простая: своего тика у запаса по расходу нет и быть
        // не должно — число нужно ровно тогда, когда его кто-то читает (окно
        // управления, «!запасы», сборы, пополнение). Заведи мы свой тик, он
        // либо отставал бы от чтения, либо крутился впустую всю ночь
        ctx.Stock.BeforeCheck += Refresh;

        // СМЕРТЬ ОБНУЛЯЕТ СУМКУ ЦЕЛИКОМ. Прочитать это как расход значит
        // насчитать «истратил 64 стрелы за минуту» и погнать бота делать
        // стопку — при том что стрелы целые и лежат на месте смерти.
        //
        // ЭТА СТРОКА НЕ ДУБЛЬ ВЕРХНЕЙ ЗАЩИТЫ «вне мира не считаем»
        // (Пересчитать: вМире = Joined && !IsDead), и это разобрано 26.08.
        // Та защита работает, ПОКА БОТ ЛЕЖИТ, а лежит он секунды: встаёт сам
        // через SelfState.RespawnDelaySeconds = 2,5…6 с. Опрос запасов в это
        // окно может не попасть ни разу — и тогда первый же опрос ПОСЛЕ
        // возрождения видит «в мире, а сумка пуста» и записывает всё в расход.
        // Стенд на это — UpkeepTests.ЖИВОЙ_ПУТЬ_возродившийся_бот_не_считает_
        // потерянное_расходом; сними строку — он покраснеет (проверено
        // подменой), а соседний, где бот остаётся лежать, останется зелёным.
        ctx.Self.OnDeath += Resync;

        // НОВОЕ СОЕДИНЕНИЕ — ВОЗМОЖНО, ДРУГОЙ МИР. Вчерашний расход снят на
        // прошлом сервере, а полная стопка — из прошлого реестра
        ctx.Bot.OnSessionReset += () =>
        {
            Resync();
            spent.Clear();
            caps.Clear();
        };

        // РЕЕСТР ПРИШЁЛ — ПЕРЕСПРОСИТЬ ПРО ПОЛНУЮ СТОПКУ. До него на всякий род
        // честно отвечается «не знаю», и запомненное «не знаю» пережило бы вход
        // в мир: бот держал бы «первую горсть» вместо настоящей стопки всю
        // смену. Тем же порядком переспрашивают про инструменты запасы
        // (Stock.RetryToolsOnRegistry) — и по той же причине
        ctx.World.OnBlockRegistryReady += caps.Clear;

        // ЕДИНСТВЕННАЯ ДВЕРЬ ПЕРЕНОСА — см. Слушать(). Подписываемся ПОСЛЕДНИМИ:
        // до этой строки Moved никем не зовётся, и порядок в конструкторе
        // читается сверху вниз как «что мы слушаем»
        Слушать();
    }

    public event Action<string>? OnLog;

    /// <summary>
    /// ЗА СКОЛЬКО МИНУТ РАСХОДА ДЕРЖАТЬ ЗАПАС.
    ///
    /// Число простое до буквальности: «сколько трачу за полчаса — столько и
    /// ношу». Другого смысла в нём нет и не должно быть — человек, крутящий
    /// ползунок, обязан понимать ответ бота без калькулятора.
    ///
    /// Отдельного «окна измерения» здесь нарочно НЕТ: оно и есть это же число.
    /// Заведи мы второе — «меряю за час, запасаю на полчаса», — человеку
    /// пришлось бы держать в голове два срока, а разойтись они могли бы молча.
    /// </summary>
    public double WindowMinutes { get; set; } = 30;

    /// <summary>
    /// СКОЛЬКО ДЕРЖАТЬ, ПОКА НЕ ТРАТИЛ НИ РАЗУ.
    ///
    /// Без этого числа правило не заводится вовсе: чтобы начать тратить стрелы,
    /// их надо сперва иметь, а расход у пустого колчана нулевой. Это и есть та
    /// самая «первая горсть», с которой живой игрок уходит из дома.
    ///
    /// Оно же служит НИЖНИМ КРАЕМ и потом: истратил бот за полчаса две стрелы —
    /// это не повод ходить с двумя.
    /// </summary>
    public int FirstTime { get; set; } = 16;

    /// <summary>Что и подо что держим (пусто — правило выключено).</summary>
    public IReadOnlyList<UpkeepPair> Pairs => pairs;

    /// <summary>
    /// Что решено держать в последний опрос и почему именно столько. Для окна
    /// управления и для «!запасы»: число, взявшееся ниоткуда, человек считает
    /// поломкой.
    /// </summary>
    public IReadOnlyList<UpkeepWant> Now
    {
        // СНИМОК, А НЕ ЖИВОЙ СПИСОК. Читают его человек («!запасы») и окно —
        // оба с чужих потоков, а пересчёт этот список чистит и набивает заново
        // (now.Clear/now.Add). Перебор во время чистки — это исключение прямо
        // посреди ответа человеку
        get { lock (gate) return now.ToArray(); }
    }

    private readonly List<UpkeepPair> pairs = [];
    private readonly List<UpkeepWant> now = [];

    /// <summary>Сколько было в сумке при прошлом взгляде: род → штук.</summary>
    private readonly Dictionary<string, int> seen = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// ЗАЧЁТ ПЕРЕНОСА: столько штук ушло из сумки НЕ В РАСХОД и убылью не
    /// считается. Копится до ближайшего взгляда и там же гасится.
    /// </summary>
    private readonly Dictionary<string, int> moved = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>Когда и сколько истрачено на самом деле.</summary>
    private readonly List<(DateTime When, string Code, int Count)> spent = [];

    /// <summary>Полная стопка по реестру: род → штук (0 — реестр не знает).</summary>
    private readonly Dictionary<string, int> caps = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// ЧТО МЫ САМИ ПОСЛЕДНИЙ РАЗ ПОСТАВИЛИ: род → число.
    ///
    /// Это и есть весь наш признак «требование моё». Держать вместо него просто
    /// список занятых родов было НЕДОСТАТОЧНО, и стенд это поймал: кто заведёт
    /// требование первым, зависит от порядка, в котором роль доносит ручки, а
    /// он не наш и меняться будет. Число же сравнивается в любом порядке: стоит
    /// в запасах не то, что писали мы, — значит писал кто-то ещё.
    /// </summary>
    private readonly Dictionary<string, int> mine = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// ПЕРВЫЙ ВЗГЛЯД ПОСЛЕ СМЕРТИ И ВХОДА В МИР НЕ СЧИТАЕТ УБЫЛИ. Ставится
    /// событием, гасится ближайшим опросом.
    /// </summary>
    private bool resync = true;

    private bool refreshing;

    /// <summary>
    /// ЗАМОК НА ВСЁ СОСТОЯНИЕ ЗАПАСА ПО РАСХОДУ.
    ///
    /// НЕ ПЕРЕСТРАХОВКА, А НАХОДКА ПРИЁМКИ. Пересчёт зовётся из
    /// <c>Stock.Check()</c> (через <c>BeforeCheck</c>), а <c>Check()</c> зовёт
    /// не только поток бота: окно управления просит <c>/api/state</c> КАЖДЫЕ
    /// ДВЕ СЕКУНДЫ, и обслуживает запрос отдельный поток пула
    /// (<c>MiniHttp</c>: <c>Task.Run(() =&gt; ServeAsync(...))</c>, без всякой
    /// передачи в цикл бота). Чат-команда «!запасы» приходит третьим потоком.
    /// Заказчик запускает бота с открытым окном — то есть это самая обычная
    /// обстановка, а не редкая.
    ///
    /// Пока замка не было, поток панели писал <c>spent</c>, <c>moved</c>,
    /// <c>now</c> и требования запасов ровно тогда, когда поток бота их читал.
    /// Сторож <c>refreshing</c> тут не спасал и не мог: он про рекурсию, а не
    /// про потоки, и его собственный комментарий это честно говорит.
    /// </summary>
    private readonly object gate = new();

    /// <summary>Про какое столкновение требований уже сказано (чтобы не повторяться).</summary>
    private readonly HashSet<string> спорныеСказаны = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>Что говорили в прошлый раз: род → строка (жалуемся на ПЕРЕМЕНУ).</summary>
    private readonly Dictionary<string, string> сказано = new(StringComparer.OrdinalIgnoreCase);

    // ---------------- ЧИСТЫЕ ПРАВИЛА ----------------

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: разобрать человеческую строку «arrow к bow, torch».
    ///
    /// Через запятую — пары, внутри пары слово «к» отделяет расходник от того,
    /// чем его тратят. Без «к» — расходник сам себе повод (то есть повод только
    /// один: он и вправду тратится).
    ///
    /// ПОЧЕМУ КОДЫ, А НЕ РУССКИЕ СЛОВА. У инструментов русское слово переводится
    /// в вид из игрового перечисления (<see cref="Stock.WhatToolIs"/>) — игра
    /// сама знает, что «кирка» это Pickaxe. Для стрел и факелов такого
    /// перечисления в игре нет, и всякий словарь «стрелы = arrow» был бы
    /// ВЫДУМАННЫМ СПИСКОМ. Коды человек и так видит в окне («Запасы: ladder
    /// 8/64») и в пресетах («pickaxe, shovel, axe, torch»).
    /// </summary>
    public static IReadOnlyList<UpkeepPair> Parse(string? text)
    {
        var список = new List<UpkeepPair>();
        foreach (string кусок in Stock.ParseList(text))
        {
            // Разделитель — отдельное слово «к», а не буква: «arrowк bow» или
            // «black к» человек пишет опиской, и молча понять его по-своему
            // хуже, чем не понять вовсе
            var слова = кусок.Split([' ', '\t'], StringSplitOptions.RemoveEmptyEntries);
            int где = Array.FindIndex(слова, с => с is "к" or "К");
            string расходник = где < 0
                ? string.Join("", слова)
                : string.Join("", слова[..где]);
            string потребитель = где < 0 || где + 1 >= слова.Length
                ? ""
                : string.Join("", слова[(где + 1)..]);
            if (расходник.Length == 0)
                continue;
            // Один род — одна строка: две записи про стрелы означали бы два
            // голоса на одно требование
            if (список.Any(p => string.Equals(p.Spend, расходник, StringComparison.OrdinalIgnoreCase)))
                continue;
            список.Add(new UpkeepPair(расходник, потребитель));
        }
        return список;
    }

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: есть ли вообще повод держать это про запас.
    ///
    /// Два повода, и любого хватает: вещь, которой это тратят, лежит в сумке
    /// (взял лук — понадобятся стрелы) ИЛИ расход уже был (стрелял, значит
    /// стреляю). Ни одного — требование СНИМАЕТСЯ целиком, а не опускается до
    /// минимума: бот без лука не должен носить стрелы вовсе, иначе он хомяк.
    /// </summary>
    public static bool Needed(bool consumerAtHand, int spentInWindow) =>
        consumerAtHand || spentInWindow > 0;

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: СКОЛЬКО ДЕРЖАТЬ.
    ///
    /// «Столько, сколько трачу» — но не меньше горсти на первый раз и не больше
    /// полной стопки. Верхний край не украшение: без него бот, отстрелявший за
    /// вылазку три стопки, потребовал бы три стопки, а это уже не запас, а
    /// склад на спине.
    /// </summary>
    /// <param name="spentInWindow">сколько истрачено за срок запаса</param>
    /// <param name="first">сколько держать до первого расхода (нижний край)</param>
    /// <param name="cap">полная стопка по реестру (верхний край)</param>
    public static int Reserve(int spentInWindow, int first, int cap)
    {
        int потолок = Math.Max(1, cap);
        int снизу = Math.Clamp(first, 0, потолок);
        return Math.Clamp(Math.Max(spentInWindow, снизу), 0, потолок);
    }

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: откуда взялось число — словами человека.
    ///
    /// Отдельной функцией и рядом с самим правилом нарочно: объяснение, которое
    /// живёт в другом файле, расходится с правилом в первый же вечер.
    /// </summary>
    /// <param name="capIsStack">
    /// Потолок и правда назван реестром как полная стопка. Ложь — реестр рода
    /// не знает, и потолком служит «ЗапасНаПервыйРаз»: называть это «полной
    /// стопкой» значит соврать человеку числом.
    /// </param>
    public static string Why(int want, int spentInWindow, double windowMinutes,
        bool consumerAtHand, string consumer, int cap, bool capIsStack = true)
    {
        if (want <= 0)
            // Ноль бывает двух РАЗНЫХ смыслов, и человеку это не всё равно: либо
            // повода нет вовсе (лука в сумке нет), либо повод есть, а держать
            // заранее человек сам запретил нулём в «ЗапасНаПервыйРаз»
            return Needed(consumerAtHand, spentInWindow)
                ? "повод есть, но заранее держать не велено («ЗапасНаПервыйРаз» — ноль)"
                : "поводов держать нет";
        if (spentInWindow > 0)
            return $"истратил {spentInWindow} за последние {windowMinutes:0.#} мин" +
                   (want > spentInWindow ? $"; меньше {want} не держу" : "") +
                   // ПРО СТОПКУ ГОВОРИМ, ТОЛЬКО ЕСЛИ ОНА И ПРАВДА СТОПКА.
                   // Приёмка поймала здесь прямую ложь человеку: когда реестр
                   // рода не знает, потолком становится «ЗапасНаПервыйРаз», и
                   // строка объявляла полной стопкой число 16, которое стопкой
                   // не является ни для чего
                   (want == cap && capIsStack ? $"; больше полной стопки ({cap}) не ношу"
                    : want == cap ? $"; больше {cap} не ношу (полной стопки этого рода " +
                                    "сервер не назвал)" : "");
        // Имя потребителя ставим, только когда оно есть: «но  при мне» с дырой
        // посреди фразы человек читает как поломку, и он прав
        return consumer.Length > 0
            ? $"ещё не тратил, но {consumer} при мне — держу на первый раз"
            : "ещё не тратил — держу на первый раз";
    }

    // ---------------- ЧТО ДЕРЖИМ ----------------

    /// <summary>
    /// ЧТО ДЕРЖАТЬ ПРО ЗАПАС — одной строкой от роли. Возвращает ответ СЛОВАМИ:
    /// что понято и что из этого следует.
    ///
    /// Строкой и с ответом — тем же порядком, что <see cref="Stock.RequireTools"/>
    /// и <see cref="Depot.KeepAtHand"/>: список перекладывается ЦЕЛИКОМ (стёртое
    /// из строки стирается и из требований), а молча принятая строка неотличима
    /// от неработающей настройки.
    /// </summary>
    public string Watching(string? list)
    {
        lock (gate)
            return WatchingLocked(list);
    }

    private string WatchingLocked(string? list)
    {
        var было = pairs.ToList();
        pairs.Clear();
        pairs.AddRange(Parse(list));

        // СНЯТОЕ ИЗ СТРОКИ СНИМАЕТСЯ И ИЗ ЗАПАСОВ. Иначе вычеркнутые из панели
        // стрелы жили бы в требованиях до перезапуска, и бот до утра ходил бы
        // за тем, чего у него больше не просят
        foreach (var ушла in было.Where(b => !pairs.Any(p =>
                     string.Equals(p.Spend, b.Spend, StringComparison.OrdinalIgnoreCase))))
            Снять(ушла.Spend);

        Refresh();

        return pairs.Count == 0
            ? "про запас ничего не держу: строка пуста"
            : "держу про запас по расходу: " + string.Join(", ", pairs) +
              $"; на {WindowMinutes:0.#} мин расхода, до первого расхода {FirstTime}";
    }

    /// <summary>
    /// ЭТО УШЛО ИЗ СУМКИ НЕ В РАСХОД.
    ///
    /// Зовёт одна дверь — <c>Actions.OnItemMoved</c> (см. <see cref="Слушать"/>);
    /// открыт метод затем, что его же зовут стенды, проверяя правило без сети.
    ///
    /// Число, а не флаг: бот кладёт в сундук стопками, и «был перенос» без
    /// количества не сказал бы, сколько убыли прощать.
    /// </summary>
    public void Moved(string? code, int count)
    {
        if (count <= 0 || code is not { Length: > 0 })
            return;
        lock (gate)
        {
            foreach (var pair in pairs)
            {
                if (!Stock.InFamily(code, pair.Spend))
                    continue;
                // СНАЧАЛА ГАСИМ УЖЕ ЗАСЧИТАННОЕ, и только остаток кладём в
                // зачёт наперёд. Так закрывается гонка, которую нашла приёмка,
                // и закрывается с ОБЕИХ сторон.
                //
                // Живой порядок событий у укладки в сундук такой: сперва
                // сумка ХУДЕЕТ (сервер прислал новый вид описи), и только
                // потом сюда приходит «это был перенос» — код сам ЖДЁТ убыли,
                // прежде чем её простить. Любой пересчёт, попавший в это окно
                // (а окно живое: панель опрашивает состояние раз в две
                // секунды), успевал записать ФАНТОМНЫЙ РАСХОД на всю стопку —
                // и требование прыгало в полную стопку на весь срок запаса,
                // то есть бот шёл крафтить стрелы сразу после того, как сдал
                // их на склад. А пришедший следом зачёт ложился в кредит,
                // который ничем не гасился и молча съедал следующие 64
                // настоящих выстрела.
                int убрать = Math.Min(count, СколькоЗасчитано(pair.Spend));
                if (убрать > 0)
                    ЗабытьРасход(pair.Spend, убрать);
                int остаток = count - убрать;
                if (остаток > 0)
                    moved[pair.Spend] = moved.GetValueOrDefault(pair.Spend) + остаток;
                return;
            }
        }
    }

    /// <summary>Сколько расхода этого рода записано прямо сейчас (весь срок).</summary>
    private int СколькоЗасчитано(string род) => spent
        .Where(з => string.Equals(з.Code, род, StringComparison.OrdinalIgnoreCase))
        .Sum(з => з.Count);

    /// <summary>
    /// ЗАБЫТЬ СТОЛЬКО-ТО РАСХОДА — начиная с самого свежего.
    ///
    /// Свежий и есть тот, который мы, скорее всего, и записали по ошибке:
    /// перенос приходит следом за убылью, а не спустя полчаса.
    /// </summary>
    private void ЗабытьРасход(string род, int сколько)
    {
        for (int i = spent.Count - 1; i >= 0 && сколько > 0; i--)
        {
            var з = spent[i];
            if (!string.Equals(з.Code, род, StringComparison.OrdinalIgnoreCase))
                continue;
            int снять = Math.Min(сколько, з.Count);
            сколько -= снять;
            if (з.Count - снять > 0)
                spent[i] = (з.When, з.Code, з.Count - снять);
            else
                spent.RemoveAt(i);
        }
    }

    /// <summary>
    /// ЗАБЫТЬ, СКОЛЬКО БЫЛО: ближайший взгляд не насчитает убыли. Смерть и
    /// новое соединение.
    /// </summary>
    public void Resync()
    {
        lock (gate)
        {
            seen.Clear();
            moved.Clear();
            resync = true;
        }
    }

    /// <summary>
    /// ПОСМОТРЕТЬ В СУМКУ, ЗАСЧИТАТЬ РАСХОД И ПЕРЕСТАВИТЬ ТРЕБОВАНИЯ.
    ///
    /// Зовётся из запасов перед каждым опросом (<see cref="Stock.BeforeCheck"/>),
    /// то есть ровно тогда, когда числа кому-то нужны.
    /// </summary>
    public void Refresh()
    {
        // ЗАМОК — ПОТОМУ ЧТО ЗОВУТ НЕ ТОЛЬКО ИЗ ЦИКЛА БОТА (см. gate): окно
        // управления просит состояние каждые две секунды со своего потока, и
        // чат-команда приходит с третьего
        lock (gate)
        {
            // ЗАПАСЫ СПРАШИВАЮТ НАС, МЫ СТАВИМ ТРЕБОВАНИЕ ЗАПАСАМ. Прямой
            // рекурсии тут нет (Require ничего не опрашивает), но случайная —
            // вопрос времени. Замок её не ловит: он повторный вход СВОЕГО
            // потока пропускает, а сторож — нет
            if (refreshing || pairs.Count == 0)
                return;
            refreshing = true;
            try
            {
                Пересчитать();
            }
            finally
            {
                refreshing = false;
            }
        }
    }

    private void Пересчитать()
    {
        var сейчас = DateTime.UtcNow;
        // Вне мира сумка пуста не потому, что всё истрачено
        bool вМире = ctx.Bot.Joined && !ctx.Self.IsDead;
        if (!вМире)
            resync = true;

        // Расход старше срока запаса больше не считается: срок и есть окно
        double окно = Math.Max(0.1, WindowMinutes);
        spent.RemoveAll(з => (сейчас - з.When).TotalMinutes > окно);

        now.Clear();
        foreach (var pair in pairs)
        {
            int вСумке = Сколько(pair.Spend);
            if (вМире)
                Засчитать(pair.Spend, вСумке, сейчас);
            else
                seen[pair.Spend] = вСумке;

            int истрачено = spent
                .Where(з => string.Equals(з.Code, pair.Spend, StringComparison.OrdinalIgnoreCase))
                .Sum(з => з.Count);
            bool повод = pair.Consumer.Length == 0 || Сколько(pair.Consumer) > 0;

            int стопка = Стопка(pair.Spend);
            // НОЛЬ — ЭТО СНЯТОЕ ТРЕБОВАНИЕ, А НЕ «ТРЕБОВАНИЕ НА НОЛЬ ШТУК». Оба
            // нуля (нет повода и «заранее не держу») ведут в одно место: запасы
            // считают ноль отменой (Stock.Require), и вести их разными дорогами
            // значило бы завести вторую запись одного и того же
            int сколько = Needed(повод, истрачено) ? Reserve(истрачено, FirstTime, стопка) : 0;
            string почему = Why(сколько, истрачено, окно, повод, pair.Consumer, стопка,
                СтопкаИзвестна(pair.Spend));
            now.Add(new UpkeepWant(pair.Spend, сколько, истрачено, повод, почему));
            if (сколько > 0)
                Поставить(pair.Spend, сколько, почему);
            else
                Снять(pair.Spend, почему);
        }

        resync = false;
    }

    /// <summary>
    /// ЗАСЧИТАТЬ УБЫЛЬ — ЗА ВЫЧЕТОМ ТОГО, ЧТО ПЕРЕНЕСЛИ.
    ///
    /// Прибавка (сделал, принёс со склада) расходом не является и зачёт
    /// переноса не гасит: положил стопку в сундук, забрал обратно — обе
    /// стороны обязаны сойтись в ноль, а не оставить долг, который назавтра
    /// съест настоящий выстрел.
    /// </summary>
    private void Засчитать(string род, int вСумке, DateTime когда)
    {
        if (resync || !seen.TryGetValue(род, out int было))
        {
            seen[род] = вСумке;
            return;
        }
        seen[род] = вСумке;
        int убыло = было - вСумке;
        if (убыло <= 0)
            return;

        int зачёт = moved.GetValueOrDefault(род);
        int прощаем = Math.Min(зачёт, убыло);
        moved[род] = зачёт - прощаем;
        int расход = убыло - прощаем;
        if (расход > 0)
            spent.Add((когда, род, расход));
    }

    /// <summary>
    /// ПОДПИСАТЬСЯ НА ЕДИНСТВЕННУЮ ДВЕРЬ ПЕРЕНОСА.
    ///
    /// «Своё» здесь — то, что кончается на uid бота (так их и различает
    /// <c>SelfState.OwnInventories</c>). Из своего в своё — не перенос наружу
    /// (курсор, одежда, рюкзак); земля под ногами хоть и «своя», но это ровно
    /// то место, куда выбрасывают, и она считается наружу.
    /// </summary>
    private void Слушать()
    {
        ctx.Actions.OnItemMoved += (from, slot, to, qty) =>
        {
            if (qty <= 0 || !Хранилище(from) || !Своё(from) || Своё(to))
                return;
            // КОД БЕРЁМ У СЛОТА ИСТОЧНИКА, И БЕРЁМ ДО ОТПРАВКИ ПАКЕТА: событие
            // говорится раньше, чем сервер опустошит слот. Придумывать код по
            // пакету нечем — его там нет
            if (ctx.Self.Inventories.TryGetValue(from, out var опись) &&
                slot >= 0 && slot < опись.Length && опись[slot].Code is { Length: > 0 } код)
                Moved(код, Math.Min(qty, Math.Max(1, опись[slot].Count)));
        };
    }

    /// <summary>Опись бота (кончается его uid); чужой сундук — нет.</summary>
    private bool Своё(string id) =>
        id.EndsWith(ctx.Bot.PlayerUid, StringComparison.Ordinal) &&
        !id.StartsWith("ground", StringComparison.Ordinal);

    /// <summary>Опись, из которой вещи и тратятся: хотбар и рюкзак.</summary>
    private static bool Хранилище(string id) =>
        id.StartsWith("hotbar", StringComparison.Ordinal) ||
        id.StartsWith("backpack", StringComparison.Ordinal);

    /// <summary>Сколько такого рода в сумках (по семье кода, а не по подстроке).</summary>
    private int Сколько(string род) =>
        ctx.Hands.CountOf(s => Stock.InFamily(s.Code, род));

    /// <summary>
    /// ПОЛНАЯ СТОПКА ПО РЕЕСТРУ. Число берётся у ИГРЫ, а не у нас: у стрелы
    /// maxstacksize 64, а у чего-нибудь модового — своё, и выдумывать его
    /// нельзя.
    ///
    /// Реестр знает КОДЫ («arrow-copper»), а требование пишется РОДОМ
    /// («arrow»), поэтому спрашиваем первый попавшийся вид этого рода. Виды
    /// одного рода стопкой не различаются — иначе игра не смогла бы класть их
    /// в один слот.
    ///
    /// Реестр рода не знает — потолком становится «на первый раз»: гадать
    /// «наверное, 64» значит однажды потребовать стопку того, что стопками не
    /// кладут.
    /// </summary>
    private int Стопка(string род)
    {
        if (!caps.TryGetValue(род, out int стопка))
        {
            стопка = 0;
            foreach (string код in ctx.World.SearchItemCodes(род, 64)
                         .Concat(ctx.World.SearchBlockCodes(род, 64)))
            {
                if (!Stock.InFamily(код, род))
                    continue;
                int своя = ctx.World.MaxStackSizeOrUnknown(код);
                if (своя > 0)
                {
                    стопка = своя;
                    break;
                }
            }
            // НОЛЬ ПОМНИМ ТОЖЕ. Опрос запасов случается по нескольку раз в
            // секунду (окно управления), а перебор реестра — это тысячи строк:
            // род, которого в реестре нет (описка человека, «arow»), стоил бы
            // этого перебора КАЖДЫЙ РАЗ и навсегда. Реестр придёт — память
            // стирается целиком, и ответ переспросится (см. конструктор)
            caps[род] = стопка;
            // ОПИСКА В РУЧКЕ — ЭТО ОТКАЗ, И ОН ОБЯЗАН НАЗВАТЬ РУЧКУ (правило 4).
            //
            // Молчание тут стоило дорого, и приёмка нашла это первым же
            // разбором: впиши человек в «ЗапасПоРасходу» слово «torhc» или
            // «arow» — реестр такого рода не знает, стопка выходит нулевой, а
            // бот НАВСЕГДА требует «на первый раз» штук несуществующего
            // предмета. Снабжение вечно ходит впустую, «Missing» вечно
            // показывает «arow 0/16», и ни одной строки о причине. Соседняя
            // ручка «КакиеСтрелыДержать» ровно этот случай говорила вслух —
            // а новая молчала.
            //
            // Говорим ТОЛЬКО когда реестр уже собран: до него «не знаю» — это
            // не описка, а «ещё не спрашивали»
            if (стопка == 0 && ctx.World.GameItemsReady)
                OnLog?.Invoke(
                    $"«{род}» — такого предмета сервер не знает; проверьте ручку " +
                    "«ЗапасПоРасходу» (там пишутся КОДЫ игры, например «arrow к bow»). " +
                    $"Пока держу по «ЗапасНаПервыйРаз» ({Math.Max(1, FirstTime)}), " +
                    "и найти это бот всё равно не сможет");
        }
        return стопка > 0 ? стопка : Math.Max(1, FirstTime);
    }

    /// <summary>Известна ли полная стопка этого рода по реестру.</summary>
    private bool СтопкаИзвестна(string род) => caps.GetValueOrDefault(род) > 0;

    /// <summary>
    /// ПОСТАВИТЬ ТРЕБОВАНИЕ — И НИКОГДА ПОВЕРХ ЧУЖОГО.
    ///
    /// ЖИВОЙ РИСК, РАДИ КОТОРОГО ЭТА ПРОВЕРКА. У факелов уже есть своя
    /// неподвижная ручка («ДержатьФакелов»), и впиши человек «torch» ещё и в
    /// запас по расходу — на одно требование заговорили бы два голоса, а
    /// побеждал бы тот, кто донёс своё последним. В этом проекте так уже
    /// кончилось однажды: до снабжения не доехала ни одна ручка крафта.
    /// Молчать нельзя, чинить самовольно — тоже: человек обязан узнать, какую
    /// из двух ручек ему повернуть.
    ///
    /// fetch: false — РАСХОДНИК ДЕЛАЮТ, А НЕ ВЫКАПЫВАЮТ. Ровно тем же порядком
    /// заведены факелы и лестницы, и причина та же живая: поручение ищет
    /// источник по реестру блоков и на «нужен факел» уходило искать НАСТЕННЫЕ
    /// ДЕРЖАТЕЛИ факелов. За МАТЕРИАЛОМ для рецепта бот при этом сходит —
    /// это решает «ДобыватьНедостающее», и здесь оно не обходится.
    ///
    /// Мерка — семья кода: по подстроке «arrow» за стрелу сойдёт наконечник
    /// («arrowhead-flint»), и бот с полной сумкой наконечников считал бы себя
    /// снаряжённым, а лук — молчал бы.
    /// </summary>
    private void Поставить(string род, int сколько, string почему)
    {
        // ЧУЖОЕ ЧИСЛО УЗНАЁТСЯ ПО ТОМУ, ЧТО ОНО НЕ НАШЕ, а не по тому, кто успел
        // первым. Порядок, в котором роль доносит ручки, нам не принадлежит:
        // база доносит запас по расходу, а своё «ДержатьФакелов» роль-наследник
        // доносит СЛЕДОМ — и «занят ли род» отвечало бы то одно, то другое.
        if (ctx.Stock.Wants.TryGetValue(род, out int стоит) &&
            (!mine.TryGetValue(род, out int наше) || стоит != наше))
        {
            // Спор один раз и вслух: молчание тут означало бы бота, у которого
            // ручка в панели ничего не делает, а почему — не сказано
            if (спорныеСказаны.Add(род))
                OnLog?.Invoke($"«{род}» просят двое: и запас по расходу ({сколько}), и " +
                              $"неподвижное требование роли ({стоит}). Чужое не трогаю — " +
                              "уберите род из «ЗапасПоРасходу» или обнулите ту ручку, " +
                              "которая держит его неподвижным");
            // Отпускаем род совсем: раз им распоряжается кто-то ещё, снимать
            // его потом (см. Снять) мы тоже не вправе
            mine.Remove(род);
            сказано.Remove(род);
            return;
        }

        // ТОТ ЖЕ СПОР, НО ПОД ДРУГИМ ИМЕНЕМ: род и вид одной семьи.
        //
        // ЖИВОЙ СЛУЧАЙ 26.08, ПОЙМАН НА СТЕНДЕ ЗАКАЗЧИКА В ЭТУ ЖЕ ВОЛНУ. Рядом
        // завелась ручка «ДержатьСтрел» с «КакиеСтрелыДержать: arrow-flint» —
        // неподвижное число под КОНКРЕТНЫЙ вид. Мы просим РОД («arrow»), и в
        // списке требований спокойно улеглись бы обе строки: «arrow-flint 64» и
        // «arrow 16». Совпадения ключей нет, спор молчит, а бот считает
        // недостачу дважды и дважды идёт её закрывать — при том что кремнёвая
        // стрела и есть стрела. Ровно эта же ловушка ждёт всякого, кто впишет в
        // «ЗапасПоРасходу» и «torch», и «torch-basic».
        if (ctx.Stock.Wants.Keys.FirstOrDefault(w =>
                !string.Equals(w, род, StringComparison.OrdinalIgnoreCase) &&
                (Stock.InFamily(w, род) || Stock.InFamily(род, w))) is { } родня)
        {
            if (спорныеСказаны.Add(род))
                OnLog?.Invoke($"«{род}» просят двое: запас по расходу ({сколько}) и " +
                              $"отдельное требование «{родня}» ({ctx.Stock.Wants[родня]}) — " +
                              "это одна и та же семья предметов, недостача считалась бы " +
                              "дважды. Чужое не трогаю: уберите род из «ЗапасПоРасходу» " +
                              $"или обнулите ту ручку, которая просит «{родня}»");
            // А СВОЁ УБИРАЕМ. Оставь мы род рядом с видом — недостача и вправду
            // считалась бы дважды, и спор остался бы одними словами в журнале
            Снять(род, $"о том же просит «{родня}»");
            return;
        }

        ctx.Stock.Require(род, сколько, fetch: false, match: c => Stock.InFamily(c, род));
        mine[род] = сколько;

        // ГОВОРИМ О ПЕРЕМЕНЕ, А НЕ О КАЖДОМ ВЗГЛЯДЕ. Опрос запасов случается по
        // нескольку раз в секунду (окно управления), и строка на каждый из них
        // — это не журнал, а метель
        string строка = $"{род} ×{сколько}: {почему}";
        if (!сказано.TryGetValue(род, out string? прежде) ||
            !string.Equals(прежде, строка, StringComparison.Ordinal))
        {
            сказано[род] = строка;
            OnLog?.Invoke(строка);
        }
    }

    /// <summary>
    /// СНЯТЬ ТРЕБОВАНИЕ — только своё. Чужое (неподвижную ручку роли) мы не
    /// заводили и снимать не вправе.
    /// </summary>
    private void Снять(string род, string почему = "поводов нет")
    {
        // Снимаем только то, что в запасах и вправду наше: перепиши его кто-то
        // после нас — мы стёрли бы чужое требование
        if (!mine.TryGetValue(род, out int наше) ||
            !ctx.Stock.Wants.TryGetValue(род, out int стоит) || стоит != наше)
        {
            mine.Remove(род);
            сказано.Remove(род);
            return;
        }
        mine.Remove(род);
        ctx.Stock.Require(род, 0);
        if (сказано.Remove(род))
            OnLog?.Invoke($"{род} про запас больше не держу: {почему}");
    }

    public override string ToString() =>
        pairs.Count == 0
            ? "запас по расходу выключен"
            : string.Join("; ", now.Select(w => w.ToString()));
}
