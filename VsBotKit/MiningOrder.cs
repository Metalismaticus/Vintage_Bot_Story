    /// <summary>
    /// Просят ли руду (а не доски и не еду) — ОТВЕТ РЕЕСТРА, и живёт он у руды
    /// (<see cref="Ores.IsOreOrder"/>) вместе со всем прочим знанием о ней.
    ///
    /// Здесь было своё правило: «слово из списка минералов ИЛИ начинается на
    /// ore-». Списка хватало ровно до первой вещи, которой в нём нет: заказ
    /// «stone-meteorite-iron» ушёл в обычное поручение, и вся рудная машина —
    /// чит зрения, осмотр на 48 бл, ход по жиле, счёт металла — прошла мимо.
    ///
    /// Камень сюда НЕ входит, но идёт тем же путём: см. <see cref="Ores.IsStoneOrder"/>
    /// и место вызова ниже. Кода «камень» в игре нет вовсе (породы зовутся
    /// rock-granite, rock-andesite), поэтому общее поручение искало источник
    /// по подстроке в коде блока и честно отвечало «не знаю, откуда берётся
    /// камень» — а бот при этом стоял на граните.
    /// </summary>
    private bool IsOreOrder(string wanted) => ctx.Ores is { } руда && руда.IsOreOrder(wanted);

    /// <summary>
    /// РАЗБИРАТЬ ЛИ ЗАПАСЫ НА ЭТОМ ЗАХОДЕ. ЧИСТОЕ ПРАВИЛО, и оно про ЦЕНУ
    /// ПЕРЕРЫВА: сколько работы заход делает ПОВТОРНО.
    ///
    /// ЖИВОЙ СЛУЧАЙ (журнал 16.08, 12:56:28 — 12:57:00). Наряд «медь ×30»
    /// донёс 29 из 30, его перебил бой, возврат честно завёл заход 3 и попросил
    /// ОСТАТОК — одну штуку. И тут же:
    ///   12:56:32 [запасы] не хватает Axe ×1
    ///   12:56:32 [склад] иду на дом за: Axe ×8
    ///   12:56:54 [склад] иду на склад (512061, 112, 512257): беру stick
    ///   12:57:00 [наряд] запасов не хватает: Axe 0/1, Knife 0/1; 25 с
    ///   12:57:00 [наряд] медь: принёс 0 из 1 … наряд отменён
    /// Двадцать пять секунд захода ушли не на медь, а на ПОВТОРНЫЙ разбор
    /// запасов — тот самый, что уже был сделан четыре минуты назад и ничего не
    /// нашёл. Место в работе возврат сохранил, а вот подготовку к работе бот
    /// каждый раз начинал с нуля. Со стороны это и есть «бегал вперёд-назад»
    /// и «метался между домом и стройкой»: домой его гнал не бой, а вот эта
    /// строка.
    ///
    /// ПРАВИЛО ТАКОЕ ЖЕ, КАКИМ УЖЕ СЧИТАЮТСЯ СРОК И РАЗВЕДКИ: подготовка — на
    /// ВЕСЬ наряд, а не на заход (см. <see cref="OrderResume.KeepFetchingAsync"/>
    /// и <paramref name="mustHaveMissing"/> ниже).
    ///
    /// НО ОДНО ИСКЛЮЧЕНИЕ ЕСТЬ, И ОНО ОБЯЗАТЕЛЬНО: если в бою сломалась кирка,
    /// идти дальше НЕЧЕМ, и молча копать без неё — это враньё про работу. Тогда
    /// за снаряжением ходят и на возврате. Мерка — не «прошло ли время», а
    /// «есть ли при себе то, без чего наряд бессмыслен» (<see cref="MustHave"/>).
    /// </summary>
    /// <param name="resumed">Это возврат после перерыва, а не первый заход.</param>
    /// <param name="mustHaveMissing">Чего-то из <see cref="MustHave"/> в сумках нет.</param>
    public static bool ShouldReplenish(bool resumed, bool mustHaveMissing) =>
        !resumed || mustHaveMissing;

    /// <summary>
    /// Выполнить наряд. Руда идёт своим путём (жилы, разведка, проходка),
    /// всё остальное — обычным поручением.
    /// </summary>
    /// <param name="searchesSpent">
    /// СКОЛЬКО РАЗВЕДОК УЖЕ ПОТРАЧЕНО ПРЕЖНИМИ ЗАХОДАМИ этого же наряда.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ради которого довод понадобился (журнал 16.08, 12:45).
    /// Наряд ушёл в разведку, через десять секунд его перебила еда, возврат
    /// завёл заход 2 — и заход 2 объявил «ухожу в разведку (1 ИЗ 3)». Потолок
    /// <see cref="MaxSearches"/> считался НА ЗАХОД, а заходов возврат даёт до
    /// четырёх: вместо трёх разведок бот успевал уйти в двенадцать, каждый раз
    /// обходя ту же округу по кругу. Заказчик это увидел так: «бегал вперед
    /// назад».
    ///
    /// Потолок обязан считаться НА ВЕСЬ НАРЯД — ровно тем же правилом, каким
    /// на весь наряд уже считается СРОК (см.
    /// <see cref="OrderResume.KeepFetchingAsync"/>: «иначе наряд с потолком в
    /// полчаса, прерываемый едой каждую минуту, жил бы вечно»). Число берётся
    /// не из своей памяти, а из сложенного отчёта прошлых заходов
    /// (<see cref="OrderReport.Searches"/>, складывает <see cref="OrderResume.Merge"/>):
    /// вторая память о том же разошлась бы с первой в первый же вечер.
    /// </param>
    /// <param name="resumed">
    /// ЭТО ВОЗВРАТ ПОСЛЕ ПЕРЕРЫВА, А НЕ ПЕРВЫЙ ЗАХОД. Нужен ровно для одного:
    /// не разбирать запасы заново на каждом заходе — см. цену этого в
    /// <see cref="ShouldReplenish"/>. Своей памяти о заходах наряд не заводит:
    /// счёт заходам ведёт возврат (<see cref="Resume"/>), и второй такой же
    /// счётчик разошёлся бы с первым на первом же «стопе».
    /// </param>
    /// <remarks>
    /// ПОЧЕМУ virtual. Настоящий наряд ходит к жиле по серверу и живёт минуты —
    /// проверить на стенде «после перерыва просит ОСТАТОК, а не весь заказ»
    /// им нельзя. Подставной наряд отвечает теми же <see cref="OrderReport"/>,
    /// и шов «роль → <see cref="OrderResume.KeepFetchingAsync"/> → наряд»
    /// становится проверяемым: без этого вчерашнюю починку возврата можно было
    /// отменить одной строкой, и весь прогон остался бы зелёным.
    /// </remarks>
    public virtual async Task<OrderReport> FetchAsync(string wanted, int count,
        CancellationToken ct = default, int searchesSpent = 0, bool resumed = false)
    {
        var started = DateTime.UtcNow;
        if (count <= 0)
            // ЗАДАНИЕ САМО СЕБЕ ПРОТИВОРЕЧИТ и узнаётся до первого удара —
            // ровно то, что означает это слово. Время его не поправит
            return Done(false, "количество должно быть больше нуля", wanted, count, 0, 0, 0, 0,
                started, new Dictionary<string, int>(), Setback.Impossible);

        // ПЕРЕСПРОС — ДО СНАРЯЖЕНИЯ И ДО ДОРОГИ.
        //
        // Заказчик просил уметь вписывать в команду «что угодно, допустим
        // метеоритное железо». Перевод человеческого слова в код игры живёт у
        // поручений (<see cref="Errands.Resolve"/>) — он же и решает, понял ли
        // бот сказанное однозначно. Если под словом подходит несколько вещей,
        // спросить надо СЕЙЧАС: снаряжаться, а тем более уходить на полчаса
        // ради слова, которого бот не понял, — это ровно то кружение, из-за
        // которого наряд и переписывали.
        //
        // Руда и порода сюда не попадают нарочно: у них свои человеческие слова
        // («медь», «камень»), и разбирает их OreCode.MetalGroups — второму
        // словарю тех же слов взяться неоткуда.
        //
        // А ВОТ ПЕРЕВЕДЁННОЕ СЛОВО МОЖЕТ ОКАЗАТЬСЯ РУДОЙ, и это второй хвост
        // того же живого случая. «Метеоритное железо» — не группа и не код: под
        // приставку не подходит, в реестре по-русски не значится, и наряд вёл
        // его обычным поручением. А в игре это блок meteorite-iron, и он
        // рудоподобен: роняет stone-meteorite-iron, пятьдесят единиц металла.
        // Человек, сказавший «метеорит», имеет в виду МЕТАЛЛ, а не щебень, —
        // значит после перевода надо переспросить дорогу ещё раз, уже у кода.
        if (!IsOreOrder(wanted) && !Ores.IsStoneOrder(wanted) && ctx.Errands is { } errands)
        {
            var понято = errands.Resolve(wanted);
            if (понято.NeedsAsking)
                // «НЕ ПОНЯЛ СЛОВО, ЖДУ ОТВЕТА ЧЕЛОВЕКА» — ЧЕСТНОГО ИМЕНИ НЕТ.
                // Это ВОПРОС, а не помеха и не отказ: под словом подошло
                // несколько вещей, и бот ждёт, какую из них человек имел в
                // виду. Setback.Stopped сюда натянуть нельзя — никто ничего не
                // останавливал; Impossible — тоже: задание выполнимо, как
                // только его уточнят. Ответ, который тут нужен, — «спроси
                // человека», а такого в словаре нет вовсе. Отдаём «причину не
                // назвали»: сам вопрос стоит словами в понято.Say
                return Done(false, понято.Say, wanted, count, 0, 0, 0, 0, started,
                    new Dictionary<string, int>());
            if (понято.Code is { Length: > 0 } код &&
                !string.Equals(код, wanted, StringComparison.OrdinalIgnoreCase) &&
                IsOreOrder(код))
            {
                OnLog?.Invoke($"«{wanted}» — это {код}, и это руда: веду рудной дорогой");
                wanted = код;
            }
        }

        // ЧТО Я ПОНЯЛ ПОД ТВОИМ СЛОВОМ — ВСЛУХ И ДО ВЫХОДА.
        //
        // Заказчик дословно: «я пишу добудь 20 меди, а он добывает 20 кусков
        // самородков, а не самородной меди, он не смотрит сколько и всего».
        // Двадцатка у человека и у бота значила разное — и узнавал он об этом
        // через сорок минут, по содержимому сундука. Теперь бот называет
        // ЕДИНИЦУ СЧЁТА и то, сколько это выходит кусков, ПОКА можно поправить.
        //
        // Только на первом заходе: возврат после обеда повторял бы эту строку
        // на каждый перерыв, а нового в ней ничего нет
        if (!resumed && IsOreOrder(wanted) && ctx.Metal is { } metal && ctx.Ores is { } руда)
            OnLog?.Invoke(metal.PlanFor(wanted, count, руда.CountIn).ToString());

        var before = ctx.Self.CarrySnapshot();
        var deadline = started.AddSeconds(MaxSeconds);

        // КОПИЛКА. Считать добытое одной разницей «сумка сейчас минус сумка на
        // входе» нельзя: рейс на склад ВЫСЫПАЕТ руду в сундук, разница снова
        // становится нулевой, и наряд на двадцать штук при сумке на десять не
        // кончился бы никогда — а отчёт врал бы «принёс 0», когда двадцать уже
        // лежат в сундуке. Поэтому добытое откладывается сюда ДО каждой
        // разгрузки и больше не теряется
        var earned = new Dictionary<string, int>(StringComparer.Ordinal);

        void Bank()
        {
            foreach (var (code, n) in SelfState.Gained(before, ctx.Self.CarrySnapshot()))
                earned[code] = earned.GetValueOrDefault(code) + n;
            before = ctx.Self.CarrySnapshot();
        }

        // 1. СНАРЯЖЕНИЕ. Дешевле проверить сейчас, чем встать на дне шахты
        if (CheckStockFirst && ctx.Stock is { } stock)
        {
            // ОТКАЗ БЕЗ КИРКИ — ВСЕГДА, А НЕ ТОЛЬКО ПРИ НЕПУСТЫХ ТРЕБОВАНИЯХ.
            // Раньше вся эта проверка стояла ВНУТРИ «если требований больше
            // нуля», и держалось это на том, что требования были зашиты в роль
            // (Require("pickaxe", 1) и Require("shovel", 1)). Теперь список
            // наполняется человеком из панели («ДержатьИнструменты»), а факелы
            // при «ДержатьФакелов = 0» требование СНИМАЮТ. Достаточно стереть
            // строку в панели — или не дождаться реестра предметов к моменту
            // доноса настроек, — и Wants пуст: наряд молча уходил на делянку
            // без кирки вместо честного «без pickaxe за рудой не ходят».
            //
            // СМОТРИМ В СУМКИ ПЕРВЫМ ДЕЛОМ, а не после пополнения: этот взгляд
            // даром, а пополнение стоит рейса домой — и оно же решает, стоит ли
            // этот рейс затевать на возврате (см. ShouldReplenish)
            var missing = MustHave.Where(m => stock.Have(m) == 0).ToList();

            // ПОПОЛНЕНИЕ — ОДИН РАЗ НА НАРЯД, А НЕ НА КАЖДЫЙ ЗАХОД. Цена
            // повторного разбора запасов и живой случай, ради которого правило
            // заведено, разобраны у ShouldReplenish: заход 4 наряда «медь ×30»
            // отдал двадцать пять секунд из двадцати пяти на поход домой за
            // топором, которого дома не было и четыре минуты назад
            if (ShouldReplenish(resumed, missing.Count > 0))
            {
                // ПОПОЛНЯТЬ — только если есть что пополнять. Пустой список
                // требований это не «всё в порядке», а «ничего не просили»
                if (stock.Wants.Count > 0)
                    OnLog?.Invoke((await stock.ReplenishAsync(ct)).ToString());
                missing = MustHave.Where(m => stock.Have(m) == 0).ToList();
            }
            else
                // МОЛЧАТЬ ТУТ НЕЛЬЗЯ: человек, читающий журнал, обязан видеть
                // разницу между «бот не пошёл за снаряжением» и «бот про него
                // забыл». И между «не пошёл» и «не понадобилось» — тоже
                OnLog?.Invoke("запасы на этом наряде уже разбирали" +
                              (MustHave.Count > 0
                                  ? $", а {string.Join(" и ", MustHave)} при себе есть"
                                  : "") +
                              " — второй раз за снаряжением не хожу, доношу остаток");

            // ПЕРЕСПРОСИТЬ. Сразу после входа в мир сумки приходят не мгновенно,
            // и живьём бот отказался идти «без кирки», держа в руках
            // pickaxe-meteoriciron: он просто спросил раньше, чем сервер
            // прислал содержимое. Отказ должен быть по факту, а не по спешке
            if (missing.Count > 0)
            {
                OnLog?.Invoke($"не вижу у себя {string.Join(", ", missing)} — переспрошу через " +
                              $"{InventorySettleSeconds:0.#} с (сумки приходят не сразу)");
                await Task.Delay(TimeSpan.FromSeconds(InventorySettleSeconds), ct)
                    .ContinueWith(_ => { }, CancellationToken.None);
                missing = MustHave.Where(m => stock.Have(m) == 0).ToList();
            }

            if (missing.Count > 0)
                // КОНЧИЛСЯ ЗАПАС У БОТА: кирки нет ни в сумке, ни дома. Сам
                // он не заведётся — тем же словом дорога читает «нужен
                // инструмент получше» (MiningRefusal.NeedBetterTool)
                return Done(false, $"без {string.Join(" и ", missing)} за рудой не ходят",
                    wanted, count, 0, 0, 0, 0, started, new Dictionary<string, int>(),
                    Setback.NoMaterial);
        }

        // Не руда и не камень — это обычное поручение, и оно уже написано
        if (!IsOreOrder(wanted) && !Ores.IsStoneOrder(wanted))
        {
            OnLog?.Invoke($"{wanted} — не руда, беру обычным поручением");
            double left = Math.Max(30, (deadline - DateTime.UtcNow).TotalSeconds);
            double was = ctx.Errands.MaxSeconds;
            ctx.Errands.MaxSeconds = left;
            try
            {
                var errand = await ctx.Errands.FetchAsync(wanted, count, ct: ct);
                var got = SelfState.Gained(before, ctx.Self.CarrySnapshot());
                // ПОМЕХУ ПОРУЧЕНИЯ НАЗВАТЬ НЕЧЕМ: своего словаря остановок у
                // поручений нет вовсе, а гадать по строке отказа — то же
                // самое, что гадать за работу. Причина стоит словами в
                // errand.Message; общего слова тут не будет, пока поручения не
                // научатся его говорить (это ИХ работа, не наряда)
                return Done(errand.Success, errand.Message, wanted, count, errand.Delivered,
                    0, 0, 0, started, got);
            }
            finally
            {
                ctx.Errands.MaxSeconds = was;
            }
        }

        // РАЗВЕДКИ СЧИТАЮТСЯ ДВАЖДЫ, И ЭТО НЕ ОПИСКА. «searches» — сколько
        // потратил ЭТОТ заход (его и вернём в отчёте: сложить заходы умеет
        // Merge, и второй раз складывать нельзя). «before» — сколько потратили
        // прежние заходы того же наряда; потолок MaxSearches меряется их суммой
        int veins = 0, hauls = 0, searches = 0, dugDown = 0, idle = 0;
        int searchesBefore = Math.Max(0, searchesSpent);
        string message = "набрал сколько просили";
        // ПОСЛЕДНЯЯ ПОМЕХА — ЕЁ И НАЗОВЁМ В ОТКАЗЕ. Без неё итог наряда
        // говорил «не нашёл» про руду, которую бот видел четырьмя строками
        // выше (см. WhenSearchesRanOut)
        string? lastMiss = null;
        // ЧЕМ НАРЯД ОБЪЯСНИТ СВОЮ ОСТАНОВКУ — общим словом. Кладётся рядом со
        // строкой отказа, в том же месте и той же строкой кода: разъехаться
        // им тогда некуда
        var помеха = Setback.None;
        // …И ПОСЛЕДНЯЯ ЖИВАЯ ПОМЕХА — та, что мешала, ПОКА ШЛИ ЧАСЫ. Нужна
        // ровно сроку, чтобы он не встал на её место: см. Resume.TimeIsNotACause
        var живая = Setback.None;

        while (!ct.IsCancellationRequested)
        {
            Bank();
            // Счёт через контекст, а не статикой: у камня выпадение своё
            // (rock-granite даёт stone-granite) и берётся из реестра сервера
            int got = ctx.Ores.CountFor(earned, wanted);
            if (got >= count)
                break;
            if (DateTime.UtcNow > deadline)
            {
                // СРОК ДОКЛАДЫВАЕТ ПОСЛЕДНЮЮ ЖИВУЮ ПОМЕХУ, А НЕ ВСТАЁТ НА ЕЁ
                // МЕСТО — и человеку словами, и возврату словом. Живой случай:
                // игрок простоял на клетке жилы пять минут, наряду отведено
                // пять минут, и в журнал выходило одно «вышло отведённое время
                // (300 с)» — то есть слово из ПОСТОЯННЫХ, отказ с первого раза
                message = $"вышло отведённое время ({MaxSeconds:0} с)" +
                          (lastMiss is { Length: > 0 } последнее
                              ? $"; последнее, что мешало: {последнее}"
                              : "");
                помеха = Resume.TimeIsNotACause(живая);
                break;
            }

            // 4. СКЛАД. Проверяем ДО добычи: класть-то всё равно некуда
            if (MayHaul && ctx.Depot is { } depot && depot.TimeToHaul())
            {
                Bank();   // добытое — в копилку ДО того, как сумка опустеет
                var trip = await depot.HaulAsync(ct);
                Bank();   // и заново от пустой сумки
                hauls++;
                if (!trip.Success && trip.Stop != HaulStop.Nothing)
                {
                    // ПОМЕХУ РЕЙСА БЕРЁМ ЕГО ЖЕ СЛОВОМ (Depot.WhatStopped), а
                    // не пересказываем строку. Разница живая: «сервер перенос
                    // не подтвердил» проходит само и стоит второго захода, а
                    // «все сундуки полны» — нет, и наряд не должен хоронить
                    // себя из-за первого
                    message = $"рейс на склад не удался: {trip.Reason}";
                    помеха = trip.Hindrance;
                    break;
                }
            }

            // 2. ЧТО ЛЕЖИТ НА ЗЕМЛЕ. Самое дешёвое из всего: наклониться.
            // Россыпь самородков — это готовый металл без кирки и без шахты,
            // и заказчик верно заметил, что бот проходил мимо неё
            if (MayTakeNuggets && await TakeNuggetsAsync(wanted, ct) > 0)
                continue;

            // 3. ЧТО ВИДНО. Руда уже вскрыта, идти близко
            double leftSeconds = Math.Max(30, (deadline - DateTime.UtcNow).TotalSeconds);
            var (vein, мешало) = await MineVisibleAsync(wanted, count - got, leftSeconds, ct);
            // ПОМЕХУ ЗАПОМИНАЕМ СРАЗУ, а не только когда она станет отказом:
            // именно её и назовёт срок, если часы кончатся следующим кругом
            if (мешало != Setback.None)
                живая = мешало;
            if (vein.Broken > 0)
            {
                veins++;
                // ЛОМАЮ, А В СУМКЕ НЕ ПРИБАВЛЯЕТСЯ. С рудой это почти не
                // встречалось (жила кончалась раньше сумки), а породы вокруг
                // бесконечно много: с полной сумкой и без склада бот копал бы
                // камень до конца наряда и отчитался «принёс 0». Два круга
                // подряд без прибавки — стоп
                Bank();
                if (ctx.Ores.CountFor(earned, wanted) == got)
                {
                    if (++idle >= 2)
                    {
                        // «КЛАСТЬ НЕКУДА» — ЧЕСТНОГО ИМЕНИ НЕТ. Сумка сама не
                        // опустеет, но и «бросай» тут неправда: лечится это
                        // рейсом на склад, то есть ответом «устрани и
                        // вернись», которого в словаре нет. NoMaterial — про
                        // кончившийся запас, а тут его СЛИШКОМ много.
                        // Причина стоит словами в самой строке
                        message = $"выломал {vein.Broken} бл, а {wanted} в сумке не прибавилось — " +
                                  "похоже, класть уже некуда";
                        break;
                    }
                }
                else
                    idle = 0;
                continue;
            }

            // ПОЧЕМУ НЕ ВЫШЛО — ВСЛУХ. Отказ осмотра тут молчал, и в журнале
            // между «не помню, где видел» и «ухожу в разведку» не было НИ СЛОВА
            // о том, на сколько блоков бот вообще смотрел. Заказчик из-за этого
            // не мог понять, действует ли включённый им чит
            if (vein.Why.Length > 0)
            {
                OnLog?.Invoke(vein.Why);
                lastMiss = vein.Why;
            }

            // ГДЕ УЖЕ ВИДЕЛ. Дешевле разведки: бот проходил мимо этой руды сам,
            // и записал её честно — с открытой гранью и не дальше, чем видно
            var remembered = await ctx.Ores.MineRememberedAsync(wanted, ct);
            if (remembered.Broken > 0)
            {
                veins++;
                continue;
            }
            OnLog?.Invoke(remembered.Why);

            // 3а. ПОРОДУ РАЗВЕДКОЙ НЕ ИЩУТ, А КОПАЮТ ВНИЗ. Разведка бьёт штреки
            // в поисках ЖИЛЫ, а камень — это и есть стена штрека. Зато под
            // ногами он есть почти всегда: на лугу сверху дёрн, а гранит
            // начинается на пару клеток ниже. Живой игрок в этом месте копает
            // вниз — и ровно это делает ручка «КопатьВнизЗаКамнем», до которой
            // наряд раньше не доходил ни при каком значении
            if (Ores.IsStoneOrder(wanted))
            {
                var (went, said) = await ctx.Ores.DigDownForStoneAsync(dugDown, ct);
                if (went <= 0)
                {
                    // «ВНИЗ НЕ ПРОБИТЬСЯ» — ЧЕСТНОГО ИМЕНИ НЕТ, и вот почему:
                    // под одной строкой тут и «упёрся в потолок ручки
                    // КопатьВнизЗаКамнем» (запрет роли), и коренная порода, и
                    // отказ клетки. Различает их прокоп (Ores), а он общего
                    // слова пока не говорит — гадать за него нельзя
                    message = said;
                    break;
                }
                dugDown += went;
                continue;
            }

            // 3б. РАЗВЕДКА. На виду пусто — уходим под землю
            if (!MayProspect || ctx.Prospecting == null)
            {
                // РАБОТУ ЗАПРЕТИЛА РОЛЬ — ровно то, что означает это слово.
                // Ждать бессмысленно: ручку крутит человек, а не время
                message = $"{wanted} на виду нет, а копать вглубь не велено";
                помеха = Setback.Stopped;
                break;
            }
            // ПОТОЛОК — НА ВЕСЬ НАРЯД, А НЕ НА ЗАХОД. Иначе возврат после еды
            // выдавал боту три новые разведки, и он обходил ту же округу по
            // четвёртому кругу (журнал 12:45: «ухожу в разведку (1 из 3)»
            // сразу после того, как одна разведка уже была потрачена)
            if (searchesBefore + searches >= MaxSearches)
            {
                // НЕ «НЕ НАШЁЛ», А «НАШЁЛ И НЕ ДОТЯНУЛСЯ», КОГДА ЭТО ТАК.
                // Решает чистое правило, здесь только факты (см. WhenSearchesRanOut)
                // «ИСКАЛ ЧЕСТНО И НЕ НАШЁЛ» — ЧЕСТНОГО ИМЕНИ НЕТ. Потолок
                // разведок считается НА ВЕСЬ НАРЯД, значит второй заход новых
                // разведок не получит и упрётся сюда же. Но и Unfinished сюда
                // натягивать нельзя: то слово ОБЕЩАЕТ сделанную долю, а наряд
                // с нулём в сумке этого обещания не выполнит и закрутит вечный
                // круг. Ответ, который тут нужен, — «поищи в другом месте»,
                // и в словаре его нет. Сама причина — в строке WhenSearchesRanOut
                message = WhenSearchesRanOut(wanted, searchesBefore + searches,
                    unreachable.Count, lastMiss, SightWords);
                break;
            }

            searches++;
            OnLog?.Invoke($"{wanted} на виду нет — ухожу в разведку " +
                          $"({searchesBefore + searches} из {MaxSearches})" +
                          (ctx.Prospecting.SeeingThroughStone
                              ? $"; смотрю сквозь камень на {ctx.Prospecting.SightRadius()} бл (чит)"
                              : ""));
            double forSearch = Math.Max(60, (deadline - DateTime.UtcNow).TotalSeconds / 2);
            double wasSearch = ctx.Prospecting.MaxSeconds;
            ctx.Prospecting.MaxSeconds = forSearch;
            try
            {
                var search = await ctx.Prospecting.SearchAsync(wanted, ct);
                if (!search.Success)
                {
                    // ПОМЕХУ РАЗВЕДКИ БЕРЁМ ЕЁ ЖЕ СЛОВОМ (Prospecting.WhatStopped).
                    // Разница живая: разведке дают ПОЛОВИНУ остатка наряда, и
                    // её «вышло время» — это ещё не конец наряда; а «дальше
                    // лава» — конец, и второй заход туда же не нужен
                    message = $"разведка: {search.Reason}";
                    помеха = search.Hindrance;
                    break;
                }
            }
            finally
            {
                ctx.Prospecting.MaxSeconds = wasSearch;
            }
        }

        if (ct.IsCancellationRequested)
        {
            // Работу остановил человек — это чужая воля, а не помеха
            message = "наряд отменён";
            помеха = Setback.Stopped;
        }
        // Прокоп вниз — это работа, и в отчёте она обязана быть видна: иначе
        // человек, крутивший «КопатьВнизЗаКамнем», не поймёт, подействовало ли
        if (dugDown > 0)
            message += $"; вниз за породой прокопано {dugDown} кл.";

        Bank();
        int total = ctx.Ores.CountFor(earned, wanted);

        // СКОЛЬКО ЭТО В МЕТАЛЛЕ И ЧЕГО Я НЕ ПОНЯЛ — вслух, рядом с отчётом.
        //
        // Первое: «принёс 4 из 20 слитков» без единиц читается как провал, а
        // 435 единиц металла — это полсотни ударов киркой, и человек вправе
        // видеть, что работа шла. Второе и важнее: если в сумке лежит подошедшее
        // под заказ, про что реестр единиц НЕ ЗНАЕТ, оно в зачёт не пошло — и
        // молчать об этом нельзя: со стороны это ровно «бот копал и не принёс»
        if (ctx.Ores.UnitFor(wanted) != MetalCount.Штуки)
        {
            var счёт = ctx.Ores.MetalIn(earned, wanted);
            OnLog?.Invoke($"{wanted}: в сумке {счёт.Pieces} шт. — это {счёт.Units} ед. металла " +
                          $"({MetalRules.FromUnits(счёт.Units, MetalCount.Слитки)} слитков)" +
                          (счёт.Unknown.Count > 0
                              ? $"; сколько металла в {string.Join(", ", счёт.Unknown)} — " +
                                "реестр не знает, в зачёт это не пошло"
                              : ""));
        }

        return Done(total >= count, message, wanted, count, total, veins, hauls, searches,
            started, earned, помеха);
    }

    /// <summary>
    /// Подобрать с земли россыпь нужного металла. Возвращает, сколько взяли.
    ///
    /// Это и добыча, и разведка сразу: генератор мира кладёт россыпь НАД
    /// залежью, так что подобранный самородок заодно говорит, где копать.
    /// </summary>
    private async Task<int> TakeNuggetsAsync(string wanted, CancellationToken ct)
    {
        if (ctx.Gathering is not { RegistryReady: true } gathering)
            return 0;

        int took = 0;
        foreach (var loose in gathering.FindLoose(SearchRadius, limit: 12))
        {
            if (ct.IsCancellationRequested)
                break;
            if (!gathering.IsNuggetLitter(loose.Code))
                continue;
            // ПОДХОДИТ ЛИ ЭТО ПОД СЛОВО — МЕРКА ОДНА НА ВЕСЬ НАРЯД, И ОНА У
            // РУДЫ (Ores.Suits): она спрашивает реестр выпадений.
            //
            // Здесь стояла ВТОРАЯ КОПИЯ того же правила — своя, по буквам
            // выпадения и по OreCode.MetalGroups. Живого случая она пережила бы
            // (щебень метеорита роняет stone-meteorite-iron, буквы сходятся), но
            // расходилась с первой уже на камне: осмотр берёт «камень» через
            // IsStoneBlock, а копия отвечала на это слово «нет» всегда. Две
            // мерки одного вопроса расходятся молча — на этом наряд и горел.
            if (!ctx.Ores.Suits(loose.Code, wanted))
                continue;
            if (await gathering.PickUpAsync(loose.Pos, ct))
                took++;
        }
        if (took > 0)
            OnLog?.Invoke($"подобрал с земли россыпей: {took}");
        return took;
    }

    /// <summary>
    /// ЧТО НАРЯД ВИДИТ ОТСЮДА: находки, дальность взгляда и готовая строка в
    /// журнал. Один шаг «осмотрелся» — без хождения, добычи и сервера.
    ///
    /// ОТКРЫТО НАРУЖУ НАРОЧНО, как и <see cref="Prospecting.Look"/>. Живой баг
    /// заказчика («медь на виду нет — ухожу в разведку» при включённом чите и
    /// меди в двадцати блоках) весь целиком сидел ЗДЕСЬ, в двух строках: на
    /// какую дальность смотрим и каким словом спрашиваем руду. Обе починки
    /// приёмка молча откатила подменой — и все тесты остались зелёными, потому
    /// что дальше по коду наряд без сервера не ходит и проверять шов было
    /// негде. Теперь есть где.
    /// </summary>
    /// <param name="wanted">Что ищем: «медь», «nativecopper», «камень».</param>
    public OreLook LookForOre(string wanted)
    {
        // НА СКОЛЬКО БЛОКОВ СМОТРИМ — ПРАВИЛО ОДНО, И ОНО В РАЗВЕДКЕ
        // (Prospecting.SightRadius). Живой случай заказчика: читы включены,
        // медь в двадцати блоках, а наряд первой же строкой отвечает «медь на
        // виду нет — ухожу в разведку». Ручка «ДальностьРудыСквозьСтены» жила
        // только у разведки, и наряд — тот, кто смотрит ПЕРВЫМ — про чит не
        // знал вовсе: он смотрел на свои честные 32 бл и уходил копать.
        // Заводить здесь второе такое правило нельзя: одна ручка обязана
        // значить одно и то же
        var (radius, сквозьКамень) = SightNow;

        // ПОРОДУ ИЩУТ ПО СЛОВУ, А НЕ ПО ПУСТОТЕ — и руду тоже. С пустым словом
        // Ores.Find берёт ЛЮБУЮ руду, и запас выборки забирает ближняя чужая
        // жила: с читом одна кварцевая жила под ногами не давала увидеть медь
        // в двадцати блоках. А отбор Ores.Suits(o, «камень») отбрасывал заодно
        // всё, что на «ore-» начинается, — и на «!добудь камень 64» бот, стоя
        // посреди гранитного карьера, отвечал «камень на виду нет».
        // Слово передаётся как есть, Ores.Find понимает и русское, и игровое
        var seen = ctx.Ores.Find(radius, wanted, limit: 24)
            .Where(o => ctx.Ores.Suits(o.Code, wanted) && !unreachable.Contains(o.Pos))
            .ToList();

        // СЛОВА — ТЕ ЖЕ, ЧТО У РАЗВЕДКИ (Prospecting.SightWord). Заказчику на
        // руки выдали проверку «в журнале обязана появиться строка “осмотр на
        // 48 бл СКВОЗЬ КАМЕНЬ (чит)…”», а печатала её только разведка, до
        // которой при работающем чите дело как раз НЕ ДОХОДИТ: наряд находит
        // медь сразу. Человек включал чит, всё работало — и он читал это как
        // «опять не починили», второй раз по тому же поводу
        string чем = SightWords;
        string say = seen.Count > 0
            ? $"осмотр на {чем}: вижу {wanted} — ближняя {seen[0]}"
            : $"осмотр на {чем}: {wanted} не вижу";
        return new OreLook(seen, radius, сквозьКамень, say);
    }

    /// <summary>
    /// Взять ближайшую видимую жилу нужного металла.
    ///
    /// <c>Live</c> — ПОМЕХА ОБЩИМ СЛОВОМ, если наряд её тут знает. Нужна
    /// сроку: без неё «вышло отведённое время» прятало и чужую заявку, и
    /// клетку, до которой не дотянуться, — а это разные новости и разные
    /// починки (см. <see cref="Resume.TimeIsNotACause"/>).
    ///
    /// Отказ САМОЙ ДОБЫЧИ (<see cref="Ores.MineVeinAsync"/>) сюда не попадает
    /// и общего слова не имеет: <see cref="VeinResult"/> говорит строкой, а
    /// гадать за добычу по буквам её строки нельзя.
    /// </summary>
    private async Task<(VeinResult Vein, Setback Live)> MineVisibleAsync(string wanted,
        int stillNeed, double seconds, CancellationToken ct)
    {
        var ores = ctx.Ores;
        var look = LookForOre(wanted);
        var seen = look.Seen.ToList();
        if (seen.Count == 0)
            // «НЕ ВИЖУ» — это ещё не помеха, а повод идти в разведку: своего
            // слова тут нет и не надо
            return (new VeinResult(0, 0, new Dictionary<string, int>(),
                look.Say + (unreachable.Count > 0
                    ? $" (вся видимая недосягаема, пробовал {unreachable.Count} кл.)"
                    : "")), Setback.None);

        // ЧУЖОЕ ПРОВЕРЯЕТСЯ У КАЖДОЙ КЛЕТКИ. Наряд — это автопоиск: клетку
        // выбирает бот, а не человек. Отойти один раз перед началом мало,
        // потому что руда видна на 32 бл во все стороны, в том числе за забор
        if (ctx.Claims is { } owners)
        {
            int was = seen.Count;
            seen = seen.Where(o => owners.Suits(o.Pos)).ToList();
            if (seen.Count == 0)
                // ЧУЖАЯ ЗАЯВКА: ждать её снятия бессмысленно, и слово на это
                // в общем словаре есть ровно одно
                return (new VeinResult(0, 0, new Dictionary<string, int>(),
                    $"вся видимая {wanted} ({was} кл.) лежит у чужого — не трогаю"),
                    Setback.NotMine);
        }

        var target = seen[0];
        // Дальность и чит — в ТОЙ ЖЕ строке, что и находка. Чужие клетки могли
        // отсеяться выше, поэтому называем ту, что берём на самом деле
        OnLog?.Invoke($"осмотр на {Prospecting.SightWord(look.Radius, look.ThroughStone)}: " +
                      $"вижу {wanted} — беру {target}, осталось набрать {stillNeed}");
        if (!await ores.ReachAsync(target.Pos, ct))
        {
            // ПОМЕТИТЬ И ИДТИ К СЛЕДУЮЩЕЙ. Рядом обычно есть другие клетки той
            // же жилы, и к ним подход бывает свободен
            unreachable.Add(target.Pos);
            // НЕ ДОТЯНУТЬСЯ: рука от ожидания не удлинится — лечится это
            // другой клеткой, и наряд ровно за ней и идёт
            return (new VeinResult(0, 0, new Dictionary<string, int>(),
                $"до {target.Pos} не подобраться — беру другую клетку жилы"),
                Setback.OutOfReach);
        }

        return (await ores.MineVeinAsync(target.Pos, ct), Setback.None);
    }

    /// <param name="stop">
    /// ЧЕМ НАРЯД ОБЪЯСНЯЕТ СВОЮ ОСТАНОВКУ — общим словом
    /// (<see cref="Setback"/>). Кладётся ЗДЕСЬ, в одном месте на все выходы
    /// из наряда: расставь его по <c>return</c>'ам, и один рано или поздно
    /// забудут (тот же разбор, что у <see cref="Roads.BuildAsync"/>).
    /// <see cref="Setback.None"/> — «причину не назвали», и это честный ответ
    /// для тех остановок, которым в словаре нет верного имени.
    /// </param>
    private OrderReport Done(bool success, string message, string wanted, int asked, int got,
        int veins, int hauls, int searches, DateTime started,
        IReadOnlyDictionary<string, int> gained, Setback stop = Setback.None)
    {
        // В ЧЁМ СЧИТАНО — В ТОТ ЖЕ ОТЧЁТ. Единицу берём у того, кто и считал
        // (Ores.CountFor), а не заводим себе вторую: разойдись они, и «принёс
        // 19 из 20 слитков» стояло бы под числом, посчитанным в штуках.
        // Камень и доски металлом не меряют — там единица остаётся штуками
        var unit = ctx.Ores?.UnitFor(wanted) ?? MetalCount.Штуки;
        var report = new OrderReport(success, message, wanted, asked, got, veins, hauls,
            searches, (DateTime.UtcNow - started).TotalSeconds, gained, unit)
        {
            // ДОДЕЛАННОМУ НАРЯДУ ПОМЕХИ НЕ ПРИПИСЫВАЕМ: набрал сколько просили
            // — значит ничто ему в итоге не помешало, а последняя мелкая
            // заминка не повод идти на второй круг
            Hindrance = success ? Setback.None : stop
        };
        OnLog?.Invoke(report.ToString());
        return report;
    }
