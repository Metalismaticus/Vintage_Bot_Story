namespace VsBotKit;

/// <summary>Итог наряда: сколько просили и сколько принесли.</summary>
/// <param name="Unit">
/// В ЧЁМ СЧИТАНЫ <see cref="Got"/> и <see cref="Asked"/>.
///
/// Без этого слова отчёт врал молча. Живой журнал 16.08: «медь: принёс 29 из 30;
/// в сумке прибавилось: ore-poor-nativecopper-andesite ×24, …» — человек читал
/// «почти набрал», а на деле это были двадцать девять КУСКОВ бедной руды, то
/// есть меньше пяти слитков. Число и его единица обязаны стоять рядом.
/// </param>
public sealed record OrderReport(
    bool Success,
    string Message,
    string Wanted,
    int Asked,
    int Got,
    int Veins,
    int Hauls,
    int Searches,
    double Seconds,
    IReadOnlyDictionary<string, int> Gained,
    MetalCount Unit = MetalCount.Штуки)
{
    /// <summary>
    /// ПОМЕХА ОБЩИМ СЛОВОМ: пройдёт ли она сама (<see cref="Setback"/>).
    ///
    /// Не вторая копия <see cref="Message"/>, а ответ на ДРУГОЙ вопрос — тот
    /// же разбор, что у дороги (<see cref="RoadReport.Hindrance"/>).
    /// <see cref="Message"/> отвечает человеку («без pickaxe за рудой не
    /// ходят»), <see cref="Hindrance"/> отвечает возврату: ждать бесполезно
    /// или подожди и возьмись заново.
    ///
    /// СВОЕГО СЛОВАРЯ ОСТАНОВОК У НАРЯДА НЕТ, И ЭТО ВИДНО ОТСЮДА. У дороги
    /// есть <see cref="RoadStop"/>, у карьера — <see cref="QuarryStop"/>, у
    /// рейса — <see cref="HaulStop"/>; наряд же всю жизнь говорил строкой, и
    /// перевести строку в слово нечем — строки меняются от правки к правке.
    /// Поэтому слово кладёт КАЖДОЕ место остановки, рядом со своей строкой, а
    /// в отчёт оно попадает одним входом (<c>MiningOrder.Done</c>).
    /// </summary>
    public Setback Hindrance { get; init; } = Setback.None;

    public override string ToString()
    {
        string what = Gained.Count == 0
            ? "ничего"
            : string.Join(", ", Gained.OrderByDescending(g => g.Value).Take(5)
                .Select(g => $"{g.Key} x{g.Value}"));
        // Единицу приписываем ПОСЛЕ чисел, а не между ними: «принёс 19 из 20
        // слитков» читается человеком так же, как читалось «принёс 19 из 20»
        return $"{Wanted}: принёс {Got} из {Asked}" +
               (Unit == MetalCount.Штуки ? "" : $" {MetalRules.Word(Unit)}") +
               (Veins > 0 ? $", жил {Veins}" : "") +
               (Searches > 0 ? $", разведок {Searches}" : "") +
               (Hauls > 0 ? $", рейсов на склад {Hauls}" : "") +
               $"; в сумке прибавилось: {what}; {Seconds:0} с — {Message}";
    }
}

/// <summary>Одна строка наряда: что принести и сколько.</summary>
public sealed record OrderLine(string What, int Count)
{
    public override string ToString() => $"{What} ×{Count}";
}

/// <summary>
/// ОДИН КУСОК ЗАКАЗА, КАК ЕГО НАПИСАЛИ, — до всякой строгости.
/// </summary>
/// <param name="What">Что добывать; пусто — написали одно число.</param>
/// <param name="Count">Сколько: своё число или общее, если своего не написали.</param>
/// <param name="HasCount">Число стояло в самой строке (а не подставлено общее).</param>
/// <param name="Raw">Кусок как набран — им и жалуются человеку, его же он и видит.</param>
public readonly record struct OrderPiece(string What, int Count, bool HasCount, string Raw);

/// <summary>
/// НАРЯД ИЗ НЕСКОЛЬКИХ СТРОК: «медь 20, олово 8» одним заданием.
///
/// ЗАКАЗЧИК 17.08, ДОСЛОВНО: «добавить бы допустим в добыче и еще где логично
/// возможность добавить несколько вещей, а не один ресурс, а точнее вид».
/// До этого «сходи за медью и оловом» значило ДВЕ задачи в очереди: две дороги
/// туда и обратно, два разбора запасов и два рейса на склад — при том что руда
/// лежит в одной и той же округе.
///
/// РАЗБОР ЗДЕСЬ ЧИСТЫЙ И ОДИН НА ВСЕХ. Строку собирают трое — чат («!добудь медь
/// 20, олово 8»), окно управления (поле «список вещей») и нейросеть, — а
/// разбирает один: три разбора одного и того же разошлись бы на первой же
/// запятой.
/// </summary>
public static class OrderLines
{
    /// <summary>
    /// Разобрать заказ в строки. Пустой список — сказать нечего, и почему,
    /// написано в <c>Problem</c>: молча вернуть пустоту значило бы отправить
    /// бота копать неизвестно что.
    /// </summary>
    /// <param name="args">«медь 20», «медь 20, олово 8», «медь 20; олово».</param>
    /// <param name="fallback">
    /// Сколько брать у строки без своего числа («медь 20, олово» — олова тоже
    /// двадцать). Ноль и меньше — у такой строки числа нет, и это отказ.
    /// </param>
    public static (IReadOnlyList<OrderLine> Lines, string Problem) Parse(string? args,
        int fallback = 0)
    {
        var lines = new List<OrderLine>();
        if (args is not { Length: > 0 })
            return (lines, "нужно: наряд <что> <сколько>, можно несколько через запятую " +
                           "(«медь 20, олово 8»)");

        foreach (var кусок in Split(args, fallback))
        {
            // ОТКАЗ ОБЯЗАН ГОВОРИТЬ, КАК НАДО. «Не понял» без образца — это
            // тупик: человек в чате не видит ни полей, ни подсказок, и гадать
            // ему не по чему
            if (кусок.What.Length == 0)
                return ([], $"нужно: наряд <что> <сколько> — в «{кусок.Raw}» есть число, " +
                            "а что добывать, не сказано");
            if (кусок.Count <= 0)
                return ([], $"нужно: наряд <что> <сколько> — для «{кусок.What}» не сказано, сколько " +
                            "(«медь 20»; в окне управления общее число стоит в поле «сколько»)");
            lines.Add(new OrderLine(кусок.What, кусок.Count));
        }

        return lines.Count > 0
            ? (lines, "")
            : ([], "нужно: наряд <что> <сколько>, можно несколько через запятую");
    }

    /// <summary>
    /// ТО ЖЕ САМОЕ, НО ДЛЯ ПОКАЗА, А НЕ ДЛЯ ПУСКА: числа может ещё не быть.
    ///
    /// ЗАЧЕМ ОТДЕЛЬНО ОТ <see cref="Parse"/>. Заказчик просил показывать разбор
    /// заказа прямо в конструкторе, ПОКА он набирает: «человек пишет „медь“ и
    /// „20“». Между этими двумя нажатиями в поле стоит одна «медь» — для ПУСКА
    /// это законный отказ («не сказано, сколько»), а для ПОКАЗА отказ не нужен:
    /// из какого блока падает медь, известно и без числа, и спрятать это до
    /// набора количества значило бы показывать пустоту как раз тогда, когда
    /// человеку и надо смотреть.
    ///
    /// ВТОРОГО РАЗБОРА ЗАПЯТЫХ ЗДЕСЬ НЕТ: режет строку тот же <see cref="Split"/>,
    /// что и у пуска. Разные тут ровно правила строгости, и они названы вслух.
    /// </summary>
    public static IReadOnlyList<OrderLine> Reading(string? args, int fallback = 0) =>
        Split(args, fallback)
            .Where(к => к.What.Length > 0)
            .Select(к => new OrderLine(к.What, Math.Max(0, к.Count)))
            .ToList();

    /// <summary>
    /// РАЗРЕЗАТЬ ЗАКАЗ ПО ЗАПЯТЫМ — одно место на пуск и на показ.
    ///
    /// Строгости тут нет никакой: что написано, то и вернули. Решать, законна
    /// ли строка без числа, — дело зовущего: <see cref="Parse"/> откажется,
    /// <see cref="Reading"/> покажет.
    /// </summary>
    public static IReadOnlyList<OrderPiece> Split(string? args, int fallback = 0)
    {
        var pieces = new List<OrderPiece>();
        if (args is not { Length: > 0 })
            return pieces;

        foreach (string piece in args.Split([',', ';'], StringSplitOptions.RemoveEmptyEntries))
        {
            var words = piece.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            if (words.Length == 0)
                continue;

            // ЧИСЛО — ПОСЛЕДНЕЕ СЛОВО, а имя — всё, что до него. Имена вещей
            // бывают из двух слов («метеоритное железо»), и резать по первому
            // пробелу значило бы терять половину названия
            bool hasCount = int.TryParse(words[^1], out int count);
            string what = hasCount ? string.Join(" ", words[..^1]) : string.Join(" ", words);
            pieces.Add(new OrderPiece(what, hasCount ? count : fallback, hasCount, piece.Trim()));
        }

        return pieces;
    }

    /// <summary>
    /// ЗАКАЗ, ЗАПИСАННЫЙ В ПОЛЕ ЗАДАЧИ, — ОДНОЙ СТРОКОЙ, как его пишут в чате.
    ///
    /// Поле «список вещей» лежит в задаче СПИСКОМ строк («медь 20», «олово 8»),
    /// а разбирает заказ одно чистое правило, и на вход ему идёт одна строка.
    /// Склейка эта нужна двоим — сборщику аргументов навыка и разбору для окна
    /// (<see cref="WorkKind.Ordered"/>), — и написанная дважды разошлась бы
    /// разделителем: склей окно через пробел, и «медь 20 олово 8» стало бы
    /// одной вещью с именем «медь 20 олово».
    /// </summary>
    public static string Written(WorkItem job, string field) =>
        string.Join(", ", job.Texts(field));

    /// <summary>Собрать строки обратно в заказ — ровно так, как его понимает <see cref="Parse"/>.</summary>
    public static string Join(IEnumerable<OrderLine> lines) =>
        string.Join(", ", lines.Select(l => $"{l.What} {l.Count}"));

    /// <summary>
    /// ОДИН ИТОГ НА ВЕСЬ МНОГОСТРОЧНЫЙ НАРЯД. Чистое правило: человеку нужен
    /// один ответ, а не три отчёта подряд, и по нему должно быть видно, какая
    /// именно строка не вышла.
    /// </summary>
    public static string Say(IReadOnlyList<OrderReport> reports)
    {
        if (reports.Count == 0)
            return "наряд пуст: ни одной строки";
        if (reports.Count == 1)
            return reports[0].ToString();
        int done = reports.Count(r => r.Success);
        return $"наряд из {reports.Count} строк: сделано {done}. " +
               string.Join(" | ", reports.Select(r => r.ToString()));
    }

    /// <summary>Весь наряд удался только тогда, когда удалась КАЖДАЯ строка.</summary>
    public static bool AllDone(IReadOnlyList<OrderReport> reports) =>
        reports.Count > 0 && reports.All(r => r.Success);
}

