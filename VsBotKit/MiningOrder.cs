/// <summary>
/// НАРЯД: «принеси столько-то того-то» — от слов до сумки.
///
/// Зачем отдельно от всего остального. Каждая часть работы у бота уже есть:
/// найти жилу (<see cref="Ores"/>), прокопаться (<see cref="Tunnel"/>), уйти
/// на глубину (<see cref="Prospecting"/>), разгрузиться (<see cref="Depot"/>),
/// снарядиться (<see cref="Stock"/>), добыть не-руду (<see cref="Errands"/>).
/// Не было главного — ПОРЯДКА, в котором это делают. И порядок этот один и
/// тот же, кто бы ни отдал приказ: человек в чате, панель или нейросеть.
/// Написанный трижды, он разошёлся бы в мелочах уже к вечеру.
///
/// ПОРЯДОК ТАКОЙ:
/// 1. снарядиться — кирка, факелы, еда (без кирки идти незачем);
/// 2. брать то, что видно, — это дёшево;
/// 3. видно нечего — уйти в разведку под землю;
/// 4. сумка полна — рейс на склад и обратно в забой;
/// 5. набрали или кончились силы — честный отчёт с числами.
///
/// СЧИТАЕМ ПРИБАВКУ В СУМКЕ, а не удары киркой: это единственное число,
/// которое человек может проверить сам.
///
/// Класс — механизм. Сколько времени дать, копать ли вглубь, носить ли на
/// склад, решает роль.
/// </summary>
public class MiningOrder
{
    private readonly BotContext ctx;

    public MiningOrder(BotContext ctx) => this.ctx = ctx;

    public event Action<string>? OnLog;

    // ---------------- настройки ----------------

    /// <summary>Сколько времени отводится на весь наряд, секунд.</summary>
    public double MaxSeconds { get; set; } = 1800;

    /// <summary>В каком радиусе искать выходы руды.</summary>
    public int SearchRadius { get; set; } = 32;

    /// <summary>Уходить под землю, когда на виду ничего нет.</summary>
    public bool MayProspect { get; set; } = true;

    /// <summary>Сколько раз подряд уходить в разведку, прежде чем сдаться.</summary>
    public int MaxSearches { get; set; } = 3;

    /// <summary>Носить добытое на склад, когда сумка полна.</summary>
    public bool MayHaul { get; set; } = true;

    /// <summary>Снаряжаться перед выходом (кирка, факелы, еда).</summary>
    public bool CheckStockFirst { get; set; } = true;

    /// <summary>Подбирать с земли куски самородной руды — это тоже добыча.</summary>
    public bool MayTakeNuggets { get; set; } = true;

    /// <summary>
    /// Без чего не выходить вовсе. Пусто — выходить с чем есть.
    /// По умолчанию кирка: без неё рудокоп бесполезен, и лучше сказать это
    /// сразу, чем через полчаса «нечем брать» на дне шахты.
    /// </summary>
    public List<string> MustHave { get; } = ["pickaxe"];

    /// <summary>Сколько ждать содержимого сумок, прежде чем отказываться из-за него.</summary>
    public double InventorySettleSeconds { get; set; } = 3;

    /// <summary>
    /// Клетки руды, до которых уже пробовали добраться и не смогли.
    ///
    /// Без этой памяти наряд зацикливался насмерть и мгновенно: руда видна в
    /// трёх блоках, но под ней вода — ход рыть нельзя. Бот брал ТУ ЖЕ клетку,
    /// получал тот же отказ, уходил «в разведку», разведка честно отвечала
    /// «руда была на виду с самого начала» — и всё повторялось. Три круга
    /// внутри ОДНОЙ СЕКУНДЫ, и наряд кончался ничем за семь секунд.
    /// </summary>
    private readonly HashSet<BlockPos> unreachable = [];

    /// <summary>
    /// ЧТО СКАЗАТЬ, КОГДА РАЗВЕДКИ КОНЧИЛИСЬ, — чистое правило, и написано оно
    /// затем, что бот СОВРАЛ.
    ///
    /// ЖИВОЙ СЛУЧАЙ (прогон 19.08, 21:12:15–21:12:18). Разведка тремя строками
    /// выше перечислила ЧЕТЫРЕ жилы метеоритного железа в двух-трёх блоках:
    ///   «нашёл: iron в (512059,111,512281), 2 бл; iron в (512059,111,512282),
    ///    2 бл; iron в (512058,111,512282), 2 бл; iron в (512059,111,512283), 3 бл»
    /// А итог наряда прозвучал так:
    ///   «stone-meteorite-iron не нашёл за 3 разведки — тут его, похоже, нет»
    /// Бот сказал «нет» про то, что сам только что видел. Человек по такому
    /// отчёту пойдёт искать метеорит в другом месте, тогда как чинить надо
    /// было снег на луче — и ровно это ему теперь и говорят.
    ///
    /// ВТОРАЯ ПОЛОВИНА ТОГО ЖЕ ВРАНЬЯ — «ТУТ ЕГО, ПОХОЖЕ, НЕТ», И ЕЁ ПОЙМАЛ
    /// САМ ЗАКАЗЧИК: «сейчас читы на иксрей явно неверно работают, бот искал с
    /// читом медь вокруг себя бегал, а не чётко бежал к руде, которая была в
    /// 100 блоках». Чит работал ровно как настроен: ручка
    /// «ДальностьРудыСквозьСтены» стояла на 48, и руда в ста блоках лежала за
    /// пределом взгляда — это НАСТРОЙКА, а не поломка. Но узнать это из отчёта
    /// было нельзя: строка про дальность («осмотр на 48 бл СКВОЗЬ КАМЕНЬ
    /// (чит)») печатается в середине работы и тонет среди сотни других, а ИТОГ
    /// наряда — тот, который человек и читает — говорил про МИР («тут его
    /// нет»), хотя знал только про свои сорок восемь блоков.
    ///
    /// Поэтому дальность теперь стоит в самом отказе, и сказана она ТЕМИ ЖЕ
    /// СЛОВАМИ, что и в осмотре (<see cref="Prospecting.SightWord"/>): два
    /// разных описания одного взгляда человек читал бы как два разных взгляда.
    ///
    /// Правило чистое: ни мира, ни сервера — только числа и строки, поэтому
    /// его проверяет стенд, а не живой прогон (правило 7 проекта).
    /// </summary>
    /// <param name="wanted">Что просили.</param>
    /// <param name="searches">Сколько разведок потрачено всего.</param>
    /// <param name="seenButUnreachable">
    /// Сколько клеток бот УВИДЕЛ и не смог до них добраться (память
    /// <see cref="unreachable"/>). Ноль — искали и не нашли; больше нуля —
    /// нашли и не дотянулись, и это совсем другая беда.
    /// </param>
    /// <param name="lastMiss">Последняя названная причина, почему не дотянулся.</param>
    /// <param name="sight">
    /// На сколько и чем бот смотрел — готовыми словами <see cref="SightWords"/>
    /// («48 бл СКВОЗЬ КАМЕНЬ (чит)»). Пусто — сказать нечего, и тогда про
    /// дальность бот молчит, а не выдумывает.
    /// </param>
    public static string WhenSearchesRanOut(string wanted, int searches,
        int seenButUnreachable, string? lastMiss, string sight = "")
    {
        string где = sight is { Length: > 0 } s ? $" (осмотр на {s})" : "";
        if (seenButUnreachable > 0)
            return $"{wanted} я НАШЁЛ{где}, но не смог до него добраться: " +
                   $"недосягаемых клеток {seenButUnreachable}" +
                   (lastMiss is { Length: > 0 } why ? $", последняя помеха — {why}" : "") +
                   $"; разведок потрачено {searches}, и дело не в них";
        // «ТУТ ЕГО НЕТ» БОЛЬШЕ НЕ ГОВОРИМ: бот знает не про «тут», а про свой
        // радиус. Дальше него он не смотрел вовсе — так и сказано
        return $"{wanted} не нашёл за {searches} разведки{где} — дальше я не смотрел" +
               (sight is { Length: > 0 }
                   ? ", и если руда за этим пределом, поднимите «ДальностьРудыСквозьСтены»"
                   : "");
    }

    /// <summary>
    /// НА СКОЛЬКО И ЧЕМ НАРЯД СМОТРИТ ПРЯМО СЕЙЧАС — одно место на весь наряд.
    ///
    /// Радиус решает разведка (<see cref="Prospecting.SightRadius(int)"/>),
