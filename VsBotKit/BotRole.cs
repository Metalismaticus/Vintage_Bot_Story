namespace VsBotKit;

/// <summary>
/// Роль бота — то, ради чего он живёт: набор способностей, навыков, команд
/// и настроек. Свой бот = свой класс-наследник:
///
/// <code>
/// class СтражРоль : BotRole
/// {
///     public override void Configure(VsBot bot)
///     {
///         bot.Behaviors.Add(new BehaviorAttackHostiles(bot.Context) { DefendRadius = 12 });
///         bot.Movement.MaxFallDamage = 5;                 // смелый: срезает через обрывы
///         bot.Commands.Add("патруль", "обойти периметр", a => ...);
///     }
/// }
/// </code>
/// </summary>
public abstract class BotRole
{
    /// <summary>Имя роли (для логов и приветствия).</summary>
    public virtual string Name => GetType().Name;

    /// <summary>
    /// БОТ, НА КОТОРОМ СТОИТ ЭТА РОЛЬ. Ставит <see cref="VsBot.UseRole"/>,
    /// снимает <see cref="VsBot.СменитьРоль"/>.
    ///
    /// Нужен ровно для одного: поворот ручки обязан лечь в след роли, иначе
    /// накрученное в окне ПОСЛЕ сборки не снимется при смене роли и уедет к
    /// новому боту чужой настройкой. Ручку крутят через
    /// <see cref="RoleKnobs.Apply(BotRole, string, System.Text.Json.JsonElement)"/>,
    /// а бота там нет — отсюда и обратная ссылка.
    ///
    /// Наружу не выведен нарочно: это проводка, а не то, чем управляет роль.
    /// </summary>
    internal VsBot? Хозяин { get; set; }

    /// <summary>
    /// РУЧКИ, ЧЬЁ НЫНЕШНЕЕ ЗНАЧЕНИЕ БОТ ВЫБРАЛ САМ, А НЕ УСЛЫШАЛ ОТ ЧЕЛОВЕКА.
    /// Пусто почти всегда: гадает бот редко и только там, где иначе не сдвинется
    /// с места.
    /// </summary>
    private HashSet<string>? догадки;

    /// <summary>
    /// ЭТО ЗНАЧЕНИЕ БОТ ВЫДУМАЛ САМ (или больше не выдумывает) — единственная
    /// дверь к тому, чтобы «догадка живёт один заход» была ПРАВДОЙ, а не
    /// обещанием в док-строке.
    ///
    /// ЖИВАЯ ЛОВУШКА, НАЙДЕННАЯ ПРИЁМКОЙ, И ОНА ТИХАЯ. Самопоиск склада при
    /// входе в мир (<c>LivingRole.ВзятьСкладЗдесь</c>, «запомнить: false») сам
    /// в пресет не писал и вслух обещал: «В пресет не пишу: это моя догадка».
    /// Но он клал догадку в ЖИВУЮ РУЧКУ, а пресет снимается с ЖИВОЙ РОЛИ
    /// целиком и на КАЖДЫЙ поворот любой ручки (<c>ControlPanel.SetKnob</c> →
    /// <c>PresetLibrary.ЗапомнитьРучки</c> → <c>Capture</c>). То есть догадка
    /// доживала ровно до первого движения мыши в окне — и уезжала в файл роли
    /// молча, вместе с чужим соседским сундуком. Цена: со следующего запуска
    /// <c>Depot.Known</c> истинно, поиск НЕ ПОВТОРИТСЯ НИКОГДА, а снятая галка
    /// «ИскатьСундукиРядом» чужой сундук из пресета уже не уберёт. Проверено
    /// живьём: поворот «ВысотаШтольни» уложил в пресет заодно «Дом».
    ///
    /// ПОЧЕМУ ПОМЕТКА ЖИВЁТ НА РОЛИ, А НЕ У СКЛАДА. Записывающих ДВА, и оба
    /// общие: пресет (<c>PresetLibrary.Capture</c>) и память мест
    /// (<c>ПамятьМест.Запомнить</c>). Спрятать правило внутрь склада значило бы
    /// написать его дважды и разъехаться на первой же роли, которая начнёт
    /// гадать про что-то другое — про дом, про пост, про место костра.
    ///
    /// ЗАБЫВАЕТСЯ САМА, КАК ТОЛЬКО ЧЕЛОВЕК СКАЖЕТ СВОЁ СЛОВО: любой удавшийся
    /// поворот ЭТОЙ ручки снимает пометку (<c>RoleKnobs.Apply</c>), откуда бы
    /// его ни повернули — из окна, из пресета или словом в чат. Иначе
    /// заданный руками склад тоже не попал бы в файл, и починка обернулась бы
    /// второй половиной той же жалобы «запоминание не работает».
    /// </summary>
    /// <param name="ручка">Имя ручки — то же, что видит окно и пресет.</param>
    /// <param name="догадка">
    /// true — значение выбрал бот сам; false — за ним стоит слово человека.
    /// </param>
    protected internal void ПометитьДогадку(string ручка, bool догадка)
    {
        if (догадка)
            (догадки ??= new HashSet<string>(StringComparer.OrdinalIgnoreCase)).Add(ручка);
        else
            догадки?.Remove(ручка);
    }

    /// <summary>
    /// ЗА ЭТИМ ЗНАЧЕНИЕМ НЕТ СЛОВА ЧЕЛОВЕКА. Спрашивают оба записывающих —
    /// пресет и память мест, — и оба такое значение пропускают.
    /// </summary>
    public bool ЭтоДогадкаБота(string ручка) => догадки?.Contains(ручка) == true;

    /// <summary>
    /// Что бот сейчас держит своей догадкой — именами ручек, для честного
    /// ответа человеку. Пусто — гадать не о чем.
    /// </summary>
    public IReadOnlyCollection<string> ДогадкиБота =>
        догадки is { Count: > 0 } d ? d.ToList() : [];

    /// <summary>
    /// Настройка бота: подключить способности, навыки, команды, задать параметры.
    /// Вызывается при UseRole; на боте, который уже в мире, — ещё и при смене
    /// роли на ходу (<see cref="VsBot.СменитьРоль"/>).
    ///
    /// ДОБАВЛЯТЬ ЗДЕСЬ МОЖНО СВОБОДНО, СНИМАТЬ ЗА СОБОЙ НЕ НАДО: всё, что
    /// Configure тронул — пороги, подписки, способности, команды, навыки, —
    /// бот снимает сам, механически, разницей снимков своих полей
    /// (<see cref="СледРоли"/>). Рукописного «а тут не забудь отписаться» в
    /// ролях нет и заводить его нельзя: он разошёлся бы с кодом молча.
    /// </summary>
    public abstract void Configure(VsBot bot);

    /// <summary>
    /// РОЛЬ СНИМАЮТ — погаси то, что живёт СВОЕЙ жизнью.
    ///
    /// Поля, подписки и добавленные способности возвращает бот сам, обходом;
    /// сюда попадает только то, чего в полях бота не видно: фоновая задача,
    /// таймер, открытый сеанс. Живой случай, ради которого метод и заведён, —
    /// роль на нейросети: её круг раздумий (<c>LlmRole.loopCts</c>) крутится
    /// отдельной задачей и гаснет лишь при следующем входе ЭТОЙ ЖЕ роли.
    /// Смени роль без этого — и два мозга на одном теле, причём второй тратит
    /// деньги заказчика.
    ///
    /// Возвращает то, что вправду остановлено, — СЛОВАМИ и по именам: смена
    /// роли обязана называть потерю, а не глотать её.
    /// </summary>
    public virtual IEnumerable<string> Снять(VsBot bot) => [];

    /// <summary>Бот вошёл в мир — можно поздороваться или начать дело.</summary>
    public virtual Task OnJoinedAsync(VsBot bot) => Task.CompletedTask;

    /// <summary>
    /// Ручку роли повернули СНАРУЖИ — из окна управления, из пресета или из
    /// чата. Роль обязана донести новое значение до механизма прямо здесь.
    ///
    /// Ради живого случая, который стоил заказчику вечера: он задал склад в
    /// панели, отправил бота разгружаться и получил «склад не задан — некуда
    /// нести». Настройки роли читались ОДИН РАЗ, в <see cref="Configure"/>, а
    /// панель крутит их позже, уже в мире, — и всё, повёрнутое после входа,
    /// оставалось лежать в поле роли мёртвым грузом.
    ///
    /// Чинить это в каждой ручке по отдельности значит завести столько же
    /// мест, где можно забыть. Место одно:
    /// <see cref="RoleKnobs.Apply(BotRole, string, System.Text.Json.JsonElement)"/>
    /// зовёт этот метод после КАЖДОГО удачного поворота.
    /// </summary>
    public virtual void OnKnobsChanged() { }

    /// <summary>
    /// Виды работ, которые эта роль умеет ставить в очередь на вечер.
    /// null — конструктора работ у роли нет, и очередь честно об этом скажет.
    ///
    /// Спрашивается ТОЛЬКО НА ЧТЕНИЕ и потому ручкой роли не становится
    /// (<see cref="RoleKnobs.Of"/> берёт свойства, которые можно записать):
    /// список работ — это устройство роли, а не настройка, которую крутят.
    /// </summary>
    public virtual WorkCatalog? Works => null;
}
