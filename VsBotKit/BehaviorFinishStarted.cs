namespace VsBotKit;

/// <summary>
/// ДОДЕЛАТЬ НАЧАТОЕ, ПОКА ДЕЛАТЬ НЕЧЕГО.
///
/// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЗАВЕДЕНО (журнал 16.08). Боту не хватало ножа,
/// он разложил цепочку вслух и пошёл по ней:
///     [запасы] чтобы получить Knife, надо: вытесать knifeblade-peridotite ×1;
///              добыть stick ×1; сделать knife-generic-peridotite ×1
/// Тесание прошло — в 13:11:51 отчёт наряда говорит «в сумке прибавилось:
/// knifeblade-peridotite x1». Палки не нашлось, цепочка честно оборвалась на
/// шаге «добыть», и лезвие пролежало в сумке до конца вечера. Заказчик
/// дословно: «вырезал из камня, но не скрафтил с палкой в инвентаре»,
/// «почему он не делал крафт инструментов в простое».
///
/// ЧЕГО НЕ ХВАТАЛО НА САМОМ ДЕЛЕ. Разбор запасов полуфабрикат ВИДИТ и сам:
/// в 12:57:03 план на топор уже начинался не с камня, а с палки — вытесанное
/// топорище он вычел из сумки. Не хватало ПОВОДА спросить: цепочку запасов
/// зовут только перед нарядом (<see cref="Stock.ReplenishAsync"/>), а между
/// нарядами бот стоит («без дела 60 с — стою, так настроено») и о начатом деле
/// не вспоминает никто.
///
/// ПОЧЕМУ ЭТО ОТДЕЛЬНАЯ СПОСОБНОСТЬ, А НЕ ЧАСТЬ БЕЗДЕЛЬЯ. Безделье
/// (<see cref="BehaviorIdle"/>) решает, КУДА ДЕТЬСЯ — стоять, бродить, уйти
/// домой; оно держит ход, пока идёт. Доделка — обычное хозяйственное дело,
/// того же веса, что «сменить сточенный инструмент» и «разложить снаряжение»,
/// и жить она обязана рядом с ними: перед бездельем, а не внутри него.
///
/// ХОДИТЬ ОНА НИКУДА НЕ БУДЕТ, и это её главное свойство. Берутся ТОЛЬКО те
/// нехватки, в разборе которых не осталось ни одного шага «добыть»
/// (<see cref="Stock.CanFinishInPlace"/>). Иначе способность с весом хозяйства
/// уводила бы бота через полкарты за палкой — то самое кружение, на которое
/// заказчик уже жаловался.
///
/// Класс — механизм. Включать ли её и как часто спрашивать, решает роль
/// (ручка «ДоделыватьНачатое»).
/// </summary>
public class BehaviorFinishStarted : BotBehavior
{
    private readonly BotContext ctx;

    public BehaviorFinishStarted(BotContext ctx) => this.ctx = ctx;

    /// <summary>
    /// Способность выключена по умолчанию — это решение роли. Продавцу за
    /// прилавком нож из лезвия собирать незачем, а копателю без топора не
    /// работать вовсе.
    /// </summary>
    public bool Enabled { get; set; }

    /// <summary>
    /// Пауза между заходами, секунд.
    ///
    /// ЧИСЛО НЕ ИЗ ВКУСА, А ИЗ ЦЕНЫ ВОПРОСА. Один заход — это разбор «что из
    /// чего» по всем требованиям сразу: обход реестра рецептов и опись сумки.
    /// Спрашивать это каждый тик значило бы вернуть те самые секунды тишины,
    /// ради ухода от которых разбору поставили потолок перебора. Минута —
    /// это и не заметно человеку, и не заметно счёту.
    /// </summary>
    public double CooldownSeconds { get; set; } = 60;

    /// <summary>Доделал: отчёт запасов целиком.</summary>
    public event Action<string>? OnFinished;

    /// <summary>Не вышло — с причиной. Молчаливого отказа здесь нет.</summary>
    public event Action<string>? OnRefused;

    /// <summary>
    /// ЖАЛОБА ГРОМКО ОДИН РАЗ, А НЕ КАЖДУЮ МИНУТУ ВСЮ НОЧЬ.
    ///
    /// ПРИЧИНА, А НЕ ВКУС. Разбор обещает работу на месте по РЕЕСТРУ («лезвие
    /// есть, палка есть, рецепт есть»), а сервер отказывает по СВОЕЙ причине:
    /// не пришёл реестр камнетёсства, сетка не приняла раскладку, вещь в руке
    /// не та. Причина при этом не проходит сама — она держится, пока не
    /// поменяется обстановка. Способность заходит раз в минуту, значит без
    /// сторожа человек получал бы 1440 одинаковых строк в сутки: ровно тот шум,
    /// от которого в этом проекте уже лечили и голод, и разломы, и бурю.
    ///
    /// Молчать тоже нельзя — бот, час назад сказавший «нож не собрать» и с тех
    /// пор молчащий, выглядит здоровым. Поэтому тревога, а не счётчик: новая
    /// причина слышна сразу, а старая напоминает о себе раз в пять минут.
    /// </summary>
    /// <remarks>
    /// Своего события «обошлось» тревоге здесь не дают нарочно: отбой человек и
    /// так читает — это <see cref="OnFinished"/> с отчётом запасов, сказанный в
    /// ту же секунду. Второй строкой «обошлось» рядом с «доделал начатое: 1 шт.»
    /// был бы пересказ.
    /// </remarks>
    private readonly Alarm неСобирается = new("доделать начатое не выходит");

    private DateTime lastRun = DateTime.MinValue;

    public override async Task<bool> TickAsync(CancellationToken ct)
    {
        if (!Enabled)
            return false;
        // Вне мира и мёртвым сервер отказывает во всём, в том числе в крафте
        if (!ctx.Bot.Joined || ctx.Self.IsDead)
            return false;
        if ((DateTime.UtcNow - lastRun).TotalSeconds < CooldownSeconds)
            return false;
        if (ctx.Stock is not { } запасы)
            return false;

        // ВОПРОС ЗАДАЁМ ДО ЗАХВАТА ТЕЛА. Он не трогает ни сеть, ни мир — только
        // сумку и реестры, — а тело, взятое ради «оказалось, нечего доделывать»,
        // на этот тик выключило бы всё, что стоит ниже
        var начатое = запасы.StartedWork();
        if (начатое.Count == 0)
        {
            lastRun = DateTime.UtcNow;
            return false;
        }

        using var hold = ctx.Turn.TryTake("доделать начатое", BodyArbiter.Importance.Routine, ct);
        if (hold == null)
            return false;   // тело занято — распорядитель уже сказал, кем

        StockReport отчёт;
        try
        {
            отчёт = await запасы.FinishStartedAsync(hold.Token);
        }
        finally
        {
            // Отсчёт паузы — от КОНЦА захода: иначе долгая тёска съедала бы
            // паузу целиком и способность бралась за дело подряд
            lastRun = DateTime.UtcNow;
        }

        if (отчёт.Crafted > 0)
        {
            // ОБСТАНОВКА ПЕРЕМЕНИЛАСЬ — тревогу снимаем, чтобы следующий отказ
            // (если он будет) прозвучал СРАЗУ, а не через оставшиеся минуты
            // молчания. Вслух отбой не говорим: он и есть строка ниже
            неСобирается.Clear();
            OnFinished?.Invoke(отчёт.Message);
            return true;
        }
        // ЧЕСТНЫЙ ОТКАЗ, А НЕ МОЛЧАНИЕ: разбор обещал работу на месте, а её не
        // вышло — значит либо реестр не пришёл, либо сервер не принял сбор, и
        // человек обязан это прочитать. Но ОДИН РАЗ НА ПРИЧИНУ — см. разбор у
        // самой тревоги: заход здесь раз в минуту, и без сторожа это сутки
        // одинаковых строк
        if (неСобирается.Raise(отчёт.Message))
            OnRefused?.Invoke(отчёт.Message);
        return false;
    }
}
