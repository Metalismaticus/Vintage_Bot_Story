namespace VsBotKit;

/// <summary>
/// ОТКРЫТАЯ БОТОМ ДВЕРЬ — одна запись долга.
/// </summary>
/// <param name="Door">
/// Клетка ХОЗЯИНА двери (низ двухблочной створки, см.
/// <see cref="WorldModel.DoorClickPos"/>). Именно по хозяину и кликают, и
/// спрашивают состояние: у верхней половины стоит служебный блок мультиблока,
/// и две записи на одну дверь означали бы два клика по одной створке — то есть
/// «закрыл, а потом открыл обратно».
/// </param>
/// <param name="At">Когда открыли. Отсюда считается терпение долга.</param>
/// <param name="TriedAt">
/// Когда последний раз кликали, ЗАКРЫВАЯ. <see cref="DateTime.MinValue"/> —
/// ни разу. Нужно потому, что ответ сервера приходит не мгновенно, а ход тела
/// идёт двадцать раз в секунду: без этой отметки бот на каждом такте слал бы
/// новый клик, и створка мигала бы «открыл-закрыл-открыл».
/// </param>
/// <param name="Tries">Сколько раз кликали, закрывая (для честного отказа словами).</param>
/// <param name="Missed">
/// Сколько раз терпение уже выходило впустую, а долг оставался за нами (см.
/// <see cref="DoorPayment.Later"/>). Нужно, чтобы отказ не выглядел одинаково
/// на первой минуте и на двадцатой: человек по журналу должен видеть, что
/// створка висит за ботом давно, а не что он «опять» про неё вспомнил.
/// </param>
/// <param name="Side">
/// С КАКОГО БОКА СТВОРКИ БОТ СТОЯЛ, КОГДА ОТКРЫЛ ЕЁ (<see cref="DoorDebt.DoorSide"/>),
/// — ось и знак. Отсюда и только отсюда узнаётся «прошёл ли я эту дверь».
///
/// Ось запоминается ОДНА, та, что была в миг открытия, и второй раз не
/// выбирается: иначе шаг вдоль стены менял бы «поперёк стены» на «вдоль», и
/// ответ «прошёл» переворачивался бы от каждого топтания. Тот же приём, что
/// у укрытия (<see cref="Shelter.HideBehindDoor"/>), и правило у них общее.
/// </param>
/// <param name="Passed">
/// ПРОШЁЛ ЛИ БОТ ЭТУ ДВЕРЬ — то есть побывал ли он по ДРУГУЮ её сторону с тех
/// пор, как открыл. Отметка ЛИПКАЯ: раз прошёл — прошёл навсегда, пока долг
/// не снят. Иначе бот, сходивший за порог и вернувшийся обратно, снова считался
/// бы «ещё не прошедшим», и своя же дверь не закрылась бы никогда.
/// </param>
public sealed record DoorOwed(BlockPos Door, DateTime At, DateTime TriedAt, int Tries,
    int Missed = 0, (int Axis, int Sign) Side = default, bool Passed = false)
{
    public override string ToString() => $"дверь {Door}";
}

/// <summary>Что делать с долгом ПРЯМО СЕЙЧАС (см. <see cref="DoorDebt.PayRule"/>).</summary>
public enum DoorPayment
{
    /// <summary>Случай не подошёл — ждём, долг остаётся за нами.</summary>
    Wait,

    /// <summary>Кликать: дверь наша, открыта, достаём рукой и она больше не нужна.</summary>
    Close,

    /// <summary>Долга нет: дверь уже закрыта (нами или кем-то). Молча вычёркиваем.</summary>
    Gone,

    /// <summary>
    /// СЛУЧАЯ ТАК И НЕ ВЫПАЛО: сказать вслух, какую дверь и что помешало, — но
    /// ДОЛГ ОСТАВИТЬ ЗА СОБОЙ.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ради которого этот ответ и заведён (журнал 18.08):
    ///   00:19:56 [движение] открыл дверь (512062, 112, 512252)
    ///   00:20:05 погиб, возрождаюсь … умер на 512062, 112, 512252
    ///   00:20:08 [позиция] … Z 512252 → 511972   (возродился в 280 бл от дома)
    ///   00:20:26 [движение] НЕ ЗАКРЫЛ за собой дверь (512062, 112, 512252):
    ///            её клетки не видно — этот кусок мира ко мне не приходил;
    ///            жду уже 30 с — случая закрыть так и не выпало
    /// Отказ был честный, и всё-таки бедой: долг тут же ВЫЧЁРКИВАЛСЯ. С 00:24
    /// бот вернулся в тот самый проём и до конца журнала (00:43) шесть раз
    /// открывал и закрывал СОСЕДНЮЮ створку — стоя в полутора блоках от той,
    /// которую сам оставил нараспашку. Двадцать три минуты, и ни одной попытки:
    /// вспоминать было уже нечего.
    ///
    /// «Не могу сейчас» и «не смогу никогда» — разные вещи, и путать их нельзя:
    /// непрогруженный чанк прогрузится, рука дотянется, из проёма бот выйдет.
    /// Насовсем долг снимает только <see cref="GiveUp"/> — то есть случай, в
    /// котором ждать нечего.
    /// </summary>
    Later,

    /// <summary>
    /// Отдать долг НЕ ВЫЙДЕТ И ВПРЕДЬ — вычёркиваем и ГОВОРИМ ВСЛУХ, какую дверь
    /// и почему. Такой случай ровно один: закрывать запрещено настройкой, и
    /// пока человек её не повернёт, ждать нечего.
    /// </summary>
    GiveUp
}

/// <summary>
/// ДОЛГ ЗА ОТКРЫТУЮ ДВЕРЬ: память о дверях, которые бот открыл сам, и правило,
/// когда их закрывать.
///
/// ЗАКАЗ ЧЕЛОВЕКА, дословно: «не всегда закрывает за собой дверь».
///
/// ЖИВОЙ СЛУЧАЙ (журнал 16.08, два дверных проёма в одной стене — x 512061 и
/// x 512062, обе на z 512252):
///   12:45:11 [движение] открыл дверь (512061, 112, 512252)
///   12:45:12 [движение] закрыл за собой дверь (512061, 112, 512252)
///   12:45:13 [движение] открыл дверь (512062, 112, 512252)
///   12:45:14 [движение] упёрся на точке 3/4 (512081, 112, 512253)…
/// и дальше про эту дверь НИ СЛОВА. Она осталась открытой на весь вечер: в
/// 14:39:05 бот открывал её снова, а между этими часами створка стояла нараспашку.
///
/// ПОЧЕМУ ТАК ВЫШЛО — разобрано по коду, а не угадано. Закрытие было привязано
/// к «прошёл насквозь», и сторона прохода бралась как вектор от створки к
/// ТОЧКЕ КЛИКА, а точку клика выбирал подход к двери — по ГЛАВНОЙ ОСИ СБЛИЖЕНИЯ.
/// У двух дверей в одной стене эта ось идёт ВДОЛЬ СТЕНЫ: бот встал сбоку (в
/// клетке соседней двери, x 512061), открыл — и запомнил сторону «запад».
/// А ушёл он потом на север (z 512254). Скалярное произведение честно ответило
/// «ты всё ещё со стороны открытия», и так отвечало бы вечно: мерили не ту ось.
/// Через полминуты дверь МОЛЧА забывалась, и долг исчезал вместе с памятью.
///
/// ЧЕМ ЭТО ЗАМЕНЕНО. Плоскость створки по-прежнему никто не угадывает: пока
/// дверь открыта, угадывать её нечем. Спрашивается ДВА ПОЛОЖЕНИЯ САМОГО БОТА —
/// где он стоял, когда сервер подтвердил открытие, и где стоит сейчас, — и по
/// ним считается БОК (<see cref="DoorSide"/>). Бок сменился — значит прошёл,
/// значит дверь больше не нужна и пора закрывать; бок тот же — значит сквозь неё
/// мне ещё идти. Живой игрок рассуждает ровно так же и никогда не считает
/// векторов.
///
/// А ВОТ ЧЕГО НЕ ХВАТАЛО ДО 19.08 и что стоило заказчику жалобы «плохо стал
/// идти»: спрашивалось только «нужна ли она мне ПРЯМО СЕЙЧАС» — не стою ли в
/// проёме и не по курсу ли она. У бота, чей поход оборвался, курса нет вовсе,
/// и ответом всегда выходило «не нужна». Разбор с журналом — у заставы 4
/// в <see cref="PayRule"/>.
///
/// ДОЛГ, А НЕ ШАГ МАРШРУТА — и это главное. Открытых дверей помнится НЕСКОЛЬКО
/// (тамбур из двух створок был неизбежен: вторая затирала первую), долг
/// переживает сорванный путь, отменённую работу и выбор другой дороги, и его не
/// стирает перезапуск движения. Снимается он ровно двумя способами: закрытием
/// ПО ФАКТУ ОТ СЕРВЕРА или честным отказом со словами и координатами.
///
/// ЧЕГО ЗДЕСЬ НЕТ. Класс не кликает по двери и не ходит к ней: кликает и ходит
/// движение (<see cref="Movement"/>), там же живут щуп «дверь по курсу»
/// (<c>FindDoorAhead</c>) и открывание. Второй такой механики в проекте быть не
/// должно, поэтому здесь только ПАМЯТЬ и ПРАВИЛА.
///
/// Закрывать ли за собой вообще — решает роль (ручка «ЗакрыватьЗаСобойДвери»,
/// она же <see cref="Movement.CloseDoorsBehind"/>).
/// </summary>
public sealed class DoorDebt
{
    /// <summary>Под замком: долг пишет ход тела, а спрашивать его может и панель.</summary>
    private readonly object gate = new();

    private readonly List<DoorOwed> owed = [];

    /// <summary>Что бот не смог за собой закрыть — с координатами и причиной.</summary>
    public event Action<string>? OnLog;

    /// <summary>
    /// Сколько дверей вообще держать в долгу. Предел механизма, а не политика:
    /// живой игрок не оставляет за спиной десяток распахнутых створок, а список
    /// без предела рос бы всю ночь.
    ///
    /// Переполнение НЕ МОЛЧИТ: самая старая дверь вычёркивается, и об этом
    /// говорится вслух — она ОСТАНЕТСЯ открытой, и закрыть её будет некому.
    /// </summary>
    public int MaxOwed { get; set; } = 8;

    /// <summary>Сколько дверей за ботом числится.</summary>
    public int Count { get { lock (gate) return owed.Count; } }

    /// <summary>Все двери, что бот за собой числит.</summary>
    public IReadOnlyList<DoorOwed> Owed { get { lock (gate) return owed.ToArray(); } }

    /// <summary>
    /// Числится ли за нами эта дверь (клетка — хозяин створки). Спрашивает
    /// стенд: «какая именно дверь осталась в долгу» — это тот вопрос, ответ на
    /// который в живом журнале и пропал.
    /// </summary>
    public bool Mine(BlockPos door)
    {
        lock (gate)
            return owed.Any(d => d.Door == door);
    }

    // ---------------- чистое правило ----------------

    /// <summary>
    /// ЧТО ДЕЛАТЬ С ДОЛГОМ ПРЯМО СЕЙЧАС — чистое правило: ни мира, ни бота,
    /// ни часов, только числа. Молчаливого ответа среди возможных нет.
    ///
    /// ПОРЯДОК ЗАСТАВ И ПОЧЕМУ ИМЕННО ТАКОЙ:
    ///
    /// 1. ДВЕРЬ УЖЕ ЗАКРЫТА — долга нет вовсе, и спрашивать дальше нечего.
    ///    Первой заставой нарочно: закрытая створка ничего не должна даже при
    ///    выключенной настройке, а вычеркнуть её надо молча — это не событие.
    ///    Спрашивается это ТОЛЬКО У ВИДИМОЙ КЛЕТКИ: у непрогруженного куска
    ///    мира «закрыта ли дверь» ответа нет вовсе, а модель отдаёт там «нет
    ///    двери», то есть «закрыта». Отойди бот на два чанка — и долг списался
    ///    бы сам собой с враньём в журнале. Тот же приём, что у временных лесов
    ///    (<see cref="TempBlocks.MayPlaceRule"/>): не видно — значит не знаем.
    ///
    /// 2. ЗАКРЫВАТЬ ЗАПРЕЩЕНО НАСТРОЙКОЙ — отказ СО СЛОВАМИ. Молча забыть было
    ///    бы хуже всего: человек, снявший галочку, вправе увидеть, во что именно
    ///    ему это обошлось, а не находить открытые двери в мире через неделю.
    ///
    /// 3. СТОЮ В САМОМ ПРОЁМЕ — рано. Живой игрок не захлопывает дверь, стоя
    ///    в ней. Это же и спасает от «открыл-закрыл у себя перед носом»: тело
    ///    открывшего бота стоит В клетке двери у старых створок, где коллизия —
    ///    тонкая пластина у края.
    ///
    /// 4. ЕЩЁ НЕ ПРОШЁЛ ЭТУ ДВЕРЬ — рано, и это САМАЯ ДОРОГАЯ из застав.
    ///    Дверь открывают ради прохода; пока проход не состоялся, дверь нужна,
    ///    и закрывать её — значит захлопывать её перед собственным носом.
    ///
    ///    ЖИВОЙ СЛУЧАЙ (журнал 18.08, 23:55:11–23:56:08), словами заказчика —
    ///    «плохо стал идти»:
    ///      23:55:11 открыл дверь (512061, 112, 512252)
    ///      23:55:12 упёрся на точке 3/6 (512061, 112, 512251),
    ///               стою (512061,5, 112, 512252,3)      ← это сама клетка двери
    ///      23:55:25 закрыл за собой дверь (512061, 112, 512252)
    ///      23:55:27 открыл дверь (512061, 112, 512252)
    ///      23:55:45 закрыл за собой дверь (512061, 112, 512252)
    ///      23:55:46 открыл дверь (512061, 112, 512252) (и то же ещё 1 раз)
    ///    Бот ни разу не вышел на северную сторону створки: он всё это время
    ///    топтался с ЮЖНОЙ, откуда её и открыл, — то отходя на пару блоков вбок
    ///    (23:55:16 «обошёл ногами: стою на (512062, 112, 512252)»), то поднимаясь
    ///    ступенями вверх (23:55:25 «остановка на (512063, 114, 512253)»). Заставы
    ///    3 и 5 обе давали дорогу: в проёме он в тот миг не стоял, а «отойти на
    ///    полтора» спрашивается только у идущего — поход же к тому мигу кончился.
    ///    Долг решал «дверь мне больше не нужна», закрывал её, и следующий
    ///    маршрут (23:55:25.984 …-> (512061, 112, 512252) -> (512061, 112, 512251))
    ///    снова вёл сквозь неё. Так и шло минутами.
    ///
    ///    «Прошёл» спрашивается НЕ У ГЕОМЕТРИИ СТВОРКИ, а у двух положений
    ///    САМОГО БОТА: где он стоял, когда сервер подтвердил открытие, и где
    ///    стоит сейчас (<see cref="DoorSide"/>, <see cref="SameDoorSide"/> —
    ///    то же правило, которым укрытие отличает «я дома» от «я за порогом»).
    ///    Это НЕ прежняя мерка «прошёл насквозь», на которой обжёгся журнал
    ///    16.08: та мерила бок от створки до ТОЧКИ КЛИКА, а точку клика выбирал
    ///    подход по главной оси сближения — у двух дверей в одной стене эта ось
    ///    шла ВДОЛЬ стены. Здесь берётся живое положение тела в миг открытия,
    ///    и та самая беда 16.08 разрешается верно: бот открыл вторую створку,
    ///    стоя в клетке первой (бок «запад»), и ушёл на восток — бок сменился,
    ///    значит прошёл, значит пора закрывать.
    ///
    /// 5. ДВЕРЬ ПРЯМО ПО КУРСУ — рано: сейчас пойду сквозь неё. Это тот самый
    ///    вопрос «нужна ли она мне», который заменил собой мерку «прошёл
    ///    насквозь»; спрашивают его у щупа <c>Movement.FindDoorAhead</c> — того
    ///    же, которым дверь и находят, чтобы открыть.
    ///
    /// 6. ЕЩЁ НЕ ОТОШЁЛ ОТ СТВОРКИ, А САМ ИДУ — рано, и это застава ПРОТИВ
    ///    МИГАНИЯ. Живой игрок закрывает дверь, отойдя от неё на шаг, а не стоя
    ///    вплотную и продолжая топтаться.
    ///
    ///    ЖИВОЙ СЛУЧАЙ (журнал 18.08, 00:19:32–00:19:56). Тело болталось между
    ///    двумя створками одного тамбура — «упёрся на точке 2/9 …, стою
    ///    (512062,5, 112, 512252,3)», «застрял, перестраиваю маршрут», — и курс
    ///    перекладывался туда-сюда по нескольку раз в секунду. Вместе с курсом
    ///    перекладывался и ответ «нужна ли мне эта дверь»: створка то по курсу
    ///    (открыть), то не нужна (закрыть). За двадцать четыре секунды две двери
    ///    открылись четырнадцать раз и закрылись один. Из тридцати семи заходов
    ///    в том журнале ДЕВЯТНАДЦАТЬ уложились в три секунды «открыл — закрыл».
    ///
    ///    Спрашивается это ТОЛЬКО НА ХОДУ: бот, который уже встал, сквозь эту
    ///    дверь никуда не идёт, и придираться к полуметру там нельзя — иначе
    ///    створка, за порогом которой бот остановился, не закроется никогда.
    ///
    /// 7. РУКА НЕ ДОСТАЁТ — ждём случая. Сервер дальше своей дальности клик
    ///    всё равно не примет, а объявлять успехом отправленный впустую пакет
    ///    запрещено правилом 4.
    ///
    /// 8. ТОЛЬКО ЧТО КЛИКАЛ — ждём ответа сервера. Без этой заставы ход тела
    ///    (двадцать тактов в секунду) слал бы клик за кликом, а клик по двери —
    ///    ПЕРЕКЛЮЧАТЕЛЬ: второй отменил бы первый.
    ///
    /// ТЕРПЕНИЕ ОБЩЕЕ НА ВСЕ ЗАСТАВЫ, КРОМЕ ПЕРВЫХ ДВУХ: если случай не выпал за
    /// отпущенный срок, бот ГОВОРИТ ВСЛУХ, какая дверь и что помешало, — но долг
    /// за собой ОСТАВЛЯЕТ (<see cref="DoorPayment.Later"/>). Раньше здесь стояло
    /// сначала молчаливое забывание через полминуты, потом — забывание со
    /// словами; и то и другое кончалось одинаково: створка оставалась
    /// нараспашку навсегда, даже когда бот через три минуты стоял к ней
    /// вплотную (разбор с числами — у <see cref="DoorPayment.Later"/>).
    /// </summary>
    /// <param name="allowed">Разрешено ли роли закрывать за собой (ЗакрыватьЗаСобойДвери).</param>
    /// <param name="seen">Видно ли клетку двери вообще (чанк пришёл).</param>
    /// <param name="stillOpen">Открыта ли дверь ПО СЛОВУ СЕРВЕРА.</param>
    /// <param name="inDoorway">Тело стоит в клетке самой двери.</param>
    /// <param name="passed">
    /// ПРОШЁЛ ЛИ БОТ ЭТУ ДВЕРЬ: побывал ли он по ДРУГУЮ её сторону с тех пор,
    /// как открыл (<see cref="DoorOwed.Passed"/>). Довод обязательный и без
    /// умолчания НАРОЧНО: с умолчанием «да» любое новое место оплаты долга
    /// молча получило бы старое поведение — то самое, из-за которого дверь
    /// захлопывалась перед носом.
    /// </param>
    /// <param name="onCourse">Дверь прямо по курсу — сейчас пойду сквозь неё.</param>
    /// <param name="distance">До середины створки, блоков.</param>
    /// <param name="reach">Длина руки игрока, блоков.</param>
    /// <param name="walking">
    /// Бот прямо сейчас ИДЁТ (у хода есть курс). Только на ходу и проверяется
    /// «отошёл ли я от створки»: вставшему она больше не понадобится.
    /// </param>
    /// <param name="stepAway">
    /// Насколько надо отойти от створки, прежде чем закрывать её на ходу
    /// (ручка роли «ОтойтиОтДвериПередЗакрытием»). Ноль — не ждать вовсе.
    /// </param>
    /// <param name="ageSeconds">Сколько долг висит.</param>
    /// <param name="patienceSeconds">Сколько ждать случая, прежде чем отказаться вслух.</param>
    /// <param name="sinceTrySeconds">
    /// Сколько прошло с последнего клика по этой двери
    /// (<see cref="double.PositiveInfinity"/> — не кликали ни разу).
    /// </param>
    /// <param name="retrySeconds">Сколько ждать ответа сервера, прежде чем кликнуть снова.</param>
    /// <param name="tries">Сколько раз уже кликали — для слов отказа.</param>
    public static (DoorPayment What, string Why) PayRule(
        bool allowed, bool seen, bool stillOpen, bool inDoorway, bool passed, bool onCourse,
        double distance, double reach,
        double ageSeconds, double patienceSeconds,
        double sinceTrySeconds, double retrySeconds, int tries = 0,
        bool walking = false, double stepAway = 0, int missed = 0)
    {
        if (seen && !stillOpen)
            return (DoorPayment.Gone, tries > 0
                ? "закрылась по слову сервера"
                : "она и так закрыта — закрывать нечего");

        if (!allowed)
            return (DoorPayment.GiveUp,
                "закрывать за собой запрещено настройкой «ЗакрыватьЗаСобойДвери» — " +
                "так и останется открытой");

        // Что именно мешает закрыть прямо сейчас (пусто — ничего не мешает)
        string blocker =
            !seen ? "её клетки не видно — этот кусок мира ко мне не приходил"
            : inDoorway ? "стою в самом проёме — закрыв её, прищемил бы себя"
            : !passed
                ? "я её так и не прошёл — стою с того же боку, с которого открыл, " +
                  "и сквозь неё мне ещё идти"
            : onCourse ? "она прямо по курсу — сейчас пойду сквозь неё"
            : walking && distance < stepAway
                ? $"я ещё в {distance:0.#} бл от створки и продолжаю идти, а отойти " +
                  $"полагается на {stepAway:0.#} — захлопни я её сейчас, через миг " +
                  "открывал бы заново"
            : distance > reach ? $"до неё {distance:0.#} бл, а рука достаёт на {reach:0.#}"
            : sinceTrySeconds < retrySeconds
                ? $"только что кликал ({tries}), жду ответа сервера"
                : "";

        if (blocker.Length == 0)
            return (DoorPayment.Close, "она мне больше не нужна, и рука достаёт");

        if (ageSeconds >= patienceSeconds)
            return (DoorPayment.Later,
                $"{blocker}; жду уже {ageSeconds:0} с" +
                (tries > 0 ? $", кликал {tries} раз(а)" : "") +
                (missed > 0 ? $", и это уже {missed + 1}-й раз, когда терпение вышло впустую" : "") +
                " — случая закрыть так и не выпало");

        return (DoorPayment.Wait, blocker);
    }

    /// <summary>
    /// ЧТО СКАЗАТЬ ПРО НЕЗАКРЫТУЮ ДВЕРЬ — чистое правило, и оно нарочно
    /// начинается с крика.
    ///
    /// Человеку, который придёт разбираться, нужны КООРДИНАТЫ: по фразе «дверь
    /// осталась открытой» не найти ничего, а открытая дверь в бурю или ночью
    /// пускает в дом кого угодно.
    /// </summary>
    public static string SayLeftOpen(BlockPos door, string why) =>
        $"НЕ ЗАКРЫЛ за собой дверь {door}: {why}";

    /// <summary>
    /// ЧТО СКАЗАТЬ ПРО ДВЕРЬ, КОТОРУЮ ЕЩЁ НАДЕЮСЬ ЗАКРЫТЬ — тот же крик и те же
    /// координаты, но с концовкой, которой не было: долг остался за ботом.
    ///
    /// Разница нужна человеку, а не коду. Прежняя строка кончалась словами
    /// «случая закрыть так и не выпало» и означала «я про неё забыл»; эта
    /// означает «закрою, как только смогу», и по журналу видно, чего ждать
    /// дальше. Врать здесь нельзя в обе стороны: обещание закрыть подкреплено
    /// тем, что запись о двери и правда остаётся в долге.
    /// </summary>
    public static string SayStillOwed(BlockPos door, string why) =>
        $"НЕ ЗАКРЫЛ за собой дверь {door}: {why}; долг за мной остаётся — " +
        "закрою, как только окажусь рядом";

    /// <summary>
    /// С КАКОГО БОКА ДВЕРИ СТОИТ ТЕЛО — чистое правило, без мира и без бота.
    ///
    /// Ось берётся та, по которой тело дальше от середины створки: у двери в
    /// стене дома это как раз «поперёк стены», то есть «внутри — снаружи».
    /// Знак и есть бок. Ноль означает «ровно на оси» — бока нет.
    ///
    /// ЖИВЁТ ЗДЕСЬ, А НЕ У УКРЫТИЯ, И ЭТО ПЕРЕЕЗД, А НЕ КОПИЯ. Правило написали
    /// для укрытия (<see cref="Shelter.HideBehindDoor"/>: «я дома» — это «дверь
    /// закрыта И я всё ещё с того же её боку»), а понадобилось оно и долгу:
    /// «прошёл ли я эту дверь» — тот же вопрос про бок, только с обратным
    /// знаком. Двух ответов на один вопрос в проекте быть не должно, поэтому
    /// правило одно и лежит там, где двери и живут; укрытие зовёт его сюда.
    /// </summary>
    public static (int Axis, int Sign) DoorSide(BlockPos door, double x, double z)
    {
        double dx = x - (door.X + 0.5);
        double dz = z - (door.Z + 0.5);
        return Math.Abs(dx) >= Math.Abs(dz)
            ? (0, Math.Sign(dx))
            : (2, Math.Sign(dz));
    }

    /// <summary>
    /// ТОТ ЖЕ ЛИ ЭТО БОК ДВЕРИ, что запомнили.
    ///
    /// ЖИВОЙ СЛУЧАЙ УКРЫТИЯ, ради которого правило заведено. Бот выходит из
    /// своего дома, дверь захлопывается за ним сама, и он стоит В ЧИСТОМ ПОЛЕ в
    /// двух шагах от порога. Проверок было две — «дверь закрыта» и «я недалеко
    /// от места, где её закрыл», — и обе отвечали ДА. Бот под дрифтером повторял
    /// «я нарочно спрятался», стоя снаружи под открытым небом.
    ///
    /// ЖИВОЙ СЛУЧАЙ ДОЛГА — тот же вопрос наоборот: «бок другой» значит
    /// «прошёл», а «бок тот же» значит «дверь мне ещё нужна» (см. заставу 4
    /// в <see cref="PayRule"/> и журнал 18.08, 23:55).
    ///
    /// Ось запоминается ОДНА, та, что была в запомненный миг, и второй раз не
    /// выбирается: иначе шаг вдоль стены менял бы «поперёк стены» на «вдоль»,
    /// и ответ переворачивался бы на ровном месте.
    /// </summary>
    public static bool SameDoorSide(BlockPos door, (int Axis, int Sign) side,
        double x, double z)
    {
        if (side.Sign == 0)
            return false;   // бока не знаем — врать про него нельзя
        double along = side.Axis == 0 ? x - (door.X + 0.5) : z - (door.Z + 0.5);
        return Math.Sign(along) == side.Sign;
    }

    /// <summary>
    /// СТОЮ ЛИ Я В САМОМ ПРОЁМЕ ЭТОЙ ДВЕРИ — чистое правило, без мира и без бота.
    ///
    /// ЖИВЁТ ЗДЕСЬ, А НЕ В ДВИЖЕНИИ, И ЭТО ПЕРЕЕЗД, А НЕ КОПИЯ. Считалось оно
    /// строкой внутри уплаты долга (<see cref="PayRule"/>, довод
    /// <c>inDoorway</c>), и потому знал ответ ровно один закрывающий из двух:
    /// укрытие (<see cref="Shelter.GoHomeAndCloseDoorAsync"/>) искало «любую
    /// дверь в трёх шагах от ног», и ПЕРВОЙ из них поиск отдаёт створку под
    /// ногами — расстояние ноль. Бот, пришедший домой и вставший ровно в
    /// проёме, захлопывал дверь НА СЕБЕ и докладывал об укрытии. Вопрос один —
    /// и ответ на него теперь один, а спрашивают его оба.
    ///
    /// ПОЧЕМУ СТОЛБ, А НЕ КЛЕТКА ХОЗЯИНА. Створка двухблочная, и ноги стоят то
    /// в низу проёма, то в верху (порог, ступенька, слой снега под ногами);
    /// спроси мы одну клетку — половина проёма перестала бы быть проёмом.
    ///
    /// ВЫСОТА БЕРЁТСЯ С ПРИБАВКОЙ 0,01, как и у самой игры: тело, ровно севшее
    /// на пол клетки, принадлежит ЕЙ, а не той, что под ним (см.
    /// <see cref="GroundSpeed.CellsAt"/> — там та же прибавка и по той же
    /// причине).
    /// </summary>
    /// <param name="door">Клетка хозяина створки (<see cref="WorldModel.DoorClickPos"/>).</param>
    /// <param name="x">Где стоит тело, ось X.</param>
    /// <param name="feetY">Высота НОГ (не номер клетки).</param>
    /// <param name="z">Где стоит тело, ось Z.</param>
    public static bool InDoorway(BlockPos door, double x, double feetY, double z) =>
        (int)Math.Floor(x) == door.X &&
        (int)Math.Floor(z) == door.Z &&
        Math.Abs((int)Math.Floor(feetY + 0.01) - door.Y) <= 1;

    // ---------------- живая половина: память ----------------

    /// <summary>
    /// ЗАПОМНИТЬ ОТКРЫТУЮ ДВЕРЬ. Зовут ПОСЛЕ подтверждения от сервера, а не
    /// вместо него: долг за дверь, которая не открылась, — это будущий клик по
    /// закрытой створке, то есть бот сам себе её ОТКРОЕТ.
    /// </summary>
    /// <param name="door">Клетка хозяина створки (WorldModel.DoorClickPos).</param>
    /// <param name="atX">
    /// Где стояло ТЕЛО в миг, когда сервер подтвердил открытие, по оси X.
    /// Отсюда берётся бок створки (<see cref="DoorSide"/>), а из бока — ответ
    /// «прошёл ли я эту дверь» (застава 4 в <see cref="PayRule"/>).
    ///
    /// Довод обязательный и без умолчания НАРОЧНО: с умолчанием любая новая
    /// точка, где бот открывает дверь, молча заводила бы долг без бока — то
    /// есть без единственного, чем этот долг отличается от прежнего, который
    /// захлопывал створку перед носом.
    /// </param>
    /// <param name="atZ">То же по оси Z.</param>
    /// <param name="now">Время открытия (доводом, чтобы правило проверялось стендом).</param>
    public DoorOwed Note(BlockPos door, double atX, double atZ, DateTime now)
    {
        DoorOwed record;
        DoorOwed? dropped = null;
        var side = DoorSide(door, atX, atZ);
        lock (gate)
        {
            // Та же дверь второй раз — тот же долг, а не второй: перезаписываем.
            // Иначе бот кликнул бы по одной створке дважды, а клик по двери —
            // переключатель: второй клик открыл бы её обратно.
            //
            // И БОК ПЕРЕПИСЫВАЕТСЯ ВМЕСТЕ С НЕЙ. Открыть уже открытую дверь
            // нельзя, значит второе «открыл» — это новый заход после того, как
            // створку кто-то закрыл: прежний бок к нему отношения не имеет
            owed.RemoveAll(d => d.Door == door);
            record = new DoorOwed(door, now, DateTime.MinValue, 0, Side: side);
            owed.Add(record);
            if (owed.Count > Math.Max(1, MaxOwed))
            {
                dropped = owed[0];
                owed.RemoveAt(0);
            }
        }
        if (dropped is { } old)
            OnLog?.Invoke(SayLeftOpen(old.Door,
                $"открытых дверей за мной набралось больше {MaxOwed}, и эта самая старая — " +
                "вычёркиваю, закрыть её будет уже некому"));
        return record;
    }

    /// <summary>
    /// ПРОШЁЛ ЛИ Я ЭТУ ДВЕРЬ — спросить у своего положения и ЗАПОМНИТЬ ответ.
    ///
    /// Спрашивать надо на каждом заходе оплаты, а помнить — навсегда, и это две
    /// разные вещи. Бот, сходивший за порог и вернувшийся обратно, стоит опять с
    /// того боку, с которого открывал: спроси мы только «где я сейчас», и своя
    /// же дверь снова числилась бы «непройденной» — то есть не закрылась бы
    /// никогда. Поэтому отметка ЛИПКАЯ.
    ///
    /// Зовут ровно из одного места — из уплаты долга (<c>Movement</c>), и
    /// оттуда же ответ уходит доводом <c>passed</c> в <see cref="PayRule"/>:
    /// живая память здесь, чистое решение — там.
    /// </summary>
    /// <returns>
    /// Прошёл ли бот эту дверь. Для двери, которой за нами не числится, —
    /// false: у чужой двери бока мы не запоминали и врать про него не станем.
    /// </returns>
    public bool WentThrough(BlockPos door, double x, double z)
    {
        lock (gate)
        {
            int at = owed.FindIndex(d => d.Door == door);
            if (at < 0)
                return false;
            if (owed[at].Passed)
                return true;
            if (SameDoorSide(door, owed[at].Side, x, z))
                return false;
            // Бока не знаем вовсе (открывал, стоя ровно на оси створки) —
            // SameDoorSide отвечает «нет» и на это; такой долг считается
            // пройденным сразу. Цена ошибки здесь несимметрична и выбрана
            // нарочно: лишний раз открыть дверь заново стоит полсекунды, а
            // оставленная нараспашку в бурю или ночью пускает в дом кого угодно
            owed[at] = owed[at] with { Passed = true };
            return true;
        }
    }

    /// <summary>
    /// ТЕРПЕНИЕ ВЫШЛО ВПУСТУЮ, А ДОЛГ ОСТАЁТСЯ — считаем терпение заново.
    ///
    /// Зовут ровно из одного места: после <see cref="DoorPayment.Later"/>, когда
    /// про дверь уже сказано вслух. Без этого счёт возраста остался бы на месте,
    /// и правило кричало бы «жду уже 30 с» на каждом такте ходьбы — двадцать раз
    /// в секунду. Это НЕ вторая заглушка повторов: заглушка (LogRepeats) стоит у
    /// голоса движения и считает одинаковые строки, а здесь переставляется сам
    /// срок, после которого боту снова есть что сказать.
    /// </summary>
    public void Missed(BlockPos door, DateTime now)
    {
        lock (gate)
        {
            int at = owed.FindIndex(d => d.Door == door);
            if (at >= 0)
                owed[at] = owed[at] with { At = now, Missed = owed[at].Missed + 1 };
        }
    }

    /// <summary>Отметить клик по двери: ответа сервера ждём, долг пока за нами.</summary>
    public void Tried(BlockPos door, DateTime now)
    {
        lock (gate)
        {
            int at = owed.FindIndex(d => d.Door == door);
            if (at >= 0)
                owed[at] = owed[at] with { TriedAt = now, Tries = owed[at].Tries + 1 };
        }
    }

    /// <summary>
    /// ДОЛГ СНЯТ. Зовут ровно в трёх случаях, и все три названы словами в
    /// <see cref="PayRule"/>: закрыли ПО ФАКТУ, дверь и так закрыта, закрывать
    /// запрещено настройкой. Способа «забыть все долги разом» здесь НЕТ
    /// НАРОЧНО: он и был той самой молчаливой очисткой, из-за которой дверь
    /// (512062, 112, 512252) простояла открытой два часа.
    ///
    /// А ВОТ «СЛУЧАЯ НЕ ВЫПАЛО» СЮДА БОЛЬШЕ НЕ ХОДИТ. Раньше ходило, и это
    /// стоило заказчику двадцати трёх минут распахнутой двери при живом боте в
    /// полутора блоках от неё (разбор с журналом — у <see cref="DoorPayment.Later"/>).
    /// Такой случай теперь только ГОВОРИТ и переставляет терпение
    /// (<see cref="Missed"/>).
    /// </summary>
    public bool Forget(BlockPos door)
    {
        lock (gate)
            return owed.RemoveAll(d => d.Door == door) > 0;
    }
}
