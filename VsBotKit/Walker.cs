    /// <summary>
    /// Ступенька, которую тело берёт шагом. Выше — только прыжком.
    ///
    /// СВОЕГО ЧИСЛА ЗДЕСЬ НЕТ: высота шага одна на весь проект
    /// (<see cref="BodySize.StepUp"/>). Именно из-за неё любой бортик в один
    /// блок останавливал бота, пока у него не появился рефлекс «упёрся —
    /// подпрыгни».
    /// </summary>
    public const double StepUp = BodySize.StepUp;

    /// <summary>
    /// СКОЛЬКО ЦЕЛЫХ КЛЕТОК БЕРЁТСЯ ПРЫЖКОМ — мерка ПЛАНИРОВЩИКА, который
    /// ходит по клеткам, а не по высотам.
    ///
    /// СВОЕГО ЧИСЛА ЗДЕСЬ БОЛЬШЕ НЕТ, и это починка настоящей беды. Тут стояло
    /// «= 1» с подписью «прыжок в игре берёт РОВНО один блок», и этой подписью
    /// бот отказывал человеку вслух: «прыжком ровно 1 бл» (журнал 19.08,
    /// 36 раз). А ноги в апексе поднимаются на <see cref="JumpPhysics.ApexRise"/>
    /// = 1,27 — на том же 1,27 стоит вся починка двойного прыжка. Заказчик
    /// поймал нас на этом прямо: «разве у героя прыжок ровно 1? мне казалось
    /// на снег запрыгивает?» — и был прав: на сугроб (подъём 1,25) тело
    /// запрыгивает, а слово бота это запрещало.
    ///
    /// Теперь число ОДНО, и целые клетки из него ВЫВОДЯТСЯ. Урежь апекс до
    /// единицы — планировщик перестанет закладывать подъёмы прыжком сам, без
    /// второй правки в другом файле.
    ///
    /// САМ ВЫВОД ЖИВЁТ В <see cref="JumpPhysics.CellsUp"/>, а здесь только имя
    /// для тех, кто привык спрашивать ходьбу. Вывод переехал туда потому, что о
    /// том же самом спрашивает <c>PathOptions</c>, а его линкует в себя
    /// клиентский МОД — <c>Walker</c> же в мод не входит, и живи формула здесь,
    /// мод считал бы маршрут своей копией.
    /// </summary>
    public static int JumpUp => JumpPhysics.CellsUp;

    // ЗДЕСЬ ЛЕЖАЛО ОСИРОТЕВШЕЕ ПРАВИЛО «NeedsJump(up) => up >= 1». Его не звал
    // НИКТО — ни библиотека, ни приложение, ни один тест, — а рядом на тот же
    // с виду вопрос отвечают три живых места, и все тремя РАЗНЫМИ вопросами:
    // «яма ли впереди» (Movement.NeedsJumpTo — про опору по линии, а не про
    // высоту), «берётся ли прыжком» (rise <= Walker.JumpUp) и «прыжком не
    // взять» (up >= Walker.JumpUp + 1). Мёртвое правило с таким именем хуже
    // отсутствующего: следующий, кто станет чинить прыжки, позовёт его — и
    // получит ответ, которым бот не живёт.

    /// <summary>
    /// ДОТЯНЕМСЯ ЛИ ВВЕРХ САМИ: шагом, прыжком или по лестнице. Всё, что
    /// выше — не «попробуем и посмотрим», а стройка (см.
    /// <see cref="ClimbAidNeeded"/>).
    ///
    /// ВЫСОТА В БЛОКАХ, А НЕ В КЛЕТКАХ, и мерка одна — апекс прыжка
    /// (<see cref="JumpPhysics.ApexRise"/>). Тот же вопрос жил в
    /// <c>Movement.ClimbOrCrossAsync</c> своей копией «up ≥ JumpUp + 1», то
    /// есть «≥ 2 блока», — и подъём в полтора блока (уступ под сугробом,
    /// полотно под ступенью) не считался ни доступным, ни требующим стройки:
    /// бот просто бился в него.
    /// </summary>
    public static bool CanRiseBy(double up, bool ladderThere) =>
        up <= JumpPhysics.ApexRise || ladderThere;

    /// <summary>
    /// КАКОЙ ПОЗОЙ ТЕЛО ВЛЕЗАЕТ В ЩЕЛЬ ТАКОЙ ВЫСОТЫ — чистое правило и весь
    /// ответ на просьбу заказчика «научи видеть высоту препятствия, некоторые
    /// можно пройти в присяд».
    ///
    /// Числа не свои: стоя нужно <see cref="BodySize.Height"/> = 1,85,
    /// в присяде <see cref="BodySize.CrouchHeight"/> = 1,48 (игра, множитель
    /// 0,8 в <c>EntityPlayer.updateEyeHeight</c>).
    ///
    /// ЧЕСТНАЯ ГРАНИЦА ПРИЁМА, и обольщаться ею нельзя: присед выигрывает 0,37
    /// бл, а НЕ целый блок. Просвет ровно в клетку (1,0) не берётся ни стоя,
    /// ни пригнувшись — там нужна кирка. Присед открывает ровно те щели, где
    /// потолок висит не по границе клетки: перевёрнутая плита (просвет 1,5),
    /// перевёрнутая ступень, тёсаный полублок под потолком, люк. И тот же
    /// просвет 1,5 получается, когда ноги СТОЯТ на плите в ходе высотой в две
    /// клетки, — а такие ступени копатель кладёт сам (stonepathslab).
    /// </summary>
    /// <param name="clearance">Свободная высота над ногами, блоков.</param>
    public static (BodyPose Pose, string Why) PoseForClearance(double clearance)
    {
        if (clearance >= BodySize.Height)
            return (BodyPose.Stand, $"просвет {clearance:0.##} бл — прохожу как стою " +
                                    $"(рост {BodySize.Height:0.##})");
        if (clearance >= BodySize.CrouchHeight)
            return (BodyPose.Crouch, $"просвет {clearance:0.##} бл: стоя не пройти " +
                                     $"(рост {BodySize.Height:0.##}), а в присяде пройду " +
                                     $"({BodySize.CrouchHeight:0.##})");
        return (BodyPose.TooLow, $"просвет {clearance:0.##} бл — не пролезу и в присяде: " +
                                 $"телу нужно {BodySize.CrouchHeight:0.##}");
    }

    /// <summary>
    /// Сколько блоков надо ПОСТРОИТЬ, чтобы подняться до нужной высоты
    /// (столб под собой или лестница по стене). Ноль — поднимемся сами.
    ///
    /// Живьём этого не хватало дважды: бот выкапывал себе яму и оставался в
    /// ней, метаясь вверх-вниз, хотя строить столб умел с самого начала.
    /// Прыжок берёт один блок, яма была глубже — и всё.
    /// </summary>
    public static int ClimbAidNeeded(int feetY, int wantY, bool ladderThere)
    {
        int up = wantY - feetY;
        if (up <= 0 || CanRiseBy(up, ladderThere))
            return 0;
        return up;
    }

