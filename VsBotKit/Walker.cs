    // ---------------- разбег: сколько разгона даёт какую дальность ----------------

    /// <summary>
    /// Долетит ли тело до клетки на таком расстоянии, если сзади было столько
    /// блоков ровной земли под разгон.
    ///
    /// СВОИХ ЧИСЕЛ ЗДЕСЬ НЕТ: дальность считает <see cref="JumpPhysics"/>,
    /// замеренный по игре. Здесь только решение — сравнить дальность с
    /// расстоянием. Раньше это сравнение делалось в трёх местах по-разному,
    /// и заказчик увидел итог как «бот стал бояться перепрыгивать».
    ///
    /// Живой случай: щель в три блока — это прыжок на 4-ю клетку, а с места
    /// тело достаёт 3.11 (замер: полёт 2.507 плюс свес хитбокса 0.6). Бот
    /// прыгал и падал. Здесь стояло 3.37 — сумма, посчитанная от бумажного
    /// полёта 2.77; сам полёт пересчитали замером, а сумму забыли, и она
    /// осталась обещать четверть клетки сверх того, что тело берёт.
    /// </summary>
    /// <param name="cells">Сколько клеток от точки отрыва до клетки приземления.</param>
    /// <param name="runUpBlocks">Сколько блоков разгона удалось взять сзади.</param>
    /// <param name="margin">
    /// Запас на ошибку модели. Это ПОЛИТИКА роли (см. SafeJumpMargin), поэтому
    /// по умолчанию ноль: механизм не решает за роль, насколько та осторожна.
    /// </param>
    public static bool JumpReaches(double cells, double runUpBlocks, double margin = 0) =>
        JumpPhysics.ReachWithRunUp(runUpBlocks) >= cells + margin;

    /// <summary>
    /// Сколько блоков разгона нужно, чтобы взять клетку на таком расстоянии.
    /// Ноль — берётся с места; бесконечность — не берётся вовсе, сколько ни
    /// разбегайся.
    ///
    /// Это в точности обратная <see cref="JumpPhysics.FlightWithRunUp"/>:
    /// те же три константы, решённые относительно разбега. Тест гоняет её
    /// туда-обратно через саму физику — чтобы «своя формула» не разошлась
    /// с игрой так же тихо, как когда-то разошлись три копии дальности.
    ///
    /// Зачем это знать заранее: разгон нужно НАЧАТЬ до отрыва, за клетку или
    /// две. Живьём тело подходило к щели шагом и прыгало с места — 3.11 бл
    /// вместо 5.45, то есть недолёт на всём, что шире двух блоков.
    /// </summary>
    public static double RunUpNeeded(double cells, double margin = 0)
    {
        // Свес хитбокса даётся даром, разгоном его добирать не надо: 0.3 на
        // взлёте и 0.3 на посадке — это края тела, а не скорость
        double flight = cells + margin - 2 * JumpPhysics.HitboxOverhang;
        if (flight <= JumpPhysics.StandingFlight)
            return 0;
        if (flight > JumpPhysics.RunningFlight)
            return double.PositiveInfinity;
        return JumpPhysics.RunUpToFullSpeed *
               (flight - JumpPhysics.StandingFlight) /
               (JumpPhysics.RunningFlight - JumpPhysics.StandingFlight);
    }

    /// <summary>
    /// Надо ли вообще разгоняться перед этим прыжком.
    ///
    /// Отдельным вопросом, потому что ответ на него — это КЛАВИША БЕГА,
    /// нажатая на клетку раньше. Живьём тело шло к точке прыжка обычным шагом
    /// и разгоняться начинало уже на её краю: полблока разгона вместо полутора.
    /// </summary>
    public static bool NeedsRunUp(double cells, double margin = 0) =>
        RunUpNeeded(cells, margin) > 0;

