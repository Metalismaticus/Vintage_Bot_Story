namespace VsBotKit;

/// <summary>Что тело должно делать на этом такте.</summary>
public enum WalkMove
{
    /// <summary>Пришли: точка достигнута.</summary>
    Arrived,
    /// <summary>Идти к точке.</summary>
    Walk,
    /// <summary>Прыгать (через провал или на ступеньку).</summary>
    Jump,
    /// <summary>Лезть по лестнице.</summary>
    Climb,
    /// <summary>Сойти с края вниз.</summary>
    StepDown,
    /// <summary>Дальше нельзя — с причиной.</summary>
    Refuse
}

/// <summary>
/// В КАКОЙ ПОЗЕ ТЕЛО ВЛЕЗАЕТ В ЩЕЛЬ. Ровно две позы, потому что ровно две есть
/// у игры (<c>EntityPlayer.updateEyeHeight</c>: полный рост и он же × 0,8);
/// «ползком» в Vintage Story нет вовсе, и выдумывать его нельзя.
/// </summary>
public enum BodyPose
{
    /// <summary>Прохожу как стою.</summary>
    Stand,
    /// <summary>Пройду пригнувшись — и только пригнувшись.</summary>
    Crouch,
    /// <summary>Не пролезу никак: тут работа кирке, а не ногам.</summary>
    TooLow
}

/// <summary>Решение на такт: что делать и почему. Причина обязательна.</summary>
public readonly record struct WalkDecision(WalkMove Move, BlockPos To, string Why)
{
    public override string ToString() => $"{Move} → {To}: {Why}";
}

/// <summary>
/// Чем перейти разрыв, который лежит между ботом и целью НА ОДНОЙ С НИМ ВЫСОТЕ.
/// Способы по ВОЗРАСТАНИЮ ЦЕНЫ: прыжок не стоит ничего, мост съедает блоки из
/// сумок и время.
/// </summary>
public enum CrossWay
{
    /// <summary>Разрыва нет — просто идти ногами.</summary>
    Walk,
    /// <summary>Перепрыгнуть. Даром.</summary>
    Jump,
    /// <summary>Выложить мост блоками из сумок и пройти по нему.</summary>
    Bridge,
    /// <summary>Ни перепрыгнуть, ни замостить — с причиной.</summary>
    None
}

/// <summary>
/// Чем спуститься с обрыва. Способы по ВОЗРАСТАНИЮ ЦЕНЫ: спрыгнуть даром и
/// мгновенно, ступени даром, но долго, лестница тратит запас, столб вниз
/// ломает под собой и назад пути не оставляет.
/// </summary>
public enum WayDown
{
    /// <summary>Спускаться некуда.</summary>
    None,
    /// <summary>Спрыгнуть: падение бот переживёт.</summary>
    Jump,
    /// <summary>Вырубить ступени вниз — по ним же можно и вернуться.</summary>
    Steps,
    /// <summary>Повесить лестницу по стене обрыва.</summary>
    Ladder,
    /// <summary>Разобрать породу под собой и осесть вместе с ней.</summary>
    Pillar,
    /// <summary>Спуска нет — с причиной и числами.</summary>
    Trapped
}

/// <summary>
/// ПРАВИЛА ХОДЬБЫ — отдельно от тела, сервера и физики.
///
/// Зачем этот класс существует. Исполнитель движения разросся до полутора
/// тысяч строк с тремя десятками особых веток (лестницы, торцы, кромки, броды,
/// спрыгивания, тупики, зацепы), и ломалась всегда одна из них. Причём
/// ломалась молча: чтобы понять, почему бот стоит, приходилось читать живой
/// журнал и гадать. За один вечер так нашлись пять разных зависаний, и все
/// пять — не в поиске пути, а в исполнении.
///
/// Общее у всех пяти одно: РЕШЕНИЕ нельзя было проверить, не подняв сервер.
/// Поэтому здесь лежат только решения — чистые функции от «где я», «куда иду»
/// и «что вокруг». Их можно прогнать стендом за миллисекунды, и ошибка вроде
/// «щуп смотрит вдевятеро дальше цели» видна сразу, а не через неделю живых
/// прогонов.
///
/// Тело эти решения ИСПОЛНЯЕТ и ничего не решает само.
/// </summary>
public static class Walker
{
    /// <summary>
    /// Точка достигнута — ноги в её клетке. И никаких порогов в сантиметрах.
    ///
    /// Пороги и стоили нам самого дорогого зависания: маршрут всегда
    /// начинается с клетки, где бот стоит, и он шёл к её середине, до которой
    /// оставалось 0.22 при пороге прихода 0.2. Стоять в клетке и есть «дойти
    /// до клетки» — так это понимает человек, так должно быть и здесь.
    /// </summary>
    public static bool Reached(BlockPos feet, BlockPos point) => feet == point;

    /// <summary>
    /// Номер первой точки маршрута, которая ещё НЕ достигнута.
    ///
    /// Пропускаем все, в чьих клетках уже стоим, — не только первую. Маршрут
    /// приходит от планировщика вместе со стартовой клеткой, а после прыжка
    /// или спуска бот может оказаться сразу на несколько точек вперёд.
    /// Возвращает длину маршрута, если пройдены все.
    /// </summary>
    public static int NextIndex(IReadOnlyList<BlockPos> path, BlockPos feet)
    {
        if (path == null || path.Count == 0)
            return 0;

        // Ищем ПОСЛЕДНЮЮ пройденную, а не первую непройденную: маршрут может
        // возвращаться в ту же клетку (обход, зигзаг), и остановиться на
        // первом совпадении значило бы пойти по второму кругу
        int passed = -1;
        for (int i = 0; i < path.Count; i++)
            if (Reached(feet, path[i]))
                passed = i;

        return passed + 1;
    }

    /// <summary>
    /// Как далеко щупать землю по курсу.
    ///
    /// НЕ ДАЛЬШЕ, ЧЕМ ИДЁМ. Живьём щуп смотрел на 0.9 блока вперёд всегда —
    /// даже когда до цели оставалось 0.22. Стоя в углу своей клетки, бот
    /// «видел» за её краем обрыв, с которого сам только что спрыгнул, и
    /// молча обрывал ход, не сделав ни шага. Позиция не менялась ни на
    /// сантиметр, маршрут строился заново от той же клетки — и так минутами.
    ///
    /// Проверка обязана быть соразмерна шагу: смотрим туда, куда правда идём.
    /// </summary>
    /// <param name="toTarget">Сколько блоков осталось до цели шага.</param>
    /// <param name="full">Обычная глубина щупа, когда идти далеко.</param>
    public static double ProbeAhead(double toTarget, double full = 0.9) =>
        Math.Max(0, Math.Min(full, toTarget));

    /// <summary>
    /// Можно ли записывать клетку в тупик.
    ///
    /// Клетку под собой — нельзя. Направление это единичный вектор, и стоя
    /// у края клетки бот получал «стену» равной собственной клетке: то есть
    /// сам себе дорожил место, где стоит. Любой будущий маршрут отсюда
    /// становился дороже на ровном месте, а виноватой выглядела дорога.
    /// </summary>
    public static bool MayBlame(BlockPos feet, BlockPos wall) => wall != feet;

    /// <summary>
    /// Стоит ли перестраивать маршрут ещё раз.
    ///
    /// Только если прошлая попытка ПРИБЛИЗИЛА к цели. Тот же маршрут второй
    /// раз даст тот же итог: живьём это выглядело как восемь перестроек за
    /// пять секунд и «бегает вперёд-назад».
    /// </summary>
    /// <param name="gapNow">Сколько осталось до цели сейчас.</param>
    /// <param name="gapBefore">Сколько оставалось на прошлой попытке.</param>
    /// <param name="step">Насколько должно было стать ближе, чтобы это считалось.</param>
    public static bool WorthReplanning(double gapNow, double gapBefore, double step = 0.5) =>
        gapNow < gapBefore - step;

    // ---------------- «стало ближе» с учётом высоты ----------------

    /// <summary>
    /// Во сколько блоков по полу обходится ОДИН блок подъёма. Число не с
    /// потолка: ровно столько же стоит подъём в поиске пути
    /// (<see cref="PathOptions.ClimbCost"/>), и здесь оно повторено значением
    /// по умолчанию, а зовущий обязан передать своё, если роль его меняла.
    /// Разойдись эти две цены — и движение считало бы «стало ближе» ровно там,
    /// где маршрут считает «стало дороже».
    /// </summary>
    public const double ClimbCostPerBlock = 2.0;

    /// <summary>
    /// Во сколько блоков по полу обходится один блок СПУСКА к цели, которая
    /// НИЖЕ. Спуск дешевле подъёма (гравитация работает даром), но не бесплатен:
    /// спрыгивание стоит здоровья, ступени — времени.
    /// </summary>
    public const double DropCostPerBlock = 1.0;

    /// <summary>
    /// НАСКОЛЬКО МЫ ДАЛЕКО ОТ ЦЕЛИ — одной меркой, где высота весит по правде.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ради которого написано («!комне», цель (512288, 119,
    /// 511772), бот внизу на 115). Мерка приближения считала прямое расстояние,
    /// где блок вниз весит столько же, сколько блок вбок. Бот спрыгивал на
    /// четыре блока, выигрывал два блока по полу — и мерка честно докладывала
    /// «частичный путь кончился, СТАЛО БЛИЖЕ (8,6 бл)». Дальше он опять лез
    /// наверх, опять спрыгивал, и так три минуты, пока не вышло время.
    ///
    /// А правда в том, что спуск на четыре блока от цели, которая ВЫШЕ, — это
    /// не приближение: эти четыре блока придётся набирать заново, и подъём
    /// стоит вдвое дороже шага по полу (см. <see cref="ClimbCostPerBlock"/>),
    /// плюс здоровье за само спрыгивание.
    /// </summary>
    /// <param name="flat">Сколько блоков до цели по полу.</param>
    /// <param name="targetAbove">
    /// На сколько блоков цель ВЫШЕ нас (минус — ниже).
    /// </param>
    /// <param name="climbCost">Цена блока подъёма (у роли — PathOptions.ClimbCost).</param>
    /// <param name="dropCost">Цена блока спуска.</param>
    public static double GapToTarget(double flat, double targetAbove,
        double climbCost = ClimbCostPerBlock, double dropCost = DropCostPerBlock) =>
        Math.Abs(flat) + (targetAbove >= 0
            ? targetAbove * Math.Max(0, climbCost)
            : -targetAbove * Math.Max(0, dropCost));

    /// <summary>
    /// СТОИТ ЛИ ВООБЩЕ ИДТИ ПО ЭТОМУ ЧАСТИЧНОМУ ПУТИ.
    ///
    /// Частичный путь берут не от хорошей жизни: полного нет, и мы идём
    /// «насколько можно», чтобы с нового места открылся обход.
    ///
    /// Огрызок, который не приближает, но и высоты не теряет, — это РАЗВЕДКА
    /// (AllowExploration в поиске пути): стоя в комнате, бот не узнает, что
    /// дверь за углом, пока не сходит посмотреть. Запрети мы и такие — вернулся
    /// бы старый ответ «не дошёл», данный не сделав ни шагу.
    ///
    /// А ВНИЗ РАЗВЕДКА НУЖНА РОВНО ТАК ЖЕ, И ЭТО ПЕРЕПИСАНО 02.09. Здесь
    /// стояло «вниз разведка не нужна: за неё платят здоровьем и высотой,
    /// которую набирать заново», и по этой строке бот не шёл в яму, через
    /// которую только и лежала дорога. Живьём, слова самого бота:
    ///   «частичный путь не беру: этот огрызок уводит вниз на 4 бл от цели,
    ///    которая выше: было 7, станет 14 — спуск стоит здоровья, а высоту
    ///    потом набирать заново»
    /// — а у хозяина на это: «даже спрыгнуть было бы ок, не такая высота», и
    /// при боте были лопата, кирка и лестницы. Бот стоял.
    ///
    /// ОБЕ ПОЛОВИНЫ ТОЙ ЦЕНЫ НАЗЫВАЛИСЬ НА ГЛАЗ, А ОБЕ УЖЕ ПОСЧИТАНЫ ДО НАС.
    /// <list type="bullet">
    /// <item>ЗДОРОВЬЕ. Сколько стоит падение, знает ИГРА
    /// (<c>EntityBehaviorHealth.OnFallToGround</c> → у нас
    /// <see cref="AStarPathFinder.EstimateFallDamage"/>), и поиск пути не
    /// отдаёт хода, чья цена больше <c>PathOptions.FallDamageBudget</c> роли
    /// (AStarPathFinder: спрыгивание и прыжок через яму). Значит у ЛЮБОГО
    /// огрызка, который нам вообще принесли, спуск уже в пределах роли —
    /// и повторять здесь «спуск стоит здоровья» нечего.</item>
    /// <item>ВЫСОТА. Чем брать её обратно, знает ровно один механизм на весь
    /// проект (<see cref="WayBackFromBelow"/> ← <c>Tunnel.ChooseWayOut</c>:
    /// ступени, лестница, столб), и спрашивают его ПЕРЕД этим правилом
    /// (<c>Movement.MayGoDown</c>). Пришёл его ответ — высота оплачена, и
    /// оплачена не догадкой, а лестницами в сумке.</item>
    /// </list>
    /// Третьей цены здесь не заводится нарочно: разъедься она с этими двумя —
    /// и бот отказывался бы спускаться туда, откуда прекрасно выходит.
    ///
    /// ПОЧЕМУ ЭТО НЕ ВЕРНЁТ ТРЁХМИНУТНУЮ КАРУСЕЛЬ «!комне» (спрыгнул — вылез —
    /// спрыгнул — вылез). Против неё в проекте стоят ДВА правила, и оба
    /// спрашиваются РАНЬШЕ этого: <see cref="UndoesClimb"/> («я уже поднимался
    /// с 115, а этот путь снова опускает меня до 115 при цели на 119») и
    /// память мест похода (<c>Movement.ScoutOrCircle</c>: «это круг»). Здесь
    /// была ТРЕТЬЯ копия того же запрета — слепая, без памяти о походе, — и
    /// платил за неё не круг, а первый честный спуск.
    /// </summary>
    /// <param name="flatNow">Сколько до цели по полу СЕЙЧАС.</param>
    /// <param name="aboveNow">На сколько цель выше нас сейчас (минус — ниже).</param>
    /// <param name="flatEnd">Сколько будет по полу в КОНЦЕ этого огрызка.</param>
    /// <param name="aboveEnd">На сколько цель будет выше нас в конце огрызка.</param>
    /// <param name="step">Насколько должно стать ближе, чтобы это считалось.</param>
    /// <param name="climbCost">Цена блока подъёма (у роли — PathOptions.ClimbCost).</param>
    /// <param name="dropCost">Цена блока спуска.</param>
    /// <param name="wayBack">
    /// ЧЕМ ОПЛАЧЕН СПУСК — ГОТОВЫЕ СЛОВА ТОГО, КТО ПОДНИМЕТ ОБРАТНО
    /// (<see cref="WayBackFromBelow"/>: «вниз на 4 бл можно: обратно — лестниц
    /// 6, хватит на 12 бл»). Пусто или null — про возврат НЕ СПРАШИВАЛИ, и
    /// тогда вниз не идём: неоплаченный спуск — это яма 23.08, из которой бот
    /// с пустыми сумками не вылез за час.
    /// </param>
    /// <returns>Take — идти ли; Why — причина, обязательная и в отказе, и в согласии.</returns>
    public static (bool Take, string Why) WorthPartialPath(
        double flatNow, double aboveNow, double flatEnd, double aboveEnd,
        double step = 0.5, double climbCost = ClimbCostPerBlock,
        double dropCost = DropCostPerBlock, string? wayBack = null)
    {
        double now = GapToTarget(flatNow, aboveNow, climbCost, dropCost);
        double end = GapToTarget(flatEnd, aboveEnd, climbCost, dropCost);
        // Насколько огрызок опускает нас ОТНОСИТЕЛЬНО ЦЕЛИ: цель стоит на
        // месте, поэтому рост «цель выше меня» и есть спуск
        double down = aboveEnd - aboveNow;

        if (end <= now - step)
            return (true, down > 0
                ? $"путь спускает на {down:0.#} бл, но всё равно приближает: " +
                  $"было {now:0.#}, станет {end:0.#} (с учётом высоты)"
                : $"путь приближает: было {now:0.#}, станет {end:0.#} (с учётом высоты)");

        if (down > 0)
            return wayBack is { Length: > 0 } paid
                ? (true, $"путь спускает на {down:0.#} бл и ближе не делает (было {now:0.#}, " +
                         $"станет {end:0.#} с учётом высоты) — иду разведать низом, спуск " +
                         $"оплачен: {paid}")
                : (false, $"этот огрызок уводит вниз на {down:0.#} бл от цели, которая " +
                          $"выше: с учётом высоты было {now:0.#}, станет {end:0.#}, а чем " +
                          "подниматься обратно, меня не спросили — неоплаченный спуск не беру");

        return (true, $"ближе не станет (было {now:0.#}, станет {end:0.#}), зато и высоты " +
                      "не теряю — иду разведать, что там");
    }

    /// <summary>
    /// ОТМЕНЯЕТ ЛИ ЭТОТ ПУТЬ УЖЕ СДЕЛАННЫЙ ПОДЪЁМ — то есть не зря ли мы лезли.
    ///
    /// ЖИВОЙ СЛУЧАЙ (тот же поход «!комне»): «я в яме на 4 бл ниже цели —
    /// выбираюсь наверх», «штольня: прошёл вверх 4 ступеней, взял 4 из 4 бл»
    /// — и следующей же строкой «спрыгиваю к (512283, 115, 511777)», ровно
    /// туда, откуда только что вылез. Круг замкнулся, и так три минуты.
    ///
    /// Труд подъёма — это вырубленные ступени, потраченное время и здоровье.
    /// Спуститься обратно на ту же отметку значит выбросить его целиком, и
    /// делать это можно только ради цели, которая внизу.
    /// </summary>
    /// <param name="endY">Высота, на которой ноги окажутся в конце пути.</param>
    /// <param name="climbedFrom">
    /// С какой отметки бот уже поднимался за этот поход (null — не поднимался,
    /// и терять нечего).
    /// </param>
    /// <param name="targetY">Высота цели: ради неё вниз идти можно.</param>
    public static (bool Undoes, string Why) UndoesClimb(int endY, int? climbedFrom, int targetY)
    {
        if (climbedFrom is not { } floor)
            return (false, "наверх я в этот поход ещё не лез — терять нечего");
        if (targetY <= endY)
            return (false, $"цель на {targetY} не выше конца пути ({endY}) — " +
                           "спуск сюда труда не отменяет");
        if (endY > floor)
            return (false, $"конец пути на {endY}, а поднимался я с {floor} — " +
                           "набранное остаётся при мне");
        return (true, $"я уже поднимался с {floor}, а этот путь снова опускает меня " +
                      $"до {endY} при цели на {targetY} — весь труд насмарку");
    }

    /// <summary>
    /// СТОИТ ЛИ СПУСКАТЬСЯ С ОБРЫВА, КОГДА ЦЕЛЬ НАВЕРХУ.
    ///
    /// Спуск с обрыва — законный ответ на «дороги нет»: живой случай со скалой
    /// начинался именно так, и там цель была НА ТОЙ ЖЕ ВЫСОТЕ. Но тот же
    /// механизм в походе «!комне» сработал при цели на четыре блока ВЫШЕ бота
    /// («впереди обрыв в 2 бл, а цель за ним — спускаюсь») и увёл его ещё ниже.
    ///
    /// Цель наверху — значит вниз мы уходим от неё, а не к ней: пройти под
    /// обрывом всё равно придётся с подъёмом, вдвое дороже каждого блока.
    /// </summary>
    /// <param name="targetAbove">На сколько блоков цель выше нас (минус — ниже).</param>
    /// <param name="drop">На сколько блоков вниз собираемся.</param>
    public static (bool Go, string Why) WorthDescending(int targetAbove, int drop)
    {
        if (targetAbove < 1)
            return (true, targetAbove == 0
                ? "цель на моей высоте — обрыв тут и правда может мешать"
                : $"цель на {-targetAbove} бл ниже меня — вниз мне и надо");
        return (false, $"цель на {targetAbove} бл ВЫШЕ меня, а спуск уводит ещё на " +
                       $"{drop} бл вниз — это дорога от цели, а не к ней");
    }

    /// <summary>
    /// ВЫБЕРУСЬ ЛИ Я ОБРАТНО — ЕДИНСТВЕННЫЙ ВОПРОС ПЕРЕД ЛЮБЫМ СПУСКОМ.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ЖУРНАЛ ЗАКАЗЧИКА 23.08 (10:55–11:04). Бот поднялся с
    /// пустыми сумками — ни кирки, ни лопаты, ни лестниц, ни блоков — и дальней
    /// дорогой сделал два шага «иду как можно ближе», каждый на два блока вниз:
    /// <code>
    ///   10:55:35 дорога: 3 точек до (47, 104, 264), всего до цели 20 бл
    ///   10:55:37 дорога: 3 точек до (45, 102, 264), всего до цели 18 бл
    ///   10:56:45 я в яме на 8 бл ниже цели — выбираюсь наверх
    ///   10:56:45 наверх на 8 бл: лестницей — лестниц 0; столбом — годных
    ///            блоков 0, а надо 8; ступенями — встать не на что
    /// </code>
    /// Дальше он час перебирал одно и то же, стоя на дне.
    ///
    /// ПОЧЕМУ ПРАВИЛО «НЕ БЕРУ ОГРЫЗОК ВНИЗ» (<see cref="WorthPartialPath"/>)
    /// НЕ СПАСЛО. Оно спрашивает про ЦЕЛЬ («уводит ли этот путь от неё»), а не
    /// про ВОЗВРАТ, и сработало, когда бот уже стоял на дне: оттуда любой
    /// огрызок и правда уводил от цели, которая наверху. Вопрос «а выберусь ли
    /// я обратно» не задавал НИКТО — ни частичный путь, ни дальняя дорога, ни
    /// спуск с уступа, ни спрыгивание. Цена спуска считалась только в хп
    /// (<c>PathOptions.FallDamageBudget</c>), а цена ПОДЪЁМА ОБРАТНО —
    /// лестницы, блоки, кирка — не считалась нигде.
    ///
    /// ВТОРОЙ МЕРКИ ЗДЕСЬ НЕТ НАРОЧНО. «Чем я поднимусь на N блоков» знает
    /// ровно один механизм на весь проект — тот, который и поднимает
    /// (<c>Scaffolding.GetOutAsync</c> → <c>Tunnel.ChooseWayOut</c>: ступени,
    /// лестница, столб). Этот вопрос ему и задаётся, а сюда приходит его
    /// ГОТОВЫЙ ОТВЕТ. Заведи мы тут свой счёт лестниц и блоков — он разошёлся
    /// бы с настоящим подъёмом на первой же правке, и бот отказывался бы
    /// спускаться туда, откуда прекрасно выходит (или наоборот).
    /// </summary>
    /// <param name="drop">На сколько блоков вниз мы окажемся ниже нынешнего пола.</param>
    /// <param name="back">
    /// Чем подъём обратно на <paramref name="drop"/> блоков возьмётся — ответ
    /// механизма подъёма. <see cref="WayOut.Trapped"/> значит «нечем».
    /// </param>
    /// <param name="backWhy">Его же слова с числами — их и покажем человеку.</param>
    /// <param name="freeDrop">
    /// Спуск, который тело отыгрывает САМО и даром: на столько блоков оно
    /// запрыгивает обратно (<see cref="JumpPhysics.CellsUp"/>). Своего числа
    /// тут нет: прыжок один на весь проект.
    /// </param>
    public static (bool Go, string Why) WayBackFromBelow(
        int drop, WayOut back, string backWhy, int freeDrop)
    {
        if (drop <= 0)
            return (true, "вниз я тут не иду — спускаться некуда");
        if (drop <= freeDrop)
            return (true, $"спуск на {drop} бл — обратно запрыгну сам " +
                          $"(прыжок берёт {freeDrop} бл), тратить нечего");
        if (back == WayOut.Trapped)
            return (false, $"вниз на {drop} бл не пойду: обратно подниматься нечем — {backWhy}");
        return (true, $"вниз на {drop} бл можно: обратно — {backWhy}");
    }

    /// <summary>
    /// ВО СКОЛЬКО РАЗ ДОРОЖАЕТ КЛЕТКА, В КОТОРУЮ ТЕЛО УЖЕ УПИРАЛОСЬ, — и когда
    /// про это пора сказать вслух.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ЖУРНАЛ 23.08. Бот упёрся в клетку (61, 112, 251)
    /// ДВЕНАДЦАТЬ раз за две минуты, каждый раз открывая и закрывая по дороге
    /// одну и ту же дверь. Ни одной строки «тупик … запомнил, буду обходить» в
    /// журнале при этом нет: память тупиков была ВЫКЛЮЧЕНА у дверей целиком, и
    /// выключена молча.
    ///
    /// ПЕРВЫЙ РАЗ — СЛУЧАЙНОСТЬ, ВТОРОЙ — СВОЙСТВО МЕСТА. Один затор бывает от
    /// обстановки: кто-то встал на пути, дверь закрылась, мир доехал не весь.
    /// Такую клетку достаточно сделать дороже — маршрут сам поищет обход, а не
    /// найдя, всё же пройдёт (это по-прежнему последний довод, а не запрет).
    /// А клетка, в которую тело не вошло ДВАЖДЫ ПОДРЯД, — это уже не обстановка,
    /// а её собственное свойство: там просто не пролезть. Третий заход в неё
    /// стоит ровно столько же, сколько первые два, и кончится тем же.
    /// </summary>
    /// <param name="bumps">Сколько раз тело упиралось в эту клетку.</param>
    /// <param name="once">Надбавка за один затор (у движения — DeadEndPenaltyFactor).</param>
    /// <param name="stubborn">
    /// Надбавка со второго затора. Не бесконечность нарочно: маршрут через
    /// такую клетку остаётся ВОЗМОЖНЫМ, если другого нет вовсе, — запрети
    /// вовсе, и бот запрёт себя в комнате собственной памятью.
    /// </param>
    public static (double Price, string? News) PriceOfBumpedCell(
        int bumps, double once, double stubborn)
    {
        if (bumps <= 0)
            return (1, null);
        if (bumps == 1)
            return (once, null);
        return (stubborn, $"тело не вошло сюда {bumps} раза подряд — " +
                          "дальше веду маршрут мимо, а не сквозь");
    }

    // ---------------- спрямление ----------------

    /// <summary>
    /// Поставлена ли эта точка СПРЯМЛЕНИЕМ, а не поиском пути.
    ///
    /// Признак простой и надёжный: поиск пути ходит ПО КЛЕТКАМ, и обычный шаг
    /// у него всегда в соседнюю. Всё, что дальше соседней клетки, — либо особый
    /// ход (прыжок, спрыгивание, зацеп: они помечены своим типом), либо работа
    /// спрямления, выкинувшего промежуточные клетки.
    ///
    /// ЗАЧЕМ ЭТО РАЗЛИЧАТЬ. Живой случай, словами хозяина: «тупо застрял и
    /// перезапуск пути не помогает. Он должен пройти через гору или мимо, а он
    /// стоит на ней и застрял». В журнале: маршрут на 94 блока из ТРЁХ точек,
    /// вторая — в семи блоках по прямой через гору. Тело шло к ней напрямик,
    /// упиралось в склон, докладывало «упёрся», а поиск пути на каждой
    /// следующей попытке отдавал ТОТ ЖЕ САМЫЙ путь: спрямление считало прямую
    /// проходимой, и никакая память тупиков этого не меняла.
    ///
    /// Не дошли до СОСЕДНЕЙ клетки — виновата дорога, и надо искать обход.
    /// Не дошли до СПРЯМЛЁННОЙ точки — виновато спрямление, и надо строить
    /// заново без него: клетка за клеткой тело пройдёт и вокруг горы, и по ней.
    /// Без этого различия обе беды лечились одинаково — и одна из них не
    /// лечилась вовсе.
    /// </summary>
    public static bool IsStraightenedLeg(BlockPos from, BlockPos to, StepKind kind) =>
        kind == StepKind.Walk &&
        Math.Max(Math.Abs(to.X - from.X), Math.Abs(to.Z - from.Z)) > 1;

