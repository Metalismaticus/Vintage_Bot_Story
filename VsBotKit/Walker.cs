    /// <summary>ЧТО ВЫШЛО ИЗ ОКНА ЗАМЕРА СКОРОСТИ.</summary>
    public enum SpeedWindow
    {
        /// <summary>
        /// Окно ещё коротко: целых тиков в нём не набралось. Ответа нет, и
        /// якорь замера трогать нельзя — окно копится дальше.
        /// </summary>
        Short,

        /// <summary>
        /// Окно РВАНОЕ: из него вышло быстрее, чем тело вообще умеет по земле.
        /// Замер выбрасывается целиком, а якорь заводится заново.
        /// </summary>
        Torn,

        /// <summary>Замер годен.</summary>
        Good
    }

    /// <summary>
    /// СКОЛЬКО ЦЕЛЫХ ТИКОВ ТЕЛА ДОЛЖНО НАБРАТЬСЯ В ОКНЕ, ЧТОБЫ ЗАМЕР ЧТО-ТО
    /// ЗНАЧИЛ. ЧИСЛО ВЫВЕДЕНО, А НЕ ПОДОБРАНО, И ВОТ ВЫВОД ЦЕЛИКОМ.
    ///
    /// ОТКУДА ВООБЩЕ БЕРЁТСЯ ОШИБКА. Путь снимается с положения тела, время —
    /// с его часов, и это ДВА РАЗНЫХ ПОЛЯ: тело сперва двигает себя
    /// (<c>physics.Tick()</c>), и только следующей строкой прибавляет тик к
    /// часам (<c>Body.StartLoop</c>). Между этими двумя строками положение уже
    /// новое, а часы ещё старые — и снимок, попавший в эту щель, приносит на
    /// ОДИН ТИК ПУТИ БОЛЬШЕ, чем на него отпущено времени. Больше одного тика
    /// оттуда не возьмётся никогда: второго <c>Tick()</c> в щели нет.
    ///
    /// ЧТО ЭТОТ ЛИШНИЙ ТИК СТОИТ. За тик тело проходит самое большее
    /// <c>SprintSpeed · TickSeconds</c> блоков; поделённое на окно из W тиков
    /// (<c>W · TickSeconds</c> секунд), это <c>SprintSpeed / W</c> бл/с —
    /// длительность тика сокращается, и число выходит в ЧИСТЫХ ТИКАХ.
    /// Дальность считает единственная формула проекта
    /// (<see cref="JumpPhysics.FlightAtSpeed"/>), она прямая, и её наклон —
    /// <c>(RunningFlight − StandingFlight) / SprintSpeed</c>. Значит рваный тик
    /// врёт о ПОЛЁТЕ ровно на
    ///     (RunningFlight − StandingFlight) / W блоков,
    /// и скорость тела в этом ответе тоже сократилась.
    ///
    /// ГДЕ ГРАНИЦА. Столько же, сколько роль и так отпустила прыжку на ошибку
    /// модели, — <c>PathOptions.SafeJumpMargin</c> (закон 1: число — ручка
    /// роли). Врать больше запаса мерке нельзя: тогда разбег кончится
    /// «я разогнан» там, где тело не долетит. Отсюда
    ///     W ≥ (RunningFlight − StandingFlight) / запас,
    /// и на заводском запасе 0,45 это 2,341 / 0,45 = 5,2 → ШЕСТЬ ТИКОВ
    /// (тик игры 1/60 с, значит окно ровно 0,1 с).
    ///
    /// ПОТОЛОК ОКНА — ВЕСЬ РАЗБЕГ. Роль, не отпустившая прыжку никакого запаса,
    /// не терпит и рваного тика, а окна без единого рваного тика не бывает;
    /// честный ответ такой роли — «окно длиной во весь разгон», то есть замер
    /// не поспеет и решать будет РАССТОЯНИЕ. Это безопасная сторона: лишний
    /// разгон прыжку не мешает, а недобранный — это дно ямы.
    /// </summary>
    /// <param name="jumpMargin">
    /// Запас прыжка роли, блоков (<c>PathOptions.SafeJumpMargin</c>).
    /// </param>
    public static int SpeedWindowTicks(double jumpMargin)
    {
        // Весь разгон в тиках: полоса RunUpToFullSpeed, пройденная ШАГОМ, —
        // тот же счёт, которым выводится терпение сторожа разбега
        int весьРазгон = (int)Math.Ceiling(
            JumpPhysics.RunUpToFullSpeed / JumpPhysics.WalkSpeed /
            BotGamePhysics.GamePlayerPhysics.TickSeconds);
        if (!(jumpMargin > 0))
            return весьРазгон;
        double надо = (JumpPhysics.RunningFlight - JumpPhysics.StandingFlight) / jumpMargin;
        return Math.Clamp((int)Math.Ceiling(надо), 1, весьРазгон);
    }

    /// <summary>
    /// СКОРОСТЬ ИЗ ОКНА ЗАМЕРА — И ЧЕСТНЫЙ ОТКАЗ ВМЕСТО ПРАВДОПОДОБНОГО ЧИСЛА.
    ///
    /// ЖИВАЯ БЕДА, РАДИ КОТОРОЙ ЭТО ПРАВИЛО ЕСТЬ (набор под нагрузкой 08.09).
    /// Разбег померил себе 8,7 бл/с — на 28 % выше <see cref="JumpPhysics.SprintSpeed"/>,
    /// физического потолка тела по земле. Столько тело не бежит НИКОГДА, и
    /// значит число говорило не о скорости, а о том, что окно замера рваное.
    /// Разбег поверил, решил «я разогнан свыше нужного», оборвался через
    /// полблока — и прыжок не долетел: «до цели 5,48 бл, с такой скорости
    /// достаю 5,45».
    ///
    /// ПРИЖАТЬ К ПОТОЛКУ БЫЛО БЫ ТИХОЙ ЛОЖЬЮ, и потому здесь отказ, а не
    /// <c>Math.Min</c>. Прижатое число значит «тело на полном ходу» — то есть
    /// ровно то, чего замер как раз и не показал; разбег кончился бы с тем же
    /// исходом, только молча. Рваный замер надо ВЫБРОСИТЬ и ждать следующего
    /// целого окна: пока скорости нет, решает пройденный путь и кромка.
    ///
    /// РАВЕНСТВО ПОТОЛКУ — ЕЩЁ НЕ РАЗРЫВ: полный бег по ровной земле это и
    /// есть <see cref="JumpPhysics.SprintSpeed"/>, и объявлять его невозможным
    /// значило бы выбрасывать самый нужный замер.
    /// </summary>
    /// <param name="blocks">Путь между двумя снимками положения, блоков.</param>
    /// <param name="seconds">Время между ними ПО ЧАСАМ ТЕЛА, секунд.</param>
    /// <param name="leastSeconds">
    /// Сколько времени должно набраться в окне, чтобы замер что-то значил, —
    /// <see cref="SpeedWindowTicks"/> тиков.
    /// </param>
    public static (SpeedWindow What, double Speed) SpeedByPath(
        double blocks, double seconds, double leastSeconds)
    {
        // Сравнение написано «не больше», а не «меньше», нарочно: так же
        // отсеивается NaN, который иначе прошёл бы обе заставы насквозь
        if (!(seconds >= leastSeconds) || !(seconds > 0))
            return (SpeedWindow.Short, -1);
        double speed = blocks / seconds;
        if (!(speed <= JumpPhysics.SprintSpeed))
            return (SpeedWindow.Torn, -1);
        return (SpeedWindow.Good, speed);
    }

    // ---------------- долетел или недолетел ----------------

    /// <summary>
    /// Насколько близко к цели должно оказаться тело, чтобы прыжок считался
    /// удавшимся. Клетка — это метр, и приземление в её дальнем углу нормально;
    /// а вот полтора метра мимо — уже не «сел с краю», а промах.
    /// </summary>
    public const double LandedWithin = 1.2;

    /// <summary>
    /// Насколько ниже цели можно оказаться и всё ещё считаться долетевшим.
    /// Больше — значит тело не село на уступ, а сползло по его стенке вниз:
    /// по горизонтали при этом всё «почти сошлось», и без этой проверки
    /// падение в яму выдавалось за успех.
    /// </summary>
    public const double LandedBelow = 1.5;

    /// <summary>
    /// Долетел ли прыжок.
    ///
    /// ГЛАВНОЕ ЗДЕСЬ — что этот вопрос вообще задаётся. На месте проверки
    /// стоял голый переход к следующей точке: недолёт был неотличим от успеха,
    /// бот честно прыгал, падал в яму и шёл дальше по маршруту, которого под
    /// ним уже не было. Со стороны это выглядело как «бот не прыгает».
    /// </summary>
    /// <param name="toTarget">Сколько блоков до цели по горизонтали ПОСЛЕ прыжка.</param>
    /// <param name="below">На сколько блоков мы НИЖЕ цели (минус — выше).</param>
    /// <param name="caughtLadder">
    /// Тело висит на лестнице. Это тоже посадка: планировщик нарочно кладёт
    /// такие ходы (JumpToLadder), игрок так перепрыгивает с уступа на лестницу
    /// в шахте. Требовать от него ещё и попасть в клетку значило бы объявить
    /// промахом удавшийся зацеп.
    /// </param>
    public static bool JumpLanded(double toTarget, double below, bool caughtLadder = false) =>
        caughtLadder || (toTarget <= LandedWithin && below <= LandedBelow);

    /// <summary>
    /// Итог прыжка одним решением: пришли — или отказ с числами промаха.
    ///
    /// Числа в причине не украшение: по журналу «не долетел: до цели 2.3 бл,
    /// ниже на 0.1» сразу видно, что промах горизонтальный (не хватило
    /// разбега), а по «до цели 0.3, ниже на 3» — что тело сорвалось со стенки.
    /// Без них в журнале была одна строка «застрял», и разбирать было нечего.
    /// </summary>
    public static WalkDecision AfterJump(BlockPos target, double toTarget, double below,
        bool caughtLadder = false)
    {
        if (caughtLadder)
            return new WalkDecision(WalkMove.Climb, target, "зацепился за лестницу в полёте");
        if (JumpLanded(toTarget, below))
            return new WalkDecision(WalkMove.Arrived, target, "долетел");
        return Refuse(target, $"не долетел: до цели {toTarget:0.#} бл, ниже на {below:0.#}");
    }

    // ---------------- размер тела ----------------

    /// <summary>
    /// Рост тела, блоков — из одного места на весь проект
    /// (<see cref="BodySize.Height"/>). Здесь рост важнее ширины: за лестницу
    /// цепляются ТЕЛОМ, а не ногами.
    /// </summary>
    public const double BodyHeight = BodySize.Height;

    /// <summary>
    /// СКОЛЬКО КЛЕТОК ВВЕРХ НУЖНО ТЕЛУ, ЧТОБЫ ПРОЙТИ, — две: ноги и голова.
    ///
    /// Ровно так и считает сама игра: EntityBehaviorControlledPhysics
    /// (Mods/VSEssentials.dll, 1.22.7) берёт
    /// <c>(int)Math.Ceiling(entity.CollisionBox.Y2)</c> и перебирает столько
    /// клеток своей колонны. Округление ВВЕРХ здесь не украшение: 1.85 не
    /// влезает в одну клетку, а полторы клетки игра не умеет.
    ///
    /// ЗАЧЕМ ОТДЕЛЬНОЕ ИМЯ. Просвет спрашивают разные механизмы — ход штольни
    /// (<see cref="Tunnel.Height"/>), выемка дороги (<see cref="Roads.Height"/>),
    /// место под удар (Quarry.CanWorkFrom). Пока числа «2» стояли в каждом
    /// своей константой, любую из них можно было опустить до единицы, и бот
    /// честно копал ход, в который телом не входил: в журнале это выглядело
    /// как «клетка вскрыта, а тело в неё не идёт» — строка без причины.
    /// </summary>
    public static int MinHeadroom => (int)Math.Ceiling(BodyHeight);

    /// <summary>
    /// НАСКОЛЬКО ТЕЛО МОЖЕТ НЕ ДОСТАВАТЬ ДО ВЕРХА ОПОРЫ И ВСЁ-ТАКИ СТОЯТЬ НА
    /// НЕЙ, блоков. Физика игрока садится на опору не точь-в-точь: за тик тело
    /// вдавливается в неё на доли блока и выталкивается обратно, и требовать
    /// точного равенства значило бы то и дело считать стоящего висящим.
    ///
    /// Число не новое: ровно с ним <see cref="Body"/> уже отличал «врос в
    /// блок» от «стою на нём», и здесь оно ровно то же — иначе два ответа на
    /// один вопрос разошлись бы на этих самых сантиметрах.
    /// </summary>
    private const double StandGap = 0.05;

    /// <summary>
    /// СТОИМ ЛИ МЫ НА БЛОКЕ, ЛЕЖАЩЕМ В НАШЕЙ ЖЕ КЛЕТКЕ НОГ — чистое правило.
    ///
    /// ЗАЧЕМ ОНО ВООБЩЕ НУЖНО. Клетка ног считается как <c>floor(Y)</c>, и для
    /// целых кубов этого хватает: встав на куб, тело оказывается РОВНО на
    /// границе клеток, и его клетка — пустая, что над кубом. Но у половины
    /// блоков игры верх коробки НЕ целый: каменная тропа 0.9375, плита 0.5,
    /// снег и того меньше. Встав на такой блок, тело остаётся ВНУТРИ его
    /// клетки по счёту <c>floor</c> — 110,9375 → клетка 110, — хотя занимает
    /// её лишь сверху и ничему в ней не мешает.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ЗА КОТОРЫЙ ЗАПЛАЧЕНО ДВАЖДЫ. Оба раза бот стоял на
    /// каменной тропе своей же дороги и оба раза не мог с неё уйти:
    ///   01:33:46 «под ногами уже stonepath-free — столбиться некуда»
    ///             (блоков в сумках было 362);
    ///   20:36:38 «столбиться в (512076, 110, 512237) нельзя: клетка занята
    ///             (stonepath-free)».
    /// Оба раза клетку ног считали как <c>floor(Y)</c> = 110, попадали в саму
    /// тропу и честно получали «занято». А живой игрок в этом месте кидает
    /// блок в клетку 111 — ту, где стоят его ноги ВЫШЕ тропы, — и поднимается.
    ///
    /// ЧЕМ ЭТО НЕ <see cref="Tunnel.StepRise"/>. Тот считает, куда ноги
    /// ПРИДУТ, встав на чужую опору сбоку; здесь — на чём они стоят СЕЙЧАС.
    /// Мерка у обоих одна (верх коробки, <c>WorldModel.GetCollisionTop</c>),
    /// и это не совпадение: разойдись они, бот снова обещал бы себе клетку,
    /// которой у него нет.
    /// </summary>
    /// <param name="y">Высота тела по физике (не по клетке).</param>
    /// <param name="feetY">Клетка ног — <c>floor(y)</c>.</param>
    /// <param name="collisionTop">
    /// Верх коробки блока В КЛЕТКЕ НОГ: 0 — там пусто, 1.0 — целый куб,
    /// 0.9375 — каменная тропа. Спрашивается у мира, не выдумывается.
    /// </param>
    public static bool StandingOnOwnCell(double y, int feetY, double collisionTop) =>
        collisionTop > 0 && y >= feetY + collisionTop - StandGap;

    /// <summary>
    /// КЛЕТКА ПОД НОГАМИ, СВОБОДНАЯ ОТ ОПОРЫ, — та самая, куда живой игрок
    /// кидает блок, чтобы подняться столбом, и та, которую он выбивает из-под
    /// себя, чтобы спуститься.
    ///
    /// На ровном полу это клетка ног и есть, и вся правка тут ничего не
    /// меняет. Разница ровно одна и ровно там, где бот два раза заперся сам:
    /// стоя НА частичном блоке своей клетки, свободна следующая клетка вверх.
    /// </summary>
    public static int CellUnderFeet(double y, int feetY, double collisionTop) =>
        StandingOnOwnCell(y, feetY, collisionTop) ? feetY + 1 : feetY;

    /// <summary>
    /// В КАКОЙ КЛЕТКЕ СТОЯТ НОГИ — и это НЕ то же самое, что
    /// <see cref="CellUnderFeet"/>.
    ///
    /// Разница ровно в одном вопросе: там спрашивают «какая клетка подо мной
    /// свободна» (куда бросить блок под ноги, что выбить, чтобы спуститься),
    /// здесь — «в какой клетке я стою» глазами мира. Ответы расходятся на
    /// НЕВЫСОКИХ блоках: на полублок (0.4375 у stonepathslab) игрок ВСХОДИТ,
    /// как на ступеньку, и остаётся в клетке этого полублока — ровно так
    /// считает <see cref="WorldModel.FeetY"/> и <see cref="WorldModel.IsStandable"/>.
    /// А блок выше шага (0.9375 у stonepath) — это уже ПОЛ: в его клетку тело
    /// не входит, и стоит оно в клетке НАД ним.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ради которого правило заведено (bot.log 16.08, 20:36:38):
    /// «стою (512066,5, 110,9, 512237,7)» — бот на СВОЁМ дорожном полотне
    /// stonepath-free. <c>floor(Y)</c> = 110, то есть клетка самой тропы, а мир
    /// в этой клетке стоять не даёт вовсе (<c>IsPassable</c> там ложь): поиск
    /// пути начинал из клетки, которой у бота нет, дорога мерила «дошёл ли я до
    /// полотна» на клетку ниже нужной и вечно отвечала «тело по ней не идёт»,
    /// а тупики запоминались этажом ниже, чем случились.
    ///
    /// НА ОБЫЧНОМ ПОЛУ ПРАВИЛО НЕ МЕНЯЕТ НИЧЕГО: встав на целый куб, тело
    /// оказывается ровно на границе клеток, и верх коробки в его собственной
    /// клетке — ноль.
    /// </summary>
    /// <param name="y">Высота тела по физике (не по клетке).</param>
    /// <param name="feetY">Клетка ног по счёту <c>floor(y)</c>.</param>
    /// <param name="collisionTop">
    /// Верх коробки блока В КЛЕТКЕ <paramref name="feetY"/>. Спрашивается у
    /// мира (<see cref="WorldModel.GetCollisionTop"/>), не выдумывается.
    /// </param>
    public static int StandingCell(double y, int feetY, double collisionTop) =>
        collisionTop > WorldModel.StepHeight && StandingOnOwnCell(y, feetY, collisionTop)
            ? feetY + 1
            : feetY;

    // ---------------- падение: сколько его ждать ----------------

    /// <summary>
    /// СКОЛЬКО ТЕЛО ПАДАЕТ НА <paramref name="blocks"/> БЛОКОВ, секунд.
    ///
    /// Своей гравитации здесь нет и быть не должно: падение и прыжок — одна и
    /// та же парабола игры. Прыжок поднимает тело на
    /// <see cref="JumpPhysics.ApexRise"/> = 1,27 бл за половину
    /// <see cref="JumpPhysics.AirTime"/> = 0,683 с, значит h(t) = ApexRise ·
    /// (t / (AirTime/2))², откуда t(h) = (AirTime/2)·√(h/ApexRise). Блок —
    /// 0,30 с, четыре — 0,61 с. Заведи рядом свою постоянную тяготения — и два
    /// ответа об одном полёте разошлись бы на первой же правке.
    ///
    /// (Пересказ времени полёта тут стоял свой — «0,72 с», и он отстал от
    /// замера: сама формула считала по <see cref="JumpPhysics.AirTime"/> и была
    /// права, а читающий комментарий — обманут.)
    /// </summary>
    public static double FallSeconds(double blocks) =>
        blocks <= 0 ? 0 : JumpPhysics.AirTime / 2 * Math.Sqrt(blocks / JumpPhysics.ApexRise);

    /// <summary>
    /// СКОЛЬКО ЖДАТЬ, ЧТО ТЕЛО САМО ПРИДЁТ В КЛЕТКУ НА <paramref name="drop"/>
    /// БЛОКОВ НИЖЕ, секунд. Ноль — ждать нечего: вниз идти некуда, а вверх
    /// тяготение не носит.
    ///
    /// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ПРАВИЛО НАПИСАНО (bot.log 16.08, 12:46:49).
    /// Штольня шла колодцем вниз, клетка под ногами была уже вскрыта, и
    /// в журнале стоит:
    ///   12:46:49.379 «копаю ход от (512180, 111, 512275) к (512180, 106, …)»
    ///   12:46:49.380 «остановка: клетка (512180, 110, 512275) вскрыта, а тело
    ///                 в неё не идёт»
    /// Одна миллисекунда на весь заход — за это время тело не падает НИКОГДА.
    /// А тремя секундами позже бот преспокойно стоит в этой самой клетке. Шаг
    /// вниз делает не ходьба, а тяготение, и судить о нём раньше, чем оно
    /// успело сработать, — это отказ, назначенный до попытки.
    ///
    /// Запас сверх самого падения — <see cref="JumpPhysics.AirTime"/>: дольше
    /// этого тело в воздухе не держится даже в прыжке, а бесконечное ожидание
    /// было бы новой бедой вместо старой.
    /// </summary>
    public static double DropWait(int drop) =>
        drop <= 0 ? 0 : FallSeconds(drop) + JumpPhysics.AirTime;

    // ---------------- лестницы ----------------

    /// <summary>
    /// Докуда бот дотягивается в высшей точке прыжка: ноги поднимаются на
    /// <see cref="JumpPhysics.ApexRise"/>, а сверху к ним прибавляется рост.
    /// Считает <see cref="JumpPhysics.ReachUp"/> — там же, где и сам прыжок:
    /// о том же расстоянии спрашивает <c>PathOptions</c>, которого мод линкует
    /// без этого файла.
    /// </summary>
    public static double LadderReach => JumpPhysics.ReachUp;

    /// <summary>
    /// Самая высокая ступень, за которую бот ещё зацепится прыжком, блоков
    /// над клеткой ног. Из <see cref="LadderReach"/> = 3.12 — то есть три.
    /// </summary>
    public static int HighestRungReachable => JumpPhysics.HighestRung;

    /// <summary>
    /// Дотянемся ли прыжком до ВИСЯЧЕЙ лестницы — такой, у которой низ обрезан
    /// и до пола не доходит.
    ///
    /// Живой случай: в шахте лестница начиналась в трёх блоках над полом, и
    /// бот бегал под ней вперёд-назад, «не находя пути наверх», хотя игрок
    /// туда просто подпрыгивает. Зацеп срабатывает по касанию тела к плите
    /// лестницы, поэтому предел считается по росту, а не по высоте прыжка:
    /// ноги поднимаются лишь на 1.27, а тело достаёт до 3.12.
    /// </summary>
    /// <param name="rungAbove">
    /// На сколько блоков выше клетки ног висит нижняя ступень. Ноль — лестница
    /// уже у ног, прыгать незачем.
    /// </param>
    public static bool CanGrabLadder(int rungAbove) =>
        rungAbove >= 0 && rungAbove <= HighestRungReachable;

    /// <summary>
    /// Где окажутся ноги после зацепа.
    ///
    /// Тело висит, КАСАЯСЬ нижней ступени, значит ноги встают на клетку ниже
    /// неё: зацепившись за ступень в трёх блоках над полом, бот поднимается
    /// на два. Знать это надо заранее — иначе исполнитель ждёт бота там, где
    /// его не будет, объявляет зацеп неудавшимся и перепрыгивает заново.
    /// </summary>
    public static int FeetAfterGrab(int feetY, int rungAbove) =>
        JumpPhysics.FeetAfterGrab(feetY, rungAbove);

    /// <summary>
    /// Докуда тянутся подряд идущие ступени ОДНОЙ лестницы. Возвращает номер
    /// последней точки этого куска: её и надо взять целью, промежуточные
    /// пропустить.
    ///
    /// Подъём по лестнице непрерывен: игрок жмёт «вверх» и держит. Исполнитель
    /// же шёл к каждой ступени как к отдельной точке — жал, отпускал, проверял
    /// приход — и на длинной шахтной лестнице это выходило рывками, а на
    /// границе клетки бот срывался и съезжал обратно.
    ///
    /// СКЛЕИВАЕМ ТОЛЬКО ОДНО НАПРАВЛЕНИЕ. Маршрут умеет возвращаться в ту же
    /// колонну (залез на площадку, а оттуда обратно вниз в шахту), и склейка
    /// «всё, что в моей колонне через блок» проглотила бы разворот целиком:
    /// бот молча пропустил бы верхнюю точку и полез бы сразу вниз.
    /// </summary>
    public static int LadderRunEnd(IReadOnlyList<BlockPos> path, int index)
    {
        if (path == null || index < 0 || index >= path.Count)
            return index;

        int end = index;
        int dir = 0;
        while (end + 1 < path.Count)
        {
            var here = path[end];
            var next = path[end + 1];
            if (next.X != here.X || next.Z != here.Z)
                break;                       // вышли из колонны — это уже шаг, а не подъём
            int rung = next.Y - here.Y;
            if (rung != 1 && rung != -1)
                break;                       // через ступень не лезут: это прыжок или спрыгивание
            if (dir == 0)
                dir = rung;
            else if (rung != dir)
                break;                       // лестница пошла обратно — другой ход
            end++;
        }
        return end;
    }

    // ---------------- вниз и через: пропасть между ботом и целью ----------------

    /// <summary>
    /// ЧЕМ ПЕРЕЙТИ РАЗРЫВ ВПЕРЕДИ — чистое правило, без мира и без тела.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ради которого написано (журнал 20:24). Заказчик построил
    /// отвесную скалу, дал боту лестницы и землю и позвал «!комне». Цель была
    /// на ТОЙ ЖЕ высоте, в 12,7 бл по полу, а между ними — провал. Бот минуту
    /// бегал кругами и отказался тремя строками подряд: «к стене не пойду»,
    /// «наверх не полезу», «впереди обрыв глубже 1 бл — стою». Обе способности,
    /// которые он звал, были про выход ВВЕРХ ИЗ ЯМЫ, и обе честно ответили «не
    /// наш случай». А случай был другой: идти надо было ВНИЗ или ЧЕРЕЗ, и такой
    /// механики не было вовсе — при полных сумках лестниц и земли.
    ///
    /// ПРЫЖОК ПЕРВЫМ, И ЭТО НЕ ВКУС. Прыжок не стоит ничего и занимает
    /// полсекунды; мост — это блок в каждую клетку разрыва, безвозвратно, плюс
    /// подход к самой кромке на каждый блок. Спрашивать про мост там, где щель
    /// берётся прыжком, значит проедать сумку на ровном месте.
    ///
    /// МОСТИТЬ ЕСТЬ СМЫСЛ ТОЛЬКО ТУДА, ГДЕ ЕСТЬ НА ЧТО ВЫЙТИ. Разрыв без
    /// противоположного края — это не щель, а обрыв, и мост в него — дорожка,
    /// обрывающаяся над пустотой: блоки потрачены, а бот стоит на её конце.
    /// Такое лечится спуском (<see cref="ChooseWayDown"/>), а не стройкой.
    /// </summary>
    /// <param name="gap">Сколько клеток подряд идти не по чему.</param>
    /// <param name="landing">За разрывом есть куда встать (свой уровень ±1 блок).</param>
    /// <param name="canJump">
    /// Тело ДОЛЕТИТ отсюда до того края. Считается по разбегу и физике игры
    /// (<see cref="JumpReaches"/>), а не по храбрости.
    /// </param>
    /// <param name="blocks">Сколько блоков в сумках годится под мост.</param>
    /// <param name="maxSpan">Шире этого бот не мостит (настройка роли).</param>
    /// <returns>
    /// Way — чем идти; Need — сколько блоков нужно на мост (0, если мост не при
    /// чём); Why — причина, обязательная и в отказе, и в согласии.
    /// </returns>
    public static (CrossWay Way, int Need, string Why) ChooseWayAcross(
        int gap, bool landing, bool canJump, int blocks, int maxSpan)
    {
        if (gap <= 0)
            return (CrossWay.Walk, 0, "разрыва впереди нет — иду ногами");
        if (!landing)
            return (CrossWay.None, 0,
                $"за разрывом в {gap} бл вставать не на что — это не щель, а обрыв: " +
                "мост туда кончится над пустотой");
        if (canJump)
            return (CrossWay.Jump, 0,
                $"щель в {gap} бл беру прыжком — это ничего не стоит, мост тут дороже");
        if (maxSpan <= 0)
            // Имя ручки, а не поля библиотеки: «MaxBridgeSpan» человек в окне
            // не найдёт, а идти ему туда
            return (CrossWay.None, gap,
                $"мостить не велено (ручка «{Movement.РучкаМоститьРазрывы}») — " +
                "перепрыгнуть не выйдет");
        if (gap > maxSpan)
            return (CrossWay.None, gap,
                $"разрыв {gap} бл шире, чем я берусь мостить ({maxSpan} бл)");
        if (blocks < gap)
            return (CrossWay.None, gap,
                $"на мост нужно {gap} блоков, в сумках {blocks}");
        return (CrossWay.Bridge, gap,
            $"перепрыгнуть не выйдет, а разрыв всего {gap} бл — кладу мост " +
            $"(блоков в сумках {blocks})");
    }

    /// <summary>
    /// ЧЕМ СПУСТИТЬСЯ С ОБРЫВА — чистое правило, без мира и без тела.
    ///
    /// Обратный ход к <see cref="Tunnel.ChooseWayOut"/>, и написан он ровно тем
    /// же порядком: способы перебираются по ВОЗРАСТАНИЮ ЦЕНЫ. До этой правки в
    /// библиотеке был только подъём — и бот, стоя над обрывом, честно говорил
    /// «дальше не иду» при полных сумках лестниц.
    ///
    /// 1. СПРЫГНУТЬ. Даром и мгновенно, но только пока падение не стоит
    ///    здоровья дороже, чем роль разрешила потратить. Спрашиваем ДВА
    ///    разрешения: осторожность роли (maxDeliberateFall — у осторожного она
    ///    нулевая, и он не спрыгивает вовсе) и бюджет урона прямо сейчас
    ///    (раненому нельзя того, что можно целому).
    /// 2. СТУПЕНИ ВНИЗ. Тоже даром, но долго: клетка вбок и клетка вниз на
    ///    каждый блок. Зато по ним же можно и подняться обратно — это
    ///    единственный спуск, который не отрезает путь назад.
    /// 3. ЛЕСТНИЦА ПО СТЕНЕ. Тратит запас, зато быстра и обратима. Как и при
    ///    подъёме, вешают её ЧЕРЕЗ ОДНУ: на N блоков нужно N/2 лестниц.
    /// 4. СТОЛБ ВНИЗ. Разобрать породу под собой и осесть вместе с ней. Даром
    ///    по сумкам, но оставляет бота на дне колодца 1×1, откуда наверх уже
    ///    ничем — поэтому последним.
    /// </summary>
    /// <param name="drop">На сколько блоков вниз надо спуститься.</param>
    /// <param name="maxDeliberateFall">Насколько роль разрешает спрыгивать НАРОЧНО.</param>
    /// <param name="fallDamage">Во что обойдётся это падение, хп.</param>
    /// <param name="damageBudget">Сколько хп бот готов на это потратить прямо сейчас.</param>
    /// <param name="stepsMaxDepth">До какой глубины ступени ВЫГОДНЕЕ лестницы.</param>
    /// <param name="ladders">Сколько лестниц в сумках.</param>
    /// <param name="wall">Есть ли стена на всю глубину, к которой крепить лестницу.</param>
    /// <param name="canCarve">Порода вокруг берётся тем, что сейчас в руках.</param>
    /// <param name="rockUnderFoot">Под ногами порода, которую можно разобрать.</param>
    /// <param name="maxDown">Глубже этого бот вниз не лезет вовсе.</param>
    public static (WayDown How, string Why) ChooseWayDown(int drop, int maxDeliberateFall,
        double fallDamage, double damageBudget, int stepsMaxDepth, int ladders, bool wall,
        bool canCarve, bool rockUnderFoot, int maxDown)
    {
        if (drop <= 0)
            return (WayDown.None, "спускаться некуда");
        if (drop > maxDown)
            return (WayDown.Trapped,
                $"обрыв в {drop} бл глубже, чем я берусь спускаться ({maxDown} бл)");

        // 1. СПРЫГНУТЬ — даром. Но оба разрешения обязательны: смелость роли
        // и здоровье прямо сейчас
        if (drop <= maxDeliberateFall && fallDamage <= damageBudget)
            return (WayDown.Jump,
                $"спрыгну с {drop} бл: падение стоит {fallDamage:0.#} хп при бюджете " +
                $"{damageBudget:0.#} — даром и сразу");

        // 2. СТУПЕНИ — тоже даром, и по ним же можно вернуться
        if (drop <= stepsMaxDepth && canCarve)
            return (WayDown.Steps,
                $"обрыв в {drop} бл — вырублю ступени вниз, ничего не тратя");

        // 3. ЛЕСТНИЦА — через одну, значит одна лестница на два блока
        int byLadder = ladders * 2;
        if (byLadder >= drop && wall)
            return (WayDown.Ladder,
                $"лестниц {ladders} — хватит на {byLadder} бл, повешу по стене и слезу");

        // Про прыжок в отказах говорим по-разному: «роль спрыгивать запретила»
        // и «спрыгнул бы, да ранен» — это разные новости, и путать их в журнале
        // значит гадать потом, кого чинить
        string noJump = maxDeliberateFall <= 0
            ? "спрыгивать не велено (осторожность роли)"
            : $"прыжок с {drop} бл стоит {fallDamage:0.#} хп при бюджете {damageBudget:0.#}";

        // 4. СТУПЕНИ ПОСЛЕДНИМ ДОВОДОМ — долго, зато выход есть всегда, пока
        // порода берётся. То же самое рассуждение, что и при подъёме
        if (canCarve)
            return (WayDown.Steps,
                $"вниз на {drop} бл: {noJump}, лестниц {ladders}" +
                (wall ? "" : ", готовой стены нет") +
                " — вырублю ступени сам, дольше, зато даром");

        // 5. СТОЛБ ВНИЗ — на дне колодца 1×1, зато внизу
        if (rockUnderFoot)
            return (WayDown.Pillar,
                $"вниз на {drop} бл: {noJump}, лестниц {ladders}, ступеней не вырубить — " +
                "разберу породу под собой и осяду вместе с ней (наверх оттуда уже нечем)");

        return (WayDown.Trapped,
            $"вниз на {drop} бл не спуститься: {noJump}, лестниц {ladders}" +
            (wall ? "" : ", готовой стены нет") +
            ", порода вокруг не берётся тем, что в руках, и под ногами разбирать нечего");
    }

    // ---------------- бежать или сбавить шаг ----------------

    /// <summary>
    /// Быстрее этого цель считается ЖИВОЙ И УХОДЯЩЕЙ, блоков в секунду.
    ///
    /// Половина блока в секунду — это заведомо меньше любого шага (у игрока
    /// 3.39 бл/с), но заведомо больше дрожания присланной сервером позиции.
    /// Стоящий сундук, клетка маршрута и лежащая на земле вещь дают ровный
    /// ноль; идущий волк — единицы.
    /// </summary>
    public const double TargetOnTheMove = 0.5;

    /// <summary>
    /// Ниже этой скорости цель снова считается стоящей. Порог возврата
    /// отодвинут нарочно (<see cref="Hysteresis"/>): позиции чужих сущностей
    /// приходят пачками, и один «пустой» замер между двумя пакетами не должен
    /// переворачивать ответ посреди погони — иначе бот дёргается «бегу — шагом»
    /// по нескольку раз в секунду.
    /// </summary>
    public const double TargetStillOnTheMove = 0.2;

    /// <summary>
    /// БЕЖАТЬ ИЛИ СБАВИТЬ ШАГ У САМОЙ ЦЕЛИ.
    ///
    /// ЖИВОЙ СЛУЧАЙ, словами заказчика: «на охоте и при погоне за мобом
    /// противника не нужно замедляться на шаг при приближении к нему, а то не
    /// может герой догнать противника». И он прав по числам: шаг — 3.39 бл/с,
    /// бег — вдвое быстрее, а сбавлял бот с шести блоков (SprintDistance).
    /// Драка же начинается с 2.3 бл (AttackReach), то есть ВСЯ погоня целиком
    /// проходила ниже этого порога — бот шёл за убегающим волком пешком и не
    /// догонял его никогда.
    ///
    /// ПОЧЕМУ СБАВЛЯТЬ ВООБЩЕ НАДО. У СТОЯЧЕЙ цели это разумно: на полном ходу
    /// тело проскакивает клетку, отходит назад, снова разгоняется — и «встать
    /// ровно на клетку» превращается в качели. Поэтому правило не отменяет
    /// сбавление, а разводит два случая: неподвижная цель и уходящая.
    ///
    /// ПРО НАПРАВЛЕНИЕ НЕ СПРАШИВАЕМ НАРОЧНО. «Убегает или бежит на меня» —
    /// вопрос, ответ на который переворачивается каждый раз, когда тварь
    /// обходит бота по кругу. А бежать за целью, которая сама несётся
    /// навстречу, ничего не стоит: остановит нас порог прихода, а не скорость.
    /// </summary>
    /// <param name="toTarget">Сколько блоков до цели по полу.</param>
    /// <param name="sprintFrom">Дальше этого бот бежит и к стоячей цели.</param>
    /// <param name="targetSpeed">Скорость самой цели, бл/с (замеряет движение).</param>
    /// <param name="wasChasing">
    /// Прежний ответ на «цель уходит» (null — ответа ещё не было). Нужен
    /// запасу порога, см. <see cref="TargetStillOnTheMove"/>.
    /// </param>
    /// <returns>
    /// Sprint — бежать ли; Chasing — считаем ли цель уходящей (это и есть новый
    /// «прежний ответ»); Why — причина, обязательная и в беге, и в шаге.
    /// </returns>
    public static (bool Sprint, bool Chasing, string Why) SprintNow(
        double toTarget, double sprintFrom, double targetSpeed, bool? wasChasing)
    {
        bool chasing = Hysteresis.Holds(targetSpeed >= TargetOnTheMove,
                                        targetSpeed >= TargetStillOnTheMove, wasChasing);
        if (chasing)
            return (true, true,
                $"цель уходит на {targetSpeed:0.#} бл/с — сбавлю шаг и не догоню её никогда");
        if (toTarget > sprintFrom)
            return (true, false,
                $"до цели {toTarget:0.#} бл, а бегу я всё, что дальше {sprintFrom:0.#}");
        return (false, false,
            $"цель стоит, до неё {toTarget:0.#} бл — подхожу шагом, чтобы встать ровно");
    }

    // ---------------- напрямик или дорогой ----------------

    /// <summary>
    /// Насколько далеко по прямой бот высматривает воду перед прямым ходом.
    ///
    /// Прямой ход и так недалёкий, а щупать сотню клеток на каждый заход — это
    /// сотня вопросов к миру ради решения, которое всё равно примет поиск пути.
    /// Тридцать два блока — это уже заметно больше любого пруда, из-за которого
    /// стоило бы огород городить.
    /// </summary>
    public const double PondSightRange = 32;

    /// <summary>
    /// СТОИТ ЛИ ИДТИ НАПРЯМИК — чистое правило, без мира и без тела.
    ///
    /// ЖИВОЙ СЛУЧАЙ, словами заказчика: «бот бежит напрямую через воду часто,
    /// даже если водоем маленький». Разбор оказался неожиданным: множитель воды
    /// есть и работает (PathOptions.SwimCostMultiplier = 2.5 — откуда именно
    /// это число, честно разобрано ТАМ ЖЕ, у самой ручки), но живёт он
    /// В ПОИСКЕ ПУТИ. А умный ход сперва
    /// пробует пройти НАПРЯМУЮ — дёшево, без всякого маршрута, — и прямой ход
    /// про воду не знает вовсе. До поиска пути дело доходит, только когда бот
    /// упрётся; пруд его не останавливает, и он плывёт напрямик.
    ///
    /// Дешевизну прямого хода при этом ломать нельзя: он затем и нужен, чтобы
    /// не гонять поиск пути на три блока по ровному полу. Поэтому правило
    /// молчит везде, где воды на прямой нет.
    ///
    /// УЖЕ В ВОДЕ — ОСОБЫЙ СЛУЧАЙ. Плывущему боту обходить нечего: он посреди
    /// пруда, и любая дорога начинается с того, чтобы выплыть. Отдавать тут ход
    /// поиску пути значило бы на каждом такте строить маршрут из воды.
    /// </summary>
    /// <param name="cells">Сколько всего клеток на прямой до цели.</param>
    /// <param name="wetCells">Сколько из них — вода (или другая дорогая местность).</param>
    /// <param name="alreadyWet">Бот уже плывёт.</param>
    /// <param name="costMultiplier">Во сколько раз дороже клетка воды (SwimCostMultiplier).</param>
    /// <param name="allowance">
    /// Сколько блоков лишнего ходу мы согласны не заметить. Лужа в одну клетку
    /// не стоит того, чтобы будить поиск пути.
    /// </param>
    public static (bool Straight, string Why) GoStraight(int cells, int wetCells,
        bool alreadyWet, double costMultiplier, double allowance = 1.0)
    {
        if (cells <= 0)
            return (true, "идти некуда — прямая пустая");
        if (wetCells <= 0)
            return (true, $"на прямой в {cells} кл дорогой местности нет — иду напрямик");
        if (alreadyWet)
            return (true, "я и так в воде — пока не выплыву, обходить нечего");

        double extra = wetCells * Math.Max(0, costMultiplier - 1);
        if (extra <= allowance)
            return (true, $"воды на прямой {wetCells} кл — это лишних {extra:0.#} бл ходу, " +
                          "дешевле пройти, чем искать обход");
        return (false, $"прямая пересекает воду на {wetCells} кл из {cells} — плыть это " +
                       $"как лишних {extra:0.#} бл ходу; пусть дорогу выбирает поиск пути");
    }

    // ---------------- отказы ----------------

    /// <summary>
    /// Отказ с причиной. Отдельным методом нарочно: молчаливый выход из хода
    /// стоил нам трёх минут зависания, которое не оставило в журнале ни
    /// строчки. Причина — обязательное поле, забыть её нельзя.
    /// </summary>
    public static WalkDecision Refuse(BlockPos at, string why) =>
        new(WalkMove.Refuse, at, why);

    /// <summary>
    /// Пора ли бросить дело: кончились попытки или вышло время. Возвращает
    /// готовый отказ с причиной — или null, если запас ещё есть.
    ///
    /// Оба потолка вместе и нарочно. Цикл перестроек упирался в счётчик
    /// попыток и заканчивался голым «нет» — в журнале ни строчки, со стороны
    /// «бот просто перестал идти». А там, где счётчика не было, бот упирался в
    /// одно и то же место три минуты и умер с голоду: время-то не считал
    /// никто. Потолок без причины и причина без потолка одинаково бесполезны.
    ///
    /// «Без потолка» — это int.MaxValue и double.PositiveInfinity, а не ноль
    /// и не минус единица: особых значений здесь нет, чтобы «ноль попыток»
    /// честно означал «ни одной попытки не дали», а не «делай сколько хочешь».
    /// </summary>
    /// <param name="at">Где мы стоим — это попадёт в отказ.</param>
    /// <param name="triesDone">Сколько попыток уже сделано.</param>
    /// <param name="maxTries">Сколько их всего разрешено.</param>
    /// <param name="secondsSpent">Сколько секунд уже потрачено.</param>
    /// <param name="secondsAllowed">Сколько их всего дано.</param>
    public static WalkDecision? GiveUp(BlockPos at, int triesDone, int maxTries,
        double secondsSpent, double secondsAllowed)
    {
        bool outOfTries = triesDone >= maxTries;
        bool outOfTime = secondsSpent >= secondsAllowed;
        if (!outOfTries && !outOfTime)
            return null;

        // Когда упёрлись в оба сразу — называем оба. Иначе разбор живого
        // журнала превращается в гадание: «кончились попытки» за четыре
        // секунды и «кончились попытки» за три минуты — это разные беды
        string why = outOfTries && outOfTime
            ? $"кончились и попытки ({triesDone} из {maxTries}), " +
              $"и время ({secondsSpent:0.#} из {secondsAllowed:0.#} с)"
            : outOfTries
                ? $"кончились попытки: {triesDone} из {maxTries}"
                : $"вышло время: {secondsSpent:0.#} из {secondsAllowed:0.#} с";
        return Refuse(at, why);
    }
}
