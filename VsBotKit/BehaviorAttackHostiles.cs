namespace VsBotKit;

/// <summary>
/// КОГО СЧИТАТЬ ВРАГОМ — ЧИСТЫЕ ПРАВИЛА, ОДНО МЕСТО НА ВСЮ БИБЛИОТЕКУ.
///
/// ГЛАВНОЕ, ЧТО НАДО ЗНАТЬ ПРО ЭТОТ ВОПРОС: СЕРВЕР НА НЕГО НЕ ОТВЕЧАЕТ.
/// Разобрано по сборкам игры 1.22.7 (ilspycmd), не по догадке:
/// <list type="bullet">
/// <item>«враждебность» в игре — не свойство вида, а СПИСОК ЖЕРТВ В ЗАДАЧЕ ИИ
/// самой твари (<c>AiTaskBaseTargetable</c>: <c>entityCodes</c>, по умолчанию
/// <c>["player"]</c>). Задачи ИИ живут в <c>server.behaviors</c>;</item>
/// <item>в пакет реестра <c>EntityTypeNet.EntityPropertiesToPacket</c> кладёт
/// ТОЛЬКО <c>properties.Client?.BehaviorsAsJsonObj</c> — серверных поведений
/// в пакете НЕТ ВОВСЕ. Значит ни задач ИИ, ни <c>emotionstates</c> бот не
/// видит;</item>
/// <item>чувства (<c>EntityBehaviorEmotionStates</c>) тоже мимо: активные
/// состояния оно держит в <c>entity.Attributes</c>, а это «only client or only
/// server side» по описанию поля в <c>Entity</c>, — синхронизируется
/// <c>WatchedAttributes</c>, и эмоций там нет;</item>
/// <item>группа появления (<c>spawnconditions.runtime.group: "hostile"</c>) —
/// тоже серверная часть описания и в пакете отсутствует.</item>
/// </list>
///
/// Остаются МЕТКИ, КЛАСС, АТРИБУТЫ И КЛИЕНТСКИЕ ПОВЕДЕНИЯ. Метки — слова самой
/// игры, и по ним враг узнаётся лучше, чем по началу имени. Но это ОЦЕНКА, а не
/// факт от сервера, и место, где она врёт, названо в
/// <see cref="BehaviorAttackHostiles.HostileTags"/>.
/// </summary>
public static class HostileRules
{
    /// <summary>
    /// Клиентское поведение игры «этим командует хозяин». Во всей игре 1.22.7
    /// его носят двое: <c>locust-*-hacked</c> и <c>mechhelper</c>.
    /// </summary>
    public const string CommandedBehavior = "commandable";

    /// <summary>Слово игры «приручён» (лось elk-tamed).</summary>
    public const string TamedTag = "tamed";

    /// <summary>Слово игры «полуприручён» (лось elk-semitamed).</summary>
    public const string SemiTamedTag = "semitamed";

    /// <summary>
    /// ЭТОТ — ЧЕЙ-ТО, И БИТЬ ЕГО НЕЛЬЗЯ, какие бы метки на нём ни стояли.
    ///
    /// Три слова игры, а не наши: у зверя есть хозяин (дерево <c>ownedby</c> в
    /// синхронизируемых свойствах — оттуда же его читает
    /// <c>EntityBehaviorOwnable.IsOwner</c> и задача <c>AiTaskComeToOwner</c>);
    /// машиной командуют (<c>commandable</c>); зверь приручён (<c>tamed</c>,
    /// <c>semitamed</c>).
    ///
    /// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЭТО ЗАВЕДЕНО: прежний список врагов ловил
    /// «locust» — и вместе с локустом ВЗЛОМАННОГО локуста, помощника живого
    /// игрока. Метка <c>mechanical</c> у них одна на двоих, и разделяет их
    /// только это.
    /// </summary>
    /// <param name="type">что сервер сказал про тип; null — реестра ещё нет</param>
    /// <param name="owned">у ЭТОЙ особи есть хозяин (<see cref="Hunting.Owned"/>)</param>
    public static bool Somebodys(EntityTypeInfo? type, bool owned) =>
        owned || SomebodysByType(type);

    /// <summary>
    /// ЧЕЙ-ТО ПО СЛОВУ ИГРЫ О САМОМ ТИПЕ — без оглядки на конкретную особь.
    ///
    /// ЗАЧЕМ ОТДЕЛЬНО. Тот же вопрос задаёт охота, и до 27.08 она собирала его
    /// РУКАМИ: спрашивала хозяина и приручённость, а про <c>commandable</c> не
    /// знала вовсе. Цена этого расхождения живая: мод, давший <c>commandable</c>
    /// дичи (<c>animal</c> + <c>huntable</c>), получал бота, который НА ОХОТЕ
    /// убьёт чужого питомца, а в самообороне того же зверя не тронет. Приёмка
    /// 27.08 назвала это второй копией правила (закон 2) — копии больше нет.
    ///
    /// «У ЭТОЙ ОСОБИ ЕСТЬ ХОЗЯИН» СЮДА НЕ ВХОДИТ НАРОЧНО: это свойство особи
    /// (дерево <c>ownedby</c>), а не типа, и отказы про него звучат своими
    /// словами — «у него есть хозяин» против «игра зовёт его чьим-то».
    /// </summary>
    public static bool SomebodysByType(EntityTypeInfo? type) =>
        (type?.Behaviors?.Contains(CommandedBehavior) ?? false) ||
        Tamed(type);

    /// <summary>
    /// ЗВЕРЬ ПРИРУЧЁН — по слову самой игры, а не по нашей догадке. Слова
    /// <c>tamed</c> и <c>semitamed</c> стоят у лося (elk-tamed, elk-semitamed),
    /// и мод, заводящий свою ручную живность, ставит их же.
    ///
    /// ОДНО МЕСТО НА ВЕСЬ ПРОЕКТ. Эти же два слова проверяла своей строкой
    /// охота (<c>Hunting.Tamed</c>) — две копии одного правила, и приёмка 27.08
    /// назвала цену: добавит мод третье слово приручения, впишут его в одно
    /// место, и бот, не трогающий чужого лося НА ОХОТЕ, станет бить его В
    /// САМООБОРОНЕ. Теперь охота спрашивает это же правило.
    /// </summary>
    public static bool Tamed(EntityTypeInfo? type) =>
        (type?.Tags.Contains(TamedTag) ?? false) ||
        (type?.Tags.Contains(SemiTamedTag) ?? false);

    /// <summary>
    /// ВРАГ: игра пометила вид одним из вражеских слов, и он при этом ничей.
    ///
    /// Реестра нет (<paramref name="type"/> = null) — «не враг»: выдумывать за
    /// сервер нельзя, а незнание тут не разрешение бить.
    /// </summary>
    /// <param name="hostileTags">какие метки роль считает вражескими</param>
    /// <param name="peacefulCodes">
    /// начала кодов, которым метки не верят (см.
    /// <see cref="BehaviorAttackHostiles.PeacefulCodes"/> — там разобрано, зачем
    /// это вообще есть и почему заменить его фактом от сервера не выходит).
    /// Пусто — значит верить меткам во всём.
    /// </param>
    public static bool Enemy(EntityTypeInfo? type, bool owned,
        IReadOnlyCollection<string> hostileTags,
        IReadOnlyCollection<string>? peacefulCodes = null) =>
        type is not null && !Somebodys(type, owned) &&
        !Peaceful(type.Code, peacefulCodes) &&
        // БЕЗ ОГЛЯДКИ НА РЕГИСТР, и это не придирка. Метки набирает ЧЕЛОВЕК в
        // ручке «ВражескиеМетки», а метки реестра приходят строчными. Здесь
        // стояло hostileTags.Any(type.Tags.Contains), то есть сверка шла
        // набором реестра (StringComparer.Ordinal): вписавший «Ferocious»
        // получал бота, который МОЛЧА не считает врагом волка. Про метку,
        // которой в реестре нет вовсе, бот теперь ещё и говорит вслух —
        // см. BehaviorAttackHostiles.ПроверитьМеткиРоли
        hostileTags.Any(метка => type.Tags.Contains(метка, StringComparer.OrdinalIgnoreCase));

    /// <summary>
    /// РОЛЬ ВЕЛЕЛА НЕ ТРОГАТЬ ЭТОТ ВИД ПО ИМЕНИ. Отдельной функцией нарочно:
    /// это ЕДИНСТВЕННОЕ место во всём узнавании врага, где решает имя, а не
    /// слово игры, — и пусть оно будет видно с одного взгляда.
    /// </summary>
    public static bool Peaceful(string code, IReadOnlyCollection<string>? peacefulCodes) =>
        peacefulCodes is { Count: > 0 } &&
        peacefulCodes.Any(p => code.StartsWith(p, StringComparison.OrdinalIgnoreCase));
}

/// <summary>
/// САМООБОРОНА от монстров (не охота): бот вступает в бой, только если
/// враждебная сущность подошла вплотную (DefendRadius) или бот получил урон —
/// тогда радиус временно расширяется. Берёт лучшее оружие из хотбара
/// (по урону из реестра), держит взгляд на противнике (Movement.FocusEntityId).
/// Охота по команде — отдельная история (роль/навык), не эта способность.
/// </summary>
public class BehaviorAttackHostiles : BotBehavior
{
    private readonly BotContext ctx;

    /// <summary>
    /// МЕТКИ ИГРЫ, ПО КОТОРЫМ БОТ УЗНАЁТ ВРАГА. Не начала имён — СЛОВА САМОЙ
    /// ИГРЫ, приехавшие с сервера в реестре типов (<see cref="EntityTypes"/>).
    ///
    /// ЧТО ЗДЕСЬ СТОЯЛО ДО 27.08 И ЧЕМ ЭТО БЫЛО ПЛОХО. Стоял рукописный список
    /// начал кодов: «drifter, wolf, hyena, locust, bear, bowtorn, shiver,
    /// bell-». Он местами угадывал, и оттого его ошибки были невидимы:
    /// <list type="bullet">
    /// <item>«locust» ловил и <c>locust-bronze-hacked</c> — ВЗЛОМАННОГО локуста,
    /// то есть ЧУЖОГО ПИТОМЦА: у него задача <c>cometoowner</c>, поведение
    /// <c>commandable</c> и хозяин. Бот шёл бить помощника живого игрока;</item>
    /// <item>в списке не было ни <c>beemob</c> (рой пчёл, метка
    /// <c>ferocious</c>, бьёт всех подряд), ни обоих боссов (<c>eidolon</c>,
    /// <c>erel</c>) — от них бот не оборонялся вовсе;</item>
    /// <item>а «bell-» с чёрточкой — это заплатка на предыдущую ошибку того же
    /// рода: без чёрточки под неё попадал <c>bellmini-normal</c>, спутник
    /// изобретателя.</item>
    /// </list>
    ///
    /// ПОЧЕМУ ИМЕННО ЭТИ ЧЕТЫРЕ МЕТКИ. Сверено по описаниям сущностей игры
    /// 1.22.7 — обеим папкам, <c>assets/survival/entities</c> и
    /// <c>assets/game/entities</c>: РАЗНЫХ МЕТОК ТАМ 25 (в одной survival —
    /// 22; «26» в прежней записи не считалось, а прикидывалось):
    /// <list type="bullet">
    /// <item><c>rust-creature</c> — дрифтер, боуторн, шивер. Трое из трёх бьют
    /// игрока, исключений нет;</item>
    /// <item><c>ferocious</c> — волк, гиена, медведь, рой пчёл. Четверо из
    /// четырёх нападают сами; это же слово игра ставит и на детёнышей волка и
    /// гиены;</item>
    /// <item><c>boss</c> — эйдолон и эрель, оба враги;</item>
    /// <item><c>mechanical</c> — локуст и колокол, но ТАКЖЕ взломанный локуст,
    /// мехпомощник и bellmini. Первых двух отводит вопрос «а не чей ли он»
    /// (<see cref="HostileRules.Somebodys"/>), и это слово игры, а не наше.</item>
    /// </list>
    ///
    /// Метка <c>mechanical</c> одна во всём наборе неточна, и потому рядом с
    /// ней стоит <see cref="PeacefulCodes"/> — там же и разбор, почему точнее
    /// не выходит.
    /// </summary>
    public HashSet<string> HostileTags { get; } = new(StringComparer.OrdinalIgnoreCase)
    {
        "rust-creature", "ferocious", "boss", "mechanical"
    };

    /// <summary>
    /// НЕ ВРАГ, ХОТЯ МЕТКИ ГОВОРЯТ ОБРАТНОЕ — ЕДИНСТВЕННАЯ ДОГАДКА ПО ИМЕНИ,
    /// КОТОРАЯ ЗДЕСЬ ОСТАЛАСЬ. Называю её вслух вместе с оправданием, потому
    /// что молча оставленная догадка и есть то, на чём проект горел четырежды.
    ///
    /// ПОЧЕМУ ОНА НУЖНА. <c>bellmini</c> — спутник селянина-изобретателя
    /// Тобиаса: десять хп, задача <c>stayclosetoentity</c> на
    /// «villager-nadiya-male-inventor-tobias», бегство от игрока, ни одной
    /// атаки. Колокол — сирена, зовущая дрифтеров. Враг из них один.
    ///
    /// ПОЧЕМУ ЕЁ НЕЛЬЗЯ ЗАМЕНИТЬ ФАКТОМ ОТ СЕРВЕРА. Я искал и не нашёл —
    /// перечисляю, где именно, чтобы следующий не искал заново:
    /// <list type="bullet">
    /// <item>метки: у обоих ровно <c>["mechanical","habitat-land"]</c>;</item>
    /// <item>класс: у обоих <c>EntityBell</c>;</item>
    /// <item>клиентские поведения: у обоих одна и та же четвёрка
    /// (repulseagents, controlledphysics, floatupwhenstuck, interpolateposition);</item>
    /// <item>звуки: у обоих только <c>hurt</c> и <c>death</c> — звук тревоги
    /// живёт в САМОЙ ЗАДАЧЕ <c>bellalarm</c> (<c>repeatSound</c>), то есть на
    /// сервере;</item>
    /// <item>атрибуты: разнятся одним <c>glitchAffected</c>, а он не про
    /// вражду — тем же словом помечен САМ ИГРОК
    /// (game/entities/humanoid/player.json), это дрожание картинки при низкой
    /// временной стабильности;</item>
    /// <item>всё остальное, чем они на деле различаются, — задачи ИИ
    /// (<c>bellalarm</c> против <c>fleeentity</c>), чувства
    /// (<c>emotionstates</c>) и условия появления, — лежит в СЕРВЕРНЫХ
    /// поведениях, а <c>EntityTypeNet.EntityPropertiesToPacket</c> кладёт в
    /// пакет только клиентские. Клиенту этого не говорят вообще.</item>
    /// </list>
    ///
    /// ЧЕМ ЭТО ЛУЧШЕ ПРЕЖНЕГО СПИСКА, раз это тоже имя. Прежде по именам
    /// узнавались ВСЕ восемь врагов, и список ошибался в обе стороны сразу
    /// (бил чужого питомца, не знал роя и боссов). Теперь имя осталось ОДНО и
    /// работает в БЕЗОПАСНУЮ сторону: лишняя запись здесь означает «не трогай»,
    /// а не «бей». Мод, заведший свою враждебную машину, попадёт под
    /// <c>mechanical</c> и будет встречен как надо; мод, заведший ручную,
    /// пометит её <c>commandable</c> или хозяином — как это делает сама игра.
    /// </summary>
    public HashSet<string> PeacefulCodes { get; } = new(StringComparer.OrdinalIgnoreCase)
    {
        "bellmini"
    };

    /// <summary>Оборонительный радиус: бой только если враг подошёл ближе.</summary>
    public double DefendRadius { get; set; } = 4.0;

    /// <summary>
    /// ЦАРАПИНА — НЕ БОЙ: ниже стольких хп за удар в драку не лезем.
    ///
    /// Живой случай ровно про это (журнал 22:52):
    ///   [чат:-5] Потеряно 0,03 хп дрифтер (моб)  → вход в бой
    /// Три сотых хп — это не нападение, а щекотка; самый слабый дрифтер бьёт
    /// на 2,5 хп (и по этому же журналу он бьёт куда сильнее). Половина хп
    /// взята с большим запасом вниз: настоящий удар любой твари её перекрывает,
    /// а рикошет брошенного камешка — нет. Число настраивается: у бота в броне
    /// и у модовых тварей своя арифметика.
    /// </summary>
    public double MinHurtToFight { get; set; } = 0.5;

    /// <summary>
    /// Верить журналу урона сервера (см. <see cref="DamageWatch"/>).
    ///
    /// Выключать НЕ НАДО без причины: с ним причина урона — факт, без него
    /// остаётся прежняя догадка «здоровье убавилось — значит напали», от
    /// которой бот и бегал в боевом режиме от собственного голода. Ручка
    /// оставлена на случай сервера, чьи строки мы не разберём.
    /// </summary>
    public bool UseDamageLog { get; set; } = true;

    /// <summary>
    /// Как часто бьёт противник, секунд, — пока не замерено по журналу урона.
    /// Полторы секунды это середина кулдауна дрифтера (500…1750 мс).
    /// </summary>
    public double EnemySwingSeconds { get; set; } = 1.5;

    /// <summary>
    /// Сколько бьёт НЕЗНАКОМАЯ тварь, хп, — пока она не ударила ни разу.
    ///
    /// Нулём это оставлять нельзя: бой считался бы бесплатным, и бот спокойно
    /// стоял бы под первым в жизни дрифтером. Два с половиной — удар самого
    /// слабого из них (drifter-normal, meleeattack.damage в описании сущности
    /// самой игры). Это ЗАПАС на первый удар и только: с первого же попадания
    /// в дело идёт замер по журналу урона.
    /// </summary>
    public double UnknownEnemyHit { get; set; } = 2.5;

    /// <summary>
    /// «Этого не завалить» — здоровье, которого не бывает. НЕ РУЧКА И НЕ ПОРОГ:
    /// крутить его незачем, оно нужно ровно на один недостижимый случай (см.
    /// <c>Facts</c>), чтобы сломанный инвариант увёл бота от боя, а не в бой.
    /// </summary>
    private const double UnfightableHealth = 1e9;

    /// <summary>
    /// Как часто перепроверять, есть ли до противника дорога. Спрашивать поиск
    /// пути дважды в секунду дорого, а обстановка за секунду не меняется.
    /// </summary>
    public double PathCheckSeconds { get; set; } = 1.5;

    /// <summary>
    /// СКОЛЬКО СЕКУНД ДАЁТСЯ ОДНОМУ ЗАХОДУ ПОГОНИ. НЕ РУЧКА И НЕ ПОЛИТИКА: это
    /// мерка ОТЗЫВЧИВОСТИ боя — сколько бот согласен ИДТИ, ни разу не
    /// переспросив себя, драться ему, отступать или лечиться.
    ///
    /// Больше ставить нельзя: пока идёт заход, бой не бьёт и не отступает — он
    /// только идёт, и тварь всё это время бьёт бота.
    ///
    /// СРОК ЭТОТ ОТДАЁТСЯ ПОДХОДУ ЦЕЛИКОМ, и это не то же самое, что было. До
    /// 31.08 их тратилось ДВА подряд — шесть секунд прямому ходу и ещё шесть
    /// маршруту, — то есть один круг цикла молчал до двенадцати секунд. Теперь
    /// заход один: ApproachAsync укладывает в этот срок и прямой ход, и
    /// маршрут, и свой самоперезапуск. Не уложился, но бот при этом ШЁЛ —
    /// следующий круг даёт ему такой же срок (см. <see cref="ChaseStepThatCounts"/>).
    /// </summary>
    private const double ChaseLegSeconds = 6;

    /// <summary>
    /// НАСКОЛЬКО НАДО СДВИНУТЬСЯ ЗА ЗАХОД, ЧТОБЫ СЧИТАТЬ ЕГО НЕ ВПУСТУЮ, блоков.
    ///
    /// Отказ подхода бывает двух родов, и от того, какой это род, зависит,
    /// продолжать погоню или бросать: «перебрал всё и не пробился» — конец, а
    /// «вышел отпущенный <see cref="ChaseLegSeconds"/>» — это МОЯ мерка
    /// отзывчивости, и наказывать за неё дорогу нечестно. Различает их
    /// СОБСТВЕННОЕ перемещение, ровно как у побега (<see cref="MinFleeStep"/>):
    /// разрыв до дрифтера не растёт и не тает, он бежит с нашей скоростью, —
