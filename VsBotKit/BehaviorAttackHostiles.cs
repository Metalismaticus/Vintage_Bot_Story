    public BehaviorAttackHostiles(BotContext ctx)
    {
        this.ctx = ctx;
        // ЛУК БЕРЁТ НАШ ЗАМЕР ХОДА ЦЕЛЕЙ, а не заводит свой: упреждение стрелы
        // и оценка «догоню ли» обязаны мерить одну и ту же скорость одной и
        // той же меркой
        Bow = new Archery(ctx, Pace);
        // Удары, случившиеся ДО того, как способность появилась, судить не наше
        // дело: подключённый посреди боя рефлекс иначе разом объявил бы
        // нападением всё, что журнал помнит за последнюю минуту
        seenHits = ctx.Damage?.Count ?? 0;

        // НАПАДЕНИЕ РАСЧИЩАЕТ СЕБЕ ДОРОГУ САМО, В ТУ ЖЕ СЕКУНДУ.
        //
        // Живой случай целиком — в BodyArbiter.MakeWay: бот шёл домой одним
        // заходом на двадцать секунд, получил шесть ударов и умер, ни разу не
        // тикнув боем. Право перебить работу у боя было, спросить его было
        // некому: цикл способностей ЖДЁТ дорогу домой и до боя не доходит.
        //
        // Поэтому будит бой САМ УДАР — событие журнала урона, а не наш ход.
        // Здесь только расчистка: судит удар и заводит стычку по-прежнему тик,
        // одним и тем же правилом (см. NoticeHurt/JudgeHit), второй копии
        // разбора тут нет
        if (ctx.Damage is { } damage)
            damage.OnHurt += WakeForFight;
        // КТО НАСКОЛЬКО БЫСТР — МЕРЯЕМ ПО ПОЛОЖЕНИЯМ ОТ СЕРВЕРА, а не в свой ход
        // (разбор живого случая — в NoticePace)
        ctx.Entities.OnEntityMoved += NoticePace;
        // СМЕРТЬ — ФАКТ ОТ СЕРВЕРА, А НЕ НАБЛЮДЕНИЕ ЗА ЗДОРОВЬЕМ В СВОЙ ХОД.
        //
        // Тот же журнал 19.08: бот умер в 18:34:16, возродился в 18:34:19 за
        // двести пятьдесят блоков, и только в 18:34:26 бой дошёл до хода —
        // с шестью предсмертными ударами в очереди. Здоровье к тому времени
        // было полное, ветка «мёртвый не дерётся» не сработала ни разу, и бот
        // честно доложил: «меня бьёт дрифтер, а живого врага в 30 бл нет».
        // Бил его дрифтер прошлой жизни, в другом конце карты
        if (ctx.Self is { } me)
            me.OnDeath += ForgetTheFight;
    }

    /// <summary>
    /// УДАР ПРИШЁЛ — РАСЧИСТИТЬ ДОРОГУ РЕФЛЕКСУ. Зовётся из потока чата, а не
    /// из хода способности, и потому не делает НИЧЕГО, кроме одного: просит
    /// распорядителя остановить дело, которое менее важно, чем спасение.
    /// Что это был за удар и с кем теперь драться — решит ход, тем же
    /// единственным правилом <see cref="CombatEntry.Judge"/>.
    /// </summary>
    private void WakeForFight(DamageHit hit)
    {
        if (CombatEntry.Judge(hit, MinHurtToFight) != FightEntry.FightBack)
            return;
        ctx.Turn.MakeWay(BodyArbiter.Importance.Reflex, $"меня бьют ({hit})");
    }

    /// <summary>
    /// ЭТОТ ВИД ИГРА ЗОВЁТ ВРАЖДЕБНЫМ, И ОН НЕ ЧЕЙ-ТО: только вопрос к реестру
    /// сервера, ни одного вопроса к себе.
    ///
    /// Отдельно от <see cref="IsHostile"/> нарочно: какие МЕТКИ считать
    /// вражескими — политика роли (<see cref="HostileTags"/>), а живость —
    /// факт от сервера, и мешать их в одну строку уже выходило боком. Стрела
    /// боуторна показывает зачем: меток <c>rust-creature</c> у неё нет вовсе
    /// (в её описании стоят <c>inanimate, projectile</c>), но даже если бы мод
    /// их поставил, её отсечёт следующий вопрос — «а живое ли это».
    ///
    /// Реестра ещё нет — «не враг»: незнание не разрешение (то же правило, что
    /// в <see cref="Hunting"/>).
    /// </summary>
    public bool HostileKind(EntityInfo e) =>
        ctx.EntityTypes is { } types &&
        HostileRules.Enemy(types.Get(e.Code), Hunting.Owned(e), HostileTags, PeacefulCodes);

    /// <summary>
    /// ЖИВОЙ ВРАГ, С КОТОРЫМ ВООБЩЕ БЫВАЕТ БОЙ — ОДНА ДВЕРЬ НА ВСЮ БИБЛИОТЕКУ.
    ///
    /// Её же спрашивают лечение («рядом опасно — не лечусь») и сон («рядом
    /// опасно — не лягу»): им передаётся именно этот метод. Прежде каждый из
    /// них дописывал к нему СВОЮ копию проверки живости
    /// (<c>&amp;&amp; (e.Health ?? 1) &gt; 0</c>) — три копии одной догадки, и
    /// все три считали воткнутую стрелу живым врагом. В журнале 17.08 это
    /// видно и с той стороны: «[сон] ночь, а рядом опасно… (и то же ещё 637
    /// раз)» — бот не ложился спать из-за стрелы.
    /// </summary>
    public bool IsHostile(EntityInfo e) =>
        e.Id != ctx.Entities.OwnEntityId && HostileKind(e) &&
        CombatTargets.CanBeFought(ctx.EntityTypes?.Inanimate(e.Code) ?? false, e.Health);

    /// <summary>
    /// Урон нанесло собственное тело, а не враг: голод или холод.
    ///
    /// Это не мелочь, а корень двух поломок сразу. Голодный бот теряет
    /// здоровье, бой принимает это за нападение, двадцать секунд ищет обидчика
    /// в тридцати блоках и ЗАБИРАЕТ ХОД — а еда и тёплая одежда стоят в очереди
    /// после боя и до них никогда не доходит. Бот честно голодал насмерть рядом
    /// с едой в сумке и мёрз, не надевая куртку.
    ///
    /// Источник урона сервер отдельно не сообщает, поэтому судим по состоянию:
    /// пустой желудок и переохлаждение — это не атака.
    /// </summary>
    private bool HurtByOwnBody(EntityInfo self)
    {
        if (self.Saturation is { } sat && sat <= 0.01f)
            return true;
        return ctx.Cold is { Ready: true } cold && cold.IsDangerousCold;
    }

    /// <summary>
    /// Гнаться за обидчиком, когда сам умираешь, — плохая идея. Пока бот
    /// голоден или замерзает, месть отменяется: сперва выжить.
    /// </summary>
    private bool TooWeakForRevenge(EntityInfo self) =>
        (self.Saturation is { } sat && self.MaxSaturation is { } max && max > 0 &&
         sat / max < VitalNeedsFraction) ||
        (ctx.Cold is { Ready: true } cold && cold.IsCold);

    /// <summary>
    /// Ниже какой доли сытости бот бросает погоню и идёт есть. Роль может
    /// поднять её сторожу и опустить охотнику.
    /// </summary>
    public double VitalNeedsFraction { get; set; } = 0.25;

    /// <summary>
    /// ХОД БОЯ — И КОНЕЦ РАСЧИСТКИ, КОТОРУЮ ЗАВЁЛ УДАР.
    ///
    /// Расчистку ставит СОБЫТИЕ (<see cref="WakeForFight"/> на каждом ударе), а
    /// кончиться она обязана ходом того, ради кого её ставили, — то есть вот
    /// этим самым. Взял бой тело — снял расчистку сам распорядитель; не взял
    /// (решил «не связываюсь», пережидает бегство, врага не видно, да и просто
    /// уже дерётся и держит тело) — снимаем здесь. Полный разбор живого случая
    /// и числа замера — у <c>BodyArbiter.WayDone</c>.
    ///
    /// ПОЧЕМУ ОБЁРТКА, А НЕ СТРОКА В КАЖДОМ ВЫХОДЕ. Выходов из хода боя больше
    /// десятка (нет себя, мёртв, врага нет, не связываюсь, тело у другого
    /// рефлекса, отмена…), и ровно четыре из них уже однажды забыли — это и
    /// была та беда. Забыть <c>finally</c> нельзя.
    /// </summary>
    public override async Task<bool> TickAsync(CancellationToken ct)
    {
        try
        {
            return await FightTurnAsync(ct);
        }
        finally
        {
            ctx.Turn.WayDone(BodyArbiter.Importance.Reflex);
        }
    }

    private async Task<bool> FightTurnAsync(CancellationToken ct)
    {
        if (ctx.Entities.Self is not { } self)
            return false;

        float health = self.Health ?? float.MaxValue;

        // ОПЕЧАТКА В «ВражескиеМетки» — ЗДЕСЬ, А НЕ ПРИ УДАРЕ. Ставить эту
        // проверку в разбор обидчика было нельзя: метка, не совпавшая ни с
        // чем, значит «врагов рядом нет вовсе», и до удара дело может не
        // дойти НИКОГДА — молчание вышло бы ровно в том случае, ради
        // которого проверка заведена
        ПроверитьМеткиРоли();

        // МЁРТВЫЙ НЕ ДЕРЁТСЯ И НЕ МСТИТ.
        //
        // Живой случай (журнал 23:50:37): бот погиб. Здоровье упало до нуля —
        // и та же проверка «меня ударили» записала СМЕРТЬ в обиду: на двадцать
        // секунд включила месть радиусом тридцать блоков. Возродился он уже в
        // другом месте и без оружия, зато с горячей памятью об обидчике: нашёл
        // дрифтера-глубинника, который его и не видел, и принялся от него
        // убегать. Смерть — это не удар, за который мстят.
        if (health <= 0.01f)
        {
            ForgetTheFight();
            lastKnownHealth = health;
            return false;   // ход отдаём возрождению: оно стоит выше в очереди
        }

        // КТО БЫСТРЕЕ — МЕРЯЕТСЯ ВНЕ ХОДА, по положениям от сервера
        // (см. NoticePace): здесь стояла эта строка, и ровно из-за неё замер
        // зависел от того, дошла ли до боя очередь

        // ОТ ЧЕГО УБАВИЛОСЬ ЗДОРОВЬЕ — СПРАШИВАЕМ СЕРВЕР, А НЕ ДОГАДЫВАЕМСЯ.
        // Прежде здесь стояло «стало меньше — значит напали», и через эту
        // строку в бой попадали голод («0,13 хп от hunger») и падение
        // («1,07 хп от gravity»)
        NoticeHurt(self, health);
        lastKnownHealth = health;

        // Мстить — значит искать обидчика ШИРЕ обычного радиуса ответа: тот,
        // кто бьёт издалека, в него просто не попадает.
        //
        // МСТЯТ ТОЛЬКО ТОМУ, КОГО НАЗВАЛ СЕРВЕР. Обидчика нет (сервер назвал
        // того, кого рядом не оказалось, — см. FindAttacker) — значит и
        // расширять круг незачем: в тридцати блоках найдётся кто-нибудь
        // враждебный всегда, и раньше бот шёл драться именно с ним. Живой
        // случай — журнал 19.08, 01:38:59: ударил шивер, а бот «взял»
        // боуторна и трижды написал «иду разбираться».
        //
        // Обороняться это не мешает: тварь, подошедшая на DefendRadius, —
        // угроза сама по себе, и её бот встречает как встречал.

        // ЧЕМ Я СЕГОДНЯ ВООРУЖЁН — СПРАШИВАЕТСЯ ДО ВЫБОРА ЦЕЛИ, а не после.
        //
        // ЖАЛОБА ЗАКАЗЧИКА: «на дальних мобов снова не агрится, просто броню
        // надевает». Так и было: круг, в котором вообще ищется враг, брался
        // оборонительным (4 бл), а лук стреляет с пяти — то есть до лука дело
        // не доходило НИ РАЗУ, потому что цели в списке ещё не было.
        // Теперь круг зависит от того, чем бот будет бить (CombatReach.MeetFrom):
        // есть лук и стрелы — встречаю с дальности выстрела.
        int arrowsCarried = Bow.ArrowsCarried();
        double shotHit = UseBow ? Bow.ShotDamage() : 0;
        double meetFrom = MeetFrom();

        bool haveAttacker = attackerId != null;
        bool avenging = Revenge != RevengePolicy.Никогда && DateTime.UtcNow < hurtUntil &&
                        !TooWeakForRevenge(self) && haveAttacker;
        double radius = avenging
            ? Math.Max(HurtResponseRadius, RevengeRadius)
            : DateTime.UtcNow < hurtUntil && haveAttacker ? HurtResponseRadius : meetFrom;
        var hostiles = ctx.Entities.Nearby(self.X, self.Y, self.Z, radius)
            .Where(e => IsHostile(e))
            .ToList();
        // Тот, кто нас бьёт, — приоритетная цель: иначе бот дёргается между
        // мобами и заново «начинает бой» с каждым, кто оказался ближе
        //
        // …А ЗА НИМ — ТОТ, КОМУ ДО МЕНЯ ЕСТЬ ДОРОГА, И ТОЛЬКО ПОТОМ БЛИЖАЙШИЙ.
        //
        // ЧТО ЛОМАЛОСЬ БЕЗ ЭТОЙ СТРОКИ. Цель бралась строго ближайшей, а вопрос
        // «дойдёт ли он до меня» задавался уже ПОСЛЕ выбора. Значит дрифтер за
        // окном в шести блоках затирал дрифтера, ВОШЕДШЕГО В ОТКРЫТУЮ ДВЕРЬ в
        // восьми: бот отвечал про первого «занимаюсь своим» и второго в этот
        // ход не видел вовсе. Список отсортирован по расстоянию (Entities
        // .Nearby), поэтому «первый достижимый» — это ближайший из тех, кто
        // вправду дойдёт.
        //
        // Спрашиваем не больше ОДНОГО лишнего раза на ход и только когда ручка
        // включена: у HeReachesMe есть свой тайник на PathCheckSeconds
        var enemy = hostiles.FirstOrDefault(e => e.Id == attackerId);
        if (enemy == null && OnlyWhoReachesMe)
            enemy = hostiles.FirstOrDefault(
                e => HeReachesMe(self, e, e.DistanceTo(self.X, self.Y, self.Z)));
        enemy ??= hostiles.FirstOrDefault();

        // «Отвечаю, но не гонюсь»: дальняя цель отбрасывается, ближняя остаётся.
        // Меряется это КРУГОМ ВСТРЕЧИ, а не оборонительным радиусом: стрелять с
        // места — это не погоня, и запрет гнаться луку не помеха
        if (enemy != null && Revenge == RevengePolicy.Рядом &&
            enemy.DistanceTo(self.X, self.Y, self.Z) > meetFrom &&
            DateTime.UtcNow >= hurtUntil)
            enemy = null;

        // Гонимся не бесконечно: роль отпускает на это столько секунд,
        // сколько считает нужным, дальше бот возвращается к своим делам
        if (enemy != null && avenging && chaseUntil == DateTime.MinValue)
            chaseUntil = DateTime.UtcNow.AddSeconds(RevengeChaseSeconds);
        if (enemy != null && avenging && DateTime.UtcNow > chaseUntil &&
            enemy.DistanceTo(self.X, self.Y, self.Z) > meetFrom)
        {
            OnRevengeGaveUp?.Invoke(enemy.Code);
            hurtUntil = DateTime.MinValue;
            chaseUntil = DateTime.MinValue;
            attackerId = null;
            enemy = null;
        }
        if (enemy == null)
            chaseUntil = DateTime.MinValue;

        if (enemy == null)
        {
            attackerId = null;
            // Врагов нет — броня только зря ускоряет голод и замедляет. Сюда же
            // попадает случай «бот зашёл в мир уже одетым». Решает это ОДНО
            // правило на все ветки боя (см. FitArmorAsync), а не своя проверка
            // в каждом углу
            return await FitGearAsync(fighting: false, fleeing: false, ct);
        }

        // Оценка «вытяну ли бой». Пока не отлежался — не лезем обратно:
        // иначе бот бегает по кругу «подрался — убежал — подрался»
        double frac = self.MaxHealth is { } max && max > 0 && self.Health is { } hp
            ? hp / max
            : 1.0;
        if (retreating && frac >= ResumeHealthFraction)
        {
            retreating = false;
            OnReady?.Invoke(frac);
        }
        else if (!retreating && frac <= RetreatHealthFraction)
        {
            retreating = true;
            OnRetreat?.Invoke(frac);
        }

        // Чем драться? Безоружным лучше уйти, чем героически лечь.
        // Лопата и кирка формально «с уроном», но драка ими — это тот же
        // проигрыш, поэтому настоящее оружие считается отдельно
        var (weaponSlot, weaponCode, weaponPower) = FindBestWeapon();
        // ЕСТЬ ЛИ ЧЕМ БИТЬ ВБЛИЗИ — ГОЛЫЙ ФАКТ, без оглядки на ручку побега.
        // «unarmed» ниже — это уже РЕШЕНИЕ («безоружен, значит бегу»), и оно
        // ложно, когда ручка FleeIfUnarmed снята. Луку нужен именно факт: если
        // меча нет, стрела — не лучший способ, а единственный, и порог доли
        // попадания для неё снимается (Archery.LastResort)
        bool haveMelee = ctx.Weapons.IsWeapon(weaponPower);
        // БЕЗОРУЖЕН — ЭТО «НЕЧЕМ ВООБЩЕ», А НЕ «НЕЧЕМ В РУКЕ». Пока здесь
        // стояло одно haveMelee, бот с луком и восемью стрелами убегал от
        // дрифтера «безоружным», продолжая при этом беречь стрелы на потом,
        // которого не будет (щуп 26.08). Порог доли попадания это НЕ трогает:
        // Archery.LastResort по-прежнему спрашивает именно ближний бой
        bool unarmed = FleeIfUnarmed && !haveMelee && shotHit <= 0;
        double gap = enemy.DistanceTo(self.X, self.Y, self.Z);

        // ПРЕДЕЛ «СВЯЗЫВАТЬСЯ ЛИ». Цель выбиралась в радиусе мести (30 бл), а
        // бой обрывался на четырнадцати («враг убежал») — и получался приступ:
        // тело отобрано у дороги, «отбиваюсь от drifter», броня надета,
        // дистанция 25 — конец стычки, броня снята, и всё сначала, дважды в
        // секунду. Предел один и тот же и на решение, и на разрыв стычки ниже.
        // КРУГ ВСТРЕЧИ ВХОДИТ В ПРЕДЕЛ, и без этого лук молчал бы иначе: цель
        // выбрана с двадцати блоков (потому что лук достаёт), а предел стоял бы
        // на четырнадцати — и счёт отвечал бы «это уже охота, а не оборона»
        // ровно про того врага, ради которого круг и расширен
        //
        // ДВА ПРЕДЕЛА, А НЕ ОДИН, И РАЗНИЦА ЖИВАЯ. Стрелять с двадцати блоков —
        // оборона; идти туда пешком, чтобы махнуть кулаком, — охота. Пока
        // предел был один, у роста круга встречи было тихое последствие:
        // стоило луку отказаться (порог доли, кончились стрелы), и управление
        // падало в погоню НОГАМИ с тех же двадцати четырёх блоков, откуда до
        // 26.08 бот врага вообще не видел
        double footLimit = avenging && Revenge == RevengePolicy.Догонять
            ? Math.Max(HurtResponseRadius + 4, RevengeRadius)
            : HurtResponseRadius + 4;
        double engageLimit = Math.Max(meetFrom, footLimit);

        // ЧТО ДЕЛАТЬ — СЧИТАЕМ ЧИСЛАМИ, ДО ПЕРВОГО ШАГА И ДО ТОГО, КАК ТРОГАТЬ
        // ТЕЛО.
        //
        // Раньше здесь стояла лесенка условий: мало здоровья — беги; нет
        // оружия — беги; иначе — гонись. Ни одно «иначе» не спрашивало
        // «догоню ли», «выживу ли» и «есть ли куда отойти», и живьём это вышло
        // семнадцатью строками «тупик (512048, 93, 512264) … запомнил, буду
        // обходить» подряд: погоня упёрлась в стену и продолжала упираться.
        // Теперь каждый ответ получает число, и берётся лучший
        // (см. CombatPlan — тот же приём, что в Tunnel.PickStepSide).
        //
        // И тело по-прежнему не трогаем, пока не решили действовать: прежде
        // владение забиралось безусловно, бегство от дальнего дрифтера
        // кончалось мгновенно, тело отпускалось — и так каждые полсекунды,
        // отбирая дорогу у роли.
        var facts = Facts(self, enemy, gap, unarmed ? 0 : weaponPower, engageLimit,
            shotHit, arrowsCarried, footLimit);
        var decision = CombatPlan.Pick(facts);
        SayPlan(enemy, decision);
        var choice = decision.Choice;

        // ЗАЩЁЛКА «В УГЛУ». Побег только что не удался — начинать его заново
        // через полсекунды нельзя, иначе бот дёргается на месте. Но на низком
        // здоровье защёлка не держит: забиться в тупик и умереть, отбиваясь,
        // хуже любого дёрганья
        if (DateTime.UtcNow < corneredUntil && frac > CriticalHealthFraction &&
            choice is CombatChoice.Flee or CombatChoice.Seal)
            choice = CombatChoice.Cornered;

        bool wantFlee = choice is CombatChoice.Flee or CombatChoice.Seal;
        bool cornered = choice == CombatChoice.Cornered;
        // К ЭТОМУ НЕ ПОДХОДЯТ, ПОКА ЕСТЬ ЧЕМ СТРЕЛЯТЬ (колокол; разбор — в
        // CombatDanger.CallsForHelp). Без лука и стрел держаться поодаль
        // бессмысленно: это было бы «стою и смотрю», а не бой
        bool keepDistance = facts.SummonsHelp && shotHit > 0 && arrowsCarried > 0;
        if (cornered && NewsAbout($"загнан:{enemy.Id}"))
            OnCornered?.Invoke();

        // ЧАСЫ ТЕРПЕНИЯ. Пошли — когда бот РЕШИЛ не связываться, будучи под
        // ударами; встали — как только он взялся хоть за что-то или его
        // перестали бить. Без них «не связываюсь» выдавало себе полный запас
        // терпения каждые полсекунды, и живьём это вышло четырьмя одинаковыми
        // строками за минуту, пока дрифтер бил бота
        if (choice == CombatChoice.Ignore && facts.UnderFire)
            enduringSince ??= DateTime.UtcNow;
        else
            enduringSince = null;

        if (choice == CombatChoice.Ignore)
        {
            KeepingDistance(enemy, gap);
            // ВОТ ЭТА СТРОКА И ЕСТЬ ЛЕЧЕНИЕ ЖИВОГО СЛУЧАЯ «не снимал броню после
            // шторма и опасности». Всю бурю 16.08 бот сидел в укрытии, дрифтеры
            // ходили рядом, решение было «не связываюсь» — и выход отсюда стоял
            // голым «return false». Броня не снималась НИ РАЗУ за восемь минут
            // после бури: единственная ветка, которая это умела, требовала
            // «врагов не видно вовсе». Теперь правило спрашивается и здесь
            await FitGearAsync(fighting: false, fleeing: false, ct);
            return false;   // не наше дело — пусть роль занимается своим
        }
        if (wantFlee && DateTime.UtcNow < calmUntil)
            return false;   // стычка уже разобрана, см. FleeCalmSeconds

        // БОЙ ВАЖНЕЕ ЛЮБОГО ДЕЛА. Забираем тело у того, кто его занял, и он
        // обязан остановиться. Без этого ловилось живьём: рефлекс уводил бота
        // от дрифтера, а задача готовки продолжала тыкать в костёр — уже с
        // двадцати пяти блоков, двадцать раз подряд «не дотянуться»
        using var hold = ctx.Turn.TryTake("бой", BodyArbiter.Importance.Reflex, ct);
        if (hold == null)
        {
            // Тело у другого рефлекса (укрытие в бурю, возрождение). Действовать
            // вслепую нельзя — вдвоём на одних клавишах бот только топчется, —
            // но и молчать нельзя: со стороны это «стоит под ударами»
            BodyBusy(ctx.Turn.Busy);
            return false;
        }
        // ДАЛЬШЕ ЖИВЁМ НА ТОКЕНЕ ВЛАДЕНИЯ, а не на общем. Перебили нас смертью
        // или бурей — бой и побег обязаны остановиться сами, а не махать руками
        // в мире, где им уже отказано
        var mine = hold.Token;

        if (wantFlee)
        {
            try
            {
                // Убегая, сбрасываем броню: она замедляет, а сейчас важна
                // скорость. Лечиться будем уже в отрыве — способность лечения
                // сама дождётся, когда рядом не станет врагов. Решает это то же
                // одно правило, что и всё прочее про броню
                await FitGearAsync(fighting: false, fleeing: true, mine);
                if (unarmed)
                    FleeingUnarmed(weaponCode ?? "голые руки", weaponPower);
                // ПРИЧИНА ПОБЕГА — ПО ТОМУ, ЧТО В РУКАХ, А НЕ ПО ЗАЩЁЛКЕ
                // ОТСТУПЛЕНИЯ. Уходить теперь можно и здоровым с мечом — когда
                // счёт показал, что размен не окупается; прежнее «retreating ?
                // … : Unarmed» в этом случае писало «драться нечем (sword)».
                // Полный разбор всё равно уходит отдельной строкой (OnPlan)
                var report = await FleeFromAsync(enemy,
                    unarmed ? FleeReason.Unarmed : FleeReason.LowHealth,
                    frac, weaponCode ?? "голые руки", mine);
                OnFled?.Invoke(report);
                ApplyFleeOutcome(report);
            }
            catch (OperationCanceledException)
            {
                // Тело забрали ещё на сборах (смерть, буря). Не ошибка
                // способности, а смена хозяина — так и говорим
                BodyBusy(ctx.Turn.Busy);
            }
            return true;
        }

        // ОРУЖИЕ БЕРЁМ ЧЕРЕЗ РУКИ, А НЕ ПАКЕТОМ МИМО НИХ.
        //
        // ЖИВОЙ СЛУЧАЙ, ради которого это переписано, словами заказчика: «после
        // боя продолжит копать оружием, это же как чит». Так и было, и виноват
        // ровно этот вызов. Здесь стоял ctx.Actions.SelectHotbarSlotAsync —
        // голый пакет 13. Он меняет слот НА СЕРВЕРЕ, но Hands.ActiveSlot об
        // этом не узнаёт: своё же переключение сервер обратно не подтверждает
        // (пакет 53 он шлёт, только когда слот меняет ОН САМ, см. Hands).
        //
        // Дальше рушилось всё, что спрашивает «а что у меня в руке»:
        //   • Mining.ArrangeHandAsync видел прежнюю кирку, решал «уже в руке,
        //     пакета не надо» — и бот копал МЕЧОМ, который держал сервер;
        //   • SecondsToBreak считал время по кирке, а бил меч: кнопку отпускали
        //     втрое раньше срока, блок оставался, и цикл добычи шёл вхолостую;
        //   • сторож «руку забрали посреди удара» сравнивал ложь с ложью и
        //     не срабатывал никогда.
        // Hands.SelectAsync делает ровно то же самое, но ЧЕСТНО: шлёт пакет,
        // запоминает слот и выжидает свои HandChangeSettleMs.
        if (weaponSlot >= 0)
            await ctx.Hands.SelectAsync(weaponSlot);
        if (mine.IsCancellationRequested)
        {
            // Тело забрали, пока мы тянулись за оружием (смерть, буря). Это не
            // ошибка способности, а смена хозяина, и уходить отсюда надо
            // молчаливым отказом, а не исключением: раньше здесь стоял
            // Task.Delay на том же токене, и такая отмена прилетала в
            // OnBehaviorError как поломка боя
            BodyBusy(ctx.Turn.Busy);
            return false;
        }
        OnWeaponChosen?.Invoke(weaponCode ?? "голые руки", weaponPower);

        OnEngage?.Invoke(enemy);
        await FitGearAsync(fighting: true, fleeing: false, mine);
        ctx.Movement.FocusEntityId = enemy.Id; // взгляд — на противника, без дёрганий

        var deadline = DateTime.UtcNow.AddSeconds(MaxEngageSeconds);
        var lastSwing = DateTime.MinValue;
        var ended = CombatEnd.LeftFight;
        bool interrupted = false;
        // Преграда, выросшая между нами уже ПОСЛЕ начала боя (см. ниже)
        CombatBarrier wall = CombatBarrier.None;
        // ПОДНЯТЫЙ ЩИТ — ЭТО ВЛАДЕНИЕ ПРИСЕДОМ, и оно живёт РОВНО столько,
        // сколько идёт размен вплотную. Держать его надо снаружи цикла: внутри
        // он берётся и отпускается по обстановке (отошли, отскочили, кончился
        // бой), а забыть отпустить нельзя ни на одном выходе — иначе бот
        // уползёт с поля боя в присяде втрое медленнее и не поймёт, почему
        IDisposable? shieldUp = null;
        try
        {
            while (!mine.IsCancellationRequested && DateTime.UtcNow < deadline)
            {
                // ЧЕМ КОНЧИЛСЯ БОЙ — ПО ФАКТУ ОТ СЕРВЕРА, А НЕ ПО ДОГАДКЕ.
                //
                // Здесь стояли ДВЕ РАЗНЫЕ догадки об одном и том же — об
                // отсутствующем здоровье. Условие выхода читало «нет здоровья —
                // значит убит» (Health ?? 0), а отбор целей парой сотен строк
                // выше — «нет здоровья — значит жив» (Health ?? 1). Оттого
                // воткнутая стрела бралась в бой и в ту же миллисекунду
                // объявлялась поверженной, и так сто восемьдесят раз подряд
                // (журнал 17.08, 23:49:47 → 23:51:14).
                //
                // Пропал из мира — это тоже НЕ победа: сущность исчезает и
                // когда просто вышла из прогруженных чанков
                var live = ctx.Entities.Get(enemy.Id);
                if (live == null)
                {
                    ended = CombatEnd.Vanished;
                    break;
                }
                if (CombatTargets.Defeated(live.Health))
                {
                    ended = CombatEnd.Defeated;
                    break;
                }
                double dist = live.DistanceTo(self.X, self.Y, self.Z);
                if (dist > engageLimit)
                    break; // дальше не пойдём: мы обороняемся, а не охотимся

                // ДЕРЖУ ДИСТАНЦИЮ — ЭТО ОТХОД, А НЕ «СТОЮ НА МЕСТЕ». Подошёл
                // ближе, чем стреляет лук, — пячусь тем же приёмом, каким бот
                // отскакивает после удара (второго способа отходить не
                // заведено). Так и считает счёт вариантов: цена боя нулевая
                // ровно потому, что размена вплотную не будет (см. RateFight,
                // ветка «держуДистанцию»), — и обещание это обязаны выполнить
                // ноги, а не слова
                if (keepDistance && dist < ShootMinRange && Bow.ArrowsCarried() > 0)
                {
                    shieldUp?.Dispose();
                    shieldUp = null;
                    if (NewsAbout($"пячусь:{enemy.Id}"))
                        OnSay?.Invoke($"пячусь от {live.Code}: он созовёт подмогу, " +
                                      $"вплотную к нему нельзя (ручка " +
                                      $"«ЗовущихПодмогуБитьИздали»)");
                    await ctx.Movement.FaceAsync(live.X, live.Z);
                    await StepBackAsync(self, enemy.Id, mine);
                    continue;
                }

                if (dist > AttackReach)
                {
                    // ЩИТ ОПУСКАЕМ, КАК ТОЛЬКО ОТОШЛИ. Присед стоит 0,65
                    // скорости, а на дистанции щит и так не поднят по правилам
                    // игры: натяг лука сам сбрасывает его в «passive»
                    // (Attributes["aiming"] == 1 в той же строке защиты)
                    shieldUp?.Dispose();
                    shieldUp = null;

                    // НА ДИСТАНЦИИ — ЛУК, ВПЛОТНУЮ — РУКА. Заказчик: «может
                    // научим бота стрелять из лука?»
                    //
                    // ПОЧЕМУ РЕШЕНИЕ ЗДЕСЬ, А НЕ ОТДЕЛЬНОЙ СПОСОБНОСТЬЮ. Это то
                    // же самое решение, что и «гнаться ли»: цель одна, тело
                    // одно, преграда одна и та же. Два решения об одном
                    // дрифтере — это ровно та беда, которой болела броня, пока
                    // решений про неё было четыре в разных углах боя.
                    //
                    // ОТКАЗ НЕ РВЁТ ПОГОНЮ: не вышло стрелять (стрел нет, стена,
                    // далеко) — сходимся ногами, как сходились всегда. Причину
                    // при этом бот называет вслух, один раз на новость
                    if (UseBow && DateTime.UtcNow - lastShot >=
                        TimeSpan.FromSeconds(Math.Max(0.1, ShootIntervalSeconds)))
                    {
                        lastShot = DateTime.UtcNow;
                        // ЩИТ ОПУСКАЕМ НА ВРЕМЯ ВЫСТРЕЛА, И ЭТО НЕ НАША
                        // ПРИДУМКА: игра сама сбрасывает щит в «passive», пока
                        // Attributes["aiming"] == 1 (та же строка, что читает
                        // присед). Держать присед при натяге — значит платить
                        // 0,35 скорости ни за что
                        // ПОРОГ ДОЛИ ПОПАДАНИЯ И ЕГО СНЯТИЕ. Оба факта берутся
                        // ОТСЮДА, потому что только здесь они и известны:
                        // «загнан» — это решение счёта вариантов выше по методу,
                        // а «нечем бить вблизи» — общая мерка оружия, та же,
                        // которой считается «бежать ли безоружным». Заведи луку
                        // свою — бот убегал бы «безоружным», продолжая при этом
                        // беречь стрелы «на потом», которого не будет
                        if (await Bow.ShootAsync(live, DrawSeconds, ShootMinRange,
                                ShootMaxRange, ShootMinChance,
                                Archery.LastResort(cornered, haveMelee, keepDistance),
                                mine))
                        {
                            OnShot?.Invoke(live.Code, dist);
                            continue;
                        }
                    }

                    // ЗОВУЩЕГО ПОДМОГУ НЕ ДОГОНЯЮТ — заказчик дословно:
                    // «луком предпочтительно, если есть, с далека убивать
                    // колокола». Почему именно так — разобрано в
                    // CombatDanger.CallsForHelp по задаче игры AiTaskBellAlarm:
                    // своего удара у колокола нет вовсе, зато на шум он каждые
                    // 1…5 с зовёт до шести глубинных тварей в двенадцать блоков
                    // вокруг. Подойти к нему и махать мечом — это начать бой со
                    // всеми, кого он успеет созвать.
                    //
                    // ДЕРЖИМСЯ, ПОКА ЛУК ДОСТАЁТ. Дальше своей «СтрелятьНеДальше»
                    // сходимся как ко всем: иначе бот стоял бы в тридцати блоках
                    // и не делал ничего
                    if (keepDistance && dist <= ShootMaxRange && Bow.ArrowsCarried() > 0)
                    {
                        if (NewsAbout($"неподхожу:{enemy.Id}"))
                            OnSay?.Invoke($"к {live.Code} не подхожу: он созовёт подмогу " +
                                          $"(ручка «ЗовущихПодмогуБитьИздали») — беру его " +
                                          $"с {dist:0.#} бл");
                        await Task.Delay(120, mine);
                        continue;
                    }

                    // К ТОМУ, ДО КОГО У НЕГО НЕТ ДОРОГИ КО МНЕ, НОГАМИ НЕ ИДЁМ.
                    //
                    // ЭТО И ЕСТЬ «БЕЖИТ В ОКНО И ДЕРЁТСЯ ПОПОЙ». Отказ выстрела
                    // выше «не рвёт погоню» — и правильно, когда причина
                    // временная (стрелы кончились, далеко). Но если ему до меня
                    // не дойти, то и мне к нему не пройти тем же проёмом: бот
                    // упирался в стену, движение писало «тупик … запомнил», а
                    // решение принималось заново каждые полсекунды. Мерка та же
                    // самая, что и у всего этого правила, второй не заводим.
                    //
                    // ЭТО НЕ ВОПРОС «ЕСТЬ ЛИ ДОРОГА МЕЖДУ НАМИ», И ПУТАТЬ ИХ
                    // НЕЛЬЗЯ — на этой путанице бот и бегал в стену (разбор
                    // строкой ниже). Здесь спрашивается «ЗАПЕРТ ЛИ Я»: воздух
                    // обводится ВОКРУГ БОТА (см. CreatureReach), и пока он не
                    // замкнулся, ответ всегда «дойдёт». Правило верное и живьём
                    // доказанное, просто отвечает оно про мои стены, а не про
                    // дорогу между нами
                    if (OnlyWhoReachesMe && !HeReachesMe(self, live, dist))
                    {
                        if (NewsAbout($"неидукнему:{enemy.Id}"))
                            OnSay?.Invoke($"к {live.Code} ногами не иду: дороги ко мне у него " +
                                          "нет, значит и мне к нему не пройти — только " +
                                          "упрусь в стену");
                        await Task.Delay(200, mine);
                        continue;
                    }

                    // БОЙ СПРАШИВАЕТ ДОРОГУ ДО ТОГО, КАК ПОБЕЖАТЬ.
                    //
                    // ЖАЛОБА ЗАКАЗЧИКА 30.08 ДОСЛОВНО: «и когда в боевом режиме
                    // снова отключается наш поиск пути, просто бежал в стену
                    // бесконечно, деградация».
                    //
                    // ЗАЩЁЛКА ВЫШЕ ЭТОГО НЕ ЛОВИТ: она про МОИ СТЕНЫ, а ногам
                    // нужен другой вопрос — есть ли дорога МЕЖДУ НАМИ. Бот в
                    // поле, тварь за стеной: воздух вокруг бота не замкнётся
                    // никогда, ответ «дойдёт», и бот бежал.
                    //
                    // ВТОРОЙ МЕРКИ ДЛЯ ЭТОГО НЕ ЗАВЕДЕНО (закон 2): вопрос
                    // «есть ли дорога между нами» в этом файле давно и один —
                    // Reachable(), тот самый поиск пути, которым бой уже считает
                    // бегство. Он же и держит ответ PathCheckSeconds, чтобы
                    // маршрут не считался каждый тик.
                    //
                    // СПРАШИВАЕТСЯ ЭТО ДО ПОХОДА, А НЕ ВМЕСТО НЕГО: подход умеет
                    // обходить сам, но бросаться в погоню за тем, до кого хода
                    // нет вовсе, — это бой ценой чужого дела, и решать такое
                    // должен бой, а не ходьба
                    if (!Reachable(self, live, dist))
                    {
                        if (NewsAbout($"нетдороги:{enemy.Id}"))
                            OnSay?.Invoke($"к {live.Code} не бегу: дороги между нами нет " +
                                          $"({dist:0.#} бл) — прямым ходом я только упрусь " +
                                          "в стену, а это не бой");
                        break;
                    }

                    // ДОЙТИ ДО ДВИЖУЩЕЙСЯ ЦЕЛИ — ГОТОВАЯ МЕХАНИКА, И ЗОВЁМ МЫ
                    // ЕЁ, А НЕ СОБИРАЕМ СВОЮ ИЗ ЕЁ ЖЕ ЧАСТЕЙ.
                    //
                    // ПРЯМОЙ ВОПРОС ЗАКАЗЧИКА 31.08: «Бой… погоня будет
                    // спрашивать путь… — а разве она не должна работать как
                    // команда ко мне?» Должна, и вот почему он прав.
                    // <c>Movement.PursueAsync</c> — это ПРИМИТИВ: держать клавиши
                    // в сторону цели, поиска пути не звать ни разу. А «!комне»
                    // ходит <see cref="Movement.ApproachAsync"/>, и та уже
                    // содержит ровно то, что бой полгода отстраивал себе рядом:
                    // прямой ход вблизи, маршрут по клеткам при упоре, счёт
                    // неудачных перепланировок (MaxReplans), самоперезапуск и имя
                    // похода по цели — чтобы отказ подхода К ЭТОЙ твари не закрыл
                    // разом все подходы (см. TripFrom).
                    //
                    // ЗДЕСЬ ЛЕЖАЛА ВТОРАЯ КОПИЯ ЭТОГО ВСЕГО: свой счёт упоров,
                    // свой заход маршрутом через MoveToCellAsync со своим сроком.
                    // Копия лечила «дороги нет вовсе» и НЕ лечила «дорога есть, но
                    // не прямая» — вокруг стены, через дверь, в обход: поиск
                    // отвечал «есть», прямой ход всё равно упирался, счётчик
                    // дотикивал, и бой сдавался там, где «комне» доходило. Проект
                    // это уже проходил — Presets.cs про «!иди»: «разница была не в
                    // уме, а в упорстве».
                    //
                    // СРОК ЗАХОДА — НАША МЕРКА ОТЗЫВЧИВОСТИ, и подход её слушает:
                    // ApproachAsync берёт maxSeconds как ОБЩИЙ срок похода вместе
                    // со всеми перепланировками и перезапусками
                    double былX = self.X, былY = self.Y, былZ = self.Z;
                    if (await ctx.Movement.ApproachAsync(
                            () => ctx.Entities.Get(enemy.Id) is { } t ? (t.X, t.Y, t.Z) : null,
                            stopDistance: AttackReach - 0.5, maxSeconds: ChaseLegSeconds,
                            ct: mine))
                        continue;

                    // ЗАХОД КОНЧИЛСЯ НИЧЕМ — ВОПРОС О ДОРОГЕ ЗАДАЁТСЯ ЗАНОВО.
                    // Прошлый ответ мог прийти из тайника секунду назад, а ноги
                    // только что показали обратное: спрашивать тайник ещё раз
                    // значило бы услышать ту же ложь и побежать в ту же стену
                    ForgetTheWay();
                    if (ctx.Entities.Get(enemy.Id) is null)
                        continue;   // пропал из мира — разберётся начало круга
                    double stalled = live.DistanceTo(self.X, self.Y, self.Z);
                    if (!Reachable(self, live, stalled))
                    {
                        if (NewsAbout($"дорогапропала:{enemy.Id}"))
                            OnSay?.Invoke($"к {live.Code} не пробьюсь: подход упёрся, " +
                                          $"а маршрута между нами нет ({stalled:0.#} бл) — " +
                                          "погоню прекращаю, в стену биться не буду");
                        break;
                    }

                    // ШЁЛ ЛИ Я ВООБЩЕ — МЕРЯЕТСЯ СВОИМ ПЕРЕМЕЩЕНИЕМ, А НЕ
                    // РАЗРЫВОМ, и это та же мерка, что у побега
                    // (<see cref="MinFleeStep"/>, там разбор): от дрифтера разрыв
                    // не растёт и не тает — он бежит с нашей скоростью, — так что
                    // «ближе не стало» ничего не говорит о том, шли мы или
                    // стояли.
                    //
                    // ЗАЧЕМ ЭТО ВООБЩЕ. Отказ подхода бывает двух разных родов, и
                    // путать их нельзя: «перебрал всё и не пробился» — это конец
                    // погони, а «вышел отпущенный мной срок» — это МОЯ мерка
                    // отзывчивости, и наказывать за неё дорогу нечестно. Обход
                    // вокруг длинной стены в ChaseLegSeconds может и не уложиться:
                    // бот шёл, шёл честно, и следующий заход его дойдёт
                    if (Math.Sqrt(Math.Pow(self.X - былX, 2) + Math.Pow(self.Y - былY, 2) +
                                  Math.Pow(self.Z - былZ, 2)) >= ChaseStepThatCounts)
                        continue;

                    // Стычка начинается заново каждые полсекунды, и без защёлки
                    // повторов этот отказ залил бы весь журнал
                    if (NewsAbout($"непробился:{enemy.Id}"))
                        OnSay?.Invoke($"к {live.Code} не пробился: заход подхода перебрал и " +
                                      $"прямой ход, и маршрут, и поднял себя заново, а я с " +
                                      $"места не сдвинулся — дорога между нами есть " +
                                      $"({stalled:0.#} бл), а ноги её не берут. Погоню бросаю, " +
                                      "а не бегаю в стену");
                    break;
                }

                await ctx.Movement.FaceAsync(live.X, live.Z);

                // ЛУК ИЗ РУКИ УБИРАЕМ, ПРЕЖДЕ ЧЕМ МАХАТЬ. Оружие берётся ОДИН
                // раз, до цикла, — а внутри цикла лук кладёт в активный слот
                // себя (Archery.ShootAsync: TakeToHandAsync(IsBow)), и назад
                // меч не возвращал НИКТО.
                //
                // ЧЕМ ЭТО КОНЧАЛОСЬ. Тварь подходит ближе длины руки — и бот
                // всю стычку машет ЛУКОМ. У лука в ассетах 1.22.7 поля
                // «attackpower» нет вовсе, то есть удар идёт по умолчанию
                // CollectibleObject.AttackPower = 0,5 — урон голых рук. При
                // этом защёлка «безоружным не лезть» молчит: она считала меч.
                // В журнале «взял sword-copper», в мире — лук.
                //
                // СПРАШИВАЕМ РУКУ, А НЕ НОМЕР СЛОТА: лук, вставая в хотбар, мог
                // подвинуть меч, и слот, запомненный до цикла, показывал бы уже
                // не на него. Ходка бесплатна, пока в руке и так нужное
                if (weaponCode is { Length: > 0 } melee && ctx.Hands.Held?.Code != melee &&
                    await ctx.Hands.TakeToHandAsync(melee, mine) is null)
                    OnSay?.Invoke($"{melee} назад в руку не встал — бью тем, " +
                                  $"что есть ({ctx.Hands.Held?.Code ?? "голые руки"})");

                // ЩИТ ПОДНЯТ, ПОКА ИДЁТ РАЗМЕН ВПЛОТНУЮ — и это единственное,
                // что в игре вообще значит «поднять щит»: ЗАЖАТЫЙ ПРИСЕД
                // (<c>Controls.Sneak &amp;&amp; aiming != 1 → "active"</c>, шанс
                // перехвата 0,9 вместо 0,2). Анимация raiseshield — косметика
                // клиента и на защиту не влияет никак.
                //
                // ПОДНИМАТЬ НАДО ИМЕННО ЗДЕСЬ, А НЕ ВОКРУГ СВОЕГО УДАРА: щит
                // срабатывает, когда бьют НАС, а не когда бьём мы. Свой удар —
                // это один пакет, и владение вокруг него жило бы микросекунды,
                // то есть не значило бы ничего.
                //
                // Смотреть на нападающего при этом обязательно (конус ±60° по
                // рысканью), и это уже сделано строкой выше — своей наводки щит
                // не заводит
                if (RaiseShield && shieldUp == null)
                    shieldUp = ctx.Shield?.Raised();

                if ((DateTime.UtcNow - lastSwing).TotalMilliseconds >= SwingIntervalMs)
                {
                    // ПЕРЕД КАЖДЫМ УДАРОМ СПРАШИВАЕМ, ЧТО МЕЖДУ НАМИ. Решение
                    // «дерусь» считается ОДИН раз, а живёт этот цикл до двадцати
                    // секунд — и всё это время бот бил, ни разу не переспросив.
                    //
                    // ЖИВОЙ СЛУЧАЙ, который сюда пролезал мимо всех пяти
                    // караулов CombatPlan: тварь на бегу заходит за угол или за
                    // столб, бот стоит от неё в двух блоках («он вплотную») и
                    // машет СКВОЗЬ БЛОК. Сервер такой удар засчитает — он
                    // проверяет только расстояние (ServerSystemEntitySimulation,
                    // пакет 17), — а живой игрок так не может, и это ровно тот
                    // чит, который заказчик просил убрать.
                    //
                    // Луч тот же самый (WhatSeparates), второго механизма нет.
                    // Спрашиваем ИМЕННО ПЕРЕД УДАРОМ, а не каждые 120 мс: раз в
                    // замах луч дёшев, и вопрос задаётся там, где от ответа
                    // что-то зависит. Погоню он не рвёт — обойти преграду
                    // ногами не запрещено никому
                    var between = WhatSeparates(live);
                    if (between != CombatBarrier.None)
                    {
                        wall = between;
                        break;
                    }

                    lastSwing = DateTime.UtcNow;
                    await ctx.Actions.AttackEntityAsync(live.Id);

                    // Ударил — отскочил. Стоять вплотную и обмениваться ударами
                    // невыгодно: моб бьёт по кулдауну, и попадает он всегда.
                    // Отход разрывает дистанцию как раз на время его замаха
                    if (KiteAfterHit)
                    {
                        // ЩИТ ОПУСКАЕМ ПЕРЕД ОТСКОКОМ. На присяде тело идёт
                        // 0,35 обычной скорости — с поднятым щитом «отскок»
                        // превратился бы в переступание на месте, то есть
                        // отменил бы сам приём
                        shieldUp?.Dispose();
                        shieldUp = null;
                        await StepBackAsync(self, enemy.Id, mine);
                    }
                }
                await Task.Delay(120, mine);
            }
        }
        catch (OperationCanceledException)
        {
            // Тело забрали посреди размена ударов (смерть, буря, приказ).
            // Это не «противник ушёл» и не «повержен» — это конец боя без
            // итога, и назвать его надо своим именем
            interrupted = true;
        }
        finally
        {
            ctx.Movement.FocusEntityId = null;
            // ЩИТ ОПУСКАЕТСЯ НА ЛЮБОМ ВЫХОДЕ — и на победе, и на смерти, и на
            // отобранном теле. Это тот же класс беды, что «не снимал броню
            // после шторма»: забытое владение приседом не видно ниоткуда, а
            // стоит 65 % скорости до конца смены
            shieldUp?.Dispose();
        }

        if (interrupted)
            BodyBusy(ctx.Turn.Busy);
        else if (wall != CombatBarrier.None)
            // НЕ «ПРОТИВНИК УШЁЛ» И НЕ «ПОВЕРЖЕН» — между нами выросла преграда.
            // Сказать это надо теми же словами, какими откажет счёт вариантов на
            // следующем тике (facts with { Barrier = … }), иначе человек прочтёт
            // в журнале два разных объяснения одного и того же отказа
            SayPlan(enemy, new CombatDecision(CombatChoice.Ignore, 100,
                (facts with { Barrier = wall }).WhyNotEngage() + " — бой прекращаю"));
        else
            OnDisengage?.Invoke(enemy, ended);

        // Броня хороша в драке, но в ней бот ест в полтора раза больше.
        // РАЗДЕВАТЬСЯ МОЖНО ТОЛЬКО КОГДА БОЙ КОНЧИЛСЯ, и это НЕ отдельное
        // условие: «рядом опасно» (недавно били, тварь в радиусе, идёт буря)
        // спрашивает то же самое одно правило — DangerNear внутри FitArmorAsync.
        // Прежнее «бесконечное снял-надел под ударами» им и держится
        await FitGearAsync(fighting: false, fleeing: false, ct);
        return true; // бой занимает ход
    }

    /// <summary>
    /// ОДЕТЬСЯ ПО ОБСТАНОВКЕ — ЕДИНСТВЕННОЕ РЕШЕНИЕ ПРО БРОНЮ ВО ВСЁМ БОЮ.
    ///
    /// Что решать — <see cref="ArmorKit.NeedArmor"/> (чистое правило, стережётся
    /// тестами). Чем делать — <see cref="ArmorKit.EquipBestAsync"/> и
    /// <see cref="ArmorKit.UnequipAllAsync"/>, единственные такие двери на весь
    /// проект: той же <c>UnequipAllAsync</c> раздевает бота кнопка в окне
    /// управления, и второй копии этой механики нет.
    ///
    /// «РЯДОМ ОПАСНО» СПРАШИВАЕТСЯ У МИРА, А НЕ У ПАМЯТИ О БОЕ: тварь в радиусе
    /// ответа, свежая обида или временная буря. Ровно этого не хватало живому
    /// случаю — бот стоял в укрытии, «не связываюсь», и снимать броню было
    /// некому, потому что опасность мерили одной веткой «врагов не видно вовсе».
    ///
    /// Возвращает true, если бот и правда переоделся (то есть занял этим ход).
    /// </summary>
    private async Task<bool> FitGearAsync(bool fighting, bool fleeing, CancellationToken ct)
    {
        // «РЯДОМ ОПАСНО» МЕРЯЕТСЯ ОБОРОНИТЕЛЬНЫМ РАДИУСОМ, А НЕ КРУГОМ ВСТРЕЧИ,
        // И ЭТО РЕШЕНО НАРОЧНО — 26.08, когда круг встречи вырос до дальности
        // выстрела (24 бл).
        //
        // Соблазн был взять сюда тот же круг: «раз я беру его в бой с двадцати
        // блоков, то и одеваться надо с двадцати». Это вернуло бы ровно ту
        // беду, которую здесь чинили: броню бот не снимал бы почти никогда —
        // дрифтер в двадцати блоках есть в любой пещере, а в броне бот ест в
        // полтора раза больше. Броня — от УДАРОВ, а удары приходят вплотную.
        //
        // Раздетым в дальний бой он при этом не выходит: решив драться, он
        // спрашивает это же правило с fighting: true (см. ниже по ходу боя), и
        // одевается независимо от расстояния. Оговорка честная: броня режет
        // точность стрельбы (rangedWeaponsAcc, до −0,3 в трёх латных
        // предметах), и лук это учитывает, доводя натяг до потолка сам.
        //
        // «ТВАРЬ В РАДИУСЕ» — ЭТО ТВАРЬ, КОТОРАЯ ДО МЕНЯ ДОЙДЁТ, и мерка тут та
        // же самая, что у решения (HeReachesMe), а не своя. Живая жалоба
        // заказчика ровно про это: дрифтер за стеной дома при закрытых дверях —
        // и бот «надел броню (3 предм.): 42 % скорости и 72 % лишнего голода».
        // Броня от УДАРОВ, а тот, кому ко мне не дойти, не ударит; заведи здесь
        // свою мерку — и бот отказывался бы драться, продолжая париться в
        // железе (закон 2).
        bool danger = DateTime.UtcNow < hurtUntil || ctx.Storms.ShelterNow ||
                      (ctx.Entities.Self is { } me &&
                       ctx.Entities.Nearby(me.X, me.Y, me.Z, DefendRadius)
                           .Any(e => IsHostile(e) &&
                                     HeReachesMe(me, e, e.DistanceTo(me.X, me.Y, me.Z))));

        // ЩИТ — ТА ЖЕ ДВЕРЬ, ЧТО И БРОНЯ, и это главное требование заказчика:
        // «надевается только в момент угрозы как и броня». Обстановку («дерусь /
        // убегаю / рядом опасно») считает ОДИН этот метод, и щит берёт её
        // готовой, а не считает заново. Отличие у него ровно одно и живёт в
        // числах правила, а не здесь: убегая, щит не снимается (см. NeedGear).
        //
        // РУКУ ОН ПОЛУЧАЕТ НЕ ВСЕГДА: слот у него общий с фонарём, и спор
        // решает одно правило на обе стороны (Shielding.WhoNeedsOffHand).
        // Здесь мы только КЛАДЁМ СВОЙ ФАКТ на весы — «угроза есть» — и
        // спрашиваем, чья теперь рука
        bool shieldChanged = false;
        if (ctx.Shield is { } shield)
        {
            shield.NoteThreat(fighting, fleeing, danger);
            shieldChanged = await shield.FitAsync(shield.WantsOffHand, ct);
        }

        if (!ArmorKit.NeedArmor(Armor, fighting, fleeing, danger))
        {
            // РАЗДЕВАЕМСЯ СРАЗУ И БЕЗ ПАУЗ: каждая лишняя секунда в доспехе —
            // это съеденная еда и потерянная скорость. Числа берём ДО снятия —
            // после него говорить о них уже не о чем
            var (walk, hunger) = ArmorKit.Cost(ctx);
            int off = await ArmorKit.UnequipAllAsync(ctx, ct);
            if (off <= 0)
                return shieldChanged;   // щит мог переодеться и без брони
            OnArmorSay?.Invoke($"снял броню ({off} предм.): рядом тихо, а она стоила " +
                               $"{-walk:P0} скорости и {hunger:P0} лишнего голода");
            return true;
        }

        // Пауза только на «додеть»: снаряжение в сумке само не заводится, и
        // перебирать инвентари дважды в секунду незачем
        if (DateTime.UtcNow < nextArmorFit)
            return shieldChanged;
        nextArmorFit = DateTime.UtcNow.AddSeconds(Math.Max(0, ArmorFitSeconds));
        int put = await ArmorKit.EquipBestAsync(ctx, ct);
        if (put <= 0)
            return shieldChanged;
        var (w, h) = ArmorKit.Cost(ctx);
        OnArmorSay?.Invoke($"надел броню ({put} предм.): {-w:P0} скорости и " +
                           $"{h:P0} лишнего голода — но рядом опасно");
        return true;
    }

    /// <summary>
    /// Забыть стычку целиком: обиду, цель, погоню, угол, затишье и терпение.
    ///
    /// Нужно ровно в одном месте — при смерти. Всё, что бот помнил о драке,
    /// относится к прошлой жизни и к прошлому месту: возрождают его в другой
    /// точке, а старая память заставляла его мстить тем, кого рядом нет.
    ///
    /// ЗОВЁТ ЭТО СМЕРТЬ ОТ СЕРВЕРА (<see cref="SelfState.OnDeath"/>), а не
    /// проверка здоровья в свой ход, и вот почему это не мелочь. Живой случай
    /// 19.08: бот умер в 18:34:16, возродился за двести пятьдесят блоков в
    /// 18:34:19, а ход до боя дошёл только в 18:34:26 — со здоровьем уже полным.
    /// Ветка «мёртвый не дерётся» не сработала ни разу, зато разом разобрались
    /// шесть предсмертных ударов, и бот честно доложил: «меня бьёт дрифтер, а
    /// живого врага в 30 бл нет». Бил его дрифтер прошлой жизни, в другом конце
    /// карты.
    /// </summary>
    private void ForgetTheFight()
    {
        hurtUntil = DateTime.MinValue;
        chaseUntil = DateTime.MinValue;
        corneredUntil = DateTime.MinValue;
        calmUntil = DateTime.MinValue;
        attackerId = null;
        retreating = false;
        enduringSince = null;
        Pace.Clear();
        // «Заперт ли я» — ответ про ТО место и ТУ дверь. Возрождают в другом
        // конце карты, и старый ответ там значит ровно ничего
        места.Clear();
        // Удары прошлой жизни судить не надо: возрождают в другом месте, и
        // «меня ударил дрифтер» относится к тому дрифтеру, которого рядом нет
        seenHits = ctx.Damage?.Count ?? seenHits;
    }

    // ======================================================================
    //  ПРИЧИНА УРОНА — ФАКТОМ
    // ======================================================================

    /// <summary>
    /// ЗАМЕР СКОРОСТИ ИДЁТ ОТ ПАКЕТА, А НЕ ОТ ХОДА СПОСОБНОСТИ.
    ///
    /// Здесь стоял обход «все враждебные в радиусе ответа» — раз в тик боя. И
    /// вот чем это кончилось живьём (журнал 19.08): ходы боя приходили через
    /// 3 и через 28 секунд, потому что тело держали то склад, то дорога домой,
    /// а замер берётся только с промежутка 0,2…2 с (см. CombatPace). Ни одного
    /// замера не набралось ни разу, и оба выхода отказывали одними словами:
    /// «скорость его ещё не мерил — гнаться вслепую не буду» и «…не знаю,
    /// оторвусь ли». Тупик был по устройству: чтобы измерить, надо было тикать,
    /// а тикать мешало то же самое, от чего надо было спасаться.
    ///
    /// Теперь меряем там, где приходят факты, — в потоке положений от сервера.
    /// Радиуса здесь нет нарочно: сервер шлёт положения тех, кто и так в
    /// прогруженных чанках, а «далеко ли он» спрашивает уже решение.
    /// </summary>
    private void NoticePace(EntityInfo e)
    {
        if (IsHostile(e))
            Pace.Sample(e, DateTime.UtcNow);
    }

    /// <summary>
    /// РАЗОБРАТЬ, ЧТО СО МНОЙ СЛУЧИЛОСЬ. Сперва по журналу урона сервера — он
    /// называет причину прямо; если образцов нет (не нашлись языковые файлы),
    /// живём по прежней догадке, но уже с порогом и с честным «не знаю».
    /// </summary>
    private void NoticeHurt(EntityInfo self, float health)
    {
        if (UseDamageLog && ctx.Damage is { Ready: true } log)
        {
            var fresh = log.Since(seenHits);
            seenHits = log.Count;
            foreach (var hit in fresh)
                JudgeHit(self, hit);
            return;
        }

        if (lastKnownHealth is not { } before)
            return;
        double lost = before - health;
        if (lost <= 0.01)
            return;

        // Причины нам не сказали — судим по состоянию тела, как раньше.
        // Это ХУЖЕ факта и потому говорится вслух другим текстом
        var guessed = new DamageHit(lost,
            HurtByOwnBody(self) ? DamageFrom.Body : DamageFrom.Unknown,
            null, $"здоровья убавилось на {lost:0.##} (причину сервер не назвал)",
            DateTime.UtcNow);
        if (guessed.From == DamageFrom.Body)
        {
            Told(guessed, FightEntry.NotAFight);
            return;
        }
        if (lost < MinHurtToFight)
        {
            Told(guessed with { From = DamageFrom.Unknown }, FightEntry.Scratch);
            return;
        }
        Told(guessed, FightEntry.Unknown);
        StartFight(self, null);
    }

    /// <summary>Один разобранный удар: лезть ли из-за него в бой.</summary>
    private void JudgeHit(EntityInfo self, DamageHit hit)
    {
        var verdict = CombatEntry.Judge(hit, MinHurtToFight);
        Told(hit, verdict);
        if (verdict == FightEntry.FightBack)
            StartFight(self, hit);
    }

    /// <summary>
    /// Сказать про удар. Настоящее нападение — событие, и говорится каждый раз;
    /// «это голод» и «это царапина» — СОСТОЯНИЕ (голод бьёт каждые шесть
    /// секунд), и через заглушку повторов, иначе получится тот самый журнал,
    /// в котором за десятками одинаковых строк не видно беды.
    /// </summary>
    private void Told(DamageHit hit, FightEntry verdict)
    {
        if (verdict == FightEntry.FightBack || NewsAbout($"урон:{verdict}:{hit.Who}"))
            OnHurtCause?.Invoke(hit, verdict);
    }

    /// <summary>Начать разбираться: запомнить обиду и выбрать, кто её нанёс.</summary>
    private void StartFight(EntityInfo self, DamageHit? hit)
    {
        // Бьют — значит никакого «оторвался» не было. Затишье снимаем сразу:
        // это единственный честный признак, что отрыв не удался
        calmUntil = DateTime.MinValue;
        hurtUntil = DateTime.UtcNow.AddSeconds(RevengeMemorySeconds);
        // Ищем обидчика в том радиусе, в каком роль разрешила мстить:
        // стрелка за двадцать блоков в десятиблочном круге не найти
        double lookFor = Revenge == RevengePolicy.Никогда
            ? HurtResponseRadius
            : Math.Max(HurtResponseRadius, RevengeRadius);
        attackerId = FindAttacker(self, hit, lookFor);
        if (attackerId != null)
            OnRevengeTarget?.Invoke(ctx.Entities.Get(attackerId.Value)?.Code ?? "?");
    }

    /// <summary>
    /// КТО ИМЕННО УДАРИЛ. Сервер называет его по имени («дрифтер», «глубинный
    /// боуторн», имя игрока) — и это единственный способ не перепутать.
    ///
    /// Живой случай заказчика: «когда нас бьет боуторн, мы можем должны идти
    /// его убивать или прятаться». Боуторн стреляет издали, а рядом с ботом
    /// стоит дрифтер, которому до нас дела нет; прежний выбор «ближайший
    /// враждебный» брал именно дрифтера — и бот дрался не с тем.
    ///
    /// Имя существа считается ровно так же, как его считает сервер
    /// (Entity.GetPrefixAndCreatureName), по языковым файлам самой игры.
    ///
    /// НАЗВАННОГО НЕ ПОДМЕНЯЮТ. Правило — <see cref="CombatTargets.WhoToFight"/>
    /// (там же живой случай «беру bowtorn-surface» и разбор), здесь только
    /// перевод сущностей в имена и обратно да честные слова про отказ.
    /// </summary>
    private long? FindAttacker(EntityInfo self, DamageHit? hit, double radius)
    {
        // РЕЕСТРА ТИПОВ НЕТ — ВРАГА УЗНАТЬ НЕЧЕМ, И МОЛЧАТЬ ОБ ЭТОМ НЕЛЬЗЯ.
        //
        // С 27.08 узнавание врага держится на МЕТКАХ ИГРЫ (см.
        // <see cref="HostileTags"/>), а метки приезжают пакетом реестра.
        // Прежний рукописный список начал кодов работал и без него — и это была
        // единственная его сильная сторона, которую тут надо назвать вслух, а
        // не потерять молча: пока реестра нет, «врагов рядом нет» — это не
        // наблюдение, а слепота, и со стороны она выглядит как «бот стоит под
        // ударами и ничего не делает»
        if (ctx.EntityTypes is not { Ready: true } && NewsAbout("нет-реестра"))
            OnSay?.Invoke(
                "меня бьют, а врага узнать нечем: реестр типов сущностей от сервера ещё " +
                "не пришёл или не разобрался. Оборона узнаёт врага по меткам игры " +
                "(ручка «ВражескиеМетки»), а метки живут только в этом реестре");

        var around = ctx.Entities.Nearby(self.X, self.Y, self.Z, radius).ToList();

        // ИГРОК НАЗВАН ПО ИМЕНИ — и это ровно тот же запрет подмены: человек,
        // задевший бота стрелой из-за спины, не превращается в дрифтера
        if (hit is { From: DamageFrom.Player, Who: { Length: > 0 } player })
        {
            var who = around.FirstOrDefault(e => e.IsPlayer &&
                string.Equals(e.PlayerName, player, StringComparison.OrdinalIgnoreCase));
            if (who != null)
                return who.Id;
            if (NewsAbout($"недостать:{player}"))
                OnAttackerOutOfReach?.Invoke(player, radius);
            return null;
        }

        var hostiles = around
            .Where(e => IsHostile(e))
            .OrderBy(e => e.DistanceTo(self.X, self.Y, self.Z))
            .ToList();

        // Имя обидчика есть только тогда, когда сервер его СКАЗАЛ и у нас есть
        // чем прочитать имена тварей его же словами
        string? named = hit is { From: DamageFrom.Creature, Who: { Length: > 0 } who2 } &&
                        ctx.Damage?.Lang != null
            ? who2
            : null;
        var lang = ctx.Damage?.Lang;
        var names = hostiles
            .Select(e => lang?.CreatureName(e.Code) ?? "")
            .ToList();

        if (CombatTargets.WhoToFight(named, names) is { } pick)
            return hostiles[pick].Id;

        if (named is { Length: > 0 } missing && NewsAbout($"неопознан:{missing}"))
        {
            // БИТЬ НЕКОГО, И ОБ ЭТОМ НАДО СКАЗАТЬ. Молчание тут выглядит как
            // «бот стоит под обстрелом и ничего не делает». Слова разные:
            // рядом вообще пусто — одно дело, а «рядом есть кого ударить, но
            // это не он» — совсем другое, и второе как раз и есть та подмена,
            // из-за которой бот дрался не с тем
            if (hostiles.Count == 0)
                OnAttackerOutOfReach?.Invoke(missing, radius);
            else
                OnStrangeAttacker?.Invoke(missing, hostiles[0].Code);
        }
        return null;
    }

    // ======================================================================
    //  ЧИСЛА ДЛЯ РЕШЕНИЯ
    // ======================================================================

    /// <summary>Своя скорость бегом: то, что говорят игра и свои статы.</summary>
    private double MySpeed() => ctx.Movement.WalkSpeed * ctx.Movement.SprintMultiplier;

    /// <summary>
    /// ЛУК И СТРЕЛЫ ПРИ СЕБЕ И РОЛЬ РАЗРЕШИЛА СТРЕЛЯТЬ. Один вопрос на весь
    /// бой: его спрашивают и круг встречи, и решение «бежать ли безоружным»,
    /// и счёт вариантов — а два ответа на него разошлись бы молча.
    /// </summary>
    private bool BowReady() => UseBow && Bow.ShotDamage() > 0 && Bow.ArrowsCarried() > 0;

    /// <summary>
    /// С КАКОГО РАССТОЯНИЯ ВСТРЕЧАЕМ ВРАГА СЕГОДНЯ — по средствам, а не по
    /// одному числу. Правило живёт в <see cref="CombatReach.MeetFrom"/>, здесь
    /// только дверь к нему из способности.
    ///
    /// БРОНЯ ЭТОТ КРУГ НЕ СПРАШИВАЕТ, и это нарочно: она от ударов, а удары
    /// приходят вплотную (разбор — в <c>FitGearAsync</c>).
    /// </summary>
    private double MeetFrom() =>
        CombatReach.MeetFrom(DefendRadius, BowReady(), ShootMaxRange, MeetWithBow);

    /// <summary>
    /// Собрать всё, что бот честно знает о стычке. Ни одного выдуманного
    /// числа: сила его удара — ЗАМЕР из журнала урона, скорость — ЗАМЕР по
    /// присланным сервером положениям, здоровье и своё, и его — от сервера.
    /// </summary>
    /// <param name="shotHit">
    /// Урон одного попадания стрелой (лук + стрела по реестру). Ноль — стрелять
    /// нечем или роль сняла ручку «СтрелятьИзЛука».
    /// </param>
    /// <param name="arrows">Сколько стрел в сумках.</param>
    private CombatFacts Facts(EntityInfo self, EntityInfo enemy, double gap,
        double weaponPower, double engageLimit, double shotHit, int arrows,
        double footLimit = 14)
    {
        string? name = ctx.Damage?.Lang?.CreatureName(enemy.Code);
        // Про КОНКРЕТНОГО врага замера может ещё не быть — тогда берём худшее,
        // что вообще получали от живых, а если и того нет — запас. Считать его
        // удар нулевым нельзя ни при каких условиях: это объявило бы любой бой
        // бесплатным, и бот стоял бы под ударами незнакомой твари
        double? measured = ctx.Damage?.WorstHitFrom(name);
        double hisHit = measured ?? ctx.Damage?.WorstHitEver() ?? UnknownEnemyHit;
        double hisEvery = ctx.Damage?.HitEverySecondsFrom(name) ?? EnemySwingSeconds;

        // СКОРОСТЬ ЕГО: СПЕРВА ЗАМЕР, ПОТОМ ОБЪЯВЛЕННОЕ ИГРОЙ.
        //
        // Замер вернее — он про эту тварь здесь и сейчас, со снегом под ногами
        // и её нынешней задачей. Но замера может не быть вовсе: тварь, которая
        // стоит вплотную и бьёт, никуда не движется, и ждать от неё замера — это
        // ровно тот тупик 19.08, где разом отказали и погоня, и бегство («скорость
        // его ещё не мерил» дважды в одной строке). Тогда берётся число из
        // описания самой твари (см. CreatureSpeeds) — не догадка, а то самое, по
        // которому её двигает сервер
        double? paced = Pace.TopSpeed(enemy.Id, DateTime.UtcNow);

        return new CombatFacts
        {
            Gap = gap,
            Reach = AttackReach,
            MySpeed = MySpeed(),
            HisSpeed = paced ?? ctx.Speeds?.TopSpeed(enemy.Code),
            HisSpeedMeasured = paced != null,
            MyHealth = self.Health ?? 1,
            MyHit = weaponPower,
            MySwingSeconds = SwingIntervalMs / 1000.0,
            // ЛУК — ВТОРОЕ СРЕДСТВО, И ЕГО ЧИСЛА ТОЖЕ ФАКТЫ, А НЕ ДОГАДКИ:
            // урон складывает реестр сервера (лук + стрела), долю попадания
            // считает сам лук тем же счётом, каким решает, стрелять ли
            // (Archery.PlanShot — одно место на двоих), стрелы пересчитаны в
            // сумках. Доля спрашивается ТОЛЬКО когда выстрел вообще возможен:
            // луч зрения и наводка стоят дорого, а на «ближе СтрелятьНеБлижеЧем»
            // ответ всё равно один
            ShotHit = shotHit,
            Arrows = arrows,
            ShootMinRange = ShootMinRange,
            ShootMaxRange = ShootMaxRange,
            // ЦИКЛ ВЫСТРЕЛА СЧИТАЕМ ТЕМ ЖЕ НАТЯГОМ, КАКИМ СЧИТАЕТСЯ ТОЧНОСТЬ.
            // Здесь стояла сырая ручка «ТянутьТетивуСекунд», а доля попадания
            // бралась с ДОТЯНУТОГО натяга (Archery.PlanShot доводит его до
            // потолка точности сам): время от одного выстрела, точность от
            // другого. В трёх латных предметах потолок уезжает на 1,313 с, цикл
            // выходит 2,513 с против объявленных 2,1 — урон в секунду был
            // завышен в 1,197 раза, и броню бот в бою надевает сам
            ShotSeconds = Math.Max(0.1, Bow.DrawTime(DrawSeconds)) +
                          Math.Max(0.1, ShootIntervalSeconds),
            // ПОЯС ДАЛЬНОСТИ СПРАШИВАЕМ У ОБЩЕГО ПРАВИЛА, А НЕ ПЕРЕПИСЫВАЕМ
            // РУКОЙ. Здесь стояла вторая копия CombatFacts.CanShoot, набранная
            // заново, чтобы не звать наводку зря: поправь одну — вторая
            // отстанет молча (закон 2)
            ShotChance = CombatFacts.InShootingBand(shotHit, arrows, gap,
                                                    ShootMinRange, ShootMaxRange)
                ? Bow.ChanceFor(enemy, DrawSeconds)
                : -1,
            // ПОРОГ ДОЛИ — ТОТ ЖЕ, ЧТО СПРАШИВАЕТ САМ ЛУК. Без него счёт клал в
            // урон выстрелы, которые лук делать откажется
            MinShotChance = ShootMinChance,
            // «ЕСТЬ ЛИ ЧЕМ ВБЛИЗИ» — ОДНА МЕРКА НА СЧЁТ И НА ЛУК. Тем же
            // ответом лук снимает порог доли (Archery.LastResort), и разойдись
            // они — счёт запретил бы бой раньше, чем лук успел бы выстрелить
            HaveMelee = ctx.Weapons.IsWeapon((float)weaponPower),
            // ЗОВЁТ ЛИ ОН ПОДМОГУ — ПО КЛАССУ ИЗ РЕЕСТРА СЕРВЕРА, а не по имени
            // (см. CombatDanger.CallsForHelp: там разобрана задача AiTaskBellAlarm
            // и все её числа)
            SummonsHelp = RangedFirstForSummoners &&
                          CombatDanger.CallsForHelp(ctx.EntityTypes?.Get(enemy.Code)?.Class),
            HisHit = hisHit,
            HisHitMeasured = measured != null,
            HisHitSeconds = hisEvery,
            // ЗДОРОВЬЕ ВРАГА СЕРВЕР ПРИСЛАЛ НАВЕРНЯКА: в цели попадает только
            // тот, кому он его шлёт (IsHostile → CombatTargets.CanBeFought).
            // Прежнее «?? 12» было ТРЕТЬЕЙ догадкой об одном и том же
            // отсутствующем здоровье — той самой, что рисовала воткнутой стреле
            // двенадцать хп и «свалю за 4,1 с» (журнал 17.08, 23:50:21).
            // Сюда теперь не попасть; а если инвариант однажды сломают, счёт
            // обязан ошибиться В СТОРОНУ ОСТОРОЖНОСТИ — «этого не завалить»,
            // и бот отойдёт, вместо того чтобы махать по пустоте
            HisHealth = enemy.Health ?? UnfightableHealth,
            // Он бьёт МЕНЯ и это он: обиду мы записали на него же. Без этого
            // бегство от стрелка упиралось в порог расстояния
            UnderFire = attackerId == enemy.Id && DateTime.UtcNow < hurtUntil,
            // МЕНЯ БЬЮТ — БЕЗ ОГЛЯДКИ НА ТО, ОПОЗНАЛИ ЛИ ОБИДЧИКА. Строка выше
            // требует совпадения имён, а FindAttacker вправе вернуть null: тогда
            // бота избивают, а расчёт «до меня не дойти» держится, и все ответы
            // отвечают «нет пути». Отменять расчёт обязан сам ФАКТ урона
            ЯПодУдаром = DateTime.UtcNow < hurtUntil,
            // СТРЕЛЯТЬ ЛИ В НЕДОСТИЖИМОГО — решает РОЛЬ (заводское «нет»)
            ShootUnreachable = ShootWhoCannotReachMe,
            Reachable = Reachable(self, enemy, gap),
            // ...И ОБРАТНЫЙ ВОПРОС: ДОЙДЁТ ЛИ ОН ДО МЕНЯ. Тот, что выше, про МОИ
            // ноги — а дверь бот открывает сам, поэтому дорога к твари у него
            // есть почти всегда, и он к ней шёл. Заказчик: «не имеет смысл
            // агриться на врагов за стенами дома, если двери закрыты»
            HeReachesMe = HeReachesMe(self, enemy, gap),
            // ЧТО МЕЖДУ НАМИ — замер лучом, а не догадка (см. WhatSeparates).
            // Без этих двух строк весь запрет боя сквозь преграду был мёртв:
            // поля оставались в умолчании, Separated всегда false, и бот махал
            // оружием сквозь стену — ровно то, что заказчик просил запретить
            Barrier = WhatSeparates(enemy),
            // СПРЯТАЛСЯ Я НАРОЧНО или просто стою за стеной — разные вещи
            // (см. CombatFacts.Sheltered): преграда про мир, укрытие про
            // собственное решение бота, и оно держит его дома даже тогда, когда
            // луч преграды не увидел.
            //
            // Спрашивается ИМЕННО Hidden, а не WalledIn. Пока здесь стоял
            // WalledIn, из двух случаев заказчика доезжал только второй:
            // «замуровался в нише» — да, а «ушёл в дом и закрыл дверь» — нет,
            // потому что этот приём укрытия никакого признака не ставил вовсе
            Hiding = Refuge?.Hidden ?? false,
            EscapeRoutes = OpenSidesAroundFeet(),
            CanSeal = SealWhenCornered && Refuge?.AvailableWallMaterial() != null,
            SealMaxOpenSides = SealMaxOpenSides,
            FleeStart = FleeStartDistance,
            EscapeDistance = FleeDistance,
            EngageLimit = engageLimit,
            FootChaseLimit = footLimit,
            MaxChaseSeconds = RevengeChaseSeconds,
            MaxFleeSeconds = MaxFleeSeconds,
            // ЦЕНЫ ОТВЕТОВ ЕДУТ ИЗ РУЧЕК, А НЕ ИЗ КОНСТАНТ СЧЁТА. Иначе роль
            // могла повернуть только пороги расстояний, а «дорого ли бросить
            // дело» решала библиотека — одинаково для сторожа и для продавца
            FleePrice = FleePrice,
            SealPrice = SealPrice,
            IgnoreSeconds = IgnoreSeconds,
            // Сколько уже терплю — замер, а не решение (см. enduringSince)
            EnduredSeconds = enduringSince is { } с
                ? (DateTime.UtcNow - с).TotalSeconds
                : 0,
            FleeGainAtLeast = FleeGainAtLeast,
            Retreating = retreating
        };
    }

    /// <summary>
    /// ЕСТЬ ЛИ ДОРОГА МЕЖДУ НАМИ — спрашиваем поиск пути ДО того, как бежать.
    ///
    /// ВОПРОС ЗАДАН ПРО ТО, ОТКУДА МОЖНО БИТЬ, а не про клетку, занятую целью:
    /// разбор внизу, у самого вызова поиска. Коротко — «дойду ли я до него»
    /// значит «дойду ли на длину руки», и длина руки в бою одна на всех
    /// (<see cref="AttackReach"/>).
    ///
    /// Ровно этого не хватало живьём: погоня шла напрямик, упиралась в стену,
    /// движение записывало «тупик … запомнил, буду обходить» — и так
    /// семнадцать раз подряд, потому что решение «гонюсь» принималось заново
    /// каждые полсекунды и про стену не знало ничего.
    ///
    /// СПРАШИВАЮТ ЭТО ДВОЕ, И ОБА ПО ДЕЛУ: счёт вариантов (<c>Facts</c> →
    /// <c>CombatPlan</c>, «гнаться значит биться в стену») и САМА ПОГОНЯ — перед
    /// заходом и после того, как заход кончился ничем. Второго до 30.08 не
    /// было, и это и есть жалоба заказчика «в боевом режиме отключается наш
    /// поиск пути, просто бежал в стену бесконечно»: решение считалось раз в
    /// стычку, а бегал бот все двадцать секунд.
    ///
    /// НЕ ПУТАТЬ С <see cref="HeReachesMe"/>: тот вопрос — «заперт ли Я»
    /// (воздух вокруг себя), этот — «есть ли дорога МЕЖДУ НАМИ». Бот в поле,
    /// тварь за стеной: первый честно отвечает «дойдёт», и только второй умеет
    /// сказать, что ногам туда не пройти.
    ///
    /// Спрашиваем не чаще, чем раз в <see cref="PathCheckSeconds"/>: поиск
    /// пути дорог, а стена за секунду не исчезает. Кто узнал ногами, что ответ
    /// устарел, стирает его сам (<see cref="ForgetTheWay"/>).
    /// </summary>
    private bool Reachable(EntityInfo self, EntityInfo enemy, double gap)
    {
        // ОН УЖЕ ЗДЕСЬ — ВОПРОС О ДОРОГЕ СНЯТ. Полоса та же самая, что у
        // соседнего вопроса «дойдёт ли он до меня» (HeReachesMe), и это не
        // придирка к числу, а ЖИВАЯ БЕДА, найденная прогоном 30.08 в тот же
        // час, когда починка и писалась.
        //
        // ЖУРНАЛ ДОСЛОВНО. Буря, бот загнан, дерётся кулаками, дрифтер в 2,3 бл
        // — ровно на длине руки (AttackReach = 2,3). Расстояние дрогнуло на
        // сотую в большую сторону, ветка «догоняю» открылась, и здесь при
        // полосе «gap <= AttackReach» спрашивался ПОИСК ПУТИ — про клетку,
        // соседнюю с моей. Клетка твари стоячей не была, ответ вышел «дороги
        // нет», и бой ПРЕРВАЛСЯ на самом размене: «к drifter-normal не бегу:
        // дороги между нами нет (2,3 бл)». Бот в это время получал по 2,5 хп
        // за удар и вскоре умер.
        //
        // ПОЧЕМУ ЭТО НЕ ПОБЛАЖКА. Поиск пути отвечает КЛЕТКАМИ, а тут идти
        // некуда — полшага. Спрашивать маршрут о полушаге значит задавать
        // вопрос, на который у мерки нет ответа, и получать «нет» вместо
        // «незачем». Заказчик про это сказал прямо: тварь рядом — бей, не
        // считай маршруты.
        if (gap <= AttackReach + CombatPlan.MeleeSlack)
            return true;
        if (pathAskedAbout == enemy.Id &&
            (DateTime.UtcNow - pathAnsweredAt).TotalSeconds < PathCheckSeconds)
            return pathExists;

        pathAskedAbout = enemy.Id;
        pathAnsweredAt = DateTime.UtcNow;
        var from = new BlockPos((int)Math.Floor(self.X), (int)Math.Floor(self.Y), (int)Math.Floor(self.Z));
        var to = new BlockPos((int)Math.Floor(enemy.X), (int)Math.Floor(enemy.Y), (int)Math.Floor(enemy.Z));
        try
        {
            var options = ctx.Movement.PathOptions.Clone();
            // СПРАШИВАЕМ ПРО ТО, ОТКУДА МОЖНО БИТЬ, А НЕ ПРО КЛЕТКУ ПОД ТВАРЬЮ.
            //
            // ОТКАТ, НАЙДЕННЫЙ ПРИЁМКОЙ 31.08 НА ЭТОМ ЖЕ СТЕНДЕ: тварь отодвинули
            // с трёх блоков на шесть, и бот побежал ПРОЧЬ — «ПЛАН: Flee —
            // оторвусь за 2,8 с», замахов ноль, тело ушло на 8 бл. Снимешь эту
            // заставу — замахов 31, подход доходит и убивает. То есть умную
            // погоню запирал вопрос, заданный не о том.
            //
            // ПОЧЕМУ ГРУБЫЙ ВОПРОС ВРЁТ. «Полный ли маршрут В КЛЕТКУ САМОЙ
            // ТВАРИ» — вопрос, на который почти всегда «нет»: клетка занята
            // тварью, а над тварью то бревно, то плита, то притолока, то уступ.
            // Дрифтеру (1,3) там место есть, телу игрока (1,85) нет, и опора в
            // колонне цели уезжает НА КРЫШУ этого потолка — а туда ногами и
            // правда не залезть. Полоса «он уже здесь» выше спасала только
            // вплотную, дальше трёх блоков бот сдавался и уходил.
            //
            // БИТЬ МОЖНО НЕ ИЗ КЛЕТКИ ЦЕЛИ, А С ДЛИНЫ РУКИ — и длина руки в бою
            // давно есть одна, <see cref="AttackReach"/>. ВТОРОГО ПОНЯТИЯ НЕ
            // ЗАВЕДЕНО (закон 2): спрашиваем ТЕМ ЖЕ СРАВНЕНИЕМ, которым бой
            // решает «бить или догонять» (<c>dist > AttackReach</c> в самой
            // стычке). Ответ «дойду» здесь значит ровно одно: есть клетка, стоя
            // в которой бой сказал бы «он в руке».
            //
            // ПРИПУСКА НА РАЗМЕН ЗДЕСЬ НЕТ НАРОЧНО, И ЭТО ПРОВЕРЕНО ПРОГОНОМ, А
            // НЕ ВЫВЕДЕНО. С полосой «AttackReach + MeleeSlack» стенд «тварь на
            // столбе в три блока» (подножие в 3,2 бл от неё) давал вот что: бой
            // считал столб достижимым, подход честно перебирал всё, что умеет —
            // присед, обход с другой стороны, дальний крюк на 12 бл, подъём по
            // стене, — и стычка съедала 56 секунд на тварь, до которой хода
            // нет. Припуск здесь не «поблажка мерке», а лишние полкилометра
            // ногами.
            //
            // ЧАСТИЧНЫЙ ПУТЬ ТУТ НЕ ПОБЛАЖКА, А СПОСОБ СПРОСИТЬ. Поиск отдаёт
            // САМУЮ БЛИЗКУЮ К ЦЕЛИ клетку, до которой ноги доходят; дальше
            // решаем МЫ — достаю ли я оттуда. «Дошёл до стены в двух шагах»
            // (ради чего частичный путь и запрещали) на этом и отсеивается: за
            // стеной до твари остаётся четыре блока, а не длина руки.
            //
            // РАЗВЕДКА ЗДЕСЬ ЛИШНЯЯ И ВЫКЛЮЧЕНА НАРОЧНО: она отдаёт самую
            // ДАЛЬНЮЮ клетку, когда к цели не приблизиться ни на шаг, — это
            // ответ на другой вопрос («куда пойти осмотреться»), и бою он
            // сказал бы про место, которое к твари не ведёт вовсе
            options.AllowPartialPath = true;
            options.AllowExploration = false;
            pathExists = ctx.Movement.PathFinder.FindPath(ctx.World, from, to, options)
                is { Count: > 1 } path &&
                // Встать можно только в клетку целиком: считаем от её середины
                // и от уровня ног — оттуда бот и будет махать
                enemy.DistanceTo(path[^1].Pos.X + 0.5, path[^1].Pos.Y, path[^1].Pos.Z + 0.5)
                    <= AttackReach;
        }
        catch
        {
            // Поиск пути — не боевая механика; его беда не должна ронять бой.
            // Не смогли спросить — считаем, что дорога есть: так бот хотя бы
            // попробует, а про упор в стену скажет движение
            pathExists = true;
        }
        return pathExists;
    }

    /// <summary>
    /// ЗАБЫТЬ ОТВЕТ ПРО ДОРОГУ МЕЖДУ НАМИ.
    ///
    /// Зовётся ровно в одном случае и по факту, а не по часам: НОГИ ТОЛЬКО ЧТО
    /// УПЁРЛИСЬ. Тайник живёт <see cref="PathCheckSeconds"/> и в обычной жизни
    /// прав — стена за секунду не исчезает; но после упора он говорит «дорога
    /// есть» о том самом месте, где бот сейчас встал. Не сотри его — и второй
    /// вопрос вернёт первый ответ, то есть не будет вопросом вовсе.
    /// </summary>
    private void ForgetTheWay() => pathAskedAbout = -1;

    /// <summary>
    /// ДОБЕРЁТСЯ ЛИ ОН ДО МЕНЯ — спрашиваем НЕ его ноги, а МОИ СТЕНЫ: обводим
    /// воздух вокруг себя и смотрим, попал ли он внутрь (см.
    /// <see cref="CreatureReach"/>).
    ///
    /// ЗАКАЗ ДОСЛОВНО: «не имеет смысл агриться на врагов за стенами дома, если
    /// двери закрыты». Прежняя мерка его не ловила: преграду бот меряет ЛУЧОМ,
    /// а сквозь окно луч проходит — и бот бросал дело, надевал броню («42 %
    /// скорости и 72 % лишнего голода») и лез к твари через окно.
    ///
    /// ВТОРОГО ПОНЯТИЯ «Я ВНУТРИ ДОМА» ЗДЕСЬ НЕ ЗАВЕДЕНО, и это нарочно: дом,
    /// стены и двери бот не размечает — он спрашивает у мира то, что и так
    /// знает: сплошная ли клетка и заперта ли дверь (её состояние присылает
    /// сервер пакетом 48).
    ///
    /// ЧЕГО ЭТОТ ВОПРОС НЕ ЗАДАЁТСЯ:
    /// <list type="bullet">
    /// <item>когда роль сняла ручку «ДратьсяСТемиКтоДоМеняДойдёт»;</item>
    /// <item>когда он ВПЛОТНУЮ — тогда он уже дошёл, и спрашивать нечего;</item>
    /// <item>чаще, чем раз в <see cref="PathCheckSeconds"/>, и заново — только
    /// если я сам сошёл с клетки: стены за полторы секунды не переставляют.</item>
    /// </list>
    /// «НЕ ЗНАЮ» ВСЕГДА ЗНАЧИТ «ДОЙДЁТ»: область не замкнулась, мира нет, обход
    /// сломался — во всех этих случаях бот обязан считать врага опасным.
    /// Врать себе, что за стеной безопасно, нельзя ни при каком незнании.
    /// </summary>
    private bool HeReachesMe(EntityInfo self, EntityInfo enemy, double gap)
    {
        if (!OnlyWhoReachesMe)
            return true;
        if (gap <= AttackReach + CombatPlan.MeleeSlack)
            return true;   // он уже здесь — вопрос о дороге снят

        return AskHisWay(self, enemy) != CreatureReach.Verdict.Cannot;
    }

    /// <summary>
    /// САМ ВОПРОС: замкнулся ли воздух вокруг меня, и попал ли он внутрь.
    ///
    /// Рост твари решает ТОЛЬКО одно — сколько клеток по высоте примерять:
    /// дрифтеру (1,3) нужны две, и окно в одну клетку ему не проход, а ползуну
    /// (0,6) хватает одной. Больше ни шаг, ни лазанье, ни полёт здесь ни при
    /// чём: сквозь блок не проходит никто.
    /// </summary>
    private CreatureReach.Verdict AskHisWay(EntityInfo self, EntityInfo enemy)
    {
        try
        {
            int клеток = CreatureReach.КлетокПоВысоте(ЕгоРост(enemy));
            var моя = ctx.World.StandingCellAt(self.X, self.Y, self.Z);
            var место = МоёМесто(клеток, моя);
            if (!место.Замкнулось)
            {
                // ГОВОРИМ ВСЛУХ И ОДИН РАЗ: молчаливое «дойдёт» человек не
                // отличит от «правило не работает», а объяснение ему нужно
                // ровно тогда, когда бот дерётся с тем, кого «не должен» замечать
                if (NewsAbout($"не-заперт:{клеток}"))
                    OnSay?.Invoke($"считаю, что дойдёт: моё место не заперто — обошёл " +
                                  $"{место.Осмотрено} клет. вокруг себя и стен со всех сторон " +
                                  "не нашёл (ручка «СколькоКлетокСмотретьПроЗапертоеМесто»)");
                return CreatureReach.Verdict.Unknown;
            }

            var его = ctx.World.StandingCellAt(enemy.X, enemy.Y, enemy.Z);
            if (место.Внутри(его.X, его.Y, его.Z))
                return CreatureReach.Verdict.Comes;

            if (NewsAbout($"заперт:{enemy.Code}"))
                OnSay?.Invoke($"{enemy.Code} до меня не дойдёт: я в запертом месте " +
                              $"({место.Осмотрено} клет.), а его тут нет — сквозь стены и " +
                              "закрытые двери не проходит никто");
            return CreatureReach.Verdict.Cannot;
        }
        catch
        {
            // Обход воздуха — не боевая механика; его беда не должна ни ронять
            // бой, ни объявлять врага безопасным
            return CreatureReach.Verdict.Unknown;
        }
    }

    /// <summary>
    /// МОЁ МЕСТО, обойденное не чаще раза в <see cref="PathCheckSeconds"/> и
    /// заново — как только я сошёл с клетки.
    ///
    /// Клетка в ключе не для скорости, а ради правды: сделал шаг за порог — и
    /// прежний ответ «я заперт» стал ложью в опасную сторону.
    /// </summary>
    private CreatureReach.Место МоёМесто(int клеток, BlockPos моя)
    {
        var сейчас = DateTime.UtcNow;
        if (места.TryGetValue(клеток, out var было) && было.Откуда.Equals(моя) &&
            (сейчас - было.Когда).TotalSeconds < PathCheckSeconds)
            return было.Место;

        var место = CreatureReach.Обвести(ctx.World, моя.X, моя.Y, моя.Z, клеток,
            Math.Max(1, ReachSearchNodes));
        места[клеток] = (сейчас, моя, место);
        return место;
    }

    /// <summary>
    /// РОСТ ЭТОЙ ТВАРИ, блоков — из реестра типов, пришедшего с сервера, плюс
    /// поправка на краулер-дрифтера (он ниже своего же типа).
    ///
    /// Реестра нет — отдаём 0, а <see cref="CreatureReach.КлетокПоВысоте"/>
    /// превращает его в ОДНУ клетку: незнание обязано делать тварь мельче и
    /// пролазнее, а не запирать её снаружи.
    /// </summary>
    private double ЕгоРост(EntityInfo enemy)
    {
        var тип = ctx.EntityTypes?.Get(enemy.Code);
        if (тип == null)
            return 0;

        // КАЖДЫЙ ПЯТЫЙ ДРИФТЕР — ПОЛЗУН, и решает это НОМЕР сущности, а не тип.
        // Правило игры дословно: EntityDrifter.Initialize, EntityId % oddsToAlter
        if (CreatureReach.ВысотаПолзуна(тип.Attributes, enemy.Id) is > 0 and var ползун)
            return ползун;
        return тип.Collision?.Height ?? 0;
    }

    /// <summary>
    /// ЧТО МЕЖДУ НАМИ: дверь, блоки или ничего.
    ///
    /// ЗАЧЕМ. Дословно от заказчика: «не лезть в бой если ты в доме с закрытой
    /// дверью (вас разделяет дверь или блоки), ты спрятался от шторма и вас
    /// разделяют блоки или дверь». Счёт вариантов (<see cref="CombatPlan"/>)
    /// это давно умеет, но факт ему НИКТО НЕ ПОДАВАЛ: поле оставалось в
    /// умолчании, и все пять караулов молчали. Живьём это выглядело так:
    /// дрифтер за стеной в двух блоках попадает под «он вплотную» (2,3 бл), и
    /// бот машет оружием сквозь блок; а если тот подальше — бот САМ ВЫХОДИТ из
    /// вырытого укрытия его обходить.
    ///
    /// Сам луч считает <see cref="Sight.LookAtCreature"/> — ровно тем же
    /// способом, что игра (три высоты, хватает одного чистого луча). Здесь
    /// только перевод «во что упёрлись» в вид преграды: дверь бот открывать
    /// умеет, а тварь нет, и слова отказа для них разные.
    /// </summary>
    private CombatBarrier WhatSeparates(EntityInfo enemy)
    {
        var seen = ctx.Hands?.Sight.LookAtCreature(enemy.X, enemy.Y, enemy.Z);
        // Считать было нечем (реестр блоков не пришёл, позиции нет) либо луч
        // прошёл — преграды НЕ ПРИДУМЫВАЕМ. Стена, которой не видели, — это
        // такой же обман, как удар сквозь неё
        if (seen is not { Known: true, Visible: false, BlockedBy: { } cell })
            return CombatBarrier.None;

        // Открытая дверь преградой не считается: сквозь проём достают оба.
        // Мультиблок-верх двери IsDoor тоже узнаёт (DoorAt идёт к хозяину)
        if (ctx.World.IsDoor(cell.X, cell.Y, cell.Z))
            return ctx.World.IsDoorOpen(cell.X, cell.Y, cell.Z)
                ? CombatBarrier.None
                : CombatBarrier.Door;
        return CombatBarrier.Blocks;
    }

