    /// ЧИСТОЕ ПРАВИЛО ДВУХ ПОРОГОВ ЗДОРОВЬЯ — одно на все роли.
    ///
    /// Пороги эти РОЛЕВЫЕ (сторожу один, охотнику другой), но связаны они
    /// намертво: «возвращаться в бой» ниже «отступать» означает выходить из
    /// отступления прямо в него же. Живьём это тот самый круг «подрался —
    /// убежал — подрался», от которого бот не успевает ни идти, ни лечиться.
    ///
    /// Правило лежит ЗДЕСЬ, а не по копии в каждой роли: копий было бы
    /// столько же, сколько ролей, и однажды одна из них разошлась бы с
    /// остальными. Жалоба возвращается словами — молча поправить вписанное
    /// человеком число значило бы оставить его думать, что настройка стоит.
    /// </summary>
    /// <returns>Что ставить и на что жаловаться (null — жаловаться не на что).</returns>
    public static (double Retreat, double Resume, string? Complaint) HealthGates(
        double retreat, double resume)
    {
        double bar = Math.Clamp(retreat, 0, 1);
        double back = Math.Clamp(resume, 0, 1);
        if (back >= bar)
            return (bar, back, null);
        return (bar, bar,
            $"возвращаться в бой при {back:P0} здоровья нельзя: отступаю я ниже {bar:P0} " +
            $"и вышел бы из отступления прямо в него же — беру {bar:P0}");
    }

