    /// <summary>
    /// Как часто повторять одну и ту же НОВОСТЬ О СОСТОЯНИИ, секунд.
    ///
    /// Одна мерка на все такие новости боя, и заглушка одна на всех
    /// (<see cref="LogRepeats"/>, та же, что у движения и добычи). Раньше здесь
    /// стояли ДВЕ рукописные заглушки со своими полями и своими числами — по
    /// одной на строку. Это ровно то, что запрещает правило 1 проекта: третья
    /// такая же строка потребовала бы третьей заглушки, и однажды её бы забыли.
    /// </summary>
    public double QuietRepeatSeconds
    {
        get => repeats.QuietSeconds;
        set => repeats.QuietSeconds = value;
    }

    // Тридцать секунд, а не десять: в бою эти строки не про беду, а про
    // обстановку («вижу, но не лезу»), и повторять их чаще незачем
    private readonly LogRepeats repeats = new() { QuietSeconds = 30 };

    /// <summary>
    /// СОСТОЯНИЕ — ЭТО НЕ СОБЫТИЕ, и говорить о нём надо ОДИН РАЗ.
    ///
    /// Способность тикает дважды в секунду. «Телом распоряжается укрытие» и
    /// «drifter в 20 бл — далеко» верны всё это время: пока не изменилось,
    /// новостей нет. Без заглушки за двадцать секунд бури набегало сорок
    /// одинаковых строк, и вместе с тридцатью «тупик …» из движения они и
    /// составляли тот журнал, в котором заказчик не смог разглядеть настоящей
    /// беды.
    ///
    /// Ключ — то, ЧТО именно за состояние (хозяин тела, противник): изменилось —
    /// строка выходит СРАЗУ, не дожидаясь конца заглушки. Это и есть «повтор
    /// только если что-то изменилось».
    ///
    /// Числа повторов тут нарочно нет: считать, сколько раз состояние осталось
    /// прежним, — то же самое, что считать тики.
    /// </summary>
    private bool NewsAbout(string key) => repeats.Say(key, DateTime.UtcNow) != null;

    /// <summary>
    /// МЕТКА, КОТОРОЙ У ИГРЫ НЕТ, — ЭТО ОПЕЧАТКА, И О НЕЙ ГОВОРЯТ ВСЛУХ.
    ///
    /// ЖИВАЯ ЦЕНА МОЛЧАНИЯ. Метки набирает человек в ручке «ВражескиеМетки».
    /// Вписал «Ferocious» с большой буквы или «rust_creature» через нижнее
    /// подчёркивание — и бот МОЛЧА переставал считать врагом волка: сверка шла
    /// с оглядкой на регистр, а пожаловаться было некому. Регистр мы теперь
    /// прощаем (см. <see cref="HostileRules.Enemy"/>), а вот саму опечатку
    /// простить нельзя — её надо назвать, потому что повернуть ручку обратно
    /// может только человек (закон 4).
    ///
    /// Спрашиваем ТОЛЬКО когда реестр уже пришёл: до него пустой список меток
    /// значит «я их ещё не видел», а не «таких меток не бывает», и жалоба на
    /// каждую метку подряд была бы враньём.
    /// </summary>
    private void ПроверитьМеткиРоли()
    {
        if (ctx.EntityTypes is not { Ready: true } types)
            return;
        var известные = types.TagNames;
        if (известные.Count == 0)
            return;
        foreach (var метка in HostileTags)
        {
            if (известные.Contains(метка) || !NewsAbout($"метка-мимо:{метка}"))
                continue;
            OnSay?.Invoke(
                $"в ручке «ВражескиеМетки» стоит «{метка}», а такой метки сервер не " +
                $"присылал вовсе — по ней я не узнаю никого. Метки игры пишутся " +
                $"строчными и через дефис (например «rust-creature», «ferocious»)");
        }
    }

