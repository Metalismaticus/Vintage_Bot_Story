    /// <summary>
    /// Что бот делает после побега. Здесь и только здесь ставятся защёлки:
    /// сам побег их не трогает, чтобы «чем кончилось» и «что теперь» не
    /// расползлись по двум местам.
    /// </summary>
    private void ApplyFleeOutcome(FleeReport report)
    {
        switch (report.Outcome)
        {
            case FleeOutcome.Escaped:
            case FleeOutcome.ChaserGone:
                // Оторвался — отпускаем и цель, и тело. Затишье не даёт
                // начать всё сначала через полсекунды
                calmUntil = DateTime.UtcNow.AddSeconds(FleeCalmSeconds);
                attackerId = null;
                break;
            case FleeOutcome.Sealed:
                // За блоком можно постоять: пробьётся — ударит, и затишье
                // снимется само (см. TickAsync)
                calmUntil = DateTime.UtcNow.AddSeconds(SealedCalmSeconds);
                break;
            case FleeOutcome.Fighting:
                // Не оторвался и закладываться нечем — принимаем бой тем,
                // что есть. «В углу» на CorneredSeconds отключает бегство,
                // иначе следующий же тик снова пошлёт бота бежать
                corneredUntil = DateTime.UtcNow.AddSeconds(CorneredSeconds);
                break;
            case FleeOutcome.Interrupted:
                break;   // тело забрал кто-то важнее — ему и решать
        }
    }

    /// <summary>
    /// Отскок после удара: пятимся СПИНОЙ, не отворачиваясь от врага, с
    /// подпрыжкой назад. Дистанцируемся не от одного противника, а от ВСЕХ
    /// враждебных рядом — стоя между двумя мобами, отходить надо от обоих.
    /// </summary>
    private async Task StepBackAsync(EntityInfo self, long enemyId, CancellationToken ct)
    {
        var phys = ctx.Body?.Physics;
        if (phys == null)
            return;

        var until = DateTime.UtcNow.AddMilliseconds(900);
        bool hopped = false;
        try
        {
            while (!ct.IsCancellationRequested && DateTime.UtcNow < until)
            {
                // Куда отходить: сумма «от каждого врага», ближние весомее
                double awayX = 0, awayZ = 0;
                EntityInfo? nearest = null;
                double nearestDist = double.MaxValue;
                foreach (var h in ctx.Entities.Nearby(phys.X, phys.Y, phys.Z, HurtResponseRadius)
                             .Where(e => IsHostile(e)))
                {
                    double dx = phys.X - h.X, dz = phys.Z - h.Z;
                    double d = Math.Max(0.3, Math.Sqrt(dx * dx + dz * dz));
                    awayX += dx / (d * d);
                    awayZ += dz / (d * d);
                    if (d < nearestDist)
                    {
                        nearestDist = d;
                        nearest = h;
                    }
                }
                if (nearest == null)
                    break;
                double len = Math.Sqrt(awayX * awayX + awayZ * awayZ);
                if (len < 0.001 || nearestDist >= KiteDistance)
                    break; // оторвались

                awayX /= len;
                awayZ /= len;

                // ПОД НОГАМИ СЗАДИ ДОЛЖНА БЫТЬ ЗЕМЛЯ. Пятясь вслепую, бот
                // срывался в пропасть и падал в воду прямо посреди боя.
                // Некуда отходить — лучше стоять и драться, чем упасть
                if (!SafeToStepBack(phys, awayX, awayZ))
                {
                    phys.Controls.Backward = false;
                    phys.Controls.Jump = false;
                    break;
                }

                // Спиной назад, лицом к ближайшему; в начале — прыжок назад
                phys.BackpedalFrom(nearest.X, nearest.Z);
                // Прыгать назад можно только с земли и только если приземлимся
                // на землю: прыжок над обрывом — это полёт в обрыв
                if (!hopped && phys.OnGround && SafeToStepBack(phys, awayX * 2, awayZ * 2))
                {
                    phys.Controls.Jump = true;
                    hopped = true;
                }
                else
                {
                    phys.Controls.Jump = false;
                }
                await Task.Delay(50, ct);
            }
        }
        catch (OperationCanceledException) { }
        finally
        {
            phys.Controls.Backward = false;
            phys.Controls.Jump = false;
        }
    }


    /// <summary>
    /// Можно ли отступить в эту сторону, не убившись: под ногами должна быть
    /// опора не ниже безопасного спрыгивания, и это не должна быть вода или
    /// лава. Проверяем клетку, куда шагнём (на ширину тела вперёд).
    /// </summary>
    private bool SafeToStepBack(BotGamePhysics.GamePlayerPhysics phys, double ux, double uz)
    {
        int x = (int)Math.Floor(phys.X + ux * 0.9);
        int z = (int)Math.Floor(phys.Z + uz * 0.9);
        int y = (int)Math.Floor(phys.Y + 0.01);

        if (ctx.World.IsDangerousLiquid(x, y, z))
            return false;
        // Вода тоже беда: в бою бот тонет, а не плавает
        if (ctx.World.IsWater(x, y, z) || ctx.World.IsWater(x, y - 1, z))
            return false;
        // Опора: своя клетка или не глубже безопасного спуска
        for (int dy = 0; dy <= SafeBackStepDrop; dy++)
            if (ctx.World.IsStandable(x, y - dy, z))
                return true;
        return false;
    }

    /// <summary>На сколько блоков вниз бот готов отступить (без урона).</summary>
    public int SafeBackStepDrop { get; set; } = 2;

    /// <summary>
    /// БЕГСТВО ЦЕЛИКОМ, от начала до конца, за одно владение телом.
    ///
    /// Так это и должно выглядеть у живого игрока: он разворачивается, бежит
    /// туда, где есть куда бежать, и либо отрывается, либо упирается в тупик и
    /// закладывается — но не «дёргается» каждые полсекунды, отбирая у себя же
    /// дорогу. Прежний побег возвращался через миг, и рефлекс начинал его
    /// заново семьдесят раз за полминуты (журнал 23:50:37-23:51:05).
    ///
    /// Возвращает ЧЕСТНЫЙ итог с числами — по нему говорится вторая (и
    /// последняя) строка про этот побег.
    /// </summary>
    private async Task<FleeReport> FleeFromAsync(EntityInfo enemy, FleeReason reason,
        double healthFraction, string weapon, CancellationToken ct)
    {
        var began = DateTime.UtcNow;
        double from = ctx.Entities.Self is { } start
            ? enemy.DistanceTo(start.X, start.Y, start.Z)
            : 0;

        OnFleeFrom?.Invoke(new FleeStart(enemy.Code, from, reason, healthFraction, weapon));

        var deadline = began.AddSeconds(MaxFleeSeconds);
        int legs = 0, wasted = 0;
        double last = from;
        (double X, double Z)? stood = null;

        FleeReport Done(FleeOutcome outcome) => new(outcome, enemy.Code, from, last,
            (DateTime.UtcNow - began).TotalSeconds, legs, wasted);

        try
        {
            while (DateTime.UtcNow < deadline)
            {
                if (ct.IsCancellationRequested)
                    return Done(FleeOutcome.Interrupted);
                if (ctx.Entities.Self is not { } me)
                    return Done(FleeOutcome.Interrupted);   // тела нет — бежать нечем
                // «Гнаться больше некому» — это исчез из мира ЛИБО сервер
                // прислал ему нуль здоровья. Прежнее «(Health ?? 0) <= 0»
                // считало погоню законченной и тогда, когда здоровья не
                // прислали вовсе, — та же догадка, что объявляла стрелу
                // поверженной. Правило теперь одно на весь бой
                if (ctx.Entities.Get(enemy.Id) is not { } chaser ||
                    CombatTargets.Defeated(chaser.Health))
                    return Done(FleeOutcome.ChaserGone);

                last = chaser.DistanceTo(me.X, me.Y, me.Z);
                if (FleeRules.Decide(last, FleeStartDistance, FleeDistance, running: true)
                    == FleeVerdict.Escaped)
                    return Done(FleeOutcome.Escaped);

                // «Загнан в угол» — это НЕ МОГУ СДВИНУТЬСЯ, а не «догоняют».
                // От быстрого моба дистанция не растёт никогда, и по прежнему
                // критерию бот сдавался сразу — потому и «не пытался убежать».
                // Смотрим на СВОЁ перемещение: бежит — значит отход работает
                if (stood is { } prev &&
                    FleeRules.RunFailed(Flat(me.X - prev.X, me.Z - prev.Z), MinFleeStep))
                {
                    if (++wasted >= FailedRunsBeforeCornered)
                        return await CorneredAsync(chaser, Done, ct);
                }
                else if (stood != null)
                {
                    wasted = 0;
                }

                stood = (me.X, me.Z);
                legs++;
                await RunOneLegAsync(me, chaser, ct);
            }

            // Время вышло, а разрыва нет. Бесконечно бегать нельзя: это и есть
            // «затупил и бегал». Оторваться не выходит — решаем как в углу
            return await CorneredAsync(ctx.Entities.Get(enemy.Id) ?? enemy, Done, ct);
        }
        catch (OperationCanceledException)
        {
            return Done(FleeOutcome.Interrupted);
        }
    }

    private static double Flat(double dx, double dz) => Math.Sqrt(dx * dx + dz * dz);

    /// <summary>
    /// Один рывок побега: пробуем несколько направлений ПРОЧЬ ОТ ВРАГА и
    /// выбираем то, куда есть куда ступить.
    ///
    /// Почему не «беги по прямой»: под землёй прямо от дрифтера обычно стена,
    /// и бот честно бежал в неё. Живой игрок в такой момент смотрит, куда
    /// вообще ведёт ход, и уходит туда — пусть и вбок. Дорогу за нас считает
    /// поиск пути: если маршрута в ту сторону нет, он так и скажет, и мы
    /// пробуем следующую.
    ///
    /// Итог рывка тут НЕ ВОЗВРАЩАЕТСЯ намеренно: удался он или нет, видно по
    /// тому, НА СКОЛЬКО СДВИНУЛОСЬ ТЕЛО (см. RunFailed), а не по слову поиска
    /// пути — он считает успехом и «дошёл до преграды в двух шагах».
    /// </summary>
    private async Task RunOneLegAsync(EntityInfo me, EntityInfo chaser, CancellationToken ct)
    {
        int tried = 0;
        int fromY = (int)Math.Floor(me.Y);
        foreach (var (x, z) in FleeRules.RunPoints(me.X, me.Z, chaser.X, chaser.Z, FleeLeg))
        {
            if (tried >= FleeTriesPerLeg || ct.IsCancellationRequested)
                break;
            int cx = (int)Math.Floor(x), cz = (int)Math.Floor(z);
            if (ctx.World.FindStandableY(cx, fromY, cz, up: 12, down: 12) is not { } y)
                continue;   // пола нет — это не дорога, а стена или обрыв
            // Вода не спасение, а утопление: в ней бот медленнее моба
            if (ctx.World.IsWater(cx, y, cz) || ctx.World.IsDangerousLiquid(cx, y, cz))
                continue;
            tried++;
            if (await ctx.Movement.MoveToCellAsync(new BlockPos(cx, y, cz), ct))
                return;   // побежали — дальше смотрим уже по факту перемещения
        }
    }

    /// <summary>
    /// Бежать некуда. Два честных выхода, и оба — то, что делает живой игрок:
    /// заложить за собой проход блоком, если есть чем и место узкое, либо
    /// принять бой тем, что в руках, и сказать об этом вслух.
    /// </summary>
    private async Task<FleeReport> CorneredAsync(EntityInfo chaser,
        Func<FleeOutcome, FleeReport> done, CancellationToken ct)
    {
        OnCornered?.Invoke();

        int open = OpenSidesAroundFeet();
        bool haveBlocks = Refuge?.AvailableWallMaterial() != null;
        if (FleeRules.PlanWhenCornered(SealWhenCornered, haveBlocks, open, SealMaxOpenSides)
            == CorneredPlan.Seal && await SealTowardAsync(chaser, ct))
            return done(FleeOutcome.Sealed);

        return done(FleeOutcome.Fighting);
    }

    /// <summary>
    /// Заложить клетку между собой и преследователем — на уровне ног и головы.
    ///
    /// Своего «поставь блок» тут нет: материал выбирает укрытие (оно же
    /// закладывает вход в бурю), ставит добыча — по правилам игры, с
    /// подтверждением от сервера. Не вышло — значит не заложился, и врать об
    /// этом нельзя.
    /// </summary>
    private async Task<bool> SealTowardAsync(EntityInfo chaser, CancellationToken ct)
    {
        if (Refuge is not { } refuge || refuge.AvailableWallMaterial() is not { } material)
            return false;
        if (ctx.Entities.Self is not { } me)
            return false;

        var (sx, sz) = FleeRules.SideToward(chaser.X - me.X, chaser.Z - me.Z);
        int fx = (int)Math.Floor(me.X) + sx;
        int fz = (int)Math.Floor(me.Z) + sz;
        int fy = (int)Math.Floor(me.Y + 0.01);

        // Низ не встал — верх ставить незачем: под ним всё равно останется
        // дыра, а блок потрачен. Чаще всего низ не встаёт как раз потому, что
        // в этой клетке стоит сам преследователь — тогда закладываться поздно
        if (!(await ctx.Mining.PlaceAsync(new BlockPos(fx, fy, fz), material, ct: ct)).Success)
            return false;
        return (await ctx.Mining.PlaceAsync(new BlockPos(fx, fy + 1, fz), material, ct: ct)).Success;
    }

    /// <summary>
    /// Сколько сторон вокруг ног открыто. Мерка «узкого места»: в штольне их
    /// одна-две, и заложиться там имеет смысл; в чистом поле — четыре, и
    /// блок в одну сторону только тратит камень и время.
    /// </summary>
    private int OpenSidesAroundFeet()
    {
        if (ctx.Entities.Self is not { } me)
            return 4;
        int x = (int)Math.Floor(me.X), z = (int)Math.Floor(me.Z);
        int y = (int)Math.Floor(me.Y + 0.01);
        int open = 0;
        foreach (var (dx, dz) in ((int, int)[])[(1, 0), (-1, 0), (0, 1), (0, -1)])
            if (ctx.World.IsPassable(x + dx, y, z + dz))
                open++;
        return open;
    }

    /// <summary>
    /// Лучшее оружие в хотбаре: слот, код и БОЕВАЯ ценность. Инструмент
    /// (кирка, лопата, топор) — не оружие: урон у него есть, но драться им
    /// всё равно что не драться, поэтому его ценность режется вдвое.
    /// </summary>
    private (int Slot, string? Code, float Power) FindBestWeapon()
    {
        var hotbar = ctx.Self.GetInventory("hotbar");
        if (hotbar == null)
            return (-1, null, 0);

        int bestSlot = -1;
        string? bestCode = null;
        float bestPower = 0;
        for (int i = 0; i < hotbar.Length && i < 10; i++)
        {
            if (hotbar[i].Code is not { } code)
                continue;
            float power = ctx.Weapons.PowerOf(ctx.World, code);
            if (power > bestPower)
            {
                bestPower = power;
                bestSlot = i;
                bestCode = code;
            }
        }
        return (bestSlot, bestCode, bestPower);
    }
}

/// <summary>Что делать с врагом прямо сейчас (см. FleeRules.Decide).</summary>
public enum FleeVerdict
{
    /// <summary>Далеко — не наше дело, пусть роль работает.</summary>
    Ignore,

    /// <summary>Бежать.</summary>
    Run,

    /// <summary>Оторвались — тело можно отпускать.</summary>
    Escaped
}

/// <summary>Чем кончился побег.</summary>
public enum FleeOutcome
{
    /// <summary>Разрыв набран, преследователь позади.</summary>
    Escaped,

    /// <summary>Преследователь пропал или погиб.</summary>
    ChaserGone,

    /// <summary>Оторваться не вышло — заложился блоком.</summary>
    Sealed,

    /// <summary>Оторваться не вышло и закладываться нечем — принимаю бой.</summary>
    Fighting,

    /// <summary>Тело забрали посреди побега (смерть, буря, приказ).</summary>
    Interrupted
}

/// <summary>Почему бот вообще побежал.</summary>
public enum FleeReason
{
    /// <summary>Драться нечем: настоящего оружия в хотбаре нет.</summary>
    Unarmed,

    /// <summary>Здоровья мало: размен ударов — верная смерть.</summary>
    LowHealth
}

/// <summary>Как разбираться, когда бежать некуда.</summary>
public enum CorneredPlan
{
    /// <summary>Заложить проход блоком.</summary>
    Seal,

    /// <summary>Принять бой тем, что есть.</summary>
    Fight
}

/// <summary>Начало побега: от кого, с какого расстояния, почему и с чем в руках.</summary>
public sealed record FleeStart(string Enemy, double Distance, FleeReason Reason,
    double HealthFraction, string Weapon);

/// <summary>
/// Итог побега с числами: было — стало — за сколько — сколькими рывками
/// (и сколько из них впустую).
/// </summary>
public sealed record FleeReport(FleeOutcome Outcome, string Enemy, double From, double To,
    double Seconds, int Legs, int Wasted);

/// <summary>
/// Чистые правила бегства. Здесь нет ни мира, ни сети — только счёт, и
/// поэтому всё это закрыто тестами (VsBotKit.Tests/FleeTests.cs).
///
/// Сюда вынесено ровно то, на чём бот погорел живьём: когда бежать начинать,
/// когда считать себя оторвавшимся, куда именно бежать и что делать, когда
/// бежать некуда.
/// </summary>
public static class FleeRules
{
    /// <summary>
    /// Бежать ли сейчас. ДВА РАЗНЫХ ПОРОГА, и в этом весь смысл.
    ///
    /// Живой случай: порог был один (18 блоков) и служил сразу и началом, и
    /// концом побега. Дрифтер стоял в двадцати с лишним блоках — бот решал
    /// «убегаю», тут же видел «до него и так больше восемнадцати», кончал
    /// побег и через полсекунды начинал заново. Семьдесят строк за полминуты
    /// и ни шага по дороге.
    ///
    /// Правильно так: пока не бежим — трогаемся с места, только если подпустил
    /// ближе <paramref name="startDistance"/>; уже бежим — не бросаем, пока не
    /// набрали <paramref name="escapeDistance"/>.
    /// </summary>
    public static FleeVerdict Decide(double distance, double startDistance,
        double escapeDistance, bool running)
    {
        if (running)
            return distance >= escapeDistance ? FleeVerdict.Escaped : FleeVerdict.Run;
        return distance <= startDistance ? FleeVerdict.Run : FleeVerdict.Ignore;
    }

    /// <summary>
    /// Рывок пропал впустую: бот сдвинулся меньше, чем на шаг. Мерка именно
    /// СВОЕГО перемещения — разрыв с быстрым мобом не растёт никогда, и по
    /// нему бот сдавался, ещё не начав бежать.
    /// </summary>
    public static bool RunFailed(double moved, double minStep) => moved < minStep;

    /// <summary>
    /// Куда бежать: точки в одном рывке от бота, первая — точно прочь от
    /// врага, дальше веером в обе стороны.
    ///
    /// Веер нужен под землёй: прямо от дрифтера чаще всего стена, а ход ведёт
    /// вбок. Какая из точек годится, решает уже мир (есть ли куда ступить и
    /// ведёт ли туда дорога) — здесь только счёт.
    /// </summary>
    public static IReadOnlyList<(double X, double Z)> RunPoints(double x, double z,
        double fromX, double fromZ, double leg)
    {
        double dx = x - fromX, dz = z - fromZ;
        double len = Math.Sqrt(dx * dx + dz * dz);
        if (len < 0.01)
        {
            // Стоим ровно на враге (так бывает, когда моб влез в нас):
            // направление всё равно нужно, берём любое
            dx = 1;
            dz = 0;
            len = 1;
        }
        dx /= len;
        dz /= len;

        var points = new List<(double X, double Z)>();
        foreach (double turn in FanAngles)
        {
            double sin = Math.Sin(turn), cos = Math.Cos(turn);
            double ux = dx * cos - dz * sin;
            double uz = dx * sin + dz * cos;
            points.Add((x + ux * leg, z + uz * leg));
        }
        return points;
    }

    /// <summary>
    /// Веер направлений в радианах: прямо прочь, потом всё круче вбок.
    ///
    /// Крайние ±1.8 (около ста десяти градусов) — это уже «мимо врага вбок»,
    /// и дальше разворачивать нельзя: при рывке в восемь блоков любая точка
    /// веера обязана оказаться ДАЛЬШЕ от преследователя, чем бот стоит сейчас,
    /// иначе «побег» подводит его под удар.
    /// </summary>
    private static readonly double[] FanAngles =
        [0, 0.6, -0.6, 1.2, -1.2, 1.8, -1.8];

    /// <summary>
    /// В какую из четырёх сторон смотрит враг: по большей из проекций.
    /// Клетка блока одна, и заложить наискосок нельзя — приходится выбирать.
    /// </summary>
    public static (int X, int Z) SideToward(double dx, double dz) =>
        Math.Abs(dx) >= Math.Abs(dz)
            ? (dx >= 0 ? 1 : -1, 0)
            : (0, dz >= 0 ? 1 : -1);

    /// <summary>
    /// Закладываться или драться. Блок в проход имеет смысл только там, где
    /// проход один-два: в чистом поле моб обойдёт его за полсекунды, а камень
    /// и время потрачены.
    /// </summary>
    public static CorneredPlan PlanWhenCornered(bool sealAllowed, bool haveBlocks,
        int openSides, int maxOpenSides) =>
        sealAllowed && haveBlocks && openSides <= maxOpenSides
            ? CorneredPlan.Seal
            : CorneredPlan.Fight;

    /// <summary>Одна строка на начало побега — с числами, а не «убегаю».</summary>
    public static string Say(FleeStart s) =>
        $"убегаю от {s.Enemy}: он в {s.Distance:0.#} бл, " +
        (s.Reason == FleeReason.Unarmed
            ? $"драться нечем ({s.Weapon})"
            : $"бой не вытяну (здоровья {s.HealthFraction:P0}, в руках {s.Weapon})");

    /// <summary>
    /// Одна строка на конец побега — с числами и с решением. Заказчик должен
    /// видеть в журнале дело, а не семьдесят одинаковых обещаний.
    /// </summary>
    public static string Say(FleeReport r)
    {
        string how = $"{r.From:0.#} → {r.To:0.#} бл за {r.Seconds:0.#} с, " +
                     $"рывков {r.Legs}" + (r.Wasted > 0 ? $" (впустую {r.Wasted})" : "");
        return r.Outcome switch
        {
            FleeOutcome.Escaped => $"оторвался от {r.Enemy}: {how}",
            FleeOutcome.ChaserGone => $"{r.Enemy} больше не гонится: {how}",
            FleeOutcome.Sealed => $"не оторвался от {r.Enemy} ({how}) — заложился блоком",
            FleeOutcome.Fighting => $"не оторвался от {r.Enemy} ({how}) — беру бой тем, что есть",
            _ => $"бегство от {r.Enemy} прервали ({how}) — телом распоряжается другой"
        };
    }
}
