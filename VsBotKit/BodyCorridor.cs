namespace VsBotKit;

/// <summary>
/// ПРОЙДЁТ ЛИ ТЕЛО ПО ПРЯМОЙ ИЗ КЛЕТКИ В КЛЕТКУ — одно правило на весь проект.
///
/// ЖИВОЙ СЛУЧАЙ, ЖУРНАЛ ЗАКАЗЧИКА 19.08:
/// <code>
///   18:32:38 упёрся на точке 4/4 (512058, 113, 512282), стою (512056,3, 112,1, 512252,7)
///   18:32:38 до точки (512058, 113, 512282) было 31 бл по прямой — её поставило
///            спрямление, а тело там не проходит
/// </code>
/// Тридцать один блок по прямой СКВОЗЬ ПОСТРОЙКУ. Строка про «спрямление
/// поставило, а тело не проходит» встречалась в журналах 82 раза: бот шёл к
/// такой точке, упирался и только ПОСЛЕ этого перестраивал маршрут клетка за
/// клеткой. Отрезок надо проверять ДО того, как по нему пошли, — этим и занят
/// этот файл.
///
/// ЧЕМ МЕРИЛИ РАНЬШЕ И ПОЧЕМУ ЭТО ВРАЛО. Спрямление тянуло НИТЬ по центрам
/// клеток и спрашивало у мира ровно одно: «есть ли тут опора на ±1 от прошлой
/// высоты». Нить толщины не имеет. Тело — имеет: коробка
/// <see cref="BodySize.Width"/> × <see cref="BodySize.Height"/>. Стоит
/// прямой пройти через проём в один блок хоть чуть-чуть не по его середине —
/// нить проходит серединой проёма, а плечо тела упирается в косяк. Столбец,
/// который задевает плечо, нить не спрашивала НИКОГДА, потому что линия в него
/// не заходит.
///
/// Второе расхождение — СТУПЕНЬКА ВВЕРХ. Нить «подрастала» на блок за клетку
/// и считала это прямой. Тело так не умеет: шаг игрока берёт 0,6
/// (<c>Walker.StepUp</c>), а блок — это 1, и поднимают на него прыжком. Внутри
/// спрямлённого отрезка прыжку неоткуда взяться: промежуточных точек в нём нет
/// по определению, тело просто бежит в стену и подпрыгивает на месте. Поэтому
/// подъём здесь запрещён вовсе, а спуск — нет: с уступа сходят ногами.
///
/// ЧТО ОСТАЛОСЬ НЕТОЧНЫМ, И ЭТО НАДО ЗНАТЬ. Правило спрашивает мир
/// пятнадцатью вопросами <see cref="IPathWorld"/>, то есть КЛЕТКАМИ: у него
/// нет коробок частичных блоков, а у тела они есть. Поэтому исполнитель
/// маршрута обязан по-прежнему уметь отказаться от спрямления (см.
/// <c>Walker.IsStraightenedLeg</c> и <c>Movement.BlameSmoothing</c>): между
/// планом и ходьбой мир к тому же успевает измениться.
/// </summary>
public static class BodyCorridor
{
    /// <summary>
    /// Как часто ставить пробы вдоль отрезка, блоков.
    ///
    /// Четверть клетки — это НЕ вкус, а требование к охвату: шаг пробы обязан
    /// быть меньше половины ширины тела (0,3), иначе между двумя пробами
    /// коробка успевает целиком пересечь соседний столбец, и он останется
    /// неспрошенным. Ровно так же считался и прежний счёт проб (len × 4).
    /// </summary>
    private const double ProbeStep = 0.25;

    /// <summary>
    /// Пройдёт ли тело по прямой из <paramref name="a"/> в <paramref name="b"/>,
    /// не сходя с земли: коробка нигде не упирается в блок, под ней всюду есть
    /// опора, и пол не поднимается ни разу. Спуск дозволен, подъём — нет:
    /// наверх поднимаются прыжком, а прыжок внутри спрямлённого отрезка
    /// исполнять нечем, промежуточных точек в нём не бывает.
    /// </summary>
    /// <param name="isLeaves">
    /// Листва ли в клетке — то же необязательное знание, что и у поиска пути
    /// (<c>PathOptions.IsLeaves</c>). СКВОЗЬ ЛИСТВУ НЕ СПРЯМЛЯЕМ: клетка с
    /// листвой — это не лишняя точка «лесенки», а РАБОТА, тело должно там
    /// остановиться и снести ветку. Не задан — вопрос не задаётся вовсе.
    /// </param>
    /// <param name="isOffLimits">
    /// ЗАКРЫТА ЛИ КЛЕТКА ДЛЯ СПРЯМЛЕНИЯ. Сам коридор об этом ничего не знает и
    /// знать не должен — он про ТЕЛО; вопрос задаётся зовущему, и задаётся
    /// ровно про ту клетку, куда встают НОГИ, на каждом новом столбце вдоль
    /// отрезка. Не задан — не задаётся вовсе (так его и зовут все, кому нужна
    /// одна проходимость).
    ///
    /// ЗАЧЕМ ЭТОТ ВОПРОС ПОЯВИЛСЯ. Поиск пути аккуратно обходит клетки рядом
    /// с огнём, назначая им цену (<c>AStarPathFinder.GroundFactor</c>,
    /// <c>LavaProximityCost</c>), а спрямление срезало углы и вело тело
    /// ВПЛОТНУЮ к костру: оно спрашивало только «пройдёт ли тело». Живая цена
    /// известна — бот сгорел в своём же костре и потерял 48 стопок вещей.
    /// Что именно закрыто, решает зовущий: сегодня это «клетка вплотную к
    /// огню, которой САМ ПОИСК ПУТИ не выбирал» (<c>AStarPathFinder.Smooth</c>).
    ///
    /// ЗДЕСЬ СПРАШИВАЕТСЯ НЕ ЦЕНА. Первый заход спрашивал именно её и брал
    /// потолком «худшую цену на выброшенном участке» — приёмка 27.08 показала
    /// щупом, что такой потолок снимает сам себя: своим же костром за спиной и
    /// памятью тупиков (множитель 100 против восьмёрки огня). Разбор — в
    /// док-строке <c>AStarPathFinder.Smooth</c>.
    /// </param>
    public static bool Straight(IPathWorld world, BlockPos a, BlockPos b,
        Func<int, int, int, bool>? isLeaves = null,
        Func<int, int, int, bool>? isOffLimits = null)
    {
        // Концы врозь больше чем на блок — это уже не прямая по земле, а
        // лестница или обрыв, и разбирать её должен маршрут по клеткам
        if (Math.Abs(a.Y - b.Y) > 1)
            return false;

        double dx = b.X - a.X, dz = b.Z - a.Z;
        double len = Math.Sqrt(dx * dx + dz * dz);
        if (len < 0.01)
            return true;

        int probes = Math.Max(1, (int)Math.Ceiling(len / ProbeStep));
        // Высота ПОЛА под телом на этой пробе и клетка, над которой оно сейчас
        int floorY = a.Y, prevX = a.X, prevZ = a.Z;
        // Отпечаток коробки на прошлой пробе: эти столбцы уже спрошены.
        // Без памяти каждый столбец спрашивался бы по четыре раза подряд, а
        // спрямление зовёт это правило десятками раз на один маршрут
        int wasX0 = int.MaxValue, wasX1 = int.MinValue;
        int wasZ0 = int.MaxValue, wasZ1 = int.MinValue;

        for (int i = 0; i <= probes; i++)
        {
            double t = i / (double)probes;
            double px = a.X + 0.5 + dx * t, pz = a.Z + 0.5 + dz * t;
            int cx = (int)Math.Floor(px), cz = (int)Math.Floor(pz);

            // ПОД ЦЕНТРОМ ОПОРА ОБЯЗАНА БЫТЬ РЯДОМ (±1) — иначе это не прямая,
            // а стена или обрыв. Вопрос тот же, что и в прежнем счёте
            bool новыйСтолбец = cx != prevX || cz != prevZ;
            if (новыйСтолбец && world.FindSupportY(cx, floorY, cz, up: 1, down: 1) is null)
                return false;
            prevX = cx;
            prevZ = cz;

            // ТЕЛО — КОРОБКА, А НЕ НИТЬ. Спрашиваем ВСЕ столбцы, которые
            // накрывает её ширина, а не один, через центр которого идёт линия.
            // Здесь же сам собой закрывается и старый запрет срезать углы: на
            // диагональном переходе коробка накрывает сразу четыре столбца, и
            // оба смежных прохода обязаны быть свободны
            int x0 = (int)Math.Floor(px - BodySize.HalfWidth);
            int x1 = (int)Math.Floor(px + BodySize.HalfWidth);
            int z0 = (int)Math.Floor(pz - BodySize.HalfWidth);
            int z1 = (int)Math.Floor(pz + BodySize.HalfWidth);

            // НОГИ САДЯТСЯ НА САМУЮ ВЫСОКУЮ ОПОРУ ПОД КОРОБКОЙ, а не под
            // центром. Так и стоит живой игрок, свесившись с уступа: пока хоть
            // край коробки над верхней ступенью, тело держит она.
            //
            // Считать этаж по одному центру было нельзя: у края уступа центр
            // уже над нижней клеткой, а коробка ещё над верхней — и правило
            // спрашивало бы верхнюю ступень на этаже НИЖЕ её пола, то есть
            // упиралось бы в собственный пол и запрещало любой спуск.
            // Вверх не смотрим вовсе (up: 0): подняться на блок — это прыжок,
            // а прыжок внутри спрямлённого отрезка исполнять нечем
            int feet = int.MinValue;
            for (int bx = x0; bx <= x1; bx++)
                for (int bz = z0; bz <= z1; bz++)
                    if (world.FindSupportY(bx, floorY, bz, up: 0, down: 1) is { } support &&
                        support > feet)
                        feet = support;
            // Под всей коробкой пусто — это не ходьба, это падение
            if (feet == int.MinValue)
                return false;
            bool этажСменился = feet != floorY;
            if (этажСменился)
            {
                floorY = feet;
                // Этаж сменился — прежний отпечаток спрошен на ДРУГОЙ высоте
                wasX0 = int.MaxValue; wasX1 = int.MinValue;
                wasZ0 = int.MaxValue; wasZ1 = int.MinValue;
            }

            // НЕ ТОЛЬКО ПРОХОДИМОСТЬ. Спрашиваем ту самую клетку, куда встают
            // ноги, — тем же местом её мерит и поиск пути (GroundFactor берёт
            // соседство с огнём по клетке ног). Столбцы под плечами сюда не
            // берём нарочно: плечо, задевшее соседний столбец, ничего не
            // стоит, а надбавка за соседство с огнём уже накрывает клетку ног
            // на клетку вокруг очага.
            //
            // СПРАШИВАЕМ И ПРИ СМЕНЕ ЭТАЖА, А НЕ ТОЛЬКО СТОЛБЦА. Приёмка 27.08
            // сняла щупом в теле правила: на спуске со ступеньки столбец
            // менялся раньше, чем пол под ним. Первая проба нового столбца
            // спрашивала его на СТАРОМ этаже (коробка ещё держалась краем за
            // верхнюю ступень), на следующей пробе пол опускался — но столбец
            // был уже не новым, и клетка, КУДА ВСТАЛИ НОГИ, не спрашивалась
            // никогда. Живьём это яма с огнём у самой ступеньки: очаг вровень
            // с ногами ловился только потому, что FireNextTo заглядывает на
            // этаж ниже, а очаг ещё блоком ниже — не ловился вовсе
            if ((новыйСтолбец || этажСменился) && isOffLimits != null &&
                isOffLimits(cx, floorY, cz))
                return false;

            // СТУПЕНЬКА ВВЕРХ ОТСЕКАЕТСЯ ЗДЕСЬ ЖЕ, и отдельного правила ей не
            // нужно: клетка, пол которой на блок выше, СПЛОШНАЯ на нашем этаже,
            // и коробка упирается в неё раньше, чем успела бы «взойти»
            for (int bx = x0; bx <= x1; bx++)
                for (int bz = z0; bz <= z1; bz++)
                {
                    if (bx >= wasX0 && bx <= wasX1 && bz >= wasZ0 && bz <= wasZ1)
                        continue;
                    // Телу нужны обе клетки столбца: ноги и голова
                    if (!world.IsEnterable(bx, floorY, bz) ||
                        !world.IsEnterable(bx, floorY + 1, bz))
                        return false;
                    if (isLeaves != null &&
                        (isLeaves(bx, floorY, bz) || isLeaves(bx, floorY + 1, bz)))
                        return false;
                }
            wasX0 = x0; wasX1 = x1;
            wasZ0 = z0; wasZ1 = z1;
        }
        return Math.Abs(floorY - b.Y) <= 1;
    }
}
