using Vintagestory.API.Common;
using Vintagestory.API.Config;

namespace VsBotKit;

/// <summary>
/// ПОЛЁТ СТРЕЛЫ — ТОТ ЖЕ ЦИКЛ, ЧТО КРУТИТ СЕРВЕР, И НИ ОДНОГО СВОЕГО ЧИСЛА.
///
/// Зачем считать полёт вообще. Лук в игре бьёт НЕ по прямой: стрела летит
/// 60 бл/с, теряет 13% скорости в секунду и падает с ускорением 16,65 бл/с².
/// На десяти блоках это уже 0,24 бл вниз, на двадцати 0,96, на сорока — 3,97.
/// Бот, стреляющий
/// «прямо в цель», не попадает НИ РАЗУ дальше пяти блоков, и виноват в этом не
/// разброс, а горизонт. Значит наводка обязана знать баллистику — иначе лука
/// нет вовсе.
///
/// ОТКУДА ЦИКЛ (проверено ilspycmd по сборкам игры 1.22.7, не по памяти):
/// <c>Vintagestory.API.Common.EntityBehaviorPassivePhysics.MotionAndCollision</c>,
/// <c>num = 60·dt</c>, и ровно три строки в этом порядке:
/// <code>
///     motion.Scale(Math.Pow(AirDragValue, dt * 33f));   // сопротивление
///     motion.Y -= GravityPerSecond / 60.0 * num;        // тяжесть
///     pos += motion * num;                              // шаг
/// </code>
/// Тикает это <c>PhysicsManager</c> с шагом <c>1/30</c> с.
///
/// И ГЛАВНОЕ — ТИК ДРОБИТСЯ НА ДЕСЯТЬ. Это поправка приёмки, и она настоящая.
/// <c>OnPhysicsTick</c> той же сборки: число подшагов равно десяти, пока длина
/// вектора движения больше 0,1, иначе единице; шаг делится на это число, и
/// весь <c>MotionAndCollision</c> крутится по разу на подшаг. У стрелы
/// начальная скорость равна стату натяга (база 1,0) — значит подшагов ВСЕГДА
/// десять, пока она не увязнет.
///
/// Конечная скорость от дробления не меняется, а ПОЛОЖЕНИЕ меняется:
/// сопротивление и тяжесть в дроблёном счёте прикладываются понемногу и
/// раньше. Один шаг на тик давал завышение падения на 0,044 бл на десяти
/// блоках и на 0,19 бл на сорока — то есть бот систематически брал выше цели
/// примерно на 0,005 рад при конусе разброса 0,028 рад, проедая шестую часть
/// точности ни за что.
///
/// ОТКУДА КОЭФФИЦИЕНТЫ. <c>SetProperties</c> берёт их у ассета стрелы
/// (assets/survival/entities/nonliving/projectile/arrow.json: airDragFactor
/// 0.25, gravityFactor 0.75) и мировых постоянных
/// (<c>GlobalConstants.AirDragAlways</c> 0.983, <c>GravityPerSecond</c> 0.37):
///   AirDragValue    = 1 − (1 − 0,983) · 0,25 = 0,99575
///   GravityPerSecond = 0,37 · 0,75            = 0,2775
///
/// НАЧАЛЬНАЯ СКОРОСТЬ. <c>ItemBow.OnHeldInteractStop</c> ставит стреле
/// <c>motion = (AheadCopy(1, pitch, yaw) − глаза) · Stats.GetBlended("bowDrawingStrength")</c>,
/// то есть ЕДИНИЧНЫЙ вектор взгляда, умноженный на стат силы натяга (база 1,0,
/// <c>EntityPlayer</c> ctor). За тик стрела проходит motion·2, тиков 30 в
/// секунду — отсюда и 60 бл/с.
///
/// ЧЕГО ЗДЕСЬ НЕТ И БЫТЬ НЕ ДОЛЖНО: СИЛА ВЫСТРЕЛА ОТ ВРЕМЕНИ НАТЯГА НЕ ЗАВИСИТ
/// ВОВСЕ. В <c>OnHeldInteractStop</c> есть ровно один порог — <c>secondsUsed
/// &lt; 0.65f → return</c>, — а дальше скорость одна и та же и для полусекунды,
/// и для пяти. Держать дольше стоит только ради ТОЧНОСТИ (см.
/// <see cref="Archery.SpreadRadians"/>), и это разные вещи.
///
/// Файл нарочно ничего не знает ни про сеть, ни про бота: чистые функции,
/// закрытые стендом (<c>ArrowFlightTests</c>).
/// </summary>
public static class ArrowFlight
{
    /// <summary>
    /// ПАДЕНИЕ СТРЕЛЫ ЗАМЕДЛЕНО ВОТ НАСТОЛЬКО, а сопротивление воздуха
    /// ослаблено вот настолько. ЕДИНСТВЕННЫЕ ДВА ЧИСЛА ЭТОГО ФАЙЛА,
    /// ПЕРЕПИСАННЫЕ РУКАМИ, и я называю это вслух: они лежат в
    /// <c>behaviorConfigs.passivephysics</c> ассета стрелы
    /// (assets/survival/entities/nonliving/projectile/arrow.json), а реестр
    /// сущностей по сети настройки поведений НЕ ШЛЁТ — спросить их у сервера
    /// нечем. Всё остальное здесь берётся у самой игры.
    /// </summary>
    public const double ArrowAirDragFactor = 0.25, ArrowGravityFactor = 0.75;

    /// <summary>
    /// Шаг физики снаряда, секунд. Число НЕ ПЕРЕПИСАНО, а взято у игры:
    /// <c>GlobalConstants.PhysicsFrameTime = 1f/30f</c>, и с тем же шагом её
    /// крутит <c>PhysicsManager</c>. Разница между <c>1f/30f</c> и <c>1.0/30.0</c>
    /// — полторы миллиардных, но копия числа однажды разошлась бы, а ссылка на
    /// него — никогда.
    /// </summary>
    public static readonly double TickSeconds = GlobalConstants.PhysicsFrameTime;

    /// <summary>
    /// НА СКОЛЬКО ПОДШАГОВ СЕРВЕР ДРОБИТ ТИК быстрому телу и с какой скорости
    /// он дробить начинает. Оба числа — из <c>OnPhysicsTick</c>, не свои.
    /// </summary>
    public const int SubSteps = 10;

    /// <inheritdoc cref="SubSteps"/>
    public const double SubStepAboveSpeed = 0.1;

    /// <summary>
    /// Множитель шага: <c>num = 60·dt</c>. При целом тике 1/30 это ровно 2, при
    /// подшаге 1/300 — 0,2. На него умножается и тяжесть, и сам шаг — в игре
    /// это одно и то же число.
    /// </summary>
    public static readonly double StepFactor = 60.0 * TickSeconds;

    /// <summary>
    /// Во сколько раз скорость убывает за тик — <c>pow(AirDragValue, dt·33)</c>,
    /// где <c>AirDragValue = 1 − (1 − AirDragAlways)·airDragFactor</c>
    /// (<c>EntityBehaviorPassivePhysics.SetProperties</c>). Для стрелы это
    /// <c>pow(0,99575; 1,1) ≈ 0,995326</c>, то есть около 13 % скорости в секунду.
    /// </summary>
    public static readonly double DragPerTick = Math.Pow(
        1.0 - (1.0 - GlobalConstants.AirDragAlways) * ArrowAirDragFactor, TickSeconds * 33);

    /// <summary>
    /// Сколько вертикальной скорости съедает тяжесть за тик:
    /// <c>GravityPerSecond/60 · num</c>. Для стрелы — <c>0,2775/60 · 2 = 0,00925</c>,
    /// то есть 16,65 бл/с².
    /// </summary>
    public static readonly double GravityPerTick =
        GlobalConstants.GravityPerSecond * ArrowGravityFactor / 60.0 * StepFactor;

    /// <summary>Сопротивление за ОДИН ПОДШАГ (десятая доля тика).</summary>
    public static readonly double DragPerSubStep = Math.Pow(
        1.0 - (1.0 - GlobalConstants.AirDragAlways) * ArrowAirDragFactor,
        TickSeconds / SubSteps * 33);

    /// <summary>Тяжесть за ОДИН ПОДШАГ.</summary>
    public static readonly double GravityPerSubStep = GravityPerTick / SubSteps;

    /// <summary>
    /// «СМОТРЮ ПРЯМО» — ЭТО π, А НЕ НОЛЬ. Соглашение самой игры:
    /// <c>EntityPos.GetViewVector(p,y) = (−cos p·sin y, sin p, −cos p·cos y)</c>,
    /// и при <c>p = π</c> вертикальная составляющая <c>sin π = 0</c>. Меньше π —
    /// вверх, больше — вниз. Тем же числом живёт всё тело бота (см.
    /// <c>Body.SendPositionAsync</c>), своей мерки здесь нет.
    /// </summary>
    public const float Level = MathF.PI;

    /// <summary>
    /// Предел наклона живого клиента, нижняя граница (взгляд вверх).
    /// Число из <c>Body</c>: серверу уходит зажатым ровно в эти рамки, и
    /// решение «этот выстрел не поднять» обязано мериться ими же.
    /// </summary>
    public const float PitchUpLimit = 1.5857964f;

    /// <summary>Предел наклона живого клиента, верхняя граница (взгляд вниз).</summary>
    public const float PitchDownLimit = 4.697389f;

    /// <summary>
    /// НА СКОЛЬКО СТРЕЛА РОЖДАЕТСЯ ВПЕРЕДИ НОГ, блоков.
    ///
    /// ЛОВУШКА ИМЕНИ, И ЕЁ НАДО НАЗВАТЬ ВСЛУХ. В <c>ItemBow</c> написано
    /// <c>Pos.BehindCopy(0.21)</c> — «позади». Но тело метода
    /// <c>EntityPos.BehindCopy</c> СЛОВО В СЛОВО совпадает с
    /// <c>HorizontalAheadCopy</c>: <c>(x + sin(yaw)·off, y, z + cos(yaw)·off)</c>,
    /// а «вперёд» при взгляде по горизонту — это как раз <c>(sin yaw, 0, cos yaw)</c>
    /// (из <c>GetViewVector</c> при <c>p = π</c>). То есть стрела появляется на
    /// 0,21 бл ВПЕРЕДИ ног, а не позади, и путь до цели на столько же короче.
    /// Поверь мы имени — систематически целились бы выше на полградуса.
    /// </summary>
    public const double MuzzleAhead = 0.21;

    /// <summary>
    /// Куда стрела прилетит по горизонтали и вертикали, если пустить её под
    /// таким наклоном. Возвращает высоту относительно дула в тот миг, когда
    /// стрела прошла <paramref name="horizontal"/> блоков вбок, и время полёта.
    ///
    /// null — не долетела вовсе за отпущенные тики (слишком далеко: горизонт
    /// съедает сопротивление).
    /// </summary>
    /// <param name="pitch">Наклон в соглашении игры: π — прямо, меньше — вверх.</param>
    /// <param name="horizontal">Горизонтальное расстояние до цели, блоков.</param>
    /// <param name="speed">Стат <c>bowDrawingStrength</c> (база 1,0).</param>
    /// <param name="maxTicks">Потолок счёта: 200 тиков — это 6,7 с полёта.</param>
    public static (double Height, double Seconds)? Reach(double pitch, double horizontal,
        double speed = 1.0, int maxTicks = 200)
    {
        if (horizontal <= 0)
            return (0, 0);

        // Единичный вектор взгляда игры. Горизонтальную часть берём по модулю:
        // сама плоскость выстрела задаётся рысканьем, а здесь считается
        // ПРОФИЛЬ полёта — «вперёд и вверх», как на чертеже
        double forward = -Math.Cos(pitch) * speed;
        double up = Math.Sin(pitch) * speed;
        if (forward <= 1e-9)
            return null;   // в стену или за спину — так стрела вбок не улетит

        double x = 0, y = 0;
        for (int tick = 0; tick < maxTicks; tick++)
        {
            // СКОЛЬКО ПОДШАГОВ — РЕШАЕТ ТЕКУЩАЯ СКОРОСТЬ, и решает по-игровому:
            // «длина вектора движения больше 0,1 — дроби на десять». Спрашивать
            // это надо КАЖДЫЙ тик, а не однажды: увязшая стрела у сервера и
            // правда переходит обратно на один шаг
            double speedNow = Math.Sqrt(forward * forward + up * up);
            int steps = speedNow > SubStepAboveSpeed ? SubSteps : 1;
            double drag = steps == 1 ? DragPerTick : DragPerSubStep;
            double gravity = steps == 1 ? GravityPerTick : GravityPerSubStep;
            double step = StepFactor / steps;

            for (int sub = 0; sub < steps; sub++)
            {
                forward *= drag;
                up *= drag;
                up -= gravity;

                double nextX = x + forward * step;
                double nextY = y + up * step;
                if (nextX >= horizontal)
                {
                    // Внутри подшага летит по прямой — доля считается линейно.
                    // Без неё ответ дёргается ступеньками
                    double part = (horizontal - x) / (nextX - x);
                    return (y + (nextY - y) * part,
                        (tick + (sub + part) / steps) * TickSeconds);
                }
                x = nextX;
                y = nextY;
            }
        }
        return null;
    }

    /// <summary>
    /// ПОД КАКИМ НАКЛОНОМ БИТЬ, чтобы попасть в точку на <paramref name="horizontal"/>
    /// блоков вбок и <paramref name="dy"/> блоков выше дула. null — не достать
    /// (слишком далеко либо выстрел не влезает в наклон живого клиента).
    ///
    /// СПОСОБ — ПОЛОВИННОЕ ДЕЛЕНИЕ, и вот почему не формула. Формула бросания
    /// без сопротивления среды тут врёт: за секунду полёта стрела теряет 13%
    /// скорости, и на сорока блоках ошибка «школьной» параболы больше метра.
    /// А цикл игры детерминирован — значит его можно просто прокрутить, и это
    /// будет ТОЧНО тот же полёт, что у сервера, а не похожий на него.
    ///
    /// Высота прилёта монотонно РАСТЁТ, когда наклон уменьшается (ствол
    /// поднимается), поэтому деление сходится за 40 шагов до тысячных радиана.
    ///
    /// БЕРЁМ НАСТИЛЬНУЮ ТРАЕКТОРИЮ, а не навесную: у любой достижимой точки их
    /// две (пологая и «через купол»), и живой лучник бьёт пологой — она
    /// быстрее, ей меньше мешает ветка над головой и упреждение по ней короче.
    /// Поиск начинается от горизонта и поднимается вверх ровно настолько,
    /// насколько надо.
    /// </summary>
    public static (float Pitch, double Seconds)? Aim(double horizontal, double dy,
        double speed = 1.0)
    {
        if (horizontal <= 0.01)
            return null;

        // Вверх поднимаемся не дальше предела живого клиента, вниз — тоже
        double up = Math.Max(PitchUpLimit, Level - 1.2);
        double down = Math.Min(PitchDownLimit, Level + 1.2);

        // Проверяем края: если даже задранный ствол не достаёт — не достанет
        if (Reach(up, horizontal, speed) is not { } high || high.Height < dy)
            return null;
        if (Reach(down, horizontal, speed) is { } low && low.Height > dy)
            return null;   // цель настолько выше нас, что стрелять некуда

        for (int i = 0; i < 40; i++)
        {
            double mid = (up + down) / 2;
            var hit = Reach(mid, horizontal, speed);
            // Не долетела — значит ствол слишком опущен либо слишком задран;
            // при поиске от горизонта вниз это всегда «мало высоты»
            if (hit is not { } h || h.Height > dy)
                up = mid;
            else
                down = mid;
        }

        double pitch = (up + down) / 2;
        return Reach(pitch, horizontal, speed) is { } found
            ? ((float)pitch, found.Seconds)
            : null;
    }

    /// <summary>
    /// Рысканье на точку — ТЕМ ЖЕ соглашением, что и весь остальной бот
    /// (<c>Movement.FaceAsync</c>: <c>Yaw = Atan2(dx, dz)</c>). Второй мерки
    /// поворота в проекте быть не должно: разойдись они — бот целился бы в одну
    /// сторону, а поворачивался в другую, и понять это по журналу было бы нечем.
    /// </summary>
    public static float YawTo(double dx, double dz) => (float)Math.Atan2(dx, dz);
}

/// <summary>
/// РЕШЁННАЯ НАВОДКА: куда встать взглядом и когда стрела долетит.
/// </summary>
/// <param name="Yaw">Рысканье корпуса.</param>
/// <param name="Pitch">Наклон в соглашении игры (π — прямо, меньше — вверх).</param>
/// <param name="Seconds">Сколько стрела будет лететь.</param>
/// <param name="AimX">Точка упреждения по X — туда бот и смотрит.</param>
/// <param name="AimZ">Точка упреждения по Z.</param>
/// <param name="Range">Расстояние до самой цели (не до упреждения), блоков.</param>
/// <param name="Horizontal">
/// Сколько блоков стреле лететь ВБОК: до точки упреждения и уже за вычетом
/// выноса дула. Это не то же самое, что <paramref name="Range"/>, и путать их
/// нельзя: по дальности до цели роль решает «стрелять или сходиться», а по
/// этому числу считается и наклон, и доля попадания
/// (<see cref="Archery.HitChance"/>). У бегущей вбок цели они расходятся на
/// метры.
/// </param>
public sealed record AimSolution(float Yaw, float Pitch, double Seconds,
    double AimX, double AimZ, double Range, double Horizontal, double AimAboveFeet);

/// <summary>
/// ЛУК — МЕХАНИЗМ. Кто, когда и зачем стреляет, решает роль; здесь только
/// «как» — и всё «как» проверено по сборкам игры, а не по памяти.
///
/// ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА — ПУНКТ 5 ЗАКОНА: бот не делает того, чего не
/// может живой игрок. У лука это не общие слова, а четыре очень конкретных
/// запрета, и каждый здесь исполнен:
///
/// 1. НИКАКОЙ ИДЕАЛЬНОЙ НАВОДКИ. Разброс кидает СЕРВЕР: на переходе
///    «прицелился» он один раз бросает кости и кладёт их в
///    <c>WatchedAttributes["aimingRandPitch"/"aimingRandYaw"]</c>
///    (<c>EntityBehaviorAimingAccuracy.OnAimingChanged</c>). Эти два числа
///    СИНХРОНИЗИРУЮТСЯ НА КЛИЕНТА — то есть бот их физически ВИДИТ и мог бы
///    вычесть, попадая всегда и в яблочко. Это и была бы та самая «идеальная
///    наводка». ЗДЕСЬ ИХ НЕ ЧИТАЮТ НИ РАЗУ, и это не забывчивость, а решение:
///    живой игрок получает те же числа и воспользоваться ими не может.
///    Промахи у бота ЕСТЬ и будут — так и задумано.
/// 2. НИКАКОЙ СТРЕЛЬБЫ СКВОЗЬ СТЕНЫ. Сервер для выстрела расстояния и
///    видимости НЕ ПРОВЕРЯЕТ ВОВСЕ (<c>AntiAbuse</c> смотрит их только при
///    непустом выделении блока или существа, а лук шлёт пустое). Значит
///    единственный, кто может здесь соврать, — мы сами. Луч честного зрения
///    спрашивается тем же механизмом, каким бой спрашивает «доставать ли
///    мечом» — <c>Sight.LookAtCreature</c>, второго нет.
/// 3. НИКАКОГО МГНОВЕННОГО НАТЯГА. Тетива держится НАСТОЯЩЕЕ время, руками
///    (<see cref="Hands.UseHeldAsync"/>), которые считают шаги по тикам своего
///    тела. Соврать серверу большим <c>UsingCount</c> можно (он прокрутит по
///    нему до 5000 шагов), и однажды этим уже соврали — см. предупреждение в
///    <c>Actions.cs</c> про «UsingCount = 200».
/// 4. НИКАКОГО ЗНАНИЯ О ЦЕЛИ СВЕРХ ЧЕСТНОГО ЗРЕНИЯ. Упреждение берётся из
///    ЗАМЕРЕННОГО хода цели (<see cref="CombatPace"/> — тот же механизм, каким
///    бой считает «догоню ли»), а не из серверных полей скорости.
///
/// ЧТО ДОЛЖНО СОЙТИСЬ, ЧТОБЫ СТРЕЛА ВЫЛЕТЕЛА (по коду сервера, всё до одного):
/// • лук в АКТИВНОМ слоте хотбара 0..9. Сервер берёт предмет по <c>SlotId</c>
///   из пакета, а при <c>SlotId ≥ 10</c> лезет в рюкзак — из левой руки лук не
///   работает совсем;
/// • стрелы — где угодно в открытых инвентарях (хотбар, рюкзак): их ищет
///   <c>ItemBow.GetNextArrow</c> обходом <c>WalkInventory</c>;
/// • <c>MouseButton = 2</c>, иначе <c>HandleHandInteraction</c> выходит молча;
/// • <c>secondsUsed ≥ 0,65</c>, где <c>secondsUsed = настоящее время + 0,02·UsingCount</c>.
///
/// И ПЯТОЕ, ДОБАВЛЕННОЕ 26.08: НИКАКОЙ СТРЕЛЬБЫ НАУГАД. Живой лучник не бьёт
/// туда, где промажет наверняка, — он подходит. Бот считает долю попадания
/// (<see cref="Archery.HitChance"/>) по своему же разбросу, по дальности и по
/// коробке цели из реестра сервера, и ниже порога роли не стреляет вовсе. Порог
/// снимается, когда стрелять больше нечем (<see cref="Archery.LastResort"/>):
/// экономия стрел не должна становиться смертью по расчёту.
///
/// БЕЗ СТРЕЛ ИГРА МОЛЧИТ, И ЭТО ХУЖЕ ОТКАЗА. <c>OnHeldInteractStart</c> ставит
/// <c>PreventDefault</c> ТОЛЬКО когда стрела нашлась; без стрел сервер даже не
/// открывает удержание, и «выстрел» проходит без единого признака неудачи.
/// Поэтому успех здесь считается ПО ФАКТУ УБЫЛИ СТРЕЛ, а не по «пакет ушёл».
/// </summary>
public sealed class Archery
{
    private readonly BotContext ctx;
    private readonly CombatPace pace;

    /// <param name="pace">
    /// ЗАМЕР ХОДА ЦЕЛЕЙ — ЧУЖОЙ И ОБЩИЙ, а не свой. Упреждение и оценка
    /// «догоню ли» в бою спрашивают ОДНО И ТО ЖЕ: с какой скоростью идёт эта
    /// тварь. Заведи лук свой замер — числа разошлись бы молча, и бот стрелял
    /// бы с упреждением на одну скорость, а решал драться по другой. Поэтому
    /// сюда передаётся <see cref="BehaviorAttackHostiles.Pace"/>, тот самый.
    /// </param>
    public Archery(BotContext ctx, CombatPace pace)
    {
        this.ctx = ctx;
        this.pace = pace;
    }

    /// <summary>Сказать вслух: что вышло и почему.</summary>
    public event Action<string>? OnLog;

    /// <summary>
    /// ЗАГЛУШКА ПОВТОРОВ — ОБЩАЯ, ТА ЖЕ, ЧТО У ДВИЖЕНИЯ И БОЯ. Отказ стрелять
    /// это СОСТОЯНИЕ, а не событие: пока между ботом и дрифтером стоит стена,
    /// ответ будет один и тот же каждую секунду боя, и без глушителя журнал
    /// заливается — ровно то, чем однажды уже болел бой («не дотянуться»
    /// двадцать раз подряд). Своей рукописной заглушки здесь заводить нельзя:
    /// правило 2 проекта.
    /// </summary>
    private readonly LogRepeats repeats = new() { QuietSeconds = 20 };

    /// <summary>
    /// Сказать ОДИН раз на новость, а не каждый выстрел. Не только отказ:
    /// оговорка «размера цели реестр не назвал» — тоже состояние, а не
    /// событие, и повторяется она с той же частотой.
    /// </summary>
    private void SayOnce(string line)
    {
        if (repeats.Say(line, DateTime.UtcNow) is { } once)
            OnLog?.Invoke(once);
    }

    /// <summary>
    /// ЧТО ИГРА СЧИТАЕТ СТРЕЛОЙ. Мерка НЕ НАША: это дословный кусок
    /// <c>ItemBow.GetNextArrow</c> — <c>Code.PathStartsWith("arrow-")</c>.
    /// Другой стрелы лук не возьмёт, как её ни назови, поэтому и спрашивать
    /// надо ровно это. Свой список материалов (crude, flint, copper…) был бы
    /// как раз тем выдуманным списком, на котором проект горел трижды.
    /// </summary>
    public static bool IsArrow(string? code) =>
        code is { Length: > 0 } && code.StartsWith("arrow-", StringComparison.Ordinal);

    /// <summary>
    /// ЧТО ИГРА СЧИТАЕТ ЛУКОМ. Спрашиваем реестр сервера: в bow.json стоит
    /// <c>tool: "bow"</c>, и сервер присылает это поле в пакете реестра
    /// (<c>Packet_ItemType.Tool</c> → <c>EnumTool.Bow</c>). Так находится и
    /// модовый лук, если он объявлен луком; список кодов не завёден нарочно.
    /// </summary>
    public bool IsBow(string? code) => ctx.World.ToolOf(code) == EnumTool.Bow;

    /// <summary>
    /// Урон этого лука по реестру (<c>attributes.damage</c>) — то самое число,
    /// которое <c>ItemBow.OnHeldInteractStop</c> складывает с уроном стрелы.
    /// Ноль — реестра нет или это не лук.
    /// </summary>
    public float BowDamage(string? code) =>
        ctx.World.GetCollectible(code)?.Attributes?["damage"].AsFloat(0f) ?? 0f;

    /// <summary>
    /// Урон ЭТОЙ стрелы по реестру (<c>attributes.damage</c>). Число это
    /// ПРИБАВКА, и она бывает отрицательной: у кремнёвой −0,5, у грубой −0,75,
    /// у стальной +2,5 (assets/survival/itemtypes/tool/arrow.json). Складывает
    /// их игра ровно так же: <c>ItemBow.OnHeldInteractStop</c> берёт
    /// <c>attributes["damage"]</c> у лука и у стрелы и СУММИРУЕТ.
    /// </summary>
    public float ArrowDamage(string? code) =>
        ctx.World.GetCollectible(code)?.Attributes?["damage"].AsFloat(0f) ?? 0f;

    /// <summary>
    /// УРОН ОДНОГО ВЫСТРЕЛА тем, что бот носит: лучший лук плюс ХУДШАЯ из
    /// носимых стрел. Ноль — стрелять нечем (нет лука или нет стрел).
    ///
    /// ПОЧЕМУ ХУДШАЯ, А НЕ ЛУЧШАЯ. Какую стрелу возьмёт игра, бот не выбирает:
    /// <c>ItemBow.GetNextArrow</c> берёт ПЕРВУЮ, какая попадётся обходом
    /// <c>WalkInventory</c>, и разложить их в этом порядке бот не умеет (об
    /// этом уже сказано вслух выше). Значит наверняка известно только одно: не
    /// хуже худшей. По этому числу решается «вытяну ли бой», и ошибаться оно
    /// обязано В СТОРОНУ ОСТОРОЖНОСТИ — «этого не завалить», а не наоборот.
    /// </summary>
    public double ShotDamage()
    {
        var bow = BestBow();
        if (bow?.Content.Code is not { Length: > 0 } лук)
            return 0;
        double? худшая = null;
        foreach (var (_, _, content) in ctx.Self.CarrySlots())
            if (IsArrow(content.Code) && content.Count > 0)
            {
                double d = ArrowDamage(content.Code);
                худшая = худшая is { } было ? Math.Min(было, d) : d;
            }
        if (худшая is not { } прибавка)
            return 0;   // стрел нет вовсе — стрелять нечем, и это не «ноль урона»
        return Math.Max(0, BowDamage(лук) + прибавка);
    }

    /// <summary>
    /// ДОЛЯ ПОПАДАНИЯ ПО ЭТОЙ ЦЕЛИ ОТСЮДА — то же число, по которому
    /// <see cref="ShootAsync"/> решает, стрелять ли. Минус — размер цели
    /// реестром не назван, считать нечем.
    ///
    /// ЗАЧЕМ ОНА СНАРУЖИ. Счёт вариантов боя (<see cref="CombatPlan"/>) обязан
    /// знать, сколько стрел уйдёт впустую: «лук бьёт по 2,75» и «лук бьёт по
    /// 2,75 в одном случае из пяти» — это разница между «свалю за 15 с» и
    /// «свалю за 75 с», то есть между честным боем и смертью по расчёту.
    /// Второго счёта доли здесь не заводится: обе стороны зовут
    /// <see cref="PlanShot"/>.
    /// </summary>
    public double ChanceFor(EntityInfo target, double drawSeconds) =>
        PlanShot(target, drawSeconds).Chance;

    /// <summary>
    /// СКОЛЬКО СЕКУНД ТЕТИВА БУДЕТ НАТЯНУТА НА САМОМ ДЕЛЕ — с учётом того, что
    /// на боте надето. Одно место на весь проект.
    ///
    /// ЗАЧЕМ ЭТО СНАРУЖИ. Цикл выстрела (натяг + пауза) считает счёт боя
    /// (<c>CombatFacts.ShotSeconds</c>), и до 27.08 он брал СЫРУЮ ручку
    /// «ТянутьТетивуСекунд», а долю попадания — с ДОТЯНУТОГО натяга: время от
    /// одного выстрела, точность от другого. Числа игры: три латных предмета
    /// дают −0,2 rangedWeaponsSpeed каждый, потолок точности уезжает с 0,54 на
    /// 1,313 с — то есть настоящий цикл 2,513 с против объявленных 2,1, и урон
    /// в секунду был завышен в 1,197 раза. Броню бот в бою надевает сам, так
    /// что это обычный случай, а не угол.
    /// </summary>
    public double DrawTime(double drawSeconds) =>
        DrawTime(drawSeconds, RangedAccPenalty(), AimSpeedMul(BestBow()?.Content.Code));

    private static double DrawTime(double drawSeconds, double накинуто, double скорость)
    {
        double доПотолка = SecondsToTopAccuracy(накинуто, скорость);
        // ТОЛЬКО В БОЛЬШУЮ СТОРОНУ И ТОЛЬКО ТОМУ, КТО ПРОСИЛ ПОЛНЫЙ НАТЯГ:
        // разбор этого выбора стоит у единственного его читателя, PlanShot
        double полныйНатягНалегке = SecondsToTopAccuracy(0, 1);
        return drawSeconds >= полныйНатягНалегке && !double.IsInfinity(доПотолка)
            ? Math.Max(drawSeconds, доПотолка)
            : drawSeconds;
    }

    /// <summary>
    /// ВСЁ, ЧТО ИЗВЕСТНО ПРО ЭТОТ ВЫСТРЕЛ ДО ТОГО, КАК ЕГО ДЕЛАТЬ.
    /// Считается ОДИН раз и одним местом (см. <see cref="PlanShot"/>).
    /// </summary>
    /// <param name="Chance">Доля попадания; минус — размер цели неизвестен.</param>
    internal sealed record ShotPlan(
        SelfState.FoundItem? Bow, int Arrows, double Range,
        AimSolution? Aim, SightResult Seen,
        double Draw, double SecondsToTop, double Spread, double Chance);

    /// <summary>
    /// ПОСЧИТАТЬ ВЫСТРЕЛ, НО НЕ ДЕЛАТЬ ЕГО — И ЭТО ОДНО МЕСТО НА ДВОИХ.
    ///
    /// Спрашивают отсюда двое: сам выстрел (<see cref="ShootAsync"/>) и счёт
    /// вариантов боя (<see cref="ChanceFor"/> → <c>CombatFacts.ShotChance</c>).
    /// Пока это были бы два счёта, они разошлись бы МОЛЧА: бой считал бы «свалю
    /// стрелами за 12 с» по одной доле попадания, а лук отказывался бы стрелять
    /// по другой — и в журнале стояли бы два разных числа про один и тот же
    /// выстрел. Ровно этой болезнью болела точка прицеливания, пока её считали
    /// в двух местах (см. <see cref="SolveFor"/>).
    ///
    /// Вслух отсюда НЕ ГОВОРИТСЯ НИЧЕГО: счёт зовётся каждый тик боя, а слова
    /// — дело того, кто и правда взялся стрелять.
    /// </summary>
    internal ShotPlan PlanShot(EntityInfo target, double drawSeconds)
    {
        var bow = BestBow();
        int arrows = ArrowsCarried();
        if (ctx.Self.Position is not { } me)
            // Где я — сервер ещё не сказал. Врать про дальность и долю нечем
            return new ShotPlan(bow, arrows, 0, null,
                new SightResult
                {
                    Visible = true,
                    Known = false,
                    Target = new BlockPos((int)Math.Floor(target.X),
                        (int)Math.Floor(target.Y), (int)Math.Floor(target.Z))
                },
                drawSeconds, 0, 0, -1);

        double range = target.DistanceTo(me.X, me.Y, me.Z);

        // ЛУЧ ЗРЕНИЯ — ТОТ ЖЕ, ЧТО У БОЯ. Спрашиваем по ногам цели: внутри он
        // сам поднимается на три высоты, и средняя из них — та самая, куда мы
        // и целимся (см. AimAboveFeet)
        var seen = ctx.Hands.Sight.LookAtCreature(target.X, target.Y, target.Z);

        // РАЗМЕР ЦЕЛИ — ИЗ РЕЕСТРА СЕРВЕРА, И ДВЕ КОРОБКИ ЗДЕСЬ РАЗНЫЕ НЕ ПО
        // недосмотру: игра целит контакт по коробке ВЫДЕЛЕНИЯ
        // (hasDirectContact), а попадание стрелы считает по коробке
        // СТОЛКНОВЕНИЙ (TryHitTarget). В ванили они совпадают, у мода — нет
        var hit = ctx.EntityTypes?.HitBox(target.Code);

        var aim = SolveFor(target);

        // РАЗБРОС СЧИТАЕМ ПО ТОМУ ЛУКУ, КОТОРЫМ И БУДЕМ СТРЕЛЯТЬ, И ПО ТОМУ, ЧТО
        // НА БОТЕ НАДЕТО, — до всякого решения: по нему считается доля
        // попадания, им же объясняется отказ. Точность режет БРОНЯ, а не лук
        // (см. RangedAccPenalty), и бот надевает её перед стычкой сам
        double накинуто = RangedAccPenalty();
        double скорость = AimSpeedMul(bow?.Content.Code);

        // СКОЛЬКО НАДО ТЯНУТЬ, ЧТОБЫ ТОЧНОСТЬ УПЁРЛАСЬ В ПОТОЛОК ПРИ ЭТОМ
        // СНАРЯЖЕНИИ — и ДОТЯГИВАЕМ, если ручка просит меньше.
        //
        // ПОЧЕМУ ДОТЯГИВАЕМ, А НЕ ОТКАЗЫВАЕМ. Число зависит не от настройки, а
        // от того, что на боте надето, и знает его только бот: голому хватает
        // 0,54 с, тому же боту в трёх латных предметах нужно 1,31 с. Одевается
        // бот перед стычкой САМ (FitGearAsync(fighting: true)), так что при
        // заводских 0,9 с он не дотягивал до потолка НИКОГДА: живьём 26.08 это
        // дало конус 0,15 рад и долю попадания 0,056 на 12,9 бл — то есть новый
        // порог «СтрелятьПриШансеНеНиже» отверг бы оба выстрела, которые в тот
        // день и правда легли в дрифтера. Дотянув до 1,31 с, бот на той же
        // дистанции получает 0,588.
        //
        // ТОЛЬКО В БОЛЬШУЮ СТОРОНУ И ТОЛЬКО ТОМУ, КТО ПРОСИЛ ПОЛНЫЙ НАТЯГ.
        // Ручка «ТянутьТетивуСекунд» остаётся тем, чем была; вопрос в том, ЧТО
        // человек ею сказал:
        //   • поставил 0,55 и больше — «тяни до упора»: голому боту столько и
        //     нужно (потолок берётся к 0,54 с). Тогда в латах бот дотягивает до
        //     СВОЕГО упора, и это исполнение той же просьбы, а не своеволие:
        //     живой лучник в тех же латах тянул бы ровно столько же (закон 5);
        //   • поставил меньше — «стреляй быстро и криво», и это ОСОЗНАННЫЙ
        //     выбор скорости против точности. Такую просьбу перебивать нельзя:
        //     иначе ручка ниже 0,54 не значила бы вообще ничего.
        // Граница здесь не выдумана — это ровно потолок точности голого бота.
        double доПотолка = SecondsToTopAccuracy(накинуто, скорость);
        double тянуть = DrawTime(drawSeconds, накинуто, скорость);

        double spreadRad = SpreadRadians(тянуть, накинуто,
            moving: false, speedMul: скорость);

        // ДОЛЯ ПОПАДАНИЯ. Минус — «размер цели неизвестен»: реестр ещё не
        // пришёл либо этого типа в нём нет. Тогда порог не спрашивается вовсе
        // (см. WhyNotShoot), и об этом сказано в журнал, а не молчком
        double chance = hit is { } box && aim is { } shot
            ? HitChance(spreadRad, shot.Horizontal, shot.Pitch,
                box.Width, box.Height, shot.AimAboveFeet, DrawStrength())
            : -1;

        return new ShotPlan(bow, arrows, range, aim, seen,
            тянуть, доПотолка, spreadRad, chance);
    }

    /// <summary>
    /// ЧТО НАПИСАНО В ОКОШКЕ ЛУКА про точность
    /// (<c>attributes.statModifier.rangedWeaponsAcc</c>): у простого 0, у
    /// длинного +0,2, у рекурсивного +0,3, у грубого −0,05.
    ///
    /// НА РАЗБРОС ЭТО НЕ ВЛИЯЕТ, И Я ГОВОРЮ ЭТО ВСЛУХ. Сверено ilspycmd по
    /// 1.22.7: единственное место во всей игре, где это число читают, —
    /// <c>ItemBow.GetHeldItemInfo</c>, то есть ПОДСКАЗКА для человека. В стат
    /// <c>rangedWeaponsAcc</c>, по которому считает <c>BaseAimingAccuracy</c>,
    /// пишет только броня (<c>ModSystemWearableStats</c>, ключ
    /// <c>wearablemod</c>). До 26.08 это число подставлялось в
    /// <see cref="SpreadRadians"/> вместо стата брони — и разброс выходил
    /// неверным дважды.
    ///
    /// ОСТАЁТСЯ ОНО РАДИ ВЫБОРА ЛУКА (<see cref="BestBow"/>): между двумя
    /// луками человек выбирает по тому же окошку. Обещание игры это, а не
    /// действующее число, — но других обещаний про луки у нас нет.
    /// </summary>
    public float BowAccuracyLabel(string? code) =>
        ctx.World.GetCollectible(code)?.Attributes?["statModifier"]["rangedWeaponsAcc"].AsFloat(0f) ?? 0f;

    /// <summary>
    /// ПОПРАВКА СНАРЯЖЕНИЯ К ТОЧНОСТИ — живой стат существа
    /// <c>rangedWeaponsAcc</c> минус база 1 (то есть 0 налегке, −0,3 в трёх
    /// латных предметах). Ровно то число, по которому считает игра.
    /// </summary>
    public double RangedAccPenalty() =>
        (ctx.Entities.Self?.StatValue("rangedWeaponsAcc") ?? 1.0) - 1.0;

    /// <summary>
    /// ВО СКОЛЬКО РАЗ БЫСТРЕЕ КОПИТСЯ ТОЧНОСТЬ: стат тела
    /// <c>rangedWeaponsSpeed</c>, умноженный на <c>rangedWeaponsSpeedMul</c>
    /// вещи в руке (<c>BaseAimingAccuracy.Update</c>).
    ///
    /// В ванильной 1.22.7 оба множителя равны единице у любого лука
    /// (<c>rangedWeaponsSpeedMul</c> в ассетах стоит ТОЛЬКО у копья), но
    /// подставлять единицу молча нельзя: мод, зелье и одежда её крутят, и
    /// напечатанный разброс разошёлся бы с настоящим без единого слова.
    /// </summary>
    public double AimSpeedMul(string? code) =>
        (ctx.Entities.Self?.StatValue("rangedWeaponsSpeed") ?? 1.0) *
        (ctx.World.GetCollectible(code)?.Attributes?["rangedWeaponsSpeedMul"].AsFloat(1f) ?? 1f);

    /// <summary>
    /// Лучший лук из носимого: по сумме урона и поправки к точности. null —
    /// лука нет ни в хотбаре, ни в сумках.
    /// </summary>
    public SelfState.FoundItem? BestBow() =>
        ctx.Self.FindBestItem(s => s.Code is { } c && IsBow(c)
            ? 1 + BowDamage(c) + BowAccuracyLabel(c)
            : 0);

    /// <summary>Сколько стрел в сумках всего (хотбар и рюкзак).</summary>
    public int ArrowsCarried()
    {
        int total = 0;
        foreach (var (_, _, content) in ctx.Self.CarrySlots())
            if (IsArrow(content.Code))
                total += content.Count;
        return total;
    }

    // ВЫБОРА ЛУЧШЕЙ СТРЕЛЫ ЗДЕСЬ НЕТ, И ЭТО НЕ ЗАБЫВЧИВОСТЬ (закон 8: что не
    // сделано — называется вслух). Он был написан, звал его ТОЛЬКО тест, и
    // позвать его было некуда: <c>ItemBow.GetNextArrow</c> берёт ПЕРВУЮ стрелу
    // обходом <c>WalkInventory</c>, а не лучшую, и переложить их бот не
    // пробует. Тест при этом назывался «лучшая выбирается по урону» — обещание,
    // которого живой бот не исполнял никогда. Чтобы выбор стал настоящим, надо
    // раскладывать стрелы в сумках в том порядке, в каком их обходит игра; это
    // отдельная работа, и её здесь нет.

    /// <summary>
    /// ОЖИДАЕМЫЙ РАЗБРОС ВЫСТРЕЛА, радиан в каждую сторону — ЧИСТОЕ ПРАВИЛО.
    ///
    /// ЗАЧЕМ ЕГО СЧИТАТЬ, ЕСЛИ КОСТИ ВСЁ РАВНО КИДАЕТ СЕРВЕР. Затем, что от
    /// него зависит, СТОИТ ЛИ ВООБЩЕ стрелять: на 30 блоках недотянутый натяг
    /// даёт конус в десять градусов, то есть промах на пять блоков, и такой
    /// выстрел — просто выброшенная стрела. Это тот же расчёт, который живой
    /// лучник делает опытом («не тянул — не попаду»), и никакого скрытого
    /// знания в нём нет: все числа взяты из формул игры, а не из её случайных
    /// бросков.
    ///
    /// ДО 26.08 ЭТО БЫЛО ОБЕЩАНИЕМ, А НЕ ПРАВДОЙ: разброс считался, печатался
    /// человеку — и решения не принимал НИКАКОГО, потому что
    /// <see cref="WhyNotShoot"/> его не спрашивал. Теперь спрашивает: конус
    /// отсюда идёт в <see cref="HitChance"/>, доля попадания сравнивается с
    /// ручкой роли «СтрелятьПриШансеНеНиже», и безнадёжный выстрел не делается.
    ///
    /// ОТКУДА ФОРМУЛА (<c>BaseAimingAccuracy.Update</c> +
    /// <c>MovingAimingAccuracy.Update</c> + <c>ItemBow.OnHeldInteractStop</c>,
    /// сверено ilspycmd по 1.22.7):
    /// <code>
    ///   потолок = min(1 − 0,075/acc, 1)
    ///   точность = clamp(t · rangedWeaponsSpeed·rangedWeaponsSpeedMul · 1,7; 0; потолок)
    ///   если t ≥ 0,75:  точность += sin(t·8)/80/max(1, acc)      // качание
    ///   точность −= штраф_хода/max(1, acc)
    ///   f        = max(0,001; 1 − точность)
    ///   отклонение = |кость| · f · 0,75,   кость ∈ [−0,5; +0,5]
    /// </code>
    /// то есть НАИБОЛЬШЕЕ отклонение — <c>0,5 · f · 0,75 = 0,375 · f</c>.
    ///
    /// ДВЕ ПОПРАВКИ ПРИЁМКИ, обе настоящие:
    /// <list type="number">
    /// <item>МНОЖИТЕЛЬ СКОРОСТИ НАВОДКИ был потерян. В ванили он равен единице
    /// (стат <c>rangedWeaponsSpeed</c> база 1; <c>rangedWeaponsSpeedMul</c> в
    /// ассетах 1.22.7 стоит только у КОПЬЯ, у луков его нет вовсе) — но БРОНЯ
    /// его режет, и молча считать его единицей нельзя;</item>
    /// <item>КАЧАНИЕ ПОСЛЕ 0,75 с не учитывалось вовсе, а заводской натяг 0,9 с
    /// как раз за этим порогом. Гуляет оно на ±1/80 точности вокруг потолка.</item>
    /// </list>
    ///
    /// КАЧАНИЕ БЕРЁТСЯ СЕРЕДИНОЙ, А НЕ ХУДШЕЙ СТОРОНОЙ, И ЭТО ИСПРАВЛЕНИЕ
    /// 26.08. Стояла худшая сторона с доводом «строка в журнале обещает
    /// „разброс ДО“». Довод был верен, ПОКА ЧИСЛО ТОЛЬКО ПЕЧАТАЛОСЬ; теперь оно
    /// РЕШАЕТ, и пессимизм стоит настоящих выстрелов. В игре качание — это
    /// <c>sin(t·8)/80</c>, оно ходит ВОКРУГ НУЛЯ, и брать его нижнюю точку как
    /// постоянную — значит считать, что боту всегда не везёт. Живое следствие
    /// прежнего счёта поймала приёмка: натяг 0,9 с выходил ХУЖЕ натяга 0,6 с
    /// (0,0328 против 0,0281 рад), а отказ при этом советовал человеку тянуть
    /// ДОЛЬШЕ — то есть крутить ручку в сторону, где становится только хуже.
    ///
    /// ЧТО ЗДЕСЬ ЗА <paramref name="rangedAcc"/> И ПОЧЕМУ ЭТО НЕ ПОПРАВКА ЛУКА.
    /// Игра берёт <c>Stats.GetBlended("rangedWeaponsAcc")</c> — стат СУЩЕСТВА, а
    /// в него пишет ровно один источник: <c>ModSystemWearableStats</c> (броня,
    /// ключ <c>wearablemod</c>). Поправка ЛУКА (<c>attributes.statModifier.
    /// rangedWeaponsAcc</c>) в 1.22.7 в стат НЕ ПОПАДАЕТ ВОВСЕ: единственное её
    /// употребление во всей игре — <c>ItemBow.GetHeldItemInfo</c>, то есть
    /// ПОДСКАЗКА В ОКОШКЕ ПРЕДМЕТА. Сюда подставлялась именно она — и выходило
    /// вдвойне неверно: учитывалось то, чего игра не считает, и терялось то,
    /// что она считает (три латных предмета дают −0,3).
    ///
    /// ЧЕГО ЗДЕСЬ НЕТ, И ЭТО СКАЗАНО ВСЛУХ. <c>SprintAimingAccuracy</c> (−0,3)
    /// не учитывается потому, что бот перед выстрелом ОСТАНАВЛИВАЕТСЯ
    /// (<c>Physics.Stop()</c> в <see cref="Archery.ShootAsync"/>) — бегущим он
    /// не тянет никогда. <c>OnHurtAimingAccuracy</c> не учитывается потому, что
    /// в 1.22.7 его <c>Update</c> вообще не трогает точность: он только гасит
    /// свой счётчик (<c>accuracyPenalty -= dt/3</c>), а вычитания из accuracy в
    /// теле метода нет. Появится в следующей версии — придётся учесть.
    /// И ЕЩЁ ОДНО: штраф хода бот считает нулевым, потому что стоит, — но
    /// накопленный штраф гаснет не мгновенно (<c>dt/2</c> за секунду), так что
    /// сразу после бега настоящий конус чуть шире напечатанного.
    ///
    /// ВАЖНОЕ И НЕОЧЕВИДНОЕ: <paramref name="heldSeconds"/> — это НАСТОЯЩЕЕ
    /// время удержания, а не то раздутое <c>secondsUsed</c>, по которому
    /// считается порог 0,65. Точность копит поведение сущности своими игровыми
    /// тиками, и обмануть её числом шагов нельзя. Оттого и выходит, что порог
    /// натяга берётся уже к 0,41 с настоящего удержания (сервер считает
    /// secondsUsed как своё время между пакетами ПЛЮС 0,02 с за каждый шаг тела,
    /// то есть t·1,6 при 30 тиках в секунду), а потолок точности у голого бота
    /// — только к 0,54 с; в латах же до потолка нужно 1,31 с, и между этими
    /// числами живут все дешёвые промахи.
    /// </summary>
    /// <param name="heldSeconds">Сколько НАСТОЯЩИХ секунд держали тетиву.</param>
    /// <param name="rangedAcc">
    /// Поправка к стату <c>rangedWeaponsAcc</c> СУЩЕСТВА (0 — налегке, −0,3 у
    /// трёх латных предметов). НЕ поправка лука: игра её не применяет.
    /// </param>
    /// <param name="moving">Бот шёл при натяге (штраф до 0,2 за 0,75 с хода).</param>
    /// <param name="speedMul">
    /// <c>rangedWeaponsSpeed</c> тела, умноженный на <c>rangedWeaponsSpeedMul</c>
    /// вещи в руке. В ванильной игре это ровно 1 у голого бота; броня режет его
    /// до 0,4, и ставить сюда единицу молча нельзя.
    /// </param>
    public static double SpreadRadians(double heldSeconds, double rangedAcc = 0,
        bool moving = false, double speedMul = 1.0)
    {
        double acc = BlendedAcc(rangedAcc);
        double held = Math.Max(0, heldSeconds);
        double aimed = Math.Clamp(held * Math.Max(0, speedMul) * 1.7, 0, AccuracyCeiling(rangedAcc));
        // КАЧАНИЕ ПОСЛЕ 0,75 с — sin(t·8)/80 — ходит ВОКРУГ НУЛЯ, поэтому в
        // счёт не входит вовсе: см. разбор в описании метода
        if (moving)
            aimed -= Math.Min(0.2, held / 0.75 * 0.2) / Math.Max(1, acc);
        double f = Math.Max(0.001, 1 - aimed);
        return 0.375 * f;
    }

    /// <summary>Стат точности целиком: база 1 плюс поправка снаряжения.</summary>
    private static double BlendedAcc(double rangedAcc) => Math.Max(0.05, 1 + rangedAcc);

    /// <summary>
    /// ПОТОЛОК ТОЧНОСТИ ИГРЫ (<c>min(1 − 0,075/acc, 1)</c>). Выше него натяг не
    /// поднимает точность, сколько ни держи.
    /// </summary>
    public static double AccuracyCeiling(double rangedAcc) =>
        Math.Min(1 - 0.075 / BlendedAcc(rangedAcc), 1);

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО: СКОЛЬКО СЕКУНД НАДО ТЯНУТЬ, ЧТОБЫ ТОЧНОСТЬ УПЁРЛАСЬ В
    /// ПОТОЛОК. Дольше тянуть незачем, короче — конус шире.
    ///
    /// ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО ЗНАТЬ БОТУ. Затем, что число зависит от
    /// СНАРЯЖЕНИЯ, а не от настройки: голому боту хватает 0,55 с, а тому же
    /// боту в латах (<c>rangedWeaponsSpeed</c> −0,2 за предмет, итого
    /// множитель 0,4) нужно 1,31 с. Заводская ручка «ТянутьТетивуСекунд» стоит
    /// на 0,9 — то есть ОДЕТЫЙ бот не дотягивает до потолка НИКОГДА, а бот
    /// одевается перед каждой стычкой сам (<c>FitGearAsync(fighting: true)</c>).
    /// Живьём 26.08 это дало конус 0,15 рад и долю попадания 0,05 на 12,9 бл:
    /// с новым порогом «СтрелятьПриШансеНеНиже» лук замолчал бы во всех шести
    /// пресетах. Теперь бот считает это число сам и НАЗЫВАЕТ ЕГО В ОТКАЗЕ.
    ///
    /// Ноль или меньше в множителе — «дотянуть нельзя никогда»: отдаём
    /// <see cref="double.PositiveInfinity"/>, а не делим на ноль.
    /// </summary>
    public static double SecondsToTopAccuracy(double rangedAcc, double speedMul) =>
        speedMul <= 0
            ? double.PositiveInfinity
            : AccuracyCeiling(rangedAcc) / (speedMul * 1.7);

    /// <summary>
    /// ВО ЧТО ПРЕВРАЩАЕТСЯ РАЗБРОС НА ЭТОЙ ДАЛЬНОСТИ, блоков вбок. Тот же
    /// конус, только в блоках: человеку в журнале нужно именно это число, а не
    /// радианы.
    /// </summary>
    public static double SpreadBlocks(double range, double heldSeconds,
        double rangedAcc = 0, bool moving = false, double speedMul = 1.0) =>
        Math.Tan(SpreadRadians(heldSeconds, rangedAcc, moving, speedMul)) * Math.Max(0, range);

    /// <summary>
    /// ВЫСОТА, КУДА ЦЕЛИТЬСЯ, над ногами цели — ПО РОСТУ ЦЕЛИ, А НЕ ПО СВОЕМУ.
    ///
    /// Ни доля, ни чей рост брать — не наши: в <c>hasDirectContact</c> самой
    /// игры (<c>AiTaskBaseTargetable</c>, сверено ilspycmd по 1.22.7) средний
    /// луч контакта идёт из <c>стрелок.SelectionBox.Y2·7/16</c> в
    /// <c>ЦЕЛЬ.SelectionBox.Y2·7/16</c> — то есть на своей стороне берётся свой
    /// рост, а на стороне цели — ЕЁ.
    ///
    /// ЗАЧЕМ ЭТО ИСПРАВЛЕНО, ЖИВЫМ СЛУЧАЕМ. Здесь стоял СВОЙ рост на обе
    /// стороны (1,85·7/16 = 0,81 бл), и по курице (0,6 бл ростом) бот целился
    /// на 0,21 бл ВЫШЕ ЕЁ МАКУШКИ, а по зайцу (0,5) — на 0,31 выше. С пяти
    /// блоков, где конус всего ±0,16 бл, это промах ПОЧТИ ВСЕГДА, и объяснить
    /// его было нечем: разброс печатался маленький, а стрелы уходили в траву.
    /// Стало видно только теперь, когда доля попадания считается числом
    /// (<see cref="HitChance"/>): по курице она выходила 0,06 против 0,94.
    ///
    /// РОСТА ЦЕЛИ НЕ ЗНАЕМ (реестр не пришёл, тип незнаком) — берём свой, как
    /// раньше. Это не «примерно верно», а «лучшее, что есть», и для дрифтера с
    /// волком оно и правда близко.
    ///
    /// ЧТО ЗДЕСЬ РАЗОШЛОСЬ С ЛУЧОМ ЗРЕНИЯ, И Я ГОВОРЮ ЭТО ВСЛУХ:
    /// <see cref="Sight.LookAtCreature"/> по-прежнему меряет ОБЕ стороны своим
    /// ростом, потому что в нём написано «рост твари сервер не шлёт». Сервер
    /// его шлёт (см. <see cref="EntityTypes.HitBox"/>), но луч — чужой
    /// механизм, его спрашивают ещё охота и стражник, и правка там отдельная.
    /// Расхождение при этом БЕЗОПАСНОЕ: луч пробует ТРИ высоты и пропускает
    /// выстрел, если прошла хоть одна, а нижняя из них (1/32 над ногами) ниже
    /// любой точки, куда мы теперь целимся.
    /// </summary>
    /// <param name="targetHeight">
    /// Рост цели из реестра сервера (<see cref="EntityTypes.SightBox"/>).
    /// Ноль или меньше — «не знаю», берётся свой рост.
    /// </param>
    public static double AimAboveFeet(double targetHeight) =>
        (targetHeight > 0 ? targetHeight : BodySize.Height) * 7 / 16.0;

    /// <summary>
    /// ДОЛЯ ПОПАДАНИЯ: КАКАЯ ЧАСТЬ ВЫСТРЕЛОВ ЛЯЖЕТ В ТУШУ. Чистое правило,
    /// 0 — не попаду никогда, 1 — попаду всегда.
    ///
    /// ЗАЧЕМ ОНО ЗАВЕДЕНО. Разброс считался и печатался, но решения не
    /// принимал: бот одинаково охотно бил и в дрифтера с восьми блоков, и в
    /// него же с тридцати четырёх, где промахивался четыре раза из пяти. Стрела
    /// стоит наконечника и древка, а копателю в шахте она дороже вдвойне.
    ///
    /// ОТКУДА БЕРЁТСЯ РАСКЛАД КОСТЕЙ — ИЗ ИГРЫ, А НЕ ИЗ ГОЛОВЫ.
    /// <c>EntityBehaviorAimingAccuracy.OnAimingChanged</c> кидает ДВЕ
    /// НЕЗАВИСИМЫЕ кости, <c>Rand.NextDouble() − 0.5</c> каждая, то есть
    /// РОВНО ("равномерно") по отрезку [−0,5; +0,5]; одна идёт в наклон, вторая
    /// в рысканье. <c>ItemBow.OnHeldInteractStop</c> умножает обе на
    /// <c>f·0,75</c>. Значит отклонение — это равномерный КВАДРАТ, а не круг и
    /// не колокол, и половина его стороны — это ровно
    /// <see cref="SpreadRadians"/>. Кости независимы, поэтому доли по двум осям
    /// перемножаются.
    ///
    /// ВБОК считается по прямой: рысканье уводит стрелу на
    /// <c>горизонталь·tg(δ)</c>, и попадание — пока это меньше половины ширины
    /// коробки.
    ///
    /// ВВЕРХ-ВНИЗ считается ТЕМ ЖЕ ПОЛЁТОМ, каким наводились
    /// (<see cref="ArrowFlight.Reach"/>), а не «горизонталь·δ», — и вот честные
    /// числа, ради которых. По ровному месту разница пустяковая: на 30 блоках
    /// полёт даёт 0,973 бл вверх и 0,975 вниз против 0,977 у прямой геометрии,
    /// то есть треть процента, и на решение это не влияет НИКАК. Вся разница
    /// живёт НА КРУТИЗНЕ, а крутизна у этого бота обычная — карьер. Цель на
    /// десять блоков вбок и на ДВАДЦАТЬ ВНИЗ (бот на краю ямы, дрифтер на дне):
    /// ствол опущен на 1,11 рад, стрела приходит почти отвесно, и тот же конус
    /// уводит её на 1,70 бл вверх и 1,95 вниз — ВШЕСТЕРО больше, чем сказала бы
    /// прямая геометрия (0,32). По ней доля вышла бы «попаду наверняка», а на
    /// деле она 0,34.
    ///
    /// И ЗАМЕТЬТЕ: 1,70 против 1,95 — вверх и вниз РАЗНО. Траектория кривая,
    /// поэтому половины конуса стоят разного числа блоков, и считаются они тут
    /// порознь. Симметричная формула этого не умеет вовсе.
    ///
    /// КОРОБКА ЦЕЛИ — ИЗ РЕЕСТРА СЕРВЕРА (<see cref="EntityTypes.HitBox"/>),
    /// та самая, которую игра двигает в положение цели и пересекает с коробкой
    /// стрелы (<c>EntityProjectileBase.TryHitTarget</c>). Она центрирована по
    /// ногам и растёт вверх — отсюда и мерка «сколько над ногами».
    ///
    /// ЧЕГО ЗДЕСЬ НЕТ, И ЭТО СКАЗАНО ВСЛУХ (закон 8). Сперва три поблажки в
    /// сторону «попаду реже, чем на самом деле»:
    /// <list type="number">
    /// <item>СВОЯ ТОЛЩИНА СТРЕЛЫ НЕ СЧИТАЕТСЯ. Пересекаются ДВЕ коробки, и у
    /// стрелы своя — 0,1×0,1 бл (arrow.json). То есть настоящая мишень на
    /// 0,05 бл шире и выше с каждой стороны. Чтобы считать и это, надо знать,
    /// КАКУЮ стрелу возьмёт игра, а выбора стрелы у бота нет вовсе (о чём уже
    /// сказано выше по файлу);</item>
    /// <item>КОРОБКА СТРЕЛЫ РАСТЯНУТА ПО ХОДУ ПОЛЁТА
    /// (<c>AdjustCollisionBox</c> добавляет к ней скорость за тик — около двух
    /// блоков). Стрела, прошедшая чуть выше макушки, иногда всё равно цепляет
    /// цель этим хвостом;</item>
    /// <item>КОРОБКА ЦЕЛИ КВАДРАТНАЯ В ПЛАНЕ и повёрнута по осям МИРА, а не к
    /// стрелку. Наискось она шире в 1,41 раза, и мы всегда берём узкую
    /// сторону.</item>
    /// </list>
    /// А ТЕПЕРЬ В ДРУГУЮ СТОРОНУ — ТО ЕСТЬ «БОТ НАГЛЕЕ ЖИВОГО». Здесь стояло
    /// «все поблажки в одну сторону, бот выходит прижимистее живого лучника, а
    /// не наглее», и это было НЕПРАВДОЙ: приёмка 26.08 назвала две, и обе
    /// настоящие.
    /// <list type="number">
    /// <item>ОШИБКА УПРЕЖДЕНИЯ: цель за время полёта может свернуть, и никакой
    /// счёт этого не знает;</item>
    /// <item>ШТРАФ ХОДА СЧИТАЕТСЯ НУЛЁМ. <see cref="Archery.ShootAsync"/> зовёт
    /// <c>SpreadRadians(moving: false)</c> жёстко, сразу после
    /// <c>Physics.Stop()</c>. В игре штраф <c>MovingAimingAccuracy</c> (до 0,2)
    /// по команде «стой» НЕ ИСЧЕЗАЕТ — он рассасывается по 0,5 в секунду. При
    /// длинном натяге он успевает уйти, но ручка «ТянутьТетивуСекунд» законно
    /// ставится и в 0,35: тогда сразу после погони бегом настоящая точность
    /// ниже расчётной примерно на 0,15, а конус шире напечатанного.</item>
    /// </list>
    /// </summary>
    /// <param name="spread">Половина конуса, радиан (<see cref="SpreadRadians"/>).</param>
    /// <param name="horizontal">Сколько блоков стреле лететь вбок (до точки упреждения).</param>
    /// <param name="pitch">Найденный наклон выстрела (соглашение игры: π — прямо).</param>
    /// <param name="targetWidth">Ширина коробки цели, блоков.</param>
    /// <param name="targetHeight">Высота коробки цели, блоков.</param>
    /// <param name="aimAboveFeet">Куда целимся над ногами (<see cref="AimAboveFeet"/>).</param>
    /// <param name="speed">Стат <c>bowDrawingStrength</c>.</param>
    public static double HitChance(double spread, double horizontal, double pitch,
        double targetWidth, double targetHeight, double aimAboveFeet, double speed = 1.0)
    {
        // Мерить нечем — не «попаду всегда» и не «никогда»: зовущий обязан
        // сперва спросить, знает ли он коробку цели, и сказать это вслух
        if (horizontal <= 0 || targetWidth <= 0 || targetHeight <= 0)
            return 0;

        spread = Math.Max(0, spread);

        // ВБОК. Конус в блоках против половины ширины коробки
        double sideways = spread <= 1e-9
            ? 1
            : Math.Min(1, Math.Atan(targetWidth / 2 / horizontal) / spread);
        if (sideways <= 0)
            return 0;

        // ВВЕРХ-ВНИЗ. Где коробка стоит относительно точки прицеливания: низ
        // ниже неё на aimAboveFeet, верх выше на остаток роста
        double low = -aimAboveFeet, high = targetHeight - aimAboveFeet;
        if (ArrowFlight.Reach(pitch, horizontal, speed) is not { } aimed)
            return 0;

        // На сколько уедет прилёт, если ствол дёрнет на весь конус вверх и на
        // весь конус вниз. null — стрела в этом случае вовсе не долетает: тогда
        // эта половина костей не попадает никуда, и мера её нулевая
        double up = ArrowFlight.Reach(pitch - spread, horizontal, speed) is { } higher
            ? higher.Height - aimed.Height
            : double.PositiveInfinity;
        double down = ArrowFlight.Reach(pitch + spread, horizontal, speed) is { } lower
            ? aimed.Height - lower.Height
            : double.PositiveInfinity;

        // Конуса нет вовсе (тетиву держали до упора и лук идеальный) — вопрос
        // только в том, накрыта ли точка прицеливания коробкой
        if (up <= 0 && down <= 0)
            return low <= 0 && high >= 0 ? sideways : 0;

        // Кость наклона РОВНАЯ, поэтому доля — это просто длина куска отрезка,
        // который лёг в коробку. Верхняя половина костей и нижняя считаются
        // порознь: вверх и вниз стрела уезжает на разное число блоков
        double vertical = Share(up, Math.Max(low, 0), high)
                        + Share(down, Math.Max(-high, 0), -low);

        return Math.Clamp(vertical, 0, 1) * sideways;

        // Какая доля ВСЕХ костей уводит стрелу в одну сторону на расстояние из
        // [from; to], где на весь конус она уходит на reach. Кость ровная, и в
        // эту сторону смотрит ровно половина костей — отсюда деление надвое
        static double Share(double reach, double from, double to)
        {
            if (double.IsInfinity(reach))
                return 0;   // туда стрела не долетает вовсе
            if (reach <= 0 || to <= from)
                return 0;
            double lo = Math.Clamp(from / reach, 0, 1);
            double hi = Math.Clamp(to / reach, 0, 1);
            return Math.Max(0, hi - lo) / 2;
        }
    }

    /// <summary>
    /// ПОСЛЕДНИЙ ДОВОД: КОГДА ПОРОГ ДОЛИ ПОПАДАНИЯ СНИМАЕТСЯ ВОВСЕ.
    ///
    /// Без этой ветки порог убивает бота ПО РАСЧЁТУ, и это не догадка, а прямое
    /// следствие: загнанный в угол бот с луком и без меча посчитал бы «попаду в
    /// одном случае из шести, порог 0,4 — не стреляю» и стоял бы с натянутым
    /// луком, пока его едят. Стрела, потраченная зря, стоит наконечника;
    /// невыстрелившая — жизни.
    ///
    /// ДВА СЛУЧАЯ, И КАЖДОГО ХВАТАЕТ ПООДИНОЧКЕ:
    /// • ЗАГНАН В УГОЛ — побег только что не удался (<c>CombatChoice.Cornered</c>,
    ///   ставится после <c>FailedRunsBeforeCornered</c> сорванных попыток).
    ///   «Подожду выстрела получше» тут не ответ: подходить будут к НАМ;
    /// • НЕЧЕМ БИТЬ ВБЛИЗИ — настоящего оружия ближнего боя нет
    ///   (<c>WeaponStandard.IsWeapon</c>). Тогда лук — не «лучший из способов»,
    ///   а единственный, и беречь стрелы не для чего: следующий ход всё равно
    ///   будет кулаком;
    /// • ПОДХОДИТЬ К НЕМУ НЕЛЬЗЯ — он созывает подмогу
    ///   (<c>CombatDanger.CallsForHelp</c>, в игре 1.22.7 это колокол). Случай
    ///   тот же самый: ближнего боя не будет, значит лук снова единственный
    ///   способ. Без этой ветки выходило бы прямое противоречие в журнале —
    ///   «подойду ближе» в отказе стрелять при решении «не подхожу».
    /// </summary>
    public static bool LastResort(bool cornered, bool haveMelee,
        bool mustKeepDistance = false) => cornered || !haveMelee || mustKeepDistance;

    /// <summary>Числа словами в том падеже, в каком они тут и стоят («из пяти»).</summary>
    private static readonly string[] Числительные =
        ["", "одном", "двух", "трёх", "четырёх", "пяти", "шести", "семи",
         "восьми", "девяти", "десяти", "одиннадцати", "двенадцати"];

    private static string Словом(int n) =>
        n >= 0 && n < Числительные.Length ? Числительные[n] : n.ToString();

    /// <summary>
    /// ДОЛЯ ПОПАДАНИЯ ЧЕЛОВЕЧЕСКИМИ СЛОВАМИ: «примерно в одном случае из пяти».
    /// Проценты в журнале боя читаются хуже: «0,19» надо переводить в голове, а
    /// «один из пяти» — нет.
    ///
    /// СЧИТАЕТСЯ ПО РЕДКОЙ СТОРОНЕ, И ЭТО НЕ УКРАШЕНИЕ. Стояло «один случай из
    /// round(1/доля)» на любую долю, и для всего пояса 0,667…0,95 это давало
    /// round = 1 при пустом слове в таблице — то есть ОБОРВАННОЕ предложение:
    /// «попаду примерно в одном случае из  (0,78)». Пояс тот — БОЛЬШИНСТВО
    /// удачных выстрелов (дрифтер в 12 бл 0,78, волк в 20 бл 0,71, заяц в 8 бл
    /// 0,91), то есть врала как раз та строка, ради которой долг и закрывали.
    /// Поймано приёмкой 26.08; прежний стенд щупал 0,2, 0,33 и 0,98 — обе
    /// стороны дыры и ни одной внутри.
    ///
    /// Выше половины считаем ПРОМАХИ и говорим «в четырёх случаях из пяти»:
    /// доля остаётся долей ПОПАДАНИЯ, предложение после «попаду» не ломается, а
    /// точность у частого исхода берётся оттуда, где её больше.
    /// </summary>
    public static string OddsInWords(double chance)
    {
        if (chance >= 0.95)
            return "почти наверняка";
        if (chance <= 0)
            return "не попаду вовсе";
        int всего, разы;
        if (chance <= 0.5)
        {
            разы = 1;
            всего = (int)Math.Round(1 / chance, MidpointRounding.AwayFromZero);
        }
        else
        {
            всего = Math.Max(2, (int)Math.Round(1 / (1 - chance), MidpointRounding.AwayFromZero));
            разы = всего - 1;
        }
        return $"примерно в {Словом(разы)} {(разы == 1 ? "случае" : "случаях")} " +
               $"из {Словом(всего)}";
    }

    /// <summary>
    /// ГДЕ ДУЛО: глаза бота, сдвинутые на 0,21 бл вперёд по рысканью
    /// (см. <see cref="ArrowFlight.MuzzleAhead"/>). Присед опускает глаза с
    /// 1,7 до 1,36 — а присед под ботом бывает не только по своей воле (щит,
    /// низкий потолок), поэтому спрашиваем ТЕЛО, а не предполагаем.
    /// </summary>
    public double EyeHeight =>
        ctx.Body is { Physics.Controls.Sneak: true } ? BodySize.CrouchEyeHeight : BodySize.EyeHeight;

    /// <summary>
    /// РЕШИТЬ НАВОДКУ ПО ЦЕЛИ: рысканье, наклон, время полёта. null — не
    /// достать (дальше, чем летит стрела, либо выстрел не влезает в наклон
    /// живого клиента).
    ///
    /// УПРЕЖДЕНИЕ СЧИТАЕТСЯ В ДВА ЗАХОДА, и это не изящество, а необходимость:
    /// время полёта зависит от того, куда целимся, а целимся мы по времени
    /// полёта. Первый заход даёт время до нынешнего места цели, второй —
    /// уточняет по сдвинутой точке. Третий заход меняет ответ уже на сантиметры.
    /// </summary>
    /// <param name="fromX">Ноги бота.</param>
    /// <param name="targetX">Ноги цели.</param>
    /// <param name="driftX">Замеренный ход цели, блоков в секунду (0 — стоит).</param>
    /// <param name="speed">Стат <c>bowDrawingStrength</c>, база 1.</param>
    /// <param name="targetHeight">
    /// Рост цели из реестра сервера. Ноль — «не знаю», и тогда точка
    /// прицеливания считается по своему росту (см. <see cref="AimAboveFeet"/>).
    /// </param>
    public static AimSolution? Solve(
        double fromX, double fromY, double fromZ,
        double targetX, double targetY, double targetZ,
        double driftX, double driftZ, double eyeHeight, double speed = 1.0,
        double targetHeight = 0)
    {
        double aimY = targetY + AimAboveFeet(targetHeight);
        double ax = targetX, az = targetZ;
        AimSolution? best = null;

        for (int pass = 0; pass < 2; pass++)
        {
            double dx = ax - fromX, dz = az - fromZ;
            double flat = Math.Sqrt(dx * dx + dz * dz);
            float yaw = ArrowFlight.YawTo(dx, dz);

            // Дуло стоит на 0,21 бл ВПЕРЁД по рысканью — значит лететь ему
            // ровно на столько меньше (имя BehindCopy обманчиво, см. там же)
            double horizontal = flat - ArrowFlight.MuzzleAhead;
            if (horizontal <= 0.01)
                return null;

            if (ArrowFlight.Aim(horizontal, aimY - (fromY + eyeHeight), speed) is not { } shot)
                return null;

            double range = Math.Sqrt(
                (targetX - fromX) * (targetX - fromX) +
                (targetZ - fromZ) * (targetZ - fromZ));
            // ТОЧКА ПРИЦЕЛИВАНИЯ ЕДЕТ ВМЕСТЕ С РЕШЕНИЕМ, и это не удобство, а
            // закон 2. Её считают двое: наводка (сюда, чтобы навести ствол) и
            // доля попадания (чтобы понять, накрыта ли туша). Пока каждый
            // считал её сам, они могли разойтись МОЛЧА — и приёмка 26.08 это
            // показала: рост цели выбрасывался из наводки, ствол уезжал выше
            // макушки, а доля по-прежнему считалась по правильной точке, и ни
            // один стенд не краснел. Теперь число одно
            best = new AimSolution(yaw, shot.Pitch, shot.Seconds, ax, az, range,
                horizontal, AimAboveFeet(targetHeight));

            // Второй заход — по точке, где цель окажется к прилёту стрелы
            ax = targetX + driftX * shot.Seconds;
            az = targetZ + driftZ * shot.Seconds;
        }
        return best;
    }

    /// <summary>
    /// ЧТО МЕШАЕТ ВЫСТРЕЛУ — СЛОВАМИ И С ИМЕНЕМ РУЧКИ. Пусто — не мешает
    /// ничего.
    ///
    /// ЧИСТОЕ ПРАВИЛО, И ЭТО ВАЖНО: живьём проверить его нельзя (нужен сервер,
    /// стрелы и дрифтер), а ошибиться дорого в обе стороны — лишнее «можно»
    /// тратит стрелы в стену, лишнее «нельзя» оставляет бота с луком
    /// безоружным. Все причины отказа названы ЗДЕСЬ и только здесь, чтобы в
    /// журнале не завелось двух разных объяснений одного отказа.
    /// </summary>
    /// <param name="arrows">Сколько стрел в сумках.</param>
    /// <param name="haveBow">Лук нашёлся.</param>
    /// <param name="range">Расстояние до цели, блоков.</param>
    /// <param name="minRange">Ближе этого не стреляем — ручка роли.</param>
    /// <param name="maxRange">Дальше этого не стреляем — ручка роли.</param>
    /// <param name="sightKnown">Луч зрения удалось посчитать.</param>
    /// <param name="visible">Цель видна (луч дошёл).</param>
    /// <param name="blockedBy">Во что упёрся луч (для слов отказа).</param>
    /// <param name="solved">Наводка решилась (стрела дотягивается).</param>
    /// <param name="chance">
    /// Доля попадания (<see cref="HitChance"/>). Отрицательная — РАЗМЕР ЦЕЛИ
    /// НЕИЗВЕСТЕН (реестр не пришёл либо тип незнаком), и тогда порог не
    /// спрашивается вовсе: незнание — не запрет, ровно как с лучом зрения.
    /// </param>
    /// <param name="minChance">С какой доли стрелять — ручка роли.</param>
    /// <param name="lastResort">
    /// Выстрел — последнее, что осталось (<see cref="LastResort"/>). Порог
    /// снимается: лучше стрела в землю, чем смерть по расчёту.
    /// </param>
    /// <param name="spreadBlocks">Конус в блоках на этой дальности — для слов.</param>
    /// <param name="heldSeconds">Сколько бот тянул («ТянутьТетивуСекунд»).</param>
    /// <param name="secondsToTop">
    /// Сколько тянуть, чтобы точность упёрлась в потолок при НЫНЕШНЕМ
    /// снаряжении (<see cref="SecondsToTopAccuracy"/>). Ноль или меньше —
    /// «неизвестно», и тогда про натяг не говорим вовсе.
    ///
    /// РАДИ ЧЕГО ЭТИ ДВА ЧИСЛА ВООБЩЕ ЗДЕСЬ. Отказ обязан называть ручку,
    /// которую надо повернуть (закон 4), — а он называл ручку, которая помочь
    /// НЕ МОЖЕТ. При заводских 0,9 с голый бот давно на потолке, и совет
    /// «дам тетиве натянуться дольше» не менял ничего; одетый же бот до
    /// потолка не дотягивает никогда, и ему нужно было ровно это — но числа
    /// ему никто не называл. Поймано приёмкой 26.08 на шипованных числах.
    /// </param>
    public static string WhyNotShoot(int arrows, bool haveBow, double range,
        double minRange, double maxRange, bool sightKnown, bool visible,
        string? blockedBy, bool solved,
        double chance = -1, double minChance = 0, bool lastResort = false,
        double spreadBlocks = 0, double heldSeconds = 0, double secondsToTop = 0)
    {
        if (!haveBow)
            return "лука нет ни в руках, ни в сумках";
        if (arrows <= 0)
            return "стрелы кончились — стрелять нечем; сколько их держать при " +
                   "себе, говорит ручка «ЗапасПоРасходу» (строкой «arrow к bow»), " +
                   "«КрафтитьНедостающее» и «ДобыватьНедостающее»";
        if (range < minRange)
            return $"он в {range:0.#} бл — ближе ручки «СтрелятьНеБлижеЧем» " +
                   $"({minRange:0.#}): на такой дистанции натяг дороже удара";
        if (range > maxRange)
            return $"до него {range:0.#} бл — дальше ручки «СтрелятьНеДальше» " +
                   $"({maxRange:0.#})";
        // «НЕ ЗНАЮ, ВИДНО ЛИ» — ЭТО НЕ ЗАПРЕТ И НЕ РАЗРЕШЕНИЕ, а «считать было
        // нечем» (реестр блоков не пришёл, позиции нет). Преграду мы тогда НЕ
        // ПРИДУМЫВАЕМ — ровно так же поступает бой (WhatSeparates): стена,
        // которой не видели, такой же обман, как удар сквозь неё. Прежний
        // комментарий здесь утверждал ОБРАТНОЕ коду, и приёмка была права
        if (sightKnown && !visible)
            return $"между нами {blockedBy ?? "преграда"} — сквозь неё живой игрок не стреляет";
        if (!solved)
            return "стрела туда не дотягивается: слишком далеко или слишком " +
                   "круто вверх для наклона живого игрока";
        // ПОРОГ ДОЛИ ПОПАДАНИЯ — ПОСЛЕДНИМ, И ЭТО НЕ ПРИДИРКА К ПОРЯДКУ. Он
        // единственный, который СНИМАЕТСЯ (см. lastResort), и единственный, чей
        // отказ звучит «подойди ближе», а не «так нельзя». Стой он выше — бот
        // говорил бы «попаду редко» там, где на самом деле между ним и целью
        // стена, и человек чинил бы не то.
        //
        // Отрицательная доля — «размер цели неизвестен». Тогда молчим и
        // стреляем: придумать за сервер ширину дрифтера нельзя, а запрет по
        // невычисленному числу оставил бы бота с луком безоружным на всю
        // сессию, если реестр типов почему-то не пришёл
        if (!lastResort && chance >= 0 && chance < minChance)
            return $"до него {range:0.#} бл, разброс до {spreadBlocks:0.#} бл — " +
                   $"{OddsInWords(chance)} ({chance:0.00}), а ручка " +
                   $"«СтрелятьПриШансеНеНиже» просит {minChance:0.##}. " +
                   ЧтоКрутитьРадиТочности(heldSeconds, secondsToTop);
        return "";
    }

    /// <summary>
    /// ЧТО ЧЕЛОВЕКУ ДЕЛАТЬ С ЭТИМ ОТКАЗОМ — ЧЕСТНО, А НЕ ВЕЖЛИВО.
    ///
    /// Совет «тяни дольше» имеет смысл РОВНО ПОКА ТОЧНОСТЬ РАСТЁТ. Дотянув до
    /// потолка, бот дальше не выигрывает ничего, и повторять этот совет —
    /// значит гонять человека крутить ручку впустую. А вот когда до потолка не
    /// дотянуто (одетый бот при заводских 0,9 с не дотягивает НИКОГДА), надо
    /// назвать не только ручку, но и ЧИСЛО: угадывать его человек не обязан.
    /// </summary>
    public static string ЧтоКрутитьРадиТочности(double heldSeconds, double secondsToTop)
    {
        if (secondsToTop <= 0 || double.IsInfinity(secondsToTop))
            return "Подойду ближе — тетива тут уже не поможет";
        if (heldSeconds >= secondsToTop)
            return "Подойду ближе: тетива натянута до упора, дольше тянуть " +
                   "бесполезно (точность уперлась в потолок игры)";
        // ПРИЧИНУ НАЗЫВАЕМ, ТОЛЬКО ЕСЛИ ОНА ЕСТЬ. Голому боту до потолка нужно
        // 0,54 с, и говорить ему «броня режет наводку» — врать в глаза: брони
        // на нём нет, а короткий натяг человек выбрал сам
        double налегке = SecondsToTopAccuracy(0, 1);
        return $"Подойду ближе — или поставьте «ТянутьТетивуСекунд» не меньше " +
               $"{secondsToTop:0.00} с: столько нужно, чтобы натянуть до упора " +
               $"(сейчас тяну {heldSeconds:0.##} с)" +
               (secondsToTop > налегке * 1.2
                   ? ". Так долго — из-за надетого: броня режет скорость наводки"
                   : "");
    }

    /// <summary>
    /// СТРЕЛЬНУТЬ ПО ЦЕЛИ — ЧЕСТНО И ПО ФАКТУ.
    ///
    /// Порядок ровно тот, в каком это делает живой игрок: взять лук в руку,
    /// встать, навестись, натянуть, довести прицел за ушедшей целью, отпустить.
    ///
    /// УСПЕХ СЧИТАЕТСЯ ПО УБЫЛИ СТРЕЛ, а не по «пакет ушёл», и без этого вся
    /// стрельба была бы враньём: сервер без стрел (или с луком не в том слоте,
    /// или с недотянутой тетивой) НИЧЕГО НЕ ОТВЕЧАЕТ — он просто не открывает
    /// удержание. Стрела же уходит из слота через <c>TakeOut(1)</c> и
    /// <c>MarkDirty</c>, то есть сервер сам присылает нам новый вид сумки. Вот
    /// это и есть факт.
    /// </summary>
    /// <param name="target">Цель — берётся её ЖИВОЕ положение, а не снимок.</param>
    /// <param name="drawSeconds">
    /// НИЖНЯЯ граница натяга в настоящих секундах — ручка роли. Меньше 0,41 —
    /// выстрела не будет вовсе (порог игры 0,65 раздутых секунд). СВЕРХУ бот
    /// сам дотянет, если снаряжение требует дольше: см. SecondsToTopAccuracy.
    /// </param>
    /// <param name="minRange">Ближе не стрелять (ручка роли).</param>
    /// <param name="maxRange">Дальше не стрелять (ручка роли).</param>
    /// <param name="minChance">
    /// С КАКОЙ ДОЛИ ПОПАДАНИЯ БРАТЬСЯ — ручка роли «СтрелятьПриШансеНеНиже».
    /// Ноль означает «порога нет», и зовущему такое лучше не оставлять молча:
    /// именно так стрелы и уходят в белый свет.
    /// </param>
    /// <param name="lastResort">
    /// Порог снять: стрелять больше нечем и уйти некуда
    /// (<see cref="LastResort"/>).
    /// </param>
    public async Task<bool> ShootAsync(EntityInfo target, double drawSeconds,
        double minRange, double maxRange, double minChance = 0,
        bool lastResort = false, CancellationToken ct = default)
    {
        if (ctx.Self.Position is null)
        {
            SayOnce("не стреляю: где я — сервер ещё не сказал");
            return false;
        }

        var plan = PlanShot(target, drawSeconds);
        var bow = plan.Bow;
        int arrows = plan.Arrows;
        double range = plan.Range;
        var seen = plan.Seen;
        var aim = plan.Aim;
        double доПотолка = plan.SecondsToTop;
        double тянуть = plan.Draw;
        double spreadRad = plan.Spread;
        double chance = plan.Chance;

        if (тянуть > drawSeconds + 1e-6)
            SayOnce($"тяну тетиву {тянуть:0.00} с вместо {drawSeconds:0.##} " +
                    "(«ТянутьТетивуСекунд»): в том, что на мне надето, точность " +
                    "растёт медленнее, и до потолка раньше не дотянуть");

        if (chance < 0 && aim != null && minChance > 0)
            SayOnce($"стреляю в {target.Code} без счёта долей: какого он размера, " +
                   "сервер в реестре типов не назвал — порог «СтрелятьПриШансеНеНиже» " +
                   "спросить не у чего");

        string why = WhyNotShoot(arrows, bow != null, range, minRange, maxRange,
            seen.Known, seen.Visible, seen.BlockedByCode, aim != null,
            chance, minChance, lastResort,
            Math.Tan(spreadRad) * Math.Max(0, aim?.Horizontal ?? range),
            тянуть, доПотолка);
        if (why.Length > 0)
        {
            SayOnce($"не стреляю в {target.Code}: {why}");
            return false;
        }

        // ЛУК ОБЯЗАН БЫТЬ В АКТИВНОМ СЛОТЕ ХОТБАРА 0..9. Сервер берёт предмет
        // по номеру слота из пакета и при SlotId ≥ 10 лезет в рюкзак — из
        // левой руки лук не выстрелит никогда. Руки это уже умеют: найдут в
        // сумке, освободят место в хотбаре, переложат и подтвердят ФАКТОМ
        // ИМЕННО ТОТ ЛУК, о котором мы считали разброс и о котором скажем в
        // журнале. Прежде здесь стояло «любой лук» (IsBow), а точность и строка
        // брались у BestBow: с двумя луками в сумке бот печатал «выстрел из
        // bow-long» и число разброса про один лук, а стрелял другим
        string лук = bow!.Content.Code!;
        if (await ctx.Hands.TakeToHandAsync(s => s.Code == лук, ct) is null)
        {
            SayOnce($"не стреляю: {лук} в руку не встал — рука занята или в хотбаре нет места");
            return false;
        }

        // СТОЯ ТОЧНЕЕ, И ЭТО ЧИСЛО ИГРЫ: MovingAimingAccuracy снимает до 0,2
        // точности за 0,75 с хода и возвращает её только за 2 с покоя. Живой
        // лучник по той же причине останавливается перед выстрелом
        ctx.Body?.Physics?.Stop();

        int before = ArrowsCarried();
        float pitchWas = ctx.Body?.Physics?.Pitch ?? ArrowFlight.Level;

        try
        {
            await AimAsync(target, ct);

            // ТЯНЕМ И ДОВОДИМ ПРИЦЕЛ. Цель за секунду натяга уходит на метр-два,
            // и живой игрок ведёт её стволом всё это время. Отпускание уходит
            // из самих рук (finally внутри UseHeldAsync), поэтому последняя
            // наводка приходится ровно на выстрел
            var draw = ctx.Hands.UseHeldAsync(Math.Max(0, тянуть), ct: ct);
            while (!draw.IsCompleted)
            {
                await Task.Delay(60, ct).ContinueWith(_ => { });
                if (ct.IsCancellationRequested)
                    break;
                await AimAsync(target, ct);
            }
            await draw;

            // ФАКТ ОТ СЕРВЕРА: стрела ушла из сумки. Ждём ПО ФАКТУ, а не глухой
            // паузой, — сервер отвечает и за сорок миллисекунд
            var until = DateTime.UtcNow.AddMilliseconds(Math.Max(1, ShotSettleMs));
            while (DateTime.UtcNow < until)
            {
                if (ArrowsCarried() < before)
                {
                    // Разброс — ТОТ ЖЕ, по которому принималось решение, а не
                    // посчитанный заново: двумя счётами он однажды разошёлся бы
                    // с решением, и в журнале стояло бы «разброс 0,4», а отказ
                    // говорил бы про 0,9
                    double spread = Math.Tan(spreadRad) * Math.Max(0, aim!.Horizontal);
                    OnLog?.Invoke(
                        $"выстрел из {лук} по {target.Code}: {aim.Range:0.#} бл, " +
                        $"лететь {aim.Seconds:0.00} с, разброс до {spread:0.#} бл, " +
                        (chance >= 0
                            ? $"попаду {OddsInWords(chance)} ({chance:0.00})" +
                              (lastResort ? " — стреляю всё равно: больше нечем" : "") + ", "
                            : "размера цели реестр не назвал, ") +
                        $"стрел осталось {ArrowsCarried()}");
                    return true;
                }
                await Task.Delay(20, ct).ContinueWith(_ => { });
            }

            // МОЛЧАНИЕ СЕРВЕРА — ЭТО ОТКАЗ, А НЕ УСПЕХ. Ровно так выглядит и
            // «тетиву не дотянул» (порог 0,65), и «лук оказался не в том
            // слоте», и «стрелы лежали в закрытом инвентаре»
            // ПОРОГ ИГРЫ — 0,41 с НАСТОЯЩЕГО удержания, а не 0,3 с, и это
            // считано, а не прикинуто: сервер берёт secondsUsed как СВОЁ время
            // между пакетами «начал» и «отпустил» ПЛЮС 0,02 с за каждый шаг
            // тела (ServerSystemInventory.callOnUsing: secondsPassed += 0,02f).
            // Тело тикает 30 раз в секунду (GlobalConstants.PhysicsFrameTime),
            // значит secondsUsed ≈ t·1,6, и порог 0,65 берётся при t ≥ 0,41
            SayOnce(
                $"выстрел не состоялся: стрел как было {before}, так и осталось. " +
                $"Тянул {тянуть:0.##} с — если меньше 0,41 с, игра выстрел не " +
                "засчитывает вовсе (ручка «ТянутьТетивуСекунд»)");
            return false;
        }
        finally
        {
            // ВЗГЛЯД ВОЗВРАЩАЕМ НА ГОРИЗОНТ. Без этого бот уходит копать,
            // задрав голову в небо: наклон живёт в теле и сам не сбрасывается,
            // а вся остальная работа считает, что смотрят прямо
            if (ctx.Body?.Physics is { } phys)
                phys.Pitch = pitchWas;
        }
    }

    /// <summary>
    /// Сколько ждать убыли стрел, миллисекунд. Это ПОТОЛОК, а не пауза: ждём
    /// ровно до факта.
    /// </summary>
    public int ShotSettleMs { get; set; } = 700;

    /// <summary>
    /// Сила натяга по СТАТУ СЕРВЕРА (<c>bowDrawingStrength</c>, база 1,0). Не
    /// постоянная: моды и зелья её крутят, а вместе с ней меняется вся
    /// баллистика. Спрашиваем сущность, как её спрашивает сама игра.
    /// </summary>
    private double DrawStrength() =>
        ctx.Entities.Self?.StatValue("bowDrawingStrength") ?? 1.0;

    /// <summary>
    /// Довести взгляд на цель: корпус — через общее движение (у него своя
    /// скорость поворота, мгновенных разворотов у живого игрока нет), наклон —
    /// прямо телу, потому что наклоном не распоряжается больше никто.
    /// </summary>
    private async Task AimAsync(EntityInfo target, CancellationToken ct)
    {
        if (ctx.Self.Position is not { } me || ctx.Entities.Get(target.Id) is not { } live)
            return;
        if (SolveFor(live) is not { } aim)
            return;

        if (ctx.Body?.Physics is { } phys)
            phys.Pitch = Math.Clamp(aim.Pitch, ArrowFlight.PitchUpLimit, ArrowFlight.PitchDownLimit);
        await ctx.Movement.FaceAsync(aim.AimX, aim.AimZ, ct);
    }

    /// <summary>
    /// НАВОДКА ПО ЦЕЛИ — ОДНА НА ВЕСЬ ФАЙЛ, и это не причёсывание, а правило 2
    /// закона в самом опасном месте.
    ///
    /// Спрашивают её ДВОЕ и по-разному: решение (<see cref="ShootAsync"/>) —
    /// один раз, чтобы посчитать долю попадания; ведение ствола
    /// (<see cref="AimAsync"/>) — каждые шестьдесят миллисекунд всего натяга.
    /// Пока это были два отдельных вызова, между ними мог тихо разойтись любой
    /// довод — рост цели, замер хода, сила натяга. И разошёлся бы САМЫМ
    /// подлым образом: доля посчитана по одной точке прицеливания, ствол
    /// наведён в другую, а журнал честно докладывает «попаду почти наверняка».
    ///
    /// ЖИВЬЁМ ЭТО ПРОВЕРИТЬ СТЕНДОМ НЕЛЬЗЯ, И Я ГОВОРЮ ЭТО ВСЛУХ: наклон живёт
    /// в игровом теле (<c>Body.Physics.Pitch</c>), а у стендового бота тела нет
    /// вовсе — <c>ctx.Body</c> там null, и строка выше просто не выполняется.
    /// Значит подмену «забыть рост цели в ведении ствола» не поймает ни один
    /// тест; её ловит только то, что забывать теперь негде.
    /// </summary>
    private AimSolution? SolveFor(EntityInfo target)
    {
        if (ctx.Self.Position is not { } me)
            return null;
        // Ход цели меряет тот же механизм, что и «догоню ли» в бою: свой
        // второй замер здесь развёл бы упреждение с оценкой боя молча
        var (driftX, driftZ) = pace.Drift(target.Id, DateTime.UtcNow);
        return Solve(me.X, me.Y, me.Z, target.X, target.Y, target.Z,
            driftX, driftZ, EyeHeight, DrawStrength(), TargetHeight(target.Code));
    }

    /// <summary>
    /// Рост цели по реестру сервера, 0 — «не знаю». Коробка ВЫДЕЛЕНИЯ, потому
    /// что высоту контакта игра меряет ею (<c>hasDirectContact</c>), а не
    /// коробкой столкновений.
    /// </summary>
    private double TargetHeight(string? code) =>
        ctx.EntityTypes?.SightBox(code)?.Height ?? 0;
}
