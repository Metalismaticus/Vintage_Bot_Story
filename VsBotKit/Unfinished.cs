namespace VsBotKit;

/// <summary>
/// ОДНО НЕЗАКРЫТОЕ ДЕЛО: то, что бот УЖЕ начал и ещё не закончил.
/// </summary>
/// <param name="Kind">
/// Какого рода незакрытое (<see cref="Unfinished.Возврат"/> и соседи). По нему
/// и решают, чем его закрывать, и по нему же ведётся безнадёга: ключ должен
/// быть постоянным, а не меняться вместе с содержимым сумки.
/// </param>
/// <param name="What">Что именно осталось — человеческими словами и с числами.</param>
/// <param name="Why">
/// Почему это считается незакрытым. Это та самая половина, ради которой
/// заказчик и просил «говорить, что доделываешь»: без неё в журнале стоит
/// «доделываю запасы» и понять из этого нечего.
/// </param>
/// <param name="Count">
/// Сколько штук незакрыто. Нужно не для отчёта: по нему <see cref="Unfinished.Moved"/>
/// отличает «заход сдвинул дело» от «заход прошёл впустую».
/// </param>
/// <param name="Mine">
/// Доделывать это МНЕ. false — за дело уже взялись без меня (прерванная работа
/// ждёт освобождения тела), и простою тут остаётся ровно одно: не мешать и
/// сказать, чего именно он ждёт.
/// </param>
public sealed record LooseEnd(string Kind, string What, string Why, int Count, bool Mine = true)
{
    public override string ToString() => $"{What} — {Why}";
}

/// <summary>
/// ХВОСТЫ — ОДИН ВОПРОС НА ВСЕХ: что бот начал и не закончил.
///
/// ЖИВОЙ СЛУЧАЙ, ради которого написано (журнал заказчика, 16.08). Бот открыл
/// вторую дверь тамбура и ушёл; путь сорвался сразу за створкой:
///   12:45:13 [движение] открыл дверь (512062, 112, 512252)
///   12:45:14 [движение] упёрся на точке 3/4 …
/// и дальше про эту дверь ни слова до 14:39. А в 13:01:06, 13:07:24, 13:14:32,
/// 13:27:48 в том же журнале стоит «без дела 60 с — стою, так настроено»: бот
/// бездельничал ЧЕТЫРЕЖДЫ, и ни разу никто не спросил его, что за ним осталось.
/// Долг за дверь при этом тикает ТОЛЬКО НА ХОДУ (см. Movement): бот, открывший
/// дверь и никуда больше не пошедший, молчал бы про неё до утра.
///
/// ПОЧЕМУ ОДИН ВОПРОС, А НЕ ТРИ ПРОВЕРКИ ВРАЗНОБОЙ. Незакрытое помнят разные
/// механизмы и по-разному: движение — долгом за двери, стройка — стоящими
/// лесами, возврат — списком ждущих работ. Спроси их поимённо внутри безделья —
/// и завтра, когда заведут четвёртый вид хвоста, простой про него не узнает и
/// промолчит. Здесь один список и один порядок, и добавлять новое надо СЮДА.
///
/// ЧЕГО ЗДЕСЬ НЕТ. Ни своей памяти, ни своих действий: закрывает хвост тот же
/// механизм, который его и завёл (<see cref="TempBlocks.TakeDownAsync"/> и
/// уплата долга за двери в <see cref="Movement"/>). Второй копии ни у одного из
/// них здесь нет и быть не должно.
///
/// НЕДОДЕЛАННЫЙ ИНСТРУМЕНТ СЮДА НЕ ВХОДИТ — И ЭТО НАРОЧНО. То самое «вытесал
/// топорище и не соединил его с палкой» доделывает отдельная способность
/// хозяйства (<see cref="BehaviorFinishStarted"/> и <see cref="Stock.StartedWork"/>),
/// и она стоит ВПЕРЕДИ безделья по весу. Простой про недобранное снаряжение
/// только ГОВОРИТ (<see cref="Запасы"/>, «доделывать не мне»): позови он ту же
/// цепочку сам — вышли бы две ручки на одно решение, и человек, снявший
/// «ДоделыватьНачатое», всё равно видел бы, как бот собирает ножи.
///
/// ЧЕГО ПРОЕКТ НЕ ПОМНИТ ВОВСЕ — И ЭТО НАДО ЗНАТЬ. Недобранного покрытия дороги
/// в памяти НЕТ: ряды и клетки живут внутри одного захода
/// (<see cref="RoadReport"/>), а между заходами их держит только возврат
/// (<see cref="RoadResume"/>) — пока он жив. Кончилась дорога — от неё остаётся
/// строка в журнале и состояние задачи в очереди («не вышла» с причиной), а не
/// незакрытое дело. Поэтому дороги в этом списке нет: выдумывать её память
/// значило бы обещать доделывание, которого не будет.
/// </summary>
public static class Unfinished
{
    /// <summary>Прерванная работа ждёт освобождения тела, чтобы доделаться сама.</summary>
    public const string Возврат = "возврат";

    /// <summary>За ботом числятся открытые им двери (<see cref="DoorDebt"/>).</summary>
    public const string Двери = "двери";

    /// <summary>За ботом стоят временные леса, которые он обещал снять.</summary>
    public const string Леса = "леса";

    /// <summary>
    /// Цепочка запасов не доведена до конца: лезвие есть, ножа нет. Доделывает
    /// её НЕ простой, а хозяйство (<see cref="BehaviorFinishStarted"/>); здесь
    /// про неё только говорят вслух — см. разбор у самого класса.
    /// </summary>
    public const string Запасы = "запасы";

    // ---------------- чистые правила ----------------

    /// <summary>
    /// ЗА ЧТО БРАТЬСЯ ПЕРВЫМ. ЧИСТОЕ ПРАВИЛО: ни бота, ни мира — только список и
    /// ответ «на это мы уже махнули рукой».
    ///
    /// Порядок берётся ТОТ, В КОТОРОМ СОБРАЛИ (<see cref="Of"/>), и он же есть
    /// порядок важности — второй сортировки здесь нет нарочно: разъедься они, и
    /// человек читал бы в журнале одно, а бот делал бы другое.
    ///
    /// Безнадёжное пропускается, а не отменяет остальное: «за ножом больше не
    /// хожу» не повод бросить открытую дверь.
    /// </summary>
    /// <param name="found">Что нашлось, в порядке важности.</param>
    /// <param name="hopeless">Про этот род уже сдались (см. <see cref="Hopeless"/>).</param>
    public static LooseEnd? First(IEnumerable<LooseEnd> found, Func<string, bool> hopeless) =>
        found.FirstOrDefault(e => !hopeless(e.Kind));

    /// <summary>
    /// СДВИНУЛСЯ ЛИ ЗАХОД С МЕСТА — чистое правило, и на нём висит вся защита от
    /// долбёжки.
    ///
    /// Мерка не «получилось ли», а «стало ли меньше»: уборка, снявшая девять
    /// лесов из десяти, успехом себя не считает (<see cref="TempCleanup.Success"/>)
    /// — и правильно делает, — но браться за неё снова СТОИТ. А вот заход,
    /// который ничего не закрыл, повторять через минуту незачем: помеха та же,
    /// и выйдет ровно тот шум, ради ухода от которого заведена безнадёга.
    /// </summary>
    public static bool Moved(bool closed, int before, int after) => closed || after < before;

    /// <summary>
    /// ЧТО СКАЗАТЬ, БЕРЯСЬ ЗА НЕЗАКРЫТОЕ. Обязательное: заказчик просил, чтобы
    /// бот в простое говорил, ЧТО он доделывает и почему, а не молча уходил.
    /// </summary>
    public static string Say(LooseEnd end) => end.Mine
        ? $"доделываю начатое ({end.Kind}): {end.What} — {end.Why}"
        : $"начатое доделаю не я: {end.What} — {end.Why}; не занимаю тело и жду";

    /// <summary>
    /// ЧТО СКАЗАТЬ ПРО ЗАХОД, КОТОРЫЙ НЕ СДВИНУЛ ДЕЛО. Уходит в безнадёгу как
    /// причина — и оттуда человеку вслух.
    /// </summary>
    public static string SayStuck(LooseEnd end, string why) =>
        $"доделать «{end.What}» не вышло: {why}";

    /// <summary>
    /// ЧТО ДЕЛАТЬ С ОЧЕРЕДЬЮ ЗАДАЧ В ПРОСТОЕ — ЧИСТОЕ ПРАВИЛО, и молчаливого
    /// ответа среди возможных нет.
    ///
    /// ЗАКАЗ ЧЕЛОВЕКА, дословно: «допустим задавать цикл задач, если они есть».
    /// Очередь в проекте одна (<see cref="WorkPlan"/>), и вторую заводить
    /// нельзя: список работ человек и так набирает в окне управления, а два
    /// списка разъехались бы в первый же вечер.
    ///
    /// ПУСТОЙ КРУГ НЕ ПОВТОРЯЕМ. Круг, не сделавший НИ ОДНОЙ задачи, второй раз
    /// даст ровно то же самое — а бот будет всю ночь гонять по кругу отказы.
    /// Это тот же приём, что у безнадёги: раз не вышло — сказать и перестать.
    /// </summary>
    /// <param name="mode">Ручка роли «ОчередьЗадачВПростое».</param>
    /// <param name="runnerBusy">Бегун очереди уже ведёт задачу.</param>
    /// <param name="pending">Сколько задач ждут своей очереди (включённых).</param>
    /// <param name="total">Сколько задач в очереди вообще.</param>
    /// <param name="lastLapEmpty">Прошлый круг не сделал ни одной задачи.</param>
    public static (bool Run, bool Repeat, string Why) QueueInIdle(IdleJobs mode, bool runnerBusy,
        int pending, int total, bool lastLapEmpty)
    {
        if (mode == IdleJobs.Нет)
            return (false, false, "очередь задач в простое не трогаю — так настроено " +
                                  "(ручка роли «ОчередьЗадачВПростое»: Нет)");

        if (runnerBusy)
            return (false, false, "очередь уже идёт — второй раз её не пускаю");

        if (pending > 0)
            return (true, false, $"в очереди ждут задач: {pending} — берусь за них, раз других дел нет");

        if (total == 0)
            return (false, false, "очередь пуста: задач в ней нет вовсе — " +
                                  "наберите их в окне управления, вкладка задач");

        if (mode == IdleJobs.Пройти)
            return (false, false, $"очередь пройдена вся ({total} задач), " +
                                  "а повторять её не велено (ОчередьЗадачВПростое: Пройти)");

        if (lastLapEmpty)
            return (false, false, "прошлый круг не сделал НИ ОДНОЙ задачи — по кругу больше не иду, " +
                                  "пока очередь не поправят: причины у каждой задачи в её итоге");

        return (true, true, $"очередь пройдена вся ({total} задач) — начинаю круг заново " +
                            "(ОчередьЗадачВПростое: ПоКругу)");
    }

    // ---------------- живая половина: что незакрыто прямо сейчас ----------------

    /// <summary>
    /// ЧТО У БОТА ОСТАЛОСЬ НЕЗАКРЫТЫМ — один вопрос ко всем, кто это помнит.
    ///
    /// ПОРЯДОК ЕСТЬ ВАЖНОСТЬ, и выбран он по цене промедления, а не по вкусу:
    ///
    /// 1. ВОЗВРАТ К ПРЕРВАННОМУ — впереди всего, потому что это единственный
    ///    случай, когда простою надо НЕ ДЕЛАТЬ, а посторониться: работа уже
    ///    ждёт освобождения тела (<see cref="Resume.Waiting"/>), и забрать тело
    ///    под уборку значило бы добить её вместо помощи.
    /// 2. ДВЕРИ — дешевле всего (клик с места, без единого шага), а открытая
    ///    ночью створка пускает в дом кого угодно. И это единственное место, где
    ///    долг за дверь вообще спрашивают у СТОЯЩЕГО бота: движение платит его
    ///    только на ходу и в конце похода, а бот, который открыл дверь и никуда
    ///    больше не пошёл, молчал бы про неё до самого утра.
    /// 3. ЛЕСА — снимаются на месте, и забытые посреди чужой постройки хуже,
    ///    чем не построенные вовсе.
    /// 4. ЗАПАСЫ — последними и НЕ НАШИМИ РУКАМИ: за них отвечает хозяйство
    ///    (<see cref="BehaviorFinishStarted"/>), стоящее впереди безделья по
    ///    весу. Простой их называет вслух и не трогает.
    /// </summary>
    public static IReadOnlyList<LooseEnd> Of(BotContext ctx)
    {
        var found = new List<LooseEnd>();

        // 1. ПРЕРВАННОЕ ЖДЁТ ВОЗВРАТА. Список короток и живёт мгновениями между
        // заходами — но именно в эти мгновения тело свободно, а значит простой
        // видит бота бездельничающим и вправе увести его домой из-под работы
        var ждут = ctx.Resume.Waiting;
        if (ждут.Count > 0)
            found.Add(new LooseEnd(Возврат,
                $"прерванная работа: {string.Join(", ", ждут.Select(w => $"«{w}»"))}",
                "её перебили, и она ждёт, когда освободится тело, чтобы доделаться сама",
                ждут.Count, Mine: false));

        // 2. ДВЕРИ, КОТОРЫЕ БОТ ОТКРЫЛ САМ. Спрашиваем и при запрещающей
        // настройке: правило долга тогда откажется ВСЛУХ и с координатами
        // (DoorDebt.PayRule), а молча висящий долг — это дверь, про которую
        // человек узнает через неделю
        if (ctx.Movement.Doors is { Count: > 0 } двери)
            found.Add(new LooseEnd(Двери,
                // БЕЗ СВОИХ СКОБОК ВОКРУГ СПИСКА: клетка печатает свои сама
                // (BlockPos.ToString → WorldOrigin.Say), и снаружи выходило
                // «дверей: 1 ((62, 112, 252))» — двойные скобки на ровном месте
                $"открытых мной дверей: {двери.Count} — " +
                string.Join("; ", двери.Owed.Take(4).Select(d => d.Door.ToString())),
                "я их открыл и ещё не закрыл — это мой долг перед миром",
                двери.Count));

        // 3. ВРЕМЕННЫЕ ЛЕСА. Запрещённую настройкой уборку сюда не берём: обещать
        // доделывание, которого не будет, нельзя, а сказать про эти блоки уже
        // сказала сама работа (TempBlocks.OweRule)
        if (ctx.Temp is { Count: > 0 } леса && леса.TakeDownAfterWork)
            found.Add(new LooseEnd(Леса,
                // Скобки — у самой клетки, а не вокруг списка (см. выше)
                $"временных блоков за мной стоит: {леса.Count} — " +
                string.Join("; ", леса.Standing.Take(3).Select(b => b.ToString())),
                "я обещал снять их, когда работа кончится, а работа кончилась",
                леса.Count));

        // 4. ЦЕПОЧКА ЗАПАСОВ — НЕ НАШИМИ РУКАМИ. Тот самый нож: лезвие вытесано,
        // палка в сумке, а требование «держать нож» не закрыто. Доделывает это
        // хозяйство, и второй ручки на то же решение здесь заводить нельзя;
        // но и промолчать про недобранное снаряжение простой не вправе — иначе
        // человек читает «без дела 60 с — стою» и не знает, чего боту не хватает
        if (ctx.Stock is { } запасы && запасы.Missing() is { Count: > 0 } нехватка)
            found.Add(new LooseEnd(Запасы,
                $"недобранное снаряжение: {string.Join(", ", нехватка)}",
                "цепочка «добыть → вытесать → собрать» не доведена до конца; " +
                "собрать начатое на месте берётся хозяйство (ручка роли «ДоделыватьНачатое»), " +
                "а ходить за материалом — наряд: в простое я за этим не хожу",
                нехватка.Count, Mine: false));

        return found;
    }

    /// <summary>
    /// ЗАКРЫТЬ ХВОСТ — ТЕМ ЖЕ МЕХАНИЗМОМ, КОТОРЫЙ ЕГО И ЗАВЁЛ.
    ///
    /// Своей работы здесь нет ни строчки: двери закрывает движение, леса снимает
    /// уборка. Вторая копия любого из них означала бы, что однажды одна из двух
    /// перестанет спрашивать «а не упаду ли, сняв этот блок из-под собственных
    /// ног».
    ///
    /// Ответ честный и всегда со словами: «закрыл» — это ПО ФАКТУ от механизма,
    /// а не по тому, что мы его позвали.
    /// </summary>
    public static async Task<(bool Closed, string Why)> FinishAsync(BotContext ctx, LooseEnd end,
        CancellationToken ct)
    {
        switch (end.Kind)
        {
            case Возврат:
                // Тут делать нечего по устройству: доделает сама работа, а наше
                // дело — не занять тело у неё под носом
                return (false, end.Why);

            case Двери:
            {
                int было = ctx.Movement.Doors.Count;
                await ctx.Movement.PayDoorDebtsAsync(ct: ct);
                int стало = ctx.Movement.Doors.Count;
                return стало == 0
                    ? (true, $"дверей за мной больше не числится (было {было})")
                    : (false, $"дверей за мной осталось {стало} из {было}: до них не дотянуться " +
                              "с того места, где стою — правило долга скажет про каждую отдельно");
            }

            case Леса:
            {
                if (ctx.Temp is not { } леса)
                    return (false, "уборка лесов к боту не подключена");
                var убрано = await леса.TakeDownAsync(ct: ct);
                return (убрано.Success, убрано.ToString());
            }

            case Запасы:
                // Сюда мы не попадаем: у этого хвоста Mine = false, и простой
                // до дела не доходит. Ветка оставлена честной, а не пустой:
                // позови её кто-нибудь — он получит имя того, кто за это отвечает
                return (false, end.Why);

            default:
                // Род незакрытого, которого здесь не разобрали, — это забытая
                // ветка, а не повод молчать
                return (false, $"не знаю, чем закрывать незакрытое рода «{end.Kind}»");
        }
    }
}
