using Axis = Vintagestory.API.MathTools.EnumAxis;
using VsBlock = Vintagestory.API.Common.Block;
using BreakIfFloating = Vintagestory.GameContent.BlockBehaviorBreakIfFloating;

namespace VsBotKit;

/// <summary>
/// ЗАБОЙ РАБОТЫ: вдоль какой оси она продвигается и с какой координаты
/// начинает. Больше ничего шахматке о работе знать не нужно.
///
/// ПЛОСКОСТЬ НЕ ЗАШИТА, И ЭТО СЛОВА ЗАКАЗЧИКА (03.09): «она не только бывает
/// вертикальной, но и горизонтальной, если мы роем тоннель, как пример с
/// дорогой горизонтальной в горе, бот должен это понимать и уметь». У карьера
/// забой горизонтальный, а работа уходит ВНИЗ — ось Y. У штольни в горе забой
/// вертикальный, работа уходит вдоль хода — ось X или Z. Правило одно, ось
/// разная, и называет её та работа, которая бьёт.
///
/// ОСЬ БЕРЁТСЯ У ИГРЫ (<see cref="Vintagestory.API.MathTools.EnumAxis"/>), а не
/// своим перечислением из трёх букв: её же возвращает <c>BlockFacing.Axis</c>,
/// и работа, которая знает свою сторону света, приносит ось оттуда без
/// пересказа.
/// </summary>
/// <param name="Ось">Вдоль чего работа продвигается.</param>
/// <param name="Начало">
/// Координата вдоль <paramref name="Ось"/> у ПЕРВОГО слоя — того, с которого
/// работа начинает: у карьера это верхний слой, у хода — ближний к устью. От
/// неё и считается чередование «добычный слой — слой-жертва»
/// (<see cref="WholeStone.ДобычныйСлой"/>).
/// </param>
public readonly record struct Забой(Axis Ось, int Начало);

/// <summary>
/// ЦЕЛЬНЫЙ КАМЕНЬ: ОДНО ПРАВИЛО НА ВЕСЬ ПРОЕКТ О ТОМ, ОТ ЧЕГО ЗАВИСИТ, ЧТО
/// ВЫПАДЕТ С КАМЕННОГО БЛОКА.
///
/// ЧТО СКАЗАЛА САМА ИГРА (проверено 28.08, ванильная 1.22.7; ни одного числа
/// и ни одного списка из головы):
///
///   1. ОБЫЧНЫЙ УДАР ДАЁТ ЩЕБЁНКУ. assets/survival/blocktypes/stone/rock.json,
///      «dropsByType»: с любого rock-* падает ПРЕДМЕТ <c>stone-{rock}</c>,
///      количеством avg 2.5. Самого блока в выпадениях нет вовсе.
///
///   2. ЦЕЛЫЙ БЛОК ДАЁТ ТОЛЬКО ПОЛНАЯ ИЗОЛЯЦИЯ. Тот же rock.json объявляет
///      поведение <c>BreakIfFloating</c>, а его код (VSSurvivalMod.dll,
///      <see cref="BreakIfFloating"/>) в <c>GetDrops</c> перебивает выпадения
///      блока и возвращает <c>new ItemStack(block, 1)</c> — РОВНО ОДИН ЦЕЛЫЙ
///      БЛОК — при условии <c>IsSurroundedByNonSolid</c>. А оно требует, чтобы
///      НИ ОДНА из ШЕСТИ граней (BlockFacing.ALLFACES) не упиралась в твёрдую
///      сторону соседа (<c>IsSideSolid</c>). Не пять граней, не «открыта хоть
///      одна» — ВСЕ ШЕСТЬ.
///
///   3. ИНСТРУМЕНТ НА ЭТО НЕ ВЛИЯЕТ. В rock.json у выпадений нет ни одного
///      условия по инструменту; кирка решает только, поддастся ли блок вообще
///      и как быстро (<c>requiredMiningTier: 2</c>, <c>resistance: 8</c>).
///      Значит «взять целым» — вопрос ПОРЯДКА УДАРОВ, а не снаряжения.
///
///   4. ИГРА ГОВОРИТ ЭТО ЧЕЛОВЕКУ САМА. В том же rock.json лежит строка
///      справочника: attributes.handbook.extraSections —
///      «Full block can be obtained by breaking all adjacent blocks».
///      То есть заказчик, прося «шахматку», пересказывал справочник игры.
///
/// ОТСЮДА И «СЛОЙ ТОЛЩЕ 1», слова заказчика: «чтобы мы не копали из камня,
/// когда слой толще 1, то нужно „шахматкой“ копать для добычи цельных блоков».
/// Это не прикидка, а следствие пункта 2: у слоя толщиной в одну клетку
/// нижняя грань упирается в нетронутую породу, шестая грань не освобождается
/// НИКОГДА, и целого блока с такого слоя не будет, сколько вокруг ни копай.
/// Городить там шахматку — терять время без единого целого блока.
///
/// ПОЧЕМУ ОТДЕЛЬНЫЙ КЛАСС. Правило нужно ДВУМ разным работам: карьеру (он
/// раскладывает шахматкой целый ОБЪЁМ) и поручению «добудь камень» (там надо
/// освободить шесть граней ОДНОЙ клетки). Раньше оно жило только внутри
/// карьера, и второму делу пришлось бы завести копию — а копия правила «что
/// выпадает с камня» разъехалась бы с первой к вечеру, как уже разъезжались
/// рукописные списки приставок (проект горел на них пять раз).
///
/// Класс — МЕХАНИЗМ и только: он отвечает «выпадет ли целым» и «какие грани
/// освободить». Стоит ли платить за это лишними ударами, решает роль
/// (ручка «ОбкапыватьРадиЦельногоБлока»).
/// </summary>
public static class WholeStone
{
    /// <summary>
    /// ИМЯ ПОВЕДЕНИЯ ИГРЫ, по которому блок при полной изоляции выпадает целым.
    ///
    /// Берётся у самой игры: SurvivalCoreSystem регистрирует его как
    /// RegisterBlockBehaviorClass("BreakIfFloating", typeof(BlockBehaviorBreakIfFloating)),
    /// а класс лежит в VSSurvivalMod.dll, на которую ссылается проект. Так
    /// переименование в игре сломает СБОРКУ, а не молча выключит проверку.
    /// </summary>
    public static string BehaviorName { get; } = ResolveBehaviorName();

    private static string ResolveBehaviorName()
    {
        const string prefix = "BlockBehavior";
        try
        {
            string name = BehaviorClassName();
            return name.StartsWith(prefix, StringComparison.Ordinal) ? name[prefix.Length..] : name;
        }
        catch
        {
            return "BreakIfFloating";
        }
    }

    // Обращение к типу из VSSurvivalMod вынесено в ОТДЕЛЬНЫЙ метод намеренно
    // (тем же приёмом живёт Gathering.PickupBehaviorClassName): сборка типа
    // проверяется при первом вызове метода, поэтому не загрузись мод —
    // исключение поймает try выше, а не уронит бота на старте
    [System.Runtime.CompilerServices.MethodImpl(
        System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private static string BehaviorClassName() => typeof(BreakIfFloating).Name;

    /// <summary>
    /// ВЫПАДЕТ ЛИ ЭТОТ БЛОК ЦЕЛЫМ, ЕСЛИ ЕГО ИЗОЛИРОВАТЬ, — СПРОШЕНО У РЕЕСТРА.
    ///
    /// Имя поведения сервер шлёт пакетом реестра, и хранит его модель мира
    /// (<see cref="WorldModel.HasBlockBehavior(int, string)"/>). Списка
    /// приставок тут нет и быть не может: в самой ванили 1.22.7
    /// <c>BreakIfFloating</c> стоит не только у rock-*, но и у crackedrock-*,
    /// ore-*, meteorite-*, rottenlog-*, termitemound-* и
    /// termitemound-harvested-* (проверено по assets/survival/blocktypes), а
    /// под приставку «rock-» из них подходит меньше половины. Для модовой
    /// породы список не работал бы вовсе.
    /// </summary>
    public static bool DropsWholeWhenFloating(WorldModel world, int blockId) =>
        blockId > 0 && world.HasBlockBehavior(blockId, BehaviorName);

    /// <summary>То же по коду блока.</summary>
    public static bool DropsWholeWhenFloating(WorldModel world, string? code) =>
        code is { Length: > 0 } &&
        world.BlockCodeToId(code) is { } id && DropsWholeWhenFloating(world, id);

    /// <summary>
    /// ПРОСЯТ САМ БЛОК, А ОБЫЧНЫМ УДАРОМ ОН НЕ ВЫПАДАЕТ — значит бить его в
    /// лоб бессмысленно, сколько ни бей.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ради которого правило и написано. Поручение
    /// («добудь rock-granite 20») выбирает источник одной меркой:
    /// <see cref="Gathering.Gives(string, IEnumerable{string}, string)"/> — «блок даёт нужное, либо он сам им
    /// зовётся, либо нужное есть среди его выпадений». Для гранита срабатывала
    /// ПЕРВАЯ половина: блок и вправду зовётся rock-granite. А выпадает с него
    /// stone-granite — щебёнка. Бот честно бил породу, честно подбирал
    /// щебёнку, и ни одного rock-granite в сумке не появлялось НИКОГДА: наряд
    /// доходил до конца отведённого времени и объявлял неудачу, не назвав
    /// настоящей причины.
    ///
    /// «ПРОСЯТ САМ БЛОК» — ЭТО РАВЕНСТВО КОДА, А НЕ ПОДСТРОКА, И ВОТ ПОЧЕМУ.
    ///
    /// Здесь стояла общая мерка «код содержит слово» (<see cref="Gathering.Holds"/>),
    /// и на просьбу «rock-granite» под неё подходил ещё и <c>crackedrock-granite</c>
    /// — треснувшая порода, у которой тоже есть BreakIfFloating, а падает с неё
    /// тот же stone-granite. В живом журнале стенда 28.08 они стоят рядом
    /// дословно: «беру rock-granite: подходящих блоков в реестре 2 (например
    /// rock-granite, crackedrock-granite)».
    ///
    /// ЧЕМ ЭТО КОНЧАЛОСЬ. Бот обкапывал ТРЕСНУВШУЮ породу, получал целый
    /// crackedrock-granite, и счёт «сколько у меня rock-granite» рос — потому
    /// что он тоже подстрочный. Человек просил двадцать гранитов и получал
    /// двадцать треснувших блоков с докладом об успехе. До обкапывания эта же
    /// подстрока давала ЧЕСТНЫЙ НОЛЬ (падала щебёнка с другим именем), то есть
    /// обкапывание превратило честную неудачу в тихий подлог — закон 4.
    ///
    /// ПОДСТРОКА ОСТАЁТСЯ ТАМ, ГДЕ ОНА ПРАВА: выбор источника у сбора
    /// (loosestones-granite-free даёт stone-granite) на ней и держится. Здесь
    /// вопрос другой — «принесём ли мы РОВНО ТО, что просили», — и ответ на
    /// него подстрокой не даётся. Просьба не совпала с кодом дословно — блок
    /// добывается как обычно, щебёнкой, и счёт честно не растёт.
    /// </summary>
    /// <param name="drops">Обычные выпадения блока (реестр, <see cref="Gathering.DropsOf"/>).</param>
    public static bool OnlyByIsolation(WorldModel world, string code,
        IEnumerable<string> drops, string wanted) =>
        string.Equals(code, wanted, StringComparison.OrdinalIgnoreCase) &&
        !drops.Any(d => Gathering.Holds(d, wanted)) &&
        DropsWholeWhenFloating(world, code);

    /// <summary>
    /// Твёрдая ли грань соседа — повторяет BlockAccessorBase.IsSideSolid:
    /// сперва слой жидкостей (там бывает лёд, и он твёрдый), если пусто или у
    /// жидкости нет ни одной твёрдой грани — слой блоков.
    ///
    /// Пока реестра нет, считаем твёрдым: осторожность важнее оптимизма —
    /// иначе бот объявил бы «сейчас упадёт целым» про блок в непрогруженном
    /// чанке и получил бы щебёнку.
    /// </summary>
    public static bool SideSolidAt(WorldModel world, int x, int y, int z, int faceIndex)
    {
        if (!world.GameBlocksReady)
            return true;
        int fluidId = world.GetLiquidId(x, y, z);
        VsBlock b = world.GetGameBlockById(fluidId);
        if (fluidId == 0 || !b.SideSolid.Any)
            b = world.GetGameBlock(x, y, z);
        return b.SideSolid[faceIndex];
    }

    /// <summary>
    /// ЧИСТОЕ ПРАВИЛО ИГРЫ: ни одного твёрдого соседа по всем шести граням —
    /// точная копия <c>BlockBehaviorBreakIfFloating.IsSurroundedByNonSolid</c>.
    /// Именно это условие и заставляет блок выпасть целиком.
    ///
    /// Мир сюда не приходит нарочно: правило проверяется без сервера и без
    /// кирки, а <paramref name="solid"/> отвечает на один вопрос —
    /// «упирается ли грань в твёрдую сторону соседа». Направление отдаём
    /// вместе с клеткой затем, что игра спрашивает у соседа ПРОТИВОПОЛОЖНУЮ
    /// грань (<c>f.Opposite</c>), а не «твёрдый ли он вообще».
    /// </summary>
    public static bool Floats(BlockPos cell, Func<BlockPos, Facing, bool> solid)
    {
        for (int i = 0; i < Facing.ALLFACES.Length; i++)
        {
            var f = Facing.ALLFACES[i];
            if (solid(new BlockPos(cell.X + f.Normali.X, cell.Y + f.Normali.Y,
                    cell.Z + f.Normali.Z), f))
                return false;
        }
        return true;
    }

    /// <summary>
    /// То же по живому миру. ВТОРОГО ПЕРЕБОРА ГРАНЕЙ ТУТ НЕТ НАРОЧНО: «висит»
    /// — это ровно «никто не держит», и спрашивается оно у
    /// <see cref="HoldingSides"/>. Пока перебор стоял здесь во второй раз,
    /// два предиката об одном и том же жили рядом в одном файле и согласия
    /// между ними не держало ничто (закон 2).
    /// </summary>
    public static bool Floats(WorldModel world, BlockPos cell) =>
        HoldingSides(world, cell).Count == 0;

    /// <summary>
    /// СКОЛЬКО У КЛЕТКИ ГРАНЕЙ — спрошено у игры (<c>BlockFacing.ALLFACES</c>),
    /// а не написано шестёркой. Число нужно тем, кто обкапывает блок по одной
    /// стороне за круг: столько кругов и бывает, больше — только если кто-то
    /// ставит блоки навстречу.
    /// </summary>
    public static int Faces => Facing.ALLFACES.Length;

    /// <summary>Шесть соседей клетки — в том же порядке, в каком их перебирает игра.</summary>
    public static IReadOnlyList<BlockPos> Neighbours(BlockPos cell)
    {
        var all = new List<BlockPos>(Facing.ALLFACES.Length);
        for (int i = 0; i < Facing.ALLFACES.Length; i++)
        {
            var f = Facing.ALLFACES[i];
            all.Add(new BlockPos(cell.X + f.Normali.X, cell.Y + f.Normali.Y, cell.Z + f.Normali.Z));
        }
        return all;
    }

    /// <summary>
    /// КАКИЕ ГРАНИ ЕЩЁ ДЕРЖАТ БЛОК — то есть что придётся снять, чтобы он упал
    /// целым. Пусто — блок уже висит, бей и получай целый.
    ///
    /// НИЖНИЙ СОСЕД ИДЁТ ПОСЛЕДНИМ — И ЭТО ПОРЯДОК САМОЙ ИГРЫ, А НЕ НАШ.
    /// <c>BlockFacing.ALLFACES</c> = { NORTH, EAST, SOUTH, WEST, UP, DOWN }
    /// (разобрано ilspycmd по VintagestoryAPI.dll 1.22.7), то есть DOWN и так
    /// стоит шестым. Он и должен быть последним по делу: пока стоят боковые,
    /// бот работает стоя рядом; сними пол под целью раньше — и придётся
    /// тянуться к оставшимся граням через дыру, а то и свалиться в неё самому.
    ///
    /// ЗДЕСЬ СТОЯЛА ПЕРЕСТАНОВКА, КОТОРАЯ ЭТОГО «ДОБИВАЛАСЬ», и она не меняла
    /// НИ ОДНОГО списка: приёмка 28.08 сняла её целиком и не получила ни одного
    /// красного. Правило, которого нет, и тест, который его «проверяет», — это
    /// ровно тот жанр, который в этом проекте ловят. Порядок теперь берётся у
    /// игры как есть, а закреплён он проверкой самого <c>ALLFACES</c>.
    /// </summary>
    public static IReadOnlyList<BlockPos> HoldingSides(WorldModel world, BlockPos cell)
    {
        var hold = new List<BlockPos>(6);
        for (int i = 0; i < Facing.ALLFACES.Length; i++)
        {
            var f = Facing.ALLFACES[i];
            var n = new BlockPos(cell.X + f.Normali.X, cell.Y + f.Normali.Y, cell.Z + f.Normali.Z);
            if (SideSolidAt(world, n.X, n.Y, n.Z, f.Opposite.Index))
                hold.Add(n);
        }
        return hold;
    }

    /// <summary>
    /// КУДА БИТЬ СЕЙЧАС, ЧТОБЫ ОСВОБОДИТЬ ГРАНЬ ЦЕЛИ — чистое правило.
    ///
    /// ЗАЧЕМ ОНО ОТДЕЛЬНО. Приёмка 28.08 доказала геометрией, что «снять шесть
    /// соседей» невыполнимо в лоб: удар требует ПРЯМОЙ ВИДИМОСТИ, а сосед,
    /// замурованный породой, не виден НИОТКУДА. Ровный выход породы — цель в
    /// верхнем слое, сверху воздух: четыре боковых снимаются легко, а НИЖНИЙ
    /// после этого закрыт сверху самой целью и с боков — породой слоем ниже.
    /// Прежний перебор упирался в него всегда, оставляя человеку четыре дыры и
    /// пустую сумку.
    ///
    /// ЧТО ДЕЛАЕТ ЖИВОЙ ИГРОК: прокапывается к нему. Правило и говорит, что
    /// снять СЕЙЧАС: видимую грань — или тот блок, который закрывает невидимую.
    ///
    /// САМУ ЦЕЛЬ НЕ ТРОГАЕМ НИ ПРИ КАКИХ УСЛОВИЯХ: сломай её сейчас — она
    /// рассыплется щебёнкой, ради ухода от которой всё и затевалось.
    /// </summary>
    /// <param name="держат">грани, которые ещё держат (<see cref="HoldingSides"/>)</param>
    /// <param name="цель">добываемый блок — его ломать нельзя</param>
    /// <param name="видно">видна ли клетка отсюда (луч бота, <c>Sight.LookAt</c>)</param>
    /// <param name="чтоЗакрывает">что перекрыло луч до клетки (null — сказать нечем)</param>
    public static СледующийУдар КудаБить(IReadOnlyList<BlockPos> держат, BlockPos цель,
        Func<BlockPos, bool> видно, Func<BlockPos, BlockPos?> чтоЗакрывает)
    {
        if (держат.Count == 0)
            return new СледующийУдар(null, null);

        foreach (var сторона in держат)
            if (видно(сторона))
                return new СледующийУдар(сторона, null);

        var closest = держат[0];
        if (чтоЗакрывает(closest) is not { } мешает)
            return new СледующийУдар(null,
                $"до соседа {closest} не дотянуться, а чем он закрыт — сказать нечем " +
                "(реестр блоков не пришёл)");
        if (мешает.Equals(цель))
            return new СледующийУдар(null,
                $"сосед {closest} закрыт САМИМ добываемым блоком — обойти его отсюда " +
                "нечем. Встаньте с другой стороны или дайте эту работу там, где порода " +
                "открыта сбоку");
        return new СледующийУдар(мешает, null, ПрокопКСоседу: closest);
    }

    /// <summary>
    /// Что бить сейчас: клетка или отказ с причиной. Обе половины пусты — все
    /// грани уже сняты, бей саму цель.
    /// </summary>
    /// <param name="Куда">клетку сломать сейчас (null — бить нечего)</param>
    /// <param name="Отказ">почему нельзя (null — беды нет)</param>
    /// <param name="ПрокопКСоседу">
    /// не грань, а помеха на пути к ней: сосед, ради которого прокапываемся.
    /// null — бьём саму грань.
    /// </param>
    public readonly record struct СледующийУдар(BlockPos? Куда, string? Отказ,
        BlockPos? ПрокопКСоседу = null);

    /// <summary>
    /// ЧЁТНОСТЬ ШАХМАТКИ по X+Y+Z: у клетки одной чётности все шесть соседей —
    /// другой. Отсюда и берётся «через одну»: снимаешь всё одной чётности, и
    /// у клеток другой освобождаются разом все шесть граней.
    /// </summary>
    public static int Parity(BlockPos c) => (c.X + c.Y + c.Z) & 1;

    /// <summary>Эта клетка той чётности, которую собираем целыми блоками.</summary>
    public static bool OnParity(BlockPos c, int parity) => Parity(c) == parity;

    // ---------------- ШАХМАТКА КАК ПОРЯДОК ПО МНОГИМ КЛЕТКАМ ----------------

    /// <summary>
    /// Координата клетки вдоль оси — чтобы не писать <c>switch</c> по осям в
    /// каждом правиле шахматки заново.
    /// </summary>
    public static int Вдоль(BlockPos c, Axis ось) => ось switch
    {
        Axis.X => c.X,
        Axis.Y => c.Y,
        _ => c.Z
    };

    /// <summary>
    /// САМАЯ ДЛИННАЯ ИЗ ТРЁХ РАЗНИЦ — ОДНО МЕСТО НА ОБА СЛУЧАЯ, И ЭТО ПОЧИНКА
    /// ПО ЗАКОНУ 2. Выражение «какая ось длиннее» стояло в этом же файле
    /// ДВАЖДЫ — у <see cref="ОсьХода"/> и у <see cref="ЗабойОбъёма"/>, — с
    /// одинаковым разрешением ничьей и врозь. Копия правила в своём же новом
    /// файле разъехалась бы с первой на первой же правке ничьей.
    ///
    /// НИЧЬЯ РАЗРЕШАЕТСЯ В ПОЛЬЗУ ГОРИЗОНТАЛИ (X, потом Z, и только потом Y), и
    /// это не вкус. Ровный уклон 1:1 бывает у хода вниз-вперёд и у дороги под
    /// уклон: по горизонтали работа уходит ДАЛЬШЕ, а слои-жертвы обязаны
    /// чередоваться вдоль ДЛИННОЙ стороны выработки — иначе их окажется
    /// столько же, сколько шагов, и добычного слоя не останется вовсе.
    /// </summary>
    public static Axis ДлиннаяОсь(int dx, int dy, int dz) =>
        dx >= dy && dx >= dz ? Axis.X : (dz >= dy ? Axis.Z : Axis.Y);

    /// <summary>
    /// ОСЬ ХОДА: вдоль чего работа шагнула. Берётся у самого шага, а не
    /// назначается — это и есть «плоскость от забоя».
    ///
    /// Шаг наискось даёт сразу две ненулевых разницы; какую взять, решает
    /// <see cref="ДлиннаяОсь"/> — одно правило на обоих спрашивающих.
    /// </summary>
    public static Axis ОсьХода(BlockPos откуда, BlockPos куда) => ДлиннаяОсь(
        Math.Abs(куда.X - откуда.X),
        Math.Abs(куда.Y - откуда.Y),
        Math.Abs(куда.Z - откуда.Z));

    /// <summary>
    /// ЗАБОЙ, СЧИТАННЫЙ С САМОГО СПИСКА, — для работы, которая своей оси не
    /// назвала.
    ///
    /// Ось — САМАЯ ДЛИННАЯ сторона выработки: вдоль неё работа и продвигается
    /// (карьер 7×7 уходит на 15 вниз, ход 1×5 уходит на сотню вперёд). Начало —
    /// тот край этой стороны, который БЛИЖЕ К ТЕЛУ: работа начинает с того
    /// забоя, у которого стоит, а не с дальнего.
    ///
    /// Это запасной ответ, а не главный: работа, которая знает свой забой,
    /// называет его сама (<see cref="Забой"/>). Запасной нужен затем, чтобы
    /// новая работа получила шахматку по факту рождения, а не после того, как
    /// кто-нибудь вспомнит дописать ей строку, — на этом проект уже трижды
    /// горел («сделали в одном месте, забыли в другом»).
    /// </summary>
    public static Забой ЗабойОбъёма(IEnumerable<BlockPos> клетки, BlockPos откуда)
    {
        int minX = int.MaxValue, minY = int.MaxValue, minZ = int.MaxValue;
        int maxX = int.MinValue, maxY = int.MinValue, maxZ = int.MinValue;
        foreach (var c in клетки)
        {
            minX = Math.Min(minX, c.X); maxX = Math.Max(maxX, c.X);
            minY = Math.Min(minY, c.Y); maxY = Math.Max(maxY, c.Y);
            minZ = Math.Min(minZ, c.Z); maxZ = Math.Max(maxZ, c.Z);
        }
        if (minX > maxX)
            return new Забой(Axis.Y, откуда.Y);

        var ось = ДлиннаяОсь(maxX - minX, maxY - minY, maxZ - minZ);
        var (lo, hi) = ось switch
        {
            Axis.X => (minX, maxX),
            Axis.Y => (minY, maxY),
            _ => (minZ, maxZ)
        };
        int я = Вдоль(откуда, ось);
        return new Забой(ось, Math.Abs(я - hi) <= Math.Abs(я - lo) ? hi : lo);
    }

    /// <summary>
    /// СЛОЙ-ЖЕРТВА: каждый второй слой поперёк забоя снимается ЦЕЛИКОМ, и целых
    /// блоков в нём не берут вовсе. Счёт идёт от <see cref="Забой.Начало"/>:
    /// первый слой — добычный.
    ///
    /// ПОЧЕМУ БЕЗ ЭТОГО НЕ ОБОЙТИСЬ (разбор карьера 28.08, слово в слово
    /// годится любой работе). В ровной шахматке по X+Y+Z все шесть соседей
    /// клетки «в крошку» — это клетки «целые». Первый слой ещё открыт, а вот
    /// любая клетка «в крошку» СЛОЕМ ГЛУБЖЕ замурована со всех шести сторон:
    /// с четырёх боков — целые клетки своего слоя, спереди и сзади — целые
    /// клетки соседних. Кликнуть по ней не с чего, значит слой не снимается,
    /// значит столбы над ним не изолируются и остаются стоять. Живьём это
    /// выглядело как «он сделал 2 слоя и затупил».
    ///
    /// Отдав каждый второй слой целиком, мы получаем на его месте сплошную
    /// пустую полку: с неё видно и бока столбов, и породу за ними. Цена названа
    /// честно: целыми выходит ЧЕТВЕРТЬ объёма, а не половина. Половина — цифра
    /// красивая, но недостижимая.
    /// </summary>
    public static bool ДобычныйСлой(BlockPos c, Забой забой) =>
        ((Вдоль(c, забой.Ось) - забой.Начало) & 1) == 0;

    /// <summary>
    /// ВЫЙДЕТ ЛИ ЭТА КЛЕТКА ЦЕЛЫМ БЛОКОМ, если снять весь список
    /// <paramref name="снимем"/>, — чистое правило, без мира и без кирки.
    ///
    /// Три условия и ни одного лишнего:
    ///   • она нужной чётности (соседи по всем шести граням — другой, значит
    ///     все они уйдут в жертву раньше);
    ///   • она в добычном слое, а не в слое-жертве (<see cref="ДобычныйСлой"/>);
    ///   • с неё вообще есть что взять целым (<paramref name="берётсяЦелым"/> —
    ///     это спрашивают у реестра, см.
    ///     <see cref="DropsWholeWhenFloating(WorldModel, int)"/>);
    ///   • и все шесть граней к тому времени освободятся: сосед либо уйдёт с
    ///     нами (он в списке), либо уже сейчас не твёрдый.
    ///
    /// САМОГО СЕБЯ ЭТО ПРАВИЛО НЕ ЗАЦИКЛИВАЕТ: сосед клетки нужной чётности
    /// всегда ДРУГОЙ чётности, значит целым его не берут никогда, значит он
    /// жертва — и снимается раньше. Проверять «а не целый ли сосед» не нужно.
    /// </summary>
    /// <param name="снимем">Весь список, который эта работа выберет.</param>
    /// <param name="твёрдо">
    /// Упирается ли грань в твёрдую сторону соседа СЕЙЧАС — тем же порядком
    /// доводов, что и у <see cref="Floats(BlockPos, Func{BlockPos, Facing, bool})"/>:
    /// приходит клетка соседа и грань со стороны цели.
    /// </param>
    public static bool ЦелымВыйдет(BlockPos c, Забой забой, int чётность,
        IReadOnlySet<BlockPos> снимем, Func<BlockPos, bool> берётсяЦелым,
        Func<BlockPos, Facing, bool> твёрдо) =>
        OnParity(c, чётность) && ДобычныйСлой(c, забой) && берётсяЦелым(c) &&
        Floats(c, (n, f) => !снимем.Contains(n) && твёрдо(n, f));

    /// <summary>
    /// ПОРЯДОК «ЧЕРЕЗ ОДНУ» — ТО, РАДИ ЧЕГО ВСЁ И ЗАТЕВАЛОСЬ. Список делится на
    /// ЖЕРТВЫ и ЦЕЛЫЕ: сперва берут жертвы, и к тому времени, когда очередь
    /// дойдёт до целых, у каждой из них не останется ни одной твёрдой грани —
    /// и она выпадет целым блоком (BreakIfFloating, разбор наверху файла).
    ///
    /// ЭТО ПОРЯДОК, А НЕ ВЫБОР: из списка не выпадает НИ ОДНОЙ клетки. Кто
    /// просил снять объём — снимет его весь, только в два захода. Поэтому
    /// правило и годится дороге с тоннелем, которым решётку недокопанного
    /// оставлять нельзя, а не одному карьеру.
    ///
    /// ВНУТРИ КАЖДОЙ ПОЛОВИНЫ ПОРЯДОК ВХОДЯЩЕГО СПИСКА СОХРАНЯЕТСЯ ДОСЛОВНО, и
    /// это не мелочь. У дороги и у штольни свой порядок выстрадан живыми
    /// случаями (сверху вниз — иначе нижняя клетка спрятана за верхней и «нет
    /// прямой видимости»), и шахматка не вправе его перетасовывать. Она вправе
    /// только отложить часть клеток НА ПОТОМ.
    /// </summary>
    public static (IReadOnlyList<BlockPos> Жертвы, IReadOnlyList<BlockPos> Целые) ЧерезОдну(
        IEnumerable<BlockPos> клетки, Забой забой, int чётность,
        Func<BlockPos, bool> берётсяЦелым, Func<BlockPos, Facing, bool> твёрдо)
    {
        var все = клетки as IReadOnlyList<BlockPos> ?? клетки.ToList();
        var снимем = new HashSet<BlockPos>(все);
        var жертвы = new List<BlockPos>(все.Count);
        var целые = new List<BlockPos>();
        foreach (var c in все)
        {
            if (ЦелымВыйдет(c, забой, чётность, снимем, берётсяЦелым, твёрдо))
                целые.Add(c);
            else
                жертвы.Add(c);
        }
        return (жертвы, целые);
    }

    /// <summary>
    /// ЧЁТНОСТЬ, ДАЮЩАЯ БОЛЬШЕ ЦЕЛЫХ БЛОКОВ НА ЭТОМ СПИСКЕ.
    ///
    /// Материал тут НЕ спрашивается нарочно: чётность выбирается один раз на
    /// всю работу, а «берётся ли целым» решается по каждой клетке отдельно —
    /// смешай мы это, и один участок глины сдвинул бы шахматку всего карьера.
    /// Равенство разрешается в пользу нуля, чтобы ответ не зависел от порядка
    /// обхода: иначе одна и та же область давала бы разный план.
    /// </summary>
    public static int ЛучшаяЧётность(IEnumerable<BlockPos> клетки, Забой забой,
        Func<BlockPos, Facing, bool> твёрдо)
    {
        var все = клетки as IReadOnlyList<BlockPos> ?? клетки.ToList();
        var снимем = new HashSet<BlockPos>(все);
        int[] счёт = new int[2];
        foreach (var c in все)
            if (ДобычныйСлой(c, забой) &&
                Floats(c, (n, f) => !снимем.Contains(n) && твёрдо(n, f)))
                счёт[Parity(c)]++;
        return счёт[0] >= счёт[1] ? 0 : 1;
    }
}
