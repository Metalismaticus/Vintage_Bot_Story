using System.Text.Json.Serialization;

namespace VsBotKit;

/// <summary>
/// Что делать боту, когда делать нечего.
///
/// Имена значений человек ВИДИТ И НАБИРАЕТ в окне управления: панель показывает
/// «выбор» обычным полем и отправляет написанное как есть, а <see cref="RoleKnobs"/>
/// разбирает его через Enum.Parse. Поэтому здесь, в отличие от остальных
/// перечислений библиотеки (их человеку не показывают вовсе), значения названы
/// по-русски — иначе в русском окне пришлось бы вслепую набирать «Wander».
///
/// По той же причине навешен преобразователь в строку: без него панель
/// показала бы номер («1»), и в сохранённый пресет лёг бы этот же номер —
/// открыв файл через полгода, понять из него ничего нельзя.
/// </summary>
[JsonConverter(typeof(JsonStringEnumConverter))]
public enum IdleAction
{
    /// <summary>Стоять на месте. По умолчанию: бот без дела никому не мешает.</summary>
    Стоять,

    /// <summary>Бродить рядом с домом, а если дома нет — рядом с местом, где застало безделье.</summary>
    Бродить,

    /// <summary>Вернуться домой и закрыть за собой дверь.</summary>
    Домой,

    /// <summary>Выйти из игры.</summary>
    Выйти
}

/// <summary>
/// ЧТО ДЕЛАТЬ С ОЧЕРЕДЬЮ ЗАДАЧ В ПРОСТОЕ.
///
/// ЗАКАЗ ЧЕЛОВЕКА, дословно: «допустим задавать цикл задач, если они есть».
/// Очередь берётся ТА ЖЕ САМАЯ, что человек набирает в окне управления
/// (<see cref="WorkPlan"/>): второй список работ развёл бы две правды о том,
/// что бот должен делать, и человек правил бы не тот.
///
/// Имена значений человек ВИДИТ И ВЫБИРАЕТ в окне управления — потому они и
/// по-русски, ровно как у <see cref="IdleAction"/> и по той же причине.
/// </summary>
[JsonConverter(typeof(JsonStringEnumConverter))]
public enum IdleJobs
{
    /// <summary>Не трогать. По умолчанию: очередь пускает человек, а не простой.</summary>
    Нет,

    /// <summary>Пройти ждущие задачи один раз и остановиться.</summary>
    Пройти,

    /// <summary>Пройдя очередь до конца, вернуть задачи в «ждёт» и начать заново.</summary>
    ПоКругу
}

/// <summary>
/// БЕЗДЕЙСТВИЕ: бот кончил дела — и что дальше.
///
/// Зачем это нужно. Бот, которому нечего делать, стоит столбом посреди мира.
/// Живому наблюдателю это неотличимо от «бот завис», а серверу лишний
/// молчаливый игрок стоит места в слоте. Что именно делать в такую минуту —
/// решение РОЛИ (лавочнику надо стоять у прилавка, копателю — уйти домой,
/// ночному боту — выйти из игры), поэтому здесь только выбор из
/// <see cref="IdleAction"/> и порог в секундах.
///
/// ЧТО СЧИТАЕТСЯ БЕЗДЕЛЬЕМ. Ровно одно: тело никем не занято
/// (<see cref="BodyArbiter.Busy"/> пуст), бот никуда не идёт и он жив. Другой
/// мерки нет и быть не должно — иначе появится вторая правда о том, чем занят
/// бот, и они разъедутся. Оборотная сторона честная и её надо знать: роль,
/// которая работает телом НЕ ЗАНЯВ его у распорядителя, со стороны выглядит
/// бездельничающей, и бот уйдёт бродить у неё из-под рук. Занимать тело —
/// обязанность любого дела, а не любезность.
///
/// ЧТО ДЕЛАЕТСЯ В ПРОСТОЕ И В КАКОМ ПОРЯДКЕ — три слоя, и первые два заведены
/// по заказу человека («нам бы научить его чему-то базовому в простое, допустим
/// задавать цикл задач, если они есть»):
///
/// 1. ЗАКРЫТЬ ХВОСТЫ (<see cref="Unfinished"/>) — то, что бот начал и не
///    закончил: свою открытую дверь, свои временные леса. Живой случай: дверь
///    (512062, 112, 512252) простояла нараспашку два часа, а бот за это время
///    четырежды бездельничал («без дела 60 с — стою, так настроено»). Цикл
///    задач такого не лечит: в очереди этой работы нет и не было, её начал сам
///    бот. Недоделанный ИНСТРУМЕНТ сюда не входит: его доделывает хозяйство
///    (<see cref="BehaviorFinishStarted"/>), стоящее впереди по весу.
/// 2. ПРОЙТИ ОЧЕРЕДЬ ЗАДАЧ (<see cref="Works"/>) — если человек так велел.
/// 3. И только когда доделывать нечего и очередь молчит — прежний выбор
///    <see cref="WhenIdle"/>: стоять, бродить, домой, выйти. Он не отменён и
///    решает ровно то же, что решал.
///
/// ДОЛГИЕ ДЕЛА ПУСКАЮТСЯ ФОНОМ, а не ожидаются прямо в тике, и это не вольность.
/// Обход способностей идёт по одной в ОДНОМ потоке: пока способность ждёт, бот
/// не ест, не лечится и не отбивается (ровно поэтому же прогулка и дорога домой
/// нарезаны на отрезки по двадцать секунд). Поэтому доделывание и очередь
/// пускаются так же, как их пускает окно управления, — отдельной задачей; тело
/// у них при нужде отбирает распорядитель (<see cref="BodyArbiter"/>), а пока
/// они его держат, бот НЕ бездельничает и отсчёт простоя идёт с нуля.
///
/// Ставить эту способность НАДО ПОСЛЕДНЕЙ в списке: пока она бродит или идёт
/// домой, она держит ход за собой, и всё, что стоит после неё, в этот тик не
/// тикает. Позади еды, лечения и боя ей самое место.
/// </summary>
public class BehaviorIdle : BotBehavior
{
    private readonly BotContext ctx;
    private readonly Shelter shelter;
    private readonly Random rnd;

    public BehaviorIdle(BotContext ctx, Shelter shelter, Random? rnd = null)
    {
        this.ctx = ctx;
        this.shelter = shelter;
        this.rnd = rnd ?? new Random();
        // Безнадёга говорит человеку ТЕМ ЖЕ голосом, что и остальные отказы
        // безделья: второго события «бот отказался» здесь заводить незачем
        Hopeless.OnSay += why => OnRefused?.Invoke(why);
    }

    /// <summary>Что делать без дела.</summary>
    public IdleAction WhenIdle { get; set; } = IdleAction.Стоять;

    /// <summary>
    /// ЗАКРЫВАТЬ ЛИ ХВОСТЫ, прежде чем браться за <see cref="WhenIdle"/>.
    /// Ручка роли «ЗакрыватьХвостыВПростое».
    /// </summary>
    public bool FinishLooseEnds { get; set; } = true;

    /// <summary>
    /// ЧТО ДЕЛАТЬ С ОЧЕРЕДЬЮ ЗАДАЧ В ПРОСТОЕ. Ручка роли «ОчередьЗадачВПростое».
    /// </summary>
    public IdleJobs RunJobs { get; set; } = IdleJobs.Нет;

    /// <summary>
    /// Очередь задач на вечер — ТА ЖЕ САМАЯ, что человек набирает в окне
    /// управления. null — очередь к боту не подключена (бот под внешним
    /// управлением, запуск без панели), и тогда цикл задач честно откажется.
    ///
    /// Доносит её роль (<c>LivingRole.UseRunner</c>): сама способность
    /// собирается раньше бегуна и знать про него ниоткуда не может.
    /// </summary>
    public WorkRunner? Works { get; set; }

    /// <summary>
    /// ЗА ЧТО ДОДЕЛЫВАТЬ БОЛЬШЕ НЕ БЕРЁМСЯ, ПОКА НЕ ИЗМЕНИТСЯ ОБСТАНОВКА.
    ///
    /// Механизм общий (<see cref="VsBotKit.Hopeless"/>), второй копии правила
    /// здесь нет. Без него простой раз в минуту заново гонял бы уборку лесов,
    /// которую не пускает непрогруженный чанк, — то самое «долбить безнадёжное».
    /// Ключ — РОД незакрытого, а не его содержимое: содержимое меняется вместе
    /// с сумкой, и счёт безнадёг рос бы на каждый поднятый камень.
    /// </summary>
    public Hopeless Hopeless { get; } = new("доделать начатое не выходит");

    /// <summary>
    /// Сколько секунд бот должен простоять без дела, прежде чем взяться за
    /// <see cref="WhenIdle"/>. Он же — пауза между прогулками: иначе «бродить»
    /// означало бы «ходить не останавливаясь», а это уже не безделье, а работа.
    /// </summary>
    public double IdleSeconds { get; set; } = 60;

    /// <summary>Как далеко от дома (или от якоря) отходить на прогулке, блоков.</summary>
    public int WanderRadius { get; set; } = 12;

    /// <summary>
    /// Ближе этого прогулка не считается прогулкой: без нижней границы
    /// случайная точка то и дело выпадает под ногами, и бот дёргается на месте.
    /// </summary>
    public int WanderMinStep { get; set; } = 4;

    /// <summary>
    /// Потолок времени на одну прогулку. Короткий нарочно: пока способность
    /// идёт, она держит ход, и бот в это время не ест, не лечится и не
    /// отбивается. Лучше десять коротких выходов, чем один долгий.
    /// </summary>
    public double WanderSeconds { get; set; } = 20;

    /// <summary>Отрезок дороги домой за один тик — по той же причине, что и прогулка.</summary>
    public double HomeSeconds { get; set; } = 20;

    /// <summary>Сколько отрезков пробовать, прежде чем честно сказать «не дошёл».</summary>
    public int HomeTries { get; set; } = 3;

    /// <summary>Ближе этого к дому бот считается пришедшим.</summary>
    public int HomeRadius { get; set; } = 3;

    /// <summary>
    /// Что сказать в игровой чат перед уходом. Пусто — молча (в журнал причина
    /// уходит всегда). Живой резон: бот, пропавший без слова, выглядит
    /// упавшим, и хозяину звонят «твой торговец сломался».
    /// </summary>
    public string Farewell { get; set; } = "";

    /// <summary>
    /// Вокруг чего бродить, если дом не задан. Ставится сам — местом, где бота
    /// застало безделье, и больше не меняется: пересчитывай его каждый раз, и
    /// бот «уползёт» прогулками сколь угодно далеко, каждая от места прошлой.
    /// </summary>
    public BlockPos? Anchor { get; set; }

    /// <summary>Стою без дела: столько-то секунд, потому что так настроено.</summary>
    public event Action<double>? OnStanding;

    /// <summary>Пошёл гулять вот к этой клетке.</summary>
    public event Action<BlockPos>? OnWander;

    /// <summary>Пошёл домой.</summary>
    public event Action<BlockPos>? OnGoingHome;

    /// <summary>Дошёл до дома.</summary>
    public event Action? OnCameHome;

    /// <summary>Не стал или не смог — с причиной. Молчаливого отказа здесь нет.</summary>
    public event Action<string>? OnRefused;

    /// <summary>Ухожу из игры, вот почему.</summary>
    public event Action<string>? OnLeaving;

    /// <summary>
    /// БЕРУСЬ ДОДЕЛЫВАТЬ ВОТ ЭТО. Говорится ДО работы и всегда: заказчик просил,
    /// чтобы бот в простое называл, что он доделывает и почему, а не уходил молча.
    /// </summary>
    public event Action<LooseEnd>? OnFinishing;

    /// <summary>Чем кончилось доделывание — словами того механизма, который его вёл.</summary>
    public event Action<string>? OnFinished;

    /// <summary>Что решил насчёт очереди задач в простое и почему.</summary>
    public event Action<string>? OnJobs;

    private DateTime? idleSince;
    private bool said;          // про нынешнее безделье уже сказано — не повторяться каждый тик
    private bool goingHome;
    private int homeTried;

    /// <summary>
    /// ГДЕ СТОЯЛ, КОГДА СКАЗАЛ «ДО ДОМА НЕ ДОШЁЛ — СТОЮ ЗДЕСЬ». null — не
    /// сдавался.
    ///
    /// ЗДЕСЬ СТОЯЛ ПРОСТОЙ ФЛАЖОК <c>bool</c>, И ОН НЕ ГАС НИКОГДА. Живой
    /// журнал 01.09: бот сидел в яме, сказал «до дома (62, 112, 254) не дошёл
    /// за 3 захода — стою здесь», через полторы минуты поднялся столбом НА
    /// ВЫСОТУ ДОМА — и домой больше не собрался ни разу за вечер. Отказ,
    /// взятый в яме, обязан протухать, когда бот сменил место или высоту;
    /// решает это чистое правило <see cref="Movement.RefusalStillHolds"/>, а
    /// здесь помнится только точка, с которой отказ и был взят.
    /// </summary>
    private BlockPos? homeGaveUpAt;
    private bool left;

    /// <summary>
    /// Доделывание, пущенное фоном. Пока оно живо, второго не заводим: тело оно
    /// держит само, но между «работа кончилась» и «распорядитель отпустил тело»
    /// есть щель, в которую влезал бы второй такой же заход.
    /// </summary>
    private Task? finishing;

    /// <summary>Круг очереди, пущенный фоном (см. <see cref="finishing"/>).</summary>
    private Task? jobsRun;

    /// <summary>
    /// Прошлый круг очереди не сделал НИ ОДНОЙ задачи. Держится до тех пор, пока
    /// круг не пройдёт с толком: иначе «ПоКругу» на очереди из одних отказов
    /// гоняло бы бота всю ночь (см. <see cref="Unfinished.QueueInIdle"/>).
    /// </summary>
    private bool lastLapEmpty;

    /// <summary>
    /// ПРО ЧТО УЖЕ СКАЗАНО ВСЛУХ — по тревоге на КАЖДЫЙ повод, а не одной
    /// отметкой на всех.
    ///
    /// ЗДЕСЬ БЫЛА ВТОРАЯ КОПИЯ <see cref="Alarm"/>, И ОНА ВРАЛА. Стояла одна
    /// строка <c>saidAbout</c> на весь простой, и повод затирал повод. Живой
    /// ход, который это ломает, достижим настройками из коробки: бот стоит,
    /// снаряжение недобрано (хвост «запасы», доделывать не нам), а очередь
    /// задач велено гонять по кругу — и очереди к боту не подключено. Тогда
    /// КАЖДЫЙ тик простоя идёт так:
    ///     Say("запасы", …)  — отметка была «очередь», значит говорим
    ///     Say("очередь", …) — отметка стала «запасы», значит говорим
    /// Две одинаковые строки за тик, и так всю ночь: ровно тот шум, от которого
    /// в этом проекте уже лечили и голод, и разломы, и бурю.
    ///
    /// Вторая беда той копии — молчание навсегда. У <see cref="Alarm"/> есть
    /// <see cref="Alarm.RepeatAfter"/>, и долгая беда напоминает о себе раз в
    /// пять минут; отметка же, сказав один раз, замолкала до конца работы. Бот,
    /// час назад сказавший «очередь не подключена» и с тех пор молчащий,
    /// выглядит здоровым (правило проекта 4).
    ///
    /// Своего счётчика здесь нет и быть не должно: «сказать один раз» в проекте
    /// живёт в <see cref="Alarm"/>, туда же ходят и безнадёга
    /// (<see cref="Hopeless{TKey}"/>), и доделка снаряжения
    /// (<see cref="BehaviorFinishStarted"/>).
    /// </summary>
    private readonly Dictionary<string, Alarm> сказано =
        new(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// БЕЗ ДЕЛА ЛИ БОТ. Правило вынесено отдельно и закрыто тестами, потому что
    /// на нём висит «уйти из игры»: ошибись здесь — и бот выйдет посреди чужой
    /// команды, бросив человека без ответа.
    /// </summary>
    /// <param name="busy">Чем занято тело (<see cref="BodyArbiter.Busy"/>), пусто — ничем.</param>
    /// <param name="moving">Бот идёт (движением могли распорядиться и не заняв тело).</param>
    /// <param name="dead">Мёртвый не бездельничает — им занято возрождение.</param>
    public static bool Idle(string busy, bool moving, bool dead) =>
        busy.Length == 0 && !moving && !dead;

    /// <summary>Настоялся ли бот положенное. null — счёт ещё не начинался.</summary>
    public static bool Ripe(DateTime? since, DateTime now, double seconds) =>
        since is { } t && (now - t).TotalSeconds >= seconds;

    /// <summary>
    /// Куда отойти на прогулке: смещение от якоря в клетках.
    ///
    /// Броском наугад с ОТБРАКОВКОЙ, а не «угол плюс расстояние»: после
    /// округления полярной точки к клеткам расстояние уезжает и наружу за
    /// радиус, и внутрь ближе минимального шага, и обещание «не дальше
    /// WanderRadius от дома» перестаёт быть правдой. Здесь оно правда.
    ///
    /// Попытки считаны: круг занимает больше половины квадрата, и двадцати
    /// бросков хватает с запасом, какой бы ни выпал случай. Если всё же не
    /// выпало — отходим ровно на минимальный шаг, а не стоим молча.
    /// </summary>
    public static (int X, int Z) WanderStep(Random rnd, int radius, int minStep)
    {
        if (radius < 1)
            return (0, 0);                       // радиус в ноль — гулять некуда
        int near = Math.Clamp(minStep, 0, radius);
        for (int i = 0; i < 20; i++)
        {
            int dx = rnd.Next(-radius, radius + 1);
            int dz = rnd.Next(-radius, radius + 1);
            int away = dx * dx + dz * dz;
            if (away <= radius * radius && away >= near * near)
                return (dx, dz);
        }
        return (near, 0);
    }

    public override async Task<bool> TickAsync(CancellationToken ct)
    {
        // ВНЕ МИРА СЧИТАТЬ НЕЧЕГО. Заодно это единственное место, где
        // забывается «уже ушёл»: вернулся в мир — значит впереди новая жизнь
        // и новое безделье
        if (!ctx.Bot.Joined)
        {
            Forget();
            left = false;
            return false;
        }
        if (left)
            return false;   // из игры уже вышли; Joined гаснет не мгновенно

        // МЁРТВЫЙ НЕ ИДЁТ НИКУДА, и проверить это обязаны мы сами: возрождение
        // (BehaviorRespawnWhenDead) чужие дела ПРЕРЫВАЕТ, но тело за собой не
        // держит — распорядитель после смерти показывает «свободно». Без этой
        // строки начатая дорога домой продолжилась бы трупом: сервер отказывает
        // мёртвому во всём, а бот честно докладывал бы «не дошёл», лёжа на
        // месте гибели
        if (ctx.Self.IsDead)
        {
            Forget();
            return false;
        }

        // Дорога домой длиннее одного тика и идёт отрезками. Порог бездействия
        // к ней больше не применяется: иначе бот шёл бы домой минуту, потом
        // минуту стоял, вспоминая, что он вообще-то шёл домой
        if (goingHome)
            return await StepHomeAsync(ct);

        if (!Idle(ctx.Turn.Busy, ctx.Movement.IsMoving, ctx.Self.IsDead))
        {
            Forget();
            return false;
        }

        // ФОНОВОЕ ДЕЛО ЕЩЁ ИДЁТ — простоя нет. Тело оно держит само, и обычно
        // мерка безделья выше уже увела бы нас отсюда; но между «работа
        // кончилась» и «распорядитель отпустил тело» есть щель, и без этой
        // заставы в неё влезал бы второй такой же заход
        if (finishing is { IsCompleted: false } || jobsRun is { IsCompleted: false })
        {
            Forget();
            return false;
        }

        idleSince ??= DateTime.UtcNow;
        if (!Ripe(idleSince, DateTime.UtcNow, IdleSeconds))
            return false;

        // 1. СНАЧАЛА ЗАКРЫТЬ ХВОСТЫ. Живой случай: дверь, открытая ботом, два
        // часа стояла нараспашку, пока он рядом бездельничал (см. Unfinished)
        if (FinishLooseEnds && await FinishSomethingAsync(ct))
            return true;

        // 2. ПОТОМ ЦИКЛ ЗАДАЧ — то самое «задавать цикл задач, если они есть»
        if (RunJobs != IdleJobs.Нет && StartJobs())
            return true;

        // 3. И только теперь прежний выбор человека: он решает, что делать,
        // когда доделывать нечего
        double idle = (DateTime.UtcNow - idleSince!.Value).TotalSeconds;
        switch (WhenIdle)
        {
            case IdleAction.Стоять:
                // Стоять — тоже решение, и о нём говорят вслух ОДИН раз:
                // человек должен отличать «так настроено» от «бот завис»
                if (!said)
                {
                    said = true;
                    OnStanding?.Invoke(idle);
                }
                return false;   // ход не забираем: стоящий не мешает никому

            case IdleAction.Бродить:
                return await WanderAsync(ct);

            case IdleAction.Домой:
                return await StartHomeAsync(ct);

            case IdleAction.Выйти:
                return await LeaveAsync(idle, ct);

            default:
                // Значение перечисления, которого здесь не разобрали, — это
                // забытая ветка, а не повод молчать
                if (!said)
                {
                    said = true;
                    OnRefused?.Invoke($"не знаю, что делать без дела: «{WhenIdle}»");
                }
                return false;
        }
    }

    /// <summary>Счёт безделья с нуля: бота чем-то заняли или он вышел из мира.</summary>
    private void Forget()
    {
        idleSince = null;
        said = false;
        // БОТА ЧЕМ-ТО ЗАНЯЛИ — значит следующий отказ будет уже про другую
        // обстановку, и прозвучать он обязан СРАЗУ, а не через оставшиеся минуты
        // молчания. Отбой вслух не говорим: на него никто не подписан, да он и
        // не новость — новость будет, когда бот снова встанет
        foreach (var тревога in сказано.Values)
            тревога.Clear();
        goingHome = false;
        homeTried = 0;
        homeGaveUpAt = null;
    }

    // ---------------- 1. ДОДЕЛАТЬ НАЧАТОЕ ----------------

    /// <summary>
    /// ВЗЯТЬСЯ ЗА ОДИН ХВОСТ. true — взялся (и тогда простой на этом тике
    /// кончился); false — закрывать нечего, незачем или не нам.
    ///
    /// Что именно считается хвостом и в каком порядке — знает
    /// <see cref="Unfinished"/>, один вопрос на всех. Здесь только тело, фон и
    /// слова.
    /// </summary>
    private async Task<bool> FinishSomethingAsync(CancellationToken ct)
    {
        var found = Unfinished.Of(ctx);
        // ОБСТАНОВКА ПЕРЕМЕНИЛАСЬ — БЕЗНАДЁГЕ ОТБОЙ. Того рода незакрытого
        // больше нет: держать на нём отказ значило бы не взяться за него, когда
        // оно появится снова. Тот же приём, что у запасов (Stock.ReplenishAsync)
        foreach (string род in Hopeless.All)
            if (!found.Any(e => string.Equals(e.Kind, род, StringComparison.OrdinalIgnoreCase)))
                Hopeless.TryAgain(род, "такого незакрытого за мной больше не числится");

        if (Unfinished.First(found, род => Hopeless.Given(род)) is not { } end)
            return false;

        // ЗА ЭТИМ УЖЕ ИДУТ БЕЗ МЕНЯ. Прерванная работа ждёт освобождения тела —
        // забрать его под уборку значило бы добить её вместо помощи. Говорим
        // один раз и уступаем: ход не забираем, потому что мы ничего не делаем
        if (!end.Mine)
        {
            Say(end.Kind, Unfinished.Say(end));
            return false;
        }

        // ТЕЛО БЕРЁМ ОБЫЧНЫМ ЧИНОМ. Routine — потому что доделывание уступает и
        // рефлексу выживания, и приказу человека: доделать нож важнее прогулки,
        // но не важнее обеда
        var hold = ctx.Turn.TryTake($"доделываю начатое: {end.What}",
            BodyArbiter.Importance.Routine, ct);
        if (hold == null)
            return false;   // тело успели занять — распорядитель уже сказал, кто и чем

        OnFinishing?.Invoke(end);
        int было = end.Count;

        // ФОНОМ, А НЕ ОЖИДАНИЕМ. Обход способностей однопоточный: дождись мы
        // здесь похода за палкой — бот всё это время не ел бы и не отбивался
        finishing = Task.Run(async () =>
        {
            bool закрыл = false;
            string почему;
            try
            {
                (закрыл, почему) = await Unfinished.FinishAsync(ctx, end, hold.Token);
            }
            catch (OperationCanceledException)
            {
                // Тело отобрал рефлекс или человек — это не беда, а порядок
                // вещей. Но молчать про брошенное на середине нельзя
                почему = $"доделывание прервали: {(hold.EndedBy.Length > 0 ? hold.EndedBy : "отменено")}";
            }
            catch (Exception e)
            {
                почему = $"доделывание сорвалось ошибкой: {e.Message}";
            }
            finally
            {
                hold.Dispose();
            }

            OnFinished?.Invoke(почему);

            // СДВИНУЛОСЬ ЛИ ДЕЛО — спрашиваем У МИРА заново, а не у собственного
            // намерения: механизм мог закрыть половину и честно назвать это
            // неудачей, и браться за вторую половину всё равно стоит
            int стало = Unfinished.Of(ctx)
                .FirstOrDefault(e => string.Equals(e.Kind, end.Kind, StringComparison.OrdinalIgnoreCase))
                ?.Count ?? 0;
            if (Unfinished.Moved(закрыл, было, стало))
                Hopeless.TryAgain(end.Kind, "дело сдвинулось — беру снова, когда понадобится");
            else
                Hopeless.GiveUp(end.Kind, Unfinished.SayStuck(end, почему));
        }, CancellationToken.None);

        // Отсчёт простоя с нуля: пока доделывание держит тело, бездельем это не
        // считается, а закончится оно — простой начнётся заново
        Forget();
        return true;
    }

    // ---------------- 2. ЦИКЛ ЗАДАЧ ----------------

    /// <summary>
    /// ВЗЯТЬСЯ ЗА ОЧЕРЕДЬ ЗАДАЧ. true — пустил круг.
    ///
    /// Тело здесь НЕ ЗАНИМАЕТСЯ, и это нарочно: очередь занимает его САМА и на
    /// каждую задачу отдельно (владение зовётся <see cref="WorkRunner.BodyOwner"/>
    /// и держится ступенью <see cref="WorkRunner.LegsImportance"/>; навык внутри
    /// задачи берёт тело по своим правилам). Займи мы его тут своим владением —
    /// оно оказалось бы РОВНО НА ПУТИ у собственных задач: равный равного не
    /// перебивает, и первая же задача получила бы отказ от нас самих. От
    /// второго пуска бережёт не тело, а <see cref="jobsRun"/>.
    ///
    /// ЗДЕСЬ СТОЯЛО, ЧТО НАВЫК БЕРЁТ ТЕЛО «как команда», И ЭТО БЫЛО ПРАВДОЙ
    /// ЛИШЬ НАПОЛОВИНУ: своих шагов бегуна (дорога к точке работы, поход к
    /// сундуку, рейс за материалом, разгрузка) не прикрывало НИЧЬЁ владение, и
    /// первый же желающий отнимал у них ноги. Живой случай назван у
    /// <see cref="WorkRunner.BodyOwner"/>.
    /// </summary>
    private bool StartJobs()
    {
        if (Works is not { } runner)
        {
            Say("очередь", "цикл задач в простое не начинаю: очередь задач к боту не подключена " +
                           "(так живёт бот под внешним управлением и любой запуск без окна)");
            return false;
        }

        var plan = runner.Plan;
        var (run, repeat, why) = Unfinished.QueueInIdle(RunJobs, runner.Busy,
            plan.Pending().Count(), plan.Jobs.Count, lastLapEmpty);
        if (!run)
        {
            Say("очередь", why);
            return false;
        }

        OnJobs?.Invoke(why);
        if (repeat)
        {
            int снова = plan.RepeatAll();
            OnJobs?.Invoke($"вернул в «ждёт» задач: {снова}");
        }

        jobsRun = Task.Run(async () =>
        {
            try
            {
                int сделано = await runner.RunAllAsync();
                // ПУСТОЙ КРУГ ЗАПОМИНАЕМ. Без этого «ПоКругу» на очереди из
                // одних отказов гоняло бы бота всю ночь, и каждый круг был бы
                // точной копией прошлого
                lastLapEmpty = сделано == 0;
                OnJobs?.Invoke($"круг очереди пройден: сделано задач {сделано}; {plan}");
            }
            catch (Exception e)
            {
                lastLapEmpty = true;
                OnJobs?.Invoke($"круг очереди оборвался ошибкой: {e.Message}");
            }
        }, CancellationToken.None);

        Forget();
        return true;
    }

    /// <summary>
    /// СКАЗАТЬ ПРО ЭТО ОДИН РАЗ, А НЕ КАЖДЫЙ ТИК. Молчать нельзя вовсе (правило
    /// проекта 4), но и печатать «очередь пуста» двадцать раз в секунду — это не
    /// честность, а шум.
    ///
    /// Тревога СВОЯ НА КАЖДЫЙ ПОВОД — почему именно так, разобрано у
    /// <see cref="сказано"/>: с одной отметкой на всех два повода затирали друг
    /// друга и печатались оба каждый тик.
    ///
    /// Строку наружу отдаём САМИ, а не событием тревоги: <see cref="Alarm"/>
    /// приписал бы к ней своё имя («очередь: …»), а человек читает эти строки
    /// как есть — с именем ручки и с тем, что делать. Тревоге здесь нужен
    /// только ответ «это новость или повтор».
    /// </summary>
    private void Say(string about, string line)
    {
        if (!сказано.TryGetValue(about, out var тревога))
            сказано[about] = тревога = new Alarm(about);
        if (тревога.Raise(line))
            OnRefused?.Invoke(line);
    }

    /// <summary>Клетка под ногами. null — сервер ещё не сказал, где мы.</summary>
    private BlockPos? Feet() => ctx.Self.Position is { } p
        ? new BlockPos((int)Math.Floor(p.X), (int)Math.Floor(p.Y), (int)Math.Floor(p.Z))
        : null;

    /// <summary>
    /// Вокруг чего гулять. Дом важнее якоря: заказчик просил «бродить рядом
    /// с домом», и дом у бота один — тот же, что у укрытия в бурю
    /// (<see cref="Shelter.Home"/>). Второго списка «где мой дом» в библиотеке
    /// быть не должно.
    /// </summary>
    private BlockPos? WanderAround()
    {
        if (shelter.Home is { } home)
            return home;
        Anchor ??= Feet();
        return Anchor;
    }

    private async Task<bool> WanderAsync(CancellationToken ct)
    {
        if (WanderAround() is not { } around)
        {
            if (!said)
            {
                said = true;
                OnRefused?.Invoke("гулять не пойду: не знаю, где стою — позиция от сервера ещё не пришла");
            }
            return false;
        }

        var (dx, dz) = WanderStep(rnd, WanderRadius, WanderMinStep);
        if (dx == 0 && dz == 0)
        {
            if (!said)
            {
                said = true;
                OnRefused?.Invoke($"гулять не пойду: радиус прогулки {WanderRadius}");
            }
            return false;
        }

        var target = new BlockPos(around.X + dx, around.Y, around.Z + dz);
        using var hold = ctx.Turn.TryTake("прогулка без дела", BodyArbiter.Importance.Routine, ct);
        if (hold == null)
            return false;   // тело успели занять — распорядитель уже сказал, кто и чем

        // Отрезок времени свой: ход у способности заберут только распорядитель
        // и отмена, а «иду наугад» само по себе может тянуться очень долго
        using var slice = CancellationTokenSource.CreateLinkedTokenSource(hold.Token);
        slice.CancelAfter(TimeSpan.FromSeconds(WanderSeconds));

        OnWander?.Invoke(target);
        bool arrived = await ctx.Movement.MoveToSmartAsync(
            target.X + 0.5, target.Z + 0.5, stopDistance: 1.0, slice.Token);
        if (!arrived)
            OnRefused?.Invoke($"до места прогулки {target} не дошёл — обхожусь другой стороной");

        // Отсчёт начинаем заново: следующая прогулка не раньше, чем через
        // тот же порог. Иначе бот ходил бы кругами без остановки
        idleSince = DateTime.UtcNow;
        said = false;
        return true;
    }

    private async Task<bool> StartHomeAsync(CancellationToken ct)
    {
        // ОТКАЗ ПРОТУХАЕТ, КОГДА БОТ СТАЛ БЛИЖЕ К ДОМУ. Разбор живого случая и
        // само правило — у <see cref="Movement.RefusalStillHolds"/>; здесь
        // только «с какого расстояния считать, что я сдвинулся».
        //
        // ЧИСЛО НЕ ВЫДУМАНО: это радиус собственной прогулки. Ближе — и бота
        // «приближал» бы к дому его же обход по округе, а поиск пути из той же
        // округи уже искал и не нашёл; дальше — и подъём столбом на высоту
        // дома (живой случай) остался бы незамеченным
        if (homeGaveUpAt is { } где)
        {
            if (shelter.Home is not { } дом || Feet() is not { } тут)
                return false;   // где я и где дом — неизвестно; отказ держим
            var (держит, почему) = Movement.RefusalStillHolds(дом, где, тут, WanderRadius);
            if (держит)
                return false;
            // ОТБОЙ ВСЛУХ. Молчаливое возвращение к делу, от которого бот
            // только что отказался, человек читает как забывчивость
            homeGaveUpAt = null;
            homeTried = 0;
            OnRefused?.Invoke(почему);
        }

        if (shelter.Home is not { } home)
        {
            if (!said)
            {
                said = true;
                OnRefused?.Invoke("домой не пойду: дом не задан (ручка роли «Дом» / Shelter.Home)");
            }
            return false;
        }

        if (Feet() is { } here && Depot.Apart(here, home) <= HomeRadius)
        {
            if (!said)
            {
                said = true;
                OnCameHome?.Invoke();   // уже дома — идти некуда, но и молчать не о чем
            }
            return false;
        }

        goingHome = true;
        homeTried = 0;
        OnGoingHome?.Invoke(home);
        return await StepHomeAsync(ct);
    }

    /// <summary>
    /// Один отрезок дороги домой. Отрезками — чтобы между ними успели тикнуть
    /// еда, лечение и бой: дорога через полкарты в одном тике означала бы, что
    /// бот идёт домой голодным и не отбиваясь.
    /// </summary>
    private async Task<bool> StepHomeAsync(CancellationToken ct)
    {
        if (shelter.Home is not { } home)
        {
            goingHome = false;
            OnRefused?.Invoke("домой не иду: дом отменили на полдороге");
            return false;
        }

        using var hold = ctx.Turn.TryTake("дорога домой без дела", BodyArbiter.Importance.Routine, ct);
        if (hold == null)
        {
            // Тело понадобилось кому-то важнее — дорога домой подождёт, но
            // счёт попыток не тратим: мы не пробовали, нас не пустили
            goingHome = false;
            return false;
        }

        homeTried++;
        bool reached = await shelter.GoHomeAndCloseDoorAsync(HomeSeconds, hold.Token);
        if (reached)
        {
            goingHome = false;
            OnCameHome?.Invoke();
            idleSince = DateTime.UtcNow;
            said = true;    // про этот дом уже всё сказано
            return true;
        }

        // СБИЛИ С ПОПЫТКИ — ПОПЫТКА НЕ ПОТРАЧЕНА. То же самое правило, что и
        // строчкой выше («нас не пустили»), только для другого конца отрезка:
        // теперь дорогу домой обрывает удар — рефлекс расчищает себе путь, не
        // дожидаясь своего хода (см. BodyArbiter.MakeWay). Без этой проверки
        // три дрифтера по пути к дому означали бы «до дома не дошёл за 3 захода
        // — стою здесь», и бот оставался бы ночевать в поле из-за царапин
        if (hold.End == BodyArbiter.Ending.Preempted)
        {
            homeTried--;
            idleSince = DateTime.UtcNow;
            return true;
        }

        if (homeTried >= HomeTries)
        {
            goingHome = false;
            // ЗАПОМИНАЕМ МЕСТО, А НЕ ФЛАЖОК: отказ взят ОТСЮДА и держит только
            // пока я тут (см. homeGaveUpAt). Места не знаем — держим как
            // раньше, от точки самого дома: тогда правило скажет «ближе не
            // стало» и отказ будет держать, а не растает молча
            homeGaveUpAt = Feet() ?? home;
            OnRefused?.Invoke($"до дома {home} не дошёл за {homeTried} захода — стою здесь " +
                              "(вернусь к этому, когда стану ближе)");
        }
        idleSince = DateTime.UtcNow;
        return true;
    }

    private async Task<bool> LeaveAsync(double idle, CancellationToken ct)
    {
        // ТЕЛО СПРАШИВАЕМ ДВАЖДЫ. Первый раз — общей меркой безделья (сюда мы
        // и попали только потому, что тело свободно), второй — вот здесь, взяв
        // его по-настоящему. Разница не придирка: между двумя тиками человек
        // успевает написать «!принеси руды», команда занимает тело, и бот,
        // проверивший занятость минуту назад, вышел бы из игры прямо посреди
        // чужого поручения. Захват у распорядителя происходит под замком —
        // проскочить между «свободно» и «беру» нельзя
        using var hold = ctx.Turn.TryTake("уход из игры", BodyArbiter.Importance.Routine, ct);
        if (hold == null)
            return false;   // занято: распорядитель уже сказал в журнал, кем

        string why = $"без дела {idle:0} с — так настроено (бездействие: {WhenIdle})";
        OnLeaving?.Invoke(why);

        // Прощание уходит ДО разрыва и с ожиданием отправки: скажи и рви — и
        // пакет останется в очереди чата, а игроки решат, что бот упал
        // Прощание — вежливость, а не отчёт о делах: радиотишина его не глушит.
        // Кому оно не нужно, тот стирает саму строку («ПрощатьсяПередУходом»)
        if (Farewell.Length > 0)
            await ctx.Bot.SendChatAsync(Farewell, reason: SayReason.Вежливость);

        // Механика разрыва живёт в клиенте и переписана здесь не будет.
        // comeBack: false — иначе приёмный цикл вернёт бота в мир, тот снова
        // окажется без дела и снова выйдет; получится не «уйти», а мигать
        ctx.Bot.Disconnect(why, comeBack: false);
        left = true;
        idleSince = null;
        return true;
    }
