namespace VsBotKit;

/// <summary>
/// Осторожность бота в пути. Заказчик поймал живьём: бот «много прыгает и
/// из-за этого разбивается» — потому что по умолчанию ему разрешалось и
/// срезать через провалы, и спрыгивать с высоты за счёт здоровья.
/// </summary>
public enum Caution
{
    /// <summary>Не прыгать и не спрыгивать вовсе — только шаг и лестницы.</summary>
    Careful,

    /// <summary>Прыгать только там, где перелёт гарантирован; вниз — без урона.</summary>
    Normal,

    /// <summary>Срезать через провалы и спрыгивать, платя здоровьем.</summary>
    Bold
}

/// <summary>
/// Настройки поиска пути. Роль бота может менять их под себя:
/// торговец бережёт шкуру (FallDamageBudget = 0), курьер срезает через обрывы.
/// Проще всего — одной ручкой: <c>bot.Movement.Caution = Caution.Careful;</c>
/// </summary>
public sealed class PathOptions
{
    /// <summary>Ходить по диагонали (короче и естественнее).</summary>
    public bool AllowDiagonals { get; set; } = true;

    /// <summary>
    /// Максимальная ступенька вверх, клеток.
    ///
    /// СВОЕГО ЧИСЛА ЗДЕСЬ БОЛЬШЕ НЕТ. Стояла голая единица, а целую клетку тело
    /// шагом не берёт вовсе (игровая StepHeight = 0,6) — берёт её прыжок, и
    /// сколько клеток он берёт, знает одно место
    /// (<see cref="JumpPhysics.CellsUp"/>). Пока тут была своя копия, апекс
    /// можно было поправить, а поиск пути остался бы со старым ответом — молча.
    /// </summary>
    public int MaxStepUp { get; set; } = JumpPhysics.CellsUp;

    /// <summary>
    /// Безопасный спуск без урона, клеток. Не своё число: порог урона от
    /// падения один на весь проект
    /// (<see cref="AStarPathFinder.FallDamageFreeHeight"/> = 3,5 бл, из
    /// <c>EntityBehaviorHealth.OnFallToGround</c>), а клетки из него
    /// отбрасываются вниз — на 3,5 блока падать даром можно, а на четыре уже
    /// нет.
    /// </summary>
    public int SafeDropDistance { get; set; } = (int)AStarPathFinder.FallDamageFreeHeight;

    /// <summary>Максимальная высота осознанного спрыгивания, блоков.</summary>
    public int MaxDeliberateFall { get; set; } = 8;

    /// <summary>
    /// Сколько хп бот готов потратить на одно спрыгивание.
    /// 0 — прыгать только там, где урона нет. Обычно ставится динамически
    /// из текущего здоровья (см. Movement).
    /// </summary>
    public double FallDamageBudget { get; set; }

    /// <summary>
    /// Во сколько блоков обхода оценивается 1 хп. Чем больше — тем охотнее
    /// бот прыгает ради экономии пути.
    /// </summary>
    /// 12 было слишком дёшево: бот штатно менял 2 хп на 25 блоков срезки.
    /// 40 блоков — это около 12 секунд бега, честная цена одного хп.
    public double BlocksPerHitPoint { get; set; } = 40;

    /// <summary>Плавать (иногда переплыть быстрее, чем оббегать).</summary>
    public bool AllowSwimming { get; set; } = true;

    /// <summary>
    /// Потолок длины прыжка, клеток до места приземления (0 — не прыгать).
    /// Именно ПОТОЛОК: настоящую дальность планировщик считает под каждый
    /// прыжок отдельно, по длине доступного разбега (см. JumpPhysics).
    /// С места берётся 3-я клетка, с полутора блоков разгона — 5-я.
    /// </summary>
    public int MaxJumpDistance { get; set; } = 5;

    /// <summary>
    /// Насколько глубоко ЗАГЛЯДЫВАТЬ вниз в поисках опоры. Это не «сколько
    /// согласны спрыгнуть» (за это отвечают SafeDropDistance и
    /// MaxDeliberateFall), а «докуда вообще видим пол».
    ///
    /// Разделять их обязательно: пока глубина взгляда равнялась готовности
    /// прыгать, осторожный бот видел вниз на три блока и с башни не находил
    /// вообще никакого пути — ни безопасного, ни рискованного. Он просто
    /// оставался наверху.
    /// </summary>
    public int MaxDropScan { get; set; } = 16;

    /// <summary>
    /// Во сколько раз дороже клетка ВПЛОТНУЮ к лаве или кипятку. Пройти по
    /// ней можно, но живой игрок так не ходит: шаг в сторону, толчок мобом —
    /// и всё кончено. Единица — «мне всё равно» (для роли-камикадзе).
    /// </summary>
    public double LavaProximityCost { get; set; } = 8;

    /// <summary>Сколько клеток позади точки отрыва вообще смотреть на разбег.</summary>
    public int MaxRunUpCells { get; set; } = 3;

    /// <summary>
    /// Какой запас дальности считать безопасным, блоков. Если бот долетел бы
    /// на столько дальше цели — прыжок гарантирован, и глубина ямы под ним
    /// уже не важна: он не промахнётся. Меньше запаса — прыжок «на пределе»,
    /// и вот тогда яма решает, прыгать или обходить.
    ///
    /// Откуда 0.45. Запас нужен на ОШИБКУ МОДЕЛИ, а её измерили: прыжок с
    /// места живьём дал 2.61 бл. Тогда модель обещала 2.77 — то есть врала на
    /// 6 % В ОПАСНУЮ СТОРОНУ (обещала больше, чем тело летит), и запас брался
    /// на это. Теперь модель говорит 2.507 (замер на игровой физике,
    /// <see cref="JumpPhysics.StandingFlight"/>) — она обещает на 4 % МЕНЬШЕ
    /// живого, то есть ошибается в сторону осторожности. Запас 0.45 оставлен
    /// как есть: на самом длинном прыжке (дальность 5.45) те же проценты — это
    /// треть блока, и урезать его было бы экономией на посадке.
    ///
    /// Раньше стояло 0.8 — число ниоткуда. Из-за него бот отказывался
    /// перепрыгивать щель в ЧЕТЫРЕ блока (это прыжок на пять клеток, запас
    /// 0.45): игрок её берёт с разбега, а бот обходил или вставал.
    /// </summary>
    public double SafeJumpMargin { get; set; } = 0.45;

    /// <summary>
    /// Какую вероятность промаха считать НУЛЁМ. Модель прыжка сама знает свою
    /// точность в несколько процентов (живой замер прыжка с места: 2.61 бл
    /// против 2.507 у модели), поэтому расчётный риск ниже этой доли — не риск,
    /// а шум округления.
    ///
    /// Без этого правила решение висело на машинном волоске: запас щели в
    /// четыре блока выходит 0.4499999 против порога 0.45, вероятность промаха
    /// 0.006 % — и прыжок, который игрок берёт с разбега, отвергался наотрез.
    /// </summary>
    public double NegligibleMissChance { get; set; } = 0.05;

    /// <summary>
    /// Надбавка к стоимости прыжка: замах, потеря управления, приземление.
    /// Не «плата за риск» — риск считается отдельно и только для прыжков на
    /// пределе. Прыжок через щель должен выигрывать у обхода в пять блоков,
    /// иначе бот бегает кругами там, где игрок перепрыгивает не задумываясь.
    /// </summary>
    public double JumpCost { get; set; } = 1.0;

    /// <summary>
    /// Максимальная длина прыжка С ВИСЕНИЯ на лестнице, клеток до места
    /// приземления. Вися, оттолкнуться не от чего — импульса прыжка нет,
    /// только слабый дрейф, которого не хватает даже на соседнюю клетку
    /// через щель. Поэтому по умолчанию ВЫКЛЮЧЕНО: между лестницами бот
    /// ходит через верх — встаёт на торец (он твёрдый) и прыгает как
    /// с земли, с полным импульсом.
    /// </summary>
    public int MaxLadderJumpDistance { get; set; } = 0;

    /// <summary>
    /// На сколько КЛЕТОК ВВЕРХ разрешено запрыгивать через щель.
    ///
    /// Без этого у поиска пути вверх были только ступенька вплотную и лестница:
    /// там, где человек с разбега перескакивает с грани на грань зигзагом, для
    /// бота была стена.
    ///
    /// СВОЕГО ЧИСЛА ЗДЕСЬ БОЛЬШЕ НЕТ. Стояла единица с подписью «прыжок
    /// поднимает тело на 1,27» — то есть ответ был выведен от руки и записан
    /// вторым числом. Ровно так проект уже разошёлся однажды: в отказе бот
    /// говорил «прыжком ровно 1 бл», а починка двойного прыжка считала по 1,27.
    /// Теперь клетки выводит <see cref="JumpPhysics.CellsUp"/>.
    /// </summary>
    public int MaxJumpUp { get; set; } = JumpPhysics.CellsUp;

    /// <summary>Лазать по лестницам — нужно для тоннелей, шахт и выходов наверх.</summary>
    public bool AllowClimbing { get; set; } = true;

    /// <summary>Цена одного блока по лестнице (лезть медленнее, чем идти).</summary>
    public double ClimbCost { get; set; } = 2.0;

    /// <summary>
    /// На сколько КЛЕТОК выше своих ног бот цепляется за висящую лестницу
    /// (нижний конец обрезан и не доходит до пола). 0 — не запрыгивать.
    ///
    /// СВОЕГО ЧИСЛА ЗДЕСЬ БОЛЬШЕ НЕТ: предел целиком выводится из прыжка и
    /// роста (<see cref="JumpPhysics.LadderMountCells"/>). Стояла двойка с
    /// подписью-пересказом того же расчёта — а пересказ рано или поздно
    /// отстаёт от расчёта, чем этот проект уже был наказан.
    /// </summary>
    public int MaxLadderMountHeight { get; set; } = JumpPhysics.LadderMountCells;

    /// <summary>
    /// Во сколько раз блок вплавь «дороже» блока бегом.
    ///
    /// ЗДЕСЬ СТОЯЛА ПОДПИСЬ «бег ~3.8 бл/с, плавание ~1.5». ПЕРВОЕ ЧИСЛО ЛОЖНО:
    /// замер на игровой физике даёт бег 6,79 бл/с
    /// (<see cref="JumpPhysics.SprintSpeed"/>), а шаг 3,393. Второе не измерено
    /// в проекте НИКЕМ: гребок игры отмеряется настоящими часами
    /// (<c>PModulePlayerInLiquid</c>: не чаще раза в 2000 мс), и стенд его не
    /// ловит — так и сказано в <c>PlayerPhysicsFactsTests</c>.
    ///
    /// ЧИСЛО ИГРЫ РЯДОМ ЕСТЬ, НО ОНО ПРО ДРУГОЕ, и путать их нельзя.
    /// <c>EntityAgent.GetWalkSpeedMultiplier</c> (VintagestoryAPI 1.22.7) делит
    /// скорость ровно на 2.5, пока ноги в жидкости
    /// («if (FeetInLiquid) num3 /= 2.5»). Но зовёт этот делитель ТОЛЬКО
    /// <c>PModuleOnGround</c>, а он применим лишь при
    /// «entity.OnGround &amp;&amp; !entity.Swimming» — то есть ровно на БРОДЕ:
    /// ноги в воде, но тело ещё идёт по дну. У ПЛЫВУЩЕГО ход считает
    /// <c>PModuleInLiquid.HandleSwimming</c> — гребком
    /// («Motion += FlyVector · (1+Push) · 0.03»), и никакого 2.5 там нет вовсе.
    ///
    /// Поэтому честно так: на мелководье 2.5 — буквально число игры, а для
    /// НАСТОЯЩЕГО плавания у проекта источника нет ни одного, и 2.5 там
    /// держится только тем, что цена завышена в безопасную сторону (обходить
    /// воду дороже, чем лезть в неё). Менять его по «скоростям» нечем, пока
    /// скорость плавания не замерена: гребок отмеряется настоящими часами
    /// (не чаще раза в 2000 мс), и стенд на быстрых тиках получил бы враньё.
    /// </summary>
    public double SwimCostMultiplier { get; set; } = 2.5;

    /// <summary>
    /// Нырять. Без этого вода для бота — плоскость: он умеет плыть только по
    /// поверхности, а значит не проплывёт под нависшим берегом, под мостом и
    /// не пройдёт затопленный проход — и застревает в воде, «не находя пути».
    /// </summary>
    public bool AllowDiving { get; set; } = true;

    /// <summary>
    /// На сколько блоков ниже поверхности воды бот готов уйти. Под водой
    /// кончается воздух (в игре 40 секунд), поэтому глубже — только осознанно.
    /// </summary>
    public int MaxDiveDepth { get; set; } = 5;

    /// <summary>Цена одного блока под водой (гребля вниз-вверх дороже, чем по поверхности).</summary>
    public double DiveCostMultiplier { get; set; } = 3.5;

    // ЧЕГО ЗДЕСЬ БОЛЬШЕ НЕТ: РУЧКИ MaxWaterExitHeight, И ЭТО ГЛАВНОЕ 27.08.
    //
    // Она говорила «из воды можно подтянуться на кромку в одну клетку», и у
    // этой единицы НЕ БЫЛО ИСТОЧНИКА — так и стояло в её собственной подписи:
    // «осторожное умолчание без источника». Врала она в обе стороны: обещала
    // выход из НЕПОЛНОЙ воды, откуда тело не выходит (замер), — и обещала его
    // же у стены, под которой полной воды нет вовсе, вроде кирпичной кладки
    // дома заказчика, встающей из моря saltwater-d-6.
    //
    // Теперь предел ЗАМЕРЕН и считается по месту: плавучесть плюс всход, а
    // если вода полная — ещё и вылаз по стенке, который игра даёт отдельной
    // поблажкой (см. JumpPhysics.ReachFromOpenWater и Buoyancy). Ручки у него
    // нет нарочно, как и у отказа шага под притолокой: оба числа мерит ИГРА,
    // а не человек, и крутить тут нечего — покрути, и бот начнёт обещать себе
    // подъём, которого тело не берёт.


    /// <summary>
    /// Учитывать скорость по блоку под ногами: по тропинке игрок идёт быстрее
    /// (×1.3), по паутине еле ползёт. Шаг по быстрому блоку дешевеет, и путь
    /// сам «прилипает» к дорогам — не потому, что мы их особо ищем, а потому
    /// что по ним и правда быстрее.
    /// </summary>
    public bool PreferFastGround { get; set; } = true;

    /// <summary>
    /// Дополнительная скидка на шаг по рукотворной дороге (0.8 = на 20%
    /// дешевле). Нужна там, где игра скорости не меняет, но дорога всё равно
    /// дорога: доски, брусчатка, кирпич.
    /// </summary>
    public double RoadCostFactor { get; set; } = 0.8;

    /// <summary>Надбавка за проход через закрытую дверь (открыть — потерять время).</summary>
    public double DoorCost { get; set; } = 2.0;

    /// <summary>
    /// Внешний штраф клетки (множитель цены, 1 — без штрафа). Сюда движение
    /// подключает память тупиков: клетки, где бот недавно упирался в стену,
    /// дорожают, и маршрут сам ищет обход вместо повторного лба.
    /// </summary>
    public Func<int, int, int, double>? ExtraCostAt { get; set; }

    /// <summary>Спрямлять маршрут после поиска (убирать «лесенки»).</summary>
    public bool SmoothPath { get; set; } = true;

    /// <summary>Предел числа просмотренных клеток (защита от зависания).</summary>
    public int MaxNodes { get; set; } = 40000;

    /// <summary>
    /// Сколько клеток поиску позволено просмотреть НА КАЖДЫЙ БЛОК расстояния
    /// до цели. Из этого числа собирается свой потолок под каждый поиск:
    /// дальней дороге он большой, перестроению на пару шагов — маленький.
    ///
    /// Зачем понадобилось. Жалоба: «иногда для перестроения чуть-чуть маршрута
    /// из-за тупика подвисает на пару секунд». Замер на стенде (поле 160×160,
    /// цель заперта в ПЯТИ блоках от бота): поиск честно обошёл 27 620 клеток,
    /// 16 млн вопросов к миру, 1,8 секунды — и это только первый заход, потому
    /// что движение зовёт поиск ещё раз, с частичным путём. Перестроение на
    /// пять шагов работало как поиск дороги через полматерика.
    ///
    /// 300 — чтобы дальний поход по-прежнему упирался только в MaxNodes:
    /// на 133 блоках потолок уже равен ему.
    /// </summary>
    public double NodesPerBlock { get; set; } = 300;

    /// <summary>
    /// Ниже этого потолок поиска не опускается, сколько бы ни было до цели.
    ///
    /// Число ИЗМЕРЕНО, а не придумано: самый тяжёлый ЧЕСТНЫЙ случай на стенде —
    /// цель в пяти блоках, а вход в карман с другого конца, обход под сотню
    /// блоков — обошёлся в 6 521 клетку. 8 000 — он же с запасом. Меньше
    /// ставить нельзя: поиск начнёт отвечать «пути нет» там, где путь есть,
    /// а врать об этом — худшее, что он может сделать.
    /// </summary>
    public int MinNodes { get; set; } = 8000;

    /// <summary>
    /// Как узнать листву. Возвращает true, если в клетке листва — то, что
    /// живой игрок сносит голыми руками, не задумываясь, и оттого сквозь
    /// неё ходит напрямик, а не кругами.
    ///
    /// ПОЧЕМУ ЭТО ВОПРОС, А НЕ СПИСОК КОДОВ. Признак листвы знает сама игра
    /// (материал блока, EnumBlockMaterial.Leaves) — а всякий список кодов
    /// врёт на первом же моде со своими деревьями. Поэтому механика здесь,
    /// а ответ даёт тот, кто держит мир:
    /// <code>
    /// options.IsLeaves = (x, y, z) =>
    ///     bot.World.BlockMaterial(x, y, z) == EnumBlockMaterial.Leaves;
    /// </code>
    /// Не задан — листва остаётся стеной, как и была: механика спит.
    /// </summary>
    public Func<int, int, int, bool>? IsLeaves { get; set; }

    /// <summary>
    /// Надбавка к цене шага за КАЖДЫЙ блок листвы, который придётся снести
    /// (под ноги и под голову — это два разных блока). 0 — сквозь листву не
    /// ходить вовсе, как <c>MaxJumpDistance = 0</c> значит «не прыгать».
    ///
    /// Откуда 4. Цена здесь мерится блоками бега — тем же, чем и всё остальное
    /// в этом поиске. Листва ломается голыми руками почти мгновенно, но тело
    /// должно остановиться, довернуть взгляд, подержать кнопку и снова
    /// разогнаться — около секунды на блок.
    ///
    /// ЧЕСТНО О САМОМ ЧИСЛЕ. Подпись здесь гласила «бег ~3,8 бл/с, значит
    /// секунда стоит примерно 4 блока обхода», и БЕГ В НЕЙ БЫЛ ВЫДУМАН: замер
    /// на игровой физике даёт 6,79 бл/с (<see cref="JumpPhysics.SprintSpeed"/>).
    /// По собственному этому рассуждению секунда возни стоит не 4 блока обхода,
    /// а около 7 — то есть бот сейчас ЧАЩЕ ЛОМИТСЯ СКВОЗЬ КУСТЫ, чем следовало
    /// бы из его же довода. Число оставлено прежним нарочно: 4 — это политика
    /// обхода, а не физика, и менять поведение поиска пути в правке про физику
    /// значило бы поменять его молча. Кому решать — тому и знать: здесь
    /// написана правда, а не удобная цифра.
    /// </summary>
    public double LeafBreakCost { get; set; } = 4;

    /// <summary>
    /// Цель недостижима (за краем прогруженных чанков, за завалом) — вернуть
    /// путь до самой близкой к ней достигнутой клетки вместо null. Так бот
    /// идёт длинными тоннелями: доходит до края видимого мира, там подгружаются
    /// новые чанки, маршрут строится дальше. Нужен внешний цикл (TravelToAsync).
    /// </summary>
    public bool AllowPartialPath { get; set; }

    /// <summary>
    /// Разрешить РАЗВЕДКУ: если ни одна клетка не оказалась ближе к цели,
    /// пойти к самой дальней разведанной вместо того, чтобы стоять на месте.
    ///
    /// Зачем это политика, а не закон: сторожу метаться незачем, а путнику
    /// без этого не выйти из дома — стоя в комнате, он не узнает, что дверь
    /// за углом. Живьём бот отвечал «Не дошёл, стою на (36, 110, 10)»,
    /// не сделав ни шагу.
    /// </summary>
    public bool AllowExploration { get; set; } = true;

    /// <summary>
    /// Насколько разведке позволено УХУДШИТЬ положение относительно старта.
    /// Ноль — «только не дальше от цели»; больше — «можно и в обход».
    /// </summary>
    public double ExploreSlack { get; set; } = 6;

    /// <summary>
    /// Почему путь не найден или найден частично. Молчаливый null — худший
    /// вид отказа: по нему невозможно понять, край мира это, предел поиска
    /// или запертая дверь.
    /// </summary>
    public Action<string>? OnTrace { get; set; }

    public PathOptions Clone() => (PathOptions)MemberwiseClone();
}

/// <summary>
/// Поиск пути. Своя реализация подставляется боту вместо стандартной:
/// <c>bot.PathFinder = new MyPathFinder();</c>
/// </summary>
public interface IPathFinder
{
    /// <summary>
    /// Маршрут от from до to; null — пути нет. Первый шаг — старт, последний —
    /// цель (или ближайшая достижимая к ней).
    /// </summary>
    /// <remarks>
    /// Возвращаются ХОДЫ, а не просто клетки: планировщик знает, где он
    /// заложил прыжок, где зацеп за лестницу, а где спрыгивание за счёт
    /// здоровья, — и обязан это сказать. Пока он возвращал голые клетки,
    /// тело переугадывало тип хода по геометрии, и каждое расхождение
    /// стоило живого бага: шаг вместо прыжка с разбега, «не долетел» без
    /// единой строки в журнале.
    ///
    /// Для чужой реализации это тем более обязательно: она может придумать
    /// ход, о котором наше тело не догадается никогда.
    /// </remarks>
    List<PathStep>? FindPath(IPathWorld world, BlockPos from, BlockPos to, PathOptions options);

    /// <summary>
    /// СКОЛЬКО КЛЕТОК ПОИСК ОСМОТРЕЛ В ПОСЛЕДНИЙ РАЗ. 0 — «не считал»: чужая
    /// реализация вправе не отвечать, и тогда механика, которой это число
    /// нужно, честно молчит, а не выдумывает своё.
    ///
    /// ЗАЧЕМ ЭТО ВЫНЕСЕНО В ДОГОВОР. Потолок осмотра свой у каждого поиска и
    /// считается от расстояния (<see cref="AStarPathFinder.NodeCeiling"/>).
    /// Когда узкий потолок соврал — «дороги нет» там, где она есть, — движение
    /// обязано узнать, сколько клеток стоила НАСТОЯЩАЯ дорога, и поднять свой
    /// пол ровно до этого числа. Иначе выбор один из двух плохих: либо снова
    /// врать, либо снять потолок совсем и вернуть жалобу хозяина «для
    /// перестроения чуть-чуть маршрута подвисает на пару секунд».
    /// </summary>
    int LastExplored => 0;
}
