namespace VsBotKit;

/// <summary>
/// ПЛАВУЧЕСТЬ: ГДЕ ДЕРЖИТСЯ ТЕЛО В ВОДЕ — ОДИН СЧЁТ НА ВЕСЬ ПРОЕКТ.
///
/// Формулы живут в <see cref="JumpPhysics"/> (тот файл нарочно ничего не знает
/// про мир: его линкует в себя клиентский мод), а здесь — ровно перевод с
/// языка мира на язык формул: сколько налито в клетку, что над ней, докуда
/// тянется полная вода. Второй такой перевод был бы вторым правилом, а по
/// закону проекта одна механика живёт в одном месте.
///
/// СПРАШИВАЮТ ЭТО ДВА КОНЦА, И ИМЕННО ПОЭТОМУ ОДИН СЧЁТ. Маршрут
/// (<see cref="AStarPathFinder"/>) решает, звать ли тело на кромку, а само тело
/// (<see cref="Movement"/>) решает, идти ли туда, куда позвали, — и живой мир
/// между этими двумя решениями успевает измениться: вода прибывает, перекрытие
/// достраивают. Разойдись счёт — и планировщик снова водил бы туда, откуда
/// тело разворачивается молча.
/// </summary>
public static class Buoyancy
{
    /// <summary>
    /// ЛИНИЯ ВОДЫ У КЛЕТКИ по счёту игры (<see cref="JumpPhysics.WaterLine"/>):
    /// заполнение самой клетки плюс по 1,125 за каждую из двух жидких клеток
    /// над ней.
    /// </summary>
    public static double WaterLineAt(this IPathWorld world, int x, int y, int z) =>
        JumpPhysics.WaterLine(y, world.LiquidFill(x, y, z),
                              world.IsWater(x, y + 1, z), world.IsWater(x, y + 2, z));

    /// <summary>
    /// ДОКУДА ТЯНЕТСЯ ПОЛНАЯ ВОДА НАД ТЕЛОМ, блоков — верх последней клетки с
    /// <c>LiquidLevel &gt;= 7</c>, считая от щупов игры вверх БЕЗ ПРОПУСКОВ.
    /// <c>double.NegativeInfinity</c> — полной воды у тела нет вовсе.
    ///
    /// ЗАЧЕМ ИМЕННО ТАК. Поблажка игры «упёрся в стену в полной воде — ползи
    /// вверх» (<c>EntityBehaviorControlledPhysics.ApplyTests</c>) щупает три
    /// высоты ОТНОСИТЕЛЬНО НОГ (<see cref="JumpPhysics.WallCrawlProbes"/>) и
    /// требует от них ровно <c>LiquidLevel &gt;= 7</c>. Пока полная вода идёт
    /// сплошняком, тело ползёт; первая неполная клетка его останавливает —
    /// потому счёт идёт вверх до разрыва, а не «где-то выше есть полная».
    ///
    /// ВОПРОС ЗАДАЁТСЯ ПО ВЫСОТЕ НОГ, А НЕ ПО НОМЕРУ КЛЕТКИ, И ЭТО ПОЧИНКА
    /// 27.08 ПО ЖИВОЙ НАХОДКЕ. Раньше здесь стояло «клетка ног полна?» — то
    /// есть терялся верхний щуп «+0,5», смотрящий на клетку ВЫШЕ ног. В море
    /// заказчика (прочие клетки 6/8, верхняя 7/8) тело выходило на кромку, а
    /// правило отказывало; хуже — два конца отвечали РАЗНОЕ, потому что поиск
    /// пути спрашивал у верхней клетки (7/8, разрешал), а тело — у своей
    /// (6/8, запрещало), и выигрывал отказ с <c>MarkUnreachableLeg</c>.
    /// </summary>
    /// <param name="feetY">Высота НОГ тела (не номер клетки).</param>
    public static double TopFullWater(this IPathWorld world, int x, double feetY, int z)
    {
        // Щупы игры: какая из трёх высот попала в ПОЛНУЮ воду. Берём самую
        // высокую из попавших — с неё тело и продолжит ползти вверх
        int начало = int.MinValue;
        foreach (double щуп in JumpPhysics.WallCrawlProbes)
        {
            int клетка = (int)Math.Floor(feetY + щуп);
            if (клетка > начало && world.LiquidFill(x, клетка, z) >= JumpPhysics.FullLiquid)
                начало = клетка;
        }
        if (начало == int.MinValue)
            return double.NegativeInfinity;
        int верх = начало;
        // Выше поверхности воды искать нечего, а вглубь неба колонна не уходит:
        // предел взят с запасом на самый глубокий затопленный ход
        while (верх - начало < 32 && world.LiquidFill(x, верх + 1, z) >= JumpPhysics.FullLiquid)
            верх++;
        return верх + 1;
    }

    /// <summary>
    /// КРОМКА ЛИ ЭТО ВООБЩЕ — или просто клетка воды.
    ///
    /// ВЫХОД ИЗ ВОДЫ — ЭТО ВЫХОД НА ОПОРУ: под ногами твёрдый верх, на котором
    /// тело СТОИТ. В клетку воды не выбираются, в неё всплывают, и мерка
    /// выхода на берег к ней неприменима вовсе.
    ///
    /// ЖИВАЯ УЛИКА, РАДИ КОТОРОЙ ЭТОТ ВОПРОС ЗАВЁДЕН (прогон 27.08,
    /// out/вода-ПОСЛЕ, Стенд2). Первый заход починки спрашивал правило у
    /// ВСЯКОЙ точки маршрута, и в море заказчика вышло:
    ///     не пойду на точку 4/4 (32, 114, 9): вплавь на кромку 114 не
    ///     подняться: вода держит ноги на 112,75
    /// Клетка (32, 114, 9) — saltwater-d-6, вода. После спрямления в маршруте
    /// остаются точки через две-три клетки, и мерить их «выходом на берег»
    /// нельзя: отказ тащит за собой MarkUnreachableLeg, то есть отравление
    /// клетки маршрута — потом туда нет ходу и с другой стороны.
    ///
    /// ЗАТОПЛЕННЫЙ БЕРЕГ — ВСЁ РАВНО КРОМКА, и просто «нет ли тут воды» не
    /// годится: в живой беде под потолком кромка (32, 114, 5) была ЗАЛИТА
    /// водой поверх кирпича. Спрашиваем не про воду, а про твёрдый верх.
    /// </summary>
    public static bool IsWaterLedge(this IPathWorld world, int x, int y, int z) =>
        world.IsSolid(x, y - 1, z) || world.FeetY(x, y, z) > y;

    /// <summary>
    /// ВЫЙДЕТ ЛИ ТЕЛО ИЗ ЭТОЙ ВОДЫ НА КРОМКУ — вопрос миру целиком, со всеми
    /// заставами разом (см. <see cref="JumpPhysics.LeaveWater"/>).
    /// </summary>
    /// <param name="world">Мир.</param>
    /// <param name="x">Клетка, в которой тело плывёт.</param>
    /// <param name="y">Клетка, в которой тело плывёт.</param>
    /// <param name="z">Клетка, в которой тело плывёт.</param>
    /// <param name="ledgeFeetY">Высота ног на кромке, куда зовёт маршрут.</param>
    public static (bool Out, string Why) LeaveWaterFrom(
        this IPathWorld world, int x, int y, int z, double ledgeFeetY)
    {
        double линия = world.WaterLineAt(x, y, z);
        return JumpPhysics.LeaveWater(ledgeFeetY, линия,
            world.TopFullWater(x, JumpPhysics.AfloatInOpenWater(линия), z),
            world.CeilingOver(x, y, z));
    }

    /// <summary>
    /// ДОКУДА ПОДНИМУТСЯ НОГИ ИЗ ЭТОЙ КЛЕТКИ ВОДЫ НА ОПОРУ, блоков: меньшее из
    /// плавучести и потолка. По этому числу поиск пути режет ДВЕ ветки вверх —
    /// ступеньку и выход на берег. Обе кончаются на ТВЁРДОМ, и потому обеим
    /// положены и всход, и вылаз по стенке.
    ///
    /// ТРЕТЬЯ ВЕТКА, ВСПЛЫТИЕ, СЧИТАЕТСЯ ДРУГИМ ЧИСЛОМ — см.
    /// <see cref="AfloatReachInWater"/>. До 27.08 она резалась этим же, и
    /// подаренные полблока всхода стоили живого «упёрся на точке (32, 115, 9)».
    /// </summary>
    public static double ReachOutOfWater(this IPathWorld world, int x, int y, int z)
    {
        double линия = world.WaterLineAt(x, y, z);
        return JumpPhysics.ReachOutOfWater(линия,
            world.TopFullWater(x, JumpPhysics.AfloatInOpenWater(линия), z),
            world.CeilingOver(x, y, z));
    }

    /// <summary>
    /// ДОКУДА ПОДНИМУТСЯ НОГИ ПЛЫВУЩЕГО, КОГДА ВСТАВАТЬ НЕ НА ЧТО (всплытие в
    /// соседнюю клетку ВОДЫ): чистая плавучесть, без всхода и без вылаза по
    /// стенке — см. <see cref="JumpPhysics.AfloatReach"/>, там и живая цена.
    /// </summary>
    public static double AfloatReachInWater(this IPathWorld world, int x, int y, int z) =>
        JumpPhysics.AfloatReach(world.WaterLineAt(x, y, z), world.CeilingOver(x, y, z));
}
