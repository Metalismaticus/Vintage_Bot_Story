namespace VsBotKit;

/// <summary>
/// ЧТО РЕШЕНО ПРО ПОСТ ПРЯМО СЕЙЧАС. Отдельным перечислением, а не парой
/// булей: «не на посту» и «слишком далеко, чтобы идти самому» — РАЗНЫЕ ответы,
/// и человеку они звучат по-разному. Пока это были два флага, вызывающий
/// проверял их в своём порядке и путал (см. <see cref="PostRules.Что"/>).
/// </summary>
public enum PostVerdict
{
    /// <summary>Точка не задана. Держать нечего — и это НЕ беда, а настройка.</summary>
    НетПоста,

    /// <summary>Стою в пределах радиуса поста: идти никуда не надо.</summary>
    НаПосту,

    /// <summary>Отошёл дальше радиуса, но в пределах поводка — возвращаюсь.</summary>
    Вернуться,

    /// <summary>
    /// Дальше поводка. Сам не пойду и скажу об этом ПО ИМЕНИ РУЧКИ: бот,
    /// молча шагающий через полкарты «на пост», — это потерянный бот.
    /// </summary>
    СлишкомДалеко
}

/// <summary>
/// ЧИСТЫЕ ПРАВИЛА УДЕРЖАНИЯ ТОЧКИ: ни мира, ни сети, ни бота — только числа.
/// Потому и закрыты стендом: на них висит решение «идти или стоять», а ошибка
/// в нём означает либо бота, дёргающегося на месте, либо бота, ушедшего
/// с поста навсегда.
/// </summary>
public static class PostRules
{
    /// <summary>
    /// НАСКОЛЬКО ТЕЛО ОТОШЛО ОТ ПОСТА, блоков.
    ///
    /// ВЫСОТА СЧИТАЕТСЯ, и это не педантизм. Пост стражника стоит на стене, на
    /// вышке, на помосте у ворот; бот, свалившийся с этой стены, по горизонтали
    /// остаётся ровно над постом — и удержание, меряющее только X и Z, честно
    /// доложило бы «я на посту», лёжа шестью блоками ниже. Ровно этой ошибкой
    /// живёт вторая, старшая копия правила (<c>BehaviorShopkeeper</c>): она
    /// меряет без Y, потому что прилавок плоский и цена ошибки там нулевая.
    ///
    /// Полблока прибавляется к X и Z, а к высоте — нет: клетка задаётся своим
    /// углом, тело стоит в её СЕРЕДИНЕ по горизонтали и на её ПОЛУ по высоте.
    /// Без этих полублоков бот у самой середины клетки поста числился бы
    /// отошедшим на 0,7 блока, и радиус поста в 0,5 не сработал бы никогда.
    /// </summary>
    public static double Отступ(double x, double y, double z, BlockPos пост)
    {
        double dx = x - (пост.X + 0.5);
        double dy = y - пост.Y;
        double dz = z - (пост.Z + 0.5);
        return Math.Sqrt(dx * dx + dy * dy + dz * dz);
    }

    /// <summary>
    /// ИДТИ ЛИ НА ПОСТ — всё решение одной функцией.
    ///
    /// ПОРЯДОК ПРОВЕРОК ЗДЕСЬ ЧАСТЬ ПРАВИЛА, а не оформление. Радиус
    /// спрашивается ПЕРВЫМ, и потому человек, который вписал поводок МЕНЬШЕ
    /// радиуса, получает работающего бота, а не парализованного: раз он сам
    /// назвал этот круг постом, стоять в нём — не «слишком далеко».
    ///
    /// ЩЕЛИ МЕЖДУ РАДИУСОМ И ПОВОДКОМ НЕТ, и второго <c>Math.Max</c> здесь
    /// поэтому тоже нет. Он тут СТОЯЛ, и приписка объясняла его щелью, «где бот
    /// и не на посту, и идти ему нельзя», — щели не существует: до второй
    /// проверки доходят только при <c>отступ &gt; радиус</c>, а при поводке
    /// короче радиуса это уже значит <c>отступ &gt; поводок</c>. Приёмка
    /// подменила ту строку и не покраснела ни одним стендом — потому что код
    /// был мёртвым, а причина выдуманной.
    ///
    /// ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ СТАРШЕЙ КОПИИ (<c>BehaviorShopkeeper</c>, где
    /// стоит <c>away &gt;= LeashRadius * 2</c>): там поводок вдвое длиннее
    /// того, что обещает его имя, и человек, поставивший «поводок 25», получал
    /// бота, уходящего за пятьдесят. Здесь поводок значит ровно то, что
    /// написано.
    /// </summary>
    /// <param name="естьПост">Точка поста задана.</param>
    /// <param name="отступ">Сколько блоков от поста до тела (<see cref="Отступ"/>).</param>
    /// <param name="радиус">Ближе этого считается «на посту».</param>
    /// <param name="поводок">Дальше этого сам не иду.</param>
    public static PostVerdict Что(bool естьПост, double отступ, double радиус, double поводок)
    {
        if (!естьПост)
            return PostVerdict.НетПоста;
        if (отступ <= радиус)
            return PostVerdict.НаПосту;
        return отступ > поводок
            ? PostVerdict.СлишкомДалеко
            : PostVerdict.Вернуться;
    }
}

/// <summary>
/// ПРО ЧТО ОТКАЗ УДЕРЖАНИЯ. Нужен затем, что имя ручки знает РОЛЬ, а не
/// механизм: у стражника поводок зовётся «ВозвращатьсяНаПостНеДальше», у
/// продавца — «ПоводокОтПоста», и назови библиотека одно из этих имён — второй
/// потребитель получил бы отказ с чужой ручкой. Приёмка поймала это дословно:
/// отказ печатал одно число, а называл ручку, в которой стоит другое.
/// </summary>
public enum PostRefusal
{
    /// <summary>Точка поста не задана.</summary>
    НетПоста,

    /// <summary>Дальше поводка — сам не пойду.</summary>
    Унесло,

    /// <summary>Пробовал и не дошёл.</summary>
    НеДойти
}

/// <summary>
/// СТОЯТЬ ТУТ И ВОЗВРАЩАТЬСЯ, ЕСЛИ УШЁЛ, — механизм библиотеки.
///
/// ЗАЧЕМ ОН ОБЩИЙ, А НЕ ВНУТРИ СТРАЖНИКА. Заказчик просил пост стражнику
/// («ему нужно СТОЯТЬ В ОДНОЙ ТОЧКЕ»), но упираются в это же самое минимум
/// трое: продавец за прилавком, бот у печи и бот, ждущий хозяина у входа.
/// Написать это внутри роли значило бы завести вторую копию одного правила —
/// а она у продавца уже была, и мерку отступа он теперь спрашивает здесь же
/// (<see cref="PostRules"/>).
///
/// СОБИРАЕТСЯ СПОСОБНОСТЬ У ВСЕХ (<c>Presets.Survive</c>) И МОЛЧИТ, пока роль
/// не задала точку: пустой <see cref="Post"/> — это не поломка, а «этой роли
/// пост не нужен». Живи она только внутри стражника, дотянуться до общего
/// правила не мог бы никто другой.
///
/// ЧЕМ ЭТО НЕ «БЕЗ ДЕЛА: ДОМОЙ» (<see cref="BehaviorIdle"/>). Тем, что
/// безделье — это СЧЁТЧИК ПОЛНОГО ПРОСТОЯ: тридцать секунд подряд ничем не
/// занятого тела, и любой чужой ход (подобрал добычу, поел, отбился) сбрасывает
/// счёт в ноль. Стражник у людных ворот такого простоя не набирает вовсе, и
/// «Домой» у него срабатывает раз в несколько минут, а то и никогда. Удержание
/// смотрит НЕ НА ЧАСЫ, А НА РАССТОЯНИЕ: отошёл дальше радиуса — вернись,
/// сколько бы дел ни случилось по дороге.
///
/// ЧТО УВОДИТ БОТА С ПОСТА И ПОЧЕМУ МЫ ЭТИМ ДЕЛАМ УСТУПАЕМ, А НЕ ПЕРЕБИВАЕМ ИХ.
/// Уводят: бой и погоня (<c>BehaviorAttackHostiles</c>), еда из кладовых и сбор
/// ягод (<c>BehaviorForageWhenNoFood</c>), своя добыча и добыча с убитых
/// (<c>BehaviorPickUpDrops</c>, <c>BehaviorLootKills</c>), уход от
/// нестабильности (<c>BehaviorSeekStability</c>), укрытие в бурю
/// (<c>BehaviorShelterFromStorm</c>), поход за вещами после смерти
/// (<c>BehaviorRecoverLoot</c>). Перебить их удержанием было бы можно — и это
/// была бы смерть на посту: бот, которому «стоять» важнее, чем «поесть»,
/// умирает с хлебом в кармане, а этой бедой проект уже горел (см.
/// <c>BodyArbiter.Importance.Vital</c>). Поэтому вес у удержания — обычное ДЕЛО
/// РОЛИ (<see cref="BehaviorWeights.Work"/>), тело берётся как
/// <see cref="BodyArbiter.Importance.Routine"/>, и любая жизненная нужда
/// забирает его у нас на полдороге. ВОЗВРАТ ОТ ЭТОГО НЕ ТЕРЯЕТСЯ: перебитая
/// попытка не считается потраченной (<see cref="BodyArbiter.Ending.Preempted"/>),
/// и на следующем тике мы идём назад снова.
///
/// ХОДА, СТОЯ НА ПОСТУ, СПОСОБНОСТЬ НЕ БЕРЁТ. Стоящий никому не мешает, и
/// забирать за это тик у приветствия, фонаря и «выглядеть живым» незачем.
/// </summary>
public class BehaviorHoldPost : BotBehavior
{
    private readonly BotContext ctx;

    public BehaviorHoldPost(BotContext ctx)
    {
        this.ctx = ctx;
        // Слово безнадёги уходит наружу тем же событием, что и прочие отказы:
        // второго пути «сказать человеку» у способности нет
        Гиблое.OnSay += строка => OnRefused?.Invoke(ПоКлючу(строка), строка);
    }

    /// <summary>
    /// ГДЕ СТОЯТЬ — в МИРОВЫХ координатах. Переводит их РОЛЬ, и только она:
    /// человек задаёт точку игровыми числами (теми, что у него на экране), а
    /// перевод в проекте делается одним правилом (<see cref="WorldOrigin"/>).
    /// Возьмись способность переводить сама — это была бы вторая дорога к
    /// одному и тому же началу отсчёта.
    ///
    /// null — ПОСТА НЕТ, и это не ошибка, а настройка: бот тогда ведёт себя
    /// ровно как без этой способности. Сказать об этом один раз всё же надо
    /// (<see cref="OnRefused"/>): молчащий бот неотличим от сломанного.
    /// </summary>
    public BlockPos? Post { get; set; }

    /// <summary>Ближе этого к посту бот считается стоящим на посту, блоков.</summary>
    public double Radius { get; set; } = 3;

    /// <summary>
    /// Дальше этого от поста бот САМ не возвращается, а честно говорит, что
    /// его унесло. Живой резон: бота уносит смертью и возрождением на кровати
    /// за полкарты, и «иду на пост» оттуда — это час ходьбы через мобов вместо
    /// одной строки в журнале, по которой человек вернёт его сам.
    /// </summary>
    public double Leash { get; set; } = 64;

    /// <summary>
    /// Отрезок дороги на пост за один тик, секунд. Отрезками — по той же
    /// причине, что и дорога домой у безделья: пока способность идёт, она
    /// держит ход, и всё это время бот не ест, не лечится и не отбивается.
    /// </summary>
    public double SecondsPerStep { get; set; } = 20;

    /// <summary>
    /// Сколько отрезков пробовать, прежде чем честно сказать «не дошёл».
    /// Без предела бот долбил бы стену между собой и постом до утра.
    /// </summary>
    public int Tries { get; set; } = 3;

    /// <summary>
    /// Передышка между заходами. Нужна ровно затем, чтобы не мешать тому, ради
    /// чего мы с поста и сошли: бой идёт рывками, и удержание, пробующее уйти
    /// на пост каждую секунду, отбирало бы ход у драки в каждой паузе.
    /// </summary>
    public TimeSpan Rest { get; set; } = TimeSpan.FromSeconds(5);

    /// <summary>
    /// «НЕ ВЫХОДИТ — ПОПРОБУЮ ПОЗЖЕ» — ОБЩИЙ МЕХАНИЗМ, А НЕ СВОЙ ФЛАЖОК.
    ///
    /// Здесь СТОЯЛ свой: <c>сдался = true</c>, и снимался он только приходом на
    /// пост, сменой точки и выходом из мира. Стражник, которого три раза подряд
    /// не пустили к посту (закрылась дверь, встал игрок в проходе, чанк не
    /// прогружен), больше не пробовал ДО КОНЦА СЕАНСА и больше ничего не
    /// говорил — при том что док-строка обещала лечить «долбил бы стену до
    /// утра». Лечила навсегда.
    ///
    /// У <see cref="Hopeless{TKey}"/> ровно то, чего копии не хватало:
    /// <see cref="Hopeless{TKey}.TryAgainAfter"/> (срок второй попытки, его же
    /// крутит общая ручка роли «НеБратьсяЗаБезнадёжноеМинут») и напоминание
    /// вслух, пока беда держится. Потребителей у него до нас четверо.
    /// </summary>
    public Hopeless Гиблое { get; } = new();

    /// <summary>Пошёл на пост: куда и с какого отступа.</summary>
    public event Action<BlockPos, double>? OnGoingBack;

    /// <summary>Встал на пост.</summary>
    public event Action<BlockPos>? OnStood;

    /// <summary>
    /// Не стал или не смог — с ПРИЧИНОЙ И ВИДОМ отказа. Вид нужен роли: имя
    /// ручки знает она, и дописывает его к нашим словам сама.
    /// Молчаливого отказа здесь нет.
    /// </summary>
    public event Action<PostRefusal, string>? OnRefused;

    private DateTime следующийЗаход = DateTime.MinValue;
    private int заходов;
    private bool наПосту = true;
    private BlockPos? прошлыйПост;

    /// <summary>Ключи безнадёги — они же попадают в строку вслух.</summary>
    private const string КлючНетПоста = "точка поста";
    private const string КлючУнесло = "поводок поста";
    private const string КлючНеДойти = "дорога на пост";

    private static PostRefusal ПоКлючу(string строка) =>
        строка.StartsWith(КлючНетПоста, StringComparison.Ordinal) ? PostRefusal.НетПоста
        : строка.StartsWith(КлючУнесло, StringComparison.Ordinal) ? PostRefusal.Унесло
        : PostRefusal.НеДойти;

    /// <summary>
    /// ТЕКУЩИЙ ОТСТУП ОТ ПОСТА, блоков. null — поста нет или бот не знает, где
    /// он. Наружу нужен окну и стендам: «стоит ли он на посту» человек обязан
    /// уметь спросить, не глядя в журнал.
    /// </summary>
    public double? Отступ => Post is { } п && ctx.Self.Position is { } p
        ? PostRules.Отступ(p.X, p.Y, p.Z, п)
        : null;

    public override async Task<bool> TickAsync(CancellationToken ct)
    {
        // ВНЕ МИРА И МЁРТВЫМ НА ПОСТ НЕ ХОДЯТ. Мёртвому сервер отказывает во
        // всём, и бот честно докладывал бы «не дошёл», лёжа на месте гибели, —
        // ровно та беда, из-за которой такая же застава стоит у безделья.
        // Без этой заставы ОДНА смерть съедала все три захода
        if (!ctx.Bot.Joined || ctx.Self.IsDead)
        {
            Забыть();
            return false;
        }

        // ТОЧКУ ПОМЕНЯЛИ — ВСЁ СНАЧАЛА. Человек передвинул пост в окне или
        // сказал «!пост тут», а мы бы до утра держали «туда не дойти» про
        // СТАРУЮ точку: со стороны это ровно «настройка не работает»
        if (!Equals(прошлыйПост, Post))
        {
            прошлыйПост = Post;
            Забыть();
        }

        if (Post is not { } пост)
        {
            Гиблое.GiveUp(КлючНетПоста,
                "не задана, стоять мне негде. Это не поломка — без неё я " +
                "просто живу как обычный бот");
            return false;
        }
        Гиблое.TryAgain(КлючНетПоста, "задана — держу её");

        if (ctx.Self.Position is not { } тело)
            return false;   // где я — ещё не знаю; сервер скажет через тик

        double отступ = PostRules.Отступ(тело.X, тело.Y, тело.Z, пост);
        switch (PostRules.Что(естьПост: true, отступ, Radius, Leash))
        {
            case PostVerdict.НаПосту:
                // ПРИШЁЛ — И ВСЕ ПРЕЖНИЕ ОТКАЗЫ СНЯТЫ. Иначе бот, однажды не
                // дошедший, молчал бы и в следующий раз, когда не дойдёт по
                // другой причине
                Забыть();
                if (!наПосту)
                {
                    наПосту = true;
                    OnStood?.Invoke(пост);
                }
                return false;   // стоящий не мешает никому: ход не забираем

            case PostVerdict.СлишкомДалеко:
                наПосту = false;
                // ЧИСЛО В ОТКАЗЕ — ТО САМОЕ, ЧТО СТОИТ В РУЧКЕ. Здесь печатался
                // Math.Max(радиус, поводок), а называлась ручка поводка: при
                // радиусе 10 и поводке 2 бот говорил «дальше поводка (10 бл)»,
                // и числа 10 в той ручке не было ни у кого
                Гиблое.GiveUp(КлючУнесло,
                    $"я в {отступ:0.#} бл от него, а сам возвращаюсь только с {Leash:0.#} бл. " +
                    "Дорога через полмира стоит дороже, чем вернуть меня рукой");
                return false;

            default:
                наПосту = false;
                break;
        }
        Гиблое.TryAgain(КлючУнесло, "я снова в пределах поводка");

        if (Гиблое.Given(КлючНеДойти) || DateTime.UtcNow < следующийЗаход)
            return false;

        using var владение = ctx.Turn.TryTake("возвращаюсь на пост",
            BodyArbiter.Importance.Routine, ct);
        if (владение == null)
            // Тело понадобилось кому-то важнее. Попытку не тратим: мы не
            // пробовали — нас не пустили. Распорядитель уже сказал, кем занято
            return false;

        заходов++;
        OnGoingBack?.Invoke(пост, отступ);

        // Отрезок времени свой: ход у способности заберут только распорядитель
        // и отмена, а дорога сама по себе может тянуться очень долго
        using var отрезок = CancellationTokenSource.CreateLinkedTokenSource(владение.Token);
        отрезок.CancelAfter(TimeSpan.FromSeconds(SecondsPerStep));
        bool дошёл = await ctx.Movement.MoveToCellAsync(пост, отрезок.Token);

        if (дошёл)
        {
            Забыть();
            наПосту = true;
            OnStood?.Invoke(пост);
            return true;
        }

        // СБИЛИ С ПОПЫТКИ — ПОПЫТКА НЕ ПОТРАЧЕНА. Дорогу на пост обрывает удар:
        // рефлекс расчищает себе путь, не дожидаясь своего хода (BodyArbiter.
        // MakeWay). Без этой строки три дрифтера по пути означали бы «не дошёл
        // за 3 захода», и стражник оставался бы стоять в поле из-за царапин
        if (владение.End == BodyArbiter.Ending.Preempted)
        {
            заходов--;
            return true;
        }

        следующийЗаход = DateTime.UtcNow + Rest;
        if (заходов >= Math.Max(1, Tries))
            Гиблое.GiveUp(КлючНеДойти,
                $"{пост} — не дошёл за {заходов} захода, стою здесь. Пост либо " +
                "замурован, либо задан внутри стены");
        return true;
    }

    /// <summary>
