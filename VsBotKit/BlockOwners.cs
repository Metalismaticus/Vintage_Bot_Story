using EnumBlockMaterial = Vintagestory.API.Common.EnumBlockMaterial;

namespace VsBotKit;

/// <summary>ЧЕЙ БЛОК СТОИТ В ЭТОЙ КЛЕТКЕ.</summary>
public enum BlockOwner
{
    /// <summary>Мой: я сам его сюда положил (<see cref="TempBlocks"/>).</summary>
    Mine,

    /// <summary>Ничей: такое кладёт в мир сама игра — порода, земля, руда, вода.</summary>
    Nature,

    /// <summary>Чужой: заявка сервера или постройка, которую ставил человек.</summary>
    Foreign,

    /// <summary>Не понял. Ломать нельзя — и надо сказать об этом вслух.</summary>
    Unknown
}

/// <summary>
/// СВОЮ ВЫЕМКУ ЛОМАТЬ МОЖНО, ЧУЖУЮ ПОСТРОЙКУ — НЕТ.
///
/// ЖИВОЙ СЛУЧАЙ, ради которого правило написано (ночь 18.08, слова заказчика):
/// «и только что бот затупил выходить через дверь и стал искать выход и ломать
/// дом изнутри».
///
/// Журнал, 00:41:16–00:41:49. Человек позвал бота командой «!комне». Дороги к
/// нему не нашлось («до (512024, 113, 512255) не хватает 1 бл по высоте»), и
/// движение решило пробиваться наверх. Дальше — пять строк подряд:
///
///   [штольня] иду вверх ступенями: ступеней 5…
///   [добыча] ломаю debarkedlog-oak-ud: 1,7 с (axe-peridotite)
///   [штольня] проходка 7 кл. (сломано 4…); попутно добыто: debarkedlog-oak-ud x4
///
/// «debarkedlog-oak» — ОКОРЁННОЕ бревно. В мире оно не растёт: его делает
/// человек. Бот вырубил лестницу сквозь стену и крышу дома заказчика — того
/// самого, чью дверь он открывает каждый вечер (512061, 112, 512252).
///
/// ТРЕТИЙ РАЗ (23.08, 11:01:57), и вот чем он отличается от первых двух:
///
///   [стройка] блоков на столб нет — добываю на месте, годных клеток вокруг 4
///   [добыча] ломаю soil-medium-normal: 1,8 с
///   [добыча] ломаю rammed-light-plain: 3 с
///
/// Бот стоял В ДВЕРЯХ дома заказчика (дверь door-sleek-windowed-purpleheart в
/// (61, 112, 252)) и выламывал ПОЛ И СТЕНУ себе на столб. Застава при этом
/// была вызвана и ответила «можно»: `rammed-light-plain` игра объявляет
/// материалом Soil (assets/survival/blocktypes/soil/rammed.json:
/// "blockmaterial": "Soil"), а <see cref="WorldMakesIt"/> считает Soil природой
/// и разбор на этом кончался — до вопроса про дверь рядом дело не доходило.
///
/// ОТКУДА БЕРЁТСЯ ОТВЕТ — пять источников, и все настоящие, ни одного
/// выдуманного списка кодов (правило 6 проекта):
///   1. СВОЯ ПАМЯТЬ. Блок, который бот поставил сам, помнит
///      <see cref="TempBlocks.Mine"/>. Свой лес — свой, разбирать можно.
///   2. ЗАЯВКИ СЕРВЕРА и приметы чужого — <see cref="Claims"/>. Приваты живых
///      игроков там уже различаются.
///   3. ОТМЕТКИ САМОГО ХОЗЯИНА — дом и склад, которые он поставил в окне
///      управления (<see cref="OwnersPlace"/>). Это его собственные слова о
///      том, где стоит его постройка, и сильнее них нет ничего.
///   4. РЕЕСТР СЕРВЕРА: есть ли у блока РЕЦЕПТ СЕТКИ (то есть игра сама
///      говорит «это делают руками»), материал блока (<c>EnumBlockMaterial</c>)
///      и вкладка творческого инвентаря.
///   5. МИР: блок-сущности рядом. Сундук, дверь, табличка, кровать, печь — всё
///      это блоки С СУЩНОСТЬЮ, и в породе их не бывает. Их наличие рядом и
///      есть ответ мира «здесь кто-то строил».
///
/// ЧЕГО ЧЕСТНОГО В ИГРЕ НЕТ, И ОБ ЭТОМ СКАЗАНО ВСЛУХ. Признака «этот блок
/// поставил игрок» у блока НЕТ вовсе: разведка этой волны перебрала поля
/// <c>Block</c>/<c>CollectibleObject</c> из VintagestoryAPI.xml, теги 1.22
/// (<c>preloaded-tags.json</c> — там только weapon, flux и open-fire),
/// сопротивление и выпадение. Ни одно из них рукотворность не различает.
/// А ВКЛАДКА «construction», на которую напрашивался ответ, НЕ ГОДИТСЯ, и это
/// проверено по ассетам, а не на глаз: её несут и <c>stone/rock.json</c>, и
/// <c>wood/woodtyped/log.json</c> — то есть вся порода мира и живое бревно.
/// Поэтому спрашиваем то, что и правда отвечает: РЕЦЕПТ. Из 595 выходов
/// рецептов сетки 1.22.7 «rammed-*», «cob-none», «drystone-*» есть, а
/// «rock-*», «soil-medium-*», «snowlayer-*» и «log-*» — нет ни одного.
///
/// НЕ ПОНЯЛ — НЕ ЛОМАЙ. Это прямое требование заказчика, и оно же —
/// правило 4 проекта: молчаливое «сломал на всякий случай» непоправимо,
/// а честный отказ поправим одной ручкой.
///
/// Правило чистое: ни мира, ни сервера, ни времени внутри — только числа и
/// строки на входе. Поэтому оно проверяется стендом (правило 7 проекта).
/// Факты для него собирает <see cref="BreakGuard"/>, и другой двери к молотку
/// в проекте нет: <see cref="Mining.BreakAsync"/> спрашивает заставу сам.
/// </summary>
public static class BlockOwners
{
    /// <summary>
    /// ТАКОЕ КЛАДЁТ В МИР САМА ИГРА — по материалу из реестра сервера.
    ///
    /// Список не выдуман: это значения <c>EnumBlockMaterial</c> из
    /// VintagestoryAPI.dll 1.22.7, разделённые по одному признаку — встречается
    /// ли такой блок в НЕТРОНУТОМ мире. Порода, земля, песок, гравий, руда,
    /// мантия, вода, лава, лёд, снег, трава, листва и огонь — встречаются.
    /// Дерево, металл, стекло, керамика, ткань, кирпич — нет: чтобы такой блок
    /// оказался в мире, его кто-то поставил.
    ///
    /// ЧЕСТНО О ПЛАТЕ. Дерево тут в «рукотворных», а живое дерево растёт само.
    /// Это НАРОЧНО и стоит недорого: живой ствол попадёт в
    /// <see cref="BlockOwner.Unknown"/>, а «не понял» запрещает ломать только
    /// РАДИ ПРОХОДА (<see cref="BreakWhy.Way"/>). Валить лес по наряду человек
    /// приказал сам, и там разбор кончается разрешением.
    ///
    /// ЭТОТ ОТВЕТ СЛАБЕЕ РЕЦЕПТА. Утрамбованная земля — тоже Soil, и ровно
    /// поэтому она трижды проезжала заставу; см. <see cref="Whose"/>, шаг 3.
    /// </summary>
    public static bool WorldMakesIt(EnumBlockMaterial material) => material is
        EnumBlockMaterial.Air or EnumBlockMaterial.Soil or EnumBlockMaterial.Gravel or
        EnumBlockMaterial.Sand or EnumBlockMaterial.Stone or EnumBlockMaterial.Ore or
        EnumBlockMaterial.Water or EnumBlockMaterial.Lava or EnumBlockMaterial.Ice or
        EnumBlockMaterial.Snow or EnumBlockMaterial.Mantle or EnumBlockMaterial.Plant or
        EnumBlockMaterial.Leaves or EnumBlockMaterial.Fire;

    /// <summary>
    /// Имя вкладки творческого инвентаря, которой игра сама помечает то, из
    /// чего сложен нетронутый мир (assets/game/config/creativetabs.json).
    /// Спрашивается у блока (<c>Block.CreativeInventoryTabs</c>) — сервер
    /// присылает её вместе с реестром (Vintagestory.Common.BlockTypeNet).
    /// </summary>
    public const string TerrainTab = "terrain";

    /// <summary>
    /// ОТМЕЧЕННОЕ ХОЗЯИНОМ МЕСТО — ЧИСТОЕ ПРАВИЛО «это его двор».
    ///
    /// ЗАЧЕМ ОНО ЕСТЬ. Заказчик отметил в окне управления дом (62, 122, 255) и
    /// склад (62, 112, 255) — и обе точки для вопроса «чей блок» были НЕВИДИМЫ:
    /// дом доносился только до укрытия, бури и снабжения (LivingRole.Дом), а
    /// про хозяина блока не знал никто. Он вправе считать, что отметки хватит.
    ///
    /// МЕРКА — КУБ, А НЕ ШАР. Дом — коробка, а точку человек ставит ВНУТРИ неё,
    /// и до угла по диагонали дальше, чем до стены. Куб со стороной 2R накрывает
    /// коробку целиком; шар того же радиуса срезал бы углы, то есть ровно те
    /// стены, за которые он и жалуется. Живое подтверждение: дом на 122, а его
    /// же дверь — на 112, десять блоков разницы по высоте, и обе отметки нужны.
    ///
    /// Возвращает пустую строку, когда место ничьё, и человеческие слова, когда
    /// оно хозяйское: их дословно читает отказ.
    /// </summary>
    /// <param name="marks">Отметки хозяина: имя («дом», «склад») и клетка.</param>
    /// <param name="radius">Ручка роли; 0 и меньше — беречь только по прочим приметам.</param>
    public static string OwnersPlace(IEnumerable<(string Name, int X, int Y, int Z)> marks,
        int x, int y, int z, int radius)
    {
        if (radius <= 0)
            return "";
        foreach (var mark in marks)
        {
            int d = Math.Max(Math.Abs(mark.X - x),
                    Math.Max(Math.Abs(mark.Y - y), Math.Abs(mark.Z - z)));
            if (d <= radius)
                return $"это в {d} бл от {mark.Name}а хозяина " +
                       $"({mark.X}, {mark.Y}, {mark.Z}), а он отметил его сам";
        }
        return "";
    }

    /// <summary>
    /// ЧЕЙ ЭТО БЛОК — чистое правило. Порядок вопросов не случаен и менять его
    /// нельзя: каждый следующий слабее предыдущего.
    /// </summary>
    /// <param name="code">Код блока — нужен только словам отказа.</param>
    /// <param name="minePlaced">Я сам его сюда положил (<see cref="TempBlocks.Mine"/>).</param>
    /// <param name="foreignWhy">
    /// Чем место чужое по заявкам и приметам (пусто — примет чужого нет).
    /// </param>
    /// <param name="material">Материал блока из реестра сервера.</param>
    /// <param name="terrainTab">
    /// Игра сама выставляет этот блок во вкладке «terrain» — то есть считает
    /// его частью нетронутого мира.
    /// </param>
    /// <param name="builtNear">
    /// Сколько рядом блок-сущностей: сундуков, дверей, табличек, кроватей,
    /// печей. Их ставит человек, и в породе их не бывает.
    /// </param>
    /// <param name="madeByHand">
    /// У блока есть РЕЦЕПТ СЕТКИ в реестре сервера — то есть игра сама
    /// говорит, что такое делают руками.
    /// </param>
    public static (BlockOwner Who, string Why) Whose(string code, bool minePlaced,
        string foreignWhy, EnumBlockMaterial material, bool terrainTab, int builtNear,
        bool madeByHand = false)
    {
        string имя = string.IsNullOrEmpty(code) ? "блок" : code;

        // 1. СВОЁ. Сильнее всех: свой лес бот и ставил, и снимает сам, и знать
        // про него больше некому
        if (minePlaced)
            return (BlockOwner.Mine, $"{имя} я сам сюда и положил");

        // 2. ЧУЖОЕ ПО ЗАЯВКЕ. Сервер и приметы сильнее любого материала: на
        // чужом привате не своя и порода
        if (foreignWhy.Length > 0)
            return (BlockOwner.Foreign, $"{имя} стоит на чужом месте ({foreignWhy})");

        // 3. ЭТО ДЕЛАЮТ РУКАМИ, И РЯДОМ ПОСТРОЙКА — ТРЕТИЙ ЖИВОЙ СЛУЧАЙ.
        //
        // Вопрос стоит ВПЕРЕДИ материала и вкладки нарочно: стена дома
        // заказчика (rammed-light-plain) по материалу — Soil, по вкладкам —
        // general и construction, и оба прежних вопроса называли её природой.
        // А рецепт сетки на неё в реестре сервера ЕСТЬ
        // (assets/survival/recipes/grid/rammedearth.json: 9 packeddirt → 6
        // rammed-light-plain), и это ответ самой игры «такое складывают руки».
        //
        // ОДНОГО РЕЦЕПТА МАЛО, И ПОТОМУ ОН НЕ РЕШАЕТ ОДИН. Крафтятся и
        // packeddirt (а он же сам родится на тропах), и soil-high-none (терра
        // прета растёт и без человека). Запрети мы всё крафтимое — карьер и
        // дорога встали бы на ровном месте. Поэтому рецепт только ПОДНОСИТ
        // блок к вопросу мира: «а стоит ли рядом чья-то дверь или сундук».
        // Стена в дверях дома — да; терра прета в чистом поле — нет.
        if (madeByHand && builtNear > 0)
            return (BlockOwner.Foreign,
                $"{имя} делают руками (в реестре сервера есть рецепт сетки на него), " +
                $"а рядом {builtNear} поставленных человеком вещей " +
                "(сундуки, двери, таблички) — это чья-то постройка");

        // 4. ОТВЕТ ИГРЫ. Вкладка «terrain» — это её собственное заявление
        // «из такого сложен мир». Она идёт ВПЕРЕДИ материала: модовый блок с
        // причудливым материалом игра всё равно называет породой сама
        if (terrainTab)
            return (BlockOwner.Nature, $"{имя} игра сама кладёт в мир " +
                                       $"(вкладка «{TerrainTab}» её реестра)");

        // 5. МАТЕРИАЛ ИЗ РЕЕСТРА
        if (WorldMakesIt(material))
            return (BlockOwner.Nature, $"{имя} — это {material} из реестра игры, " +
                                       "такое лежит в мире само");

        // 6. РУКОТВОРНОЕ, А РЯДОМ ПОСТРОЙКА. Сундук или дверь возле бревна — это
        // не совпадение, а дом; ровно так и было в живом случае
        if (builtNear > 0)
            return (BlockOwner.Foreign, $"{имя} — не порода ({material}), а рядом " +
                                        $"{builtNear} поставленных человеком вещей " +
                                        "(сундуки, двери, таблички) — это чья-то постройка");

        // 7. НЕ ПОНЯЛ. Прямое требование человека: тогда не ломать и сказать
        return (BlockOwner.Unknown, $"не понял, чей это {имя}: игра сама такое в мир " +
                                    $"не кладёт (материал {material}), моей метки на нём нет, " +
                                    "а примет чужого рядом не видно");
    }

    /// <summary>
    /// МОЖНО ЛИ ЭТО СЛОМАТЬ — ОДНО ПРАВИЛО НА ВСЕХ, КТО ЗАМАХИВАЕТСЯ, и «нет»
    /// здесь всегда со словами и с ИМЕНЕМ РУЧКИ: отказ, из которого не видно,
    /// чем его снять, человек читает как поломку.
    ///
    /// ПОЧЕМУ ОДНО. Дорог к молотку было шесть, и заставу спрашивали четыре из
    /// них; дорога, карьер, руда, костёр, грядка и укрытие били
    /// <see cref="Mining.BreakAsync"/> напрямую. Теперь застава стоит В САМОМ
    /// <see cref="Mining.BreakAsync"/>, и обойти её нельзя ничем.
    ///
    /// ЗАЯВКА СЕРВЕРА — ЗАПРЕТ БЕЗ ОГОВОРОК, и ручка его не снимает. Ломать в
    /// чужом привате не может и живой игрок: сервер откажет
    /// (ServerSystemBlockSimulation.HandleBlockPlaceOrBreak), а бот, который
    /// пробует, только копит себе приметы чужого на ровном месте. Ручка про
    /// другое — про постройку БЕЗ заявки, вроде дома заказчика.
    ///
    /// ЧЕМ РАЗЛИЧАЮТСЯ «РАДИ ПРОХОДА» И «ПО ДЕЛУ» — словами самого заказчика:
    /// «зачем ломать, если был путь, ЛОМАТЬ КРАЙНЯЯ МЕРА же». Крайняя мера —
    /// это <see cref="BreakWhy.Way"/>: столб, ступени, потолок, расчистка. Ей
    /// во дворе хозяина не разрешено ничего, кроме своих же лесов и того, что
    /// игра сама зовёт заменяемым мусором. А работу человек назвал сам —
    /// «прокопай тут дорогу», — и породу по наряду бот копает и во дворе.
    /// </summary>
    /// <param name="who">Чей блок (<see cref="Whose"/>).</param>
    /// <param name="why">Почему так решено — уходит в отказ дословно.</param>
    /// <param name="purpose">Зачем замахнулись.</param>
    /// <param name="mayBreakForeign">Ручка роли «ЛоматьЧужоеРадиВыхода».</param>
    /// <param name="claimed">Место закрыто ЗАЯВКОЙ сервера, а не приметой.</param>
    /// <param name="ownersPlace">
    /// Слова <see cref="OwnersPlace"/>: пусто — место ничьё, иначе это двор
    /// хозяина, и он отметил его сам.
    /// </param>
    /// <param name="litter">
    /// Игра сама зовёт этот блок заменяемым (снег, трава): любой поставленный
    /// блок его затирает, и живой игрок сметает такое не глядя.
    /// </param>
    public static (bool May, string Why) MayBreak(BlockOwner who, string why,
        BreakWhy purpose, bool mayBreakForeign, bool claimed = false,
        string ownersPlace = "", bool litter = false)
    {
        const string knob = nameof(LivingRole.ЛоматьЧужоеРадиВыхода);
        string keep = BreakGuard.РучкаБерегуДомИСклад;
        string двор = ownersPlace.Length > 0 ? $"; {ownersPlace}" : "";

        // 1. СВОЙ ЛЕС — СВОЙ ВЕЗДЕ, и во дворе хозяина тоже. Иначе бот не смог
        // бы снять собственную подпорку, поставленную у его крыльца, и выход
        // ступенями сломался бы целиком
        if (who == BlockOwner.Mine)
            return (true, why);

        // 2. ЗАЯВКА СЕРВЕРА. Сильнее и ручки, и мусора: в чужом привате не
        // рвут и травинку
        if (who == BlockOwner.Foreign && claimed)
            return (false, $"{why} — заявку сервера не обходит и живой игрок, " +
                           $"её не снимает и настройка «{knob}»");

        // 3. ЧУЖАЯ ПОСТРОЙКА
        if (who == BlockOwner.Foreign)
            return mayBreakForeign
                ? (true, $"{why}{двор}, но настройка «{knob}» это разрешает")
                : (false, $"{why}{двор} — чужую постройку не ломаю " +
                          $"(разрешает настройка «{knob}», сейчас она выключена)");

        // 4. МУСОР ПО РЕЕСТРУ. Снег и трава у крыльца — не постройка, и живой
        // игрок сметает их не думая: игра сама затирает такое любым блоком.
        // Ниже заявки нарочно — на чужом привате не дадут и этого
        if (litter)
            return (true, why);

        // 5. ДВОР ХОЗЯИНА. Он отметил дом и склад в окне, и этого довольно.
        // Ради прохода тут не ломаем НИЧЕГО; по наряду — только то, что игра
        // сама кладёт в мир, а «не понял» так и останется нетронутым
        if (ownersPlace.Length > 0 && (purpose == BreakWhy.Way || who != BlockOwner.Nature))
            return (false, purpose == BreakWhy.Way
                ? $"{ownersPlace} — ради прохода я во дворе хозяина не ломаю ничего, " +
                  $"кроме своих же лесов (радиус задаёт настройка «{keep}»)"
                : $"{why}; {ownersPlace} — во дворе хозяина копаю только то, что " +
                  $"игра сама кладёт в мир (радиус задаёт настройка «{keep}»)");

        // 6. МИР
        if (who == BlockOwner.Nature)
            return (true, why);

        // 7. НЕ ПОНЯЛ. Ради прохода — не трогаем и говорим; по наряду человек
        // сам назвал место и работу (валить лес, разбирать завал), и отказ тут
        // означал бы «наряд не выполнен» на ровном месте
        if (purpose == BreakWhy.Work)
            return (true, $"{why}; ломаю только потому, что это работа, которую " +
                          "назначил человек, — ради прохода я бы не стал");

        return mayBreakForeign
            ? (true, $"{why}; ломаю только потому, что настройка «{knob}» включена")
            : (false, $"{why} — пока не понял, ломать не стану " +
                      $"(разрешает настройка «{knob}», сейчас она выключена)");
    }
