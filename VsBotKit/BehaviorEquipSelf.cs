namespace VsBotKit;

/// <summary>
/// СНАРЯДИТЬСЯ, ПОКА ДЕЛАТЬ НЕЧЕГО — недостающий патрон в револьвере.
///
/// ЖИВОЙ СЛУЧАЙ, ЖУРНАЛ ЗАКАЗЧИКА 23.08. Бот поднялся с пустыми сумками и
/// вслух перечислил, чего у него нет:
///     [безделье] начатое доделаю не я: недобранное снаряжение: ladder: 0/64,
///     Pickaxe: 0/1, Shovel: 0/1, Axe: 0/1, Knife: 0/1 — цепочка «добыть →
///     вытесать → собрать» не доведена до конца; ... а ходить за материалом —
///     наряд: в простое я за этим не хожу; НЕ ЗАНИМАЮ ТЕЛО И ЖДУ
/// И стал ждать. Без кирки он не копает, не столбится и не выбирается из ямы;
/// без ножа не разделывает; драться ему было нечем — «лучшее в хотбаре
/// flaxfibers». За девять минут он умер дважды. Слова заказчика: «револьвер
/// опять не так работает, бот же умрет».
///
/// ЧЕГО НЕ ХВАТАЛО НА САМОМ ДЕЛЕ — НЕ МЕХАНИЗМА, А ПОВОДА. Добор запасов в
/// проекте есть и работает (<see cref="Stock.ReplenishAsync"/>: сумки → склад
/// работы → дом → крафт → добыть рядом), но зовут его ТОЛЬКО ПЕРЕД НАРЯДОМ —
/// из <c>SurvivorRole</c> и <c>MiningOrder</c>. Между нарядами о нём не
/// вспоминает никто, и простой лишь СООБЩАЛ о нехватке, честно добавляя, что
/// сам за ней не пойдёт. Заказчик читал это как «бот стоит и умирает».
///
/// ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ «ДОДЕЛАТЬ НАЧАТОЕ». Соседняя способность
/// (<see cref="BehaviorFinishStarted"/>) НАРОЧНО никуда не ходит: она берёт
/// только то, что собирается на месте, чтобы не уводить бота через полкарты за
/// палкой. Эта — ходит, и в этом весь её смысл: кирка лежит в сундуке склада,
/// и «не пойду» означает «останусь без кирки навсегда». Поэтому у неё свой
/// выключатель, а не общий с доделкой: человек вправе разрешить одно и
/// запретить другое.
///
/// ЧЕГО ОНА НЕ ДЕЛАЕТ. Она не заводит второй цепочки «где взять» и не решает,
/// что боту носить: список требований — это запасы роли (те самые «Pickaxe: 1,
/// ladder: 64»), а «где взять» — снабжение. Здесь только ПОВОД спросить.
/// Ходить ли за материалом в мир и собирать ли по рецепту — по-прежнему решают
/// ручки «ДобыватьНедостающее» и «КрафтитьНедостающее»: их эта способность
/// не обходит, а наследует, потому что зовёт тот же самый добор.
///
/// ВЕС — ХОЗЯЙСТВЕННЫЙ, И ЭТО НЕ НЕДОСМОТР. Тело берётся как
/// <see cref="BodyArbiter.Importance.Routine"/>: голод, рана и бой перебивают
/// сборы без разговоров. Живой игрок, услышав дрифтера за спиной, тоже бросает
/// поход за киркой.
///
/// Класс — механизм. Ходить ли за снаряжением в простое и как часто
/// спрашивать, решает роль (ручка «СнаряжатьсяВПростое»).
/// </summary>
public class BehaviorEquipSelf : BotBehavior
{
    private readonly BotContext ctx;

    public BehaviorEquipSelf(BotContext ctx) => this.ctx = ctx;

    /// <summary>
    /// Способность выключена по умолчанию — включает роль. Стражнику на посту
    /// уходить за киркой незачем, а копателю без кирки не работать вовсе.
    /// </summary>
    public bool Enabled { get; set; }

    /// <summary>
    /// Пауза между заходами, секунд.
    ///
    /// ЧИСЛО ИЗ ЦЕНЫ ВОПРОСА, А НЕ ИЗ ВКУСА. Заход — это поход на склад и
    /// обратно, то есть десятки секунд ходьбы. Спрашивать чаще, чем он длится,
    /// значит гонять бота между сундуком и работой — ровно то «метание», на
    /// которое заказчик уже жаловался («метался между домом и строительством»).
    /// Две минуты — это и не заметно человеку, и заведомо длиннее похода.
    /// </summary>
    public double CooldownSeconds { get; set; } = 120;

    /// <summary>Снарядился: отчёт запасов целиком, по факту от механизма.</summary>
    public event Action<string>? OnEquipped;

    /// <summary>Не вышло — с причиной. Молчаливого отказа здесь нет.</summary>
    public event Action<string>? OnRefused;

    /// <summary>
    /// ЖАЛОБА ГРОМКО ОДИН РАЗ, А НЕ КАЖДЫЕ ДВЕ МИНУТЫ ВСЮ НОЧЬ.
    ///
    /// Причина «кирки нет ни в сумках, ни на складе, а руды рядом не видно» не
    /// проходит сама: она держится, пока человек не принесёт кирку. Без
    /// сторожа это семьсот одинаковых строк в сутки — тот самый шум, от
    /// которого в этом проекте уже лечили голод, разломы и бурю. Молчать тоже
    /// нельзя: бот, которому нечем работать, и молчащий об этом, выглядит
    /// здоровым.
    /// </summary>
    private readonly Alarm нечемСнарядиться = new("снарядиться не выходит");

    private DateTime lastRun = DateTime.MinValue;

    public override async Task<bool> TickAsync(CancellationToken ct)
    {
        if (!Enabled)
            return false;
        // Вне мира и мёртвым сервер отказывает во всём — и в сундуке, и в крафте
        if (!ctx.Bot.Joined || ctx.Self.IsDead)
            return false;
        if ((DateTime.UtcNow - lastRun).TotalSeconds < CooldownSeconds)
            return false;
        if (ctx.Stock is not { } запасы)
            return false;

        // ВОПРОС ЗАДАЁМ ДО ЗАХВАТА ТЕЛА. Он не трогает ни сеть, ни мир — только
        // сумку и реестр, — а тело, взятое ради «оказалось, всё на месте», на
        // этот тик выключило бы всё, что стоит ниже
        var нехватка = запасы.Missing();
        int былоНеХватало = Shortfall(нехватка);
        if (нехватка.Count == 0)
        {
            lastRun = DateTime.UtcNow;
            // Обстановка переменилась — следующий отказ прозвучит сразу
            нечемСнарядиться.Clear();
            return false;
        }

        using var hold = ctx.Turn.TryTake("снарядиться", BodyArbiter.Importance.Routine, ct);
        if (hold == null)
            return false;   // тело занято — распорядитель уже сказал, кем

        StockReport отчёт;
        try
        {
            отчёт = await запасы.ReplenishAsync(hold.Token);
        }
        finally
        {
            // Отсчёт паузы — от КОНЦА захода: иначе долгий поход на склад съел
            // бы паузу целиком и способность бралась за дело подряд
            lastRun = DateTime.UtcNow;
        }

        // УСПЕХ — ТОЛЬКО ПО ФАКТУ ПРИБЫЛИ В СУМКЕ, а не по тому, что мы
        // сходили, и не по числам отчёта: «сделано» и «добыто» он считает по
        // своим шагам, а нам важно ровно одно — стало ли у бота больше того,
        // чего не хватало. «Сходил на склад и вернулся ни с чем» — это отказ,
        // и звучать он обязан отказом
        if (Shortfall(запасы.Missing()) < былоНеХватало)
        {
            нечемСнарядиться.Clear();
            OnEquipped?.Invoke(отчёт.Message);
            return true;
        }

        if (нечемСнарядиться.Raise(отчёт.Message))
            OnRefused?.Invoke(отчёт.Message);
        return false;
    }

    /// <summary>
    /// НАСКОЛЬКО ВСЕГО НЕ ХВАТАЕТ — суммой штук, а не числом строк.
    ///
    /// Строками мерить нельзя: принеси бот 60 лестниц из 64, строка «ladder
    /// 4/64» останется на месте, и заход, который и правда сходил на склад,
    /// прозвучал бы отказом.
    /// </summary>
    private static int Shortfall(IReadOnlyList<StockNeed> need)
    {
        int sum = 0;
        foreach (var n in need)
            sum += n.Missing;
        return sum;
    }
}
