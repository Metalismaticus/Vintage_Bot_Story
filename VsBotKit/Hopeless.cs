namespace VsBotKit;

/// <summary>
/// БЕЗНАДЁГА: РАЗ НЕ ВЫШЛО — НЕ ДОЛБИТЬ ЭТО КАЖДЫЙ РАЗ.
///
/// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЗАВЕДЕНО (журнал 16.08, 12:45-12:57). Перед
/// КАЖДЫМ заходом наряда бот заново гонял всю цепочку снабжения за топором и
/// ножом — и каждый раз получал один и тот же ответ:
///
///     [запасы] не хватает Axe ×1
///     [склад] Axe со склада не беру: Axe на складе нет: опись свежая…
///     [запасы] чтобы получить Axe, надо: добыть stone-chert ×2; вытесать…
///     [поручение] stone-chert рядом больше не нахожу
///     [снабжение] не хватает Axe (надо 1, есть 0); искал так: сумки… → крафт… → добыть рядом…
///
/// Десять строк, четыре раза за две минуты, и ни одной новости: stone-chert в
/// округе нет и не появится. Заказчик читает такой журнал как сломанного бота —
/// настоящая беда тонет между повторами. И дело не только в словах: цепочка
/// каждый раз ХОДИТ — осматривает округу, спрашивает опись, лезет в реестр
/// рецептов, — то есть тратит те самые секунды, которых наряду не хватило.
///
/// ПРАВИЛО ЗДЕСЬ НЕ НОВОЕ, ЕГО ПРОСТО НЕ БЫЛО ГДЕ ВЗЯТЬ. Ровно это уже написано
/// у отметки дома (<c>BehaviorKeepHomeSpawn</c>) отдельным флажком
/// <c>gearHopeless</c> — по прямой просьбе заказчика: «если не нашёл в игровой
/// сессии дома шестеренку, то больше не бегает по кд домой на склад». Флажок
/// был один, на один случай, и повторить его для запасов значило бы завести
/// вторую копию того же правила. Теперь правило одно и живёт здесь, а тот
/// флажок — первый его потребитель.
///
/// ЧЕМ ЭТО НЕ <see cref="LogRepeats"/>. Тот глушит ПОВТОРЯЮЩУЮСЯ СТРОКУ и ничего
/// не знает о работе: с ним бот молчал бы, но по-прежнему обходил бы округу за
/// кремнем перед каждым заходом. Здесь глушится сама ПОПЫТКА.
///
/// ЧЕМ ЭТО НЕ МОЛЧАНИЕ. Отказ говорится вслух — один раз на причину, и
/// повторяется <see cref="RemindAfter"/>, чтобы про долгую беду не забыли
/// совсем. За «сказать один раз» отвечает <see cref="Alarm"/> — тот же самый,
/// которым это уже сделано у планировщика и у датчика состояния; второй такой
/// счётчик здесь нарочно не заводится.
///
/// КОГДА ПРОБОВАТЬ СНОВА — три честных случая, и ни одного выдуманного:
///   • ПРИЧИНА СМЕНИЛАСЬ («не дошёл до склада» вместо «на складе нет») — это
///     новость, и <see cref="Alarm"/> скажет её сразу;
///   • обстановка изменилась и об этом СКАЗАЛ вызывающий
///     (<see cref="TryAgain"/>): нехватка закрылась, сундук пополнили;
///   • прошло <see cref="TryAgainAfter"/> — мир меняется не по нашим часам,
///     хозяин мог положить топор в сундук. null — не пробовать до конца захода
///     (ровно то, о чём просил заказчик про шестерёнку).
///
/// Времени сам не спрашивает: «сейчас» приходит доводом, поэтому правило
/// проверяется стендом целиком (правило 7 проекта).
///
/// ПОЧЕМУ КЛЮЧ ЛЮБОЙ, А НЕ ТОЛЬКО СТРОКА. Приёмка нашла в дереве ТРИ копии
/// этого правила: здесь (ключ — код вещи), у подбора с земли
/// (<c>Pickup.gaveUp</c>, ключ — номер сущности) и у добычи с убитых
/// (<c>BehaviorLootKills.failed</c>, тоже номер). Последняя прямо в пояснении
/// признавалась копией второй: «та же мерка, что у подбора». Свести их мешал
/// один-единственный <c>string</c> в ключе — поэтому ключ теперь любой, а
/// строковый случай остался отдельным именем <see cref="Hopeless"/> ради тех,
/// кто уже им пользуется.
/// </summary>
/// <typeparam name="TKey">
/// Про ЧТО сдались: код вещи, имя работы, номер сущности на земле.
/// </typeparam>
public class Hopeless<TKey> where TKey : notnull
{
    private readonly object gate = new();

    /// <summary>
    /// Про что сдались: причина вслух (её ведёт <see cref="Alarm"/>) и когда
    /// сдались (по этому и решается, не пора ли попробовать снова).
    /// </summary>
    private readonly Dictionary<TKey, (Alarm Say, DateTime At)> given;

    /// <param name="about">
    /// Общая приставка к слову вслух («за временной шестерёнкой»). Пусто —
    /// строка выйдет как «{что}: {почему}», то есть ровно так, как её печатал
    /// вызывающий до этого механизма.
    /// </param>
    /// <param name="same">
    /// Чем ключи считаются одинаковыми (строкам нужен разбор без учёта
    /// регистра, номерам сущностей — ничего).
    /// </param>
    public Hopeless(string about = "", IEqualityComparer<TKey>? same = null)
    {
        About = about;
        given = new Dictionary<TKey, (Alarm, DateTime)>(same);
    }

    /// <summary>Про что этот счёт безнадёг — попадает в строку вслух.</summary>
    public string About { get; }

    /// <summary>
    /// Через сколько попробовать снова. null — до конца захода не пробовать
    /// вовсе: так просил заказчик про временную шестерёнку («больше не бегает
    /// по кд домой на склад»).
    ///
    /// Десять минут — не вкус, а цена вопроса: заход наряда длится минуты, и
    /// за это время бот успевает четыре раза сходить по одной и той же пустой
    /// цепочке. Реже пробовать значит не заметить положенный в сундук топор;
    /// чаще — вернуть тот самый шум.
    /// </summary>
    public TimeSpan? TryAgainAfter { get; set; } = TimeSpan.FromMinutes(10);

    /// <summary>
    /// Как часто напоминать вслух, пока безнадёга держится. Полностью замолчать
    /// нельзя: бот, который час назад сказал «топора нет» и с тех пор молчит,
    /// выглядит здоровым.
    /// </summary>
    public TimeSpan RemindAfter { get; set; } = TimeSpan.FromMinutes(5);

    /// <summary>
    /// СКОЛЬКО БЕЗНАДЁГ ДЕРЖАТЬ В ПАМЯТИ, прежде чем выметать отлежавшие.
    ///
    /// Это предел механизма, а не ручка роли. Он понадобился, как только ключом
    /// стал номер сущности: кодов вещей у бота десятки, а кусков руды и туш за
    /// смену — тысячи, и без выметания счёт рос бы до конца работы программы.
    /// Обе сведённые сюда копии несли такой предел своим кодом (128 у подбора,
    /// 64 у добычи с убитых) — теперь он один.
    ///
    /// ВЫМЕТАЕТСЯ ТОЛЬКО ОТЛЕЖАВШЕЕ СВОЙ СРОК. Запись, которой ещё рано на
    /// вторую попытку, не выбрасывается никогда, даже за пределом: выбросить её
    /// значило бы тихо нарушить собственное обещание «за этим больше не хожу».
    /// Поэтому при <see cref="TryAgainAfter"/> = null (не пробовать до конца
    /// захода) счёт растёт и за предел — и это правильно.
    /// </summary>
    public int Remember { get; set; } = 128;

    /// <summary>Сказать вслух: отказ, напоминание или отбой.</summary>
    public event Action<string>? OnSay;

    /// <summary>О чём сейчас сдались (пусто — ни о чём).</summary>
    public IReadOnlyCollection<TKey> All
    {
        get { lock (gate) return [.. given.Keys]; }
    }

    /// <summary>Скольким делам сейчас отказано (для стендов и счётчиков).</summary>
    public int Count
    {
        get { lock (gate) return given.Count; }
    }

    /// <summary>
    /// СДАЛИСЬ. Возвращает true, если про это СКАЗАЛИ вслух (первый раз,
    /// причина сменилась или пришёл срок напомнить).
    /// </summary>
    /// <param name="what">За чем ходили: код вещи, имя работы, номер вещи на земле.</param>
    /// <param name="why">Почему не вышло — словами того, кто пробовал.</param>
    public bool GiveUp(TKey what, string why, DateTime? now = null)
    {
        var at = now ?? DateTime.UtcNow;
        Alarm say;
        lock (gate)
        {
            if (!given.TryGetValue(what, out var had))
            {
                say = new Alarm(About.Length > 0 ? $"{About}: {what}" : $"{what}")
                {
                    RepeatAfter = RemindAfter
                };
                say.OnRaise += Said;
                say.OnClear += Said;
            }
            else
            {
                say = had.Say;
                say.RepeatAfter = RemindAfter;
            }
            // Срок отсчитывается ОТ ПОСЛЕДНЕЙ ПОПЫТКИ, а не от первой: иначе
            // после ожидания бот пробовал бы снова каждый заход подряд —
            // ровно тот шум, ради которого всё и написано
            given[what] = (say, at);
            SweepLocked(at);
        }
        return say.Raise(why, at);
    }

    /// <summary>
    /// Вымести отлежавшие своё записи, когда их стало больше
    /// <see cref="Remember"/>. Зовётся под замком из <see cref="GiveUp"/> —
    /// то есть ровно тогда, когда счёт и растёт.
    ///
    /// МОЛЧА И БЕЗ ОТБОЯ: отлежавшая запись и так больше никого не держит
    /// (<see cref="Given"/> ответил бы про неё «пробуй снова»), а рассказывать
    /// про сотню забытых кусков руды — тот же шум, ради ухода от которого
    /// механизм и написан.
    /// </summary>
    private void SweepLocked(DateTime at)
    {
        if (given.Count <= Remember || TryAgainAfter is not { } wait)
            return;
        foreach (var key in given.Where(p => at - p.Value.At >= wait)
                                 .Select(p => p.Key).ToList())
            given.Remove(key);
    }

    /// <summary>
    /// НЕ ПРОБОВАТЬ ЛИ ЭТО СЕЙЧАС. true — уже сдались, и с тех пор ничего не
    /// изменилось; пробовать снова значит повторить ту же пустую работу.
    ///
    /// Отлежавшая своё запись СТИРАЕТСЯ прямо здесь: «пора попробовать снова»
    /// и «мы про это забыли» — одно и то же, и держать вторую мерку было бы
    /// лишним поводом им разойтись.
    /// </summary>
    public bool Given(TKey what, DateTime? now = null)
    {
        var at = now ?? DateTime.UtcNow;
        Alarm say;
        TimeSpan waited;
        lock (gate)
        {
            if (!given.TryGetValue(what, out var had))
                return false;
            if (TryAgainAfter is not { } wait)
                return true;                       // до конца захода не пробуем
            if (at - had.At < wait)
                return true;
            given.Remove(what);
            say = had.Say;
            waited = wait;
        }
        // ОТБОЙ ВСЛУХ. Человек читает «пробую снова» и не гадает, почему бот
        // вдруг опять пошёл за тем же самым — и почему следом снова тот же
        // отказ. Молчаливое возвращение к безнадёжному делу выглядит как
        // забывчивость, а не как выдержанный срок
        // МЕРКА ПО СРОКУ, А НЕ ПО ВКУСУ. Пока безнадёгу мерили минутами
        // (снабжение, подбор), «прошло 10 мин» читалось само. Движению срок
        // отпущен секундами, и та же строка выходила «прошло 0,3 мин» — число,
        // по которому человек не поймёт ровно ничего. Считаем тем, что видно
        say.Clear(waited.TotalMinutes >= 1
            ? $"прошло {waited.TotalMinutes:0.#} мин — пробую снова"
            : $"прошло {waited.TotalSeconds:0.#} с — пробую снова");
        return false;
    }

    /// <summary>Почему сдались (пусто — не сдавались).</summary>
    public string Why(TKey what)
    {
        lock (gate)
            return given.TryGetValue(what, out var had) ? had.Say.Reason : "";
    }

    /// <summary>
    /// ОБСТАНОВКА ИЗМЕНИЛАСЬ — пробуем снова. Зовёт тот, кто это УЗНАЛ:
    /// нехватка закрылась, сундук пополнили, бот ушёл в другое место.
    /// Возвращает true, если и правда сдавались (тогда об отбое стоит сказать).
    /// </summary>
    public bool TryAgain(TKey what, string? why = null)
    {
        Alarm? say;
        lock (gate)
        {
            if (!given.Remove(what, out var had))
                return false;
            say = had.Say;
        }
        return say.Clear(why);
    }

    /// <summary>
    /// ЗАБЫТЬ ВСЁ: новое соединение, другой мир, другой набор предметов.
    /// Возвращает, скольким делам вернули надежду.
    ///
    /// Молча, и это нарочно: рассказывать про десяток отбоев на входе в мир —
    /// тот же шум, только в другом месте.
    /// </summary>
    public int Forget()
    {
        lock (gate)
        {
            int was = given.Count;
            given.Clear();
            return was;
        }
    }

    private void Said(string line) => OnSay?.Invoke(line);
}

/// <summary>
/// БЕЗНАДЁГА, ПРО КОТОРУЮ ГОВОРЯТ СЛОВОМ: код вещи («gear-temporal»), имя
/// работы. Это <see cref="Hopeless{TKey}"/> со строковым ключом и разбором без
/// учёта регистра — сервер пишет коды как ему удобно, а «Axe» и «axe» это одна
/// и та же нехватка.
///
/// Отдельным именем, а не просто <c>Hopeless&lt;string&gt;</c>, нарочно: так у
/// давних потребителей (запасы, отметка дома) в коде не меняется ни строчки, и
/// сведение трёх копий в один механизм ничем им не грозит.
/// </summary>
public sealed class Hopeless : Hopeless<string>
{
    public Hopeless(string about = "") : base(about, StringComparer.OrdinalIgnoreCase) { }
}
