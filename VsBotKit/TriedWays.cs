namespace VsBotKit;

/// <summary>
/// ПРИЁМ, КОТОРЫЙ ОТСЮДА НЕ СДВИНУЛ ДЕЛО, ВЫЧЁРКИВАЕТСЯ — И БОТ СЧИТАЕТ ЗАНОВО.
///
/// ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ МЕХАНИЗМОМ. Правило это в проекте уже жило, но жило
/// ВНУТРИ одного цикла — выхода наверх (<see cref="Scaffolding.GetOutAsync"/>),
/// строками «этот приём отсюда не поднял ни на блок — вычёркиваю его и считаю
/// заново». А беда, от которой оно бережёт, к подъёму отношения не имеет вовсе.
///
/// ЖИВОЙ СЛУЧАЙ, ради которого правило вынесено сюда (журнал 16.08, 14:35:41 и
/// до конца файла). Бот пересиживал временную бурю в коробке, которой обложился
/// сам. Буря кончилась, он взялся разбирать стенку — и не смог. Разбор
/// возвращал «не вышло», буря по-прежнему считалась пережитой, а способность
/// звала разбор СНОВА на следующем же тике. Строка «[укрытие] стенка не
/// поддалась» шла ДВА С ПОЛОВИНОЙ РАЗА В СЕКУНДУ, минутами, пережила даже
/// переподключение к серверу и не кончилась до конца журнала: пять тысяч триста
/// пятьдесят девять раз подряд. Ни разу за это время бот не спросил себя, помог
/// ли ему хоть один удар.
///
/// ПРАВИЛО ЖЕ ОБЩЕЕ, а не про лестницы: любой перебор приёмов обязан считать,
/// сколько кругов прошло ВПУСТУЮ, и приём, который не сдвинул дело НИ НА ЕДИНИЦУ,
/// из перебора убирать. Тогда цикл кончается сам — приёмов конечное число.
///
/// МЕРЯЕТ СДВИГ ВЫЗЫВАЮЩИЙ, И ТОЛЬКО ПО ФАКТУ. Подъём меряет свою высоту, выход
/// из укрытия — открылся ли ход наружу. Здесь только счёт и слова: соблазн
/// «пусть механизм сам спросит, получилось ли» кончился бы тем, что мерка уехала
/// бы от дела, к которому относится.
/// </summary>
/// <typeparam name="TWay">Чем перебираем: приём подъёма, путь наружу, что угодно.</typeparam>
public sealed class TriedWays<TWay> where TWay : notnull
{
    private readonly HashSet<TWay> lost = [];
    private readonly Dictionary<TWay, int> gained = [];

    /// <param name="allowance">
    /// Сколько ПУСТЫХ кругов терпим. Больше, чем приёмов (плюс разовые попытки
    /// вроде «докопать материал»), взяться неоткуда: каждый пустой круг либо
    /// вычёркивает приём навсегда, либо тратит такую разовую попытку.
    /// </param>
    /// <param name="empty">
    /// Чем кончился пустой круг, СЛОВАМИ ДЕЛА: «не поднял ни на блок»,
    /// «стену не сдвинул ни на блок». Механизм не знает, в чём мерят сдвиг, а
    /// человек, читающий журнал, должен видеть именно свою мерку.
    /// </param>
    public TriedWays(int allowance, string empty)
    {
        Allowance = Math.Max(0, allowance);
        Empty = empty;
    }

    /// <summary>Сколько пустых кругов терпим.</summary>
    public int Allowance { get; }

    /// <summary>Чем кончился пустой круг — словами дела.</summary>
    public string Empty { get; }

    /// <summary>Сколько кругов прошло впустую.</summary>
    public int Fruitless { get; private set; }

    /// <summary>Приёмы, которые ОТСЮДА уже не сдвинули дело.</summary>
    public IReadOnlySet<TWay> Lost => lost;

    /// <summary>Насколько сдвинулось дело всеми приёмами вместе.</summary>
    public int Moved { get; private set; }

    /// <summary>Стоит ли делать ещё круг.</summary>
    public bool MayTry => Fruitless <= Allowance;

    /// <summary>Вычеркнут ли этот приём.</summary>
    public bool Crossed(TWay way) => lost.Contains(way);

    /// <summary>Насколько сдвинул дело именно этот приём.</summary>
    public int GainedBy(TWay way) => gained.GetValueOrDefault(way);

    /// <summary>
    /// КРУГ ПРОШЁЛ ВПУСТУЮ, А ПРИЁМ НИ ПРИ ЧЁМ. Так считается разовая попытка
    /// поправить обстоятельства — например, докопать блоков на столб: приём она
    /// не тратит, но и повторять её бесконечно нельзя.
    /// </summary>
    public void SpentRound() => Fruitless++;

    /// <summary>
    /// ВЫЧЕРКНУТЬ ПРИЁМ, НЕ СЧИТАЯ КРУГА. Один круг иногда доказывает негодность
    /// СРАЗУ ДВУХ записей, и вторая не должна врать про число пустых кругов.
    ///
    /// ЖИВОЙ СЛУЧАЙ (журнал 16.08, 20:36:36–20:36:38). Лесенка вычёркивает
    /// сторону вместе с КЛЕТКОЙ, из которой рубила (иначе качание тела между
    /// двумя соседними клетками стирало бы весь список). Но ступень «в сторону
    /// (1, 0)» увела бота на клетку вбок, не подняв ни на блок, — и в новой
    /// клетке запись оказалась новой. Одна и та же сторона выбиралась ДЕВЯТЬ
    /// раз подряд, бот уехал девять блоков вбок и не поднялся ни на один. Тут
    /// один круг доказал две вещи: «из этой клетки в эту сторону» не вышло И
    /// «эта сторона ведёт по ровному, откуда бы я в неё ни шагнул». Второе
    /// вычёркивается ЭТИМ способом — пустой круг всё равно был один.
    /// </summary>
    public void CrossOut(TWay way) => lost.Add(way);

    /// <summary>
    /// ЧТО ВЫШЛО У ПРИЁМА — по факту, замеренному вызывающим.
    ///
    /// Ноль и минус означают «не сдвинул»: приём вычёркивается навсегда, круг
    /// числится пустым. Возвращает, сдвинулось ли дело, — чтобы вызывающий не
    /// повторял то же сравнение с нулём второй раз и не разошёлся с нами в
    /// мерке.
    /// </summary>
    public bool Note(TWay way, int moved)
    {
        if (moved <= 0)
        {
            CrossOut(way);
            Fruitless++;
            return false;
        }
        gained[way] = gained.GetValueOrDefault(way) + moved;
        Moved += moved;
        return true;
    }

    /// <summary>
    /// Слова о вычеркнутом приёме — те самые, что уже знает журнал заказчика:
    /// «этот приём отсюда не поднял ни на блок — вычёркиваю его и считаю заново».
    /// </summary>
    public string SayCrossedOut() =>
        $"этот приём отсюда {Empty} — вычёркиваю его и считаю заново";

    /// <summary>
    /// ЧЕЙ ВКЛАД БОЛЬШЕ — тот приём и называем. Приёмов в одном деле выходит и
    /// два (лестница кончилась на половине, остаток добрали ступенями), и
    /// сказать «вышел лестницей» про такое значит соврать о том, что произошло.
    /// </summary>
    /// <param name="none">Чем ответить, если не сдвинул никто.</param>
    public TWay Dominant(TWay none)
    {
        var best = none;
        int most = 0;
        foreach (var (way, moved) in gained)
            if (moved > most)
            {
                most = moved;
                best = way;
            }
        return best;
    }

    /// <summary>
    /// Вычеркнутые приёмы человеческими словами, через запятую (пусто — ни одного).
    /// </summary>
    public string CrossedOut(Func<TWay, string> name) =>
        lost.Count == 0 ? "" : string.Join(", ", lost.Select(name));
}
