namespace VsBotKit;

/// <summary>Почему проходка остановилась.</summary>
public enum TunnelStop
{
    /// <summary>Дошли: цель достигнута или в руке.</summary>
    Done,
    /// <summary>Отменили снаружи.</summary>
    Cancelled,
    /// <summary>Кончилось отведённое время.</summary>
    Timeout,
    /// <summary>Реестр блоков сервера ещё не пришёл — копать вслепую нельзя.</summary>
    NotReady,
    /// <summary>Нечем взять породу: нет кирки нужного тира.</summary>
    NoTool,
    /// <summary>Кирка вот-вот сломается, запасной нет.</summary>
    ToolWorn,
    /// <summary>Некуда складывать добычу.</summary>
    InventoryFull,
    /// <summary>Впереди лава или кипяток.</summary>
    Lava,
    /// <summary>Вода не унялась: заложить нечем, не велено или течёт дальше.</summary>
    Water,
    /// <summary>Над головой нестабильная порода.</summary>
    Unstable,
    /// <summary>Блок впереди не ломается (коренная порода, чужая постройка).</summary>
    Blocked,
    /// <summary>Под ногами пропасть, а заделать её нечем.</summary>
    NoFooting,
    /// <summary>Тело не смогло войти в прокопанную клетку.</summary>
    Stuck,

    /// <summary>
    /// ХОД ЗАДАН НИЖЕ РОСТА ТЕЛА: такую нору выкопать можно, а пройти по ней
    /// нельзя — значит и ходом она не станет.
    ///
    /// Отдельно от <see cref="Stuck"/> нарочно, и разница тут та же, что у
    /// дороги (<see cref="RoadStop.NoHeadroom"/>): «Stuck» — это «мир
    /// помешал», а здесь задание само себе противоречит, и узнаётся это ДО
    /// первого удара. Молча зажать число до роста тела нельзя: зажми — и
    /// человек никогда не узнает, что его число не доехало.
    /// </summary>
    NoHeadroom
}

/// <summary>
