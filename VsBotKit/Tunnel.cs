/// <summary>Итог проходки — по фактам, а не по намерениям.</summary>
public sealed record TunnelReport(
    TunnelStop Stop,
    string Reason,
    BlockPos StoppedAt,
    int Steps,
    int Broken,
    int Placed,
    int Torches,
    double LeftToTarget,
    double Seconds,
    IReadOnlyDictionary<string, int> Gained)
{
    public bool Success => Stop == TunnelStop.Done;

    /// <summary>
    /// ПОМЕХА ОБЩИМ СЛОВОМ: пройдёт ли она сама (<see cref="Setback"/>).
    ///
    /// Не вторая копия <see cref="Stop"/>, а ответ на ДРУГОЙ вопрос — тот же
    /// разбор, что у дороги (<see cref="RoadReport.Hindrance"/>).
    /// <see cref="Stop"/> отвечает человеку («вода не унялась»),
    /// <see cref="Hindrance"/> — тому, кто звал проходку: ждать бесполезно или
    /// подожди и возьмись заново. Считает одно чистое правило
    /// (<see cref="Tunnel.WhatStopped"/>).
    /// </summary>
    public Setback Hindrance { get; init; } = Setback.None;

    public override string ToString()
    {
        string what = Gained.Count == 0
            ? "ничего"
            : string.Join(", ", Gained.OrderByDescending(g => g.Value).Take(5)
                .Select(g => $"{g.Key} x{g.Value}"));
        return $"проходка {Steps} кл. (сломано {Broken}" +
               (Placed > 0 ? $", заделано {Placed}" : "") +
               (Torches > 0 ? $", факелов {Torches}" : "") +
               $"); попутно добыто: {what}; " +
               $"до цели {LeftToTarget:0.#} бл; {Seconds:0} с; " +
               $"остановка на {StoppedAt}: {Reason}";
    }
}

/// <summary>
/// ШТОЛЬНЯ: прокопать ход туда, куда пешком не пройти.
///
/// Зачем отдельная механика. Карьер снимает ОБЪЁМ по плану, а поиск пути ходит
/// по тому, что УЖЕ есть. Между ними дыра, и она вскрылась живьём: руда лежит
/// в одном блоке за стеной, бот честно доложил «ближе 1 бл не подобраться» —
/// и встал. Живой игрок в этом месте просто прокапывается. Ровно это здесь и
/// делается, и делается один раз на всех: и на безголового бота, и на мод.
///
/// ХОД — ЛЕСЕНКОЙ, А НЕ КОЛОДЦЕМ. Отвесная шахта вниз копается быстрее всего
/// и ровно один раз: обратно из неё не выбраться, а прыжок в игре берёт один
/// блок. Поэтому высота меняется не больше чем на клетку за шаг и всегда
/// вместе с шагом в сторону — получается обычная лестница, по которой можно
/// вернуться. Когда цель ровно под ногами, ход нарочно виляет вбок: два
/// столбца туда-обратно и есть винтовая лестница в шахте два на один.
///
/// ВОДА — НЕ ПОВОД ВСТАТЬ. Увидев воду вплотную к ходу, проходка закладывает
/// её блоком из сумки и копает дальше, как это делает живой игрок. Отказ
/// остаётся там, где он честен: закладывать нечем, вода не унялась (тогда
/// сначала отступаем) и лава (её заложить не успеешь — сгоришь).
///
/// ЧЕСТНОСТЬ. Проходка отказывается и говорит причину: лава за стеной,
/// незаложенная вода, нестабильный потолок, нечем взять породу, кончается
/// кирка, полные сумки. Молчаливого «стою» здесь быть не может.
///
/// Класс — МЕХАНИЗМ. Куда копать, что делать с попутной рудой и стоит ли
/// тратить факелы, решает роль.
/// </summary>
public class Tunnel
{
    private readonly BotContext ctx;

    public Tunnel(BotContext ctx) => this.ctx = ctx;

    public event Action<string>? OnLog;

    // ---------------- настройки ----------------

    /// <summary>
    /// ВЫСОТА ХОДА ШТОЛЬНИ в блоках. Умолчание — <see cref="Walker.MinHeadroom"/>,
    /// то есть ровно те две клетки, в которые влезает тело (ноги и голова).
    /// Один пришлось бы проползать, а ползать бот не умеет.
    ///
    /// Число не своё, а взято у общего правила нарочно: своя константа «2»
    /// здесь однажды разошлась бы с ростом тела, и ход остался бы низким при
    /// исправленном везде росте.
    ///
    /// У ШТОЛЬНИ СВОЯ РУЧКА, А НЕ ОБЩАЯ С ДОРОГОЙ, И ВОТ ПОЧЕМУ.
    ///
    /// ПЕРВОЕ — ЭТО РАЗНЫЕ РАБОТЫ И РАЗНАЯ ЦЕНА КЛЕТКИ. Выемка дороги
    /// (<see cref="Roads.Height"/>) — полоса шириной <see cref="Roads.Width"/>
    /// (заводское три), по которой ХОДЯТ и в которой РАБОТАЮТ: там бот мостит
    /// полотно и ставит блоки над головой, оттого заказчик и просил пять —
    /// «а то бот не может его застраивать». Штольня — ход в ОДНУ клетку,
    /// прокопанный к руде за стеной; по нему проходят раз туда и раз обратно,
    /// строить в нём нечего. Лишняя клетка высоты там — это лишний ряд породы
    /// на всю длину хода и ни одного нового дела.
    ///
    /// ВТОРОЕ — ЧИСЛО ПЯТЬ СКАЗАНО ПРО ДОРОГУ, ДОСЛОВНО: «высоту спуска надо
    /// поднять, и сделать настраиваемой У ДОРОГИ». Про штольню хозяин не
    /// говорил ничего, и поставить ей ту же пятёрку значило бы назначить число
    /// за него.
    ///
    /// ТРЕТЬЕ — ОБЩЕЕ У НИХ РОВНО ОДНО, И ОНО УЖЕ ОБЩЕЕ: нижняя граница, рост
    /// тела <see cref="Walker.MinHeadroom"/>, выведенный из хитбокса игрока.
    /// На нём стоят обе высоты, и второй константы «2» в проекте нет.
    ///
    /// НИЖЕ РОСТА — ОТКАЗ ВСЛУХ, А НЕ МОЛЧАЛИВЫЙ ЗАЖИМ: см.
    /// <see cref="TunnelStop.NoHeadroom"/> и <see cref="TooLow"/>.
    /// </summary>
    public int Height { get; set; } = Walker.MinHeadroom;

    /// <summary>
    /// ВЫСОТА СТУПЕНЕЙ ВЫХОДА — РОСТ ТЕЛА, И РУЧКА ЗДЕСЬ НИ ПРИ ЧЁМ.
    ///
    /// ЛЕСЕНКА — НЕ ХОД. По ходу (<see cref="Height"/>) ходят: раз туда к руде,
    /// раз обратно, и хозяин вправе захотеть его повыше. По ступеням выхода
    /// (<see cref="ClimbOutAsync"/>, <see cref="ClimbOutByAsync"/>,
    /// <see cref="StepDownAsync"/>) поднимаются ОДИН раз и уходят; каждая
    /// лишняя клетка высоты там — лишний ряд породы на КАЖДУЮ ступень, а
    /// ступеней столько же, сколько блоков глубины.
    ///
    /// ЧЕМ ЭТО БЫЛО ДО СИХ ПОР И ЧТО ЛОМАЛО. Лесенка читала ту же
    /// <see cref="Height"/>, и обе крайности ручки били живьём:
    ///   • ВысотаШтольни = 1 — на ступень вскрывалась ОДНА клетка вместо двух,
    ///     тело в неё не влезало, и бот три стороны подряд повторял «клетка
    ///     вскрыта, а тело в неё не идёт» (приёмка, 38,108,27: четыре блока в
    ///     мусор, 14 секунд вместо 4, вылез случайно четвёртой стороной);
    ///   • ВысотаШтольни = 5 — на каждую ступень снималось ПЯТЬ клеток вместо
    ///     двух: «выход из ямы» и «выход из воды», доказанные живьём,
    ///     дорожали в два с половиной раза ни за что.
    /// Обе беды от одного корня: у выхода спрашивали число, сказанное про ход.
    ///
    /// Своей константы «2» здесь нет нарочно: рост тела в проекте один и
    /// выведен из хитбокса игрока (<see cref="Walker.MinHeadroom"/>).
    ///
    /// ОТКРЫТО НАРУЖУ РАДИ ОДНОГО, И ЭТОТ ОДИН — СТЕНД: чтобы спрашивающий «что
    /// бы ты вскрыл» (<see cref="CellsToBreakFor"/>) мог назвать РАБОТУ, а не
    /// подставить первое попавшееся число. Живого читателя снаружи у этого
    /// свойства нет — все четыре внешних чтения из набора, и сказано это вслух
    /// там же, у самого окна. Разбор — там же.
    /// </summary>
    public static int StairHeadroom => Walker.MinHeadroom;

    /// <summary>
    /// КАК РУЧКИ ШТОЛЬНИ ЗОВУТСЯ У ЧЕЛОВЕКА. Механизм своих отказов не
    /// подписывает именами свойств: от «Height» в журнале толку столько же,
    /// сколько от «ход низковат». Человеческое имя знает роль, она же его сюда
    /// и кладёт — тем же приёмом, что у дороги (<see cref="RoadKnobs"/>).
    /// </summary>
    public TunnelKnobs Knobs { get; } = new();

    /// <summary>
    /// ЧТО ПРО СЛОМАННУЮ РУЧКУ ВЫСОТЫ УЖЕ СКАЗАНО ВСЛУХ. null — не говорили
    /// ничего (или ручку поправили).
    ///
    /// Живёт на штольне, а не в <see cref="Run"/>: голос звучит у ступеней
    /// (<see cref="StairsAsync"/>), а туда заходят с КАЖДЫМ уступом, и свой
    /// <see cref="Run"/> у каждого захода — память внутри него не пережила бы
    /// и второй ступени. Разбор — там же, у самого голоса.
    /// </summary>
    private string? сказаноПроНизкуюРучку;

    /// <summary>
