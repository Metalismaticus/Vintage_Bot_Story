/// <summary>
/// Что видно с одной стороны, если шагнуть туда И ВВЕРХ на клетку.
///
/// Все факты спрашиваются у игры ПО КАРТЕ МИРА, а не выдумываются и не
/// выясняются ударом: стоит ли под будущей ступенью твердь, берётся ли порода
/// ступени тем, что сейчас в руках, нет ли там лавы, видно ли её отсюда,
/// сколько клеток ломать и во сколько секунд они обойдутся.
///
/// ЖИВОЙ СЛУЧАЙ, ради которого набор расширен (журнал выхода из ямы на 11 бл,
/// 2,5 минуты):
///   «[штольня] ступень в сторону (1, 0): под будущей ступенью стоит порода»
///   «[руки] до (512034, 105, 512256) нет прямой видимости: мешает
///    rock-peridotite в (512033, 105, 512256)»
///   «[штольня] ступень в сторону (1, 0) не вышла — поворачиваю и пробую другую»
/// и то же самое ещё три раза, по три секунды и по целому шторму поиска пути
/// на каждую сторону. А «нет прямой видимости» ЗНАЕТСЯ ЗАРАНЕЕ: это тот же
/// луч из глаз, который бот считает сам, и считать его можно до первого удара.
/// </summary>
/// <param name="Support">Под клеткой ног будущей ступени стоит твердь.</param>
/// <param name="Rise">
/// НА СКОЛЬКО КЛЕТОК ЭТА СТУПЕНЬ СДВИНЕТ НОГИ В НУЖНУЮ СТОРОНУ ПО ВЫСОТЕ
/// (вверх на выходе из ямы, вниз на спуске). Ноль — «шаг вбок и та же высота».
///
/// ЖИВОЙ СЛУЧАЙ, ради которого поле заведено (журнал 16.08, 20:36:36–20:36:38,
/// девять раз подряд за две секунды):
///   «ступень в сторону (1, 0): под будущей ступенью стоит порода — вырублю
///    ступень и встану на неё даром (ломать 0 кл, около 0 с, оценка 100)»
///   «ступень в сторону (1, 0) не вышла (по высоте не сдвинула)»
/// Бот стоял на каменной тропе (stonepath), а у неё верх коллизии 0,9375 бл, не
/// целая клетка (assets/survival/blocktypes/stone/generic/stonepath.json). Тропа
/// «твердь» по любой мерке (0,94 &gt; StepHeight 0,6), опора под будущей ступенью
/// была, ломать было нечего — а ноги после шага оказывались на 110,94, ровно там
/// же, где были. Девять блоков вбок и ноль вверх.
///
/// Считать высоту НОМЕРОМ КЛЕТКИ опоры и было ошибкой: важен ВЕРХ опоры, а не
/// её номер. Мерка тут та же самая, которой лесенка потом меряет свой успех
/// (клетка ног), — иначе правило снова обещало бы одно, а тело делало другое.
/// </param>
/// <param name="Carvable">Клетки ступени пусты или ломаются тем, что в руках.</param>
/// <param name="Safe">В клетках ступени нет лавы или кипятка.</param>
/// <param name="Visible">
/// До каждой клетки ступени ОТСЮДА есть прямая видимость — или взгляд ей
/// закрывает клетка ЭТОЙ ЖЕ ступени, которую мы сломаем раньше (такая помеха
/// не в счёт: она откроется сама). Рука бьёт только то, что видит, поэтому
/// невидимая ступень — это не «попробую», а заведомо потраченные секунды.
/// </param>
/// <param name="Blocks">Сколько клеток придётся сломать (пустые не в счёт).</param>
/// <param name="Seconds">
/// Во сколько секунд обойдутся все клетки ступени ЛУЧШИМ, что есть в сумках.
/// Здесь и виден тир инструмента: та же порода бронзовой киркой держится
/// втрое дольше, чем железной, и это разница между «вылез» и «не успел».
/// </param>
public readonly record struct StepSide(bool Support, bool Carvable, bool Safe,
    bool Visible = true, int Blocks = 1, double Seconds = 0, int Rise = 1);

/// <summary>
/// ЧЕГО СТОИТ ОДИН ВАРИАНТ СТУПЕНИ: число и причина.
///
/// Число нужно затем, чтобы варианты можно было СРАВНИТЬ, не трогая их телом.
/// Больше — лучше (дешевле); <see cref="StepFooting.None"/> — вариант не
/// годится вовсе, и <see cref="Score"/> у него <see cref="Tunnel.NoStep"/>.
/// </summary>
public readonly record struct StepRating(int Score, StepFooting Footing, string Why)
{
    /// <summary>Годится ли вариант к работе.</summary>
    public bool Usable => Footing != StepFooting.None;
}

/// <summary>Выбранная сторона ступени: номер, опора, оценка и причина.</summary>
public readonly record struct StepPick(int Side, StepFooting Footing, int Score, string Why);

/// <summary>
/// ЧЕМ КОНЧИЛАСЬ ОДНА СТУПЕНЬ. Три разных исхода, и путать их нельзя: от них
/// зависит и счёт в отчёте, и то, что именно вычёркивается из перебора.
/// </summary>
public enum StairOutcome
{
    /// <summary>Взяла высоту. Вот это и есть ступень.</summary>
    Took,
    /// <summary>
    /// Тело переехало в другую клетку, а по высоте не сдвинулось. Это ШАГ
    /// ВБОК, а не ступень: считать его ступенью — врать в отчёте, а искать
    /// помеху в покинутой клетке — гоняться за собственным хвостом.
    /// </summary>
    Sideways,
    /// <summary>Тело осталось там же: помеха в ЭТОЙ клетке.</summary>
    Stuck
}

/// <summary>
/// ЧЕЛОВЕЧЕСКИЕ ИМЕНА РУЧЕК, КОТОРЫМИ ПРАВЯТ ШТОЛЬНЮ. Кладёт их сюда роль —
/// она их и придумала; механизм только вставляет их в свои отказы, чтобы
/// человеку было что покрутить.
///
/// Ровно тот же приём и ровно та же причина, что у дороги
/// (<see cref="RoadKnobs"/>): живой случай 16.08, дословно, — «вести до предела
/// мне не велено настройкой». Отказ был честный, а НАЗВАНИЯ настройки в нём не
/// было, и человек трижды пробовал наугад.
///
/// Умолчания — имена свойств самого механизма: библиотеку можно взять и без
/// роли, и тогда честнее назвать хоть их, чем не назвать ничего.
/// </summary>
public sealed class TunnelKnobs
{
    /// <summary>Чем задают высоту хода (<see cref="Tunnel.Height"/>).</summary>
    public string Height { get; set; } = nameof(Tunnel.Height);
}

