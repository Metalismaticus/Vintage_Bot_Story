namespace VsBotKit;

/// <summary>
/// НА КАКОЙ ВЫСОТЕ СТОЯТ НОГИ — ОДНА МЕРКА НА ВЕСЬ ПРОЕКТ.
///
/// ЗАЧЕМ ОТДЕЛЬНЫМ ПРАВИЛОМ. Мерка была выписана ДВАЖДЫ: у безголового бота
/// (<c>WorldModel.FeetY</c>) и в клиентском моде (<c>ModPathWorld.FeetY</c>),
/// а третий, укороченный, счёт той же высоты сидел внутри
/// <c>ModPathWorld.StandingWalkSpeed</c>. Док-строка мода при этом уверяла:
/// «тем же правилом, что у бота». Это было НЕПРАВДОЙ, и неправдой ровно в том
/// месте, которое чинили живьём:
///
///   у бота       — три случая (тонкий блок в клетке; тонкий блок ПОД клеткой,
///                  который выше шага; целый блок),
///   у мода       — один (тонкий блок в клетке),
///   у скорости   — свой третий: «тонкий блок в клетке, но не выше шага».
///
/// То есть починку 26.08 (дорожная плита под ногами) мод не получил вовсе:
/// маршрут для игрока считает ОН, и считал он его по мерке, от которой бот
/// отказался тем же вечером. Пока копий было три, следующая починка вылечила
/// бы одну и оставила две — молча.
///
/// ЧТО ЭТО ЗА ВЫСОТА. Точная высота ног в блоках, если стоять в этой клетке:
/// на полном кубе снизу — ровно граница клетки, на тонком блоке В САМОЙ
/// клетке (плита, дорожная плита, пластина транслокатора, слой снега) — его
/// верх. Ею живут подъём в поиске пути (<c>AStarPathFinder</c>), просвет над
/// головой (<c>WorldModel.ClearanceAt</c>) и скорость хода
/// (<see cref="GroundSpeed"/>).
///
/// Файл нарочно ничего не знает ни про сеть, ни про мир: его линкует в себя
/// клиентский МОД — как <see cref="Ceiling"/>, <see cref="GroundSpeed"/> и
/// <see cref="BodySize"/>. Разница у мода с ботом остаётся ровно одна и живёт
/// НЕ ЗДЕСЬ, а в ответе про блок: у бота непрогруженная клетка это «коллизии
/// нет» (0), у мода — «стена» (1).
/// </summary>
public static class Footing
{
    /// <summary>
    /// ВЫСОТА НОГ, ЕСЛИ СТОЯТЬ В КЛЕТКЕ <paramref name="y"/>, блоков.
    /// </summary>
    /// <param name="y">Номер клетки, в которой стоят ноги.</param>
    /// <param name="stepUp">
    /// На сколько тело всходит шагом, блоков (<see cref="BodySize.StepUp"/>).
    /// Довод, а не константа внутри: мир меряет им же и стену, и ступеньку
    /// (<c>IsPassable</c>), и разъехаться эти два ответа не должны.
    /// </param>
    /// <param name="collisionTop">
    /// Верх коллизии блока в клетке ЭТОГО ЖЕ столбца: 1 у куба, 0,5 у плиты,
    /// 0 у воздуха. Спрашивается лениво — про клетку под ногами вопрос идёт,
    /// только если он нужен.
    /// </param>
    public static double FeetY(int y, float stepUp, Func<int, float> collisionTop)
    {
        // 1. ТОНКИЙ БЛОК В САМОЙ КЛЕТКЕ НОГ — плита, пластина транслокатора,
        //    снег. На него встают, и он приподнимает ноги.
        float inCell = collisionTop(y);
        if (inCell > 0 && inCell < 1)
            return y + inCell;

        // 2. ТОНКИЙ БЛОК ПОД НОГАМИ, НА КОТОРЫЙ НЕ ВСТАЮТ — И ЭТО ЖИВОЙ СЛУЧАЙ
        //    26.08. Дорожная плита (stonepath, верх 0,9375) выше шага, поэтому
        //    клетку с ней бот считает НЕПРОХОДИМОЙ и стоит в клетке НАД ней —
        //    а ноги при этом на 0,0625 НИЖЕ её пола. Прежняя мерка отвечала
        //    «ровно на полу», и подъём на соседний целый блок выходил ровно
        //    1,0 вместо 1,0625.
        //
        //    Цена этой шестнадцатой доли блока оказалась велика: поиск пути
        //    считал такой подъём обычным шагом, тело шага в 0,6 не осиливало и
        //    упиралось, а клетка запоминалась НЕПРОХОДИМОЙ. За четыре минуты
        //    живого прогона бот выдумал себе тринадцать тупиков, прыгнув всего
        //    шесть раз. Журнал: «упёрся на точке 2/4 (46, 111, 234), стою
        //    (46,5, 109,9, 235,3)» — вот эти 109,9 и есть 109,9375.
        //
        //    ГРАНИЦА ЗДЕСЬ ИМЕННО ШАГ, и это находка того же прогона — дыра в
        //    первой же правке правила. Блок НЕ ВЫШЕ шага (снег 0,25, плита 0,5)
        //    держит ноги В СВОЕЙ СОБСТВЕННОЙ клетке: её и вернул случай 1.
        //    Спроси мы про клетку НАД ним — ответ «ноги на снегу» был бы ложью
        //    на целую клетку, и подъём выходил бы нулевым. Живьём это дало
        //    новый упор: «упёрся на точке 3/23 (83, 106, 271), стою
        //    (83,5, 105,2, 270,7)» — бот стоял на двух слоях снега и не видел
        //    подъёма вовсе.
        float below = collisionTop(y - 1);
        if (below > stepUp && below < 1)
            return y - 1 + below;

        // 3. ЦЕЛЫЙ БЛОК ПОД НОГАМИ (или лестница, у которой коробка в целую
        //    клетку: она тонкая по горизонтали, тело входит внутрь, и ноги
        //    остаются на полу клетки) — ноги ровно на границе клетки.
        return y;
    }
}
