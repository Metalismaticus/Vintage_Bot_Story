namespace VsBotKit;

/// <summary>
/// ЧТО ОСТАНОВИЛО РАБОТУ — ОДИН СЛОВАРЬ НА ВСЕ РАБОТЫ СРАЗУ.
///
/// ПРЯМАЯ ПРОСЬБА ЗАКАЗЧИКА, ДОСЛОВНО (01.09): «если мешает игрок, то
/// пробовать заново, а не сбрасывать и вообще на все бы задачи так и не только
/// из-за игрока, как бы сделать это все умнее».
///
/// ЧТО БЫЛО. Возврат к прерванной работе (<see cref="Resume"/>) умел ровно
/// один случай — «меня перебило другое дело» (<c>BodyArbiter.Ending.Preempted</c>):
/// бот пошёл поесть, отбился, вернулся и доделал. А когда работу останавливал
/// МИР — игрок встал на клетку, тварь пробежала, чанк не доехал, — повтора не
/// было ВОВСЕ: работа умирала на месте, и бот звал человека.
///
/// ГЛАВНОЕ ЗДЕСЬ — РАЗЛИЧИТЬ ПОМЕХУ ВРЕМЕННУЮ И ПОСТОЯННУЮ, и это и есть весь
/// словарь. Временную пережидают и берутся заново; постоянную называют вслух
/// и бросают, потому что от ожидания она не пройдёт. Мерить это строкой
/// причины нельзя: слова у каждой работы свои и меняются от правки к правке, —
/// поэтому работа отвечает СЛОВОМ ИЗ ЭТОГО СПИСКА, а решает одно чистое
/// правило (<see cref="Resume.Passing"/>).
///
/// СВОЕГО СЛОВАРЯ У КАЖДОЙ РАБОТЫ ТУТ НЕ ЗАВОДИТСЯ. У дороги есть
/// <see cref="RoadStop"/>, у рейса — <c>HaulStop</c>: они отвечают на «чем
/// кончилась ИМЕННО ЭТА работа» и нужны её собственному отчёту. Здесь вопрос
/// другой и общий — «какого РОДА была помеха», — и ответ на него один на всех,
/// иначе правило возврата пришлось бы писать заново под каждую работу.
/// </summary>
public enum Setback
{
    /// <summary>
    /// Помеха не названа: работа либо дошла до конца, либо встала, не сказав
    /// чем. Повтора НЕ будет — гадать за работу нельзя (правило 4 проекта:
    /// успех и отказ только по факту, а не по догадке).
    /// </summary>
    None,

    // ---------------- временные: подождать и ПОВТОРИТЬ ----------------

    /// <summary>
    /// МЕСТО ЗАНЯЛ ЖИВОЙ: игрок встал на клетку, тварь пробежала, чужая
    /// повозка перегородила ход. Через полминуты его там уже нет — ровно тот
    /// случай, с которого заказчик и начал.
    /// </summary>
    Crowd,

    /// <summary>
    /// МИР ЕЩЁ НЕ ДОЕХАЛ: чанк не пришёл, реестр блоков сервера не пришёл.
    /// Это не свойство места, а состояние связи, и оно проходит само.
    /// </summary>
    NotLoaded,

    /// <summary>
    /// МИР ПЕРЕМЕНИЛСЯ ПОД РУКАМИ: гравий осыпался в только что вскрытую
    /// клетку, воду прорвало, кто-то поставил блок. Работа считала мир одним,
    /// а он стал другим — второй заход считает уже новый.
    /// </summary>
    Shifted,

    /// <summary>
    /// ЗАХОД КОНЧИЛСЯ, А РАБОТА — НЕТ: у неё свой потолок на один вызов
    /// (у дороги это <see cref="Roads.MaxCells"/>). Помеха тут не в мире, но
    /// ответ тот же — взяться за остаток, а не звать человека.
    ///
    /// Живьём дорога говорила «остаток дороги надо задать ещё раз», и задавать
    /// его было некому: очередь читала это как конец работы.
    ///
    /// ОТВЕЧАЯ ТАК, РАБОТА ОБЕЩАЕТ, ЧТО СВОЮ ДОЛЮ СДЕЛАЛА. На этом обещании
    /// стоит обнуление счёта возвратов (<c>Resume.RunAsync</c>): доля
    /// кладётся быстро, и мерить её секундами нельзя. Работа, которая скажет
    /// «Unfinished», не сдвинувшись ни на клетку, закрутит себя в вечный круг
    /// — до потолка своего собственного срока.
    /// </summary>
    Unfinished,

    // ---------------- постоянные: честный отказ с причиной ----------------

    /// <summary>Дороги туда нет вовсе: обрыв, вода, стена без обхода.</summary>
    NoRoute,

    /// <summary>Кончился материал: нечем мостить, нечем столбиться.</summary>
    NoMaterial,

    /// <summary>Чужая заявка, запертая чужая дверь, чужой сундук.</summary>
    NotMine,

    /// <summary>
    /// НЕ ДОТЯНУТЬСЯ. Постоянная нарочно: рука не удлинится от ожидания, и
    /// лечится это ДРУГИМ МЕСТОМ, а не второй попыткой с того же.
    /// </summary>
    OutOfReach,

    /// <summary>
    /// ЗАДАНИЕ САМО СЕБЕ ПРОТИВОРЕЧИТ: уклон круче посильного, просвет ниже
    /// роста тела. Узнаётся до первого удара и от времени не меняется.
    /// </summary>
    Impossible,

    /// <summary>
    /// ДАЛЬШЕ УБЬЁТ. Лава за стеной, осыпающийся свод над головой, вода,
    /// заливающая ход. Работа встала не потому, что ей ПОМЕШАЛИ, а потому что
    /// следующий удар киркой стоил бы жизни.
    ///
    /// ПОЧЕМУ ОТДЕЛЬНОЕ СЛОВО, А НЕ ОДНО ИЗ ГОТОВЫХ — три раза «нельзя»:
    ///   • <see cref="Impossible"/> — про ЗАДАНИЕ, которое само себе
    ///     противоречит (уклон круче посильного). Здесь задание разумное:
    ///     карьер на семь клеток вглубь выкопать можно, просто на пятой лава;
    ///   • <see cref="NoRoute"/> — про ДОРОГУ, которой нет. Здесь она есть, по
    ///     ней нельзя идти ЖИВЫМ, и это разные вещи;
    ///   • <see cref="Shifted"/> перевернуло бы ответ на противоположный: бот
    ///     пережидал бы пять секунд и лез к лаве снова, и так трижды подряд.
    ///
    /// ПОСТОЯННАЯ, И ЭТО НЕ ОСТОРОЖНОСТЬ, А ФАКТ: лава не остынет, свод не
    /// срастётся, вода не уйдёт оттого, что бот подождёт. Лечится это другим
    /// местом или другим планом, и решать это человеку — значит, ему и надо
    /// сказать словом, а не молчанием.
    /// </summary>
    Deadly,

    /// <summary>Кончилось отведённое время — это не помеха, а срок.</summary>
    OutOfTime,

    /// <summary>Работу остановил человек или запретила роль.</summary>
    Stopped
}

/// <summary>
/// Чем кончилась работа, которую вели с возвратом.
/// </summary>
/// <param name="What">имя работы — то же, что видно в «занят: …»</param>
/// <param name="Tries">сколько раз брались за дело (первый заход тоже считается)</param>
/// <param name="Back">сколько раз ВОЗВРАЩАЛИСЬ после перерыва</param>
/// <param name="Finished">
/// дело дошло до СВОЕГО конца: и тела у него не отбирали, и сама работа
/// ответила «сделано». Одного «тело не отбирали» тут мало — см. разбор у
/// <see cref="Resume.Verdict"/>
/// </param>
/// <param name="End">чем кончился последний заход</param>
/// <param name="By">кто помешал в последний раз</param>
/// <param name="Say">та самая строка для человека</param>
public sealed record ResumeReport(string What, int Tries, int Back, bool Finished,
    BodyArbiter.Ending End, string By, string Say)
{
    public override string ToString() => Say;
}

/// <summary>
/// ПРЕРВАЛИ — ВЕРНИСЬ И ДОДЕЛАЙ.
///
/// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЭТО НАПИСАНО (журнал заказчика, 21:37-21:39).
/// Человек дал «!карьер 7 15» — план на 720 клеток. Через полторы минуты:
///   еда лежит в 0,1 бл — иду поднимать
///   [тело] «поднять еду» важнее — прерываю «команда карьер»
///   [карьер] сломано 67 из 720 кл. … остановка на (512357, 112, 511747): отменено
/// И ВСЁ. Карьер не возобновился никогда. Со стороны это выглядело так:
/// «дал задачу карьера, а он скопал только часть сверху и не стал углубляться».
///
/// Само прерывание было ПРАВИЛЬНЫМ: голодный бот важнее ямы. Неправильно было
/// то, что прерванная работа умирала. Распорядитель тела
/// (<see cref="BodyArbiter"/>) умел сказать «важнее — прерываю», но никто не
/// помнил, ЧТО прервали, и некому было вернуться.
///
/// ПОЧЕМУ ОТДЕЛЬНЫЙ МЕХАНИЗМ, А НЕ ЗАПЛАТКА В КАРЬЕРЕ. Ровно то же случается со
/// штольней, дорогой и нарядом: любое дело длиннее минуты рано или поздно
/// перебивает рефлекс. Написать возврат внутри карьера значит переписать его
/// потом ещё три раза и три раза по-разному.
///
/// ПРАВИЛА ВОЗВРАТА — три, и все проверены стендом:
/// 1. перебил РЕФЛЕКС выживания (бой, побег, еда) — вернуться: цель не менялась,
///    помеха временная, тело он отдаст сам;
/// 2. сменилась ЦЕЛЬ (новый приказ человека) — не возвращаться: иначе бот после
///    «!иди домой» молча уйдёт обратно копать;
/// 3. оборвали НАСМЕРТЬ («стоп», смерть, выход из мира) — не возвращаться:
///    это прямое неподчинение.
///
/// И потолок: если возвращаться приходится раз за разом и каждый раз работу
/// сбивают, не дав ничего сделать, — бросаем и говорим вслух, сколько раз
/// возвращались и кто мешал. Молчаливое верчение по кругу выглядит для человека
/// точно так же, как и мёртвая работа, только ещё и жрёт время.
///
/// Класс — МЕХАНИЗМ: он не знает ни про карьер, ни про роль. Ему дают имя
/// работы, её важность и то, ЧЕМ её продолжить; продолжать «с того места»
/// умеет сама работа (у карьера это <see cref="Quarry.Remaining"/>).
/// </summary>
public sealed class Resume
{
    private readonly BodyArbiter turn;

    public Resume(BodyArbiter turn) => this.turn = turn;

    public event Action<string>? OnLog;

    // ---------------- настройки ----------------

    /// <summary>
    /// Сколько раз подряд возвращаться к работе, которую сбивают ВПУСТУЮ.
    /// Три — потому что два раза подряд бывает и по случайности (дрифтер прошёл
    /// мимо, еда упала под ноги), а три подряд означают, что боту сейчас не до
    /// работы: он голоден, ранен или в осаде.
    /// </summary>
    public int MaxReturns { get; set; } = 3;

    /// <summary>
    /// Сколько секунд заход должен продержаться, чтобы считаться НЕ ВПУСТУЮ.
    ///
    /// Без этой мерки потолок попыток врёт в обе стороны. Карьер на час,
    /// который трижды за час прерывали на обед, был бы брошен как «безнадёжный»,
    /// хотя работа шла. А бот, которого сбивают через секунду после старта,
    /// крутился бы вечно — попытки-то каждый раз «новые».
    /// </summary>
    public double ProgressSeconds { get; set; } = 20;

    /// <summary>
    /// Пауза перед возвратом. Рефлекс только что отпустил тело, и лезть в ту же
    /// секунду значит отобрать его у него же на полудороге — например у подбора
    /// еды, который ещё не донёс её до рта.
    /// </summary>
    public double PauseSeconds { get; set; } = 1;

    /// <summary>
    /// ПАУЗА ПЕРЕД ПОВТОРОМ, КОГДА РАБОТУ ОСТАНОВИЛ МИР, а не рефлекс.
    ///
    /// ЧИСЛО ДРУГОЕ, ПОТОМУ ЧТО И ЖДЁМ МЫ ДРУГОГО. <see cref="PauseSeconds"/>
    /// меряет ход способностей: секунды хватает, чтобы не отобрать тело у
    /// рефлекса на полудороге. А тут ждут, пока ПЕРЕМЕНИТСЯ МИР — игрок сойдёт
    /// с клетки, тварь пробежит, чанк доедет. За секунду ничего этого не
    /// случается, и повтор вышел бы тем же самым отказом, только втрое.
    ///
    /// Пять секунд — не вкус, а цена вопроса. Меньше — повтор застаёт ту же
    /// обстановку; больше — человек видит бота, который «просто стоит», а
    /// заказчик на это уже жаловался дословно: «он просто стоял афк».
    ///
    /// Число — политика, и живёт оно ручкой роли («ЖдатьПеременыМираСекунд»);
    /// здесь только умолчание механизма.
    /// </summary>
    public double WorldPauseSeconds { get; set; } = 5;

    /// <summary>
    /// Сколько ждать освобождения тела, прежде чем честно отказаться. Бой с
    /// медведем и поход за едой длятся минуты, поэтому счёт на минуты.
    /// </summary>
    public double WaitForBodySeconds { get; set; } = 180;

    /// <summary>Сколько записей хранить в журнале прерванного.</summary>
    public int JournalDepth { get; set; } = 20;

    // ---------------- чистые правила ----------------

    /// <summary>
    /// ПОМЕХА ВРЕМЕННАЯ ИЛИ ПОСТОЯННАЯ — ЧИСТОЕ ПРАВИЛО И ОДНО НА ВСЕ РАБОТЫ.
    ///
    /// Здесь и живёт весь ответ на просьбу заказчика «и вообще на все бы задачи
    /// так»: заплатки в дороге, в наряде и в карьере разошлись бы на первой же
    /// правке, а это — одно место, где сказано, что проходит само, а что нет.
    /// Разбор каждого слова — у <see cref="Setback"/>.
    ///
    /// Возвращает пару: ждать ли и БРАТЬСЯ ЛИ ЗАНОВО — и что сказать человеку.
    /// Молчаливого «нет» тут быть не может: причина, по которой бот не стал
    /// пробовать второй раз, — ровно то, чего человеку не хватало в журнале.
    /// </summary>
    public static (bool Wait, string Why) Passing(Setback stop) => stop switch
    {
        Setback.Crowd => (true, "место занял живой — он уйдёт"),
        Setback.NotLoaded => (true, "мир ещё не доехал — он придёт"),
        Setback.Shifted => (true, "мир переменился под руками — пересчитаю его заново"),
        Setback.Unfinished => (true, "заход кончился, а работа — нет"),

        Setback.NoRoute => (false, "дороги туда нет — от ожидания она не появится"),
        Setback.NoMaterial => (false, "кончился материал — сам он не заведётся"),
        Setback.NotMine => (false, "это чужое — ждать тут нечего"),
        Setback.OutOfReach => (false, "не дотянуться — рука от ожидания не удлинится, " +
                                      "тут нужно другое место"),
        Setback.Impossible => (false, "задание само себе противоречит — время его не поправит"),
        Setback.Deadly => (false, "дальше опасно для жизни — лава, обвал и вода " +
                                  "от ожидания не расходятся, тут нужно другое место"),
        Setback.OutOfTime => (false, "кончился отведённый срок, а не помеха прошла"),
        Setback.Stopped => (false, "работу остановили, а не помешали ей"),

        // Работа встала и помехи не назвала. Догадываться за неё нельзя:
        // пустой повтор стоит ровно столько же, сколько первый заход
        _ => (false, "работа встала сама и помехи не назвала")
    };

    /// <summary>
    /// СРОК — ЭТО СИМПТОМ, А НЕ ПРИЧИНА: ОН ДОКЛАДЫВАЕТ ПОСЛЕДНЮЮ ЖИВУЮ
    /// ПОМЕХУ, А НЕ ЗАМЕНЯЕТ ЕЁ СОБОЙ. ЧИСТОЕ ПРАВИЛО, ОДНО НА ВСЕ РАБОТЫ.
    ///
    /// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЗАВЕДЕНО. Игрок встал на клетку жилы и
    /// простоял там пять минут. Наряду отведено пять минут — и он честно
    /// доложил «вышло отведённое время (300 с)». Слово <see cref="Setback.OutOfTime"/>
    /// лежит среди ПОСТОЯННЫХ, то есть возврат прочитал это как «дальше
    /// пробовать незачем», — а мешал-то <see cref="Setback.Crowd"/>, который проходит
    /// сам за полминуты. Помеха была живая, лежала рядом (у наряда это
    /// <c>lastMiss</c>, у карьера — последний пропуск слоя) и в отказ не
    /// попадала: срок вставал на её место.
    ///
    /// ЭТО ТОТ ЖЕ ЖАНР ВРАНЬЯ, НА КОТОРОМ ПРОЕКТ УЖЕ ГОРЕЛ: очередь задач
    /// объявляла «не смог за 300 с» через две секунды после начала. Число там
    /// было настоящее, а причина — подменённая.
    ///
    /// <paramref name="lastLive"/> — что мешало РАБОТЕ В ПОСЛЕДНИЙ РАЗ, пока
    /// шли часы. <see cref="Setback.None"/> — не мешало ничто, и тогда срок и
    /// вправду вся причина: работа просто не успела.
    ///
    /// ЧЕГО ЭТО ПРАВИЛО НЕ ДЕЛАЕТ. Оно не выдаёт времени сверх отведённого:
    /// у всей работы срок один, и сторожит его <see cref="WithinBudget"/> —
    /// там, где этот срок и заведён.
    /// </summary>
    public static Setback TimeIsNotACause(Setback lastLive) =>
        lastLive == Setback.None ? Setback.OutOfTime : lastLive;

    /// <summary>
    /// ПЕРЕЖИТАЯ ПОМЕХА — НЕ ПРИЧИНА ОСТАНОВКИ. ЧИСТОЕ ПРАВИЛО, ОДНО НА ВСЕ
    /// РАБОТЫ И ВТОРАЯ ПОЛОВИНА <see cref="TimeIsNotACause"/>.
    ///
    /// ЧТО ЭТО ЗА ПОМЕХА. Работа идёт клетка за клеткой, и часть клеток она
    /// ОБХОДИТ, продолжая дальше: у карьера это пропуск (<c>Run.Skip</c> —
    /// «клетку обошёл и работаю ДАЛЬШЕ»), у дороги — обойдённый ряд. Такая
    /// помеха мешала, пока шли часы, но работу НЕ ОСТАНОВИЛА, и класть её в
    /// причину остановки можно ровно в одном случае: если она ПРОХОДИТ САМА.
    ///
    /// ПОЧЕМУ ИМЕННО ТАК, А НЕ «КЛАСТЬ ВСЁ ПОДРЯД». Срок докладывает пережитую
    /// помеху затем, чтобы работа получила ВТОРОЙ ЗАХОД, когда ей не хватило
    /// только времени, а мешал кто-то проходящий. Проходящая помеха этот заход
    /// даёт; постоянная его ОТНИМАЕТ — и отнимает у работы, которая шла себе
    /// дальше и на постоянную помеху не жаловалась.
    ///
    /// ЖИВОЙ СЛУЧАЙ, НАЗВАННЫЙ ПРИЁМКОЙ 09.09. Карьер на 720 клеток обошёл ОДНУ
    /// клетку у воды на первой минуте («вода рядом» — <see cref="Setback.Deadly"/>)
    /// и упёрся в срок на десятой. В отказ шло «дальше опасно для жизни — лава,
    /// обвал и вода от ожидания не расходятся, тут нужно другое место»: место
    /// объявлялось негодным, второго захода карьер не получал — а нужно ему
    /// было ОДНО ВРЕМЯ, и 719 клеток из 720 стояли себе спокойно.
    ///
    /// Своего словаря тут нет: что проходит само, знает <see cref="Passing"/>,
    /// и второй копии ему не заводим.
    /// </summary>
    /// <param name="seen">помеха, которую работа ПЕРЕЖИЛА, а не встала от неё</param>
    /// <returns>её же слово — или <see cref="Setback.None"/>, «докладывать нечего»</returns>
    public static Setback LivedThrough(Setback seen) =>
        Passing(seen).Wait ? seen : Setback.None;

    /// <summary>
    /// СРОК ВСЕЙ РАБОТЫ ГАСИТ ПОМЕХУ ОДНОГО ЗАХОДА. ЧИСТОЕ ПРАВИЛО.
    ///
    /// ВТОРАЯ ПОЛОВИНА <see cref="TimeIsNotACause"/>, и без неё та была бы
    /// опасна. Заход кончился по своему потолку, помеха живая и временная
    /// («игрок на клетке») — значит браться заново. Но если у ВСЕЙ работы
    /// времени больше нет, второй заход упрётся в тот же срок в первую же
    /// секунду, и так до потолка повторов: три пустых захода и приговор
    /// «брался заново трижды, а помеха не прошла» — про помеху, которой уже
    /// никто не мешал. Кончилось время, и это правда.
    ///
    /// ПОЧЕМУ ЗДЕСЬ, А НЕ В САМОЙ РАБОТЕ. Работа знает только СВОЙ потолок на
    /// один вызов; сколько осталось у всего дела, знает тот, кто этот срок и
    /// завёл, — возврат работы (<c>OrderResume.KeepFetchingAsync</c>,
    /// <c>RoadResume.KeepBuildingAsync</c>, <c>Quarry.KeepQuarryingAsync</c>).
    /// Спрашивать это у работы значило бы завести вторую память о сроке.
    /// </summary>
    /// <param name="secondsLeft">сколько осталось у ВСЕЙ работы, не у захода</param>
    public static Setback WithinBudget(Setback stop, double secondsLeft) =>
        secondsLeft > 0 ? stop : Setback.OutOfTime;

    /// <summary>
    /// Возвращаться ли к прерванной работе. ЧИСТОЕ ПРАВИЛО: вся политика
    /// возврата стоит на нём, и стенд проверяет именно его.
    ///
    /// ДВА ПОВОДА ВЕРНУТЬСЯ, И ВТОРОГО ДО 01.09 НЕ БЫЛО ВОВСЕ:
    ///   • тело отобрал рефлекс (<c>Ending.Preempted</c>) — как и было;
    ///   • работа встала САМА, и помеха у неё временная
    ///     (<see cref="Passing"/>) — это и есть просьба заказчика «если мешает
    ///     игрок, то пробовать заново, а не сбрасывать».
    ///
    /// <paramref name="backAlready"/> — сколько раз ВПУСТУЮ уже возвращались
    /// подряд. Заход, в котором работа шла дольше <see cref="ProgressSeconds"/>,
    /// счёт обнуляет (см. <see cref="Fruitless"/>). Потолок ОДИН на оба повода
    /// нарочно: «сколько раз подряд браться за дело, которое не идёт» — один
    /// вопрос, и два числа на него разъехались бы.
    /// </summary>
    /// <param name="stop">
    /// Чем работа объяснила СВОЮ остановку. <see cref="Setback.None"/> —
    /// не объяснила ничем, и тогда повтора нет (прежнее поведение).
    /// </param>
    public static (bool Again, string Why) ShouldResume(BodyArbiter.Ending end, Setback stop,
        int backAlready, int maxReturns)
    {
        if (backAlready >= maxReturns)
            return (false, $"брался заново {Times(backAlready)} — это потолок " +
                           "(ручка «ВозвращатьсяКПрерванному»)");
        if (end == BodyArbiter.Ending.Preempted)
            return (true, "тело отобрал рефлекс — помеха временная по своей природе");
        // Оборвали насмерть или сменили цель: тут не помеха, а чужая воля
        if (end != BodyArbiter.Ending.None)
            return (false, "работу оборвали, а не помешали ей");
        return Passing(stop);
    }

    /// <summary>
    /// Был ли заход пустым: работу сбили раньше, чем она успела что-то сделать.
    /// Пустые заходы считаются подряд — они и упираются в потолок.
    /// </summary>
    public static bool Fruitless(double workedSeconds, double progressSeconds) =>
        workedSeconds < progressSeconds;

    /// <summary>
    /// ПОТОЛОК ВСЕХ ЗАХОДОВ ОДНОЙ РАБОТЫ — СТОРОЖ ОТ ВЕЧНОГО КРУГА, И СТОИТ ОН
    /// У САМОГО МЕХАНИЗМА.
    ///
    /// ЖИВОЙ ЗАМЕР ПРИЁМКИ 09.09. Работа, отдающая <see cref="Setback.Unfinished"/>
    /// и не делающая НИЧЕГО, получила ДВЕСТИ заходов при
    /// <see cref="MaxReturns"/> = 3, а приговор потом сказал «возвращался после
    /// перерыва однажды». Причина простая: <c>Unfinished</c> обнуляет счёт
    /// пустых возвратов БЕЗУСЛОВНО (иначе дорога в сто рядов бросалась бы на
    /// четвёртой сотне клеток — доля кладётся быстро, и мерить её секундами
    /// нельзя), и работа, которая это обещание НАРУШАЕТ, крутит механизм вечно.
    ///
    /// ПОЧЕМУ ЗДЕСЬ, А НЕ У ЗОВУЩИХ. Сторожа стояли у них поимённо:
    /// <c>RoadResume.KeepBuildingAsync</c> сам гасит <c>Unfinished</c> при
    /// <c>RowsDone &lt;= 0</c>, <c>Tunnel</c> — при <c>Steps == 0</c>. Это ОДНА
    /// МЕХАНИКА В ДВУХ МЕСТАХ (закон 2), и держалась она на том, что новый
    /// зовущий не забудет скопировать сторож. Забудет — вернётся круг, а
    /// механизм, который можно закрутить навсегда честной с виду работой, — это
    /// беда механизма, а не того, кто его позвал. Сторожа у зовущих при этом
    /// НУЖНЫ и остаются: они ловят ложь на первом же заходе и называют её
    /// точным словом, а этот — последняя застава на случай, когда не поймали.
    ///
    /// ТО ЖЕ ЧИСЛО ДЕРЖИТ И ВТОРОЙ КРУГ — «помеха временная, но повторяется
    /// вечно»: заход, живущий дольше <see cref="ProgressSeconds"/>, обнуляет
    /// счёт возвратов, и работа с помехой раз в полминуты до потолка повторов
    /// не доходит НИКОГДА. Оба круга — один вопрос: «сколько ВСЕГО раз браться
    /// за одну работу», — и ответ на него один.
    ///
    /// ПОЧЕМУ СТО. Заход кладёт долю целиком (у дороги
    /// <see cref="Roads.MaxCells"/> = 2048 клеток, у штольни
    /// <c>Tunnel.MaxSteps</c> = 256): работе, которой честно мало ста таких
    /// долей, мал не потолок, а её собственный предел на вызов. А сто пустых
    /// заходов — это убыток КОНЕЧНЫЙ и названный вслух, в отличие от круга.
    ///
    /// ПОЧЕМУ ЧИСЛО, А НЕ РУЧКА. Это не политика хозяина бота: он не выбирает,
    /// сколько раз боту крутиться на месте, и по этому числу ничего не решает —
    /// та же причина, по какой без ручки живёт <see cref="JournalDepth"/>.
    /// </summary>
    public const int MaxPasses = 100;

    /// <summary>
    /// ЗАКРУТИЛИСЬ ЛИ. ЧИСТОЕ ПРАВИЛО: <paramref name="passesDone"/> — сколько
    /// заходов работа уже получила (первый тоже считается).
    ///
    /// Молчаливого «хватит» тут быть не может: круг со стороны выглядит для
    /// человека точно так же, как зависший бот, и назвать его надо словами.
    ///
    /// СЛОВА ГОВОРЯТ РОВНО ТО, ЧТО МЕХАНИЗМ ВИДЕЛ: «заходов столько-то, а
    /// работа всё не кончается». Сказать «и не сдвинулась» он не вправе —
    /// сдвинулась ли работа, знает она сама, и ложное имя причины хуже
    /// честного «не знаю» (закон 4).
    /// </summary>
    public static (bool Circle, string Why) Circling(int passesDone) =>
        passesDone >= MaxPasses
            ? (true, $"заходов уже {passesDone}, а работа всё не кончается — это круг, " +
                     $"а не работа (потолок заходов {MaxPasses})")
            : (false, "");

    /// <summary>Сколько раз — по-русски, чтобы отчёт читался, а не считался.</summary>
    public static string Times(int n) => n switch
    {
        <= 0 => "ни разу",
        1 => "однажды",
        2 => "дважды",
        3 => "трижды",
        _ => $"{n} раз"
    };

    /// <summary>
    /// Что сказать человеку про судьбу работы. ЧИСТОЕ ПРАВИЛО и обязательное:
    /// молчание тут и есть та беда, с которой всё началось — карьер умер, а в
    /// журнале не было ни строчки о том, что он умер насовсем.
    ///
    /// <paramref name="done"/> — ОТВЕТ САМОЙ РАБОТЫ, дошла ли она до своего
    /// конца, и без него тут была прямая ложь. <see cref="BodyArbiter.Ending"/>
    /// знает ровно одно: отбирали ли тело. Работа возвращается «сама» и когда
    /// сломалась кирка, и когда набились сумки, и когда не нашлось пути, — а
    /// печаталось на это «доделал». Живой случай: «!карьер 7 15», кирка
    /// сломалась на 3-й клетке из 720 — в журнале «[возврат] «карьер (…)»:
    /// доделал». Та же подмена мерки, из-за которой склад докладывал «легло
    /// 112 шт.» при пустом сундуке: мерить надо то, что видит человек.
    /// </summary>
    /// <param name="stop">
    /// Чем работа объяснила свою остановку (<see cref="Setback"/>). Нужно за
    /// двумя вещами, и обе — про честность отказа:
    ///   • у работы, которую бросили НА ПОТОЛКЕ ПОВТОРОВ, «мешать не мешали» —
    ///     прямая ложь: мешал мир, и он не прошёл;
    ///   • у работы, ВСТАВШЕЙ ПО НАЗВАННОЙ ПОМЕХЕ, — та же ложь, и вот её
    ///     живой случай (замер приёмки 09.09). <see cref="Setback.Deadly"/>,
    ///     <see cref="Setback.NoRoute"/>, <see cref="Setback.NoMaterial"/> и
    ///     истёкший срок — все четыре давали человеку ОДНУ строку: «работа
    ///     встала сама (причина в её отчёте); мешать не мешали». Ради чего
    ///     словарь и писан («честный отказ С ПРИЧИНОЙ»), на самом отказе не
    ///     произносилось: <see cref="Passing"/> считался в
    ///     <see cref="ShouldResume"/> и ВЫБРАСЫВАЛСЯ, а до человека доходил
    ///     ровно из одной ветки — потолка повторов.
    /// </param>
    public static string Verdict(string what, BodyArbiter.Ending end, string by,
        int back, int maxReturns, bool done, Setback stop = Setback.None) => end switch
    {
        BodyArbiter.Ending.None when done => back > 0
            ? $"«{what}»: доделал, возвращался после перерыва {Times(back)}"
            : $"«{what}»: доделал",

        // ПОТОЛОК ПОВТОРОВ ПРИ ЖИВОЙ ПОМЕХЕ. Ветка стоит ВЫШЕ общей «встала
        // сама» нарочно: та говорит «мешать не мешали», а здесь мешали — и
        // помеха оказалась долгой. Человеку нужно знать оба числа: сколько раз
        // брались и чего ждали
        BodyArbiter.Ending.None when back >= maxReturns && stop != Setback.None =>
            $"«{what}»: брался заново {Times(back)}, а помеха не прошла " +
            $"({Passing(stop).Why}) — бросаю; причина в отчёте работы",

        // РАБОТА ВСТАЛА САМА И ПОМЕХУ НАЗВАЛА — ЗНАЧИТ ЕЁ И ГОВОРИМ, СЛОВАРЁМ.
        // Ветка стоит ВЫШЕ общей по той же причине, что и потолок повторов:
        // «мешать не мешали» тут неправда — мешали, и помеха постоянная.
        // Человек читает не «причина в её отчёте» (то есть «ищи сам»), а саму
        // причину и то, чем она лечится: «дороги туда нет», «кончился
        // материал», «тут нужно другое место»
        BodyArbiter.Ending.None when stop != Setback.None => back > 0
            ? $"«{what}»: до конца НЕ довёл — {Passing(stop).Why}; " +
              $"возвращался после перерыва {Times(back)}"
            : $"«{what}»: до конца НЕ довёл — {Passing(stop).Why}",

        // Тело не отбирали, работа не доделана и помехи НЕ НАЗВАЛА. Гадать за
        // неё нельзя: причину знает она сама и говорит её своим отчётом —
        // здесь важно не выдать это за успех
        BodyArbiter.Ending.None => back > 0
            ? $"«{what}»: до конца НЕ довёл — работа встала сама (причина в её отчёте); " +
              $"мешать не мешали, возвращался после перерыва {Times(back)}"
            : $"«{what}»: до конца НЕ довёл — работа встала сама (причина в её отчёте); " +
              "мешать не мешали",

        BodyArbiter.Ending.Halted =>
            $"«{what}»: оборвали насмерть ({by}) — не возвращаюсь",

        BodyArbiter.Ending.Retargeted =>
            $"«{what}»: сменилась цель, тело забрало «{by}» — не возвращаюсь",

        // Тот самый отказ, которого не хватало: сколько раз возвращались,
        // что мешало и почему бросаем
        _ when back >= maxReturns =>
            $"возвращался к «{what}» {Times(back)}, каждый раз перебивают — " +
            $"бросаю, причина: {by}",

        _ => $"«{what}»: перебил «{by}», возвращаюсь"
    };

    /// <summary>
    /// ЧТО СКАЗАТЬ ПРО ОБОРВАННОЕ ОДНОРАЗОВОЕ ДЕЛО — то, к которому возврата НЕ
    /// БУДЕТ. null — не обрывали, говорить не о чем.
    ///
    /// ЖИВОЙ СЛУЧАЙ (журнал 16.08):
    ///   13:04:59 [тело] «бой» важнее — прерываю «отнести nugget-nativecopper на склад из окна»
    ///   13:05:40 [тело] «бой» важнее — прерываю «обход склада из окна»
    /// и ни строчки дальше. Слова заказчика: «бой отменяет некоторые задания, а
    /// не временно их паузит». Обрыв был ПРАВИЛЬНЫМ — жизнь важнее рейса, — а
    /// вот молчание после него неправильным: человек нажал кнопку, получил в
    /// ответ «отнёс 0» и не узнал ни кто помешал, ни того, что бот к делу уже
    /// не вернётся.
    ///
    /// ПОЧЕМУ ЭТО ОТДЕЛЬНОЕ ПРАВИЛО, А НЕ <see cref="Verdict"/>. Тот отвечает за
    /// работу, которую ВЕДУТ С ВОЗВРАТОМ, и на обрыв рефлексом честно говорит
    /// «возвращаюсь». Одноразовому делу такое обещать нельзя: кнопка окна — это
    /// один запрос, который ждёт ответа, и заставить браузер ждать освобождения
    /// тела до <see cref="WaitForBodySeconds"/> нельзя. Слова разные потому, что
    /// и правда разное; общий тут — разбор конца (<see cref="BodyArbiter.Ending"/>),
    /// и он один на оба правила.
    /// </summary>
    public static string? NoReturn(BodyArbiter.Ending end, string by) => end switch
    {
        BodyArbiter.Ending.None => null,
        BodyArbiter.Ending.Preempted =>
            $"дело оборвал «{by}» — он важнее, но это дело одноразовое: " +
            "к незаконченному не возвращаюсь, начните заново, когда он отпустит",
        BodyArbiter.Ending.Retargeted =>
            $"дело оборвало «{by}»: боту дали другую цель — не доделываю",
        _ => $"дело оборвали насмерть ({by}) — не доделываю"
    };

    // ---------------- память прерванного ----------------

    private readonly object gate = new();
    private readonly List<string> journal = [];
    private readonly HashSet<string> waiting = new(StringComparer.Ordinal);
    private int stopEpoch;
    private string stopWhy = "";

    /// <summary>
    /// Какие работы прямо сейчас ждут освобождения тела, чтобы доделаться.
    /// Пусто — никто никого не ждёт. Это и есть память прерванного, видимая
    /// снаружи: окну управления и ответу на «чем занят».
    /// </summary>
    public IReadOnlyCollection<string> Waiting
    {
        get { lock (gate) return [.. waiting]; }
    }

    /// <summary>Последние записи о прерванном: что, кто помешал, чем кончилось.</summary>
    public IReadOnlyList<string> Journal
    {
        get { lock (gate) return [.. journal]; }
    }

    /// <summary>
    /// БОЛЬШЕ НЕ ВОЗВРАЩАТЬСЯ — общий выключатель для «стоп» и для выхода из мира.
    ///
    /// Одного <see cref="BodyArbiter.Interrupt"/> мало: между заходами работа
    /// тела не держит вовсе (ждёт, пока рефлекс доест), и прерывать в этот миг
    /// нечего — а вернуться она всё равно собиралась. Поэтому у возврата есть
    /// собственный выключатель, и «стоп» обязан дёргать оба.
    /// </summary>
    public void StopAll(string why)
    {
        lock (gate)
        {
            stopEpoch++;
            stopWhy = why;
            waiting.Clear();
        }
        Note($"возвращаться к прерванному больше не буду: {why}");
        turn.Interrupt(why);
    }

    private void Note(string line)
    {
        lock (gate)
        {
            journal.Add(line);
            int depth = Math.Max(1, JournalDepth);
            if (journal.Count > depth)
                journal.RemoveRange(0, journal.Count - depth);
        }
        OnLog?.Invoke(line);
    }

    // ---------------- работа ----------------

    /// <summary>
    /// Вести работу так, чтобы рефлекс её не убивал.
    ///
    /// <paramref name="work"/> ОТВЕЧАЕТ, ДОШЛА ЛИ ОНА ДО СВОЕГО КОНЦА (true —
    /// сделано, false — встала по своей причине). Спрашивать обязательно:
    /// распорядитель тела знает только, отбирали ли тело, и без ответа самой
    /// работы «вернулась» приходилось читать как «доделала» — то есть врать
    /// про сломанную кирку и полные сумки (см. <see cref="Verdict"/>).
    ///
    /// <paramref name="work"/> зовут по разу на заход, и первым доводом идёт
    /// НОМЕР захода (1 — первый). Продолжать с того места, где встали, — дело
    /// самой работы: карьер, например, каждый раз копает остаток плана
    /// (<see cref="Quarry.Remaining"/>), а не начинает яму заново. Работа,
    /// которая на втором заходе начнёт всё сначала, испортит сделанное — такую
    /// сюда отдавать нельзя, и номер захода дан ровно затем, чтобы это было
    /// видно в коде вызывающего.
    ///
    /// ЧЬИМ ТЕЛОМ РАБОТАЕМ. Если тело свободно — берём своё владение и живём
    /// по нему. Если тело УЖЕ занято (обычный случай: команда из чата взяла его
    /// как «команда карьер» и позвала навык), первый заход идёт под чужим
    /// владением — иначе равный по важности сам себе откажет, и работа не
    /// начнётся вовсе. Тогда же у чужого владения и спрашивают, что случилось:
    /// по голому токену отмены рефлекс от «стопа» не отличить.
    ///
    /// А вот ВОЗВРАЩАЕМСЯ уже на своё владение: чужое к тому времени мертво
    /// навсегда, и токен, пришедший сюда доводом, вместе с ним. Это не обход
    /// отмены, а её замена на живую: «стоп», смерть и выход из мира гасят новое
    /// владение точно так же (см. <see cref="StopAll"/>).
    /// </summary>
    public Task<ResumeReport> RunAsync(string what, BodyArbiter.Importance level,
        Func<int, CancellationToken, Task<bool>> work, CancellationToken ct = default) =>
        RunAsync(what, level,
            async (attempt, token) => (await work(attempt, token), Setback.None), ct);

    /// <summary>
    /// ТО ЖЕ САМОЕ, НО РАБОТА ЕЩЁ И НАЗЫВАЕТ, ЧТО ЕЁ ОСТАНОВИЛО.
    ///
    /// Вход тут ОДИН, а не два механизма: короткий (<c>Task&lt;bool&gt;</c>)
    /// зовёт этот же, подставляя <see cref="Setback.None"/> — «помеху не
    /// назвали», то есть прежнее поведение слово в слово. Работа, которая
    /// помеху называть научилась, получает за это повтор при временной
    /// (<see cref="Passing"/>) и честный отказ при постоянной.
    /// </summary>
    public async Task<ResumeReport> RunAsync(string what, BodyArbiter.Importance level,
        Func<int, CancellationToken, Task<(bool Done, Setback Stop)>> work,
        CancellationToken ct = default)
    {
        int myEpoch;
        lock (gate) myEpoch = stopEpoch;

        int tries = 0, back = 0, backTotal = 0;
        var end = BodyArbiter.Ending.None;
        string by = "";
        // До первого захода работа ничего не сделала — и объявлять её
        // сделанной нельзя даже на секунду
        bool done = false;
        // Чем работа объяснила свою остановку в ПОСЛЕДНИЙ раз: по нему решают
        // повтор и по нему же говорят приговор, когда повторы кончились
        var stop = Setback.None;
        // Пусто — круга не было. Слова кладёт Circling, своего суждения тут нет
        string circled = "";

        try
        {
            while (true)
            {
                if (Stopped(myEpoch, out string stoppedWhy))
                {
                    end = BodyArbiter.Ending.Halted;
                    by = stoppedWhy;
                    break;
                }

                // ПЕРВЫЙ заход слушается токена вызывающего; на возвратах тот
                // токен уже мёртв — его погасило то самое прерывание
                if (tries == 0 && ct.IsCancellationRequested)
                {
                    end = BodyArbiter.Ending.Halted;
                    by = "отменено снаружи";
                    break;
                }

                // ЧУЖОЕ ВЛАДЕНИЕ БЕРЁМ ТОЛЬКО РОВНО РАВНОЕ ПО ВАЖНОСТИ. Это и
                // есть признак «оно моё же, только этажом выше»: команда из
                // чата взяла тело как «команда карьер» и позвала карьер. Более
                // важное владение чужое по-настоящему — под рефлексом бегства
                // копать нельзя, и тут честнее отказ
                var above = tries == 0 ? turn.Current : null;
                var borrowed = above is not null && above.Level == level ? above : null;

                var mine = borrowed != null ? null
                    : tries == 0 ? turn.TryTake(what, level, ct)
                    : await turn.TakeAsync(what, level, WaitForBodySeconds);

                if (mine == null && borrowed == null)
                {
                    // Тела не дали. На первом заходе это обычный отказ «занят»,
                    // на возврате — беда: работа так и осталась недоделанной, и
                    // сказать об этом надо ровно теми словами
                    string why = tries == 0
                        ? $"«{what}» не начинаю: тело занято «{turn.Busy}»"
                        : $"к «{what}» не вернулся: тело держит «{turn.Busy}» " +
                          $"дольше {WaitForBodySeconds:0} с — работа осталась недоделанной";
                    Note(why);
                    return new ResumeReport(what, tries, backTotal, false,
                        BodyArbiter.Ending.Halted, turn.Busy, why);
                }

                // ЕЩЁ РАЗ ПРО «СТОП», УЖЕ С ТЕЛОМ В РУКАХ. Ждать освобождения
                // можно минутами, и «стоп», сказанный в это время, обязан
                // застать нас ДО того, как мы снова примемся за работу: иначе
                // человек увидит, что бот после «стоп» сделал ещё один заход
                if (Stopped(myEpoch, out string stopped))
                {
                    mine?.Dispose();
                    end = BodyArbiter.Ending.Halted;
                    by = stopped;
                    break;
                }

                tries++;
                var startedAt = DateTime.UtcNow;
                // Под чужим владением работа слушается ОБОИХ: и токена
                // вызывающего (там живёт «стоп» навыка), и самого владения —
                // иначе, позвав нас с неотменяемым токеном, вызывающий получил
                // бы работу, которую не остановить ничем
                using var linked = borrowed == null
                    ? null
                    : CancellationTokenSource.CreateLinkedTokenSource(ct, borrowed.Token);
                var token = mine?.Token ?? linked!.Token;
                done = false;
                stop = Setback.None;
                try
                {
                    (done, stop) = await work(tries, token);
                }
                catch (OperationCanceledException) when (token.IsCancellationRequested)
                {
                    // Работа вылетела по своей же отмене — это не беда, а ровно
                    // то, чего от неё и ждут. Причину спросим у владения тела,
                    // а не у исключения: исключение её не знает
                }
                finally
                {
                    if (mine != null)
                    {
                        end = mine.End;
                        by = mine.EndedBy;
                        mine.Dispose();
                    }
                    else
                    {
                        // Чужому владению верим ТОЛЬКО если его и вправду
                        // перебили. Иначе выйдет ложь наоборот: работа спокойно
                        // доработала до конца, а мы объявили её прерванной и
                        // полезли доделывать сделанное
                        end = borrowed!.Interrupted ? borrowed.End : BodyArbiter.Ending.None;
                        by = end == BodyArbiter.Ending.None ? "" : borrowed.EndedBy;
                    }
                }

                double worked = (DateTime.UtcNow - startedAt).TotalSeconds;
                // Заход, в котором работа шла долго, обнуляет счёт пустых
                // возвратов: помеха раз в полчаса — это жизнь, а не безнадёга.
                //
                // И ЗАХОД, КОНЧИВШИЙСЯ ПО СВОЕМУ ПОТОЛКУ, — ТОЖЕ, СКОЛЬКО БЫ ОН
                // НИ ДЛИЛСЯ. Setback.Unfinished значит «свою долю я сделал, но
                // работа длиннее одного вызова»; мерить такой заход секундами
                // значило бы бросить дорогу в сто рядов на четвёртой сотне
                // клеток только потому, что каждая сотня кладётся быстро
                if (!Fruitless(worked, ProgressSeconds) || stop == Setback.Unfinished)
                    back = 0;

                // ДОДЕЛАННОЙ РАБОТЕ ПОМЕХИ НЕ ПРИПИСЫВАЕМ. Работа могла
                // сказать «сделано» и назвать помеху последнего ряда заодно;
                // повторять сделанное из-за неё — то самое кружение, на которое
                // заказчик и жаловался
                var (again, whyAgain) = ShouldResume(end, done ? Setback.None : stop,
                    back, MaxReturns);

                // …И ПОСЛЕДНЯЯ ЗАСТАВА — ОТ ВЕЧНОГО КРУГА. Счёт возвратов
                // обнуляется (долгим заходом или обещанием Unfinished), и
                // работа, которая обещание нарушает, крутила механизм без конца:
                // живой замер — 200 заходов при потолке возвратов 3. Спрашиваем
                // ПОСЛЕ ShouldResume нарочно: пока повтора и так нет, круга нет
                // тоже, и лишним словом человека не пугаем
                if (again && Circling(tries) is { Circle: true } circle)
                {
                    again = false;
                    circled = circle.Why;
                }

                if (!again)
                    break;

                back++;
                backTotal++;
                lock (gate) waiting.Add(what);
                // ЖДЁМ РАЗНОГО — ЖДЁМ ПО-РАЗНОМУ. Рефлекс отпускает тело за
                // секунду, а мир (игрок на клетке, недоехавший чанк) меняется
                // дольше: разбор обоих чисел — у PauseSeconds и WorldPauseSeconds
                bool отобрали = end == BodyArbiter.Ending.Preempted;
                double пауза = отобрали ? PauseSeconds : WorldPauseSeconds;
                Note(отобрали
                    ? $"«{what}» перебил «{by}» через {worked:0} с — вернусь и доделаю " +
                      $"(возврат {back} из {MaxReturns})"
                    : $"«{what}» встала сама через {worked:0} с: {whyAgain} — жду " +
                      $"{пауза:0.#} с и берусь заново (возврат {back} из {MaxReturns})");

                if (пауза > 0)
                    await Task.Delay(TimeSpan.FromSeconds(пауза));
            }
        }
        finally
        {
            lock (gate) waiting.Remove(what);
        }

        // КРУГ ДОПИСЫВАЕТСЯ К ПРИГОВОРУ, А НЕ ЗАМЕНЯЕТ ЕГО. Приговор отвечает
        // на «чем кончилась работа», круг — на «почему я перестал за неё
        // браться»; это разные вопросы, и человеку нужны оба. Второй копии
        // словаря тут нет: слова круга пишет одно чистое правило (Circling)
        string say = Verdict(what, end, by, back, MaxReturns, done, done ? Setback.None : stop);
        if (circled.Length > 0)
            say += $"; {circled} — бросаю";
        Note(say);
        // «Доделал» — это И тело не отбирали, И сама работа сказала «сделано».
        // Раньше здесь стояло одно только «end == None», и отчёт объявлял
        // законченным карьер, вставший на третьей клетке из-за сломанной кирки
        return new ResumeReport(what, tries, backTotal,
            end == BodyArbiter.Ending.None && done, end, by, say);
    }

    private bool Stopped(int myEpoch, out string why)
    {
        lock (gate)
        {
            why = stopWhy;
            return stopEpoch != myEpoch;
        }
    }
}
