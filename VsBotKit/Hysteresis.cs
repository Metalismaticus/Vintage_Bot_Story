namespace VsBotKit;

/// <summary>
/// ПОРОГ С ЗАПАСОМ (ГИСТЕРЕЗИС) — ОДИН МЕХАНИЗМ НА ВСЕ ДРОЖАЩИЕ ЧИСЛА.
///
/// ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЭТО ВЫНЕСЕНО ОТДЕЛЬНО (bot.log 16.08, 12:52–13:26).
/// Бот копал наклонную штольню и мотал фонарь туда-сюда: 58 пар «взял → убрал»,
/// медиана 0,9 с, самая быстрая 0,49 с. Причина не во времени суток — на дворе
/// был полдень, — а в МЕСТЕ: у порога «светло/темно» стояло ОДНО число на оба
/// направления, и шаг под кровлю переворачивал ответ, а шаг обратно возвращал.
/// Каждый переворот — два переноса вещи на сервер и занятая левая рука.
///
/// ЧТО ДЕЛАЕТ ЗАПАС. Порогов становится ДВА: один — чтобы ответить «да», другой,
/// отодвинутый, — чтобы вернуться к «нет». Между ними держится ПРЕЖНИЙ ответ, и
/// дрожание числа у самой границы больше ничего не переворачивает.
///
/// ПОЧЕМУ МЕХАНИЗМ, А НЕ ПРАВКА В ФОНАРЕ. Ровно эта беда уже была разобрана
/// руками в другом месте — <see cref="StabilityRules.RunVerdict"/> («бегу — не
/// бегу» по пять раз в секунду у порога стабильности). Второй рукописной копии
/// быть не должно: правило здесь одно, а пороги свои у каждого — они политика и
/// живут в ролях. Потребителей у него сейчас пятеро: свет чанка, глубина под
/// небом и часы суток (<see cref="BehaviorCarryLight.IsDarkHere"/>),
/// стабильность (<see cref="StabilityRules.RunVerdict"/>) и «цель уходит»
/// на погоне (<see cref="Walker.SprintNow"/>).
///
/// САМИ ЧИСЛА СЮДА НЕ ЕДУТ, и это нарочно: у света это уровни, у глубины —
/// блоки, у часов — часы, а у стабильности — доля от нуля до единицы. Сравнение
/// с порогом умеет делать тот, кто мерит (<see cref="Lighting.IsDark"/> знает
/// про ночь и про устаревшие цифры, <see cref="GameClock.NightWithin"/> — про
/// длину суток мира). Сюда приходят два готовых ответа, и повторять чужие
/// сравнения тут нечем и незачем.
/// </summary>
public static class Hysteresis
{
    /// <summary>
    /// ОТВЕТ С ЗАПАСОМ: «да» — по своему порогу, «нет» — только когда число
    /// ушло и за второй, отодвинутый.
    /// </summary>
    /// <param name="on">
    /// Число дошло до порога включения («темно», «уже уходить», «ночь»).
    /// </param>
    /// <param name="stillOn">
    /// Число ещё не ушло за порог выключения. Порог этот отодвинут в сторону
    /// «нет», поэтому «да» без «ещё да» невозможно — а если такое пришло, оно
    /// разобрано ниже честно, а не молча.
    /// </param>
    /// <param name="was">
    /// Прежний ответ; null — ответа ещё не было. Первый ответ даётся ПО ПОРОГУ
    /// ВКЛЮЧЕНИЯ, а не по отодвинутому: иначе бот, впервые открывший глаза в
    /// сумерках, считал бы себя в темноте и брал бы фонарь на пустом месте.
    /// </param>
    public static bool Holds(bool on, bool stillOn, bool? was) =>
        on || (stillOn && (was ?? on));
}
