namespace VsBotKit;

/// <summary>
/// КАК ЗЕМЛЯ МЕНЯЕТ СКОРОСТЬ ХОДА — чистое правило самой игры, без мира и без
/// тела.
///
/// ЖИВОЙ СЛУЧАЙ, СЛОВАМИ ЗАКАЗЧИКА (19.08): «возможно проблемы из-за снега, но
/// сложно. плоохо стал идти, особенно в конце». На его снимке мир весь в снегу:
/// «Осень, −4,0 °C», сугробы на земле и на крышах.
///
/// ЧТО ГОВОРЯТ АССЕТЫ ИГРЫ 1.22.7
/// (assets/survival/blocktypes/liquid/snowlayer.json): слоёв снега семь, и
/// коробки коллизии у них ТРИ РАЗНЫЕ —
///   snowlayer-1   → коробки НЕТ ВОВСЕ (collisionbox: null);
///   snowlayer-2…4 → y2 = 0.125;
///   snowlayer-5…7 → y2 = 0.25;
/// а тормозят все семь по-своему: walkspeedmultiplier от 0.95 до 0.65.
///
/// ПОЧЕМУ ОТСЮДА ЭТО ВИДНО, А ИЗ ОДНОГО БЛОКА — НЕТ. Игра берёт ДВА блока
/// (<c>EntityAgent.GetWalkSpeedMultiplier</c>, VintagestoryAPI 1.22.7): тот,
/// что под ногами, и тот, В КОТОРОМ ноги стоят. На ровной земле это одно и то
/// же, а на снегу — нет, и промахнуться можно в обе стороны:
///   • у <c>snowlayer-1</c> коробки нет, ноги стоят на земле под ним, и блок
///     «под ногами» — обычная земля: снега, покрывшего осенью всю карту, из
///     одной клетки не видно НИКОГДА;
///   • у слоёв потолще коробка есть, и ноги поднимаются В САМ СНЕГ. Тогда «под
///     ногами» — уже снег, а не дорожное полотно под ним, и каменная тропа с её
///     1,3 превращается под сугробом в самую медленную землю в округе.
///
/// ОТДЕЛЬНЫМ ФАЙЛОМ НАРОЧНО. Этот счёт нужен обеим жизням библиотеки: и
/// безголовому боту (<see cref="WorldModel.WalkSpeedAt"/>), и клиентскому моду,
/// который линкует его прямо в себя — как <see cref="JumpPhysics"/> и
/// <see cref="BlockPos"/>. Второй копии этой арифметики — в моде, в поиске пути
/// или в оценке скорости — быть не должно.
/// </summary>
public static class GroundSpeed
{
    /// <summary>
    /// ДВЕ КЛЕТКИ, У КОТОРЫХ ИГРА СПРАШИВАЕТ СКОРОСТЬ ХОДА, — и это НЕ одна
    /// клетка «под ногами». Начало той самой игровой функции:
    /// <code>
    ///   int below  = (int)(Pos.InternalY - 0.05);
    ///   int inside = (int)(Pos.InternalY + 0.01);
    /// </code>
    /// Своей «удобной» мерки тут нет и быть не может: разойдись хоть на сотую —
    /// и бот считал бы скорость по одному блоку, а шёл по другому.
    ///
    /// Приведение <c>(int)</c>, а не <c>Math.Floor</c>, — тоже не мелочь: так
    /// написано в игре, и на отрицательных высотах эти два счёта расходятся.
    /// Мир игры лежит выше нуля, но повторяем мы игру, а не свои ожидания.
    /// </summary>
    /// <param name="feetY">Высота НОГ (не номер клетки).</param>
    public static (int Below, int Inside) CellsAt(double feetY) =>
        ((int)(feetY - 0.05), (int)(feetY + 0.01));

    /// <summary>
    /// МНОЖИТЕЛЬ СКОРОСТИ ХОДА — произведение двух блоков, и второй считается,
    /// ТОЛЬКО пока клетки разные. Последняя строка той же игровой функции:
    /// <code>
    ///   return … * (blockBelow.WalkSpeedMultiplier *
    ///               ((below == inside) ? 1f : blockInside.WalkSpeedMultiplier));
    /// </code>
    /// Оговорка «клетки разные» не украшение: без неё снег, в котором стоят
    /// ноги, тормозил бы вдвое сильнее, чем на самом деле (0,65² = 0,42).
    /// </summary>
    public static float Of(float below, float inside, bool sameCell) =>
        below * (sameCell ? 1f : inside);
}
