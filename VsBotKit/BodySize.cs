namespace VsBotKit;

/// <summary>
/// РАЗМЕР ТЕЛА ИГРОКА — ОДИН ОТВЕТ НА ВЕСЬ ПРОЕКТ.
///
/// ОТКУДА ЧИСЛА: игра 1.22.7, assets/game/entities/humanoid/player.json,
/// «hitboxSize: { x: 0.6, y: 1.85 }» (глаза там же — 1.7). Тем же размером
/// бот поднимает своё тело на игровой физике
/// (<c>GamePlayerPhysics.CollisionBoxSize</c>), и тем же меряет игрока сервер.
/// Догадок здесь нет и быть не может.
///
/// ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Размер тела жил в дереве россыпью и под разными
/// именами: у добычи («встал бы в меня самого»), у транслокаторов («не попал
/// на пластину»), у прыжка («свес хитбокса на взлёте»), у лестниц (рост тела) —
/// и, что хуже всего, У САМОЙ ФИЗИКИ, которая этой коробкой и упирается в мир
/// (<c>GamePlayerPhysics</c>: пара 0,6 × 1,85 стояла там своими литералами).
/// Каждая копия отвечала на свой вопрос, поэтому расхождения не было видно, —
/// а место, где размера НЕ СПРОСИЛИ ВОВСЕ, стоило заказчику живого зависания:
/// спрямление маршрута мерило проходимость нитью по центрам клеток и о толщине
/// тела не знало (см. <see cref="BodyCorridor"/>).
///
/// Теперь ответ ОДИН, и это проверяется телом на стенде, а не словом:
/// <c>BodySizeIsOneAnswerTests</c> поднимает бота на игровой физике и сверяет
/// коробку поднятого тела и с этими числами, и с ассетами игры. Разведи их
/// снова — покраснеет.
///
/// Файл нарочно ничего не знает ни про сеть, ни про мир: его линкует в себя
/// клиентский МОД (как <see cref="JumpPhysics"/> и <see cref="BlockPos"/>),
/// а мод считает маршрут тем же кодом, что и безголовый бот.
/// </summary>
public static class BodySize
{
    /// <summary>Ширина коробки тела, блоков (hitboxSize.x).</summary>
    public const double Width = 0.6;

    /// <summary>
    /// Половина ширины: настолько коробка торчит от точки, где бот стоит, в
    /// каждую сторону. Именно этой половиной тело и цепляет соседний столбец,
    /// в который линия по центрам клеток не заглядывает.
    /// </summary>
    public const double HalfWidth = Width / 2;

    /// <summary>Рост тела, блоков (hitboxSize.y).</summary>
    public const double Height = 1.85;

    /// <summary>
    /// ВЫСОТА ГЛАЗ НАД НОГАМИ, блоков. Из тех же ассетов, что и коробка:
    /// assets/game/entities/humanoid/player.json, «eyeHeight: 1.7».
    ///
    /// ЭТО НЕ УКРАШЕНИЕ ОПИСИ. Из глаз выходит ЛУЧ РУКИ: сервер меряет
    /// дальность до блока от глаз (<c>Hands.DistanceToPoint</c>), ими же
    /// считается «дотянусь ли отсюда» у карьера (<c>Quarry.ArmReaches</c>) и
    /// «видно ли грань» у добычи. Ошибись на полметра — и бот выбирает клетку,
    /// с которой сервер удара не примет, а человек читает «не дотянуться» и
    /// не понимает, почему.
    ///
    /// ЗАЧЕМ ЗДЕСЬ, А НЕ ЛИТЕРАЛОМ У РУК. Литерал там и стоял: <c>Hands</c>
    /// подставлял 1.7 запасным ответом, когда у поднятого тела ещё нет
    /// <c>LocalEyePos</c>. Число из тех же двух строк ассета, что рост и
    /// ширина, — а жило отдельно от них, и правка ассета игры починила бы
    /// коробку и оставила глаза на старом месте МОЛЧА.
    /// </summary>
    public const double EyeHeight = 1.7;

    /// <summary>
    /// НА СКОЛЬКО ТЕЛО ВСХОДИТ ШАГОМ, не отрываясь от земли, блоков.
    ///
    /// ОТКУДА ЧИСЛО: игра 1.22.7,
    /// <c>EntityBehaviorControlledPhysics.StepHeight = 0.6f</c> (VSEssentials.dll,
    /// поле читается из атрибута «stepHeight»), а в
    /// assets/game/entities/humanoid/player.json такого атрибута НЕТ ВОВСЕ —
    /// значит у игрока действует ровно это умолчание. Замер телом на игровой
    /// физике — <c>PlayerPhysicsFactsTests</c>.
    ///
    /// ЗАЧЕМ ЗДЕСЬ, А НЕ ПЯТЬЮ ЛИТЕРАЛАМИ. Это же число до сих пор было
    /// выписано ЧЕТЫРЕ РАЗА, и каждый раз своим именем: <c>WorldModel.StepHeight</c>
    /// (по нему мир решает, стена перед нами или ступенька), <c>Walker.StepUp</c>
    /// (им бот объясняет человеку отказ), <c>GamePlayerPhysics.StepHeight</c>
    /// (ею тело и правда всходит) и <c>ModPathWorld.StepHeight</c> в клиентском
    /// моде. Четыре ответа на один вопрос — это четыре шанса разойтись; ровно
    /// так уже разошлись «прыжком ровно 1 бл» и апекс 1,27, и разошлись молча.
    /// </summary>
    public const double StepUp = 0.6;

    /// <summary>
    /// ВО СКОЛЬКО РАЗ ПРИСЕД УКОРАЧИВАЕТ ТЕЛО.
    ///
    /// ОТКУДА ЧИСЛО: игра 1.22.7, <c>EntityPlayer.updateEyeHeight</c>
    /// (VintagestoryAPI.dll). Там на присяде обе величины умножаются на одно
    /// и то же:
    ///   <c>if ((controls.Sneak || !PrevFrameCanStandUp) &amp;&amp; !IsClimbing
    ///        &amp;&amp; !IsFlying) { eye *= 0.8; height *= 0.8; }</c>
    /// и полученным ростом игра переписывает НЕ ТОЛЬКО картинку:
    ///   <c>OriginCollisionBox.Y2 = CollisionBox.Y2 = …</c>
    ///   <c>OriginSelectionBox.Y2 = SelectionBox.Y2 = …</c>
    /// то есть присед меняет саму КОРОБКУ, которой тело упирается в мир.
    /// Для сравнения: сидя на полу (FloorSitting) множители другие — 0,5 для
    /// глаз и 0,55 для роста, — и путать их нельзя.
    /// </summary>
    public const double CrouchScale = 0.8;

    /// <summary>
    /// РОСТ ТЕЛА В ПРИСЯДЕ, блоков: 1,85 × 0,8 = 1,48.
    ///
    /// ЭТО И ЕСТЬ ПРОСВЕТ, КОТОРЫЙ ПРОСИЛ ЗАКАЗЧИК СЛОВАМИ «научи видеть высоту
    /// препятствия, некоторые можно пройти в присяд». Разница со стоячим ростом
    /// — 0,37 бл, и обольщаться ею нельзя: в ЦЕЛУЮ клетку (просвет 1,0)
    /// присевший не влезет так же, как и стоячий. Присед открывает ровно те
    /// щели, где потолок висит НЕ по границе клетки: перевёрнутая плита
    /// (низ коробки 0,5 — просвет 1,5), перевёрнутая ступень, тёсаный
    /// полублок под потолком, люк в потолке.
    ///
    /// Пример живой и близкий копателю: он сам кладёт ступени
    /// <c>stonepathslab-free</c>. Встань на такую плиту в ходе высотой два
    /// блока — и просвет над головой станет 1,5: стоя не пройти, в присяде
    /// пройти.
    /// </summary>
    public const double CrouchHeight = Height * CrouchScale;

    /// <summary>
    /// ВЫСОТА ГЛАЗ В ПРИСЯДЕ, блоков: 1,7 × 0,8 = 1,36. Тем же множителем и в
    /// той же строке игры, что и рост. Важно потому, что из глаз выходит луч
    /// руки: присев, бот целится в блок с другой высоты, и «дотянусь ли»
    /// считается от неё.
    /// </summary>
    public const double CrouchEyeHeight = EyeHeight * CrouchScale;

    /// <summary>
    /// КАК БЫСТРО КОРОБКА ДОЕЗЖАЕТ ДО НОВОГО РОСТА, доля разницы в секунду.
    ///
    /// В игре присед не мгновенный (<c>updateEyeHeight</c>):
    ///   <c>d = (want − Y2) · 5 · dt; Y2 = Y2 + d</c>
    /// — то есть тело подбирается к нужному росту экспоненциально, со
    /// скоростью 5 в секунду. На деле от 1,85 до 1,48 (с запасом в сотую)
    /// проходит около 0,7 с.
    ///
    /// ЭТО НЕ УКРАШЕНИЕ. Зажать шифт и в тот же миг шагнуть в полуторную щель
    /// нельзя — коробка ещё не села, и тело упрётся. Кто жмёт присед ради
    /// прохода, обязан дать телу эти доли секунды.
    /// </summary>
    public const double CrouchFitPerSecond = 5.0;
}
