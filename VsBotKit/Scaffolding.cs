namespace VsBotKit;

/// <summary>
/// ЧЕМ ДЛЯ БОТА СТАНОВИТСЯ ТО, ЧТО ОН ПОСТРОИЛ, ЧТОБЫ ПОДНЯТЬСЯ, — ДОРОГОЙ ИЛИ
/// ЛЕСАМИ. Два случая, и до 01.09 они были одним.
///
/// ЖИВАЯ ЖАЛОБА ЗАКАЗЧИКА 01.09, ДОСЛОВНО: «тогда нет смысла убирать те леса,
/// по которым он вылез, это уже ошибка». В журнале того же вечера бот вылез из
/// ямы столбом на 4 бл, записал столб в леса, ушёл на два десятка блоков,
/// вспомнил про долг, вернулся, не дотянулся («не дотянуться до (25, 111, 239),
/// до цели 20,6 бл»), был перебит едой — и долг остался висеть, дёргая его к
/// яме при каждом безделье. А снимись он — бот оказался бы на дне той же ямы.
///
/// РЕШАЕТ ЭТО НЕ СТРОЙКА И НЕ СТОЛБ: они не знают, зачем их позвали. Знает
/// звавший, и потому довод идёт СВЕРХУ — от того, кто просил подъём.
/// </summary>
public enum ClimbKeep
{
    /// <summary>
    /// ДОРОГА: этим бот ВЫБРАЛСЯ ИЗ ЯМЫ (своей выработки, карьера, провала).
    /// Она остаётся стоять, и в долг на снос не пишется вовсе — снять её
    /// значит вернуть себя туда, откуда только что вылез. Это же и умолчание:
    /// оставить лишний блок в мире дешевле, чем запереть себя.
    /// </summary>
    Road,

    /// <summary>
    /// ЛЕСА: этим бот ДОТЯНУЛСЯ ДО ЧЕГО-ТО В ВОЗДУХЕ (подъём к цели, «!заберись»,
    /// столб к позвавшему). Внизу под ними земля, и разбираются они НА СПУСКЕ,
    /// сверху вниз, стоя на них, — ровно как это делает живой игрок, забирая
    /// блоки обратно. Тем и разбираются: спуск столбом
    /// (<see cref="Mining.PillarDownAsync"/>) ломает клетку под ногами и
    /// вычёркивает её из долга (<c>TempBlocks.Forget</c>).
    /// </summary>
    Scaffold
}

/// <summary>Чем бот выбрался наверх (или почему не выбрался).</summary>
public enum ClimbBuild
{
    /// <summary>Ничего строить не пришлось.</summary>
    NotNeeded,
    /// <summary>Ступени, вырубленные в стене. Даром.</summary>
    Steps,
    /// <summary>Столб из блоков под ногами.</summary>
    Pillar,
    /// <summary>Лестница по стене.</summary>
    Ladder,
    /// <summary>Не вышло.</summary>
    Failed
}

/// <param name="Placed">Сколько блоков поставлено.</param>
/// <param name="Climbed">На сколько блоков поднялись.</param>
public record BuildClimbResult(bool Success, ClimbBuild Way, int Placed, int Climbed, string Why)
{
    public override string ToString() => Way switch
    {
        ClimbBuild.NotNeeded => "строить не пришлось",
        // «Ничего не потратив» — только когда и правда ничего: под ступень
        // случается подложить блок из сумки, и молчать об этом нельзя. Тем же
        // враньём был бы отчёт «вышел ступенями» про подъём, где половину
        // взяли лестницей, — поэтому приём называет тот, кто поднял больше
        ClimbBuild.Steps => Placed > 0
            ? $"вышел ступенями на {Climbed} бл, потратив {Placed} бл"
            : $"вышел по ступеням на {Climbed} бл, ничего не потратив",
        ClimbBuild.Ladder => $"построил лестницу {Placed} бл, поднялся на {Climbed}",
        ClimbBuild.Pillar => $"поднялся столбом на {Climbed} бл",
        // ПРИСЛОВЬЕ БЕРЁТСЯ У ТОГО, КТО ЕГО ОБЪЯВИЛ, А НЕ ПЕРЕПИСЫВАЕТСЯ СЮДА.
        // Отчёт стройки ложится в ClimbResult.Why целиком, и подъём убирает
        // второе присловье, сверяясь с ЭТИМ словом. Стояла тут его копия в
        // кавычках — и док-строка ClimbResult.НеВышло уверяла, что копии нет:
        // разойдись они, сторож двойного присловья зеленел бы при живой беде
        _ => $"{ClimbResult.НеВышло}: {Why}"
    };
}

/// <summary>
/// СТРОЙКА РАДИ ПОДЪЁМА: лестница по стене.
///
/// Зачем отдельно от столба. Столб под ногами — приём быстрый, но у него две
/// беды: он оставляет посреди мира палку из земли и с него нельзя слезть
/// иначе как разобрав его. Лестница по стене лишена обеих: по ней ходят
/// вверх и вниз сколько угодно, и это то, что живой игрок строит, когда
/// собирается возвращаться, — выход из шахты, подъём на башню, спуск в яму.
///
/// ЧЕРЕЗ ОДНУ. Игроки ставят лестницы не сплошняком, а через блок: рост тела
/// почти два блока, поэтому оно всегда касается хотя бы одной перекладины, и
/// лезется так же, а материала уходит вдвое меньше. Бот делает так же —
/// и потому же умеет по таким лазать (см. WorldModel.CanHangAt).
///
/// Механика честная: лестницы берутся из сумок и тратятся по-настоящему.
/// </summary>
public class Scaffolding
{
    private readonly BotContext ctx;

    public Scaffolding(BotContext ctx) => this.ctx = ctx;

    public event Action<string>? OnLog;

    /// <summary>
    /// Кем подписаны леса, поставленные стройкой. Слово одно на весь класс: по
    /// нему уборка отличает свои подпорки от чужих, и разойдись эти подписи
    /// копиями — «убери леса стройки» перестало бы находить половину из них.
    /// </summary>
    public const string ЛесаСтройки = "стройка";

    /// <summary>Код лестницы (часть кода — их в игре несколько видов).</summary>
    public string LadderCode { get; set; } = "ladder";

    /// <summary>
    /// Ставить через одну. Игроки так и делают: тело касается перекладины
    /// в любом случае, а материала вдвое меньше. Роль может потребовать
    /// сплошную — например, чтобы по ней бегали новички-люди.
    /// </summary>
    public bool EveryOtherBlock { get; set; } = true;

    /// <summary>Насколько высоко бот берётся строить за один заход.</summary>
    public int MaxHeight { get; set; } = 32;

    /// <summary>Сколько ждать подтверждения подъёма на ступень, секунд.</summary>
    public double StepSeconds { get; set; } = 2.5;

    /// <summary>
    /// Построить лестницу вверх по стене и подняться по ней.
    ///
    /// Стена нужна: лестница крепится к ней, в воздухе висеть не будет.
    /// Если стены рядом нет — говорим об этом прямо, а не строим столб
    /// втихую: подмена приёма без спроса это враньё о том, что произошло.
    /// </summary>
    /// <param name="keep">
    /// ДОРОГА ЭТО ИЛИ ЛЕСА (<see cref="ClimbKeep"/>). Лестница, по которой бот
    /// вылез из ямы, — такая же дорога, как и столб: снимешь её — и он снова
    /// на дне. Умолчание то же и по той же причине.
    /// </param>
    public async Task<BuildClimbResult> LadderUpAsync(int height, CancellationToken ct = default,
        ClimbKeep keep = ClimbKeep.Road)
    {
        if (ctx.Body?.Physics is not { } phys)
            return new BuildClimbResult(false, ClimbBuild.Failed, 0, 0, "тело не на физике");
        if (height <= 0)
            return new BuildClimbResult(true, ClimbBuild.NotNeeded, 0, 0, "");
        if (height > MaxHeight)
            return new BuildClimbResult(false, ClimbBuild.Failed, 0, 0,
                $"{height} бл выше, чем я берусь строить ({MaxHeight})");

        int startY = (int)Math.Floor(phys.Y + 0.01);
        int fx = (int)Math.Floor(phys.X), fz = (int)Math.Floor(phys.Z);

        // Есть ли вообще к чему крепиться: ищем сторону, где твердь стоит по
        // всей высоте подъёма. Без опоры лестница просто не встанет
        if (WallSide(fx, startY, fz, height) is not { } side)
            return new BuildClimbResult(false, ClimbBuild.Failed, 0, 0,
                "рядом нет стены, к которой крепить лестницу");

        // СТОРОНУ НАЗЫВАЕТ ТОТ, КТО ЕЁ ВЫБИРАЕТ, — А ВЫБИРАЕТ ЕЁ ИГРА.
        // Здесь стояло «строю лестницу вдоль стены юг», и это было неправдой:
        // до сервера наш выбор не доходит вовсе (щёлкаем мы по грани соседа,
        // а сторону сервер берёт своим правилом — Mining.SideGamePicks). В
        // живом журнале 30.08 01:43:25 рядом стояли «вдоль стены юг» и
        // «ladder-stick-north встал бы в меня самого» — две стороны в двух
        // строках подряд, и человек по ним чинил не то
        OnLog?.Invoke($"строю лестницу на {height} бл: опора есть (стена {side.Name}), " +
                      "щёлкаю по ней — тогда сторону перекладине игра возьмёт мою");

        int placed = 0;
        for (int up = 0; up < height && !ct.IsCancellationRequested; up++)
        {
            int y = startY + up;
            // Через одну: перекладина нужна не на каждом уровне
            bool needRung = NeedsRung(up, EveryOtherBlock);

            if (needRung && ctx.World.IsPassable(fx, y, fz))
            {
                var at = new BlockPos(fx, y, fz);
                // ЛЕСТНИЦА — ЛЕСА: её вешают, чтобы подняться, и в конце работы
                // снимают. Спрашиваем разрешение ДО установки — в чужой заявке
                // её не повесит и живой игрок
                var (may, whyNot) = ctx.Temp.MayPlace(at);
                if (!may)
                    return new BuildClimbResult(false, ClimbBuild.Failed, placed,
                        (int)Math.Floor(phys.Y) - startY,
                        $"перекладину на {y} ставить нельзя: {whyNot}");
                var result = await ctx.Mining.PlaceAsync(at, LadderCode,
                    ClickFaceForWall(side.Face), ct);
                if (!result.Success)
                    return new BuildClimbResult(false, ClimbBuild.Failed, placed,
                        (int)Math.Floor(phys.Y) - startY,
                        $"перекладина на {y} не встала: {result}");
                // Числим за собой ТОЛЬКО подтверждённое: список лесов, куда
                // попали не вставшие блоки, — это список мест, где бот потом
                // будет ломать пустоту.
                //
                // …И ТОЛЬКО ЛЕСА, а не всякую перекладину: разбор двух случаев —
                // у ClimbKeep, живая жалоба заказчика там же
                if (keep == ClimbKeep.Scaffold)
                    ctx.Temp.Note(at, LadderCode, ЛесаСтройки, $"лестница наверх на {height} бл");
                placed++;
            }

            // И сразу лезем на поставленное: строить выше с земли не выйдет —
            // руки не достанут
            if (!await ClimbOneAsync(phys, y + 1, ct))
                return new BuildClimbResult(false, ClimbBuild.Failed, placed,
                    (int)Math.Floor(phys.Y) - startY, $"не поднялся на {y + 1}");
        }

        var done = LadderVerdict(placed, (int)Math.Floor(phys.Y) - startY, height,
            ct.IsCancellationRequested);
        OnLog?.Invoke(done.ToString());
        return done;
    }

    /// <summary>
    /// Нужна ли перекладина на этом уровне подъёма. Правило одно: игроки
    /// ставят лестницы через блок, тело всё равно касается перекладины, а
    /// материала уходит вдвое меньше.
    /// </summary>
    public static bool NeedsRung(int up, bool everyOtherBlock) =>
        !everyOtherBlock || up % 2 == 0;

    /// <summary>Сколько перекладин уйдёт на подъём такой высоты.</summary>
    public static int RungsFor(int height, bool everyOtherBlock)
    {
        int n = 0;
        for (int up = 0; up < height; up++)
            if (NeedsRung(up, everyOtherBlock))
                n++;
        return n;
    }

    /// <summary>
    /// ЧЕМ КОНЧИЛАСЬ ЛЕСТНИЦА — по ФАКТУ подъёма, а не по намерению.
    ///
    /// Находка приёмки: успехом считалось «поднялся хоть на блок». Цикл
    /// постройки выходит и по отмене, и тогда наружу шло «построил лестницу
    /// 1 бл, поднялся на 1» с Success=true. Движение по этому Success решало,
    /// что бот выбрался из ямы, обнуляло счёт маршрутов и строило дорогу
    /// заново со дна — по журналу это выглядело как «выбрался и всё равно
    /// не идёт».
    /// </summary>
    public static BuildClimbResult LadderVerdict(int placed, int climbed, int height,
        bool cancelled)
    {
        if (climbed >= height)
            return new BuildClimbResult(true, ClimbBuild.Ladder, placed, climbed, "");
        return new BuildClimbResult(false, ClimbBuild.Failed, placed, climbed,
            $"лестница подняла на {climbed} из {height} бл" +
            (cancelled ? " — отменили" : " (перекладины кончились или не влез)"));
    }

    /// <summary>
    /// ЕСТЬ ЛИ ВООБЩЕ СТЕНА, К КОТОРОЙ КРЕПИТЬ ЛЕСТНИЦУ НА ВСЮ ВЫСОТУ ПОДЪЁМА.
    ///
    /// ГРАНЬ ОТСЮДА — ЭТО И ЕСТЬ ВЫБОР СТОРОНЫ, И ТАК БЫЛО НЕ ВСЕГДА. Здесь
    /// стояло «сторону перекладине выбирает САМ СЕРВЕР, и наш ответ до него не
    /// доходит вовсе; грань отсюда идёт установке лишь запасным ответом». Это
    /// верно ровно наполовину — и на той половине, где бот и застревал.
    ///
    /// ПРАВИЛО ИГРЫ ЦЕЛИКОМ (<c>BlockBehaviorLadder.TryPlaceBlock</c>,
    /// VSSurvivalMod 1.22.7): щёлкнули по ВЕРТИКАЛЬНОЙ грани (пол, потолок) —
    /// сторону сервер берёт сам, дальнюю от тела
    /// (<see cref="Mining.SideGamePicks"/> = <c>Block.SuggestedHVOrientation</c>);
    /// щёлкнули по БОКОВОЙ — сторона равна <c>Face.Opposite</c>, то есть нашей.
    /// А держится перекладина (<c>HasSupport</c>) прежде всего за твердь СО
    /// СТОРОНЫ СВОЕЙ ГРАНИ. Стало быть, стену надо не только НАЙТИ, но и
    /// ЩЁЛКНУТЬ ПО НЕЙ — иначе сторона выйдет случайной, держаться будет не за
    /// что, и сервер молча откажет («cantattachladder»). Живой журнал 01.09 и
    /// разбор — в <see cref="Mining.PlaceAsync"/>.
    ///
    /// Грань в саму установку идёт через <see cref="ClickFaceForWall"/>.
    ///
    /// ЖИВОЙ СЛУЧАЙ, КОТОРЫМ ЭТО И ВЫЯСНИЛОСЬ (мой стенд 30.08, 01:43:25; бот
    /// на дне ямы 1×1 глубиной 3, в сумке ladder-stick-north ×6 — ровно то,
    /// чего ему не хватало по жалобе заказчика 29.08):
    ///   «[стройка] лестниц 6 — хватит на 12 бл»
    ///   «[стройка] строю лестницу на 3 бл вдоль стены юг»
    ///   «[добыча] ladder в (-42, 108, -55): ladder-stick-north встал бы в меня
    ///    самого — пробую ещё раз (1 из 3)»
    ///   «[движение] с (-42, 108, -55) не сойти: в радиусе 2 нет ни одного
    ///    места, где можно встать»
    ///   «[стройка] этот приём отсюда не поднял ни на блок — вычёркиваю его»
    /// Две стороны в двух строках подряд — «юг» от нас и «north» от заставы, —
    /// и ни одного пакета на сервер: отказ был наш собственный.
    ///
    /// ПОЧИНЕНО НЕ ЗДЕСЬ, И ЭТО ГЛАВНОЕ. Выбором стены такое не лечится: я
    /// пробовал брать дальнюю стену — живьём сторона сменилась с «север» на
    /// «юг», а отказ остался тот же, потому что застава смотрела не на стену, а
    /// на КОРОБКУ БЛОКА ИЗ РУКИ. Чинилось это там, где и стояло:
    /// <see cref="Mining.CodeThatWillStand"/> спрашивает у правила игры, какая
    /// разновидность встанет на самом деле, и застава меряет уже её.
    /// </summary>
    private (string Name, int Face)? WallSide(int x, int y, int z, int height)
    {
        // Грани в игре: 0 север (-Z), 1 восток (+X), 2 юг (+Z), 3 запад (-X)
        var sides = new (string Name, int Face, int Dx, int Dz)[]
        {
            ("север", 0, 0, -1), ("восток", 1, 1, 0),
            ("юг", 2, 0, 1), ("запад", 3, -1, 0)
        };
        foreach (var (name, face, dx, dz) in sides)
        {
            bool solidAll = true;
            for (int up = 0; up < height; up++)
                if (!ctx.World.IsSolid(x + dx, y + up, z + dz))
                {
                    solidAll = false;
                    break;
                }
            if (solidAll)
                return (name, face);
        }
        return null;
    }

    /// <summary>
    /// ПО КАКОЙ ГРАНИ ЩЁЛКНУТЬ, ЧТОБЫ ПЕРЕКЛАДИНА ПРИЖАЛАСЬ К ЭТОЙ СТЕНЕ, —
    /// чистое правило, и оно ОБРАТНОЕ правилу игры.
    ///
    /// Игра при клике по боковой грани ставит блок стороной
    /// <c>blockSel.Face.Opposite</c> (<c>BlockBehaviorLadder.TryPlaceBlock</c>).
    /// Значит, чтобы получить сторону «юг», щёлкнуть надо гранью «север» — то
    /// есть по самой южной стене, в её северное лицо. Ровно так это и делает
    /// живой игрок: наводится на стену и вешает лестницу на неё.
    ///
    /// Грани игры: 0 север (−Z), 1 восток (+X), 2 юг (+Z), 3 запад (−X), и
    /// противоположная — через две.
    /// </summary>
    /// <param name="wallFace">Грань-направление НА стену (как её отдаёт WallSide).</param>
    public static int ClickFaceForWall(int wallFace) => (wallFace + 2) % 4;

    /// <summary>Подняться на одну ступень по уже поставленной лестнице.</summary>
    private async Task<bool> ClimbOneAsync(BotGamePhysics.GamePlayerPhysics phys, int toY,
        CancellationToken ct)
    {
        var until = DateTime.UtcNow.AddSeconds(StepSeconds);
        while (DateTime.UtcNow < until && !ct.IsCancellationRequested)
        {
            if (phys.Y >= toY - 0.05)
                return true;
            // На лестнице прыжок означает «лезть вверх» — это правило игры,
            // проверено живьём
            phys.Controls.Jump = true;
            await Task.Delay(50, ct).ContinueWith(_ => { });
        }
        phys.Controls.Jump = false;
        return phys.Y >= toY - 0.05;
    }

    /// <summary>
    /// ИМЕНА РУЧЕК РОЛИ, КОТОРЫМИ ЧЕЛОВЕК ВКЛЮЧАЕТ И ВЫКЛЮЧАЕТ «ЗАПЕРТЫЙ
    /// КОПАЕТ», — строками, а не через <c>nameof</c>: сами ручки живут в роли
    /// (SurvivorRole.ВыбиратьсяНаверх, SurvivorRole.ДобыватьМатериалНаСтолб) и в
    /// шести пресетах, а библиотека про роли не знает и знать не должна.
    ///
    /// Нужны они ОТКАЗУ. Молчаливое «выхода нет» и «порода не берётся» при
    /// стальной кирке в руке человек читает как поломку бота, а не как свой
    /// выбор, — и чинит не то. Тот же приём стоит рядом, у заставы
    /// (<see cref="BreakGuard.РучкаБерегуДомИСклад"/>).
    ///
    /// ЗА ТЕМ, ЧТО ЭТА СТРОКА — НЕ ВЫДУМКА, СТЕРЕЖЁТ ОТДЕЛЬНЫЙ СТЕНД
    /// (<c>ИмяРучкиВОтказеНастоящееTests</c>), и заведён он по замечанию
    /// приёмки 31.08. Прежде эти имена сверялись только САМИ С СОБОЙ: стенды
    /// сравнивали отказ бота с этой же константой, так что переименуй кто-то
    /// свойство роли — обе стороны сравнения поехали бы вместе, набор остался
    /// бы зелёным, а бот звал бы человека повернуть ручку, которой в окне нет.
    /// Теперь строка сверяется с ЖИВЫМ списком ручек ролей — тем самым, что
    /// показывает окно (<c>RoleKnobs.Of</c>).
    /// </summary>
    public const string РучкаВыбиратьсяНаверх = "ВыбиратьсяНаверх";

    /// <inheritdoc cref="РучкаВыбиратьсяНаверх"/>
    public const string РучкаДобыватьМатериалНаСтолб = "ДобыватьМатериалНаСтолб";

    /// <summary>
    /// Рубить ли ступени в стене, прежде чем тратить лестницы и блоки, —
    /// то есть ВЫКАПЫВАТЬСЯ ЛИ ИЗ ЯМЫ. Выключает тот, кому нельзя портить
    /// стены вокруг. Ручка роли — <see cref="РучкаВыбиратьсяНаверх"/>.
    ///
    /// ВЫКЛЮЧАТЕЛЬ — НЕ ГРАНИЦА «ЧУЖОЕ НЕ ТРОГАЮ», и путать их нельзя. Чужое
    /// бережёт застава (<see cref="BreakGuard.MayBreak"/>) на каждом ударе, и
    /// она же не даст выломать дом хозяина ни при какой этой галочке. Эта
    /// решает другое: браться ли за кирку РАДИ СЕБЯ вообще.
    /// </summary>
    public bool CarveSteps { get; set; } = true;

    /// <summary>
    /// Добывать материал на столб ПРЯМО НА МЕСТЕ, когда сумки пусты.
    /// Выключает тот, кому нельзя копать вокруг (жилец, караванщик).
    /// Ручка роли — <see cref="РучкаДобыватьМатериалНаСтолб"/>.
    /// </summary>
    public bool MineForPillar { get; set; } = true;

    /// <summary>
    /// Сколько пустых ударов подряд терпим, добывая блоки на столб.
    ///
    /// Порог нужен из-за игрового правила: камень падает ОСКОЛКАМИ (stone-*),
    /// а это предмет, а не блок, и столбиться ими нельзя. Бот в каменной
    /// пещере мог бы долбить стену до предела времени и не получить ни одного
    /// годного блока — вместо этого он честно скажет, что тут не из чего.
    /// </summary>
    public int EmptyBreaksAllowed { get; set; } = 3;

    /// <summary>Клетка, в которой стоят ноги.</summary>
    private BlockPos? Feet => ctx.Self.Position is { } p
        ? new BlockPos((int)Math.Floor(p.X), (int)Math.Floor(p.Y), (int)Math.Floor(p.Z))
        : null;

    /// <summary>
    /// ДОБЫТЬ БЛОКИ НА СТОЛБ ТУТ ЖЕ, вокруг себя.
    ///
    /// Живой случай: «сейчас умер и застрял в пещере без инструментов, можно
    /// было бы определить где сломать блоки земли и вылезти, но он затупил и
    /// бегал». Бот возродился с пустыми сумками, и столб ему строить было не
    /// из чего — а вокруг лежала земля, которая в игре ломается голой рукой.
    ///
    /// ЧТО брать — спрашиваем у игры, а не у списка кодов: Mining.CanBreak
    /// знает по реестру сервера, возьмётся ли клетка тем, что сейчас есть
    /// (земля, гравий, песок и глина берутся рукой, камень — нет), а
    /// Mining.FastestSeconds говорит, сколько это займёт. Сначала бьём самое
    /// быстрое: на дне ямы каждая секунда — это ещё и голод, и мобы.
    ///
    /// ГОДНОСТЬ ПРОВЕРЯЕТСЯ ПО ФАКТУ, а не по намерению: считаем блоки в
    /// сумках до и после. Иначе осколки камня сошли бы за материал.
    ///
    /// Возвращает, на сколько прибавилось годных на столб блоков.
    /// </summary>
    public async Task<int> MineForPillarAsync(int want, CancellationToken ct = default)
    {
        if (!MineForPillar)
        {
            // Молчаливый ноль тут неотличим от «копал и не докопался», а это
            // разные новости: во втором случае вокруг нечего брать, в первом
            // боту ЗАПРЕЩЕНО брать. Жильцу и караванщику запрещают нарочно —
            // чтобы не разбирали чужую постройку на столб
            OnLog?.Invoke("на столб копать не буду: ломать блоки вокруг мне не велено " +
                          $"(ручка роли «{РучкаДобыватьМатериалНаСтолб}»)");
            return 0;
        }
        if (Feet is not { } at)
        {
            OnLog?.Invoke("копать на столб не могу — не знаю, где стою");
            return 0;
        }

        int had = ctx.Tunnel.SpareBlocks();
        if (had >= want)
            return 0;

        // Куда бить: стены вокруг на уровне ног и головы и пол СОСЕДНИХ
        // клеток. Свой пол не трогаем — провалимся ещё ниже; клетку над
        // головой тоже: её пробьёт сам столб, когда упрётся в потолок
        var around = new List<BlockPos>();
        foreach (var (dx, dz) in Tunnel.Sides)
        {
            around.Add(new BlockPos(at.X + dx, at.Y, at.Z + dz));
            around.Add(new BlockPos(at.X + dx, at.Y + 1, at.Z + dz));
            around.Add(new BlockPos(at.X + dx, at.Y - 1, at.Z + dz));
        }

        // ЧУЖУЮ ПОСТРОЙКУ НА СТОЛБ НЕ РАЗБИРАЮТ — И СПРАШИВАЕМ ДО УДАРА.
        //
        // Это ВТОРАЯ дорога к кирке ради выхода, и застава на ней была только
        // выключателем MineForPillar («ломать вокруг вообще нельзя»). Живой
        // случай тот же самый (ночь 18.08): бот не нашёл дороги к позвавшему,
        // полез наверх и вырубил стену дома заказчика. Ступени эту заставу
        // прошли бы (Tunnel.ClearAsync), а добыча блоков на столб — нет: она
        // бьёт напрямую Mining.BreakAsync. Значит дом уехал бы в столб.
        //
        // 23.08 это и случилось в третий раз: бот стоял В ДВЕРЯХ дома и
        // выломал себе на столб пол (soil-medium-normal) и стену
        // (rammed-light-plain) — застава была вызвана и ответила «можно»,
        // потому что игра зовёт утрамбованную землю материалом Soil.
        //
        // Второго решения тут не заводится: чей блок — знает BlockOwners, а
        // факты собирает общая застава (BreakGuard). Спрашиваем РАДИ ПРОХОДА
        // (BreakWhy.Way): столб — не наряд человека, а бот сам решил, что
        // иначе не выберется, и это ровно та «крайняя мера», про которую
        // заказчик написал трижды
        var spared = new List<string>();
        var order = around
            .Where(c => ctx.World.IsSolid(c.X, c.Y, c.Z) && ctx.Mining.CanBreak(c))
            .Where(c =>
            {
                var (may, whose) = ctx.Break.MayBreak(c, BreakWhy.Way);
                if (!may)
                    spared.Add($"{c}: {whose}");
                return may;
            })
            // СНАЧАЛА СВОЙ ЛЕС, И ТОЛЬКО ПОТОМ ЧУЖОЙ МИР. «Ломать крайняя
            // мера» — это и про порядок: подпорка, которую бот сам подложил
            // под ступень, стоит ровно тут же и в мире ничего не меняет, а
            // клетка земли — это дырка в чьём-то дворе навсегда. Внутри
            // каждой половины порядок прежний, по скорости: на дне ямы
            // секунда — это ещё и голод, и мобы
            .OrderBy(c => ctx.Temp?.Mine(c) == true ? 0 : 1)
            .ThenBy(c => ctx.Mining.FastestSeconds(c))
            .ToList();
        // Пощажённое называем вслух: «копал и не докопался» и «вокруг чужой
        // дом» — разные новости, и чинят их в разных местах
        foreach (string чьё in spared)
            OnLog?.Invoke($"на столб не трогаю {чьё}");
        if (order.Count == 0)
        {
            // ОТКАЗ НАЗЫВАЕТ РУЧКУ. Без имени настройки человек читает это как
            // поломку, а не как свой выбор, — правило 4 проекта
            OnLog?.Invoke(spared.Count > 0
                ? $"на столб копать нечего: всё годное вокруг ({spared.Count} кл.) — " +
                  "чужая постройка или двор хозяина, а их я не разбираю " +
                  $"(разрешают настройки «{nameof(LivingRole.ЛоматьЧужоеРадиВыхода)}» " +
                  $"и «{BreakGuard.РучкаБерегуДомИСклад}»)"
                : "на столб копать нечего: вокруг ничего не берётся тем, что есть " +
                  "(камень без кирки не взять, а земли рядом нет)");
            return 0;
        }

        // СЧИТАЕМ ДО ПЕРВОГО УДАРА, ХВАТИТ ЛИ ТОГО, ЧТО ВОКРУГ. Потолка этого
        // здесь не было вовсе (место названо приёмкой — Scaffolding.cs:426), и
        // копка начиналась ПЕРВОЙ: пока правило гадало, чем выходить, четыре
        // клетки чужой земли уже лежали в сумке.
        //
        // ЖИВОЙ ЗАМЕР ПРИЁМКИ 31.08, «!заберись 100 120 240» с ровного места:
        //   «блоков на столб нет — добываю на месте, годных клеток вокруг 4»
        //   «добыл на столб 3 бл»
        // Надо было девять. Ни один приём от трёх блоков не заводится (столб
        // просит блок на клетку, купленная ступень — тоже), и эти три блока не
        // могли ничем помочь ещё ДО первого удара: клеток вокруг всего четыре.
        // То есть четыре дырки в чужом дворе были выкопаны заведомо зря.
        //
        // МЕРКА — КЛЕТКИ, А НЕ БУДУЩАЯ ДОБЫЧА, и она нарочно скупая: с клетки
        // падает один блок, а из камня — осколки, то есть предмет, которым не
        // столбиться (см. EmptyBreaksAllowed). Значит «клеток вокруг» — это
        // потолок сверху, и если даже он не дотягивает, копать незачем.
        //
        // ЧЕГО ЭТОТ ПОТОЛОК НЕ ОТНИМАЕТ: выхода из ямы. Там вокруг стоит стена
        // и клеток вдесятеро больше нужного, а сам выход берётся ступенями
        // задолго до этой копки
        if (had + order.Count < want)
        {
            OnLog?.Invoke($"на столб копать не берусь: годных клеток вокруг {order.Count}, " +
                          $"с ними в сумках будет самое большее {had + order.Count} бл, " +
                          $"а на подъём надо {want} — столько мне тут не набрать, и " +
                          "рыть чужую землю впустую я не стану");
            return 0;
        }

        OnLog?.Invoke($"блоков на столб нет — добываю на месте, годных клеток вокруг {order.Count}");
        int empty = 0;
        foreach (var cell in order)
        {
            if (ct.IsCancellationRequested)
                break;
            if (ctx.Tunnel.SpareBlocks() >= want)
                break;
            if (ctx.World.IsPassable(cell.X, cell.Y, cell.Z))
                continue;   // осыпалось само, пока мы копали соседнюю

            string what = ctx.World.GetBlockCode(cell) ?? "порода";
            int was = ctx.Tunnel.SpareBlocks();
            var broke = await ctx.Mining.BreakAsync(cell, ct, why: BreakWhy.Way);
            if (!broke.Success)
            {
                OnLog?.Invoke($"{what} в {cell} не поддался: {broke}");
                continue;
            }
            // Выпавшее лежит на земле сущностью — само в сумку не прыгнет
            await ctx.Mining.CollectDropsAsync(4, 6, ct);

            if (ctx.Tunnel.SpareBlocks() > was)
            {
                empty = 0;
                continue;
            }
            if (++empty >= EmptyBreaksAllowed)
            {
                OnLog?.Invoke($"сломал {empty} клетки подряд, а на столб ничего не выпало " +
                              "(из камня падают осколки, а это предмет, им не столбиться) — " +
                              "тут материала нет");
                break;
            }
        }

        int got = ctx.Tunnel.SpareBlocks() - had;
        OnLog?.Invoke(got > 0
            ? $"добыл на столб {got} бл (надо было {want - had})"
            : "добыть на столб ничего не вышло");
        return got;
    }

    /// <summary>
    /// ВЫБРАТЬСЯ НАВЕРХ — ПО РАСЧЁТУ, А НЕ ПРОБОЙ.
    ///
    /// ЖИВОЙ СЛУЧАЙ, словами заказчика: «не нравится логика, он в начале
    /// пробует наживую, а не просчитывает что лучше и не выбирает самый
    /// оптимальный способ выбраться. Много лишних действий и подвисает при
    /// выборе другого действия». В журнале выход из ямы на 11 бл занял две с
    /// половиной минуты: бот брался за ступени, лестницу и столб ПО ОЧЕРЕДИ
    /// ТЕЛОМ, и каждый неудавшийся приём стоил секунд и целого шторма поиска
    /// пути. Правило при этом спрашивалось — и тут же выбрасывалось.
    ///
    /// ТЕПЕРЬ ПРАВИЛО РЕШАЕТ, а тело только исполняет:
    /// 1. считаем силы по карте мира (<see cref="Tunnel.ChooseWayOut"/>) —
    ///    лестницы, блоки, берётся ли порода, есть ли стена;
    /// 2. делаем РОВНО ТО, что правило назвало, и ничего сверх;
    /// 3. приём, который не сдвинул ни на блок, вычёркиваем и СЧИТАЕМ ЗАНОВО —
    ///    но не перебираем оставшиеся телом «а вдруг»;
    /// 4. правило сказало «нечем» — отказ СРАЗУ, с числами, без единого удара.
    ///
    /// Порядок приёмов по-прежнему за правилом, и он по возрастанию цены:
    /// ступени в стене — даром, лестница — из сумки, столб — из блоков. Это
    /// ответ на прежний живой случай: бот сидел на дне собственной шахты под
    /// сплошным андезитом и девять раз отвечал «выбраться не вышло», а заказчик
    /// возразил по делу — «выход всегда возможен лесенкой».
    ///
    /// ЭТО ЕДИНСТВЕННЫЙ ВЫХОД НАВЕРХ ВО ВСЁМ ПРОЕКТЕ. Второй копией был подъём
    /// к цели (<see cref="Climbing.ClimbToAsync"/>): он звал столб напрямую и
    /// потому не знал ни про лестницу в сумке, ни про кирку в руке. Живой
    /// журнал 29.08, 23:41:10 — «столб вырос на 0 из 4 бл» при двадцати
    /// четырёх лестницах. Теперь оба спрашивают здесь.
    /// </summary>
    /// <param name="blockCode">
    /// Чем столбиться, если правило выберет столб; пусто — любым подходящим
    /// блоком из сумок. Ступеней и лестницы это не касается: первые рубятся
    /// тем, что в руке, вторая берётся своя (<see cref="LadderCode"/>).
    /// </param>
    /// <param name="keep">
    /// ДОРОГА ЭТО ИЛИ ЛЕСА (<see cref="ClimbKeep"/>) — довод звавшего, потому
    /// что знает про это только он. Умолчание «дорога»: сюда заходят прежде
    /// всего те, кто ВЫБИРАЕТСЯ (движение из ямы, карьер, рудокоп), а лишний
    /// блок в мире дешевле запертого бота.
    /// </param>
    public async Task<BuildClimbResult> GetOutAsync(int height, CancellationToken ct = default,
        string blockCode = "", ClimbKeep keep = ClimbKeep.Road)
    {
        if (height <= 0)
            return new BuildClimbResult(true, ClimbBuild.NotNeeded, 0, 0, "");
        if (ctx.Body?.Physics is not { } phys)
            return new BuildClimbResult(false, ClimbBuild.Failed, 0, 0, "тело не на физике");

        int left = height, climbed = 0, placed = 0;
        string why = "";
        // ПРИЁМ, КОТОРЫЙ ОТСЮДА НЕ СДВИНУЛ, ВЫЧЁРКИВАЕТСЯ И БОЛЬШЕ НЕ СЧИТАЕТСЯ.
        // Счёт этот держит один на весь проект механизм (см. TriedWays): то же
        // правило спасает и выход из укрытия после бури, где без него бот
        // долбил стену пять тысяч раз подряд. Круг либо поднимает хоть на блок,
        // либо навсегда вычёркивает приём; приёмов три да одна докопка — больше
        // четырёх пустых кругов взяться неоткуда
        var ways = new TriedWays<WayOut>(allowance: 3, empty: "не поднял ни на блок");
        bool digged = false;

        while (left > 0 && ways.MayTry && !ct.IsCancellationRequested)
        {
            var (how, plan) = PlanWayOut(left, ways.Lost);
            why = plan;
            OnLog?.Invoke($"наверх на {left} бл: {plan}");

            if (how == WayOut.None)
                break;

            if (how == WayOut.Trapped)
            {
                // ПУСТЫЕ СУМКИ — НЕ ПРИГОВОР: живой игрок на дне ямы копает
                // землю вокруг себя и столбится ею. Ровно об этом и просил
                // заказчик после смерти без инструментов. Но копаем ОДИН раз и
                // только когда без блоков выхода нет вовсе — иначе это и есть
                // те «лишние действия», на которые он жаловался
                if (!digged && MineForPillar && ctx.Tunnel.SpareBlocks() < left)
                {
                    digged = true;
                    ways.SpentRound();
                    if (await MineForPillarAsync(left, ct) > 0)
                        continue;   // запасы переменились — правило спросим заново
                }
                break;
            }

            // ЭТО МЕРКА ПРИБЫТКА, А НЕ ЗАДАНИЕ ЛЕСЕНКЕ. Отсюда меряется, на
            // сколько блоков приём и правда поднял тело, — по игровой физике и
            // стоя (ниже, у ways.Note). Заданием эта высота быть не может:
            // физика и своя модель мира ходят по разным часам, и перевод
            // «на 2 бл» → «до уровня N» одними часами с обратным переводом
            // другими и стоил заказчику живого случая 23:54 (см. ClimbOutByAsync)
            int wasY = (int)Math.Floor(phys.Y + 0.01);
            switch (how)
            {
                case WayOut.Steps:
                {
                    // Ступени вырубаем на ВСЮ нужную высоту: порог выгоды выше
                    // уже сработал, здесь он только помешал бы довести начатое.
                    //
                    // ПРОСИМ «НА N БЛОКОВ», А НЕ «ДО УРОВНЯ N»: уровень лесенка
                    // сочтёт сама, от той же клетки ног, которой она меряет
                    // каждую ступень. Живой случай — в Tunnel.ClimbOutByAsync
                    var report = await ctx.Tunnel.ClimbOutByAsync(left, ct, left);
                    placed += report.Placed;   // подложенные под ступени опоры — тоже расход
                    if (!report.Success)
                        OnLog?.Invoke($"ступенями: {report.Reason}");
                    break;
                }
                case WayOut.Ladder:
                {
                    var byLadder = await LadderUpAsync(left, ct, keep);
                    placed += byLadder.Placed;
                    if (!byLadder.Success)
                        OnLog?.Invoke($"лестницей: {byLadder.Why}");
                    break;
                }
                case WayOut.Pillar:
                    placed += await ctx.Mining.PillarUpAsync(left, blockCode, ct, keep);
                    break;
            }

            // МЕРЯЕМ ПО ФАКТУ — по своей высоте, а не по тому, что ответил приём.
            // Живой урок склада: успех считали по намерению, и «легло 112 шт.»
            // приходило при пустом сундуке.
            //
            // И МЕРЯЕМ СТОЯ. Живой случай 20:36:34: высоту спросили в прыжке,
            // получили «взял 2 из 2 бл», доложили наружу успех — а тело в тот
            // же миг падало обратно на прежний уровень. Прыжок тянет на 1,27 бл,
            // и в полёте всякая мерка высоты врёт (см. Movement.WaitUntilStandingAsync)
            await ctx.Movement.WaitUntilStandingAsync(ct);
            int went = (int)Math.Floor(phys.Y + 0.01) - wasY;
            if (!ways.Note(how, went))
            {
                OnLog?.Invoke(ways.SayCrossedOut());
                // ПРИЁМ УШЁЛ — ПУСТЬ УБЕРЁТ ЗА СОБОЙ. Живой случай 12:53:13:
                // лестница не подняла ни на блок, но перекладину в клетку ног
                // повесить успела — и следующий же приём получил «столбиться
                // нельзя: клетка занята (ladder-wood-acacia-north)», а за ним и
                // ступени встали, потому что на лестнице тело не прыгает.
                // Один неудавшийся приём отнимал у бота все остальные
                if (Feet is { } stand)
                    // КЛЕТКИ ТЕЛА МЕРЯЮТСЯ РОСТОМ ТЕЛА, А НЕ ВЫСОТОЙ ХОДА.
                    // Здесь стояло ctx.Tunnel.Height — высота ШТОЛЬНИ, число
                    // из окна хозяина, и ручка сама зовёт поставить пятёрку.
                    // Замерено: при пятёрке — 25 клеток, верх «ноги+4». То есть
                    // бот выдёргивал собственные перекладины на три ряда ВЫШЕ
                    // МАКУШКИ — ровно те, по которым и лез бы следующей
                    // попыткой. Правило одно и живёт у штольни, а высоты у него
                    // больше нет параметром: подставить сюда ручку не из чего,
                    // и прежняя строка теперь не собирается (см. Tunnel.BodyCells)
                    await ctx.Temp.PullInTheWayAsync(
                        Tunnel.BodyCells(stand),
                        $"{ЧтоЗаПриём(how)} не подняла и оставила свой блок под ногами", ct);
                continue;
            }
            climbed += went;
            left -= went;
            if (left > 0)
                OnLog?.Invoke($"поднялся на {went} бл, до верха ещё {left} — добираю");
        }

        if (left <= 0)
            return new BuildClimbResult(true, WayBuilt(ways.Dominant(WayOut.None)), placed, climbed, "");

        // ОТКАЗ НАЗЫВАЕТ, ЧЕГО НЕ ХВАТИЛО. «Не вышло» без чисел в журнале не
        // разбирается никак — на этом и погорел прошлый заход
        string failed = $"до верха ещё {left} из {height} бл" +
                        (climbed > 0 ? $" (поднялся на {climbed})" : "") + $": {why}";
        OnLog?.Invoke(failed);
        return new BuildClimbResult(false, ClimbBuild.Failed, placed, climbed, failed);
    }

    /// <summary>
    /// ВЫБРАТЬСЯ ИЗ СВОЕЙ ЖЕ ВЫРАБОТКИ ДО НУЖНОЙ ВЫСОТЫ — ОДНО МЕСТО НА ВСЕХ,
    /// КТО ЗАКАПЫВАЕТСЯ.
    ///
    /// ПОЧЕМУ ЭТО ПЕРЕЕХАЛО СЮДА. Копий было две — <c>Quarry.ClimbOutToAsync</c>
    /// и <c>Ores.ClimbOutToAsync</c>. Совпадали они всем: заставой, порогом
    /// «меньше двух блоков — запрыгну сам», зовом <see cref="GetOutAsync"/> и
    /// правилом успеха; расходились только словами в журнал («со дна карьера до
    /// края N бл» против «нужное на N бл выше»). Двойной механикой их назвали
    /// три волны подряд и три волны подряд не сводили. Разъехаться им было
    /// куда, и цена расхождения не словесная: правило успеха тут НЕ «приём
    /// доложил успех», а «ноги правда поднялись», — почини это в одной копии, и
    /// вторая продолжала бы врать.
    ///
    /// ПОРОГ «МЕНЬШЕ ДВУХ — НЕ СТРОЮ». На один блок живой игрок запрыгивает
    /// сам; лестница и столб ради него — это потраченная лестница и потерянные
    /// секунды.
    ///
    /// УСПЕХ — ПО ФАКТУ ПОДЪЁМА, А НЕ ПО СЛОВУ ПРИЁМА. <see cref="GetOutAsync"/>
    /// докладывает неудачу и тогда, когда поднял на часть высоты: с такого
    /// места работа продолжается, и звать это провалом — врать в другую
    /// сторону.
    /// </summary>
    /// <param name="wantedY">Высота, до которой надо подняться.</param>
    /// <param name="feet">
    /// Чем спросить клетку ног — и до подъёма, и после. Спрашивается ИМЕННО
    /// меркой звавшего: мерок «где мои ноги» в дереве больше десятка и они
    /// РАЗНЫЕ (голый <c>floor(Y)</c> у рудокопа против
    /// <see cref="WorldModel.StandingCellAt"/> у карьера). Свести их — отдельная
    /// работа; подставить здесь свою значило бы тихо сменить поведение обоим
    /// звавшим заодно со сведением копий.
    /// </param>
    /// <param name="announce">
    /// Сказать про подъём, когда число блоков уже известно, а работа ещё не
    /// начата: у карьера, у рудокопа и у подъёма к цели это разные слова про
    /// одно и то же, и отнимать их у них незачем.
    /// </param>
    /// <param name="blockCode">
    /// Чем столбиться, если правило выберет столб; пусто — любым подходящим
    /// блоком из сумок. Спрашивает это только человек напрямую («!заберись
    /// … <c>чем</c>») и ИИ-надстройка; карьеру и рудокопу назвать блок нечем,
    /// и они его не называют.
    /// </param>
    /// <returns>
    /// <c>Up</c> — поднялись ли на самом деле; <c>Need</c> — на сколько блоков
    /// было нужно; <c>Why</c> — что доложил сам подъём (пусто, если строить не
    /// понадобилось вовсе).
    /// </returns>
    /// <param name="keep">
    /// ДОРОГА ЭТО ИЛИ ЛЕСА (<see cref="ClimbKeep"/>). Умолчание «дорога»:
    /// отсюда выбираются карьер и рудокоп — из СВОЕЙ ЖЕ ВЫРАБОТКИ, — и
    /// построенное ими есть выход из неё.
    /// </param>
    public async Task<(bool Up, int Need, string Why)> ClimbOutToAsync(int wantedY,
        Func<BlockPos?> feet, CancellationToken ct = default, Action<int>? announce = null,
        string blockCode = "", ClimbKeep keep = ClimbKeep.Road)
    {
        if (feet() is not { } here)
            return (false, 0, "");

        int need = wantedY - here.Y;
        if (need < 2)
            return (false, need, "");   // на один блок бот запрыгнет сам

        announce?.Invoke(need);
        var got = await GetOutAsync(need, ct, blockCode, keep);
        return (got.Success || (feet() is { } now && now.Y > here.Y), need, got.ToString());
    }

    /// <summary>
    /// Ничего ещё не пробовали — вычёркивать нечего. Отдельным полем, чтобы
    /// бумажный вопрос (<see cref="WayBack"/>) не плодил пустое множество на
    /// каждый спуск: спрашивают его в цикле поиска пути.
    /// </summary>
    private static readonly IReadOnlySet<WayOut> НичегоНеВычеркнуто =
        new HashSet<WayOut>();

    /// <summary>
    /// ЧЕМ Я ПОДНИМУСЬ ОБРАТНО НА <paramref name="height"/> БЛОКОВ — ТОТ ЖЕ
    /// ВОПРОС, ЧТО И У ВЫХОДА, НО НА БУМАГЕ: до единого удара киркой.
    ///
    /// Это половина шва, которую движение зовёт через
    /// <see cref="Movement.WayBackUp"/>, чтобы решить, спускаться ли
    /// (<see cref="Movement.MayGoDown"/>). Вторая половина — подключение в
    /// <c>VsBot</c>, рядом со строкой, которой подключён сам подъём.
    ///
    /// ЖИВАЯ БЕДА, РАДИ КОТОРОЙ ЗАВЕДЕНО. Крючок <c>Movement.WayBackUp</c>
    /// существовал, его док-строка обещала подключение «к Scaffolding.WayBack»,
    /// а ТАКОГО ЧЛЕНА В ПРОЕКТЕ НЕ БЫЛО ВОВСЕ. Все четыре живых звонящих
    /// уходили в ветку «спросить некому» и печатали «вниз иду не спросясь:
    /// подъём обратно посчитать некому» — то есть вопрос «а выберусь ли я
    /// обратно» ЖИВЬЁМ НЕ ЗАДАВАЛСЯ НИ РАЗУ. Стенд был зелен потому, что
    /// подключал крючок сам.
    ///
    /// ВТОРОГО СЧЁТА ТУТ НЕТ: ответ даёт ровно тот же <see cref="PlanWayOut"/>,
    /// которым выход и делается. Разница одна — <b>ничего не вычеркнуто</b>:
    /// вычеркнутое копится ВНУТРИ одного похода наверх (см. <c>TriedWays</c> в
    /// <see cref="GetOutAsync"/>), а спрашивают нас ДО спуска, когда никакого
    /// похода ещё не было.
    /// </summary>
    public (WayOut How, string Why) WayBack(int height) =>
        height <= 0
            ? (WayOut.None, "подниматься не на что")
            : PlanWayOut(height, НичегоНеВычеркнуто);

    /// <summary>
    /// ЧЕМ ВЫХОДИТЬ ОТСЮДА ПРЯМО СЕЙЧАС: собрать запасы и мир в числа и спросить
    /// правило. Мирская половина <see cref="WayOutPlan"/> — и место, где
    /// вычеркнутый приём перестаёт учитываться. Ни одного решения тут нет:
    /// всё, что решает, живёт в чистой половине и стережётся тестами.
    /// </summary>
    /// <param name="lost">Приёмы, которые отсюда уже не сдвинули ни на блок.</param>
    private (WayOut How, string Why) PlanWayOut(int height, IReadOnlySet<WayOut> lost)
    {
        // ЧИСЛА ЗДЕСЬ — НАСТОЯЩИЕ, ВСЕГДА.
        //
        // Живой случай (журнал 16.08, 20:36:39). Вычеркнутый приём обнулялся
        // прямо тут — «блоков 0», «лестниц 0», — и отказ выходил такой:
        // «столбом — годных под столб блоков 0, а надо 2 … (в сумках на самом
        // деле блоков 16)». Человек видит в одной строке ноль и шестнадцать и
        // читает это как враньё; и он прав — приём выбыл не из-за запасов.
        // Вычеркнутое теперь называется вычеркнутым (см. Tunnel.ChooseWayOut,
        // поле crossed), а числа остаются теми, что в сумках
        int ladders = ctx.Hands.CountOf(LadderCode);
        int blocks = ctx.Tunnel.SpareBlocks();
        // Порода «берётся» — это не только «ломается», но и «до неё дотянуться»
        // и «встав на неё, подняться»: ступени, до которых не достаёт рука или
        // которые не дают высоты, — не выход, а потерянные секунды.
        //
        // …И ЕСТЬ ЛИ ВО ЧТО РУБИТЬ. ЭТО ВТОРОЙ ВОПРОС, И ЗДЕСЬ ЕГО НЕ ЗАДАВАЛИ
        // ВОВСЕ — ровно та строка, которую назвала приёмка (Scaffolding.cs:738).
        //
        // Разница между вопросами живая. <c>CanCarveOut</c> отвечает «СДЕЛАЕТСЯ
        // ЛИ ступень отсюда» и честно говорит «да» там, где опоры под будущей
        // ступенью нет, зато в сумке лежит блок: живой игрок кладёт его и
        // всходит (StepsOverEmptinessTests, отнимать это нельзя). А
        // <c>SomethingToCarveNear</c> отвечает «ЕСТЬ ЛИ ВО ЧТО РУБИТЬ», и на
        // ровном месте под открытым небом ответы расходятся.
        //
        // ЖИВОЙ ЗАМЕР ПРИЁМКИ 31.08, «!заберись 100 120 240» с ровной земли:
        //   «блоков на столб нет — добываю на месте, годных клеток вокруг 4»
        //   «добыл на столб 3 бл»
        //   «яма в 9 бл — выйду ступенями, ничего не тратя»
        //   «сделал 1 ступеней из 9, взял по высоте 0 из 9 бл»
        // Первый же вопрос отвечал «да» (три блока в сумке — опору подложат),
        // правило выбирало ступени как самый дешёвый приём — а лесенка на
        // ровном месте покупает КАЖДУЮ опору своим блоком, то есть это столб,
        // только вбок. Сорок три секунды и четыре клетки чужой земли в мусор.
        //
        // Спрашиваем ОБА вопроса здесь, а не в лесенке: тут выбирают приём, и
        // отменять уже выбранное её отказом — это и есть те «лишние действия»,
        // на которые жаловался заказчик. Своего ответа тут нет, оба даёт мир
        //
        // …И СПРАШИВАЕМ ЭТО ТОЛЬКО У ТОГО, КОМУ РУБИТЬ ВЕЛЕНО. Осмотр стоит
        // 405 опросов мира (рука 4 бл: 9 на 9 клеток вокруг и 5 по высоте), а
        // при снятой ручке он выбрасывался целиком — строкой ниже про стену
        // написано ровно обратное правило, и оно тут старше. Ответ `есть`
        // читают только там, где CarveSteps уже true (отказ роли называется
        // первым и своими словами), так что порядок слагаемых ничего не меняет
        // В ОТВЕТЕ, — и ровно потому его нельзя было оставить на честном слове.
        //
        // ПОРЯДОК ЭТИХ ДВУХ СЛОВ СТЕРЕЖЁТ ЗапретРолиСтаршеОсмотраМираTests: он
        // читает эту самую строку и краснеет на перестановке. Приёмка 31.08 её
        // и делала — все 203 стенда вокруг остались зелены, потому что лишние
        // 405 опросов мира не видны ни в отчёте, ни в ударах, а только во
        // времени
        bool есть = CarveSteps && ctx.Tunnel.SomethingToCarveNear();
        bool carve = есть && ctx.Tunnel.CanCarveOut();
        // Стену щупаем, только если есть чем её занять: лишний осмотр мира —
        // это те самые лишние действия
        bool wall = ladders > 0 && WallHere(height);

        // ЗАПРЕТ РОЛИ — ЭТО НЕ ПОМЕХА В МИРЕ, И НАЗЫВАТЬ ЕГО ПОРОДОЙ НЕЛЬЗЯ.
        //
        // Здесь стояло `carve ? null : ctx.Tunnel.WhyNoStepsOut()` — то есть
        // человеку с выключенной ручкой бот объяснял отказ УСТРОЙСТВОМ МИРА:
        // «порода вокруг не берётся тем, что в руках». Вокруг при этом мог
        // стоять андезит, а в руке — стальная кирка, которой бот минуту назад
        // этот андезит и ломал (живой журнал 29.08, 23:39–23:41). Человек
        // читает такое как поломку и несёт боту вторую кирку, а повернуть надо
        // было ручку. Отказ обязан называть ЕЁ ИМЯ — это правило 4 проекта
        //
        // И «РУБИТЬ НЕ ВО ЧТО» НАЗЫВАЕТСЯ ПЕРВЫМ, ПОТОМУ ЧТО ОНО СТАРШЕ ВСЕХ
        // ПРОЧИХ ПРИЧИН. Спроси тут одного лишь соседа (WhyNoStepsOut), и на
        // ровном месте с блоком в сумке он ответил бы ОБЕЩАНИЕМ — «готовой
        // опоры под ступенью нет, подложу блок из сумки и встану на него», — а
        // стоит это обещание внутри ОТКАЗА: человек читает, что бот и мог бы, и
        // не стал. Слова берутся у лесенки (Tunnel.РубитьНеВоЧто), чтобы выбор
        // приёма и сама лесенка не объясняли одну ровную землю по-разному
        string? stepsWhy = !CarveSteps
            ? $"рубить ступени мне не велено (ручка роли «{РучкаВыбиратьсяНаверх}»)"
            : carve ? null
            : !есть ? Tunnel.РубитьНеВоЧто
            : ctx.Tunnel.WhyNoStepsOut();

        // ОТКАЗ НАЗЫВАЕТ СВОЮ ПРИЧИНУ, А НЕ ЧУЖУЮ. «Ступени не берутся» бывает
        // от породы, от недосягаемости и — с 20:36:36 — от ровного места вокруг;
        // спрашиваем у того, кто и выбирает сторону ступени
        var (how, why) = WayOutPlan(height, ladders, blocks, carve, wall,
            ctx.Tunnel.StepsOutMaxDepth, lost, stepsWhy);

        // И ВТОРАЯ РУЧКА, БЕЗ КОТОРОЙ ОТКАЗ ПОСЫЛАЕТ ЧЕЛОВЕКА НЕ ТУДА.
        // «Годных под столб блоков 0, а надо 4» человек читает как «принеси
        // блоков» — а бот мог бы накопать их сам, вокруг себя
        // (<see cref="MineForPillarAsync"/>), и не копает не потому, что нечего,
        // а потому что не велено. Говорим это ровно тогда, когда это и есть
        // недостающее звено: выхода нет и блоков не хватает
        if (how == WayOut.Trapped && !MineForPillar && blocks < height)
            why += $"; добывать материал на столб мне не велено " +
                   $"(ручка роли «{РучкаДобыватьМатериалНаСтолб}»)";

        // ЧТО УЖЕ ВЫЧЕРКНУТО — ВСЛУХ. Без этой строки человек не понимает,
        // почему бот не берётся за самый дешёвый приём, который сам же назвал
        if (lost.Count > 0)
            why += "; вычеркнуто отсюда: " + string.Join(", ", lost.Select(ЧтоЗаПриём));

        // ЧТО ЛЕЖИТ В СУМКАХ, НО ПОД НОГИ НЕ ПОЙДЁТ, — ТОЖЕ ВСЛУХ.
        //
        // Живой случай 12:54:47: «блоков под столб 0» при трёх с лишним сотнях
        // stonepath-free в сумках. Ноль тут честный — дорожное полотно бот под
        // ноги больше не кладёт (Mining.SpareFits), — но человек, читающий одно
        // «0», пойдёт носить боту блоки, которых у него полны сумки
        var idle = ctx.Mining.SpareRejected().OrderByDescending(t => t.Count).Take(3).ToList();
        if (idle.Count > 0)
            why += "; под ноги не кладу: " +
                   string.Join(", ", idle.Select(t => $"{t.Code} ×{t.Count} ({t.Why})"));
        return (how, why);
    }

    /// <summary>Как назвать приём человеку — словом, а не именем из кода.</summary>
    private static string ЧтоЗаПриём(WayOut how) => how switch
    {
        WayOut.Steps => "ступени",
        WayOut.Ladder => "лестница",
        WayOut.Pillar => "столб",
        _ => how.ToString()
    };

    /// <summary>
    /// ЧЕМ ВЫХОДИТЬ — ЧИСТОЕ ПРАВИЛО: числа на вход, приём и причина на выход.
    /// Половина без мира и без тела, и потому проверяемая на стенде.
    ///
    /// ЗАЧЕМ ОТДЕЛЬНО ОТ <see cref="Tunnel.ChooseWayOut"/>. Между «что вокруг»
    /// и «чем выходить» есть ещё один шаг — ПОРОГ ВЫГОДЫ СТУПЕНЕЙ, и врал
    /// именно он. Здесь стояло <c>stepsMaxDepth: height</c>, то есть «ступени
    /// выгодны на любой глубине», и первая же ветка правила отвечала «выйду
    /// ступенями» ВСЕГДА — даже когда в сумке лежало шесть лестниц, а рядом
    /// стояла готовая стена. Ровно это и видно в журнале заказчика: выход
    /// на 11 бл вырубался ступенями две с половиной минуты вместо десяти
    /// секунд с лестницей. Само чистое правило было при этом верным — врал
    /// вызывающий, и стеречь надо было ЕГО.
    ///
    /// ВЫХОД ЭТИМ ПОРОГОМ НЕ ОТНИМАЕТСЯ. «Выход всегда возможен лесенкой»
    /// держит не он, а последний довод <see cref="Tunnel.ChooseWayOut"/>: пока
    /// порода берётся, ступени остаются, когда не хватило ни лестниц, ни
    /// блоков. А обещать ступени там, где порода не берётся или до неё не
    /// дотянуться, нельзя вовсе — тогда порог ноль.
    /// </summary>
    /// <param name="height">На сколько блоков подниматься.</param>
    /// <param name="ladders">Сколько лестниц в сумках.</param>
    /// <param name="blocks">Сколько блоков в сумках годится под столб.</param>
    /// <param name="canCarve">
    /// Порода вокруг БЕРЁТСЯ и до неё ДОТЯНУТЬСЯ (см. <see cref="Tunnel.CanCarveOut"/>).
    /// </param>
    /// <param name="wall">Есть ли готовая стена под лестницу на всю высоту.</param>
    /// <param name="stepsWorthDepth">
    /// Из какой глубины ступени ещё ВЫГОДНЫ (<see cref="Tunnel.StepsOutMaxDepth"/>,
    /// по умолчанию 3 бл). Это НЕ нужная высота: подставить сюда height —
    /// и есть та самая беда на две с половиной минуты.
    /// </param>
    /// <param name="crossed">
    /// Приёмы, которые ОТСЮДА уже пробовали и которые не подняли ни на блок.
    /// Правило их не выбирает и называет вычеркнутыми, а не «нехваткой»
    /// (см. <see cref="Tunnel.ChooseWayOut"/>).
    /// </param>
    /// <param name="stepsWhy">
    /// Почему ступени не берутся — словами мира (<see cref="Tunnel.WhyNoStepsOut"/>).
    /// </param>
    public static (WayOut How, string Why) WayOutPlan(int height, int ladders, int blocks,
        bool canCarve, bool wall, int stepsWorthDepth,
        IReadOnlySet<WayOut>? crossed = null, string? stepsWhy = null) =>
        Tunnel.ChooseWayOut(height, ladders, blocks,
            stepsMaxDepth: canCarve ? stepsWorthDepth : 0,
            canCarve: canCarve, wall: wall, crossed: crossed, stepsWhy: stepsWhy);

    /// <summary>Каким приёмом вышли — словами отчёта о стройке.</summary>
    private static ClimbBuild WayBuilt(WayOut how) => how switch
    {
        WayOut.Steps => ClimbBuild.Steps,
        WayOut.Ladder => ClimbBuild.Ladder,
        WayOut.Pillar => ClimbBuild.Pillar,
        WayOut.None => ClimbBuild.NotNeeded,
        _ => ClimbBuild.Failed
    };

    /// <summary>Есть ли рядом стена на всю высоту — то есть встанет ли лестница.</summary>
    private bool WallHere(int height)
    {
        if (ctx.Body?.Physics is not { } phys)
            return false;
        return WallSide((int)Math.Floor(phys.X), (int)Math.Floor(phys.Y + 0.01),
            (int)Math.Floor(phys.Z), height) != null;
    }

    // ---------------- мост через пропасть ----------------

    /// <summary>
    /// Шире этого моста бот не строит за один заход. Это предел МЕХАНИЗМА
    /// (столько блоков он вообще берётся выложить), а не решение «мостить ли»:
    /// решение принимает <see cref="Walker.ChooseWayAcross"/>, и у движения
    /// свой, обычно более скромный, порог.
    /// </summary>
    public int MaxBridgeSpan { get; set; } = 8;

    /// <summary>
    /// ПЕРЕКРЫТЬ РАЗРЫВ БЛОКАМИ И ПРОЙТИ ПО НИМ.
    ///
    /// ЖИВОЙ СЛУЧАЙ (журнал 20:24): между ботом и целью лежал провал, в сумках
    /// была земля и лестницы, а перейти было нечем — механики моста в
    /// библиотеке не было вовсе. Бот бегал кругами и отказался.
    ///
    /// Делаем ровно то же, что живой игрок: кладём блок в клетку ПОД будущими
    /// ногами, шагаем на него, повторяем. Не «строим мост целиком, а потом
    /// идём»: дальше двух-трёх клеток рука не достаёт, да и стоя на кромке
    /// незачем гадать, что там за пятым блоком.
    ///
    /// И ГЛАВНОЕ — ШИФТ. Заказчик описал приём дословно: «нужно чуть
    /// выдвинуться вперёд с зажатым шифтом и ставить блок, глядя на боковую
    /// стенку (как в майнкрафте)». Без приседа мост был приёмом на удачу: тело
    /// идёт к ЦЕНТРУ следующей клетки, а за ней ещё пусто — разгон выносит
    /// бота с кромки в ту самую пропасть, ради которой мост и клали. Присед в
    /// игре это чинит намертво (<c>EntityPlayer</c>/<c>HandleSneaking</c>: шаг
    /// за край отменяется по каждой оси отдельно), и держать его надо ВСЮ
    /// переправу — потому что клавишу сбрасывает любой <c>Physics.Stop()</c>,
    /// а его зовёт и подход к клетке, и прицеливание перед установкой.
    ///
    /// В КАКУЮ ГРАНЬ ЦЕЛИТЬСЯ, бот уже знает сам: <c>Hands.NeighbourToClickOn</c>
    /// перебирает пол, потолок и четыре БОКОВЫЕ грани соседей — над пустотой
    /// боковая и остаётся единственной, ровно как у живого игрока.
    ///
    /// ЧЕСТНОСТЬ ЗДЕСЬ ГЛАВНОЕ. Блоки берутся из сумок и тратятся
    /// по-настоящему; успех меряется не «поставил», а «ноги стоят на той
    /// стороне». Мост, положенный до половины, — это неудача с числами, а не
    /// «частичный успех»: по половине моста никуда не придёшь.
    /// </summary>
    /// <param name="under">
    /// Клетки, которые надо ЗАЛОЖИТЬ, — на уровень ниже будущих ног, ближние
    /// первыми. Считает их тот, кто видит курс (движение): механизм стройки
    /// про цель похода знать не должен.
    /// </param>
    public async Task<BridgeResult> BridgeAsync(IReadOnlyList<BlockPos> under,
        CancellationToken ct = default)
    {
        if (under.Count == 0)
            return new BridgeResult(true, 0, 0, "мостить нечего");
        if (under.Count > MaxBridgeSpan)
            return new BridgeResult(false, 0, 0,
                $"разрыв в {under.Count} кл шире, чем я берусь мостить ({MaxBridgeSpan})");

        int have = ctx.Mining.SpareBlocks();
        if (have < under.Count)
            return new BridgeResult(false, 0, 0,
                $"на мост нужно {under.Count} блоков, в сумках {have}");

        if (ctx.Body is not { } body)
            return new BridgeResult(false, 0, 0,
                "мостить некому: тела ещё нет, а без приседа мост над пропастью — " +
                "это шаг в неё");

        OnLog?.Invoke($"кладу мост в {under.Count} кл с зажатым шифтом " +
                      $"(блоков в сумках {have})");

        using var crouch = body.HoldCrouch();
        int placed = 0, crossed = 0;
        foreach (var cell in under)
        {
            if (ct.IsCancellationRequested)
                return new BridgeResult(false, placed, crossed,
                    $"мост прервали: положил {placed} из {under.Count}, прошёл {crossed}");

            // Клетка могла оказаться и не пустой: осыпалось, или мы уже ходили
            // тут раньше. Тратить на неё блок незачем
            if (ctx.World.IsPassable(cell.X, cell.Y, cell.Z))
            {
                string? code = ctx.Mining.SpareBlock();
                if (code == null)
                    return new BridgeResult(false, placed, crossed,
                        $"блоки кончились на {placed}-м из {under.Count} — мост оборвался " +
                        "над пустотой, дальше не иду");

                var laid = await ctx.Mining.PlaceAsync(cell, code, 4, ct);
                if (!laid.Success)
                    return new BridgeResult(false, placed, crossed,
                        $"блок моста в {cell} не встал: {laid} (положил {placed} из {under.Count})");
                placed++;
            }

            // ШАГАЕМ РОВНО ТЕЛОМ и проверяем по ногам: «блок стоит» и «я на нём»
            // — разные вещи, и врать про второе нельзя (на этом уже горел склад,
            // считавший успех по убыли своей сумки)
            var step = new BlockPos(cell.X, cell.Y + 1, cell.Z);
            if (!await ctx.Movement.StepIntoAsync(step, ct: ct))
                return new BridgeResult(false, placed, crossed,
                    $"мост положен на {placed} кл, а тело в {step} не пошло — прошёл {crossed}");
            crossed++;
        }

        OnLog?.Invoke($"мост пройден: положил {placed} бл, прошёл {crossed} кл");
        return new BridgeResult(true, placed, crossed, "");
    }

    // ---------------- насыпь под постройкой ----------------

    /// <summary>
    /// Выше этой насыпи бот не подсыпает за один заход. Предел МЕХАНИЗМА, а не
    /// решение «сыпать ли»: решает зовущий (у дороги это ручка человека).
    ///
    /// Три — не круглое число, а длина руки. Ставя блок, бот стоит НА СОСЕДНЕЙ
    /// клетке сверху, и до дна насыпи ему тянуться от глаз: при глубине 3 это
    /// √(1 + 4,2²) ≈ 4,3 бл при досягаемости игры 4,5 (<see cref="Hands.Reach"/>),
    /// а при глубине 4 уже ≈ 5,3 — сервер такого клика не примет. Глубже
    /// пустоту надо не засыпать, а мостить (<see cref="BridgeAsync"/>).
    /// </summary>
    public int MaxFillHeight { get; set; } = 3;

    /// <summary>
    /// ПОДСЫПАТЬ ОПОРУ СНИЗУ — засыпать столбик пустоты, чтобы тому, что
    /// кладут сверху, было на чём лежать.
    ///
    /// ЖИВОЙ СЛУЧАЙ 23.08, СЛОВА ЗАКАЗЧИКА: «если не хватает блоков и лестница
    /// висит в воздухе, то пусть достраивает землей основу и на ней строит».
    /// Над провалом дорога клала НАСТИЛ — один слой блоков по оси, — а поверх
    /// него мостила ряд в три клетки: держалась одна средняя, края висели.
    ///
    /// ЧЕМ ЭТО НЕ МОСТ. Мост — ход СКВОЗЬ пустоту: один слой под ногами, и
    /// глубина ему безразлична. Насыпь — опора В пустоте: снизу доверху, и
    /// глубина для неё и есть цена. Приёмы разные, и путать их нельзя — ровно
    /// поэтому здесь отдельное имя, а не флажок у моста.
    ///
    /// СНИЗУ ВВЕРХ, И ЭТО НЕ ПОРЯДОК РАДИ ПОРЯДКА. Живой игрок не ставит блок
    /// в пустоту: он кликает по ГРАНИ уже стоящего. Первому блоку опора —
    /// верх грунта, каждому следующему — верх предыдущего. Начни бот сверху,
    /// и первый блок повис бы ни на чём — то есть был бы читом.
    ///
    /// ЧЕСТНОСТЬ. Блоки тратятся по-настоящему; кончились — досыпаем добытым
    /// на месте (<see cref="MineForPillarAsync"/>, ровно та же земля вокруг,
    /// которой бот столбится), а не вышло и это — отказ с числами. Насыпь,
    /// доведённая до середины, — неудача, а не «частичный успех»: полотно
    /// ляжет на воздух там же, где и лежало.
    /// </summary>
    /// <param name="column">
    /// Клетки столбика СНИЗУ ВВЕРХ. Считает их тот, кто знает, что кладёт
    /// сверху (у дороги — <see cref="RoadPlan.Footing"/>): механизм стройки
    /// про полотно знать не должен.
    /// </param>
    public async Task<FillResult> EmbankAsync(IReadOnlyList<BlockPos> column,
        CancellationToken ct = default)
    {
        if (column.Count == 0)
            return new FillResult(true, 0, "подсыпать нечего");
        if (column.Count > MaxFillHeight)
            return new FillResult(false, 0,
                $"насыпь в {column.Count} бл выше, чем я берусь подсыпать ({MaxFillHeight})");

        // ПУСТЫЕ КЛЕТКИ СЧИТАЕМ ЗАРАНЕЕ: осыпалось, подсыпали прошлым заходом,
        // или под краем полосы грунт оказался выше, чем под осью, — тратить на
        // такую клетку блок и удар незачем
        var empty = column.Where(c => !ctx.World.IsSolid(c.X, c.Y, c.Z)).ToList();
        if (empty.Count == 0)
            return new FillResult(true, 0, "насыпь уже стоит");

        int have = ctx.Mining.SpareBlocks();
        if (have < empty.Count && MineForPillar)
        {
            // Та же земля вокруг, которой бот столбится: отдельного «добыть на
            // насыпь» нет и не надо — вопрос-то один, «нечем строить».
            //
            // ПРОСИМ СТОЛЬКО, СКОЛЬКО НАДО ВСЕГО, А НЕ НЕДОСТАЧУ. Здесь стояло
            // `empty.Count - have`, и это была разница в мерке: копка меряет
            // want СУМКОЙ ЦЕЛИКОМ (у неё первой же строкой `had >= want` — уже
            // есть, копать незачем), а ей подавали ОСТАТОК.
            //
            // ЖИВЬЁМ: на насыпь не хватает 2 бл, в сумке 3 — копке говорили
            // «набери 2», она видела в сумке 3 и честно отвечала «уже есть»,
            // МОЛЧА и ни разу не ударив. А насыпь тут же отказывалась: «на
            // насыпь в 5 бл блоков нет: в сумках 3» — стоя на земле, из которой
            // эти два блока и берутся. Бот врал про нехватку на материале.
            //
            // Второй мерки тут не заводится: у выхода из ямы
            // (<see cref="GetOutAsync"/>) копку зовут ровно так же — всей
            // нуждой, `MineForPillarAsync(left)`
            await MineForPillarAsync(empty.Count, ct);
            have = ctx.Mining.SpareBlocks();
        }
        if (have < empty.Count)
            return new FillResult(false, 0,
                $"на насыпь в {empty.Count} бл блоков нет: в сумках {have}");

        // ШИФТ ПО ТОЙ ЖЕ ПРИЧИНЕ, ЧТО У МОСТА: сыплем, стоя на кромке над
        // пустотой, и любой шаг за край — падение в неё же
        using var crouch = ctx.Body?.HoldCrouch();
        int placed = 0;
        foreach (var cell in empty)
        {
            if (ct.IsCancellationRequested)
                return new FillResult(false, placed,
                    $"насыпь прервали: подсыпал {placed} из {empty.Count}");

            string? code = ctx.Mining.SpareBlock();
            if (code == null)
                return new FillResult(false, placed,
                    $"блоки кончились на {placed}-м из {empty.Count} — насыпь оборвалась");

            var laid = await ctx.Mining.PlaceAsync(cell, code, 4, ct);
            if (!laid.Success)
                return new FillResult(false, placed,
                    $"блок насыпи в {cell} не встал: {laid} (подсыпал {placed} из {empty.Count})");
            placed++;
        }

        OnLog?.Invoke($"подсыпал основание: {placed} бл");
        return new FillResult(true, placed, "");
    }

    // ---------------- спуск с обрыва ----------------

    /// <summary>Глубже этого бот не спускается за один заход.</summary>
    public int MaxDescend { get; set; } = 32;

    /// <summary>
    /// СПУСТИТЬСЯ НА N БЛОКОВ ЛЮБЫМ СПОСОБОМ — обратный ход к
    /// <see cref="GetOutAsync"/>, и построен он тем же порядком: приёмы
    /// перебираются по возрастанию цены, каждый неудавшийся называет причину.
    ///
    /// ПРО ПРЫЖОК ЗДЕСЬ НЕТ НИ СЛОВА, и это нарочно. Спрыгнуть — самый дешёвый
    /// спуск, но он не стройка: его делает движение своим телом, и решает про
    /// него движение же (у него бюджет урона и осторожность роли). Сюда зовут
    /// уже после того, как прыжок отвергли.
    /// </summary>
    public async Task<DescendResult> GetDownAsync(int depth, CancellationToken ct = default)
    {
        if (depth <= 0)
            return new DescendResult(true, WayDown.None, 0, 0, "спускаться некуда");
        if (ctx.Body?.Physics is not { } phys)
            return new DescendResult(false, WayDown.Trapped, 0, 0, "тело не на физике");
        if (depth > MaxDescend)
            return new DescendResult(false, WayDown.Trapped, 0, 0,
                $"{depth} бл глубже, чем я берусь спускаться ({MaxDescend})");

        int startY = (int)Math.Floor(phys.Y + 0.01);
        int fx = (int)Math.Floor(phys.X), fz = (int)Math.Floor(phys.Z);
        var underFoot = new BlockPos(fx, startY - 1, fz);

        // 0. СНАЧАЛА СПРАШИВАЕМ ПРАВИЛО и говорим вслух, чем собираемся слезать.
        // Прыжок отсюда исключён (maxDeliberateFall = 0): его уже рассмотрели
        // и отвергли выше, у того, кто владеет телом
        var (how, why) = Walker.ChooseWayDown(depth, maxDeliberateFall: 0,
            fallDamage: 0, damageBudget: 0,
            stepsMaxDepth: ctx.Tunnel.StepsOutMaxDepth,
            ladders: ctx.Hands.CountOf(LadderCode),
            wall: WallDown(fx, startY, fz, depth) != null,
            canCarve: CarveSteps && ctx.Tunnel.CanCarveOut(-1),
            rockUnderFoot: ctx.World.IsSolid(underFoot.X, underFoot.Y, underFoot.Z) &&
                           ctx.Mining.CanBreak(underFoot),
            maxDown: MaxDescend);
        // ГЛУБИНА НАЗЫВАЕТСЯ ОДИН РАЗ. Правило само начинает свои отказы с неё
        // («вниз на 6 бл не спуститься: спрыгивать не велено…»), и приставка
        // перед ними выходила заиканием — живой журнал 01.09, первая же строка,
        // которую читает человек: «[стройка] вниз на 6 бл: вниз на 6 бл не
        // спуститься: …». А в ВЫБОРЕ приёма («лестниц 6 — хватит на 12 бл»)
        // глубины нет, и там она нужна. То же правило, что у присловья отказа
        // в ClimbResult.ToString, и по той же причине
        string сколько = $"вниз на {depth} бл";
        OnLog?.Invoke(why.StartsWith(сколько, StringComparison.Ordinal)
            ? why
            : $"{сколько}: {why}");
        if (how == WayDown.Trapped)
            return new DescendResult(false, WayDown.Trapped, 0, 0, why);

        // ПРИЁМЫ ПРОБУЕМ В ТОМ ПОРЯДКЕ, КОТОРЫЙ НАЗВАЛО ПРАВИЛО, а остальные
        // следом. Сказать «повешу лестницу» и молча начать рубить ступени
        // значит соврать о том, что происходит: подмена приёма без спроса —
        // это ровно то враньё, за которое ловили выход наверх
        WayDown[] order = how switch
        {
            WayDown.Ladder => [WayDown.Ladder, WayDown.Steps, WayDown.Pillar],
            WayDown.Pillar => [WayDown.Pillar, WayDown.Steps, WayDown.Ladder],
            _ => [WayDown.Steps, WayDown.Ladder, WayDown.Pillar]
        };

        int wentTotal = 0, placedTotal = 0;
        foreach (var tryWay in order)
        {
            if (depth <= 0 || ct.IsCancellationRequested)
                break;
            int wasY = (int)Math.Floor(phys.Y + 0.01);

            switch (tryWay)
            {
                case WayDown.Steps when CarveSteps:
                {
                    var report = await ctx.Tunnel.StepDownAsync(wasY - depth, ct, depth);
                    // ПОДЛОЖЕННЫЕ ПОД СТУПЕНЬ ОПОРЫ — ТОЖЕ РАСХОД, И СЧИТАЕТСЯ
                    // ОН ЗДЕСЬ. Строки этой не было вовсе, и число из отчёта
                    // лесенки выбрасывалось молча: спуск, на который ушло
                    // четыре блока из сумки, докладывал «ничего не потратив».
                    // Наверх это уже сведено ровно так же (см. WayOut.Steps в
                    // GetOutAsync: «placed += report.Placed»), и две мерки
                    // одного расхода — это и есть та вторая копия, за которую
                    // проект ловит сам себя
                    placedTotal += report.Placed;
                    if ((int)Math.Floor(phys.Y + 0.01) >= wasY)
                        OnLog?.Invoke($"ступенями вниз не вышло ({report.Reason}) — пробую иначе");
                    break;
                }
                case WayDown.Ladder when ctx.Self.FindCarried(LadderCode) != null:
                {
                    var byLadder = await LadderDownAsync(depth, ct);
                    placedTotal += byLadder.Placed;
                    if (!byLadder.Success)
                        OnLog?.Invoke($"лестницей вниз не вышло ({byLadder.Why}) — пробую иначе");
                    break;
                }
                case WayDown.Pillar:
                    await ctx.Mining.PillarDownAsync(depth, ct);
                    break;
                default:
                    continue;
            }

            // МЕРЯЕМ ПО ФАКТУ — по своей высоте, а не по тому, что ответил приём.
            // Живой урок склада: успех считали по намерению, и «легло 112 шт.»
            // приходило при пустом сундуке
            int went = wasY - (int)Math.Floor(phys.Y + 0.01);
            if (went <= 0)
                continue;
            wentTotal += went;
            depth -= went;
            if (depth <= 0)
                return new DescendResult(true, tryWay, placedTotal, wentTotal, "");
            OnLog?.Invoke($"{tryWay} спустил на {went} бл, до низа ещё {depth} — добираю");
        }

        string failed = $"вниз получилось только на {wentTotal} бл, осталось ещё {depth}: " +
                        "ни ступени, ни лестница, ни разбор под собой не довели";
        OnLog?.Invoke(failed);
        return new DescendResult(false, WayDown.Trapped, placedTotal, wentTotal, failed);
    }

    /// <summary>
    /// ЛЕСТНИЦА ВНИЗ ПО СТЕНЕ ОБРЫВА.
    ///
    /// Порядок работы тот же, что и наверх (<see cref="LadderUpAsync"/>), и по
    /// той же причине: выше двух клеток рука не достаёт, значит перекладину
    /// вешают и тут же на неё сходят. Только колонна берётся не своя, а
    /// СОСЕДНЯЯ: под собой у бота пол, а спускаться надо вдоль обрыва.
    ///
    /// Через одну — так же, как наверх: рост тела 1.85, и висящее тело всегда
    /// касается хотя бы одной перекладины.
    /// </summary>
    public async Task<DescendResult> LadderDownAsync(int depth, CancellationToken ct = default)
    {
        if (ctx.Body?.Physics is not { } phys)
            return new DescendResult(false, WayDown.Ladder, 0, 0, "тело не на физике");
        if (depth <= 0)
            return new DescendResult(true, WayDown.None, 0, 0, "");
        if (depth > MaxHeight)
            return new DescendResult(false, WayDown.Ladder, 0, 0,
                $"{depth} бл ниже, чем я берусь строить ({MaxHeight})");

        int startY = (int)Math.Floor(phys.Y + 0.01);
        int fx = (int)Math.Floor(phys.X), fz = (int)Math.Floor(phys.Z);

        if (WallDown(fx, startY, fz, depth) is not { } column)
            return new DescendResult(false, WayDown.Ladder, 0, 0,
                $"рядом нет пустой колонны на {depth} бл вниз со стеной, к которой " +
                "крепить лестницу");

        OnLog?.Invoke($"вешаю лестницу вниз на {depth} бл в колонну " +
                      $"{WorldOrigin.SayFlat(column.X, column.Z)} вдоль стены {column.Name}");

        int placed = 0;
        for (int down = 0; down < depth && !ct.IsCancellationRequested; down++)
        {
            int y = startY - down;
            if (NeedsRung(down, EveryOtherBlock) && ctx.World.IsPassable(column.X, y, column.Z))
            {
                var at = new BlockPos(column.X, y, column.Z);
                var (may, whyNot) = ctx.Temp.MayPlace(at);
                if (!may)
                    return new DescendResult(false, WayDown.Ladder, placed,
                        startY - (int)Math.Floor(phys.Y + 0.01),
                        $"перекладину на {y} ставить нельзя: {whyNot}");
                var result = await ctx.Mining.PlaceAsync(at, LadderCode,
                    ClickFaceForWall(column.Face), ct);
                if (!result.Success)
                    return new DescendResult(false, WayDown.Ladder, placed,
                        startY - (int)Math.Floor(phys.Y + 0.01),
                        $"перекладина на {y} не встала: {result}");
                ctx.Temp.Note(at, LadderCode, ЛесаСтройки, $"лестница вниз на {depth} бл");
                placed++;
            }

            if (!await DescendOneAsync(phys, column.X, column.Z, y, ct))
                return new DescendResult(false, WayDown.Ladder, placed,
                    startY - (int)Math.Floor(phys.Y + 0.01), $"не спустился на {y}");
        }

        int went = startY - (int)Math.Floor(phys.Y + 0.01);
        var done = LadderDownVerdict(placed, went, depth, ct.IsCancellationRequested);
        OnLog?.Invoke(done.Why.Length > 0 ? done.Why
            : $"спустился по лестнице на {went} бл, перекладин {placed}");
        return done;
    }

    /// <summary>
    /// ЧЕМ КОНЧИЛАСЬ ЛЕСТНИЦА ВНИЗ — по ФАКТУ спуска, а не по намерению.
    /// Та же находка приёмки, что и наверх (см. <see cref="LadderVerdict"/>):
    /// «спустился хоть на блок» успехом не считается, иначе движение решит,
    /// что бот уже внизу, и станет строить дорогу с обрыва.
    /// </summary>
    public static DescendResult LadderDownVerdict(int placed, int descended, int depth,
        bool cancelled)
    {
        if (descended >= depth)
            return new DescendResult(true, WayDown.Ladder, placed, descended, "");
        return new DescendResult(false, WayDown.Ladder, placed, descended,
            $"лестница спустила на {descended} из {depth} бл" +
            (cancelled ? " — отменили" : " (перекладины кончились или не слез)"));
    }

    /// <summary>
    /// Соседняя колонна, по которой можно спуститься: сама пустая на всю
    /// глубину, а рядом с ней стена, к которой встанут перекладины.
    ///
    /// Ищем именно СОСЕДНЮЮ: под ногами у бота пол (он же на нём стоит), и
    /// лестницу в собственный пол не воткнёшь. У кромки обрыва такая колонна —
    /// это сам обрыв, а стеной ей служит порода, на которой бот стоит.
    /// </summary>
    private (int X, int Z, string Name, int Face)? WallDown(int fx, int fy, int fz, int depth)
    {
        int lowest = fy - depth + 1;
        foreach (var (dx, dz) in Tunnel.Sides)
        {
            int cx = fx + dx, cz = fz + dz;
            bool empty = true;
            for (int y = lowest; y <= fy && empty; y++)
                if (!ctx.World.IsPassable(cx, y, cz))
                    empty = false;
            if (!empty)
                continue;
            if (WallSide(cx, lowest, cz, depth) is { } side)
                return (cx, cz, side.Name, side.Face);
        }
        return null;
    }

    /// <summary>
    /// Спуститься на одну клетку по уже повешенной перекладине.
    ///
    /// ПРИСЕД — ТОЛЬКО ВИСЯ НА ЛЕСТНИЦЕ, и это правило игры, а не осторожность:
    /// стоя на земле присед запрещает шагнуть за край, и бот замирал бы на
    /// кромке навсегда. Пока не зацепились — просто идём в колонну и падаем в
    /// неё, игра сама подхватит лазанием (то же самое делает спуск в движении).
    /// </summary>
    private async Task<bool> DescendOneAsync(BotGamePhysics.GamePlayerPhysics phys,
        int cx, int cz, int toY, CancellationToken ct)
    {
        var until = DateTime.UtcNow.AddSeconds(StepSeconds);
        try
        {
            while (DateTime.UtcNow < until && !ct.IsCancellationRequested)
            {
                if (phys.Y <= toY + 0.05)
                    return true;
                phys.WalkToward(cx + 0.5, cz + 0.5, sprint: false);
                phys.Controls.Jump = false;
                phys.Controls.Sneak = phys.Climbing;
                await Task.Delay(50, ct).ContinueWith(_ => { });
            }
        }
        finally
        {
            phys.Controls.Sneak = false;
            phys.Stop();
        }
        return phys.Y <= toY + 0.05;
    }
}

/// <param name="Placed">Сколько блоков легло в мост.</param>
/// <param name="Crossed">Сколько клеток бот по нему ПРОШЁЛ (ногами, а не намерением).</param>
public record BridgeResult(bool Success, int Placed, int Crossed, string Why)
{
    public override string ToString() => Success
        ? $"мост {Placed} бл пройден ({Crossed} кл)"
        : $"мост не вышел: {Why}";
}

/// <summary>Чем кончилась насыпь (<see cref="Scaffolding.EmbankAsync"/>).</summary>
/// <param name="Placed">Сколько блоков легло в основание.</param>
public record FillResult(bool Success, int Placed, string Why)
{
    public override string ToString() => Success
        ? (Placed == 0 ? "подсыпать не пришлось" : $"основание подсыпано на {Placed} бл")
        : $"насыпь не вышла: {Why}";
}

/// <param name="Placed">Сколько блоков поставлено (перекладин лестницы).</param>
/// <param name="Descended">На сколько блоков спустились.</param>
public record DescendResult(bool Success, WayDown Way, int Placed, int Descended, string Why)
{
    public override string ToString() => Way switch
    {
        WayDown.None => "спускаться не пришлось",
        WayDown.Jump => $"спрыгнул на {Descended} бл",
        // «НИЧЕГО НЕ ПОТРАТИВ» — ТОЛЬКО КОГДА И ПРАВДА НИЧЕГО. Стояло тут это
        // слово БЕЗ УСЛОВИЯ, а лесенка вниз (Tunnel.StepDownAsync) подкладывает
        // под ступень блок из сумки всякий раз, когда опоры нет, и число это
        // возвращает отчётом. Человек читал «ничего не потратив» и не находил в
        // сумке четырёх блоков земли. У подъёма это уже разведено надвое
        // (BuildClimbResult.ToString, ветка ClimbBuild.Steps) — и теми же
        // словами, чтобы отчёт спуска и отчёт подъёма читались одинаково
        WayDown.Steps => Placed > 0
            ? $"сошёл ступенями на {Descended} бл, потратив {Placed} бл"
            : $"сошёл по ступеням на {Descended} бл, ничего не потратив",
        WayDown.Ladder => $"повесил лестницу {Placed} бл, спустился на {Descended}",
        WayDown.Pillar => $"разобрал под собой {Descended} бл и осел вместе с породой",
        // ПРИСЛОВЬЕ БЕРЁТСЯ У ТОГО, КТО ЕГО ОБЪЯВИЛ, А НЕ ПЕРЕПИСЫВАЕТСЯ СЮДА —
        // ровно как у подъёма (BuildClimbResult.ToString). С тех пор как
        // «!слезь» зовёт спуск отсюда, этот отчёт ложится в ClimbResult.Why
        // целиком, и второе присловье там снимается сверкой С ЭТИМ словом:
        // стой тут его копия в кавычках — разойдись они, и человек прочёл бы
        // «вниз не вышло: вниз не вышло: …», как читал у подъёма 31.08
        _ => $"{ClimbResult.ВнизНеВышло}: {Why}"
    };
}
