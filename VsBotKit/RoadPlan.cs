using GameMaterial = Vintagestory.API.Common.EnumBlockMaterial;

namespace VsBotKit;

/// <summary>Чем закрыта одна клетка дорожного полотна.</summary>
public enum RoadPiece
{
    /// <summary>Ровное место: полный блок покрытия, верх вровень с полом клетки.</summary>
    Floor,

    /// <summary>
    /// СТУПЕНЬКА — ровно та, которую заказал человек: «блок, полублок на блок
    /// той же высоты что дорога». То есть в клетке ДВА слоя: полный блок
    /// покрытия на той же высоте, что полотно соседней клетки, и полублок на
    /// нём. Верх выходит на полклетки выше — на него всходят без прыжка.
    ///
    /// ИГРОВОЙ БЛОК-СТУПЕНЬ (stonepathstairs и родня) сюда НЕ ВХОДИТ и больше
    /// не кладётся нигде. Живой случай приёмки: «полублоки пишет бот, а
    /// крафтит лестницы (ступеньки) дороги» — в журнале стояло «перепады беру
    /// полублоками», а в крафт уходила игровая ступень, потому что решение
    /// «есть ли ступени» пересчитывалось на каждом окне и молча
    /// переворачивалось, как только выломанного камня хватало на рецепт.
    /// Механика теперь одна, и слово от дела отстать не может.
    /// </summary>
    Step,

    /// <summary>Одной клеткой такой перепад не берётся — так дорогу не проложить.</summary>
    None
}

/// <summary>Что делают с рядом полотна.</summary>
public enum RoadWork
{
    /// <summary>ПРОХОДКА: выкопать ход над будущим полотном.</summary>
    Dig,

    /// <summary>УКЛАДКА: положить полотно.</summary>
    Pave
}

/// <summary>Слой в клетке полотна: снизу полный блок, сверху (у ступеньки) полублок.</summary>
public enum RoadLayer
{
    /// <summary>Полный блок покрытия.</summary>
    Full,

    /// <summary>Полублок — верхняя половинка ступеньки.</summary>
    Half
}

/// <summary>
/// Одна клетка ПРОДОЛЬНОГО профиля дороги.
/// </summary>
/// <param name="Level">
/// Высота хода в ПОЛУБЛОКАХ: 2·Y — пол вровень с клеткой Y, нечётное — полублок.
/// </param>
/// <param name="Piece">Чем эта клетка закрыта.</param>
/// <param name="OffGround">
/// На сколько полублоков полотно отошло от земли: плюс — насыпь (под дорогой
/// пусто), минус — выемка (дорогу придётся вкапывать в склон). Ноль — легло
/// по земле. Число нужно тому, кто строит: насыпь в воздухе бот не держит.
/// </param>
public sealed record RoadLevel(int Level, RoadPiece Piece, int OffGround)
{
    public override string ToString() =>
        $"{Level / 2.0:0.#} ({Piece})" + (OffGround == 0 ? "" : $", от земли {OffGround / 2.0:+0.#;-0.#}");
}

/// <summary>Поперечный ряд полотна: клетки одной поперечины дороги.</summary>
/// <param name="Index">Номер ряда от начала дороги.</param>
/// <param name="Centre">Осевая клетка ряда (по ней бот идёт).</param>
/// <param name="Cells">Клетки ряда от оси наружу — ближние кладутся первыми.</param>
public sealed record RoadRow(int Index, BlockPos Centre, IReadOnlyList<BlockPos> Cells)
{
    public override string ToString() => $"ряд {Index} у {Centre}: {Cells.Count} кл.";
}

/// <summary>Коробка коллизии блока в долях клетки — так её отдаёт реестр игры.</summary>
public readonly record struct BlockBox(float X1, float Y1, float Z1, float X2, float Y2, float Z2);

/// <summary>
/// ПЛАН ДОРОГИ — чистые правила без мира: где ляжет полотно и как разобрать
/// перепад высоты.
///
/// Зачем отдельно от <see cref="Roads"/>. Живьём дорога стоит по полчаса на
/// отрезок, и проверить в ней раскладку клеток или разбор склона нельзя —
/// сначала надо дойти. Правила, которые не спрашивают мир, обязаны считаться
/// без мира и закрываться тестами (правило 6 проекта): «дорога шириной 3 между
/// A и B», «где ровное полотно, а где ступенька» и «сперва копаем весь ход или
/// мостим по клетке» — ровно такие правила.
///
/// СЧЁТ В ПОЛУБЛОКАХ. Игра различает полклетки: плита — 0.5, шаг игрока без
/// прыжка — 0.6 (<see cref="WorldModel.StepHeight"/>). Считать высоту дороги
/// целыми блоками нельзя — тогда любой подъём становится прыжком, а заказчик
/// просил именно лесенку из полублоков и блоков. Поэтому высота полотна
/// меряется полублоками: чётный уровень — полный блок, нечётный — полублок.
/// </summary>
public static class RoadPlan
{
    /// <summary>Шире этого дорогу не кладём: край полотна выходит из-под руки бота.</summary>
    public const int MaxWidth = 9;

    // ---------------- раскладка полотна ----------------

    /// <summary>
    /// Смещения полосы от оси для дороги такой ширины.
    ///
    /// Нечётная ширина ложится симметрично, ЧЁТНАЯ — на клетку вправо от оси:
    /// полклетки в мире не бывает, и этот выбор надо сделать один раз и
    /// записать, иначе две половины дороги, положенные в разные заходы, не
    /// сойдутся.
    /// </summary>
    public static int[] Offsets(int width)
    {
        int w = Math.Clamp(width, 1, MaxWidth);
        int lo = -((w - 1) / 2);
        var all = new int[w];
        for (int i = 0; i < w; i++)
            all[i] = lo + i;
        // От оси наружу: осевую полосу бот кладёт первой и по ней же идёт.
        // Если материал кончится на середине ряда, ходить будет по чему
        Array.Sort(all, (a, b) => Math.Abs(a) != Math.Abs(b)
            ? Math.Abs(a) - Math.Abs(b)
            : a - b);
        return all;
    }

    /// <summary>
    /// Ось дороги: клетки от A до B, по одной оси за шаг.
    ///
    /// Диагональных перескоков нет намеренно. Дорога шириной 1, положенная по
    /// диагонали, — это цепочка клеток, соединённых углами: пройти по ней
    /// нельзя, а выглядит она как готовая дорога.
    ///
    /// Y в клетках — ПОДСКАЗКА (прямая от A к B), где искать землю; настоящую
    /// высоту полотна считает <see cref="Levels"/> по тому, что под ногами, и
    /// прямой она не идёт: закреплены только концы.
    /// </summary>
    public static IReadOnlyList<BlockPos> Centerline(BlockPos from, BlockPos to)
    {
        var line = new List<BlockPos> { from };
        int x = from.X, z = from.Z;
        int dx = Math.Abs(to.X - x), dz = Math.Abs(to.Z - z);
        int sx = Math.Sign(to.X - x), sz = Math.Sign(to.Z - z);
        int err = dx - dz;
        int guard = dx + dz + 2;

        while ((x != to.X || z != to.Z) && line.Count < guard)
        {
            // Ровно одна ось за шаг — «else if», а не два «if» подряд
            if (x != to.X && (2 * err > -dz || z == to.Z))
            {
                err -= dz;
                x += sx;
            }
            else
            {
                err += dx;
                z += sz;
            }
            line.Add(new BlockPos(x, 0, z));
        }

        // Высоту раздаём прямой: это только подсказка, где смотреть землю
        int n = line.Count;
        for (int i = 0; i < n; i++)
        {
            int y = n == 1 ? from.Y : from.Y + (int)Math.Round((to.Y - from.Y) * (double)i / (n - 1));
            line[i] = new BlockPos(line[i].X, y, line[i].Z);
        }
        return line;
    }

    /// <summary>
    /// Полотно рядами: на каждой клетке оси — поперечная полоса нужной ширины.
    ///
    /// Поперечная ось выбирается один раз на всю дорогу — по тому, вдоль чего
    /// дорога длиннее. Крутить полосу вслед за каждым изломом оси значило бы
    /// оставлять в дороге клинья и дыры на каждом повороте.
    /// </summary>
    public static IReadOnlyList<RoadRow> Rows(BlockPos from, BlockPos to, int width)
    {
        var line = Centerline(from, to);
        var offsets = Offsets(width);
        bool alongX = Math.Abs(to.X - from.X) >= Math.Abs(to.Z - from.Z);

        var rows = new List<RoadRow>(line.Count);
        for (int i = 0; i < line.Count; i++)
        {
            var c = line[i];
            var cells = new List<BlockPos>(offsets.Length);
            foreach (int o in offsets)
                cells.Add(alongX ? new BlockPos(c.X, c.Y, c.Z + o) : new BlockPos(c.X + o, c.Y, c.Z));
            rows.Add(new RoadRow(i, c, cells));
        }
        return rows;
    }

    /// <summary>
    /// Все клетки полотна одним списком, без повторов. Повторы бывают на
    /// изломах оси: соседние ряды там накрывают одну и ту же клетку.
    /// </summary>
    public static IReadOnlyList<BlockPos> Cells(BlockPos from, BlockPos to, int width)
    {
        var seen = new HashSet<(int, int)>();
        var all = new List<BlockPos>();
        foreach (var row in Rows(from, to, width))
        foreach (var cell in row.Cells)
            if (seen.Add((cell.X, cell.Z)))
                all.Add(cell);
        return all;
    }

    // ---------------- порядок работ ----------------

    /// <summary>
    /// В КАКОМ ПОРЯДКЕ БРАТЬСЯ ЗА РЯДЫ: пары «что делать — с каким рядом».
    ///
    /// ЗАКАЗ ЧЕЛОВЕКА, дословно: «может для реализма в начале плюс копает, а
    /// уже потом пробежит и поставит везде дорогу? а то нереалистично
    /// смотрится». До этого копка и укладка чередовались КЛЕТКА ЗА КЛЕТКОЙ:
    /// бот срубал траву над одной клеткой, мостил её же, шагал вперёд и снова
    /// махал киркой — со стороны это не стройка, а дёрганье.
    ///
    /// <paramref name="digFirst"/> — сперва ПРОЙТИ ВЕСЬ ХОД и выкопать его, и
    /// только потом вернуться к началу и уложить полотно. Выключено — старый
    /// порядок, ряд за рядом; он остаётся ради коротких дорог в один-два ряда,
    /// где второй проход — это лишняя ходьба туда-обратно.
    ///
    /// Правило чистое нарочно: сам порядок живьём не проверить (дорога стоит
    /// получаса на отрезок), а перепутать его местами — дело одной строки.
    /// </summary>
    public static IReadOnlyList<(RoadWork Work, int Row)> Order(int rows, bool digFirst)
    {
        int n = Math.Max(0, rows);
        var order = new List<(RoadWork, int)>(n * 2);
        if (digFirst)
        {
            for (int i = 0; i < n; i++)
                order.Add((RoadWork.Dig, i));
            for (int i = 0; i < n; i++)
                order.Add((RoadWork.Pave, i));
        }
        else
        {
            for (int i = 0; i < n; i++)
            {
                order.Add((RoadWork.Dig, i));
                order.Add((RoadWork.Pave, i));
            }
        }
        return order;
    }

    // ---------------- разбор перепада ----------------

    /// <summary>
    /// Чем закрыть клетку, если предыдущая была на уровне <paramref name="from"/>,
    /// а эта должна выйти на <paramref name="to"/> (оба — в полублоках).
    ///
    /// ПРАВИЛО ЖИВОГО ИГРОКА. Без прыжка человек всходит на 0.6 блока
    /// (<see cref="WorldModel.StepHeight"/>) — то есть на полублок и не на
    /// целый. Отсюда:
    ///   ровно (или пришли на целую высоту) → полный блок покрытия;
    ///   полблока                           → СТУПЕНЬКА «блок + полублок»;
    ///   целый блок и больше                → одной клеткой не берётся.
    ///
    /// ЦЕЛЫЙ БЛОК ЗА КЛЕТКУ БОЛЬШЕ НЕ БЕРЁМ. Раньше его брала игровая
    /// ступень, но заказчик просил другого: «я просил из них делать
    /// ступеньки — блок, полублок на блок той же высоты что дорога».
    /// Ступенька поднимает на полклетки, значит блок высоты растягивается
    /// на две клетки — это и есть цена заказа, и она честная.
    /// </summary>
    public static RoadPiece PieceOf(int from, int to) =>
        Math.Abs(to - from) > 1 ? RoadPiece.None
        : IsHalf(to) ? RoadPiece.Step
        : RoadPiece.Floor;

    /// <summary>Уровень стоит на полублоке (нечётное число полублоков).</summary>
    public static bool IsHalf(int level) => level % 2 != 0;

    /// <summary>
    /// ДОКУДА ПОЛОТНО ДОБЕРЁТСЯ ПО ВЫСОТЕ за столько рядов — в полублоках и
    /// туда, и обратно.
    ///
    /// Ядро тут одно на всех, и это не мелочь: этим же числом отвечает отказ
    /// «уклон не по силам» (<see cref="Reached"/>), им же закрепляет конец
    /// сама разметка (<see cref="Levels"/>), им же считается выполнимая
    /// высота конца (<see cref="WholeEnd"/>). Разойдись они — и бот отказывал
    /// бы по одному уклону, а вёл дорогу по другому.
    /// </summary>
    public static int Lead(int start, int want, int rows)
    {
        int steps = Math.Max(0, rows - 1);          // переходов между рядами
        return want >= start ? Math.Min(want, start + steps) : Math.Max(want, start - steps);
    }

    /// <summary>
    /// КОРИДОР РЯДА — между какими уровнями полотну позволено быть на
    /// <paramref name="row"/>-м ряду, чтобы И от начала не оторваться, И к
    /// концу успеть выйти.
    ///
    /// Оба конца дороги закреплены заданием, а за ряд полотно берёт не больше
    /// полублока: значит от начала оно не уйдёт дальше, чем ряд по полублоку,
    /// и к концу обязано подойти на столько же. Пересечение этих двух конусов
    /// и есть коридор; на первом и последнем ряду он схлопывается в точку —
    /// ровно то, чего требовал заказчик жалобой «он не учитывает высоту в
    /// задании».
    ///
    /// Пустым коридор бывает от одного: концы не соединить, перепад круче,
    /// чем есть рядов. Звать сюда с таким концом нельзя, и потому
    /// <see cref="Levels"/> прежде всего приводит конец к достижимому
    /// (<see cref="Lead"/>).
    /// </summary>
    public static (int Lo, int Hi) Corridor(int row, int rows, int start, int end)
    {
        int last = Math.Max(0, rows - 1);
        int i = Math.Clamp(row, 0, last);
        return (Math.Max(start - i, end - (last - i)), Math.Min(start + i, end + (last - i)));
    }

    /// <summary>
    /// ЦЕНА РЯДА — во что обходится полотно, разошедшееся с землёй на
    /// <paramref name="offGround"/> полублоков. Ею и меряется «как можно ближе
    /// к земле» у <see cref="Levels"/>.
    ///
    /// ПОЧЕМУ НЕ ПРОСТО «НА СКОЛЬКО РАЗОШЛОСЬ». Цена в полублоках расхождения
    /// выглядит честной, а на живом стенде оказалась вредной: над провалом в
    /// пять блоков полотно начинало ПОЛЗТИ К ДНУ, до которого всё равно не
    /// достаёт. Оно резало выемку в подходах — там-то земля целая, — и роняло
    /// настил моста на клетку ниже, где его не к чему прислонить: стенд
    /// <c>ДорогаМоститПровалМиромTests</c> ответил «блок моста … не встал: не
    /// дотянуться». Работы это не убавляло НИ НА УДАР: настил над ямой в блок
    /// ровно такой же, как над пропастью в пятьдесят.
    ///
    /// ВВЕРХ ЦЕНА СТУПЕНЬКАМИ, ВНИЗ — ПО ГЛУБИНЕ, и разница эта не прихоть, а
    /// разная природа двух работ (см. <see cref="Roads.MaxCutFill"/>):
    ///   0 и +1 — ПОЛОТНО ЛЕЖИТ НА ЗЕМЛЕ: блок вровень или плита на природном
    ///            блоке. Даром, и лучше этого нет ничего;
    ///   +2, +3 — полотно выше земли, но под клеткой есть на что опереться и по
    ///            чему щёлкнуть: лишний блок под ноги, не больше;
    ///   +4 и выше — ПРОВАЛ (<see cref="Roads.VoidUnder"/>): нужен мост. Дороже
    ///            всего — и ВЫСОТА К ЦЕНЕ НЕ ПРИБАВЛЯЕТ: мост меряется длиной
    ///            пролёта, а не глубиной, и опуститься к дну на полпути не
    ///            укорачивает ни одного пролёта;
    ///   ниже нуля — ВЫЕМКА, и здесь каждый полублок ГЛУБИНЫ считается: копать
    ///            столбец одинаково что на полблока, что на десять, но глубину
    ///            меряет предел («ГлубинаВыемкиДороги»), и каждый полублок
    ///            ближе к земле — это полблока запаса до отказа.
    /// </summary>
    public static int RowPrice(int offGround) =>
        offGround < 0 ? -offGround
        : offGround <= 1 ? 0
        : Roads.VoidUnder(offGround) ? 2
        : 1;

    /// <summary>
    /// РАЗМЕТКА ВЫСОТ — главное правило дороги: на каком уровне ляжет полотно
    /// у каждой клетки оси.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ИЗ-ЗА КОТОРОГО ПРАВИЛО ПЕРЕПИСАНО. 22.08 два заказа
    /// подряд кончились нулём, и оба на обычном рельефе:
    ///   20:59:51 вниз, (52,112,252) → (55,96,281), 33 ряда: «на 33-м ряду
    ///            полотно на заданной высоте 96,5 разошлось с землёй на
    ///            −17,5 бл — выемку глубже не роем»;
    ///   21:02:34 вверх, (52,112,252) → (55,128,281), 33 ряда: «с 4-го ряда
    ///            полотно висит над землёй 30 рядов подряд, а мост я кладу не
    ///            длиннее 8 кл.».
    /// Слова заказчика: «а теперь просто не строит дорогу вниз и вверх». Беда
    /// у обоих одна: профиль ДЕРЖАЛ ПРЯМУЮ от начальной высоты к конечной, а
    /// земле оставалось только совпасть с ней. Не совпала — выемка в
    /// семнадцать блоков и насыпь на тридцать рядов, и оба раза ноль работы.
    ///
    /// НАСТОЯЩАЯ ДОРОГА ТАК НЕ СТРОИТСЯ: она ИДЁТ ПО ЗЕМЛЕ, сглаживая её в
    /// пределах уклона, и попадает в заданные концы. Отсюда правило —
    /// КОРИДОР И ПОДГОНКА К ЗЕМЛЕ:
    ///   • КОРИДОР (<see cref="Corridor"/>) держит закон: концы лежат на
    ///     заданных высотах, за ряд полотно берёт не больше полублока;
    ///   • ПОДГОНКА выбирает ВНУТРИ коридора самую дешёвую разметку, а цену
    ///     ряда назначает <see cref="RowPrice"/> — по тому, во что этот ряд
    ///     обойдётся работой: даром по земле, лишний блок под ноги над ней,
    ///     мост над провалом, каждый полублок глубины в выемке.
    ///
    /// ПОЧЕМУ ПЕРЕБОРОМ, А НЕ ФОРМУЛОЙ. «Прижать к земле» на глаз — это зажать
    /// землю в коридор клетка за клеткой, и такая разметка рвётся на первом же
    /// обрыве: земля умеет прыгнуть на пять блоков за клетку, а полотно — на
    /// полблока, и после прыжка соседние клетки разойдутся круче, чем можно.
    /// Считается поэтому как самый дешёвый путь: у каждого ряда перебираются
    /// все уровни его коридора, и у каждого уровня помнится лучшая цена всего
    /// пути позади. Предшественников у уровня ровно три (полблока вниз, столько
    /// же вверх и остаться), так что весь счёт — это (рядов × высот × 3)
    /// сложений: тридцать три ряда живого рельефа считаются за доли
    /// миллисекунды, и ответ ТОЧНЫЙ, а не «на глаз».
    ///
    /// ДВЕ МЕРЫ, И СТАРШАЯ — ЦЕНА РАБОТ. Единица цены дороже ЛЮБОГО числа
    /// перемен уровня: на то и множитель (рядов + 1) — перемен в дороге всегда
    /// меньше, чем рядов. Вторая мера — само число перемен: при равной цене
    /// дорога обязана выбрать ровную площадку, а не пилу в полблока, потому
    /// что каждая перемена — это лишняя ступенька, лишний полублок и лишний
    /// удар киркой. Именно вторая мера и держит полотно ровным над провалом,
    /// где ползти к дну бессмысленно.
    ///
    /// РАВНОЕ РАЗРЕШАЕТСЯ ВНИЗ. Выемку бот роет всегда, а насыпь надо мостить,
    /// и мост длиннее восьми клеток он не кладёт вовсе: из двух одинаково
    /// дешёвых разметок нижняя — та, которая доведёт дорогу до конца.
    /// </summary>
    /// <param name="ground">
    /// Высота ПОЛА (клетка, куда встают ноги) под клетками оси — подряд,
    /// начиная с ряда <paramref name="first"/>. Это и цель разметки, и мера
    /// расхождения (<see cref="RoadLevel.OffGround"/>).
    /// </param>
    /// <param name="first">Номер первого ряда этого куска в дороге целиком.</param>
    /// <param name="rows">Сколько рядов у дороги ЦЕЛИКОМ — по ним и коридор.</param>
    /// <param name="start">Уровень полотна на ПЕРВОМ ряду дороги (полублоки).</param>
    /// <param name="end">Уровень полотна на ПОСЛЕДНЕМ ряду дороги (полублоки).</param>
    /// <param name="previous">
    /// Уровень последней уже размеченной клетки, если дорога продолжается: без
    /// него каждый новый кусок начинал бы профиль заново и в стыке вырастала
    /// бы ступенька, которой никто не планировал.
    /// </param>
    public static IReadOnlyList<int> Levels(IReadOnlyList<int> ground, int first, int rows,
        int start, int end, int? previous = null)
    {
        int n = ground.Count;
        if (n == 0)
            return [];

        // Конец берём ТОЛЬКО достижимый: до недостижимого коридор пуст на
        // каждом ряду и размечать было бы нечего. Браться ли за неподъёмный
        // уклон — не дело правила (см. Roads.LeadTooSteep), но вести дорогу
        // в высоту, которой не достать, оно не станет
        end = Lead(start, end, rows);

        // Перебираем от самой низкой отметки до самой высокой: ниже и выше
        // полотну делать нечего — там оно дальше и от земли, и от обоих концов
        int low = Math.Min(start, end), high = Math.Max(start, end);
        foreach (int g in ground)
        {
            low = Math.Min(low, g * 2);
            high = Math.Max(high, g * 2);
        }
        if (previous is { } stitch)
        {
            low = Math.Min(low, stitch - 1);
            high = Math.Max(high, stitch + 1);
        }
        int span = high - low + 1;

        const long Never = long.MaxValue / 4;    // сюда полотну нельзя
        long work = n + 1;                       // единица цены работ (см. про две меры)
        var cost = new long[span];               // лучшая цена пути до этого ряда
        var next = new long[span];
        var came = new int[n * span];            // откуда пришли — разворачиваем назад

        var (lo0, hi0) = Corridor(first, rows, start, end);
        for (int at = 0; at < span; at++)
        {
            int level = low + at;
            came[at] = -1;
            // Дорога продолжается — от уже выложенной клетки не оторваться
            // дальше чем на полублок, иначе в стыке вырастет обрыв
            bool allowed = level >= lo0 && level <= hi0 &&
                           (previous is not { } was || Math.Abs(level - was) <= 1);
            cost[at] = !allowed
                ? Never
                : work * RowPrice(level - ground[0] * 2) +
                  (previous is { } same && same != level ? 1 : 0);
        }

        for (int k = 1; k < n; k++)
        {
            var (lo, hi) = Corridor(first + k, rows, start, end);
            int soil = ground[k] * 2;
            for (int at = 0; at < span; at++)
            {
                int level = low + at;
                next[at] = Never;
                came[k * span + at] = -1;
                if (level < lo || level > hi)
                    continue;

                // Три предшественника, и ни одним больше: круче полублока за
                // ряд человек без прыжка не всходит. Перебор идёт СНИЗУ ВВЕРХ,
                // и при равной цене побеждает нижний — см. про выемку выше
                long best = Never;
                int pick = -1;
                for (int p = Math.Max(0, at - 1); p <= Math.Min(span - 1, at + 1); p++)
                {
                    if (cost[p] >= Never)
                        continue;
                    long sum = cost[p] + (p == at ? 0 : 1);
                    if (sum < best)
                        (best, pick) = (sum, p);
                }
                if (pick < 0)
                    continue;
                next[at] = best + work * RowPrice(level - soil);
                came[k * span + at] = pick;
            }
            (cost, next) = (next, cost);
        }

        var levels = new int[n];
        long cheapest = Never;
        int tail = -1;
        for (int at = 0; at < span; at++)
            if (cost[at] < cheapest)
                (cheapest, tail) = (cost[at], at);

        if (tail < 0)
        {
            // Пути нет — значит позвали со стыком, до которого от коридора не
            // дотянуться полублоком. Молчать нельзя: размечаем ближайшим к
            // земле, и первый же непосильный перепад назовёт себя числом сам
            // (PieceOf вернёт None, и дорога честно встанет)
            for (int k = 0; k < n; k++)
            {
                var (lo, hi) = Corridor(first + k, rows, start, end);
                levels[k] = Math.Clamp(ground[k] * 2, lo, hi);
            }
            return levels;
        }

        for (int k = n - 1; k >= 0; k--)
        {
            levels[k] = low + tail;
            tail = came[k * span + tail];
        }
        return levels;
    }

    /// <summary>
    /// ПРОДОЛЬНЫЙ ПРОФИЛЬ: разметка высот (<see cref="Levels"/>) плюс то, чем
    /// каждая клетка закрывается и насколько она разошлась с землёй.
    ///
    /// ВЫСОТЫ ИЗ ЗАДАНИЯ — ЭТО КОНЦЫ. «дорога x1 y1 z1 x2 y2 z2» задаёт не
    /// только куда вести, но и на какой высоте начать и кончить; между концами
    /// полотно идёт ПО ЗЕМЛЕ, а не по прямой — см. <see cref="Levels"/>.
    /// </summary>
    /// <remarks>
    /// ЗА КЛЕТКУ — НЕ БОЛЬШЕ ПОЛУБЛОКА. Другого шага у дороги нет: перепад
    /// берётся ступенькой «блок + полублок», а она поднимает ровно на
    /// полклетки. Игровая ступень поднимала за клетку на целый блок, но
    /// заказчик от неё отказался прямо («я просил из них делать ступеньки —
    /// блок, полублок на блок той же высоты что дорога»), и вместе с ней ушла
    /// развилка «есть ступени / нет ступеней». Развилка эта была ещё и
    /// лживой: решение пересчитывалось на каждом окне, журнал же о смене
    /// молчал — отсюда жалоба «полублоки пишет бот, а крафтит лестницы».
    /// </remarks>
    public static IReadOnlyList<RoadLevel> Profile(IReadOnlyList<int> ground, int first, int rows,
        int start, int end, int? previous = null)
    {
        var levels = Levels(ground, first, rows, start, end, previous);
        var profile = new RoadLevel[levels.Count];
        for (int i = 0; i < levels.Count; i++)
        {
            int? before = i == 0 ? previous : levels[i - 1];
            var piece = before is { } prev
                ? PieceOf(prev, levels[i])
                : IsHalf(levels[i]) ? RoadPiece.Step : RoadPiece.Floor;
            profile[i] = new RoadLevel(levels[i], piece, levels[i] - ground[i] * 2);
        }
        return profile;
    }

    /// <summary>
    /// ПРОФИЛЬ БЕЗ ЗАДАННЫХ КОНЦОВ — просто по земле, в пределах уклона. Так
    /// работает «домости остаток» и всё, что зовёт профиль без задания: концом
    /// становится сама земля под последней клеткой, и подгонять полотно
    /// оказывается не к чему, кроме рельефа.
    ///
    /// <paramref name="previous"/> — стык с уже выложенным: он закрепляет не
    /// первый ряд этого куска, а ряд ПЕРЕД ним, потому кусок и разметится как
    /// ряды с первого по n-й дороги из n+1 ряда.
    /// </summary>
    public static IReadOnlyList<RoadLevel> Profile(IReadOnlyList<int> ground, int? previous = null) =>
        ground.Count == 0
            ? []
            : previous is { } stitch
                ? Profile(ground, 1, ground.Count + 1, stitch, ground[^1] * 2, stitch)
                : Profile(ground, 0, ground.Count, ground[0] * 2, ground[^1] * 2);

    /// <summary>
    /// В какой клетке лежит сам блок покрытия для этого уровня хода.
    /// Полный блок — ПОД ногами, полублок — В клетке ног (ноги стоят на его
    /// верхе, ровно как считает <see cref="WorldModel.FeetY"/>).
    /// </summary>
    public static int BlockY(int level) => IsHalf(level) ? Half(level) : level / 2 - 1;

    /// <summary>
    /// ИЗ ЧЕГО СКЛАДЫВАЕТСЯ КЛЕТКА ПОЛОТНА — снизу вверх, в том порядке, в
    /// каком её и кладут.
    ///
    /// Ровное место — один полный блок покрытия под ногами. СТУПЕНЬКА — два
    /// слоя, и это дословно заказ человека: «блок, полублок на блок той же
    /// высоты что дорога». Нижний слой ступеньки лежит на той же высоте, что
    /// полотно соседней ровной клетки (BlockY(level) − 1 == BlockY(level − 1)),
    /// поэтому он и кладётся тем же покрытием — это продолжение дороги, а не
    /// подпорка сбоку. Верхний слой — полублок, по нему и всходят.
    ///
    /// ЖИВОЙ СЛУЧАЙ. Раньше в клетке перепада ставился ОДИН блок: либо игровая
    /// ступень (её заказчик не просил и увидел в крафте), либо голый полублок
    /// в воздухе над ямой — держаться ему было не на чем.
    ///
    /// А ЕСЛИ ПОД ПЛИТОЙ УЖЕ ЕСТЬ ТВЕРДЬ — НИЖНЕГО БЛОКА НЕТ ВОВСЕ. Слова
    /// заказчика 19.08, дословно: «схема у лестницы твоя не экономная, зачем
    /// ставить под плиты дороги блок дороги? если можно было под ней не
    /// выкапывать просто и ставить на природный блок?». Он прав, и цена
    /// прежней схемы считается: на спуске ступенька приходится на КАЖДЫЙ
    /// ВТОРОЙ ряд, то есть на дороге в 40 рядов шириной 3 это 60 клеток — 60
    /// выломанных природных блоков и 60 положенных вместо них блоков покрытия,
    /// причём ни одного из них не видно: сверху их накрывает та самая плита.
    /// Нижний блок нужен ровно тогда, когда держаться плите не на чем — на
    /// насыпи, над водой, над своей же ямой.
    /// </summary>
    /// <param name="bedHolds">
    /// Под будущей плитой (<see cref="Bed"/>) уже стоит твердь: природный
    /// блок склона, чужая дорога, своё же полотно с прошлого захода. Спрашивает
    /// это МИР — у чистого правила его нет; здесь только следствие.
    /// </param>
    public static IReadOnlyList<(int Y, RoadLayer Layer)> Layers(int level, bool bedHolds) =>
        !IsHalf(level) ? [(BlockY(level), RoadLayer.Full)]
        : bedHolds ? [(BlockY(level), RoadLayer.Half)]
        : [(BlockY(level) - 1, RoadLayer.Full), (BlockY(level), RoadLayer.Half)];

    /// <summary>
    /// СКОЛЬКО КЛЕТОК ПУСТОТЫ ПОД ПОЛОТНОМ — то есть насколько высокую насыпь
    /// придётся подвести, чтобы дороге было на чём лежать.
    ///
    /// ЖИВОЙ СЛУЧАЙ 23.08, СЛОВА ЗАКАЗЧИКА: «если не хватает блоков и лестница
    /// висит в воздухе, то пусть достраивает землей основу и на ней строит».
    /// До этой правки бот над провалом бросал НАСТИЛ — один слой блоков по оси
    /// (<c>Roads.BridgeRunAsync</c>), — а потом мостил поверх него полный ряд
    /// в три клетки. Настил держал только среднюю; края ложились в воздух, и
    /// ступенька со стороны выглядела ровно как висящая лестница.
    ///
    /// ЧИСЛО СЧИТАЕТСЯ ИЗ <see cref="Layers"/>, А НЕ ВТОРОЙ РАСКЛАДКОЙ: пустота
    /// кончается там, где начинается САМЫЙ НИЖНИЙ слой полотна, — а какой он,
    /// знает раскладка. Разойдись эти двое, и бот подсыпал бы не под то, что
    /// кладёт.
    ///
    /// Ноль у отхода 0…3 не случаен и не подгонка: до полутора блоков нижний
    /// слой полотна ложится ПРЯМО НА ЗЕМЛЮ (при отходе 2 блок покрытия встаёт
    /// в клетку над верхом естественного грунта), и подсыпать там нечего.
    /// Пустота начинается с отхода 4 — с той же четвёрки, за которой у
    /// <see cref="Roads.VoidUnder"/> начинается «полотно висит».
    /// </summary>
    /// <param name="offGround">
    /// Отход полотна от земли в ПОЛУБЛОКАХ (<see cref="RoadLevel.OffGround"/>).
    /// Минус — выемка, там пустоты нет по определению.
    /// </param>
    public static int FillDepth(int offGround) =>
        offGround <= 0 ? 0 : Math.Max(0, offGround / 2 - 1);

    /// <summary>
    /// ЧТО ИМЕННО ПОДСЫПАТЬ ПОД ОДНОЙ КЛЕТКОЙ ПОЛОТНА — снизу вверх, в том
    /// порядке, в каком блоки и кладут: каждый следующий встаёт на верх
    /// предыдущего, и так до низа полотна.
    ///
    /// ПОРЯДОК ТУТ НЕ УКРАШЕНИЕ. Живой игрок не ставит блок в пустоту — он
    /// кликает по ГРАНИ уже стоящего. Начни бот сверху, и первый же блок
    /// повис бы ни на чём: это и есть тот самый чит, который нам запрещён.
    /// Снизу вверх каждому есть на что опереться: первому — верх грунта,
    /// остальным — верх предыдущего.
    /// </summary>
    /// <param name="ground">
    /// Высота НОГ на естественной земле под этой клеткой: сам грунт кончается
    /// на <paramref name="ground"/> − 1, а <paramref name="ground"/> — уже
    /// первая пустая клетка над ним.
    /// </param>
    public static IReadOnlyList<int> Footing(int level, bool bedHolds, int ground)
    {
        int lowest = Layers(level, bedHolds).Min(l => l.Y);
        if (lowest <= ground)
            return [];
        var fill = new List<int>(lowest - ground);
        for (int y = ground; y < lowest; y++)
            fill.Add(y);
        return fill;
    }

    /// <summary>
    /// ЛЯЖЕТ ЛИ В ЭТУ ВЫСОТУ СЛОЙ ПОЛОТНА — и какой именно. null — не ляжет
    /// ничего: клетка выемки над дорогой, там будет пусто.
    ///
    /// ЗАЧЕМ ОТДЕЛЬНОЕ ИМЯ ДЛЯ ОДНОЙ СТРОКИ. Вопрос «а сюда мы что-нибудь
    /// кладём?» задают ДВА разных дела, и оба ошибались на нём живьём:
    ///
    ///   • КОПКА. Клетку, где лежит наше же полотно, первым проходом
    ///     выламывать нельзя. Раньше берегли ОДНУ постель (<see cref="Bed"/>),
    ///     а у ступеньки слоя два — и верхний, полублок, оставался
    ///     незащищённым. Живой случай 17.08, 23:48:09: заход прервали ради еды,
    ///     возврат начал дорогу заново с той же клетки — и первым же ударом
    ///     бот снёс собственный полублок («[добыча] ломаю stonepathslab-free»),
    ///     положенный секундой раньше. Со стороны это ровно то, на что жаловался
    ///     заказчик: «ступени дороги неправильно делает».
    ///
    ///   • ОТКАЗ. Клетка, куда ляжет блок, ОБЯЗАНА освободиться: не вышло —
    ///     дороги здесь не будет. Клетка просвета над ней — уборка: сквозь
    ///     папоротник и траву проходят как сквозь воздух, и вставать из-за них
    ///     всей дорогой не за что (см. <see cref="Roads.ToBreak"/>).
    ///
    /// Считается ИЗ <see cref="Layers"/>, второй раскладки тут нет: разойдись
    /// они — и бот берёг бы не то, что кладёт.
    /// </summary>
    /// <param name="bedHolds">См. <see cref="Layers"/>: под плитой уже есть твердь.</param>
    public static RoadLayer? LayerAt(int level, int y, bool bedHolds)
    {
        foreach (var (at, layer) in Layers(level, bedHolds))
            if (at == y)
                return layer;
        return null;
    }

    /// <summary>
    /// ХОД, КОТОРЫЙ НАДО ВЫКОПАТЬ, — клетки над полотном на высоту тела.
    ///
    /// Это первый проход дороги: в выемке ровно эти клетки и есть «копка», в
    /// поле — трава да низкие ветки. Полотно тут НЕ трогается нарочно: сними
    /// пол первым проходом — и по собственной дороге не пройти вторым.
    ///
    /// Отсчёт от КЛЕТКИ НОГ, а не от блока покрытия: у ступеньки полублок
    /// лежит в клетке ног, и она тоже обязана быть чистой, иначе полублок
    /// некуда ставить. Раньше высота считалась от блока покрытия, и на
    /// ступеньке ход прочищался на клетку выше, чем нужно.
    /// </summary>
    public static IReadOnlyList<BlockPos> Trench(IEnumerable<BlockPos> cells, int level, int height)
    {
        int floor = FeetCell(level);
        var all = new List<BlockPos>();
        foreach (var cell in cells)
            for (int h = 0; h < Math.Max(1, height); h++)
                all.Add(new BlockPos(cell.X, floor + h, cell.Z));
        return all;
    }

    /// <summary>
    /// ВЫЕМКА ПОД ОДИН РЯД — ВСЁ, что вынимают ПЕРВЫМ проходом: и ход над
    /// полотном, и САМУ КЛЕТКУ ПОЛОТНА.
    ///
    /// ЖИВОЙ СЛУЧАЙ, ради которого правило появилось, дословно: «дорогу все
    /// еще моментально ставит — выкопал блок и туда блок дороги, а я просил в
    /// начале копать, а только потом пойти ставить блоки». Два прохода в боте
    /// были и раньше, но первый снимал ОДИН ЛИШЬ ход над полотном
    /// (<see cref="Trench"/>), а на ровном поле над полотном пусто — копать там
    /// нечего. Земля же из-под самого полотна выламывалась укладкой за миг до
    /// установки блока: ровно то «выкопал — и туда же поставил», которое
    /// человек и увидел. Копка первого прохода обязана вынимать ПОСТЕЛЬ
    /// полотна, иначе никакого первого прохода на глаз нет.
    ///
    /// СВЕРХУ ВНИЗ. Снимешь низ раньше верха — верх осыплется на голову
    /// (гравий, песок) и копать придётся дважды.
    ///
    /// <paramref name="height"/> — сколько клеток чистить НАД полотном; ноль
    /// значит «только постель» (так выходит при выключенном
    /// <c>Roads.ClearHeadroom</c>: над дорогой не убираем, но положить полотно
    /// всё равно некуда, пока клетка занята).
    ///
    /// ПОД СТУПЕНЬКОЙ, КОТОРУЮ ДЕРЖИТ ЗЕМЛЯ, НЕ КОПАЕМ ВОВСЕ — прямая просьба
    /// заказчика 19.08: «под ней не выкапывать просто и ставить на природный
    /// блок». Низ выемки поэтому берётся у <see cref="Bottom"/>, второй
    /// арифметики тут нет: копаем ровно до самого нижнего слоя, который сюда
    /// ЛЯЖЕТ (<see cref="Layers"/>), — а у экономной ступеньки этот слой один,
    /// и лежит он на клетку выше.
    /// </summary>
    /// <param name="bedHolds">
    /// Держит ли клетку плиты то, что под ней уже стоит (см. <see cref="Layers"/>).
    /// Спрашивается ПО КЛЕТКЕ: у ряда шириной три склон под краем и под осью
    /// бывает разный, и мерить их одной меркой значило бы копать лишнее там,
    /// где земля держит, или ставить плиту в воздух там, где не держит.
    /// </param>
    public static IReadOnlyList<BlockPos> Cut(IEnumerable<BlockPos> cells, int level, int height,
        Func<BlockPos, bool> bedHolds)
    {
        int floor = FeetCell(level);
        int top = floor + Math.Max(0, height) - 1;
        var all = new List<BlockPos>();
        foreach (var cell in cells)
            for (int y = top, bottom = Bottom(level, bedHolds(cell)); y >= bottom; y--)
                all.Add(new BlockPos(cell.X, y, cell.Z));
        return all;
    }

    /// <summary>
    /// НИЗ ВЫЕМКИ — самая нижняя клетка, которую вынимает первый проход. Она же
    /// клетка САМОГО НИЖНЕГО СЛОЯ ПОЛОТНА: копают ровно до того, что сюда
    /// ляжет, и ни на блок глубже.
    ///
    /// У ровного места это блок под ногами; у ступеньки — он же, пока ей нужен
    /// нижний блок, и КЛЕТКА НОГ, когда не нужен: там ляжет одна плита, а под
    /// ней остаётся нетронутая земля.
    ///
    /// Считается ИЗ <see cref="Layers"/> — второй раскладки тут нет: разойдись
    /// они, и первый проход копал бы не под то, что кладёт второй.
    /// </summary>
    public static int Bottom(int level, bool bedHolds) =>
        Layers(level, bedHolds).Min(l => l.Y);

    /// <summary>
    /// СТОЛБЕЦ ВЫЕМКИ СНИМАЕТСЯ СВЕРХУ ВНИЗ, И НИЖЕ ЗАДЕРЖАННОЙ КЛЕТКИ —
    /// НИЧЕГО. Делит выемку (<see cref="Cut"/>) на «беру сейчас» и
    /// «оставляю на потом».
    ///
    /// ЖИВОЙ СЛУЧАЙ 01:31:00, дословно из журнала:
    ///   «[руки] до (512066, 110, 512241) нет прямой видимости: мешает
    ///    soil-medium-normal в (512066, 111, 512241)»
    ///   «остановка: (512066, 110, 512241) в выемке дороги: до
    ///    soil-medium-none не дотянуться»
    /// Мешающий блок — ЭТО ТОЖЕ БЛОК ВЫЕМКИ, его всё равно предстояло снять.
    /// <see cref="Cut"/> и тогда выдавал столбец сверху вниз, но клетка под
    /// собственными ногами задерживалась (ломать пол под собой — упасть), а
    /// следом бот преспокойно брался за клетку ПОД ней и упирался в свою же
    /// кровлю. Так дорога вниз вставала на первом же ряду десять заходов
    /// подряд.
    ///
    /// Задержана клетка — значит НАД оставшимся в этом столбце стоит порода:
    /// ни рукой достать, ни увидеть. Всё, что ниже, уходит туда же, куда
    /// ушла она.
    ///
    /// <paramref name="hold"/> — «эту клетку сейчас не трогаю» (у дороги это
    /// клетка под ногами). Порядок в обоих списках — сверху вниз, столбец за
    /// столбцом в том же порядке, в каком их назвали: доламывают отложенное
    /// тем же правилом.
    /// </summary>
    public static (IReadOnlyList<BlockPos> Now, IReadOnlyList<BlockPos> Later) TopDown(
        IEnumerable<BlockPos> cells, Func<BlockPos, bool> hold)
    {
        var now = new List<BlockPos>();
        var later = new List<BlockPos>();
        foreach (var column in cells.GroupBy(c => (c.X, c.Z)))
        {
            bool roof = false;      // выше по столбцу осталась неснятая кровля
            foreach (var cell in column.OrderByDescending(c => c.Y))
            {
                if (roof || hold(cell))
                {
                    roof = true;
                    later.Add(cell);
                    continue;
                }
                now.Add(cell);
            }
        }
        return (now, later);
    }

    /// <summary>
    /// НА КАКОЙ ВЫСОТЕ (в полублоках) ОКАЖЕТСЯ ПОЛОТНО У ПОСЛЕДНЕГО РЯДА,
    /// если вести от <paramref name="from"/> к <paramref name="to"/> за
    /// <paramref name="rows"/> рядов.
    ///
    /// ЖИВОЙ СЛУЧАЙ 01:30:57, дословно: «веду по заданной высоте: от 112 к 80,
    /// это 32 бл подъёма на 38 рядов — круче полублока за клетку дорога не
    /// идёт, до конца этот подъём не выберет». Бот ЗАРАНЕЕ знал, что заданный
    /// уклон ему не по силам, и всё равно брался — а потом десять раз подряд
    /// падал. Знание должно быть ЧИСЛОМ, а не присказкой в конце строки:
    /// отсюда и эта функция.
    ///
    /// Считает ровно то же, что <see cref="Levels"/> зажимом «полблока за
    /// ряд»: между 38 рядами всего 37 переходов, и дальше 18,5 бл дорога от
    /// начала не уйдёт, куда её ни зови. Арифметика одна на всех —
    /// <see cref="Lead"/>; здесь только перевод целых высот в полублоки.
    /// </summary>
    public static int Reached(int from, int to, int rows) => Lead(from * 2, to * 2, rows);

    /// <summary>
    /// Сколько рядов нужно, чтобы дорога ВЫБРАЛА такой перепад высоты. Число
    /// для человека: «нужно 65 рядов, а их 38» — это ответ, с которым можно
    /// что-то сделать, в отличие от «до конца не выберет».
    /// </summary>
    public static int RowsToClimb(int from, int to) => Math.Abs(to - from) * 2 + 1;

    /// <summary>
    /// БЛИЖАЙШАЯ ВЫСОТА КОНЦА, ДО КОТОРОЙ ДОРОГА ДОЙДЁТ ЦЕЛИКОМ на этой длине.
    ///
    /// Живой случай 16.08, 20:25–20:29, дословно из журнала: бот трижды подряд
    /// отказал — «от 111 к 80… нужно 63 рядов», потом «к 79… нужно 65 рядов»,
    /// потом «к 92… нужно 39 рядов» — и только с четвёртой попытки, задав 93,
    /// человек угадал число, которое бот знал с самого начала. Отказ, который
    /// называет беду, но не называет выполнимого, заставляет человека
    /// подбирать вручную то, что механизм уже посчитал.
    ///
    /// Считается ИЗ <see cref="Reached"/>, второй арифметики тут нет: докуда
    /// полотно дойдёт — уже известно в полублоках, остаётся округлить это до
    /// целой высоты В СТОРОНУ НАЧАЛА. На спуске 92,5 округляется вверх, до 93:
    /// ниже полотно не опустится, значит 92 так и осталось бы недостижимым.
    /// На подъёме — наоборот, вниз.
    /// </summary>
    public static int NearestEnd(int from, int to, int rows) => WholeEnd(from * 2, to * 2, rows);

    /// <summary>
    /// То же самое, но и начало, и цель — в ПОЛУБЛОКАХ, а ответ целой высотой.
    ///
    /// Отдельной дверью — потому что спрашивают отсюда двое, и у второго
    /// начало не целое: разведка считает выполнимую высоту конца от того
    /// уровня, на котором полотно УЖЕ лежит (<see cref="Roads.OnGroundEnd"/>),
    /// а он бывает и на полублоке.
    /// </summary>
    public static int WholeEnd(int start, int want, int rows)
    {
        double feet = FeetY(Lead(start, want, rows));
        return (int)(want >= start ? Math.Floor(feet) : Math.Ceiling(feet));
    }

    /// <summary>
    /// ЧТО ДОЛЖНО СТОЯТЬ У ГОТОВОГО РЯДА — раскладка «задумано» клетка за
    /// клеткой: полотно твердью, ход над ним пустотой.
    ///
    /// СОБРАНА ИЗ ТЕХ ЖЕ ПРАВИЛ, КОТОРЫМИ РЯД И КЛАЛИ: слои полотна берутся у
    /// <see cref="Layers"/>, ход — у <see cref="Trench"/>. Второй раскладки для
    /// проверки заводить нельзя: она разошлась бы с первой на первой же правке,
    /// и сверка стала бы честно сносить правильно положенное.
    ///
    /// ТВЕРДЬ ПОБЕЖДАЕТ ПУСТОТУ (<see cref="BuildCheck.Merge"/>), и без этого
    /// правила сверка была бы вредна: ход отсчитывается ОТ КЛЕТКИ НОГ, а верх
    /// ступеньки — полублок — в клетке ног и лежит. Иначе собственный полублок
    /// на каждой ступеньке оказался бы «лишним блоком в ходе».
    /// </summary>
    /// <param name="height">
    /// Сколько клеток НАД полотном должно быть чисто. Ноль — над дорогой не
    /// убирали (<c>Roads.ClearHeadroom</c> выключен), и требовать там пустоты
    /// значит требовать того, чего не обещали.
    /// </param>
    /// <param name="bedHolds">
    /// Держит ли клетку плиты то, что под ней уже стоит (см. <see cref="Layers"/>).
    /// Тот же вопрос, что у <see cref="Cut"/>, и задавать его сверке надо ТЕМ
    /// ЖЕ: спроси она иначе — и экономная ступенька, положенная одной плитой,
    /// показалась бы сверке недостачей нижнего блока.
    /// </param>
    public static IReadOnlyList<MeantCell> MeantCells(IEnumerable<BlockPos> cells, int level,
        int height, Func<BlockPos, bool> bedHolds)
    {
        var row = cells.ToList();
        var all = new List<MeantCell>();
        // Ноль — ход не чистили вовсе, и требовать пустоты там, где её не
        // обещали, значит выдумывать себе недостачу. Сам Trench нулевой высоты
        // не знает: ему «ноль» означает «хотя бы клетка ног»
        if (height > 0)
            foreach (var cell in Trench(row, level, height))
                all.Add(new MeantCell(cell, Meant.Clear));
        foreach (var cell in row)
            foreach (var (y, _) in Layers(level, bedHolds(cell)))
                all.Add(new MeantCell(new BlockPos(cell.X, y, cell.Z), Meant.Solid));
        return BuildCheck.Merge(all);
    }

    /// <summary>
    /// ПОСТЕЛЬ — клетка прямо под ногами. У ровного места в ней и лежит блок
    /// покрытия; у ступеньки в ней лежит НИЖНИЙ блок — тот самый, который
    /// нужен, только когда держаться плите больше не на чем.
    ///
    /// «Самый нижний слой полотна» спрашивают не здесь, а у <see cref="Bottom"/>:
    /// у экономной ступеньки постель не трогают вовсе, и звать её низом выемки
    /// значило бы копать ровно то, от чего заказчик и просил избавиться.
    /// </summary>
    public static int Bed(int level) => FeetCell(level) - 1;

    /// <summary>
    /// КУДА ВСТАЮТ НОГИ В УЖЕ ВЫКОПАННОЙ, НО ЕЩЁ НЕ ЗАМОЩЁННОЙ ВЫЕМКЕ —
    /// на клетку НИЖЕ будущего полотна.
    ///
    /// Это не второе имя низа выемки, а другой вопрос с тем же ответом, и
    /// потому он и отвечается через <see cref="Bottom"/>: первый проход
    /// вынимает выемку ДО этой клетки включительно (<see cref="Cut"/>), значит
    /// верхняя оставшаяся твердь — под ней, и ноги стоят в ней самой. Полотно
    /// ляжет сюда только вторым проходом, и до тех пор дно хода ниже дороги.
    ///
    /// ЖИВОЙ СЛУЧАЙ 01:32:26, дословно: «ход выкопан, а к началу дороги
    /// (512067, 112, 512241) я не вернулся — полотно класть неоткуда». Бот шёл
    /// назад на БУДУЩУЮ высоту полотна (112), а стоять в выкопанном ходе можно
    /// было только на 111: цель висела на блок выше пола, и с дна ямы до неё
    /// честно не находилось пути.
    /// </summary>
    /// <param name="bedHolds">
    /// См. <see cref="Layers"/>. У экономной ступеньки под плитой не копали —
    /// значит и дно хода там на блок выше, и звать бота ниже него значит звать
    /// его в твердь.
    /// </param>
    public static int DugFeetCell(int level, bool bedHolds) => Bottom(level, bedHolds);

    /// <summary>Клетка, в которой окажутся ноги на этом уровне.</summary>
    public static int FeetCell(int level) => Half(level);

    /// <summary>Точная высота ног на этом уровне.</summary>
    public static double FeetY(int level) => level / 2.0;

    /// <summary>Деление пополам ВНИЗ: −5 полублоков — это клетка −3, а не −2.</summary>
    private static int Half(int level) => level >= 0 ? level / 2 : (level - 1) / 2;

    // ---------------- узнать полублок и ступень по форме ----------------

    private const float Slop = 0.05f;

    private static bool Near(float a, float b) => Math.Abs(a - b) <= Slop;

    /// <summary>Коробка накрывает клетку целиком по горизонтали.</summary>
    private static bool Wide(BlockBox b) =>
        Near(b.X1, 0) && Near(b.X2, 1) && Near(b.Z1, 0) && Near(b.Z2, 1);

    /// <summary>Коробка накрывает по горизонтали ровно половину клетки.</summary>
    private static bool HalfWide(BlockBox b)
    {
        float ax = b.X2 - b.X1, az = b.Z2 - b.Z1;
        return (Near(ax, 1) && Near(az, 0.5f)) || (Near(az, 1) && Near(ax, 0.5f));
    }

    /// <summary>
    /// Высота «в половину клетки» — но с допуском НА ГЛАЗ, а не до сотой.
    ///
    /// ПОЧЕМУ ТАК ШИРОКО. Приёмка ловила это на живой игре: у каменной плиты
    /// верх 0.5, а у ДОРОЖНОЙ плиты самой игры (stonepathslab) — 0.4375,
    /// потому что всё дорожное покрытие «утоплено» на одну шестнадцатую.
    /// Проверка «ровно 0.5 ± 0.05» не признавала полублоком именно тот
    /// полублок, который бот и должен класть на дорогу: он лежал в сумке, а
    /// бот докладывал «полублоков в сумках нет» и вставал на первой кочке.
    ///
    /// Существенно здесь одно: на такую высоту игрок ВСХОДИТ без прыжка
    /// (<see cref="WorldModel.StepHeight"/> — 0.6), а на целый блок уже нет.
    /// </summary>
    private static bool HalfHigh(float height) => height is >= 0.3f and <= 0.65f;

    /// <summary>
    /// Коробка держит клетку как ПОЛ: во всю ширину, от самого низа и почти
    /// до верха. «Почти» — та же утопленная шестнадцатая у дорожного камня.
    /// </summary>
    private static bool FloorBox(BlockBox b) => Wide(b) && Near(b.Y1, 0) && b.Y2 >= 0.75f;

    /// <summary>
    /// ПОЛОТНО по форме: сплошной пол на всю клетку. Годится и полный куб
    /// (булыжник), и утопленный дорожный камень — по обоим ходят как по полу.
    /// </summary>
    public static bool LooksLikeFloor(IReadOnlyList<BlockBox> boxes) =>
        boxes.Count == 1 && FloorBox(boxes[0]);

    /// <summary>
    /// ПОЛУБЛОК по форме, а не по имени: одна коробка во всю клетку по
    /// горизонтали и примерно в половину по высоте (см. <see cref="HalfHigh"/>).
    ///
    /// По форме — потому что в модах плиту зовут как угодно, а вот полкуба
    /// остаётся полкубом: именно по этой высоте игра решает, всходит на неё
    /// игрок без прыжка или нет.
    /// </summary>
    public static bool LooksLikeSlab(IReadOnlyList<BlockBox> boxes) =>
        boxes.Count == 1 && Wide(boxes[0]) && HalfHigh(boxes[0].Y2 - boxes[0].Y1) &&
        (Near(boxes[0].Y1, 0) || Near(boxes[0].Y2, 1));

    /// <summary>
    /// СТУПЕНЬ по форме: низ во всю клетку примерно в половину высоты плюс
    /// верх в полклетки до самого верха. Ровно те две коробки, по которым
    /// игрок всходит на блок двумя шагами по полблока.
    ///
    /// Допуски широкие по той же причине, что и у полублока: у дорожной
    /// ступени игры (stonepathstairs) коробки 0…0.4375 и 0.4375…0.9375, и
    /// проверка «ровно по половинкам» не признавала ступенью ступень.
    /// </summary>
    public static bool LooksLikeStair(IReadOnlyList<BlockBox> boxes)
    {
        if (boxes.Count < 2)
            return false;
        bool low = false, high = false;
        foreach (var b in boxes)
        {
            if (Wide(b) && Near(b.Y1, 0) && HalfHigh(b.Y2 - b.Y1))
                low = true;
            else if (HalfWide(b) && b.Y1 >= 0.25f && b.Y2 >= 0.75f)
                high = true;
        }
        return low && high;
    }

    /// <summary>Обычный полный куб: ни полублок, ни ступень.</summary>
    public static bool LooksLikeCube(IReadOnlyList<BlockBox> boxes) =>
        boxes.Count == 1 && Wide(boxes[0]) && Near(boxes[0].Y1, 0) && Near(boxes[0].Y2, 1);

    // ---------------- где стоять, пока мостишь ----------------

    /// <summary>
    /// Тело занимает эту клетку полотна: ноги В ней или НА ней. И то и другое
    /// мешает: в клетку со своим телом сервер блок не поставит, а сломать пол
    /// под собой — это упасть в собственную дорогу.
    /// </summary>
    public static bool StandsOn(BlockPos feet, BlockPos floor) =>
        floor == feet || floor == new BlockPos(feet.X, feet.Y - 1, feet.Z);

    /// <summary>Тело мешает хоть одной из клеток, которые сейчас тронем.</summary>
    public static bool InTheWay(BlockPos feet, IEnumerable<BlockPos> busy) =>
        busy.Any(floor => StandsOn(feet, floor));

    /// <summary>
    /// ПОЛ ПРЯМО ПОД НОГАМИ — сломать его значит упасть.
    ///
    /// Отдельно от <see cref="StandsOn"/> нарочно, и разница тут не
    /// придирка. Установке мешают ОБЕ клетки — и та, где ноги, и та, что под
    /// ними: в клетку со своим телом сервер блок не поставит. А копке мешает
    /// только НИЖНЯЯ: траву вокруг собственных ног бот срубает не сходя с
    /// места, и отходить ради неё в сторону на каждом ряду — это не стройка,
    /// а переминание с ноги на ногу.
    /// </summary>
    public static bool FloorUnderFeet(BlockPos feet, IEnumerable<BlockPos> cells) =>
        cells.Any(c => c.X == feet.X && c.Z == feet.Z && c.Y == feet.Y - 1);

    /// <summary>
    /// КУДА СОЙТИ С ПОЛОТНА: годные места из предложенных, ближние первыми.
    ///
    /// Из списка выбрасываются места НА полотне и В полотне — те, где бот
    /// снова окажется в собственной работе. Без этого он сходит на соседнюю
    /// клетку дороги, через ряд сходит с неё снова, и весь заход уходит в
    /// переминание с ноги на ногу.
    ///
    /// Порядок — по числу шагов (вбок плюс по высоте), дальше по координатам,
    /// чтобы выбор был ОДИНАКОВЫМ при одинаковой обстановке: иначе бот
    /// метался бы между двумя равноудалёнными местами.
    /// </summary>
    public static IReadOnlyList<BlockPos> StepOffSpots(BlockPos feet,
        IEnumerable<BlockPos> standable, IReadOnlyCollection<BlockPos> busy) =>
        standable
            .Where(s => s != feet && !InTheWay(s, busy))
            .OrderBy(s => Math.Abs(s.X - feet.X) + Math.Abs(s.Z - feet.Z) + Math.Abs(s.Y - feet.Y))
            .ThenBy(s => s.X).ThenBy(s => s.Z).ThenBy(s => s.Y)
            .ToList();

    /// <summary>
    /// Ноги стоят на этой клетке дороги.
    ///
    /// Допуск в блок вниз — не небрежность. Дорожное покрытие игры утоплено на
    /// одну шестнадцатую (верх коллизии 0.9375), полублок — на половину: ноги
    /// оказываются НИЖЕ верха клетки, и округление вниз роняет «клетку ног» на
    /// единицу. Сравнение на точное равенство считало бы бота не дошедшим до
    /// дороги, по которой он в эту секунду идёт.
    /// </summary>
    public static bool FeetOnRoad(BlockPos feet, BlockPos roadCell) =>
        feet.X == roadCell.X && feet.Z == roadCell.Z &&
        (feet.Y == roadCell.Y || feet.Y == roadCell.Y - 1);

    // ---------------- чем мостить, а чем нельзя ----------------

    /// <summary>Насколько блок годится в дорожное полотно.</summary>
    public enum SurfaceFit
    {
        /// <summary>
        /// ЦЕННОЕ: руда, самородок, металл. Мостить этим нельзя НИКОГДА —
        /// даже если больше нечем и дорога из-за этого не выйдет.
        /// </summary>
        Precious,

        /// <summary>
        /// Полотном не бывает: трава без коллизии, лёд, стекло, ткань, а
        /// также полублок и ступень — у них своя работа на перепадах.
        /// </summary>
        Unfit,

        /// <summary>
        /// Ровный пол обычной скорости: булыжник, доска, земля. Ходить не
        /// быстрее, но и не спотыкаться.
        /// </summary>
        Plain,

        /// <summary>ДОРОГА: игра сама говорит, что по такому блоку быстрее.</summary>
        Road
    }

    /// <summary>
    /// Код без домена: сервер зовёт блок то «game:ore-poor-nativecopper», то
    /// «ore-poor-nativecopper», а разбор кода руды ждёт короткую форму.
    /// </summary>
    public static string ShortCode(string code) => code[(code.IndexOf(':') + 1)..];

    /// <summary>
    /// СМЕНА ПОЛУБЛОКА — ВСЛУХ. Чистое правило: что сказать, когда верх
    /// ступеньки со следующего ряда кладётся уже ДРУГИМ полублоком. null —
    /// говорить не о чем (первый ряд или полублок тот же).
    ///
    /// ЖИВОЙ СЛУЧАЙ, ради которого правило появилось. На выходе бот называет
    /// КОНКРЕТНЫЙ полублок («полублок — andesite-slab ×90 из сумок»), а выбор
    /// пересчитывается на КАЖДОМ ряду со ступенькой и берёт тот, которого
    /// сейчас больше. В сумках дорожная плита ×64 и андезитовая ×90: через
    /// полсотни ступенек андезита стало меньше — и бот молча начинал класть
    /// другое. У полного слоя такой переход давно назван словами
    /// («{code} кончился — перехожу на {more}»), у полублока не было ни строки.
    /// Это тот же класс расхождения слова и дела, что «полублоки пишет, а
    /// крафтит лестницы».
    ///
    /// Числа обязательны: «сменился» без остатков не отвечает на вопрос
    /// человека «а прежний-то кончился или просто отстал по счёту».
    /// </summary>
    /// <param name="was">чем брали перепады до сих пор («» — ещё ничем)</param>
    /// <param name="now">чем берём с этого ряда</param>
    /// <param name="leftOfWas">сколько прежнего осталось в сумках</param>
    /// <param name="haveNow">сколько нового в сумках</param>
    public static string? SlabSwitch(string was, string now, int leftOfWas, int haveNow)
    {
        if (was.Length == 0 || now.Length == 0 ||
            string.Equals(was, now, StringComparison.OrdinalIgnoreCase))
            return null;
        return leftOfWas <= 0
            ? $"полублок {was} кончился — верх ступенек беру {now} ×{haveNow}"
            : $"полублок сменился: был {was} (осталось {leftOfWas}), " +
              $"верх ступенек беру {now} ×{haveNow}";
    }

    /// <summary>
    /// ЦЕННОЕ ЛИ ЭТО. Спрашиваем прежде всего реестр: у руды и у металлических
    /// блоков материал так и записан (Ore, Metal).
    ///
    /// ЖИВОЙ СЛУЧАЙ. Бот только что выкопал жилу и в сумке у него лежала
    /// ore-poor-nativecopper-andesite. Выбор покрытия шёл «самый быстрый блок
    /// из сумок, а быстрых нет — самый многочисленный», и в полотно поехала
    /// медная руда: 81 клетка дороги — это 81 потерянная руда.
    ///
    /// ВТОРОЙ РУБЕЖ — ТОЖЕ РЕЕСТР, А НЕ ПРИСТАВКА КОДА. Здесь стояло
    /// «код начинается на ore-», и на этом мимо проходило ровно то же, что
    /// прошло мимо у наряда: метеорит (meteorite-iron) материалом «Stone» и
    /// приставки не имеет, а стоит пятидесяти единиц металла за кусок — в
    /// полотно такое класть нельзя. Теперь спрашивающий приносит ответ реестра
    /// (<see cref="Metals.MetalInside"/>): у правила чистые руки, а знание
    /// одно на весь проект.
    ///
    /// КОДА В ПОДПИСИ БОЛЬШЕ НЕТ, и это не мелочь: пока он тут стоял, правило
    /// само разбирало строку — и всякий, кто его звал, думал, что имени
    /// достаточно.
    /// </summary>
    /// <param name="material">Материал блока из реестра сервера.</param>
    /// <param name="metalInside">
    /// В блоке или в его выпадениях реестр видит металл. Это и есть второй
    /// рубеж: модовая руда с материалом «камень» и метеорит ловятся им.
    /// </param>
    public static bool IsPrecious(GameMaterial material, bool metalInside) =>
        material is GameMaterial.Ore or GameMaterial.Metal || metalInside;

    /// <summary>
    /// Из чего вообще мостят. Не список кодов, а список МАТЕРИАЛОВ реестра:
    /// камень, кирпич, обожжённая глина, гравий, дерево, песок, земля. Всё
    /// остальное — лёд (скользит и тает), стекло, ткань, растения, жидкости,
    /// мантия (её не выломать) — полотном не бывает.
    /// </summary>
    public static bool IsSurfaceMaterial(GameMaterial material) => material is
        GameMaterial.Stone or GameMaterial.Brick or GameMaterial.Ceramic or
        GameMaterial.Gravel or GameMaterial.Wood or GameMaterial.Sand or GameMaterial.Soil;

    /// <summary>
    /// Насколько материал хорош ПОД НОГАМИ при равной скорости: камень и
    /// кирпич не осыпаются и не горят, песок с землёй — наоборот. Больше —
    /// лучше.
    /// </summary>
    public static int SurfaceGrade(GameMaterial material) => material switch
    {
        GameMaterial.Stone or GameMaterial.Brick => 3,
        GameMaterial.Ceramic or GameMaterial.Gravel => 2,
        GameMaterial.Wood => 1,
        _ => 0
    };

    /// <summary>
    /// Годится ли блок в покрытие — по тому, что о нём говорит реестр игры:
    /// материал, множитель хода и форма коробок коллизии.
    /// </summary>
    /// <param name="boxes">
    /// Коробки коллизии. null или пусто — блок без коллизии (трава, цветок,
    /// деревянная дорожка, которая кладётся ПОВЕРХ пола): полотном не бывает.
    /// </param>
    /// <param name="metalInside">
    /// Ответ реестра «есть ли внутри металл» — второй рубеж ценного
    /// (<see cref="IsPrecious"/>). Приносит его зовущий: у чистого правила
    /// реестра под рукой нет.
    /// </param>
    public static SurfaceFit JudgeSurface(string code, GameMaterial material, float walkSpeed,
        IReadOnlyList<BlockBox>? boxes, bool metalInside)
    {
        _ = code;   // остаётся ради читаемости зовущих: они меряют именно блок
        if (IsPrecious(material, metalInside))
            return SurfaceFit.Precious;
        if (!IsSurfaceMaterial(material) || boxes is not { Count: > 0 } || !LooksLikeFloor(boxes))
            return SurfaceFit.Unfit;
        return walkSpeed > 1f ? SurfaceFit.Road : SurfaceFit.Plain;
    }

    /// <summary>Кандидат в покрытие: что это, сколько его и что о нём знает реестр.</summary>
    /// <param name="Count">Сколько штук под рукой (0 — только рецепт, в сумках нет).</param>
    public sealed record SurfaceOption(string Code, int Count, GameMaterial Material,
        float WalkSpeed, SurfaceFit Fit)
    {
        public override string ToString() =>
            $"{Code}" + (Count > 0 ? $" ×{Count}" : "") +
            $" ({Material}, ход {WalkSpeed:0.##}, {Fit})";
    }

    /// <summary>
    /// ЛУЧШЕЕ ПОКРЫТИЕ ИЗ ПРЕДЛОЖЕННЫХ. Ценное и негодное отбрасывается
    /// ВСЕГДА — даже когда больше положить нечего: пустая дорога и честный
    /// отказ лучше, чем дорога из медной руды.
    ///
    /// Порядок: сперва дорожное (ради скорости дорогу и кладут), потом по
    /// множителю хода, потом по стойкости материала, и только потом по
    /// количеству — чтобы куча земли не побеждала горсть булыжника.
    /// </summary>
    public static SurfaceOption? BestSurface(IEnumerable<SurfaceOption> options) =>
        options
            .Where(o => o.Fit is SurfaceFit.Road or SurfaceFit.Plain)
            .OrderByDescending(o => o.Fit == SurfaceFit.Road)
            .ThenByDescending(o => o.WalkSpeed)
            .ThenByDescending(o => SurfaceGrade(o.Material))
            .ThenByDescending(o => o.Count)
            // Порядок обязан быть УСТОЙЧИВЫМ: иначе два одинаково хороших
            // блока чередуются от ряда к ряду и дорога выходит полосатой
            .ThenBy(o => o.Code, StringComparer.Ordinal)
            .FirstOrDefault();
}
