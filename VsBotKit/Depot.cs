    private BlockPos? Feet => ctx.Self.Position is { } p
        ? new BlockPos((int)Math.Floor(p.X), (int)Math.Floor(p.Y), (int)Math.Floor(p.Z))
        : null;

    /// <summary>Склад вообще задан.</summary>
    public bool Known => Chests.Count > 0;

    /// <summary>
    /// ПРИЗНАКИ ХРАНИЛИЩА В КОДЕ БЛОКА — ЗАПАСНОЙ ОТВЕТ, А НЕ ГЛАВНЫЙ.
    ///
    /// ГЛАВНЫЙ ОТВЕТ ДАЁТ РЕЕСТР СЕРВЕРА: <c>WorldModel.IsContainerBlock</c>
    /// читает атрибут блока <c>inventoryClassName</c> — тот самый, которым
    /// игра и отличает контейнер от мебели. Он знает и <c>stationarybasket</c>
    /// (тростниковый сундук, класс инвентаря «basket»), которого в списке ниже
    /// нет и никогда не было, и модовые ящики, и обожжённый
    /// <c>storagevessel</c>.
    ///
    /// ЧТО ЭТОТ СПИСОК ЛОВИТ ЛИШНЕГО, И ЭТО НАЗВАНО ВСЛУХ: <c>trapcrate</c> —
    /// КОРЗИННАЯ ЛОВУШКА (класс <c>BlockBasketTrap</c>, атрибута
    /// <c>inventoryClassName</c> у неё нет вовсе) — содержит «crate» и по коду
    /// сходит за хранилище. Живьём это значит «склад назначен на ловушку».
    /// Ловушка эта видна ТОЛЬКО когда реестр уже пришёл, а блок ещё не
    /// опознан, — в живом порядке пакетов такого окна почти нет, но список
    /// остаётся догадкой по имени, и держать его надо ровно за то, за что он
    /// заведён: за минуту до реестра, пока сервер ещё не сказал ничего.
    ///
    /// Бочку сюда не берём — она для жидкостей. Кто спрашивает про сундук по
    /// БЛОК-СУЩНОСТИ, идёт к <see cref="Readables.ContainersBySign"/>.
    /// </summary>
    public static readonly string[] StorageMarkers =
        ["chest", "trunk", "storagevessel", "crate"];

    /// <summary>
    /// ЛОВУШКИ И ПРОЧЕЕ, ЧТО НОСИТ СЛОВО ХРАНИЛИЩА, НО ХРАНИЛИЩЕМ НЕ ЯВЛЯЕТСЯ.
    ///
    /// Одно имя, и оно проверено по ассетам 1.22.7: <c>trapcrate</c> — это
    /// <c>BlockBasketTrap</c>, корзинная ловушка на мелкую живность, и
    /// атрибута <c>inventoryClassName</c> у неё нет. Работает список в
    /// БЕЗОПАСНУЮ сторону: лишняя запись здесь значит «не считать складом», а
    /// не «считать».
    /// </summary>
    public static readonly string[] NotStorageCodes = ["trapcrate"];

    /// <summary>
    /// Воздух ли это. Сравниваем ПУТЬ целиком, а не по вхождению: «stairs»
    /// и «chair» содержат «air», и по вхождению лестница оказалась бы пустотой.
    /// </summary>
    public static bool IsAirCode(string? code)
    {
        if (string.IsNullOrEmpty(code))
            return true;
        int colon = code.IndexOf(':');
        return (colon >= 0 ? code[(colon + 1)..] : code)
            .Equals("air", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>Похож ли блок на хранилище по коду (запасной ответ, см. StorageMarkers).</summary>
    public static bool LooksLikeStorage(string? code) =>
        !string.IsNullOrEmpty(code) &&
        !NotStorageCodes.Any(m => code.Contains(m, StringComparison.OrdinalIgnoreCase)) &&
        StorageMarkers.Any(m => code.Contains(m, StringComparison.OrdinalIgnoreCase));

    /// <summary>
    /// Что в точке склада — по тому, что бот про неё знает. Чистое правило:
    /// код блока, есть ли у блок-сущности инвентарь, и как далеко идти.
    ///
    /// Порядок важен. Сначала расстояние: за полмиллиона блоков чанк не
    /// загружен, блок читается воздухом, и без этой проверки бот сказал бы
    /// «пусто, но схожу посмотрю» и потратил бы весь рейс.
    ///
    /// Инвентарь важнее кода: если сервер прислал содержимое, там хранилище,
    /// как бы ни назывался блок (бочка, ящик мода, чужой контейнер).
    ///
    /// «НЕ ЗНАЮ» ВАЖНЕЕ «ПУСТО». Пока модель мира отдавала за незагруженный
    /// чанк воздух, эти два ответа были неразличимы, и склад отвечал про
    /// проверенную пустоту то же, что про непроверенную. Теперь про незнание
    /// спрашивают отдельно (<paramref name="known"/>).
    /// </summary>
    /// <param name="known">пришёл ли боту тот кусок мира (WorldModel.IsKnown)</param>
    public static DepotPoint Judge(string? blockCode, bool hasInventory,
        double? distance, double maxDistance, bool known = true)
    {
        if (distance is { } d && d > maxDistance)
            return DepotPoint.TooFar;
        if (hasInventory)
            return DepotPoint.Storage;
        if (!known)
            return DepotPoint.Unknown;
        if (IsAirCode(blockCode))
            return DepotPoint.Nothing;
        return LooksLikeStorage(blockCode) ? DepotPoint.Storage : DepotPoint.NotStorage;
    }

    /// <summary>
    /// Как назвать точку человеку.
    ///
    /// Бот живёт в абсолютных координатах мира (512258, 111, 511740), а игра
    /// показывает игроку свои (258, 111, −260). В отказе человек обязан узнать
    /// те числа, которые сам вписывал, иначе отказ ему ничего не говорит.
    /// Перевода здесь нет и не будет — он один на весь бот
    /// (VsBot.PlayerCoords); сюда подают готовую подпись. Пока её не подали,
    /// называем мировые координаты как есть: врать про них нельзя.
    /// </summary>
    public Func<BlockPos, string> PointName { get; set; } = p => p.ToString();

    /// <summary>
    /// Сказать про точку по-человечески. Отказ обязан объяснять, ЧТО именно
    /// проверено: «склад не задан» без причины заказчик уже видел, и понять
    /// по нему было нечего.
    /// </summary>
    /// <param name="where">точка так, как её называют человеку (см. <see cref="PointName"/>)</param>
    public static string Explain(DepotPoint what, string where, string? blockCode,
        double? distance)
    {
        string away = distance is { } d ? $"{d:0} бл" : "неизвестно сколько";
        return what switch
        {
            DepotPoint.Storage => string.IsNullOrEmpty(blockCode)
                ? $"в {where} стоит хранилище — годится под склад"
                : $"в {where} стоит {blockCode} — годится под склад",
            DepotPoint.NotStorage =>
                $"в {where} стоит {blockCode}, а не сундук — складывать некуда",
            // СОВЕТ ЗДЕСЬ БЫЛ ПРЯМО ОБРАТНЫМ ПРАВДЕ, и это худший вид отказа:
            // он звучал уверенно и уводил человека ровно туда, откуда его
            // спасали. Стояло «Жду АБСОЛЮТНЫЕ координаты мира (у спавна они
            // около 512000) … их надо переводить». После волны координат ни
            // панель, ни чат, ни пресет абсолютных не ждут: ручка «Склад» —
            // это GamePos, панель подписывает её «игровые» (ControlPanel.CoordsOf),
            // а перевод делает роль (SurvivorRole.ОтнестиСкладБоту → bot.WorldCell).
            // Человек, послушавшийся прежнего совета, вписал бы 512258 — и склад
            // уехал бы за полмиллиона блоков, то есть в тот самый отказ, который
            // он читает. Числа «512000» тут больше нет и по второй причине: оно
            // нигде в игре не зашито, это лишь середина карты обычного размера
            // (см. WorldOrigin) — у мира с другим размером или сдвинутым спавном
            // оно ДРУГОЕ, и называть его человеку значит врать ему уверенно.
            DepotPoint.TooFar =>
                $"до склада {where} {away} — за один рейс не дойти. Координаты я жду " +
                "ИГРОВЫЕ — те самые, что показывает игра; промах в сотни тысяч блоков " +
                "означает, что вписаны мировые: переводить их не надо, впишите игровые",
            // Незнание НАЗЫВАЕТСЯ незнанием. Раньше здесь стояло «пусто: либо
            // сундука нет, либо кусок мира не пришёл» — одна строка на два
            // разных положения, и по ней нельзя было понять, чинить ли склад
            DepotPoint.Unknown =>
                $"про {where} я ничего не знаю: этот кусок мира мне не присылали " +
                $"(до точки {away}) — схожу и посмотрю",
            _ => $"в {where} воздух — сундука там нет (до точки {away})"
        };
    }

    /// <summary>
    /// Расстояние по прямой между клетками. Открыто нарочно: на этом числе
    /// стоит весь потолок <see cref="MaxDistance"/>, и проверять его надо
    /// той же функцией, какой считает бот, а не похожей формулой из теста.
    /// </summary>
    public static double Apart(BlockPos a, BlockPos b)
    {
        double dx = a.X - b.X, dy = a.Y - b.Y, dz = a.Z - b.Z;
        return Math.Sqrt(dx * dx + dy * dy + dz * dz);
    }

    /// <summary>
    /// Что бот видит в точке склада прямо сейчас — ГЛАЗАМИ, а не через стенку.
    ///
    /// «Хранилище тут или нет» решается по ТИПУ блока: код («chest», «crate»)
    /// и признак контейнера из реестра игры. Раньше вопрос звучал иначе —
    /// «прислал ли сервер слоты» — и ответ на него бот получал, не подходя к
    /// сундуку и не открывая его. Это заглядывание внутрь, и живой игрок так
    /// не умеет; вид же снаружи ему доступен вполне.
    /// </summary>
    public DepotPointReport Check(BlockPos pos)
    {
        bool known = ctx.World.IsKnown(pos);
        string? code = ctx.World.GetBlockCode(pos);
        bool inventory = ctx.World.IsContainerBlock(pos.X, pos.Y, pos.Z);
        double? away = Feet is { } here ? Apart(here, pos) : null;
        var what = Judge(code, inventory, away, MaxDistance, known);
        return new DepotPointReport(what, pos, code, away,
            Explain(what, PointName(pos), code, away));
    }

    /// <summary>
    /// ВСЕ ТОЧКИ СКЛАДА ПО ПОРЯДКУ: сперва заданные человеком, а следом —
    /// соседние сундуки в <see cref="NeighbourRadius"/> от каждой, ближние
    /// раньше дальних.
    ///
    /// Порядок держим ровно такой: человек назвал главный сундук, и начинать
    /// надо с него, а по соседям расходиться, только когда он полон.
    ///
    /// Соседей узнаём тем же правилом, что и точку, вписанную руками
    /// (Check → Judge): пока здесь искали слово «chest», бот брал сундук, но
    /// проходил мимо корзины и глиняного сосуда, которые сам же признавал
    /// складом, если их вписать, — одна механика отвечала два разных ответа.
    /// </summary>
    public IReadOnlyList<BlockPos> Points()
    {
        var all = new List<BlockPos>(Chests);
        if (NeighbourRadius <= 0 || Chests.Count == 0)
            return all;

        var known = new HashSet<BlockPos>(Chests);
        foreach (var anchor in Chests)
            ChestsAround(anchor, NeighbourRadius, known, all);
        return all;
    }

    /// <summary>
    /// СУНДУКИ ВОКРУГ ТОЧКИ — одно место на все «поищи рядом»: и соседи склада
    /// (<see cref="Points"/>), и кладовые дома (<see cref="HomePoints"/>)
    /// набираются ровно этим перебором. Вторая копия разошлась бы на первой же
    /// правке: соседей склада уже однажды искали по слову «chest», а вписанную
    /// руками корзину тот же бот складом признавал.
    /// </summary>
    /// <param name="known">что уже взято — сюда же дописываются находки</param>
    /// <param name="into">куда складывать найденное, ближние раньше дальних</param>
    private void ChestsAround(BlockPos anchor, int radius, HashSet<BlockPos> known,
        List<BlockPos> into)
    {
        if (radius <= 0)
            return;
        var min = new BlockPos(anchor.X - radius, anchor.Y - radius, anchor.Z - radius);
        var max = new BlockPos(anchor.X + radius, anchor.Y + radius, anchor.Z + radius);
        // Берём только ВИДИМЫЕ: сквозь стену сундуки знает лишь сервер, а
        // живой игрок находит склад глазами (WorldModel.IsExposed)
        foreach (var be in ctx.World.BlockEntitiesIn(min, max)
                     .OrderBy(be => Apart(anchor, be.Pos)))
        {
            if (!known.Add(be.Pos))
                continue;
            if (Check(be.Pos).What == DepotPoint.Storage)
                into.Add(be.Pos);
        }
    }

    /// <summary>
    /// СУНДУКИ, КОТОРЫЕ БОТ ВИДИТ ВОКРУГ СЕБЯ, ближние раньше дальних. Склад
    /// НЕ ТРОГАЕТ: это ответ на вопрос «что тут стоит», а не «возьми это».
    ///
    /// Заведено ради слова «!склад тут» — и ради самопоиска при входе в мир,
    /// который с 29.08 зовёт ровно его же (<c>LivingRole.ВзятьСкладЗдесь</c>).
    /// Оно берёт ближний сундук ТОЧКОЙ склада, а остальные приходят соседями
    /// (<see cref="Points"/>) — и чтобы назвать человеку честное число, надо
    /// сперва посмотреть, НИЧЕГО НЕ МЕНЯЯ. Способ «найти и сразу взять всё под
    /// склад» здесь жил и убран: он говорил «взято 16», а донесение роли тут же
    /// сводило список к одной точке с соседями — и число было правдой ровно до
    /// следующего мига.
    ///
    /// Перебор тот же самый, что у соседей склада и кладовых дома
    /// (<see cref="ChestsAround"/>): вторая копия однажды разошлась бы, и
    /// «вижу вокруг» стало бы значить не то же, что «беру под склад».
    /// </summary>
    /// <param name="мимо">
    /// сколько блок-сущностей рядом складом НЕ признаны. Число нужно вслух:
    /// «сундуков не нашлось» рядом с бочкой и печью человек читает как поломку
    /// зрения, а «ещё 3 складом не признаны» — как ответ
    /// </param>
    /// <param name="почему">
    /// пусто — искали и вот что нашли; иначе искать было НЕЧЕМ, и пустой список
    /// значит не «сундуков нет», а «своей клетки ещё не знаю»
    /// </param>
    public IReadOnlyList<BlockPos> StorageNear(int radius, out int мимо, out string почему)
    {
        if (Feet is not { } here)
        {
            // Молчаливый пустой список здесь неотличим от «искал и не нашёл», а
            // это разные беды: во втором случае надо ставить сундук, в первом —
            // ждать входа в мир, потому что своей клетки ещё нет
            мимо = 0;
            почему = "где я — пока неизвестно (своя сущность приходит уже после входа в мир)";
            return [];
        }
        почему = "";
        // Запоминаем, ЧТО именно осмотрели: без этого отказ «сундуков рядом не
        // нашлось» назвать радиус не может, а «не искал» и «искал и не нашёл» —
        // разные ответы человеку (см. WhyNoDepot)
        searchedRadius = radius;
        var found = new List<BlockPos>();
        // В «осмотренное» кладётся ВСЁ, что попалось на глаза, а в находки —
        // только хранилища; разница между ними и есть «мимо»
        var осмотрено = new HashSet<BlockPos>();
        ChestsAround(here, radius, осмотрено, found);
        мимо = осмотрено.Count - found.Count;
        return found;
    }

    // ---------------- ДОМ КАК КЛАДОВАЯ ----------------
    //
    // ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ ВТОРЫМ СКЛАДОМ. Заказчик поправил дословно: «если
    // нет ресурсов для стройки и для проекта не отмечен склад с ресурсами, то
    // смотреть дома недостающие». Дом — это НЕ второй словарь складов: точка
    // дома в боте одна (<see cref="Shelter.Home"/>), её доносит роль ручкой
    // «Дом» — той же самой, по которой бот спит, прячется от бури и ставит
    // точку возрождения. Здесь у неё появляется ещё один потребитель, и ни
    // одного нового понятия.
    //
    // Сундуки дома ищутся ТЕМ ЖЕ перебором, что и соседи склада
    // (<see cref="ChestsAround"/>), опись у них ОБЩАЯ со складской, ходит к ним
    // тот же <see cref="TakeAsync"/> — меняется только список точек в обходе.

    /// <summary>
    /// Клетка дома в МИРОВЫХ координатах; null — дом не задан. Доносит роль
    /// (LivingRole.ОтнестиДомБоту) вместе с домом укрытия и бури.
    /// </summary>
    public BlockPos? Home { get; set; }

    /// <summary>
    /// В каком радиусе от дома считать сундуки домашней кладовой, блоков.
    /// Двенадцать — это ДОМ ЦЕЛИКОМ, а не «что под ногами»: сундуки по дальним
    /// углам жилища в такую мерку укладываются, а соседский дом — уже нет.
    ///
    /// Мерка нарочно СВОЯ, а не общая с «сундуками вокруг меня»
    /// (<c>LivingRole.СундукиВокругВРадиусе</c>, 8): там человек СТОИТ у своих
    /// ящиков и меряет от себя, здесь бот меряет от точки дома, в котором его
    /// самого может и не быть.
    /// </summary>
    public int HomeRadius { get; set; } = 12;

    /// <summary>Дом задан и в нём есть куда заглянуть.</summary>
    public bool HomeKnown => Home != null || Chests.Count > 0;

    /// <summary>
    /// ГДЕ ИСКАТЬ ДОМА: постоянный склад роли плюс сундуки вокруг точки дома.
    ///
    /// Постоянный склад входит сюда нарочно. Под временной подменой
    /// (<see cref="UseTemporary"/>) он спрятан из <see cref="Chests"/> — а это
    /// ровно та кладовая, куда бот носит добытое всю остальную жизнь, и «дома»
    /// для него значит именно её.
    /// </summary>
    public IReadOnlyList<BlockPos> HomePoints()
    {
        var all = new List<BlockPos>();
        var known = new HashSet<BlockPos>();
        // Постоянные точки роли — первыми: их назвал человек
        foreach (var pos in temporary != null ? permanent : Chests)
            if (known.Add(pos))
                all.Add(pos);
        foreach (var anchor in all.ToList())
            ChestsAround(anchor, NeighbourRadius, known, all);
        if (Home is { } home)
            ChestsAround(home, HomeRadius, known, all);
        return all;
    }

    /// <summary>
    /// Почему дома взять нечего — по фактам. «Дом не задан» и «дома этого нет»
    /// человек чинит по-разному: первое ручкой в панели, второе — сундуком.
    /// </summary>
    public string WhyNoHome()
    {
        if (Home == null && (temporary != null ? permanent : Chests).Count == 0)
            return "дом не задан: ни точки дома, ни постоянного склада роли мне не давали";
        return Home == null
            ? "точка дома не задана, а в постоянном складе роли идти некуда: " +
              string.Join("; ", (temporary != null ? permanent : Chests).Select(p => Check(p).Reason))
            : $"дома {PointName(Home.Value)} сундуков не видно " +
              $"(искал в радиусе {HomeRadius}; этот кусок мира мне мог и не приходить)";
    }

    /// <summary>Сколько соседних сундуков сейчас взято под склад сверх заданных.</summary>
    public int NeighboursTaken() => Points().Count - Chests.Count;

    /// <summary>Что бот видит во всех точках склада — включая взятых соседей.</summary>
    public IReadOnlyList<DepotPointReport> Verify() => Points().Select(Check).ToList();

    /// <summary>
    /// Сколько мест бот ВИДИТ в точке склада. null — содержимого не видно, и
    /// причин этому три: там не хранилище, чанк ещё не пришёл или — чаще
    /// всего — бот в этот сундук НЕ ЗАГЛЯДЫВАЛ. Пересчитать места в закрытом
    /// сундуке живой игрок не может, и врать про них нельзя: «мест там 15» без
    /// открытия — выдумка, на которой строится решение «иду туда».
    /// </summary>
    public int? FreeSlotsAt(BlockPos pos) =>
        ctx.World.GetContainerContents(pos) is { } inside
            ? Container.FreeSlotsInside(inside)
            : null;

    /// <summary>
    /// Почему нести некуда — по фактам, а не одним словом. Живьём заказчик
    /// получил «склад не задан» ПРИ ЗАДАННОМ складе и не мог понять, что
    /// проверять: ручку в панели, координаты или сундук.
    /// </summary>
    public string WhyNoDepot()
    {
        if (Chests.Count == 0)
            return searchedRadius is { } r
                ? $"склад не задан: точку мне не давали, а сундуков в радиусе {r} " +
                  "вокруг не нашлось"
                : "склад не задан: точку мне не давали (ручка роли пуста или её " +
                  "изменение до меня не доехало), сундуков рядом я не искал";

        string neighbours = NeighbourRadius > 0
            ? $" (соседние сундуки в радиусе {NeighbourRadius} тоже осмотрены, " +
              $"взято под склад {NeighboursTaken()})"
            : " (соседние сундуки брать не велено — NeighbourRadius = 0)";
        return "склад задан, но идти некуда: " +
               string.Join("; ", Verify().Select(p => p.Reason)) + neighbours;
    }

    /// <summary>
    /// СЧИТАТЬ ЛИ НЕУДАЧУ ЖИВОЙ ПОМЕХОЙ. ЧИСТОЕ ПРАВИЛО, И ОНО ОДНО НА ВЕСЬ
    /// РЕЙС: только то, что случилось ПОКА СРОК ЕЩЁ НЕ ВЫШЕЛ.
    ///
    /// ЗАЧЕМ ОГОВОРКА, БЕЗ КОТОРОЙ ВРАНЬЁ ПРОСТО МЕНЯЕТ СТОРОНУ. Живая помеха
    /// нужна сроку затем, чтобы он не вставал на её место
    /// (<see cref="Resume.TimeIsNotACause"/>). Но подходу к сундуку отдаётся
    /// ОСТАТОК ТОГО ЖЕ САМОГО СРОКА (<c>ComeToChestAsync</c>), и подход, в него
    /// не уложившийся, честно говорит «к сундуку не подошёл: время вышло».
    /// Запиши такую неудачу живой помехой — и срок начнёт свидетельствовать о
    /// самом себе: он же и помешал, он же и объяснил, а человек прочтёт «до
    /// склада не дойти» там, где дорога была в порядке и не хватило минуты.
    ///
    /// ОТДЕЛЬНЫМ ПРАВИЛОМ, А НЕ СТРОКОЙ ВНУТРИ ОБХОДА, ПОТОМУ ЧТО ИНАЧЕ ЕГО
    /// НЕЧЕМ СТЕРЕЧЬ: срок, кончающийся ровно посреди попытки подойти, на
    /// стенде не поймать иначе как часами, а стенд с часами краснеет через раз
    /// под полным прогоном. Здесь же вопрос чистый и проверяется в лоб.
    /// </summary>
    /// <param name="now">когда неудача случилась</param>
    /// <param name="deadline">когда кончается срок всего рейса</param>
    public static bool CountsAsLive(DateTime now, DateTime deadline) => now < deadline;

    /// <summary>Сумка набита: свободных мест осталось не больше порога.</summary>
    public static bool BagIsFull(int freeSlots, int haulWhenFreeSlots) =>
        freeSlots <= haulWhenFreeSlots;

    /// <summary>
    /// ЧЕМ КОНЧИЛСЯ РЕЙС — по тому, что осталось в сумке, а не по намерению.
    ///
    /// Живой случай приёмки: сундук склада забит, свободных мест в сумке 4 при
    /// пороге 3. Бот сходил, ничего не положил, вернулся — и рейс считался
    /// удавшимся («сундук не вместил всё — иду к следующему», Success=true),
    /// потому что «полным» рейс признавался только при нуле сложенного И
    /// полной по порогу сумке. Навык «разгрузка» отвечал очередью «сделано»,
    /// и наряд продолжался с полной сумкой.
    ///
    /// Правило простое: груз, ради которого шли, должен был остаться в сундуке.
    /// Хоть один слот вернулся с ботом — это не Done.
    ///
    /// ОТКАЗ ОБЯЗАН НАЗЫВАТЬ ЧИСЛА. Заказчик получил ровно эту строку:
    /// «в сундуки легло 112 шт., а 7 стопок груза остались при мне —
    /// складывать больше некуда», и по ней нельзя было понять ничего: то ли
    /// сундук один и он полон, то ли их пять и перенос сломан. Поэтому сюда
    /// подаются два числа — сколько сундуков осмотрено и сколько мест в них
    /// увидено, — и по второму отличается теснота от несработавшего переноса.
    /// </summary>
    /// <param name="stored">сколько предметов легло в сундуки</param>
    /// <param name="slotsLeft">сколько слотов груза (не своего) осталось в сумке</param>
    /// <param name="lastReason">чем кончился обход сундуков</param>
    /// <param name="chestsInspected">в сколько сундуков бот на самом деле заглянул</param>
    /// <param name="freeSlots">
    /// сколько свободных мест в них увидено; null — не увидено ни одного
    /// содержимого (ни один сундук так и не открылся)
    /// </param>
    public static (HaulStop Stop, string Reason) JudgeHaul(int stored, int slotsLeft,
        string lastReason, int chestsInspected = 0, int? freeSlots = null)
    {
        if (slotsLeft <= 0)
            return (HaulStop.Done, lastReason);

        string put = stored > 0
            ? $"в сундуки легло {stored} шт., а {slotsLeft} стопок груза остались при мне"
            : $"сундуки не взяли ничего: {slotsLeft} стопок груза так и остались при мне";
        string seen = $"осмотрено сундуков: {chestsInspected}";

        // Места есть, а груз не лёг — значит дело не в тесноте. Называть это
        // «склад полон» было бы враньём, и чинил бы человек не то
        if (freeSlots is > 0)
            return (HaulStop.PutFailed,
                $"{put}. {seen}, свободных мест в них видно {freeSlots} — " +
                "тесноты нет, перенос сервер не подтвердил");

        return (HaulStop.DepotFull, freeSlots is null
            ? $"{put}. {seen}, а сколько в них мест — не видно (содержимое не пришло)"
            : $"{put}. {seen}, свободных мест в них не осталось ни одного — " +
              "поставьте ещё сундук рядом или задайте вторую точку склада");
    }

    /// <summary>
    /// ЧЕМ КОНЧИЛСЯ ПОХОД НА СКЛАД ЗА ВЕЩЬЮ — чистое правило, всё числами.
    ///
    /// ЗАЧЕМ ОНО ЗАВЕДЕНО. Заказчик прочитал в журнале:
    ///
    ///     сундук (512061,112,512257) и так под рукой — беру Knife не сходя с места
    ///     trunk-south (512061,112,512257): забрано стопок 0
    ///     …остальные 15: «пусто»
    ///     на складе Knife нет — искал в 16 сундук(ах)
    ///
    /// и ответил: «в сундуке была, в инвентаре была». Врал не сундук — врал
    /// ИТОГ: «искал в 16» бот сказал про сундуки, из которых НИ ОДИН не отдал
    /// опись. По такой строке человек чинит склад, а чинить надо чтение.
    ///
    /// Поэтому «там этого нет» имеет право прозвучать ТОЛЬКО когда опись
    /// прочитана целиком. Иначе честный ответ — «не знаю», и он должен назвать,
    /// сколько сундуков промолчало.
    /// </summary>
    /// <param name="wanted">часть кода предмета: «pickaxe», «gear-temporal»</param>
    /// <param name="got">на сколько штук прибавилось в сумках — ПО ФАКТУ</param>
    /// <param name="need">сколько надо иметь при себе всего</param>
    /// <param name="had">сколько было при себе до похода</param>
    /// <param name="chests">сколько точек склада было в обходе</param>
    /// <param name="reached">до скольких бот дошёл (или дотянулся)</param>
    /// <param name="read">сколько сундуков ОТДАЛИ опись</param>
    /// <param name="unread">сколько открылись, но опись так и не прислали</param>
    /// <param name="byNote">
    /// Сколько сундуков НЕ ОТКРЫВАЛИ ВОВСЕ, ответив по свежей записи описи.
    ///
    /// Отдельно от <paramref name="reached"/> нарочно: «дошёл» и «знаю» —
    /// разные вещи, и путать их нельзя ни в отказе, ни в счёте. Без этого
    /// числа рейс, целиком отвеченный по памяти, выходил бы «до склада не
    /// дошёл ни разу» — то есть враньём наоборот.
    /// </param>
    public static (TakeStop Stop, string Why) JudgeTake(string wanted, int got, int need,
        int had, int chests, int reached, int read, int unread, int byNote = 0)
    {
        if (got > 0)
            return (TakeStop.Got, $"взял со склада {wanted} ×{got} (было {had}, надо {need})" +
                                  (had + got < need
                                      ? $" — это меньше, чем надо: не хватает {need - had - got}"
                                      : ""));

        // «НИ РАЗУ НЕ ДОШЁЛ» — только если и знать было неоткуда. Сундук,
        // пропущенный по свежей записи, — это не недостижимый сундук, а
        // сэкономленный поход
        if (reached == 0 && byNote == 0)
            return (TakeStop.NoRoute,
                $"до склада за {wanted} не дошёл ни разу (точек в обходе {chests})");

        // МЕРКА ОТКАЗА — ПРОЧИТАННЫЕ, А НЕ «НИКТО НЕ ПРОМОЛЧАЛ».
        //
        // Приёмка поймала это на живом случае: путь просился В КЛЕТКУ сундука,
        // и все шестнадцать оказались недостижимы, кроме одного — до которого
        // бот дотянулся рукой. Сундук, до которого не дошли, не попадает ни в
        // reached, ни в unread; так же выпадают и те, до кого обход не добрался
        // (кончился срок рейса, отменили). По условию «unread == 0» отказ
        // выходил категоричным, да ещё и спорил сам с собой: «на складе Knife
        // нет: опись прочитана во всех 1 сундук(ах) из 16».
        //
        // Считаем ровно то, что проверено: сколько сундуков ОТДАЛИ опись. Не
        // все — значит ответ «не знаю», и он обязан назвать обе недостачи:
        // промолчавших и тех, до кого не добрались.
        if (read < chests)
        {
            int unseen = Math.Max(0, chests - reached);
            var чего = new List<string>();
            if (unread > 0)
                чего.Add($"{unread} открыл, а описи от них не дождался");
            if (unseen > 0)
                чего.Add($"до {unseen} не добрался вовсе");
            return (TakeStop.Unread,
                $"{wanted} со склада не взял, и «его там нет» сказать не могу: " +
                $"опись прочитана в {read} сундук(ах) из {chests}" +
                (чего.Count > 0 ? $" — {string.Join("; ", чего)}" : "") +
                "; что внутри остальных, НЕ ЗНАЮ");
        }

        return (TakeStop.NotThere,
            $"на складе {wanted} нет: опись прочитана во всех {chests} сундук(ах)");
    }

    /// <summary>Про полную сумку без склада уже жаловались — второй раз незачем.</summary>
    private bool complainedFullNoDepot;

    /// <summary>
    /// Пора нести: свободных мест осталось меньше порога И есть куда.
    ///
    /// Когда нести некуда, бот об этом ГОВОРИТ, а не просто отвечает «нет».
    /// Со стороны «сумка полна, склада нет» выглядело как «бот сам по себе
    /// перестал копать»: наряд спрашивает это в цикле и на «нет» молча идёт
    /// добывать дальше — в сумку, куда уже ничего не влезет. Жалуемся один
    /// раз на положение, а не каждый оборот цикла, иначе журнал не прочесть.
    /// </summary>
    public bool TimeToHaul()
    {
        bool full = BagIsFull(ctx.Self.FreeCarrySlots(), HaulWhenFreeSlots);
        if (full && !Known)
        {
            if (!complainedFullNoDepot)
            {
                complainedFullNoDepot = true;
                OnLog?.Invoke("сумка полна, а нести некуда: " + WhyNoDepot());
            }
            return false;
        }
        complainedFullNoDepot = false;
        return full;
    }

    /// <summary>
    /// Своё по маске кода: кирка, лопата, топор, факелы. Правило чистое —
    /// только код и список масок, — и цена ошибки в нём велика: сданная на
    /// склад кирка означает поход обратно с пустыми руками.
    /// </summary>
    public static bool KeptByMask(string code, IEnumerable<string> masks) =>
        masks.Any(m => code.Contains(m, StringComparison.OrdinalIgnoreCase));

    /// <summary>
    /// Оставить ли это при себе — чистое правило: всё, что оно спрашивает у
    /// мира, подано сюда числами.
    ///
    /// Вынесено отдельно потому, что цена ошибки велика (сданная на склад
    /// кирка означает поход обратно с пустыми руками), а проверить решение на
    /// живом сервере нельзя — реестр предметов приходит только оттуда.
    /// </summary>
    /// <param name="durability">запас прочности по реестру (0 — не инструмент)</param>
    /// <param name="safeFood">еда, которая питает и не отнимает здоровье</param>
    public static bool Keep(string code, IEnumerable<string> masks, bool keepTools,
        bool keepFood, int durability, bool safeFood) =>
        KeptByMask(code, masks) ||
        // Прочность есть только у инструментов и оружия — по ней узнаётся и
        // модовый молот, которого нет ни в одной маске
        (keepTools && durability > 0) ||
        (keepFood && safeFood);

    /// <summary>
    /// Оставить ли это при себе ХОТЬ СКОЛЬКО-НИБУДЬ. Инструмент, факелы и еда
    /// — да; порода, руда и прочая добыча — нет, за ней и шли.
    ///
    /// ЭТО ВОПРОС ПРО РОД. Сколько именно штук остаётся при боте, а сколько
    /// едет в сундук, отвечает <see cref="Cargo"/> — и рейс спрашивает ЕГО.
    /// </summary>
    public bool Keep(string code) =>
        Keep(code, KeepMasks, KeepTools, KeepFood,
            ctx.World.Durability(code), ctx.World.IsSafeFood(code)) ||
        // ЧТО ВЕЛЕНО ДЕРЖАТЬ ПРИ СЕБЕ — ТО И МОЁ, и это не удобство, а сведение
        // двух списков в один. «Что моё» склад мерил своими масками («pickaxe,
        // shovel, axe, torch»), а «что держать» живёт в запасах — и совпадали
        // они ровно до тех пор, пока их писала одна рука. Потребовали 64
        // лестницы — склад начал сдавать их в сундук: лестницы ни в одной маске
        // не значатся. Сделанные боту стрелы уехали бы туда же в первый рейс, и
        // он пошёл бы делать новые: то самое метание, на которое заказчик
        // жаловался.
        //
        // Правило (Keep выше) остаётся ЧИСТЫМ и проверяется без сервера; здесь
        // только второй источник того же вопроса. Запасы могут быть ещё не
        // собраны (склад заводится раньше их) — тогда ответ прежний
        (ctx.Stock is { } запасы && запасы.Wanted(code));

    /// <summary>
    /// СКОЛЬКО ШТУК ЭТОГО — ГРУЗ, то есть поедет на склад. Ноль — всё моё,
    /// с места не схожу.
    ///
    /// ПОЧЕМУ ВОПРОС ПЕРЕДЕЛАН ИЗ «ЧЬЁ ЭТО» В «СКОЛЬКО ИЗ ЭТОГО МОЁ». Здесь
    /// стоял мой же честный отказ: «Wanted отвечает „моё“ на любое количество:
    /// бот, подбирающий отстрелянные стрелы, накопит их сколько угодно».
    /// Именно так и было — сумка забивалась, а рейс на склад отвечал «в сумке
    /// только своё — нести нечего», потому что и одна стрела, и четыреста
    /// давали складу одно и то же слово «моё». Теперь ответ — ЧИСЛО, и берётся
    /// оно из того же списка требований (<see cref="Stock.SurplusOf(string)"/>),
    /// а не из второго списка «сколько чего носить»: такого списка в проекте
    /// нет и заводить его нельзя.
    ///
    /// ПОРЯДОК ВОПРОСОВ ВАЖЕН, И ЧИСЛО СИЛЬНЕЕ РОДА. Спросить сперва маски
    /// («pickaxe, shovel, axe, torch») значило бы оставить починку без силы:
    /// факел и лестница попадают и в маску, и в требования, и маска «моё
    /// целиком» перебила бы любое число. Поэтому: сказали ли ЧИСЛОМ — держимся
    /// числа; не сказали — решают маски, прочность и съедобность, как решали
    /// всегда.
    ///
    /// ЧЕГО ЭТО НЕ УМЕЕТ, И Я ГОВОРЮ ЭТО ВСЛУХ. У вещи, про которую в
    /// требованиях НЕТ НИ СЛОВА, а маска есть, количество по-прежнему любое:
    /// сотня факелов при пустой ручке «ДержатьФакелов» так и останется при
    /// боте. Числа для неё взять неоткуда — маска это род, а не счёт, — и
    /// выдумывать его здесь значило бы завести ту самую вторую запись.
    /// Лечится это не кодом, а ручкой: впишите вещь в запас (например,
    /// «ЗапасПоРасходу: torch»), и излишек поедет в сундук.
    /// </summary>
    public int Cargo(string? code)
    {
        if (code is not { Length: > 0 })
            return 0;
        if (ctx.Stock is { } запасы && запасы.Wanted(code))
            return запасы.SurplusOf(code);
        if (Keep(code))
            return 0;
        // ДОБЫЧА ЕДЕТ ВСЯ. Число всё равно называем настоящее, а не «сколько
        // угодно»: им же меряется и отчёт о рейсе, и «всё ли сложил»
        return ctx.Hands.CountExactly(code);
    }

    /// <summary>
    /// ЧТО ОСТАВЛЯТЬ ПРИ СЕБЕ — одной строкой от роли: «pickaxe, shovel, axe,
    /// torch». Возвращает ответ СЛОВАМИ: что понято и что из этого следует.
    ///
    /// Почему строкой и с ответом. Список масок — политика роли, а роль доносит
    /// свои решения на КАЖДЫЙ поворот любой ручки в окне; список поэтому
    /// перекладывается ЦЕЛИКОМ (стёртое из строки стирается и из масок), иначе
    /// снятая маска жила бы до перезапуска. А молча принятая строка неотличима
    /// от неработающей настройки — потому механизм и отвечает словами, а не
    /// кивком.
    ///
    /// ПУСТАЯ СТРОКА — ЭТО НЕ «ОСТАВЛЯТЬ ВСЁ», а «масок нет»: своим тогда
    /// считается только то, что узнаётся по прочности
    /// (<see cref="KeepTools"/>) и по съедобности (<see cref="KeepFood"/>).
    /// Факел прочности не имеет и в этом случае уедет в сундук — об этом здесь
    /// и сказано вслух.
    ///
    /// Механики тут ровно столько: разбор строки. Ни одного кода предмета
    /// библиотека при этом не выдумывает — что писать, решает роль.
    /// </summary>
    public string KeepAtHand(string? list)
    {
        var masks = (list ?? "").Split(',',
                StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Select(m => m.ToLowerInvariant())
            .Distinct(StringComparer.Ordinal)
            .ToList();

        KeepMasks.Clear();
        KeepMasks.AddRange(masks);

        string ещё = (KeepTools, KeepFood) switch
        {
            (true, true) => "всё, у чего есть прочность, и еду",
            (true, false) => "всё, у чего есть прочность",
            (false, true) => "еду",
            _ => ""
        };
        if (masks.Count > 0)
            return "при себе оставляю: " + string.Join(", ", masks) +
                   (ещё.Length > 0 ? "; и " + ещё : "");
        return ещё.Length > 0
            // Факел назван тут не для красоты: он не инструмент, прочности не
            // имеет и первым же рейсом уедет в сундук — а бот вернётся в
            // тёмный забой без света и не увидит в стене руду
            ? $"по названию при себе не оставляю ничего — только {ещё}. " +
              "Факел прочности не имеет и уедет в сундук"
            : "при себе не оставляю НИЧЕГО: на склад уедут и кирка, и еда — " +
              "в забой я вернусь с пустыми руками";
    }

    // ---------------- ОПИСЬ СКЛАДА ----------------
    //
    // ЗАЧЕМ ОНА ЕСТЬ. Прямая просьба заказчика: «каждое возвращение домой
    // сканировать все сундуки и записывать, чтобы потом ориентироваться, нужно
    // домой чтобы что-то взять или нет».
    //
    // Живой случай, ради которого это писалось (заход 22:32): боту понадобилась
    // временная шестерёнка. Он пошёл домой и перебрал ВСЕ ШЕСТНАДЦАТЬ сундуков
    // подряд, открывая каждый, — потому что не помнил, что в них лежит. Ни
    // одной шестерёнки там не было. Весь рейс ушёл на то, чтобы выяснить это
    // заново, и так на каждый заход.
    //
    // ЭТО НЕ ЧИТ. Заглядывать в закрытый сундук бот по-прежнему не умеет (см.
    // WorldModel.MayLookInside): в опись попадает только то, что он ОТКРЫЛ САМ.
    // Живой игрок помнит содержимое сундука, в который заглядывал, — и ровно
    // так же не знает, что туда положили после него. Поэтому у каждой записи
    // есть время осмотра, и решение считает её возраст.

    /// <summary>
    /// Опись по клеткам. Ключ — та же точка, что и у сундука; двух записей на
    /// один сундук не бывает, новая перекрывает старую.
    /// </summary>
    private readonly Dictionary<BlockPos, DepotShelf> shelves = [];

    /// <summary>
    /// Опись пишет бот, а читает опрос из браузера своим потоком — панель
    /// показывает её живьём. Без замка чтение падало бы посреди записи.
    /// </summary>
    private readonly Lock shelvesLock = new();

    /// <summary>
    /// Сколько минут запись описи считается свежей. Свежий сундук осмотр
    /// пропускает: обходить шестнадцать сундуков на каждый рейс, когда их
    /// смотрели минуту назад, — та же беготня, только наоборот.
    /// </summary>
    public double ScanFreshMinutes { get; set; } = 5;

    /// <summary>
    /// Через сколько минут ответ «этого там нет» перестаёт быть ответом.
    ///
    /// Мерка нужна только ОТРИЦАТЕЛЬНОМУ ответу, и вот почему. «Там лежит
    /// шестерёнка» устаревает не страшно: сходил и не нашёл — потерял рейс.
    /// «Там шестерёнки нет» устаревает опасно: по старой записи бот откажется
    /// идти за вещью, которую хозяин положил в сундук десять минут назад.
    /// </summary>
    public double ScanStaleMinutes { get; set; } = 30;

    /// <summary>
    /// Осматривать сундуки склада при каждом возвращении домой. Это и есть
    /// заказанное «каждое возвращение домой сканировать все сундуки».
    /// </summary>
    public bool ScanOnHaul { get; set; } = true;

    /// <summary>
    /// Сколько секунд отводится на осмотр склада. Потолок нужен: шестнадцать
    /// сундуков по четыре секунды — это минута, и без потолка опись съедала бы
    /// рейс, ради которого бот пришёл.
    /// </summary>
    public double ScanSeconds { get; set; } = 60;

    /// <summary>
    /// ПОДХОДИТ ЛИ КОД ПОД ИСКОМОЕ — одна мерка на всю работу со складом:
    /// и «взять со склада» (<see cref="TakeAsync"/>), и опись, и счёт того, что
    /// уже в сумке, спрашивают ЗДЕСЬ. Разойдись они — опись отвечала бы
    /// «шестерёнка есть» про то, чего «взять» не берёт.
    ///
    /// ДВА ВИДА ИСКОМОГО, и путать их нельзя:
    ///
    /// 1. КУСОК КОДА («pickaxe», «gear-temporal») — так спрашивает человек и
    ///    ручки роли. Ищется вхождением: «pickaxe» находит «game:pickaxe-copper».
    ///
    /// 2. КОД-ОБРАЗЕЦ ИЗ РЕЦЕПТА («stone-*», «soil-*») — так называет материал
    ///    сам сервер, и другого имени у ингредиента НЕТ. Ищется по правилам
    ///    игры (Vintagestory.API.Util.WildcardUtil.Match: домены обязаны
    ///    совпасть, путь сверяется целиком, «*» закрывает остаток).
    ///
    /// ЖИВОЙ СЛУЧАЙ 15.08, ради которого пункт 2 и появился: «там было всё для
    /// крафта дороги, а он не стал туда возвращаться». Дорожный камень —
    /// «stone-*» плюс «soil-*»; вхождением «soil-*» не находится НИ В ОДНОМ
    /// коде мира (звёздочка в кодах не встречается), и склад с двумя сундуками
    /// земли честно отвечал «этого тут нет». А вхождением БЕЗ звёздочки
    /// («stone-») нашёлся бы и «cobblestone-granite», которого рецепт не примет,
    /// — бот сходил бы за булыжником и снова не смог доделать. Поэтому образец
    /// сверяется целиком, как это делает сама игра.
    /// </summary>
    public static bool Suits(string? code, string wanted)
    {
        if (code is not { Length: > 0 } c || wanted.Length == 0)
            return false;
        return wanted.Contains('*')
            ? FitsPattern(c, wanted)
            : c.Contains(wanted, StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>
    /// Сверка с кодом-образцом рецепта — по правилам игры
    /// (<see cref="Vintagestory.API.Util.WildcardUtil"/>). Отдельным методом
    /// затем, что образец приходит от сервера в любом виде, а разбор адреса
    /// (<c>AssetLocation</c>) на мусоре бросает исключение: опись, упавшая
    /// посреди обхода склада, — это потерянный рейс.
    /// </summary>
    public static bool FitsPattern(string code, string pattern)
    {
        try
        {
            return Vintagestory.API.Util.WildcardUtil.Match(
                new Vintagestory.API.Common.AssetLocation(pattern),
                new Vintagestory.API.Common.AssetLocation(code),
                null);
        }
        catch (Exception)
        {
            return false;
        }
    }

    /// <summary>
    /// СКОЛЬКО ИСКОМОГО УЖЕ ПРИ СЕБЕ — ТОЙ ЖЕ МЕРКОЙ, ЧТО И НА ПОЛКЕ.
    ///
    /// Не украшение: <c>Hands.CountOf(строка)</c> ищет ВХОЖДЕНИЕМ и про
    /// звёздочку рецепта не знает. Спроси его про «soil-*» — ответом всегда
    /// будет ноль, даже когда сумка полна земли, и бот пошёл бы на склад за
    /// тем, что у него в руках, а вернувшись — снова за тем же.
    /// </summary>
    public int AtHand(string wanted) =>
        ctx.Hands.CountOf(s => Suits(s.Code, wanted));

    /// <summary>
    /// Пересчитать слоты в опись: что и сколько, и сколько мест свободно.
    /// Чистое правило — его проверяют тестом, не поднимая ни мира, ни сервера.
    /// </summary>
    public static (Dictionary<string, int> Items, int Free) Tally(
        IReadOnlyList<SlotContent>? slots)
    {
        var items = new Dictionary<string, int>(StringComparer.Ordinal);
        int free = 0;
        foreach (var s in slots ?? [])
        {
            if (s.IsEmpty || s.Code is not { Length: > 0 } code)
            {
                free++;
                continue;
            }
            items[code] = items.TryGetValue(code, out int had) ? had + s.Count : s.Count;
        }
        return (items, free);
    }

    /// <summary>
    /// «Когда смотрел» по-человечески. Числа в минутах человек читает плохо:
    /// «смотрел 143 мин назад» ничего ему не говорит.
    /// </summary>
    public static string Ago(double minutes)
    {
        if (minutes < 1)
            return "только что";
        if (minutes < 60)
            return $"{minutes:0} мин назад";
        return $"{minutes / 60:0.#} ч назад";
    }

    /// <summary>
    /// ЗАПИСАТЬ В ОПИСЬ то, что бот видел в сундуке. null вместо содержимого —
    /// значит не увидел (не открылся, не дотянулся, чанка нет), и записи не
    /// будет: выдумывать пустой сундук нельзя, «пусто» и «не смотрел» —
    /// разные ответы, на которых всё это и держится.
    /// </summary>
    /// <remarks>
    /// СЛОТЫ СЮДА ПОДАЮТ ТОЛЬКО ЖИВЫЕ — те, что сервер прислал в ответ на наше
    /// открытие (<see cref="Container.OpenAndPeekAsync"/>). Данные чанка сюда
    /// нести нельзя: модель мира кладёт блок-сущность в память один раз, когда
    /// чанк пришёл, и больше её не трогает, — по ним бот уже докладывал «пусто»
    /// про сундук, куда сам же сложил тысячу предметов часом раньше.
    /// </remarks>
    public DepotShelf? Note(BlockPos pos, IReadOnlyList<SlotContent>? inside)
    {
        if (inside == null)
            return null;
        var (items, free) = Tally(inside);
        var shelf = new DepotShelf(pos, items, inside.Count, free, DateTime.UtcNow);
        lock (shelvesLock)
            shelves[pos] = shelf;
        return shelf;
    }

    /// <summary>Вся опись, свежие записи раньше старых. Снимок — панель читает своим потоком.</summary>
    public IReadOnlyList<DepotShelf> Shelves
    {
        get
        {
            lock (shelvesLock)
                return shelves.Values.OrderByDescending(s => s.Seen).ToList();
        }
    }

    /// <summary>Что записано про этот сундук (null — не заглядывали ни разу).</summary>
    public DepotShelf? ShelfAt(BlockPos pos)
    {
        lock (shelvesLock)
            return shelves.TryGetValue(pos, out var shelf) ? shelf : null;
    }

    /// <summary>
    /// Забыть запись про сундук: его сломали или он оказался не тем. Без этого
    /// опись врала бы про несуществующее хранилище.
    /// </summary>
    public bool ForgetShelf(BlockPos pos)
    {
        lock (shelvesLock)
            return shelves.Remove(pos);
    }

    /// <summary>Забыть опись целиком (переподключение, смена мира).</summary>
    public void ForgetShelves()
    {
        int had;
        lock (shelvesLock)
        {
            had = shelves.Count;
            shelves.Clear();
        }
        if (had > 0)
            OnLog?.Invoke($"опись склада забыта ({had} сундук(ов)) — посмотрю заново");
    }

    /// <summary>Сколько этого добра лежит по описи во всех осмотренных сундуках.</summary>
    public int InDepot(string wanted) => Shelves.Sum(s => s.CountOf(wanted));

    /// <summary>Где именно это лежит по описи — сундуки, в которых оно записано.</summary>
    public IReadOnlyList<BlockPos> WhereIs(string wanted) =>
        Shelves.Where(s => s.CountOf(wanted) > 0).Select(s => s.Pos).ToList();

    /// <summary>
    /// ИДТИ ЛИ НА СКЛАД ЗА ЭТИМ — чистое правило, ради которого опись и
    /// заводилась. Всё, что оно спрашивает у мира, подано сюда числами: это
    /// решение стоило заказчику целого рейса за шестерёнкой, и проверять его
    /// надо тестом, а не прогоном в игре.
    ///
    /// Порядок ответов важен:
    ///   1) уже при себе — никуда не идём, что бы ни лежало на складе;
    ///   2) по описи ЕСТЬ — идём, даже если запись стара: сходить и не найти
    ///      дешевле, чем не пойти за нужным;
    ///   3) описи нет вовсе / она неполная / она стара — НЕ ЗНАЮ, надо
    ///      сходить посмотреть. Это не то же самое, что «там нет»;
    ///   4) и только когда опись свежая и полная — честное «там этого нет».
    /// </summary>
    /// <param name="wanted">часть кода предмета: «pickaxe», «gear-temporal»</param>
    /// <param name="need">сколько надо иметь при себе всего</param>
    /// <param name="inBag">сколько уже при себе</param>
    /// <param name="inDepot">сколько насчитала опись</param>
    /// <param name="shelvesSeen">про сколько сундуков склада есть запись</param>
    /// <param name="shelvesTotal">сколько сундуков в складе сейчас</param>
    /// <param name="ageMinutes">возраст самой старой записи, минут</param>
    /// <param name="staleMinutes">после скольких минут «там нет» уже не ответ</param>
    public static DepotErrand JudgeErrand(string wanted, int need, int inBag, int inDepot,
        int shelvesSeen, int shelvesTotal, double ageMinutes, double staleMinutes,
        IReadOnlyList<BlockPos>? where = null)
    {
        where ??= [];

        if (inBag >= need)
            return new DepotErrand(DepotTrip.NotNeeded, wanted, need, inBag, inDepot, where,
                $"{wanted} и так при мне ×{inBag} (надо {need}) — на склад незачем");

        if (inDepot > 0)
            return new DepotErrand(DepotTrip.Go, wanted, need, inBag, inDepot, where,
                $"по описи {wanted} на складе ×{inDepot}" +
                (where.Count > 0 ? $" (в {string.Join("; ", where)})" : "") +
                $", смотрел {Ago(ageMinutes)} — иду за ним" +
                (inBag > 0 ? $"; при мне уже {inBag} из {need}" : ""));

        if (shelvesSeen == 0)
            return new DepotErrand(DepotTrip.Unknown, wanted, need, inBag, inDepot, where,
                shelvesTotal > 0
                    ? $"описи склада нет: ни в один из {shelvesTotal} сундуков я не " +
                      $"заглядывал — надо сходить и посмотреть, есть ли там {wanted}"
                    : $"описи склада нет, и самого склада тоже — про {wanted} сказать нечего");

        if (shelvesSeen < shelvesTotal)
            return new DepotErrand(DepotTrip.Unknown, wanted, need, inBag, inDepot, where,
                $"{wanted} нет в описанных сундуках, но описано их {shelvesSeen} из " +
                $"{shelvesTotal} — в остальные я не заглядывал, надо сходить и посмотреть");

        if (ageMinutes > staleMinutes)
            return new DepotErrand(DepotTrip.Unknown, wanted, need, inBag, inDepot, where,
                $"по описи {wanted} на складе не было, но смотрел я {Ago(ageMinutes)} " +
                $"(старее {staleMinutes:0} мин) — за это время могли положить, схожу проверю");

        return new DepotErrand(DepotTrip.NotThere, wanted, need, inBag, inDepot, where,
            $"{wanted} на складе нет: опись свежая ({Ago(ageMinutes)}), осмотрены все " +
            $"{shelvesTotal} сундук(ов) — домой за этим не пойду");
    }

    /// <summary>
    /// ПО КАКИМ ТОЧКАМ СКЛАДА СЧИТАЕТСЯ ОПИСЬ. Не по всем заданным: точка, в
    /// которой бот СВОИМИ ГЛАЗАМИ увидел, что сундука там нет, — не сундук, и
    /// ждать от неё записи бессмысленно.
    ///
    /// ЖИВОЙ АФК 27.08, словами заказчика: «задал, поотносил несколько раз всё
    /// на склад и стоит афк в карьере». Склад отмечают ТАМ, ГДЕ СТОИШЬ («!склад
    /// тут» и поле в окне берут клетку под ногами), а сундуки бот добирает
    /// ВОКРУГ отметки (<see cref="Points"/> → ChestsAround). Значит сама
    /// отметка — пол, и заглянуть в неё нельзя НИКОГДА. Вот три строки его
    /// журнала подряд, 23:15:12, все в одну миллисекунду:
    ///     опись говорит: Pickaxe нет в описанных сундуках, но описано их
    ///         16 из 17 — в остальные я не заглядывал, надо сходить и посмотреть
    ///     в 16 сундук(ах) Pickaxe нет по описи … — туда не иду
    ///     на складе Pickaxe нет: опись прочитана во всех 16 сундук(ах)
    /// Семнадцатая точка — (62, 112, 254), его же отметка склада, про которую
    /// тот же бот в том же журнале говорит «туда не иду: в (62, 112, 254)
    /// воздух — сундука там нет». «Опись полна» стало недостижимым НАВСЕГДА,
    /// <see cref="JudgeErrand"/> ни разу не ответил «этого тут нет», и бот на
    /// КАЖДУЮ вещь заново собирался идти смотреть — и никуда не шёл, потому что
    /// обход ту же точку выбрасывал. Так он и простоял вечер: 21 круг за fat,
    /// 21 за fish-raw, 21 за grain-rye, 6 за ladder, 5 за киркой.
    ///
    /// МЕРКА ТУТ ТА ЖЕ, ПО КАКОЙ СТРОИТСЯ ОБХОД
    /// (<see cref="DepotPointReport.WorthGoing"/>), и это главное: считать опись
    /// по одним точкам, а ходить по другим — значит завести два счёта об одном
    /// складе, которые не сойдутся никогда. Неизвестное (кусок мира ещё не
    /// приходил) в счёт идёт по-прежнему: туда бот и правда пойдёт смотреть, и
    /// отвечать «этого тут нет», не заглянув, нельзя.
    ///
    /// Спрашивают отсюда оба, кто считает опись, — и решение
    /// (<see cref="Ask"/>), и строка человеку (<see cref="Inventory"/>): иначе
    /// окно показывало бы «сундуков 16 из 17» рядом с «осмотрены все 16».
    /// <see cref="Points"/> при этом остаётся полным нарочно: осмотр
    /// (<see cref="ScanAsync(double, CancellationToken)"/>) и отказы (<see cref="WhyNoDepot"/>) обязаны
    /// негодную точку ВИДЕТЬ и НАЗЫВАТЬ — молча её выбросить значило бы скрыть
    /// от человека, что он отметил склад не там.
    /// </summary>
    /// <param name="where">null — склад, каким он сейчас задан</param>
    public IReadOnlyList<BlockPos> ТочкиДляОписи(IReadOnlyList<BlockPos>? where = null) =>
        Годные(where, вслух: false);

    /// <summary>
    /// САМ ОТБОР ГОДНЫХ ТОЧЕК — ОДИН НА ВСЕХ, КТО ЕГО СПРАШИВАЕТ.
    ///
    /// Мерка тут одна (<see cref="DepotPointReport.WorthGoing"/>), а спрашивают
    /// её трое: опись (<see cref="ТочкиДляОписи"/>), поход
    /// (<see cref="ТочкиДляПохода"/>) и разгрузка, которая посреди рейса
    /// оглядывается — рядом мог стоять сундук, которого из забоя было не видно
    /// (<see cref="HaulAsync"/>). Выписана она была ПОРОЗНЬ ТРИЖДЫ, и приёмка
    /// назвала это незакрытым долгом: разойдись эти три мерки на одну правку —
    /// бот считал бы опись по одним точкам, ходил по другим, а добирал третьи,
    /// и объяснить человеку числа в отказе стало бы нечем. Ровно так уже
    /// случалось: «осмотрены все 16» при семнадцати заданных точках.
    ///
    /// РАЗНИЦА МЕЖДУ ТРЕМЯ ОСТАЛАСЬ ОДНА — СОВЕСТЬ, и она здесь доводом.
    /// Поход про негодную точку ГОВОРИТ (человек отметил склад не там, и знать
    /// об этом он должен, стоя в забое); опись и взгляд по сторонам молчат:
    /// первая — арифметика, вторую бот делает у КАЖДОГО сундука, и голос
    /// залил бы журнал одним и тем же отказом.
    ///
    /// СТОРОЖ НА ЭТОТ ДОВОД ПОСТАВЛЕН 29.08, И ДО ТОГО ЕГО НЕ БЫЛО. Приёмка
    /// перевернула «вслух» у описи — 5153 проверки остались зелёными: разницу,
    /// ради которой довод и заведён, не сторожило НИЧТО. Теперь все три
    /// вызывающих накрыты, и каждый краснеет от подмены в обе стороны:
    /// <c>DepotTests.Опись_про_негодную_точку_молчит_а_поход_называет_её_вслух</c>
    /// и <c>DepotTests.Взгляд_по_сторонам_посреди_рейса_не_повторяет_отказ</c>.
    /// </summary>
    /// <param name="where">null — склад, каким он сейчас задан</param>
    /// <param name="вслух">называть ли те точки, куда бот не пойдёт</param>
    private List<BlockPos> Годные(IReadOnlyList<BlockPos>? where, bool вслух)
    {
        var видно = (where ?? Points()).Select(Check).ToList();
        if (вслух)
            foreach (var негодная in видно.Where(p => !p.WorthGoing))
                OnLog?.Invoke("туда не иду: " + негодная.Reason);
        return видно.Where(p => p.WorthGoing).Select(p => p.Pos).ToList();
    }

    /// <summary>
    /// ТОЧКИ, ПО КОТОРЫМ БОТ И ВПРАВДУ ПОЙДЁТ, — И ВСЛУХ О ТЕХ, КУДА НЕ ПОЙДЁТ.
    ///
    /// РЯДОМ С <see cref="ТочкиДляОписи"/> И О ДРУГОМ. Опись СЧИТАЕТ и потому
    /// молчит: это арифметика, которую человек читает одной строкой в окне.
    /// А ПОХОД — это дело, и негодная точка в нём означает, что человек
    /// отметил склад не там. Про это надо СКАЗАТЬ, стоя в забое, а не молча
    /// вычеркнуть.
    ///
    /// ЗАЧЕМ ОДИН МЕТОД НА ДВА РЕЙСА. Отбор «куда идти» жил в проекте ДВУМЯ
    /// копиями, и мерка у них совпадала, а СОВЕСТЬ разошлась: разгрузка
    /// (<see cref="HaulAsync"/>) негодные точки называла, а рейс ЗА ВЕЩЬЮ
    /// (<see cref="TakeReportAsync"/>) выбрасывал их МОЛЧА.
    ///
    /// ВОТ ЧЕМ ЭТО КОНЧАЛОСЬ, УЛИКОЙ ИЗ ЖУРНАЛА ЗАКАЗЧИКА 27.08 23:15:12. Точек
    /// склада у него семнадцать; семнадцатая — его собственная отметка
    /// (62, 112, 254), а отмечают склад ТАМ, ГДЕ СТОИШЬ, то есть отметка
    /// пришлась на пол. Разгрузка про неё честно писала «туда не иду: в
    /// (62, 112, 254) воздух — сундука там нет». А рейс за киркой той же
    /// минутой отвечал: «на складе Pickaxe нет: опись прочитана во всех 16
    /// сундук(ах)» — шестнадцать вместо семнадцати, и ни слова о том, куда
    /// делась одна. Человек читал «бот всё осмотрел» и не мог узнать, что
    /// половина его настройки указывает в пустоту.
    ///
    /// Число в том отказе — это ДЛИНА ЭТОГО СПИСКА (см. <see cref="JudgeTake"/>),
    /// поэтому и говорить о выброшенных обязан тот, кто список строит.
    ///
    /// САМ ОТБОР ЖИВЁТ В <see cref="Годные"/> — одним местом на все три
    /// спрашивающих; здесь остаётся только решение «говорить вслух».
    /// </summary>
    /// <param name="where">null — склад, каким он сейчас задан</param>
    public List<BlockPos> ТочкиДляПохода(IReadOnlyList<BlockPos>? where = null) =>
        Годные(where, вслух: true);

    /// <summary>
    /// Спросить опись: надо ли на склад за этим. Числа берутся у сумки и у
    /// описи, решение — у чистого правила <see cref="JudgeErrand"/>.
    ///
    /// ОПИСЬ СВЕРЯЕТСЯ ПОИМЁННО, А НЕ ЧИСЛАМИ. Приёмка поймала обратное:
    /// «записей столько же, сколько сундуков» — не то же самое, что «осмотрены
    /// ЭТИ сундуки». Живой случай: задача с временным хранилищем, склад — ОДИН
    /// чужой сундук, а в памяти лежат шестнадцать записей про дом. По числам
    /// выходило 16 ≥ 1, опись «полная и свежая», и бот отвечал «кирки на складе
    /// нет — домой за этим не пойду», ни разу не заглянув в сундук задания. То
    /// же самое случалось после <see cref="SetChest"/>, сменившего список.
    ///
    /// Поэтому и «что лежит», и «когда смотрел» считаются ТОЛЬКО по записям о
    /// сундуках, которые складом являются СЕЙЧАС (<see cref="Points"/>).
    /// Иначе ответ «иду за ним (в такой-то сундук)» звал бы туда, куда обход
    /// (<see cref="TakeAsync"/>) всё равно не пойдёт: маршрут он строит по тем
    /// же Points.
    /// </summary>
    /// <param name="where">
    /// В КАКИЕ СУНДУКИ СМОТРЕТЬ. null — склад, каким он сейчас задан
    /// (<see cref="Points"/>). Снабжение подаёт сюда домашние точки
    /// (<see cref="HomePoints"/>): опись, обход и счёт от этого не меняются —
    /// меняется только список клеток, и второго «взять со склада» заводить не
    /// приходится.
    /// </param>
    public DepotErrand Ask(string wanted, int need = 1, IReadOnlyList<BlockPos>? where = null)
    {
        var points = ТочкиДляОписи(where);
        var опись = points.Select(ShelfAt).OfType<DepotShelf>().ToList();
        var now = DateTime.UtcNow;
        // Возраст берём по САМОЙ СТАРОЙ записи: ответ «этого там нет» опирается
        // на весь склад разом, и свежесть у него не выше свежести худшего звена.
        // Один сундук, осмотренный минуту назад, не делает свежими пятнадцать
        // двухчасовых — а отказ «не пойду» другого основания и не имеет
        double age = опись.Count > 0 ? опись.Max(s => s.AgeMinutes(now)) : 0;
        return JudgeErrand(wanted, need, AtHand(wanted),
            опись.Sum(s => s.CountOf(wanted)), опись.Count, points.Count, age, ScanStaleMinutes,
            опись.Where(s => s.CountOf(wanted) > 0).Select(s => s.Pos).ToList());
    }

    /// <summary>
    /// Опись одной строкой — для панели, чата и журнала.
    ///
    /// Считается ПОИМЁННО и по нынешнему складу, тем же счётом, что и решение
    /// «идти ли» (<see cref="Ask"/>): иначе окно показывало бы «сундуков 16 из
    /// 1» на задаче с временным хранилищем, а решение бралось бы совсем из
    /// других записей. Память о сундуках, складом больше не считающихся, не
    /// выбрасывается (склад ещё вернут), но и в счёт склада не идёт.
    ///
    /// Точки берутся ОДНИМ зовом с решением (<see cref="ТочкиДляОписи"/>):
    /// «сундуков 16 из 17» в окне рядом с «осмотрены все 16» в журнале — это
    /// не две подробности, а два несходящихся счёта, и один вечер такой пары
    /// заказчику уже стоил бота, простоявшего до утра.
    /// </summary>
    public string Inventory()
    {
        var points = ТочкиДляОписи();
        var опись = points.Select(ShelfAt).OfType<DepotShelf>().ToList();
        int прочих = Shelves.Count - опись.Count;
        string хвост = прочих > 0
            ? $"; в памяти ещё {прочих} запис(ей) о сундуках, складом сейчас не считающихся"
            : "";
        if (опись.Count == 0)
            return "опись склада пуста: ни в один сундук склада я ещё не заглядывал" + хвост;
        var now = DateTime.UtcNow;
        int штук = опись.Sum(s => s.Pieces);
        int видов = опись.SelectMany(s => s.Items.Keys).Distinct(StringComparer.Ordinal).Count();
        int мест = опись.Sum(s => s.FreeSlots);
        return $"опись склада: сундуков {опись.Count} из {points.Count}, видов {видов}, " +
               $"штук {штук}, свободных мест {мест}; последний осмотр " +
               $"{Ago(опись.Min(s => s.AgeMinutes(now)))}{хвост}";
    }

    /// <summary>
    /// ОБОЙТИ СУНДУКИ СКЛАДА И ПЕРЕПИСАТЬ, ЧТО В НИХ ЛЕЖИТ.
    ///
    /// Каждый сундук честно открывается: содержимое закрытого бот не видит
    /// вовсе. Свежие записи пропускаются (<see cref="ScanFreshMinutes"/>) —
    /// иначе осмотр сам стал бы той беготнёй, от которой избавляет.
    /// </summary>
    /// <param name="seconds">сколько секунд на это отведено</param>
    public async Task<DepotScan> ScanAsync(double seconds, CancellationToken ct = default)
    {
        var deadline = DateTime.UtcNow.AddSeconds(Math.Max(1, seconds));
        var points = Points();
        if (points.Count == 0)
            return new DepotScan(0, 0, 0, 0, "осматривать нечего: " + WhyNoDepot());

        int looked = 0, missed = 0, skipped = 0, pieces = 0, notChest = 0;
        string? stopped = null;

        foreach (var pos in points)
        {
            if (ct.IsCancellationRequested)
            {
                stopped = "осмотр склада отменён";
                break;
            }
            if (DateTime.UtcNow > deadline)
            {
                stopped = $"на осмотр склада было {seconds:0} с — их не хватило";
                break;
            }

            if (ShelfAt(pos) is { } was && was.AgeMinutes(DateTime.UtcNow) <= ScanFreshMinutes)
            {
                skipped++;
                continue;
            }

            // К ВОЗДУХУ НЕ ХОДЯТ И ВОЗДУХ НЕ ОТКРЫВАЮТ — ЖИВОЙ ЖУРНАЛ ЗАКАЗЧИКА:
            //     [склад] сундук (62, 112, 254) в опись не попал:
            //     air (62, 112, 254): открыл, но опись из него так и не пришла
            //     за 2500 мс — что внутри, НЕ ЗНАЮ
            // Точка склада отмечается ТАМ, ГДЕ СТОИШЬ («!склад тут» и поле в
            // окне берут клетку под ногами), и у него она пришлась на пол. Бот
            // раз за разом шёл к ней, слал правый клик В ВОЗДУХ, ждал описи
            // 2500 мс и называл воздух «сундуком». Живой игрок так не умеет
            // (правило 5), а человеку из этой строки не понять, что чинить.
            //
            // Мерка та же, что у обхода и у описи (DepotPointReport.WorthGoing
            // → Годные): в проверенную пустоту не идут, а в НЕИЗВЕСТНОЕ (чанк
            // ещё не приходил) идут — там и правда надо посмотреть. Спрашивать
            // её был обязан и осмотр, и он один из троих не спрашивал.
            //
            // Точка при этом НЕ ВЫБРАСЫВАЕТСЯ МОЛЧА (см. Годные): осмотр обязан
            // негодную ВИДЕТЬ и НАЗЫВАТЬ — иначе человек не узнает, что отметил
            // склад не там.
            var видно = Check(pos);
            if (!видно.WorthGoing)
            {
                notChest++;
                OnLog?.Invoke($"в опись не беру: {видно.Reason} — склад отмечен не там " +
                              "(ручка роли «Склад» или слово «!склад тут», стоя У СУНДУКА)");
                continue;
            }

            // К сундуку подходят одинаково отовсюду (см. ComeToChestAsync):
            // до этой правки опись просила дорогу В КЛЕТКУ сундука и уезжала
            // на крышу — ровно как рейс с грузом и поход за вещью
            if (!await ComeToChestAsync(pos, "переписываю опись", deadline, ct))
            {
                OnLog?.Invoke($"до сундука {pos} не дойти — в опись он не попадёт");
                missed++;
                continue;
            }

            var box = Container.Chest(ctx, ctx.Hands, pos);
            box.OnLog += m => OnLog?.Invoke(m);
            // Смотрим ЖИВУЮ опись — ту, что сервер прислал в ответ на это самое
            // открытие. «Не дождался описи» и «пусто» тут разные ответы, и
            // первый в опись не пишется вовсе
            var peek = await box.OpenAndPeekAsync(ct);
            await box.CloseAsync(ct);
            if (Note(pos, peek.Slots) is not { } shelf)
            {
                OnLog?.Invoke($"сундук {pos} в опись не попал: {peek.Reason}");
                missed++;
                continue;
            }
            looked++;
            pieces += shelf.Pieces;
        }

        string reason =
            $"опись обновлена: осмотрено {looked}, пропущено свежих {skipped}, " +
            $"не вышло {missed} (из {points.Count}); насчитано штук {pieces}" +
            // НЕГОДНЫЕ ТОЧКИ — ОТДЕЛЬНЫМ ЧИСЛОМ, А НЕ ВНУТРИ «не вышло»: это
            // не сбой дороги, а неверная отметка человека, и чинится она им.
            // Какая именно негодность (воздух, другой блок, промах в сотни
            // тысяч блоков), сказано строкой про саму точку — там, где её видно
            (notChest > 0 ? $"; негодных точек склада {notChest}" : "") +
            (stopped is { } why ? $"; {why}" : "");
        OnLog?.Invoke(reason);
        return new DepotScan(looked, missed, skipped, pieces, reason, notChest);
    }

    /// <summary>Обойти склад с обычным потолком времени (<see cref="ScanSeconds"/>).</summary>
    public Task<DepotScan> ScanAsync(CancellationToken ct = default) =>
        ScanAsync(ScanSeconds, ct);

    /// <summary>
    /// ПОДОЙТИ К СУНДУКУ — одно место на весь склад: обход описи, рейс с
    /// грузом и поход за вещью ходят к сундукам ОДИНАКОВО.
    ///
    /// ЖИВОЙ СЛУЧАЙ ЗАКАЗЧИКА СО СКРИНШОТОМ (заход 23:09). Сундуки сложены
    /// стенкой в четыре яруса в комнате под крышей, бот стоит в этой же
    /// комнате в двух шагах:
    ///   «[склад] иду на склад (512061, 112, 512257)»
    ///   «[движение] дорога: цель уточнил по высоте 112 → 117»
    ///   «[движение] дорога: хожу по кругу … — дальше пути нет»
    /// и так все шестнадцать сундуков, по тридцать пять секунд на каждый.
    ///
    /// Причина была в ВОПРОСЕ, а не в дороге: склад просил маршрут В САМУ
    /// КЛЕТКУ СУНДУКА. Клетка твёрдая, встать в неё нельзя, и поиск пути честно
    /// уводил на ближайшее место, где стоять МОЖНО, — на крышу. Сундук
    /// открывают взглядом, а не ногами: спрашивать надо «откуда до него
    /// дотянуться» (<see cref="Movement.ComeWithinReachAsync"/>), и это же
    /// правило само отвечает «и так под рукой — никуда не иду».
    /// </summary>
    /// <param name="chest">Клетка сундука.</param>
    /// <param name="why">Зачем идём — этим словом склад и отчитается («беру Knife»).</param>
    /// <param name="deadline">Общий срок рейса: подходу отдаётся его остаток.</param>
    private async Task<bool> ComeToChestAsync(BlockPos chest, string why, DateTime deadline,
        CancellationToken ct)
    {
        // Рука достаёт 4,5 бл: дотягиваемся — идти незачем. Отвечает на это тот
        // же подход, но сказать об этом надо ГОЛОСОМ СКЛАДА: человек читает
        // «[склад] …», и молчание тут выглядит как пропущенный сундук
        if (ctx.Hands.InReach(chest))
        {
            OnLog?.Invoke($"сундук {chest} и так под рукой — {why} не сходя с места");
            return true;
        }

        OnLog?.Invoke($"иду на склад {chest}: {why}");
        return await ctx.Movement.ComeWithinReachAsync(chest, () => ctx.Hands.InReach(chest),
            ctx.Hands.EyeHeight, ctx.Hands.Reach,
            Math.Max(10, (deadline - DateTime.UtcNow).TotalSeconds), ct);
    }

