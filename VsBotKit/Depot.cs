    /// <summary>
    /// БЕГАТЬ ЛИ ЗА НЕДОСТАЮЩИМ МАТЕРИАЛОМ — И НА СКЛАД, И ДОМОЙ: рейс к
    /// сундукам один, и разрешение у него тоже одно. Политика роли; здесь
    /// только место, где число живёт в единственном числе.
    ///
    /// У этой ручки ДВА ЛИЦА снаружи — поле задачи «домойЗаМатериалом» и
    /// галочка роли, — но хозяин один: очередь задач
    /// (<see cref="WorkRunner.RunHomeForMaterial"/>) держит сюда дверь, а не
    /// свою копию. Две копии одного порога эта работа уже разбирала однажды
    /// (порог оружия), и стоила она человеку половины настройки.
    /// </summary>
    public bool SupplyForCraft { get; set; } = true;

    /// <summary>
    /// Сколько раз за ОДНУ работу отлучаться на склад. Два — потому что первый
    /// рейс лечит обычную нехватку, второй бывает нужен, когда рецепту нужны
    /// два разных материала и первого хватило, а второй кончился следом.
    /// </summary>
    public int SupplyRuns { get; set; } = 2;

    /// <summary>
    /// На сколько сборов рецепта брать материал за один рейс. Рецепт называет
    /// нехватку на ОДИН сбор («камня надо 4»), а дороге нужны сотни клеток.
    /// </summary>
    public int SupplyBatch { get; set; } = 8;

    /// <summary>
    /// ДАЛЬШЕ ЭТОГО ЗА МАТЕРИАЛОМ НЕ ХОДИМ, блоков. 0 — порога нет.
    ///
    /// ЗАКАЗ 15.08: «порог „стоит ли идти“ (далеко ли, много ли времени) —
    /// настройкой роли». Это не то же, что <see cref="MaxDistance"/>: та
    /// говорит «склада там не бывает вовсе» (защита от опечатки в координатах),
    /// а эта — «склад мой, но за четырьмя камнями я туда не пойду». Разгрузку
    /// полной сумки порог не трогает: её всё равно надо нести.
    /// </summary>
    public double SupplyMaxBlocks { get; set; }

    /// <summary>
    /// И НЕ ДОЛЬШЕ ЭТОГО, минут на дорогу туда-обратно. 0 — порога нет.
    /// Считается по той же скорости шага, какой ходит тело
    /// (<c>Movement.WalkSpeed</c>), а не по выдуманному числу.
    /// </summary>
    public double SupplyMaxMinutes { get; set; }

    /// <summary>
    /// ЧТО И СКОЛЬКО НЕСТИ СО СКЛАДА. ЧИСТОЕ ПРАВИЛО.
    ///
    /// Нехватку рецепт называет НА ОДИН СБОР («stone-*: надо 4»), а дороге
    /// нужны не четыре камня, а сотни: рейс ради одного крафта — это рейс на
    /// каждый метр полотна. Считаем СКОЛЬКО ИМЕТЬ ПРИ СЕБЕ ВСЕГО — именно так
    /// спрашивает <see cref="TakeAsync"/>, и лишнего он не выгребет.
    ///
    /// Того, чего и так хватает (надо не больше, чем есть), в список не
    /// кладём: за ним идти незачем.
    /// </summary>
    public static IReadOnlyList<(string Code, int Count)> Shopping(
        IReadOnlyList<(string Code, int Need, int Have)> lacking, int batch)
    {
        int times = Math.Max(1, batch);
        return lacking
            .Where(l => l.Need > l.Have)
            .Select(l => (l.Code, Count: Math.Max(1, l.Need) * times))
            .ToList();
    }

    /// <summary>Чего не хватило — одной строкой для журнала и итога работы.</summary>
    public static string Names(IReadOnlyList<(string Code, int Need, int Have)> lacking) =>
        lacking.Count == 0
            ? "неизвестно чего"
            : string.Join(", ", lacking.Select(l => $"{l.Code} (надо {l.Need}, есть {l.Have})"));

    /// <summary>
    /// СТОИТ ЛИ ИДТИ — ЧИСТОЕ ПРАВИЛО ПОРОГА. Пустая строка — идти стоит,
    /// иначе это готовый ответ человеку.
    ///
    /// Всё, что оно спрашивает у мира, подано числами: расстояние до ближайшей
    /// точки склада и скорость шага. Так порог можно проверить стендом, а не
    /// сорокаминутным прогоном в игре.
    /// </summary>
    /// <param name="blocks">до ближайшей точки склада, блоков (null — не знаю, где стою)</param>
    /// <param name="walkSpeed">блоков в секунду (0 и меньше — не знаю)</param>
    /// <param name="maxBlocks">дальше не ходим (0 — порога нет)</param>
    /// <param name="maxMinutes">дольше не ходим, туда-обратно (0 — порога нет)</param>
    public static string TooFarForMaterial(double? blocks, double walkSpeed,
        double maxBlocks, double maxMinutes)
    {
        // «Не знаю, где стою» — не повод отказывать: отказ по незнанию
        // человек читает как поломку ног, а рейс он всё равно ограничил
        // временем (MaxSeconds)
        if (blocks is not { } away)
            return "";

        if (maxBlocks > 0 && away > maxBlocks)
            return $"до склада {away:0} бл, а за материалом дальше {maxBlocks:0} бл ходить " +
                   "не велено настройкой — работаю тем, что есть";

        if (maxMinutes > 0 && walkSpeed > 0)
        {
            double minutes = 2 * away / walkSpeed / 60;
            if (minutes > maxMinutes)
                return $"дорога на склад и назад — это {minutes:0.#} мин ({away:0} бл " +
                       $"туда-обратно шагом {walkSpeed:0.##} бл/с), а за материалом дольше " +
                       $"{maxMinutes:0.#} мин ходить не велено настройкой";
        }
        return "";
    }

    /// <summary>До ближайшей точки склада, блоков. null — не знаю, где стою, или склада нет.</summary>
    public double? BlocksToDepot() => BlocksTo(null);

    /// <summary>
    /// До ближайшей клетки из обхода, блоков. null — не знаю, где стою, или
    /// идти некуда. Порог «стоит ли овчинка» меряется ЭТИМ числом и для склада,
    /// и для дома: два разных счёта разошлись бы на первой же правке.
    /// </summary>
    public double? BlocksTo(IReadOnlyList<BlockPos>? where)
    {
        if (Feet is not { } here)
            return null;
        var points = where ?? Points();
        return points.Count == 0 ? null : points.Min(p => Apart(here, p));
    }

    /// <summary>Чем кончился рейс за материалом.</summary>
    /// <param name="Went">бот и вправду ходил (а не отказался с порога)</param>
    /// <param name="Brought">сколько штук ПРИБАВИЛОСЬ в сумках — по сумке, а не по пакетам</param>
    public sealed record SupplyReport(bool Went, int Brought, string Reason)
    {
        public override string ToString() => Reason;
    }

    /// <summary>
    /// СХОДИТЬ ЗА НЕДОСТАЮЩИМ МАТЕРИАЛОМ В СУНДУКИ И ВЕРНУТЬСЯ — ОДИН РЕЙС НА
    /// ВСЕ КЛАДОВЫЕ: и на склад этой работы, и домой (обход задаёт
    /// <paramref name="where"/>).
    ///
    /// ЗАКАЗ 15.08, слова заказчика: «он знал что у него есть склад и проверил
    /// что там есть, там было все для крафта дороги, а он не стал туда
    /// возвращаться и докрафчивать».
    ///
    /// ЭТО ОДНО ЗВЕНО, А НЕ ВСЯ ЦЕПОЧКА. Порядок «сумки → склад этой работы →
    /// дом → крафт → добыть рядом» держит снабжение (<see cref="Supply"/>), и
    /// зовут его дорога, запасы и крафт. Сюда приходят только за сундуками.
    ///
    /// ВТОРОГО МЕХАНИЗМА ЗДЕСЬ НЕТ И ЗАВОДИТЬ ЕГО НЕЛЬЗЯ. Всё уже есть:
    /// решение «идти ли» принимает опись (<see cref="Ask"/>), дорогу, обход
    /// сундуков и ВОЗВРАТ В ЗАБОЙ делает <see cref="TakeAsync"/>. Здесь —
    /// только порог «стоит ли овчинка» и список покупок.
    ///
    /// «Вернуться и доделать» сюда не входит нарочно: доделывает тот, кто
    /// работу и начинал (навык через <see cref="Resume"/>, крафт — повторной
    /// закладкой). Взять на себя ещё и это значило бы завести второй возврат.
    /// </summary>
    /// <param name="lacking">чего и сколько не хватает на ОДИН сбор рецепта</param>
    /// <param name="allowed">
    /// Разрешение старше настройки склада: очередь задач подаёт сюда поле самой
    /// задачи («домойЗаМатериалом»), а оно старше галочки роли. null — решает
    /// <see cref="SupplyForCraft"/>.
    /// </param>
    /// <param name="ct">Отмена.</param>
    /// <param name="where">
    /// В какие сундуки идти. null — склад, каким он сейчас задан. Снабжение
    /// (<see cref="Supply"/>) подаёт сюда домашние точки: рейс, пороги и счёт
    /// принесённого те же, меняются только клетки в обходе.
    /// </param>
    public async Task<SupplyReport> SupplyAsync(
        IReadOnlyList<(string Code, int Need, int Have)> lacking, bool? allowed = null,
        CancellationToken ct = default, IReadOnlyList<BlockPos>? where = null)
    {
        if (lacking.Count == 0)
            return new SupplyReport(false, 0, "чего не хватает, никто не назвал — идти не за чем");

        // ЧЕГО НЕ ХВАТИЛО — НАЗЫВАЕТСЯ ВСЕГДА И ПЕРВЫМ, даже когда идти мы
        // никуда не станем. Человек утром читает журнал и обязан узнать, ЧЕМ
        // именно бот не смог доделать работу: без этого имени отказ «на складе
        // не нашлось» ничего ему не говорит и проверить его нечем
        string чего = Names(lacking);
        string куда = where is null ? "склад" : "дом";

        if (!(allowed ?? SupplyForCraft))
            return new SupplyReport(false, 0,
                $"не хватает {чего}, а рейс за материалом выключен настройкой — " +
                "работаю тем, что есть");
        if (where is null ? !Known : where.Count == 0)
            return new SupplyReport(false, 0, $"не хватает {чего}, а идти за этим некуда: " +
                                              (where is null ? WhyNoDepot() : WhyNoHome()));

        if (TooFarForMaterial(BlocksTo(where), ctx.Movement.WalkSpeed,
                SupplyMaxBlocks, SupplyMaxMinutes) is { Length: > 0 } тяжело)
            return new SupplyReport(false, 0, $"не хватает {чего}, но {тяжело}");

        var shopping = Shopping(lacking, SupplyBatch);
        if (shopping.Count == 0)
            return new SupplyReport(false, 0, $"{чего} — этого и так хватает, на {куда} незачем");

        OnLog?.Invoke($"не хватает материала — {чего}; иду на {куда} за: " +
                      string.Join(", ", shopping.Select(s => $"{s.Code} ×{s.Count}")));

        int brought = 0;
        // ЧЕМ КОНЧИЛОСЬ У КАЖДОГО — а не одно слово на весь рейс. Отказ обязан
        // отличать «этого там нет» от «туда не дошёл»: чинят их по-разному
        var стоп = new List<TakeStop>();
        var почему = new List<string>();
        foreach (var (code, count) in shopping)
        {
            if (ct.IsCancellationRequested)
                break;
            var (got, stop, why) = await TakeReportAsync(code, count, ct, where);
            brought += got;
            стоп.Add(stop);
            if (got <= 0)
                почему.Add(why);
        }

        if (brought > 0)
            return new SupplyReport(true, brought, $"принёс {(where is null ? "со склада" : "из дома")} " +
                                                   $"{brought} шт ({чего})");
        // «Не дошёл» ЗВУЧИТ ИНАЧЕ, ЧЕМ «нет». Живой случай: бот отвечал «на
        // складе не нашлось» про сундуки, до которых так и не добрался, — и
        // человек шёл проверять сундуки вместо дороги
        bool ноги = стоп.Count > 0 && стоп.All(s => s == TakeStop.NoRoute);
        return new SupplyReport(true, 0, ноги
            ? $"до {(where is null ? "склада" : "дома")} за {чего} не дойти: " +
              string.Join("; ", почему)
            : $"{(where is null ? "на складе" : "дома")} {чего} не нашлось — доделывать нечем" +
              (почему.Count > 0 ? $" ({string.Join("; ", почему)})" : ""));
    }

    /// <summary>
    /// ПОМЕХА ВРЕМЕННАЯ ИЛИ ПОСТОЯННАЯ — СЛОВАМИ РЕЙСА, ПЕРЕВЕДЁННЫМИ В ОБЩИЕ
    /// (<see cref="Setback"/>). ЧИСТОЕ ПРАВИЛО.
    ///
    /// ЗАЧЕМ ПЕРЕВОД, А НЕ ОДИН СЛОВАРЬ НА ВСЕХ — разобрано у дороги
    /// (<see cref="Roads.WhatStopped"/>): <see cref="HaulStop"/> отвечает на
    /// «чем кончился ИМЕННО ЭТОТ рейс» и нужен его отчёту, общее слово — на
    /// «пройдёт ли это само», и по нему решает возврат.
    ///
    /// ДВА СЛОВА ЗДЕСЬ ЧЕСТНО НЕ НАЗВАНЫ, И ЭТО НАЗВАНО ВСЛУХ НИЖЕ. Соврать
    /// именем причины хуже, чем сказать «не знаю»: человек чинил бы не то.
    /// </summary>
    /// <param name="lastLive">
    /// Последняя ЖИВАЯ помеха рейса. Нужна ровно сроку:
    /// см. <see cref="Resume.TimeIsNotACause"/>.
    ///
    /// КЛАДЁТ ЕЁ ОДНО МЕСТО — обход сундуков в <c>HaulLoadAsync</c>, там же и
    /// разобрано, почему живой считается только та неудача подхода, что
    /// случилась ПОКА СРОК ЕЩЁ НЕ ВЫШЕЛ. Довод этот раньше стоял мёртвым:
    /// боевой вызов его не передавал НИКОГДА, и у рейса срок всегда выходил
    /// <see cref="Setback.OutOfTime"/> — то есть симптом вместо причины, ровно
    /// то враньё, ради которого <see cref="Resume.TimeIsNotACause"/> и заведён.
    /// </param>
    public static Setback WhatStopped(HaulStop stop, Setback lastLive = Setback.None) =>
        stop switch
        {
            // Отнёс и вернулся; нести нечего — это не помеха вовсе
            HaulStop.Done => Setback.None,
            HaulStop.Nothing => Setback.None,

            HaulStop.Cancelled => Setback.Stopped,
            HaulStop.NoRoute => Setback.NoRoute,

            // СРОК ДОКЛАДЫВАЕТ ПОМЕХУ, А НЕ ВСТАЁТ НА ЕЁ МЕСТО
            HaulStop.Timeout => Resume.TimeIsNotACause(lastLive),

            // «Места в сундуках ЕСТЬ, а груз не лёг: сервер перенос не
            // подтвердил» — это состояние СВЯЗИ, а не свойство склада, и
            // проходит оно само. Ровно так же дорога читает неотвеченный
            // пакет добычи (MiningRefusal.NoAnswer → NotLoaded)
            HaulStop.PutFailed => Setback.NotLoaded,

            // ---- ЧЕСТНОГО ИМЕНИ НЕТ, И ПОДСОВЫВАТЬ ЧУЖОЕ НЕЛЬЗЯ ----
            //
            // «СКЛАД ПОЛОН» (DepotFull). Ждать бесполезно — но и «бросай» тут
            // неправда: сундуки разгружает человек, и правильный ответ ему —
            // «поставь ещё сундук, и я вернусь». Такого ответа в словаре нет
            // (он про свойство ПОМЕХИ, а «устрани и вернись» — свойство того,
            // кто звал), а из двенадцати слов не подходит ни одно:
            // NoMaterial — про кончившийся запас У БОТА, NotMine — про чужое,
            // OutOfReach — про руку. Отдаём «причину не назвали»: она читается
            // как честный отказ, а САМА причина стоит словами в Reason —
            // «свободных мест в них не осталось ни одного — поставьте ещё
            // сундук рядом или задайте вторую точку склада».
            HaulStop.DepotFull => Setback.None,

            // «СКЛАД НЕ ЗАДАН ИЛИ В ТОЧКЕ НЕТ СУНДУКА» (NoDepot). Это не
            // помеха, а ненастроенность: мир ни при чём, ждать нечего, и
            // человеку надо не «повторить», а указать точку. Impossible сюда
            // натягивать нельзя — там задание САМО СЕБЕ противоречит, а тут
            // задание разумно и невыполнимо только до первого щелчка по карте
            HaulStop.NoDepot => Setback.None,

            // «СЛОЖИЛ, НО В ЗАБОЙ НЕ ВЕРНУЛСЯ» (LostTheWayBack). Груз-то лёг:
            // рейс сделал своё дело и встал на обратной дороге. Назвать это
            // NoRoute значило бы сказать «до склада не дойти» — прямая
            // неправда, до склада он как раз дошёл
            HaulStop.LostTheWayBack => Setback.None,

            _ => Setback.None
        };

    /// <param name="live">
    /// Последняя ЖИВАЯ помеха рейса — та, что мешала, пока шли часы. Приходит
    /// с обхода сундуков (<c>HaulLoadAsync</c>) и нужна ровно сроку. Пусто —
    /// рейс встал не по сроку либо помехи не видел вовсе.
    /// </param>
    private HaulReport Finish(HaulStop stop, string reason,
        bool returned, DateTime started, int stored = 0, Setback live = Setback.None)
    {
        var left = ctx.Self.CarrySnapshot();
        var report = new HaulReport(stop, reason, stored, ctx.Self.FreeCarrySlots(), returned,
            (DateTime.UtcNow - started).TotalSeconds, left)
        {
            // Помеху общим словом считает чистое правило, и считает ЗДЕСЬ — в
            // одном месте на все девять выходов из рейса. Расставь его по
            // ним поимённо, и один рано или поздно забудут (тот же разбор,
            // что у Roads.BuildAsync)
            Hindrance = WhatStopped(stop, live)
        };
        OnLog?.Invoke(report.ToString());
        return report;
    }

    // ЗДЕСЬ ЖИЛ «FindChestsNear» — ВТОРОЙ СПОСОБ ВЗЯТЬ СКЛАД ВОКРУГ СЕБЯ, И
    // ЕГО БОЛЬШЕ НЕТ. Он клал под склад ВСЕ найденные сундуки и объявлял их
    // число вслух, а «где склад» у роли живёт ОДНОЙ точкой: первое же
    // донесение (SetChest) сводило список к ней и соседям по радиусу. Живой
    // прогон у дома заказчика — «под склад взято сундуков: 16», а /api/depot
    // сразу после: «точек: 3». Тринадцать сундуков исчезали молча.
    //
    // Взять склад вокруг себя умеет ровно одно место — LivingRole
    // .ВзятьСкладЗдесь: ближний сундук становится точкой «Склад», остальные
    // приходят соседями (NeighbourRadius), считается это ПОСЛЕ донесения, и о
    // сундуках, оставшихся за радиусом соседей, говорится вслух. Оттуда же
    // кормится и самопоиск при входе в мир (SurvivorRole.ИскатьСундукиРядом).
    // Механизму склада для этого хватает двух своих дверей: посмотреть, ничего
    // не трогая (StorageNear), и принять названную точку (SetChest).
}
