namespace VsBotKit;

/// <summary>Чем кончился рейс на склад.</summary>
public enum HaulStop
{
    /// <summary>Отнёс и вернулся.</summary>
    Done,
    /// <summary>Отменили снаружи.</summary>
    Cancelled,
    /// <summary>Кончилось отведённое время.</summary>
    Timeout,
    /// <summary>
    /// Нести некуда: точка склада не задана ИЛИ в заданной точке сундука нет.
    /// Оба случая честно расписаны в <see cref="HaulReport.Reason"/>.
    /// </summary>
    NoDepot,
    /// <summary>До склада не дойти.</summary>
    NoRoute,
    /// <summary>Все сундуки полны.</summary>
    DepotFull,
    /// <summary>
    /// Места в сундуках ЕСТЬ, а груз в них не лёг: сервер перенос не
    /// подтвердил. Отдельно от <see cref="DepotFull"/> нарочно — чинить это
    /// надо не постройкой сундуков, а разбором переноса.
    /// </summary>
    PutFailed,
    /// <summary>Нести нечего.</summary>
    Nothing,
    /// <summary>Отнёс, но обратно в забой не вернулся.</summary>
    LostTheWayBack
}

/// <summary>Итог рейса — по фактической убыли в сумках.</summary>
public sealed record HaulReport(
    HaulStop Stop,
    string Reason,
    int Stored,
    int FreeSlotsAfter,
    bool Returned,
    double Seconds,
    IReadOnlyDictionary<string, int> Left)
{
    public bool Success => Stop == HaulStop.Done;

    /// <summary>
    /// ПОМЕХА ОБЩИМ СЛОВОМ: пройдёт ли она сама (<see cref="Setback"/>).
    ///
    /// Не вторая копия <see cref="Stop"/>, а ответ на ДРУГОЙ вопрос — тот же
    /// разбор, что и у дороги (<see cref="RoadReport.Hindrance"/>).
    /// <see cref="Stop"/> отвечает человеку («все сундуки полны»),
    /// <see cref="Hindrance"/> — тому, кто звал рейс: ждать бесполезно или
    /// подожди и возьмись заново. Считает одно чистое правило
    /// (<see cref="Depot.WhatStopped"/>), своего суждения у отчёта тут нет.
    ///
    /// ЗАЧЕМ ЭТО РЕЙСУ ОСОБЕННО. Рейс почти никогда не сам себе хозяин: его
    /// зовёт наряд посреди добычи (<c>MiningOrder.FetchAsync</c>). Голый отказ
    /// рейса хоронил вместе с рейсом и наряд, который его позвал.
    /// </summary>
    public Setback Hindrance { get; init; } = Setback.None;

    public override string ToString() =>
        $"на склад сложено {Stored} шт., мест в сумке {FreeSlotsAfter}" +
        (Returned ? ", вернулся в забой" : ", в забой не вернулся") +
        $"; {Seconds:0} с: {Reason}";
}

/// <summary>
/// Чем кончился поход НА СКЛАД ЗА ВЕЩЬЮ. Три отказа вместо одного нарочно:
/// «там этого нет», «я не смог прочитать» и «не дошёл» чинят по-разному.
/// </summary>
public enum TakeStop
{
    /// <summary>Вещь у бота — по счёту сумки, а не по отправленным пакетам.</summary>
    Got,
    /// <summary>Опись прочитана целиком, и этого там правда нет.</summary>
    NotThere,
    /// <summary>
    /// Часть сундуков опись не отдала. Сказать «там нет» не о чем: бот в них
    /// НЕ ЗАГЛЯДЫВАЛ, хотя и открывал.
    /// </summary>
    Unread,
    /// <summary>Ни до одного сундука не дошёл.</summary>
    NoRoute
}

/// <summary>Что стоит в точке, назначенной складом.</summary>
public enum DepotPoint
{
    /// <summary>Там хранилище — нести есть куда.</summary>
    Storage,
    /// <summary>
    /// ТОЧНО пусто: чанк у бота есть, и в клетке воздух. Идти туда незачем —
    /// это уже не «может быть, посмотрю», а проверенный факт.
    /// </summary>
    Nothing,
    /// <summary>
    /// ПРО ЭТУ КЛЕТКУ БОТ НИЧЕГО НЕ ЗНАЕТ: её чанк не приходил или уже
    /// выгружен. Не путать с <see cref="Nothing"/> — раньше это был один
    /// ответ на оба случая, и бот честно ходил проверять пустое место.
    /// Сюда сходить стоит: чаще всего это родной склад, до которого бот
    /// отошёл на пару сотен блоков.
    /// </summary>
    Unknown,
    /// <summary>Там стоит другой блок — сундука нет.</summary>
    NotStorage,
    /// <summary>Дальше, чем склад бывает: похоже на опечатку в координатах.</summary>
    TooFar
}

/// <summary>
/// Что бот выяснил про точку склада, НЕ СХОДЯ С МЕСТА: блок и его содержимое
/// приходят вместе с чанком, спрашивать сервер отдельно не нужно.
/// </summary>
public sealed record DepotPointReport(
    DepotPoint What,
    BlockPos Pos,
    string? BlockCode,
    double? Distance,
    string Reason)
{
    /// <summary>
    /// Стоит ли туда идти. Идём в хранилище и в НЕИЗВЕСТНОЕ (чанк не пришёл —
    /// надо подойти и посмотреть). В проверенную пустоту не идём: бот уже
    /// видел эту клетку, и там воздух.
    ///
    /// Живой случай, ради которого это разделено: бот доходил до точки, где
    /// сундука нет, безуспешно её открывал и докладывал «не открылся» —
    /// потратив на дорогу время рейса и ничего не выяснив.
    /// </summary>
    public bool WorthGoing => What is DepotPoint.Storage or DepotPoint.Unknown;

    public override string ToString() => Reason;
}

/// <summary>
/// ЧТО БОТ ВИДЕЛ В ОДНОМ СУНДУКЕ СКЛАДА — И КОГДА ИМЕННО.
///
/// Время тут не украшение, а половина смысла. Живой игрок помнит, что лежало в
/// сундуке, куда он заглядывал час назад, но выдавать эту память за нынешнее
/// положение дел нельзя: из сундука могли всё вынести. Поэтому опись всегда
/// отвечает двумя вещами сразу — «что» и «когда смотрел», и решение
/// (<see cref="Depot.JudgeErrand"/>) считает возраст записи.
/// </summary>
/// <param name="Pos">клетка сундука, мировые координаты</param>
/// <param name="Items">код предмета → сколько штук</param>
/// <param name="Slots">сколько мест в сундуке всего</param>
/// <param name="FreeSlots">сколько из них пустых</param>
/// <param name="Seen">когда бот в него заглядывал (UTC)</param>
public sealed record DepotShelf(
    BlockPos Pos,
    IReadOnlyDictionary<string, int> Items,
    int Slots,
    int FreeSlots,
    DateTime Seen)
{
    /// <summary>Сколько всего штук лежит.</summary>
    public int Pieces => Items.Values.Sum();

    /// <summary>Сколько разных видов лежит.</summary>
    public int Kinds => Items.Count;

    /// <summary>Сколько минут прошло с осмотра. Отрицательного возраста не бывает.</summary>
    public double AgeMinutes(DateTime now) => Math.Max(0, (now - Seen).TotalMinutes);

    /// <summary>Сколько тут этого добра — по той же мерке, что и «взять со склада».</summary>
    public int CountOf(string wanted) =>
        Items.Where(p => Depot.Suits(p.Key, wanted)).Sum(p => p.Value);

    public override string ToString() =>
        $"{Pos}: видов {Kinds}, штук {Pieces}, мест свободно {FreeSlots} из {Slots}";
}

/// <summary>Стоит ли идти на склад за вещью — ответ описи.</summary>
public enum DepotTrip
{
    /// <summary>Уже при себе — идти незачем.</summary>
    NotNeeded,
    /// <summary>По описи это там лежит — иду.</summary>
    Go,
    /// <summary>
    /// ПРОВЕРЕННОЕ «ТАМ ЭТОГО НЕТ»: опись свежая и полная. Ради этого ответа
    /// опись и заводилась — см. <see cref="Depot.JudgeErrand"/>.
    /// </summary>
    NotThere,
    /// <summary>
    /// НЕ ЗНАЮ: описи нет, она неполная или устарела. Не путать с
    /// <see cref="NotThere"/> — туда надо сходить и посмотреть.
    /// </summary>
    Unknown
}

/// <summary>Ответ описи на вопрос «надо ли домой за этим».</summary>
public sealed record DepotErrand(DepotTrip What, string Wanted, int Need, int InBag,
    int InDepot, IReadOnlyList<BlockPos> Where, string Reason)
{
    /// <summary>
    /// Идти ли. Идём, когда по описи это там ЕСТЬ и когда НЕ ЗНАЕМ; в
    /// проверенную пустоту не идём — ровно как с точкой склада
    /// (<see cref="DepotPointReport.WorthGoing"/>).
    /// </summary>
    public bool Worth => What is DepotTrip.Go or DepotTrip.Unknown;

    public override string ToString() => Reason;
}

/// <summary>Чем кончился осмотр склада.</summary>
/// <param name="Looked">в сколько сундуков заглянул и записал</param>
/// <param name="Missed">до скольких не дошёл или они не открылись</param>
/// <param name="Skipped">сколько пропустил, потому что опись по ним ещё свежая</param>
/// <param name="Pieces">сколько штук всего насчитал в осмотренных</param>
/// <param name="NotChest">
/// СКОЛЬКО ТОЧЕК СКЛАДА ОКАЗАЛИСЬ НЕГОДНЫМИ — и бот это выяснил, НЕ СХОДЯ С
/// МЕСТА (<see cref="DepotPointReport.WorthGoing"/>): там воздух, там стоит
/// другой блок или до неё сотни тысяч блоков (промах в координатах).
///
/// Считается отдельно от <paramref name="Missed"/> нарочно: «не дошёл» и «там
/// не сундук» человек чинит по-разному. Первое — дорога, второе — его
/// собственная отметка склада, и назвать её надо прямо (живой журнал: точка
/// склада пришлась на пол, и бот вечер за вечером ходил открывать воздух).
/// Какая именно негодность — сказано строкой про саму точку.
/// </param>
public sealed record DepotScan(int Looked, int Missed, int Skipped, int Pieces, string Reason,
    int NotChest = 0)
{
    public override string ToString() => Reason;
}

/// <summary>
/// СКЛАД: куда носить добытое и куда возвращаться работать.
///
/// Зачем это отдельная механика. Всё, что копает, упирается в одно и то же:
/// сумка полна. Карьер на этом просто останавливался
/// (<see cref="QuarryStop.InventoryFull"/>), штольня — тоже, и дальше человек
/// должен был прийти и разгрузить бота руками. Живой игрок в этом месте идёт
/// к сундуку и возвращается в забой; ровно это здесь и делается.
///
/// ДВЕ ТОЧКИ, А НЕ ОДНА. Склад — это не только сундук, но и место, откуда
/// бота увели: без него бот после разгрузки стоит у сундука и не знает, куда
/// идти. Забой запоминается сам, перед выходом.
///
/// Класс — механизм. Где склад, что оставлять при себе и когда пора нести,
/// решает роль.
/// </summary>
public class Depot
{
    private readonly BotContext ctx;

    public Depot(BotContext ctx) => this.ctx = ctx;

    public event Action<string>? OnLog;

    // ---------------- настройки ----------------

    /// <summary>
    /// Сундуки склада по порядку. Первый полон — бот идёт ко второму.
    /// Пусто — склада нет, и бот честно об этом скажет.
    ///
    /// Координаты АБСОЛЮТНЫЕ МИРОВЫЕ (у спавна это около 512000), а не те,
    /// что игра показывает игроку. Класть сюда руками можно, но тогда не
    /// будет ни проверки точки, ни строчки в журнале — для этого есть
    /// <see cref="SetChest"/> и <see cref="AddChest"/>.
    /// </summary>
    public List<BlockPos> Chests { get; } = [];

    /// <summary>Куда возвращаться после разгрузки. Запоминается само перед выходом.</summary>
    public BlockPos? Face { get; set; }

    /// <summary>
    /// ЗАВОДСКИЕ МАСКИ «СВОЕГО»: кирка, лопата, топор, факелы.
    ///
    /// Список стоит здесь отдельным полем затем, что его же берёт заводским
    /// значением ручка роли («ОставлятьПриСебе»). Два списка в двух файлах
    /// разошлись бы на первой же правке, и человек, ручку не тронувший, получил
    /// бы поведение, которого библиотека ему не обещала.
    /// </summary>
    public static readonly string[] DefaultKeepMasks = ["pickaxe", "shovel", "axe", "torch"];

    /// <summary>
    /// Что оставлять при себе. Инструменты и еда остаются всегда — без них
    /// бот вернётся в забой и станет там бесполезен.
    ///
    /// САМ СПИСОК — ПОЛИТИКА РОЛИ, а не механика: рудокопу кирка нужна, а
    /// продавцу за прилавком незачем. Роль перекладывает его целиком одной
    /// строкой — <see cref="KeepAtHand"/>.
    /// </summary>
    public List<string> KeepMasks { get; } = [.. DefaultKeepMasks];

    /// <summary>Оставлять при себе всё, у чего есть прочность (инструменты, оружие).</summary>
    public bool KeepTools { get; set; } = true;

    /// <summary>Оставлять при себе еду: голодный бот по дороге не выживет.</summary>
    public bool KeepFood { get; set; } = true;

    /// <summary>При скольких свободных местах пора на склад.</summary>
    public int HaulWhenFreeSlots { get; set; } = 3;

    /// <summary>Сколько секунд отводится на весь рейс.</summary>
    public double MaxSeconds { get; set; } = 300;

    /// <summary>Возвращаться в забой после разгрузки.</summary>
    public bool ReturnToFace { get; set; } = true;

    /// <summary>
    /// БРАТЬ ПОД СКЛАД СОСЕДНИЕ СУНДУКИ в этом радиусе от каждой заданной
    /// точки, блоков. 0 — только сами заданные точки.
    ///
    /// Живой случай: «в сундуки легло 112 шт., а 7 стопок груза остались при
    /// мне — складывать больше некуда». Сундук у дома был один и он полон, а
    /// рядом с ним стояли ещё три пустых: склад умеет список точек, но панель
    /// даёт вписать ОДНУ. Человеку проще поставить сундуки в ряд, чем вводить
    /// координаты каждого.
    ///
    /// Соседи не запоминаются в <see cref="Chests"/> нарочно: их каждый раз
    /// ищут заново. Сундук могли сломать или поставить новый, а список,
    /// заданный человеком, должен оставаться тем, что он задал.
    /// </summary>
    public int NeighbourRadius { get; set; }

    /// <summary>
    /// Дальше этого склада не бывает, блоков. Это не физика, а защита от
    /// опечатки: заказчик вписал в панель координаты, которые показывает игра
    /// (258, 111, −260), бот же живёт в абсолютных (512258, 111, 511740) — и
    /// «склад» оказался за полмиллиона блоков. Без такой проверки бот честно
    /// уходит туда на весь <see cref="MaxSeconds"/> и возвращается ни с чем.
    /// </summary>
    public double MaxDistance { get; set; } = 1000;

    // ---------------- где склад ----------------

    /// <summary>Радиус последнего поиска сундуков рядом; null — не искали.</summary>
    private int? searchedRadius;

    /// <summary>
    /// Назначить складом ОДНУ точку, забыв прежние. Отвечает тем, что бот в
    /// этой точке видит, — и это же говорит вслух.
    ///
    /// КООРДИНАТЫ ЖДУТ АБСОЛЮТНЫЕ МИРОВЫЕ — те, в которых живёт модель мира
    /// (у спавна около 512000, 512000). Игра показывает игроку координаты ОТ
    /// ТОЧКИ СПАВНА, и переводить их — дело вызывающего (VsBot.WorldCell);
    /// здесь перевода нет и не будет, иначе одна и та же точка означала бы
    /// разное в разных местах.
    ///
    /// Менять склад можно НА ХОДУ, а не только при сборке роли: панель крутит
    /// ручки уже в мире, и пока склад читался один раз при запуске, заказчик
    /// задавал склад и получал в ответ «склад не задан».
    /// </summary>
    public DepotPointReport SetChest(BlockPos pos)
    {
        // ПОД ВРЕМЕННОЙ ПОДМЕНОЙ ПОСТОЯННЫЙ СКЛАД ТОЛЬКО ЗАПОМИНАЕТСЯ.
        //
        // Живой случай приёмки: идёт задача «карьер» со сдачей во временный
        // сундук у забоя, человек в панели двигает ползунок «СмелостьВПути» — роль
        // на КАЖДЫЙ поворот любой ручки доносит свои настройки заново и зовёт
        // SetChest с постоянной точкой. Прежний SetChest молча стирал подмену,
        // и бот с этой секунды носил груз за триста блоков, а вкладка «Задачи»
        // по-прежнему писала «сдаю во временное хранилище».
        if (temporary is { } was)
        {
            bool same = permanent.Count == 1 && permanent[0] == pos;
            permanent.Clear();
            permanent.Add(pos);
            var later = Check(pos);
            // Молчим, если постоянный склад и так был этой точкой: иначе
            // журнал заливает строкой на каждый поворот соседней ручки
            if (!same)
                OnLog?.Invoke($"постоянный склад запомнил ({later.Reason}), но сейчас сдаю " +
                              $"во временное хранилище {was} — верну его после задачи");
            return later;
        }

        Chests.Clear();
        Chests.Add(pos);
        var seen = Check(pos);
        OnLog?.Invoke($"склад теперь тут — {seen.Reason}");
        return seen;
    }

    /// <summary>
    /// Добавить ещё один сундук в конец очереди: первый полон — бот пойдёт
    /// к следующему. Координаты абсолютные мировые, как и у <see cref="SetChest"/>.
    /// </summary>
    public DepotPointReport AddChest(BlockPos pos)
    {
        var seen = Check(pos);
        // Под подменой пополняется постоянный список, а не временный: задача
        // сдаёт ровно в тот сундук, который ей назначили
        var list = temporary != null ? permanent : Chests;
        if (list.Contains(pos))
        {
            OnLog?.Invoke($"склад {pos} уже в списке — {seen.Reason}");
            return seen;
        }
        list.Add(pos);
        OnLog?.Invoke(temporary != null
            ? $"постоянный склад ещё и тут — {seen.Reason} (сдаю пока во временное хранилище)"
            : $"склад ещё и тут — {seen.Reason}");
        return seen;
    }

    /// <summary>Забыть склад целиком (например, ручку роли очистили).</summary>
    public void Forget()
    {
        // Забываем и то, что вокруг уже искали. Иначе после очистки ручки
        // отказ говорил бы «сундуков в радиусе 12 не нашлось» про округу, где
        // их нашли и только что выкинули из списка, — а это уже враньё
        searchedRadius = null;
        if (temporary != null)
        {
            // Временную подмену этим не снимают: для этого есть DropTemporary,
            // и она одна знает, куда вернуть постоянный склад
            OnLog?.Invoke(permanent.Count > 0
                ? "постоянный склад роли забыт; сдаю во временное хранилище, после задачи " +
                  "возвращать будет некуда"
                : "постоянного склада и так не было — забывать нечего");
            permanent.Clear();
            return;
        }
        if (Chests.Count == 0)
        {
            OnLog?.Invoke("склада и так не было — забывать нечего");
            return;
        }
        OnLog?.Invoke("склад забыт: " + string.Join("; ", Chests));
        Chests.Clear();
    }

    // ---------------- временная подмена склада ----------------

    /// <summary>Постоянный склад роли, спрятанный под временной подменой.</summary>
    private readonly List<BlockPos> permanent = [];

    /// <summary>Куда сдаём, пока идёт задача с временным хранилищем. null — подмены нет.</summary>
    private BlockPos? temporary;

    /// <summary>Склад сейчас подменён временным хранилищем задачи.</summary>
    public bool Temporary => temporary != null;

    /// <summary>
    /// СДАВАТЬ ВРЕМЕННО СЮДА — на время одной задачи.
    ///
    /// Подмена живёт здесь, а не у того, кто её просит, ровно потому, что
    /// снаружи её нельзя защитить: роль доносит свои настройки в механизмы на
    /// каждый поворот ручки в панели и не знает и не должна знать, что сейчас
    /// идёт задача с чужим сундуком.
    /// </summary>
    public DepotPointReport UseTemporary(BlockPos pos)
    {
        if (temporary == null)
        {
            permanent.Clear();
            permanent.AddRange(Chests);
        }
        temporary = pos;
        Chests.Clear();
        Chests.Add(pos);
        var seen = Check(pos);
        OnLog?.Invoke($"сдаю временно сюда — {seen.Reason}" +
                      (permanent.Count > 0
                          ? $"; постоянный склад ({string.Join("; ", permanent)}) верну после задачи"
                          : "; постоянного склада у роли нет"));
        return seen;
    }

    /// <summary>
    /// Снять временную подмену и вернуть постоянный склад роли.
    /// false — подмены не было (повторный вызов ничего не делает).
    /// </summary>
    public bool DropTemporary()
    {
        if (temporary == null)
            return false;
        temporary = null;
        Chests.Clear();
        Chests.AddRange(permanent);
        permanent.Clear();
        OnLog?.Invoke(Chests.Count > 0
            ? "постоянный склад роли вернулся: " + string.Join("; ", Chests)
            : "временное хранилище снято, а постоянного склада у роли и не было");
        return true;
    }

