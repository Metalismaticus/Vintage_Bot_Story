    /// <summary>
    /// ОТНЕСТИ НА СКЛАД ИМЕННО ЭТО — по прямому приказу человека.
    ///
    /// Заказчик: «чтобы можно в вебформе пкм на предмет и выбирать на него
    /// надеть, отнести на склад или выкинуть». Умения «отнеси вот это» у
    /// склада не было ВОВСЕ: рейс несёт всё, что не входит в «оставить при
    /// себе» (<see cref="Keep(string)"/>), и выбирает это сам. Значит кирку,
    /// которую человек велел убрать в сундук, бот принёс бы обратно — она в
    /// списке «своего».
    ///
    /// ПРИКАЗ СИЛЬНЕЕ СПИСКА «СВОЕГО»: раз названа вещь, несём её, даже если
    /// это кирка или еда. Зато и НИЧЕГО ДРУГОГО не несём — тем же рейсом
    /// разгружать всё подряд было бы своеволием.
    ///
    /// НЕСЁМ ВСЁ ТАКОЕ, ЧТО ПРИ СЕБЕ, а не одну стопку: человек, показавший
    /// на кучку руды, имеет в виду руду, а не «вот эти шестнадцать штук из
    /// сорока восьми». Сколько ушло на самом деле, скажет отчёт.
    /// </summary>
    /// <param name="code">Точный код предмета из описи сумки.</param>
    public Task<HaulReport> HaulItemAsync(string code, CancellationToken ct = default)
    {
        string wanted = (code ?? "").Trim();
        if (wanted.Length == 0)
            return Task.FromResult(Finish(HaulStop.Nothing,
                "не сказано, что нести", false, DateTime.UtcNow));
        // ПРИКАЗ НЕ ЗНАЕТ НИКАКИХ ИЗЛИШКОВ: сказано нести — несём всё такое,
        // что при себе, будь это хоть последняя кирка. Запас тут не
        // спрашивается вовсе, и в этом вся разница с обычной разгрузкой
        return HaulLoadAsync(
            c => string.Equals(c, wanted, StringComparison.OrdinalIgnoreCase)
                ? ctx.Hands.CountExactly(c)
                : 0,
            $"несу {wanted}",
            $"{wanted} при мне нет — нести нечего", поИзлишку: false, ct: ct);
    }

    /// <summary>
    /// РЕЙС НА СКЛАД — одно место на все рейсы. Что считать грузом, решает
    /// мерка на входе: обычная разгрузка несёт всё, что не «своё»
    /// (<see cref="HaulAsync"/>), приказ из окна — одну названную вещь
    /// (<see cref="HaulItemAsync"/>).
    ///
    /// Мерка ОДНА на весь рейс, и это важно: ею меряется и «нести ли вообще»,
    /// и «что класть в сундук», и «всё ли сложил», и «сколько осталось при
    /// мне». Разойдись хоть одна — бот доложил бы «разгрузился», унося груз
    /// обратно, ровно как это уже было с полной сумкой и Success = true.
    ///
    /// МЕРКА ОТВЕЧАЕТ ЧИСЛОМ, А НЕ «ДА/НЕТ», и живёт она ПО ЖИВОЙ СУМКЕ:
    /// спрошенная снова после переноса, она сама вычитает уже сданное. Никакой
    /// своей памяти «сколько ещё осталось сдать» тут поэтому нет — а была бы,
    /// разошлась бы с сумкой на первом же отказе сервера.
    /// </summary>
    /// <param name="mine">
    /// Код → сколько ШТУК этого сдать. Ноль — вещь остаётся при боте целиком.
    /// </param>
    /// <param name="errand">Чем бот отчитается по дороге («складываю груз»).</param>
    /// <param name="nothing">Что сказать, когда нести нечего.</param>
    /// <param name="поИзлишку">
    /// Рейс идёт ЗА ИЗЛИШКОМ (обычная разгрузка), а не по приказу человека.
    /// Различать обязательно: приказ несёт названное целиком и никаких
    /// излишков не знает — звать сданное «лишним» в его отчёте значит врать
    /// (см. отчётный цикл в конце метода).
    /// </param>
    private async Task<HaulReport> HaulLoadAsync(Func<string, int> mine, string errand,
        string nothing, bool поИзлишку, CancellationToken ct = default)
    {
        var started = DateTime.UtcNow;

        // Отказ обязан называть, ЧТО проверено. Заказчик получил «склад не
        // задан — некуда нести» при заданном в панели складе и не мог понять,
        // куда смотреть: в ручку, в координаты или под ноги
        if (!Known)
            return Finish(HaulStop.NoDepot, WhyNoDepot(), false, started);

        // Нести ли вообще: если в сумке только кирка и факелы, рейс впустую
        int carrying = ctx.Self.CarrySlots()
            .Count(s => !s.Content.IsEmpty && s.Content.Code is { } c && mine(c) > 0);
        if (carrying == 0)
            return Finish(HaulStop.Nothing, nothing, false, started);

        // СКОЛЬКО ЧЕГО БЫЛО ПРИ МНЕ ДО РЕЙСА — ради честного отчёта «отнёс
        // лишние 120, осталось 80». Считается по СУМКЕ (её содержимое присылает
        // сервер), а не по тому, сколько мы задумали положить в сундук: между
        // задумкой и фактом стоят отказ переноса, полный сундук и застрявший
        // курсор, и все трое живьём случались
        var былоПриМне = ctx.Self.CarrySlots()
            .Where(s => !s.Content.IsEmpty && s.Content.Code is { } c && mine(c) > 0)
            .Select(s => s.Content.Code!)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToDictionary(c => c, ctx.Hands.CountExactly, StringComparer.OrdinalIgnoreCase);

        // КУДА ИДТИ, РЕШАЕМ НЕ СХОДЯ С МЕСТА. Блок в точке склада и его
        // содержимое приходят вместе с чанком, спрашивать сервер не нужно, —
        // а бот уходил к точке, которой не существует, на все MaxSeconds и
        // возвращался ни с чем. Про негодную точку надо говорить, стоя в
        // забое, а не через пять минут ходьбы
        var route = ТочкиДляПохода();
        if (route.Count == 0)
            return Finish(HaulStop.NoDepot, WhyNoDepot(), false, started);

        var face = RememberFace();
        var deadline = started.AddSeconds(MaxSeconds);

        int stored = 0;
        string reason = $"обошёл сундуков: {route.Count}";

        // ЧТО ИМЕННО ОСМОТРЕНО, а не что задумано. Отказ «складывать некуда»
        // обязан назвать оба числа — сколько сундуков бот на самом деле открыл
        // и сколько мест в них увидел; без них человек не может понять, ставить
        // ему ещё сундук или чинить перенос
        int reached = 0, inspected = 0;
        int? roomSeen = null;

        // ПОСЛЕДНЯЯ ЖИВАЯ ПОМЕХА — та, что мешала, ПОКА ШЛИ ЧАСЫ. Нужна ровно
        // сроку и ровно затем, чтобы он не встал на её место
        // (Resume.TimeIsNotACause). Кладёт её обход ниже — одно место на весь
        // рейс.
        //
        // ЧЕГО РЕЙС НЕ ПОМНИТ, СКАЗАНО ВСЛУХ, И ЭТО НЕ МЕЛОЧЬ. Сундук, который
        // не открылся, отдаёт одно и то же «мест не видно» и когда до него не
        // дотянулись (постоянная помеха), и когда содержимое просто не пришло
        // (временная, проходит сама): у Container.PutReport обе они — FreeSlots
        // = null, и различить их отсюда нечем. Выбрать любую значило бы соврать
        // именем причины в половине случаев, а это хуже честного «не знаю»
        // (правило 4). Появится у укладки своё слово — заведём и это.
        var живая = Setback.None;

        // Обход растёт ПО ХОДУ ДЕЛА, поэтому счётчик, а не foreach. Из забоя
        // соседних сундуков не видно: чужой чанк ещё не пришёл, и модель мира
        // отдаёт там воздух. Придя к первому сундуку, бот наконец видит округу
        // — и если груз при нём ещё остался, соседи дописываются в конец
        for (int i = 0; i < route.Count; i++)
        {
            var chest = route[i];
            if (ct.IsCancellationRequested)
                return Finish(HaulStop.Cancelled, "отменено", false, started);
            if (DateTime.UtcNow > deadline)
                return Finish(HaulStop.Timeout, $"вышло время рейса ({MaxSeconds:0} с)",
                    false, started, live: живая);

            // СУНДУК ОТКРЫВАЮТ ВЗГЛЯДОМ, А НЕ НОГАМИ — весь разбор в
            // ComeToChestAsync: и «и так под рукой», и «встань рядом, откуда
            // достанешь», и почему просить дорогу в клетку сундука нельзя
            if (!await ComeToChestAsync(chest, errand, deadline, ct))
            {
                reason = $"до склада {chest} не дойти";
                // ПОМЕХУ ЗАПОМИНАЕМ СРАЗУ, а не только когда она станет отказом:
                // именно её и назовёт срок, если часы кончатся следующим кругом
                // (тот же порядок, что у наряда — MiningOrder, «живая»).
                //
                // СЛОВО БЕРЁМ У САМОГО РЕЙСА, А НЕ ВЫДУМЫВАЕМ ВТОРОЕ: «не дойти
                // ни до одного сундука» рейс уже называет HaulStop.NoRoute (см.
                // ниже, reached == 0), и переводит его то же чистое правило.
                // Заведи мы здесь своё слово — у одного и того же события стало
                // бы два имени, и разъехались бы они на первой же правке.
                //
                // ТОЛЬКО ПОКА СРОК ЕЩЁ НЕ ВЫШЕЛ, И ЭТО ГЛАВНАЯ ОГОВОРКА —
                // разобрана она у самого правила (CountsAsLive), второй копии
                // рассуждения тут не заводим
                if (CountsAsLive(DateTime.UtcNow, deadline))
                    живая = WhatStopped(HaulStop.NoRoute);
                continue;
            }

            reached++;

            var box = Container.Chest(ctx, ctx.Hands, chest);
            box.OnLog += m => OnLog?.Invoke(m);
            var put = await box.PutAllReportAsync(mine, ct);
            stored += put.Stored;
            // «Осмотрен» — тот, чьё содержимое бот УВИДЕЛ. Дойти и не открыть
            // (не дотянулся, сундук не отдал содержимое) — это не осмотр, и
            // считать его в отказе значило бы завышать проверенное
            if (put.FreeSlots is { } free)
            {
                inspected++;
                roomSeen = (roomSeen ?? 0) + free;
            }
            OnLog?.Invoke($"в склад {chest} легло {put.Stored} шт. " +
                          (put.FreeSlots is { } f ? $"(мест там осталось {f})" : "(мест не видно)") +
                          $"; {put.Reason}");

            // Всё, что хотели, сложили — дальше по сундукам ходить незачем
            if (ctx.Self.CarrySlots().All(s => s.Content.IsEmpty ||
                    (s.Content.Code is { } c && mine(c) <= 0)))
            {
                reason = "разгрузился";
                break;
            }
            reason = "сундук не вместил всё — иду к следующему";

            // Груз ещё при мне — оглядываемся: рядом мог стоять сундук,
            // которого из забоя было не видно
            if (NeighbourRadius <= 0)
                continue;
            int wasKnown = route.Count;
            // ТЕМ ЖЕ ОТБОРОМ, ЧТО И ВЕСЬ МАРШРУТ (route выше собран ровно им):
            // своя копия «Points + WorthGoing» стояла здесь третьей, и мерка у
            // неё совпадала с двумя другими только пока их никто не правил.
            // Молча — нарочно: этот взгляд по сторонам бот делает у КАЖДОГО
            // сундука, и голос повторял бы один отказ на весь рейс
            foreach (var extra in Годные(null, вслух: false))
                if (!route.Contains(extra))
                    route.Add(extra);
            if (route.Count > wasKnown)
                OnLog?.Invoke($"рядом нашлось ещё сундуков под склад: {route.Count - wasKnown} " +
                              $"(радиус {NeighbourRadius})");
        }

        if (reached == 0)
            return Finish(HaulStop.NoRoute, reason, false, started);

        // СКОЛЬКО ГРУЗА ОСТАЛОСЬ ПРИ МНЕ — считаем У СУНДУКА, а не после
        // возвращения: по дороге в забой бот проходит по вещам и подбирает их
        // ногами, и этот новый груз к «сундук не вместил» отношения не имеет
        int leftToStore = ctx.Self.CarrySlots()
            .Count(s => !s.Content.IsEmpty && s.Content.Code is { } c && mine(c) > 0);

        // ЧТО ИМЕННО СДАНО — ПО ФАКТУ УБЫЛИ В СУМКЕ. Отчёт нужен человеку не
        // ради вежливости: это единственная строка, по которой видно, что
        // излишек считается тем же числом, каким бот его держит. Говорим только
        // про то, что бот считает СВОИМ (стрелы, лестницы, факелы): руду и
        // породу он несёт целиком, и про них уже сказано «в склад … легло N шт.»
        //
        // ДВЕ ЛЖИ, КОТОРЫЕ ЗДЕСЬ СТОЯЛИ, ОБЕ ПОЙМАНЫ ПРИЁМКОЙ 26.08:
        //  1. «при себе оставил N» печаталось ПО КОДУ, а запас один на семью:
        //     при «ЗапасПоРасходу: arrow» человек читал «оставил 80» дважды, а
        //     у бота было 160. Теперь про код говорится только то, что про код
        //     и меряется (убыль слота), а про запас — его настоящее имя и общее
        //     число, по одному разу на требование;
        //  2. слово «лишние» стояло и при ПРИКАЗЕ ЧЕЛОВЕКА, который никаких
        //     излишков не знает (см. HaulItemAsync): «!отнеси arrow-flint» при
        //     ровном запасе печатало «отнёс лишние 64, при себе оставил 0» —
        //     бот сдал весь запас (верно, приказ сильнее) и назвал это
        //     излишком (неверно). Отсюда параметр поИзлишку
        var названные = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var (код, было) in былоПриМне)
        {
            if (ctx.Stock is not { } запасы || !запасы.Wanted(код))
                continue;
            int осталось = ctx.Hands.CountExactly(код);
            int ушло = было - осталось;
            if (ушло <= 0)
            {
                OnLog?.Invoke($"{(поИзлишку ? "лишних " : "")}{код} сдать не вышло: " +
                              $"как было {было} при мне, так и осталось");
                continue;
            }
            OnLog?.Invoke(поИзлишку
                ? $"отнёс на склад лишние {ушло} ({код}), таких при себе осталось {осталось}"
                : $"отнёс на склад {ушло} ({код}) по приказу, " +
                  $"таких при себе осталось {осталось}");
            // ПРО ЗАПАС — ОДИН РАЗ НА ТРЕБОВАНИЕ, А НЕ НА КАЖДЫЙ КОД
            if (запасы.KeptUnder(код) is { } под && названные.Add(под.Запас))
                OnLog?.Invoke($"по запасу «{под.Запас}» держу {под.Держать}, " +
                              $"при мне сейчас {под.Есть}");
        }

        // ОПИСЬ СКЛАДА — РАЗ УЖ ПРИШЛИ. Прямая просьба заказчика: «каждое
        // возвращение домой сканировать все сундуки и записывать, чтобы потом
        // ориентироваться, нужно домой чтобы что-то взять или нет». Делаем это
        // ЗДЕСЬ, а не отдельным походом: бот уже стоит у склада, и обойти
        // соседние сундуки стоит секунд, а не рейса. Осмотр идёт после
        // разгрузки — сперва дело, потом перепись
        if (ScanOnHaul)
        {
            double left = Math.Min(ScanSeconds, (deadline - DateTime.UtcNow).TotalSeconds);
            if (left < 5)
                OnLog?.Invoke("опись склада не обновляю: времени рейса почти не осталось");
            else
                await ScanAsync(left, ct);
        }

        // Обратно в забой. Не вернуться — это не провал рейса (добыча уже в
        // сундуке), но сказать об этом надо: иначе бот молча стоит у склада
        bool returned = false;
        if (ReturnToFace)
        {
            // Забой запоминается по своей клетке, а её может не быть. Молчать
            // тут нельзя: со стороны «в забой не вернулся» без причины
            // неотличимо от заблудившегося бота
            if (face is not { } back)
            {
                OnLog?.Invoke("возвращаться некуда: где был забой, я не запомнил — " +
                              "своей клетки не было видно");
            }
            else
            {
                double left = Math.Max(10, (deadline - DateTime.UtcNow).TotalSeconds);
                returned = await ctx.Movement.TravelToAsync(back, left, ct);
                if (!returned)
                    return Finish(HaulStop.LostTheWayBack,
                        $"сложил, но обратно в {back} не дошёл", false, started, stored);
            }
        }

        var (stop, why) = JudgeHaul(stored, leftToStore, reason, inspected, roomSeen);
        return Finish(stop, why, returned, started, stored);
    }

    /// <summary>
    /// ВЗЯТЬ СО СКЛАДА НУЖНОЕ — обратный ход к <see cref="HaulAsync"/>.
    ///
    /// Ради живого случая: боту говорят «копать нечем — положите кирку в сумку
    /// ИЛИ В СУНДУК СКЛАДА», а сходить за ней в тот самый сундук он не умел.
    /// То же и с временной шестерёнкой: точку возрождения ставить нечем, хотя
    /// три штуки лежат дома в ящике. В мире такое не выкапывается — его либо
    /// делают, либо приносят, и «принести» это как раз здесь.
    ///
    /// Возвращает, на сколько ШТУК прибавилось в сумках, — по счёту сумки, а
    /// не по числу отправленных пакетов.
    /// </summary>
    /// <param name="wanted">Часть кода предмета: «pickaxe», «gear-temporal».</param>
    /// <param name="count">Сколько штук нужно иметь при себе всего.</param>
    /// <param name="ct">Отмена.</param>
    /// <param name="where">
    /// В какие сундуки идти. null — склад, каким он сейчас задан. Снабжение
    /// (<see cref="Supply"/>) подаёт сюда домашние точки: обход, опись и счёт
    /// принесённого остаются те же самые.
    /// </param>
    public async Task<int> TakeAsync(string wanted, int count, CancellationToken ct = default,
        IReadOnlyList<BlockPos>? where = null) =>
        (await TakeReportAsync(wanted, count, ct, where)).Got;

    /// <summary>
    /// ТО ЖЕ САМОЕ, НО С ИМЕНЕМ ОБОРВАВШЕГОСЯ ЗВЕНА. Снабжение обязано отличать
    /// «там этого нет» от «туда не дошёл» и сказать это человеку разными
    /// словами: первое чинят сундуком, второе — дорогой. Обход тут ОДИН и тот
    /// же, <see cref="TakeAsync"/> просто выбрасывает подробности.
    /// </summary>
    public async Task<(int Got, TakeStop Stop, string Why)> TakeReportAsync(
        string wanted, int count, CancellationToken ct = default,
        IReadOnlyList<BlockPos>? where = null)
    {
        int before = AtHand(wanted);
        if (before >= count)
            return (0, TakeStop.Got, $"{wanted} и так при мне ×{before} (надо {count})");
        if (where is null && !Known)
        {
            string нет = WhyNoDepot();
            OnLog?.Invoke($"{wanted} со склада не взять: {нет}");
            return (0, TakeStop.NoRoute, нет);
        }
        if (where is { Count: 0 })
        {
            string нет = WhyNoHome();
            OnLog?.Invoke($"{wanted} дома не взять: {нет}");
            return (0, TakeStop.NoRoute, нет);
        }

        // СПЕРВА СПРАШИВАЕМ ОПИСЬ, А ПОТОМ ИДЁМ. Ровно здесь и жила беготня,
        // на которую жаловался заказчик: за одной временной шестерёнкой бот
        // обошёл все шестнадцать сундуков, открыл каждый и не нашёл ничего —
        // и так на каждый заход, потому что помнить было нечем. Отказ «домой
        // за этим не пойду» отдаётся ТОЛЬКО по свежей и полной описи (см.
        // JudgeErrand): по неполной или старой бот всё равно идёт смотреть
        var опись = Ask(wanted, count, where);
        if (!опись.Worth)
        {
            OnLog?.Invoke($"{wanted} со склада не беру: {опись.Reason}");
            return (0, опись.What == DepotTrip.NotThere ? TakeStop.NotThere : TakeStop.Got,
                опись.Reason);
        }
        OnLog?.Invoke("опись говорит: " + опись.Reason);

        // ЧТО ИМЕННО ВЫБРОШЕНО ИЗ ОБХОДА — ВСЛУХ, И ТЕМ ЖЕ МЕСТОМ, ЧТО У
        // РАЗГРУЗКИ. Здесь стоял свой отбор, и он МОЛЧАЛ: негодная точка
        // просто исчезала, а её исчезновение потом уменьшало число в отказе
        // человеку («опись прочитана во всех 16 сундук(ах)» при семнадцати
        // точках). Разбор живого случая — в ТочкиДляПохода
        var route = ТочкиДляПохода(where);
        if (route.Count == 0)
        {
            string нет = where is null ? WhyNoDepot() : WhyNoHome();
            OnLog?.Invoke($"{wanted} не взять: {нет}");
            return (0, TakeStop.NoRoute, нет);
        }

        // СУНДУК, ГДЕ ЭТО ЛЕЖИТ ПО ОПИСИ, — ПЕРВЫМ. Порядок точек человек
        // задавал под разгрузку («главный сундук сначала»), а за вещью надо
        // идти туда, где её видели: иначе опись знает ответ, а ноги всё равно
        // обходят склад по кругу
        var знаем = WhereIs(wanted);
        if (знаем.Count > 0)
            route = route.OrderBy(p => знаем.Contains(p) ? 0 : 1).ToList();

        var face = RememberFace();
        var deadline = DateTime.UtcNow.AddSeconds(MaxSeconds);

        // ЧТО ИМЕННО ПРОВЕРЕНО, а не сколько точек было в списке. Заказчик
        // прочитал «на складе Knife нет — искал в 16 сундук(ах)» при ноже,
        // лежавшем в первом же из них: бот ни в один сундук не заглянул (опись
        // не пришла), но отчитался так, будто осмотрел все шестнадцать
        int reached = 0, read = 0, unread = 0, byNote = 0;

        foreach (var chest in route)
        {
            if (ct.IsCancellationRequested || DateTime.UtcNow > deadline)
                break;
            if (AtHand(wanted) >= count)
                break;

            // СВЕЖАЯ ЗАПИСЬ ОТВЕЧАЕТ ЗА СУНДУК — И ХОДИТЬ ТУДА НЕ НАДО.
            //
            // ЖИВОЙ СЛУЧАЙ 23.08, 11:00:43–11:03:52. Голодный бот искал по
            // очереди fat, fish-raw, grain-rye, bandage-clean,
            // bandage-alcoholed и poultice-reed-horsetail — и НА КАЖДУЮ вещь
            // заново обходил все шестнадцать сундуков, сам же печатая после
            // каждого круга «опись прочитана во всех 16 сундук(ах)» и тут же
            // начиная следующий. Сотни строк журнала и минуты времени на
            // вопрос, ответ на который у него уже записан, — а он в это время
            // терял по 0,13 хп каждые шесть секунд.
            //
            // Ручка на это была заведена давно (ScanFreshMinutes: «свежий
            // сундук осмотр пропускает»), но спрашивал её только осмотр
            // склада; рейс ЗА ВЕЩЬЮ не спрашивал никто.
            //
            // МЕРКА — «ЗАСТАРЕЛОСТЬ», А НЕ «СВЕЖЕСТЬ», и это не описка.
            // Пропуск опирается на ОТРИЦАТЕЛЬНЫЙ ответ («этого тут нет»), а
            // ему цену назначает ScanStaleMinutes — та самая мерка, что
            // заведена ровно для отрицательных ответов: «там лежит» устаревает
            // не страшно, «там нет» — опасно.
            if (ShelfAt(chest) is { } записано &&
                записано.AgeMinutes(DateTime.UtcNow) < ScanStaleMinutes &&
                записано.CountOf(wanted) == 0)
            {
                byNote++;
                read++;
                continue;
            }

            // Та же беда, что и при выгрузке, и лечится тем же подходом
            // (см. ComeToChestAsync): за вещью шли В КЛЕТКУ сундука. Ровно так
            // бот перебрал все 16 сундуков за временной шестерёнкой, стоя
            // посреди склада, — см. заход 22:32
            if (!await ComeToChestAsync(chest, $"беру {wanted}", deadline, ct))
            {
                OnLog?.Invoke($"до склада {chest} не дойти — за {wanted} схожу в другой");
                continue;
            }
            reached++;

            var box = Container.Chest(ctx, ctx.Hands, chest);
            box.OnLog += m => OnLog?.Invoke(m);

            // СНАЧАЛА ПОСМОТРЕТЬ И ЗАПИСАТЬ, и только потом лезть руками. Так
            // делает и живой игрок, и так наполняется опись: этот самый обход
            // за шестерёнкой второй раз уже не понадобится — бот решит по
            // записи, не выходя из забоя. Чужого сундука это не удорожает:
            // открытие всё равно было бы, а в сундук без искомого мы теперь
            // просто не полезем
            var peek = await box.OpenAndPeekAsync(ct);
            await box.CloseAsync(ct);
            if (Note(chest, peek.Slots) is not { } shelf)
            {
                // ОПИСЬ НЕ ПРИШЛА — это НЕ «в сундуке пусто». Считаем такие
                // сундуки отдельно: без этого числа итог «на складе нет»
                // становится враньём ровно в том случае, когда вещь там есть
                unread++;
                OnLog?.Invoke($"сундук {chest} в опись не попал: {peek.Reason}");
                continue;
            }
            read++;
            if (shelf.CountOf(wanted) == 0)
            {
                OnLog?.Invoke($"в сундуке {chest} {wanted} нет — записал и иду дальше");
                continue;
            }

            // Условие спрашивается на КАЖДЫЙ слот, поэтому лишнего бот не
            // выгребет: набрал сколько просили — остальное оставит хозяину
            await box.TakeAllAsync(
                code => AtHand(wanted) < count && Suits(code, wanted), ct);
        }

        int got = AtHand(wanted) - before;
        // Молчаливого «сходил и ничего» быть не должно: человек кладёт вещь в
        // сундук и обязан узнать, взял её бот или нет — и почему
        // ОДНА СТРОКА ВМЕСТО ПЯТНАДЦАТИ. Про сундуки, отвеченные по записи,
        // человеку сказать надо — иначе «сходил на склад» и «ничего не сделал»
        // выглядят одинаково, — но сказать ОДИН РАЗ: пятнадцать строк «в
        // сундуке нет» и были той бедой, которую мы тут чиним
        if (byNote > 0)
            OnLog?.Invoke($"в {byNote} сундук(ах) {wanted} нет по описи " +
                          $"(смотрел не дольше {ScanStaleMinutes:0} мин назад) — туда не иду");

        var (stop, why) = JudgeTake(wanted, got, count, before, route.Count,
            reached, read, unread, byNote);
        OnLog?.Invoke(why);

        if (ReturnToFace && face is { } back && got > 0)
        {
            double left = Math.Max(10, (deadline - DateTime.UtcNow).TotalSeconds);
            if (!await ctx.Movement.TravelToAsync(back, left, ct))
                OnLog?.Invoke($"взял {wanted}, но обратно в {back} не дошёл");
        }
        return (got, stop, why);
    }

