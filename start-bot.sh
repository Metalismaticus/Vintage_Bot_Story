#!/usr/bin/env sh
# Обычный житель: живёт, слушается команд в чате, сам никуда не бежит.
# Подключается к 127.0.0.1:42420. Всё, что напечатаете здесь после входа,
# уйдёт в игровой чат. quit — выход.
#
# --diag добавляет команды проверки: !часы !предмет !сколько !копай
#        !припасы !костёр !еда !собери !вспаши !путь !обрыв и другие
#
# Если игра стоит не в обычном месте, скажите об этом один раз:
#   export VINTAGE_STORY=/путь/к/игре
set -e
cd "$(dirname "$0")"
exec dotnet run --project VintageBotStory -- --diag "$@"
