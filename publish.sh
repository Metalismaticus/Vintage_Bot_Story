#!/usr/bin/env sh
# СОБРАТЬ ОДИН ФАЙЛ НА КАЖДУЮ СИСТЕМУ — чтобы бота мог запустить человек,
# который не ставил ни .NET, ни исходников.
#
# Что получится:  out/win-x64/VintageBotStory.exe
#                 out/linux-x64/VintageBotStory
#                 out/osx-arm64/VintageBotStory   (Apple на M-процессорах)
#                 out/osx-x64/VintageBotStory     (Apple на Intel)
#
# Внутри каждого — сам .NET, поэтому ставить его отдельно не нужно. Игра
# нужна: бот берёт из неё физику, реестр блоков и библиотеку сжатия, и без
# установленной Vintage Story он честно об этом скажет при запуске.
#
# Запускается двойным щелчком: без единого аргумента бот открывает окно
# управления в браузере и ждёт, пока в нём нажмут «Вход».
#
# ПРО СБОРКУ ПОД ЧУЖУЮ СИСТЕМУ — БОЛЬШЕ НИЧЕГО НЕ НУЖНО.
# Раньше рядом с ботом обязана была лежать Lib/libzstd ТОЙ системы, под
# которую собираем, и взять её можно было только из установки игры под эту
# систему: с Windows-машины архив для Linux и macOS собрать было нечем.
# Теперь эту библиотеку бот берёт САМ ПРИ ЗАПУСКЕ — из игры, установленной на
# машине, где он работает (см. VsBotKit/GameNatives.cs). Поэтому все четыре
# системы собираются с любой одной машины и никаких переменных не просят.
set -e
cd "$(dirname "$0")"

# ИМЕНА ПЕРЕМЕННЫХ ЗДЕСЬ ЛАТИНСКИЕ, И ЭТО НЕ ПРИДИРКА К СТИЛЮ.
# Оболочки допускают в имени переменной только латиницу, цифры и подчёркивание.
# Раньше тут стояло «СИСТЕМЫ=…», и любая оболочка честно отвечала
# «СИСТЕМЫ=win-x64: command not found» — то есть скрипт сборки не работал
# вообще нигде. Комментарии по-русски остаются: их читают люди, а не sh.
targets="${*:-win-x64 linux-x64 osx-arm64 osx-x64}"

for target in $targets; do
    echo "=== $target ==="
    dotnet publish VintageBotStory/VintageBotStory.csproj \
        -c Release \
        -r "$target" \
        --self-contained true \
        -p:PublishSingleFile=true \
        -p:IncludeNativeLibrariesForSelfExtract=true \
        -p:DebugType=none \
        -o "out/$target" \
        --nologo
done

echo
echo "Готово. Раздавать нужно ВСЮ папку out/<система>: рядом с программой лежит"
echo "папка presets — это готовые боты, которые видно в окне управления."
