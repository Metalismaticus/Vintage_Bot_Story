using VsBotKit;
using VsBotKit.Panel;   // метка [KnobPlace] — где настройке стоять в окне управления

namespace VintageBotStory;

/// <summary>
/// ЧТО ЗНАЧИТ «НЕ ПУСКАТЬ» — РАЗБОР ПРЕЖДЕ КОДА, потому что здесь легче всего
/// соврать человеку.
///
/// Заказчик дословно: «ему нужно стоять в одной точке, кушать со склада и не
/// пускать людей по списку который задан как раз в новой вкладке».
///
/// БОТ — ЖИВОЙ ИГРОК, А НЕ СЕРВЕР. Чужим движением он не распоряжается: в игре
/// нет ни клиентского способа запретить человеку идти, ни игрока, который
/// собой перегораживает проход, — <c>EntityPlayer</c> другому игроку не
/// препятствие (столкновения считаются с блоками мира, не с чужими телами).
/// Всё, что можно было бы назвать «не пустил», делает СЕРВЕР: бан, кик,
/// клейм-привилегия. Обещать это ролью значит нарисовать человеку рычаг,
/// который никуда не соединён.
///
/// ЧТО ЖИВОЙ ОХРАННИК ВПРАВДУ МОЖЕТ И ЧТО ИЗ ЭТОГО ВЗЯТО:
///   • УВИДЕТЬ И УЗНАТЬ В ЛИЦО — имена игроков рядом бот читает всегда
///     (<see cref="EntityInfo.PlayerName"/>). Взято.
///   • СКАЗАТЬ В ЧАТ, назвав по имени: «тебе сюда нельзя». Взято, это главное
///     дело роли.
///   • ПОЗВАТЬ ХОЗЯИНА — назвать его ником в том же сообщении. Взято.
///   • УДАРИТЬ. Единственное действие, которое вправду может прогнать человека,
///     и единственное необратимое. Взято РУЧКОЙ РОЛИ и по умолчанию ВЫКЛЮЧЕНО:
///     драка со «своими по списку» — это политика хозяина, а не наше решение.
///   • ВСТАТЬ НА ПУТИ — НЕ взято, и это отказ, а не забывчивость: телом чужого
///     игрока не остановить, и «бот загораживает проход» было бы театром,
///     который человек примет за охрану.
///   • ЗАБАНИТЬ, КИКНУТЬ, ЗАКРЫТЬ КЛЕЙМОМ — НЕ взято: это права сервера. Если
///     хозяин даст боту админские права, «/ban ник» из чата у него сработает
///     так же, как у живого админа, — но это отдельный заказ и отдельная
///     ответственность, и молча делать это нельзя.
///
/// ИТОГ ОДНОЙ СТРОКОЙ, и он же написан в описании роли для окна: стражник
/// ЗАМЕЧАЕТ, ПРЕДУПРЕЖДАЕТ И ЗОВЁТ, а по прямому разрешению хозяина — БЬЁТ.
/// Держать человека силой он не умеет и не притворяется, что умеет.
/// </summary>
public static class GuardRules
{
    /// <summary>Чем разделяют ники в списке: запятая, точка с запятой, перевод строки.</summary>
    private static readonly char[] Разделители = [',', ';', '\n', '\r'];

    /// <summary>
    /// РАЗОБРАТЬ СПИСОК НИКОВ, набранный человеком одной строкой.
    ///
    /// Чистое правило: ни бота, ни мира — строка на входе, имена на выходе.
    /// Ошибка здесь стоит либо «предупреждает всех подряд», либо «молчит про
    /// того, кого вписали», и увидеть её в мире можно только тем, что бот
    /// повёл себя не так; потому и стенд.
    ///
    /// Пробелы по краям срезаются (человек набирает «вася, петя» с пробелом),
    /// пустые куски выбрасываются (лишняя запятая в конце — обычное дело), а
    /// повторы в разном регистре считаются одним именем: в игре ник
    /// единственный, и «Вася» с «вася» — это один человек.
    /// </summary>
    public static IReadOnlyList<string> Ники(string? строка)
    {
        if (string.IsNullOrWhiteSpace(строка))
            return [];
        var видели = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var список = new List<string>();
        foreach (string кусок in строка.Split(Разделители))
        {
            string ник = кусок.Trim();
            if (ник.Length > 0 && видели.Add(ник))
                список.Add(ник);
        }
        return список;
    }

    /// <summary>
    /// ЕСТЬ ЛИ ЭТОТ ЧЕЛОВЕК В СПИСКЕ.
    ///
    /// СРАВНЕНИЕ ЦЕЛИКОМ, А НЕ ПО ЧАСТИ СЛОВА, и это не придирка. Возьми мы
    /// «содержит» — строка «Ив» в списке накрыла бы Ивана, Ивонну и Иванушку
    /// разом, а строка «а» — половину сервера. Цена ошибки здесь — бот, который
    /// бьёт не того; поэтому имя должно совпасть полностью, с точностью до
    /// регистра букв.
    ///
    /// ПУСТОЙ СПИСОК НЕ ЗАПРЕЩАЕТ НИКОГО. Это тоже решение, а не мелочь: «пусто
    /// значит всех» дало бы стражника, который на первом же запуске набросился
    /// на хозяина.
    /// </summary>
    public static bool Чужой(string? список, string? имя) =>
        !string.IsNullOrWhiteSpace(имя) &&
        Ники(список).Any(н => string.Equals(н, имя, StringComparison.OrdinalIgnoreCase));

    /// <summary>Заводское предупреждение — если человек стёр своё.</summary>
    public const string ЗаводскоеПредупреждение = "{ник}, тебе сюда нельзя. Уходи.";

    /// <summary>Заводской зов хозяина.</summary>
    public const string ЗаводскойЗов = "{хозяин}, у ворот {ник}.";

    /// <summary>
    /// ЧТО СКАЗАТЬ В ЧАТ: шаблон с подстановкой «{ник}» и «{хозяин}».
    ///
    /// ПУСТОЙ ШАБЛОН — НЕ МОЛЧАНИЕ, А ЗАВОДСКАЯ ФРАЗА. Стереть текст в окне
    /// человек может случайно (выделил, нажал Delete, ушёл), и стражник, молча
    /// переставший предупреждать, выглядит как сломанный. Выключают
    /// предупреждение ГАЛОЧКОЙ («ПредупреждатьВЧат»), а не пустым полем: у
    /// «выключить» должно быть одно место, и оно должно называться словом.
    ///
    /// ХОЗЯИН НЕ НАЗВАН — про хозяина ничего и не говорится: «{хозяин}» не
    /// превращается в пустоту посреди фразы («, у ворот вася»), а вся строка
    /// с ним просто не собирается. Об этом решает <see cref="Сказать"/> вызывающий.
    /// </summary>
    public static string Подставить(string? шаблон, string ник, string? хозяин)
    {
        string текст = string.IsNullOrWhiteSpace(шаблон) ? ЗаводскоеПредупреждение : шаблон;
        return текст
            .Replace("{ник}", ник, StringComparison.OrdinalIgnoreCase)
            .Replace("{хозяин}", (хозяин ?? "").Trim(), StringComparison.OrdinalIgnoreCase)
            .Trim();
    }

    /// <summary>
    /// ЦЕЛИКОМ ТО, ЧТО УЙДЁТ В ЧАТ: предупреждение чужому и, если хозяин
    /// назван и его велено звать, зов хозяина — ОДНОЙ строкой.
    ///
    /// Одной, а не двумя: две строки подряд от одного игрока в чате читаются
    /// как спам, и живой охранник так не говорит. Пусто — значит сказать
    /// нечего, и звать сервер незачем.
    /// </summary>
    public static string Сказать(bool предупреждать, string? шаблон,
        bool зватьХозяина, string? зовШаблон, string? хозяин, string ник)
    {
        var части = new List<string>();
        if (предупреждать)
            части.Add(Подставить(шаблон, ник, хозяин));
        if (зватьХозяина && !string.IsNullOrWhiteSpace(хозяин))
            части.Add(Подставить(string.IsNullOrWhiteSpace(зовШаблон) ? ЗаводскойЗов : зовШаблон,
                ник, хозяин));
        return string.Join(" ", части.Where(ч => ч.Length > 0)).Trim();
    }

    /// <summary>
    /// БИТЬ ЛИ ЭТОГО ЧЕЛОВЕКА ПРЯМО СЕЙЧАС.
    ///
    /// Три условия И ВСЕ ТРИ ОБЯЗАТЕЛЬНЫ, потому что удар необратим:
    ///   1) хозяин разрешил (ручка «Бить», заводское — НЕТ);
    ///   2) человек в списке чужих (иначе бьём случайного прохожего);
    ///   3) он ВНУТРИ охраняемой зоны (иначе стражник бьёт того, кто уже ушёл,
    ///      и гонится за ним по полю).
    /// Дальность удара сюда приходит доводом, а не берётся числом: она живёт у
    /// боевой способности (<c>BehaviorAttackHostiles.AttackReach</c>), и второй
    /// её копии здесь быть не должно.
    /// </summary>
    public static bool Бить(bool разрешено, bool чужой, double отПоста, double радиусЗоны,
        double доЧеловека, double дальностьУдара) =>
        разрешено && чужой && отПоста <= радиусЗоны && доЧеловека <= дальностьУдара;

    /// <summary>
    /// ПОРА ЛИ ГОВОРИТЬ СНОВА. Без этого правила стражник повторяет
    /// предупреждение каждый тик — то есть несколько раз в секунду, — и чат
    /// становится нечитаемым, а бот выглядит сломанным.
    ///
    /// Срок отсчитывается ДЛЯ КАЖДОГО ЧЕЛОВЕКА отдельно (это забота
    /// вызывающего): двое чужих не должны затыкать друг друга.
    /// </summary>
    public static bool ПораГоворить(DateTime сейчас, DateTime когдаМожно) => сейчас >= когдаМожно;
}

/// <summary>
/// СПОСОБНОСТЬ СТРАЖНИКА: заметить чужого по списку, предупредить его в чат,
/// позвать хозяина и — только если хозяин это прямо разрешил — ударить.
///
/// ПОЧЕМУ КОДОМ, А НЕ СБОРКОЙ ИЗ ГОТОВЫХ УМЕНИЙ. Заказчик разрешил прямо:
/// «поведение прописывается отдельно кодом, если оно не может быть просто
/// собрано из готовых скиллов». Собрать это было не из чего: боевая
/// способность заводится КОДАМИ ТВАРЕЙ и только в ответ на удар, приветствие
/// здоровается со всеми одинаково, а списка имён как настройки у бота не было
/// вовсе. Два других дела стражника — стоять в точке и кормиться со склада —
/// собираются готовым (см. <see cref="GuardRole.Configure"/>): первое —
/// библиотечным удержанием точки (<see cref="BehaviorHoldPost"/>), второе —
/// рефлексом еды из кладовых. Своего кода здесь для них нет.
///
/// ХОДА НЕ БЕРЁТ, ПОКА ТОЛЬКО ГОВОРИТ. Речь ничего не занимает: пока стражник
/// предупреждает, он обязан продолжать есть, лечиться и отбиваться. Тело
/// берётся ровно на удар и ровно на подход к тому, кого бьют.
/// </summary>
public class BehaviorGuardGate : BotBehavior
{
    private readonly BotContext ctx;

    /// <summary>
    /// Боевая способность бота — ИСТОЧНИК ЧИСЕЛ УДАРА, а не второй боец.
    /// Дальность и частота размаха живут у неё; переписать их сюда значило бы
    /// завести второе место, где хранится одно и то же, и однажды они разойдутся.
    /// </summary>
    private readonly BehaviorAttackHostiles бой;

    /// <summary>
    /// ГЛАЗА — ТЕ ЖЕ, ЧТО У ВСЕГО ОСТАЛЬНОГО БОТА. Своей проверки видимости
    /// здесь не заводится: она уже есть и считает лучами самой игры
    /// (<see cref="Sight.LookAtCreature"/>), теми же тремя высотами.
    /// </summary>
    private readonly Sight глаза;

    public BehaviorGuardGate(BotContext ctx, BehaviorAttackHostiles бой)
    {
        this.ctx = ctx;
        this.бой = бой;
        глаза = new Sight(ctx);
    }

    /// <summary>
    /// ЦЕНТР ОХРАНЯЕМОЙ ЗОНЫ — в МИРОВЫХ координатах, доносит роль.
    ///
    /// ЭТО ТА ЖЕ ТОЧКА, У КОТОРОЙ СТРАЖНИК И СТОИТ (<see cref="BehaviorHoldPost.Post"/>):
    /// роль считает её ОДИН раз и раздаёт обеим способностям
    /// (<see cref="GuardRole.ДонестиОбщее"/>). Спроси мы её у укрытия сами, как
    /// было раньше, — вышло бы два ответа на вопрос «где мой пост»: один у
    /// зоны, другой у ног.
    ///
    /// Раньше здесь стояло <c>убежище.Home</c>, то есть общая точка «Дом», и
    /// док-строка обещала, что своей точки у стражника не будет. Обещание
    /// снято по прямому заказу 23.08: «охраннику не хватает настроек где
    /// конкретно стоять». Что старше — разобрано у ручки <c>GuardRole.Пост</c>.
    /// </summary>
    public BlockPos? Пост { get; set; }

    /// <summary>
    /// КАК ЭТА СПОСОБНОСТЬ ЗОВЁТСЯ ЧЕЛОВЕКУ. Не украшение: этим самым словом
    /// человек двигает её вес в строке «ВесаВажности» («стража 85; еда 80») и
    /// по нему же находит её в списке важности в окне. Библиотечная таблица
    /// имён назвать её не может — она в VsBotKit, а роль в приложении, и ссылка
    /// идёт в одну сторону (см. <see cref="BotBehavior.Title"/>); без этой
    /// строки стражник назывался бы человеку «GuardGate».
    /// </summary>
    public override string Title => "стража";

    /// <summary>Список запрещённых ников одной строкой (ручка роли «ЧужиеНики»).</summary>
    public string Чужие { get; set; } = "";

    /// <summary>Ник хозяина, которого зовут (ручка роли «Хозяин»).</summary>
    public string Хозяин { get; set; } = "";

    /// <summary>Радиус охраняемой зоны ВОКРУГ ПОСТА, блоков.</summary>
    public double Радиус { get; set; } = 24;

    /// <summary>Говорить ли чужому в чат.</summary>
    public bool Предупреждать { get; set; } = true;

    /// <summary>Что говорить чужому (шаблон с «{ник}»).</summary>
    public string Предупреждение { get; set; } = GuardRules.ЗаводскоеПредупреждение;

    /// <summary>Звать ли хозяина.</summary>
    public bool ЗватьХозяина { get; set; } = true;

    /// <summary>Как звать хозяина (шаблон с «{хозяин}» и «{ник}»).</summary>
    public string Зов { get; set; } = GuardRules.ЗаводскойЗов;

    /// <summary>Не повторять сказанное одному и тому же человеку чаще этого срока.</summary>
    public TimeSpan Повтор { get; set; } = TimeSpan.FromSeconds(120);

    /// <summary>Бить чужого. Заводское — НЕТ: удар необратим и решает его хозяин.</summary>
    public bool Бить { get; set; }

    /// <summary>Подходить к чужому, чтобы ударить (иначе бьёт только подошедшего вплотную).</summary>
    public bool Подходить { get; set; }

    /// <summary>Сколько секунд на один подход к нарушителю.</summary>
    public double СекундНаПодход { get; set; } = 12;

    /// <summary>Сказать в игровой чат. Роль решает, каким голосом и глушится ли это.</summary>
    public event Action<string>? OnSay;

    /// <summary>Строка в журнал хозяина.</summary>
    public event Action<string>? OnLog;

    /// <summary>Кого заметили: ник и расстояние от поста. Для окна и стендов.</summary>
    public event Action<string, double>? OnSpotted;

    /// <summary>Когда с этим человеком можно заговорить снова.</summary>
    private readonly Dictionary<string, DateTime> молчатьДо = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>О чём уже пожаловались: чтобы не повторять один и тот же отказ каждый тик.</summary>
    private readonly HashSet<string> сказанное = [];
    private DateTime следующийУдар = DateTime.MinValue;

    /// <summary>
    /// ЧЕСТНЫЙ ОТКАЗ ОДИН РАЗ. Стражник без поста или с пустым списком не
    /// работает вовсе, и молчать об этом нельзя: со стороны это неотличимо от
    /// «бот сломался». Но и повторять это шестьдесят раз в минуту нельзя —
    /// журнал заказчика тогда состоит из одной строки.
    /// </summary>
    private void ЖаловатьсяРаз(string ключ, string что)
    {
        if (сказанное.Add(ключ))
            OnLog?.Invoke(что);
    }

    private void ЖалобаСнята(string ключ) => сказанное.Remove(ключ);

    public override async Task<bool> TickAsync(CancellationToken ct)
    {
        // ОТКАЗЫ ПРО НАСТРОЙКУ — ПЕРВЫМИ, ДО ВСЯКОГО «ГДЕ Я». Порядок тут не
        // вкусовой: «поста нет» и «список пуст» — это правда о НАСТРОЙКЕ, она
        // верна и до входа в мир. Спроси мы сперва «где я», бот, ещё не
        // вошедший на сервер, молчал бы о том, что его забыли настроить, — а
        // человек в это время смотрел бы на окно и ждал работающего стражника.

        // ПОСТ ДОНОСИТ РОЛЬ, и он же — центр зоны. Пусто здесь значит, что не
        // заполнена НИ ОДНА из двух точек: ни своя «Пост», ни общая «Дом»
        if (Пост is not { } пост)
        {
            ЖаловатьсяРаз("нет-поста",
                "стражнику не задан ПОСТ: это ручка роли «Пост» (вкладка «Настройка роли») " +
                "или команда «!пост тут», сказанная там, где я должен стоять. Без поста " +
                "охранять нечего — зона считается вокруг него. Не задан и «Пост», и общий " +
                "«Дом»: пока пусты оба, я просто обычный бот");
            return false;
        }
        ЖалобаСнята("нет-поста");

        var ники = GuardRules.Ники(Чужие);
        if (ники.Count == 0)
        {
            ЖаловатьсяРаз("пустой-список",
                "список запрещённых ников пуст — не пускать некого. Впишите ники через запятую " +
                "во вкладке «Настройка роли», поле «ЧужиеНики». Пустой список НИКОГО не запрещает");
            return false;
        }
        ЖалобаСнята("пустой-список");

        // А вот дальше без «где я» нельзя: кого видно, считается от нас
        if (ctx.Entities.Self is not { } себя)
            return false;

        // Ищем вокруг СЕБЯ, а зону считаем от ПОСТА: стражник, отошедший на
        // три шага, не должен переставать видеть тех, кто уже в воротах
        double видеть = Радиус + 16;
        var рядом = ctx.Entities.Nearby(себя.X, себя.Y, себя.Z, видеть)
            .Where(e => e.IsPlayer && e.Id != ctx.Entities.OwnEntityId &&
                        GuardRules.Чужой(Чужие, e.PlayerName))
            .Select(e => (Кто: e, ОтПоста: Расстояние(e, пост)))
            .Where(п => п.ОтПоста <= Радиус)
            .OrderBy(п => п.ОтПоста)
            // ЛУЧ ЗРЕНИЯ НЕ БЕСПЛАТЕН, а у ворот на людном сервере стоят
            // десятки. Столько же смотрит за тик и приветствие
            // (<c>Meetings.WatchAtMost</c>) — второго числа тут не заводим
            .Take(СмотретьЗаТик)
            .ToList();

        // СМОТРИМ ГЛАЗАМИ, А НЕ СПИСКОМ СУЩНОСТЕЙ. Ближайший — не значит
        // видимый: за стеной он для живого охранника не существует
        var чужой = рядом.FirstOrDefault(п => Вижу(п.Кто));
        if (чужой.Кто == null && рядом.Count > 0)
            // Кто-то из списка в зоне, но ни одного не видно. Молчать нельзя:
            // со стороны это неотличимо от «стражник не работает». И повторять
            // каждый тик нельзя — потому один раз, как и все прочие отказы
            ЖаловатьсяРаз("невидно",
                $"в зоне есть кто-то из списка ({рядом.Count}), но ни одного не видно: " +
                "между нами блоки. Живой охранник сквозь стену тоже не смотрит — " +
                "поставьте пост так, чтобы подход просматривался");
        else if (чужой.Кто != null)
            ЖалобаСнята("невидно");

        if (чужой.Кто is not { } человек || человек.PlayerName is not { Length: > 0 } ник)
            return false;

        OnSpotted?.Invoke(ник, чужой.ОтПоста);

        // 1. СЛОВО. Первое и главное: живой охранник сперва говорит
        if (!молчатьДо.TryGetValue(ник, out var когда))
            когда = DateTime.MinValue;
        if (GuardRules.ПораГоворить(DateTime.UtcNow, когда))
        {
            молчатьДо[ник] = DateTime.UtcNow + Повтор;
            string речь = GuardRules.Сказать(Предупреждать, Предупреждение,
                ЗватьХозяина, Зов, Хозяин, ник);
            if (речь.Length > 0)
                OnSay?.Invoke(речь);
            OnLog?.Invoke($"[стража] {ник} в зоне, {чужой.ОтПоста:0.#} бл от поста" +
                          (речь.Length > 0 ? $"; сказал: {речь}" : "; говорить нечем — всё выключено"));
        }

        // 2. УДАР. Только по прямому разрешению хозяина, и об отказе — вслух
        if (!Бить)
            return false;

        double доЧеловека = человек.DistanceTo(себя.X, себя.Y, себя.Z);
        if (РукаНеДостаёт(доЧеловека) && !Подходить)
        {
            ЖаловатьсяРаз($"недостать:{ник}",
                $"бить {ник} велено, но он в {доЧеловека:0.#} бл, а рука достаёт на " +
                $"{бой.AttackReach:0.#}; подходить не велено (ручка «ПодходитьЧтобыУдарить»)");
            return false;
        }
        ЖалобаСнята($"недостать:{ник}");

        using var ход = ctx.Turn.TryTake("стража: чужой у поста",
            BodyArbiter.Importance.Reflex, ct);
        if (ход == null)
            return false;

        if (РукаНеДостаёт(доЧеловека))
        {
            long id = человек.Id;
            bool дошёл = await ctx.Movement.ApproachAsync(
                () => ctx.Entities.Get(id) is { } ц ? (ц.X, ц.Y, ц.Z) : null,
                Math.Max(1.0, бой.AttackReach - 0.3), СекундНаПодход, ход.Token);
            if (!дошёл)
            {
                OnLog?.Invoke($"[стража] до {ник} не дошёл за {СекундНаПодход:0} с");
                return true;
            }
            доЧеловека = ctx.Entities.Get(id)?.DistanceTo(себя.X, себя.Y, себя.Z) ?? double.MaxValue;
        }

        if (!GuardRules.Бить(Бить, true, чужой.ОтПоста, Радиус, доЧеловека, бой.AttackReach))
            return true;

        // Частота размаха — ЕЁ ЖЕ, боевой способности: своего числа тут нет
        if (DateTime.UtcNow < следующийУдар)
            return true;
        следующийУдар = DateTime.UtcNow.AddMilliseconds(Math.Max(1, бой.SwingIntervalMs));
        await ctx.Actions.AttackEntityAsync(человек.Id, ход.Token);
        OnLog?.Invoke($"[стража] ударил {ник} ({доЧеловека:0.#} бл)");
        return true;

        // Дальность руки — ЕЁ ЖЕ, боевой способности: своего числа тут нет
        bool РукаНеДостаёт(double далеко) => далеко > бой.AttackReach;
    }

    /// <summary>
    /// Сколько ближайших осматривать за тик: луч зрения не бесплатный. Столько
    /// же смотрит приветствие (<c>Meetings.WatchAtMost</c>).
    /// </summary>
    private const int СмотретьЗаТик = 5;

    /// <summary>
    /// ВИЖУ ЛИ Я ЭТОГО ЧЕЛОВЕКА ПО-ЧЕСТНОМУ.
    ///
    /// ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ — И ЭТО НЕ ПРИДИРКА. Без проверки стражник
    /// «замечал» человека по одному только расстоянию: сквозь стену, сквозь
    /// гору, в кромешной темноте, в наглухо закрытой комнате за двадцать
    /// блоков — и тут же называл его ПО ИМЕНИ В ОБЩИЙ ЧАТ. Живой охранник так
    /// не может, и три беды сразу:
    ///   • это выдаёт бота с головой: человек, стоящий в закрытом подвале,
    ///     читает в чате своё имя и понимает, что его видят сквозь камень;
    ///   • на людном сервере это чистое преимущество, которого у людей нет;
    ///   • с включённым «Бить» стражник шёл бить того, кого не видит.
    /// Сам проект называет действие без прямой видимости ЧИТОМ
    /// (<see cref="Cheats.NoLineOfSight"/>) — то есть тем, что включают вслух и
    /// нарочно. Делать это молча и с завода было нельзя.
    ///
    /// СЧИТАЕТСЯ ЧУЖИМ МЕХАНИЗМОМ, А НЕ СВОИМ: <see cref="Sight.LookAtCreature"/>
    /// ведёт те же три луча и на тех же высотах, что и сама игра, и им же
    /// пользуется приветствие (<c>Meetings.CanSee</c>). Своей второй проверки
    /// видимости в проекте быть не должно.
    ///
    /// ПРОВЕРИТЬ НЕЧЕМ — ЗНАЧИТ ВИДНО. Пока реестр блоков сервера не пришёл,
    /// врать про преграду нельзя; так же поступают и руки
    /// (<c>Hands.InReach</c>), и приветствие.
    ///
    /// ЧИТ «БЕЗ ПРЯМОЙ ВИДИМОСТИ» ОСТАЁТСЯ ЕДИНСТВЕННЫМ ВЫКЛЮЧАТЕЛЕМ. Своей
    /// ручки роли здесь нарочно не заводится: второе место, где отключается
    /// одно и то же, разошлось бы с первым, а этот рубильник уже есть, уже
    /// объявляется в журнал и уже честно зовётся читом.
    /// </summary>
    private bool Вижу(EntityInfo кто)
    {
        if (ctx.Cheats.On(ctx.Cheats.NoLineOfSight, nameof(Cheats.NoLineOfSight)))
            return true;
        глаза.Range = Радиус + 16;
        var взгляд = глаза.LookAtCreature(кто.X, кто.Y, кто.Z);
        return !взгляд.Known || взгляд.Visible;
    }

    /// <summary>
    /// СКОЛЬКО ДО ПОСТА — СПРАШИВАЕМ У ОБЩЕГО ПРАВИЛА, А НЕ СЧИТАЕМ ЗАНОВО.
    ///
    /// Здесь ЛЕЖАЛА вторая копия <see cref="PostRules.Отступ"/>, побуквенно
    /// та же самая, включая полублоки по X и Z и высоту без полублока, — и
    /// лежала она В ОДНОЙ РОЛИ с первой. Живьём это значило: поправь кто-нибудь
    /// соглашение о полублоке или о высоте в общем правиле — стражник начал бы
    /// СТОЯТЬ по одной мерке, а окликать чужих по другой, то есть охранять
    /// круг не вокруг того места, где стоит.
    /// </summary>
    private static double Расстояние(EntityInfo кто, BlockPos пост) =>
        PostRules.Отступ(кто.X, кто.Y, кто.Z, пост);
}

/// <summary>
/// СТРАЖНИК — РОЛЬ БЕЗ НЕЙРОСЕТИ.
///
/// Заказчик дословно: «стражнника для теста хотел без ИИ, у него должны быть
/// кастомные настройки… ему нужно стоять в одной точке, кушать со склада и не
/// пускать людей по списку который задан как раз в новой вкладке».
///
/// ТРИ ЕГО ДЕЛА И ОТКУДА КАЖДОЕ БЕРЁТСЯ:
///   1. СТОЯТЬ В ОДНОЙ ТОЧКЕ — готовым: точка это общая настройка «Дом», а
///      «БезДела: Домой» возвращает к ней. Своего кода нет и не надо.
///   2. КОРМИТЬСЯ СО СКЛАДА — готовым: рефлекс еды берёт съестное из кладовых
///      (BehaviorForageWhenNoFood.FromStores), а где кладовые — говорит общая
///      настройка склада. Своего кода нет и не надо.
///   3. НЕ ПУСКАТЬ ПО СПИСКУ — своим кодом, <see cref="BehaviorGuardGate"/>.
///      Что «не пускать» вправду значит, разобрано в <see cref="GuardRules"/>,
///      и разобрано ЧЕСТНО: держать человека силой бот не умеет.
///
/// НЕЙРОСЕТИ ЗДЕСЬ НЕТ ВОВСЕ — ни ключа, ни поставщика, ни счёта за думанье.
/// Прежний «стражник» был пресетом роли ИИ, и решала за него модель: она могла
/// прозевать вход, ошибиться именем или заговорить вместо дела. Список ников,
/// сравнение и молчание между окриками — это правило на десять строк, и
/// платить за него нейросетью незачем.
/// </summary>
public class GuardRole : LivingRole
{
    public override string Name => "Стражник";

    // ================= СВОЁ У СТРАЖНИКА =================
    //
    // ВСЁ, ЧТО НИЖЕ, — СВОЁ: ни у выживальщика, ни у продавца, ни у ИИ таких
    // настроек нет. Ровно они и показываются на вкладке «Настройка роли», о
    // которой просил заказчик: «что мы туда вписали кастомного, то отдельно и
    // настраивается».

    /// <summary>Имя раздела окна: свои настройки стражника.</summary>
    public const string Стража = "стража";

    /// <summary>Как раздел зовётся человеку.</summary>
    public const string СтражаЗаголовок = "Стража";

    /// <summary>Одной строкой: что лежит в разделе.</summary>
    public const string СтражаОписание =
        "кого не пускать, что говорить, кого звать и бить ли — всё, чем " +
        "стражник отличается от любого другого бота";

    /// <summary>
    /// ГДЕ КОНКРЕТНО СТОЯТЬ — ТРИ ЧИСЛА, ТЕ САМЫЕ, ЧТО ПОКАЗЫВАЕТ ОКНО
    /// КООРДИНАТ В ИГРЕ.
    ///
    /// ПРЯМОЙ ЗАКАЗ 23.08: «охраннику не хватает настроек где конкретно
    /// стоять». А ещё раньше, 22.08, когда стражник только заказывался: «ему
    /// нужно СТОЯТЬ В ОДНОЙ ТОЧКЕ». Мы тогда решили обойтись общей точкой
    /// «Дом» — и обещание «своей второй точки не будет» стояло прямо в этом
    /// файле. Оно снято, и вот чем оно вышло человеку: «Дом» ЛЕЖАЛ ТОГДА на
    /// чужой вкладке («Общие настройки» → «Точки роли»), а за настройкой
    /// стражника он шёл во вкладку «Настройка роли», где её не было вовсе.
    ///
    /// С 29.08 ЭТО УЖЕ НЕ ТАК, и путать два времени нельзя: «Склад» и «Дом»
    /// переехали на вкладку «Настройка роли» по прямой просьбе заказчика
    /// («сохранение склада и дома давай на одной странице настроек — в
    /// настройки роли»), и «Пост» стоит теперь рядом с ними, на той же
    /// странице. Довод выше остаётся в силе не вкладкой, а смыслом: «где
    /// стоять» и «где прятаться в бурю» — разные вопросы.
    ///
    /// ЧТО СТАРШЕ — «ПОСТ» ИЛИ «ДОМ». Старше ПОСТ, и порядок такой:
    ///   • «Пост» задан — стражник стоит на нём, и зона считается вокруг него;
    ///   • «Пост» пуст — зона считается вокруг «Дома», ровно как до 23.08, а
    ///     удержание точки молчит и один раз честно говорит, какой ручки не
    ///     хватает. Пустой «Пост» — это НЕ поломка, а прежний стражник;
    ///   • «Дом» при этом остаётся тем же, чем он у всех ролей: где прятаться
    ///     в бурю, где возрождаться и где искать свои сундуки. «Где стоять» он
    ///     больше не значит.
    /// Две точки, заполненные РАЗНЫМИ местами, вместе с «БезДела: Домой» —
    /// единственный способ заставить стражника ходить между ними; об этом
    /// говорится один раз в журнал, а не чинится молча за человека
    /// (см. <see cref="ДонестиОбщее"/>).
    ///
    /// КООРДИНАТЫ ИГРОВЫЕ. Внутри мир живёт в абсолютных (512061, 112, 512257),
    /// и перевод делается ОДНИМ правилом на весь проект
    /// (<see cref="WorldOrigin"/>), уже после входа в мир: до входа переводить
    /// нечем, и роль об этом честно говорит, а не отправляет бота за полмиллиона
    /// блоков.
    ///
    /// ЗАДАЁТСЯ ТРЕМЯ ДОРОГАМИ, И ВСЕ ТРИ УЖЕ ЕСТЬ: числами в окне, щелчком по
    /// карте (вкладка «Задачи и карта» — точка сама попадает в список, потому
    /// что она игровая) и командой «!пост тут» с того места, где бот стоит.
    /// </summary>
    [KnobPlace(Стража, Title = СтражаЗаголовок, About = СтражаОписание, Order = 1, Main = true)]
    public GamePos? Пост { get; set; }

    /// <summary>
    /// НА СКОЛЬКО МОЖНО ОТОЙТИ ОТ ПОСТА, блоков. Дальше — возвращается.
    ///
    /// Не ноль нарочно: тело стоит не в углу клетки, а где придётся внутри неё,
    /// и «ровно в точку» означало бы бота, дёргающегося на месте всю смену.
    /// Высота считается наравне с шириной: пост у ворот часто стоит на стене
    /// или на помосте, и бот, свалившийся вниз, по горизонтали остаётся ровно
    /// над постом (разбор — <see cref="PostRules.Отступ"/>).
    /// </summary>
    [KnobPlace(Стража, Title = СтражаЗаголовок, About = СтражаОписание, Order = 2, Main = true)]
    public double ОтходитьОтПостаНеДальше { get; set; } = 3;

    /// <summary>
    /// ПОВОДОК: дальше этого от поста стражник САМ не возвращается, а говорит,
    /// что его унесло.
    ///
    /// ПОЧЕМУ НЕ «ПоводокОтПоста», КАК У ПРОДАВЦА. Такая ручка у продавца уже
    /// есть (<c>HelperRole.ПоводокОтПоста</c>), и «своим» у роли считается то,
    /// чего нет ни у одной другой (<c>RoleCatalog.OnlyHere</c>). Возьми
    /// стражник то же имя — ручка перестала бы быть своей У ОБОИХ и ушла бы с
    /// вкладки «Настройка роли» на общую, то есть ровно туда, откуда заказчик
    /// её и просил забрать. Имя здесь ещё и честнее: поводок продавца ничего
    /// не удерживает, он только отсекает «слишком далеко, сам не пойду», —
    /// именно это тут и написано словами.
    ///
    /// Зачем предел вообще. Бота уносит смертью и возрождением: кровать или
    /// точка возрождения может стоять в получасе ходьбы, и «иду на пост»
    /// оттуда — это час дороги через мобов вместо одной строки в журнале, по
    /// которой человек вернёт его сам. Отказ называет эту ручку по имени.
    ///
    /// Поводок КОРОЧЕ радиуса поста — не запрет, а описка: раз человек сам
    /// назвал этот круг постом, стоять в нём не может быть «слишком далеко»
    /// (<see cref="PostRules.Что"/>).
    /// </summary>
    [KnobPlace(Стража, Title = СтражаЗаголовок, About = СтражаОписание, Order = 3)]
    public double ВозвращатьсяНаПостНеДальше { get; set; } = 64;

    /// <summary>
    /// СПИСОК ЗАПРЕЩЁННЫХ НИКОВ — ЧЕРЕЗ ЗАПЯТУЮ. Та самая настройка, ради
    /// которой заводилась вкладка: «не пускать людей по списку который задан
    /// как раз в новой вкладке».
    ///
    /// Имя сравнивается ЦЕЛИКОМ и без оглядки на регистр букв: «Вася» в списке
    /// накрывает «вася» и не накрывает «Василия». Почему не «по части слова» —
    /// разобрано в <see cref="GuardRules.Чужой"/>: цена ошибки здесь бот,
    /// который бьёт не того.
    ///
    /// ПУСТОЙ СПИСОК НИКОГО НЕ ЗАПРЕЩАЕТ, и стражник об этом СКАЖЕТ в журнал
    /// один раз, а не будет молча стоять с видом работающего.
    /// </summary>
    [KnobPlace(Стража, Title = СтражаЗаголовок, About = СтражаОписание, Order = 4, Main = true)]
    public string ЧужиеНики { get; set; } = "";

    /// <summary>
    /// РАДИУС ОХРАНЯЕМОЙ ЗОНЫ ВОКРУГ ПОСТА, блоков. Пост — это ручка «Пост»,
    /// а пока она пуста — общая точка «Дом» (что старше, разобрано у самой
    /// ручки <see cref="Пост"/>).
    ///
    /// Чужой ВНЕ этого круга стражника не касается: он не гоняется за людьми по
    /// полю и не окликает прохожих за сто блоков.
    /// </summary>
    [KnobPlace(Стража, Title = СтражаЗаголовок, About = СтражаОписание, Order = 5, Main = true)]
    public double ОхранятьВРадиусе { get; set; } = 24;

    /// <summary>
    /// ГОВОРИТЬ ЛИ ЧУЖОМУ В ЧАТ. Главное и, по умолчанию, единственное дело
    /// стражника: заметил — назвал по имени и сказал, что сюда нельзя.
    ///
    /// РАДИОТИШИНА («ПисатьВЧатОСвоихДелах») ЭТОГО НЕ ГЛУШИТ, и это разобранное
    /// решение, а не недосмотр. Радиотишина прячет рассказы бота о своей работе
    /// («мощу дорогу, 3 ряда из 38»); предупреждение у ворот — не рассказ о
    /// работе, а сама работа, и погасить её настройкой «не болтай о своих
    /// делах» значило бы выключить роль исподтишка. Выключается она ЗДЕСЬ,
    /// одной галочкой с понятным именем.
    /// </summary>
    [KnobPlace(Стража, Title = СтражаЗаголовок, About = СтражаОписание, Order = 6, Main = true)]
    public bool ПредупреждатьВЧат { get; set; } = true;

    /// <summary>
    /// ЧТО ГОВОРИТЬ ЧУЖОМУ. «{ник}» подставляется именем пришедшего, «{хозяин}»
    /// — ником из настройки «Хозяин».
    ///
    /// Стёрли текст — берётся заводская фраза, а не молчание: выключают
    /// предупреждение галочкой выше, и у «выключить» должно быть одно место.
    /// </summary>
    [KnobPlace(Стража, Title = СтражаЗаголовок, About = СтражаОписание, Order = 7)]
