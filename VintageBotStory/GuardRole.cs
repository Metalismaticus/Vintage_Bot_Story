    /// <summary>
    /// ЗАВОДСКИЕ ПРИВЫЧКИ СТРАЖНИКА. Это УМОЛЧАНИЯ, а не запреты: пресет и
    /// окно старше нашего слова, и хозяин ночной стражи включит сон обратно.
    ///
    /// Почему именно так:
    ///   • «БезДела: Домой» ОСТАВЛЕНО, но «стоять в одной точке» держится уже
    ///     не им, а удержанием поста (<see cref="BehaviorHoldPost"/>). Оставлено
    ///     затем, что пустой «Пост» обязан вести себя КАК РАНЬШЕ: без него
    ///     возврат к общей точке «Дом» — единственное, что у стражника есть.
    ///     Заполнены ОБЕ точки и врозь — механизмов возврата становится два, и
    ///     они тянут в разные стороны; за человека мы этого не чиним, а
    ///     говорим один раз в журнал (см. <see cref="ДонестиОбщее"/>);
    ///   • порог безделья короткий: отвлёкся на драку — возвращайся на пост
    ///     через полминуты, а не через минуту;
    ///   • сон выключен: пост есть пост, и кровати у ворот обычно нет;
    ///   • мстить «Никогда» — то есть отбиваться только от подошедшего
    ///     вплотную: бросить пост и убежать за дрифтером в поле хуже, чем
    ///     принять бой;
    ///   • ЧЕТЫРЕ ПРИЁМА ПУТИ ПОГАШЕНЫ — разбор ниже, у самих строк.
    ///
    /// ПОЧЕМУ ПУТЬ ГАСИТСЯ ЗДЕСЬ, А НЕ ЗАВОДСКИМ ЗНАЧЕНИЕМ РУЧКИ. Ручки эти
    /// теперь общие (LivingRole), и заводское у них ОДНО на всех — «да», как
    /// у выживальщика: без выхода наверх ему не выбраться из собственного
    /// карьера. Стражнику нужно противоположное, и одно общее умолчание обоим
    /// не годится. Единственное честное место для своего умолчания — здесь:
    /// конструктор отрабатывает ДО пресета, и слово человека остаётся старше
    /// нашего (это сторожит <c>RoleDebtTests.Умолчание_роли_не_стирает_настройку_пресета</c>).
    /// </summary>
    public GuardRole()
    {
        БезДела = IdleAction.Домой;
        ПорогБезделья = 30;
        СпатьНочью = false;
        Мстить = RevengePolicy.Никогда;

        // ПРОБИВАТЬСЯ НАВЕРХ — НЕТ: стражник стоит у ЧУЖОЙ постройки (ворота,
        // стена), и ступени в этой стене означают дыру в ней. Включают там, где
        // стражник стоит на своём же дворе и запертым остаться не должен; что
        // при этом можно ломать, решает не эта ручка, а застава (BreakGuard) и
        // «ЛоматьЧужоеРадиВыхода»
        ВыбиратьсяНаверх = false;
        // ДОБЫВАТЬ МАТЕРИАЛ НА СТОЛБ — НЕТ, по той же причине: копать пол под
        // воротами стражнику незачем
        ДобыватьМатериалНаСтолб = false;
        // МОСТИТЬ РАЗРЫВЫ — НЕТ: мост через ров перед воротами это дыра в
        // обороне, которую стражник сам себе и построил
        МоститьРазрывы = false;
        // СПУСКАТЬСЯ С ОБРЫВОВ — НЕТ: спрыгнувший с надвратной площадки обратно
        // на неё уже не поднимется (выход наверх у него тоже выключен), и пост
        // остаётся пустым
        СпускатьсяСОбрывов = false;
    }

    public override void Configure(VsBot bot)
    {
        // --- Готовое поведение: выжить и вести себя как игрок ---
        // ОТСЮДА БЕРЁТСЯ «КУШАТЬ СО СКЛАДА»: рефлекс еды сам ходит в кладовые
        // (BehaviorForageWhenNoFood, FromStores), а где кладовые — говорит ручка
        // «Склад» на вкладке «Настройка роли», рядом с «Домом» и «Постом»
        // (с 29.08 она есть у всякой живущей роли, а не у одного копателя).
        // Своего кода для этого у стражника нет и заводить его было бы второй
        // копией механики
        var выживание = bot.Survive();
        bot.CommonCommands();

        // Круг самообороны — ручка роли «ВступатьВБойСРасстояния» (в пресете
        // стражника она узкая: из-за поста он не уходит).
        //
        // А ВОТ КРУГ СБОРА ЕДЫ ЗДЕСЬ И ПРАВДА БЫЛ ПРИБИТ ЧИСЛОМ — «Foraging.Radius = 12»
        // стояло ровно под словами «жёсткого числа здесь больше нет», и слова
        // были неправдой (приёмка 27.08, находка 9). Теперь это общая ручка
        // «РадиусСбораЕды» из LivingRole, и двенадцать стоят в guard.json.

        // ПОСТА НЕ ЛОМАЕМ, НО СТРОК ОБ ЭТОМ ЗДЕСЬ БОЛЬШЕ НЕТ. Стояло пять
        // присваиваний в bot.Movement и bot.Scaffolding — ровно те же, что у
        // выживальщика и у продавца, слово в слово. Теперь ручки общие
        // (LivingRole), и доносит их одна общая проводка; своё «нет» стражник
        // ставит умолчанием в конструкторе, рядом с причиной.

        // --- ГОТОВОЕ: СТОЯТЬ НА ПОСТУ И ВОЗВРАЩАТЬСЯ НА НЕГО ---
        //
        // СПОСОБНОСТЬ БЕРЁТСЯ ИЗ ОБЩЕГО НАБОРА, А НЕ СОБИРАЕТСЯ ЗДЕСЬ. Собирал
        // её раньше сам стражник — и получалось, что правило лежит в
        // библиотеке, а дотянуться до него может он один. Теперь она есть у
        // всякой роли (Presets.Survive) и молчит, пока точка не задана.
        //
        // ИМЯ РУЧКИ В ОТКАЗЕ ДОПИСЫВАЕТ РОЛЬ. Способность знает ВИД беды, но не
        // знает, как ручка зовётся у того, кто ею пользуется: поводок у
        // стражника — «ВозвращатьсяНаПостНеДальше», у продавца — «ПоводокОтПоста».
        // Пока имена стояли в библиотеке, отказ называл чужую ручку
        пост = выживание.Post;
        пост.OnRefused += (вид, почему) => bot.Log($"[пост] {почему}. " + вид switch
        {
            PostRefusal.НетПоста => "Ручка роли «Пост» (вкладка «Настройка роли»)",
            PostRefusal.Унесло => "Ручка роли «ВозвращатьсяНаПостНеДальше»",
            _ => "Ручки роли «Пост» и «ЗаходовНаПост»",
        });

        // --- Своё дело роли: не пускать по списку ---
        стража = new BehaviorGuardGate(bot.Context, выживание.Combat);
        стража.OnLog += m => bot.Log(m);
        // ГОЛОСОМ ВЕЖЛИВОСТИ, а не отчётом о работе: у этой речи есть СВОЯ
        // ручка («ПредупреждатьВЧат»), и вторая, гасящая то же самое
        // (радиотишина), была бы второй копией одного выключателя — см.
        // док-строку ручки
        стража.OnSay += текст => _ = bot.SayAsync(текст, reason: SayReason.Вежливость);
        bot.Behaviors.Add(стража);

        bot.Commands.Add("стража", "кого я не пускаю и где мой пост", async a =>
        {
            var ники = GuardRules.Ники(ЧужиеНики);
            await a.ReplyAsync(ники.Count == 0
                ? $"{ГдеПостСловами()}. Список запрещённых пуст — не пускать некого"
                : $"{ГдеПостСловами()}. Не пускаю: {string.Join(", ", ники)}" +
                  (Бить ? ". Бить велено" : ". Бить не велено"));
        });

        // «ВСТАНЬ СЮДА» С МЕСТА, ГДЕ БОТ СТОИТ — той же дорогой, что «!дом тут»
        // и «!склад тут» у копателя: слово меняет САМУ РУЧКУ роли, доносит её
        // живьём и тут же пишет в файл готового бота. Иначе «где мой пост»
        // живёт в двух местах (в чате одно, в окне другое) и они разъезжаются
        // молча — ровно на этом заказчик однажды потерял склад.
        bot.Commands.Add("пост", "пост [тут] — где я стою и куда возвращаюсь", async a =>
        {
            if (a.Text.Trim() is "тут" or "здесь")
            {
                await a.ReplyAsync(ВстатьЗдесь(bot));
                return;
            }
            // ГДЕ Я ОТНОСИТЕЛЬНО ПОСТА — СПРАШИВАЕМ У САМИХ НОГ, а не считаем
            // тут заново: второе такое же вычитание разъехалось бы с первым, и
            // бот говорил бы в чат одно, а возвращался по другому
            string сколько = пост?.Отступ is { } д ? $", сейчас я в {д:0.#} бл от него" : "";
            await a.ReplyAsync(ГдеПостСловами() + сколько +
                (Пост == null && Дом != null
                    ? ". Своя точка «Пост» пуста — стою по общей точке «Дом», как раньше"
                    : ""));
        });

        ОбщиеНастройкиГотовы(bot);
    }

    /// <summary>
    /// Донести настройки стражника: общие делает база, здесь только своё.
    /// ЗДЕСЬ, А НЕ В <c>Configure</c>: окно крутит ручки уже в мире, а Configure
    /// отработал до входа — список ников, вписанный вечером, обязан доехать
    /// сейчас же, а не после перезапуска.
    /// </summary>
    protected override void ДонестиОбщее()
    {
        base.ДонестиОбщее();
        ОтнестиПост();
        if (стража is not { } с)
            return;
        с.Чужие = ЧужиеНики ?? "";
        с.Хозяин = Хозяин ?? "";
        с.Радиус = Math.Max(1, ОхранятьВРадиусе);
        с.Предупреждать = ПредупреждатьВЧат;
        с.Предупреждение = ЧтоСказатьЧужому ?? "";
        с.ЗватьХозяина = ЗватьХозяина;
        с.Зов = ЧемЗватьХозяина ?? "";
        // Отрицательного срока не бывает: минус опиской означал бы «говорить
        // каждый тик», то есть залитый чат
        с.Повтор = TimeSpan.FromSeconds(Math.Max(0, ПовторятьНеЧащеСекунд));
        с.Бить = Бить;
        с.Подходить = ПодходитьЧтобыУдарить;
        с.СекундНаПодход = Math.Max(1, СекундНаПодход);
    }

    /// <summary>
    /// ГДЕ СТОЯТЬ — ОДИН ОТВЕТ НА ВСЕХ, КТО СПРАШИВАЕТ. Чистое правило, потому
    /// что вопрос «что старше, „Пост“ или „Дом“» человек читает не из кода, а
    /// из поведения бота, и разъехаться ответам тут негде: их разъезд означал
    /// бы бота, который зону считает вокруг одной точки, а стоит у другой.
    ///
    /// «Пост» СТАРШЕ. «Дом» остаётся запасным ровно затем, чтобы пустой «Пост»
    /// вёл себя КАК РАНЬШЕ: до 23.08 постом была именно общая точка «Дом», и
    /// молча отнять её у тех, кто уже настроил стражника, нельзя.
    /// </summary>
    public static GamePos? ГдеСтоять(GamePos? пост, GamePos? дом) => пост ?? дом;

    /// <summary>
    /// ДОНЕСТИ ТОЧКУ ПОСТА ДО ОБЕИХ СПОСОБНОСТЕЙ — ЗОНЫ И НОГ. Перевод игровых
    /// координат в мировые делается ОДНИМ правилом
    /// (<c>GameCoords.WorldCell</c> → <see cref="WorldOrigin"/>) и ТОЛЬКО после
    /// входа в мир: сдвиг приходит пакетом спавна, а до него перевод дал бы
    /// точку в полумиллионе блоков отсюда. Образец — <c>LivingRole.ОтнестиДомБоту</c>.
    ///
    /// УДЕРЖАНИЕ ПИТАЕТСЯ ТОЛЬКО СВОЕЙ ТОЧКОЙ, а зона — ещё и «Домом». Разница
    /// нарочная: «Пост» пуст — стражник ведёт себя как до 23.08 (зона вокруг
    /// дома, возврат через «БезДела: Домой»), и второго механизма возврата к
    /// той же точке мы не заводим.
    /// </summary>
    private void ОтнестиПост()
    {
        if (Бот is not { } bot)
            return;

        // ЧИСЛА, КОТОРЫМ ПЕРЕВОД НЕ НУЖЕН, ДОНОСЯТСЯ ВСЕГДА. Стояли они ниже,
        // за двумя заставами («точка пуста» и «мы ещё не в мире»), — и до входа
        // в мир, а также при пустом «Посте» не доезжали вовсе. Живьём это
        // значит: человек крутит «ЗаходовНаПост» в окне, задаёт точку, и упорство
        // у бота остаётся заводское, потому что оно так и не доехало
        if (пост is { } ноги)
        {
            // НОЛЬ И МИНУС В ОКНЕ — ЭТО ОПИСКА, А НЕ НАСТРОЙКА. Радиус в ноль
            // даёт бота, дёргающегося на месте всю смену: тело стоит не в углу
            // клетки, а где придётся внутри неё
            ноги.Radius = Math.Max(0.5, ОтходитьОтПостаНеДальше);
            ноги.Leash = Math.Max(1, ВозвращатьсяНаПостНеДальше);
            ноги.Tries = Math.Max(1, ЗаходовНаПост);
            ноги.SecondsPerStep = Math.Max(1, СекундНаЗаходКПосту);
            ноги.Rest = TimeSpan.FromSeconds(Math.Max(0, ПередышкаМеждуЗаходамиСекунд));
            // СРОК ВТОРОЙ ПОПЫТКИ — ТОТ ЖЕ, ЧТО У ВСЕЙ ПРОЧЕЙ БЕЗНАДЁГИ
            // (общая ручка «НеБратьсяЗаБезнадёжноеМинут»): второго срока
            // «когда пробовать снова» в проекте заводить нельзя
            ноги.Гиблое.TryAgainAfter =
                TimeSpan.FromMinutes(Math.Max(1, НеБратьсяЗаБезнадёжноеМинут));
        }

        var где = ГдеСтоять(Пост, Дом);
        if (где is not { } точка)
        {
            if (стража is { } з)
                з.Пост = null;
            if (пост is { } н)
                н.Post = null;
            return;
        }

        if (!bot.CoordsKnown())
        {
            // Одна жалоба, а не одна на каждый поворот любой ручки. Молчать
            // нельзя: «задал пост, и ничего не произошло» со стороны неотличимо
            // от «настройка не работает»
            if (!жаловалсяНаПост)
            {
                жаловалсяНаПост = true;
                bot.Log($"[пост] {точка} запомнил, но перевести в мировые координаты пока " +
                        "нечем — точка спавна приходит только после входа в мир; донесу, как войду");
            }
            return;
        }
        жаловалсяНаПост = false;

        var клетка = bot.WorldCell(точка);
        if (стража is { } зона)
            зона.Пост = клетка;
        if (пост is { } удержание)
        {
            // ТОЧКУ УДЕРЖАНИЯ ДАЁТ ТОЛЬКО СВОЯ РУЧКА. «Дом» сюда не попадает
            // нарочно: к нему уже ходит безделье («БезДела: Домой»), и второй
            // возврат к той же точке гонял бы бота вдвое чаще, чем нужно
            удержание.Post = Пост is { } своя ? bot.WorldCell(своя) : null;
        }

        // ДВА ВОЗВРАТА, ТЯНУЩИЕ В РАЗНЫЕ СТОРОНЫ — САМОЕ ВРЕМЯ СКАЗАТЬ ОБ ЭТОМ.
        // Заполнены обе точки, они РАЗНЫЕ, и безделье велено уводить домой:
        // удержание тянет на пост, безделье — домой, и бот ходит между ними всю
        // смену. За человека мы его ручки не переписываем (окно и пресет старше
        // нашего слова), но и молчать про такое нельзя — со стороны это ровно
        // «бот сошёл с ума»
        // МЕРИМ РАДИУСОМ ПОСТА, А НЕ «НЕ РАВНО». Дом в одном блоке от поста
        // никакой ходьбы не даёт: удержание считает бота стоящим на посту в
        // пределах своего радиуса, и жалоба там была бы шумом на пустом месте —
        // а шум в отказах ровно тем и опасен, что за ним не видно настоящей беды
        if (Пост is { } п && Дом is { } д && БезДела == IdleAction.Домой
            && PostRules.Отступ(bot.WorldCell(д).X + 0.5, bot.WorldCell(д).Y,
                                bot.WorldCell(д).Z + 0.5, bot.WorldCell(п))
               > Math.Max(0.5, ОтходитьОтПостаНеДальше))
            СказатьЕслиНовое("пост",
                $"пост {п} и дом {д} — РАЗНЫЕ места, а «БезДела» стоит «Домой»: я буду " +
                "ходить между ними. Оставьте одно из двух — либо «БезДела: Стоять» " +
                "(тогда держит пост), либо очистите ручку «Пост» (тогда постом снова " +
                "станет «Дом»)");
    }

    /// <summary>Уже пожаловались, что координаты поста перевести нечем.</summary>
    private bool жаловалсяНаПост;

    /// <summary>
    /// ЗАПОМНИТЬ ПОСТ ТАМ, ГДЕ БОТ СТОИТ — для команды «!пост тут». Возвращает
    /// ответ человеку словами; молчания тут быть не должно.
    ///
    /// «ЗАПОМНИЛ» ЗНАЧИТ И НА СЛЕДУЮЩИЙ ЗАПУСК ТОЖЕ: точка ложится в ручку
    /// роли, доносится живьём и тем же записывающим уходит в файл готового
    /// бота, каким пишет окно управления. Половина жалобы «запоминание не
    /// работает у дома и склада» была ровно про пропущенную запись в файл.
    ///
    /// ПЕРЕВОДИМ ТОЛЬКО ПОСЛЕ ВХОДА В МИР. Без сдвига «где я» вернуло бы
    /// мировые числа (512061…), и человек получил бы пост за полмиллиона
    /// блоков от себя — молча.
    /// </summary>
    private string ВстатьЗдесь(VsBot bot)
    {
        if (!bot.CoordsKnown())
            return "не знаю начала отсчёта мира — точка спавна приходит только после входа " +
                   "в мир. Скажите «!пост тут» ещё раз, когда я войду";
        if (bot.GamePosHere() is not { } здесь)
            return "не знаю, где я — пост запомнить не от чего";
        Пост = здесь;
        // ЧЕРЕЗ ТУ ЖЕ ДВЕРЬ, ЧТО И ОКНО, — иначе пост, заданный словом, при
        // смене роли остался бы на НОВОМ боте чужой точкой, а заданный в
        // окне — не остался. Близнеца «!дом тут» через эту дверь уже провели,
        // а «!пост тут» шёл мимо: тот же промах, только у той самой роли,
        // ради которой заказ и делался
        Донести();
        return $"Запомнил пост: {здесь}, отходить не дальше {ОтходитьОтПостаНеДальше:0.#} бл. " +
               bot.ЗапомнитьРоль();
    }

    /// <summary>
    /// ГДЕ МОЙ ПОСТ — ОДНОЙ СТРОКОЙ, для чата и для стенда. Вынесено из тела
    /// команды нарочно: ответ уходит в игровой чат, и содержимого его не видит
    /// никто, включая приёмку, — тест на команду проходил бы и там, где строка
    /// врёт (тот же довод, что у <c>Presets.StabilityReport</c>).
    /// </summary>
    public string ГдеПостСловами()
    {
        var где = ГдеСтоять(Пост, Дом);
        if (где is not { } точка)
            return "ПОСТА НЕТ: пусты и своя ручка «Пост», и общая «Дом». Встаньте, где надо, " +
                   "и скажите «!пост тут»";
        string чья = Пост != null ? "пост" : "пост по общей точке «Дом»";
        return $"{чья} {точка}, зона {ОхранятьВРадиусе:0} бл, " +
               (Пост != null
                   ? $"отходить не дальше {ОтходитьОтПостаНеДальше:0.#} бл"
                   : "удержание точки выключено — заполните ручку «Пост»");
    }

