log.Write(бегун.Catalog is { } виды
    ? $"[задачи] очередь: {очередь.Jobs.Count} шт, файл {хранилищеЗадач.Path}; " +
      $"виды работ роли: {виды.Names()}"
    : $"[задачи] очередь: {очередь.Jobs.Count} шт, файл {хранилищеЗадач.Path}; " +
      $"у роли «{выбранная.Name}» конструктора работ нет — ставить в очередь нечего");

