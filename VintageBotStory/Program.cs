// Страница в браузере вместо настольного окна: бот безголовый, его место —
// фон или сервер без графики, где настольное окно не запустится вовсе.
// Панель ничего не делает сама — зовёт те же команды, навыки и умения,
// что и чат, поэтому второго мозга у бота не заводится.
ControlPanel? панель = null;
if (cfg.Panel.Use)
{
    панель = new ControlPanel(bot, cfg.Panel.Port)
    {
        Roles = каталог,
        Presets = пресеты,
        Config = cfg,
        Account = account,
        // Умения для окна берём У РОЛИ, если она их уже собрала: иначе окно
        // заводит СВОЙ набор и не видит того, что добавила роль (например
        // shop_status и shop_round у нейросетевого продавца). Два независимых
        // списка умений — это два разных мозга у одного бота
        Tools = (выбранная as LlmRole)?.Tools ?? BotToolbox.Standard(bot),
        // ПАРОЛЬ АДМИНИСТРАТОРА СПРАШИВАЕТ САМА ПАНЕЛЬ (ControlPanel.Start →
        // PanelPasswordSource). Отсюда ей нужен только способ спросить его без
        // эха: «panel.askPassword: true» — это запуск руками из терминала.
        // В режиме MCP сюда не доходят вовсе (выход выше), а служба без консоли
        // получит честный отказ вместо тихо открытого по ключу окна
        AskSecret = ReadSecret,
        // Без этих двух вкладка «Задачи» честно скажет, что очередь к окну
        // не подключена, и не будет делать ничего
        Jobs = бегун,
        JobsStore = хранилищеЗадач,
        // Серверный режим достаёт и до окна: журнал в нём короче, а подписи к
        // настройкам (2,6 МБ файла документации) не читаются вовсе. Окно про
        // выключенные подписи ГОВОРИТ — молчаливо голый список ручек мы уже
        // получали в жалобу «нефига не понятно, что делают некоторые»
        Explanations = cfg.ServerMode.EffectiveDecorations
    };
    if (cfg.ServerMode.EffectivePanelLogLines > 0)
        панель.LogLines = cfg.ServerMode.EffectivePanelLogLines;
    панель.OnLog += m => log.Write($"[панель] {m}");

    // УМЕНИЯ ОКНА — У НОВОЙ РОЛИ, А НЕ У ПРЕЖНЕЙ. Набор снят один раз, при
    // сборке окна; после смены роли он указывал бы на умения ушедшего бота
    // (у продавца на нейросети это shop_status и shop_round), и окно водило бы
    // бота чужими руками
    bot.OnRoleChanged += (_, стала) =>
    {
        // Окно могло и не открыться (занятый порт) — тогда «панель» тут уже
        // null, и перецеплять умения некому
        if (панель is { } окно)
            окно.Tools = (стала as LlmRole)?.Tools ?? BotToolbox.Standard(bot);
    };

    // ---------------- СМЕНА РОЛИ БЕЗ ПЕРЕЗАПУСКА ----------------
    //
    // СЛОВА ЗАКАЗЧИКА 23.08: «хочется смену настроек и роли без перезапуска».
    // До сегодня «выбрать готового бота» в окне не делало НИЧЕГО: выбор ложился
    // в bot.json, окно просило перезапустить бота руками, а руки запускают
    // start-bot-panel.bat со своим «--preset digger» — и поднимался прежний бот.
    // Со стороны это ровно «настройки не запоминаются».
    //
    // ПОЧЕМУ ЭТО ЗДЕСЬ, А НЕ В ОКНЕ. Собрать роль из готового бота умеет
    // библиотека пресетов, а держат её запуск и окно ПОРОЗНЬ (у окна могут быть
    // своя папка и свои настройки). Роль же на боте одна. Сменить её должен
    // тот, кто держит бота, — иначе заведётся вторая сборка роли, и они
    // разойдутся в первый же вечер.
    //
    // ГОВОРИМ ЧЕРЕЗ bot.Log, А НЕ log.Write, И ЭТО ВАЖНО: окно показывает поток
    // слов бота (ControlPanel подписан на VsBot.OnLog), а прямая запись в файл
    // до окна не доходит. Смена роли обязана быть видна ТАМ, где её затеяли.
    // ОТВЕЧАЕМ ОКНУ ИТОГОМ, А НЕ МОЛЧАНИЕМ. Пока событие было Action, окно
    // узнавало о смене одним способом — перечитывало bot.Role — и потому не
    // могло отличить «сменилась целиком» от «сменилась, но прежняя вернулась не
    // вся». Отсюда и брались два противоположных ответа на одно нажатие: окно
    // писало «перезапуск не нужен», журнал — «бот сейчас полубот».
    // null значит «роль не менял», и окно говорит об этом человеку.
    панель.OnRestartRequested += id =>
    {
        if (пресеты.Find(id) is not { } готовый)
        {
            bot.Log($"[роль] готового бота «{id}» нет — роль не менял, остаюсь {bot.Role?.Name}");
            return null;
        }

        var (новая, беды) = пресеты.Build(готовый, каталог);
        foreach (string беда in беды)
            bot.Log($"[пресет] {беда}");
        if (новая == null)
        {
            // Молча подставить другую роль значит всю ночь гонять не того бота
            bot.Log($"[роль] «{id}» не собрался — остаюсь {bot.Role?.Name}");
            return null;
        }

        // Нейросеть думает вслух — у новой роли тоже. Без этой строки
        // сменённый на думающего бот молчал бы о том, чем занят
        if (новая is LlmRole ии2)
            ии2.OnThought += m => bot.Log($"[ии] {m}");

        // ОЧЕРЕДЬ НА ВЕЧЕР ОСТАНАВЛИВАЕМ ДО СМЕНЫ И НАЗЫВАЕМ ЗАДАЧУ.
        //
        // Бот сам этого сделать не может: очередь живёт СНАРУЖИ него (её держат
        // запуск и окно), и о смене роли она узнала бы только тем, что следующий
        // навык вдруг перестал существовать. Молча брошенный на полпути карьер —
        // это «бот вдруг встал», а виды работ новой роли к прежней задаче
        // отношения не имеют вовсе
        if (бегун.Current is { } задача)
        {
            bot.Log($"[роль] смена роли останавливает задачу очереди: " +
                    $"«{задача.Title}» (навык «{задача.Skill}») — она остаётся в очереди");
            бегун.Stop();
        }

        var итог = bot.СменитьРоль(новая);
        foreach (string строка in итог.Словами())
            bot.Log($"[роль] {строка}");

        // ВЫБОР ПЕРЕЖИВАЕТ ПЕРЕЗАПУСК. В bot.json его уже записало окно
        // (ControlPanel.ApplyPreset), а ручки новой роли лежат в её пресете —
        // но отладка и слово при входе читаются ТОЛЬКО при запуске, и об этом
        // надо сказать поимённо, а не общим «перезапустите»
        foreach (string что in СменаРоли.ЧегоСменаНеДелает(
                     готовый.Diag && !cfg.Diag, готовый.Script, bot.Joined,
                     BotConfig.ПочемуНеЗапомнится(BotConfig.ИмяПресет, cfg.ИзСтрокиЗапуска)))
            bot.Log($"[роль] после смены остаётся при запуске: {что}");

        return итог;
    };
    try
    {
        string адрес = панель.Start();
        // В режиме MCP в консоль писать НЕЛЬЗЯ: там протокол. Адрес всё
        // равно есть в журнале
        if (!mcpMode)
        {
            // ЧЕМ ЗАПЕРТО ОКНО — В КОНСОЛЬ ПЕРВОЙ СТРОКОЙ. «Окно управления:
            // такой-то адрес» без этого слова человек читает как «оно
            // защищено», а чем именно — не знает: с паролем в адресе ключа нет
            // вовсе, без пароля адрес и ЕСТЬ доступ к боту
            Console.WriteLine($"Окно управления: {панель.DoorNote}");
            Console.WriteLine($">>> ОКНО УПРАВЛЕНИЯ: {адрес}");
            if (cfg.Panel.OpenBrowser)
                панель.OpenInBrowser();
        }
    }
    catch (Exception e)
    {
        // Без панели бот всё равно работает — но молчать о том, что окно
        // не открылось, нельзя: человек будет ждать его напрасно
        log.Write($"[панель] не открылась: {e.Message}");
        if (!mcpMode)
            Console.WriteLine($"Окно управления не открылось: {e.Message}");
        панель = null;
    }
}

// Запись прогона: «--record» пишет всё, что шло по сети, в файл рядом с ботом.
// Пригодится, чтобы разовую находку на живом сервере превратить в тест
PacketLog? record = null;
if (args.Contains("--record"))
{
    string path = Path.Combine(BotFolders.State(), "records",
        $"{bot.Name}-{DateTime.Now:yyyyMMdd-HHmmss}.rec");
    record = PacketLog.RecordTo(path).Attach(bot.Client);
    bot.Log($"[запись] пишу прогон в {path}");
}

if (cfg.Script is { Length: > 0 } script)
    DiagnosticCommands.RunScriptOnJoin(bot, string.Join(";", script));

bot.OnJoined += () => Console.WriteLine(">>> БОТ В ИГРЕ <<<");

// Что напечатано в консоли — бот скажет в игровом чате ("quit" — выход)
_ = Task.Run(() =>
{
    string? input;
    while ((input = Console.ReadLine()) != null)
    {
        input = input.Trim().Trim('﻿');
        if (input == "quit") { bot.Dispose(); break; }
        if (input.Length > 0 && bot.Joined) _ = bot.SayAsync(input);
    }
});

// ---------------- работа ----------------
//
// «Запустить бота» и «войти на сервер» — РАЗНЫЕ вещи. Пока окно управления
// открыто, программа живёт и ждёт: адрес, пароль сервера и то, под кем
// входить — ником или аккаунтом, — выбираются в окне. Вышли с сервера —
// ждём снова, а не завершаемся.
bool ждёмОкно = панель != null && cfg.Panel.WaitForStart;
var войти = new TaskCompletionSource();
if (панель != null)
    панель.OnConnectRequested += () => войти.TrySetResult();

while (true)
{
    if (ждёмОкно)
    {
        log.Write("жду команды «Вход» из окна управления");
        if (!mcpMode)
            Console.WriteLine("Бот запущен и ждёт. Войдите на сервер в окне управления.");
        await войти.Task;
        войти = new TaskCompletionSource();
    }

    try
    {
        await bot.RunAsync();
    }
    catch (IOException e)
    {
        Console.WriteLine($"Соединение разорвано: {e.Message}");
        log.Write($"соединение разорвано: {e.Message}");
    }

    // Без окна возвращаться некуда — раньше здесь программа и заканчивалась
    if (панель == null)
        break;
    ждёмОкно = true;
    log.Write("с сервера вышел; жду новой команды из окна управления");
}

log.Flush();
