if (args is [.., "--recsummary", var recPath] || (args.Contains("--recsummary") && args.Length >= 2))
{
    string path = args[Array.IndexOf(args, "--recsummary") + 1];
    var packets = PacketLog.Read(path);
    long bytes = packets.Sum(p => (long)p.Body.Length);
    Console.WriteLine($"Записей {packets.Count}, тел на {bytes / 1024 / 1024} МБ");
    // Сортируем по ОБЪЁМУ, а не по числу: раздувают запись обычно не частые
    // мелкие пакеты, а редкие огромные (реестр игры — один пакет на 30 МБ)
    var bySize = packets.GroupBy(p => (p.PacketId, p.Incoming))
        .Select(g => (g.Key.PacketId, g.Key.Incoming, Count: g.Count(),
                      Bytes: g.Sum(p => (long)p.Body.Length)))
        .OrderByDescending(t => t.Bytes)
        .Take(12);
    foreach (var (id, incoming, count, size) in bySize)
        Console.WriteLine($"  {(incoming ? "<<" : ">>")} id {id,3}: {count,7} шт, {size / 1024,8} КБ");
    return;
}

