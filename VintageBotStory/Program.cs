Task<string?> AskPasswordAsync() => Task.FromResult(
    Environment.GetEnvironmentVariable(cfg.Account.PasswordEnv) is { Length: > 0 } fromEnv
        ? fromEnv
        : mcpMode
            ? null
            : ReadSecret($"Пароль аккаунта {cfg.Account.Email} (не отображается): "));

Task<string?> AskCodeAsync(string why) => Task.FromResult(
    Environment.GetEnvironmentVariable(cfg.Account.CodeEnv) is { Length: > 0 } fromEnv
        ? fromEnv
        : mcpMode
            ? null
            : ReadSecret($"{why}. Введите код: "));

// Ввод без эха: пароль не должен остаться на экране и в истории терминала
static string? ReadSecret(string prompt)
{
    Console.Write(prompt);
    var typed = new System.Text.StringBuilder();
    try
    {
        while (true)
        {
            var key = Console.ReadKey(intercept: true);
            if (key.Key == ConsoleKey.Enter)
                break;
            if (key.Key == ConsoleKey.Escape)
            {
                Console.WriteLine();
                return null;
            }
            if (key.Key == ConsoleKey.Backspace)
            {
                if (typed.Length > 0)
                    typed.Length--;
                continue;
            }
            if (!char.IsControl(key.KeyChar))
                typed.Append(key.KeyChar);
        }
    }
    catch (InvalidOperationException)
    {
        // Консоли нет (служба, перенаправленный ввод) — читаем обычной строкой
        Console.WriteLine();
        return Console.ReadLine();
    }
    Console.WriteLine();
    return typed.ToString();
}

