using VsBotKit;
using VsBotKit.Panel;   // метка [KnobPlace] — где настройке стоять в окне управления

namespace VintageBotStory;

/// <summary>
/// РОЛЬ ПОД ВНЕШНИМ УПРАВЛЕНИЕМ (MCP): бот живой и сам за собой следит, но
/// своих дел не имеет — что делать, решает внешний клиент (Claude Code,
/// редактор, свой скрипт) через инструменты.
///
/// Именно это нужно для проверки модов: рефлексы держат бота в живых (он не
/// висит в воздухе, отбивается, ест и лечится), а разработчик мода водит его
/// руками из своего редактора и смотрит, что на самом деле произошло в мире.
///
/// ВАЖНОЕ И НЕОЧЕВИДНОЕ. Сама роль СЕРВЕР НЕ ПОДНИМАЕТ: обмен с клиентом идёт
/// по stdin/stdout процесса, а их занимает запуск бота. Сервер поднимается
/// только при ключе <c>--mcp</c>. Выбрать эту роль в окне управления и ждать
/// клиента — значит ждать напрасно, поэтому роль говорит об этом вслух, а не
/// стоит молча живым чучелом.
/// </summary>
public class McpRole : LivingRole
{
    public override string Name => "MCP";

    private VsBot? бот;

    /// <summary>Сказал ли запуск, что клиент действительно подключён.</summary>
    private bool клиентЗаявлен;

    // «ЗДОРОВАТЬСЯ» ПРИ ВХОДЕ теперь общая (LivingRole): смысл был один и тот
    // же, что у Выживальщика, а объявлений — два. Умолчание «нет» осталось
    // нашим и переехало в конструктор (в проверках мода лишний шум мешает).
    //
    // ДВА ОТЛИЧИЯ, О КОТОРЫХ ЧЕСТНЕЕ СКАЗАТЬ ВСЛУХ. Место в окне было «люди, 0»;
    // ноль в метке означает «порядка не задано» (см. KnobHelp.PlaceOf), и ручка
    // на деле уезжала в хвост раздела, за «КомандыИзЧата». Теперь у неё общее
    // место «люди, 1» — то есть первой в разделе. А «показать сразу» держится
    // не меткой, а списком ГлавныеНастройки ниже: метка общая на все роли, и
    // Main = true в ней сдвинул бы раскладку Выживальщику.

    /// <summary>
    /// ЧТО ПОКАЗАТЬ В ОКНЕ СРАЗУ. Список короткий нарочно: у этой роли своих
    /// ручек всего две, и обе — про то, чтобы бот не мешал наблюдению за модом.
    ///
    /// Свойство ТОЛЬКО НА ЧТЕНИЕ: записываемое стало бы ручкой (RoleKnobs берёт
    /// свойства, которые можно записать), и список главных настроек сам оказался
    /// бы настройкой.
    /// </summary>
    public IReadOnlyList<string> ГлавныеНастройки =>
        [nameof(Здороваться), nameof(РадиусСбораЕды)];

    // РУЧКИ «РадиусЗаЕдой» ЗДЕСЬ БОЛЬШЕ НЕТ — ЭТО БЫЛО ТРЕТЬЕ ИМЯ ОДНОЙ ВЕЩИ.
    //
    // Она крутила ровно то же, что «РадиусСбораЕды» у копателя и что жёсткие
    // числа 12 и 24 в коде стражника и продавца: BehaviorForageWhenNoFood.Radius.
    // Приёмка 27.08 назвала это одной механикой в ЧЕТЫРЁХ местах, и добавила
    // главное: этой ручки не было НИ В ОДНОМ пресете (роль mcp — способ
    // запуска, в каталоге ролей её нет), то есть по закону 1 для заказчика её
    // не существовало вовсе. Теперь ручка одна, общая, в LivingRole; прежнее
    // имя понимается по [KnobWasNamed], а своё умолчание роль ставит ниже.

    /// <summary>
    /// СВОИ УМОЛЧАНИЯ РОЛЬ СТАВИТ ЗДЕСЬ, А НЕ В <c>Configure</c>, И ЭТО НЕ ВКУС.
    ///
    /// Порядок запуска такой: роль СОБИРАЕТСЯ (сюда), потом пресет крутит её
    /// ручки (RoleKnobs.ApplyAll), и только потом зовётся <c>Configure</c>. Стой
    /// эти две строки в Configure — они молча перетирали бы написанное человеком
    /// в файле пресета: панель показывала бы одно, файл говорил другое, а в
    /// журнале про расхождение не было бы ни строки.
    ///
    /// ПОЧЕМУ ИМЕННО ЭТИ ТРИ. Проверка мода — это ОПЫТ, и лишнее в нём мешает:
    /// бот, помахавший прохожему, поздоровавшийся в чат или взявший к ночи
    /// факел, портит наблюдение. Но это умолчание, а не запрет: тот, кто
    /// проверяет мод на свет или на приветствия, вправе включить их обратно, и
    /// его слово старше нашего.
    ///
    /// «Здороваться = false» стоит теперь ЗДЕСЬ, а не начальным значением
    /// свойства: свойство стало общим (LivingRole), и там умолчание «да» —
    /// такое же, каким оно было у Выживальщика. Разные умолчания у разных
    /// ролей — это нормально; ненормально было объявлять одну ручку дважды.
    /// </summary>
    public McpRole()
    {
        МахатьИгрокам = false;
        ФонарьВРуке = false;
        Здороваться = false;
        // Своё умолчание круга сбора: клиент оставил бота у своего блока и
        // ждёт его там, а не в тридцати клетках у малинника. Совсем запретить
        // нельзя — голодный бот умрёт посреди проверки, и виноват будет мод
        РадиусСбораЕды = 16;
    }

    public override void Configure(VsBot bot)
    {
        бот = bot;
        bot.Survive();
        bot.CommonCommands();

        // Никуда не уходим сами: клиент ждёт бота там, где его оставил
        ОтнестиРадиусБоту();

        bot.Log(ПодВнешнимКлиентом()
            ? "[mcp] внешний клиент есть: бот живёт рефлексами и ждёт его команд"
            : "[mcp] ВНЕШНЕГО КЛИЕНТА НЕТ: роль выбрана без ключа --mcp, сервер не поднят. " +
              "Бот будет просто жить и слушать команды чата. " +
              "Чтобы им управлял редактор, запустите бота с ключом --mcp " +
              "(и укажите в настройках клиента СОБРАННЫЙ VintageBotStory.exe, а не «dotnet run»)");

        bot.Commands.Add("mcp", "кто сейчас управляет ботом", a => a.ReplyAsync(Состояние()));

        // ГДЕ ЗАДАЮТСЯ ДАННЫЕ ОТ ИИ — вопрос, с которым заказчик пришёл к этой
        // роли тоже: она называется «под внешним управлением», и человек ищет
        // здесь поле для ключа. Ключа тут нет и не будет — за думанье платит
        // тот, кто подключился. Сказать это один раз дешевле, чем объяснять
        // потом, почему настройки поставщика не показываются
        bot.Log("[mcp] ключ нейросети этой роли не нужен: думает и платит внешний клиент. " +
                "Поставщик, модель и потолок трат задаются у роли «Под управлением нейросети» " +
                $"(список поставщиков — команда «{bot.Commands.Prefix}ии поставщики»)");

        // Умолчания «не махать» и «без фонаря» стоят в конструкторе НАРОЧНО:
        // здесь они перетёрли бы пресет человека (см. McpRole())
        ОбщиеНастройкиГотовы(bot);
    }

    public override Task OnJoinedAsync(VsBot bot)
    {
        // Про отсутствие клиента говорим и после входа: первую строку журнала
        // при живом сервере не видно вовсе — там stdout занят протоколом
        if (!ПодВнешнимКлиентом())
            bot.Log("[mcp] напоминаю: внешнего клиента нет, команд ждать неоткуда");

        // Приветствие говорит база по общей ручке «Здороваться»; фраза наша
        return base.OnJoinedAsync(bot);
    }

    /// <summary>
    /// ЧТО ГОВОРИТ БОТ ПОД ВНЕШНИМ УПРАВЛЕНИЕМ. Коротко и с пометкой «(MCP)»:
    /// эта строка нужна не гостям лавки, а тому, кто смотрит на чат сервера и
    /// проверяет, что нужный бот вошёл именно тем, кем его запускали.
    /// </summary>
    protected override string? ФразаПриВходе(VsBot bot) => $"{bot.Name}: на связи (MCP)";

    protected override void ДонестиОбщее()
    {
        base.ДонестиОбщее();
        ОтнестиРадиусБоту();
    }

    /// <summary>
    /// Запуск сообщает роли, что сервер поднят и клиент на связи.
    ///
    /// Метод, а не свойство, нарочно: «кто нами управляет» — это факт о том,
    /// как запустили процесс, а не настройка, которую крутят в окне. Свойством
    /// он попал бы в список ручек роли, и человек мог бы «включить» клиента,
    /// которого нет.
    /// </summary>
    public void ВнешнийКлиентПодключён() => клиентЗаявлен = true;

    /// <summary>
    /// Управляет ли ботом внешний клиент.
    ///
    /// Два источника, и оба говорят только «да»: явное заявление от запуска —
    /// точный ответ; ключ командной строки — запасной, чтобы роль не врала,
    /// если проводку в запуск забыли вписать. Соврать в другую сторону они не
    /// могут: ложного «да» ни один из них не даёт.
    /// </summary>
    private bool ПодВнешнимКлиентом() =>
        клиентЗаявлен || Environment.GetCommandLineArgs().Contains("--mcp");

    private string Состояние() =>
        ПодВнешнимКлиентом()
            ? "Мной управляет внешний клиент по MCP. Сам я ничего не затеваю, " +
              "только держусь в живых."
            : "Внешнего клиента нет: бот запущен без ключа --mcp, сервер не поднят. " +
              "Я просто живу и слушаю команды чата.";

    /// <summary>
    /// Донести радиус до механизма сбора еды. Зовётся и из ручки, и из сборки:
    /// повёрнутая в окне ручка обязана подействовать сразу, а не после
    /// перезапуска — иначе «задал и ничего не произошло» неотличимо от
    /// «настройка не работает».
    /// </summary>
    private void ОтнестиРадиусБоту()
    {
        if (бот?.Behaviors.Get<BehaviorForageWhenNoFood>() is { } сборЕды)
            сборЕды.Radius = Math.Max(1, РадиусСбораЕды);
    }
}
