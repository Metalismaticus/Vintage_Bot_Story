using VsBotKit;
using VsBotKit.Panel;   // метка [KnobPlace] — где настройке стоять в окне управления

namespace VintageBotStory;

/// <summary>
/// Роль-образец: бот-продавец.
///
/// Смотрите, из чего она состоит: пресет выживания одной строкой, обычные
/// команды чата одной строкой, и дальше — только ПОЛИТИКА: насколько бот смел,
/// что для него магазин, когда торговать. Механизмы (ходить, драться, лечиться,
/// прятаться от бури, ломать блоки) лежат в библиотеке и переписывать их
/// в каждой роли не нужно.
/// </summary>
public class HelperRole : LivingRole
{
    public override string Name => "Продавец";

    /// <summary>
    /// Сколько ХП УРОНА бот согласен принять за одно спрыгивание с высоты.
    /// Ноль — не спрыгивать вовсе, только шаг и лестницы.
    ///
    /// ПОЧЕМУ НЕ «СМЕЛОСТЬ». Ручка звалась так, и ровно так же звалась ручка
    /// Выживальщика — но там это НОМЕР СТУПЕНИ (0 трус, 1 обычный, 2 смелый),
    /// а здесь хиты. Совпадало ВСЁ: имя, раздел, место в окне и признак
    /// «главная», — не совпадали единицы. Одно слово на два счёта означало, что
    /// строчку «Смелость: 2», переложенную человеком из одного пресета в
    /// другой, не отличить ни глазом, ни разбором: целое 2 ложится в дробную
    /// ручку БЕЗ ЖАЛОБЫ (<c>JsonElement.GetDouble()</c> берёт целое молча), и
    /// шумела как раз безопасная половина (GetInt32 на «2.0» бросает
    /// FormatException), а молчала опасная. Проверено прогоном, а не додумано.
    /// Развели ИМЕНА — и это единственное, что тут вправду лечит; сторожит
    /// разведённые имена RoleDebtTests.
    ///
    /// СТАРОЕ ИМЯ ПРИ ЭТОМ ПОНИМАЕТСЯ, И ОБ ЭТОМ ГОВОРЯТ ВСЛУХ. Прежде здесь
    /// стоял отказ («у роли „Продавец“ нет настройки „Смелость“») с
    /// обоснованием «ни в одном готовом пресете этого ключа не было — терять
    /// нечего». Обоснование проверялось ТОЛЬКО по presets/*.json и было
    /// неправдой: пресеты пишет не одна поставка. Панель на КАЖДЫЙ поворот
    /// ручки снимает пресет с живой роли (ControlPanel.SetKnob → SaveKnobs →
    /// <see cref="PresetLibrary.Capture"/>), а Capture кладёт в файл ВСЕ ручки
    /// по их тогдашним именам. Значит у любого хозяина Продавца, хоть раз
    /// двинувшего ползунок, в папке состояния лежит свой «trader.json» (или
    /// «последний.json») со строкой «Смелость», и своё там СТАРШЕ приехавшего
    /// с программой (<see cref="PresetLibrary.Directory"/>). Отказ терял именно
    /// это число: хозяин, поставивший 0 («не спрыгивать вовсе»), после
    /// обновления получал жалобу и заводские 2.0 хп — то есть бота, который
    /// снова спрыгивает с высоты и бьётся.
    ///
    /// СВОЁ СТАРОЕ ЧИСЛО ЗНАЧИТ ТО ЖЕ САМОЕ. У Продавца «Смелость» и раньше
    /// была в хитах — док-строка прежней сборки слово в слово: «насколько бот
    /// смел с прыжками с высоты (хп урона за прыжок)». Так что метка ниже не
    /// подменяет смысл, а возвращает потерянное; разными единицы были У ДВУХ
    /// РОЛЕЙ, а не у этой ручки во времени.
    ///
    /// И ЧУЖОЕ ЧИСЛО НЕ ЛОЖИТСЯ МОЛЧА — двумя разными способами. Во-первых,
    /// пресет НАЗЫВАЕТ СВОЮ РОЛЬ, и <see cref="PresetLibrary.Build"/> крутит
    /// его ручки у той роли, которую он назвал (единственный, кто зовёт
    /// ApplyAll, — это он): пресет выживальщика поднимает выживальщика, а не
    /// Продавца. Во-вторых, если человек всё же переложит строку руками, старое
    /// имя уйдёт ОТДЕЛЬНЫМ списком «переименовано», а не в жалобы, и в журнале
    /// встанет причина из <see cref="KnobWasNamedAttribute.Why"/> — про ступени
    /// и про хиты в одной строке. Молчания, ради избавления от которого имена и
    /// разводили, не остаётся ни на одном пути.
    /// </summary>
    [KnobPlace("безопасность", Order = 1, Main = true)]
    [KnobWasNamed("Смелость", Why = "у Выживальщика так звалась СТУПЕНЬ осторожности " +
        "(0 трус, 1 обычный, 2 смелый), а у Продавца это ХИТЫ УРОНА за одно спрыгивание; " +
        "если число приехало из пресета другой роли — проверьте его")]
    public double ЗдоровьяНаСпрыгивание { get; set; } = 2.0;

    /// <summary>Проводить сделки (false — только осматривать и докладывать).</summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание,
        Order = 1, Main = true)]
    public bool Торговать { get; set; } = true;

    // ================= СВОЯ ТОРГОВЛЯ ПРОДАВЦА =================
    //
    // ЖИВЫЕ СЛОВА ЗАКАЗЧИКА, ради которых этот раздел появился: «у продавца
    // тоже будут свои [настройки], а сейчас как-то все не так». И он был прав:
    // из ста четырёх настроек Продавца СВОИХ у него было ДВЕ («Торговать» и
    // цена спрыгивания), остальные сто две — общие для всех ролей. Выбрать
    // Продавца и не увидеть в окне ни одной торговой ручки — это и значит «как
    // выбор роли на что-то влияет».
    //
    // А ЧИСЛА ПРИ ЭТОМ БЫЛИ, все до одного: радиус магазина, радиус прилавка,
    // образец на прилавке, место поста, поводок, срок обхода, рейсы за сделку,
    // слоты под перевозку, срок проверки кассы, код монеты. Они лежали ВНУТРИ
    // механизмов (TraderShop, BehaviorShopkeeper) заводскими значениями, и
    // повернуть их было нечем — ни из окна, ни пресетом. Это прямое нарушение
    // правила проекта «числа и пороги — ручки роли»: механизм считает, роль
    // решает. Здесь они и становятся решением роли.

    /// <summary>
    /// ЗАВОДСКИЕ ЧИСЛА ТОРГОВЛИ СПРАШИВАЕМ У САМИХ МЕХАНИЗМОВ, а не переписываем
    /// в роль числами. Перепиши мы их — у каждого порога стало бы ДВА места, и
    /// правка в механизме молча разошлась бы с тем, что окно называет
    /// «заводским»: человек нажал бы «Вернуть как было» и получил не то, с чем
    /// механизм родился.
    ///
    /// Пустышки живые и настоящие, но НИКУДА не подключены: ни бота, ни лавки
    /// им не дают, ни одного метода у них не зовут — из них только читают
    /// начальные значения свойств. Заводится по одной на процесс.
    /// </summary>
    private static readonly TraderShop ЗаводскаяЛавка = new(null!, null!);

    /// <summary>Та же пустышка для способности продавца — см. выше.</summary>
    private static readonly BehaviorShopkeeper ЗаводскийПрилавок = new(null!, null!);

    /// <summary>Имя раздела окна: торговые ручки Продавца.</summary>
    public const string Торговля = "торговля";

    /// <summary>Как раздел зовётся человеку.</summary>
    public const string ТорговляЗаголовок = "Торговля";

    /// <summary>Одной строкой: что лежит в разделе.</summary>
    public const string ТорговляОписание =
        "лавка, прилавки, касса и пост: где границы магазина, чем платят, " +
        "сколько товара оставлять образцом и как далеко бот отходит от прилавка";

    /// <summary>
    /// ЧЕМ ПЛАТЯТ В ЭТОЙ ЛАВКЕ — код предмета-монеты («gear-rusty»).
    ///
    /// Это НЕ подпись валюты, а именно код вещи: бот считает монеты в кассе,
    /// берёт их из обменного сундука и кладёт сдачу — по этому коду. Сервера с
    /// модовой валютой (свои монеты, самородки, слитки) без этой ручки были
    /// боту недоступны вовсе: код был зашит в механизм.
    /// </summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание, Order = 2)]
    public string КодМонеты { get; set; } = ЗаводскаяЛавка.CurrencyCode;

    /// <summary>
    /// РАДИУС МАГАЗИНА от таблички «!STORE», блоков: докуда бот считает
    /// прилавки своими. Больше — захватит соседние постройки, меньше — не
    /// увидит дальний угол своей же лавки.
    /// </summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание, Order = 3)]
    public double РадиусМагазина { get; set; } = ЗаводскаяЛавка.StoreRadius;

    /// <summary>
    /// НАСКОЛЬКО БЛИЗКО К ТАБЛИЧКЕ ИЩЕТСЯ ЕЁ СУНДУК, блоков. Табличку и сундук
    /// прилавка связывает только расстояние; поставьте их дальше — и прилавок
    /// станет табличкой без товара.
    /// </summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание, Order = 4)]
    public double РадиусПрилавка { get; set; } = ЗаводскаяЛавка.StallRadius;

    /// <summary>
    /// СКОЛЬКО ЕДИНИЦ ТОВАРА ВСЕГДА ОСТАЁТСЯ В СУНДУКЕ КАК ОБРАЗЕЦ. По нему
    /// бот узнаёт прилавок, даже когда товар кончился. Ноль — прилавок с
    /// распроданным товаром бот перестанет узнавать вовсе.
    /// </summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание, Order = 5)]
    public int ОбразцовНаПрилавке { get; set; } = ЗаводскаяЛавка.SampleUnits;

    /// <summary>
    /// ГДЕ ИСКАТЬ МЕСТО ДЛЯ ПОСТА, блоков от таблички «!STORE». Пост — клетка
    /// внутри магазина, на которой бот стоит между обходами.
    /// </summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание, Order = 6)]
    public int ИскатьПостВРадиусе { get; set; } = ЗаводскаяЛавка.PostSearchRadius;

    /// <summary>
    /// НА СКОЛЬКО БЛОКОВ НИЖЕ ТАБЛИЧКИ «!STORE» ИСКАТЬ ПОЛ. Таблички вешают
    /// высоко, и меньшего не хватает: бот не находит, куда встать.
    /// </summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание, Order = 7)]
    public int ПостНижеТабличкиДо { get; set; } = ЗаводскаяЛавка.PostDrop;

    /// <summary>
    /// СКОЛЬКО РЕЙСОВ МАКСИМУМ ЗА ОДНУ СДЕЛКУ. Крупная покупка не влезает в
    /// сумки разом, и бот носит её частями; предел нужен, чтобы одна сделка не
    /// съела весь вечер.
    /// </summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание, Order = 8)]
    public int РейсовЗаСделку { get; set; } = ЗаводскаяЛавка.MaxTrips;

    /// <summary>
    /// СКОЛЬКО СЛОТОВ ХОТБАРА ЗАНИМАТЬ ПОД ПЕРЕВОЗКУ. Десять — весь хотбар
    /// (одиннадцатый занят умением, двенадцатый — левой рукой). Меньше — бот
    /// оставит себе место под инструмент, но за один рейс унесёт меньше.
    /// </summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание, Order = 9)]
    public int СлотовПодПеревозку { get; set; } = ЗаводскаяЛавка.CargoSlots;

    /// <summary>
    /// КАК ЧАСТО ЗАГЛЯДЫВАТЬ В КАССУ, секунд. Поход к сундуку стоит времени, а
    /// касса меняется только когда кто-то купил.
    /// </summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание, Order = 10)]
    public double ЗаглядыватьВКассуРазВСекунд { get; set; } =
        ЗаводскаяЛавка.CashCheckInterval.TotalSeconds;

    /// <summary>Как часто обходить прилавки, секунд.</summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание, Order = 11)]
    public double ОбходПрилавковРазВСекунд { get; set; } =
        ЗаводскийПрилавок.Interval.TotalSeconds;

    /// <summary>
    /// РАДИУС ПОСТА, блоков: насколько бот вправе отойти от своей клетки между
    /// обходами. Это не поводок, а «переминаться на месте».
    /// </summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание, Order = 12)]
    public double РадиусПоста { get; set; } = ЗаводскийПрилавок.PostRadius;

    /// <summary>
    /// ПОВОДОК: дальше этого от поста считаем, что бота унесло, и возвращаемся.
    /// За товаром на склад он при этом ходит — поводок про «унесло», а не про
    /// работу.
    /// </summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание, Order = 13)]
    public double ПоводокОтПоста { get; set; } = ЗаводскийПрилавок.LeashRadius;

    /// <summary>Как часто пробовать вернуться на пост, если не дошёл, секунд.</summary>
    [KnobPlace(Торговля, Title = ТорговляЗаголовок, About = ТорговляОписание, Order = 14)]
    public double ПробоватьНаПостРазВСекунд { get; set; } =
        ЗаводскийПрилавок.PostRetry.TotalSeconds;

    /// <summary>
    /// СВОИ УМОЛЧАНИЯ РОЛЬ СТАВИТ ЗДЕСЬ, А НЕ В <c>Configure</c>, И ЭТО НЕ ВКУС.
    ///
    /// Порядок запуска такой: роль СОБИРАЕТСЯ (сюда), потом пресет крутит её
    /// ручки (<see cref="RolePreset"/> → RoleKnobs.ApplyAll), и только потом
    /// зовётся <c>Configure</c>. Стой эта строка в Configure — она молча
    /// перетирала бы написанное человеком: пресет с «ФонарьВРуке»: true давал бы
    /// бота с выключенным фонарём, панель показывала бы «выкл», в файле пресета
    /// стояло бы «вкл», и в журнале про расхождение — ни строки. Ровно то
    /// двойное управление, ради избавления от которого заводился RoleKnobs.
    ///
    /// ФОНАРЬ ПРОДАВЦУ НИ К ЧЕМУ: лавка освещена, а за левую руку игра берёт 20%
    /// скорости голода — платить за это, стоя за прилавком, незачем. Это именно
    /// УМОЛЧАНИЕ, а не запрет: захочет хозяин ночной лавки — включит, и его
    /// слово будет старше нашего.
    ///
    /// ЗДЕСЬ ЖЕ ГАСЯТСЯ ЧЕТЫРЕ ПРИЁМА ПУТИ, и по той же причине, что фонарь:
    /// ручки эти теперь общие (LivingRole), заводское у них ОДНО на всех —
    /// «да», как у выживальщика, которому без выхода наверх не выбраться из
    /// собственного карьера. Продавцу нужно противоположное, а второго
    /// заводского значения у одной ручки не бывает — значит своё умолчание
    /// роль ставит там, где её собирают.
    /// </summary>
    public HelperRole()
    {
        ФонарьВРуке = false;

        // ПРОБИВАТЬСЯ НАВЕРХ — НЕТ: продавец стоит ВНУТРИ чужой постройки, и
        // любая работа этой механики означает дыру в товарном складе. Включают
        // там, где лавка своя и запертым остаться нельзя; что при этом можно
        // ломать, решает застава (BreakGuard) и «ЛоматьЧужоеРадиВыхода»
        ВыбиратьсяНаверх = false;
        // ДОБЫВАТЬ МАТЕРИАЛ НА СТОЛБ — НЕТ: копать пол лавки продавцу незачем
        ДобыватьМатериалНаСтолб = false;
        // МОСТИТЬ РАЗРЫВЫ — НЕТ: мост из четырёх блоков посреди лавки это чужая
        // постройка, испорченная нашими руками. Прыгать продавец при этом не
        // разучился: прыжок стоит ноль блоков и решается смелостью, а не этой
        // ручкой
        МоститьРазрывы = false;
        // СПУСКАТЬСЯ С ОБРЫВОВ — НЕТ, по той же причине: ступени и лестницы
        // вниз по чужой стене — та же порча чужого двора
        СпускатьсяСОбрывов = false;
    }

    public override void Configure(VsBot bot)
    {
        бот = bot;
        // --- Готовое поведение: выжить и вести себя как игрок ---
        var выживание = bot.Survive();
        bot.CommonCommands();

        // --- Условия применения: чем эта роль отличается от любой другой ---
        bot.Movement.MaxFallDamage = ЗдоровьяНаСпрыгивание;   // цена прыжка вниз, хп
        // Круг самообороны продавца — ручка роли «ВступатьВБойСРасстояния»
        // (в пресете торговца узкая: за мобами он не гоняется).
        //
        // Круг сбора еды был прибит здесь числом 24 — теперь это общая ручка
        // «РадиусСбораЕды» из LivingRole, и двадцать четыре стоят в trader.json:
        // за ягодами далеко от лавки продавец не уходит, но решает это хозяин.

        // ПРОДАВЕЦ НЕ ЛОМАЕТ ЛАВКУ, НО СТРОК ОБ ЭТОМ ЗДЕСЬ БОЛЬШЕ НЕТ. Стояло
        // пять присваиваний в bot.Movement и bot.Scaffolding — те же самые, что
        // у выживальщика и у стражника. Ручки стали общими (LivingRole), их
        // доносит одна общая проводка, а своё «нет» продавец ставит умолчанием
        // в конструкторе, рядом с причиной.

        // --- Дело роли: магазин ---
        var магазин = new TraderShop(bot.Context, bot.Read);
        магазин.OnLog += m => bot.Log($"[торговля] {m}");
        // ОТВЕТ ПОКУПАТЕЛЮ (положил монеты — ждёт слова), а не рассказ о своих
        // делах: радиотишина такое не глушит, см. LivingRole.ПисатьВЧатОСвоихДелах
        магазин.OnAnnounce += text => bot.SayAsync(text, reason: SayReason.Ответ);

        продавец = new BehaviorShopkeeper(bot.Context, магазин) { ExecuteDeals = Торговать };
        продавец.OnLog += m => bot.Log($"[продавец] {m}");
        bot.Behaviors.Add(продавец);

        // --- Навык: то же дело, но по команде ---
        bot.Skills.Register(new DelegateSkill("обход", "обойти прилавки прямо сейчас",
            async (_, _, ct) =>
            {
                await магазин.SurveyAsync(ct);
                return SkillResult.Ok($"прилавков {магазин.Stalls().Count}");
            }));

        bot.Commands.Add("магазин", "что я знаю о лавке", async a =>
        {
            var прилавки = магазин.Stalls();
            await a.ReplyAsync(прилавки.Count == 0
                ? "Прилавков не вижу"
                : "Прилавки: " + string.Join("; ", прилавки.Select(s => s.ToString())));
        });

        // Общие ручки — из базовой роли. Раньше их не было вовсе: продавец к
        // ночи брал факел в левую руку и махал покупателям, а выключить это
        // из окна управления было нечем
        ОбщиеНастройкиГотовы(bot);
    }

    /// <summary>
    /// Донести настройки Продавца: общие делает база, здесь только своё.
    ///
    /// ЗДЕСЬ, А НЕ В <c>Configure</c>, И ЭТО НЕ ВКУС: окно крутит ручки уже в
    /// мире, а Configure отработал до входа. Пока торговые числа стояли только
    /// в механизмах, повёрнутое в окне не доезжало никуда — ровно та беда, из-за
    /// которой заказчик вечер искал свой склад.
    /// </summary>
    protected override void ДонестиОбщее()
    {
        base.ДонестиОбщее();
        if (продавец is { } лавочник)
        {
            лавочник.ExecuteDeals = Торговать;
            лавочник.Interval = ВСекундах(ОбходПрилавковРазВСекунд);
            лавочник.PostRadius = РадиусПоста;
            лавочник.LeashRadius = ПоводокОтПоста;
            лавочник.PostRetry = ВСекундах(ПробоватьНаПостРазВСекунд);
        }
        // ЛАВКУ СПРАШИВАЕМ У ПРОДАВЦА, А НЕ ДЕРЖИМ ВТОРУЮ ССЫЛКУ. Своё поле
        // тут было, и оно указывало на тот же самый объект: два имени одной
        // вещи — это две головы, которые однажды кивнут врозь (в мире лавка у
        // способности одна, а роль правила бы свою). Дверь наружу у способности
        // уже есть и заведена ровно за этим (BehaviorShopkeeper.Shop)
        if (продавец?.Shop is { } магазин)
        {
            магазин.CurrencyCode = КодМонеты;
            магазин.StoreRadius = РадиусМагазина;
            магазин.StallRadius = РадиусПрилавка;
            магазин.SampleUnits = ОбразцовНаПрилавке;
            магазин.PostSearchRadius = ИскатьПостВРадиусе;
            магазин.PostDrop = ПостНижеТабличкиДо;
            магазин.MaxTrips = РейсовЗаСделку;
            магазин.CargoSlots = СлотовПодПеревозку;
            магазин.CashCheckInterval = ВСекундах(ЗаглядыватьВКассуРазВСекунд);
        }
        if (бот is { } bot)
            bot.Movement.MaxFallDamage = ЗдоровьяНаСпрыгивание;
    }

    /// <summary>
    /// Секунды из окна — в срок механизма. ОТРИЦАТЕЛЬНОГО СРОКА НЕ БЫВАЕТ:
    /// человек вписывает минус опиской, а механизм с отрицательным сроком
    /// делает своё дело КАЖДЫЙ тик — то есть бот вместо торговли ходит к кассе
    /// без остановки. Ноль оставляем как есть: это законное «каждый раз».
    /// </summary>
    private static TimeSpan ВСекундах(double секунд) =>
        TimeSpan.FromSeconds(Math.Max(0, секунд));

    private VsBot? бот;
    private BehaviorShopkeeper? продавец;

    /// <summary>
    /// ЧТО ГОВОРИТ ПРОДАВЕЦ, ВОЙДЯ В МИР. Раньше он говорил это БЕЗУСЛОВНО, и
    /// выключить приветствие из окна управления было нечем: ручка «Здороваться»
