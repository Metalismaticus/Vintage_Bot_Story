    /// как и было), а «что сказать» осталось делом роли.
    /// </summary>
    protected override string? ФразаПриВходе(VsBot bot) =>
        $"{Name} на связи! {bot.Commands.Prefix}{bot.Commands.HelpCommand} — что я умею";
