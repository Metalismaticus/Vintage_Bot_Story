    /// <summary>Короткие ответы — командами: их ждут сразу, а не через полчаса.</summary>
    private void Команды(VsBot bot)
    {
        // «ИДИ КО МНЕ» СО СТОЛБОМ. Команда общая (Presets.CommonCommands), но
        // решение «достраивать ли столб, когда дороги наверх нет» принадлежит
        // роли — потому здесь и перекрываем. Переехало от «Жителя» вместе с
        // ним самим: без этой замены выживальщик, позванный на второй этаж,
        // честно топтался бы внизу
        bot.Commands.Add("комне", "подойти к позвавшему (наверх — со столбом)", async a =>
        {
            if (a.SenderEntity is not { } caller)
            {
                await a.ReplyAsync("Не вижу тебя — подойди поближе");
                return;
            }
            bool ok = await bot.Movement.ApproachAsync(
                () => bot.Entities.Get(caller.Id) is { } t ? (t.X, t.Y, t.Z) : null,
                stopDistance: 1.5, maxSeconds: 90, ct: a.Token);

            if (!ok && СтолбитьсяКГостю && bot.Self.Position is { } me &&
                bot.Entities.Get(caller.Id) is { } up && up.Y > me.Y + 2)
            {
                await a.ReplyAsync($"Дороги наверх нет — забираюсь ({up.Y - me.Y:0} бл вверх)");
                var поднялся = await bot.Climbing.ClimbToAsync(
                    new BlockPos((int)Math.Floor(up.X), (int)Math.Round(up.Y), (int)Math.Floor(up.Z)),
                    120, a.Token);
                ok = поднялся.Success;
                if (!ok)
                    await a.ReplyAsync(поднялся.ToString());
            }

            if (bot.Entities.Get(caller.Id) is { } теперь)
                await bot.Movement.FaceAsync(теперь.X, теперь.Z);
            await a.ReplyAsync(ok ? $"Я тут! ({bot.PlayerCoordsHere()})"
                                  : $"Не смог дойти, стою на ({bot.PlayerCoordsHere()})");
        });

        // ПАМЯТЬ ПРЕРВАННОГО ВИДНА ЧЕЛОВЕКУ. Иначе «бот бросил карьер» и «бот
        // ждёт, пока освободится тело, чтобы его доделать» выглядят одинаково
        bot.Commands.Add("возврат", "что прервали и вернусь ли доделывать", a =>
        {
            var ждёт = bot.Resume.Waiting;
            var журнал = bot.Resume.Journal;
            return a.ReplyAsync(
                (ждёт.Count > 0 ? "Жду тела, чтобы доделать: " + string.Join("; ", ждёт)
                                : "Недоделанного за мной нет") +
                (журнал.Count > 0 ? ". Последнее: " + журнал[^1] : "") +
                (bot.Tunnel.Unfinished is { } лесенка
                    ? $". Ещё не доведена лесенка: {лесенка}" : ""));
        });

        bot.Commands.Add("добудь",
            "добудь <что> <сколько> [, <что> <сколько> …] — уйти и принести; " +
            "вещей можно назвать несколько через запятую", async a =>
        {
            // РАЗБОР — ТО ЖЕ ЧИСТОЕ ПРАВИЛО, что у навыка и у окна управления.
            // Свой разбор здесь означал бы, что «!добудь медь 20, олово 8» из
            // чата и та же строка из окна значат разное
            var (строки, беда) = OrderLines.Parse(a.Text);
            if (строки.Count == 0)
            {
                await a.ReplyAsync($"{беда} Например: !добудь медь 20 или " +
                                   "!добудь медь 20, олово 8");
                return;
            }
            await a.ReplyAsync($"Пошёл за {OrderLines.Join(строки)}. «!стоп» — прервать");

            // Через навык, а не напрямую: так дело видно в панели и его можно
            // прервать. Иначе «стоп» бота не остановит
            var итог = await bot.Skills.RunAsync("наряд", OrderLines.Join(строки), a.Token);
            await a.ReplyAsync(итог.Message ?? (итог.Success ? "Принёс" : "Не вышло"));
        });

        bot.Commands.Add("копай", "копай [сторона] [глубина] — карьер здесь", async a =>
        {
            await a.ReplyAsync($"Копаю карьер ({a.Words.ElementAtOrDefault(0) ?? РазмерКарьера.ToString()})");
            var итог = await bot.Skills.RunAsync("карьер", a.Text, a.Token);
            await a.ReplyAsync(итог.Message ?? "Готово");
        });

        bot.Commands.Add("разведай", "разведай [что] — уйти под землю и поискать", async a =>
        {
            await a.ReplyAsync($"Ухожу в разведку ({(a.Text.Length > 0 ? a.Text : "любая руда")})");
            var итог = await bot.Skills.RunAsync("разведка", a.Text, a.Token);
            await a.ReplyAsync(итог.Message ?? "Готово");
        });

        // КАК БОТ СОБИРАЕТСЯ ЭТО ДОБЫТЬ — СПРОСИТЬ, НЕ ЗАПУСКАЯ.
        //
        // Ради проверки того самого случая, из-за которого запасы и переписаны:
        // «Axe: 0/1 (не хватает 1)» на каждый наряд. Чтобы человек не гадал, что
        // бот думает, он спрашивает вслух и читает ответ целиком:
        //   «топор: добыть stone-granite ×2; вытесать axehead-granite ×1;
        //    добыть stick ×1; сделать axe-granite ×1»
        // или честный отказ с недостающим. Ходить при этом бот никуда не идёт —
        // это справка, а не работа
        bot.Commands.Add("какдобыть", "какдобыть <что> — чем бот закроет нехватку " +
                                      "(рецепт, тёска, что собрать) без похода", async a =>
        {
            string что = a.Text.Trim();
            if (что.Length == 0)
            {
                await a.ReplyAsync("Нужно: !какдобыть <что>. Понимаю и русское слово " +
                                   "(«топор»), и код предмета («axe-flint»)");
                return;
            }
            // Человеческое слово переводим тем же переводчиком, что и требования:
            // второго словаря «топор → Axe» у бота быть не должно
            string цель = bot.Stock.ToolKind(что) ?? что;
            var разбор = bot.Stock.PlanFor(цель, 1);
            // НЕ СОШЛОСЬ — ОТВЕЧАЕТ ТОТ, КТО ЗНАЕТ РЕЕСТР. Сам разбор знает
            // только КОДЫ, и на «!какдобыть bow-crude» живой бот 27.08 сказал
            // «негде взять bow-crude» — свалив на пустой мир то, что запрещено
            // чертой класса. Второго объяснения одного отказа мы не заводим:
            // это те же слова, которыми отказывает снаряжение
            await a.ReplyAsync($"{цель}: " +
                (разбор.Possible ? разбор.ToString() : bot.Stock.Refusal(цель, разбор)));
        });

        // А ТЕПЕРЬ ПРОЙТИ ЭТОТ РАЗБОР ЦЕЛИКОМ.
        //
        // ЗАЧЕМ ДВЕРЬ. «!какдобыть» показывал цепочку и НИЧЕГО не делал, а
        // сделать её было нечем: «!добудь» ходит только в мир (поручения),
        // «!сделать» собирает только из того, что уже в сумке. Цепочку целиком —
        // «добыть кремень, вытесать лезвие, добыть палку, собрать нож, срубить
        // бревно, собрать лоток, намыть волокна, скрутить тетиву, собрать лук» —
        // умеет одна мастерская (Stock.MakeAsync), и до 27.08 позвать её мог
        // только сам бот изнутри снаряжения. Проверить живьём длинную цепочку
        // было НЕЧЕМ, и ровно поэтому две волны подряд отчитывались стендом.
        bot.Commands.Add("сделай", "сделай <что> [сколько] — пройти всю цепочку: " +
                                   "добыть, вытесать, намыть, собрать", async a =>
        {
            var слова = a.Words;
            if (слова.Length == 0)
            {
                await a.ReplyAsync("Нужно: !сделай <что> [сколько], например «!сделай pan-wooden»");
                return;
            }
            int сколько = слова.Length > 1 && int.TryParse(slovoЧисло(слова), out int n) && n > 0 ? n : 1;
            string что = слова.Length > 1 && int.TryParse(slovoЧисло(слова), out _)
                ? string.Join(' ', слова[..^1])
                : a.Text.Trim();
            string цель = bot.Stock.ToolKind(что) ?? что;

            await a.ReplyAsync($"Делаю {цель} ×{сколько}. «!стоп» — прервать");
            var (почему, вышло) = await bot.Stock.MakeAsync(цель, сколько, ct: a.Token);
            await a.ReplyAsync(почему is { Length: > 0 }
                ? $"{цель}: вышло {вышло} из {сколько} — {почему}"
                : $"{цель}: сделал {вышло} из {сколько}");

            static string slovoЧисло(string[] w) => w[^1];
        });

        // «!СКЛАД [ТУТ]» ЗДЕСЬ БОЛЬШЕ НЕТ: слово переехало в LivingRole вслед
        // за самой ручкой «Склад» — оно нужно всякой живущей роли, а не одному
        // копателю (каталог ролей обещает его и стражнику)

        bot.Commands.Add("дорога",
            "дорога <x1> <y1> <z1> <x2> <y2> <z2> [ширина] — замостить полосу", async a =>
        {
            await a.ReplyAsync("Мощу дорогу. «!стоп» — прервать");
            var итог = await bot.Skills.RunAsync("дорога", a.Text, a.Token);
            await a.ReplyAsync(итог.Message ?? (итог.Success ? "Замостил" : "Не вышло"));
        });

        bot.Commands.Add("собери", "собери [радиус] [мест] — набрать ягод, грибов и диких овощей",
            async a =>
        {
            await a.ReplyAsync("Иду за дикой едой. «!стоп» — прервать");
            var итог = await bot.Skills.RunAsync("сбор", a.Text, a.Token);
            await a.ReplyAsync(итог.Message ?? (итог.Success ? "Набрал" : "Не вышло"));
        });

        bot.Commands.Add("запасы", "что у меня с киркой, факелами и едой", async a =>
        {
            var нехватка = bot.Stock.Missing();
            // ОТКУДА ВЗЯЛОСЬ САМО ЧИСЛО — вторая правда, и она не та же, что
            // «почему не хватает». Человек, увидевший «arrow: 3/20», спрашивает
            // и то, и другое: «почему только три» отвечает нехватка (её причину
            // помнит безнадёга снабжения), а «почему двадцать» — запас по
            // расходу, и без него двадцатка выглядит взявшейся ниоткуда
            string поРасходу = bot.Upkeep.Pairs.Count == 0
                ? ""
                : " Запас по расходу: " + bot.Upkeep + ".";
            await a.ReplyAsync((нехватка.Count == 0
                ? $"Запасы в порядке: {bot.Stock}"
                : "Не хватает: " + string.Join(", ", нехватка)) + поРасходу);
        });

        // РАЗГРУЗКА БЫЛА ТОЛЬКО НАВЫКОМ — то есть жила во вкладке «Задачи», а
        // в чате её не существовало. Заказчик искал её словами и не нашёл:
        // «не могу найти команду разгрузиться в отмеченный склад, инвентарь у
        // бота полный и он не идет». Навык и команда — один и тот же вызов,
        // поэтому второй механики тут не заводится
        async Task Разгрузиться(ChatCommandArgs a)
        {
            if (!bot.Depot.Known)
            {
                await a.ReplyAsync("Склад не задан: укажите его в окне управления " +
                                   "или встаньте у сундука и скажите «!склад тут»");
                return;
            }
            await a.ReplyAsync("Иду на склад. «!стоп» — прервать");
            var итог = await bot.Skills.RunAsync("разгрузка", "", a.Token);
            await a.ReplyAsync(итог.Message ?? "Готово");
        }

        bot.Commands.Add("разгрузка", "отнести добытое на склад и вернуться", Разгрузиться);
        // ТО ЖЕ ДЕЛО ДРУГИМ СЛОВОМ. Живой случай: заказчик написал
        // «!разгружайся» и получил «Не знаю команду». Человек говорит боту
        // глаголом («разгружайся»), а не существительным («разгрузка»), и
        // спорить с ним об этом — значит требовать от него помнить нашу
        // грамматику. Обработчик тут ОДИН И ТОТ ЖЕ, второй механики не
        // заводится: имена — это вход, а не поведение
        bot.Commands.Add("разгружайся", "то же, что «разгрузка»", Разгрузиться);

        bot.Commands.Add("помню", "помню <что> — где я это видел (медь, олово, камень)", async a =>
        {
            if (bot.Self.Position is not { } p)
            {
                await a.ReplyAsync("Не знаю, где стою, — от чего считать расстояния?");
                return;
            }
            var где = new BlockPos((int)Math.Floor(p.X), (int)Math.Floor(p.Y), (int)Math.Floor(p.Z));
            await a.ReplyAsync(bot.Resources.Tell(a.Text.Trim(), где));
        });

        bot.Commands.Add("владения", "чьё вокруг: заявки сервера и подмеченное самим", async a =>
        {
            if (bot.Self.Position is not { } p)
            {
                await a.ReplyAsync("Не знаю, где стою, — до чужого мерить не от чего");
                return;
            }
            var где = new BlockPos((int)Math.Floor(p.X), (int)Math.Floor(p.Y), (int)Math.Floor(p.Z));
            string заявки = bot.Claims.ClaimsKnown
                ? $"заявок знаю {bot.Claims.Count} (чужих площадок {bot.Claims.ForeignAreaCount})"
                : "заявок сервер не присылал";
            await a.ReplyAsync($"{заявки}; подмечено самим {bot.Claims.SeenCount}; " +
                               bot.Claims.Judge(где).Say());
        });

        bot.Commands.Add("руда", "какая руда видна вокруг", async a =>
        {
            var видно = bot.Ores.Find(32, a.Text.Trim(), limit: 8);
            await a.ReplyAsync(видно.Count == 0
                ? "Руды на виду нет — скажите «!разведай», уйду под землю"
                : "Вижу: " + string.Join("; ", видно.Select(o =>
                    $"{OreCode.WhatItGives(o.Metal)} ({OreCode.RichnessWords(o.Richness)}) " +
                    $"в {a.Here(o.Pos)}, {o.Distance:0} бл")));
        });
    }

    public override Task OnJoinedAsync(VsBot bot)
    {
        // ВСЕ НАСТРОЙКИ ЗАНОВО, а не только склад. Только теперь известна точка
        // спавна, а значит и перевод игровых координат в мировые; до входа он
        // давал бы сдвиг (0, 0) и увёл бы склад за полмиллиона блоков.
        // Остальные пороги переносить не обязательно, но и вреда нет: доносим
        // всё одним местом, чтобы не заводить второе.
        //
        // База подписана на сам вход (OnJoined) и доносит настройки там же, но
        // это ДРУГОЙ миг: событие приходит сразу, а роль зовут через три
        // секунды, когда сервер уже договорил. Донесение идемпотентно, и лишний
        // раз тут дешевле, чем гадать, успела ли прийти точка спавна
        // ЧЕРЕЗ ДВЕРЬ ДОНЕСЕНИЯ, А НЕ ПРЯМО В ТЕЛО: всё, что роль кладёт в поля
        // бота, обязано лечь в её след, иначе при смене роли оно останется на
        // новом боте чужой настройкой, а смена скажет «вернулось всё». Дом и
        // склад до входа в мир в поля бота не пишутся ВООБЩЕ (перевод координат
        // без точки спавна невозможен) — значит без этой двери они не снялись
        // бы никогда
        Донести();

        // Сундуки рядом — ТОЛЬКО если своего склада не задали: иначе бот
        // молча подменит указанную человеком точку первым попавшимся ящиком.
        //
        // ТЕМ ЖЕ САМЫМ МЕХАНИЗМОМ, ЧТО И СЛОВО «!СКЛАД ТУТ», И ЭТО ГЛАВНОЕ
        // ЗДЕСЬ. Прежде тут стоял свой, второй способ взять склад вокруг
        // (Depot.FindChestsNear): он клал под склад ВСЕ найденные сундуки,
        // объявлял их число в журнал — и следом донесение сводило склад к
        // ОДНОЙ точке плюс соседям по радиусу. Живой прогон у дома заказчика:
        //   19:33:29 [склад] под склад взято сундуков: 16 (ближний — (65, 113, 257))
        //   /api/depot сразу после → «точек: 3»
        // Тринадцать сундуков исчезали МОЛЧА. Ровно эту беду однажды уже
        // починили — но только со стороны «!склад тут» (LivingRole
        // .ВзятьСкладЗдесь: считать ПОСЛЕ донесения и вслух назвать, сколько
        // осталось за радиусом соседей). Двух способов взять склад вокруг себя
        // не бывает, поэтому здесь теперь зовётся ТОТ ЖЕ, ЕДИНСТВЕННЫЙ, и
        // человек при входе в мир читает то же честное число, что и в чате.
        //
        // ГОВОРИМ ВСЕГДА, а не только когда что-то взяли: «сундуков в радиусе
        // 12 вокруг не вижу» — это ответ, а молчание неотличимо от поломки.
        //
        // СВОЙ РАДИУС И БЕЗ ЗАПИСИ В ПРЕСЕТ — оба довода у самих этих слов
        // (ручка «СундукиПриВходеВРадиусе» и «запомнить» у ВзятьСкладЗдесь).
        // Механизм при этом ОДИН И ТОТ ЖЕ, что и у слова «!склад тут».
        //
        // Снизу ноль: отрицательный радиус — описка, а ноль законен и значит
        // «при входе не искать вовсе», как и снятая галочка выше
        if (ИскатьСундукиРядом && !bot.Depot.Known)
            bot.Log("[склад] самопоиск при входе в мир: " +
                    ВзятьСкладЗдесь(bot, Math.Max(0, СундукиПриВходеВРадиусе),
                        запомнить: false));

        // Приветствие говорит база: «сказать ли» — общая ручка «Здороваться»,
        // а «что сказать» — наше дело, ФразаПриВходе ниже
        return base.OnJoinedAsync(bot);
    }

    /// <summary>
    /// ЧТО ГОВОРИТ ВЫЖИВАЛЬЩИК, ВОЙДЯ В МИР. Не «привет», а список команд:
    /// человек, поднявший бота впервые, иначе не знает ни одного слова, которое
    /// тот понимает, и ищет их в файлах.
    /// </summary>
    protected override string? ФразаПриВходе(VsBot bot) =>
        $"{Name} на месте. «!добудь медь 20, олово 8», «!копай», «!разведай», " +
        "«!дорога x1 y1 z1 x2 y2 z2 3», «!собери», «!склад тут», «!дом тут», " +
        "«!помню медь», «!запасы»";

