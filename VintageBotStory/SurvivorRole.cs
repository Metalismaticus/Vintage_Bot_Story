    /// </summary>
    protected override void ДонестиОбщее()
    {
        base.ДонестиОбщее();

        if (Бот is not { } bot)
            return;

        bot.Movement.Caution = СмелостьВПути switch
        {
            <= 0 => Caution.Careful,
            1 => Caution.Normal,
            _ => Caution.Bold
