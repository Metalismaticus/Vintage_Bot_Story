using VsBotKit;
using VsBotKit.Panel;   // метка [KnobPlace] — где настройке стоять в окне управления

namespace VintageBotStory;

/// <summary>
/// ВЫЖИВАЛЬЩИК — бот, который просто живёт, а по приказу работает под землёй:
/// карьеры, штольни, руда, дороги.
///
/// ПОЧЕМУ ОН ЖЕ И «ЖИТЕЛЬ». Раньше в каталоге стояли обе роли, и заказчик
/// справедливо спросил, чем они отличаются. Ответ был неприятный: НИЧЕМ, кроме
/// умолчаний. «Житель» — это тот же бот с выключенными работами: своей механики
/// у него не было ни одной, а половину его настроек (дом, фонарь, приветствие,
/// безделье) даёт всем один и тот же пресет выживания. Поэтому житель стал
/// НАСТРОЙКАМИ выживальщика (presets/resident.json), а не отдельной ролью:
/// роль — это код, пресет — это текст, и путать их в одном списке нельзя.
///
/// Роль — ПОЛИТИКА, и только она: размеры карьера, глубина разведки, что
/// держать при себе, где склад, стоит ли мостить дороги. Ни одной механики
/// здесь нет — всё берётся из библиотеки.
///
/// Выживальщик НЕ затевает работу сам. Он ждёт приказа: так его удобнее
/// испытывать, и так он не убегает копать посреди другого дела.
///
/// ПОЧЕМУ ОН ТЕПЕРЬ НАСЛЕДУЕТ <see cref="LivingRole"/>, А НЕ BotRole. Так было
/// не всегда, и причина у прежнего порядка честная: выживальщик появился ПЕРВЫМ
/// и завёл себе все общие ручки сам, а <c>LivingRole</c> родилась позже — из
/// жалобы, что у Продавца и у Жителя тех же ручек нет вовсе. Их тогда
/// СКОПИРОВАЛИ отсюда, оставив выживальщика на старой ветке, — и с того дня
/// каждая новая ручка заводилась ДВАЖДЫ. В прошлую волну так вышло с семью
/// настройками боя; ревизия нашла у двух копий разошедшиеся номера мест.
///
/// Теперь общее живёт в одном месте — в базовой роли, — а здесь остаётся то,
/// чего нет ни у кого другого: карьер, руда, дороги, штольня, склад.
/// Ни одна ручка при этом не пропала и не сменила смысла: имена, умолчания и
/// места в окне у выживальщика те же самые (номера мест общих ручек взяты
/// ИМЕННО ОТСЮДА, см. заголовок LivingRole).
///
/// ПУТЬ И ПРЕПЯТСТВИЯ ОТСЮДА УШЛИ 07.09, и здесь стояло, что они остаются.
/// Причина ухода — та же, по которой ушли бой и приветствие: ходить САМ, без
/// приказа, обязан всякий бот. Стражник идёт к посту, продавец обходит
/// прилавки, ИИ ходит своими умениями — а двадцать три ручки этой ходьбы были
/// заведены у одного выживальщика, и стражник с продавцом успели завести себе
/// ЧЕТЫРЕ ИЗ НИХ ОТДЕЛЬНО: двенадцать объявлений на четыре настройки.
///
/// ИМЯ КЛАССА ТОЖЕ ПОМЕНЯЛОСЬ 07.09: было <c>DiggerRole</c>, и оно врало.
/// Ролей четыре — survivor, guard, trader, ai, — пятой роли «копатель» нет и не
/// было; пресеты digger.json, quarry-only.json и resident.json поднимают ОДНУ
/// эту роль, разными настройками. Прежнее имя сбивало и заказчика, и нас:
/// целый разговор шёл про «ручку у копателя», которой не бывает. Строка
/// <c>"digger"</c> в пресетах при этом НЕ ТРОНУТА и трогать её нельзя — это
/// имя ПРЕСЕТА, а не класса.
/// </summary>
public class SurvivorRole : LivingRole
{
    // Имя обязано совпадать с названием роли в каталоге (Roles.Catalog):
    // окно управления по этому совпадению узнаёт, какой ролью назвать бота,
    // когда снимает с него пресет
    public override string Name => "Выживальщик";

    /// <summary>
    /// ЗАВОДСКИЕ ОТЛИЧИЯ ОТ ОСТАЛЬНЫХ ЖИВУЩИХ РОЛЕЙ — их три, и все здесь.
    ///
    /// ИНСТРУМЕНТЫ. У базовой роли «ДержатьИнструменты» пусто: продавцу за
    /// прилавком кирка ни к чему. Выживальщику наоборот — без лопаты он копает
    /// землю мечом (живой случай: «ломаю soil-low-none: 1,8 с
    /// (blade-blackguard-iron)», лопатой тот же блок берётся за 0,4 с). Пресет
    /// resident.json этой строки не задаёт вовсе и держится на заводском
    /// значении — потеряй мы его при переезде, Житель остался бы без
    /// инструментов молча.
    ///
    /// ЛЕСТНИЦЫ. У базовой роли ноль по той же причине: лавочник за палками не
    /// пойдёт. А выживальщик лезет в ямы весь день, и живой журнал 16.08 дважды
    /// за ночь встал ровно на этом: «наверх на 2 бл: … а есть блоков 0 и
    /// лестниц 0».
    ///
    /// ШЕСТЬДЕСЯТ ЧЕТЫРЕ — ПРЯМОЙ ЗАКАЗ 20.08: «поправь в запасах количество
    /// лестниц — нужно с собой носить 64». До него здесь стояло четыре, и
    /// считались они «под живую яму»: лестницы вешают ЧЕРЕЗ ОДНУ, значит
    /// четыре — восемь блоков подъёма, ровно обе ямы из журнала 16.08 (2 и
    /// 4 бл). Мерка была верной для ТОЙ ночи и слишком короткой для смены в
    /// забое: одна лестница расходуется безвозвратно (снимать за собой их
    /// никто не ходит), и после двух подъёмов запас кончался посреди работы.
    /// Стопка в игре и есть 64 — это «полная стопка лестниц в сумке», а не
    /// придуманное число.
    ///
    /// РЕЙС НА СКЛАД САМОМУ. Третье отличие, и появилось оно 09.09, когда
    /// «РазгружатьсяСам» переехала в <see cref="LivingRole"/>. У общей родни
    /// заводское «нет» — ровно то, что механизм имел без ручки
    /// (<c>BehaviorHaulWhenFull.Enabled</c>; пресет выживания гасит рейс
    /// отдельной строкой, а сама способность говорит о лавочнике: «посреди
    /// торговли уходить к сундукам незачем»). Копателю нужно обратное, и
    /// причина у него своя: он ЛОМАЕТ ПОРОДУ ВЕСЬ ДЕНЬ, сумка набирается за
    /// минуты, а выломанное в полную сумку падает на землю и там остаётся —
    /// это и есть жалоба, ради которой галочку заводили («инвентарь у бота
    /// полный и он не идет»). Второго заводского значения у одной ручки не
    /// бывает, значит своё копатель ставит здесь — до пресета, чтобы слово
    /// человека осталось старше нашего.
    /// </summary>
    public SurvivorRole()
    {
        ДержатьИнструменты = "кирка, лопата, топор, нож";
        ДержатьЛестниц = 64;
        РазгружатьсяСам = true;
        // ЗАПАС ПО РАСХОДУ, ЖИВОЙ ПРИМЕР ЗАКАЗЧИКА 26.08: «чтобы бот сам
        // понимал чего ему не достает и крафтил, например стрелы». Стрелы — не
        // «оружие копателя», а ПЕРВЫЙ потребитель общего правила «чем
        // пользуюсь — то и держу»; строка настраивается, и вписать сюда факелы
        // или бинты человек волен в окне.
        //
        // «к bow» не украшение, а весь смысл: без лука в сумке требование
        // СНИМАЕТСЯ целиком, и копатель, который стрелять не собирается, не
        // потащит с собой ни одной стрелы. Заказчик уже жаловался на метания
        // за припасами — правило нарочно молчит, пока лука нет.
        ЗапасПоРасходу = "arrow к bow";
    }

    // ---------------- где чему стоять в окне управления ----------------

    // РАЗДЕЛ «ПУТЬ» ЖИВЁТ В LivingRole, И ЕГО ИМЯ ТОЖЕ (Путь, ПутьЗаголовок,
    // ПутьОписание — унаследованные константы, потому ниже они пишутся без
    // приставки). Раздел уехал туда вслед за двадцатью тремя своими ручками:
    // ходьба — это то, что делает КАЖДАЯ роль, а заведена она была у одного
    // выживальщика. Здесь остались две ручки раздела, чей механизм роль зовёт
    // своим умением, — столб к позвавшему и разбор под собой.

    // ---------------- настройки ----------------

    /// <summary>
    /// Осторожность в пути ТРЕМЯ СТУПЕНЯМИ: 0 — трус (обходит, не прыгает
    /// вовсе), 1 — обычный, 2 — смелый (срезает через провалы, платит хп).
    /// Это НОМЕР СТУПЕНИ, а не хиты: см. <see cref="Caution"/>.
    ///
    /// ПОЧЕМУ НЕ ПРОСТО «СМЕЛОСТЬ». Ручка звалась так, и ровно так же звалась
    /// ручка Продавца — при том, что там это ХП УРОНА за прыжок
    /// (HelperRole.ЗдоровьяНаСпрыгивание), а не ступень. Совпадали имя, раздел,
    /// место в окне и признак «главная» — не совпадали только единицы, а окно
    /// управления позволяет применить пресет, написанный для одной роли, к
    /// другой. «Смелость: 2» значила у одного «смелый», у другого «два хп», и
    /// проверено прогоном: число 2 из пресета выживальщика ложилось Продавцу
    /// МОЛЧА (2 → 2.0), вчетверо подняв ему цену прыжка против заводских 0.5.
    /// Теперь имена разные и в каждом видны свои единицы, а чужой пресет
    /// получает честный отказ вместо тихой подмены.
    ///
    /// ПОЧЕМУ ОНА НЕ УЕХАЛА В LivingRole ВСЛЕД ЗА ПОЛУТОРА ДЕСЯТКАМИ РОДНИ,
    /// И ЧЕМ Movement.Caution ОТЛИЧАЕТСЯ ОТ Movement.DescendCliffs. Этого
    /// раньше не назвал никто, а разница есть, и она в двух вещах сразу.
    ///
    /// ПЕРВОЕ: DescendCliffs — ОДНО ПОЛЕ, и хозяин у него один. Caution — не
    /// поле, а СЕТТЕР-РАЗВЁРТКА: одной записью он кладёт пять чисел разом
    /// (PathOptions.MaxJumpDistance, MaxDeliberateFall, SafeDropDistance,
    /// SafeJumpMargin и Movement.MaxFallDamage).
    ///
    /// ВТОРОЕ, И ОНО РЕШАЮЩЕЕ: на последнее из этих пяти чисел У ПРОДАВЦА УЖЕ
    /// ЕСТЬ СВОЯ РУЧКА — HelperRole.ЗдоровьяНаСпрыгивание, и доносит он её
    /// СВОЕЙ строкой ПОСЛЕ base.ДонестиОбщее (HelperRole: bot.Movement
    /// .MaxFallDamage = ЗдоровьяНаСпрыгивание). Приедь «СмелостьВПути» в общую
    /// родню — на одно поле механизма заговорили бы два голоса, причём второй
    /// затирал бы первый молча; мало того, обе ручки встали бы НА ОДНО МЕСТО В
    /// ОКНЕ («безопасность» 1, главная — у Продавца там стоит именно она), то
    /// есть повторилась бы ровно та ничья имён, из-за которой их когда-то и
    /// разводили.
    ///
    /// Переезд поэтому стоит НЕ ПЕРЕЕЗДА, А РАЗБОРА: кто хозяин
    /// Movement.MaxFallDamage — ступень осторожности или отдельное число хп, —
    /// и он тронет HelperRole, файл соседнего потока. Долг назван вслух и в
    /// отчёте волны; до разбора ручка остаётся здесь, и у четырёх ролей
    /// осторожность стоит на заводской Caution.Normal.
    /// </summary>
    [KnobPlace("безопасность", Order = 1, Main = true)]
    [KnobWasNamed("Смелость",
        Why = "у Продавца ручка с этим именем значила хп урона за прыжок, а не ступень")]
    public int СмелостьВПути { get; set; } = 1;

    /// <summary>Сторона карьера в блоках.</summary>
    [KnobPlace("работа", Order = 1, Main = true)]
    public int РазмерКарьера { get; set; } = 7;

    /// <summary>Глубина карьера в слоях.</summary>
    [KnobPlace("работа", Order = 2, Main = true)]
    public int ГлубинаКарьера { get; set; } = 3;

    /// <summary>
    /// Снимать объём карьера ЦЕЛИКОМ — ровная яма, но весь камень крошкой.
    ///
    /// Выключено — карьер идёт ШАХМАТКОЙ, и тогда ЧЕТВЕРТЬ объёма выходит
    /// ЦЕЛЫМИ блоками: у клетки, потерявшей все шесть соседей, срабатывает
    /// правило игры BreakIfFloating, и она падает целым строительным блоком —
    /// его не надо ни обжигать, ни складывать по четыре. Плата — вид: пока яма
    /// не добита, в ней стоит решётка недобранных клеток.
    ///
    /// ЧЕТВЕРТЬ, А НЕ ПОЛОВИНА, и врать тут нельзя — по этой строке человек
    /// считает выход до работы. Ровная шахматка по чётности сулит половину, но
    /// половину взять НЕ ВЫХОДИТ: между слоями целых блоков обязан лежать слой,
    /// снятый начисто, иначе к нижним клеткам нечем подойти. Этот слой-жертва и
    /// съедает половину обещанного (см. Quarry.IsHarvestLayer). Карьер 7×15 —
    /// это около двух сотен целых блоков из 735, а не под четыре.
    ///
    /// Настройка появилась потому, что заказчик увидел эту решётку на снимках
    /// и счёл яму недокопанной. Замысел должен быть виден и выбираем, а не
    /// объясняться после.
    /// </summary>
    [KnobPlace("работа", Order = 3, Main = true)]
    public bool РовнаяЯмаЦеликом { get; set; }

    /// <summary>На сколько блоков опускаться в разведке.</summary>
    [KnobPlace("руда", Order = 1)]
    public int ГлубинаРазведки { get; set; } = 24;

    /// <summary>Длина одного штрека в разведке.</summary>
    [KnobPlace("руда", Order = 2)]
    public int ДлинаШтрека { get; set; } = 24;

    /// <summary>Сколько штреков бить с одного уровня.</summary>
    [KnobPlace("руда", Order = 3)]
    public int ЧислоШтреков { get; set; } = 4;

    /// <summary>
    /// ЧЕРЕЗ СКОЛЬКО КЛЕТОК ХОДА ОГЛЯДЫВАТЬСЯ. Разведка смотрит на стены не всю
    /// дорогу, а рывками: прошёл столько-то клеток — осмотрелся.
    ///
    /// ПОЧЕМУ ЭТО ПОЛИТИКА. Цена у числа с обеих сторон, и выбирает её хозяин.
    /// Чаще — дороже по времени: один осмотр перебирает клетки шара, и на
    /// читерском радиусе это десятки тысяч вопросов к модели мира. Реже —
    /// дешевле, но можно пройти мимо вскрытой жилы: между двумя взглядами
    /// открывается несколько метров стены, и что в них было, бот не узнает.
    /// Ноль означал бы «оглядываться на каждом шагу», и это не бережливость, а
    /// вставший бот, — поэтому снизу одна клетка.
    /// </summary>
    [KnobPlace("руда", Order = 11)]
    public int ОсматриватьсяЧерезКлеток { get; set; } = 6;

    /// <summary>
    /// ОСТАНАВЛИВАТЬСЯ НА ПЕРВОЙ ЖЕ ПОДХОДЯЩЕЙ НАХОДКЕ.
    ///
    /// ПОЧЕМУ ЭТО ПОЛИТИКА. Наряду «принеси 20 меди» первой жилы хватает —
    /// дальше копать не надо, надо брать и нести. А разведке места под будущую
    /// шахту первая жила не говорит ничего: ей нужна вся картина уровня, и
    /// выключенная остановка — это как раз она. Механизм в обоих случаях один и
    /// тот же, разное — чего от него хотят.
    /// </summary>
    [KnobPlace("руда", Order = 12)]
    public bool ОстанавливатьсяНаПервойНаходке { get; set; } = true;

    // РУЧКА «ДержатьФакелов» ПЕРЕЕХАЛА В LivingRole (09.09) и стоит там на
    // прежнем месте копателя (снаряжение, 2) — раскладка окна не сдвинулась ни
    // на строку. Читатель у неё был один и общий (Stock.Require, тот же самый,
    // куда доносится «ДержатьЛестниц»), а ручка стояла у одного; про этот
    // разлад вслух говорили два ЧУЖИХ общих места — подпись
    // «ДержатьСверхЗапасаПроцентов» и спор голосов в Upkeep.Поставить, — и оба
    // называли стражнику, продавцу, ИИ и MCP ручку, которой у них не было

    // РУЧКА «СобиратьЕду» ПЕРЕЕХАЛА В LivingRole (09.09) и стоит там на прежнем
    // месте копателя (пропитание, 0, главная) — раскладка окна не сдвинулась ни
    // на строку. ЕСТ ВСЯКИЙ БОТ: читатель у неё один — способность
    // BehaviorForageWhenNoFood, а ставит её всем пяти ролям один и тот же пресет
    // выживания (Presets.Survive). Четыре роли из пяти жили с заводским «да»
    // библиотеки и снять его не могли ничем, хотя четыре соседние галочки того же
    // раздела у них в окне стояли и работали

    // РУЧКА «РадиусСбораЕды» ПЕРЕЕХАЛА В LivingRole — та же механика была в
    // ЧЕТЫРЁХ местах (здесь, второе имя у роли мода, жёсткие 12 и 24 в коде
    // стражника и продавца). Имя, раздел и порядок сохранены, пресеты копателя
    // менять не пришлось.

    // ДИКИЕ ПОСЕВЫ И ЧУЖИЕ ГРЯДКИ («СобиратьПосевы», «ТрогатьЧужиеГрядки»)
    // переехали в LivingRole — они у всех живущих ролей одни и те же, и на
    // прежних местах (6 и 7) там же и стоят

    /// <summary>
    /// При каком остатке прочности менять кирку.
    ///
    /// Место в окне переехало с третьего на девятое, и вот почему: три первых
    /// строки раздела теперь заняты тем, ЧТО держать при себе (инструменты,
    /// факелы, лестницы), а четвёртая и пятая — тем, ЧЕМ это пополнять
    /// (сделать или сходить взять). Замена изношенной кирки — не про запас, а
    /// про износ, и стоять между ними ей незачем.
    /// </summary>
    [KnobPlace(LivingRole.Снаряжение, Title = LivingRole.СнаряжениеЗаголовок, About = LivingRole.СнаряжениеОписание, Order = 9)]
    public int МенятьКиркуПри { get; set; } = 25;

