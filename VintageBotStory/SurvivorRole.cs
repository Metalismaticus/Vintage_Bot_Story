                return итог.Success ? SkillResult.Ok(итог.ToString())
                                    : SkillResult.Fail(итог.ToString());
            }));

        // ДОРОГА СТРОИТСЯ ОТРЕЗКОМ: от точки до точки, заданной ширины.
        // Прежний навык брал одну точку и мостил маршрут поиска пути — а тот
        // перепады ОБХОДИТ, тогда как дорога обязана их взять, и ширины у него
        // нет вовсе
        bot.Skills.Register(new DelegateSkill("дорога",
            // «НА ЗАДАННОЙ ВЫСОТЕ» ЗДЕСЬ СТОЯЛО И БЫЛО НЕПРАВДОЙ. Полотно
            // держит заданными КОНЦЫ, а между ними идёт по земле, сглаживая её
            // в пределах уклона (RoadPlan.Levels). Справка, обещающая одну
            // высоту на всю дорогу, — это тот же нарисованный рычаг: человек
            // заказывает по ней, получает другое и считает это поломкой
            "дорога <x1> <y1> <z1> <x2> <y2> <z2> [ширина] — замостить полосу от точки до " +
            "точки: концы лягут на заданных высотах, между ними полотно идёт по земле",
            async (ctx, args, ct) =>
            {
                var w = args.Split(' ', StringSplitOptions.RemoveEmptyEntries);
                if (w.Length < 6 ||
                    !int.TryParse(w[0], out int x1) || !int.TryParse(w[1], out int y1) ||
                    !int.TryParse(w[2], out int z1) || !int.TryParse(w[3], out int x2) ||
                    !int.TryParse(w[4], out int y2) || !int.TryParse(w[5], out int z2))
                    return SkillResult.Fail("нужно: дорога <x1> <y1> <z1> <x2> <y2> <z2> [ширина]");
                int ширина = w.Length > 6 && int.TryParse(w[6], out int ш) ? ш : ctx.Roads.Width;
                // Координаты человек называет игровые — переводим во внутренние.
                // ЧЕРЕЗ ВОЗВРАТ, как карьер и наряд: дорога на сотню рядов идёт
