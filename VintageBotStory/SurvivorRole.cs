        // (Recover.OnGaveUp в Configure).
        //
        // ЧТО ИМЕННО УЕХАЛО ОТСЮДА, чтобы читатель не искал пропажу:
        //   • РАДИУС САМООБОРОНЫ — ручка «ВступатьВБойСРасстояния» (LivingRole),
