        //     одном пресете, — для заказчика этого числа не существовало (закон 1);
        //   • ДИКАЯ ЕДА — главный выключатель цепочки «СобиратьЕду» вместе с
        //     именем для отказа и круг сбора: способность сбора стоит у всех
        //     пяти ролей, и второе чтение отсюда было бы вторым голосом;
        //   • БЕГСТВО — «БежатьБлиже» и «ЗакладыватьсяВУглу», к порогу отрыва и
        //     радиусу самообороны, которые жили там и раньше. Здесь исчезло и
        //     «Combat.Refuge = bot.Shelter»: чем закладываться, бою отдаёт сам
        //     пресет выживания, и строка была ВТОРОЙ копией той же (закон 2);
        //   • ДОМ КАК ТОЧКА ВОЗРОЖДЕНИЯ — и галочка, и точка, и цена дороги за
        //     ней («ДомДальше», «ДопускДома»);
        //   • РЕЙС НА СКЛАД — все три ручки («РазгружатьсяСам»,
