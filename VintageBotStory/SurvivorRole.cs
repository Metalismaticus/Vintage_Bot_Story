    /// <summary>
    /// ОТ ЧУЖОГО ОТХОДИМ ДО НАЧАЛА РАБОТЫ, а не посреди неё: уйти со вскрытой
    /// жилы дороже, чем не начинать её у чужого забора. Заказчик просил прямо:
    /// «в автопоиске чего-либо избегать приваты игроков и стараться от них в
    /// расстоянии 500 блоков добывать что-либо».
    ///
    /// Возвращает причину отказа или null, если место годится (в том числе
    /// когда бот отошёл и дошёл). Само правило «годится ли место» и «куда
    /// отойти» живёт в механизме — здесь только решение роли им пользоваться.
    /// </summary>
    private static async Task<string?> ОтойтиОтЧужого(BotContext ctx, CancellationToken ct)
    {
        if (ctx.Claims.KeepAway <= 0)
            return null;
        if (ctx.Self.Position is not { } p)
            return null;   // где стою — неизвестно; мерить не от чего, работу не срываем
        var здесь = new BlockPos((int)Math.Floor(p.X), (int)Math.Floor(p.Y), (int)Math.Floor(p.Z));
        if (ctx.Claims.Suits(здесь))
            return null;
        if (ctx.Claims.Aside(здесь) is not { } подальше)
            return $"работать негде: {ctx.Claims.Judge(здесь).Say()}";
        if (!await ctx.Movement.TravelToAsync(подальше, 300, ct))
            return $"до годного места {подальше} не дошёл — работу не начинаю";
        return null;
    }

    /// <summary>
    /// Долгие дела — навыками, а не командами. Разница важная: навык видно в
    /// панели, у него есть имя, и его можно прервать словом «стоп». Команда,
    /// которая копает полчаса, ничем из этого не обладает.
    /// </summary>
    private void Навыки(VsBot bot)
    {
        bot.Skills.Register(new DelegateSkill("наряд",
            "наряд <что> <сколько> [, <что> <сколько> …] — принести столько-то руды или ресурса; " +
            "вещей можно назвать несколько через запятую",
            async (ctx, args, ct) =>
            {
                // РАЗБОР ЗАКАЗА — ОДНО ЧИСТОЕ ПРАВИЛО (OrderLines.Parse), и оно
                // же разбирает то, что пришло из окна управления. Заказчик
                // 17.08: «добавить бы допустим в добыче … возможность добавить
                // несколько вещей, а не один ресурс». Свой разбор здесь и
                // второй в панели разошлись бы на первой же запятой
                var (строки, беда) = OrderLines.Parse(args);
                if (строки.Count == 0)
                    return SkillResult.Fail(беда);

                // КИРКА ПЕРЕД ВЫХОДОМ, а не по приходе. Живой случай: бот погиб,
                // возродился голым, отказался идти за вещами (412 бл — дальше
                // порога) и всё равно ушёл на делянку за 411 блоков, где копать
                // было нечем. Смотрим на пояс ДО дороги, как живой игрок
                if (ctx.Stock.Have("pickaxe") == 0)
                {
                    var снаряжение = await ctx.Stock.ReplenishAsync(ct);
                    if (ctx.Stock.Have("pickaxe") == 0)
                        return SkillResult.Fail($"копать нечем — кирки нет ({снаряжение}). " +
                                                "Положите кирку в сумку или в сундук склада");
                }

                if (await ОтойтиОтЧужого(ctx, ct) is { } чужое)
                    return SkillResult.Fail(чужое);

                // «Я ПОНЯЛ ТЕБЯ ВОТ ТАК» — В ЧАТ, ДО ВЫХОДА. Заказчик мерил
                // понимание бота по содержимому сундука через сорок минут: он
                // просил «20 меди», получал двадцать кусков руды и не мог
                // понять, где разошлись. Строку собирает механизм
                // (Metals.PlanFor) — тот же, что печатает её в журнал; здесь
                // только решение, КОМУ сказать, а это дело роли
                foreach (var строка in строки)
                    await bot.SayAsync(ctx.Metal.PlanFor(строка.What, строка.Count,
                        bot.Ores.CountIn).ToString(), reason: SayReason.Отчёт);

                // ЧЕРЕЗ ВОЗВРАТ, тем же механизмом, что и карьер. Живой случай
                // (журнал 23:31-23:32): «поесть fruit-pinkapple» важнее —
                // прерываю «команда добудь» → «медь: принёс 0 из 10 … наряд
                // ОТМЕНЁН», и через пятьдесят секунд то же самое ещё раз. Голод
                // перебивал правильно, а вот наряд после перерыва умирал целиком
                // и начинался с нуля — это и есть то «кружение», на которое
                // жаловался заказчик. Теперь бот доедает и доносит ОСТАТОК
                var итоги = await OrderResume.KeepFetchingAllAsync(ctx, строки,
                    BodyArbiter.Importance.Command, bot.Log, ct);
                string сказ = OrderLines.Say(итоги);
                return OrderLines.AllDone(итоги) ? SkillResult.Ok(сказ) : SkillResult.Fail(сказ);
            }));

