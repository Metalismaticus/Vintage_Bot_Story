            //
            // ЛУК СЮДА ВХОДИТ ТОЙ ЖЕ СТРОКОЙ (ЧтоДержатьВРуках), а не второй
            // веткой: бот, потерявший лук вместе с телом, обязан собраться
            // заново ИМЕННО С ЛУКОМ — иначе галочка «НуженЛук» работала бы
            // ровно до первой смерти и молчала об этом
            bot.Log("[инструменты] " + bot.Stock.RequireTools(ЧтоДержатьВРуках()));
            if (ДержатьФакелов > 0)
