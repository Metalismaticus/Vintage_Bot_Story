        выживание.Recover.OnGaveUp += why =>
        {
            bot.Log($"за вещами не иду ({why}) — собираюсь заново: {ЧтоДержатьВРуках()}");
            // ТОТ ЖЕ СПИСОК, ЧТО И ВЕЗДЕ. Здесь стояли жёсткие «pickaxe» и
            // «shovel»: заказчик просил «инструменты нужно крафтить ВСЕ (я про
