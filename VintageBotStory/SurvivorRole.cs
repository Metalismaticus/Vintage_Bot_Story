    /// <summary>
    /// ВИДЫ РАБОТ для очереди задач. Это ПОЛИТИКА копателя: какие поля показать
    /// человеку в окне и как из этих полей собрать строку аргументов УЖЕ
    /// СУЩЕСТВУЮЩЕГО навыка. Новых умений здесь не заводится ни одного —
    /// каждому виду работы соответствует навык из <see cref="Навыки"/>.
    ///
    /// Каталог собирается ОДИН РАЗ и запоминается: бегун очереди берёт его при
    /// запуске, и второй, собранный позже, разошёлся бы с тем, который на самом
    /// деле исполняется. Умолчания при этом не устаревают — сборщики аргументов
    /// читают ручки роли не сейчас, а в тот миг, когда задачу пускают, поэтому
    /// «сторона карьера», повёрнутая в панели вечером, доедет до вечерней же
    /// задачи.
    /// </summary>
    public override WorkCatalog? Works => работы ??= СобратьРаботы();

    private WorkCatalog? работы;

    private WorkCatalog СобратьРаботы() => new WorkCatalog()
        .Add(new WorkKind("наряд", "Наряд: принести руду или ресурс", "наряд")
            {
                About = "Найти на виду или под землёй и принести столько, сколько сказано."
            }
            // СПИСОК ВЕЩЕЙ, А НЕ ОДНА: заказчик 17.08 просил «добавить бы
            // допустим в добыче и еще где логично возможность добавить
            // несколько вещей, а не один ресурс, а точнее вид». Сказав тут
            // «список вещей», роль включает в окне строки «вещь + сколько» с
            // подсказкой при наборе — само окно имён полей роли не разбирает
            // (см. WorkFieldKinds.Things)
            .Things(WorkFields.What, "что добывать: «медь 20», «олово 8» — строк можно несколько",
                required: true)
            // БОЛЬШЕ НЕ ОБЯЗАТЕЛЬНО: число теперь бывает у каждой строки. Это
            // умолчание для строк, где числа не написали
            .Int(WorkFields.HowMany, "сколько брать у строки без своего числа")
            .Int(WorkFields.Radius, "в каком радиусе искать выходы руды")
            .Cell(WorkFields.Start, "откуда искать; пусто — где стою")
            .Storage().Limit()
            .Args(j =>
            {
                // Разбирает СТРОКИ то же чистое правило, что и чат: заведи тут
                // свой разбор — «медь 20, олово 8» из окна и из чата значили бы
                // разное, и объяснить это человеку было бы нечем
                var (строки, беда) = OrderLines.Parse(
                    OrderLines.Written(j, WorkFields.What), j.Int(WorkFields.HowMany) ?? 0);
                return строки.Count > 0 ? WorkArgs.From(OrderLines.Join(строки))
                                        : WorkArgs.No(беда);
            }))

        // СПОСОБ СЪЁМА ЗДЕСЬ НЕ УТВЕРЖДАЮТ, А НАЗЫВАЮТ РУЧКУ. Каталог работ
        // человек читает в панели — в том же окне, где стоит ручка «ровная яма
        // целиком» (см. РовнаяЯмаЦеликом). Прежняя строка обещала шахматку
        // безусловно: включив ровную яму, человек читал бы тут же, рядом, что
        // карьер копает решёткой — ровно тот спор, ради которого ручку и завели
        .Add(new WorkKind("карьер", "Карьер", "карьер")
            {
                // ИМЯ ЗДЕСЬ НАРОЧНО СЛОВАМИ, А НЕ ГОРБОМ. В окне подпись под
                // ручкой рисует KnobHelp.Words: «РовнаяЯмаЦеликом» человек
                // читает там как «ровная яма целиком», и каталог работ говорит
                // ровно то же, что стоит у переключателя (см. QuarryTests)
                About = "Выкопать яму на заданную глубину. Как снимать объём — ручка " +
                        "«ровная яма целиком»: выключена — шахматкой (четверть объёма " +
                        "выходит целыми блоками, но до конца работы в яме стоит решётка), " +
                        "включена — ровная яма, весь камень крошкой."
            }
            .Cell(WorkFields.Start, "центр верхнего слоя", required: true)
            .Int(WorkFields.Width, "сторона карьера в блоках")
            .Int(WorkFields.Depth, "слоёв вниз")
            .Storage().Limit()
            // Обе ручки подставляются вместе: разбор аргументов навыка
            // ПОЗИЦИОННЫЙ, и одна глубина без стороны была бы принята за сторону
            .Args(j => WorkArgs.From(
                $"{j.Int(WorkFields.Width) ?? РазмерКарьера} {j.Int(WorkFields.Depth) ?? ГлубинаКарьера}")))

        .Add(new WorkKind("штольня", "Штольня до точки", "штольня")
            {
                About = "Прокопать ход туда, куда пешком не пройти."
            }
            .Cell(WorkFields.End, "куда вести ход", required: true)
            .Cell(WorkFields.Start, "устье; пусто — где стою")
            .Storage().Limit()
            // Точка уходит ИГРОВЫМИ числами: навык зовёт перевод сам, и делать
            // это дважды значило бы уехать на второй сдвиг
            .Args(j => j.Cell(WorkFields.End) is not { } куда ? WorkArgs.Need(WorkFields.End)
                     : WorkArgs.From($"{куда.X} {куда.Y} {куда.Z}")))

        .Add(new WorkKind("дорога", "Дорога отрезком", "дорога")
            {
                About = "Замостить полосу от точки до точки НА ЗАДАННОЙ ВЫСОТЕ (её берут из " +
                        "обеих точек): сперва пройти всю дорогу и выкопать выемку, потом " +
                        "вернуться и уложить полотно. Перепад — ступенька «блок + полублок»."
            }
            .Cell(WorkFields.Start, "откуда вести дорогу", required: true)
            .Cell(WorkFields.End, "куда вести дорогу", required: true)
            .Int(WorkFields.Width, $"ширина полотна в клетках, 1..{RoadPlan.MaxWidth}")
            .Storage().Limit()
            .Args(j =>
            {
                if (j.Cell(WorkFields.Start) is not { } откуда) return WorkArgs.Need(WorkFields.Start);
                if (j.Cell(WorkFields.End) is not { } куда) return WorkArgs.Need(WorkFields.End);
                int ширина = j.Int(WorkFields.Width) ?? ШиринаДороги;
                if (ширина < 1 || ширина > RoadPlan.MaxWidth)
                    return WorkArgs.No($"ширина полотна бывает от 1 до {RoadPlan.MaxWidth} клеток " +
                                       $"(дальше край дороги выходит из-под руки), а задано {ширина}");
                return WorkArgs.From($"{откуда.X} {откуда.Y} {откуда.Z} " +
                                     $"{куда.X} {куда.Y} {куда.Z} {ширина}");
            }))

        .Add(new WorkKind("разведка", "Разведка под землёй", "разведка")
            {
                About = "Обойти округу ногами, потом уйти вниз и бить штреки."
            }
            .Thing(WorkFields.What, "какой металл; пусто — любой")
            .Cell(WorkFields.Start, "откуда бить ствол; пусто — где стою")
            .Int(WorkFields.Depth, "на сколько блоков опускаться")
            .Int(WorkFields.Radius, "радиус обхода округи ногами")
            .Storage().Limit()
            .Args(j => j.Text(WorkFields.What) is { } металл ? WorkArgs.From(металл) : WorkArgs.None()))

        .Add(new WorkKind("сбор", "Сбор дикой еды", "сбор")
            {
                About = "Обойти округу и набрать ягод, грибов и диких овощей. " +
                        "Ядовитое не берётся."
            }
            .Cell(WorkFields.Start, "якорь: радиус мерится от него, туда же бот вернётся")
            .Int(WorkFields.Radius, "как далеко отходить")
            .Int(WorkFields.HowMany, "сколько мест обобрать")
            .Storage().Limit()
            .Args(j => WorkArgs.From(
                $"{j.Int(WorkFields.Radius) ?? РадиусСбораЕды} {j.Int(WorkFields.HowMany) ?? 8}")))

        .Add(new WorkKind("разгрузка", "Разгрузка", "разгрузка")
            {
                About = "Отнести добытое на склад и вернуться в забой."
            }
            .Storage().Limit())

        .Add(new WorkKind("снаряжение", "Снаряжение", "снаряжение")
            {
                About = "Пополнить запасы: кирка, факелы."
            }
            .Storage().Limit());
