using VsBotKit;
using VsBotKit.Agent;

namespace VintageBotStory;

/// <summary>
/// КАКИЕ РОЛИ БЫВАЮТ У ЭТОГО БОТА — один список на всех, кто спрашивает:
/// аргументы запуска, окно управления и пресеты.
///
/// РОЛЕЙ ЧЕТЫРЕ, И КАЖДАЯ ЗАКАЗАНА ВСЛУХ. Сперва было три — «готовые роли, это
/// что? нужно 3 — продавец, ИИ бот и наш сейчас выживальщик»; четвёртой стал
/// СТРАЖНИК, и тоже по прямой просьбе: «стражнника для теста хотел без ИИ, у
/// него должны быть кастомные настройки». Роли для него не было вовсе — был
/// пресет роли ИИ, то есть сторож, за которого думает нейросеть, и это не то,
/// что просили. До всего этого ролей показывалось шесть, и половина списка
/// была не ролями:
///  • «Житель» — это ВЫЖИВАЛЬЩИК, которому не давали работы: ни одной своей
///    механики у него не было, только другие умолчания. Теперь он пресет
///    (presets/resident.json) — настройка роли, а не роль;
///  • «Служебный (с читами)» — это не роль, а РУБИЛЬНИК. Читы включаются в
///    bot.json (раздел cheats) и щелчком в окне управления, и включённый чит
///    там называется вслух. Отдельная роль для этого означала, что «честный»
///    и «нечестный» бот — разные существа, хотя разница в одном флаге;
///  • «Под внешним управлением (MCP)» — это СПОСОБ ЗАПУСКА, а не занятие:
///    роль поднимается только ключом --mcp, потому что обмен с редактором
///    идёт по stdin/stdout процесса. Выбрать её в окне и ждать клиента —
///    значит ждать напрасно, и в каталоге ей не место (см. Program.cs, ветка
///    mcpMode: она создаёт McpRole руками, до всякого каталога).
///
/// РОЛЬ И ПРЕСЕТ — РАЗНОЕ. Роль — это КОД: свои навыки, команды и способности.
/// Пресет — это ТЕКСТ с настройками одной из наших ролей (папка presets).
/// Смешивать их в одном списке и значило «готовые роли, это что?». Стражник
/// показал это в живом виде: пока он был пресетом, «не пускать по списку»
/// приходилось объяснять словами нейросети — потому что механики не было.
///
/// ЧЕТЫРЕ — ТОЛЬКО НАШИХ. Пятую пишет хозяин бота и кладёт собранным
/// файлом в папку <c>roles</c> рядом с программой (см. <see cref="ПапкиСвоихРолей"/>
/// и <see cref="RoleCatalog.AddFromFolder"/>). Своя роль встаёт в тот же
/// список и ничем не хуже наших: её видно в окне, её можно выбрать пресетом,
/// её ручки показываются тем же способом. Прежде «своя роль» значила «правь
/// исходники этого приложения и пересобирай его», то есть была недоступна
/// никому, кроме нас.
/// </summary>
public static class Roles
{
    /// <summary>Выживальщик: он же копатель, он же обычный житель без работы.</summary>
    public const string Выживальщик = "survivor";

    /// <summary>Продавец у прилавка.</summary>
    public const string Продавец = "trader";

    /// <summary>Ботом думает нейросеть.</summary>
    public const string ИИ = "ai";

    /// <summary>
    /// Стражник у ворот — БЕЗ нейросети. Заказчик просил его прямо:
    /// «стражнника для теста хотел без ИИ, у него должны быть кастомные
    /// настройки».
    /// </summary>
    public const string Стражник = "guard";

    /// <summary>
    /// Как зовётся папка со своими ролями. Рядом с <c>presets</c> и нарочно:
    /// человек ищет «куда положить своё» в одном месте, а не в двух.
    /// </summary>
    public const string ПапкаРолей = "roles";

    /// <summary>
    /// «Свои роли держу вот здесь» — переменная окружения, как у картинок
    /// (<c>VSBOT_ICONS</c>). Нужна там, где рядом с программой класть нельзя:
    /// контейнер, каталог только для чтения, бот и роли на разных томах.
    /// </summary>
    public const string ПеременнаяПапкиРолей = "VSBOT_ROLES";

    /// <summary>
    /// ГДЕ ИСКАТЬ СВОИ РОЛИ — по порядку и без повторов.
    ///
    /// Мест четыре, и каждое заведено живой бедой, а не про запас:
    ///  1. сказанное переменной окружения — старше всего, это прямое слово
    ///     человека;
    ///  2. рядом с ПРОЕКТОМ, если бот запущен из папки сборки: сама папка
    ///     сборки стирается пересборкой целиком, и однажды так уже пропали
    ///     18 560 выгруженных картинок (см. <see cref="BotFolders.Lasting"/>);
    ///  3. в папке состояния — там же, где <c>bot.json</c>: в контейнере рядом
    ///     с программой лежит слой образа, который пересборка стирает;
    ///  4. рядом с программой — то самое «положить в папку с ботом», как
    ///     человек это и понимает.
    ///
    /// При обычной установке 3 и 4 — одна и та же папка, и названа она будет
    /// один раз: два одинаковых пути подряд читаются как два разных места.
    /// </summary>
    public static string?[] ПапкиСвоихРолей() =>
    [
        Environment.GetEnvironmentVariable(ПеременнаяПапкиРолей),
        BotFolders.Lasting is { Length: > 0 } рядомСПроектом
            ? Path.Combine(рядомСПроектом, ПапкаРолей) : null,
        Path.Combine(BotFolders.State(), ПапкаРолей),
        Path.Combine(BotFolders.Beside, ПапкаРолей)
    ];

    /// <summary>
    /// Каталог с нашими ролями и со своими ролями хозяина бота.
    ///
    /// Порядок именно такой: сперва наши, потом свои. Чужая роль не должна
    /// молча занять имя нашей — при совпадении каталог откажет ей вслух
    /// (<see cref="RoleCatalog.Notes"/>), а не подменит копателя.
    ///
    /// ЧИСЛА РОЛЕЙ ЗДЕСЬ НЕТ НАРОЧНО. Здесь стояло «с нашими тремя ролями» —
    /// и стояло уже после того, как четвёртой завели стражника; приёмка нашла
    /// это в третьем круге подряд. Единственное место, где число ролей —
    /// правда, это сам список в <see cref="ТолькоНаши"/>; всякий его пересказ
    /// живёт до первой новой роли и потом врёт молча.
    /// </summary>
    public static RoleCatalog Catalog()
    {
        var каталог = ТолькоНаши();
        каталог.AddFromFolders(ПапкиСвоихРолей());
        return каталог;
    }

    /// <summary>
    /// Только роли, приехавшие с программой. Отдельно от <see cref="Catalog"/>
    /// затем, что стенду нужен список без чужих файлов: положи кто-нибудь свою
    /// роль рядом с испытательной сборкой — и проверка «в списке ровно наши
    /// роли» краснела бы не по своей вине.
    ///
    /// НАЗВАНИЕ (<c>Title</c>) ОБЯЗАНО СОВПАДАТЬ С <c>BotRole.Name</c> САМОЙ
    /// РОЛИ: окно управления по этому совпадению узнаёт, какой ролью назвать
    /// бота, когда снимает с него пресет (ControlPanel ищет запись по
    /// <c>e.Title == role.Name</c>). Разойдись они — снятый пресет получил бы
    /// чужое имя роли и при следующем запуске поднял бы другого бота, молча.
    /// Своим ролям это же правило даёт сам каталог: он берёт название у
    /// <c>BotRole.Name</c> образца (<see cref="RoleCatalog.AddFromFile"/>).
    /// </summary>
    public static RoleCatalog ТолькоНаши() => new RoleCatalog()
        .Add(Выживальщик, "Выживальщик",
            "Живёт сам: ест, отбивается, прячется от бури, спит. По приказу — " +
            "карьеры, штольни, руда, дороги. Скажите «!добудь медь 20» — уйдёт, " +
            "найдёт, выработает жилу и принесёт. Ничего сам не затевает",
            () => new SurvivorRole(),
            "кирка по зубам той породе, что копаем (для работ под землёй)",
            "сундук рядом под склад — или скажите в чате «!склад тут»")

        .Add(Продавец, "Продавец",
            "Стоит в лавке, обходит прилавки, торгует по табличкам",
            () => new HelperRole(),
            "магазин размечен табличками: !STORE (граница), !CASH + min N (касса), " +
            "!ТОВАР + buy N / sell N (прилавок)")

        // Конструктор БЕЗ АРГУМЕНТОВ нарочно: он поднимает потолок ответа с
        // 2048 до 8192. У claude-opus-5 размышление и текст делят один потолок,
        // и на 2048 длинный ход обрывается на полуслове
        .Add(ИИ, "ИИ",
            "Решения принимает нейросеть; она зовёт те же умения, что человек в чате",
            () => new AiTraderRole(),
            "ключ поставщика: поле «Ключ» во вкладке «Настройка роли» или " +
            "переменная окружения ANTHROPIC_API_KEY (переменная старше); " +
            "весь список — команда «!ии поставщики»",
            "лавка нужна только при включённой настройке «Магазин»")

        // СТРАЖНИК — ЧЕТВЁРТАЯ РОЛЬ, И ОНА БЕЗ НЕЙРОСЕТИ. Заказчик дословно:
        // «стражнника для теста хотел без ИИ, у него должны быть кастомные
        // настройки… ему нужно стоять в одной точке, кушать со склада и не
        // пускать людей по списку». Прежде «стражник» был ПРЕСЕТОМ роли ИИ, и
        // за него решала модель: она могла прозевать вход, ошибиться именем
        // или заговорить вместо дела. Список ников и сравнение — это правило
        // на десять строк, и нейросеть за него платить не должна
        .Add(Стражник, "Стражник",
            "Стоит на посту, кормится со склада, знает всех в лицо. Кого нет " +
            "в списке — не трогает; кто в списке — назван по имени в чат, а " +
            "хозяин позван. Держать силой не умеет и не притворяется",
            () => new GuardRole(),
            // ПОСТ — ЭТО РУЧКА «ПОСТ», А НЕ «ДОМ». Здесь стояло «точка „Дом“ —
            // это ПОСТ», и это была ложь в окне у самого стражника: своя ручка
            // «Пост» у него есть, она СТАРШЕ дома (GuardRole.ГдеСтоять:
            // пост ?? дом), и пустой «Дом» ему вовсе не нужен. «Дом» остаётся
            // запасным ровно затем, чтобы стражник с пустым «Постом» вёл себя
            // как до 23.08, — и молчать об этом тоже нельзя
            "точка «Пост» — там, где стоять: вокруг неё считается охраняемая " +
            "зона (поставьте её на карте или скажите «!пост тут»). Пусто — " +
            "постом служит общая точка «Дом», как было раньше",
            "список запрещённых ников — вкладка «Настройка роли», поле «ЧужиеНики»",
            "сундук с едой рядом с постом — или скажите в чате «!склад тут»");

    /// <summary>
    /// Какую роль просят аргументы запуска. Ничего не сказано — выживальщик:
    /// это тот бот, который просто живёт, пока ему не дали дела.
    ///
    /// Ключ <c>--mcp</c> сюда не доходит и дойти не должен: внешнее управление
    /// поднимается в <c>Program.cs</c> раньше каталога, своей веткой.
    /// </summary>
    public static string FromArgs(string[] args, BotConfig cfg)
    {
        if (cfg.Ai || args.Contains("--ai")) return ИИ;
        if (args.Contains("--trader")) return Продавец;
        if (args.Contains("--guard")) return Стражник;
        return Выживальщик;
    }

    /// <summary>
    /// ЧТО СТАЛО СО СТАРЫМИ КЛЮЧАМИ. Молчать о них нельзя: человек, запустивший
    /// бота с <c>--cheater</c>, получит обычного честного бота и будет думать,
    /// что читы работают. Возвращает строки для журнала; пусто — старых ключей
    /// в командной строке нет.
    /// </summary>
    public static IReadOnlyList<string> ProblemsWithOldFlags(string[] args)
    {
        var сказать = new List<string>();
        if (args.Contains("--digger"))
            сказать.Add("ключ --digger больше не нужен: копатель и есть выживальщик, " +
                        "он поднимается сам. Готовые настройки — «--preset digger»");
        if (args.Contains("--cheater"))
            сказать.Add("ключ --cheater БОЛЬШЕ НИЧЕГО НЕ ВКЛЮЧАЕТ: роли с читами нет, " +
                        "и это не потеря — читы живут в bot.json (раздел cheats) и в окне " +
                        "управления, причём каждый включённый называется вслух в журнале. " +
                        "Бот сейчас запущен ЧЕСТНЫМ");
        return сказать;
    }
}
