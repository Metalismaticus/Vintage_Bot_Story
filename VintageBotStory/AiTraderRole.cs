    public override void Configure(VsBot bot)
    {
        бот = bot;

        // Рефлексы выживания, стандартный набор умений и обычные команды чата.
        // Умения берутся из BotToolbox.Standard — те же самые, что у окна
        // управления и у внешнего клиента: списка умений нейросети отдельно
        // от списка умений человека в этом проекте нет
        base.Configure(bot);

        if (магазин && лавка == null)
            ПоднятьЛавку();

        // Чем думать — спрашиваем ДО входа в мир. «Бота не пустили» человек
        // отличает сразу, а «вошёл и молчит без объяснений» — нет
        ПроверитьЧемДумать(вслух: true);

        bot.Commands.Add("ии",
            "ии [пуск|стоп|забудь|поставщики] — чем бот думает, сколько потрачено и можно ли тратить дальше",
            async a =>
            {
                switch (a.Words.Length > 0 ? a.Words[0].ToLowerInvariant() : "")
                {
                    case "":
                        await a.ReplyAsync(Состояние());
                        break;

                    case "поставщики":
                    case "операторы":
                        // Тот же самый список, что показывает окно выпадающим
                        // списком. Ключи не печатаются — только «есть/нет»
                        await a.ReplyAsync($"Сейчас: {Настройки.Поставщик}.\n{AiSettings.Поставщики()}");
                        break;

                    case "стоп":
                        почемуНеДумаю = $"остановлено в чате ({a.Sender})";
                        запретИзЗаНастроек = false;
                        Budget.TurnOff(почемуНеДумаю);
                        await a.ReplyAsync("Больше не думаю. «!ии пуск» — снова.");
                        break;

                    case "пуск":
                        // Перепроверяем ключ: включать нечего, если думать нечем
                        if (ПроверитьЧемДумать(вслух: true) is { } беда)
                        {
                            await a.ReplyAsync($"Думать нечем: {беда}. {Настройки.КакВключить()}");
                            break;
                        }
                        почемуНеДумаю = null;
                        Budget.TurnOn();
                        await a.ReplyAsync($"Думаю снова. {Настройки.Чем()}");
                        break;

                    case "забудь":
                        Budget.Forget();
                        await a.ReplyAsync("Забыл потраченное: лимиты считаются заново.");
                        break;

                    default:
                        await a.ReplyAsync(
                            "Не понял. «!ии», «!ии пуск», «!ии стоп», «!ии забудь», «!ии поставщики»");
                        break;
                }
            });
    }

    public override Task OnJoinedAsync(VsBot bot)
    {
        var идёт = base.OnJoinedAsync(bot); // поднимает разговор и цикл раздумий
        ЗапомнитьПодсказку();

        // Отказ повторяем на КАЖДОМ входе: после обрыва связи бот возвращается
        // сам, и человек смотрит в журнал не с начала
        if (почемуНеДумаю is { Length: > 0 } беда)
            bot.Log($"[ии] НЕ ДУМАЮ: {беда}. {Настройки.КакВключить()}");
        else
            bot.Log($"[ии] думаю: {Настройки.Чем()}, раздумье раз в {ДуматьРазВСекунд:0} с");

        return идёт;
    }

    /// <summary>
    /// Ручку повернули снаружи — из окна управления, из пресета или из чата.
    ///
    /// Живой случай: характер и дело уходят в модель ОДИН раз, при входе в мир
    /// (там собирается подсказка). Окно крутит их позже, уже в игре, и без
    /// пересборки они лежали бы в поле роли мёртвым грузом: в окне новый
    /// характер, в игре прежний, и объяснить это нечем.
    /// </summary>
    public override void OnKnobsChanged()
    {
        // Общие ручки (дом, фонарь, приветствие, безделье, чат) доносит база —
        // без этого вызова они остались бы мёртвым грузом
        base.OnKnobsChanged();

        if (бот is not { Joined: true })
            return;

        // ПРО «РЕФЛЕКСЫ ВЫЖИВАНИЯ» ГОВОРИТ ОДНА МЕТКА, А НЕ ДВА МЕСТА. Здесь
        // СТОЯЛА жалоба в журнал ровно об этом же, а у самой ручки есть
        // [KnobPlace(AtStartOnly = …)], и окно показывает её ЧЕЛОВЕКУ рядом с
        // полем, в тот же миг, когда он ручку и крутит. Метка старше и доходит
        // туда, куда жалоба не доходила: заказчик крутит ручки в браузере, а не
        // в файле журнала.
        if (ПодсказкаИзменилась())
            ЗаявитьПересборку("характер, дело или правила изменились");
    }

    // ---------------- лавка ----------------

    private void ПоднятьЛавку()
    {
        var b = бот!;
        var л = new TraderShop(b.Context, b.Read);
        л.OnLog += m => b.Log($"[торговля] {m}");
        // ОТВЕТ ПОКУПАТЕЛЮ, а не рассказ о своих делах: человек обратился к боту
        // действием — положил монеты или товар в сундук — и ждёт слова
        // («Продал 3 × … Забирайте!»). Радиотишина такое не глушит: продавец,
        // молча забравший деньги, — это жалоба хозяину, а не «настоящий игрок»
        л.OnAnnounce += text => b.SayAsync(text, reason: SayReason.Ответ);
        b.Behaviors.Add(new BehaviorShopkeeper(b.Context, л) { ExecuteDeals = true });
        лавка = л;

        // ...и два умения поверх механизма — чтобы нейросеть знала о магазине.
        // Торговлю они не повторяют, а спрашивают тот же самый механизм
        Tools.Add("shop_status", "Что сейчас в магазине: прилавки, цены, склады, касса.",
            _ => Task.FromResult(Описание(b, л)));

        Tools.Add("shop_round", "Обойти прилавки прямо сейчас и посмотреть, что положили игроки.",
            async ct =>
            {
                var сделки = await л.SurveyAsync(ct);
                return сделки.Count == 0
                    ? "новых вкладов в сундуках нет"
                    : string.Join("; ", сделки.Select(d => d.ToString()));
            });

        // Лавочника подставляем ТОЛЬКО если характер и дело остались нашими:
        // текст, переписанный человеком, затирать нельзя
        if (Характер == ОбычныйХарактер) Характер = ХарактерЛавочника;
        if (Цель == ОбычноеДело) Цель = ДелоЛавочника;
        if (Правила == ОбычныеПравила) Правила = ПравилаЛавочника;

        b.Log("[ии] лавка поднята: сделки проводит способность продавца, " +
              "у нейросети два умения поверх неё (shop_status, shop_round)");

        // О новых умениях и новом характере модель узнаёт из подсказки, а её
        // собирают в начале разговора — значит разговор надо начать заново
        if (b.Joined)
            ЗаявитьПересборку("поднялась лавка: появились новые умения");
    }

    private static string Описание(VsBot bot, TraderShop магазин)
    {
        var прилавки = магазин.Stalls();
        string касса = магазин.Cash() is { } c
            ? $"касса на ({bot.PlayerCoords(c.Chest.X, c.Chest.Y, c.Chest.Z)}), неснижаемый остаток {c.MinReserve}"
            : "кассы не вижу";
        if (прилавки.Count == 0)
            return "Прилавков не вижу. " + касса;
        return "Прилавки:\n" + string.Join("\n", прилавки.Select(s =>
            $"- {s.ProductName}: продаём за {s.WeSellFor}, покупаем за {s.WeBuyFor}, " +
            $"сундук ({bot.PlayerCoords(s.Chest.X, s.Chest.Y, s.Chest.Z)})")) + "\n" + касса;
    }

    // ---------------- чем думать ----------------

    /// <summary>
    /// Проверить, есть ли чем думать, и распорядиться бюджетом.
    /// Возвращает первую причину отказа или null.
    ///
    /// Правило «чего не хватает» живёт в <see cref="AiSettings"/> и проверено
    /// тестами; здесь только последствия — запрет тратиться и слова в журнал.
    /// </summary>
    private string? ПроверитьЧемДумать(bool вслух)
    {
        var беды = Настройки.ЧегоНеХватает();

        if (беды.Count > 0)
        {
            // Не «пусть попробует и получит отказ»: обращение без ключа — это
            // гарантированная неудача раз в минуту до утра, и платная попытка
            почемуНеДумаю = string.Join("; ", беды);
            запретИзЗаНастроек = true;
            Budget.TurnOff(почемуНеДумаю);
            if (вслух)
            {
                // КАЖДАЯ БЕДА — СВОЕЙ СТРОКОЙ. «Не могу думать» одной фразой
                // заставляет гадать, что чинить: ключ, поставщика или модель
                foreach (string беда in беды)
                    бот?.Log($"[ии] НЕ ДУМАЮ: {беда}");
                бот?.Log($"[ии] {Настройки.КакВключить()}");
            }
            return беды[0];
        }

        // Снимаем ТОЛЬКО свой запрет: человеческий («!ии стоп») не трогаем
        if (запретИзЗаНастроек)
        {
            запретИзЗаНастроек = false;
            почемуНеДумаю = null;
            Budget.TurnOn();
            if (вслух)
                бот?.Log($"[ии] думать есть чем: {Настройки.Чем()}");
        }
        return null;
    }

    /// <summary>Состояние для чата: чем думаем, что разрешено, сколько истрачено.</summary>
    private string Состояние()
    {
        string чем = почемуНеДумаю is { Length: > 0 } беда
            ? $"НЕ ДУМАЮ: {беда}"
            : $"Думаю: {Настройки.Чем()}";
        string цена = Budget.InputPricePerMillion > 0 || Budget.OutputPricePerMillion > 0
            ? ""
            : " Цену не считаю: тариф не задан (настройки ЦенаВходаЗаМиллион и ЦенаВыходаЗаМиллион).";
        return $"{чем}. {Budget.Summary()}{цена}";
    }

    // ---------------- подсказка модели ----------------

    private void ЗапомнитьПодсказку()
    {
        былХарактер = Характер;
        былоДело = Цель;
        былиПравила = Правила;
    }

    private bool ПодсказкаИзменилась() =>
        былХарактер != Характер || былоДело != Цель || былиПравила != Правила;

    /// <summary>
    /// Пересобрать подсказку и начать разговор заново — но не сразу.
    ///
    /// Пауза здесь не для красоты: окно управления применяет настройки по
    /// одной, и три повёрнутые ручки означали бы три пересборки подряд, а
    /// каждая начинает новый разговор и стоит одного платного хода.
    /// </summary>
    private void ЗаявитьПересборку(string почему)
    {
        int моя = ++заявкаНаПересборку;
        _ = Task.Run(async () =>
        {
            await Task.Delay(2000);
            if (моя != заявкаНаПересборку || бот is not { Joined: true } b)
                return; // пришла заявка посвежее — пересоберём по ней
            b.Log($"[ии] {почему} — пересобираю подсказку модели и начинаю разговор заново");
            await началоРазговора(b);
            ЗапомнитьПодсказку();
        });
    }

    /// <summary>
    /// Жалоба на настройку. Не исключение: настроек в пресете бывает десяток,
    /// и из-за одной опечатки нельзя терять остальные. Но и молчать нельзя —
    /// иначе бот всю ночь работает не так, как написано в окне.
    /// </summary>
    private void Пожаловаться(string что) => бот?.Log($"[ии] настройка: {что}");
}
