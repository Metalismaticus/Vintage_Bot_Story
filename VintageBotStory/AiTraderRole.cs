    /// <summary>
    /// Держать лавку: поднять механизм магазина и дать нейросети два умения
    /// поверх него. Выключить обратно нельзя — способность продавца уже в теле
    /// бота, и роль об этом скажет, а не сделает вид, что убрала её.
    /// </summary>
    [KnobPlace("люди", Order = 11, Main = true)]
    public bool Магазин
    {
        get => магазин;
        set
        {
            if (лавка != null && !value)
            {
                Пожаловаться("лавка уже поднята; снять её можно только перезапуском бота");
                return;
            }
            магазин = value;
            if (value && бот != null && лавка == null)
                ПоднятьЛавку();
        }
    }

