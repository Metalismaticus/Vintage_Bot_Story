    /// <summary>Думаем Claude: ключ из окружения (или из окна), модель из настроек роли.</summary>
    public AiTraderRole() : this(СвойКлиент()) { }

    public AiTraderRole(ILlmClient llm) : base(llm)
    {
        // ОДНО МЕСТО НАСТРОЕК ИИ. Роль их не хранит и не проверяет сама:
        // разойдись эти правила копиями по ролям — и «усилие» где-то
        // проверялось бы, а где-то молча превращалось в самое дорогое
        Настройки = new AiSettings(llm, Budget, что => Пожаловаться(что));
        началоРазговора = base.OnJoinedAsync;
        Характер = ОбычныйХарактер;
        Цель = ОбычноеДело;
        Правила = ОбычныеПравила;
        ДуматьРазВСекунд = 60; // мир — не гонка: думать раз в минуту достаточно
    }

    /// <summary>
    /// Клиент Claude с потолком ответа, которого хватает на РАЗДУМЬЕ И ОТВЕТ
    /// сразу. У современных моделей размышление включено по умолчанию и
    /// списывается из того же потолка, что и текст: со стандартными двумя
    /// тысячами токенов длинный ход обрывается на полуслове, и модель
    /// отвечает огрызком.
    ///
    /// КЛЮЧ, ЗАДАННЫЙ В ОКНЕ, ПОДКЛАДЫВАЕТСЯ ЗДЕСЬ — и это единственное место,
    /// где он вообще берётся с диска. Заказчик просил задавать ключ в вебформе;
    /// окно кладёт его в файл секретов (<see cref="BotSecrets"/>), а SDK читает
    /// ПЕРЕМЕННУЮ ОКРУЖЕНИЯ и читает её ровно один раз — вот в этой строке,
    /// когда создаётся клиент. Значит переносить сохранённое в окружение надо
    /// прямо перед ней, и нигде больше.
    ///
    /// ПЕРЕМЕННАЯ, ЗАДАННАЯ ДО ЗАПУСКА, ОСТАЁТСЯ СТАРШЕ: <see
    /// cref="BotSecrets.ПоложитьВОкружение"/> не перебивает непустую. Тем, у
    /// кого ключ живёт в окружении, эта строка не меняет ничего.
    /// </summary>
    private static ClaudeClient СвойКлиент()
    {
        new BotSecrets().ПоложитьВОкружение();
        return new() { MaxTokens = 8192 };
    }

