/// <summary>
/// РОЛЬ ПОД УПРАВЛЕНИЕМ НЕЙРОСЕТИ.
///
/// Роль задаёт только АЛГОРИТМ и УСЛОВИЯ: кем себя считать, чем заниматься,
/// чего не делать, чем думать и сколько на это тратить. Ходить, смотреть,
/// говорить, копать, торговать бот умеет сам — это механизмы библиотеки, и
/// нейросеть зовёт РОВНО ТЕ ЖЕ умения, что человек в чате и кнопки в окне
/// управления (<see cref="BotToolbox.Standard"/>). Второго мозга у бота нет.
///
/// ЧЕМ ДУМАТЬ. Поставщик, модель, глубина раздумья, длина разговора и потолок
/// трат живут в ОДНОМ месте — <see cref="AiSettings"/>. Свойства ниже ничего не
/// решают: они витрина для окна управления (окно показывает свойства роли) и
/// зовут те же настройки. Второго места, где это задаётся, нет — иначе «в окне
/// одно, в запросе другое» стало бы вопросом времени.
///
/// КЛЮЧ роль не видит ВООБЩЕ: она спрашивает у настроек лишь «задана ли
/// переменная окружения». Значение читает сам SDK. Без этой проверки бот входил
/// в мир, начинал думать и получал отказ сети — раз в минуту, всю ночь, молча
/// для того, кто не читает журнал.
///
/// <code>
/// bot.UseRole(new AiTraderRole());               // Claude, ключ из окружения
/// bot.UseRole(new AiTraderRole(своя_нейросеть));  // любая другая модель
/// </code>
/// </summary>
public class AiTraderRole : LlmRole
{
